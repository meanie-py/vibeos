"""Decode raw debugcon (bochs debug port 0xE9) output against a trace catalog.

The kernel emits single-byte markers via `out 0xe9, al` at key boot milestones.
QEMU captures these with `-debugcon file:path`. This module decodes the raw bytes
against a JSON catalog generated by `rustconv trace-catalog`, producing a triage
report showing how far the kernel got before crashing.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

# Catalog lives in rustconv/data/
CATALOG_DIR = Path(__file__).resolve().parent.parent.parent / "tools" / "rustconv" / "data"


@dataclass
class TracePoint:
    char: str
    function: str
    file: str
    line: int
    description: str


@dataclass
class DebugconResult:
    raw_bytes: bytes
    milestones_reached: list[TracePoint] = field(default_factory=list)
    last_milestone: TracePoint | None = None
    next_expected: TracePoint | None = None
    hex_dumps: dict[str, str] = field(default_factory=dict)


def load_catalog(arch: str) -> dict | None:
    """Load trace catalog JSON for the given architecture.

    Returns None if catalog file doesn't exist.
    """
    path = CATALOG_DIR / f"trace_catalog_{arch}.json"
    if not path.exists():
        return None
    return json.loads(path.read_text())


def decode_debugcon(raw: bytes, catalog: dict) -> DebugconResult:
    """Decode raw debugcon bytes against a trace catalog.

    Uses sequential matching: walks raw bytes and catalog trace points in parallel.
    When a byte matches the next expected milestone char, record it and advance.
    Hex dump delimiters consume through the closing delimiter.
    """
    result = DebugconResult(raw_bytes=raw)

    trace_points = catalog.get("trace_points", [])
    hex_delimiters = {d["open"]: d for d in catalog.get("hex_dump_delimiters", [])}

    # Build TracePoint objects from catalog, skipping error markers ('!')
    # for sequential matching (errors are conditional branches)
    milestones = []
    for tp in trace_points:
        if tp["char"] == "!":
            continue  # Skip error paths — they only fire on bugcheck
        milestones.append(
            TracePoint(
                char=tp["char"],
                function=tp["function"],
                file=tp["file"],
                line=tp["line"],
                description=tp["description"],
            )
        )

    milestone_idx = 0
    i = 0

    while i < len(raw):
        byte_val = raw[i]
        ch = chr(byte_val) if 32 <= byte_val < 127 else None

        if ch is None:
            i += 1
            continue

        # Check if this opens a hex dump
        if ch in hex_delimiters:
            delim = hex_delimiters[ch]
            close_ch = delim["close"]
            # Consume through closing delimiter
            j = i + 1
            hex_content = []
            while j < len(raw):
                c = chr(raw[j]) if 32 <= raw[j] < 127 else None
                if c == close_ch:
                    break
                if c is not None:
                    hex_content.append(c)
                j += 1
            result.hex_dumps[delim["description"]] = "".join(hex_content)

            # Advance milestone index past both delimiters if they match
            while milestone_idx < len(milestones) and milestones[milestone_idx].char == ch:
                result.milestones_reached.append(milestones[milestone_idx])
                milestone_idx += 1
            # Skip past the closing delimiter milestone too
            if j < len(raw):
                close_char = chr(raw[j])
                while (
                    milestone_idx < len(milestones) and milestones[milestone_idx].char == close_char
                ):
                    result.milestones_reached.append(milestones[milestone_idx])
                    milestone_idx += 1
            i = j + 1
            continue

        # Try to match against next expected milestone
        if milestone_idx < len(milestones) and ch == milestones[milestone_idx].char:
            result.milestones_reached.append(milestones[milestone_idx])
            milestone_idx += 1
            i += 1
            continue

        # Non-matching byte — skip (noise or hex dump data without delimiters)
        i += 1

    # Set last/next pointers
    if result.milestones_reached:
        result.last_milestone = result.milestones_reached[-1]
    if milestone_idx < len(milestones):
        result.next_expected = milestones[milestone_idx]

    return result


def format_debugcon_report(result: DebugconResult) -> str:
    """Format a DebugconResult into a human-readable triage report."""
    lines = []
    n = len(result.raw_bytes)
    lines.append(f"=== Debugcon Triage ({n} bytes captured) ===")

    if n == 0:
        lines.append("NO OUTPUT — kernel did not reach first trace point")
        return "\n".join(lines)

    # Show raw bytes as printable string
    raw_str = result.raw_bytes.decode("ascii", errors="replace")
    if len(raw_str) > 120:
        raw_str = raw_str[:60] + "..." + raw_str[-60:]
    lines.append(f"Raw: {raw_str}")
    # Also show hex for non-printable byte detection
    hex_str = result.raw_bytes.hex()
    if len(hex_str) > 400:
        hex_str = hex_str[:200] + "..." + hex_str[-200:]
    lines.append(f"Hex: {hex_str}")

    if result.last_milestone:
        tp = result.last_milestone
        lines.append(f"LAST REACHED: '{tp.char}' = {tp.function}()")
        lines.append(f"  {tp.file}:{tp.line} — {tp.description}")

    if result.next_expected:
        tp = result.next_expected
        lines.append(f"CRASHED BEFORE: '{tp.char}' = {tp.function}()")
        lines.append(f"  {tp.file}:{tp.line} — {tp.description}")

    total = len(result.milestones_reached)
    lines.append(f"Milestones: {total} reached")

    if result.hex_dumps:
        lines.append("Hex dumps:")
        for desc, content in result.hex_dumps.items():
            lines.append(f"  {desc}: {content}")

    return "\n".join(lines)


def debugcon_report(raw: bytes, arch: str) -> str | None:
    """One-shot: load catalog, decode, format. Returns None if no catalog."""
    catalog = load_catalog(arch)
    if catalog is None:
        return None
    result = decode_debugcon(raw, catalog)
    return format_debugcon_report(result)
