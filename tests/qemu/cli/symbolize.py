"""`vibeos-cli sym` — resolve an address to module!symbol+offset.

Why this exists: `qemu/build-index.sh` indexes exactly ntoskrnl.exe and
ntkrnlmp.exe, so until now every USER-MODE address had to be resolved by hand
with objdump plus a throwaway nearest-symbol script. That is the whole WoW64
lane, the winetest corpus and every stock application. Four addresses in one
session was the detection event.

The rule this module keeps: never name a symbol we cannot prove owns the
address. It declines on a shared image base, and declines on an offset large
enough to prove the nearest symbol is not the right one — the same discipline
`triage._resolve_addr` already applies to the kernel index.
"""

from __future__ import annotations

import subprocess
from dataclasses import dataclass
from pathlib import Path

# Past this, "nearest preceding symbol" stops being evidence. A PE's symbol
# table omits plenty (static helpers, thunks, data-only regions), so some symbol
# always sorts below any address and will happily be reported as a match.
MAX_SANE_OFFSET = 0x20000


@dataclass(frozen=True)
class Module:
    base: int
    end: int
    name: str
    path: str
    unique: bool

    def contains(self, addr: int) -> bool:
        return self.base <= addr < self.end


def modules_path(repo: Path, arch: str) -> Path:
    return repo / "qemu" / f"modules-{arch}.tsv"


def symbols_path(repo: Path, arch: str) -> Path:
    return repo / "qemu" / f"symbols-{arch}-user.tsv"


def load_modules(repo: Path, arch: str) -> list[Module]:
    p = modules_path(repo, arch)
    if not p.is_file():
        return []
    out: list[Module] = []
    for line in p.read_text().splitlines():
        parts = line.split("\t")
        if len(parts) != 5:
            continue
        base, end, name, path, flag = parts
        try:
            out.append(Module(int(base, 16), int(end, 16), name, path, flag == "unique"))
        except ValueError:
            continue
    return out


def index_is_stale(repo: Path, arch: str) -> bool:
    """True when the media was rebuilt after the index was written.

    Deliberately keyed on livecd.iso rather than on the individual binaries: it
    is regenerated by every build, so it cannot say "fresh" for a tree whose
    modules moved. A stale index does not fail loudly on its own -- it names a
    plausible WRONG symbol -- so the check has to be here rather than left to
    whoever reads the output.
    """
    idx = symbols_path(repo, arch)
    if not idx.is_file():
        return True
    iso = repo / f"build-{arch}" / "livecd.iso"
    if not iso.is_file():
        return False
    return iso.stat().st_mtime > idx.stat().st_mtime


def build_index(repo: Path, arch: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["bash", str(repo / "qemu" / "build-user-index.sh"), arch],
        cwd=repo,
        capture_output=True,
        text=True,
    )


def lookup_symbol(repo: Path, arch: str, module: str, addr: int) -> tuple[str, int, str] | None:
    """Nearest defined symbol at or below `addr` within `module`."""
    p = symbols_path(repo, arch)
    if not p.is_file():
        return None
    best: tuple[str, int, str] | None = None
    prefix = module + "\t"
    with p.open() as fh:
        for line in fh:
            if not line.startswith(prefix):
                if best is not None:
                    break  # file is sorted by module; we are past it
                continue
            parts = line.rstrip("\n").split("\t")
            if len(parts) != 4:
                continue
            try:
                sym_addr = int(parts[1], 16)
            except ValueError:
                continue
            if sym_addr > addr:
                continue
            if best is None or sym_addr > best[1]:
                best = (parts[2], sym_addr, parts[3])
    return best


def resolve(repo: Path, arch: str, addr: int, want_module: str | None = None) -> str:
    mods = load_modules(repo, arch)
    if not mods:
        return f"{addr:#x} -> (no index; run qemu/build-user-index.sh {arch})"

    if want_module:
        cands = [m for m in mods if m.name.lower() == want_module.lower()]
        if not cands:
            return f"{addr:#x} -> (no module named {want_module} in the {arch} index)"
    else:
        cands = [m for m in mods if m.contains(addr)]

    if not cands:
        return f"{addr:#x} -> (no user-mode module covers this address)"

    uniq = [m for m in cands if m.unique] if not want_module else cands
    if not uniq:
        names = ", ".join(sorted({m.name for m in cands})[:6])
        return (
            f"{addr:#x} -> (ambiguous: {len(cands)} modules share this base — {names}"
            f"{', ...' if len(cands) > 6 else ''}; pass --module)"
        )
    if len(uniq) > 1:
        names = ", ".join(sorted({m.name for m in uniq}))
        return f"{addr:#x} -> (overlapping modules: {names}; pass --module)"

    m = uniq[0]
    hit = lookup_symbol(repo, arch, m.name, addr)
    if hit is None:
        return f"{addr:#x} -> {m.name}+{addr - m.base:#x} (no symbol table entry)"
    name, sym_addr, src = hit
    off = addr - sym_addr
    if off > MAX_SANE_OFFSET:
        return (
            f"{addr:#x} -> {m.name}+{addr - m.base:#x} "
            f"(no symbol: nearest is {off:#x} away — outside any function)"
        )
    where = "" if src in ("-", "") else f"  {src}"
    return f"{addr:#x} -> {m.name}!{name}+{off:#x}{where}"


def run(args, repo: Path) -> int:
    arch = args.arch
    if index_is_stale(repo, arch) or args.rebuild:
        print(f"[sym] building the {arch} user-mode index (media is newer)...")
        cp = build_index(repo, arch)
        if cp.returncode != 0:
            print(cp.stderr.strip()[:2000])
            print(f"[sym] index build FAILED for {arch}")
            return 1
    rc = 0
    for raw in args.addr:
        try:
            addr = int(raw, 16)  # int(x, 16) already accepts a 0x prefix
        except ValueError:
            print(f"{raw} -> (not a hex address)")
            rc = 1
            continue
        print(resolve(repo, arch, addr, args.module))
    return rc
