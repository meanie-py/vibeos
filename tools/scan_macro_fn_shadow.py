def self_test() -> int:
    import tempfile

    global RUST_ROOT, C_ROOT
    ok = 0
    for desc, files, want in SELF_TEST:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "Cargo.toml").write_text("[package]\nname='t'\n")
            for rel, body in files.items():
                dest = root / rel
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(body)
            saved, RUST_ROOT = RUST_ROOT, root
            saved_c, C_ROOT = C_ROOT, root
            try:
                got = [Path(rel).name for rel, _, _ in scan(rust_files())]
            finally:
                RUST_ROOT = saved
                C_ROOT = saved_c
        if sorted(got) == sorted(want):
            ok += 1
        else:
            print(f"FAIL: {desc}\n  want {sorted(want)}\n  got  {sorted(got)}")
    print(f"self-test: {ok}/{len(SELF_TEST)}")
    return 0 if ok == len(SELF_TEST) else 1


def main() -> int:
    if "--self-test" in sys.argv:
        return self_test()
    lint = "--lint" in sys.argv
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    paths = [Path(a).resolve() for a in args] if args else rust_files()

    hits = scan(paths)
    seen = set()
    for rel, name, line in hits:
        if lint:
            # No line number, matching every other baselined scanner: a baseline keyed to
            # line numbers goes stale on the next edit above the finding, and re-blessing it
            # re-blesses everything else that drifted with it.
            if (rel, name) in seen:
                continue
            seen.add((rel, name))
            print(f"{rel}: {name} [MACRO_FN_SHADOW]")
            continue
        print(
            f"{rel}:{line}: {name} [MACRO_FN_SHADOW]  (this crate defines "
            f"`macro_rules! {name}` — import it with `use crate::{name};` "
            f"rather than shadowing it)"
        )
    if not lint and hits:
        print(f"\n{len(hits)} empty fn(s) shadowing a macro of their own crate")
    return 1 if hits else 0


if __name__ == "__main__":
    sys.exit(main())
