#!/usr/bin/env python3
"""
scan_macro_fn_shadow.py — the crate already has the macro. A module re-declared
the same name as an empty `fn`, and every call site in it now goes out of line.

THE POINT. AGENTS.md states it as an absolute: "Never translate a C debug MACRO
into a no-op `fn`. An out-of-line no-op is an optimization barrier that uncloaks
latent ABI mismatches -> ud2 -> BUGCHECK. Use a `macro_rules!`." This scanner is
that rule with a command behind it. It fires when ONE crate defines a name BOTH
as `macro_rules! NAME` and as `fn NAME(..) {}` with an empty body — which is to
say, the correct mechanism already exists a few files away and a module grew a
silent shadow of it anyway.

WHY IT MATTERS, from the incident that opened this. shell32-rust has had
`#[macro_export] macro_rules! UNREFERENCED_PARAMETER` in win32.rs since the
cohab flip — its own comment cites the ud2/BUGCHECK class, so the rule was known
and fixed centrally. Two modules carried a local `fn` shadow anyway:

    recycle_bin.rs:1412       #[inline] fn UNREFERENCED_PARAMETER<T>(_: T) {}
    dialogs/drvdefext.rs:796  pub fn UNREFERENCED_PARAMETER<T>(_param: T) {}   (no #[inline])

Neither is reachable from the macro: BOTH modules are declared BEFORE `win32` in
lib.rs, and `macro_rules!` textual scoping only runs forward. So the shadow was
not carelessness, it was the module doing the only thing that compiles — which
is exactly why a human rule was never going to hold here and a check has to.
The fix is an explicit `use crate::NAME;` (a `#[macro_export]` macro lives at the
crate root, so a path import reaches it from anywhere, in any order).

WHY NOTHING ELSE SEES THIS CLASS. `scan_dropped_prints` has a NOOP finding for
the same SHAPE, but it is gated on `name in ALWAYS_ON` — DPRINT1, DbgPrint*, ERR,
FIXME. That is correct for what it owns (a lost DIAGNOSTIC), and it means the
class is only covered for names that print. `UNREFERENCED_PARAMETER` prints
nothing, so it sat outside every scanner in the tree. This one is keyed on a
property of the crate — "you already defined this as a macro" — instead of on a
hardcoded list, so it needs no seeding and covers names nobody has thought of.

WHY THE BODY MUST BE EMPTY. A same-named `fn` with a REAL body is ordinary and
common: shell32-rust has `pub fn LOWORD(l: DWORD) -> WORD { (l & 0xFFFF) as WORD }`
in win32.rs, which is a legitimate inline helper, not a shadow. Requiring an empty
body is what separates "two spellings of one computation" from "a macro lowered to
a barrier". Narrow on purpose: a false positive here would be a lint you cannot
satisfy by doing the right thing.

SCOPE is per CRATE (the nearest ancestor holding a Cargo.toml), because that is
the boundary `macro_rules!` and `#[macro_export]` actually live at. A `fn` in
crate A that shares a name with a macro in unrelated crate B is not a shadow.

TWO WIDENINGS, from the PAGED_CODE sweep (2026-10-08).

  * DDK_MACROS names are macros in EVERY crate. PAGED_CODE() is a macro in every
    DDK header we compile against, yet 12 crates had it as an empty fn and NONE had
    a `macro_rules!` -- so the crate-local key above could never fire, and the
    class sat in 71 files outside every scanner. A name on this list needs no
    in-crate macro to be a finding.
  * An `extern` DECLARATION of a DDK_MACROS name is the same finding. It has no body to
    test for emptiness, but a declaration is out of line by construction, and it is
    the worse spelling: 59 of those files declared `fn PAGED_CODE();` in an extern
    block, resolved at link time by whichever crate in the image happened to export
    a `#[no_mangle]` no-op -- fastfat's 29 had no definition in fastfat at all.
"""

