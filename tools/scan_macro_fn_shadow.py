REPO = Path(__file__).resolve().parent.parent
RUST_ROOT = REPO / "sdk" / "lib" / "rust"
SKIP_FILE_RE = re.compile(r"(bindgen_[a-z0-9_]+\.rs$|/target/|/\.responses/)")
GENERATED_RE = re.compile(r"automatically generated by rust-bindgen|@generated")

MACRO_DEF_RE = re.compile(r"(?m)^\s*macro_rules!\s+([A-Za-z_]\w*)")

# C macros of the DDK that must never be lowered to a fn, whatever the crate defines.
DDK_MACROS = frozenset({"PAGED_CODE", "PAGED_CODE_LOCKED", "UNREFERENCED_PARAMETER"})

# Where the C a translation came from lives. The dead-macro set is harvested from here.
C_ROOT = REPO

# A C macro whose expansion DISCARDS its arguments, in at least one configuration:
#   #define DPRINT_URB(...)  do { if(0) { DbgPrint(__VA_ARGS__); } } while(0)
#   #define DPRINT_URB       __noop
#   #define TRACE_(ch, ...)  ((void)0)
# Its arguments are never evaluated. An empty Rust `fn` of the same name evaluates every one
# of them before doing nothing -- including a dereference the C never performs.
_C_DEFINE_RE = re.compile(r"^\s*#\s*define\s+([A-Za-z_]\w*)(\([^)]*\))?(?:\s+(.*?))?\s*$")
_DISCARDS_RE = re.compile(
    # `VOID` as well as `void`: ReactOS's own debug.h spells it `((VOID) 0)`.
    r"__noop|\(\s*\(\s*(?:void|VOID)\s*\)\s*0\s*\)|\(\s*(?:void|VOID)\s*\)\s*0|"
    r"do\s*\{\s*\}\s*while\s*\(\s*0\s*\)|"
    r"do\s*\{\s*if\s*\(\s*0\s*\)\s*\{.*\}\s*;?\s*\}\s*while\s*\(\s*0\s*\)|",
    re.S,
)


def _c_headers(root: Path) -> list[Path]:
    """Tracked headers under `root` (git, so build-* trees never count); a plain walk when
    `root` is not a checkout (the self-test's temp dir)."""
    import subprocess

    try:
        out = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--", "*.h"],
            capture_output=True,
            check=True,
        ).stdout
        return [root / p.decode("utf8", "replace") for p in out.split(b"\0") if p]
    except (OSError, subprocess.CalledProcessError):
        return sorted(root.rglob("*.h"))


def dead_c_macros(root: Path) -> frozenset[str]:
    """Every macro some C header defines as argument-discarding (see _DISCARDS_RE)."""
    names: set[str] = set()
    for path in _c_headers(root):
        try:
            lines = path.read_text("utf8", "replace").splitlines()
        except OSError:
            continue
        i = 0
        while i < len(lines):
            line = lines[i]
            while line.endswith("\\") and i + 1 < len(lines):
                i += 1
                line = line[:-1] + " " + lines[i]
            i += 1
            m = _C_DEFINE_RE.match(line)
            if not m:
                continue
            body = re.sub(r"/\*.*?\*/|//.*$", "", m.group(3) or "").strip()
            # An EMPTY expansion only discards arguments when there are arguments: an
            # object-like `#define FOO` is a flag or an include guard, not a callable.
            if not body and m.group(2) is None:
                continue
            if _DISCARDS_RE.fullmatch(body):
                names.add(m.group(1))
    return frozenset(names)


def c_function_names(root: Path, names: set[str]) -> frozenset[str]:
    """The subset of `names` that some C file DECLARES or DEFINES as a function: a line
    that starts with a return type (or with the name itself, K&R style) and reaches
    `NAME(`. `#define`s start with `#` and never match.

    Two look-alikes are NOT a C function, and both were caught counting as one:
      * our own `rust_cohab_stub.c` link stubs (`void assert(int c) { (void)c; }`) are
        the same no-op as the Rust they sit beside, not ReactOS's C;
      * a call statement written at column 0 (`assert(width > 0);` in vendored glu):
        with no return type in front, a line ending in `;` is a call, not a definition.
    """
    import subprocess

    if not names:
        return frozenset()
    alt = "|".join(sorted(names))
    rx = rf"^([A-Za-z_][A-Za-z0-9_ \t\*]*[ \t\*])?({alt})[ \t]*\("
    try:
        proc = subprocess.run(
            [
                "git",
                "-C",
                str(root),
                "grep",
                "-hE",
                rx,
                "--",
                "*.c",
                "*.h",
                ":!sdk/lib/rust",
                ":!**/rust_cohab_stub.c",
            ],
            capture_output=True,
            check=False,
        )
        # 1 is "no match" -- a real answer. Only "not a checkout" (the self-test's temp
        # dir) falls back to a walk; a walk of the whole tree here would cost minutes.
        out = proc.stdout.decode("utf8", "replace") if proc.returncode in (0, 1) else None
    except OSError:
        out = None
    if out is None:
        pat = re.compile(rx)
        out = "\n".join(
            line
            for f in [*root.rglob("*.c"), *root.rglob("*.h")]
            if f.name != "rust_cohab_stub.c"
            for line in f.read_text("utf8", "replace").splitlines()
            if pat.match(line)
        )
    head = re.compile(rx)
    found = set()
    for line in out.splitlines():
        m = head.match(line)
        if m is None:
            continue
        typed = (m.group(1) or "").strip() not in ("", "return")
        # No return type in front: a K&R definition, unless it ends like a call.
        if typed or not line.rstrip().endswith(";"):
            found.add(m.group(2))
    return frozenset(found)


_PARSER = None


def _walk(node):
    yield node
    for child in node.children:
        yield from _walk(child)


def crate_of(path: Path) -> Path:
    """Nearest ancestor holding a Cargo.toml — the scope macros actually live at."""
    for parent in path.parents:
        if (parent / "Cargo.toml").is_file():
            return parent
        if parent == RUST_ROOT:
            break
    return path.parent


@source_facts()
def empty_body_fns(src: bytes) -> list[tuple[str, int, int]]:
    """(name, 1-based line, parameter count) for every `fn NAME(..) {}` whose body has no
    statements.

    A body holding only COMMENTS counts as empty: comments emit no code, so the
    out-of-line barrier is just as real, and `fn X() { /* no-op */ }` is a spelling a
    translation actually produces. Note this is deliberately one notch wider than
    `scan_dropped_prints`'s NOOP predicate (`not body.named_children`), which counts a
    comment as content because tree-sitter makes it a named node.
    """
    import tree_sitter_rust as tsr
    from tree_sitter import Language, Parser, Query, QueryCursor

    global _PARSER
    if _PARSER is None:
        _PARSER = Parser(Language(tsr.language()))

    out = []
    tree = _PARSER.parse(src)
    query = Query(_PARSER.language, "(function_item) @fn")
    nodes = QueryCursor(query).captures(tree.root_node).get("fn", [])
    for node in sorted(nodes, key=lambda n: n.start_byte):
        name_node = node.child_by_field_name("name")
        body = node.child_by_field_name("body")
        if name_node is None or body is None:
            continue
        comments = ("line_comment", "block_comment")
        if any(child.type not in comments for child in body.named_children):
            continue
        name = src[name_node.start_byte : name_node.end_byte].decode("utf8", "replace")
        params = node.child_by_field_name("parameters")
        nparams = 0 if params is None else len(params.named_children)
        out.append((name, src[: node.start_byte].count(b"\n") + 1, nparams))
    # Bodyless declarations inside an `extern` block: out of line by construction. Only for
    # DDK_MACROS: a crate-macro NAME declared extern is often a real function of the same
    # name living elsewhere (CONTAINING_RECORD, freeldr's TRACE family), a different question.
    query = Query(
        _PARSER.language, "(foreign_mod_item (declaration_list (function_signature_item) @sig))"
    )
    sigs = QueryCursor(query).captures(tree.root_node).get("sig", [])
    for node in sorted(sigs, key=lambda n: n.start_byte):
        name_node = node.child_by_field_name("name")
        if name_node is None:
            continue
        name = src[name_node.start_byte : name_node.end_byte].decode("utf8", "replace")
        if name in DDK_MACROS:
            params = node.child_by_field_name("parameters")
            nparams = 0 if params is None else len(params.named_children)
            out.append((name, src[: node.start_byte].count(b"\n") + 1, nparams))
    return out


def rust_files() -> list[Path]:
    if not RUST_ROOT.is_dir():
        return []
    return [p for p in sorted(source_files(RUST_ROOT)) if not SKIP_FILE_RE.search(p.as_posix())]


_SPEC_EXPORT_RE = re.compile(r"^\s*@\s+\w+(?:\s+-\S+)*\s+([A-Za-z_]\w*)", re.M)


def spec_exports() -> frozenset[str]:
    """Every name a tracked `.spec` file exports."""
    out: set[str] = set()
    listed = subprocess.run(
        ["git", "ls-files", "*.spec"], cwd=REPO, capture_output=True, text=True
    ).stdout.split()
    for rel in listed:
        try:
            out |= set(_SPEC_EXPORT_RE.findall((REPO / rel).read_text(errors="replace")))
        except OSError:
            continue
    return frozenset(out)


def _no_mangle_at(path: Path, line: int) -> bool:
    """Whether the fn starting at `line` (1-based) carries `#[no_mangle]`."""
    try:
        lines = path.read_text(errors="replace").splitlines()
    except OSError:
        return False
    i = line - 2
    while i >= 0 and lines[i].strip().startswith(("#[", "///", "//")):
        if "no_mangle" in lines[i]:
            return True
        i -= 1
    return "no_mangle" in lines[line - 1] if 0 < line <= len(lines) else False


def scan(paths: list[Path]) -> list[tuple[str, str, int]]:
    """(relpath, macro name, line) for each empty `fn` shadowing a macro in its crate."""
    macros: dict[Path, set[str]] = {}
    shadows: list[tuple[Path, str, int, int]] = []
    for path in paths:
        try:
            raw = path.read_bytes()
        except OSError:
            continue
        text = raw.decode("utf8", "replace")
        if GENERATED_RE.search(text[:4096]):
            continue
        crate = crate_of(path)
        found = set(MACRO_DEF_RE.findall(text))
        if found:
            macros.setdefault(crate, set()).update(found)
        for name, line, nparams in empty_body_fns(raw):
            shadows.append((path, name, line, nparams))

    # Names the C defines as argument-discarding are macros in EVERY crate, like DDK_MACROS:
    # the no-op may sit in a shim crate that serves its callers' extern declarations, so no
    # crate-local key could ever see it (drvtrace-shim's DPRINT_URB, 2026-10-08).
    dead = dead_c_macros(C_ROOT) if shadows else frozenset()
    # A harvested name is only a hazard when it is a macro and NOTHING else, and only
    # for an fn that takes arguments. The first rule set reported 5 false positives:
    # RtlPrefetchMemoryNonTemporal and AcpiOsWaitEventsComplete are real exported
    # functions (a discarding macro of that name lives in a test stub / another
    # platform's header), KiEnterInterruptTrap is a real i386 FORCEINLINE, and
    # PrepareForSetPixel / Ki386PerfEnd take no arguments, so there is nothing to
    # evaluate eagerly.
    candidates = {n for _, n, _, _ in shadows if n in dead}
    real_fns = c_function_names(C_ROOT, candidates) if candidates else frozenset()
    exports = spec_exports() if shadows else frozenset()
    hits = []
    for path, name, line, nparams in shadows:
        # An EXPORT whose C body is empty is the C's own shape, not a shadow: ndis.h has
        # `#define NdisFreeSpinLock(..)` for callers and control.c #undefs it to define the
        # ndis.spec export. A `#[no_mangle]` fn some .spec exports is an ABI obligation.
        # (fastfat's DPRINT_URB, this scanner's motivating case, is in no .spec.)
        if name in exports and _no_mangle_at(path, line):
            continue
        harvested = name in dead and nparams > 0 and name not in real_fns
        if name in DDK_MACROS or harvested or name in macros.get(crate_of(path), ()):
            try:
                rel = path.relative_to(REPO).as_posix()
            except ValueError:
                rel = path.as_posix()
            hits.append((rel, name, line))
    return sorted(hits)


