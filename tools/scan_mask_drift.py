#!/usr/bin/env python3
"""
scan_mask_drift.py — every translated file carries its own oracle. Use it.

THE POINT (field manual, "A hand-typed bit-flag literal that names the wrong
member"). rustconv keeps the original C as trailing comments in the same `.rs`,
so a file that masks `X &= ~NAMED_CONST` in its C and `X & !0xLITERAL` in its
Rust has stated its own intent and then contradicted it, in one blob. No header
catalog, no C build, and no cross-file reasoning is needed to see that.

That is not hypothetical. It found E21 unprompted: `NtOpenKey` masked
`& !0x0100u32` where the C masks `~KEY_WOW64_RES` (**0x0300**) — the named
constant was defined thirty lines up and used correctly by `NtCreateKey`
sixty lines down. `KEY_WOW64_32KEY` therefore survived into
`ObCheckObjectAccess`, where no key's DACL grants it, so every
`RegOpenKeyEx(.., KEY_WOW64_32KEY)` in the OS returned ACCESS_DENIED while the
identical `RegCreateKeyEx` succeeded. It also found i386 `KeFlushCurrentTb`
having dropped its whole `KF_GLOBAL_PAGE` branch — global TLB entries survived
every flush — which had no symptom and nobody looking for it.

WHY NOTHING ELSE SEES THIS CLASS. `verify_constants` checks `const NAME = V;`
DEFINITIONS, and the definition here was right. `scan_inline_flag_literals`
checks a literal against a name in an ADJACENT comment, and there is no adjacent
comment — the C lives 1700 lines away at the end of the file. `cargo check` is
green either way: both spellings are `u32`. The bug is a *relationship* between
two regions of one file, which is exactly what a whole-file read can see and a
local one cannot.

Its first full sweep found the registry's whole `HIVE_*` family open-coded and
four of eight copies wrong — `CmLoadKey` setting 0x4 and `CmUnloadKey` 0x40 for
`HIVE_IS_UNLOADING` (0x20), against guards testing 0x4 and 0x200 — so the C's
"refuse to resolve a key in a hive that is unloading" protection was inert on the
unload path it exists for.

WHAT IT REPORTS. For each `TARGET &= ~NAME` in the commented C, the live Rust
must mask the same TARGET with the same NAME:

  MISMATCH  live masks a LITERAL whose value != NAME's. A bug, or the C moved.
            Zero tree-wide as of 2026-08-01; keep the baseline empty of these.
  OPENCODED live masks a literal we cannot resolve NAME against. Usually just
            wants the name back; occasionally a MISMATCH we could not prove.
  DROPPED   nothing in live code masks that target at all. The mask, or the
            branch holding it, did not survive translation.

TARGET is the identifier immediately left of the `&`, so `p->Flags &= ~X` and
`(*p).Flags &= !X` pair up on `Flags` without modelling either language's member
access. Pairing on it is what makes this specific enough to gate: the same file
routinely masks six different variables. Compared case-insensitively, and a
`let` binding counts as its own target, because translation re-cases and rebinds.

OCCURRENCES ARE NOT COUNTED. "The C masks it 4 times, the Rust 3" looks like the
obvious rule and is a trap: a C block repeats a statement once per call site,
rustfmt merges paths, and a fix's own explanatory comment quoting the C reads as
another C occurrence. Values are compared; absence is reported; counts are not.

CALIBRATION, so nobody re-derives it: the live spelling is usually
`&= !(NAME as ULONG)`, so a pattern accepting only `!NAME` reports ~4x noise
(109 raw hits vs 27). And check the sibling arch before believing a DROPPED —
amd64's `KeFlushCurrentTb` C really is CR3-only, so only the i386 copy had a
branch to lose.

Usage:
    python3 tools/scan_mask_drift.py                 # full report
    python3 tools/scan_mask_drift.py --lint          # terse (CLI baseline gate)
    python3 tools/scan_mask_drift.py --self-test     # prove the scanner can SEE (#69)
    python3 tools/scan_mask_drift.py <file.rs ...>   # just these files

Suppress a verified false positive at the source, on the live line:

    Flags &= !0x3F;  // nolint: mask-drift (MEM_EXECUTE_OPTION_VALID_FLAGS is 0x3F)

Output is line-number-free (`<file>: <TARGET> &= ~<NAME> [KIND]`) so unrelated
edits never churn the baseline — only a genuinely new or changed mask does.
"""

from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RUST_ROOT = REPO / "sdk" / "lib" / "rust"

sys.path.insert(0, str(REPO / "tools" / "rustconv"))

SKIP_FILE_RE = re.compile(r"(bindgen_[a-z0-9_]+\.rs$|/target/|/\.responses/)")
GENERATED_RE = re.compile(r"automatically generated by rust-bindgen|@generated")

# Cheap byte prefilter: no `& ~` anywhere means no commented-C mask to check.
# Cuts the sweep from 3063 files to ~278 before any parsing happens.
PREFILTER_RE = re.compile(rb"&=?\s*~")

NOLINT_RE = re.compile(r"\bnolint\b\s*[:(\[]?\s*([a-z0-9_-]*)", re.I)
NOLINT_IDS = {"", "all", "mask-drift", "mask_drift", "scan_mask_drift"}

# `TARGET &= ~EXPR` / `TARGET & ~EXPR` in C, and the Rust `!` equivalent. TARGET
# is whatever identifier abuts the `&`, which for `p->Flags` or `(*p).Flags` is
# the member — the same token on both sides, without parsing member access.
# Compared case-INSENSITIVELY: translation routinely re-cases a local (the C's
# `Cr4` is `cr4` in the Rust), and nothing in this tree gives one scope two
# variables differing only in case.
C_MASK_RE = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s*&=?\s*~\s*(\(?[^;{}]*)")
RS_MASK_RE = re.compile(r"([A-Za-z_][A-Za-z0-9_]*)\s*&=?\s*!\s*(\(?[^;{}]*)")

# An UPPER_SNAKE token is a constant name; `0x300`, `as ULONG`, `sizeof` are not.
CONST_NAME_RE = re.compile(r"\b([A-Z][A-Z0-9_]{2,})\b")
CAST_KW = {
    "ULONG",
    "USHORT",
    "UCHAR",
    "ULONGLONG",
    "ULONG_PTR",
    "SIZE_T",
    "DWORD",
    "ACCESS_MASK",
    "UINT",
    "INT",
    "LONG",
    "WORD",
    "BYTE",
    "ULONG64",
    "ULONG32",
}

# `const NAME: T = <expr>;` in the same file — the first place to resolve a name.
IN_FILE_CONST_RE = re.compile(
    r"^\s*(?:pub\s*(?:\([^)]*\)\s*)?)?(?:const|static)\s+([A-Z_][A-Z0-9_]*)\s*:\s*[^=]+=\s*([^;]+);"
)
LITERAL_RE = re.compile(r"^[\s()0-9a-fA-FxX_|<>+*&~ulUL]*$")

MASK32 = 0xFFFFFFFF


def suppressed(line_text: str) -> bool:
    m = NOLINT_RE.search(line_text)
    return m is not None and m.group(1).lower() in NOLINT_IDS


_STOP_2CH = {"==", "!=", "&&", "||", "<=", ">="}


def trim_operand(s: str) -> str:
    """Cut a `~`/`!` operand at the end of the mask expression.

    `0x12F2u32) != 0 {` -> `0x12F2u32`. Without this the whole tail of the
    enclosing `if` rides along, which both invents constant names out of the
    trailing prose and makes the literal unparseable — the real
    `OBJ_VALID_KERNEL_ATTRIBUTES` bug reported DROPPED instead of MISMATCH
    because its literal sat inside `if (... & !0x12F2u32) != 0 {`.
    """
    depth = 0
    i = 0
    while i < len(s):
        c = s[i]
        pair = s[i : i + 2]
        if pair in _STOP_2CH:
            break
        if c == "(":
            depth += 1
        elif c == ")":
            if depth == 0:
                break
            depth -= 1
        elif c == ",":
            break
        elif c in "<>":
            if pair not in ("<<", ">>"):
                break
            i += 1
        i += 1
    return s[:i]


def mask_names(operand: str) -> set[str]:
    """Constant names inside a `~`/`!` operand, minus cast keywords.

    `(NAME as ULONG)` -> {NAME}; `(A | B)` -> {A, B}; `0x300u32` -> set().
    """
    return {n for n in CONST_NAME_RE.findall(operand) if n not in CAST_KW}


_AST_BINOPS = (
    ast.BitOr,
    ast.BitAnd,
    ast.BitXor,
    ast.LShift,
    ast.RShift,
    ast.Add,
    ast.Sub,
    ast.Mult,
)
_AST_UNARYOPS = (ast.Invert, ast.USub)


def _fold(node) -> int | None:
    """Constant-fold an `ast` node, refusing anything that isn't int arithmetic.

    `ast` rather than `eval`: this parses attacker-irrelevant but ARBITRARY
    source out of the tree, and a scanner that can execute what it scans is a
    scanner nobody can run in CI.
    """
    if isinstance(node, ast.Expression):
        return _fold(node.body)
    if isinstance(node, ast.Constant):
        return node.value if isinstance(node.value, int) else None
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, _AST_UNARYOPS):
        v = _fold(node.operand)
        return None if v is None else (~v if isinstance(node.op, ast.Invert) else -v)
    if isinstance(node, ast.BinOp) and isinstance(node.op, _AST_BINOPS):
        lhs, rhs = _fold(node.left), _fold(node.right)
        if lhs is None or rhs is None:
            return None
        if isinstance(node.op, ast.BitOr):
            return lhs | rhs
        if isinstance(node.op, ast.BitAnd):
            return lhs & rhs
        if isinstance(node.op, ast.BitXor):
            return lhs ^ rhs
        if isinstance(node.op, ast.LShift):
            return lhs << rhs if 0 <= rhs < 128 else None
        if isinstance(node.op, ast.RShift):
            return lhs >> rhs if 0 <= rhs < 128 else None
        if isinstance(node.op, ast.Add):
            return lhs + rhs
        if isinstance(node.op, ast.Sub):
            return lhs - rhs
        return lhs * rhs
    return None


def eval_const(expr: str) -> int | None:
    """Value of a constant RHS made only of literals and bitwise operators.

    Deliberately narrow: `0x7F2 | 0x10000` and `1 << 3` resolve, anything
    naming another constant does not. Guessing here would turn a scanner that
    proves things into one that asserts them (§9.113b's lesson).
    """
    s = expr.strip()
    s = re.sub(r"\bas\s+[\w:]+", "", s)
    s = re.sub(
        r"\b(0[xX][0-9a-fA-F_]+|\d[\d_]*)(u8|u16|u32|u64|usize|i8|i16|i32|i64|isize)?\b",
        lambda m: m.group(1).replace("_", ""),
        s,
    )
    s = s.replace("!", "~")  # Rust spells bitwise NOT `!`; Python spells it `~`
    if not LITERAL_RE.match(s) or not re.search(r"\d", s):
        return None
    try:
        return _fold(ast.parse(s.strip(), mode="eval"))
    except SyntaxError:
        return None


def in_file_consts(text: str) -> dict[str, int]:
    out: dict[str, int] = {}
    for line in text.splitlines():
        m = IN_FILE_CONST_RE.match(line)
        if not m:
            continue
        val = eval_const(m.group(2))
        if val is not None:
            out.setdefault(m.group(1), val)
    return out


_CATALOG: dict[str, int] | None = None


def catalog() -> dict[str, int]:
    """The C header catalog verify_constants curates. Loaded once, lazily —
    a run whose files hold no resolvable literal never pays for it."""
    global _CATALOG
    if _CATALOG is None:
        try:
            from rustconv.verify_constants import build_c_catalog

            _CATALOG = build_c_catalog()
        except Exception:
            _CATALOG = {}
    return _CATALOG


def resolve(name: str, local: dict[str, int]) -> int | None:
    if name in local:
        return local[name]
    return catalog().get(name)


# ── comment / code split ─────────────────────────────────────────────
def split_comments(src: bytes) -> tuple[str, list[str]]:
    """(live_code_text, comment_lines) with comments blanked out of the code.

    tree-sitter, not a line test: `//` inside a string literal is not a comment,
    a `/* */` spans lines, and the whole premise here is that the two regions
    are told apart correctly.
    """
    import tree_sitter_rust as tsr
    from tree_sitter import Language, Parser, Query, QueryCursor

    global _PARSER, _QUERY
    if _PARSER is None:
        lang = Language(tsr.language())
        _PARSER = Parser(lang)
        _QUERY = Query(lang, "(line_comment) @c (block_comment) @c")

    root = _PARSER.parse(src).root_node
    nodes = sorted(QueryCursor(_QUERY).captures(root).get("c", []), key=lambda n: n.start_byte)

    buf = bytearray(src)
    comments = []
    for n in nodes:
        comments.append(src[n.start_byte : n.end_byte].decode("utf8", "replace"))
        for i in range(n.start_byte, n.end_byte):
            if buf[i] != 0x0A:
                buf[i] = 0x20
    return buf.decode("utf8", "replace"), comments


_PARSER = None
_QUERY = None

# `let [mut] NAME [: T] =` — the binding a masked value flows into.
LET_RE = re.compile(r"\blet\s+(?:mut\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*(?::[^=;]+)?=")

_STMT_SPLIT_RE = re.compile(r"[;{}]")


def statements(live: str) -> list[tuple[str, int, int]]:
    """[(statement_text, first_line, last_line)] — 0-based, `;`/brace delimited.

    Crude on purpose. It only has to keep a `let` binding together with the
    mask expression it binds, which no Rust construct splits across a `;`.
    """
    out = []
    pos = 0
    line = 0
    for m in _STMT_SPLIT_RE.finditer(live):
        chunk = live[pos : m.start()]
        end = line + chunk.count("\n")
        if chunk.strip():
            out.append((chunk, line, end))
        pos = m.end()
        line = end + live[m.start() : m.end()].count("\n")
    tail = live[pos:]
    if tail.strip():
        out.append((tail, line, line + tail.count("\n")))
    return out


# ── the scan ─────────────────────────────────────────────────────────
def scan_file(path: Path, rel: str) -> list[tuple[str, str, str, str]]:
    """[(rel, target, name, kind)] for one file."""
    src = path.read_bytes()
    if not PREFILTER_RE.search(src):
        return []
    text = src.decode("utf8", "replace")
    if GENERATED_RE.search(text[:800]):
        return []

    live, comments = split_comments(src)

    # C side: lowercased TARGET -> {NAME: count}, plus the C's own casing to report.
    c_masks: dict[str, dict[str, int]] = {}
    as_written: dict[str, str] = {}
    for c in comments:
        for target, operand in C_MASK_RE.findall(c):
            key = target.lower()
            for name in mask_names(trim_operand(operand)):
                as_written.setdefault(key, target)
                c_masks.setdefault(key, {})
                c_masks[key][name] = c_masks[key].get(name, 0) + 1
    if not c_masks:
        return []

    # Live side: TARGET -> (names masked, literal values masked).
    #
    # By STATEMENT, not by line: rustfmt wraps `let mut DesiredAccess =\n
    # DesiredAccess & !KEY_WOW64_RES;` freely, and a line-based read of that
    # sees a binding with no mask followed by a mask with no binding.
    live_names: dict[str, dict[str, int]] = {}
    live_lits: dict[str, list[int]] = {}
    suppressed_targets: set[str] = set()
    nolint_lines = {i for i, ln in enumerate(text.splitlines()) if suppressed(ln)}

    for stmt, line0, line1 in statements(live):
        hits = RS_MASK_RE.findall(stmt)
        if not hits:
            continue
        # `let mut X = Y & !FLAG` masks X as much as it masks Y — the C it came
        # from wrote `X &= ~FLAG`, and which operand carries the name is a
        # translation artifact. Credit both, so a rebinding is not a false DROPPED.
        bound = {m.group(1).lower() for m in LET_RE.finditer(stmt)}
        if nolint_lines & set(range(line0, line1 + 1)):
            suppressed_targets |= bound | {t.lower() for t, _ in hits}
            continue
        for target, operand in hits:
            operand = trim_operand(operand)
            names = mask_names(operand)
            for t in bound | {target.lower()}:
                if names:
                    d = live_names.setdefault(t, {})
                    for n in names:
                        d[n] = d.get(n, 0) + 1
                else:
                    val = eval_const(operand)
                    if val is not None:
                        live_lits.setdefault(t, []).append(val)

    local = in_file_consts(text)
    out = []
    for target, names in sorted(c_masks.items()):
        if target in suppressed_targets:
            continue
        lits = live_lits.get(target, [])
        masked_live = live_names.get(target, {})
        for name in sorted(names):
            if not lits:
                # No literal to compare. Only a target the live code never masks
                # AT ALL is worth reporting; a partial count is not evidence —
                # OCCURRENCES ARE NOT COUNTED, deliberately. The C block repeats
                # a statement per call site, rustfmt merges paths, and an
                # explanatory comment that QUOTES the C (as several fixes here
                # do) reads as another C occurrence. Every count-based rule this
                # started with reported those as drops.
                if not masked_live:
                    out.append((rel, as_written[target], name, "DROPPED"))
                continue
            # A literal masks this target where the C used a name. Compare — but
            # only when the C is unambiguous about which constant that is;
            # `Flags &= ~A` plus `Flags &= ~B` gives no way to say which one the
            # literal stands for, and guessing invents mismatches.
            if len(names) > 1:
                continue
            want = resolve(name, local)
            if want is None:
                out.append((rel, as_written[target], name, "OPENCODED"))
            elif not any((lit & MASK32) == (want & MASK32) for lit in lits):
                out.append((rel, as_written[target], name, "MISMATCH"))
    return out


def rust_files() -> list[Path]:
    return [p for p in sorted(RUST_ROOT.rglob("*.rs")) if not SKIP_FILE_RE.search(str(p))]


# ── self-test: prove the scanner can see (#69) ───────────────────────
# Each case is a whole synthetic file. The first two are the E21 and
# KeFlushCurrentTb bugs reduced to their shape; the rest are the false positives
# that a naive version of this scanner reported, kept as regressions so a future
# widening of the regexes has to stay quiet on them.
SELF_TEST = [
    (
        "E21: literal masks half the named constant",
        """
const KEY_WOW64_RES: ACCESS_MASK = 0x00000300;
pub fn NtOpenKey(DesiredAccess: u32) -> u32 {
    let mut DesiredAccess = DesiredAccess & !0x0100u32;
    DesiredAccess
}
//     DesiredAccess &= ~KEY_WOW64_RES;
""",
        ["MISMATCH"],
    ),
    (
        "E21 rustfmt-wrapped: the binding and its mask are on different LINES",
        """
const KEY_WOW64_RES: ACCESS_MASK = 0x00000300;
pub fn NtOpenKey(Access: u32) -> u32 {
    let mut DesiredAccess =
        Access & !0x0100u32;
    DesiredAccess
}
//     DesiredAccess &= ~KEY_WOW64_RES;
""",
        ["MISMATCH"],
    ),
    (
        "the C's mask is INSIDE a commented-out block that the Rust kept as code",
        """
const KEY_WOW64_RES: ACCESS_MASK = 0x00000300;
pub fn NtCreateKey(DesiredAccess: u32) -> u32 {
    let mut DesiredAccess = DesiredAccess;
    DesiredAccess &= !KEY_WOW64_RES;
    DesiredAccess
}
//     DesiredAccess &= ~KEY_WOW64_RES;
""",
        [],
    ),
    (
        "KeFlushCurrentTb: the whole masking branch is gone",
        """
pub fn KeFlushCurrentTb() { let cr3 = read_cr3(); write_cr3(cr3); }
//     Cr4 = __readcr4();
//     __writecr4(Cr4 &~ CR4_PGE);
""",
        ["DROPPED"],
    ),
    (
        "correct: translation re-cased the local (C `Cr4` -> Rust `cr4`)",
        """
pub fn KeFlushCurrentTb() {
    let cr4: ULONG = readcr4();
    writecr4(cr4 & !CR4_PGE);
}
//     Cr4 = __readcr4();
//     __writecr4(Cr4 &~ CR4_PGE);
""",
        [],
    ),
    (
        "correct: live masks the same name through an `as` cast",
        """
pub fn f(dc: &mut DC) { dc.flags &= !(DC_DIRTY_RAO as ULONG); }
//     pdc->flags &= ~DC_DIRTY_RAO;
""",
        [],
    ),
    (
        "correct: open-coded literal that matches the in-file constant",
        """
const MEM_EXECUTE_OPTION_VALID_FLAGS: u32 = 0x3F;
pub fn f(x: u32) -> u32 { let Options = x & !0x3F; Options }
//     Options &= ~MEM_EXECUTE_OPTION_VALID_FLAGS;
""",
        [],
    ),
    (
        "correct: `~` on a bare literal names nothing to check",
        """
pub fn f(x: u32) -> u32 { x & !0xFFF }
//     Address &= ~0xFFF;
""",
        [],
    ),
    (
        "correct: a nolint on the live line suppresses",
        """
pub fn f(x: u32) -> u32 { let Flags = x & !0x3F; Flags } // nolint: mask-drift (checked)
//     Flags &= ~SOME_UNRESOLVABLE_NAME;
""",
        [],
    ),
    (
        "different target: masking Foo does not excuse dropping Bar's mask",
        """
pub fn f(a: u32, b: u32) { let Foo = a & !(REAL_FLAG as ULONG); let _ = Foo; let _ = b; }
//     Foo &= ~REAL_FLAG;
//     Bar &= ~OTHER_FLAG;
""",
        ["DROPPED"],
    ),
]


def self_test() -> int:
    import tempfile

    bad = 0
    with tempfile.TemporaryDirectory() as td:
        for i, (label, body, want) in enumerate(SELF_TEST):
            p = Path(td) / f"case{i}.rs"
            p.write_text(body)
            got = sorted(k for _, _, _, k in scan_file(p, f"case{i}.rs"))
            if got != sorted(want):
                bad += 1
                print(f"FAIL  {label}\n      want {sorted(want)}, got {got}")
            else:
                print(f"ok    {label}")
    print(f"\n{len(SELF_TEST) - bad}/{len(SELF_TEST)} self-test cases pass")
    if bad:
        print("the scanner does not detect what it claims to — fix it before trusting a green run")
    return 1 if bad else 0


def main() -> int:
    argv = [a for a in sys.argv[1:] if not a.startswith("--")]
    lint = "--lint" in sys.argv
    if "--self-test" in sys.argv:
        return self_test()

    paths = [Path(a) for a in argv] if argv else rust_files()
    hits = []
    for p in paths:
        try:
            rel = str(p.resolve().relative_to(REPO))
        except ValueError:
            rel = str(p)
        try:
            hits.extend(scan_file(p, rel))
        except OSError:
            continue

    hits = sorted(set(hits))
    for rel, target, name, kind in hits:
        print(f"{rel}: {target} &= ~{name} [{kind}]")

    if not lint:
        by_kind: dict[str, int] = {}
        for _, _, _, k in hits:
            by_kind[k] = by_kind.get(k, 0) + 1
        summary = ", ".join(f"{v} {k}" for k, v in sorted(by_kind.items())) or "none"
        print(f"\n{len(hits)} mask(s) the C clears that the live Rust does not: {summary}")
        if hits:
            print(
                "MISMATCH is a value bug or a moved C; OPENCODED wants the name back so it\n"
                "cannot drift again; DROPPED means the mask (or its branch) did not survive.\n"
                "fix: restore the named mask; suppress a verified FP on the live line with\n"
                "     // nolint: mask-drift (reason)"
            )
    return 1 if hits else 0


if __name__ == "__main__":
    sys.exit(main())
