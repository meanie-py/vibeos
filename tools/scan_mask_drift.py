def self_test() -> int:
    import tempfile

    bad = 0
    with tempfile.TemporaryDirectory() as td:
        for i, (label, body, want) in enumerate(SELF_TEST):
            p = Path(td) / f"case{i}.rs"
            p.write_text(body)
            got = sorted(h[4] for h in scan_file(p, f"case{i}.rs"))
            if got != sorted(want):
                bad += 1
                print(f"FAIL  {label}\n      want {sorted(want)}, got {got}")
            else:
                print(f"ok    {label}")
    print(f"\n{len(SELF_TEST) - bad}/{len(SELF_TEST)} self-test cases pass")
    if bad:
        print("the scanner does not detect what it claims to — fix it before trusting a green run")
    return 1 if bad else 0


def main() -> int:
    argv = [a for a in sys.argv[1:] if not a.startswith("--")]
    lint = "--lint" in sys.argv
    if "--self-test" in sys.argv:
        return self_test()

    paths = [Path(a) for a in argv] if argv else rust_files()
    hits = []
    for p in paths:
        try:
            rel = str(p.resolve().relative_to(REPO))
        except ValueError:
            rel = str(p)
        try:
            hits.extend(scan_file(p, rel))
        except OSError:
            continue

    hits = sorted(set(hits))
    for rel, target, op, name, kind, detail in hits:
        # The baselined (`--lint`) line is line-number- AND value-free, so an
        # unrelated edit never churns it. The full report carries the values,
        # because a MISMATCH without them makes every reader re-derive both.
        suffix = f"  ({detail})" if detail and not lint else ""
        print(f"{rel}: {target} {op}{name} [{kind}]{suffix}")

    if not lint:
        by_kind: dict[str, int] = {}
        for *_, k, _d in hits:
            by_kind[k] = by_kind.get(k, 0) + 1
        summary = ", ".join(f"{v} {k}" for k, v in sorted(by_kind.items())) or "none"
        print(f"\n{len(hits)} bit-flag(s) whose live Rust contradicts its own C: {summary}")
        if hits:
            print(
                "MISMATCH is a value bug or a moved C; OPENCODED wants the name back so it\n"
                "cannot drift again; DROPPED means the mask (or its branch) did not survive.\n"
                "fix: restore the named mask; suppress a verified FP on the live line with\n"
                "     // nolint: mask-drift (reason)"
            )
    return 1 if hits else 0


if __name__ == "__main__":
    sys.exit(main())
