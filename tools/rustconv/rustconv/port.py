def _seed_item_bank(stem: str, macros: dict, thinking: str, item_path) -> None:
    """Split replies banked whole (before the per-item bank) into items, when still valid.

    A whole-set reply counts only if its key is the one the CURRENT rules and definitions
    give that set -- the same test that made it replay before.
    """
    for old in sorted((STATE_ROOT / stem).glob("macros-*.json")):
        try:
            data = json.loads(old.read_text())
            names = set(data["macros"])
        except (OSError, ValueError, KeyError):
            continue
        if not names <= set(macros) or old.stem.startswith("macros-reply-"):
            continue
        subset = {n: macros[n] for n in names}
        if old.stem not in (
            f"macros-{local_macros.key(subset, thinking)}",
            f"macros-{local_macros.legacy_key(subset, thinking)}",
        ):
            continue
        try:
            items = local_macros.parse_reply(data["reply"], names)
        except ValueError:
            continue
        for name, item in items.items():
            if not item_path(name).is_file():
                item_path(name).write_text(item)


def _drop_invented_macro_consts(modules: Path, defs: dict) -> set[str]:
    """Function-like C macros a module re-made as a `const`, removed; returns their names.

    The C has only `#define PIIX_REG_UDMATIM(Channel) (0x4A + (Channel))`, yet intel.rs came
    back with `pub const PIIX_REG_UDMATIM: u8 = 0x4A;` -- the value for channel 0, invented --
    beside calls `PIIX_REG_UDMATIM(Channel)`. The name then resolves, so it is not among the
    names this stage ports, and the calls fail as E0618 forever. A `const` of a name the C
    defines ONLY with parameters is never right; the macro port replaces it.
    """
    dropped: set[str] = set()
    for rs in sorted(modules.glob("*.rs")):
        text = rs.read_text()
        new = text
        for m in list(_CONST_ITEM.finditer(text)):
            name = m.group("name")
            d = defs.get(name)
            if d is None or d.params is None or d.kind != "macro":
                continue
            if not re.search(rf"\b{re.escape(name)}\s*\(", text):
                continue
            new = new.replace(m.group(0), "", 1)
            dropped.add(name)
        if new != text:
            rs.write_text(new)
            print(f"macros: {rs.name}: invented const(s) for function-like macros dropped")
    return dropped


_CONST_ITEM = re.compile(
    r"(?m)^(?:pub(?:\([^)]*\))?\s+)?const\s+(?P<name>[A-Za-z_]\w*)\s*:[^=;]+=[^;]*;[^\n]*\n"
)


def _sdk_macros(state: dict, crate: Path, prelude: Path, unresolved: set[str]) -> None:
    """SDK header macros the crate CALLS, lowered from the TUs' own preprocessor ($0).

    See sdk_macros.py. A name rustc cannot resolve and the crate spells as a call
    (`PropSheet_Changed(..)` or `PropSheet_Changed!(..)`) is offered; one the preprocessor
    says is not a function-like macro is simply not lowered, and what the lowering refuses is
    listed for a hand port.
    """
    from . import sdk_macros

    sources = "\n".join(
        rs.read_text(errors="replace") for rs in (crate / "src" / state["stem"]).glob("*.rs")
    )
    called = {n for n in unresolved if re.search(rf"\b{re.escape(n)}\s*!?\s*\(", sources)}
    wanted = called | sdk_macros.existing(prelude)
    kinds = prelude_resolve.unresolved(
        state["crate"],
        RUST_TARGETS["amd64"],
        REPO / "sdk" / "lib" / "rust",
        STATE_ROOT / state["stem"] / "target-amd64",
    )
    had = sdk_macros.existing_items(prelude)
    want_types = {n for n, ns in kinds.items() if "type" in ns} | had["type"]
    want_values = {n for n, ns in kinds.items() if ns == {"value"}} - called | had["value"]
    hand = local_macros.hand_ported(prelude) - sdk_macros.existing(prelude)
    hand -= had["type"] | had["value"] | had["fn"]
    # ...but a name ALSO defined outside every generated block stays hand-owned: the
    # scaffold's `pub const NULL` once landed in this block too (mmsys, E0428), and then
    # subtracting the block's own names above handed NULL back to the lowering.
    hand |= sdk_macros.outside_block_names(prelude)
    # A name another GENERATED block now owns (resolve's facts) is dropped from this one.
    hand |= sdk_macros.outside_sdk_block_names(prelude)
    # A name a SHARED crate provides (win32macros-rust's LOWORD/MAKELONG/UlongToPtr) is never
    # lowered per crate: a local copy makes `refresh_shared_crates` drop the shared re-export,
    # and the duplicate then perpetuates itself on every replay.
    hand |= set().union(*prelude_resolve.shared_provides(REPO / "sdk" / "lib" / "rust").values())
    wanted -= hand
    tus = [REPO / t for t in state["tus"]]
    com = sdk_macros.com_wrappers(crate / "src", (called | had["fn"]) - hand)
    wanted -= set(com)
    lowered, refused = sdk_macros.lower_for_crate(REPO, tus, crate / "src", wanted)
    items, item_refused = sdk_macros.object_items(
        REPO, tus, crate / "src", want_values - hand, want_types - hand
    )
    items.update(com)
    refused.update(item_refused)
    if sdk_macros.write_block(prelude, sdk_macros.render_block(lowered, items)):
        print(
            f"macros: {len(lowered)} SDK header macro(s) and {len(items)} type/pointer "
            f"constant(s) lowered ($0): {', '.join(sorted({*lowered, *items}))}"
        )
    pasting = {n for n, why in refused.items() if why.startswith("token pasting")}
    widen = sdk_macros.widening_macros(REPO, tus, pasting)
    for rs in _unit_files(crate, state["stem"]):
        text = rs.read_text()
        new, n = sdk_macros.widen_call_sites(text, widen)
        if n:
            rs.write_text(new)
            print(f"macros: {rs.stem}: {n} TEXT-style literal(s) widened to UTF-16 ($0)")
    for name in widen:
        refused.pop(name, None)
    for name, why in sorted(refused.items()):
        print(f"macros: SDK macro {name} NOT lowered, hand-port it: {why}")


def _without_token_pasting(macros: dict) -> tuple[dict, list[str]]:
    """Drop every macro that pastes with `##`, and every macro that reaches one.

    `##` builds an identifier from an argument, which a macro_rules! cannot do on stable.
    Sent to the model anyway, imm32's `CS_StrA(pCS, Name) ... (pCS)->dw##Name##Offset` came
    back reading `(*pCS).Name` -- a field that does not exist, and with another argument one
    that does and is the wrong one. These are hand ports; their callers stay errors until
    they are written.
    """
    # `, ##__VA_ARGS__` is GNU's comma swallow, not pasting: it builds no identifier, and
    # macro_rules! spells it `$(, $a:expr)*`. cmd's ConOutPrintf/ConErrResPrintf family
    # (~140 call sites) is nothing else, and was refused as a hand port.
    pasting = {n for n, m in macros.items() if "##" in re.sub(r",\s*##\s*__VA_ARGS__", "", m.body)}
    while True:
        reach = {
            n
            for n, m in macros.items()
            if n not in pasting and any(re.search(rf"\b{q}\b", m.body) for q in pasting)
        }
        if not reach:
            break
        pasting |= reach
    return {n: m for n, m in macros.items() if n not in pasting}, sorted(pasting)


def stage_macros(
    stem: str, *, model: str, cost_cap: float, dry_run: bool, thinking: str = "on"
) -> None:
    """Port the module's own function-like C macros the crate calls (local_macros.py)."""
    state = load_state(stem)
    started = time.time()
    crate = _crate_dir(state)
    prelude = crate / "src" / "prelude.rs"
    module_dir = REPO / state["module_dir"]
    files = _module_sources(module_dir)
    defs, ambiguous = local_macros.module_macros(files, REPO)
    # Functions the module's HEADERS define inline: a macro of the same name wins.
    # A cppapp module's header functions are class members, rendered and translated by
    # cpp_app: read as C they become a free `audio_membuffer(this)` shadowing the class.
    if not state.get("cppapp"):
        for name, fn in local_macros.header_functions(_module_headers(module_dir), REPO).items():
            defs.setdefault(name, fn)
    names = prelude_resolve.unresolved_names(
        state["crate"],
        RUST_TARGETS["amd64"],
        REPO / "sdk" / "lib" / "rust",
        STATE_ROOT / stem / "target-amd64",
    )
    # An object-like macro is ported only where the crate CALLS it (`SpInfFindFirstLine(..)`);
    # used as a plain value it is a constant, which is resolve's business.
    called = {
        n
        for n in names & set(defs)
        if defs[n].params is not None
        or defs[n].kind == "fn"
        or any(
            re.search(rf"\b{re.escape(n)}\s*\(", rs.read_text(errors="replace"))
            for rs in (crate / "src" / stem).glob("*.rs")
        )
    }
    called |= _drop_invented_macro_consts(crate / "src" / stem, defs)
    _sdk_macros(state, crate, prelude, names - set(defs))
    wanted = called | local_macros.existing(prelude)
    hand = local_macros.hand_ported(prelude)
    macros = {n: m for n, m in local_macros.closure(wanted, defs).items() if n not in hand}
    skipped = sorted(names & ambiguous)
    if skipped:
        print(f"macros: defined differently in two places, hand-port: {', '.join(skipped)}")
    macros, pasting = _without_token_pasting(macros)
    if pasting:
        print(f"macros: token-pasting (##), hand-port above the block: {', '.join(pasting)}")
    if not macros:
        print("macros: nothing to port")
        _record(state, "macros", started, ported=0, usd=0.0)
        return
    # Banked PER ITEM (by its definition, the prompt rules and the thinking mode), so a
    # macro added later buys only itself rather than re-buying the whole set.
    item_dir = STATE_ROOT / stem / "macros"
    item_dir.mkdir(parents=True, exist_ok=True)

    def item_path(name: str) -> Path:
        return item_dir / f"{name}-{local_macros.key({name: macros[name]}, thinking)}.rs"

    _seed_item_bank(stem, macros, thinking, item_path)
    ported = {n: item_path(n).read_text() for n in macros if item_path(n).is_file()}
    todo = {n: m for n, m in macros.items() if n not in ported}
    usd = 0.0
    if not todo:
        print(f"macros: {len(macros)} item(s) replayed from the bank ($0)")
    else:
        text = local_macros.prompt(todo, local_macros.in_scope_macros(prelude) | set(ported))
        print(f"macros: {len(todo)} to port ({len(ported)} banked): {', '.join(sorted(todo))}")
        if dry_run:
            print(text)
            return
        from .__main__ import MODEL_ALIASES
        from .batch_runner import submit_single
        from .config import DEEPSEEK_MAX_TOKENS, MODEL_PRICING, cost_usd

        api_model = MODEL_ALIASES.get(model, model)
        pin, pout = MODEL_PRICING[api_model]
        # Worst case: every output token the request may use (reasoning counts).
        out_max = DEEPSEEK_MAX_TOKENS if thinking == "on" else 16000
        ceiling = (len(text) / 2 * pin + out_max * pout) / 1e6
        if ceiling > cost_cap:
            raise PortError(f"macros: worst case ${ceiling:.3f} exceeds --cost-cap ${cost_cap:.2f}")
        # Thinking ON by default, unlike bodies: a macro gets none of the per-function audits
        # (seals, placement, c2rust anchor), and 22 of them cost cents. The thinking-off
        # reply for setuplib compiled `VersionInfo32_Children` as a pointer `.wrapping_add`
        # that scales by the struct size where the C adds BYTES as an integer.
        os.environ["RUSTCONV_DEEPSEEK_THINKING"] = "enabled" if thinking == "on" else "disabled"
        res = submit_single(text, model=api_model, system_prompt=local_macros.SYSTEM)
        usd = cost_usd(api_model, res.input_tokens, res.output_tokens, res.cache_read_tokens)
        if not res.success:
            raise PortError(f"macros: model call failed: {res.error}")
        raw = STATE_ROOT / stem / f"macros-reply-{int(time.time())}.json"
        raw.write_text(json.dumps({"macros": sorted(todo), "reply": res.rust_code, "usd": usd}))
        try:
            fresh = local_macros.parse_reply(res.rust_code, set(todo))
        except ValueError as e:
            raise PortError(f"macros: reply rejected ({e}); banked reply: {raw}") from e
        for name, item in fresh.items():
            item_path(name).write_text(item)
        ported.update(fresh)
        print(f"macros: bought for ${usd:.4f}, reply kept in {raw}")
    # A reply calls a macro the prompt did not list as in scope -- one the prelude gained
    # later -- as a function: pata.h's NUM_TO_BITMAP came back as `RTL_BITS_OF(ULONG)` (46
    # errors in pciidex). The banked text stays as bought; the `!` is applied on every render,
    # the same rewrite integrate gives the module bodies.
    from .crate_integrate import fix_macro_calls

    rust_macros = local_macros.in_scope_macros(prelude) | {
        n for n in ported if macros[n].kind == "macro"
    }
    ported = {
        n: fix_macro_calls(text, rust_macros, {n} if macros[n].kind == "fn" else set())[0]
        for n, text in ported.items()
    }
    changed = local_macros.write_block(prelude, local_macros.render(ported, macros))
    _record(state, "macros", started, ported=len(ported), usd=round(usd, 4), changed=changed)
    print(f"macros: {len(ported)} in the prelude; run `port integrate {stem}` to fix call sites")


