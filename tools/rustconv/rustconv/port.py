def _crate_dir(state: dict) -> Path:
    return REPO / "sdk" / "lib" / "rust" / state["crate"]


def stage_island(stem: str) -> None:
    state = load_state(stem)
    started = time.time()
    env = dict(os.environ, OUT_CRATE_DIR=str(_crate_dir(state) / "src"))
    proc = subprocess.run(
        ["bash", str(GEN), stem], cwd=REPO, env=env, capture_output=True, text=True
    )
    log = STATE_ROOT / stem / "island.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    log.write_text(proc.stdout + proc.stderr)
    islands = sorted(p.name for p in (_crate_dir(state) / "src").glob("types_*.rs"))
    _record(state, "island", started, rc=proc.returncode, islands=islands)
    if proc.returncode != 0:
        tail = "\n".join((proc.stdout + proc.stderr).splitlines()[-15:])
        raise PortError(
            f"gen_driver_types.sh {stem} failed (rc {proc.returncode}); log {log}\n{tail}"
        )
    print(f"island: {', '.join(islands)}")


def stage_scaffold(module_dir: Path, target: str | None) -> None:
    started = time.time()
    dp = derive(module_dir, target)
    state = load_state(dp.module.crate_stem)
    kept: list[Path] = []
    written = pd.scaffold_crate(dp, _crate_dir(state), force=False, kept=kept)
    member = add_workspace_member(state["crate"])
    _record(state, "scaffold", started, written=len(written), kept=len(kept), member_added=member)
    print(
        f"scaffold: {len(written)} file(s) written, {len(kept)} kept, into {_crate_dir(state)}"
        f"{'; workspace member added' if member else ''}"
    )


def add_workspace_member(crate: str) -> bool:
    """`cargo check -p` (and crate-repair) need the crate in the workspace. A red member must
    not LAND -- the flip lands only once it is green on all three arches -- but it has to be
    a member while it is being worked on."""
    manifest = REPO / "sdk" / "lib" / "rust" / "Cargo.toml"
    text = manifest.read_text()
    m = re.search(r"^members = \[\n(.*?)^\]", text, re.M | re.S)
    if not m:
        raise PortError(f"{manifest}: no `members = [ ... ]` block")
    if re.search(rf'^\s*"{re.escape(crate)}",?\s*$', m.group(1), re.M):
        return False
    manifest.write_text(text[: m.end(1)] + f'    "{crate}",\n' + text[m.end(1) :])
    return True


