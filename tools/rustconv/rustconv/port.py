def _arch_only_tus(state: dict, tus: list[str]) -> dict[str, str]:
    """TUs the CMakeLists compiles only on some arches, mapped to one that compiles them.

    translate resolves a TU's CMake owner at its --arch (arm64 by default), and pciidex's
    `if(ARCH STREQUAL "i386") list(APPEND SOURCE chipset/pata_legacy.c)` has no owner
    there. Every other TU keeps the default, so nothing already banked changes key.
    """
    out: dict[str, str] = {}
    module_dir = REPO / state["module_dir"]
    per_arch: dict[str, set[str]] = {}
    for arch in ("arm64", "amd64", "i386"):
        try:
            dp = pd.derive(module_dir, REPO, arch=arch, target=state.get("target"))
        except Exception:  # an arch that cannot derive owns nothing
            per_arch[arch] = set()
            continue
        per_arch[arch] = {str(p.relative_to(REPO)) for p in dp.module.compiled_tus}
    for tu in tus:
        if tu in per_arch["arm64"]:
            continue
        owner = next((a for a in ("amd64", "i386") if tu in per_arch[a]), None)
        if owner:
            out[tu] = owner
    return out


def _target_args(state: dict) -> list[str]:
    """translate's --target for this module.

    A user-mode module goes through the `name:dir` form, which builds a user-DLL target on
    the ntdll-sys substrate. A kernel module must not: that path cannot read ntkrnl-sys
    (it has two umbrellas, `ddk` and `hal_ddk`) and refused pciidex outright. Kernel
    modules use their registered TARGETS entry, which carries the kernel conventions.
    """
    if state.get("usermode", True):
        return [
            "--target",
            f"{state['stem']}:{state['module_dir']}",
            "--output-crate",
            state["crate"],
        ]
    from .projects.reactos.targets import TARGETS

    known = TARGETS.get(state["stem"])
    if known is None or Path(known.output_crate).name != state["crate"]:
        raise PortError(
            f"{state['stem']} is a kernel module with no TARGETS entry writing "
            f"{state['crate']}: register one in projects/reactos/targets.py"
        )
    return ["--target", state["stem"]]


def _crate_dir(state: dict) -> Path:
    return REPO / "sdk" / "lib" / "rust" / state["crate"]


def _add_island_headers(dp: pd.DerivedProfile, extra: dict[str, str]) -> None:
    """Headers resolve found a missing TYPE in (state `island_headers`: regex -> why), added
    to every island's allowlist so a re-derive keeps them."""
    for rx, why in sorted(extra.items()):
        if rx not in dp.allow_files:
            dp.allow_files.append(rx)
            dp.allow_reasons[rx] = why
        for isl in dp.islands:
            if rx not in isl.allow_files:
                isl.allow_files.append(rx)


def _type_defined_in(text: str, name: str) -> bool:
    n = re.escape(name)
    return bool(
        re.search(rf"\}}[^;{{}}]*\b{n}\b[^;{{}}]*;", text)
        or re.search(rf"\btypedef\b[^;{{}}]*\b{n}\s*[;,\[)]", text)
        or re.search(rf"\b(?:struct|union|enum)\s+{n}\s*\{{", text)
    )


def _resolve_island_types(state: dict, names: set[str]) -> set[str]:
    """A TYPE the C sees through an SDK header's own includes -- setuplib's MOUNTDEV_NAME, in
    ddk/mountmgr.h, reached via <mountdev.h> -- is outside the derived allowlist by design
    (it follows only the headers the module names). It was a hand step ("add its header to
    the island allowlist"); now: the one closure header that defines it is added to the
    module's arm, recorded in the port state so a re-derive keeps it, and the island is
    regenerated. A name defined in several headers, or in a base platform header the -sys
    crate owns, is reported instead. Returns the names the new island should now provide.
    """
    if not names:
        return set()
    dp = derive(REPO / state["module_dir"], state.get("target"))
    found: dict[str, list[pd.HeaderRef]] = {n: [] for n in names}
    for ref in dp.closure.headers.values():
        try:
            text = ref.path.read_text(errors="replace")
        except OSError:
            continue
        text = re.sub(r"/\*.*?\*/|//[^\n]*", " ", text, flags=re.S)
        for n in names:
            if re.search(rf"\b{re.escape(n)}\b", text) and _type_defined_in(text, n):
                found[n].append(ref)
    extra = dict(state.get("island_headers", {}))
    added: set[str] = set()
    for n, refs in sorted(found.items()):
        if len(refs) != 1:
            if refs:
                where = ", ".join(r.name for r in refs)
                print(f"resolve: type {n} is defined in several headers ({where}); hand-pick")
            continue
        ref = refs[0]
        if ref.kind in ("crt", "toolchain") or ref.name.startswith(("ndk/", "wine/")):
            print(f"resolve: type {n} is in {ref.name}, a base header -- the -sys crate's job")
            continue
        rx = pd._hdr_regex(ref.name)
        if rx in dp.allow_files and rx in extra:
            continue  # already there: the island does not define it for another reason
        extra[rx] = f"defines {n} (resolve: a type the module reaches via {ref.includers[0]})"
        added.add(n)
    if not added:
        return set()
    state["island_headers"] = extra
    _record(state, "island-headers", time.time(), added=sorted(added))
    print(f"resolve: island allowlist += {len(added)} type(s): {', '.join(sorted(added))}")
    stage_derive(REPO / state["module_dir"], state.get("target"))
    stage_island(state["stem"])
    return added


def stage_island(stem: str) -> None:
    state = load_state(stem)
    started = time.time()
    env = dict(os.environ, OUT_CRATE_DIR=str(_crate_dir(state) / "src"))
    proc = subprocess.run(
        ["bash", str(GEN), stem], cwd=REPO, env=env, capture_output=True, text=True
    )
    log = STATE_ROOT / stem / "island.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    log.write_text(proc.stdout + proc.stderr)
    islands = sorted(p.name for p in (_crate_dir(state) / "src").glob("types_*.rs"))
    _record(state, "island", started, rc=proc.returncode, islands=islands)
    if proc.returncode != 0:
        tail = "\n".join((proc.stdout + proc.stderr).splitlines()[-15:])
        raise PortError(
            f"gen_driver_types.sh {stem} failed (rc {proc.returncode}); log {log}\n{tail}"
        )
    print(f"island: {', '.join(islands)}")


def stage_scaffold(module_dir: Path, target: str | None) -> None:
    started = time.time()
    dp = derive(module_dir, target)
    state = load_state(dp.module.crate_stem)
    kept: list[Path] = []
    written = pd.scaffold_crate(dp, _crate_dir(state), force=False, kept=kept)
    member = add_workspace_member(state["crate"])
    _seed_switch_facts(state, _crate_dir(state) / "src" / "prelude.rs")
    _record(state, "scaffold", started, written=len(written), kept=len(kept), member_added=member)
    print(
        f"scaffold: {len(written)} file(s) written, {len(kept)} kept, into {_crate_dir(state)}"
        f"{'; workspace member added' if member else ''}"
    )


def add_workspace_member(crate: str) -> bool:
    """`cargo check -p` (and crate-repair) need the crate in the workspace. A red member must
    not LAND -- the flip lands only once it is green on all three arches -- but it has to be
    a member while it is being worked on."""
    manifest = REPO / "sdk" / "lib" / "rust" / "Cargo.toml"
    text = manifest.read_text()
    m = re.search(r"^members = \[\n(.*?)^\]", text, re.M | re.S)
    if not m:
        raise PortError(f"{manifest}: no `members = [ ... ]` block")
    if re.search(rf'^\s*"{re.escape(crate)}",?\s*$', m.group(1), re.M):
        return False
    manifest.write_text(text[: m.end(1)] + f'    "{crate}",\n' + text[m.end(1) :])
    return True


