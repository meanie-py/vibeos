_C_IDENT = re.compile(r"\b[A-Za-z_]\w*\b")
_ARM_HEAD = re.compile(
    r"^([ \t]*)([A-Za-z_]\w*(?:[ \t]*\|[ \t]*[A-Za-z_]\w*)*)[ \t]*=>[ \t]*", re.M
)


def _dead_only_names(c_text: str) -> set[str]:
    """Identifiers the C names ONLY on lines this tree never compiles."""
    dead = dead_regions.never_compiled_lines(c_text)
    # Comments out, line count kept: `/* prefer native version */` is not an identifier.
    c_text = re.sub(
        r"/\*.*?\*/|//[^\n]*", lambda m: "\n" * m.group(0).count("\n"), c_text, flags=re.S
    )
    c_text = re.sub(r'"(?:[^"\\\n]|\\.)*"', '""', c_text)
    live: set[str] = set()
    gone: set[str] = set()
    for n, line in enumerate(c_text.splitlines(), 1):
        (gone if n in dead else live).update(_C_IDENT.findall(line))
    return gone - live


def _arm_end(text: str, pos: int) -> int | None:
    """End of a match arm's body starting at `pos` (just past `=>`), trailing `,` included.
    A `{ ... }` block or a one-line expression; anything else is left alone."""
    if pos < len(text) and text[pos] == "{":
        depth, i, n = 0, pos, len(text)
        while i < n:
            c = text[i]
            if c == '"':
                i += 1
                while i < n and text[i] != '"':
                    i += 2 if text[i] == "\\" else 1
            elif text.startswith("//", i):
                i = text.find("\n", i)
                if i < 0:
                    return None
                continue
            elif c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    end = i + 1
                    if text[end : end + 1] == ",":
                        end += 1
                    return end
            i += 1
        return None
    eol = text.find("\n", pos)
    line = text[pos : eol if eol >= 0 else len(text)].rstrip()
    if line.endswith(",") and "{" not in line and "}" not in line:
        return pos + len(line)
    return None


def _strip_rust_comments(text: str) -> str:
    return re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)


def _drop_dead_arms(path: Path, c_file: Path) -> list[str]:
    """A `match` arm whose pattern names only constants the C spells in a DEAD region.

    Dead tokens are permitted to the model, never demanded (dead_regions.py), so a body may
    keep a `#ifndef __REACTOS__` case. inetcpl's DllMain came back with
    `DLL_WINE_PREATTACH => return FALSE`: the name is defined nowhere in our tree, so the
    arm is a binding that matches EVERY reason -- DllMain would have refused the load. The
    arm does not exist in any C we compile; it is dropped, and an alternative of a live arm
    loses just the dead name.
    """
    dead = _dead_only_names(c_file.read_text(errors="replace"))
    if not dead:
        return []
    text = path.read_text()
    out: list[str] = []
    pos, dropped = 0, []
    for m in _ARM_HEAD.finditer(text):
        if m.start() < pos:
            continue
        names = [n.strip() for n in m.group(2).split("|")]
        hit = [n for n in names if n in dead]
        if not hit:
            continue
        keep = [n for n in names if n not in dead]
        if keep:
            out.append(text[pos : m.start(2)] + " | ".join(keep))
            pos = m.end(2)
            dropped += hit
            continue
        end = _arm_end(text, m.end())
        if end is None:
            continue
        line_end = text.find("\n", end)
        if text[end : line_end if line_end >= 0 else len(text)].strip() == "":
            end = line_end + 1 if line_end >= 0 else len(text)
        out.append(text[pos : m.start()])
        pos = end
        dropped += hit
    if not dropped:
        return []
    out.append(text[pos:])
    path.write_text("".join(out))
    return dropped


_WINE_DBCH_ITEM = re.compile(
    r"^(?:#\[no_mangle\]\n)?pub\s+static\s+(?:mut\s+)?(__wine_dbch_\w+)\s*:[^\n]*;\n", re.M
)


def _wine_debug_storage(path: Path) -> list[str]:
    """`WINE_DEFAULT_DEBUG_CHANNEL(ch)` is two statics in a HEADER macro, and resolve writes
    them once in the prelude (`_wine_debug_channels`). A translation that spells its own --
    inetcpl's security.c came back with `pub static __wine_dbch___default: [u8; 8] =
    *b"inetcpl\0"`, two TUs each with a different invented type -- shadows the real
    `*mut __wine_debug_channel`, so it is dropped, and the bodies that then indexed it as
    bytes (`__wine_dbch___default[0]`, the struct's first field) read `.flags`."""
    text = path.read_text()
    names = _WINE_DBCH_ITEM.findall(text)
    new = _WINE_DBCH_ITEM.sub("", text)
    new, n = re.subn(r"\b(__wine_dbch_\w+)\[0\]", r"(*\1).flags", new)
    # `TRACE_ON(extrac32)` pastes `&__wine_dbch_##ch`, which macro_rules cannot: name the
    # channel static for win32macros-rust's `TRACE_ON!`.
    new, k = re.subn(
        r"\b((?:WINE_)?(?:TRACE|WARN|FIXME|ERR))_ON!?\(\s*(?!__wine_dbch_)(\w+)\s*\)",
        lambda m: f"{m.group(1).removeprefix('WINE_')}_ON!(__wine_dbch_{m.group(2)})",
        new,
    )
    if new == text:
        return []
    path.write_text(new)
    return names + ([f"[0] -> .flags x{n}"] if n else []) + ([f"*_ON(ch) x{k}"] if k else [])


#: stdlib.h's dllimport data and the accessor its `_M_CEE_PURE` arm spells it through.
_CRT_DATA = {
    "__argc": "__p___argc",
    "__argv": "__p___argv",
    "__wargv": "__p___wargv",
    "_environ": "__p__environ",
    "_wenviron": "__p__wenviron",
    "_pgmptr": "__p__pgmptr",
    "_wpgmptr": "__p__wpgmptr",
}
#: stdio.h: `#define _iob __iob_func()`, `#define stdin (&_iob[0])` (findstr).
_CRT_STREAMS = {"stdin": 0, "stdout": 1, "stderr": 2}


def _crt_data_globals(path: Path) -> list[str]:
    """A bare `__argc` / `__wargv` (stdlib.h's `_CRTIMP extern` DATA) -> `(*__p___argc())`.

    Data imported from a DLL is an `__imp_` slot holding its address, which an `extern
    static` of the plain name never links to; win32macros-rust's accessors read the slot.
    The rewrite is the header's own `_M_CEE_PURE` expansion. A name the module declares
    itself (a local, a field, a `static`) is left alone."""
    text = path.read_text()
    done: list[str] = []
    for name, acc in _CRT_DATA.items():
        if not re.search(rf"\b{name}\b", text):
            continue
        if re.search(rf"\b(?:let(?:\s+mut)?|static(?:\s+mut)?|fn)\s+{name}\b|\b{name}\s*:", text):
            continue
        new, n = re.subn(rf"(?<![\w.:]){name}\b(?!\s*[(!])", f"(*{acc}())", text)
        if n:
            text = new
            done.append(f"{name} x{n}")
    for name, idx in _CRT_STREAMS.items():
        if not re.search(rf"\b{name}\b", text) or re.search(
            rf"\b(?:let(?:\s+mut)?|static(?:\s+mut)?|fn)\s+{name}\b|\b{name}\s*:", text
        ):
            continue
        new, n = re.subn(rf"(?<![\w.:]){name}\b(?!\s*[(!])", f"__iob_func().add({idx})", text)
        if n:
            text = new
            done.append(f"{name} x{n}")
    if done:
        path.write_text(text)
    return done


_ZERO_ARRAY_FIELD = re.compile(
    r"\b(?P<field>[A-Za-z_]\w*):\s*\[\s*0(?:\s+as\s+[\w:]+)*(?:\s*,\s*0(?:\s+as\s+[\w:]+)*)+\s*,?\s*\]"
)


def _zero_array_literals(path: Path) -> list[str]:
    """`bReserved: [0, 0, 0, 0, 0, 0]` in a struct literal -> `unsafe { zeroed() }`.

    c2rust lays a file-scope initializer out for ONE arch: mplay32's TBBUTTON table carried
    amd64's six `bReserved` bytes, and i386's field is two. An all-zero array is the same
    value at any length, and `zeroed()` takes the length from the field's declared type, so
    the literal stops encoding an arch."""
    text = path.read_text()
    fields: list[str] = []

    def one(m: re.Match[str]) -> str:
        fields.append(m.group("field"))
        return f"{m.group('field')}: unsafe {{ ::core::mem::zeroed() }}"

    new = _ZERO_ARRAY_FIELD.sub(one, text)
    if new == text:
        return []
    path.write_text(new)
    return sorted(set(fields))


_C2RUST_UNNAMED_LIT = re.compile(
    r"\bc2rust_unnamed(?:_\d+)?\s*:\s*C2RustUnnamed(?:_\d+)?\s*\{\s*(?P<field>[A-Za-z_]\w*)\s*:"
)


def _anon_unions(island: str) -> dict[str, list[tuple[str, str]]]:
    """field -> [(owning struct, `__bindgen_anon_N`)] for every bindgen anonymous member."""
    out: dict[str, list[tuple[str, str]]] = {}
    for m in re.finditer(
        r"^pub (?:union|struct) (\w+)__bindgen_ty_(\d+) \{(.*?)^\}", island, re.M | re.S
    ):
        owner, n, body = m.group(1), m.group(2), m.group(3)
        for f in re.findall(r"^\s*pub (\w+):", body, re.M):
            out.setdefault(f, []).append((owner, f"__bindgen_anon_{n}"))
    return out


def _c2rust_unnamed(path: Path, island: str) -> list[str]:
    """c2rust's names for C's anonymous struct/union members, as bindgen spells them.

    c2rust calls an anonymous member `c2rust_unnamed` (type `C2RustUnnamed_N`); bindgen calls
    it `__bindgen_anon_N` (type `<Owner>__bindgen_ty_N`). A file-scope initializer keeps
    c2rust's (magnify's NOTIFYICONDATA `c2rust_unnamed: C2RustUnnamed { uTimeout: 0 }`), and
    an access path does too (dxdiag's `archInfo.c2rust_unnamed.c2rust_unnamed.wProcessor
    Architecture`). An initializer is renamed to the island member that owns the field; an
    access just loses the segments, and crate-repair's anon_union_field adds bindgen's path."""
    text = path.read_text()
    unions = _anon_unions(island)
    done: list[str] = []

    def lit(m: re.Match[str]) -> str:
        owners = unions.get(m.group("field"), [])
        before = text[: m.start()]
        # The literal's struct: the nearest `Name {` opened before it that owns the field.
        for owner, member in sorted(owners, key=lambda o: before.rfind(f"{o[0]} {{"), reverse=True):
            if before.rfind(f"{owner} {{") >= 0:
                n = member.rsplit("_", 1)[1]
                done.append(f"{owner}.{member}")
                return f"{member}: {owner}__bindgen_ty_{n} {{ {m.group('field')}:"
        return m.group(0)

    new = _C2RUST_UNNAMED_LIT.sub(lit, text)
    new, k = re.subn(r"\.c2rust_unnamed(?:_\d+)?\b(?!\s*:)", "", new)
    if k:
        done.append(f".c2rust_unnamed x{k}")
    if new == text:
        return []
    path.write_text(new)
    return done


_STR_AS_PTR = re.compile(r'(?<![\w"])(?:TEXT!\(\s*)?"((?:[^"\\\n]|\\.)*)"(\s*\))?\.as_ptr\(\)')


def _c_str_literals(path: Path) -> list[str]:
    """`"1".as_ptr()` -> `b"1\\0".as_ptr()`: a Rust `&str` has no NUL.

    magnify (an ANSI module, where `TEXT(x)` lowers to `x`) passed `"1".as_ptr()` to
    CB_ADDSTRING; the control read on through rodata, and selecting an item copied that
    run-on text into a 2-char stack buffer. A literal that already ends in `\\0` is left
    alone. In a UNICODE module the result is a type error, which is the loud outcome."""
    text = path.read_text()
    fixed: list[str] = []

    def one(m: re.Match[str]) -> str:
        body = m.group(1)
        if m.group(0).startswith("TEXT!") != bool(m.group(2)):
            return m.group(0)  # unbalanced TEXT!( ... ) -- not this shape
        if body.endswith("\\0") or not body.isascii():
            return m.group(0)
        fixed.append(body[:24])
        return f'b"{body}\\0".as_ptr()'

    new = _STR_AS_PTR.sub(one, text)
    if new == text:
        return []
    path.write_text(new)
    return fixed


def _aw_export_names(path: Path, c_file: Path) -> list[str]:
    """`#[no_mangle] fn _tWinMain` -> `#[export_name = "wWinMain"]`.

    The C DEFINES `_tWinMain`, which tchar.h makes `wWinMain` under UNICODE; the CRT startup
    calls `wWinMain`, and a `#[no_mangle]` on the C spelling exports a symbol nobody calls
    (notepad: undefined `wWinMain` at link). Only an alias every built arch agrees on."""
    from .macro_authority import MacroAuthorityError, identifier_aliases

    text = path.read_text()
    names = re.findall(
        r"#\[no_mangle\]\s*(?:#\[[^\]]*\]\s*)*pub\s+(?:unsafe\s+)?extern\s+\"\w+\"\s+fn\s+(\w+)",
        text,
    )
    if not names:
        return []
    try:
        aliases = identifier_aliases(REPO, c_file.resolve())
    except MacroAuthorityError:
        return []
    done: list[str] = []
    for name in names:
        target = aliases.get(name)
        if not target or target == name:
            continue
        new = re.sub(
            rf"#\[no_mangle\](\s*(?:#\[[^\]]*\]\s*)*pub\s+(?:unsafe\s+)?extern\s+\"\w+\"\s+fn\s+{re.escape(name)}\b)",
            rf'#[export_name = "{target}"]\1',
            text,
            count=1,
        )
        if new != text:
            text = new
            done.append(f"{name} -> {target}")
    if done:
        path.write_text(text)
    return done


def _drop_macro_externs(path: Path, fn_macros: set[str]) -> list[str]:
    """Remove a module's own `extern` declaration of a name the C preprocessor says is a
    function-like MACRO. hotplug's eject.rs declared `fn ListView_InsertColumn(..)` and
    `fn ListView_SetColumnWidth(..)` -- macros over SendMessage that no DLL exports -- and it
    compiled, then failed at link (`undefined symbol _ListView_InsertColumn@12`). Without the
    declaration the call is unresolved, and `port macros` lowers the real macro."""
    text = path.read_text()
    dropped: list[str] = []
    out: list[str] = []
    depth_extern = False
    for line in text.split("\n"):
        if re.match(r'\s*(?:pub\s+)?(?:unsafe\s+)?extern\s+"[^"]+"\s*\{', line):
            depth_extern = True
        elif depth_extern and re.match(r"\s*\}", line):
            depth_extern = False
        m = re.match(
            r"\s*(?:pub(?:\([^)]*\))?\s+)?fn\s+([A-Za-z_]\w*)\s*\(.*\)[^;{]*;\s*(?://.*)?$", line
        )
        if depth_extern and m and m.group(1) in fn_macros:
            dropped.append(m.group(1))
            continue
        # A bodyless `fn X(..);` OUTSIDE an extern block is never Rust ("free function
        # without a body"). notepad's dialog.c preamble carried `fn ZeroMemory(..);`; port
        # resolve then took it for a sibling definition, made it `pub`, re-exported it over
        # win32macros-rust's macro, and every `ZeroMemory!(` call went back to a call.
        if not depth_extern and m and re.match(r"(?:pub(?:\([^)]*\))?\s+)?fn\b", line):
            dropped.append(m.group(1))
            continue
        out.append(line)
    if dropped:
        path.write_text("\n".join(out))
    return dropped


def stage_integrate(stem: str) -> None:
    """Move each translated file onto the crate's prelude (crate_integrate): the per-file
    substrate globs and hand-declared externs a standalone translation carries are WRONG
    once it is a module of the crate -- an extern "C" redeclaration shadows the prelude's
    correct extern "system" one and breaks i386."""
    state = load_state(stem)
    started = time.time()
    crate = _crate_dir(state)
    unprovided: dict[str, list[str]] = {}
    dead_used: dict[str, list[str]] = {}
    changed = 0
    ptr_types, decls = _pointer_decls(state)
    ptr_targets = pointer_depth.pointer_targets(_island_texts(crate))
    depth_fixed: list[str] = []
    flex_fields, _ = flex_index.field_shapes()
    crate_types = sizeof_restore.crate_types(crate / "src")
    fn_macros = _module_fn_macros(state)
    island_consts = _island_consts(crate / "src")
    unicode = _TCHAR_BEGIN in (crate / "src" / "prelude.rs").read_text(errors="replace")
    island_statics = _island_extern_statics(crate / "src")
    for path in _unit_files(crate, stem):
        renamed = _tchar_entry_point(path, unicode)
        if renamed:
            print(f"integrate: {path.stem}: entry point {renamed}")
        exported = _export_island_statics(path, island_statics)
        if exported:
            print(f"integrate: {path.stem}: #[no_mangle] on {', '.join(exported)}")
        shadow = _drop_island_shadows(path, island_consts)
        if shadow:
            changed += 1
            print(
                f"integrate: {path.stem}: const(s) redeclaring the island's dropped: "
                + "; ".join(shadow)
            )
        derefd = _pointer_field_not_address(path, crate / "src")
        if derefd:
            changed += 1
            print(
                f"integrate: {path.stem}: pointer field passed by VALUE, not its address: "
                + ", ".join(derefd)
            )
        counted = _count_the_array(path)
        if counted:
            changed += 1
            print(
                f"integrate: {path.stem}: {counted} element count(s) taken of the array, "
                "not a pointer to it"
            )
        unnamed = _c2rust_unnamed(path, "\n".join(_island_texts(crate)[:1]))
        if unnamed:
            changed += 1
            print(
                f"integrate: {path.stem}: c2rust anonymous members as bindgen's: "
                + ", ".join(unnamed)
            )
        cstr = _c_str_literals(path)
        if cstr:
            changed += 1
            print(
                f"integrate: {path.stem}: {len(cstr)} Rust str literal(s) passed to C got their NUL"
            )
        zeroed = _zero_array_literals(path)
        if zeroed:
            changed += 1
            print(
                f"integrate: {path.stem}: all-zero array field(s) take their type's length: "
                + ", ".join(zeroed)
            )
        crt = _crt_data_globals(path)
        if crt:
            changed += 1
            print(f"integrate: {path.stem}: CRT data read through its accessor: {', '.join(crt)}")
        wine = _wine_debug_storage(path)
        if wine:
            changed += 1
            print(
                f"integrate: {path.stem}: wine debug channel storage is the prelude's: "
                + ", ".join(wine)
            )
        dropped = _drop_macro_externs(path, fn_macros)
        if dropped:
            changed += 1
            print(
                f"integrate: {path.stem}: extern decl(s) for C macros dropped: {', '.join(dropped)}"
            )
        report = crate_integrate.integrate_path(path, crate)
        changed += report.changed
        if report.kept_unprovided:
            unprovided[path.stem] = report.kept_unprovided
        print(f"integrate: {report.summary()}")
        c_file = REPO / state["module_dir"] / f"{path.stem}.c"
        if c_file.is_file():
            exported = _aw_export_names(path, c_file)
            if exported:
                changed += 1
                print(
                    f"integrate: {path.stem}: definition(s) spelled with an SDK alias "
                    f"export the real name: {', '.join(exported)}"
                )
            dead_arms = _drop_dead_arms(path, c_file)
            if dead_arms:
                changed += 1
                print(
                    f"integrate: {path.stem}: match arm(s) the C has only in a dead "
                    f"#if region dropped: {', '.join(dead_arms)}"
                )
            # Anything else a dead region alone names is a statement, which is not safe to
            # drop by pattern -- so it is LOUD. inetcpl's security_on_destroy kept a
            # `#ifndef __REACTOS__` ImageList_Destroy: a double free of the list comctl32
            # had already destroyed with the listview. Hand-port the function (`port hand`).
            still = sorted(
                n
                for n in _dead_only_names(c_file.read_text(errors="replace"))
                if re.search(rf"\b{re.escape(n)}\b", _strip_rust_comments(path.read_text()))
            )
            if still:
                dead_used[path.stem] = still
                print(
                    f"integrate: {path.stem}: WARNING: the C names these only in a dead #if "
                    f"region, yet the translation uses them -- review: {', '.join(still)}"
                )
            corrected = _verify_local_defines(path, c_file)
            if corrected:
                changed += 1
                print(
                    f"integrate: {path.stem}: #define value(s) corrected from clang: "
                    + "; ".join(corrected)
                )
        if c_file.is_file():
            text = path.read_text()
            new, restored = sizeof_restore.restore(text, c_file, crate_types)
            if restored:
                path.write_text(new)
                changed += 1
                print(f"integrate: {path.stem}: dropped sizeof put back: {'; '.join(restored)}")
            offsets, refused = offset_restore.restore_file(path, c_file)
            if offsets:
                changed += 1
                print(f"integrate: {path.stem}: FIELD_OFFSET tables per-arch again: {', '.join(offsets)}")
            for why in refused:
                print(f"integrate: {path.stem}: WARNING: offset table left as c2rust folded it: {why}")
        text = path.read_text()
        new, fixes = pointer_depth.repair(text, decls, ptr_types, ptr_targets)
        new, not_fixed, not_refused = logical_not.repair(new, decls)
        # C indexes a trailing `T Arr[1]` past its declared length; Rust's bounds check on the
        # bindgen `[T; 1]` panics instead (pciidex's resource walk, on the PIIX3's second
        # descriptor, was the --ata-stack boot's first Rust panic).
        new, flexed = flex_index.rewrite(new, flex_fields)
        if flexed:
            print(f"integrate: {path.stem}: {flexed} flexible-array index(es) made unchecked")
        if new != text:
            path.write_text(new)
            changed += 1
            depth_fixed += [f"{path.stem}::{f}" for f in fixes]
        for f in not_fixed:
            print(f"integrate: {path.stem}::{f} C logical `!x` read as bitwise `!(x) != 0`, fixed")
        for f in not_refused:
            print(
                f"integrate: {path.stem}::{f} has `!(x) ==/!= 0` and its C uses `~`: check by hand"
            )
    variadic, variadic_refused = _variadic_twins(state, crate, stem)
    changed += bool(variadic)
    placeholders = _strip_unit_placeholders(state)
    changed += len(placeholders)
    if placeholders:
        print(f"integrate: `static X: () = ();` placeholders dropped in {', '.join(placeholders)}")
    channels = _wine_channel_macro_calls(state, crate)
    changed += len(channels)
    if channels:
        print(
            "integrate: WINE_DEFAULT_DEBUG_CHANNEL from the prelude macro in "
            f"{len(channels)} module(s)"
        )
    if depth_fixed:
        print(
            f"integrate: {len(depth_fixed)} function(s) read a pointer typedef as its struct "
            "(`*mut PFOO`, `(*(*x))`); the C's declarations put back:"
        )
        for f in depth_fixed:
            print(f"  {f}")
    _record(
        state,
        "integrate",
        started,
        changed=changed,
        unprovided=unprovided,
        pointer_depth=depth_fixed,
        variadic=variadic,
        variadic_refused=variadic_refused,
        dead_used=dead_used,
    )
    if unprovided:
        print("integrate: names nothing provides (a prelude gap, or invented by the model):")
        for mod, names in unprovided.items():
            print(f"  {mod}: {', '.join(names)}")


