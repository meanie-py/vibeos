_GENERATED_MARK = "generated by `rustconv data-port"


def stage_data(stem: str, tu_arg: str) -> None:
    """A C DATA TU -- tables, no code -- as Rust statics, for $0 (c_data_port.py).

    usetup's `mui_tables.c` (the 30 lang/*.h MUI tables) is the case it was built for: no
    model call, no c2rust, every byte from clang. Writes `src/<stem>/<tu>/`, wires the module
    into lib.rs, and comments the TU out of the CMakeLists the way `flip` does. Re-run it
    after editing the C tables: the output directory is the generator's, and every file in
    it that the generator wrote and no longer writes is removed. After the flip the TU has
    no compile command of its own; macro_authority borrows a sibling's (the module's flags
    are its target's, so that is exact), as it does to re-assemble a flipped bank.
    """
    from . import c_data_port as cdp

    started = time.time()
    state = load_state(stem)
    module = REPO / state["module_dir"]
    tu = (module / tu_arg) if (module / tu_arg).is_file() else (REPO / tu_arg)
    if not tu.is_file():
        raise PortError(f"data: no {tu_arg} in {module.relative_to(REPO)}")
    src = _crate_dir(state) / "src"
    try:
        files = cdp.port(REPO, tu.resolve(), src)
    except cdp.DataPortError as e:
        raise PortError(f"data: {e}") from e
    name = re.sub(r"\W", "_", tu.stem).lower()
    out = src / stem / name
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("*.rs"):
        if old.name not in files and _GENERATED_MARK in old.read_text():
            old.unlink()
    for fname, text in files.items():
        path = out / fname
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
    lib = src / "lib.rs"
    text = lib.read_text()
    block = re.search(rf"(?m)^pub mod {re.escape(stem)} \{{\n(.*?)^\}}", text, re.S)
    if block is None:
        raise PortError(f"data: lib.rs has no `pub mod {stem} {{ .. }}` block")
    if not re.search(rf"\bpub mod {name};", block.group(1)):
        text = (
            text[: block.end(1)]
            + f"    pub mod {name}; // C data: `port data`\n"
            + text[block.end(1) :]
        )
        lib.write_text(text)
    cml = module / "CMakeLists.txt"
    rel = str(tu.resolve().relative_to(module.resolve()))
    rs = (out / "mod.rs").relative_to(REPO)
    old_cml = cml.read_text()
    new_cml = re.sub(
        rf"(?m)^(\s*){re.escape(rel)}\b[^\n]*$",
        lambda m: f"{m.group(1)}# {rel}  # replaced by Rust ({rs}, generated: port data)",
        old_cml,
    )
    if new_cml != old_cml:
        cml.write_text(new_cml)
        subprocess.run(
            [sys.executable, str(REPO / "tools" / "cohab_census.py"), "--write"],
            cwd=REPO,
            check=True,
        )
    data = sorted({*state.get("data_tus", []), str(tu.resolve().relative_to(REPO))})
    state["data_tus"] = data
    _record(state, "data", started, tu=str(tu.relative_to(REPO)), files=len(files))
    lines = sum(t.count("\n") for t in files.values())
    print(f"data: {tu.name} -> {out.relative_to(REPO)} ({len(files)} files, {lines} lines)")


def stage_oracle(stem: str) -> None:
    """The module's pre-flip C as an opt-in `<target>_c` (c_oracle.py): what modrun runs the
    Rust against. Re-run after the CMakeLists changes; `python -m rustconv.c_oracle --check`
    reports staleness."""
    from . import c_oracle

    module = REPO / load_state(stem)["module_dir"]
    try:
        current = c_oracle.write(module)
    except c_oracle.OracleError as e:
        raise PortError(f"oracle: {e}") from e
