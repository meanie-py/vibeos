def _tu_output(state: dict, tu: str) -> Path:
    return _crate_dir(state) / "src" / state["stem"] / f"{Path(tu).stem}.rs"


def _has_body(path: Path) -> bool:
    if not path.is_file():
        return False
    text = path.read_text(errors="replace")
    return bool(re.search(r"\b(?:fn|static|const)\s+\w+", text))


def set_expand_macros(stem: str, tus: list[str]) -> list[str]:
    """Record that these TUs translate with the module's own macros expanded in the C."""
    state = load_state(stem)
    known = {Path(t).name for t in state["tus"]}
    bad = sorted(set(tus) - known)
    if bad:
        raise PortError(f"not TUs of {stem}: {', '.join(bad)}")
    state["expand_macros"] = sorted(set(state.get("expand_macros", [])) | set(tus))
    _record(state, "expand-macros", time.time(), tus=state["expand_macros"])
    return state["expand_macros"]


_DEFINE_GUID_RE = re.compile(
    r"^\s*DEFINE_GUID\(\s*(\w+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,"
    r"\s*(0x[0-9A-Fa-f]+)\s*,((?:\s*0x[0-9A-Fa-f]+\s*,?){8})\)",
    re.M,
)


def initguid_module(c_path: Path) -> str | None:
    """Rust for a TU that only instantiates GUIDs (`#define INITGUID` + includes), else None.

    diskpart's guid.c is three lines -- `#define INITGUID`, `<guiddef.h>`, `<diskguid.h>` --
    which define storage for every DEFINE_GUID in the headers. There is nothing for a model
    to translate (translate found 0 functions and left the module missing), and the values
    are data the header states exactly, so they are lowered here for $0.
    """
    text = re.sub(r"/\*.*?\*/|//[^\n]*", "", c_path.read_text(errors="replace"), flags=re.S)
    lines = [ln.strip() for ln in text.splitlines() if ln.strip()]
    if "#define INITGUID" not in lines:
        return None
    includes = []
    for ln in lines:
        m = re.match(r"#\s*include\s*[<\"]([^>\"]+)[>\"]", ln)
        if m:
            includes.append(m.group(1))
        elif ln != "#define INITGUID":
            return None  # anything else is real code: translate it
    guids: dict[str, str] = {}
    for inc in includes:
        if Path(inc).name == "guiddef.h":
            continue
        hits = sorted((REPO / "sdk" / "include").rglob(Path(inc).name))
        hits = [h for h in hits if "/host/" not in str(h)]
        if len(hits) != 1:
            raise PortError(f"{c_path.name}: cannot place <{inc}> ({len(hits)} candidates)")
        for m in _DEFINE_GUID_RE.finditer(hits[0].read_text(errors="replace")):
            name, d1, d2, d3, tail = m.groups()
            d4 = ", ".join(re.findall(r"0x[0-9A-Fa-f]+", tail))
            # #[no_mangle]: guid.c DEFINES these with external linkage, and the island
            # declares them `extern` (DEFINE_GUID without INITGUID), so a mangled static
            # left every reference undefined at link.
            guids[name] = (
                f"#[no_mangle]\npub static {name}: GUID = GUID {{ Data1: {d1}, Data2: {d2}, "
                f"Data3: {d3}, Data4: [{d4}] }};"
            )
    if not guids:
        raise PortError(f"{c_path.name}: INITGUID TU whose headers define no GUID")
    head = (
        f"// {c_path.name}: INITGUID storage for {', '.join(includes)}, lowered from the "
        "headers' DEFINE_GUID lines by `rustconv port translate` ($0).\n"
        "use crate::prelude::*;\n\n"
    )
    return head + "\n".join(guids[n] for n in guids) + "\n"


def failing_audit_tus(state: dict) -> list[str]:
    """TU file names whose latest translate log says a banked body fails the audit."""
    out = []
    for tu in state["tus"]:
        stem = Path(tu).stem
        logs = sorted(
            (STATE_ROOT / state["stem"]).glob(f"translate-{stem}-thinking-*.log"),
            key=lambda p: p.stat().st_mtime,
        )
        if logs and "banked body FAILS the current audit" in logs[-1].read_text(errors="replace"):
            out.append(Path(tu).name)
    return out


def stage_translate(
    stem: str,
    *,
    model: str,
    cost_cap: float,
    only: list[str],
    dry_run: bool,
    mode: str = "mechanical",
    concurrency: int = 5,
    thinking: str = "on",
    escalate: bool = False,
    rebuy_fn: list[str] | None = None,
    replay_only: bool = False,
    no_c2rust: list[str] | None = None,
    revisit: list[str] | None = None,
) -> tuple[float, list[str]]:
    """Run translate per TU; return (USD spent, file names of the TUs it ran)."""
    state = load_state(stem)
    started = time.time()
    # STICKY, because the anchor is part of what was bought: a TU translated without one
    # replays from the bank only when asked for without one again (replay, escalation).
    if no_c2rust:
        known = {Path(t).name for t in state["tus"]}
        unknown = sorted(set(no_c2rust) - known)
        if unknown:
            raise PortError(f"--no-c2rust: not a TU of {stem}: {', '.join(unknown)}")
        state["no_c2rust"] = sorted(set(state.get("no_c2rust", [])) | set(no_c2rust))
        _record(state, "no-c2rust", started, tus=state["no_c2rust"])
    picked = [t for t in state["tus"] if not only or Path(t).name in only]
    # An escalation pass revisits TUs that already have output: their good bodies replay
    # for $0 and only rejected / audit-failing functions are bought again, with thinking.
    # `--rebuy-fn` names bodies inside TUs that already have output, so those are revisited
    # too (their other functions replay for $0).
    todo = (
        picked
        if escalate or rebuy_fn or replay_only
        # A TU just switched to expanded macros has output, but its question changed.
        else [
            t
            for t in picked
            if not _has_body(_tu_output(state, t)) or Path(t).name in (revisit or [])
        ]
    )
    spent = 0.0
    done: list[dict] = []
    arch_only = _arch_only_tus(state, todo)
    for tu in todo:
        lowered = initguid_module(REPO / tu)
        if lowered is not None:
            out = _tu_output(state, tu)
            if not dry_run:
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(lowered)
            print(f"translate: {Path(tu).name}: INITGUID storage lowered ($0)")
            continue
        left = cost_cap - spent
        # A replay-only run never buys, so the cap cannot stop it. It used to: `port replay`
        # passes cap 0, and every replay ever run broke out here before the first TU and
        # reassembled nothing -- each "rebuild from the banks" re-ran resolve/repair/fix over
        # whatever the files already held.
        # Nor a dry run: it is how you learn what the cap should BE, and it buys nothing.
        if left <= 0 and not (replay_only or dry_run):
            print(
                f"translate: cost cap ${cost_cap:.2f} reached; {len(todo) - len(done)} TU(s) left"
            )
            break
        out = _tu_output(state, tu)
        cmd = [
            sys.executable,
            "-m",
            "rustconv",
            *(["--arch", arch_only[tu]] if tu in arch_only else []),
            "translate",
            str(REPO / tu),
            *_target_args(state),
            "-m",
            model,
            "--seal-facts",
            "--seal-calls",
            "--seal-wide",
            "--retry-rejects",
            "1",
            "--cost-cap",
            f"{left:.2f}",
            "-o",
            str(out),
            "--mode",
            mode,
            "--concurrency",
            str(concurrency),
        ]
        # Per TU, recorded in the state so `port replay` asks the bank the same question.
        if Path(tu).name in state.get("expand_macros", []):
            cmd += ["--expand-local-macros", state["module_dir"]]
        if dry_run:
            cmd.append("--dry-run")
        if Path(tu).name in state.get("no_c2rust", []):
            cmd.append("--no-c2rust")
        env = dict(
            os.environ, RUSTCONV_DEEPSEEK_THINKING="enabled" if thinking == "on" else "disabled"
        )
        if escalate:
            cmd += ["--rebuy-rejected", "--reassemble"]
        if replay_only:
            # Reassemble from the bank after a stitcher/postprocess fix: never a purchase.
            cmd += ["--replay-only", "--reassemble"]
        # Only the names THIS TU defines: translate reports a name its worklist never
        # missed, and every other TU's names would be exactly that.
        c_text = (REPO / tu).read_text(errors="replace")
        mine = [n for n in rebuy_fn or [] if re.search(rf"^\s*{re.escape(n)}\s*\(", c_text, re.M)]
        if mine:
            cmd += ["--rebuy-fn", *mine]
            if "--reassemble" not in cmd:
                cmd.append("--reassemble")
        t0 = time.time()
        proc = subprocess.run(
            cmd, cwd=REPO / "tools" / "rustconv", capture_output=True, text=True, env=env
        )
        # One log per TU per PASS: the escalation pass used to overwrite the cheap pass's
        # log, which destroyed exactly the token counts the cheap-vs-thinking comparison needs.
        log = STATE_ROOT / stem / f"translate-{Path(tu).stem}-thinking-{thinking}.log"
        log.write_text(proc.stdout + proc.stderr)
        cost = _run_cost(proc.stdout + proc.stderr)
        # Keyed on the run's own report, not on the output file: a TU revisited for
        # --rebuy-fn / --escalate still holds its PREVIOUS output, so "no body" never fired.
        # Never on a replay: the retry BUYS (`--rebuy-rejected`, a cap of at least $0.01).
        if not (dry_run or replay_only) and "parallel translation completed with rejected" in (
            proc.stdout + proc.stderr
        ):
            # The parallel path does not re-roll a rejected worker; the sequential one does,
            # with the reject fed back. Accepted workers replay for $0, so this buys only
            # the rejects again.
            retry = [c for c in cmd if c not in ("--concurrency", str(concurrency))]
            retry += ["--concurrency", "1", "--rebuy-rejected"]
            retry[retry.index("--cost-cap") + 1] = f"{max(0.01, left - cost):.2f}"
            proc = subprocess.run(
                retry, cwd=REPO / "tools" / "rustconv", capture_output=True, text=True, env=env
            )
            log.write_text(
                log.read_text()
                + "\n=== sequential retry of rejects ===\n"
                + proc.stdout
                + proc.stderr
            )
            cost += _run_cost(proc.stdout + proc.stderr)
        spent += cost
        fns, tok_in, tok_out = _tokens(log.read_text())
        done.append(
            {
                "tu": tu,
                "rc": proc.returncode,
                "bought": fns,
                "tokens_in": tok_in,
                "tokens_out": tok_out,
                "usd": cost,
                "seconds": round(time.time() - t0, 1),
                "body": _has_body(out),
            }
        )
        to_buy = _to_buy(log.read_text())
        done[-1]["to_buy"] = to_buy
        status = (
            f"would buy {to_buy} fn(s)" if dry_run else ("body" if _has_body(out) else "NO BODY")
        )
        if dry_run and proc.returncode:
            status = f"REFUSED (see {log})"
        print(
            f"translate: {Path(tu).name}: rc={proc.returncode} ${cost:.4f} "
            f"{status} ({round(time.time() - t0)}s)"
        )
    _record(
        state,
        "translate",
        started,
        model=model,
        mode=mode,
        concurrency=concurrency,
        thinking=thinking,
        escalate=escalate,
        usd=round(spent, 4),
        runs=done,
        dry_run=dry_run,
    )
    print(
        f"translate: {len(done)} TU(s), ${spent:.4f}"
        + (f", {sum(d['to_buy'] for d in done)} fn(s) to buy" if dry_run else "")
    )
    if not dry_run:
        applied = apply_hand_bodies(_crate_dir(state), state["stem"])
        if applied:
            print(f"translate: {len(applied)} hand-ported body(ies) applied: {', '.join(applied)}")
    return spent, [Path(d["tu"]).name for d in done]


def _fn_item_span(text: str, name: str) -> tuple[int, int] | None:
    """(start, end) of the column-0 `... fn NAME(` item, attributes above it included."""
    m = re.search(rf"^[^\n]*\bfn {re.escape(name)}\s*\(", text, re.M)
    if m is None:
        return None
    start = m.start()
    while True:  # take the item's own attributes / doc lines with it
        prev = text.rfind("\n", 0, start - 1) + 1 if start > 0 else 0
        line = text[prev:start].strip()
        if start > 0 and (line.startswith("#[") or line.startswith("///")):
            start = prev
            continue
        break
    brace = text.find("{", m.end())
    if brace < 0:
        return None
    depth, i = 0, brace
    while i < len(text):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return start, i + 1
        i += 1
    return None


def apply_hand_bodies(crate: Path, stem: str) -> list[str]:
    """Overlay `<crate>/hand/<Fn>.rs` onto the reassembled modules. Returns what it applied.

    A body neither the model nor `port fix` can produce is hand-ported ONCE, committed beside
    the crate, and re-applied after every reassembly -- otherwise a `port replay` restores the
    banked body and, if that body does not parse, blinds resolve and crate-repair for the
    whole crate (atapi's AtaCreateIdeDirectory hid 2,100 errors that way). The file holds the
    complete item; it replaces the item of the same name wherever the module defines it.
    """
    hand = crate / "hand"
    applied: list[str] = []
    if not hand.is_dir():
        return applied
    modules = sorted((crate / "src" / stem).glob("*.rs"))
    for override in sorted(hand.glob("*.rs")):
        name = override.stem
        body = override.read_text().strip("\n") + "\n"
        for mod in modules:
            text = mod.read_text()
            span = _fn_item_span(text, name)
            if span is None:
                continue
            new = text[: span[0]] + body.rstrip("\n") + text[span[1] :]
            if new != text:
                mod.write_text(new)
            applied.append(name)
            break
        else:
            raise PortError(f"hand/{override.name}: no module of {stem} defines `fn {name}`")
    return applied


def flip_cmake(cml: str, state: dict) -> str:
    """The module's CMakeLists with every translated TU replaced by the Rust staticlib.

    The cohab flip, as setuplib, usetup and diskpart all did it by hand: each TU's source line
    is commented out naming its `.rs` (the C stays on disk), a one-line stub TU keeps the
    target non-empty, and the target links `rust_staticlib_variant`'s archive. Idempotent; a
    TU missing from the source list is an error, never a skip.
    """
    stem, crate, target = state["stem"], state["crate"], state["target"]
    module = REPO / state["module_dir"]
    lines = cml.split("\n")
    last = None
    for tu in state["tus"]:
        rel = str((REPO / tu).relative_to(module))
        rs = _tu_output(state, tu).relative_to(REPO)
        pat = re.compile(rf"^(\s*){re.escape(rel)}(\s*\)?)\s*$")
        hit = next((i for i, ln in enumerate(lines) if pat.match(ln)), None)
        if hit is None:
            if any(re.match(rf"^\s*#\s*{re.escape(rel)}\b", ln) for ln in lines):
                last = max(
                    last or 0,
                    next(
                        i
                        for i, ln in enumerate(lines)
                        if re.match(rf"^\s*#\s*{re.escape(rel)}\b", ln)
                    ),
                )
                continue  # already flipped
            raise PortError(f"flip: {rel} is not in {module}/CMakeLists.txt's source lists")
        m = pat.match(lines[hit])
        assert m is not None
        lines[hit] = f"{m.group(1)}# {rel}  # replaced by Rust ({rs}){m.group(2).rstrip()}"
        if m.group(2).strip():  # the `)` closing the list rode on this line: keep it live
            lines[hit] = f"{m.group(1)}# {rel}  # replaced by Rust ({rs})\n{m.group(1)})"
        last = max(last or 0, hit)
    text = "\n".join(lines)
    if "rust_cohab_stub.c" not in text and last is not None:
        lines = text.split("\n")
        indent = re.match(r"^(\s*)", lines[last]).group(1)  # type: ignore[union-attr]
        lines.insert(last + 1, f"{indent}rust_cohab_stub.c")
        text = "\n".join(lines)
    variant = f"{stem}_rust"
    if f"rust_staticlib_variant({variant} " not in text:
        add = re.search(rf"^add_(?:executable|library)\(\s*{re.escape(target)}\b", text, re.M)
        if add is None:
            raise PortError(f"flip: no add_executable/add_library({target}) in the CMakeLists")
        depth, i = 0, text.index("(", add.start())
        while i < len(text):
            depth += {"(": 1, ")": -1}.get(text[i], 0)
            if depth == 0 and text[i] == ")":
                break
            i += 1
        end = text.index("\n", i) + 1 if "\n" in text[i:] else len(text)
        head = (
            f"# Every translation unit is Rust now ({crate}, `rustconv port`); the C stays on\n"
            f"# disk. The target keeps a stub TU and links the Rust archive.\n"
            f'rust_staticlib_variant({variant} {crate} "" TRUE)\n'
        )
        tail = (
            f"add_dependencies({target} rust_{variant})\n"
            f"target_link_libraries({target} ${{{variant}_LIB}})\n"
        )
        text = text[: add.start()] + head + text[add.start() : end] + tail + text[end:]
    return text


def stage_flip(stem: str) -> None:
    started = time.time()
    state = load_state(stem)
    module = REPO / state["module_dir"]
    cml = module / "CMakeLists.txt"
    new = flip_cmake(cml.read_text(), state)
    stub = module / "rust_cohab_stub.c"
    if not stub.exists():
        stub.write_text(
            f"/* {stem} is Rust (sdk/lib/rust/{state['crate']}); a CMake target needs one TU. */\n"
            f"typedef int {stem}_rust_cohab_placeholder;\n"
        )
    changed = new != cml.read_text()
    if changed:
        cml.write_text(new)
        # A flip IS a census change (check-tooling's test_cohab_census fails until the
        # snapshot is re-recorded); record it here rather than leave it to be remembered.
        subprocess.run(
            [sys.executable, str(REPO / "tools" / "cohab_census.py"), "--write"],
            cwd=REPO,
            check=True,
        )
    _record(state, "flip", started, changed=changed)
    print(f"flip: {cml.relative_to(REPO)} {'rewritten' if changed else 'already flipped'}")


def _tokens(log: str) -> tuple[int, int, int]:
    """(functions bought, input tokens, output tokens) from a translate log.

    Sequential lines read `OK (6736 in / 1312 out)`, parallel ones `OK (6118/16287)`.
    """
    n = tin = tout = 0
    for m in re.finditer(r"\bOK \((\d+)(?: in / |/)(\d+)(?: out)?\)", log):
        n += 1
        tin += int(m.group(1))
        tout += int(m.group(2))
    return n, tin, tout


def _to_buy(log: str) -> int:
    """Functions a run would pay for: the `Resume cache: … N to buy` line(s) it printed."""
    return sum(int(m.group(1)) for m in re.finditer(r"\b(\d+) to buy\b", log))


_COST_RE = re.compile(r"\$([0-9]+\.[0-9]+)")


def _run_cost(log: str) -> float:
    """The run's final reported spend: the last `[running $X]` / `total $X` figure it printed."""
    marks = [
        m for m in re.finditer(r"(?:running|total|spent|cost)[^\n$]*\$([0-9]+\.[0-9]+)", log, re.I)
    ]
    return float(marks[-1].group(1)) if marks else 0.0


