def upsert_profile_arm(script: str, arm: str, label: str) -> str:
    """Insert or replace the `  <label>)` arm of gen_driver_types.sh's case table.

    An arm is the label's whether it is `  <label>)` or a multi-island `  a|<label>|b)`.
    Matching only the bare form re-appended inetcpl's `inetcpl|inetcpl-types_1)` arm on
    every derive -- six copies, the first of which `case` kept running. Every arm carrying
    the label is replaced: the first by the new arm, the rest dropped.

    A `    # >>> hand` ... `    # <<< hand` section of the old arm is carried into the new one
    (before its `;;`): knobs derive cannot know, such as cmd's EXTRA_BL_ITEMS/EXTRA_RAW_LINES
    pinning stream.h's CON_STREAM to conutils-h, would otherwise vanish on the next derive.
    """
    head = re.compile(rf"^  (?:[\w.+-]+\|)*{re.escape(label)}(?:\|[\w.+-]+)*\)\n", re.M)
    spans = []
    for m in head.finditer(script):
        end = script.index("\n    ;;\n", m.end()) + len("\n    ;;\n")
        spans.append((m.start(), end))
    hand = [
        h.group(0)
        for a, b in spans[:1]
        for h in re.finditer(r"^    # >>> hand\n.*?^    # <<< hand\n", script[a:b], re.M | re.S)
    ]
    if hand and "# >>> hand" not in arm:
        body = arm.rstrip("\n")
        cut = body.rindex("\n    ;;")
        arm = body[:cut] + "\n" + "".join(hand).rstrip("\n") + body[cut:] + "\n"
    if spans:
        out, pos = [], 0
        for i, (a, b) in enumerate(spans):
            out.append(script[pos:a])
            if i == 0:
                out.append(arm.rstrip("\n") + "\n")
            pos = b
        out.append(script[pos:])
        return "".join(out)
    default = re.search(r"^  \*\) echo \"unknown driver", script, re.M)
    if not default:
        raise PortError("gen_driver_types.sh: no `*)` default arm to insert before")
    return script[: default.start()] + arm.rstrip("\n") + "\n" + script[default.start() :]


def require_built(module_dir: Path) -> None:
    """Refuse a module its parent CMakeLists never `add_subdirectory()`s.

    liccpa is `#add_subdirectory(liccpa)#disabled in trunk`: derive, island and scaffold all
    ran clean over it, and only translate stopped -- on "no compile command", a message that
    sends you to rebuild a tree that will never compile it.
    """
    parent = module_dir.resolve().parent / "CMakeLists.txt"
    if not parent.is_file():
        return
    live = re.sub(r"#[^\n]*", "", parent.read_text(errors="replace"))
    if re.search(rf"\badd_subdirectory\(\s*{re.escape(module_dir.resolve().name)}\s*\)", live):
        return
    if re.search(r"\badd_subdirectory\(", live):
        raise PortError(
            f"{module_dir}: {parent} does not add_subdirectory() it -- the build never "
            "compiles this module, so there is nothing to replace"
        )


def recorded_mode(module_dir: Path, target: str | None) -> bool | None:
    """The --usermode/--kernel a previous `port derive` of this module was given.

    A static library whose consumers live in another CMakeLists (winegdi -> gdi32) has no
    module type profile_derive can see, so the mode is asked for once and remembered: every
    later stage re-derives, and making each of them repeat the flag is a recipe to forget.
    """
    rel = str(module_dir.resolve().relative_to(REPO))
    found = set()
    for p in sorted(STATE_ROOT.glob("*/state.json")):
        st = json.loads(p.read_text())
        # No --target means the directory's only target, which state records by name.
        if st.get("module_dir") != rel or (target is not None and st.get("target") != target):
            continue
        if "mode_override" in st:
            found.add(st["mode_override"])
    return found.pop() if len(found) == 1 else None


def derive(
    module_dir: Path, target: str | None, arch: str = "i386", usermode: bool | None = None
) -> pd.DerivedProfile:
    require_built(module_dir)
    if usermode is None:
        usermode = recorded_mode(module_dir, target)
    # A module whose CMakeLists carries the flip's own `# x.c  # replaced by Rust` lines is
    # flipped even when real C still compiles beside the stub: mstsc keeps its 18 vendored
    # rdesktop TUs, so the "already flipped" refusal never fired and a re-derive recorded
    # ZERO TUs -- every later stage would have had nothing to integrate.
    cml = module_dir / "CMakeLists.txt"
    if cml.is_file() and "# replaced by Rust (" in cml.read_text(errors="replace"):
        dp = pd.derive(
            module_dir.resolve(),
            REPO,
            arch=arch,
            target=target,
            usermode=usermode,
            flipped_sources=True,
        )
        blocking = [f for f in dp.errors if f.code != "SWITCH_CONST_IN_BASE_HEADER"]
        if blocking:
            lines = "\n".join(str(f) for f in blocking)
            raise PortError(f"profile_derive reports BLOCKING errors -- fix these first:\n{lines}")
        return dp
    try:
        dp = pd.derive(module_dir.resolve(), REPO, arch=arch, target=target, usermode=usermode)
    except pd.ProfileDeriveError as e:
        # After the cohab flip the module compiles only its rust_*.c scaffolding; the C the
        # crate translates is still listed, commented out. Re-deriving (a new island rule,
        # say) must read THAT list, not refuse.
        if "already flipped" not in str(e):
            raise
        dp = pd.derive(
            module_dir.resolve(),
            REPO,
            arch=arch,
            target=target,
            usermode=usermode,
            flipped_sources=True,
        )
    blocking = [f for f in dp.errors if f.code != "SWITCH_CONST_IN_BASE_HEADER"]
    if blocking:
        lines = "\n".join(str(f) for f in blocking)
        raise PortError(f"profile_derive reports BLOCKING errors -- fix these first:\n{lines}")
    return dp


def switch_facts(dp: pd.DerivedProfile) -> list[str]:
    """Case-label constants a BASE header owns and the -sys crate lacks.

    The fix profile_derive asks for is transcribing each into the prelude, and that is
    mechanical: scaffold has clang evaluate them (`_resolve_facts`), so a translated
    `STD_INPUT_HANDLE =>` arm names a constant instead of binding everything. resolve cannot
    find these on its own -- an unknown name in a pattern is a binding, not an error.
    """
    return sorted(
        m.group(1)
        for f in dp.errors
        if f.code == "SWITCH_CONST_IN_BASE_HEADER"
        for m in [re.search(r"`(\w+)`", f.detail)]
        if m
    )


_PATTERN_ARM = re.compile(r"(?m)^\s*\|?\s*([A-Za-z_][\w\s|]*?)\s*=>")


def _pattern_idents(modules_dir: Path) -> set[str]:
    """Bare identifiers used as `match` arm patterns (`Name =>`, `A | B =>`) in the crate.

    Such a name is either a constant or a catch-all binding, and rustc only warns about the
    latter. Offered to `island_enum_aliases`, which aliases exactly the ones that are a
    unique enumerator of one enum on every arch and ignores the rest.
    """
    out: set[str] = set()
    for rs in modules_dir.glob("*.rs"):
        text = rs.read_text(errors="replace")
        for pattern in _PATTERN_ARM.findall(text):
            out |= {
                n.strip()
                for n in pattern.split("|")
                if re.fullmatch(r"[A-Za-z_]\w*", n.strip())
                and n.strip() != "_"
                and not n.strip().islower()
            }
    return out


def _undefined_pattern_constants(src: Path, modules_dir: Path, sys_src: Path | None) -> set[str]:
    """Upper-case match-arm identifiers that no `const`/`static` or prelude import defines."""
    wanted = {n for n in _pattern_idents(modules_dir) if prelude_resolve.looks_constant(n)}
    if not wanted:
        return set()
    from tools.source_walk import source_files  # repo-root package: imported at use

    files = list(source_files(src, "*.rs")) + (list(sys_src.glob("*.rs")) if sys_src else [])
    defined: set[str] = set()
    for f in files:
        text = f.read_text(errors="replace")
        defined |= set(re.findall(r"\b(?:const|static(?:\s+mut)?)\s+([A-Z_][A-Z0-9_]*)\b", text))
        defined |= set(re.findall(r"\bas\s+([A-Z_][A-Z0-9_]*)\s*[,;}]", text))
        for m in re.finditer(r"\buse\s+[\w:]+::\{([^}]*)\}", text):
            defined |= {w.strip().split(" as ")[-1].strip() for w in m.group(1).split(",")}
        defined |= set(re.findall(r"\buse\s+[\w:]+::([A-Z_][A-Z0-9_]*)\s*;", text))
    return wanted - defined


def _seed_switch_facts(state: dict, prelude: Path) -> None:
    names = state.get("switch_facts", [])
    if not names or not prelude.is_file():
        return
    _resolve_facts(state, prelude, names)
    # Judged by the facts block itself: `_resolve_facts` hands back its input untouched when
    # every name is already there, which read as "could not evaluate" on the second run.
    left = set(names) - set(prelude_resolve.existing_facts(prelude))
    if left:
        raise PortError(
            f"clang could not evaluate case-label constant(s) {', '.join(sorted(left))}: "
            "an unresolved name in a match arm binds everything -- transcribe them into "
            f"{prelude} by hand"
        )


def stage_derive(
    module_dir: Path,
    target: str | None,
    usermode: bool | None = None,
    functions: str | None = None,
    block: list[str] | None = None,
) -> pd.DerivedProfile:
    started = time.time()
    dp = derive(module_dir, target, usermode=usermode)
    stem = dp.module.crate_stem
    _add_island_headers(dp, load_state(stem).get("island_headers", {}))
    arm = pd.emit_profile(dp)
    if not arm.lstrip().startswith(f"{stem})") and "|" not in arm.split(")", 1)[0]:
        raise PortError(f"derived arm is not labelled {stem!r}:\n{arm[:200]}")
    script = GEN.read_text()
    prior = load_state(stem)
    if "real_unions" not in prior:
        # Decided ONCE, when port first writes the arm: a crate nothing has compiled against
        # yet takes real Rust unions. usetup's bodies read `Event.KeyEvent.uChar` as the C
        # does, and against `__BindgenUnionField` that was 150 of its 422 errors. A crate
        # whose arm predates port keeps the emulation its translations already call.
        prior["real_unions"] = not re.search(rf"^  {re.escape(stem)}\)\n", script, re.M)
    if prior["real_unions"] and "REAL_UNIONS=1" not in arm:
        arm = re.sub(r"^(    USERMODE=1)$", r"\1\n    REAL_UNIONS=1", arm, count=1, flags=re.M)
    # derive always emits BLOCKLIST_FUNCS=1 (the only safe answer before the crate has any
    # #[no_mangle] for FROM_CRATE to subtract). Once a human settles it the other way --
    # winegdi and opengl32 call ~110 gdi32/kernel32/advapi32 APIs no prelude declares -- the
    # decision lives in the state, so a later re-derive (resolve's island-header pass does
    # one) cannot quietly put the hand-written surface back.
    if functions is not None:
        prior["functions"] = functions
    # Island items a module must never see, remembered like `functions`: winegdi's closure
    # pulls wine's winternl.h, which declares RtlEqualSid & co. BOOL where ntdll defines
    # BOOLEAN (scan_bool_width); winegdi calls none of them.
    if block:
        prior["island_block"] = sorted(set(prior.get("island_block", [])) | set(block))
    if prior.get("island_block") and "EXTRA_BL_ITEMS=" not in arm:
        arm = re.sub(
            r"^(    DRIVER_DIR=.*)$",
            lambda m: f"    EXTRA_BL_ITEMS=( {' '.join(prior['island_block'])} )\n{m.group(1)}",
            arm,
            count=1,
            flags=re.M,
        )
    if prior.get("functions") == "from-crate":
        arm = re.sub(
            r"^    BLOCKLIST_FUNCS=1$",
            "    BLOCKLIST_FUNCS=0\n    BLOCKLIST_FUNCS_FROM_CRATE=1",
            arm,
            count=1,
            flags=re.M,
        )
    updated = upsert_profile_arm(script, arm, stem)
    if updated != script:
        GEN.write_text(updated)
    state = load_state(stem)
    # A VENDORED source (vendor.yaml) is not a translation target: it stays C, in the CMake
    # source list, beside the module's own Rust. mstsc's target compiles 18 vendor/rdesktop
    # TUs; each was scaffolded as a module, translate refused it ("no proven CMake source
    # owner"), and `port check` counted 18 untranslated modules on a crate it called green.
    if str(REPO / "tools") not in sys.path:
        sys.path.insert(0, str(REPO / "tools"))
    import vendored  # tools/vendored.py: the vendor.yaml reader

    own = [p for p in dp.module.compiled_tus if not pd.is_shim_tu(p)]
    kept = [p for p in own if not vendored.is_vendored(str(p.relative_to(REPO)), REPO)]
    if len(kept) != len(own):
        print(
            f"derive: {stem}: {len(own) - len(kept)} vendored TU(s) stay C: "
            + ", ".join(p.name for p in own if p not in kept)
        )
    state.update(
        module_dir=str(module_dir.resolve().relative_to(REPO)),
        target=dp.module.name,
        crate=dp.crate_name,
        # Never the rust_*.c cohab scaffolding a flipped module's re-derive also lists.
        tus=[str(p.relative_to(REPO)) for p in kept],
        usermode=dp.module.is_usermode,
        switch_facts=switch_facts(dp),
        switch_enums=sorted(
            m.group(1)
            for f in dp.findings
            if f.code == "SWITCH_CONST_ENUM_PREFIXED"
            for m in [re.search(r"`(\w+)`", f.detail)]
            if m
        ),
        real_unions=prior["real_unions"],
        **({"functions": prior["functions"]} if "functions" in prior else {}),
        **({"island_block": prior["island_block"]} if "island_block" in prior else {}),
    )
    if usermode is not None:
        state["mode_override"] = usermode
    _record(
        state, "derive", started, tus=len(dp.module.compiled_tus), arm_changed=updated != script
    )
    print(
        f"derive: {stem} — {len(dp.module.compiled_tus)} TU(s), crate {dp.crate_name}"
        f"{' (arm written)' if updated != script else ' (arm unchanged)'}"
    )
    return dp


