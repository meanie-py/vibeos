def _repair(stem: str, crate: str) -> str:
    from . import crate_repair as cr

    # A session that ends at max_passes while still lowering the count is converging slowly
    # (a nested cast is fixed one layer per pass), so it gets another, up to four. diskpart's
    # replay stopped at pass 10 with 26 wide-literal `*const` -> PWSTR sites one session from
    # done, and read 62 errors where a standalone crate-repair reached 36.
    best: int | None = None
    for _ in range(4):
        session = cr.repair_crate(
            crate,
            root=REPO / "sdk" / "lib" / "rust",
            targets=list(RUST_TARGETS),
            max_passes=10,
            target_dirs=_target_dirs(stem),
        )
        # One applying the same rules every pass with flat counts is oscillating.
        for ps in session.passes:
            rules: dict[str, int] = {}
            for e in ps.applied:
                rules[e.rule] = rules.get(e.rule, 0) + 1
            top = ", ".join(f"{r} {n}" for r, n in sorted(rules.items(), key=lambda kv: -kv[1])[:4])
            print(f"  repair pass {ps.index}: {ps.error_counts} applied {len(ps.applied)} ({top})")
        last = sum(session.passes[-1].error_counts.values()) if session.passes else 0
        if session.status != "max_passes" or (best is not None and last >= best):
            break
        best = last
    return session.status


def stage_replay(
    stem: str, *, fix_cap: float = 0.0, fix_rounds: int = 1, model: str = "deepseek"
) -> None:
    """Rebuild the crate from everything already bought, in order, for $0.

    translate (bank) -> resolve -> macros (bank) -> integrate -> crate-repair -> resolve ->
    crate-repair -> fix (bank, plus `--fix-cap` of new purchases) -> check.

    resolve runs TWICE because rustc reports unresolved names only once nothing halts it:
    before crate-repair setuplib's resolve saw 5 unresolved names, after it 46 -- the
    constants among them reached `port fix` unresolved, and the model invented values.
    """
    started = time.time()
    stage_translate(
        stem,
        model="deepseek",
        cost_cap=0.0,
        only=[],
        dry_run=False,
        thinking="off",
        replay_only=True,
    )
    stage_resolve(stem)
    stage_macros(stem, model="deepseek", cost_cap=0.0, dry_run=False)
    stage_integrate(stem)
    state = load_state(stem)
    print(f"replay: crate-repair {_repair(stem, state['crate'])}")
    stage_resolve(stem)
    # Macros again: rustc names an unresolved macro only once the errors in front of it are
    # gone, so the first pass misses what repair uncovers (access's `IntToPtr`). The bank
    # and the SDK lowering are $0; this pass buys nothing new.
    stage_macros(stem, model=model, cost_cap=0.0, dry_run=False)
    stage_integrate(stem)
    print(f"replay: crate-repair {_repair(stem, state['crate'])}")
    # Before fix, so fix never pays to repair a function the hand bank replaces.
    apply_hand(stem)
    stage_fix(
        stem,
        model=model,
        cost_cap=fix_cap,
        rounds=fix_rounds,
        thinking="off",
        concurrency=8,
    )
    apply_hand(stem)
    # A hand body can name what nothing bought did (wined3dcfg's InitSettings calls
    # RegCloseKey): resolve after it, or the replay ends with that name unresolved.
    stage_resolve(stem)
    # Once more, AFTER the hand bank: a hand body is written against the prelude of its day,
    # and the prelude moves (strsafe-rust began providing RtlStringCchPrintfA as a macro, and
    # usetup's 12 banked call sites still called it as a function). Repair is deterministic
    # and idempotent, so a body that needs nothing is left byte-identical.
    print(f"replay: crate-repair {_repair(stem, state['crate'])}")
    # And resolve once more: rustc names an unresolved constant only when nothing in front
    # of it halts the check, so the fixes above can UNCOVER names (main's WHEEL_PAGESCROLL,
    # clang-evaluable all along, surfaced only after fix round 2).
    stage_resolve(stem)
    stage_check(stem)
    print(f"replay: {(time.time() - started) / 60:.1f} min")


