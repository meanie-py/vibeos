"""rustconv port — take one plain-C module to a Rust crate, stage by stage.

WHY THIS EXISTS
---------------
Measured 2026-10-05 over ~280 agent-hours of the translation lanes' sessions: the paid
translate calls were 1-6% of the time; smoke/gate/build/check were 45-60% and reading
another 17-24%. A module port is mostly HAND-OFFS between tools that already exist --
profile_derive prints a profile "to paste into gen_driver_types.sh", the island is
generated by hand, the crate is scaffolded by hand, each TU is translated with flags an
agent must remember, and the cargo grind is run per arch. This command does the hand-offs,
in order, idempotently, and records how long each stage took.

STAGES (each re-runnable; state in ~/vibeos-rust-staging/port/<stem>/state.json)
  derive     profile_derive the module, refuse on blocking ERROR findings, and upsert the
             derived arm into gen_driver_types.sh.
  island     run gen_driver_types.sh <stem> into the crate (all three arches).
  scaffold   write the crate skeleton (never overwrites; the island is kept).
  translate  sealed DeepSeek translation of each TU that has no body yet, under --cost-cap.
  integrate  move each translated file onto the crate prelude (crate_integrate).
  check      cargo check on all three targets; error counts per file.

It never touches CMake, the workspace members or the build: the flip is a separate,
deliberate step once `check` is green on every arch.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

from . import crate_integrate
from . import profile_derive as pd

REPO = Path(__file__).resolve().parents[3]
GEN = REPO / "tools" / "rustconv" / "gen_driver_types.sh"
STATE_ROOT = Path(
    os.environ.get("RUSTCONV_PORT_STATE", Path.home() / "vibeos-rust-staging" / "port")
)
RUST_TARGETS = {
    "i386": "i686-pc-windows-gnu",
    "amd64": "x86_64-pc-windows-gnu",
    "arm64": "aarch64-pc-windows-gnullvm",
}


class PortError(RuntimeError):
    pass


# --------------------------------------------------------------------------------------
# state
# --------------------------------------------------------------------------------------


def _state_path(stem: str) -> Path:
    return STATE_ROOT / stem / "state.json"


def load_state(stem: str) -> dict:
    p = _state_path(stem)
    return json.loads(p.read_text()) if p.is_file() else {"stem": stem, "stages": []}


def _record(state: dict, stage: str, started: float, **result) -> None:
    state["stages"].append(
        {
            "stage": stage,
            "seconds": round(time.time() - started, 1),
            "at": time.strftime("%Y-%m-%dT%H:%M:%S"),
            **result,
        }
    )
    p = _state_path(state["stem"])
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(".tmp")
    tmp.write_text(json.dumps(state, indent=1))
    tmp.replace(p)


# --------------------------------------------------------------------------------------
# derive
# --------------------------------------------------------------------------------------


def upsert_profile_arm(script: str, arm: str, label: str) -> str:
    """Insert or replace the `  <label>)` arm of gen_driver_types.sh's case table."""
    start = re.search(rf"^  {re.escape(label)}\)\n", script, re.M)
    if start:
        end = script.index("\n    ;;\n", start.end()) + len("\n    ;;\n")
        return script[: start.start()] + arm.rstrip("\n") + "\n" + script[end:]
    default = re.search(r"^  \*\) echo \"unknown driver", script, re.M)
    if not default:
        raise PortError("gen_driver_types.sh: no `*)` default arm to insert before")
    return script[: default.start()] + arm.rstrip("\n") + "\n" + script[default.start() :]


def derive(module_dir: Path, target: str | None, arch: str = "i386") -> pd.DerivedProfile:
    dp = pd.derive(module_dir.resolve(), REPO, arch=arch, target=target)
    if dp.errors:
        lines = "\n".join(str(f) for f in dp.errors)
        raise PortError(f"profile_derive reports BLOCKING errors -- fix these first:\n{lines}")
    return dp


def stage_derive(module_dir: Path, target: str | None) -> pd.DerivedProfile:
    started = time.time()
    dp = derive(module_dir, target)
    stem = dp.module.crate_stem
    arm = pd.emit_profile(dp)
    if not arm.lstrip().startswith(f"{stem})") and "|" not in arm.split(")", 1)[0]:
        raise PortError(f"derived arm is not labelled {stem!r}:\n{arm[:200]}")
    script = GEN.read_text()
    updated = upsert_profile_arm(script, arm, stem)
    if updated != script:
        GEN.write_text(updated)
    state = load_state(stem)
    state.update(
        module_dir=str(module_dir.resolve().relative_to(REPO)),
        target=dp.module.name,
        crate=dp.crate_name,
        tus=[str(p.relative_to(REPO)) for p in dp.module.compiled_tus],
        usermode=dp.module.is_usermode,
    )
    _record(
        state, "derive", started, tus=len(dp.module.compiled_tus), arm_changed=updated != script
    )
    print(
        f"derive: {stem} — {len(dp.module.compiled_tus)} TU(s), crate {dp.crate_name}"
        f"{' (arm written)' if updated != script else ' (arm unchanged)'}"
    )
    return dp


# --------------------------------------------------------------------------------------
# island / scaffold
# --------------------------------------------------------------------------------------


def _crate_dir(state: dict) -> Path:
    return REPO / "sdk" / "lib" / "rust" / state["crate"]


def stage_island(stem: str) -> None:
    state = load_state(stem)
    started = time.time()
    env = dict(os.environ, OUT_CRATE_DIR=str(_crate_dir(state) / "src"))
    proc = subprocess.run(
        ["bash", str(GEN), stem], cwd=REPO, env=env, capture_output=True, text=True
    )
    log = STATE_ROOT / stem / "island.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    log.write_text(proc.stdout + proc.stderr)
    islands = sorted(p.name for p in (_crate_dir(state) / "src").glob("types_*.rs"))
    _record(state, "island", started, rc=proc.returncode, islands=islands)
    if proc.returncode != 0:
        tail = "\n".join((proc.stdout + proc.stderr).splitlines()[-15:])
        raise PortError(
            f"gen_driver_types.sh {stem} failed (rc {proc.returncode}); log {log}\n{tail}"
        )
    print(f"island: {', '.join(islands)}")


def stage_scaffold(module_dir: Path, target: str | None) -> None:
    started = time.time()
    dp = derive(module_dir, target)
    state = load_state(dp.module.crate_stem)
    kept: list[Path] = []
    written = pd.scaffold_crate(dp, _crate_dir(state), force=False, kept=kept)
    member = add_workspace_member(state["crate"])
    _record(state, "scaffold", started, written=len(written), kept=len(kept), member_added=member)
    print(
        f"scaffold: {len(written)} file(s) written, {len(kept)} kept, into {_crate_dir(state)}"
        f"{'; workspace member added' if member else ''}"
    )


def add_workspace_member(crate: str) -> bool:
    """`cargo check -p` (and crate-repair) need the crate in the workspace. A red member must
    not LAND -- the flip lands only once it is green on all three arches -- but it has to be
    a member while it is being worked on."""
    manifest = REPO / "sdk" / "lib" / "rust" / "Cargo.toml"
    text = manifest.read_text()
    m = re.search(r"^members = \[\n(.*?)^\]", text, re.M | re.S)
    if not m:
        raise PortError(f"{manifest}: no `members = [ ... ]` block")
    if re.search(rf'^\s*"{re.escape(crate)}",?\s*$', m.group(1), re.M):
        return False
    manifest.write_text(text[: m.end(1)] + f'    "{crate}",\n' + text[m.end(1) :])
    return True


# --------------------------------------------------------------------------------------
# translate
# --------------------------------------------------------------------------------------


def _tu_output(state: dict, tu: str) -> Path:
    return _crate_dir(state) / "src" / state["stem"] / f"{Path(tu).stem}.rs"


def _has_body(path: Path) -> bool:
    if not path.is_file():
        return False
    text = path.read_text(errors="replace")
    return bool(re.search(r"\bfn\s+\w+", text))


def stage_translate(
    stem: str,
    *,
    model: str,
    cost_cap: float,
    only: list[str],
    dry_run: bool,
    mode: str = "mechanical",
    concurrency: int = 5,
) -> None:
    state = load_state(stem)
    started = time.time()
    todo = [
        t
        for t in state["tus"]
        if (not only or Path(t).name in only) and not _has_body(_tu_output(state, t))
    ]
    spent = 0.0
    done: list[dict] = []
    for tu in todo:
        left = cost_cap - spent
        if left <= 0:
            print(
                f"translate: cost cap ${cost_cap:.2f} reached; {len(todo) - len(done)} TU(s) left"
            )
            break
        out = _tu_output(state, tu)
        cmd = [
            sys.executable,
            "-m",
            "rustconv",
            "translate",
            str(REPO / tu),
            "--target",
            f"{stem}:{state['module_dir']}",
            "--output-crate",
            state["crate"],
            "-m",
            model,
            "--seal-facts",
            "--seal-calls",
            "--seal-wide",
            "--retry-rejects",
            "1",
            "--cost-cap",
            f"{left:.2f}",
            "-o",
            str(out),
            "--mode",
            mode,
            "--concurrency",
            str(concurrency),
        ]
        if dry_run:
            cmd.append("--dry-run")
        t0 = time.time()
        proc = subprocess.run(cmd, cwd=REPO / "tools" / "rustconv", capture_output=True, text=True)
        log = STATE_ROOT / stem / f"translate-{Path(tu).stem}.log"
        log.write_text(proc.stdout + proc.stderr)
        cost = _run_cost(proc.stdout + proc.stderr)
        spent += cost
        done.append(
            {
                "tu": tu,
                "rc": proc.returncode,
                "usd": cost,
                "seconds": round(time.time() - t0, 1),
                "body": _has_body(out),
            }
        )
        print(
            f"translate: {Path(tu).name}: rc={proc.returncode} ${cost:.4f} "
            f"{'body' if _has_body(out) else 'NO BODY'} ({round(time.time() - t0)}s)"
        )
    _record(
        state,
        "translate",
        started,
        model=model,
        mode=mode,
        concurrency=concurrency,
        usd=round(spent, 4),
        runs=done,
        dry_run=dry_run,
    )
    print(f"translate: {len(done)} TU(s), ${spent:.4f}")


_COST_RE = re.compile(r"\$([0-9]+\.[0-9]+)")


def _run_cost(log: str) -> float:
    """The run's final reported spend: the last `[running $X]` / `total $X` figure it printed."""
    marks = [
        m for m in re.finditer(r"(?:running|total|spent|cost)[^\n$]*\$([0-9]+\.[0-9]+)", log, re.I)
    ]
    return float(marks[-1].group(1)) if marks else 0.0


