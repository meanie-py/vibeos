def stage_check(stem: str) -> dict:
    """Error counts per arch and per file, from the same JSON diagnostics `fix` and
    crate-repair count (the old short-format scrape disagreed with them by ~17)."""
    from . import crate_repair as cr

    state = load_state(stem)
    started = time.time()
    result: dict[str, dict] = {}
    for arch, diags in _check_json(stem, state["crate"]).items():
        per_file: dict[str, int] = {}
        untranslated = 0
        catch_all = 0
        for d in diags:
            # In a translated C `switch`, an unreachable arm means an earlier arm's "constant"
            # is a BINDING that matches everything (pciidex's `BusQueryDeviceID =>` answered
            # every ID query with the device ID). rustc only warns; it is a defect.
            if (d.get("code") or {}).get("code") == "unreachable_patterns":
                catch_all += 1
                primary = next((sp for sp in d.get("spans") or [] if sp.get("is_primary")), None)
                where = primary["file_name"] if primary else "<no span>"
                per_file[where] = per_file.get(where, 0) + 1
                continue
            if not cr.is_error_diagnostic(d):
                continue
            primary = next((sp for sp in d.get("spans") or [] if sp.get("is_primary")), None)
            where = primary["file_name"] if primary else "<no span>"
            # A module the scaffold declares but no translation has written yet is a TO-DO,
            # not a defect of the translated code; counting it as an error buried the signal.
            if "file not found for module" in str(d.get("message")):
                untranslated += 1
                continue
            per_file[where] = per_file.get(where, 0) + 1
        globs = _masking_glob(diags)
        # A C `case` constant that became a catch-all BINDING compiles with a warning only,
        # and is the one defect here that is a silent wrong answer (input's TVN_SELCHANGED
        # swallowed every WM_NOTIFY: OK never saved). Counted as an error so "clean" means it.
        catch: set[str] = set()
        suspects: set[str] = set()
        for d in diags:
            catch |= prelude_resolve.pattern_bindings(d)
            suspects |= prelude_resolve._shared_value_patterns(d)
        visible = prelude_resolve._visible_value_names(
            REPO / "sdk" / "lib" / "rust", state["crate"]
        )
        if suspects:
            catch |= suspects - visible
        # And statically: a bare UPPER_CASE arm that names nothing visible. A catch-all that is
        # the LAST arm leaves no arm unreachable, so rustc says nothing at all -- usrmgr's
        # `LVN_ENDLABELEDIT =>` sent every list-view notification to the label-edit handler.
        catch |= _undefined_arm_names(state, visible)
        if catch:
            per_file["<catch-all match arm>"] = len(catch)
            print(
                f"check {arch}: CATCH-ALL -- match arm(s) binding an undefined constant: "
                + ", ".join(sorted(catch))
            )
        errors = sum(per_file.values())
        result[arch] = {
            "rc": 101 if errors or untranslated else 0,
            "errors": errors,
            "untranslated": untranslated,
            "by_file": per_file,
            "masked_by": globs,
        }
        print(f"check {arch}: errors={errors} (+{untranslated} module(s) not translated yet)")
        if catch_all:
            print(
                f"check {arch}: {catch_all} of them are unreachable match arms -- an earlier "
                "arm binds everything (an enumerator `port resolve` did not alias)"
            )
        if globs:
            # rustc stops reporting unresolved names once a glob import fails: the name might
            # have come from that glob. inicache's invented `use ntdll_sys::nt::tier1::*;`
            # took setuplib from 40-odd E0425 to ZERO while fixing nothing.
            print(
                f"check {arch}: UNDERCOUNT -- a failed glob import hides every unresolved-name "
                f"error; fix it first (`port integrate` swaps substrate globs): {', '.join(globs)}"
            )
    # A C `for` lowered to `while` must repeat the step before every `continue`; a path that
    # never writes the loop variable retries the same index forever (atapi's enumerator).
    stuck = [
        f"{f.relative_to(REPO)}:{h.line} (no `{h.step}`)"
        for f in sorted(_crate_dir(state).glob("src/**/*.rs"))
        for h in loop_step.scan(f.read_text(errors="replace"))
    ]
    for line in stuck:
        print(f"check: continue skips the loop step -- {line}")
    # A union member written under its neighbour's name compiles (same type) and is silent:
    # pciidex's task-file block sent every command to port 0 and read Error as Status.
    _, decls = _pointer_decls(state)
    reslots = [
        f"{f.relative_to(REPO)}:{h.line} {h.fn} `.{h.member}`"
        for f in sorted(_crate_dir(state).glob("src/**/*.rs"))
        if not f.name.startswith("types_")
        for h in union_slot.scan(f.read_text(errors="replace"), decls)
    ]
    for line in reslots:
        print(f"check: union member the C never writes there -- {line}")
    # A `case` arm whose C ends `goto L;` must leave the Rust arm too: falling out runs the
    # code after the `match` (pciidex's START_DEVICE forwarded the IRP a second time).
    falls = [
        f"{f.relative_to(REPO)}:{h.line} {h.fn} `{h.case}` (C: goto {h.label})"
        for f in sorted(_crate_dir(state).glob("src/**/*.rs"))
        for h in goto_arm.scan(f.read_text(errors="replace"), decls)
    ]
    for line in falls:
        print(f"check: match arm falls through where the C jumps -- {line}")
    for r in result.values():
        r["loop_skips"] = len(stuck)
        r["union_reslots"] = len(reslots)
        r["goto_falls"] = len(falls)
        if stuck or reslots or falls:
            r["rc"] = 101
    _record(
        state,
        "check",
        started,
        **{
            a: {
                k: r[k]
                for k in (
                    "rc",
                    "errors",
                    "untranslated",
                    "loop_skips",
                    "union_reslots",
                    "goto_falls",
                )
            }
            for a, r in result.items()
        },
    )
    return result


_ARM = re.compile(r"(?m)^\s*((?:[A-Z][A-Z0-9_]*\s*\|\s*)*[A-Z][A-Z0-9_]*)\s*(?:if\b[^=]*)?=>")


def _undefined_arm_names(state: dict, visible: set[str]) -> set[str]:
    """UPPER_CASE bare-name `match` arms in the translated modules that name no constant the
    crate can see (its sources, ntdll-sys, the shared crates): each is a catch-all binding."""
    src_dir = _crate_dir(state) / "src" / state["stem"]
    out: set[str] = set()
    for p in src_dir.glob("*.rs"):
        text = p.read_text(errors="replace")
        for m in _ARM.finditer(text):
            for name in re.split(r"\s*\|\s*", m.group(1)):
                if name and name not in visible:
                    out.add(name)
    return out


def _masking_glob(diags: list[dict]) -> list[str]:
    """`file:line` of each failed GLOB import (E0432 whose `use` ends in `::*`)."""
    out = []
    for d in diags:
        if (d.get("code") or {}).get("code") != "E0432":
            continue
        primary = next((sp for sp in d.get("spans") or [] if sp.get("is_primary")), None)
        src = ((primary or {}).get("text") or [{}])[0].get("text", "")
        if primary and re.search(r"::\s*\*\s*;", src):
            out.append(f"{primary['file_name']}:{primary['line_start']}")
    return out


def stage_status(stem: str) -> None:
    state = load_state(stem)
    total = 0.0
    for s in state["stages"]:
        total += s["seconds"]
        extra = {k: v for k, v in s.items() if k not in ("stage", "seconds", "at", "runs")}
        print(f"{s['at']}  {s['stage']:10s} {s['seconds']:8.1f}s  {json.dumps(extra)[:140]}")
    print(f"{len(state['stages'])} stage run(s), {total / 60:.1f} min")
    # The ledger of record: translate logs are overwritten by every replay, so a spend summed
    # from them read $0 for runs that cost dollars (setuplib: "~$7" said, $10.10 recorded).
    usd: dict[str, float] = {}
    for st in state["stages"]:
        if isinstance(st.get("usd"), (int, float)):
            usd[st["stage"]] = usd.get(st["stage"], 0.0) + st["usd"]
    by_stage = ", ".join(f"{k} ${v:.2f}" for k, v in sorted(usd.items()))
    print(f"spent ${sum(usd.values()):.2f} ({by_stage or 'nothing'})")


def _module(arg: str) -> Path:
    p = Path(arg)
    return p if p.is_absolute() or p.exists() else REPO / p


def _hold(name: str):
    """One `port` run per module at a time, across shells and sessions.

    Two replays of setuplib once ran at once -- a background launch that looked dead was not --
    and each rewrote the modules, the hand bank and the fix splices under the other. An
    exclusive flock on the module's state dir; the second run fails at once and says so.
    """
    import fcntl

    path = STATE_ROOT / name / ".lock"
    path.parent.mkdir(parents=True, exist_ok=True)
    f = path.open("a+")
    try:
        fcntl.flock(f, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        f.close()
        raise PortError(
            f"another `rustconv port` run holds {name} ({path}); let it finish"
        ) from None
    return f


def main(args) -> int:
    if args.port_stage == "status":  # read-only: never waits on, or blocks, a running stage
        return _main(args)
    try:
        held = _hold(getattr(args, "stem", None) or _module(args.module).resolve().name)
    except PortError as e:
        print(f"port: {e}", file=sys.stderr)
        return 1
    try:
        return _main(args)
    finally:
        held.close()


def _main(args) -> int:
    try:
        if args.port_stage == "derive":
            stage_derive(
                _module(args.module), args.target, args.usermode, args.functions, args.block
            )
        elif args.port_stage == "island":
            stage_island(args.stem)
        elif args.port_stage == "cppapp":
            stage_cppapp(args.stem)
        elif args.port_stage == "scaffold":
            stage_scaffold(_module(args.module), args.target)
        elif args.port_stage == "translate":
            if args.expand_macros:
                tus = args.only or [Path(t).name for t in load_state(args.stem)["tus"]]
                on = set_expand_macros(args.stem, tus)
                print(f"translate: macros expanded in the C for {', '.join(on)}")
            spent, ran = stage_translate(
                args.stem,
                revisit=(args.only or None) if args.expand_macros else None,
                model=args.model,
                cost_cap=args.cost_cap,
                only=args.only or [],
                dry_run=args.dry_run,
                mode=args.mode,
                concurrency=args.concurrency,
                thinking="off" if args.escalate else args.thinking,
                rebuy_fn=args.rebuy_fn,
                replay_only=args.replay_only,
                no_c2rust=args.no_c2rust,
                skip_fn=args.skip_fn,
            )
            if args.escalate and not args.dry_run:
                # One cap for the whole invocation, and the escalation revisits only what
                # the cheap pass just bought -- not every TU that already had output. With
                # nothing new (everything already translated) it re-checks what was asked.
                # Plus every TU holding a banked body the CURRENT audit refuses: usetup's
                # cabinet.c and cmdcons.c kept literal C `goto`s through an escalation that
                # never looked at them (they had output), and every replay reassembled them
                # into parse errors that hid the crate's real type errors.
                stale = failing_audit_tus(load_state(args.stem))
                if args.only:
                    stale = [t for t in stale if t in args.only]
                stage_translate(
                    args.stem,
                    model=args.model,
                    cost_cap=max(0.0, args.cost_cap - spent),
                    only=sorted(set(ran) | set(stale)) or args.only or [],
                    dry_run=False,
                    mode=args.mode,
                    concurrency=args.concurrency,
                    thinking="on",
                    escalate=True,
                )
        elif args.port_stage == "headers":
            stage_headers(
                args.stem,
                model=args.model,
                cost_cap=args.cost_cap,
                dry_run=args.dry_run,
                thinking=args.thinking,
            )
        elif args.port_stage == "macros":
            stage_macros(
                args.stem,
                model=args.model,
                cost_cap=args.cost_cap,
                dry_run=args.dry_run,
                thinking=args.thinking,
            )
        elif args.port_stage == "replay":
            stage_replay(
                args.stem, fix_cap=args.fix_cap, fix_rounds=args.fix_rounds, model=args.model
            )
        elif args.port_stage == "fix":
            stage_fix(
                args.stem,
                model=args.model,
                cost_cap=args.cost_cap,
                rounds=args.rounds,
                thinking=args.thinking,
                concurrency=args.concurrency,
                only=args.only,
                dry_run=args.dry_run,
            )
        elif args.port_stage == "hand":
            if args.apply:
                apply_hand(args.stem)
            else:
                stage_hand(args.stem, args.functions, drop=args.drop)
        elif args.port_stage == "integrate":
            stage_integrate(args.stem)
        elif args.port_stage == "resolve":
            stage_resolve(args.stem)
        elif args.port_stage == "check":
            stage_check(args.stem)
        elif args.port_stage == "flip":
            stage_flip(args.stem)
        elif args.port_stage == "data":
            stage_data(args.stem, args.tu)
        elif args.port_stage == "oracle":
            stage_oracle(args.stem)
        elif args.port_stage == "status":
            stage_status(args.stem)
    except (PortError, pd.ProfileDeriveError) as e:
        print(f"port: {e}", file=sys.stderr)
        return 1
    return 0


def add_parser(sub) -> None:
    p = sub.add_parser("port", help="Drive one plain-C module to a Rust crate, stage by stage")
    stages = p.add_subparsers(dest="port_stage", required=True)
    for name in ("derive", "scaffold"):
        q = stages.add_parser(name)
        q.add_argument("module", help="module directory (holding CMakeLists.txt)")
        q.add_argument("--target", default=None, help="CMake target, when there are several")
    mode = stages.choices["derive"].add_mutually_exclusive_group()
    mode.add_argument(
        "--usermode",
        dest="usermode",
        action="store_const",
        const=True,
        default=None,
        help="a static library whose consumers are in another CMakeLists (remembered)",
    )
    mode.add_argument("--kernel", dest="usermode", action="store_const", const=False)
    stages.choices["derive"].add_argument(
        "--functions",
        choices=("blocked", "from-crate"),
        default=None,
        help="island function declarations: blocked (BLOCKLIST_FUNCS=1, the default) or "
        "from-crate (emit them minus the crate's own #[no_mangle]); remembered",
    )
    stages.choices["derive"].add_argument(
        "--block",
        action="extend",
        nargs="*",
        default=[],
        metavar="NAME",
        help="island items to blocklist (EXTRA_BL_ITEMS); remembered",
    )
    for name in ("island", "integrate", "resolve", "check", "status", "flip"):
        stages.add_parser(name).add_argument("stem")
    stages.add_parser(
        "cppapp", help="a C++ module: render its classes, lower its bodies to synthetic units ($0)"
    ).add_argument("stem")
    stages.add_parser(
        "oracle", help="the pre-flip C as <target>_c, for modrun's runtime diff (c_oracle)"
    ).add_argument("stem")
    q = stages.add_parser("data", help="a C DATA TU (tables, no code) as Rust statics, $0")
    q.add_argument("stem")
    q.add_argument("tu", help="the .c, relative to the module (or the repo)")
    q = stages.add_parser("hand", help="bank hand-written functions so replays keep them")
    q.add_argument("stem")
    q.add_argument(
        "functions", nargs="*", help="file.rs:Name, or file.rs:New=Old (from src/<stem>/)"
    )
    q.add_argument("--drop", action="store_true", help="forget these banked functions")
    q.add_argument("--apply", action="store_true", help="re-apply every banked function")
    q = stages.add_parser(
        "headers",
        help="translate the header inline functions the crate calls, through a TU that "
        "includes each header (after resolve; replay keeps them)",
    )
    q.add_argument("stem")
    q.add_argument("-m", "--model", default="haiku")
    q.add_argument("--cost-cap", type=float, required=True)
    q.add_argument("--dry-run", action="store_true")
    q.add_argument("--thinking", choices=("on", "off"), default="off")
    q = stages.add_parser("macros", help="port the module's own C macros the crate calls")
    q.add_argument("stem")
    q.add_argument("-m", "--model", default="haiku")
    q.add_argument("--cost-cap", type=float, default=0.30)
    q.add_argument("--dry-run", action="store_true")
    q.add_argument("--thinking", choices=("on", "off"), default="on")
    q = stages.add_parser("replay", help="rebuild the crate from the banks, in order, for $0")
    q.add_argument("stem")
    q.add_argument("--fix-cap", type=float, default=0.0, help="USD of NEW fix purchases")
    q.add_argument("--fix-rounds", type=int, default=1)
    q.add_argument("-m", "--model", default="haiku", help="model for NEW fix purchases")
    q = stages.add_parser(
        "fix", help="send each function rustc still rejects back to the model, errors attached"
    )
    q.add_argument("stem")
    q.add_argument("-m", "--model", default="haiku")
    q.add_argument("--cost-cap", type=float, required=True)
    q.add_argument("--rounds", type=int, default=3)
    # off: retries carry the refusal reason instead (escalating bought the same wrong
    # answers at ~10x on setuplib). escalate: thinking on for refused functions too.
    q.add_argument("--thinking", choices=("off", "on", "escalate"), default="off")
    q.add_argument("--concurrency", type=int, default=8)
    q.add_argument("--only", nargs="*", help="function names to limit the run to")
    q.add_argument("--dry-run", action="store_true")
    q = stages.add_parser("translate")
    q.add_argument("stem")
    q.add_argument("-m", "--model", default="haiku")
    q.add_argument(
        "--cost-cap",
        type=float,
        required=True,
        help=(
            "USD for this invocation: no new TU starts once it is spent. A TU already running "
            "is never killed (that re-bills it), and translate's own per-TU cap is an "
            "estimate, so the last TU can overshoot -- setuplib's $3 run ended at $3.18"
        ),
    )
    q.add_argument("--only", nargs="*", help="TU file names to limit the run to")
    q.add_argument(
        "--expand-macros",
        action="store_true",
        help="from now on, expand the module's own macros in the C of these TUs (--only, or "
        "all); recorded in the state so replay keeps asking the bank the same question",
    )
    q.add_argument("--dry-run", action="store_true")
    # mechanical: a faithful transliteration (C control flow and pointers kept), which is
    # what the placement and difftest oracles compare against -- and the only mode
    # translate fans out under --concurrency.
    q.add_argument("--mode", choices=["mechanical", "idiomatic"], default="mechanical")
    q.add_argument("--concurrency", type=int, default=5)
    # Measured on setuplib: thinking OFF is ~1/40th the cost per small function, but it
    # carried C `goto`s over literally in 2 of 6 TUs. --escalate takes the cheap pass first,
    # then re-buys ONLY what the deterministic checks reject, with thinking on.
    q.add_argument("--thinking", choices=["on", "off"], default="on")
    q.add_argument(
        "--escalate",
        action="store_true",
        help="cheap pass with thinking off, then thinking on for rejects only",
    )
    q.add_argument(
        "--rebuy-fn",
        action="extend",
        nargs="*",
        default=[],
        metavar="NAME",
        help="accepted bodies to buy again (passed to translate --rebuy-fn); revisits their TUs",
    )
    q.add_argument(
        "--no-c2rust",
        action="extend",
        nargs="*",
        default=[],
        metavar="TU",
        help="TU file names to translate without a c2rust anchor, as a deliberate choice "
        "when c2rust cannot transpile them on any arch (remembered in the port state)",
    )
    q.add_argument(
        "--skip-fn",
        action="extend",
        nargs="*",
        default=[],
        metavar="NAME",
        help="functions to assemble their TU without (hand-port them, then `port hand`); "
        "remembered in the port state, and recorded as an audit finding by translate",
    )
    q.add_argument(
        "--replay-only",
        action="store_true",
        help="reassemble every TU from banked bodies only ($0; a missing body is an error)",
    )
