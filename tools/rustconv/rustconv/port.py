_WINE_DEFAULT_CHANNEL = re.compile(r"^[ \t]*WINE_DEFAULT_DEBUG_CHANNEL\(\s*(\w+)\s*\)", re.M)
_CHANNEL_ITEM = re.compile(
    r"^[ \t]*(?:pub(?:\([^)]*\))?[ \t]+)?(?:static[ \t]+(?:mut[ \t]+)?|const[ \t]+)"
    r"(__wine_dbch_\w+)[ \t]*:",
    re.M,
)
# `static NAME: () = ();` -- what the model writes for a C forward declaration it has no Rust
# spelling for. Never meaningful, and when NAME is the function's own (comctl32's
# UPDOWN_Paint, TOOLBAR_CalcStrings) it is a duplicate definition.
_UNIT_PLACEHOLDER = re.compile(
    r"(?:^[ \t]*#\[[^\n]*\]\n(?:[ \t]*\n)*)*^[ \t]*(?:pub(?:\([^)]*\))?[ \t]+)?static[ \t]+"
    r"\w+[ \t]*:[ \t]*\(\)[ \t]*=[ \t]*\(\)[ \t]*;[ \t]*\n",
    re.M,
)


def _strip_unit_placeholders(state: dict) -> list[str]:
    """Drop every `static NAME: () = ();` (and its attributes) from the module's outputs."""
    changed = []
    for tu in state["tus"]:
        path = _tu_output(state, tu)
        if not path.is_file():
            continue
        text = path.read_text()
        new = _UNIT_PLACEHOLDER.sub("", text)
        if new != text:
            path.write_text(new)
            changed.append(path.stem)
    return changed


def _strip_channel_items(text: str) -> str:
    """Remove every `static __wine_dbch_*` item -- a definition or an extern-block entry --
    through its terminating `;` at bracket depth 0, with any attribute lines above it."""
    while m := _CHANNEL_ITEM.search(text):
        depth, i = 0, m.end()
        while i < len(text):
            ch = text[i]
            if ch in "([{":
                depth += 1
            elif ch in ")]}":
                depth -= 1
            elif ch == ";" and depth == 0:
                break
            i += 1
        start = m.start()
        while True:  # attributes and a comment naming the macro ride with the item
            prev = text.rfind("\n", 0, max(start - 1, 0)) + 1
            line = text[prev:start].strip()
            if start and (line.startswith("#[") or line.startswith("// WINE_DEFAULT_DEBUG")):
                start = prev
                continue
            break
        end = text.find("\n", i)
        text = text[:start] + text[(len(text) if end < 0 else end + 1) :]
    return text


def _wine_channel_macro_calls(state: dict, crate: Path) -> list[str]:
    """Give each module its `WINE_DEFAULT_DEBUG_CHANNEL(ch)` deterministically.

    The macro defines a per-file `static struct __wine_debug_channel __wine_dbch_ch =
    { ~0, "ch" }` and `__wine_dbch___default` pointing at it, and the translated TRACE/ERR
    sites read both. Left to the paid preamble, comctl32's 38 files came back as six
    different things: a byte string, an `extern` declaration nothing defines (an undefined
    symbol at link), and a struct with `flags: 0` where the C says `~0` -- logging silently
    off. A header macro is substrate, not translation: strip whatever the preamble made of
    it and invoke the prelude's `wine_default_debug_channel!` instead. Opt-in by the prelude
    defining that macro, and re-applied on every integrate, so a replay keeps it.
    """
    prelude = crate / "src" / "prelude.rs"
    if "macro_rules! wine_default_debug_channel" not in prelude.read_text(errors="replace"):
        return []
    changed = []
    for tu in state["tus"]:
        m = _WINE_DEFAULT_CHANNEL.search((REPO / tu).read_text(errors="replace"))
        path = _tu_output(state, tu)
        if m is None or not path.is_file():
            continue
        text = path.read_text()
        call = f"crate::wine_default_debug_channel!(__wine_dbch_{m.group(1)});\n"
        new = _strip_channel_items(text)
        if call not in new:
            # After the leading inner attributes and `use` lines, before the first item.
            lines = new.splitlines(keepends=True)
            at = 0
            for i, line in enumerate(lines):
                if line.startswith(("#![", "use ", "pub use ")) or not line.strip():
                    at = i + 1
                    continue
                if line.lstrip().startswith("//"):
                    continue
                break
            lines.insert(at, call)
            new = "".join(lines)
        if new != text:
            path.write_text(new)
            changed.append(path.stem)
    return changed


def _drop_stale_variadic_imports(files: list[Path], names: set[str]) -> None:
    """Drop `use crate::<m>::F;` for each C-variadic entry F the prelude now declares.

    A sibling was wired to F while <m> still extern-declared it; that block is stripped, so
    the import names a private glob re-export (E0603) -- cmd had 7, ErrorMessage and
    ConOutPrintfPaging. The prelude's extern block is F's one declaration.
    """
    if not names:
        return
    stale = re.compile(
        rf"^use crate::[\w:]+::(?:{'|'.join(map(re.escape, sorted(names)))});\n", re.M
    )
    for path in files:
        text = path.read_text()
        if (new := stale.sub("", text)) != text:
            path.write_text(new)


def _variadic_twins(state: dict, crate: Path, stem: str) -> tuple[list[str], dict[str, str]]:
    """C-variadic definitions -> a Rust `_v` twin + a generated C trampoline (variadic_shim).

    The shim is regenerated from EVERY twin in the crate each run (not just this run's new
    ones). Fails loud when a twin has no variadic C definition of the same arity, or a
    parameter has no ABI-identical primitive C spelling: a twin without its trampoline links
    nothing under the original name, and every caller is a silent unresolved import.
    """
    done: list[str] = []
    refused: dict[str, str] = {}
    all_twins: dict[str, tuple[list[tuple[str, str]], str]] = {}
    twin_texts: list[str] = []
    for path in _unit_files(crate, stem):
        rw = variadic_shim.rewrite(path.read_text())
        refused.update(rw.refused)
        if rw.names:
            path.write_text(rw.text)
            done += rw.names
        lowered, n = variadic_shim.lower_twin_va_starts(path.read_text())
        if n:
            path.write_text(lowered)
        # The rewrite's own per-file `extern "C" { fn F(.., ...) }` spells parameters in the
        # C's text (sndvol32: `lpTarget: *LPWSTR`, not Rust) and duplicates the prelude block
        # written below from the twin: drop it.
        text = path.read_text()
        stripped = re.sub(
            r'extern "C" \{\n    // The C-variadic entry is a trampoline[^\n]*\n'
            r"(?:    //[^\n]*\n)*(?:    pub fn \w+\([^\n]*\.\.\.\)[^\n]*;\n)+\}\n",
            "",
            text,
        )
        if stripped != text:
            path.write_text(stripped)
        if found := variadic_shim.twins(path.read_text()):
            all_twins.update(found)
            twin_texts.append(path.read_text(errors="replace"))
    for name, why in refused.items():
        print(f"integrate: variadic {name} left as is: {why}")
    _drop_stale_variadic_imports(list(_unit_files(crate, stem)), set(all_twins))
    # A twin a hand-banked function replaces gets no trampoline: the hand version defines the
    # C name itself (ndis's NdisWriteErrorLogEntry reads only its fixed arguments, so it is a
    # plain fixed-arity `extern "C"` fn), and a trampoline would define it a second time.
    replaced = set()
    for entry in _hand_dir(stem).glob("*.json"):
        try:
            replaced.add(json.loads(entry.read_text())["name"])
        except (OSError, ValueError, KeyError):
            continue
    all_twins = {n: v for n, v in all_twins.items() if f"{n}_v" not in replaced}
    if not all_twins:
        return done, refused
    units = [REPO / u for u in _units(state) if (REPO / u).is_file()]
    sys_src = prelude_resolve.island_substrate(crate / "src", REPO / "sdk" / "lib" / "rust")
    # The twins' own files come FIRST (alias_maps keeps the first spelling), then the crate's
    # prelude: a module-local typedef such as cmd's `LPDIRSWITCHFLAGS` (dir.c's DirPrintf) is
    # declared in the unit and later hoisted to the prelude by resolve -- never in the island
    # -- and a local alias shadows an island one exactly as Rust's scope does.
    prelude = crate / "src" / "prelude.rs"
    if prelude.is_file():
        twin_texts.append(prelude.read_text(errors="replace"))
    maps = variadic_shim.alias_maps(
        [
            twin_texts
            + [
                p.read_text(errors="replace")
                for p in (
                    crate / "src" / f"types_{suffix}.rs",
                    *(
                        (sys_src / f"bindgen_{suffix}.rs", sys_src / "bindgen_common.rs")
                        if sys_src is not None
                        else ()
                    ),
                )
                if p.is_file()
            ]
            for suffix in ("i386", "amd64", "arm64")
        ]
    )
    entries: dict[str, tuple[str, str]] = {}
    for name, (params, ret) in sorted(all_twins.items()):
        tu = next(
            (
                u
                for u in units
                if variadic_shim.c_variadic_arity(u.read_text(errors="replace"), name) is not None
            ),
            None,
        )
        if tu is None:
            raise SystemExit(f"integrate: {name}_v has no C definition of {name} with `...`")
        arity = variadic_shim.c_variadic_arity(tu.read_text(errors="replace"), name)
        if arity != len(params):
            raise SystemExit(
                f"integrate: {name}_v takes {len(params)} fixed parameter(s), the C {arity}"
            )
        try:
            entries[name] = (str(tu), variadic_shim.c_trampoline(name, params, ret, maps))
        except ValueError as e:
            raise SystemExit(f"integrate: cannot spell {name}'s trampoline: {e}") from e
    shim = variadic_shim.write_shim(REPO / state["module_dir"], entries)
    variadic_shim.ensure_dependency(crate / "Cargo.toml")
    # The C entry callers name (`ErrorMsgBox(h, id, arg)`) is the trampoline, declared here
    # from the twin. A declaration a translation carried by hand sat outside every bank, so
    # `port replay` dropped it and fontview's ten ErrorMsgBox calls went unresolved.
    prelude = crate / "src" / "prelude.rs"
    decls = [
        f"    pub fn {name}({''.join(f'{p}: {t}, ' for p, t in params)}...)"
        + (f" -> {ret}" if ret and ret != "()" else "")
        + ";"
        for name, (params, ret) in sorted(all_twins.items())
    ]
    block = (
        "// ==== port variadic: C-variadic entry points, trampolines in the module's "
        "rust_varargs_shim.c (generated -- `rustconv port integrate`) ====\n"
        'extern "C" {\n' + "\n".join(decls) + "\n}\n// ==== end port variadic ====\n"
    )
    text = prelude.read_text()
    m = re.search(r"// ==== port variadic:.*?// ==== end port variadic ====\n", text, re.S)
    new = text[: m.start()] + block + text[m.end() :] if m else text.rstrip("\n") + "\n\n" + block
    if new != text:
        prelude.write_text(new)
    print(
        f"integrate: {len(entries)} C-variadic entry point(s) -> `_v` twin + "
        f"{shim.relative_to(REPO)}: {', '.join(sorted(entries))}"
        + (f" ({len(done)} rewritten this run)" if done else "")
    )
    print("integrate: the shim must be in the module's cohab CMake source list")
    return done, refused


# One-line scalar consts only: a c2rust-laid `[WCHAR; 24]` table (`unsafe { transmute(..) }`,
# spanning lines and holding `;`) is a different TYPE from the island's `&[u16; N]` literal
# and is the module's own storage, not a shadow.
_TOP_CONST = re.compile(
    r"^(?:pub(?:\([^)]*\))?\s+)?const\s+([A-Za-z_]\w*)\s*:\s*(?!\[)[^=\n]+=\s*(?!unsafe\b)([^;\n{]+);[^\n]*\n",
    re.M,
)


def _island_consts(src: Path) -> dict[str, str]:
    """`pub const NAME = VALUE` the island (clang-exact, from the module's own headers)
    defines identically on every arch."""
    per = [
        dict(re.findall(r"^pub const (\w+): [^=]+= ([^;]+);", p.read_text(errors="replace"), re.M))
        for p in sorted(src.glob("types_*.rs"))
    ]
    if not per:
        return {}
    return {k: v for k, v in per[0].items() if all(d.get(k) == v for d in per[1:])}


def _drop_island_shadows(path: Path, island: dict[str, str]) -> list[str]:
    """A TOP-LEVEL `const` in a translated module that the island also defines.

    The island is the header as clang read it; a module-level copy can only shadow it, and
    the model writes them from memory: timedate's preamble carried `IDC_CPLICON = 1000`,
    `IDS_CPLNAME = 100`, `IDS_CPLDESCRIPTION = 101` ("Assumed values") over resource.h's 1,
    1001, 1002 -- the applet lost its icon, name and description. Dropped so the island's
    value is the one in scope; a differing value is reported."""
    text = path.read_text()
    out: list[str] = []

    def repl(m: re.Match[str]) -> str:
        name, value = m.group(1), m.group(2).strip()
        if name not in island:
            return m.group(0)
        norm = lambda v: re.sub(r"\s|_|(?:as\s+\w+)|(?:u|i)(?:8|16|32|64|size)\b", "", v)  # noqa: E731
        same = norm(value) == norm(island[name])
        out.append(name if same else f"{name} (was {value}, island {island[name]})")
        return ""

    new = _TOP_CONST.sub(repl, text)
    if new != text:
        path.write_text(new)
    return out


_COUNT_OF_PTR = re.compile(
    r"\b(ARRAYSIZE|_countof|RTL_NUMBER_OF)!\(\s*core::ptr::addr_of_mut!\(([^()]*(?:\([^()]*\)[^()]*)*)\)(?:\s+as\s+[\w:*]+)?\s*\)"
)


_LOCAL_CONST = re.compile(
    r"(?m)^(?P<head>(?:pub(?:\([^)]*\))?\s+)?const\s+(?P<name>[A-Za-z_]\w*)\s*:\s*(?P<ty>[\w:]+)\s*=\s*)"
    r"(?P<val>-?\(?\s*-?(?:0[xX][0-9a-fA-F_]+|[0-9][0-9_]*)(?:[iu](?:8|16|32|64|size))?\s*\)?(?:\s+as\s+[\w:]+)*)\s*;"
)


def _verify_local_defines(path: Path, c_file: Path) -> list[str]:
    """A module-level integer `const` the C `#define`s in its own TU, checked against clang.

    The preamble writes a TU's own constants from MEMORY: usrmgr's
    `#define VALID_GENERAL_FLAGS (UF_PASSWD_CANT_CHANGE | ... | UF_LOCKOUT)` came back as
    `0x0001_0242` with a comment calling UF_LOCKOUT 0x200 (it is 0x10), so unchecking
    "Account is locked out" never unlocked. The seal never sees file-scope `#define` bodies.
    clang evaluates the name in the TU on every arch; a different value is replaced."""
    from . import sdk_facts
    from .macro_authority import MacroAuthorityError

    c_text = c_file.read_text(errors="replace")
    defined = set(re.findall(r"(?m)^\s*#\s*define\s+([A-Za-z_]\w*)\s+\S", c_text))
    text = path.read_text()
    found = {m.group("name"): m for m in _LOCAL_CONST.finditer(text) if m.group("name") in defined}
    if not found:
        return []
    try:
        res = sdk_facts.resolve(REPO, c_file, sorted(found))
    except MacroAuthorityError:
        return []
    out: list[str] = []
    for fact in res.facts:
        m = found[fact.name]
        lit = re.search(r"-?\s*(0[xX][0-9a-fA-F_]+|[0-9][0-9_]*)", m.group("val"))
        if lit is None:
            continue
        neg = m.group("val").lstrip("(").lstrip().startswith("-")
        have = int(lit.group(1).replace("_", ""), 0) * (-1 if neg else 1)
        # Equal as values, or as the same 32-bit pattern (`-1` vs `0xFFFFFFFF` for a DWORD).
        if have == fact.value or (have & 0xFFFFFFFF) == (fact.value & 0xFFFFFFFF):
            continue
        new_val = f"{fact.value:#x}" if fact.value >= 0 else str(fact.value)
        text = text.replace(m.group(0), f"{m.group('head')}{new_val} as {m.group('ty')};", 1)
        out.append(f"{fact.name} {m.group('val').strip()} -> {new_val}")
    if out:
        path.write_text(text)
    return out


_ADDR_OF_FIELD = re.compile(
    r"core::ptr::addr_of(?:_mut)?!\(\(\*(?P<var>[A-Za-z_]\w*)\)\.(?P<field>[A-Za-z_]\w*)\)"
    r"(?P<casts>(?:\s+as\s+\*(?:const|mut)\s+(?:WCHAR|u16|c_char|i8|u8|CHAR))"
    r"(?:\s+as\s+[\w:]+)*)"
)
_PTR_TYPE = re.compile(r"^(?:\*(?:const|mut)\s|L?P(?:C)?(?:W)?STR$|L?P(?:C)?TSTR$|PWCHAR$|PCHAR$)")


def _struct_fields(src: Path) -> dict[str, dict[str, str]]:
    """struct -> field -> declared type text, across the crate (islands and modules)."""
    if str(REPO) not in sys.path:
        sys.path.insert(0, str(REPO))
    from tools.source_walk import source_files

    out: dict[str, dict[str, str]] = {}
    for p in source_files(src, "*.rs"):
        for m in re.finditer(r"pub struct (\w+)\s*\{([^}]*)\}", p.read_text(errors="replace")):
            out.setdefault(m.group(1), {}).update(
                {f: t.strip() for f, t in re.findall(r"pub (\w+)\s*:\s*([^,\n]+),", m.group(2))}
            )
    return out


def _pointer_field_not_address(path: Path, src: Path) -> list[str]:
    """`addr_of!((*p).f) as *const WCHAR` where `f` is itself a POINTER (`PWSTR`), not an array.

    For an array field the address IS the string; for a pointer field it is the address of
    the pointer, read as UTF-16 garbage. mmsys's ShowSoundScheme did both in adjacent lines --
    `APP_MAP.szName` is `WCHAR[MAX_PATH]`, `LABEL_MAP.szName` a `PWSTR` -- so every sound
    label showed the pointer's bytes. The variable's declared type names the struct; only a
    field whose declared type is a pointer is rewritten to its value."""
    if str(REPO) not in sys.path:
        sys.path.insert(0, str(REPO))
    from tools.source_walk import source_files

    text = path.read_text()
    if "addr_of" not in text:
        return []
    fields = _struct_fields(src)
    aliases: dict[str, str] = {}
    for p in source_files(src, "*.rs"):
        for a, t in re.findall(
            r"pub type (\w+)\s*=\s*\*mut\s+(\w+)\s*;", p.read_text(errors="replace")
        ):
            aliases[a] = t
    decl = re.compile(r"\b(?:let\s+mut\s+|let\s+|mut\s+)?(\w+)\s*:\s*(?:\*mut\s+)?(\w+)\s*[=,)]")
    fn_starts = [
        m.start()
        for m in re.finditer(r"(?m)^\s*(?:pub\s+)?(?:unsafe\s+)?(?:extern\s+\"\w+\"\s+)?fn\s", text)
    ]
    out: list[str] = []

    def var_type(var: str, at: int) -> str | None:
        # Scoped to the ENCLOSING function: mmsys declares `pMap` as PAPP_MAP in FindApp
        # and as PLABEL_MAP elsewhere, and a file-wide table picked the wrong one.
        start = max((f for f in fn_starts if f <= at), default=0)
        hits = [t for v, t in decl.findall(text[start:at]) if v == var]
        return hits[-1] if hits else None

    def repl(m: re.Match[str]) -> str:
        ty = var_type(m.group("var"), m.start())
        struct = aliases.get(ty or "", ty)
        while struct in aliases:
            struct = aliases[struct]
        ftype = fields.get(struct or "", {}).get(m.group("field"))
        if ftype is None or not _PTR_TYPE.search(ftype):
            return m.group(0)
        out.append(f"{m.group('var')}.{m.group('field')}")
        return f"((*{m.group('var')}).{m.group('field')}){m.group('casts')}"

    new = _ADDR_OF_FIELD.sub(repl, text)
    if new != text:
        path.write_text(new)
    return out


def _count_the_array(path: Path) -> int:
    """`ARRAYSIZE!(addr_of_mut!(x) [as LPWSTR])` -> `ARRAYSIZE!(x)`.

    C's `ARRAYSIZE(x)` names the ARRAY; the model, having spelled every other use of the
    buffer as a pointer, passed the pointer too, and `.len()` of a raw pointer does not
    exist (console's font.rs, four sites). The element count is a property of the array,
    which is what the C measured."""
    text = path.read_text()
    new, n = _COUNT_OF_PTR.subn(lambda m: f"{m.group(1)}!({m.group(2)})", text)
    if n:
        path.write_text(new)
    return n


