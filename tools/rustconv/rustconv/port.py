"""rustconv port — take one plain-C module to a Rust crate, stage by stage.

WHY THIS EXISTS
---------------
Measured 2026-10-05 over ~280 agent-hours of the translation lanes' sessions: the paid
translate calls were 1-6% of the time; smoke/gate/build/check were 45-60% and reading
another 17-24%. A module port is mostly HAND-OFFS between tools that already exist --
profile_derive prints a profile "to paste into gen_driver_types.sh", the island is
generated by hand, the crate is scaffolded by hand, each TU is translated with flags an
agent must remember, and the cargo grind is run per arch. This command does the hand-offs,
in order, idempotently, and records how long each stage took.

STAGES (each re-runnable; state in ~/vibeos-rust-staging/port/<stem>/state.json)
  derive     profile_derive the module, refuse on blocking ERROR findings, and upsert the
             derived arm into gen_driver_types.sh.
  island     run gen_driver_types.sh <stem> into the crate (all three arches).
  scaffold   write the crate skeleton (never overwrites; the island is kept).
  translate  sealed DeepSeek translation of each TU that has no body yet, under --cost-cap.
  integrate  move each translated file onto the crate prelude (crate_integrate).
  resolve    fill the prelude from what the tree already agrees on (prelude_resolve).
  fix        compiler-in-the-loop: each function rustc still rejects goes back to the
             model with its errors attached; guarded, banked, reverted if worse.
  check      cargo check on all three targets; error counts per file.
  replay     all of the above from the banks, in order, for $0 (resolve twice: see there).

It never touches CMake, the workspace members or the build: the flip is a separate,
deliberate step once `check` is green on every arch.
"""

