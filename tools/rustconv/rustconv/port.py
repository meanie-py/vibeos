_WINE_BEGIN = "// ==== port resolve: wine debug channels (generated) ===="
_WINE_END = "// ==== end wine debug channels ===="


def _wine_debug_channels(state: dict, prelude: Path) -> list[str]:
    """wine/debug.h's `WINE_DEFAULT_DEBUG_CHANNEL(ch)` / `WINE_DECLARE_DEBUG_CHANNEL(ch)`:
    `static struct __wine_debug_channel __wine_dbch_ch = { (unsigned char)~0, "ch" }` and,
    for the default, `__wine_dbch___default = &__wine_dbch_ch`. Statics in a HEADER, so no
    translated function carries them and the island has only an `extern` -- usrmgr linked
    with `undefined symbol ___wine_dbch___default` on i386, as appwiz had (by hand)."""
    if "macro_rules! wine_default_debug_channel" in prelude.read_text():
        # Each file defines its own channel through the macro (_wine_channel_macro_calls):
        # comctl32's 39 TUs have 39 different DEFAULT channels, which one prelude-level
        # `__wine_dbch___default` cannot express. Writing statics here would duplicate them.
        return []
    module_dir = REPO / state["module_dir"]
    default: str | None = None
    declared: list[str] = []
    for f in sorted([*module_dir.rglob("*.c"), *module_dir.rglob("*.h")]):
        text = re.sub(r"/\*.*?\*/|//[^\n]*", "", f.read_text(errors="replace"), flags=re.S)
        for m in re.finditer(r"\bWINE_(DEFAULT|DECLARE)_DEBUG_CHANNEL\(\s*(\w+)\s*\)", text):
            if m.group(1) == "DEFAULT":
                default = default or m.group(2)
            if m.group(2) not in declared:
                declared.append(m.group(2))
    text = prelude.read_text()
    pat = re.compile(re.escape(_WINE_BEGIN) + r".*?" + re.escape(_WINE_END) + r"\n", re.S)
    outside = pat.sub("", text)
    src = "\n".join(
        p.read_text(errors="replace") for p in (prelude.parent / state["stem"]).glob("*.rs")
    )
    # win32macros-rust's WINE_TRACE!/TRACE!-family name the default channel in their
    # EXPANSION, which this text scan never sees: a call is a use of it.
    uses_default = "__wine_dbch___default" in src or bool(
        re.search(r"\bWINE_(?:TRACE|WARN|FIXME|ERR)!?\s*\(", src)
    )
    lines: list[str] = []
    for ch in declared:
        name = f"__wine_dbch_{ch}"
        needed = name in src or (ch == default and uses_default)
        if not needed or re.search(rf"\bstatic\s+(?:mut\s+)?{name}\b", outside + src):
            continue
        raw = ch.encode()[:14] + b"\0" * (15 - len(ch.encode()[:14]))
        lit = "".join(f"\\x{b:02x}" for b in raw)
        lines.append(
            f"pub static mut {name}: __wine_debug_channel = __wine_debug_channel {{\n"
            f"    flags: !0u8, // (unsigned char)~0\n"
            "    name: unsafe { ::core::mem::transmute::<[u8; 15], [::core::ffi::c_char; 15]>"
            f'(*b"{lit}") }},\n'
            "};"
        )
    if (
        default
        and uses_default
        and not re.search(r"\bstatic\s+(?:mut\s+)?__wine_dbch___default\b", outside)
    ):
        lines.append(
            "pub static mut __wine_dbch___default: *mut __wine_debug_channel =\n"
            f"    unsafe {{ &raw mut __wine_dbch_{default} }};"
        )
    # The types themselves: wine/debug.h is a base header no island allowlists, so a crate
    # whose bodies spell the expanded TRACE (`let __dbch: *mut __wine_debug_channel`) had
    # nothing to name -- inetcpl, 42 errors; dnsapi/iphlpapi/msgina carry hand copies.
    island = "\n".join(
        p.read_text(errors="replace") for p in sorted(prelude.parent.glob("types_*.rs"))
    )
    types: list[str] = []
    if re.search(r"\b__wine_debug_class\b", src + outside) and not re.search(
        r"\b(?:type|enum|struct)\s+__wine_debug_class\b", outside + island
    ):
        types.append("pub type __wine_debug_class = ::core::ffi::c_int; // enum, wine/debug.h")
    if (lines or re.search(r"\b__wine_debug_channel\b", src)) and not re.search(
        r"\bstruct\s+__wine_debug_channel\b", outside + island
    ):
        types.append(
            "#[repr(C)]\n"
            "pub struct __wine_debug_channel { // wine/debug.h\n"
            "    pub flags: ::core::ffi::c_uchar,\n"
            "    pub name: [::core::ffi::c_char; 15],\n"
            "}"
        )
    block = "\n".join([_WINE_BEGIN, *types, *lines, _WINE_END]) + "\n" if lines or types else ""
    new = (
        pat.sub(lambda _m: block, text)
        if pat.search(text)
        else (text.rstrip("\n") + "\n\n" + block if block else text)
    )
    if new != text:
        prelude.write_text(new)
    return [ln.split()[3].rstrip(":") for ln in lines] + [
        t.split("pub ", 1)[1].split()[1] for t in types
    ]


_A_ALIAS_RE = re.compile(r"^pub type (\w+) = (\w+)A;", re.M)


def _tchar_structs(state: dict, prelude: Path) -> dict[str, str]:
    """The TCHAR-dependent STRUCT names the crate uses, re-pointed at their W form.

    ntdll-sys is generated without UNICODE, so its `WNDCLASS` is `WNDCLASSA`: spider's
    `RegisterClass(&wndclass)` handed RegisterClassW an ANSI struct (a type error, caught --
    but only because the field types also differ). Any `pub type X = <base>A;` in the islands
    whose `<base>W` also exists, for a name the translated units actually spell."""
    crate_src = prelude.parent
    island = [crate_src / "types_amd64.rs"]
    island += sorted((REPO / "sdk" / "lib" / "rust" / "ntdll-sys" / "src").glob("*amd64*.rs"))
    text = "\n".join(p.read_text(errors="replace") for p in island if p.is_file())
    defined = set(re.findall(r"^pub (?:struct|type|union) (\w+)", text, re.M))
    units = "\n".join(
        p.read_text(errors="replace") for p in (crate_src / state["stem"]).glob("*.rs")
    )
    out = {}
    for name, base in _A_ALIAS_RE.findall(text):
        if f"{base}W" in defined and re.search(rf"\b{re.escape(name)}\b", units):
            out[name] = f"{base}W"
    return out


def _unicode_tchar(state: dict, prelude: Path) -> bool:
    """A UNICODE module's TCHAR is WCHAR; ntdll-sys (built without UNICODE) exports
    `TCHAR = c_char`, and a prelude that only globs it gave 27 control-panel buffers HALF
    the bytes the C has -- `RegEnumValueW` told 128 WCHARs into a 128-byte array. Written
    when every TU's real compile command carries -DUNICODE; a name the prelude already
    defines by hand is left to it."""
    from .macro_authority import compile_argv

    unicode = bool(state["tus"]) and all(
        "-DUNICODE" in (compile_argv(REPO, "amd64", (REPO / t).resolve()) or [])
        for t in state["tus"]
    )
    text = prelude.read_text()
    pat = re.compile(re.escape(_TCHAR_BEGIN) + r".*?" + re.escape(_TCHAR_END) + r"\n", re.S)
    outside = pat.sub("", text)
    hand = set(re.findall(r"^\s*pub type (\w+)", outside, re.M))
    block = ""
    if unicode:
        lines = [f"pub type {n} = {t};" for n, t in _TCHAR_TYPES.items() if n not in hand]
        lines += [
            f"pub type {n} = {t};"
            for n, t in sorted(_tchar_structs(state, prelude).items())
            if n not in hand and n not in _TCHAR_TYPES
        ]
        if lines:
            block = "\n".join([_TCHAR_BEGIN, *lines, _TCHAR_END]) + "\n"
    new = (
        pat.sub(lambda _m: block, text)
        if pat.search(text)
        else (text.rstrip("\n") + "\n\n" + block if block else text)
    )
    if new != text:
        prelude.write_text(new)
    return bool(block)


def _arch_link_names(state: dict, prelude: Path) -> list[str]:
    """Give each prelude extern that the preprocessor ALIASES on some arches only a
    `#[cfg_attr(target_arch = .., link_name = ..)]` for those arches (macro_authority.
    arch_only_aliases): i386's `GetWindowLongPtrW` is `GetWindowLongW`."""
    from .macro_authority import arch_only_aliases

    aliases: dict[str, dict[str, str]] = {}
    for tu in state["tus"]:
        try:
            aliases.update(arch_only_aliases(REPO, (REPO / tu).resolve()))
        except Exception:  # reported by the identifier-alias pass already
            continue
    text = prelude.read_text()
    done: list[str] = []
    lines = text.split("\n")
    out: list[str] = []
    for line in lines:
        m = re.match(r"(\s*)pub fn ([A-Za-z_]\w*)\s*\(", line)
        # A hand-written declaration that already names its link symbol is left alone
        # (appwiz's `#[cfg(target_arch = "x86")]` pair predates this).
        if (
            m
            and m.group(2) in aliases
            and not any("link_name" in o and "cfg_attr" not in o for o in out[-3:])
        ):
            ind, name = m.group(1), m.group(2)
            for arch, target in sorted(aliases[name].items()):
                attr = (
                    f'{ind}#[cfg_attr(target_arch = "{_RUST_ARCH[arch]}", link_name = "{target}")]'
                )
                if not (out and attr in out[-3:]):
                    out.append(attr)
            done.append(name)
        out.append(line)
    new = "\n".join(out)
    if new != text:
        prelude.write_text(new)
    return sorted(set(done))


def stage_resolve(stem: str, max_passes: int = 4) -> None:
    """Fill the prelude with what the tree already agrees on (prelude_resolve.py).

    Run to a fixed point (bounded): rustc emits the `unreachable pattern ... matches any
    value` warning -- the only sign of a C `case` constant that became a catch-all binding --
    only when the crate has NO errors, and a resolve round rewrites the extern block midway,
    so the round that would have seen it never did. input's TVN_SELCHANGED was found only
    by a reviewer: OK/Apply on its settings page never saved.
    """
    workspace = REPO / "sdk" / "lib" / "rust"
    seen: set[str] = set()
    # Each round can uncover only the NEXT catch-all arm (the earlier one hid it), so a
    # long switch needs several; the loop stops as soon as a round uncovers nothing new.
    for _round in range(8):
        _stage_resolve_once(stem, max_passes, extra=seen)
        state = load_state(stem)
        left = set(
            prelude_resolve.unresolved(
                state["crate"], RUST_TARGETS["amd64"], workspace, STATE_ROOT / stem / "target-amd64"
            )
        )
        # Plus the catch-all arms no warning names (a LAST-arm binding; see _undefined_arm_names).
        left |= _undefined_arm_names(
            state, prelude_resolve._visible_value_names(workspace, state["crate"])
        )
        if not left or left <= seen:
            return
        seen |= left
        print(f"resolve: another round for what the last one uncovered: {', '.join(sorted(left))}")


def _stage_resolve_once(stem: str, max_passes: int = 4, extra: set[str] | None = None) -> None:
    """One resolve round (see stage_resolve). `extra`: names an earlier round's final check
    uncovered, offered from the first pass -- this round's own first check cannot see them."""
    state = load_state(stem)
    started = time.time()
    crate = _crate_dir(state)
    prelude = crate / "src" / "prelude.rs"
    workspace = REPO / "sdk" / "lib" / "rust"
    pending = _c_defined_names([REPO / t for t in state["tus"]])
    shared = set().union(*prelude_resolve.shared_provides(workspace).values())
    # A name that is a function-like MACRO to this module's own preprocessor is never an
    # extern fn, whatever another crate declared: winsrv's `fn RTL_FIELD_SIZE(t: usize, f:
    # usize)` was copied by consensus and shadowed the real macro. Dropped, including copies
    # an earlier run made.
    from .macro_authority import function_like_macros, identifier_aliases

    c_macros: set[str] = set()
    # ...nor a name the module's preprocessor ALIASES to another (`#define snprintf
    # _snprintf`): the C calls the target, and _resolve_externs declares it and re-exports it
    # under the alias. usetup got oleaut32-rust's `snprintf` by consensus -- a symbol ntdll
    # does not export.
    id_aliases: set[str] = set()
    for tu in state["tus"]:
        try:
            c_macros |= function_like_macros(REPO, (REPO / tu).resolve())
            id_aliases |= set(identifier_aliases(REPO, (REPO / tu).resolve()))
        except Exception as e:  # reported, then judged without it
            print(f"resolve: no macro authority for {tu}: {str(e).splitlines()[0][:120]}")
    # ...and a name a shared crate provides is imported from it, never copied: tree consensus
    # had copied `extern` declarations of ntstrsafe's RtlString* family, which are header
    # inlines no DLL exports -- they compile, then fail at link.
    # ...and never a name the HAND-written part of the prelude already defines (the PnP
    # constants, the kernel helpers): a consensus copy of it is E0428 -- atapi got bootvid's
    # `CmResourceTypePort: u32` beside its own `u8`, and advapi32's `FALSE: BOOL`.
    hand = prelude_resolve.hand_written_names(prelude)
    shared |= hand
    # ...and never a name `port macros` lowered from the SDK header itself: the lowering is
    # the C's own expansion (`HKEY_CURRENT_USER` sign-extended through LONG_PTR on 64-bit),
    # a consensus copy (`0x8000_0001usize as HKEY`) only a neighbour's guess -- and both
    # together are E0428.
    from . import sdk_macros

    _sdk = sdk_macros.existing_items(prelude)
    shared |= sdk_macros.existing(prelude) | _sdk["type"] | _sdk["value"] | _sdk["fn"]
    # ...and never a FORCEINLINE helper ntdll-sys already implements in Rust (inlines.rs,
    # re-exported through `ntdll_sys::nt`, which the island globs): diskpart got
    # winlogon-sys's bindgen `extern` InitializeListHead/IsListEmpty/RemoveEntryList/
    # RemoveHeadList, which shadow the real ones and fail at link -- no DLL exports them.
    if state.get("usermode", True):
        inl = workspace / "ntdll-sys" / "src" / "inlines.rs"
        if inl.is_file():
            shared |= set(re.findall(r"^pub (?:unsafe )?fn (\w+)", inl.read_text(), re.M))
    # ...and never a name the ISLAND defines: main's prelude carried shell32's
    # `PSN_APPLY: UINT` over the island's `PSN_APPLY: i32`, its `match` arms then disagreed
    # (PSN_RESET still came from the island), and crate-repair stacked `as i32) as u32` forty
    # deep alternating between them. The island is the module's own header.
    shared |= _island_constants(state)
    copied = {
        k: v
        for k, v in prelude_resolve.existing_block(prelude).items()
        if not (v.kind == "fn" and (k in c_macros or k in id_aliases))
        and k not in shared
        # A copy of a name SOME arch's island defines shadows the island there (ndis's
        # SharedSystemTime); dropped, and the gap reported by the pass below instead.
        and k not in _island_defined(crate / "src")
        # A copy made before test harnesses stopped counting as consensus.
        and not prelude_resolve.is_test_source(v.path)
    }
    # Re-derive every kept copy from the tree as it is NOW: a copy is only as right as the run
    # that made it. usetup kept 40 setuplib externs under `extern "C"` from a run whose ABI
    # was written unquoted (unreadable, so read back as C) -- every one undefined at link,
    # because setuplib's exports are stdcall. A copy nothing defines any more is dropped and
    # resolved afresh.
    fresh = prelude_resolve.workspace_items(set(copied), workspace, crate)
    for name in list(copied):
        if copied[name].path == "island enum":
            continue
        pick, _why = prelude_resolve.consensus(name, fresh.get(name, []))
        if pick is None:
            del copied[name]
        else:
            copied[name] = pick
    # On disk BEFORE the passes: rustc decides what is unresolved, and a copy dropped above
    # but still in the file reads as resolved -- it then skipped the prototype settling and
    # vanished at the final write (usetup's SelectPartition, once diskpart's twin landed).
    prelude_resolve.write_block(prelude, prelude_resolve.render(copied))
    siblings = prelude_resolve.existing_siblings(prelude)
    modules_dir = crate / "src" / stem
    # Each kept import is re-checked against the module it names: a definition renamed since
    # (integrate's C-variadic `F` -> `F_v`) leaves `pub use crate::m::F;` pointing at m's own
    # glob import of F -- E0603 "private function import" -- and nothing else revisits it.
    live = prelude_resolve.sibling_definitions(set(siblings), modules_dir)
    stale = {n for n, mod in siblings.items() if mod not in {m for m, _ in live.get(n, [])}}
    if stale:
        siblings = {n: m for n, m in siblings.items() if n not in stale}
        prelude_resolve.write_siblings(prelude, prelude_resolve.render_siblings(siblings, stem))
        print(f"resolve: dropped {len(stale)} stale sibling import(s): {', '.join(sorted(stale))}")
    island_sys = prelude_resolve.island_substrate(crate / "src", workspace)
    kernel_sys = (
        island_sys if island_sys is not None and island_sys.parent.name == "ntkrnl-sys" else None
    )
    substrate: dict[str, dict[str, str | None]] = {
        n: {} for n in prelude_resolve.existing_substrate(prelude)
    }
    substrate_why: dict[str, str] = {}
    # Names the crate calls that no import library exports on every arch: header inlines the
    # island declares as externs. They resolve, so the unresolved list never asks for them --
    # the link does. Offered to the substrate alongside the unresolved names.
    exported = prelude_resolve.module_exports(REPO / state["module_dir"], REPO)
    link_wanted: set[str] = set()
    if kernel_sys is not None and exported is not None:
        link_wanted = prelude_resolve.called_names(modules_dir) - exported
    res = prelude_resolve.Resolution()
    ambiguous: dict[str, list[str]] = {}
    types_only: set[str] = set()
    seen_names: set[str] = set()
    for n in range(1, max_passes + 1):
        wanted = prelude_resolve.unresolved(
            state["crate"], RUST_TARGETS["amd64"], workspace, STATE_ROOT / stem / "target-amd64"
        )
        names = set(wanted) | (set(extra or ()) if n == 1 else set())
        seen_names |= names
        types_only = {k for k, ns in wanted.items() if ns == {"type"}}
        # A copy of the wrong KIND for a name wanted only as a type is what caused the gap.
        for name in types_only & set(copied):
            # ...except an island enum alias: the island says the name IS that constant, so a
            # type use of it is the translation's mistake (atapi typed locals
            # `DevicePowerState` where the C says DEVICE_POWER_STATE). Dropping it only
            # re-copied it next pass, every pass.
            if copied[name].kind != "type" and copied[name].path != "island enum":
                del copied[name]
        # The crate's OWN definitions first: a name one translated module defines is
        # imported from it, never copied from the tree.
        found_here = prelude_resolve.sibling_definitions(names - set(siblings), modules_dir)
        wired = 0
        for name, defs in sorted(found_here.items()):
            mods = sorted({m for m, _ in defs})
            if len(mods) != 1:
                ambiguous[name] = mods
                continue
            if not all(is_pub for _, is_pub in defs):
                prelude_resolve.promote_pub(modules_dir / f"{mods[0]}.rs", name)
            siblings[name] = mods[0]
            wired += 1
        if wired:
            prelude_resolve.write_siblings(prelude, prelude_resolve.render_siblings(siblings, stem))
        names -= set(found_here)
        # A header helper the kernel -sys crate implements in Rust is imported from it, before
        # tree consensus is asked -- C macros included, since the substrate's port IS the
        # macro's Rust form. atapi's InsertTailList (16 copies, two ABIs), KeQuerySystemTime
        # and MmGetMdlVirtualAddress (C macros, never asked) all live in ntkrnl-sys.
        if kernel_sys is not None:
            found_sub, sub_why = prelude_resolve.substrate_helpers(
                # A name that became hand-written (or a sibling's) since the block was last
                # written leaves it: re-offering the old block unfiltered was an E0255.
                (names | set(substrate) | link_wanted) - shared - set(siblings),
                kernel_sys,
                "ntkrnl_sys",
            )
            wired += len(set(found_sub) - set(substrate))
            substrate = found_sub
            substrate_why = {k: v for k, v in sub_why.items() if k in names}
            for name in substrate:
                copied.pop(name, None)
            ties = prelude_resolve.glob_ties(crate / "src", modules_dir, kernel_sys)
            prelude_resolve.write_substrate(
                prelude,
                prelude_resolve.render_substrate(
                    prelude_resolve.with_glob_ties(substrate, ties), "ntkrnl_sys"
                ),
            )
            names -= set(substrate)
        res.pending = sorted(names & pending)
        # An identifier alias of a FUNCTION is _resolve_externs' (the A/W switch); one of a
        # CONSTANT (`#define TVN_SELCHANGED TVN_SELCHANGEDW`) goes on to the clang-evaluated
        # facts. Subtracting every alias dropped input's TVN_SELCHANGED silently -- a bare
        # name in a `match` arm, so the first arm caught every WM_NOTIFY and OK never saved.
        fn_aliases = {n for n in id_aliases if not prelude_resolve.looks_constant(n)}
        todo = names - pending - set(copied) - c_macros - shared - fn_aliases
        # Plus every enum member a C `case` label names (derive's SWITCH_CONST_ENUM_PREFIXED):
        # in a Rust pattern the bare name is a BINDING, never unresolved, so it would never
        # reach this alias step on its own. diskpart's FormatCallback matched `PROGRESS` and
        # `DONE` bare, and the first arm caught every command.
        # The Rust says the same thing directly, and is the only witness when derive's C audit
        # recorded nothing: pciidex's switch_enums was EMPTY, so `BusQueryDeviceID =>` bound
        # every IRP_MN_QUERY_ID and each ID query answered with the device ID -- the channel
        # PDO never matched the CriticalDeviceDatabase and the --ata-stack boot hit 0x6B.
        case_enums = (
            set(load_state(stem).get("switch_enums", [])) | _pattern_idents(modules_dir)
        ) - set(copied)
        aliases = prelude_resolve.island_enum_aliases(todo | case_enums, crate / "src", island_sys)
        copied.update(aliases)
        todo -= set(aliases)
        items = prelude_resolve.workspace_items(todo, workspace, crate)
        for name in types_only & set(items):
            items[name] = [i for i in items[name] if i.kind == "type"]
        new = len(aliases)
        res.conflicting, res.undefined = {}, []
        # A name SOME arch's island defines is an arch-specific gap, never tree consensus: a
        # copied item shadows the island on the arches that have it too. ndis's
        # `SharedSystemTime` (KUSER_SHARED_DATA.SystemTime, kernel address, amd64/arm64 only)
        # got storport's `0x7ffe0008` -- InterruptTime, user mode -- on every arch.
        in_island = _island_defined(crate / "src")
        for name in sorted(todo & set(in_island)):
            res.conflicting[name] = (
                f"the island defines it on {', '.join(sorted(in_island[name]))} only: "
                "an arch-specific gap, not tree consensus -- port its per-arch C"
            )
        todo -= set(in_island)
        for name in sorted(todo):
            found = items.get(name, [])
            if not found:
                res.undefined.append(name)
                continue
            pick, why = prelude_resolve.consensus(name, found)
            if pick is None:
                res.conflicting[name] = why
                continue
            copied[name] = pick
            new += 1
        print(
            f"resolve pass {n}: {len(names)} unresolved, {wired} wired to a sibling module, "
            f"{new} copied from tree consensus"
        )
        if not new and not wired:
            break
        prelude_resolve.write_block(prelude, prelude_resolve.render(copied))
    # Every wired name stays `pub`, every run: a $0 reassembly (`--replay-only`) rewrites
    # the modules from the bank and drops the promotion an earlier run made (E0603).
    for name, mod in sorted(siblings.items()):
        path = modules_dir / f"{mod}.rs"
        if path.is_file():
            prelude_resolve.promote_pub(path, name)
    # Unconditionally: a pass that finds nothing new still has to drop the stale copies
    # filtered above, and the shared-macro list is judged against the cleaned prelude.
    prelude_resolve.write_block(prelude, prelude_resolve.render(copied))
    for path in prelude_resolve.refresh_shared_crates(crate, workspace):
        print(f"resolve: refreshed the `{path}` re-export list")
    # A name the tree declares two ways is settled by the module's OWN prototype: keep the
    # candidates whose ABI and arity match what clang sees through this module's headers,
    # and take consensus among those. c2rust (the prototype route below) cannot transpile
    # every TU -- usetup.c panics it -- and then setuplib's CreatePartitionList and
    # SelectPartition were left undeclared once diskpart, which defines its own, landed.
    settled = _settle_by_prototype(
        state,
        {
            n
            for n, why in res.conflicting.items()
            if why.startswith(("ABI disagreement", "signature disagreement"))
        },
        workspace,
        crate,
    )
    if settled:
        copied.update(settled)
        res.conflicting = {k: v for k, v in res.conflicting.items() if k not in settled}
        prelude_resolve.write_block(prelude, prelude_resolve.render(copied))
        print(
            f"resolve: {len(settled)} settled by the module's prototype: "
            + ", ".join(sorted(settled))
        )
    type_names = [n for n in res.undefined if n in types_only]
    # A constant the tree defines only as an expression (`CTL_CODE(..)`), or with values that
    # disagree, is the clang probe's question too: it reads the C's own definition.
    # usetup's IOCTL_CONSOLE_* were reported "no literal definition" and dropped.
    const_split = [
        n
        for n, why in res.conflicting.items()
        if why == "no literal definition" or why.endswith("different values")
    ]
    evaluated_split = set(const_split) - set(_resolve_facts(state, prelude, const_split))
    res.conflicting = {k: v for k, v in res.conflicting.items() if k not in evaluated_split}
    res.undefined = (
        _resolve_facts(state, prelude, [n for n in res.undefined if n not in types_only])
        + type_names
    )
    _seed_switch_facts(state, prelude)
    # A constant used only as a match pattern is never "unresolved" either -- it binds. atapi's
    # `IOCTL_SCSI_RESCAN_BUS =>` (a CTL_CODE macro nothing defined) caught every IOCTL the FDO
    # does not handle, rescanning the bus instead of passing the IRP down.
    loose = _undefined_pattern_constants(crate / "src", modules_dir, island_sys)
    if loose:
        still = _resolve_facts(state, prelude, sorted(loose))
        for name in still:
            print(f"resolve: `{name} =>` binds everything and clang could not evaluate it")
    type_gaps = set(res.undefined) | {
        n for n, why in res.conflicting.items() if why.startswith("a type")
    }
    found = _resolve_local_types(state, prelude, type_gaps)
    _resolve_anonymous_types(state)
    align_definition_abis(state)
    align_definition_returns(state)
    island_found = _resolve_island_types(load_state(stem), type_gaps - found)
    if island_found:
        state = load_state(stem)  # it recorded island_headers + derive + island
    found |= island_found
    # A function the tree declares with DIFFERENT ABIs (kernel32's Sleep, RegCloseKey: some
    # crates say "C", some "system") is settled the same way as one nobody declares -- by
    # the prototype clang sees and the calling convention it reports. diskpart had eleven
    # such calls left unresolved.
    abi_split = {
        n
        for n, why in res.conflicting.items()
        if why.startswith(("ABI disagreement", "mixed", "signature disagreement"))
    }
    abi_split |= id_aliases & seen_names
    found |= _resolve_externs(state, prelude, (set(res.undefined) | abi_split) - found)
    res.undefined = [n for n in res.undefined if n not in found]
    res.conflicting = {k: v for k, v in res.conflicting.items() if k not in found}
    res.copied = copied
    chans = _wine_debug_channels(state, prelude)
    if chans:
        print(f"resolve: wine debug channel storage written: {', '.join(chans)}")
    if _unicode_tchar(state, prelude):
        print("resolve: UNICODE module -- TCHAR family is WCHAR (ntdll-sys's glob says c_char)")
    linked = _arch_link_names(state, prelude)
    if linked:
        print(
            f"resolve: {len(linked)} extern(s) link to another name on some arches: "
            + ", ".join(linked)
        )
    _record(
        state,
        "resolve",
        started,
        copied=len(copied),
        pending=res.pending,
        undefined=res.undefined,
        conflicting=sorted(res.conflicting),
    )
    if siblings:
        print(f"resolve: {len(siblings)} name(s) imported from the module's own translations")
    if substrate:
        print(f"resolve: {len(substrate)} header helper(s) imported from ntkrnl-sys")
    if kernel_sys is not None:
        # Only names with a Rust port on some arch: a pure glob tie needs no unpinning. Plus
        # every function the prelude DEFINES: a wrapper there (KeInitializeSpinLock over the
        # island's lock type) is the binding, and a module's `ddk::{..}` pin of the same name
        # bypassed it straight to the bindgen extern -- pciidex.sys's undefined symbol.
        ported = {n for n, per in substrate.items() if any(v is not None for v in per.values())}
        ported |= set(
            re.findall(
                r"(?m)^pub\s+(?:unsafe\s+)?(?:extern\s+\"[^\"]+\"\s+)?fn\s+(\w+)",
                prelude.read_text(),
            )
        )
        unpinned = prelude_resolve.unpin_substrate(modules_dir, ported, "ntkrnl_sys")
        if unpinned:
            print(
                f"resolve: {sum(unpinned.values())} per-file pin(s) of the bindgen extern dropped "
                f"in favour of the prelude's helper ({', '.join(sorted(unpinned))})"
            )
    guid_block, guid_refused = initguid_storage(state, crate, modules_dir)
    write_guid_block(prelude, guid_block)
    if guid_block:
        print(f"resolve: {guid_block.count('pub static')} INITGUID GUID(s) given storage")
    if guid_refused:
        refused = ", ".join(guid_refused)
        print(f"resolve: GUIDs with no single DEFINE_GUID value in the tree: {refused}")
    if link_wanted:
        # Declared as an extern (by the island or a consensus copy), exported by nothing the
        # module imports, and not ported by the substrate either: these fail at LINK. Loud
        # here, where the fix (a port in ntkrnl-sys/src/inline) is still cheap to name.
        declared = {k for k, v in copied.items() if v.kind == "fn"}
        for island in (crate / "src").glob("types_*.rs"):
            declared |= set(
                re.findall(
                    r"^\s*pub\s+fn\s+([A-Za-z_]\w*)\b[^{;=]*;",
                    island.read_text(errors="replace"),
                    re.M,
                )
            )
        gaps = (link_wanted & declared) - set(substrate) - shared - set(siblings)
        # ...minus what the crate defines itself (atapi.h prototypes AtaAddChannel, so the
        # island declares it) and what a static library the module links defines in C.
        gaps -= set(prelude_resolve.sibling_definitions(gaps, modules_dir))
        gaps = sorted(gaps - _static_lib_functions(REPO / state["module_dir"], gaps))
        if gaps:
            print(
                f"resolve: {len(gaps)} called name(s) no import library exports on every arch "
                f"and ntkrnl-sys does not port -- these will not link: {', '.join(gaps)}"
            )
    if substrate_why:
        print(
            "resolve: ntkrnl-sys defines these but cannot provide them: "
            + "; ".join(f"{k} ({v})" for k, v in sorted(substrate_why.items()))
        )
    if ambiguous:
        print(
            "resolve: defined by more than one translated module (C `static` twins?), "
            "not wired: " + ", ".join(f"{k} ({'/'.join(v)})" for k, v in sorted(ambiguous.items()))
        )
    if res.pending:
        print(
            f"resolve: {len(res.pending)} name(s) the module's C defines but no translated "
            "module does (untranslated TU, or a header inline): " + ", ".join(res.pending)
        )
    if res.undefined:
        print(
            "resolve: defined nowhere in the tree (island allowlist? invented?): "
            + ", ".join(res.undefined)
        )
    if res.conflicting:
        print("resolve: not copied (the tree disagrees, or it is not ours to copy):")
        for name, why in sorted(res.conflicting.items()):
            print(f"    {name}: {why}")


def _known_types(state: dict) -> set[str]:
    """Type names the crate can spell: its own, and those of every -sys crate it globs in
    (setuplib's NTSTATUS arrives through `pub use ntdll_sys::nt::*;`)."""
    if str(REPO) not in sys.path:
        sys.path.insert(0, str(REPO))
    from tools.source_walk import source_files

    crate_src = _crate_dir(state) / "src"
    sources = list(source_files(crate_src))
    workspace = REPO / "sdk" / "lib" / "rust"
    text = "".join(p.read_text(errors="replace") for p in crate_src.glob("*.rs"))
    for sys_crate in sorted(set(re.findall(r"\buse (\w+_sys)::", text))):
        sources += source_files(workspace / sys_crate.replace("_", "-") / "src")
    out: set[str] = set()
    for src in sources:
        out |= set(
            re.findall(
                r"(?m)^\s*pub (?:type|struct|union|enum) (\w+)", src.read_text(errors="replace")
            )
        )
    return out


def _settle_by_prototype(state: dict, names: set[str], workspace: Path, crate: Path) -> dict:
    """{name: tree Item} for each split name one candidate group matches exactly: the ABI
    class and parameter count clang reports for it through the module's own TUs."""
    from . import sdk_facts
    from .macro_authority import MacroAuthorityError

    if not names:
        return {}
    protos: dict[str, tuple[str, int]] = {}
    for tu in state["tus"]:
        todo = sorted(names - set(protos))
        if not todo:
            break
        try:
            protos.update(sdk_facts.function_prototypes(REPO, REPO / tu, todo))
        except MacroAuthorityError:
            continue
    items = prelude_resolve.workspace_items(set(protos), workspace, crate)
    out = {}
    for name, (abi, arity) in protos.items():
        match = [
            i
            for i in items.get(name, [])
            if i.kind == "fn"
            and prelude_resolve._abi_class(i.abi) == abi
            and prelude_resolve._arity(i.text) == arity
        ]
        pick, _why = prelude_resolve.consensus(name, match) if match else (None, "")
        if pick is not None:
            out[name] = pick
    return out


def _resolve_externs(state: dict, prelude: Path, names: set[str]) -> set[str]:
    """Functions the module's C calls and no Rust declares, two ways, both exact:

    * `#define InstallFat12BootCode InstallFatBootCode` -- an object-like macro naming a
      function the crate defines: `pub use` the function under the macro's name;
    * a prototype in a header the island does not cover (`vfatlib.h`'s VfatFormat, the CRT's
      iswspace): c2rust's signature, agreed on every arch, with the calling convention clang
      reports on i386 -- c2rust writes `extern "C"` even for a stdcall (NTAPI) function.
    """
    from . import c2rust_anchor, sdk_facts
    from .macro_authority import MacroAuthorityError, function_like_macros, identifier_aliases

    # Never a name the hand-written prelude declares, including one an earlier run put in
    # this block before the hand declaration existed (E0428).
    # Nor one the consensus block declares (E0428: diskpart's consensus K32LoadStringW, and
    # the declaration made for its `LoadStringW` alias once flipped TUs got aliases back).
    declared = prelude_resolve.hand_written_names(prelude) | {
        k for k, v in prelude_resolve.existing_block(prelude).items() if v.kind == "fn"
    }
    names = (set(names) | prelude_resolve.existing_externs(prelude)) - declared
    sigs: dict[str, tuple[str, str, str]] = {}
    module_dir = REPO / state["module_dir"]
    files = _module_sources(module_dir)
    defs, _ambiguous = local_macros.module_macros(files, REPO)
    stem = state["stem"]
    modules_dir = _crate_dir(state) / "src" / stem
    aliases: dict[str, str] = {}
    for name in sorted(names):
        m = defs.get(name)
        if m is None or m.params is not None or m.kind != "macro":
            continue
        target = m.body.strip().strip("()").strip()
        if re.fullmatch(r"[A-Za-z_]\w*", target):
            aliases[name] = target
    where = prelude_resolve.sibling_definitions(set(aliases.values()), modules_dir)
    for name, target in aliases.items():
        mods = sorted({mod for mod, _ in where.get(target, [])})
        if len(mods) != 1:
            continue
        prelude_resolve.promote_pub(modules_dir / f"{mods[0]}.rs", target)
        sigs[name] = (
            "use",
            f"pub use crate::{stem}::{mods[0]}::{target} as {name};",
            defs[name].where,
        )
    todo = names - set(sigs)
    # The SDK's A/W aliases (`#define GetModuleHandle GetModuleHandleW`): declare the target
    # from its prototype below and re-export it under the name the C spells. Only to a
    # FUNCTION -- an alias of a function-like macro (CopyMemory -> RtlCopyMemory) is a call
    # site that needs `!`, not a declaration.
    sdk_alias: dict[str, str] = {}
    for tu in state["tus"]:
        pending = {n for n in todo if n not in sdk_alias}
        if not pending:
            break
        try:
            known = identifier_aliases(REPO, REPO / tu)
            macros = function_like_macros(REPO, REPO / tu)
        except MacroAuthorityError:
            continue
        from . import sdk_macros

        try:
            deep = sdk_macros.object_expansions(REPO, REPO / tu, pending - set(known))
        except sdk_macros.LowerError:
            deep = {}
        for name in pending:
            target = known.get(name) or deep.get(name)
            if (
                target
                and re.fullmatch(r"[A-Za-z_]\w*", target)
                and target not in macros
                and target != name
            ):
                sdk_alias[name] = target
    # A target a SHARED crate provides is re-exported from it under the alias: openglcfg's
    # `StringCchCopy` is strsafe-rust's `StringCchCopyW`, never an extern (strsafe is header
    # code no DLL exports).
    shared_paths = {
        n: (f"{ident}::{module}" if module else ident)
        for (ident, module), names in prelude_resolve.shared_provides(
            REPO / "sdk" / "lib" / "rust"
        ).items()
        for n in names
    }
    for name, target in sorted(sdk_alias.items()):
        if target in shared_paths:
            sigs[name] = (
                "use",
                f"pub use {shared_paths[target]}::{target} as {name};",
                "sdk alias",
            )
    sdk_alias = {n: t for n, t in sdk_alias.items() if t not in shared_paths}
    # A target already declared (hand-written or consensus) is aliased, not declared again.
    todo = (todo - set(sdk_alias) - set(sigs)) | {
        t for t in sdk_alias.values() if t not in declared
    }
    for tu in state["tus"]:
        if not todo:
            break
        c_file = REPO / tu
        try:
            found = c2rust_anchor.extern_signatures(c_file, todo)
            abis = sdk_facts.function_abis(REPO, c_file, sorted(found)) if found else {}
        except (c2rust_anchor.C2RustError, MacroAuthorityError) as e:
            print(f"resolve: externs of {tu}: {str(e).splitlines()[0][:120]}")
            continue
        for name, sig in found.items():
            if name not in abis:
                print(f"resolve: {name}: clang reported no plain cdecl/stdcall type; hand-port it")
                continue
            # A `va_list` parameter is `core::ffi::VaList`, which is `c_variadic` -- nightly.
            # Declaring it would make the crate unbuildable on stable; a caller forwards its
            # list through the module's C shim instead (pciidex's vibeos_vDbgPrintEx).
            if "VaList" in sig:
                print(
                    f"resolve: {name}: takes a va_list (not declarable on stable); use the C shim"
                )
                todo.discard(name)
                continue
            abi = "C" if "..." in sig else abis[name]
            sigs[name] = (abi, sig, Path(tu).name)
            todo.discard(name)
    # An alias TARGET no prototype could declare (c2rust emits nothing for FormatMessageW,
    # whose last parameter is `va_list *`) falls back to the tree's agreed declaration of
    # it; the unresolved name was the alias, so the consensus pass never asked for it.
    targets = {t for t in sdk_alias.values() if t in todo}
    if targets:
        found_items = prelude_resolve.workspace_items(
            targets, REPO / "sdk" / "lib" / "rust", _crate_dir(state)
        )
        for target in sorted(targets):
            item, _why = prelude_resolve.consensus(target, found_items.get(target, []))
            if item is not None and item.kind == "fn" and item.abi:
                text = re.sub(r"^.*?\bfn\b", "fn", item.text)
                sigs[target] = (item.abi.strip('"'), text, item.path)
                todo.discard(target)
    for name, target in sorted(sdk_alias.items()):
        if target in sigs or re.search(rf"\bfn {re.escape(target)}\b", prelude.read_text()):
            sigs[name] = ("use", f"pub use crate::prelude::{target} as {name};", "sdk alias")
    lost = sorted(f"{n} -> {t}" for n, t in sdk_alias.items() if n not in sigs)
    if lost:
        print(f"resolve: SDK alias target declared nowhere, hand-declare it: {', '.join(lost)}")
    prelude_resolve.write_externs(prelude, prelude_resolve.render_externs(sigs))
    if sigs:
        print(f"resolve: {len(sigs)} extern/alias declaration(s): {', '.join(sorted(sigs))}")
    return set(sigs)


_RUST_FN_DEF = re.compile(
    r"(?m)^(?P<head>[ \t]*(?:pub(?:\([^)]*\))?[ \t]+)?(?:unsafe[ \t]+)?extern[ \t]+)"
    r'"(?P<abi>C|system)"(?P<tail>[ \t]+fn[ \t]+(?P<name>[A-Za-z_]\w*)[ \t]*[<(])'
)


def align_definition_abis(state: dict) -> dict[str, list[str]]:
    """Give every function the crate DEFINES the calling convention its C declares.

    The model and c2rust both default to `extern "C"`; an NTAPI callback the C hands to
    `RtlQueryRegistryValues` or `EnumerateBootStoreEntries` is stdcall, so on i386 the
    callee pops the wrong number of bytes and the stack is off from then on. rustc only
    notices where the code casts the function to the slot's type (setuplib: E0605 at nine
    sites); a definition that is merely exported compiles and corrupts. clang answers per C
    function (sdk_facts.function_abis); a name it cannot type is left alone and reported.
    Returns {module file: [renamed functions]}.
    """
    from . import sdk_facts
    from .macro_authority import MacroAuthorityError

    modules = _crate_dir(state) / "src" / state["stem"]
    changed: dict[str, list[str]] = {}
    for tu in state["tus"]:
        path = modules / f"{Path(tu).stem}.rs"
        if not path.is_file():
            continue
        text = path.read_text()
        defs = {m.group("name"): m.group("abi") for m in _RUST_FN_DEF.finditer(text)}
        if not defs:
            continue
        try:
            abis = sdk_facts.function_abis(REPO, REPO / tu, sorted(defs))
        except MacroAuthorityError as e:
            print(f"resolve: ABIs of {tu}: {str(e).splitlines()[0][:120]}")
            continue
        wrong = {n for n, abi in defs.items() if n in abis and abis[n] != abi}
        if not wrong:
            continue

        def fix(m: re.Match[str], wrong=wrong, abis=abis) -> str:
            if m.group("name") not in wrong:
                return m.group(0)
            return f'{m.group("head")}"{abis[m.group("name")]}"{m.group("tail")}'

        path.write_text(_RUST_FN_DEF.sub(fix, text))
        changed[path.name] = sorted(wrong)
    for name, fns in sorted(changed.items()):
        print(f"resolve: {name}: calling convention set from the C for {', '.join(fns)}")
    return changed


_PRIMITIVE_RET = re.compile(r"^(?:[iu](?:8|16|32|64|size)|bool|\(\))$")


def _split_top(params: str) -> list[str]:
    out, depth, cur = [], 0, ""
    for i, ch in enumerate(params):
        if ch == ">" and i and params[i - 1] == "-":
            cur += ch  # the `->` of a fn-pointer type, not a closing angle bracket
            continue
        depth += {"(": 1, "<": 1, "[": 1, ")": -1, ">": -1, "]": -1}.get(ch, 0)
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [p.strip() for p in out if p.strip()]


def align_definition_returns(state: dict) -> dict[str, list[str]]:
    """Give a crate-defined function the signature its C prototype names.

    diskpart's command table is `EXIT_CODE (*func)(INT, PWSTR*)` and every `*_main` returns
    EXIT_CODE, an enum bindgen makes `u32`; the model wrote `-> i32` for all of them and the
    table failed 31 times (E0308, fn item vs fn pointer). The prototype is the authority:
    c2rust reads it from a TU that only DECLARES the function (one that defines it gives no
    prototype). A function only ever CALLED has its primitive return replaced by the named
    C type; one used as a VALUE (a callback: usetup's GetSettingDescription took `usize`
    where the slot says ULONG) takes the prototype's parameter and return types whole, since
    a function pointer must match exactly and only the declaration can say what it is.
    """
    from . import c2rust_anchor

    modules = _crate_dir(state) / "src" / state["stem"]
    texts = {p: p.read_text() for p in sorted(modules.glob("*.rs"))}
    every = "\n".join(texts.values())
    defs: dict[str, tuple[Path, str, str | None]] = {}  # name -> (file, params, ret)
    for path, text in texts.items():
        for m in re.finditer(r"\bfn\s+([A-Za-z_]\w*)\s*\(", text):
            depth, i = 1, m.end()
            while i < len(text) and depth:
                depth += {"(": 1, ")": -1}.get(text[i], 0)
                i += 1
            r = re.match(r"\s*(?:->\s*([^{;]+?)\s*)?\{", text[i:])
            if r:
                defs[m.group(1)] = (path, text[m.end() : i - 1], r.group(1))
    callbacks = {n for n in defs if re.search(rf"(?<!fn )\b{re.escape(n)}\b(?!\s*[(!:])", every)}
    wanted = {
        n
        for n, (_, _, ret) in defs.items()
        if n in callbacks or (ret is not None and _PRIMITIVE_RET.match(ret))
    }
    # Only names a module HEADER declares: a `static` function has no prototype for c2rust
    # to find, and asking every TU about it costs a c2rust run per TU per arch (usetup's
    # replay spent most of an hour here).
    headers = " ".join(
        h.read_text(errors="replace") for h in (REPO / state["module_dir"]).rglob("*.h")
    )
    # `NAME(` is a prototype; `TYPEDEF NAME;` declares through a function typedef, which is
    # how pciidex.h declares every callback (`CHANNEL_START_IO AtaAhciStartIo;`).
    todo = {n for n in wanted if re.search(rf"\b{re.escape(n)}\s*[(;]", headers)}
    # A `static` CALLBACK has no prototype anywhere: its own definition is the authority, and
    # an exact type is what a fn-pointer slot needs (pciidex's PataEnableInterrupts took
    # `Enable: i32` where the C says BOOLEAN, and could not be stored).
    statics = (callbacks & wanted) - todo
    proto: dict[str, str] = {}
    for tu in state["tus"]:
        if not statics:
            break
        text = (REPO / tu).read_text(errors="replace")
        mine = {n for n in statics if re.search(rf"(?m)^{re.escape(n)}\s*\(", text)}
        if not mine:
            continue
        try:
            found = c2rust_anchor.definition_signatures(REPO / tu, mine)
        except c2rust_anchor.C2RustError:
            continue
        proto.update(found)
        statics -= set(found)
    for tu in state["tus"]:
        if not todo:
            break
        own = set(
            re.findall(r"^\w[^\n;]*?\b(\w+)\s*\(", (REPO / tu).read_text(errors="replace"), re.M)
        )
        ask = todo - own
        if not ask:
            continue
        try:
            found = c2rust_anchor.extern_signatures(REPO / tu, ask)
        except c2rust_anchor.C2RustError:
            continue
        proto.update(found)
        todo -= set(found)
    changed: dict[str, list[str]] = {}
    for name, sig in sorted(proto.items()):
        path, params, ret = defs[name]
        m = re.match(r"fn\s+\w+\s*\((.*)\)\s*(?:->\s*(.+?))?\s*;$", sig.strip(), re.S)
        if m is None:
            continue
        # c2rust spells a by-value `va_list` as `core::ffi::VaList` (nightly); integrate lowers
        # it, so the prototype must be lowered the same way or the two rewrite each other.
        c_params = _split_top(variadic_shim.lower_va_list_types(m.group(1))[0])
        c_ret = m.group(2)
        new_params, new_ret = params, ret
        if name in callbacks:
            rust = _split_top(params)
            if len(rust) == len(c_params) and all(":" in p for p in rust + c_params):
                new_params = ", ".join(
                    f"{r.split(':', 1)[0].strip()}: {c.split(':', 1)[1].strip()}"
                    for r, c in zip(rust, c_params, strict=True)
                )
            new_ret = c_ret
        elif c_ret and re.fullmatch(r"[A-Za-z_]\w*", c_ret) and not _PRIMITIVE_RET.match(c_ret):
            new_ret = c_ret
        if (new_params, new_ret) == (params, ret):
            continue
        text = texts[path]
        head = re.search(
            rf"\bfn\s+{re.escape(name)}\s*\({re.escape(params)}\)\s*(?:->\s*{re.escape(ret)}\s*)?\{{"
            if ret is not None
            else rf"\bfn\s+{re.escape(name)}\s*\({re.escape(params)}\)\s*\{{",
            text,
        )
        if head is None:
            continue
        tail = f" -> {new_ret} {{" if new_ret else " {"
        texts[path] = text[: head.start()] + f"fn {name}({new_params}){tail}" + text[head.end() :]
        path.write_text(texts[path])
        changed.setdefault(path.name, []).append(name)
    for fname, fns in sorted(changed.items()):
        print(f"resolve: {fname}: signature set from the C prototype for {', '.join(fns)}")
    return changed


def _resolve_local_types(state: dict, prelude: Path, names: set[str]) -> set[str]:
    """Types a .c file defines for itself (c2rust_anchor.local_types), into the prelude.

    Re-extracts what the block already holds, so the block never goes stale. Returns every
    name the block now defines.
    """
    from . import c2rust_anchor

    names = set(names) | prelude_resolve.existing_local_types(prelude)
    # C's `typedef struct _X {..} X;`: fetching the tag without its typedef leaves the model's
    # own `struct X` standing beside c2rust's `_X` (setuplib's HIVE_LIST_ENTRY tables).
    names |= {n[1:] for n in names if n.startswith("_") and len(n) > 1}
    # Never a type the island already defines. A name reads as unresolved while a sibling
    # glob makes it AMBIGUOUS (atapi's SCSI_REQUEST_BLOCK, opaque in ntkrnl-sys and whole in
    # the UNBLOCKed island), and a copy pinned here then collides with the explicit re-export
    # that settles the ambiguity -- forever, since the block re-extracts what it holds.
    island: set[str] = set()
    sys_crate = "ntdll-sys" if state.get("usermode", True) else "ntkrnl-sys"
    sys_island = REPO / "sdk" / "lib" / "rust" / sys_crate / "src" / "bindgen_amd64.rs"
    for isl in [*prelude.parent.glob("types_*.rs"), sys_island]:
        if isl.is_file():
            island |= set(
                re.findall(r"^pub (?:struct|union|enum|type) (\w+)", isl.read_text(), re.M)
            )
    # ...nor a base type the -sys crate owns (pciidex had ULONG/PVOID/NTSTATUS pinned here).
    # Except an OPAQUE island stub (`_unused: [u8; 0]`): a header that only forward-declares
    # `struct _CFFILE` gives bindgen nothing more, while usetup's cabinet.c defines the whole
    # struct -- and 50 field accesses failed against the stub. Those, and the island's
    # pointer aliases to them (PCFFILE would still point at the stub), are taken from the TU
    # that defines them; a stub no TU defines stays the island's.
    opaque: set[str] = set()
    for isl in prelude.parent.glob("types_*.rs"):
        text = isl.read_text()
        stubs = set(re.findall(r"^pub struct (\w+) \{\n\s*_unused: \[u8; 0\],\n\}", text, re.M))
        opaque |= stubs
        opaque |= {
            alias
            for alias, target in re.findall(r"^pub type (\w+) = \*(?:mut|const) (\w+);", text, re.M)
            if target in stubs
        }
    names |= opaque
    names -= island - opaque
    # ...nor one the prelude's hand-written part defines: the scaffold's `size_t = usize`
    # got a second, c2rust `size_t = c_ulonglong` beside it (E0428, and amd64's width).
    hand = re.sub(
        r"^// ==== (?!end)[^\n]*\n.*?^// ==== end [^\n]*\n?",
        "",
        prelude.read_text(),
        flags=re.S | re.M,
    )
    names -= set(re.findall(r"^pub (?:type|struct|union|enum) (\w+)", hand, re.M))
    items: dict[str, tuple[str, str]] = {}
    for tu in state["tus"]:
        c_file = REPO / tu
        todo = {n for n in names if n not in items}
        if not todo:
            break
        try:
            agreed, differs = c2rust_anchor.local_types(c_file, todo)
        except c2rust_anchor.C2RustError as e:
            print(f"resolve: local types of {tu}: {str(e).splitlines()[0][:120]}")
            continue
        for name, text in agreed.items():
            items.setdefault(name, (text, Path(tu).name))
        for name in differs:
            print(f"resolve: local type {name} differs across arches in {tu}; hand-port it")
    prelude_resolve.write_local_types(prelude, items)
    # The island's OTHER structs still name the stub (usetup's search struct has
    # `File: PCFFILE` -> the island's `_CFFILE`), so the stub itself must go: it is replaced
    # by an import of the definition just written. Re-applied on every resolve, since a
    # regenerated island brings the stub back.
    real = {
        n for n in opaque & set(items) if re.search(rf"\bpub struct {re.escape(n)}\b", items[n][0])
    }
    for isl in prelude.parent.glob("types_*.rs"):
        text = isl.read_text()
        new_text = text
        for name in sorted(real):
            stub = rf"^pub struct {re.escape(name)} \{{\n\s*_unused: \[u8; 0\],\n\}}\n"
            new_text = re.sub(
                rf"(?:^#\[[^\n]*\]\n)*{stub}",
                f"use crate::prelude::{name}; // whole in the TU that defines it (port resolve)\n",
                new_text,
                flags=re.M,
            )
        if new_text != text:
            isl.write_text(new_text)
    if items:
        print(f"resolve: {len(items)} local type item(s) from c2rust: {', '.join(sorted(items))}")
        dropped = drop_model_type_twins(_crate_dir(state) / "src" / state["stem"], set(items))
        for name, mods in sorted(dropped.items()):
            print(f"resolve: {name}: the model's own definition dropped from {', '.join(mods)}")
    return set(items)


_ANON_NAME = re.compile(r"\bC2RustUnnamed\w*")
_ANON_IMPORT = re.compile(r"(?m)^use crate::[\w:]+::C2RustUnnamed\w*;[^\n]*\n")


def _literal_fields(code: str, name: str) -> frozenset[str]:
    """The field names `code`'s struct literals of `name` spell (`name { a: .., b: .. }`)."""
    out: set[str] = set()
    for m in re.finditer(rf"\b{re.escape(name)}\s*\{{", code):
        depth, i, top = 0, m.end() - 1, []
        while i < len(code):
            c = code[i]
            if c in "([{":
                depth += 1
            elif c in ")]}":
                depth -= 1
                if depth == 0:
                    break
            top.append(c if depth == 1 else " ")
            i += 1
        out |= set(re.findall(r"(?:^|[{,])\s*(\w+)\s*:(?!:)", "".join(top)))
    return frozenset(out)


def _resolve_anonymous_types(state: dict) -> dict[str, list[str]]:
    """Each module's missing `C2RustUnnamed_N` types, from ITS OWN TU's c2rust output.

    The translation can use one (a function-local `static const struct {..} T[]` is
    `[C2RustUnnamed_163; 16]` in the anchor it was shown) without defining it, and the
    file-scope harvest only carries types for file-scope tables. These names are numbered
    per transpile, so a sibling's same-named type is a different struct: an import of one
    (which in-crate import resolution used to add) is removed, never trusted. Returns
    `{module file: [names written]}`.
    """
    from . import c2rust_anchor

    written: dict[str, list[str]] = {}
    for tu in state["tus"]:
        path = _tu_output(state, tu)
        if not path.is_file():
            continue
        text = path.read_text()
        code = re.sub(r"//[^\n]*", "", text)
        defined = set(
            re.findall(r"(?m)^\s*(?:pub\s+)?(?:struct|union|enum|type)\s+(C2RustUnnamed\w*)", code)
        )
        missing = set(_ANON_NAME.findall(code)) - defined
        if not missing:
            continue
        fields = {n: _literal_fields(code, n) for n in missing}
        try:
            agreed, differs = c2rust_anchor.anonymous_types(REPO / tu, fields)
        except c2rust_anchor.C2RustError as e:
            print(f"resolve: anonymous types of {tu}: {str(e).splitlines()[0][:120]}")
            continue
        for name, why in sorted(differs.items()):
            print(f"resolve: {path.name}: no single {Path(tu).name} type for {name} ({why})")
        new = _ANON_IMPORT.sub("", text)
        blocks = [agreed[n] for n in sorted(agreed) if n not in defined]
        if blocks:
            # After the leading `use`/attribute lines, so the module's header stays first.
            head = re.match(r"(?:(?:use |#!\[|//)[^\n]*\n|\n)*", new)
            at = head.end() if head else 0
            new = new[:at] + "\n".join(f"{b}\n" for b in blocks) + "\n" + new[at:]
            written[path.name] = sorted(agreed)
        if new != text:
            path.write_text(new)
    for fname, names in sorted(written.items()):
        print(
            f"resolve: {fname}: {len(names)} anonymous type(s) from its own TU: {', '.join(names)}"
        )
    return written


def drop_model_type_twins(modules: Path, names: set[str]) -> dict[str, list[str]]:
    """Remove a translated module's own `struct`/`union`/`type` for a name the prelude now
    takes from c2rust -- the compiler-exact layout wins, as it already does for statics.

    The model collapses C's `typedef struct _HIVE_LIST_ENTRY {..} HIVE_LIST_ENTRY;` into one
    `struct HIVE_LIST_ENTRY`, while c2rust's data tables (and the prelude) spell the tag
    `_HIVE_LIST_ENTRY`: the module's definition shadows the prelude's and the two types never
    unify (setuplib: registry's hive tables, partinfo's partition-type tables, fsutil's
    file-system table).
    """
    from .c2rust_anchor import _type_items

    out: dict[str, list[str]] = {}
    for path in sorted(modules.glob("*.rs")):
        text = path.read_text()
        items = {n: t for n, t in _type_items(text).items() if n in names}
        if not items:
            continue
        for name, item in items.items():
            text = (
                text.replace(item + "\n", "", 1)
                if item + "\n" in text
                else text.replace(item, "", 1)
            )
            out.setdefault(name, []).append(path.name)
        path.write_text(text)
    return out


def _island_constants(state: dict) -> set[str]:
    """Constants EVERY arch's island defines (`types_<arch>.rs`, plus `types_N_<arch>.rs`)."""
    src = _crate_dir(state) / "src"
    per_arch: list[set[str]] = []
    for arch in ("i386", "amd64", "arm64"):
        names: set[str] = set()
        for island in src.glob(f"types*_{arch}.rs"):
            names |= set(
                re.findall(
                    r"(?m)^pub (?:const|static) (\w+)\s*:", island.read_text(errors="replace")
                )
            )
        if names:
            per_arch.append(names)
    return set.intersection(*per_arch) if per_arch else set()


def _resolve_facts(state: dict, prelude: Path, undefined: list[str]) -> list[str]:
    """Constants the module's C sees and no Rust in the tree defines: clang evaluates them.

    setuplib had STATUS_PARTITION_FAILURE (ntstatus.h) and its own setuplib.h
    ERROR_SYSTEM_PARTITION_NOT_FOUND defined nowhere in Rust; asked to fix the functions
    using them, the model wrote 0xC000017D (it is 0xC0000172) and a different ERROR_ name.
    The value comes from the target compiler, per arch, agreed on all three (sdk_facts).
    Returns the names still undefined.
    """
    from . import sdk_facts
    from .macro_authority import MacroAuthorityError

    facts = prelude_resolve.existing_facts(prelude)
    # A fact is a stand-in for a constant the island lacks. Once a later resolve widens the
    # island (`island_headers`), the island defines it too and the prelude copy is a second
    # definition: atapi's replay gained ata_shared.h in its island AFTER the facts pass had
    # evaluated 47 of its constants, and every one became an E0428 on every arch.
    in_island = _island_constants(state)
    # ...and the same for an island ENUM alias the consensus block now carries, or a name a
    # translated module defines (re-exported by the siblings block): inetcpl's facts from a
    # run before urlmon.h was islanded kept URLZONE_* beside their `tagURLZONE` aliases, and
    # INTERNET_MAX_URL_LENGTH beside connections.rs's own const -- E0428 / E0255.
    # Any name the consensus block copies, not only island enum aliases: clipbrd carried
    # `WM_MOUSEHWHEEL: i32 = 0x20E` (fact) beside `WM_MOUSEHWHEEL: u32 = 526` (consensus).
    in_island |= set(prelude_resolve.existing_block(prelude))
    in_island |= set(prelude_resolve.existing_siblings(prelude))
    stale = sorted(set(facts) & in_island)
    for name in stale:
        del facts[name]
    if stale:
        print(
            f"resolve: {len(stale)} fact(s) dropped, the island or a module defines them now: "
            + ", ".join(stale)
        )
    wanted = sorted(n for n in undefined if prelude_resolve.looks_constant(n) and n not in facts)
    if not wanted:
        prelude_resolve.write_facts(prelude, prelude_resolve.render_facts(facts))
        return undefined
    known_types = _known_types(state)
    # Each name is probed in a TU that mentions it, so the TU's own headers are in scope.
    by_tu: dict[str, list[str]] = {}
    texts = {t: (REPO / t).read_text(errors="replace") for t in state["tus"]}
    for name in wanted:
        tu = next((t for t, x in texts.items() if re.search(rf"\b{name}\b", x)), state["tus"][0])
        by_tu.setdefault(tu, []).append(name)
    unresolved: dict[str, str] = {}
    for tu, names in sorted(by_tu.items()):
        try:
            r = sdk_facts.resolve(REPO, REPO / tu, names)
        except MacroAuthorityError as e:
            print(f"resolve: facts probe failed for {tu}: {str(e).splitlines()[0]}")
            unresolved.update({n: "probe failed" for n in names})
            continue
        for f in r.facts:
            ty = prelude_resolve.fact_rust_type(
                f.c_type, f.value, known_types, bare_int_unsigned=not state.get("usermode", True)
            )
            facts[f.name] = (ty, f.value, Path(tu).name)
        unresolved.update(r.unresolved)
    prelude_resolve.write_facts(prelude, prelude_resolve.render_facts(facts))
    got = [n for n in wanted if n in facts]
    if got:
        print(f"resolve: {len(got)} constant(s) evaluated by clang: {', '.join(got)}")
    for name, why in sorted(unresolved.items()):
        print(f"resolve: not evaluated: {name}: {why}")
    return [n for n in undefined if n not in facts]


