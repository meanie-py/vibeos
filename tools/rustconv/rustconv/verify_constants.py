# ── C Header Catalog Builder ──────────────────────────────────────────


def parse_c_hex(s: str) -> int | None:
    """Parse a C numeric literal to int."""
    s = s.strip()
    # Strip inline C comments and trailing semicolons/suffixes
    if "/*" in s:
        s = s[: s.index("/*")].strip()
    s = s.rstrip(";").rstrip("ULul").strip()
    try:
        if s.startswith("0x") or s.startswith("0X"):
            return int(s, 16)
        if s.startswith("0") and len(s) > 1 and s[1:].isdigit():
            return int(s, 8)
        if s.lstrip("-").isdigit():
            return int(s)
    except ValueError:
        pass
    return None


def parse_c_multichar(s: str) -> int | None:
    """Parse C multi-character literal like 'abcd' to u32."""
    s = s.strip()
    if s.startswith("'") and s.endswith("'"):
        chars = s[1:-1]
        if 1 <= len(chars) <= 4:
            # Pad to 4 chars from left (C pads with nulls on left)
            chars = chars.rjust(4, "\0")
            val = 0
            for c in chars:
                val = (val << 8) | ord(c)
            return val & 0xFFFFFFFF
    return None


def parse_ntstatus_cast(s: str) -> int | None:
    """Parse ((NTSTATUS)0xC0000001) pattern — reject macro calls and expressions."""
    s = s.strip()
    # Reject expressions with operators or macro-call commas
    if any(op in s for op in [",", "|", "+", "<<", ">>"]):
        return None
    m = re.search(r"0x[0-9A-Fa-f]+", s)
    if m:
        return int(m.group(), 16)
    return None


# ── WDK constants absent from ReactOS headers ────────────────────────
# These are real Windows DDK values that ReactOS headers do not define
# (they only appear in SAL annotations or driver-private contexts). Without
# a definition to cross-check against, a fabricated Rust value would pass
# silently. Seed them explicitly. Verified against the Windows WDK.
WDK_CONSTANT_SEED = {
    # POOL_TYPE — the no-execute variants (wdm.h). Windows: NonPagedPoolNx = 512.
    #
    # But seed the value THIS TREE COMPILES, not the one Windows ships. NX pool is
    # an NT6.2 feature ReactOS does not implement, so every in-tree consumer
    # redefines the name to the plain pool type before using it, under an
    # `#ifdef __REACTOS__` (and `__REACTOS__` is defined tree-wide,
    # CMakeLists.txt:87): cdfs/cdprocs.h:62, fastfat/fatprocs.h:47,
    # cdrom/cdrom.h:68, disk/disk.h:75, classpnp/dictlib.c:32 — all
    # `#define NonPagedPoolNx NonPagedPool`. Nothing here ever compiles 512, so
    # seeding 512 made this checker demand the one value that is WRONG for the
    # tree, and it flagged correct Rust as a mismatch.
    #
    # Seeding the effective value instead of skipping the name keeps the check
    # alive: an invented pool type still fails. If a module ever uses real NX
    # pool, it will stop defining the macro, and this seed is what must change.
    "NonPagedPoolNx": 0,  # NonPagedPool
    "NonPagedPoolNxCacheAligned": 4,  # NonPagedPoolCacheAligned
    # No in-tree module overrides this one, so it keeps the Windows value.
    "NonPagedPoolSessionNx": 544,  # 0x220 = NonPagedPoolNx + 32
}


def _eval_enum_expr(expr: str, scope: dict[str, int]) -> int | None:
    """Evaluate a C enum initializer: int/hex literals, prior enum names,
    and the operators + - | << found in real POOL_TYPE-style enums. Returns
    None if any token can't be resolved (so we don't fabricate a value)."""
    expr = expr.strip()
    if not expr:
        return None
    # Tokenize into names, numbers, and operators.
    tokens = re.findall(r"0[xX][0-9A-Fa-f]+|\d+|[A-Za-z_][A-Za-z0-9_]*|<<|[|+\-]", expr)
    if not tokens:
        return None
    py = []
    for t in tokens:
        if re.fullmatch(r"0[xX][0-9A-Fa-f]+", t):
            py.append(str(int(t, 16)))
        elif t.isdigit() or t in ("<<", "|", "+", "-"):
            py.append(t)
        elif re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", t):
            if t in scope:
                py.append(str(scope[t]))
            else:
                return None  # unresolved name — bail rather than guess
        else:
            return None
    try:
        # Only arithmetic/bitwise over integers; no names/calls remain.
        return int(eval(" ".join(py), {"__builtins__": {}}, {})) & 0xFFFFFFFF
    except Exception:
        return None


# ── CTL_CODE (IOCTL/FSCTL device-control codes) ──────────────────────
# IOCTL_*/FSCTL_* constants are #defined via the CTL_CODE() macro, not as plain
# literals, so the #define/multichar/ntstatus parsers above all skip them — they
# never enter the catalog and a garbage-translated Rust copy goes unchecked. This
# is exactly the class that cost the arm64 0x64/0x23 grind: ramdisk-rust had
# `const FSCTL_CREATE_RAM_DISK = 0x900c4` (real: 0x240000) and
# `IOCTL_DISK_CHECK_VERIFY = 0x70000` (real: 0x74800, collided with
# GET_DRIVE_GEOMETRY) — both silently dead dispatch arms, no compiler warning.
# We evaluate the macro: CTL_CODE(DeviceType, Function, Method, Access)
#   = (DeviceType << 16) | (Access << 14) | (Function << 2) | Method
# (winioctl.h / iotypes.h). All four operands resolve from the catalog scope; if
# any can't be resolved we skip the def rather than fabricate a value.

# Base operands — standardized Windows values, identical across every DDK
# version. Seeded (not header-harvested) because ReactOS defines FILE_*_ACCESS
# via aliases (FILE_READ_ACCESS = FILE_READ_DATA) in some headers and as literals
# in others; seeding removes the order-dependence and guarantees correctness.
CTL_BASE_SEED = {
    "METHOD_BUFFERED": 0,
    "METHOD_IN_DIRECT": 1,
    "METHOD_OUT_DIRECT": 2,
    "METHOD_NEITHER": 3,
    "FILE_ANY_ACCESS": 0,
    "FILE_READ_ACCESS": 1,
    "FILE_WRITE_ACCESS": 2,
}

# Headers that define IOCTL_*/FSCTL_* — directly (CTL_CODE) or through a
# device-specific wrapper macro (_AFD_CONTROL_CODE, _TDI_CONTROL_CODE,
# _NDIS_CONTROL_CODE, USB_CTL, …). The DDK device headers use multi-line
# continuation defs, so the text is continuation-joined before scanning;
# iotypes.h/winioctl.h supply the FILE_DEVICE_* device-type literals, the
# CTL_CODE primitive, and the IOCTL_*_BASE aliases the wrappers need. Adding a
# header here is the only step needed to bring a new IOCTL family under the net
# — values are computed generically (see _expand_func_macros), not hardcoded.
CTL_CODE_HEADERS = (
    "sdk/include/xdk/iotypes.h",
    "sdk/include/psdk/winioctl.h",
    "sdk/include/psdk/ntdddisk.h",
    "sdk/include/psdk/ntddcdrm.h",
    "sdk/include/psdk/ntddstor.h",
    "sdk/include/psdk/ntddscsi.h",
    "sdk/include/psdk/ntddvol.h",
    "sdk/include/reactos/drivers/ntddrdsk.h",
    # Wrapper-macro IOCTL families (each bottoms out in CTL_CODE or its own
    # bit-packing — all handled generically by the func-macro expander):
    "sdk/include/reactos/drivers/afd/shared.h",  # _AFD_CONTROL_CODE → IOCTL_AFD_*
    "sdk/include/psdk/ntddtdi.h",  # _TDI_CONTROL_CODE → IOCTL_TDI_*
    "sdk/include/psdk/ntddndis.h",  # _NDIS_CONTROL_CODE → IOCTL_NDIS_*
    "sdk/include/psdk/usbiodef.h",  # USB_CTL → IOCTL_*_USB_*
)

# CTL_CODE seeded as a builtin function-like macro so the evaluator works even
# when winioctl.h isn't in scope (e.g. unit tests / a family header that assumes
# it). A header-parsed CTL_CODE (identical) harmlessly overrides this.
_BUILTIN_FUNC_MACROS: dict[str, tuple[list[str], str]] = {
    "CTL_CODE": (
        ["DeviceType", "Function", "Method", "Access"],
        "(((DeviceType) << 16) | ((Access) << 14) | ((Function) << 2) | (Method))",
    ),
}


def _join_line_continuations(text: str) -> str:
    r"""Join C `\`-continued lines so a multi-line #define is one logical line."""
    return re.sub(r"\\\n", " ", text)


def _split_top_commas(s: str) -> list[str]:
    """Split on commas not nested inside parentheses."""
    parts, depth, cur = [], 0, ""
    for ch in s:
        if ch == "(":
            depth += 1
            cur += ch
        elif ch == ")":
            depth -= 1
            cur += ch
        elif ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return [p.strip() for p in parts]


def _matching_paren(s: str, open_idx: int) -> int | None:
    """Index of the ')' that closes the '(' at open_idx, or None if unbalanced."""
    depth = 0
    for i in range(open_idx, len(s)):
        if s[i] == "(":
            depth += 1
        elif s[i] == ")":
            depth -= 1
            if depth == 0:
                return i
    return None


def _parse_func_macros(text: str) -> dict[str, tuple[list[str], str]]:
    """Collect function-like macro defs `#define NAME(p1, p2, …) body` (text
    already continuation-joined) — the CTL_CODE-family wrappers (CTL_CODE itself,
    _AFD_CONTROL_CODE, _TDI_CONTROL_CODE, _NDIS_CONTROL_CODE, USB_CTL, …) that
    IOCTL/FSCTL defines invoke. Returns NAME → (param_names, body). Object-like
    macros (a space before `(`, so no params) are ignored. Extra non-arithmetic
    macros that happen to match are harmless — they only expand when an IOCTL body
    calls them, and a non-integer expansion just fails evaluation (skipped)."""
    macros: dict[str, tuple[list[str], str]] = {}
    fm_re = re.compile(r"#define\s+([A-Za-z_]\w*)\(([^)]*)\)\s+(.+?)\s*$")
    for raw in text.splitlines():
        line = re.sub(r"/\*.*?\*/", "", raw)
        line = re.sub(r"//.*", "", line).strip()
        m = fm_re.match(line)
        if not m:
            continue
        params = [p.strip() for p in m.group(2).split(",") if p.strip()]
        if params:
            macros[m.group(1)] = (params, m.group(3).strip())
    return macros


def _expand_func_macros(
    expr: str, func_macros: dict[str, tuple[list[str], str]], depth: int = 0
) -> str:
    """Recursively expand function-like macro CALLS in expr — CTL_CODE(…),
    _AFD_CONTROL_CODE(…), and nested wrappers — to their argument-substituted
    bodies, so the result is pure integer arithmetic _eval_int_expr can evaluate.
    Whole-word param substitution (so a param `Method` never matches inside
    `METHOD_NEITHER`); each argument is itself expanded first (nested calls in
    args). Depth-guarded: a runaway / self-referential macro bails, leaving an
    unevaluable expression → the def is skipped, never fabricated. Family-agnostic
    — AFD's bespoke `(BASE<<12 | Op<<2 | Method)` packing works identically to a
    CTL_CODE-based one; both are just arithmetic after expansion."""
    if depth > 24 or "(" not in expr:
        return expr
    search_from = 0
    pat = re.compile(r"\b([A-Za-z_]\w*)\s*\(")
    while True:
        m = pat.search(expr, search_from)
        if not m:
            return expr
        name = m.group(1)
        if name not in func_macros:
            search_from = m.end()
            continue
        open_idx = m.end() - 1  # the '(' the regex matched
        close_idx = _matching_paren(expr, open_idx)
        if close_idx is None:
            return expr
        params, body = func_macros[name]
        args = _split_top_commas(expr[open_idx + 1 : close_idx])
        if len(args) != len(params):
            search_from = m.end()  # not a valid invocation — skip past it
            continue
        new_body = body
        for p, a in zip(params, args, strict=True):  # lengths checked above
            a_exp = _expand_func_macros(a.strip(), func_macros, depth + 1)
            new_body = re.sub(r"\b" + re.escape(p) + r"\b", "(" + a_exp + ")", new_body)
        expr = expr[: m.start()] + "(" + new_body + ")" + expr[close_idx + 1 :]
        return _expand_func_macros(expr, func_macros, depth + 1)


def _eval_int_expr(
    expr: str, scope: dict[str, int], func_macros: dict[str, tuple[list[str], str]] | None = None
) -> int | None:
    """Evaluate an integer expression (literals, scope names, + - | & << >> ~ ^
    and parens). With func_macros, function-like macro calls are expanded first.
    Returns None if any token is unrecognized or a name is unresolved — so we
    never fabricate a value from an expression we didn't fully understand."""
    expr = expr.strip()
    if not expr:
        return None
    if func_macros:
        expr = _expand_func_macros(expr, func_macros).strip()
    tokens = re.findall(r"0[xX][0-9A-Fa-f]+|\d+|[A-Za-z_]\w*|<<|>>|[|&+\-()~^]", expr)
    # Reject if tokenization didn't consume the whole expression (stray * / , etc.)
    if "".join(tokens) != re.sub(r"\s+", "", expr):
        return None
    py = []
    for t in tokens:
        if re.fullmatch(r"0[xX][0-9A-Fa-f]+", t):
            py.append(str(int(t, 16)))
        elif t.isdigit() or t in ("<<", ">>", "|", "&", "+", "-", "(", ")", "~", "^"):
            py.append(t)
        elif re.fullmatch(r"[A-Za-z_]\w*", t):
            if t in scope:
                py.append(str(scope[t]))
            else:
                return None  # unresolved name — bail rather than guess
        else:
            return None
    try:
        return int(eval(" ".join(py), {"__builtins__": {}}, {})) & 0xFFFFFFFF
    except Exception:
        return None


def parse_ioctl_defines(
    text: str,
    scope: dict[str, int],
    func_macros: dict[str, tuple[list[str], str]],
    ctl_acc: dict[str, set],
) -> None:
    """Find `#define (IOCTL|FSCTL)_NAME <expr>` defs (text already
    continuation-joined), expand any function-like wrapper macros, evaluate to an
    integer, and accumulate NAME→{values}. Namespace-scoped to the IOCTL_/FSCTL_
    device-control namespace so unrelated macros are never evaluated. One path
    subsumes every form: a plain literal, a direct CTL_CODE(…), and any wrapper
    (_AFD_/_TDI_/_NDIS_CONTROL_CODE, USB_CTL, …). A def whose body doesn't fully
    resolve is skipped; the caller drops any NAME with >1 distinct value (header
    ambiguity — e.g. the same IOCTL defined per-arch or guarded differently)."""
    ioctl_re = re.compile(r"#define\s+((?:IOCTL|FSCTL)_[A-Z0-9_]+)\s+(.+)$")
    for raw in text.splitlines():
        line = re.sub(r"/\*.*?\*/", "", raw.strip())
        line = re.sub(r"//.*", "", line).strip()
        m = ioctl_re.match(line)
        if not m:
            continue
        val = _eval_int_expr(m.group(2).strip(), scope, func_macros)
        if val is not None:
            ctl_acc.setdefault(m.group(1), set()).add(val)


def parse_c_enums(text: str, enum_acc: dict[str, set]) -> None:
    """Parse `enum { ... }` bodies, assigning C enum semantics (sequential
    counter, honoring `= EXPR` overrides). Accumulates name→{values seen}
    into enum_acc (across all headers). A member whose initializer can't be
    evaluated resets the counter so we never emit a wrong auto-incremented
    value for the rest of that enum. The caller drops any name that collected
    more than one distinct value (ambiguous — the same identifier lives in
    multiple enums, e.g. `UserRequest`/`Isa`) so we never false-positive on it."""
    for raw_body in re.findall(r"\benum\b[^{};]*\{([^}]*)\}", text):
        # Preprocessor lines inside enum bodies (e.g. GateWait behind
        # `#if (NTDDI_VERSION >= NTDDI_WS03)` in ndk/ketypes.h) used to poison
        # the tail of the enum. Strip them and take the union of all branches —
        # a member whose value differs across branches then collects multiple
        # values and is dropped by the ambiguity rule below, which is the safe
        # outcome for arch/version-divergent enums.
        body = "\n".join(ln for ln in raw_body.splitlines() if not ln.lstrip().startswith("#"))
        # Strip comments, then split members on top-level commas.
        body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
        body = re.sub(r"//.*", "", body)
        scope: dict[str, int] = {}
        nxt: int | None = 0
        for member in body.split(","):
            member = member.strip()
            if not member:
                continue
            m = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\s*(?:=\s*(.+))?$", member, re.S)
            if not m:
                nxt = None
                continue
            name, init = m.group(1), m.group(2)
            if init is not None:
                val = _eval_enum_expr(init, {**scope})
            else:
                val = nxt
            if val is None:
                nxt = None  # lost the counter — don't fabricate downstream
                continue
            scope[name] = val
            enum_acc.setdefault(name, set()).add(val)
            nxt = (val + 1) & 0xFFFFFFFF  # C enums are int — wrap (e.g. -1 → 0)


def build_c_catalog(reactos_root: Path, include_enums: bool = False) -> dict[str, int]:
    """Build name→value mapping from C headers.

    include_enums=False (default, used by the build gate): only #define values
    and the WDK seed — high-confidence, zero false positives. include_enums=True
    (the `--enums` finder): also merge C enum members. Enum members are powerful
    for catching fabricated selectors but FP-prone, because a generic identifier
    (`BusRelations`, `UserRequest`) can name a member of an enum that isn't in
    our header list, then collide with a same-named member that is. Treat
    `--enums` output as candidates for manual review, not a gate."""
    catalog = dict(WDK_CONSTANT_SEED)
    enum_acc: dict[str, set] = {}

    header_files = [
        reactos_root / "sdk/include/xdk/iotypes.h",
        reactos_root / "sdk/include/xdk/setypes.h",
        reactos_root / "sdk/include/psdk/ntstatus.h",
        reactos_root / "ntoskrnl/include/internal/tag.h",
        reactos_root / "ntoskrnl/include/internal/io.h",
        reactos_root / "sdk/include/xdk/ketypes.h",
        # ndk/ketypes.h holds the DISPATCHER enums (ADJUST_REASON, KTHREAD_STATE,
        # KOBJECTS, KWAIT_REASON…). Its absence let a translated
        # `const AdjustUnwait = 3` (header: 1) ship in ke/wait.rs and silently
        # kill the unwait priority boost for every thread wakeup (found by the
        # 2026-07-04 dispatcher audit). Keep it in the catalog so `--enums`
        # catches dispatcher-enum drift. The sibling ndk type headers joined it
        # the same day (info classes, LPC message types, object/section enums).
        # NB: some ndk enums legitimately diverge between the NTOS_MODE_USER
        # and kernel branches (e.g. KWAIT_REASON's WrGuardedMutex: 22 user-mode
        # vs 35 kernel/xdk) — the multi-value ambiguity rule drops those.
        reactos_root / "sdk/include/ndk/ketypes.h",
        reactos_root / "sdk/include/ndk/pstypes.h",
        reactos_root / "sdk/include/ndk/obtypes.h",
        reactos_root / "sdk/include/ndk/mmtypes.h",
        reactos_root / "sdk/include/ndk/extypes.h",
        reactos_root / "sdk/include/ndk/lpctypes.h",
        reactos_root / "sdk/include/ndk/cmtypes.h",
        reactos_root / "sdk/include/ndk/iotypes.h",
        reactos_root / "sdk/include/reactos/drivers/ntddrdsk.h",
        # RM_API_NUMBER: the lsass <-> kernel SRM command protocol. It starts at 1, and
        # se-rust's dispatch matched 0/1/2 with the names as comments, so every lsass
        # RmCreateLogonSession ran the DELETE handler and LogonUser always failed
        # STATUS_NO_SUCH_LOGON_SESSION (2026-10-08, modrun's logon suite).
        reactos_root / "sdk/include/reactos/srmp.h",
        # I/O error-log message codes (IO_ERR_* / IO_WARNING_* / IO_RECOVERED_*).
        # These are typed NTSTATUS and handed to IoWriteErrorLogEntry, so a wrong
        # value writes the WRONG message into the system event log. Added
        # 2026-07-24 after the §9.113 sweep generalized: classpnp declared
        # IO_ERR_NOT_READY = 0xC0040002 (real: 0xC004000F) and
        # IO_WARNING_IO_OPERATION_RETRIED = 0x80040032 (real: 0x80040099) — proven
        # invented because sibling files in the SAME crate had them right.
        reactos_root / "sdk/include/psdk/ntiologc.h",
        # STATUS_ROS_EXEFMT_* — ReactOS-internal statuses that cross a module
        # boundary (section_pe.rs produces, section.rs compares). section.rs had
        # an invented 0xC000FFFE vs the real 0xA0100001, so every comparison
        # silently failed and a non-PE image section leaked the raw internal
        # status instead of STATUS_INVALID_IMAGE_NOT_MZ.
        reactos_root / "sdk/include/reactos/exeformat.h",
        # Bugcheck stop codes. ntkrnl_sys::bugcodes is generated + self-verifying
        # (tools/gen_bugcodes.py), but hand-declared copies still exist in
        # ntkrnl-sys/src/mm.rs and friends; this keeps those honest too.
        reactos_root / "sdk/lib/rust/reactos-link/committed-headers/bugcodes.h",
        # Base NT typedefs/limits (UNICODE_STRING_MAX_BYTES, …). Found via
        # scan_const_contradictions: 8 copies of UNICODE_STRING_MAX_BYTES were
        # right and 2 were not (0xFFFC, 0xFFFF vs the real 65534) — and both wrong
        # ones sit in BOUNDS CHECKS, including RPC server input validation.
        reactos_root / "sdk/include/xdk/ntbasedef.h",
    ]

    define_re = re.compile(r"^#define\s+([A-Z_][A-Z0-9_]*)\s+(.+?)(?:\s*//.*)?$")

    for hfile in header_files:
        if not hfile.exists():
            continue
        text = hfile.read_text(errors="replace")
        for line in text.splitlines():
            m = define_re.match(line.strip())
            if not m:
                continue
            name, expr = m.group(1), m.group(2).strip()

            # Try hex/decimal
            val = parse_c_hex(expr)
            if val is not None:
                catalog[name] = val
                continue

            # Try multi-char literal
            val = parse_c_multichar(expr)
            if val is not None:
                catalog[name] = val
                continue

            # Try NTSTATUS cast
            val = parse_ntstatus_cast(expr)
            if val is not None:
                catalog[name] = val
                continue

        # Enum members (e.g. POOL_TYPE) — not #defines, but real constants.
        parse_c_enums(text, enum_acc)

    # Merge only UNAMBIGUOUS enum members: a name that resolved to more than
    # one distinct value lives in multiple enums (generic identifiers like
    # `UserRequest`, `Isa`, `BusRelations`) and can't be checked from a flat
    # `const NAME = VALUE` line without knowing its enum type — skip it.
    # #define/seed entries already in the catalog always win.
    if include_enums:
        for name, vals in enum_acc.items():
            if len(vals) == 1:
                catalog.setdefault(name, next(iter(vals)))

    # ── CTL_CODE device-control codes (IOCTL_*/FSCTL_*) ──────────────────
    # Build an evaluation scope: catalog literals (incl. FILE_DEVICE_* from
    # iotypes.h) + extra device-type literals/aliases from the CTL headers +
    # the base-operand seed (authoritative). Then evaluate every CTL_CODE def.
    alias_re = re.compile(r"^#define\s+([A-Z_][A-Z0-9_]*)\s+([A-Z_][A-Z0-9_]*)\s*(?://.*)?$")
    scope = dict(catalog)
    aliases: dict[str, str] = {}
    ctl_texts: list[str] = []
    func_macros: dict[str, tuple[list[str], str]] = dict(_BUILTIN_FUNC_MACROS)
    for rel in CTL_CODE_HEADERS:
        hfile = reactos_root / rel
        if not hfile.exists():
            continue
        text = _join_line_continuations(hfile.read_text(errors="replace"))
        ctl_texts.append(text)
        func_macros.update(_parse_func_macros(text))  # CTL_CODE + wrapper families
        for raw in text.splitlines():
            line = raw.strip()
            m = define_re.match(line)
            if m:
                v = parse_c_hex(m.group(2).strip())
                if v is not None:
                    scope.setdefault(m.group(1), v)
                    continue
            am = alias_re.match(line)
            if am:
                aliases.setdefault(am.group(1), am.group(2))
    # Resolve identifier aliases (e.g. IOCTL_DISK_BASE → FILE_DEVICE_DISK) to a
    # fixpoint, then let the base-operand seed win over any header definition.
    for _ in range(8):
        progressed = False
        for k, tgt in aliases.items():
            if k not in scope and tgt in scope:
                scope[k] = scope[tgt]
                progressed = True
        if not progressed:
            break
    scope.update(CTL_BASE_SEED)

    ctl_acc: dict[str, set] = {}
    for text in ctl_texts:
        parse_ioctl_defines(text, scope, func_macros, ctl_acc)
    # Merge unambiguous codes; a plain-literal #define already in catalog wins.
    for name, vals in ctl_acc.items():
        if len(vals) == 1:
            catalog.setdefault(name, next(iter(vals)))

    return catalog


# ── Rust Constant Parser ─────────────────────────────────────────────


def parse_rust_const(line: str) -> tuple[str, int] | None:
    """Parse a Rust const definition, return (name, value) or None."""
    # Pattern: [pub[(crate|super|in …)]] const NAME: TYPE = VALUE;  (NAME may be
    # mixed-case, e.g. enum-derived constants like NonPagedPoolNx — not just
    # SCREAMING_CASE). TYPE may be path-qualified (ntkrnl_sys::ddk::ULONG).
    # `pub const` was invisible until 2026-07-04 — ~27K kernel-crate consts
    # escaped the checker (the AdjustUnwait=3 bug would have been undetectable
    # had the translator written `pub const`).
    m = re.match(
        r"(?:pub(?:\([^)]*\))?\s+)?const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*[\w:]+\s*=\s*(.+?)\s*;",
        line.strip(),
    )
    if not m:
        return None
    name, expr = m.group(1), m.group(2).strip()

    # Hex literal
    hm = re.match(r"(0x[0-9A-Fa-f_]+)(?:_?[ui]\d+)?", expr)
    if hm:
        return name, int(hm.group(1).replace("_", ""), 16)

    # Decimal literal (optionally type-suffixed: 3u8, 2_i32, 5usize)
    dm = re.match(r"(-?[0-9][0-9_]*)(?:_?[ui](?:8|16|32|64|size))?$", expr)
    if dm:
        val = int(dm.group(1).replace("_", ""))
        if val < 0:
            val = val & 0xFFFFFFFF
        return name, val

    # u32::from_le_bytes(*b"abcd") or from_le_bytes([...])
    m2 = re.search(r'from_le_bytes\(\*?b"(.{4})"\)', expr)
    if m2:
        return name, struct.unpack("<I", m2.group(1).encode("latin-1"))[0]
    m3 = re.search(r"from_le_bytes\(\[(.+)\]\)", expr)
    if m3:
        parts = [p.strip().strip("b'\"").replace("\\", "") for p in m3.group(1).split(",")]
        if len(parts) == 4:
            try:
                bs = bytes(ord(p[0]) if len(p) == 1 else int(p, 0) for p in parts)
                return name, struct.unpack("<I", bs)[0]
            except (ValueError, IndexError):
                pass

    # Cast pattern: 0xXXXX_u32 as i32
    m4 = re.match(r"(0x[0-9A-Fa-f_]+)_?u\d+\s+as\s+i\d+", expr)
    if m4:
        return name, int(m4.group(1).replace("_", ""), 16)

    return None


def fix_const_line(line: str, name: str, c_val: int) -> str:
    """Rewrite a const definition line with the correct C value."""
    # Match the const pattern and replace the value. The leading `\s*` (captured
    # in the prefix) preserves indentation so FUNCTION-LOCAL consts get fixed too —
    # parse_rust_const strips the line so it detects them, but without this the
    # rewrite silently no-op'd on any `    const NAME = ...` (e.g. cdrom-rust's
    # IOCTL_CDROM_GET_INQUIRY_DATA / IOCTL_SCSI_PASS_THROUGH_DIRECT_EX).
    m = re.match(
        r"(\s*(?:pub(?:\([^)]*\))?\s+)?const\s+"
        + re.escape(name)
        + r"\s*:\s*[\w:]+\s*=\s*)(.+?)(;.*)",
        line.rstrip(),
    )
    if not m:
        return line
    prefix, _old_val, suffix = m.group(1), m.group(2), m.group(3)

    # Determine the best representation
    rust_type = re.search(r":\s*(\w+)", prefix)
    type_name = rust_type.group(1) if rust_type else "ULONG"

    if type_name in ("NTSTATUS", "i32") and c_val > 0x7FFFFFFF:
        # NTSTATUS: use unsigned cast pattern
        new_val = f"0x{c_val:08X}_u32 as i32"
    elif c_val > 0xFFFF:
        new_val = f"0x{c_val:08X}"
    elif c_val > 0xFF:
        new_val = f"0x{c_val:04X}"
    else:
        new_val = f"0x{c_val:02X}"

    return prefix + new_val + suffix


# Constants that differ per architecture (#ifdef _WIN64 etc.) — skip auto-fix
ARCH_DEPENDENT_CONSTANTS = {
    "PORT_MAXIMUM_MESSAGE_LENGTH",  # 512 on 64-bit, 256 on 32-bit
    # ndk/mmtypes.h defines this TWICE under a bitness #ifdef (0x7FFFFFFF vs
    # 0x7FF). The flat catalog keeps whichever it parses last, so a correct
    # per-arch Rust value would false-mismatch. Skip.
    "MMWSLE_PREVIOUS_FREE_MASK",
    # PS_QUOTA_TYPE's max sentinel: the enum has NTDDI_LONGHORN-gated members
    # (PsWorkingSet, PsCpuRate) that the flat catalog counts but the build's
    # NTDDI level excludes → catalog says 5, real build (bindgen) is 3. It's a
    # QuotaEntry[] loop bound, so a wrong value is an OOB read — the checker
    # must NOT push the raw-header count here. (Cross-check named enum maxes
    # against bindgen, not the raw header.)
    "PsQuotaTypes",
}


def verify_file(rs_path: Path, catalog: dict[str, int], fix: bool = False) -> list[dict]:
    """Verify constants in a single Rust file. Returns list of mismatches."""
    mismatches = []
    lines = rs_path.read_text().splitlines()
    modified = False

    for lineno, line in enumerate(lines, 1):
        parsed = parse_rust_const(line)
        if not parsed:
            continue
        name, rust_val = parsed

        if name in ARCH_DEPENDENT_CONSTANTS:
            continue

        # `#[cfg(...)]`-gated declarations are the Rust spelling of the header's
        # own `#ifdef` — e.g. MEMORY_ALLOCATION_ALIGNMENT is 16 under _WIN64 and
        # 8 otherwise, and iomgr declares BOTH under target_pointer_width. The
        # flat catalog can only hold one of the two header values, so comparing
        # against a gated declaration reports a mismatch on correct code. Skipping
        # them removes the whole false-positive class that ARCH_DEPENDENT_CONSTANTS
        # was being hand-fed one name at a time.
        gated = False
        for back in range(1, 4):
            if lineno - 1 - back < 0:
                break
            prev = lines[lineno - 1 - back].strip()
            if prev.startswith("#[cfg("):
                gated = True
                break
            if not (prev.startswith("//") or prev.startswith("#[")):
                break
        if gated:
            continue

        # Pool tags (`TAG_*`) are compared unreliably: the C catalog parses
        # `#define TAG_MDL ' LDM'` via parse_c_multichar (big-endian nibble
        # order) while the Rust side is `u32::from_le_bytes(*b"...")` — the two
        # conventions disagree on byte order, so every tag "mismatches" even
        # when both spell the same 4 chars. Skip until the comparison is made
        # byte-order-aware. (Tag drift is cosmetic — pool-dump display — not
        # boot-affecting; a dedicated tag check is tracked separately.)
        if name.startswith("TAG_"):
            continue

        if name in catalog:
            c_val = catalog[name]
            # Signed C values (e.g. THREAD_BASE_PRIORITY_MIN = -2) vs Rust's
            # 32-bit-masked parse (0xFFFFFFFE): compare as u32.
            if c_val < 0:
                c_val = c_val & 0xFFFFFFFF
            if rust_val != c_val:
                mismatches.append(
                    {
                        "file": str(rs_path),
                        "line": lineno,
                        "name": name,
                        "rust_val": f"0x{rust_val:08X}",
                        "c_val": f"0x{c_val:08X}",
                    }
                )
                if fix:
                    lines[lineno - 1] = fix_const_line(line, name, c_val)
                    modified = True

    if fix and modified:
        rs_path.write_text("\n".join(lines) + "\n")

    return mismatches


def main():
    parser = argparse.ArgumentParser(description="Verify Rust constants against C headers")
    parser.add_argument("files", nargs="*", help="Rust files to check (default: all)")
    parser.add_argument("--fix", action="store_true", help="Auto-fix mismatches")
    parser.add_argument(
        "--enums",
        action="store_true",
        help="Also check against C enum members (FP-prone finder, "
        "not for gating — review hits manually)",
    )
    args = parser.parse_args()

    reactos_root = _RUSTCONV_REACTOS_ROOT  # tools/rustconv → reactos/

    catalog = build_c_catalog(reactos_root, include_enums=args.enums)
    # Volatile summary → stderr so the gate baseline (stdout-only) captures just the
    # stable `MISMATCH:` finding lines. Otherwise the catalog/file counts (which move
    # on any header or workspace-file change) read as new findings on every edit.
    print(
        f"C catalog: {len(catalog)} constants from headers" + (" (+enums)" if args.enums else ""),
        file=sys.stderr,
    )

    if args.files:
        rs_files = [Path(f) for f in args.files]
    else:
        # Whole Rust kernel/driver workspace — IOCTL/FSCTL garbage consts live in the
        # driver crates (ramdisk, cdrom, fastfat, …), not just ntoskrnl-rust. Skip
        # build output under target/. Skip bindgen-GENERATED files: they compile from
        # the project's headers at the real NTDDI level, i.e. they ARE ground truth —
        # when they disagree with this catalog's flat header parse it's the catalog
        # picking a different #ifdef branch (IO_REPARSE_TAG_VALID_VALUES,
        # MAXIMUM_PROC_PER_GROUP) or a cross-header generic-name collision
        # (BITS_PER_ENTRY, DISPATCH_LENGTH), never a translation bug; "fixing" them
        # would corrupt generated code (the PsQuotaTypes lesson, generalized).
        # By CONTENT as well as name: a crate's own island (`types_<arch>.rs`, emitted by
        # gen_driver_types.sh) is the same bindgen output under another name, and the ATA
        # islands' MAXIMUM_PROC_PER_GROUP is exactly the #ifdef-branch case described above.
        rs_files = sorted(
            p
            for p in source_files(reactos_root / "sdk/lib/rust")
            if "/target/" not in p.as_posix()
            and not p.name.startswith(("bindgen_", "hal_bindgen_"))
            and not _bindgen_generated(p)
        )

    total_mismatches = 0
    files_fixed = 0
    for rs_file in rs_files:
        mismatches = verify_file(rs_file, catalog, fix=args.fix)
        if mismatches:
            for m in mismatches:
                action = "FIXED" if args.fix else "MISMATCH"
                print(
                    f"  {action}: {m['file']}:{m['line']}: {m['name']}: "
                    f"Rust={m['rust_val']} → C={m['c_val']}"
                )
            total_mismatches += len(mismatches)
            if args.fix:
                files_fixed += 1

    summary = (
        f"Fixed {total_mismatches} constants in {files_fixed} files"
        if args.fix
        else f"{total_mismatches} mismatches found across {len(rs_files)} files"
    )
    print(summary, file=sys.stderr)
    return 1 if total_mismatches > 0 and not args.fix else 0


if __name__ == "__main__":
    sys.exit(main())
