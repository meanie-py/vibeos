"""kbd_layouts — every keyboard layout DLL's data TU as Rust, for $0.

`dll/keyboard/CMakeLists.txt` lists the layouts (`_keyboard_layouts`); each is ONE data TU,
`dll/keyboard/<layout>/<layout>.c`, ending in `KbdLayerDescriptor(VOID) { return &table; }`.
This drives `c_data_port` (clang decides every byte) over all of them into
`sdk/lib/rust/kbdlayouts-rust/src/<layout>/` and adds, to each module, the accessor

    #[export_name = "<layout>_KbdLayerDescriptor"]
    pub unsafe extern "system" fn KbdLayerDescriptor() -> PKBDTABLES { addr_of_mut!(<table>) }

(the table named by the C's own `return`). The `pub mod <layout>;` list in lib.rs lives
between generated markers. Like `port data`, a re-run rewrites changed files only and removes
files this generator wrote that it no longer writes. A layout c_data_port cannot do is
REPORTED with its reason and makes the exit status nonzero -- never skipped silently.

    python -m rustconv.kbd_layouts [--only kbdus,kbdfr] [--jobs 4] [--arches i386,amd64,arm64]
"""

from __future__ import annotations

import argparse
import re
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from . import c_data_port as cdp
from . import macro_authority as ma
from .config import REACTOS_ROOT

REPO = REACTOS_ROOT  # the invoked tree, not this file's checkout
KEYBOARD = REPO / "dll" / "keyboard"
CRATE = REPO / "sdk" / "lib" / "rust" / "kbdlayouts-rust" / "src"
# The family cell that links every layout DLL: one [[bin]] per layout.
CELL = REPO / "sdk" / "lib" / "rust" / "kbdlayouts-cargo" / "Cargo.toml"
BEGIN = "// BEGIN GENERATED: layouts (python -m rustconv.kbd_layouts)"
END = "// END GENERATED: layouts"
# c_data_port stamps its files with this; only files carrying it are the generator's to prune.
MARK = "generated by `rustconv data-port"


class LayoutError(Exception):
    pass


def layouts(cmake: Path = KEYBOARD / "CMakeLists.txt") -> list[str]:
    """The layout names `_keyboard_layouts` lists, in order."""
    m = re.search(r"list\(APPEND _keyboard_layouts\s+(.*?)\)", cmake.read_text(), re.S)
    if m is None:
        raise LayoutError(f"{cmake}: no `list(APPEND _keyboard_layouts ...)`")
    names = [n for n in m.group(1).split() if not n.startswith("#")]
    if len(set(names)) != len(names):
        raise LayoutError(f"{cmake}: _keyboard_layouts repeats a layout")
    return names


_ADDR = re.compile(r"(?:\(\s*PKBD\w*\s*\)\s*)?&\s*(\w+)((?:\s*(?:\.\s*\w+|\[\s*\d+\s*\]))*)")


def returned_table(src: str, fn: str = "KbdLayerDescriptor") -> str | None:
    """The Rust place expression (`keyboard_layout_table`, `t.Base`, `nls_tables[0]`) whose
    address the C's `fn` returns; None when the TU does not define `fn`."""
    text = re.sub(r"/\*.*?\*/|//[^\n]*", "", src, flags=re.S)
    if not re.search(rf"\b{fn}\s*\(", text):
        return None
    m = re.search(
        rf"\b{fn}\s*\(\s*(?:VOID|void)?\s*\)\s*\{{\s*return\s*(.*?)\s*;\s*\}}", text, re.S
    )
    if m is None:
        raise LayoutError(f"{fn} is defined but is not `{{ return ...; }}`")
    a = _ADDR.fullmatch(m.group(1).strip())
    if a is None:
        raise LayoutError(f"{fn} returns `{m.group(1).strip()}`, not &table[.member][idx]")
    return a.group(1) + re.sub(r"\s+", "", a.group(2))


def accessor(
    layout: str, place: str, fn: str = "KbdLayerDescriptor", ret: str = "PKBDTABLES"
) -> str:
    what = "the layout's tables" if fn == "KbdLayerDescriptor" else "its NLS tables"
    return (
        "\n"
        f"/// `{layout}.dll` export `{fn}`: {what}. The name is per layout so that\n"
        "/// every layout can live in one staticlib; its .spec maps it onto the real name.\n"
        f'#[export_name = "{layout}_{fn}"]\n'
        f'pub unsafe extern "system" fn {fn}() -> {ret} {{\n'
        f"    addr_of_mut!({place}) as {ret}\n"
        "}\n"
    )


def generate(layout: str, arches: tuple[str, ...]) -> dict[str, str]:
    """{file: text} for src/<layout>/, or LayoutError/DataPortError."""
    tu = KEYBOARD / layout / f"{layout}.c"
    if not tu.is_file():
        raise LayoutError(f"no {tu.relative_to(REPO)}")
    src = tu.read_text(errors="replace")
    place = returned_table(src)
    if place is None:
        raise LayoutError("no `KbdLayerDescriptor(VOID) { return ...; }`")
    nls = returned_table(src, "KbdNlsLayerDescriptor")
    files = cdp.port(REPO, tu, CRATE, arches)
    for p in (place, nls):
        table = p.split(".")[0].split("[")[0] if p else None
        if table and not any(
            re.search(rf"\bstatic mut {re.escape(table)}:", t) for t in files.values()
        ):
            raise LayoutError(f"the C returns {table}, which c_data_port did not emit")
    files["mod.rs"] = files["mod.rs"].rstrip("\n") + "\n" + accessor(layout, place)
    if nls:
        files["mod.rs"] += accessor(layout, nls, "KbdNlsLayerDescriptor", "PKBDNLSTABLES")
    return files


def write_layout(layout: str, files: dict[str, str]) -> int:
    """Write src/<layout>/ the way `stage_data` does: changed files only, and prune what the
    generator wrote before and no longer writes. Returns the number of files touched."""
    out = CRATE / layout
    out.mkdir(parents=True, exist_ok=True)
    touched = 0
    for old in out.glob("*.rs"):
        if old.name not in files and MARK in old.read_text():
            old.unlink()
            touched += 1
    for name, text in files.items():
        path = out / name
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            touched += 1
    return touched


_SPEC_LINE = re.compile(
    r"^@ stdcall (KbdLayerDescriptor|KbdNlsLayerDescriptor)\(\)(?:[ \t]+\S+)?[ \t]*$", re.M
)


def wire_spec(layout: str, files: dict[str, str]) -> bool:
    """Point the layout's .spec exports at the accessors this generator wrote.

    Every layout shares one staticlib, so each accessor is `<layout>_<Name>` and the .spec
    maps the real export name onto it. Upstream's .spec says plain `KbdLayerDescriptor()`;
    left that way, the DLL's link fails (`KbdLayerDescriptor: undefined`), as five new
    layouts did on the 2026-10-11 sync. An export the C does not define is an error, never
    a dropped line."""
    spec = KEYBOARD / layout / f"{layout}.spec"
    text = spec.read_text()
    mod = files["mod.rs"]

    def point(m: re.Match[str]) -> str:
        name = m.group(1)
        if f'#[export_name = "{layout}_{name}"]' not in mod:
            raise LayoutError(f"{spec.name} exports {name}, which {layout}.c does not define")
        return f"@ stdcall {name}() {layout}_{name}"

    new = _SPEC_LINE.sub(point, text)
    if new != text:
        spec.write_text(new)
    return new != text


def wire_lib(names: list[str]) -> bool:
    """The `pub mod <layout>;` list between the markers in lib.rs (which carries them)."""
    lib = CRATE / "lib.rs"
    text = lib.read_text()
    if BEGIN not in text or f"{END}\n" not in text:
        raise LayoutError(f"{lib}: the generated-layouts markers are missing")
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(f"{END}\n", 1)[1]
    new = f"{head}{BEGIN}\n" + "".join(f"pub mod {n};\n" for n in names) + f"{END}\n{tail}"
    if new != text:
        lib.write_text(new)
    return new != text


def wire_bins(names: list[str], cell: Path | None = None) -> bool:
    """The family cell's [[bin]] list: one per layout, in the CMake list's order.

    `add_cargo_module(... BINS)` refuses to configure when it differs from
    `_keyboard_layouts`, and this generator needs a configured tree (its compile commands)
    to port a new layout. So the bins are written FIRST, from the list alone: an upstream
    sync's new layout (kbd103, 2026-10-15) then configures, and the port runs after."""
    cell = cell or CELL
    text = cell.read_text()
    i = text.find("[[bin]]")
    if i < 0:
        raise LayoutError(f"{cell}: no [[bin]] section")
    bins = "\n".join(f'[[bin]]\nname = "{n}"\npath = "src/main.rs"\n' for n in names)
    new = text[:i] + bins
    if new != text:
        cell.write_text(new)
    return new != text


def _one(n: str, arches: tuple[str, ...]) -> tuple[str, dict[str, str] | None, str]:
    # No target compiles a layout's .c since the cargo family cell; dll/keyboard's
    # kbdlayouts_flags stub carries the directory's compile flags (in the worker: the
    # registry is per process).
    ma.register_flags_dir(KEYBOARD / n, KEYBOARD)
    try:
        return n, generate(n, arches), ""
    except (LayoutError, cdp.DataPortError) as e:
        return n, None, str(e)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--only", help="comma-separated layouts (default: all of _keyboard_layouts)")
    p.add_argument("--jobs", type=int, default=8)
    p.add_argument("--arches", default=",".join(cdp.ARCHES))
    a = p.parse_args(argv)
    arches = tuple(a.arches.split(","))
    every = layouts()
    todo = a.only.split(",") if a.only else every
    unknown = [n for n in todo if n not in every]
    if unknown:
        print(f"kbd_layouts: not in _keyboard_layouts: {unknown}")
        return 2
    wire_bins(every)

    with ProcessPoolExecutor(max_workers=a.jobs) as ex:
        results = list(ex.map(_one, todo, [arches] * len(todo)))
    failed = [(n, why) for n, f, why in results if f is None]
    for n, f, _ in results:
        if f is not None:
            try:
                wire_spec(n, f)
            except LayoutError as e:
                failed.append((n, str(e)))
                continue
            write_layout(n, f)
    done = [n for n, f, _ in results if f is not None and n not in dict(failed)]
    # lib.rs lists every layout that has a generated module on disk (an --only run must not
    # drop the others).
    present = [n for n in every if (CRATE / n / "mod.rs").is_file()]
    wire_lib(present)
    print(f"kbd_layouts: {len(done)} generated, {len(failed)} failed, {len(present)} modules")
    for n, why in failed:
        print(f"  FAILED {n}: {why.splitlines()[0] if why else '?'}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
