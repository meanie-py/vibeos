# ── Spec Parser ──────────────────────────────────────────────────────


def parse_spec(spec_path: Path) -> dict[str, dict]:
    """Parse ntoskrnl.spec → {name: {conv, param_count}} mapping."""
    catalog = {}
    spec_re = re.compile(
        r"^@\s+(stdcall|cdecl|fastcall)\s+"
        r"(?:-arch=[^\s]+\s+)?"
        r"(\w+)\s*\(([^)]*)\)"
    )
    if not spec_path.exists():
        return catalog
    for line in spec_path.read_text().splitlines():
        m = spec_re.match(line.strip())
        if m:
            conv, name, params = m.group(1), m.group(2), m.group(3).strip()
            param_count = len(params.split()) if params else 0
            catalog[name] = {"conv": conv, "params": param_count}
    return catalog


# ── Bindgen Parser ───────────────────────────────────────────────────


def parse_bindgen(bindgen_path: Path) -> dict[str, dict]:
    """Parse bindgen_i386.rs → {name: {conv, param_count, return_type}} mapping.

    Declarations are buffered from `pub fn` to `;` and params counted by splitting
    on top-level commas (the old per-line counter miscounted every declaration whose
    param list and return type were split across lines).
    """
    catalog = {}
    if not bindgen_path.exists():
        return catalog

    extern_re = re.compile(r'^\s*(?:pub\s+)?unsafe\s+extern\s+"(\w+)"')
    fn_start_re = re.compile(r"^\s*pub\s+fn\s+(\w+)\s*\(")

    def count_params(decl: str) -> int:
        decl = decl.replace("->", "\u2192")
        try:
            open_i = decl.index("(")
        except ValueError:
            return 0
        depth, close_i = 0, -1
        for i in range(open_i, len(decl)):
            if decl[i] in "([<":
                depth += 1
            elif decl[i] in ")]>":
                depth -= 1
                if depth == 0:
                    close_i = i
                    break
        if close_i < 0:
            return 0
        inner = decl[open_i + 1 : close_i]
        parts, depth, cur = [], 0, []
        for ch in inner:
            if ch in "([<":
                depth += 1
            elif ch in ")]>":
                depth -= 1
            if ch == "," and depth == 0:
                parts.append("".join(cur))
                cur = []
            else:
                cur.append(ch)
        parts.append("".join(cur))
        return len([q for q in parts if ":" in q])  # `...` varargs not counted (spec omits them)

    current_conv = None
    fn_name = None
    fn_buf = None

    for line in bindgen_path.read_text().splitlines():
        if fn_buf is None:
            m = extern_re.match(line)
            if m:
                current_conv = m.group(1)
                continue
            if line.strip() == "}":
                current_conv = None
                continue
            m = fn_start_re.match(line)
            if m and current_conv:
                fn_name = m.group(1)
                fn_buf = line.strip()
        else:
            fn_buf += " " + line.strip()

        if fn_buf is not None and fn_buf.rstrip().endswith(";"):
            ret_match = re.search(r"->\s*(\S+)\s*;\s*$", fn_buf)
            catalog[fn_name] = {
                "conv": current_conv,
                "params": count_params(fn_buf),
                "ret": ret_match.group(1) if ret_match else "void",
            }
            fn_buf = None

    return catalog


# ── Rust File Scanner ────────────────────────────────────────────────


# `\s*` between the attribute and `pub`, NOT `[^\n]*\n`: the shim files put the whole
# thing on one line (`#[no_mangle] pub unsafe extern "C" fn InterlockedIncrement(..)`),
# and requiring a newline missed every one of them — which is 4 of the 5 cases this
# function exists to suppress.
_LOCAL_DEF_RE = re.compile(
    r"#\[no_mangle\]\s*(?:#\[[^\]]*\]\s*)*pub\s+(?:unsafe\s+)?"
    r'(?:extern\s+"[A-Za-z-]+"\s+)?fn\s+(\w+)\s*[(<]'
)


def crate_local_definitions(crate_dir: Path, _cache={}) -> frozenset:  # noqa: B006 — memo cache
    """Names this crate DEFINES with #[no_mangle], i.e. the ones the linker resolves
    in-crate rather than to the kernel export.

    Without this, the spec is applied as the authority to call sites it does not govern.
    All 6 of the [ABI] findings in the 2026-07-25 baseline were this: cdrom ships its own
    `InterlockedCompareExchange`/`InterlockedIncrement` (real AtomicI32 SeqCst bodies, not
    stubs) though ntoskrnl.spec exports them `fastcall -arch=i386,arm`; classpnp defines
    `IoWMIDeviceObjectToProviderId` and disk defines `KeFlushIoBuffers`, whose spec entries
    do not even cover i386. In each case the local `extern "C"` decl correctly matches the
    local shim, and "should be stdcall per ntoskrnl.spec" is advice that would BREAK the
    link (an i386 `extern "system"` decl decorates the name `_Foo@N`, which the undecorated
    shim does not export). Whether the shim ought to exist at all is a separate question and
    a different report.
    """
    key = str(crate_dir)
    if key in _cache:
        return _cache[key]
    names = set()
    src = crate_dir / "src"
    if src.is_dir():
        for f in source_files(src):
            try:
                names.update(_LOCAL_DEF_RE.findall(f.read_text(encoding="utf-8", errors="replace")))
            except OSError:
                continue
    _cache[key] = frozenset(names)
    return _cache[key]


def crate_dir_of(rs_path: Path) -> Path | None:
    """Nearest ancestor holding a Cargo.toml."""
    for parent in rs_path.resolve().parents:
        if (parent / "Cargo.toml").is_file():
            return parent
    return None


def scan_extern_blocks(rs_path: Path, spec: dict, bindgen: dict) -> list[dict]:
    """Scan for ABI, param count, and C macro issues in extern blocks.

    Parser notes (each fixed a real false-positive class, 2026-07-05):
    - fn declarations are BUFFERED from `fn` to `;` and params counted by splitting
      on top-level commas — continuation lines holding several params used to count
      as one, flagging every wrapped multi-param decl as an arity mismatch.
    - a #[cfg] that excludes i386 (not(target_arch = "x86")) suppresses ABI findings:
      stdcall/fastcall are i386-isms; on amd64/arm64 extern "C" is the same ABI.
    - spec param counts are i386 STACK SLOTS (LONGLONG/ULONGLONG/double = 2), so a
      spec-based arity check only flags rust_params > spec_slots (a definite bug);
      bindgen counts real args and is compared exactly.
    - a name the crate DEFINES with #[no_mangle] links in-crate, so ntoskrnl.spec is not
      the authority for its call sites (2026-07-25: that was all 6 [ABI] findings).
    """
    crate = crate_dir_of(rs_path)
    local_defs = crate_local_definitions(crate) if crate else frozenset()
    return extern_facts(str(rs_path), rs_path.read_text(), spec, bindgen, sorted(local_defs))


@source_facts()
def extern_facts(path: str, text: str, spec: dict, bindgen: dict, local_defs) -> list[dict]:
    rs_path = Path(path)
    issues = []

    # kernel-rust/src/lib.rs is the symbol-force umbrella: zero-arg extern "C"
    # placeholder decls feeding `unsafe extern "C" fn()` arrays that pin symbols
    # into the link. Conventions there are Rust type-system plumbing, not ABI —
    # a "fix" breaks the arrays (E0308) without changing any call.
    if rs_path.as_posix().endswith("kernel-rust/src/lib.rs"):
        return issues

    lines = text.splitlines()

    # File-level arch gating: a file only compiled on non-x86 arches (by naming
    # convention: *_amd64.rs / *_arm64.rs, or an amd64/ / arm64/ path segment)
    # can't produce i386 ABI bugs — suppress ABI findings exactly like a
    # not(target_arch="x86") cfg block. i386-suffixed files stay fully checked.
    parts = set(rs_path.parts)
    stem = rs_path.stem
    file_skips_x86 = (
        stem.endswith("_amd64")
        or stem.endswith("_arm64")
        or "amd64" in parts
        or "arm64" in parts
        or "arm" in parts
    )

    extern_re = re.compile(r'^\s*(?:pub\s+)?(?:unsafe\s+)?extern\s+"(C|system|stdcall|cdecl)"\s*\{')
    rejoin_re = re.compile(
        r'^\}\s*(?:pub\s+)?(?:unsafe\s+)?extern\s+"(C|system|stdcall|cdecl)"\s*\{\s*$'
    )
    fn_re = re.compile(r"^\s*(?:pub\s+)?fn\s+(\w+)\s*\(")
    link_name_re = re.compile(r'#\[link_name\s*=\s*"(\w+)"\]')
    static_re = re.compile(r"^\s*(?:pub\s+)?(?:static\s+(?:mut\s+)?)\w+")
    cfg_re = re.compile(r"#\[cfg\((.*)\)\]")

    def cfg_excludes_x86(cfg_text: str) -> bool:
        t = cfg_text.replace(" ", "")
        if 'not(target_arch="x86")' in t:
            return True
        # cfg targeting only specific non-x86 arch(es)
        arches = re.findall(r'target_arch="(\w+)"', t)
        return bool(arches) and "x86" not in arches and "not(" not in t

    def count_params(decl: str) -> int:
        # decl is the full text from `fn` to `;`. Extract the top-level ( ... ).
        # Neutralize `->` first: its '>' is not a closing angle bracket (nested
        # fn-pointer types like Option<unsafe extern fn(..) -> PVOID> undercounted).
        decl = decl.replace("->", "\u2192")
        try:
            open_i = decl.index("(")
        except ValueError:
            return 0
        depth, close_i = 0, -1
        for i in range(open_i, len(decl)):
            if decl[i] in "([<":
                depth += 1
            elif decl[i] in ")]>":
                depth -= 1
                if depth == 0:
                    close_i = i
                    break
        if close_i < 0:
            return 0
        inner = decl[open_i + 1 : close_i]
        # split on top-level commas
        parts, depth, cur = [], 0, []
        for ch in inner:
            if ch in "([<":
                depth += 1
            elif ch in ")]>":
                depth -= 1
            if ch == "," and depth == 0:
                parts.append("".join(cur))
                cur = []
            else:
                cur.append(ch)
        parts.append("".join(cur))
        return len([q for q in parts if ":" in q])  # `...` varargs not counted (spec omits them)

    in_extern = False
    current_conv = None
    brace_depth = 0
    pending_link_name = None
    pending_cfg = None  # cfg attr immediately preceding the extern block
    block_skips_x86 = False
    fn_buf = None  # buffered decl text
    fn_line = 0

    for lineno, line in enumerate(lines, 1):
        # Strip line comments BEFORE any parsing: braces inside comments corrupt the
        # depth count (a stray '{' in a comment left the parser "inside" the previous
        # extern "C" block, misattributing conventions), and a trailing comment after
        # `;` broke decl-end detection.
        stripped = line.split("//")[0].strip()

        if not in_extern:
            cm = cfg_re.search(stripped)
            if cm:
                pending_cfg = cm.group(1)
                continue
            em = extern_re.match(stripped)
            if em:
                current_conv = em.group(1)
                # Net brace count on the header line itself: a one-line block
                # (`extern "C" { static X: T; }`) opens AND closes here — entering
                # block state with depth=1 used to leave the parser "inside" that
                # block for the rest of the file, misattributing every later
                # block's convention.
                brace_depth = stripped.count("{") - stripped.count("}")
                in_extern = brace_depth > 0
                block_skips_x86 = file_skips_x86 or (
                    bool(pending_cfg) and cfg_excludes_x86(pending_cfg)
                )
                pending_cfg = None
                if not in_extern:
                    # scan any inline fn decl in the one-liner
                    inner = stripped[stripped.index("{") + 1 : stripped.rindex("}")]
                    fm = fn_re.match(inner.strip())
                    if fm and inner.rstrip().rstrip("}").rstrip().endswith(";"):
                        _check_fn(
                            issues,
                            rs_path,
                            lineno,
                            fm.group(1),
                            fm.group(1),
                            current_conv,
                            count_params(inner),
                            spec,
                            bindgen,
                            skip_abi=block_skips_x86,
                            local_defs=local_defs,
                        )
                    current_conv = None
                continue
            if stripped and not stripped.startswith("//") and not stripped.startswith("#["):
                pending_cfg = None
            continue

        # `} extern "system" {` closes one block and opens the next on one line. Its braces
        # net to zero, so without this the parser stayed "inside" the first block and gave
        # every later decl the FIRST block's convention (fastfat verfysup.rs, 2026-10-10:
        # correct only because the stale convention happened to match).
        jm = rejoin_re.match(stripped) if brace_depth == 1 else None
        if jm:
            current_conv = jm.group(1)
            pending_link_name = None
            fn_buf = None
            continue

        brace_depth += stripped.count("{") - stripped.count("}")
        if brace_depth <= 0:
            in_extern = False
            current_conv = None
            pending_link_name = None
            fn_buf = None
            continue

        lm = link_name_re.search(stripped)
        if lm:
            pending_link_name = lm.group(1)
            continue

        if fn_buf is None:
            if static_re.match(stripped):
                pending_link_name = None
                continue
            fm = fn_re.match(stripped)
            if not fm:
                if stripped and not stripped.startswith("//") and not stripped.startswith("#["):
                    pending_link_name = None
                continue
            fn_rust_name = fm.group(1)
            fn_name = pending_link_name or fn_rust_name
            fn_line = lineno
            pending_link_name = None
            fn_buf = stripped

            if fn_name in C_MACROS and fn_name not in C_MACRO_EXCEPTIONS:
                issues.append(
                    {
                        "file": str(rs_path),
                        "line": lineno,
                        "type": "C_MACRO",
                        "fn_name": fn_rust_name,
                        "detail": f"{fn_name} is a C macro, not a real function "
                        "— should be inlined in Rust",
                    }
                )
        else:
            fn_buf += " " + stripped

        if fn_buf is not None and fn_buf.rstrip().endswith(";"):
            # slot-style decl (every param `_: usize`, e.g. the ke/ssdt.rs syscall
            # table) encodes i386 stack slots by design — skip the arity check by
            # reporting param_count 0 (0 is never compared).
            slot_style = re.search(r"\(\s*_\s*:\s*usize", fn_buf) is not None
            _check_fn(
                issues,
                rs_path,
                fn_line,
                fn_name,
                fn_rust_name,
                current_conv,
                0 if slot_style else count_params(fn_buf),
                spec,
                bindgen,
                skip_abi=block_skips_x86,
                local_defs=local_defs,
            )
            fn_buf = None

    return issues


def _check_fn(
    issues,
    rs_path,
    lineno,
    fn_name,
    rust_name,
    conv,
    param_count,
    spec,
    bindgen,
    skip_abi=False,
    local_defs=frozenset(),
):
    """
        crate = crate_dir_of(rs_path)
        local_defs = crate_local_definitions(crate) if crate else frozenset()
    Check a single extern fn declaration against spec/bindgen."""
    # Skip allowlisted
    if fn_name in CDECL_ALLOWLIST:
        return
    if any(fn_name.endswith(s) for s in SHIM_SUFFIXES):
        return

    # ABI check (suppressed for decls cfg-gated off i386 — stdcall/fastcall
    # are i386-isms; extern "C" is the same ABI on amd64/arm64)
    # A name this crate DEFINES with #[no_mangle] links in-crate; the spec describes an
    # export the linker will never reach for it, so it is not the authority here.
    if conv == "C" and not skip_abi and fn_name not in local_defs:
        expected_conv = None
        source = None
        if fn_name in spec and spec[fn_name]["conv"] in ("stdcall", "fastcall"):
            expected_conv = spec[fn_name]["conv"]
            source = "ntoskrnl.spec"
        elif fn_name in bindgen and bindgen[fn_name]["conv"] in ("stdcall", "system"):
            expected_conv = bindgen[fn_name]["conv"]
            source = "bindgen_i386.rs"
        if expected_conv:
            issues.append(
                {
                    "file": str(rs_path),
                    "line": lineno,
                    "type": "ABI",
                    "fn_name": rust_name,
                    "detail": f'declared extern "C" (cdecl), '
                    f"should be {expected_conv} (per {source})",
                }
            )

    # Parameter count check — skipped for C-macro names: a crate-local shim decl
    # for a macro is not comparable to bindgen's inline-fn signature (the C_MACRO
    # finding already covers these).
    if fn_name in C_MACROS:
        return
    ref = None
    ref_source = None
    if fn_name in spec:
        ref = spec[fn_name]
        ref_source = "ntoskrnl.spec"
    if fn_name in bindgen:
        ref = bindgen[fn_name]
        ref_source = "bindgen_i386.rs"

    if ref and ref["params"] > 0 and param_count > 0:
        if ref_source == "ntoskrnl.spec":
            # spec counts i386 stack slots (8-byte args take 2) — rust arg count can
            # only be <= slots, so only rust > slots is a definite arity bug
            mismatch = param_count > ref["params"]
        else:
            mismatch = param_count != ref["params"]
        if mismatch:
            issues.append(
                {
                    "file": str(rs_path),
                    "line": lineno,
                    "type": "PARAM_COUNT",
                    "fn_name": rust_name,
                    "detail": (
                        f"Rust declares {param_count} params, {ref_source} has {ref['params']}"
                    ),
                }
            )


# ── Flexible Array Scanner ───────────────────────────────────────────


def scan_flexible_arrays(rs_path: Path) -> list[dict]:
    """Scan for direct indexing of known flexible array fields."""
    return flexible_facts(str(rs_path), rs_path.read_text())


@source_facts()
def flexible_facts(path: str, text: str) -> list[dict]:
    rs_path = Path(path)
    issues = []
    lines = text.splitlines()

    for lineno, line in enumerate(lines, 1):
        for struct_name, field_name in FLEXIBLE_ARRAYS.items():
            if field_name is None:
                continue
            # Match patterns like .Objects[i] or .Objects[i as usize]
            pattern = rf"\.{field_name}\s*\["
            if re.search(pattern, line):
                # Skip if it's .Objects[0] (that's safe), however the zero is spelled
                if re.search(rf"\.{field_name}\s*\[\s*0\s*(?:as\s+usize\s*|usize\s*)?\]", line):
                    continue
                # An element of an ARRAY of structs (`ViaUdmaTimings[k].Data[i]`) is fixed-size:
                # a variable-length struct is never stored past element 0 of an array.
                if re.search(
                    rf"\[(?!\s*0\s*(?:as\s+usize\s*)?\])[^\[\]]+\]\s*\.{field_name}\s*\[", line
                ):
                    continue
                # Skip a same-named FIXED array reached through its known parent field
                parents = FIXED_ARRAY_PARENTS.get(field_name, ())
                not_via_parent = "".join(f"(?<!{p})" for p in parents)
                if parents and not re.search(rf"{not_via_parent}\.{field_name}\s*\[", line):
                    continue
                # Skip if in a comment
                stripped = line.lstrip()
                if stripped.startswith("//") or stripped.startswith("*"):
                    continue
                issues.append(
                    {
                        "file": str(rs_path),
                        "line": lineno,
                        "type": "FLEX_ARRAY",
                        "fn_name": field_name,
                        "detail": f"Direct indexing of flexible array {struct_name}.{field_name} "
                        f"— use pointer arithmetic instead (bindgen declares as [T; 1])",
                    }
                )

    return issues


# ── Main ─────────────────────────────────────────────────────────────


def main():
    parser = argparse.ArgumentParser(
        description="Comprehensive FFI verification for Rust kernel code"
    )
    parser.add_argument("files", nargs="*", help="Rust files to check (default: all)")
    args = parser.parse_args()

    reactos_root = _RUSTCONV_REACTOS_ROOT

    spec = parse_spec(reactos_root / "ntoskrnl/ntoskrnl.spec")
    print(f"Spec catalog: {len(spec)} exports")

    bindgen = parse_bindgen(reactos_root / "sdk/lib/rust/ntkrnl-sys/src/bindgen_i386.rs")
    print(f"Bindgen catalog: {len(bindgen)} functions")

    if args.files:
        rs_files = [Path(f) for f in args.files]
    else:
        # Scan every workspace crate's src/, not just ntoskrnl-rust: kernel-side crates
        # (win32k-rust, hal-rust, driver crates, ...) import the same NTAPI symbols and
        # carry the same extern "C"-vs-"system" hazard. The spec/bindgen maps are keyed
        # by function name, so unknown (crate-internal) externs are simply skipped.
        # Generated/assertion files are excluded — they aren't hand-written decls.
        rust_root = reactos_root / "sdk/lib/rust"
        rs_files = sorted(
            f
            for src_dir in rust_root.glob("*/src")
            for f in source_files(src_dir)
            if not (
                f.name.startswith("bindgen_")
                or f.name.startswith("size_check_")
                or f.name.startswith("offset_check_")
                # A crate's own island (`types_<arch>.rs`) is bindgen output by another name.
                or _bindgen_generated(f)
            )
        )

    counts = {"ABI": 0, "PARAM_COUNT": 0, "C_MACRO": 0, "FLEX_ARRAY": 0}
    for rs_file in rs_files:
        issues = scan_extern_blocks(rs_file, spec, bindgen)
        issues += scan_flexible_arrays(rs_file)
        for issue in issues:
            tag = issue["type"]
            counts[tag] += 1
            print(
                f"  [{tag}] {issue['file']}:{issue['line']}: {issue['fn_name']}: {issue['detail']}"
            )

    print("\nSummary:")
    for tag, count in counts.items():
        if count > 0:
            print(f"  {tag}: {count}")
    total = sum(counts.values())
    print(f"  TOTAL: {total} issues across {len(rs_files)} files")
    return 1 if total > 0 else 0


if __name__ == "__main__":
    sys.exit(main())
