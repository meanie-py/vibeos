#!/usr/bin/env python3
"""Point an island's `extern` declaration of a crate-defined global at the definition.

    python3 tools/rustconv/drop_crate_globals.py <island.rs>... <crate src dir>

gen_driver_types.sh runs this on each island it writes under BLOCKLIST_FUNCS_FROM_CRATE: the
island must declare what the module IMPORTS but not what it DEFINES. A translated C++ module
defines its globals in Rust (mspaint's `#[no_mangle] pub static mut g_hinstExe` in
main_cpp_h.rs), and bindgen re-declares each one from the header as an `extern` static. The
other modules then reach their own crate's variable through the linker -- and the extern's
type also reaches cppapp's Rust-ABI vtables (`__delete: unsafe fn(*mut T)`), so each such
global is an `improper_ctypes` warning (all 48 in the tree on 2026-10-17).

The extern block becomes `pub use crate::<module>::NAME;`, so every glob importer of the
island sees the definition itself. A global that is not `pub`, or is defined twice, keeps
its declaration (listed); one the module IMPORTS (`ATL::_pobjMapEntryFirst`) is untouched.

Run it directly on a committed island to apply this one step without a full regeneration.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from extern_to_use import module_files

# A top-level static, at column 0: one inside a fn or an inline `mod` is not this module's.
STATIC_DEF = re.compile(r"^(pub(?:\([^)]*\))?\s+)?static\s+(?:mut\s+)?(\w+)\s*:", re.M)
# bindgen's shape: one `unsafe extern "C"` block per global, attributes (`#[link_name]`) and all.
EXTERN_GLOBAL = re.compile(
    r'^unsafe extern "C" \{\n(?:[ \t]*#\[[^\n]*\]\n)*[ \t]*pub static (?:mut )?(\w+):[^\n]*;\n\}\n',
    re.M,
)


def crate_globals(crate_src: Path) -> dict[str, list[tuple[str, bool]]]:
    """{name: [(module path, is pub)]} for every top-level static in hand-written modules."""
    out: dict[str, list[tuple[str, bool]]] = {}
    for key, text in module_files(crate_src).items():
        # An island's own `extern` statics are not definitions. A cppapp-generated module
        # (mspaint's cpp_classes.rs) is: that is where `toolsModel` lives.
        if "automatically generated by rust-bindgen" in text[:400]:
            continue
        for m in STATIC_DEF.finditer(text):
            out.setdefault(m.group(2), []).append((key, (m.group(1) or "").strip() == "pub"))
    return out


def rewrite(island: str, own: dict[str, list[tuple[str, bool]]]) -> tuple[str, int, list[str]]:
    n = 0
    kept: list[str] = []

    def sub(m: re.Match[str]) -> str:
        nonlocal n
        defs = own.get(m.group(1))
        if not defs:
            return m.group(0)
        if len(defs) != 1 or not defs[0][1]:
            kept.append(f"{m.group(1)}: {defs}")
            return m.group(0)
        n += 1
        path = f"crate::{defs[0][0]}::" if defs[0][0] else "crate::"
        return f"pub use {path}{m.group(1)};\n"

    return EXTERN_GLOBAL.sub(sub, island), n, kept


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    *islands, crate_src = (Path(a) for a in argv)
    own = crate_globals(crate_src)
    for p in islands:
        text, n, kept = rewrite(p.read_text(), own)
        p.write_text(text)
        print(f"  ({p.name}: {n} crate-defined global(s) now `pub use` the definition)")
        for k in sorted(set(kept)):
            print(f"  KEPT extern (not pub, or defined twice): {k}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
