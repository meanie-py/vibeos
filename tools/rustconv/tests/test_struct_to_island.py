"""struct_to_island: a hand copy of an island struct becomes a re-export, and only when that
is a rename (or the header's packing, which the copy dropped)."""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import struct_to_island as s2i

ISLAND = """/* automatically generated by rust-bindgen 0.72.1 */
#[repr(C)]
#[derive(Debug, Copy, Clone)]
pub struct tagMENUITEMINFOW {
    pub cbSize: UINT,
    pub hSubMenu: HMENU,
}
pub type MENUITEMINFOW = tagMENUITEMINFOW;
#[repr(C{packed})]
pub struct _SHQUERYRBINFO {
    pub cbSize: DWORD,
    pub i64Size: ::core::ffi::c_longlong,
}
pub type SHQUERYRBINFO = _SHQUERYRBINFO;
#[repr(C)]
pub struct _STRRET {
    pub uType: UINT,
    pub __bindgen_anon_1: _STRRET__bindgen_ty_1,
}
pub type STRRET = _STRRET;
#[repr(C)]
pub struct _SHELLDETAILS {
    pub fmt: ::core::ffi::c_int,
    pub str_: STRRET,
}
pub type SHELLDETAILS = _SHELLDETAILS;
#[repr(C)]
pub struct _REGFOLDERINFO {
    pub Count: UINT,
}
pub type REGFOLDERINFO = _REGFOLDERINFO;
"""

HAND = """use crate::types::*;

#[repr(C)]
#[derive(Copy, Clone)]
pub struct MENUITEMINFOW {
    pub cbSize: UINT,
    pub hSubMenu: HMENU,
}

#[repr(C)]
pub struct SHQUERYRBINFO {
    pub cbSize: DWORD,
    pub i64Size: i64,
}

#[repr(C)]
pub struct STRRET {
    pub uType: UINT,
    pub u: STRRET_u,
}

#[repr(C)]
pub struct SHELLDETAILS {
    pub fmt: i32,
    pub str_: STRRET,
}

#[repr(C)]
pub struct REGFOLDERINFO {
    pub Count: UINT,
}
unsafe impl Sync for REGFOLDERINFO {}
"""


def _crate(tmp: Path) -> Path:
    src = tmp / "src"
    src.mkdir()
    (src / "lib.rs").write_text("pub mod island;\npub mod hand;\n")
    (src / "island.rs").write_text(
        "// Generated by tools/rustconv/gen_driver_types.sh. Do not edit by hand.\n"
    )
    for arch in s2i.ARCHES:
        packed = ", packed" if arch == "i386" else ""
        (src / f"island_{arch}.rs").write_text(ISLAND.replace("{packed}", packed))
    (src / "hand.rs").write_text(HAND)
    return src


def test_rename_and_packing_correction_swap_the_rest_stay(tmp_path):
    changed, done, kept = s2i.plan(_crate(tmp_path), "island", None)
    text = changed["hand"]
    assert "pub use crate::island::MENUITEMINFOW;" in text
    # shellapi.h is pshpack1 on 32-bit only: the unpacked copy was 4 bytes too big on i386.
    assert "pub use crate::island::SHQUERYRBINFO;" in text
    assert any("SHQUERYRBINFO" in d and "i386:C,packed" in d for d in done)
    # Field names differ (bindgen's anonymous union): kept. SHELLDETAILS embeds that kept
    # copy, so swapping it would change what `.str_` is: kept by the fixpoint.
    assert "pub struct STRRET" in text and "pub struct SHELLDETAILS" in text
    assert any("SHELLDETAILS" in k and "keeps its own copy" in k for k in kept)
    # The crate implements Sync for its copy; a second module doing the same on the shared
    # island type would collide.
    assert "pub struct REGFOLDERINFO" in text
    assert any("REGFOLDERINFO" in k and "implements" in k for k in kept)
