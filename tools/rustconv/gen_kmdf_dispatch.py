#!/usr/bin/env python3
"""gen_kmdf_dispatch.py — generate kmdf-sys/src/dispatch.rs.

The KMDF client side: every `Wdf*` API in <wdf.h> is a FORCEINLINE function whose
body dispatches through a load-time-bound table:

    FORCEINLINE NTSTATUS WdfDeviceCreate(...) {
        return ((PFN_WDFDEVICECREATE) WdfFunctions[WdfDeviceCreateTableIndex])
               (WdfDriverGlobals, ...);
    }

This emits one `#[inline] pub unsafe fn WdfXxx(..)` per API — a 1:1 Rust
translation of that body. Signatures come from the bindgen-emitted `PFN_WDFXXX`
typedefs (clang-validated, correct per-arch calling convention), so this is NOT a
hand-rolled-ABI gamble. Indices come from the bindgen `_WDFFUNCENUM_*TableIndex`
constants. `WdfFunctions_01017` (version-stamped per the <wdf.h> macro) and
`WdfDriverGlobals` are defined by the C wdfdriverentry stub and filled by
WdfVersionBind at load.

Source of truth = kmdf-sys/src/types_amd64.rs (type-alias NAMES are identical
across arches; only the fn-ptr calling convention differs, and that lives inside
the per-arch PFN typedef, not in the wrappers — so one dispatch.rs serves x3).

Run from anywhere:  python3 tools/rustconv/gen_kmdf_dispatch.py
"""
import re
import sys
import pathlib

HERE = pathlib.Path(__file__).resolve()
SRC_ROOT = HERE.parents[2]  # tools/rustconv/.. -> repo root
KMDF = SRC_ROOT / "sdk/lib/rust/kmdf-sys/src"
TYPES = KMDF / "types_amd64.rs"
OUT = KMDF / "dispatch.rs"


def split_top_level(s: str):
    """Split on top-level commas, honoring (), [], <> nesting."""
    parts, depth, cur = [], 0, []
    for ch in s:
        if ch in "([<":
            depth += 1
        elif ch in ")]>":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    tail = "".join(cur).strip()
    if tail:
        parts.append(tail)
    return parts


def match_paren(s: str, open_idx: int):
    """Given index of '(', return index of the matching ')'."""
    depth = 0
    for i in range(open_idx, len(s)):
        if s[i] == "(":
            depth += 1
        elif s[i] == ")":
            depth -= 1
            if depth == 0:
                return i
    raise ValueError("unbalanced paren")


def main():
    text = TYPES.read_text()

    # api-name -> table index. const looks like:
    #   pub const _WDFFUNCENUM_WdfDeviceCreateTableIndex: _WDFFUNCENUM = 75;
    indices = {}
    for m in re.finditer(
        r"pub const _WDFFUNCENUM_(\w+?)TableIndex: _WDFFUNCENUM\s*=\s*(\d+);", text
    ):
        indices[m.group(1)] = int(m.group(2))

    # PFN typedef bodies. capture the inner of Option<...>:
    #   pub type PFN_X = ::core::option::Option< unsafe extern "CC" fn(...) -> R, >;
    pfn_body = {}
    for m in re.finditer(
        r"pub type (PFN_\w+)\s*=\s*::core::option::Option<\s*(.*?)\s*>;", text, re.S
    ):
        pfn_body[m.group(1)] = m.group(2)

    out = []
    skipped = []
    for api in sorted(indices, key=lambda a: indices[a]):
        pfn = "PFN_" + api.upper()
        body = pfn_body.get(pfn)
        if body is None:
            skipped.append((api, "no PFN typedef"))
            continue
        open_idx = body.find("fn(")
        if open_idx < 0:
            skipped.append((api, "no fn("))
            continue
        po = open_idx + 2  # the '('
        pc = match_paren(body, po)
        params_raw = body[po + 1 : pc]
        rest = body[pc + 1 :].strip().rstrip(",").strip()
        ret = ""
        if rest.startswith("->"):
            ret = rest[2:].strip()
        params = split_top_level(params_raw)
        # first param is always DriverGlobals: PWDF_DRIVER_GLOBALS — drop it.
        if params and params[0].split(":")[0].strip() in ("DriverGlobals", "Globals"):
            params = params[1:]
        names = []
        for p in params:
            if ":" not in p:
                skipped.append((api, f"unparsable param {p!r}"))
                names = None
                break
            names.append(p.split(":")[0].strip())
        if names is None:
            continue

        sig_params = ", ".join(params)
        fwd = ", ".join(["WdfDriverGlobals"] + names)
        ret_clause = f" -> {ret}" if ret else ""
        out.append(
            f"#[inline]\n"
            f"pub unsafe fn {api}({sig_params}){ret_clause} {{\n"
            f"    let __f: {pfn} = ::core::mem::transmute::<WDFFUNC, {pfn}>(\n"
            f"        *WdfFunctions_01017.add(_WDFFUNCENUM_{api}TableIndex as usize));\n"
            f"    (__f.unwrap_unchecked())({fwd})\n"
            f"}}\n"
        )

    header = (
        "// @generated by tools/rustconv/gen_kmdf_dispatch.py — do not edit by hand.\n"
        "// One inline wrapper per WDF API: a 1:1 translation of the <wdf.h> FORCEINLINE body\n"
        "//   ((PFN_WDFXXX) WdfFunctions[WdfXxxTableIndex])(WdfDriverGlobals, ...).\n"
        "// WdfFunctions_01017 / WdfDriverGlobals are defined by the C wdfdriverentry stub\n"
        "// (sdk/lib/drivers/wdfdriverentry) and populated at load by WdfVersionBind.\n"
        "#![allow(non_snake_case, non_camel_case_types, dead_code, unused_imports)]\n"
        "#![allow(clippy::all)]\n"
        "// WDF handle/value types + PFN typedefs + index consts + the binding externs:\n"
        "use crate::types::*;\n"
        "// kernel types in the signatures (NTSTATUS, ACCESS_MASK, PCUNICODE_STRING, ...):\n"
        "// blocklisted out of crate::types and resolved on the single ntkrnl-sys ddk identity.\n"
        "use ntkrnl_sys::ddk::*;\n\n"
    )
    OUT.write_text(header + "\n".join(out) + "\n")
    print(f"wrote {OUT}  ({len(out)} dispatchers, {len(skipped)} skipped)")
    if skipped:
        for api, why in skipped[:40]:
            print(f"  skip {api}: {why}", file=sys.stderr)


if __name__ == "__main__":
    main()
