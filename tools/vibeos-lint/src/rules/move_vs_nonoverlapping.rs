//! A C `RtlMoveMemory`/`memmove` translated as `copy_nonoverlapping`.
//!
//! `RtlMoveMemory` is the overlap-safe copy; `copy_nonoverlapping` is memcpy, and on
//! overlapping ranges it is UB whose forward copy can smear the source over itself.
//! classpnp's `ClassReadDriveCapacity` shifts an 8-byte READ_CAPACITY_DATA up one
//! ULONG inside its _EX with `RtlMoveMemory`; the Rust used `copy_nonoverlapping`,
//! found when arming debug-assertions turned on rustc's UB checks (2026-11-01).
//! A Rust function is flagged when its same-module C twin (or twins: every one must
//! agree) makes more overlap-safe moves than the Rust keeps -- `ptr::copy`,
//! `copy_within`, `RtlMoveMemory`, `memmove` -- while the Rust still has a
//! `copy_nonoverlapping`. A move whose ranges provably never overlap may stay a
//! `copy_nonoverlapping` with `// nolint: move-vs-nonoverlapping (why)` in the body.
use crate::{twins, Corpus, Rule};
use rayon::prelude::*;
use regex::Regex;
use std::sync::LazyLock;

pub struct MoveVsNonoverlapping;
impl Rule for MoveVsNonoverlapping {
    fn name(&self) -> &'static str {
        "scan_move_vs_nonoverlapping"
    }
    fn needs_c_twins(&self) -> bool {
        true
    }
    fn run(&self, c: &Corpus) -> Result<Vec<String>, String> {
        let index = c.c_twins();
        let files: Vec<_> = c
            .rust_files()
            .filter(|f| f.text.contains("copy_nonoverlapping"))
            .filter(|f| !SKIP.is_match(&f.path.to_string_lossy()))
            .filter(|f| !f.text.starts_with("/* automatically generated by rust-bindgen"))
            .collect();
        let mut out: Vec<String> = files
            .par_iter()
            .flat_map_iter(|f| {
                scan(&f.text, &f.path, index)
                    .into_iter()
                    .map(move |x| format!("{}:{x}", f.path.display()))
            })
            .collect();
        out.sort();
        Ok(out)
    }
}

static SKIP: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"(/target/|/\.responses/|bindgen_[a-z0-9_]+\.rs$|/island_[a-z0-9_]+\.rs$)").unwrap()
});
static NONOVERLAPPING: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\bcopy_nonoverlapping\s*(::\s*<[^>]*>\s*)?\(").unwrap());
// `copy(` (bare or `ptr::copy(`) / `.copy_to(` / `.copy_from(` are the overlap-safe pointer methods; the
// `_nonoverlapping` spellings are excluded by the word boundary before `(`.
static RUST_MOVE: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"(\bcopy|\.copy_to|\.copy_from|\bcopy_within|\bRtlMoveMemory|\bmemmove|\bwmemmove|\bMoveMemory)\s*(::\s*<[^>]*>\s*)?\(").unwrap()
});
static C_MOVE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\b(RtlMoveMemory|memmove|wmemmove|MoveMemory)\s*\(").unwrap());
static NOLINT: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\bnolint:[\w\s,-]*\bmove-vs-nonoverlapping\b").unwrap());

fn scan(text: &str, path: &std::path::Path, index: &twins::CIndex) -> Vec<String> {
    let blank = twins::blank_rust(text);
    let newlines: Vec<_> = blank.match_indices('\n').map(|(at, _)| at).collect();
    let mut out = Vec::new();
    for fun in twins::rust_functions(&blank, path) {
        let Some(first) = NONOVERLAPPING.find(&fun.body) else {
            continue;
        };
        let raw_body = &text[fun.body_start..fun.body_start + fun.body.len()];
        if NOLINT.is_match(raw_body) {
            continue;
        }
        let twins: Vec<_> = index
            .get(&fun.name)
            .iter()
            .filter(|t| twins::same_module(path, t))
            .collect();
        let Some(c_moves) = twins.iter().map(|t| C_MOVE.find_iter(&t.body).count()).min() else {
            continue;
        };
        let rust_moves = RUST_MOVE.find_iter(&fun.body).count();
        if c_moves <= rust_moves {
            continue;
        }
        let at = fun.body_start + first.start();
        let line = newlines.partition_point(|&nl| nl < at) + 1;
        out.push(format!(
            "{line}: move-vs-nonoverlapping {}: C makes {c_moves} overlap-safe move(s), Rust keeps {rust_moves} and uses copy_nonoverlapping",
            fun.name
        ));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::SourceFile;
    use std::path::PathBuf;

    fn run(c_path: &str, c_text: &str, rust: &str) -> Vec<String> {
        let c = Corpus::new(
            PathBuf::from("."),
            vec![
                SourceFile::new(c_path.into(), c_text.into()),
                SourceFile::new("sdk/lib/rust/classpnp-rust/src/class.rs".into(), rust.into()),
            ],
        );
        MoveVsNonoverlapping.run(&c).unwrap()
    }

    const C: &str = "NTSTATUS ClassReadDriveCapacity(PVOID Fdo)\n{\n    RtlMoveMemory((PUCHAR)&d + 4, &d, 8);\n    return 0;\n}\n";

    #[test]
    fn rtlmovememory_lowered_to_memcpy_is_flagged() {
        let got = run(
            "drivers/storage/class/classpnp/class.c",
            C,
            "pub unsafe fn ClassReadDriveCapacity(Fdo: PVOID) -> NTSTATUS {\n    core::ptr::copy_nonoverlapping(a, b, 8);\n    0\n}\n",
        );
        assert_eq!(got.len(), 1, "{got:?}");
        assert!(got[0].starts_with("sdk/lib/rust/classpnp-rust/src/class.rs:2: move-vs-nonoverlapping ClassReadDriveCapacity"), "{got:?}");
    }

    #[test]
    fn kept_moves_and_suppressions_pass() {
        let kept = "pub unsafe fn ClassReadDriveCapacity(Fdo: PVOID) -> NTSTATUS {\n    core::ptr::copy(a, b, 8);\n    core::ptr::copy_nonoverlapping(x, y, 4);\n    0\n}\n";
        assert!(run("drivers/storage/class/classpnp/class.c", C, kept).is_empty());
        let nolint = "pub unsafe fn ClassReadDriveCapacity(Fdo: PVOID) -> NTSTATUS {\n    // nolint: move-vs-nonoverlapping (disjoint buffers)\n    core::ptr::copy_nonoverlapping(a, b, 8);\n    0\n}\n";
        assert!(run("drivers/storage/class/classpnp/class.c", C, nolint).is_empty());
    }

    #[test]
    fn twin_from_another_module_is_ignored() {
        let rust = "pub unsafe fn ClassReadDriveCapacity(Fdo: PVOID) -> NTSTATUS {\n    core::ptr::copy_nonoverlapping(a, b, 8);\n    0\n}\n";
        assert!(run("dll/win32/shell32/other.c", C, rust).is_empty());
    }
}
