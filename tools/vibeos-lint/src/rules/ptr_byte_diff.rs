static PREFILTER: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r" as (?:usize|isize|u64|i64|u32|i32|ULONG_PTR|LONG_PTR|UINT_PTR|INT_PTR|DWORD_PTR|SIZE_T|SSIZE_T|ULONG|LONG|DWORD|UINT)\s*\)?\s*(?:-|\.wrapping_sub\(|\.checked_sub\()").unwrap()
});
static SUB: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"([A-Za-z_][A-Za-z0-9_]*(?:\.(?:as_ptr|as_mut_ptr)\(\))?)\s+as\s+(?:usize|isize|u64|i64|u32|i32|ULONG_PTR|LONG_PTR|UINT_PTR|INT_PTR|DWORD_PTR|SIZE_T|SSIZE_T|ULONG|LONG|DWORD|UINT)\s*\)?\s*(?:-|\.wrapping_sub\(|\.checked_sub\()\s*(\()?\s*([A-Za-z_][A-Za-z0-9_]*(?:\.(?:as_ptr|as_mut_ptr)\(\))?)\s+as\s+(?:usize|isize|u64|i64|u32|i32|ULONG_PTR|LONG_PTR|UINT_PTR|INT_PTR|DWORD_PTR|SIZE_T|SSIZE_T|ULONG|LONG|DWORD|UINT)\b(\s*\))?").unwrap()
});
static AFTER: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"^\s*(?:as\s+[\w:]+\s*)?(?:\)\s*(?:as\s+[\w:]+\s*)?)*(\/|>>|\*)")
        .unwrap()
});
static CCAST: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"\(\s*(?:const\s+)?[A-Za-z_][\w\s]*\**\s*\)\s*\(?\s*([A-Za-z_]\w*)\s*\)?\s*-\s*\(\s*(?:const\s+)?[A-Za-z_][\w\s]*\**\s*\)\s*\(?\s*([A-Za-z_]\w*)\b").unwrap()
});
static CPLAIN: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"([A-Za-z_]\w*)\s*-\s*([A-Za-z_]\w*)").unwrap());
fn last(ty: &str) -> &str {
    ty.trim().rsplit("::").next().unwrap_or(ty).trim()
}
fn classify(ty: &str) -> Option<&'static str> {
    let t = ty.trim();
    if let Some(rest) = t.strip_prefix('*') {
        let rest = rest
            .trim_start()
            .strip_prefix("mut ")
            .or_else(|| rest.trim_start().strip_prefix("const "));
        if let Some(inner) = rest {
            if inner.trim_start().starts_with('*') {
                return Some("other");
            }
            let n = last(inner);
            if BYTE_ELEM.contains(&n) {
                return Some("byte");
            }
            if WIDE_ELEM.contains(&n) {
                return Some("wide");
            }
            return Some("other");
        }
    }
    let n = last(t);
    if BYTE_PTR.contains(&n) {
        Some("byte")
    } else if WIDE_PTR.contains(&n) {
        Some("wide")
    } else {
        None
    }
}
fn decl(scope: &str, name: &str) -> Option<String> {
    let mut found = None;
    let mut from = 0;
    while let Some(rel) = scope[from..].find(name) {
        let at = from + rel;
        let end = at + name.len();
        from = end;
        if scope[..at]
            .chars()
            .next_back()
            .is_some_and(|c| c.is_alphanumeric() || c == '_' || c == '.')
            || scope[end..]
                .chars()
                .next()
                .is_some_and(|c| c.is_alphanumeric() || c == '_')
        {
            continue;
        }
        let mut j = end;
        while j < scope.len() && scope.as_bytes()[j].is_ascii_whitespace() {
            j += 1
        }
        if scope.as_bytes().get(j) != Some(&b':') || scope.as_bytes().get(j + 1) == Some(&b':') {
            continue;
        }
        let mut depth = 0i32;
        let mut k = j + 1;
        for (off, c) in scope[j + 1..].char_indices() {
            let pos = j + 1 + off;
            if "<[(".contains(c) {
                depth += 1
            } else if ">])".contains(c) {
                if depth == 0 {
                    k = pos;
                    break;
                }
                depth -= 1
            } else if ",;={".contains(c) && depth == 0 {
                k = pos;
                break;
            }
            k = pos + c.len_utf8()
        }
        let ty = scope[j + 1..k].trim();
        if !ty.is_empty() {
            found = Some(ty.to_string())
        }
    }
    found
}
fn operand_class(fn_scope: &str, file_text: &str, op: &str) -> Option<&'static str> {
    let base = op.split('.').next().unwrap_or(op);
    let ty = decl(fn_scope, base).or_else(|| decl(file_text, base))?;
    if op.ends_with("_ptr()") {
        let re = crate::regexes::cached(r"^\[\s*([^;\]]+?)\s*;").unwrap();
        let c = re.captures(ty.trim())?;
        classify(&format!("*mut {}", &c[1]))
    } else {
        classify(&ty)
    }
}
fn is_word(c: char) -> bool {
    c.is_alphanumeric() || c == '_'
}
fn is_sub_match_valid(text: &str, at: usize) -> bool {
    !text[..at]
        .chars()
        .next_back()
        .is_some_and(|c| is_word(c) || c == '.')
}
fn close_of(text: &str, at: usize) -> usize {
    let mut depth = 0i32;
    for (i, c) in text
        .char_indices()
        .filter(|(i, _)| *i >= at)
        .take_while(|(i, _)| *i < at + 300)
    {
        if c == '(' {
            depth += 1
        } else if c == ')' {
            if depth == 0 {
                return i + 1;
            }
            depth -= 1
        } else if ";{},".contains(c) && depth == 0 {
            return i;
        }
    }
    at
}
fn scaling(text: &str, m: &Captures<'_>) -> Option<String> {
    let end = m.get(4).map_or(m.get(0).unwrap().end(), |x| x.start());
    let tail = close_of(text, end);
    AFTER
        .captures(&text[tail..])
        .or_else(|| AFTER.captures(&text[end..]))
        .map(|c| c[1].to_string())
}
fn snippet(body: &str, start: usize, end: usize) -> String {
    let lo = body[..start].rfind('\n').map_or(0, |x| x + 1);
    let hi = body[end..].find('\n').map_or(body.len(), |x| end + x);
    body[lo..hi]
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .chars()
        .take(110)
        .collect()
}
fn c_verdict(twins: &[&Function], a: &str, b: &str) -> Option<(String, String)> {
    for insensitive in [false, true] {
        for f in twins {
            for m in CCAST.captures_iter(&f.body) {
                let aa = m.get(1).unwrap().as_str();
                let bb = m.get(2).unwrap().as_str();
                let matched = if insensitive {
                    aa.eq_ignore_ascii_case(a) && bb.eq_ignore_ascii_case(b)
                } else {
                    aa == a && bb == b
                };
                if matched {
                    let x = m.get(0).unwrap();
                    return Some(("bytes".into(), snippet(&f.body, x.start(), x.end())));
                }
            }
            for m in CPLAIN.captures_iter(&f.body) {
                let aa = m.get(1).unwrap().as_str();
                let bb = m.get(2).unwrap().as_str();
                let matched = if insensitive {
                    aa.eq_ignore_ascii_case(a) && bb.eq_ignore_ascii_case(b)
                } else {
                    aa == a && bb == b
                };
                if !matched {
                    continue;
                }
                let x = m.get(0).unwrap();
                let start = x.start();
                let end = x.end();
                if f.body[..start]
                    .chars()
                    .next_back()
                    .is_some_and(|c| is_word(c) || c == '.' || c == '>')
                    || f.body[end..].chars().next().is_some_and(is_word)
                {
                    continue;
                }
                let tail = f.body[end..].trim_start();
                if tail.starts_with("->") || tail.starts_with('.') || tail.starts_with('[') {
                    continue;
                }
                let lo = f.body[..start].rfind('\n').map_or(0, |i| i + 1);
                let hi = f.body[start..]
                    .find('\n')
                    .map_or(f.body.len(), |i| start + i);
                let pre = &f.body[lo..start];
                let post = &f.body[end..hi];
                let bytes = crate::regexes::cached(r"^\s*\)?\s*\*\s*(?:sizeof|2\b)")
                    .unwrap()
                    .is_match(post)
                    || crate::regexes::cached(r"(?:sizeof\s*\([^)]*\)|\b2)\s*\*\s*\(?\s*$")
                        .unwrap()
                        .is_match(pre);
                return Some((
                    if bytes { "bytes" } else { "elements" }.into(),
                    snippet(&f.body, start, end),
                ));
            }
        }
    }
    None
}
fn generated(text: &str) -> bool {
    let prefix: String = text.chars().take(2000).collect();
    GEN.iter().any(|g| prefix.contains(g))
}
fn search_window(text: &str, hit_start: usize, hit_end: usize) -> (usize, usize) {
    let total_chars = text.chars().count();
    let start_chars = text[..hit_start].chars().count();
    let end_chars = text[..hit_end].chars().count();
    let lo_chars = start_chars.saturating_sub(120);
    let hi_chars = (end_chars + 200).min(total_chars);
    let lo = text
        .char_indices()
        .nth(lo_chars)
        .map_or(text.len(), |(i, _)| i);
    let hi = text
        .char_indices()
        .nth(hi_chars)
        .map_or(text.len(), |(i, _)| i);
    (lo, hi)
}
fn candidates(
    file: &crate::SourceFile,
    root: &Path,
    index: &crate::twins::CIndex,
) -> Vec<(usize, String, String, String, String, Option<String>)> {
    let raw = &file.text;
    if generated(raw) {
        return vec![];
    }
    if !PREFILTER.is_match(raw) {
        return vec![];
    }
    let text = twins::blank_rust(raw);
    let abs = root.join(&file.path);
    let funcs = file.twin_functions(root);
    let mut ms = std::collections::BTreeSet::<usize>::new();
    for hit in PREFILTER.find_iter(&text) {
        let (lo, hi) = search_window(&text, hit.start(), hit.end());
        for m in SUB.captures_iter(&text[lo..hi]) {
            let at = lo + m.get(0).unwrap().start();
            if !is_sub_match_valid(&text, at) {
                continue;
            }
            ms.insert(at);
        }
    }
    let mut out = vec![];
    for at in ms {
        let Some(m) = SUB.captures_at(&text, at) else {
            continue;
        };
        let whole = m.get(0).unwrap();
        let at = whole.start();
        if m.get(2).is_some() && m.get(4).is_none() {
            continue;
        }
        let line = text[..at].bytes().filter(|&b| b == b'\n').count() + 1;
        let lines: Vec<_> = raw.split('\n').collect();
        if lines.get(line - 1).is_some_and(|l| {
            crate::regexes::cached(r"//\s*nolint(?::\s*ptr-byte-diff\b|\s*$)")
                .unwrap()
                .is_match(l)
        }) {
            continue;
        }
        let owner = twins::enclosing(&funcs, at);
        let scope = owner
            .map(|f| format!("{}{}", f.params, f.body))
            .unwrap_or_else(|| text.clone());
        let ca = operand_class(&scope, &text, &m[1]);
        let cb = operand_class(&scope, &text, &m[3]);
        if ca != Some("wide") || cb != Some("wide") {
            continue;
        }
        let scaled = scaling(&text, &m);
        if matches!(scaled.as_deref(), Some("/") | Some(">>")) {
            continue;
        }
        let fn_name = owner.map_or("", |f| f.name.as_str()).to_string();
        let twins = if fn_name.is_empty() {
            vec![]
        } else {
            twins::prefer(&abs, index.get(&fn_name))
        };
        let (tag, why, evidence) = match c_verdict(&twins, &m[1], &m[3]) {
            None => (
                "ptr-byte-diff-unpaired".to_string(),
                if twins.is_empty() {
                    "no C function of this name"
                } else {
                    "no C twin subtracts these operands"
                }
                .to_string(),
                String::new(),
            ),
            Some((unit, _ev)) if unit == "bytes" && scaled.as_deref() != Some("*") => continue,
            Some((unit, ev)) => (
                "ptr-byte-diff".into(),
                if unit == "elements" {
                    "C counts elements"
                } else {
                    "Rust scales a byte count again"
                }
                .into(),
                ev,
            ),
        };
        let src = lines
            .get(line - 1)
            .unwrap_or(&"")
            .trim()
            .chars()
            .take(110)
            .collect::<String>();
        let _ = (why, evidence, src);
        out.push((
            line,
            fn_name,
            m[1].split('.').next().unwrap_or(&m[1]).to_string(),
            m[3].split('.').next().unwrap_or(&m[3]).to_string(),
            tag,
            scaled,
        ));
    }
    out
}
impl Rule for PtrByteDiff {
    fn name(&self) -> &'static str {
        "scan_ptr_byte_diff"
    }
    fn needs_c_twins(&self) -> bool {
        true
    }
    fn run(&self, c: &Corpus) -> Result<Vec<String>, String> {
        let mut out = vec![];
        for f in c.rust_files() {
            for (line, fn_name, a, b, tag, _scaled) in candidates(f, &c.root, c.c_twins()) {
                out.push(format!(
                    "{}:{}: {} {}({} - {})",
                    f.path.display(),
                    line,
                    tag,
                    fn_name,
                    a,
                    b
                ));
            }
        }
        Ok(out)
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn unicode_prefix_and_windows_are_character_based() {
        let text = format!("{}name as usize - other as usize", "é".repeat(250));
        let hit = PREFILTER.find(&text).unwrap();
        let (lo, hi) = search_window(&text, hit.start(), hit.end());
        assert!(text.is_char_boundary(lo) && text.is_char_boundary(hi));
        assert!(text[lo..hi].contains("name as usize - other as usize"));
        assert!(!generated(&format!("{}@generated", "é".repeat(2000))));
        // Python checks the first 2000 characters; the complete nine-character marker
        // must fit in that window, so its `@` begins no later than character 1991.
        assert!(generated(&format!("{}@generated", "é".repeat(1990))));
    }
    #[test]
    fn classify_and_decl() {
        assert_eq!(classify("LPCWSTR"), Some("wide"));
        assert_eq!(classify("*const u8"), Some("byte"));
        assert_eq!(decl("fn f(a: LPCWSTR) {}", "a").as_deref(), Some("LPCWSTR"));
    }
    #[test]
    fn scaled_and_subtrahend_guard() {
        let a = "(p as isize - q as isize) as ULONG";
        let m = SUB.captures(a).unwrap();
        assert_eq!(scaling(a, &m), None);
        let later = "(p as isize - q as isize); let unrelated: *mut u8 = ptr;";
        assert_eq!(scaling(later, &SUB.captures(later).unwrap()), None);
        let a = "(p as isize - q as isize) as ULONG / 2";
        let m = SUB.captures(a).unwrap();
        assert_eq!(scaling(a, &m).as_deref(), Some("/"));
        assert!(SUB
            .captures("p as usize - (q as usize + 1)")
            .unwrap()
            .get(2)
            .is_some());
    }
    #[test]
    fn c_verdict_kinds() {
        let f = |body: &str| Function {
            name: "F".into(),
            path: PathBuf::from("x.c"),
            line: 1,
            body: body.into(),
            body_start: 0,
            params: String::new(),
            ret: String::new(),
        };
        assert_eq!(
            c_verdict(&[&f("{ n = p - q; }")], "p", "q").unwrap().0,
            "elements"
        );
        assert_eq!(
            c_verdict(&[&f("{ n = (ULONG_PTR)p - (ULONG_PTR)q; }")], "p", "q")
                .unwrap()
                .0,
            "bytes"
        );
        assert_eq!(
            c_verdict(&[&f("{ n = (p - q) * sizeof(WCHAR); }")], "p", "q")
                .unwrap()
                .0,
            "bytes"
        );
    }
    #[test]
    fn version_fixture_with_real_style_twins() {
        let rust=crate::SourceFile::new("version-rust/src/lib.rs".into(),"unsafe fn VersionInfo32_QueryValue(info:*const u8, mut lpSubBlock:LPCWSTR)->i32 { let mut lpNextSlash:LPCWSTR=lpSubBlock; let len=(lpNextSlash as isize-lpSubBlock as isize) as UINT; len as i32 }".into());
        let c = crate::SourceFile::new(
            "dll/win32/version/version.c".into(),
            "int VersionInfo32_QueryValue(const WCHAR *lpSubBlock, const WCHAR *lpNextSlash) { return lpNextSlash - lpSubBlock; }".into(),
        );
        let corpus = Corpus::new(PathBuf::from("/repo"), vec![rust, c]);
        assert_eq!(corpus.c_twins().get("VersionInfo32_QueryValue").len(), 1);
        let rust_file = corpus.rust_files().next().unwrap();
        assert_eq!(
            candidates(rust_file, &corpus.root, corpus.c_twins()).len(),
            1
        );
        assert!(PtrByteDiff.run(&corpus).unwrap().iter().any(
            |f| f.contains("ptr-byte-diff VersionInfo32_QueryValue(lpNextSlash - lpSubBlock)")
        ));
    }
}
