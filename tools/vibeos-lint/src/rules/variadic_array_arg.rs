use crate::{Corpus, Rule};
use rayon::prelude::*;
use regex::Regex;
use std::collections::{HashMap, HashSet};
use std::path::{Path, PathBuf};
use std::sync::Mutex;

pub struct VariadicArrayArg;

struct Patterns {
    structs: Regex,
    fields: Regex,
    ptr_alias: Regex,
    alias: Regex,
    use_alias: Regex,
    statics: Regex,
    variadic: Regex,
    comments: Regex,
    calls: Regex,
    declaration: Regex,
    if_else: Regex,
    ident: Regex,
    place: Regex,
}

impl Patterns {
    fn set_calls(&mut self, names: &HashSet<String>) {
        if names.is_empty() {
            return;
        }
        let mut names: Vec<_> = names.iter().map(|name| regex::escape(name)).collect();
        names.sort_by(|a, b| b.len().cmp(&a.len()).then(a.cmp(b)));
        self.calls = Regex::new(&format!(r"\b({})\s*\(", names.join("|")))
            .expect("escaped variadic function names");
    }

    fn new() -> Self {
        let re = |s| Regex::new(s).expect("valid variadic-array rule regex");
        Self {
            structs: re(r"(?s)\bstruct\s+(\w+)\s*\{([^{}]*)\}"),
            fields: re(r"(?:^|[,{\n])\s*(?:pub(?:\([^)]*\))?\s+)?(\w+)\s*:\s*(\S)"),
            ptr_alias: re(r"\btype\s+(\w+)\s*=\s*\*(?:mut|const)\s+([\w:]+)\s*;"),
            alias: re(r"\btype\s+(\w+)\s*=\s*([\w:]+)\s*;"),
            use_alias: re(r"\bpub\s+use\s+[\w:]*?(\w+)\s+as\s+(\w+)\s*;"),
            statics: re(r"\bstatic\s+(?:mut\s+)?(\w+)\s*:\s*\["),
            variadic: re(r"(?s)\bfn\s+(\w+)\s*\(([^;{]*?)\.\.\.\s*\)"),
            comments: re(r"(?s)/\*.*?\*/"),
            calls: re(r"\b(\w+)\s*\("),
            declaration: re(r"\bfn\s*$"),
            if_else: re(r"(?s)^if\s.+\{\s*(\w+)\s*\}\s*else\s*\{\s*(\w+)\s*\}$"),
            ident: re(r"^\w+$"),
            place: re(r"^(?:\(\*(\w+)\)|(\w+))\.(\w+)$"),
        }
    }
}

#[derive(Default)]
struct Index {
    structs: HashMap<String, HashMap<String, bool>>,
    ptr_alias: HashMap<String, String>,
    alias: HashMap<String, String>,
    variadic: HashSet<String>,
    statics: HashSet<(PathBuf, String)>,
    // These caches belong to this rule invocation, never to global process state.
    array_patterns: Mutex<HashMap<String, Regex>>,
    type_patterns: Mutex<HashMap<String, Regex>>,
}

fn generated(text: &str) -> bool {
    text.chars()
        .take(600)
        .collect::<String>()
        .contains("automatically generated by rust-bindgen")
}

fn last_segment(t: &str) -> &str {
    t.rsplit("::").next().unwrap_or(t)
}

fn crate_of(path: &Path) -> PathBuf {
    for parent in path.ancestors().skip(1) {
        if parent.join("Cargo.toml").is_file() {
            return parent.to_path_buf();
        }
    }
    path.parent().unwrap_or(path).to_path_buf()
}

impl Index {
    fn add(
        &mut self,
        text: &str,
        crate_dir: &Path,
        p: &Patterns,
        aliases: &mut Vec<(String, String)>,
    ) {
        aliases.extend(
            p.use_alias
                .captures_iter(text)
                .map(|m| (m[1].to_owned(), m[2].to_owned())),
        );
        if !generated(text) {
            self.statics.extend(
                p.statics
                    .captures_iter(text)
                    .map(|m| (crate_dir.to_path_buf(), m[1].to_owned())),
            );
        }
        for m in p.structs.captures_iter(text) {
            let fields = self.structs.entry(m[1].to_owned()).or_default();
            // Match Python's per-struct dict comprehension: the last duplicate field wins,
            // then merge each struct definition into the global index using logical OR.
            let mut current = HashMap::new();
            for f in p.fields.captures_iter(&m[2]) {
                current.insert(f[1].to_owned(), &f[2] == "[");
            }
            for (name, is_array) in current {
                *fields.entry(name).or_default() |= is_array;
            }
        }
        for m in p.ptr_alias.captures_iter(text) {
            self.ptr_alias
                .insert(m[1].to_owned(), last_segment(&m[2]).to_owned());
        }
        for m in p.alias.captures_iter(text) {
            self.alias
                .insert(m[1].to_owned(), last_segment(&m[2]).to_owned());
        }
        self.variadic
            .extend(p.variadic.captures_iter(text).map(|m| m[1].to_owned()));
    }

    fn resolve<'a>(&'a self, mut t: &'a str) -> &'a str {
        let mut seen = HashSet::new();
        while seen.insert(t) {
            if let Some(next) = self.ptr_alias.get(t) {
                t = next;
            } else if let Some(next) = self.alias.get(t).filter(|next| next.as_str() != t) {
                t = next;
            } else {
                break;
            }
        }
        t
    }
}

fn window(text: &str, before: usize) -> &str {
    let prefix = &text[..before];
    let start = prefix
        .rfind("\nfn ")
        .unwrap_or(0)
        .max(prefix.rfind(" fn ").unwrap_or(0));
    &prefix[start..]
}

fn var_type(text: &str, var: &str, before: usize, index: &Index) -> Option<String> {
    let mut cache = index.type_patterns.lock().unwrap();
    let pattern = cache.entry(var.to_owned()).or_insert_with(|| {
        let var = regex::escape(var);
        Regex::new(&format!(
            r"\b{var}\s*:\s*(?:\*(?:mut|const)\s+|&(?:mut\s+)?)?([\w:]+)|\blet\s+(?:mut\s+)?{var}\s*=[^;]*?\bas\s+\*(?:mut|const)\s+([\w:]+)\s*;"
        )).expect("escaped variable regex")
    }).clone();
    drop(cache);
    pattern
        .captures_iter(window(text, before))
        .last()
        .map(|m| last_segment(m.get(1).or_else(|| m.get(2)).unwrap().as_str()).to_owned())
}

fn is_array_var(text: &str, var: &str, before: usize, crate_dir: &Path, index: &Index) -> bool {
    let mut cache = index.array_patterns.lock().unwrap();
    let pattern = cache
        .entry(var.to_owned())
        .or_insert_with(|| {
            Regex::new(&format!(
                r"(?:\blet\s+(?:mut\s+)?|[(,]\s*(?:mut\s+)?){}\b\s*(:\s*\[)?",
                regex::escape(var)
            ))
            .expect("escaped local regex")
        })
        .clone();
    drop(cache);
    if let Some(m) = pattern.captures_iter(window(text, before)).last() {
        return m.get(1).is_some();
    }
    index
        .statics
        .contains(&(crate_dir.to_path_buf(), var.to_owned()))
}

fn split_args(text: &str, open: usize) -> Vec<&str> {
    let bytes = text.as_bytes();
    let mut args = Vec::new();
    let mut depth = 0usize;
    let mut start = open + 1;
    let mut i = open;
    while i < bytes.len() {
        let c = bytes[i];
        if c == b'"' {
            i += 1;
            while i < bytes.len() {
                if bytes[i] == b'\\' {
                    i += 2;
                } else if bytes[i] == b'"' {
                    i += 1;
                    break;
                } else {
                    i += 1;
                }
            }
            continue;
        }
        match c {
            b'(' | b'[' | b'{' => depth += 1,
            b')' | b']' | b'}' => {
                depth = depth.saturating_sub(1);
                if depth == 0 {
                    args.push(text[start..i].trim());
                    return args;
                }
            }
            b',' if depth == 1 => {
                args.push(text[start..i].trim());
                start = i + 1;
            }
            _ => {}
        }
        i += 1;
    }
    Vec::new()
}

fn scan(text: &str, crate_dir: &Path, index: &Index, p: &Patterns) -> Vec<usize> {
    if generated(text) || index.variadic.is_empty() {
        return Vec::new();
    }
    let text = p.comments.replace_all(text, |m: &regex::Captures<'_>| {
        m[0].as_bytes()
            .iter()
            .map(|b| if *b == b'\n' { '\n' } else { ' ' })
            .collect::<String>()
    });
    let mut out = Vec::new();
    for m in p.calls.captures_iter(&text) {
        let full = m.get(0).unwrap();
        if !index.variadic.contains(&m[1]) {
            continue;
        }
        if let Some(prev) = text[..full.start()].chars().next_back() {
            // Python's negative lookbehind also excludes qualified names and methods.
            if prev == '.' || prev == ':' || prev == '_' || prev.is_alphanumeric() {
                continue;
            }
        }
        let line_start = text[..full.start()].rfind('\n').map_or(0, |n| n + 1);
        let prefix = &text[line_start..full.start()];
        if prefix.trim_start().starts_with("//") || p.declaration.is_match(prefix) {
            continue;
        }
        for arg in split_args(&text, full.end() - 1).into_iter().skip(1) {
            let mut bare = arg;
            while bare.starts_with('(') && bare.ends_with(')') {
                bare = bare[1..bare.len() - 1].trim();
            }
            let branches = p.if_else.captures(bare);
            let candidates: Vec<&str> = if let Some(ref branches) = branches {
                vec![
                    branches.get(1).unwrap().as_str(),
                    branches.get(2).unwrap().as_str(),
                ]
            } else if p.ident.is_match(bare) {
                vec![bare]
            } else {
                Vec::new()
            };
            let mut hit = candidates
                .into_iter()
                .any(|c| is_array_var(&text, c, full.start(), crate_dir, index));
            if !hit {
                if let Some(place) = p.place.captures(arg) {
                    let var = place.get(1).or_else(|| place.get(2)).unwrap().as_str();
                    if let Some(t) = var_type(&text, var, full.start(), index) {
                        hit = index
                            .structs
                            .get(index.resolve(&t))
                            .and_then(|fields| fields.get(&place[3]))
                            .copied()
                            .unwrap_or(false);
                    }
                }
            }
            if hit {
                out.push(text[..full.start()].bytes().filter(|b| *b == b'\n').count() + 1);
            }
        }
    }
    out
}

impl Rule for VariadicArrayArg {
    fn name(&self) -> &'static str {
        "scan_variadic_array_arg"
    }

    fn run(&self, corpus: &Corpus) -> Result<Vec<String>, String> {
        let mut p = Patterns::new();
        let mut files: Vec<_> = corpus
            .rust_files()
            .filter(|f| {
                !f.path
                    .components()
                    .any(|part| part.as_os_str() == ".responses")
            })
            .collect();
        files.sort_by(|a, b| a.path.cmp(&b.path));
        let mut crates = HashMap::new();
        let dirs: Vec<_> = files
            .iter()
            .map(|f| {
                let parent = f.path.parent().unwrap_or(&f.path);
                crates
                    .entry(parent.to_path_buf())
                    .or_insert_with(|| crate_of(&corpus.root.join(&f.path)))
                    .clone()
            })
            .collect();
        let mut index = Index::default();
        let mut aliases = Vec::new();
        for (f, dir) in files.iter().zip(&dirs) {
            index.add(&f.text, dir, &p, &mut aliases);
        }
        // Python updates this set once, so alias chains intentionally do not transitively resolve.
        let added: Vec<_> = aliases
            .into_iter()
            .filter(|(target, _)| index.variadic.contains(target))
            .map(|(_, name)| name)
            .collect();
        index.variadic.extend(added);
        p.set_calls(&index.variadic);
        let out: Vec<Vec<String>> = files
            .par_iter()
            .zip(&dirs)
            .map(|(f, dir)| {
                scan(&f.text, dir, &index, &p)
                    .into_iter()
                    .map(|line| format!("{}:{line}: variadic-array-arg", f.path.display()))
                    .collect()
            })
            .collect();
        Ok(out.into_iter().flatten().collect())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::SourceFile;

    #[test]
    fn paid_artifact_directories_are_not_part_of_the_index() {
        let corpus = Corpus {
            root: PathBuf::from("/fixture"),
            files: vec![SourceFile::new(
                "sdk/lib/rust/.responses/bad.rs".into(),
                format!("{DEF}\nfn f(ip: PInfo) {{ note(0, (*ip).name); }}"),
            )],
        };
        assert!(VariadicArrayArg.run(&corpus).unwrap().is_empty());
    }

    fn findings(definitions: &str, body: &str) -> Vec<usize> {
        let mut p = Patterns::new();
        let mut index = Index::default();
        let dir = Path::new("fixture");
        let mut aliases = Vec::new();
        index.add(definitions, dir, &p, &mut aliases);
        index.add(body, dir, &p, &mut aliases);
        let added: Vec<_> = aliases
            .into_iter()
            .filter(|(target, _)| index.variadic.contains(target))
            .map(|(_, name)| name)
            .collect();
        index.variadic.extend(added);
        p.set_calls(&index.variadic);
        scan(body, dir, &index, &p)
    }

    const DEF: &str = "extern \"C\" { fn note(fmt: *const u8, ...); }\nstruct Info { pub name: [u8; 256], other: *const u8 }\ntype PInfo = *mut Info; type Alias = PInfo;";

    #[test]
    fn fields_aliases_casts_and_pointers() {
        let body = "fn test(ip: Alias) {\n note(b\"x\\0\".as_ptr(), (*ip).name);\n note(b\"x\\0\".as_ptr(), (*ip).other);\n note(b\"x\\0\".as_ptr(), (*ip).name.as_ptr());\n let p = ip as *mut Info; note(b\"x\\0\".as_ptr(), p.name);\n}";
        assert_eq!(findings(DEF, body), vec![2, 5]);
    }

    #[test]
    fn statics_locals_aliases_and_branches() {
        let defs = format!("{DEF}\nstatic mut a: [u16; 4] = [0;4]; static b: [u16;4] = [0;4];\npub use crate::note as gprintf;");
        let body = "fn test() {\n gprintf(p, (a));\n note(p, if flag { a } else { b });\n let a = ptr; note(p, a);\n let mut local: [u8;4] = [0;4]; note(p, local);\n}\nfn shadow(b: *const u16) { note(p, b); }";
        assert_eq!(findings(&defs, body), vec![2, 3, 5]);
    }

    #[test]
    fn comments_generated_and_qualified_calls() {
        let body = "fn f(ip: PInfo) {\n // note(p, (*ip).name);\n /* note(p, (*ip).name); */\n module::note(p, (*ip).name);\n thing.note(p, (*ip).name);\n note(p, (*ip).name);\n}";
        assert_eq!(findings(DEF, body), vec![6]);
        assert!(findings(
            DEF,
            &format!("// automatically generated by rust-bindgen\n{body}")
        )
        .is_empty());
    }

    #[test]
    fn nested_arguments_and_duplicate_findings() {
        assert_eq!(
            split_args(
                "note(b\"x,\\\"y\", f(a,b), if c { a } else { b }, [1,2])",
                4
            ),
            vec!["b\"x,\\\"y\"", "f(a,b)", "if c { a } else { b }", "[1,2]"]
        );
        assert_eq!(
            findings(DEF, "fn f(ip: PInfo) { note(p, (*ip).name, (*ip).name); }"),
            vec![1, 1]
        );
    }

    #[test]
    fn generated_statics_not_indexed_and_crates_do_not_leak() {
        let p = Patterns::new();
        let mut index = Index::default();
        let mut aliases = Vec::new();
        index.add(
            "// automatically generated by rust-bindgen\nstatic a: [u8;4];",
            Path::new("a"),
            &p,
            &mut aliases,
        );
        index.add("static b: [u8;4];", Path::new("a"), &p, &mut aliases);
        assert!(!is_array_var("fn f() {", "a", 8, Path::new("a"), &index));
        assert!(!is_array_var("fn f() {", "b", 8, Path::new("b"), &index));
        assert!(is_array_var("fn f() {", "b", 8, Path::new("a"), &index));
    }

    #[test]
    fn cached_patterns_keep_scope_and_call_name_boundaries() {
        let defs = format!(
            "{DEF}\nstatic a: [u8; 4];\nextern \"C\" {{ fn note_long(p: *const u8, ...); }}"
        );
        let body = "fn first() { note(p, a); let a: [u8;4]; note_long(p, a); unrelated(p, a); }\nfn second(a: *const u8) { note(p, a); }\nfn third() { let a: [u8;4]; note(p, a); }";
        assert_eq!(findings(&defs, body), vec![1, 1, 3]);
        let p = Patterns::new();
        let mut index = Index::default();
        let mut aliases = Vec::new();
        index.add(DEF, Path::new("fixture"), &p, &mut aliases);
        assert_eq!(
            var_type("fn f(ip: PInfo) {", "ip", "fn f(ip: PInfo) {".len(), &index),
            Some("PInfo".to_owned())
        );
        assert_eq!(
            var_type("fn f(ip: Alias) {", "ip", "fn f(ip: Alias) {".len(), &index),
            Some("Alias".to_owned())
        );
        assert_eq!(index.type_patterns.lock().unwrap().len(), 1);
    }
}
