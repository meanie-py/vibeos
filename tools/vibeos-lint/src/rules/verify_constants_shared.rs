// Fixed patterns retain their compiled search state across source lines.
fn re(p: &str) -> &'static Regex {
    static PATTERNS: std::sync::LazyLock<BTreeMap<&'static str, Regex>> = std::sync::LazyLock::new(
        || {
            [
            r"0[xX][0-9A-Fa-f]+|\d+|[A-Za-z_]\w*|<<|[|+\-]",
            r"^\p{Nd}$",
            r"(?s)\benum\b[^{};]*\{([^}]*)\}",
            r"(?s)^([A-Za-z_][A-Za-z0-9_]*)\s*(?:=\s*(.+))?$",
            r"(?s)/\*.*?\*/",
            r"//.*",
            r"^#define\s+([A-Z_][A-Z0-9_]*)\s+(.+?)(?:\s*//.*)?$",
            r"(?s)^(?:pub(?:\([^)]*\))?\s+)?const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*[\w:]+\s*=\s*(.+?)\s*;",
            r"^(0x[0-9A-Fa-f_]+)(?:_?[ui]\d+)?",
            r"^(-?[0-9][0-9_]*)(?:_?[ui](?:8|16|32|64|size))?$",
            r#"from_le_bytes\(\*?b"(.{4})"\)"#,
            r"from_le_bytes\(\[(.+)\]\)",
            r"^(0x[0-9A-Fa-f_]+)_?u\d+\s+as\s+i\d+",
        ]
        .into_iter()
        .map(|pattern| (pattern, Regex::new(pattern).expect("valid scanner regex")))
        .collect()
        },
    );
    PATTERNS
        .get(p)
        .unwrap_or_else(|| panic!("unregistered constants pattern: {p}"))
}

pub fn is_target_rust(f: &SourceFile) -> bool {
    let p = f.path.to_string_lossy();
    !p.split('/').any(|x| x == "target")
        && !f.path.file_name().is_some_and(|n| {
            let n = n.to_string_lossy();
            n.starts_with("bindgen_") || n.starts_with("hal_bindgen_")
        })
        && !f
            .text
            .lines()
            .next()
            .unwrap_or("")
            .contains("automatically generated by rust-bindgen")
}

fn parse_enum_expr(expr: &str, scope: &BTreeMap<String, u32>) -> Option<u32> {
    let token_re = re(r"0[xX][0-9A-Fa-f]+|\d+|[A-Za-z_]\w*|<<|[|+\-]");
    let tokens: Vec<String> = token_re
        .find_iter(expr)
        .map(|m| m.as_str().to_owned())
        .collect();
    if tokens.is_empty() {
        return None;
    }
    // Python eval's supported grammar here has |, +, -, <<; parentheses are
    // removed by the Python tokenizer and thus have no grouping effect.
    #[derive(Clone, Copy)]
    struct V {
        low: u32,
        hint: i64,
    }
    let mut vals: Vec<V> = Vec::new();
    let mut ops: Vec<String> = Vec::new();
    let mut expect_value = true;
    let prec = |o: &str| match o {
        "|" => 1,
        "<<" => 2,
        "+" | "-" => 3,
        _ => 0,
    };
    let apply = |vals: &mut Vec<V>, op: &str| -> Option<()> {
        let b = vals.pop()?;
        let a = vals.pop()?;
        vals.push(match op {
            "|" => V {
                low: a.low | b.low,
                hint: (a.low | b.low) as i64,
            },
            "+" => V {
                low: a.low.wrapping_add(b.low),
                hint: a.hint.saturating_add(b.hint),
            },
            "-" => V {
                low: a.low.wrapping_sub(b.low),
                hint: a.hint.saturating_sub(b.hint),
            },
            "<<" => {
                if b.hint < 0 {
                    return None;
                }
                let low = if b.hint >= 32 {
                    0
                } else {
                    a.low.wrapping_shl(b.hint as u32)
                };
                V {
                    low,
                    hint: if b.hint >= 32 {
                        0
                    } else {
                        a.hint.checked_shl(b.hint as u32).unwrap_or(i64::MAX)
                    },
                }
            }
            _ => return None,
        });
        Some(())
    };
    let mut unary_negative = false;
    for token in tokens {
        if token == "+" || token == "-" {
            if expect_value {
                if token == "-" {
                    unary_negative = !unary_negative;
                }
                continue;
            }
        }
        if token == "|" || token == "+" || token == "-" || token == "<<" {
            if expect_value {
                return None;
            }
            while ops.last().is_some_and(|o| prec(o) >= prec(&token)) {
                apply(&mut vals, &ops.pop()?)?;
            }
            ops.push(token);
            expect_value = true;
            continue;
        }
        if !expect_value {
            return None;
        }
        let (low, hint) = if token.starts_with("0x") || token.starts_with("0X") {
            let low = modulo_literal(&token, 16)?;
            (low, bounded_literal(&token[2..], 16))
        } else if token.chars().all(|x| is_decimal_digit(x)) {
            let low = modulo_literal(&token, 10)?;
            (low, bounded_literal(&token, 10))
        } else {
            let v = *scope.get(&token)?;
            (v, v as i64)
        };
        let v = if unary_negative {
            V {
                low: 0u32.wrapping_sub(low),
                hint: hint.saturating_neg(),
            }
        } else {
            V { low, hint }
        };
        vals.push(v);
        unary_negative = false;
        expect_value = false;
    }
    if expect_value {
        return None;
    }
    while let Some(op) = ops.pop() {
        apply(&mut vals, &op)?;
    }
    (vals.len() == 1).then(|| vals[0].low)
}

fn is_decimal_digit(c: char) -> bool {
    if c.is_ascii_digit() {
        return true;
    }
    let mut buf = [0; 4];
    re(r"^\p{Nd}$").is_match(c.encode_utf8(&mut buf))
}

fn bounded_literal(s: &str, radix: u32) -> i64 {
    let mut v = 0i64;
    let normalized = if radix == 10 {
        crate::integers::decimal(s).ok()
    } else {
        Some(s.to_owned())
    };
    let Some(normalized) = normalized else {
        return i64::MAX;
    };
    for c in normalized.chars() {
        let Some(d) = c.to_digit(radix) else {
            return i64::MAX;
        };
        v = v.saturating_mul(radix as i64).saturating_add(d as i64);
    }
    v
}

fn modulo_literal(s: &str, radix: u32) -> Option<u32> {
    let normalized;
    let digits = if radix == 16 {
        &s[2..]
    } else {
        normalized = crate::integers::decimal(s).ok()?;
        &normalized
    };
    if digits.is_empty() {
        return None;
    }
    let mut v = 0u32;
    for c in digits.chars() {
        v = v.wrapping_mul(radix).wrapping_add(c.to_digit(radix)?);
    }
    Some(v)
}

pub fn enum_values(c: &Corpus) -> BTreeMap<String, u32> {
    let mut all: BTreeMap<String, BTreeSet<u32>> = BTreeMap::new();
    let enum_re = re(r"(?s)\benum\b[^{};]*\{([^}]*)\}");
    let member_re = re(r"(?s)^([A-Za-z_][A-Za-z0-9_]*)\s*(?:=\s*(.+))?$");
    let block = re(r"(?s)/\*.*?\*/");
    let line_comment = re(r"//.*");
    for rel in FIXED_ORDER {
        let Some(f) = c.files.iter().find(|f| f.path == Path::new(rel)) else {
            continue;
        };
        for cap in enum_re.captures_iter(&f.text) {
            let mut body = cap[1]
                .lines()
                .filter(|l| !l.trim_start().starts_with('#'))
                .collect::<Vec<_>>()
                .join("\n");
            body = block.replace_all(&body, "").into_owned();
            body = line_comment.replace_all(&body, "").into_owned();
            let mut scope = BTreeMap::<String, u32>::new();
            let mut next = Some(0u32);
            for member in body.split(',').map(str::trim).filter(|x| !x.is_empty()) {
                let Some(m) = member_re.captures(member) else {
                    next = None;
                    continue;
                };
                let name = m[1].to_owned();
                let value = m
                    .get(2)
                    .map(|x| parse_enum_expr(x.as_str(), &scope))
                    .unwrap_or(next);
                let Some(value) = value else {
                    next = None;
                    continue;
                };
                scope.insert(name.clone(), value);
                all.entry(name).or_default().insert(value);
                next = Some(value.wrapping_add(1));
            }
        }
    }
    let mut out = BTreeMap::new();
    for (name, vals) in all {
        if vals.len() == 1 {
            out.insert(name, *vals.iter().next().unwrap());
        }
    }
    out
}

fn from_catalog(v: i128) -> Big {
    Big::parse(&v.to_string()).unwrap()
}

fn direct_header_names(c: &Corpus) -> BTreeSet<String> {
    let define = re(r"^#define\s+([A-Z_][A-Z0-9_]*)\s+(.+?)(?:\s*//.*)?$");
    let mut names: BTreeSet<String> = [
        "NonPagedPoolNx",
        "NonPagedPoolNxCacheAligned",
        "NonPagedPoolSessionNx",
        "POOL_NX_ALLOCATION",
        "MdlMappingNoExecute",
    ]
    .into_iter()
    .map(str::to_owned)
    .collect();
    for rel in FIXED_ORDER {
        let Some(f) = c.files.iter().find(|f| f.path == Path::new(rel)) else {
            continue;
        };
        for line in f.text.lines() {
            if let Some(m) = define.captures(line.trim()) {
                if catalog::header_value(m.get(2).unwrap().as_str()).is_some() {
                    names.insert(m[1].to_owned());
                }
            }
        }
    }
    names
}

pub fn combined_catalog(c: &Corpus, enums: bool) -> BTreeMap<String, Big> {
    let base = catalog::catalog(c);
    let mut out: BTreeMap<String, Big> = base
        .into_iter()
        .map(|(k, v)| {
            let mut b = from_catalog(v);
            if b.is_negative() {
                b = Big::parse(&b.rem_bits(32).to_string()).unwrap();
            }
            (k, b)
        })
        .collect();
    // The Python catalogue applies ReactOS NT6.2 downgrades after direct
    // headers. Reapply them here because the shared literal catalogue starts
    // with the same values but its later header scan may overwrite them.
    out.insert("POOL_NX_ALLOCATION".into(), Big::zero());
    out.insert("MdlMappingNoExecute".into(), Big::zero());
    if enums {
        let direct = direct_header_names(c);
        for (name, val) in enum_values(c) {
            let value = from_catalog(val as i128);
            if direct.contains(&name) {
                out.entry(name).or_insert(value);
            } else {
                // Python merges enum members before its later CTL_CODE phase;
                // an enum therefore wins over a same-named computed IOCTL.
                out.insert(name, value);
            }
        }
    }
    out
}

fn rust_const(line: &str) -> Option<(String, Big)> {
    let decl = re(
        r"(?s)^(?:pub(?:\([^)]*\))?\s+)?const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*[\w:]+\s*=\s*(.+?)\s*;",
    );
    let m = decl.captures(line.trim())?;
    let name = m[1].to_owned();
    let expr = m[2].trim();
    if let Some(h) = re(r"^(0x[0-9A-Fa-f_]+)(?:_?[ui]\d+)?").captures(expr) {
        return Some((name, Big::parse(&h[1].replace('_', ""))?));
    }
    if let Some(d) = re(r"^(-?[0-9][0-9_]*)(?:_?[ui](?:8|16|32|64|size))?$").captures(expr) {
        let mut value = Big::parse(&d[1].replace('_', ""))?;
        if value.is_negative() {
            value = Big::parse(&value.rem_bits(32).to_string())?;
        }
        return Some((name, value));
    }
    if let Some(m) = re(r#"from_le_bytes\(\*?b"(.{4})"\)"#).captures(expr) {
        let bytes = m[1].as_bytes();
        if bytes.len() == 4 {
            return Some((
                name,
                Big::from_be_bytes(&[bytes[3], bytes[2], bytes[1], bytes[0]]),
            ));
        }
    }
    if let Some(m) = re(r"from_le_bytes\(\[(.+)\]\)").captures(expr) {
        let parts: Vec<_> = m[1].split(',').map(str::trim).collect();
        if parts.len() == 4 {
            let mut b = Vec::new();
            for p in parts {
                let q = p
                    .trim_matches(|c| c == 'b' || c == '\'' || c == '"')
                    .replace('\\', "");
                let v = if q.len() == 1 {
                    q.as_bytes()[0]
                } else {
                    let n = Big::parse(&q)?;
                    n.rem_bits(8) as u8
                };
                b.push(v);
            }
            return Some((name, Big::from_be_bytes(&[b[3], b[2], b[1], b[0]])));
        }
    }
    if let Some(m) = re(r"^(0x[0-9A-Fa-f_]+)_?u\d+\s+as\s+i\d+").captures(expr) {
        return Some((name, Big::parse(&m[1].replace('_', ""))?));
    }
    None
}

fn format_big_hex(v: &Big) -> String {
    let s = v.render().strip_prefix("0x").unwrap_or("0").to_owned();
    format!("0x{:0>8}", s)
}

pub fn findings(c: &Corpus, enums: bool) -> Vec<String> {
    let catalog = combined_catalog(c, enums);
    let excluded = [
        "PORT_MAXIMUM_MESSAGE_LENGTH",
        "MMWSLE_PREVIOUS_FREE_MASK",
        "PsQuotaTypes",
    ];
    let mut out = Vec::new();
    for f in c
        .sources("verify-constants-rust")
        .filter(|f| is_target_rust(f))
    {
        let lines: Vec<_> = f.text.lines().collect();
        for (idx, line) in lines.iter().enumerate() {
            let Some((name, mut value)) = rust_const(line) else {
                continue;
            };
            if excluded.contains(&name.as_str()) || name.starts_with("TAG_") {
                continue;
            }
            let mut gated = false;
            for back in 1..=3 {
                if idx < back {
                    break;
                }
                let prev = lines[idx - back].trim();
                if prev.starts_with("#[cfg(") {
                    gated = true;
                    break;
                }
                if !(prev.starts_with("//") || prev.starts_with("#[")) {
                    break;
                }
            }
            if gated {
                continue;
            }
            let Some(want) = catalog.get(&name) else {
                continue;
            };
            if value.is_negative() {
                value = Big::parse(&value.rem_bits(32).to_string()).unwrap();
            }
            if &value != want {
                let path = c.root.join(&f.path);
                let line_no = f.line(line.as_ptr() as usize - f.text.as_ptr() as usize);
                out.push(format!(
                    "  MISMATCH: {}:{}: {}: Rust={} → C={}",
                    path.display(),
                    line_no,
                    name,
                    format_big_hex(&value),
                    format_big_hex(want)
                ));
            }
        }
    }
    out
}

