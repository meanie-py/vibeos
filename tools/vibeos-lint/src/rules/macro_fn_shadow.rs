use crate::{Corpus, Rule, SourceFile, SourceSet};
use regex::Regex;
use std::{
    collections::{BTreeMap, BTreeSet},
    path::{Path, PathBuf},
    sync::LazyLock,
};

pub struct MacroFnShadow;
static SOURCES: &[SourceSet] = &[
    SourceSet::tracked("macro_headers", &["h"], &[]),
    SourceSet::tracked("macro_c_sources", &["c", "h"], &[]),
    SourceSet::tracked("macro_specs", &["spec"], &[]),
    SourceSet::tree("macro_manifests", &["sdk/lib/rust"], &[], &["Cargo.toml"]),
];
const DDK_MACROS: &[&str] = &[
    "PAGED_CODE",
    "PAGED_CODE_LOCKED",
    "UNREFERENCED_PARAMETER",
    "NT_ASSERT",
    "NT_ASSERTMSG",
];
static MACRO_DEF: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"(?m)^\s*macro_rules!\s+([A-Za-z_]\w*)").unwrap());
static GENERATED: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"automatically generated by rust-bindgen|@generated").unwrap()
});
static C_DEFINE: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"^\s*#\s*define\s+([A-Za-z_]\w*)(\([^)]*\))?(?:\s+(.*?))?\s*$").unwrap()
});
static STRIP_C_COMMENT: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"/\*.*?\*/|//.*$").unwrap());
static IDENT: LazyLock<Regex> = LazyLock::new(|| crate::regexes::cached(r"[A-Za-z_]\w*").unwrap());
static DISCARD: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"(?s)\A(?:__noop|\(\s*\(\s*(?:void|VOID)\s*\)\s*0\s*\)|\(\s*(?:void|VOID)\s*\)\s*0|do\s*\{\s*\}\s*while\s*\(\s*0\s*\)|do\s*\{\s*if\s*\(\s*0\s*\)\s*\{.*\}\s*;?\s*\}\s*while\s*\(\s*0\s*\)|\{\s*;?\s*\}|)\z").unwrap()
});
static SPEC_EXPORT: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"(?m)^\s*@\s+\w+(?:\s+-\S+)*\s+([A-Za-z_]\w*)").unwrap()
});
static NO_MANGLE: LazyLock<Regex> = LazyLock::new(|| crate::regexes::cached(r"no_mangle").unwrap());
fn visit_rust(
    node: tree_sitter::Node<'_>,
    in_extern: bool,
    src: &[u8],
    empty: &mut Vec<(String, usize, usize, bool)>,
    bodied: &mut BTreeSet<String>,
) {
    let in_extern = in_extern || node.kind() == "foreign_mod_item";
    if node.kind() == "function_item" {
        if let (Some(name), Some(body)) = (
            node.child_by_field_name("name"),
            node.child_by_field_name("body"),
        ) {
            let fn_name =
                String::from_utf8_lossy(&src[name.start_byte()..name.end_byte()]).into_owned();
            let mut body_cursor = body.walk();
            let statements = body
                .named_children(&mut body_cursor)
                .filter(|n| !matches!(n.kind(), "line_comment" | "block_comment"))
                .count();
            if statements == 0 {
                let nparams = node
                    .child_by_field_name("parameters")
                    .map_or(0, |p| p.named_child_count());
                let line = node.start_position().row + 1;
                empty.push((fn_name, line, nparams, false));
            } else {
                bodied.insert(fn_name);
            }
        }
    } else if in_extern && node.kind() == "function_signature_item" {
        if let (Some(name), Some(params)) = (
            node.child_by_field_name("name"),
            node.child_by_field_name("parameters"),
        ) {
            let fn_name =
                String::from_utf8_lossy(&src[name.start_byte()..name.end_byte()]).into_owned();
            let line = node.start_position().row + 1;
            empty.push((fn_name, line, params.named_child_count(), true));
        }
    }
    let mut cursor = node.walk();
    for child in node.named_children(&mut cursor) {
        visit_rust(child, in_extern, src, empty, bodied);
    }
}

fn empty_and_bodied(file: &SourceFile) -> (Vec<(String, usize, usize, bool)>, BTreeSet<String>) {
    let mut empty = Vec::new();
    let mut bodied = BTreeSet::new();
    if let Ok(tree) = file.rust_tree() {
        visit_rust(
            tree.root_node(),
            false,
            file.text.as_bytes(),
            &mut empty,
            &mut bodied,
        );
    }
    (empty, bodied)
}
fn crate_of(path: &Path, manifests: &BTreeSet<String>) -> String {
    let s = path.to_string_lossy().replace('\\', "/");
    let mut cur = PathBuf::from(s);
    cur.pop();
    loop {
        let key = format!("{}/Cargo.toml", cur.to_string_lossy().replace('\\', "/"));
        if manifests.contains(&key) {
            return cur.to_string_lossy().replace('\\', "/");
        }
        if !cur.pop() {
            break;
        }
    }
    path.parent()
        .unwrap_or(Path::new(""))
        .to_string_lossy()
        .replace('\\', "/")
}
fn dead_c_macros(headers: &[&SourceFile]) -> BTreeSet<String> {
    let mut empty = BTreeSet::new();
    let mut bodies = Vec::<(String, String)>::new();
    for f in headers {
        let lines = f.text.lines().collect::<Vec<_>>();
        let mut i = 0;
        while i < lines.len() {
            let mut line = lines[i].to_owned();
            while line.ends_with('\\') && i + 1 < lines.len() {
                i += 1;
                line.pop();
                line.push(' ');
                line.push_str(lines[i]);
            }
            i += 1;
            let Some(m) = C_DEFINE.captures(&line) else {
                continue;
            };
            let body = STRIP_C_COMMENT
                .replace_all(m.get(3).map_or("", |x| x.as_str()), "")
                .trim()
                .to_owned();
            if body.is_empty() && m.get(2).is_none() {
                empty.insert(m[1].to_owned());
                continue;
            }
            bodies.push((m[1].to_owned(), body));
        }
    }
    let mut names = BTreeSet::new();
    for (name, body) in bodies {
        let expanded = IDENT.replace_all(&body, |caps: &regex::Captures<'_>| {
            if empty.contains(&caps[0]) {
                "".to_owned()
            } else {
                caps[0].to_owned()
            }
        });
        if DISCARD.is_match(expanded.trim()) {
            names.insert(name);
        }
    }
    names
}
fn c_function_names(cfiles: &[&SourceFile], names: &BTreeSet<String>) -> BTreeSet<String> {
    if names.is_empty() {
        return BTreeSet::new();
    }
    let alt = names
        .iter()
        .map(|n| regex::escape(n))
        .collect::<Vec<_>>()
        .join("|");
    let re = crate::regexes::cached(&format!(
        r"^([A-Za-z_][A-Za-z0-9_ \t*]*[ \t*])?({alt})[ \t]*\("
    ))
    .unwrap();
    let mut found = BTreeSet::new();
    for f in cfiles {
        let path = f.path.to_string_lossy().replace('\\', "/");
        if path.starts_with("sdk/lib/rust/") || path.ends_with("/rust_cohab_stub.c") {
            continue;
        }
        for line in f.text.lines() {
            if let Some(m) = re.captures(line) {
                let typed = m.get(1).map_or("", |x| x.as_str()).trim();
                if !typed.is_empty() || !line.trim_end().ends_with(';') {
                    found.insert(m[2].to_owned());
                }
            }
        }
    }
    found
}
fn no_mangle(file: &SourceFile, line: usize) -> bool {
    let lines = file.text.lines().collect::<Vec<_>>();
    if line == 0 || line > lines.len() {
        return false;
    }
    let mut i = line as isize - 2;
    while i >= 0 && lines[i as usize].trim_start().starts_with("#[")
        || i >= 0 && lines[i as usize].trim_start().starts_with("///")
        || i >= 0 && lines[i as usize].trim_start().starts_with("//")
    {
        if NO_MANGLE.is_match(lines[i as usize]) {
            return true;
        }
        i -= 1;
    }
    NO_MANGLE.is_match(lines[line - 1])
}

impl Rule for MacroFnShadow {
    fn name(&self) -> &'static str {
        "scan_macro_fn_shadow"
    }
    fn source_sets(&self) -> &'static [SourceSet] {
        SOURCES
    }
    fn run(&self, c: &Corpus) -> Result<Vec<String>, String> {
        let manifests = c
            .sources("macro_manifests")
            .filter(|f| f.path.file_name().is_some_and(|n| n == "Cargo.toml"))
            .map(|f| f.path.to_string_lossy().replace('\\', "/"))
            .collect::<BTreeSet<_>>();
        let rust = c.rust_files().collect::<Vec<_>>();
        let mut macros = BTreeMap::<String, BTreeSet<String>>::new();
        let mut shadows = Vec::new();
        let mut live = BTreeSet::new();
        for f in &rust {
            if crate::regexes::cached(r"(bindgen_[a-z0-9_]+\.rs$|/target/|/\.responses/)")
                .unwrap()
                .is_match(&f.path.to_string_lossy())
                || GENERATED.is_match(&f.text.chars().take(4096).collect::<String>())
            {
                continue;
            }
            let crate_key = crate_of(&f.path, &manifests);
            macros
                .entry(crate_key.clone())
                .or_default()
                .extend(MACRO_DEF.captures_iter(&f.text).map(|m| m[1].to_owned()));
            let (items, bodied) = empty_and_bodied(f);
            live.extend(bodied);
            let rel = f.path.to_string_lossy().replace('\\', "/");
            shadows.extend(items.into_iter().map(|(name, line, nparams, decl)| {
                (f, name, line, nparams, decl, crate_key.clone(), rel.clone())
            }));
        }
        let headers = c
            .sources("macro_headers")
            .filter(|f| f.path.extension().is_some_and(|e| e == "h"))
            .collect::<Vec<_>>();
        let dead = dead_c_macros(&headers);
        let candidates = shadows
            .iter()
            .filter(|x| dead.contains(&x.1))
            .map(|x| x.1.clone())
            .collect::<BTreeSet<_>>();
        let cfiles = c
            .sources("macro_c_sources")
            .filter(|f| f.path.extension().is_some_and(|e| e == "c" || e == "h"))
            .collect::<Vec<_>>();
        let real = c_function_names(&cfiles, &candidates);
        let exports = c
            .sources("macro_specs")
            .filter(|f| f.path.extension().is_some_and(|e| e == "spec"))
            .flat_map(|f| {
                SPEC_EXPORT
                    .captures_iter(&f.text)
                    .map(|m| m[1].to_owned())
                    .collect::<Vec<_>>()
            })
            .collect::<BTreeSet<_>>();
        let mut out = BTreeSet::new();
        for (file, name, line, nparams, decl, crate_key, rel) in shadows {
            if exports.contains(&name) && no_mangle(file, line) {
                continue;
            }
            let harvested = dead.contains(&name) && nparams > 0 && !real.contains(&name);
            let hit = if decl {
                DDK_MACROS.contains(&name.as_str()) || (harvested && !live.contains(&name))
            } else {
                DDK_MACROS.contains(&name.as_str())
                    || harvested
                    || macros.get(&crate_key).is_some_and(|m| m.contains(&name))
            };
            if hit {
                out.insert(format!("{rel}: {name} [MACRO_FN_SHADOW]"));
            }
        }
        Ok(out.into_iter().collect())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;
    fn files(items: &[(&str, &str)]) -> Corpus {
        Corpus::new(
            PathBuf::from("/repo"),
            items
                .iter()
                .map(|(p, s)| SourceFile::new((*p).into(), (*s).into()))
                .collect(),
        )
    }
    fn rows(items: &[(&str, &str)]) -> Vec<String> {
        MacroFnShadow.run(&files(items)).unwrap()
    }

    #[test]
    fn local_macro_shadow_fires_and_real_body_or_macro_import_passes() {
        let bad = "#[macro_export]\nmacro_rules! UNREFERENCED_PARAMETER { ($($arg:tt)*) => {{}}; }\n#[inline] fn UNREFERENCED_PARAMETER<T>(_: T) {}\n";
        assert_eq!(
            rows(&[
                (
                    "sdk/lib/rust/demo-rust/Cargo.toml",
                    "[package]\nname=\"demo\"\n"
                ),
                ("sdk/lib/rust/demo-rust/src/lib.rs", bad)
            ]),
            vec!["sdk/lib/rust/demo-rust/src/lib.rs: UNREFERENCED_PARAMETER [MACRO_FN_SHADOW]"]
        );
        let good = "macro_rules! LOWORD { ($x:expr) => {$x}; }\npub fn LOWORD(l:u32)->u16 { (l & 0xffff) as u16 }\n";
        assert!(rows(&[
            ("sdk/lib/rust/demo-rust/Cargo.toml", ""),
            ("sdk/lib/rust/demo-rust/src/lib.rs", good)
        ])
        .is_empty());
    }

    #[test]
    fn ddk_macro_extern_and_discarding_c_macro_fire() {
        let ddk = "extern \"C\" { fn UNREFERENCED_PARAMETER(param:*mut core::ffi::c_void); }\n";
        assert_eq!(
            rows(&[("sdk/lib/rust/demo-rust/src/close.rs", ddk)]),
            vec!["sdk/lib/rust/demo-rust/src/close.rs: UNREFERENCED_PARAMETER [MACRO_FN_SHADOW]"]
        );
        let src = "pub fn DPRINT(arg:u32) {}\n";
        assert_eq!(
            rows(&[
                ("sdk/lib/rust/demo-rust/src/lib.rs", src),
                ("sdk/include/debug.h", "#define DPRINT(x) ((void)0)\n")
            ]),
            vec!["sdk/lib/rust/demo-rust/src/lib.rs: DPRINT [MACRO_FN_SHADOW]"]
        );
    }

    #[test]
    fn real_c_function_and_spec_export_abi_definition_are_not_shadows() {
        let src = "pub fn assert(_c:bool) {}\n#[no_mangle]\npub unsafe extern \"C\" fn Exported(x:u32) {}\n";
        let got = rows(&[
            ("sdk/lib/rust/demo-rust/src/lib.rs", src),
            ("sdk/include/debug.h", "#define assert(x) ((VOID)0)\n"),
            ("sdk/lib/demo.c", "void assert(int c) { (void)c; }\n"),
            ("dll/demo/demo.spec", "@ cdecl Exported(long)\n"),
        ]);
        assert!(got.is_empty(), "{got:?}");
        let call = "assert(width > 0);\n";
        assert_eq!(
            rows(&[
                (
                    "sdk/lib/rust/demo-rust/src/lib.rs",
                    "pub fn assert(_c:bool) {}\n"
                ),
                ("sdk/include/debug.h", "#define assert(x) ((VOID)0)\n"),
                ("sdk/lib/mipmap.c", call)
            ]),
            vec!["sdk/lib/rust/demo-rust/src/lib.rs: assert [MACRO_FN_SHADOW]"]
        );
    }

    #[test]
    fn control_macro_without_arguments_is_not_harvested_and_generated_files_skip() {
        let src = "pub fn Empty() {}\n";
        let got = rows(&[
            ("sdk/lib/rust/demo-rust/src/lib.rs", src),
            ("sdk/include/macros.h", "#define EMPTY_MACRO()\n"),
        ]);
        assert!(got.is_empty(), "{got:?}");
        let generated =
            "// automatically generated by rust-bindgen\npub fn UNREFERENCED_PARAMETER() {}\n";
        assert!(rows(&[("sdk/lib/rust/demo-rust/src/lib.rs", generated)]).is_empty());
    }

    #[test]
    fn tree_sitter_rows_keep_line_numbers_after_multibyte_source_prefixes() {
        let src = "// 🧡 heading\n\nfn first() {}\nfn second() {}\n";
        let f = SourceFile::new("demo.rs".into(), src.into());
        let (empty, _) = empty_and_bodied(&f);
        assert_eq!(empty.iter().map(|x| x.1).collect::<Vec<_>>(), vec![3, 4]);
    }

    #[test]
    fn cursor_walk_visits_all_functions_in_a_large_file() {
        let mut src = String::new();
        for i in 0..1500 {
            src.push_str(&format!("fn f{i}() {{}}\n"));
        }
        let f = SourceFile::new("many.rs".into(), src);
        let (empty, bodied) = empty_and_bodied(&f);
        assert_eq!(empty.len(), 1500);
        assert!(bodied.is_empty());
        assert_eq!(empty.last().unwrap().1, 1500);
    }
}
