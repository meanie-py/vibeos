//! A Rust function whose C twin catches with `__except`, while the Rust catches nothing.
//!
//! The translations were made from C built with DUMMY_PSEH, where `_SEH2_TRY { body }` runs
//! the body and `_SEH2_EXCEPT { handler }` is dead. A port of that shape keeps the body and
//! drops the handler, and nothing fails until the exception actually arrives. In the
//! kernel that is a bugcheck (a bad user buffer, or a raise-by-design callee such as
//! `MmProbeAndLockPages` with nobody to catch it); in user mode the process dies. The tree
//! has real catches now: `ntkrnl_sys::seh` and `ntdll_sys::seh` (`try_except`, `rpc_try`),
//! fastfat's `fat_try_except`, `MmTryProbeAndLockPages`, and validate-first probes
//! (`ntkrnl_sys::probe`) for the user-pointer class. A function using none of them, whose
//! twin has an `__except`, is listed.
//!
//! This replaces nothing in `scan_dropped_seh_pairs`, which only knows five direct raisers
//! and clears a whole FILE on any catch-looking token. It works per function and does not
//! try to decide whether the try body can raise: a handler the C wrote is presumed needed
//! until someone reads it. A function that is safe without one says so with
//! `nolint(dead_seh)` and the reason, in or just above it.
//!
//! Tags: `kernel`/`user`/`rtl` (sdk/lib/rtl, linked into both) from the C twin's path; then
//! `raise` when the try body calls a known raise-by-design callee (only a real catch clears
//! these: a probe answers a bad pointer, not a raise), `probe` when it probes user memory,
//! `other` otherwise (a bare user-pointer dereference, or a callee that raises somewhere down
//! its own chain).
use crate::{twins, Corpus, Rule};
use regex::Regex;
use std::collections::{BTreeSet, HashMap};
use std::sync::LazyLock;

pub struct DeadSehHandlers;
impl Rule for DeadSehHandlers {
    fn name(&self) -> &'static str {
        "scan_dead_seh_handlers"
    }
    fn needs_c_twins(&self) -> bool {
        true
    }
    fn run(&self, c: &Corpus) -> Result<Vec<String>, String> {
        let index = c.c_twins();
        let mut parsed = Vec::new();
        for f in c.rust_files() {
            let path = f.path.to_string_lossy();
            if SKIP.is_match(&path) || GENERATED.is_match(head(&f.text, 4096)) {
                continue;
            }
            let blank = twins::blank_rust(&f.text);
            let funs = twins::rust_functions(&blank, &f.path);
            parsed.push((f, crate_key(&path), funs));
        }
        // Helpers that catch, per CRATE: a body calling one is caught too. PsSuspendThread
        // puts its try_except in `suspend_caught`, which both call sites share; cdrom's
        // DeviceSendSrbSynchronously calls `__SEH2_ProbeAndLockPages` from ddk_shims.rs.
        let mut strong: HashMap<String, Vec<String>> = HashMap::new();
        let mut any: HashMap<String, Vec<String>> = HashMap::new();
        for (_, key, funs) in &parsed {
            for h in funs {
                if STRONG.is_match(&h.body) {
                    strong.entry(key.clone()).or_default().push(h.name.clone());
                }
                if CATCH.is_match(&h.body) {
                    any.entry(key.clone()).or_default().push(h.name.clone());
                }
            }
        }
        let mut out = BTreeSet::new();
        for (f, key, funs) in &parsed {
            let s: Vec<&str> = strong.get(key).map_or(vec![], |v| v.iter().map(String::as_str).collect());
            let a: Vec<&str> = any.get(key).map_or(vec![], |v| v.iter().map(String::as_str).collect());
            let helpers = Helpers { strong: &s, any: &a };
            for fun in funs {
                if let Some(line) = check(fun, &f.text, index.get(&fun.name), &helpers) {
                    out.insert(format!("{}: {line}", f.path.display()));
                }
            }
        }
        Ok(out.into_iter().collect())
    }
}

/// The crate a Rust file belongs to: its path up to `/src/` (the whole path if none).
fn crate_key(path: &str) -> String {
    path.find("/src/").map_or(path, |i| &path[..i]).to_string()
}

/// Generated and test code, and cargo build scripts: a build.rs is a host program, never a
/// translation, and its `fn main` once twinned with a rostest's `main` (rpcrt4-cargo).
static SKIP: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(
        r"(bindgen_[a-z0-9_]+\.rs$|types_[a-z0-9_]+\.rs$|/\.responses/|-sys/src/|difftest|/tests?/|/build\.rs$)",
    )
    .unwrap()
});
static GENERATED: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"automatically generated by rust-bindgen|@generated").unwrap()
});
/// `_SEH2_EXCEPT(`, `__except(`, `RpcExcept(`: a C handler that runs code on an exception.
static C_EXCEPT: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"\b(?:_SEH2_EXCEPT|__except|RpcExcept)\s*\(").unwrap());
static C_TRY: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"\b(?:_SEH2_TRY|__try|RpcTryExcept)\b").unwrap());
/// Every way the Rust tree catches, or makes the catch unnecessary.
static CATCH: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(concat!(
        r"\bprobe::|\b(?:try_except(?:_all)?|fat_try_except|rpc_try[a-z_]*|MmTryProbeAndLockPages|",
        r"probe_[a-z_]+|Probe[A-Za-z]*Safe|safe_copy_[a-z_]+|copy_(?:from|to)_user|",
        r"capture_(?:from_)?user[a-z_]*|KmProtectedCopyMemory|write_user(?:_nofail)?|",
        r"read_user[a-z_]*|catch_unwind)\b",
    ))
    .unwrap()
});
/// A real catch: the only answer to a raise-by-design callee.
static STRONG: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(concat!(
        r"\b(?:try_except(?:_all)?|fat_try_except|rpc_try[a-z_]*|MmTryProbeAndLockPages|",
        r"catch_unwind)\b",
    ))
    .unwrap()
});
static NOLINT: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"(?i)\bnolint\s*\(\s*dead_seh\b").unwrap());
static C_PROBE: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"\b(?:ProbeFor(?:Read|Write)\w*|Probe\w*AndCapture\w*|ProbeAndZeroHandle)\s*\(")
        .unwrap()
});
/// Callees whose CONTRACT is to raise on failure (the class validate-first cannot close), as
/// THIS tree implements them. Not ExAllocatePoolWithQuotaTag: Windows' raises, but this
/// tree's C and Rust both set Raise = FALSE and return NULL, so its callers need a NULL
/// check, not a catch.
static C_RAISE: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(concat!(
        r"\b(?:ExRaise\w*|RtlRaise\w*|MmProbeAndLockPages|MmProbeAndLockProcessPages|",
        r"MmMapLockedPages(?:SpecifyCache)?|",
        r"Cc(?:CopyRead|CopyWrite|FastCopyRead|FastCopyWrite|MapData|PinRead|PinMappedData|",
        r"PreparePinWrite|PrepareMdlWrite|MdlRead|ZeroData|SetFileSizes|InitializeCacheMap)|",
        r"FsRtlAllocatePool\w*|FsRtlInitializeBaseMcb|FsRtlAddLargeMcbEntry|\w+RaiseStatus|KeSuspendThread|KeReleaseSemaphore|KeReleaseMutant|",
        r"KeWaitFor\w+|KeInsertQueue\w*|IoCreateStreamFileObject\w*)\s*\(",
    ))
    .unwrap()
});

struct Helpers<'a> {
    strong: &'a [&'a str],
    any: &'a [&'a str],
}

fn calls_one(body: &str, names: &[&str], own: &str) -> bool {
    names.iter().any(|n| {
        *n != own
            && body.match_indices(n).any(|(at, _)| {
                let before = body[..at].chars().next_back();
                let after = body[at + n.len()..].trim_start().chars().next();
                !before.is_some_and(|c| c.is_ascii_alphanumeric() || c == '_') && after == Some('(')
            })
    })
}

fn check(
    fun: &twins::Function,
    raw: &str,
    twins_for_name: &[twins::Function],
    helpers: &Helpers,
) -> Option<String> {
    let twin = twins::prefer(&fun.path, twins_for_name)
        .into_iter()
        .find(|t| twins::same_module(&fun.path, t))?;
    let handlers = C_EXCEPT.find_iter(&twin.body).count();
    if handlers == 0 {
        return None;
    }
    let tried = try_bodies(&twin.body);
    // Only a raiser the Rust STILL calls needs a real catch. A port that turned the C's own
    // `RtlRaiseStatus(s)` into `return Err(s)` (NtSetUuidSeed) has converted the contract,
    // which is the Tier-1 fix, and a probe then covers what is left.
    let raises = C_RAISE.find_iter(&tried).any(|m| {
        let name = m.as_str().trim_end_matches(|c: char| c == '(' || c.is_whitespace());
        calls_one(&fun.body, &[name], "")
    });
    // A probe answers a bad POINTER; it cannot catch a callee that raises by contract.
    // NtReleaseSemaphore probed its out-parameter and so looked caught, while the raise
    // from KeReleaseSemaphore it exists to catch bugchecked the kernel.
    let caught = if raises {
        STRONG.is_match(&fun.body) || calls_one(&fun.body, helpers.strong, &fun.name)
    } else {
        CATCH.is_match(&fun.body) || calls_one(&fun.body, helpers.any, &fun.name)
    };
    if caught {
        return None;
    }
    // A suppression in the function, or in the 400 characters of doc/attributes above it.
    let start = raw[..fun.body_start.min(raw.len())]
        .char_indices()
        .rev()
        .nth(399)
        .map_or(0, |(i, _)| i);
    let end = (fun.body_start + fun.body.len()).min(raw.len());
    if raw.get(start..end).is_some_and(|s| NOLINT.is_match(s)) {
        return None;
    }
    let kind = if raises {
        "raise"
    } else if C_PROBE.is_match(&tried) {
        "probe"
    } else {
        "other"
    };
    let mode = mode_of(&twin.path);
    Some(format!(
        "{} [{mode} {kind}] C {} has {handlers} handler(s)",
        fun.name,
        twin.path.display()
    ))
}

/// Where the twin runs: `kernel`, `user`, or `rtl` (sdk/lib/rtl, linked into both).
fn mode_of(path: &std::path::Path) -> &'static str {
    const KERNEL: &[&str] = &[
        "ntoskrnl/", "drivers/", "hal/", "win32ss/gdi/ntgdi", "win32ss/user/ntuser",
        "win32ss/user/rtl", "win32ss/reactx", "win32ss/drivers", "sdk/lib/drivers",
        "sdk/lib/cmlib", "sdk/lib/kdgdb", "sdk/lib/fslib",
    ];
    if path.starts_with("sdk/lib/rtl") {
        "rtl"
    } else if KERNEL.iter().any(|p| path.starts_with(p)) {
        "kernel"
    } else {
        "user"
    }
}

/// At most `n` bytes from the start, cut back to a char boundary.
fn head(s: &str, n: usize) -> &str {
    let mut end = s.len().min(n);
    while !s.is_char_boundary(end) {
        end -= 1;
    }
    &s[..end]
}

/// The text of every `try` body in a C function (up to its `except`/`finally`), for tagging.
fn try_bodies(body: &str) -> String {
    let mut out = String::new();
    for m in C_TRY.find_iter(body) {
        let rest = &body[m.end()..];
        let Some(open) = rest.find('{') else { continue };
        let at = m.end() + open;
        if let Some(close) = twins::match_brace(body, at) {
            out.push_str(&body[at..close]);
            out.push('\n');
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    #[test]
    fn a_cargo_build_script_is_not_a_translation() {
        assert!(SKIP.is_match("sdk/lib/rust/rpcrt4-cargo/build.rs"));
        assert!(!SKIP.is_match("sdk/lib/rust/rpcrt4-rust/src/build.rs.bak"));
    }

    fn run(c_text: &str, rs: &str) -> Vec<String> {
        let corpus = Corpus::new(
            PathBuf::from("."),
            vec![
                crate::SourceFile::new("ntoskrnl/io/iomgr/irp.c".into(), c_text.into()),
                crate::SourceFile::new("sdk/lib/rust/iomgr-rust/src/irp.rs".into(), rs.into()),
            ],
        );
        DeadSehHandlers.run(&corpus).unwrap()
    }

    const C: &str = "NTSTATUS NTAPI IoLockIt(PMDL Mdl)\n{\n    _SEH2_TRY\n    {\n        \
        MmProbeAndLockPages(Mdl, UserMode, IoReadAccess);\n    }\n    \
        _SEH2_EXCEPT(EXCEPTION_EXECUTE_HANDLER)\n    {\n        IoFreeMdl(Mdl);\n        \
        _SEH2_YIELD(return _SEH2_GetExceptionCode());\n    }\n    _SEH2_END;\n    \
        return STATUS_SUCCESS;\n}\n";

    #[test]
    fn a_dropped_handler_is_listed_and_tagged() {
        let bad = "#[no_mangle]\npub unsafe extern \"system\" fn IoLockIt(Mdl: PMDL) -> NTSTATUS {\n    \
            MmProbeAndLockPages(Mdl, 1, 0);\n    STATUS_SUCCESS\n}\n";
        let out = run(C, bad);
        assert_eq!(out.len(), 1, "{out:?}");
        assert!(out[0].contains("IoLockIt [kernel raise]"), "{out:?}");
    }

    #[test]
    fn a_real_catch_or_a_reasoned_suppression_clears_it() {
        let caught = "pub unsafe extern \"system\" fn IoLockIt(Mdl: PMDL) -> NTSTATUS {\n    \
            if ntkrnl_sys::probe::MmTryProbeAndLockPages(Mdl, 1, 0) < 0 { IoFreeMdl(Mdl); }\n    \
            STATUS_SUCCESS\n}\n";
        assert!(run(C, caught).is_empty());
        let waived = "// nolint(dead_seh): kernel-mode MDL over nonpaged pool, cannot fault\n\
            pub unsafe extern \"system\" fn IoLockIt(Mdl: PMDL) -> NTSTATUS {\n    \
            MmProbeAndLockPages(Mdl, 0, 0);\n    STATUS_SUCCESS\n}\n";
        assert!(run(C, waived).is_empty());
    }

    #[test]
    fn a_raise_converted_to_err_needs_only_a_probe() {
        let c = "NTSTATUS NTAPI IoLockIt(PUCHAR Seed)\n{\n    _SEH2_TRY\n    {\n        \
            if (!Ok()) RtlRaiseStatus(STATUS_ACCESS_DENIED);\n        ProbeForRead(Seed, 6, 1);\n    }\n    \
            _SEH2_EXCEPT(EXCEPTION_EXECUTE_HANDLER)\n    {\n        Status = _SEH2_GetExceptionCode();\n    }\n    \
            _SEH2_END;\n    return Status;\n}\n";
        let converted = "pub unsafe extern \"system\" fn IoLockIt(Seed: *const u8) -> NTSTATUS {\n    \
            if Ok() == 0 { return STATUS_ACCESS_DENIED; }\n    \
            match safe_copy_from_user(d, Seed.cast(), 6, 1, 1) { Ok(()) => 0, Err(s) => s }\n}\n";
        assert!(run(c, converted).is_empty());
    }

    #[test]
    fn a_generic_helper_with_a_closure_bound_counts() {
        // rtl's validators share `valid_or_fault<F: FnOnce() -> u8>`; the `->` inside
        // its generics used to hide the helper from the function parser.
        let helper = "unsafe fn or_fault<F: FnOnce() -> NTSTATUS>(f: F) -> NTSTATUS {\n    \
            ntkrnl_sys::seh::try_except_all(f).unwrap_or_else(|c| c)\n}\n";
        let body = "pub unsafe extern \"system\" fn IoLockIt(Mdl: PMDL) -> NTSTATUS {\n    \
            or_fault(|| { MmProbeAndLockPages(Mdl, 1, 0); 0 })\n}\n";
        assert!(run(C, &format!("{helper}{body}")).is_empty());
        let nested = helper.replace("<F: FnOnce() -> NTSTATUS>", "<F: FnOnce() -> Option<NTSTATUS>>");
        assert!(run(C, &format!("{nested}{body}")).is_empty(), "one level of nesting");
    }

    #[test]
    fn a_catch_in_a_same_file_helper_counts() {
        let helper = "unsafe fn lock_caught(Mdl: PMDL) -> Result<(), NTSTATUS> {\n    \
            ntkrnl_sys::seh::try_except(&mut (), |_| MmProbeAndLockPages(Mdl, 1, 0), |_, _| 1)\n}\n\
            pub unsafe extern \"system\" fn IoLockIt(Mdl: PMDL) -> NTSTATUS {\n    \
            match lock_caught(Mdl) { Ok(()) => 0, Err(s) => s }\n}\n";
        assert!(run(C, helper).is_empty());
        let probe_only = "pub unsafe extern \"system\" fn IoLockIt(Mdl: PMDL) -> NTSTATUS {\n    \
            probe_user_buffer_write(Mdl, 4, 4, 1).ok();\n    MmProbeAndLockPages(Mdl, 1, 0);\n    0\n}\n";
        assert_eq!(run(C, probe_only).len(), 1, "a probe does not catch a raise");
    }

    #[test]
    fn try_except_all_is_a_real_catch() {
        let rs = "pub unsafe extern \"system\" fn IoLockIt(Mdl: PMDL) -> NTSTATUS {\n    \
            match ntkrnl_sys::seh::try_except_all(|| MmProbeAndLockPages(Mdl, 1, 0)) {\n        \
            Ok(()) => 0,\n        Err(s) => s,\n    }\n}\n";
        assert!(run(C, rs).is_empty());
    }

    #[test]
    fn a_catch_in_another_file_of_the_same_crate_counts() {
        let corpus = |helper_path: &str| {
            Corpus::new(
                PathBuf::from("."),
                vec![
                    crate::SourceFile::new("ntoskrnl/io/iomgr/irp.c".into(), C.into()),
                    crate::SourceFile::new(
                        "sdk/lib/rust/iomgr-rust/src/irp.rs".into(),
                        "pub unsafe extern \"system\" fn IoLockIt(Mdl: PMDL) -> NTSTATUS {\n    \
                         lock_caught(Mdl)\n}\n"
                            .into(),
                    ),
                    crate::SourceFile::new(
                        helper_path.into(),
                        "pub unsafe fn lock_caught(Mdl: PMDL) -> NTSTATUS {\n    \
                         ntkrnl_sys::seh::try_except_all(|| MmProbeAndLockPages(Mdl, 1, 0)).err().unwrap_or(0)\n}\n"
                            .into(),
                    ),
                ],
            )
        };
        let same = corpus("sdk/lib/rust/iomgr-rust/src/shims.rs");
        assert!(DeadSehHandlers.run(&same).unwrap().is_empty());
        let other = corpus("sdk/lib/rust/ob-rust/src/shims.rs");
        assert_eq!(DeadSehHandlers.run(&other).unwrap().len(), 1, "another crate's helper is not ours");
    }

    #[test]
    fn a_commented_out_c_handler_is_not_a_handler() {
        let c = "NTSTATUS NTAPI IoLockIt(PMDL Mdl)\n{\n    /* _SEH2_EXCEPT(1) { } */\n    \
            return 0;\n}\n";
        let rs = "pub unsafe extern \"system\" fn IoLockIt(Mdl: PMDL) -> NTSTATUS { 0 }\n";
        assert!(run(c, rs).is_empty());
    }
}
