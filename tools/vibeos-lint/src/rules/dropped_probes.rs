//! Compare executable Rust user-buffer validation against commented C.
use crate::{Corpus, Rule, SourceFile};
use regex::Regex;
use std::{collections::HashMap, sync::LazyLock};
use tree_sitter::Node;
pub struct DroppedProbes;
impl Rule for DroppedProbes {
    fn name(&self) -> &'static str {
        "scan_dropped_probes"
    }
    fn run(&self, c: &Corpus) -> Result<Vec<String>, String> {
        let mut out = Vec::new();
        for f in c.rust_files() {
            for (_, n, k, _) in scan_file(f)? {
                out.push(format!("{}: {n} [{k}]", f.path.display()));
            }
        }
        out.sort();
        Ok(out)
    }
}
const ALTS: &str = r"[A-Za-z0-9_]*ProbeFor[A-Za-z0-9_]*|[A-Za-z0-9_]*ProbeAndCapture[A-Za-z0-9_]*|[A-Za-z0-9_]*ProbeAndLock[A-Za-z0-9_]*|ProbeArrayFor[A-Za-z0-9_]*|ProbeAndZeroHandle|probe_user_buffer_write|probe_user_buffer|probe_read_user|probe_write_user|probe_read_ulong|probe_write_ulong|probe_write_handle|probe_write_boolean|probe_write_size_t|probe_read_generic|probe_write_generic|probe_capture_unicode_string_header|write_user_nofail|write_user|safe_copy_from_user|safe_copy_to_user|safe_copy_raw|mm_user_probe_address|probe_for_read|probe_for_write|copy_from_user|copy_to_user|capture_user|probe_and_capture_unicode_string|probe_or_done!";
static PROBE: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(&format!(r"(?:{ALTS})\s*(?:::\s*<[^;{{}}()]*>\s*)?[({{]")).unwrap()
});
static NOT: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(
        r"(?:BasepProbeForDllManifest|LdrpManifestProberRoutine|LdrSetDllManifestProber)\s*\(",
    )
    .unwrap()
});
static WRITE: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"ProbeForWrite[A-Za-z0-9_]*\s*\(").unwrap());
static RANGE: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"probe_user_buffer\s*\(").unwrap());
static LIVE_WRITE: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"(?:probe_user_buffer_write|probe_write_[a-z_]+|write_user(?:_nofail)?|safe_copy_to_user|ProbeForWrite[A-Za-z0-9_]*|probe_for_write|copy_to_user)\s*(?:::\s*<[^;{}()]*>\s*)?\(").unwrap()
});
static ID: LazyLock<Regex> = LazyLock::new(|| crate::regexes::cached(r"[A-Za-z_]\w*").unwrap());
static NOLINT: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"(?i)\bnolint\b\s*[:(\[]?\s*([a-z0-9_-]*)").unwrap());
static SKIP: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"(bindgen_[a-z0-9_]+\.rs$|/\.responses/)").unwrap());
static GENERATED: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"automatically generated by rust-bindgen|@generated").unwrap()
});
static PREFILTER: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"Probe(?:For|And|Array)").unwrap());
static AS_CAST: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"(?s)\bas\b.*$").unwrap());
const NO_KEY: &[&str] = &[
    "as",
    "const",
    "mut",
    "core",
    "ffi",
    "c_void",
    "ptr",
    "addr_of",
    "addr_of_mut",
    "size_of",
    "mem",
    "sizeof",
    "PVOID",
    "PCHAR",
    "PUCHAR",
    "ULONG",
    "ULONG_PTR",
    "_",
];
fn walk<'a>(n: Node<'a>, v: &mut Vec<Node<'a>>) {
    v.extend(crate::syntax::preorder(n));
}
fn boundary(s: &str, at: usize) -> bool {
    at == 0
        || !s[..at]
            .chars()
            .next_back()
            .is_some_and(|c| c.is_ascii_alphanumeric() || c == '_')
}
fn valid_calls<'a>(s: &'a str, re: &Regex) -> Vec<regex::Match<'a>> {
    re.find_iter(s).filter(|m| boundary(s, m.start())).collect()
}
fn count(s: &str) -> usize {
    valid_calls(s, &PROBE)
        .iter()
        .filter(|m| !NOT.is_match(&s[m.start()..]))
        .count()
}
fn first_arg(s: &str, start: usize) -> &str {
    let mut d = 0;
    let b = s.as_bytes();
    let mut j = start;
    while j < b.len() {
        match b[j] {
            b'(' | b'[' | b'{' => d += 1,
            b')' | b']' | b'}' => {
                if d == 0 {
                    break;
                }
                d -= 1
            }
            b',' if d == 0 => break,
            _ => (),
        }
        j += 1
    }
    &s[start..j]
}
fn key(a: &str) -> Option<String> {
    let stripped = AS_CAST.replace(a, "");
    ID.find_iter(&stripped)
        .map(|x| x.as_str())
        .filter(|x| !NO_KEY.contains(x))
        .last()
        .map(str::to_owned)
}
fn keys(s: &str, re: &Regex) -> std::collections::HashSet<String> {
    let mut out = std::collections::HashSet::new();
    for m in valid_calls(s, re) {
        if let Some(k) = key(first_arg(s, m.end())) {
            out.insert(k);
        }
    }
    out
}
fn suppressed(s: &str) -> bool {
    NOLINT.captures_iter(s).any(|m| {
        matches!(
            m[1].to_ascii_lowercase().as_str(),
            "" | "all" | "dropped-probe" | "dropped_probe" | "scan_dropped_probes"
        )
    })
}
fn base(name: &str) -> Vec<String> {
    let mut v = vec![name.to_owned()];
    for s in [
        "_impl", "_body", "_inner", "_core", "_helper", "_worker", "Impl", "Body", "Inner", "Core",
        "Helper", "Worker",
    ] {
        if name.ends_with(s) && name.len() > s.len() {
            v.push(name[..name.len() - s.len()].into())
        }
    }
    v
}
fn scan_file(f: &SourceFile) -> Result<Vec<(String, String, String, String)>, String> {
    let path = f.path.to_string_lossy().into_owned();
    if f.path.components().any(|p| p.as_os_str() == "target")
        || SKIP.is_match(&path)
        || !PREFILTER.is_match(&f.text)
    {
        return Ok(vec![]);
    }
    if GENERATED.is_match(&f.text.chars().take(4096).collect::<String>()) {
        return Ok(vec![]);
    }
    let tree = f.rust_tree()?;
    let (live, craw) = crate::rules::dropped_prints::regions(&f.text, &tree);
    let cfuncs = crate::rules::dropped_prints::c_function_bodies(&craw);
    let mut cf = HashMap::<String, usize>::new();
    let mut cw = HashMap::<String, std::collections::HashSet<String>>::new();
    for (n, b) in cfuncs {
        *cf.entry(n.clone()).or_default() += count(&b);
        cw.entry(n).or_default().extend(keys(&b, &WRITE));
    }
    if !cf.values().any(|x| *x > 0) {
        return Ok(vec![]);
    }
    let mut nodes = Vec::new();
    walk(tree.root_node(), &mut nodes);
    let mut rf = HashMap::<String, (usize, usize, usize, String)>::new();
    for node in nodes.iter().filter(|n| n.kind() == "function_item") {
        let (Some(name), Some(body)) = (
            node.child_by_field_name("name"),
            node.child_by_field_name("body"),
        ) else {
            continue;
        };
        let nm = std::str::from_utf8(&f.text.as_bytes()[name.start_byte()..name.end_byte()])
            .unwrap_or("");
        let text = live[body.start_byte()..body.end_byte()].to_owned();
        let n = count(&text);
        for key in base(nm) {
            if let Some(x) = rf.get_mut(&key) {
                x.0 += n;
                x.1 = x.1.min(node.start_byte());
                x.2 = x.2.max(body.end_byte());
                x.3.push_str(&text)
            } else {
                rf.insert(key, (n, node.start_byte(), body.end_byte(), text.clone()));
            }
        }
    }
    let mut out = Vec::new();
    for (cn_name, cn) in &cf {
        if *cn == 0 {
            continue;
        }
        let rn = if rf.contains_key(cn_name) {
            cn_name.clone()
        } else {
            let cr: Vec<_> = rf
                .keys()
                .filter(|x| x.eq_ignore_ascii_case(cn_name))
                .collect();
            let cc = cf
                .keys()
                .filter(|x| x.eq_ignore_ascii_case(cn_name))
                .count();
            if cr.len() != 1 || cc != 1 {
                continue;
            }
            cr[0].clone()
        };
        let (rn_count, decl, end, body) = &rf[&rn];
        if suppressed(&f.text[decl.saturating_sub(240)..*end]) {
            continue;
        }
        if rn_count < cn {
            out.push((
                path.clone(),
                cn_name.clone(),
                if *rn_count == 0 { "ALL" } else { "PARTIAL" }.into(),
                format!("C validates {cn}x, live {rn_count}x"),
            ));
        }
        let range_keys = keys(body, &RANGE);
        let live_write_keys = keys(body, &LIVE_WRITE);
        let weak: Vec<_> = cw
            .get(cn_name)
            .map(|x| {
                x.intersection(&range_keys)
                    .filter(|k| !live_write_keys.contains(*k))
                    .cloned()
                    .collect()
            })
            .unwrap_or_default();
        if !weak.is_empty() {
            let mut weak = weak;
            weak.sort();
            out.push((
                path.clone(),
                cn_name.clone(),
                "WEAK".into(),
                format!("C write-probes, live range-checks: {}", weak.join(", ")),
            ));
        }
    }
    out.sort();
    Ok(out)
}
