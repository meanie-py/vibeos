//! Hand-written bitfield unit calls that bypass named bindgen accessors.
use crate::{Corpus, Rule};
use regex::Regex;
use std::sync::LazyLock;
pub struct RawBitfield;
impl Rule for RawBitfield {
    fn name(&self) -> &'static str {
        "scan_raw_bitfield"
    }
    fn run(&self, corpus: &Corpus) -> Result<Vec<String>, String> {
        let mut out = Vec::new();
        for file in corpus.rust_files() {
            if SKIP.is_match(&file.path.to_string_lossy()) {
                continue;
            }
            for line in scan_text(&file.text) {
                out.push(format!("{}:{line}: raw-bitfield", file.path.display()));
            }
        }
        Ok(out)
    }
}
static SKIP: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"(/target/|/\.responses/)").unwrap());
static NOLINT: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"//\s*nolint(?::\s*raw-bitfield\b|\s*$|:?\s*\()").unwrap());
static RAW: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"\b_bitfield_\d+\s*\.\s*(?:set|get|raw_set|raw_get|set_bit|get_bit)\s*\(").unwrap()
});
static STRING: LazyLock<Regex> = LazyLock::new(|| Regex::new(r#"b?"(?:\\.|[^"\\])*""#).unwrap());
static WORD: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"^\w$").unwrap());
fn scan_text(text: &str) -> Vec<usize> {
    let first = text.split('\n').take(6).collect::<Vec<_>>().join("\n");
    if [
        "automatically generated by rust-bindgen",
        "@generated",
        "Do not edit manually",
    ]
    .iter()
    .any(|m| first.contains(m))
    {
        return Vec::new();
    }
    let mut out = Vec::new();
    for (i, line) in text.split('\n').enumerate() {
        let code = STRING.replace_all(line.split("//").next().unwrap(), "\"\"");
        if NOLINT.is_match(line) {
            continue;
        }
        let hit = RAW.find_iter(&code).any(|m| {
            let prefix = &code[..m.start()];
            if !prefix.ends_with("self.") {
                return true;
            }
            let prior = prefix[..prefix.len() - 5].chars().next_back();
            prior.is_some_and(|c| {
                let mut bytes = [0; 4];
                WORD.is_match(c.encode_utf8(&mut bytes))
            })
        });
        if hit {
            out.push(i + 1);
        }
    }
    out
}
#[cfg(test)]
mod tests {
    use super::*;
    const SOURCE: &str = r#"
unsafe fn f(p: *mut S) {
    (*p)._bitfield_1.set(0, 28, 28);             // finding: a guess at the layout
    if s.u.Flags._bitfield_1.get(0, 1) != 0 {}   // finding
    (*p).set_PageCode(0x1C);                     // right: the named accessor
    // (*p)._bitfield_1.set(0, 1, 1);            right: a comment
    let t = "_bitfield_1.set(0, 1, 1)";          // right: a string
    x._bitfield_2.set(0, 4, 1); // nolint: raw-bitfield (test)
}
impl S {
    pub fn set_Valid(&mut self, val: u8) { self._bitfield_1.set(7usize, 1u8, val as u64) }
}
"#;
    #[test]
    fn dedicated_fixtures() {
        assert_eq!(scan_text(SOURCE), vec![3, 4]);
        assert!(scan_text(&format!(
            "/* automatically generated by rust-bindgen */\n{SOURCE}"
        ))
        .is_empty());
    }
    #[test]
    fn scanner_control_and_self_guard() {
        assert_eq!(scan_text("unsafe fn page(p: *mut MODE_INFO_EXCEPTIONS) {\n    (*p)._bitfield_1.set(0, 0x1C, 0x1C);\n}\n"), vec![2]);
        assert!(scan_text(
            "unsafe fn page(p: *mut MODE_INFO_EXCEPTIONS) {\n    (*p).set_PageCode(0x1C);\n}\n"
        )
        .is_empty());
        assert_eq!(
            scan_text("myself._bitfield_1.get(0,1);\nself._bitfield_1.get(0,1);"),
            vec![1]
        );
    }
}
