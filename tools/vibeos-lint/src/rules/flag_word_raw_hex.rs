//! A win32k/user32 flag word masked with a raw hex literal.
//!
//! These fields hold bit sets that the C only ever touches through named
//! constants (DIRTY_*/DC_*, DCX_*, WNDS_*, WS_*, CURSORF_*, CSF_*). A raw hex
//! literal beside one is a number the translation recalled instead of copying,
//! and verify_constants cannot see it because no name was ever written.
//! DC_vPrepareDCsForBlit shipped `ulDirty_ & 0x00000008` for DIRTY_TEXT (0x4),
//! so a DC with a dirty background re-realized its text brush on every blit and
//! SetPixel painted black; fillshap and DIRTY_DEFAULT had the same invention.
use crate::{Corpus, Rule};
use regex::Regex;

pub struct FlagWordRawHex;

/// Fields whose every C use names its bits. A bare `flags` is deliberately
/// absent: too many unrelated structs share the name.
const FIELDS: &[&str] = &[
    "ulDirty_",
    "DCXFlags",
    "state",
    "state2",
    "style",
    "ExStyle",
    "CURSORF_flags",
    "CSF_flags",
];

struct Patterns {
    nolint: Regex,
    access: Regex,
    hex: Regex,
}

impl Patterns {
    fn new() -> Self {
        let re = |s: &str| Regex::new(s).expect("valid flag-word-raw-hex regex");
        let fields = FIELDS.join("|");
        Self {
            nolint: re(r"//\s*nolint(?::\s*flag-word-raw-hex\b|\s*$|:?\s*\()"),
            // `.field` (optionally closed by `)`) followed by a bit operator.
            access: re(&format!(r"\.(?:{fields})\b\)?\s*(?:&=|\|=|\^=|&[^&]|\|[^|])")),
            hex: re(r"\b0[xX][0-9a-fA-F]+"),
        }
    }
}

fn scan_line(line: &str, p: &Patterns) -> bool {
    let code = line.split("//").next().unwrap_or("");
    let Some(m) = p.access.find(code) else {
        return false;
    };
    // The mask operand runs until the comparison or logical operator that
    // consumes it, or the end of the statement: `x.style & WS_CHILD != 0 &&
    // y == 0x10` compares y, it does not mask style.
    let rest = &code[m.end() - 1..];
    let end = ["&&", "||", "==", "!=", "{", ";"]
        .iter()
        .filter_map(|t| rest.find(t))
        .min()
        .unwrap_or(rest.len());
    p.hex.is_match(&rest[..end])
}

fn scan(text: &str, p: &Patterns) -> Vec<usize> {
    let prefix = text.split('\n').take(6).collect::<Vec<_>>().join("\n");
    if ["automatically generated by rust-bindgen", "@generated"]
        .iter()
        .any(|s| prefix.contains(s))
    {
        return Vec::new();
    }
    let mut out = Vec::new();
    for (i, line) in text.split('\n').enumerate() {
        let t = line.trim_start();
        if t.starts_with("//") || t.starts_with('*') || p.nolint.is_match(line) {
            continue;
        }
        if scan_line(line, p) {
            out.push(i + 1);
        }
    }
    out
}

impl Rule for FlagWordRawHex {
    fn name(&self) -> &'static str {
        "scan_flag_word_raw_hex"
    }
    fn run(&self, corpus: &Corpus) -> Result<Vec<String>, String> {
        let p = Patterns::new();
        let mut files: Vec<_> = corpus.rust_files().collect();
        files.sort_by(|a, b| a.path.cmp(&b.path));
        let mut out = Vec::new();
        for f in files {
            for line in scan(&f.text, &p) {
                out.push(format!(
                    "{}:{line}: flag-word-raw-hex: name the C's constant instead of a literal",
                    f.path.display()
                ));
            }
        }
        Ok(out)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_shipped_inventions() {
        let p = Patterns::new();
        for line in [
            "    if (*(*pdcDest).pdcattr).ulDirty_ & 0x00000008 != 0 {",
            "    if (*(*pdcDest).pdcattr).ulDirty_ & (0x00000020 | 0x00000002) != 0 {",
            "    if (*(*dc).pdcattr).ulDirty_ & (0x00000004 | 0x00020000) != 0 {",
            "    (*(*pdc).pdcattr).ulDirty_ |= 0x00010000 | 0x00000004 | 0x00000008;",
            "    (*Wnd).state2 &= !0x20000000;",
            "    if (*pWnd).ExStyle & (WS_EX_TOOLWINDOW | 0x100) != 0 {",
        ] {
            assert!(scan_line(line, &p), "{line}");
        }
    }

    #[test]
    fn named_constants_and_unrelated_code() {
        let p = Patterns::new();
        for line in [
            "    if (*(*pdcDest).pdcattr).ulDirty_ & DIRTY_TEXT != 0 {",
            "    (*(*pdc).pdcattr).ulDirty_ |= DIRTY_DEFAULT;",
            "    (*Wnd).style &= !WS_VISIBLE;",
            "    if (*pWnd).style & WS_CHILD != 0 && x == 0x10 {",
            "    let flags = obj.flags & 0xff;",
            "    if a.state && b == 0x1 {",
            "    let style = 0x10; // style |= 0x20",
            "    x.styles & 0x1",
        ] {
            assert!(!scan_line(line, &p), "{line}");
        }
    }

    #[test]
    fn comments_generated_and_suppressed() {
        let p = Patterns::new();
        assert!(scan("// x.style & 0x10\n * x.style & 0x10", &p).is_empty());
        assert!(scan("// @generated\nx.style & 0x10;", &p).is_empty());
        assert!(scan("x.style & 0x10; // nolint: flag-word-raw-hex reason", &p).is_empty());
        assert_eq!(scan("\nx.style & 0x10;", &p), vec![2]);
    }
}
