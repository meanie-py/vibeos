//! Compare executable Rust diagnostics with the original C kept in Rust comments.
use crate::{Corpus, Rule, SourceFile};
use regex::Regex;
use std::{collections::HashMap, sync::LazyLock};
use tree_sitter::Node;

pub struct DroppedPrints;
impl Rule for DroppedPrints {
    fn name(&self) -> &'static str {
        "scan_dropped_prints"
    }
    fn run(&self, c: &Corpus) -> Result<Vec<String>, String> {
        let mut out = Vec::new();
        for f in c.rust_files() {
            for (_, n, k, _) in print_facts(f)? {
                out.push(format!("{}: {n} [{k}]", f.path.display()));
            }
        }
        out.sort();
        Ok(out)
    }
}
const ALWAYS: &[&str] = &[
    "DPRINT1",
    "DbgPrintEx",
    "vDbgPrintEx",
    "DbgPrint",
    "ERR",
    "FIXME",
];
const IMPL: &[&str] = &[
    "_impl", "_body", "_inner", "_core", "_helper", "_worker", "Impl", "Body", "Inner", "Core",
    "Helper", "Worker",
];
const LIVE_NAMES: &[&str] = &[
    "dbg_print",
    "dbg_print_ex",
    "debug_print",
    "dbgprint",
    "dprintf",
    "err",
    "trace",
    "error",
    "errors",
    "warn",
    "info",
    "fixme",
    "println",
    "eprintln",
];
const NOT_PRINT: &[&str] = &["noop", "sprint", "printf", "format", "_str", "str_"];
static C_PRINT: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"(DPRINT1|DbgPrintEx|vDbgPrintEx|DbgPrint|ERR|FIXME)\s*\(").unwrap()
});
static LIVE_FN: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"(DPRINT1|DbgPrintEx|vDbgPrintEx|DbgPrint|ERR|FIXME|DbgPrintSz)\s*\(")
        .unwrap()
});
static MACRO: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"([A-Za-z_][A-Za-z0-9_]*)\s*!").unwrap());
static DECL: LazyLock<Regex> = LazyLock::new(|| crate::regexes::cached(r"\bfn\s+$").unwrap());
static SILENT: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"^[\s(){}\[\];,]*$").unwrap());
static NOLINT: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"(?i)\bnolint\b\s*[:(\[]?\s*([a-z0-9_-]*)").unwrap());
static C_SIG_NAME: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"([A-Za-z_][A-Za-z0-9_]*)\s*\(").unwrap());
static C_SIG_REJECT: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r#"^\s*(typedef|struct|enum|union|extern\s*"C")\b"#).unwrap()
});
static SKIP_FILE: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"(bindgen_[a-z0-9_]+\.rs$|/target/|/\.responses/)").unwrap()
});
static GENERATED: LazyLock<Regex> = LazyLock::new(|| {
    crate::regexes::cached(r"automatically generated by rust-bindgen|@generated").unwrap()
});
static PREFILTER: LazyLock<Regex> =
    LazyLock::new(|| crate::regexes::cached(r"(DPRINT1|DbgPrint|ERR|FIXME)\s*[({!]").unwrap());
fn walk<'a>(node: Node<'a>, out: &mut Vec<Node<'a>>) {
    out.push(node);
    let mut c = node.walk();
    for ch in node.children(&mut c) {
        walk(ch, out)
    }
}
pub(super) fn regions(text: &str, tree: &tree_sitter::Tree) -> (String, String) {
    let src = text.as_bytes();
    let mut live = src.to_vec();
    let mut c = vec![b' '; src.len()];
    for (i, b) in src.iter().enumerate() {
        if *b == b'\n' {
            c[i] = b'\n'
        }
    }
    let mut nodes = Vec::new();
    walk(tree.root_node(), &mut nodes);
    for n in nodes
        .into_iter()
        .filter(|n| n.kind() == "line_comment" || n.kind() == "block_comment")
    {
        let (s, e) = (n.start_byte(), n.end_byte());
        for i in s..e {
            if src[i] != b'\n' {
                live[i] = b' '
            }
        }
        c[s..e].copy_from_slice(&src[s..e]);
        for i in s..(s + 2).min(e) {
            c[i] = b' '
        }
        if &src[s..(s + 2).min(e)] == b"/*" {
            for i in e.saturating_sub(2).max(s)..e {
                c[i] = b' '
            }
        }
    }
    (
        String::from_utf8(live).unwrap(),
        String::from_utf8(c).unwrap(),
    )
}
fn silent_macro(node: Node<'_>, src: &[u8]) -> bool {
    let mut arms = Vec::new();
    let mut cursor = node.walk();
    for ch in node.children(&mut cursor) {
        if ch.kind() == "macro_rule" {
            arms.push(ch)
        }
    }
    if arms.is_empty() {
        return false;
    }
    for arm in arms {
        let mut c = arm.walk();
        let trees: Vec<_> = arm
            .children(&mut c)
            .filter(|n| n.kind() == "token_tree")
            .collect();
        let Some(rhs) = trees.last() else {
            return false;
        };
        if !SILENT
            .is_match(std::str::from_utf8(&src[rhs.start_byte()..rhs.end_byte()]).unwrap_or(""))
        {
            return false;
        }
    }
    true
}
fn base_names(n: &str) -> Vec<String> {
    let mut x = vec![n.to_owned()];
    for suf in IMPL {
        if n.ends_with(suf) && n.len() > suf.len() {
            x.push(n[..n.len() - suf.len()].into())
        }
    }
    x
}
fn suppressed(s: &str) -> bool {
    NOLINT.captures_iter(s).any(|c| {
        matches!(
            c.get(1).unwrap().as_str().to_ascii_lowercase().as_str(),
            "" | "all" | "dropped-print" | "dropped_print" | "scan_dropped_prints"
        )
    })
}
fn char_window_start(s: &str, at: usize, count: usize) -> usize {
    s[..at]
        .char_indices()
        .rev()
        .nth(count.saturating_sub(1))
        .map_or(0, |(i, _)| i)
}
fn c_name(sig: &str) -> Option<String> {
    let mut lines: Vec<_> = sig.lines().collect();
    while lines.last().is_some_and(|x| x.trim().is_empty()) {
        lines.pop();
    }
    let mut rev = Vec::new();
    for line in lines.into_iter().rev() {
        if line.trim().is_empty() {
            break;
        }
        rev.push(line)
    }
    rev.reverse();
    let s = rev.join(" ").trim().to_owned();
    if s.is_empty() || s.ends_with(['=', ',']) || C_SIG_REJECT.is_match(&s) {
        return None;
    }
    let mut found = None;
    for m in C_SIG_NAME.find_iter(&s) {
        let before = &s[..m.start()];
        let depth = before.matches('(').count() as isize - before.matches(')').count() as isize;
        if depth == 0 {
            if let Some(c) = C_SIG_NAME.captures(m.as_str()) {
                found = Some(c[1].to_owned())
            }
        }
    }
    found
}
fn count_cprints(s: &str) -> usize {
    C_PRINT
        .captures_iter(s)
        .filter(|c| {
            let at = c.get(0).unwrap().start();
            !s[..at]
                .chars()
                .next_back()
                .is_some_and(|x| x.is_ascii_alphanumeric() || x == '_')
        })
        .count()
}
pub(super) fn blank_c_noise(text: &str) -> String {
    let mut out = text.as_bytes().to_vec();
    let b = text.as_bytes();
    let (mut i, n) = (0usize, b.len());
    while i < n {
        let c = b[i];
        let next = if i + 1 < n { b[i + 1] } else { 0 };
        if c == b'/' && next == b'/' {
            let mut j = i;
            while j < n && b[j] != b'\n' {
                out[j] = b' ';
                j += 1
            }
            i = j;
        } else if c == b'/' && next == b'*' {
            let mut j = i + 2;
            while j + 1 < n && !(b[j] == b'*' && b[j + 1] == b'/') {
                j += 1
            }
            let end = if j + 1 < n { j + 2 } else { n };
            for k in i..end {
                if b[k] != b'\n' {
                    out[k] = b' '
                }
            }
            i = end;
        } else if c == b'"' || c == b'\'' {
            let mut j = i + 1;
            while j < n && b[j] != c && b[j] != b'\n' {
                if b[j] == b'\\' {
                    j = (j + 2).min(n)
                } else {
                    j += 1
                }
            }
            for k in i + 1..j.min(n) {
                out[k] = b' '
            }
            i = if j < n && b[j] == c { j + 1 } else { j };
        } else {
            i += 1
        }
    }
    String::from_utf8(out).expect("C masking preserves UTF-8")
}
pub(super) fn c_function_bodies(c: &str) -> Vec<(String, String)> {
    let clean = blank_c_noise(c);
    let mut out = Vec::new();
    let mut depth = 0isize;
    let mut seg = 0usize;
    let mut start = None;
    for (i, ch) in clean.char_indices() {
        if ch == '{' {
            if depth == 0 {
                start = Some(i)
            }
            depth += 1
        } else if ch == '}' {
            depth -= 1;
            if depth == 0 {
                if let Some(st) = start {
                    if let Some(name) = c_name(&clean[seg..st]) {
                        out.push((name, clean[st + 1..i].to_owned()))
                    }
                }
                start = None;
                seg = i + 1
            } else if depth < 0 {
                depth = 0
            }
        } else if ch == ';' && depth == 0 {
            seg = i + 1
        }
    }
    out
}
fn c_functions(c: &str) -> HashMap<String, usize> {
    let mut out = HashMap::new();
    for (name, body) in c_function_bodies(c) {
        *out.entry(name).or_insert(0) += count_cprints(&body)
    }
    out
}
fn live_prints(s: &str, noop: &[String]) -> usize {
    let mut n = 0;
    for m in LIVE_FN.captures_iter(s) {
        let mat = m.get(0).unwrap();
        let name = &m[1];
        if mat.start() > 0
            && s[..mat.start()]
                .chars()
                .next_back()
                .is_some_and(|x| x.is_ascii_alphanumeric() || x == '_')
        {
            continue;
        }
        let tail = s[..mat.start()].chars().rev().take(8).collect::<String>();
        if noop.iter().any(|x| x == name) || DECL.is_match(&tail.chars().rev().collect::<String>())
        {
            continue;
        }
        n += 1
    }
    for m in MACRO.captures_iter(s) {
        let mat = m.get(0).unwrap();
        if mat.start() > 0
            && s[..mat.start()]
                .chars()
                .next_back()
                .is_some_and(|x| x.is_ascii_alphanumeric() || x == '_')
        {
            continue;
        }
        let name = m[1].to_ascii_lowercase();
        if LIVE_NAMES.contains(&name.as_str())
            || name.contains("print") && !NOT_PRINT.iter().any(|x| name.contains(x))
        {
            n += 1
        }
    }
    n
}
fn print_facts(f: &SourceFile) -> Result<Vec<(String, String, String, String)>, String> {
    let p = f.path.to_string_lossy();
    if p.split('/').any(|part| part == "target") || SKIP_FILE.is_match(&p) {
        return Ok(vec![]);
    }
    if GENERATED.is_match(&f.text.chars().take(4096).collect::<String>())
        || !PREFILTER.is_match(&f.text)
    {
        return Ok(vec![]);
    }
    let tree = f.rust_tree()?;
    let (src, c) = regions(&f.text, tree);
    let nodes = {
        let mut v = Vec::new();
        walk(tree.root_node(), &mut v);
        v
    };
    let bytes = f.text.as_bytes();
    let mut funcs = HashMap::<String, (usize, usize, usize)>::new();
    let mut noop = Vec::new();
    for n in &nodes {
        if n.kind() == "function_item" {
            let Some(name) = n.child_by_field_name("name") else {
                continue;
            };
            let Some(body) = n.child_by_field_name("body") else {
                continue;
            };
            let nm = std::str::from_utf8(&bytes[name.start_byte()..name.end_byte()])
                .unwrap()
                .to_owned();
            if ALWAYS.contains(&nm.as_str()) && body.named_child_count() == 0 {
                noop.push(nm.clone())
            }
        } else if n.kind() == "macro_definition" {
            let name = n
                .child_by_field_name("name")
                .map(|x| std::str::from_utf8(&bytes[x.start_byte()..x.end_byte()]).unwrap_or(""))
                .unwrap_or("");
            if ALWAYS.contains(&name) && silent_macro(*n, bytes) {
                noop.push(name.to_owned())
            }
        }
    }
    for n in &nodes {
        if n.kind() == "function_item" {
            let Some(name) = n.child_by_field_name("name") else {
                continue;
            };
            let Some(body) = n.child_by_field_name("body") else {
                continue;
            };
            let nm = std::str::from_utf8(&bytes[name.start_byte()..name.end_byte()])
                .unwrap()
                .to_owned();
            let count = live_prints(&src[body.start_byte()..body.end_byte()], &noop);
            for key in base_names(&nm) {
                let e = funcs
                    .entry(key)
                    .or_insert((0, n.start_byte(), body.end_byte()));
                e.0 += count;
                e.1 = e.1.min(n.start_byte());
                e.2 = e.2.max(body.end_byte());
            }
        }
    }
    noop.sort();
    noop.dedup();
    let mut out = Vec::new();
    for n in &noop {
        let spans = nodes
            .iter()
            .filter(|x| x.kind() == "function_item" || x.kind() == "macro_definition")
            .filter(|x| {
                x.child_by_field_name("name").is_some_and(|y| {
                    std::str::from_utf8(&bytes[y.start_byte()..y.end_byte()]).unwrap_or("") == n
                })
            });
        for x in spans {
            if !suppressed(&f.text[char_window_start(&f.text, x.start_byte(), 240)..x.end_byte()]) {
                out.push((
                    p.to_string(),
                    n.clone(),
                    "NOOP".into(),
                    "expands to nothing — the call site prints nothing".into(),
                ))
            }
        }
    }
    let cfuncs = c_functions(&c);
    if !cfuncs.values().any(|x| *x > 0) {
        return Ok(out);
    }
    let mut ci_r = HashMap::<String, Vec<String>>::new();
    for k in funcs.keys() {
        ci_r.entry(k.to_lowercase()).or_default().push(k.clone())
    }
    let mut ci_c = HashMap::<String, Vec<String>>::new();
    for k in cfuncs.keys() {
        ci_c.entry(k.to_lowercase()).or_default().push(k.clone())
    }
    let mut names: Vec<_> = cfuncs.keys().collect();
    names.sort();
    for cnm in names {
        let cn = cfuncs[cnm];
        if cn == 0 {
            continue;
        }
        let rn = if funcs.contains_key(cnm) {
            cnm.clone()
        } else {
            let cand = ci_r.get(&cnm.to_lowercase()).cloned().unwrap_or_default();
            if cand.len() != 1 || ci_c.get(&cnm.to_lowercase()).map_or(0, Vec::len) != 1 {
                continue;
            }
            cand[0].clone()
        };
        let (rc, decl, end) = funcs[&rn];
        if rc >= cn || suppressed(&f.text[char_window_start(&f.text, decl, 240)..end]) {
            continue;
        }
        out.push((
            p.to_string(),
            rn,
            if rc == 0 { "ALL" } else { "PARTIAL" }.into(),
            format!("C prints {cn}x, live {rc}x"),
        ))
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{Corpus, SourceFile};
    use std::path::PathBuf;
    fn c(s: &str) -> Corpus {
        Corpus::new(
            PathBuf::from("."),
            vec![SourceFile::new("sdk/lib/rust/t.rs".into(), s.into())],
        )
    }
    #[test]
    fn actual_c_comment_control_reports_all() {
        let x=c("pub unsafe extern \"system\" fn Foo() { return; }\n// VOID Foo()\n// {\n//  DbgPrint(\"x\");\n// }");
        assert!(DroppedPrints
            .run(&x)
            .unwrap()
            .iter()
            .any(|x| x == "sdk/lib/rust/t.rs: Foo [ALL]"));
    }
    #[test]
    fn no_print_is_quiet() {
        let x = c("pub fn Foo(){ work(); }\n// VOID Foo() { work(); }");
        assert!(DroppedPrints.run(&x).unwrap().is_empty());
    }
}

