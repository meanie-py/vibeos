use crate::{Corpus, Rule};
use regex::Regex;
pub struct BitwiseNotBool;
const KEYWORDS: &[&str] = &[
    "if", "while", "return", "match", "in", "else", "let", "break", "mut", "as", "move",
];
struct Patterns {
    nolint: Regex,
    string: Regex,
    word: Regex,
}
impl Patterns {
    fn new() -> Self {
        let re = |s| Regex::new(s).expect("valid bitwise-not-bool regex");
        Self {
            nolint: re(r"//\s*nolint(?::\s*bitwise-not-bool\b|\s*$|:?\s*\()"),
            string: re(r#"b?"(?:\\.|[^"\\])*""#),
            word: re(r"[A-Za-z0-9_]+$"),
        }
    }
}
fn starts_value(c: u8) -> bool {
    c.is_ascii_alphabetic() || b"_(*".contains(&c)
}
fn scan_line(line: &str, p: &Patterns) -> bool {
    let strings = p.string.replace_all(line, "\"\"");
    let bytes = strings.as_bytes();
    for i in 0..bytes.len().saturating_sub(2) {
        if bytes[i] == b'!'
            && bytes[i + 1] == b'!'
            && starts_value(bytes[i + 2])
            && (i == 0 || !(bytes[i - 1].is_ascii_alphanumeric() || b"_!".contains(&bytes[i - 1])))
        {
            return true;
        }
    }
    let bytes = line.as_bytes();
    for i in 0..bytes.len().saturating_sub(1) {
        if bytes[i] != b'!' || !starts_value(bytes[i + 1]) {
            continue;
        }
        let before = line[..i].trim_end();
        if let Some(word) = p.word.find(before) {
            if !KEYWORDS.contains(&word.as_str()) {
                continue;
            }
        }
        if (before.ends_with('&') || before.ends_with('|') || before.ends_with('^'))
            && !(before.ends_with("&&") || before.ends_with("||"))
        {
            continue;
        }
        let mut depth = 0isize;
        let mut j = i + 1;
        while j < bytes.len() {
            let c = bytes[j];
            if b"([{".contains(&c) {
                depth += 1;
            } else if b")]}".contains(&c) {
                depth -= 1;
                if depth < 0 {
                    break;
                }
            } else if depth == 0 && (bytes[j..].starts_with(b"!=") || bytes[j..].starts_with(b"=="))
            {
                let rest = line[j + 2..].trim_start();
                if rest.starts_with('0')
                    && !rest[1..].chars().next().is_some_and(|c| c.is_numeric())
                    && !rest
                        .as_bytes()
                        .get(1)
                        .is_some_and(|c| *c == b'x' || *c == b'X')
                {
                    return true;
                }
                break;
            } else if depth == 0
                && (c == b'&'
                    || c == b'|'
                    || bytes[j..].starts_with(b"<<")
                    || bytes[j..].starts_with(b">>"))
            {
                break;
            }
            j += 1;
        }
    }
    false
}
fn scan(text: &str, p: &Patterns) -> Vec<usize> {
    let prefix = text.split('\n').take(6).collect::<Vec<_>>().join("\n");
    if [
        "automatically generated by rust-bindgen",
        "@generated",
        "Do not edit manually",
    ]
    .iter()
    .any(|s| prefix.contains(s))
    {
        return Vec::new();
    }
    let mut out = Vec::new();
    for (i, line) in text.split('\n').enumerate() {
        let stripped = line.trim();
        if stripped.starts_with("//") || stripped.starts_with('*') || p.nolint.is_match(line) {
            continue;
        }
        if scan_line(line, p) {
            out.push(i + 1);
        }
    }
    out
}
impl Rule for BitwiseNotBool {
    fn name(&self) -> &'static str {
        "scan_bitwise_not_bool"
    }
    fn run(&self, corpus: &Corpus) -> Result<Vec<String>, String> {
        let p = Patterns::new();
        let mut files: Vec<_> = corpus.rust_files().collect();
        files.sort_by(|a, b| a.path.cmp(&b.path));
        let mut out = Vec::new();
        for f in files {
            for line in scan(&f.text, &p) {
                out.push(format!("{}:{line}: bitwise-not-bool", f.path.display()));
            }
        }
        Ok(out)
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn keyword_is_not_a_macro_name() {
        // usetup/powercfg: `if !success` was misread as the macro `if!`.
        let p = Patterns::new();
        assert!(scan_line("    if !success != 0 {", &p));
        assert!(!scan_line("    if success == 0 {", &p));
        assert!(!scan_line("    assert!(x != 0);", &p));
    }
    #[test]
    fn logical_not_comparisons_and_double_not() {
        let p = Patterns::new();
        for line in [
            "if !(flags & MASK) != 0 {",
            "while !Success == 0 {",
            "return !value != 0;",
            "if x && !flag != 0 {",
            "if !!value {",
            "let n = !!(a & b);",
        ] {
            assert!(scan_line(line, &p), "{line}");
        }
    }
    #[test]
    fn legitimate_masks_macros_and_other_comparisons() {
        let p = Patterns::new();
        for line in [
            "x & !MASK != 0",
            "x | !MASK != 0",
            "x ^ !MASK != 0",
            "offset_of!(T,f) == 0",
            "assert!(x) == 0",
            "if !x != 0x10 {",
            "if !x != 01 {",
            "if !x | y != 0 {",
            "\"!!value\"",
            "foo!!x",
            "!!!x",
        ] {
            assert!(!scan_line(line, &p), "{line}");
        }
    }
    #[test]
    fn comment_generated_and_suppressed_lines() {
        let p = Patterns::new();
        assert!(scan(
            "// !!value\n * !!value\nif !!value {} // nolint: bitwise-not-bool reason",
            &p
        )
        .is_empty());
        assert!(scan("// @generated\nif !!value {}", &p).is_empty());
        assert_eq!(scan("\nif !!value {}", &p), vec![2]);
    }
}
