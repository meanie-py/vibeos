#!/usr/bin/env python3
"""
scan_ptr_byte_diff.py — C's `p - q` on typed pointers counts ELEMENTS; the translation
subtracted ADDRESSES and counted bytes.

    C:            NameLength = SourcePtr - StartPtr;                     // WCHARs
    translated:   NameLength = (SourcePtr as isize - StartPtr as isize) as ULONG;   // bytes
    faithful:     NameLength = SourcePtr.offset_from(StartPtr) as ULONG;

On a `WCHAR *` the two differ by exactly 2x, and the result compiles, links and boots.
Found 2026-09-26 by `rustconv difftest-contract`, twice in one day and in two DLLs:

  * version.dll `VersionInfo32_QueryValue` — every sub-block key compared at twice its
    length, so no 32-bit child block was ever found;
  * kernel32 `BaseCreateVDMEnvironment` — GetShortPathNameW was told twice the room,
    the fallback copy moved 4x the name and DestPtr advanced 2x: an overrun.

Neither was visible to smoke. Both were found by grading, then the class was grepped.

WHY IT NEEDS THE C. Subtracting addresses is RIGHT whenever the C did it too —
`(ULONG_PTR)p - (ULONG_PTR)q`, `(PCHAR)p - (PCHAR)q`, or `(p - q) * sizeof(WCHAR)` for a
UNICODE_STRING byte length — and the tree is full of that (553 raw address subtractions;
kernel32 `move.c` even computes a WCHAR count and uses it as bytes, which the Rust now
deliberately corrects). A Rust-only rule cannot tell those apart. So:

  1. RUST: an `a as <int> - b as <int>` (or `.wrapping_sub`) whose operands BOTH resolve,
     from their declarations in the same function or file, to pointers whose element is
     wider than a byte (WCHAR / USHORT / ULONG and their P-typedefs), and whose result is
     not immediately divided or shifted back into elements. 23 sites on 2026-09-26.
  2. C: the function of the same name (tools/c_twin.py) is searched for the same two
     operand names. The C counted BYTES if it cast them to an integer or byte pointer, or
     scaled the difference by `sizeof`/`2`; otherwise it counted elements.
  3. Verdict. The Rust result is bytes; it is correct only when the C's is bytes too AND
     the Rust did not scale it again. So:
        ELEMENTS   the C counted elements          -> finding: `ptr-byte-diff`
        SCALED     the Rust scales bytes again     -> finding: `ptr-byte-diff`
        BYTES      the C counted bytes, as Rust    -> silent
        UNPAIRED   no C twin, or the C expression was not found -> finding:
                   `ptr-byte-diff-unpaired` — a review item, not a verdict.

Usage:
    python3 tools/scan_ptr_byte_diff.py            # report with the C evidence
    python3 tools/scan_ptr_byte_diff.py --lint     # terse (CLI baseline gate)
    python3 tools/scan_ptr_byte_diff.py PATH...    # restrict to files/dirs

Suppress a reviewed site with `// nolint: ptr-byte-diff` on the line.
Exit 1 if any finding.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tools.c_twin import CIndex, Func, blank_rust, enclosing, prefer, rust_functions
from tools.source_walk import source_files

REPO = Path(__file__).resolve().parent.parent
RUST_ROOT = REPO / "sdk" / "lib" / "rust"

SKIP_PATH_RE = re.compile(r"(/target/|/\.responses/)")
NOLINT_RE = re.compile(r"//\s*nolint(?::\s*ptr-byte-diff\b|\s*$)")
GEN_MARKERS = ("automatically generated by rust-bindgen", "@generated", "Do not edit manually")

_INT = (
    r"(?:usize|isize|u64|i64|u32|i32|ULONG_PTR|LONG_PTR|UINT_PTR|INT_PTR|DWORD_PTR|"
    r"SIZE_T|SSIZE_T|ULONG|LONG|DWORD|UINT)"
)
_OPND = r"(?P<{n}>[A-Za-z_][A-Za-z0-9_]*(?:\.(?:as_ptr|as_mut_ptr)\(\))?)"
# No leading `\(?\s*`: blanked comments are long runs of spaces, and a pattern that may
# start on whitespace rescans each run from every position (quadratic: 25 s for two files).
SUB_RE = re.compile(
    r"(?<![\w.])"
    + _OPND.format(n="a")
    + r"\s+as\s+"
    + _INT
    + r"\s*\)?\s*(?:-|\.wrapping_sub\(|\.checked_sub\()\s*(?P<bp>\()?\s*"
    + _OPND.format(n="b")
    + r"\s+as\s+"
    + _INT
    + r"\b(?P<bclose>\s*\))?"
)

# SUB_RE's shape anchored on its rarest literal. SUB_RE itself starts at every identifier and
# costs 4 s across the tree; files are rejected, and SUB_RE is confined, by this first.
PREFILTER_RE = re.compile(r" as " + _INT + r"\s*\)?\s*(?:-|\.wrapping_sub\(|\.checked_sub\()")

# Element types of one byte (or of no size, c_void — address arithmetic by definition).
BYTE_ELEM = {
    "u8",
    "i8",
    "c_char",
    "c_uchar",
    "c_schar",
    "CHAR",
    "UCHAR",
    "BYTE",
    "c_void",
    "VOID",
    "BOOLEAN",
}
BYTE_PTR = {
    "PVOID", "LPVOID", "PCVOID", "LPCVOID", "PSTR", "LPSTR", "PCSTR", "LPCSTR", "PCHAR",
    "PUCHAR", "PBYTE", "LPBYTE", "PCCH", "PCH", "PSZ", "PCSZ", "LPCH", "PBOOLEAN", "HANDLE",
    "PCUCHAR",
}  # fmt: skip
# Scalar elements wider than a byte: the ones whose difference someone reads as a COUNT.
WIDE_ELEM = {
    "u16", "i16", "WCHAR", "USHORT", "wchar_t", "c_ushort", "SHORT", "WORD", "u32", "i32",
    "ULONG", "LONG", "DWORD", "UINT", "INT", "c_ulong", "c_long", "c_int", "c_uint", "u64",
    "i64", "ULONGLONG", "LONGLONG",
}  # fmt: skip
WIDE_PTR = {
    "PWSTR", "LPWSTR", "PCWSTR", "LPCWSTR", "PWCHAR", "PWCH", "PCWCH", "LPWCH", "LPCWCH",
    "PUSHORT", "PWORD", "LPWORD", "PULONG", "PLONG", "PDWORD", "LPDWORD", "PUINT", "LPUINT",
    "PINT", "LPINT", "PULONGLONG", "PLONGLONG", "PWSZ", "PCWSZ", "PSHORT",
}  # fmt: skip


def _last(ty: str) -> str:
    return ty.strip().split("::")[-1].strip()


def classify(ty: str) -> str | None:
    """'byte' | 'wide' | 'other' for a pointer type spelling, None if not a pointer."""
    ty = ty.strip()
    m = re.match(r"\*\s*(?:mut|const)\s+(.+)$", ty)
    if m:
        inner = m.group(1).strip()
        if inner.startswith("*"):
            return "other"
        if _last(inner) in BYTE_ELEM:
            return "byte"
        if _last(inner) in WIDE_ELEM:
            return "wide"
        return "other"
    if _last(ty) in BYTE_PTR:
        return "byte"
    if _last(ty) in WIDE_PTR:
        return "wide"
    return None


def _decl(scope: str, name: str) -> str | None:
    """Type annotation of `name` in `scope` (last one wins: shadowing is later).

    A hand scan, not a regex: a lazy type pattern with a lookahead cost 1.5 s over the
    tree on the file-level fallback alone. The type runs to the first `,;={` or
    unbalanced `)` outside `<>`/`[]`/`()`."""
    found = None
    at = scope.find(name)
    n = len(name)
    while at >= 0:
        nxt = at + n
        if (at == 0 or not (scope[at - 1].isalnum() or scope[at - 1] in "_.")) and not (
            nxt < len(scope) and (scope[nxt].isalnum() or scope[nxt] == "_")
        ):
            j = nxt
            while j < len(scope) and scope[j] in " \t\n":
                j += 1
            if j < len(scope) and scope[j] == ":" and scope[j + 1 : j + 2] != ":":
                depth = 0
                k = j + 1
                while k < len(scope):
                    c = scope[k]
                    if c in "<[(":
                        depth += 1
                    elif c in ">])":
                        if depth == 0:
                            break
                        depth -= 1
                    elif c in ",;={" and depth == 0:
                        break
                    k += 1
                ty = scope[j + 1 : k].strip()
                if ty:
                    found = ty
        at = scope.find(name, nxt)
    return found


def operand_class(fn_scope: str, file_text: str, op: str) -> str | None:
    base = op.split(".")[0]
    ty = _decl(fn_scope, base) or _decl(file_text, base)
    if ty is None:
        return None
    if op.endswith("_ptr()"):
        m = re.match(r"\[\s*([^;\]]+?)\s*;", ty.strip())
        return classify("*mut " + m.group(1)) if m else None
    return classify(ty)


# The difference is turned back into elements (`/ size_of`, `/ 2`, `>> 1`) or scaled up
# (`* 2`, `* size_of`). Looked for immediately after the closing paren of the subtraction.
_AFTER_OP = re.compile(r"\s*(?:as\s+[\w:]+\s*)?(?:\)\s*(?:as\s+[\w:]+\s*)?)*(?P<op>/|>>|\*)")


def _close_of(text: str, at: int) -> int:
    """Index of the `)` closing the innermost group containing `at`, or `at`."""
    depth = 0
    for i in range(at, min(len(text), at + 300)):
        c = text[i]
        if c == "(":
            depth += 1
        elif c == ")":
            if depth == 0:
                return i + 1
            depth -= 1
        elif c in ";{}," and depth == 0:
            return i
    return at


def rust_scaling(text: str, m: re.Match[str]) -> str | None:
    # Before any `)` the match consumed, so the group it closes is the one measured.
    end = m.start("bclose") if m.group("bclose") else m.end()
    tail_at = _close_of(text, end)
    after = _AFTER_OP.match(text, tail_at) or _AFTER_OP.match(text, end)
    return after.group("op") if after else None


# C evidence. The C spelled the same two operand names; how did it subtract them?
def _c_cast(name: str) -> str:
    return r"\(\s*(?:const\s+)?[A-Za-z_][\w\s]*\**\s*\)\s*\(?\s*" + re.escape(name) + r"\b"


def c_verdict(twins: list[Func], a: str, b: str) -> tuple[str, str] | None:
    """('bytes'|'elements', evidence) from the first twin that subtracts a and b."""
    return _c_verdict(twins, a, b, 0) or _c_verdict(twins, a, b, re.I)


def _c_verdict(twins: list[Func], a: str, b: str, flags: int) -> tuple[str, str] | None:
    # Case-insensitive second pass: a C macro operand often comes back as a local,
    # `IDI_APPLICATION` -> `let idi_application`.
    ea, eb = re.escape(a), re.escape(b)
    cast_re = re.compile(_c_cast(a) + r"\s*\)?\s*-\s*" + _c_cast(b), flags)
    plain_re = re.compile(r"(?<![\w>.])" + ea + r"\s*-\s*" + eb + r"\b(?!\s*(?:->|\.|\[))", flags)
    for f in twins:
        body = f.body
        for m in cast_re.finditer(body):
            return "bytes", _snippet(body, m)
        for m in plain_re.finditer(body):
            lo = body.rfind("\n", 0, m.start()) + 1
            hi = body.find("\n", m.end())
            line = body[lo:hi]
            rel_s = m.start() - lo
            rel_e = m.end() - lo
            # `(p - q) * sizeof(WCHAR)` / `sizeof(WCHAR) * (p - q)` / `* 2` — bytes after all.
            post = line[rel_e:]
            pre = line[:rel_s]
            if re.match(r"\s*\)?\s*\*\s*(?:sizeof|2\b)", post) or re.search(
                r"(?:sizeof\s*\([^)]*\)|\b2)\s*\*\s*\(?\s*$", pre
            ):
                return "bytes", _snippet(body, m)
            return "elements", _snippet(body, m)
    return None


def _snippet(body: str, m: re.Match[str]) -> str:
    lo = body.rfind("\n", 0, m.start()) + 1
    hi = body.find("\n", m.end())
    return " ".join(body[lo : hi if hi >= 0 else len(body)].split())[:110]


@dataclass
class Site:
    path: Path
    line: int
    fn: str
    a: str
    b: str
    scaling: str | None
    src: str


def candidates(path: Path) -> list[Site]:
    try:
        raw = path.read_text(errors="replace")
    except OSError:
        return []
    if any(g in raw[:2000] for g in GEN_MARKERS):
        return []
    # Cheap prefilter on the raw text: most files have no candidate, and blanking plus
    # function extraction is most of the scan's cost.
    if not PREFILTER_RE.search(raw):
        return []
    text = blank_rust(raw)
    lines = raw.split("\n")
    funcs = rust_functions(text, path)
    out = []
    matches: dict[int, re.Match[str]] = {}
    for hit in PREFILTER_RE.finditer(text):
        # Only look near a literal hit: SUB_RE over the whole file starts at every identifier.
        for m in SUB_RE.finditer(text, max(0, hit.start() - 120), hit.end() + 200):
            matches.setdefault(m.start(), m)
    for m in (matches[k] for k in sorted(matches)):
        ln = text.count("\n", 0, m.start()) + 1
        if NOLINT_RE.search(lines[ln - 1]):
            continue
        owner = enclosing(funcs, m.start())
        scope = (owner.params + owner.body) if owner else text
        # `a as usize - (b as usize + x)`: the subtrahend is the whole group, not `b`.
        if m.group("bp") and not m.group("bclose"):
            continue
        ca = operand_class(scope, text, m.group("a"))
        cb = operand_class(scope, text, m.group("b"))
        if ca != "wide" or cb != "wide":
            continue
        scaling = rust_scaling(text, m)
        if scaling in ("/", ">>"):
            continue
        out.append(
            Site(
                path=path,
                line=ln,
                fn=owner.name if owner else "",
                a=m.group("a").split(".")[0],
                b=m.group("b").split(".")[0],
                scaling=scaling,
                src=lines[ln - 1].strip()[:110],
            )
        )
    return out


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("-")]
    lint = "--lint" in sys.argv
    roots = [Path(a) for a in args] if args else [RUST_ROOT]
    files: list[Path] = []
    for root in roots:
        if root.is_file():
            files.append(root)
        elif root.is_dir():
            files.extend(source_files(root))
        else:
            print(f"scan_ptr_byte_diff: no such path: {root}", file=sys.stderr)
            return 2

    sites = [
        s for f in sorted(set(files)) if not SKIP_PATH_RE.search(str(f)) for s in candidates(f)
    ]
    index = CIndex()
    index.load({s.fn for s in sites if s.fn})

    findings = []
    for s in sites:
        twins = prefer(s.path, index.get(s.fn)) if s.fn else []
        v = c_verdict(twins, s.a, s.b)
        if v is None:
            tag = "ptr-byte-diff-unpaired"
            why = "no C twin subtracts these operands" if twins else "no C function of this name"
            evidence = ""
        else:
            unit, evidence = v
            if unit == "bytes" and s.scaling != "*":
                continue
            tag = "ptr-byte-diff"
            why = "C counts elements" if unit == "elements" else "Rust scales a byte count again"
        try:
            rel = s.path.relative_to(REPO)
        except ValueError:
            rel = s.path
        findings.append((str(rel), s, tag, why, evidence))

    for rel, s, tag, why, evidence in findings:
        if lint:
            print(f"{rel}:{s.line}: {tag} {s.fn}({s.a} - {s.b})")
        else:
            print(f"{rel}:{s.line}: {tag}: {s.fn}: `{s.a} - {s.b}` subtracts addresses — {why}")
            print(f"    rust: {s.src}")
            if evidence:
                print(f"    c:    {evidence}")
    if not lint:
        print(f"\n{len(findings)} site(s)")
        if findings:
            print("fix: an element count is `a.offset_from(b)`; a byte count the C also meant")
            print("     needs no change — mark the reviewed line `// nolint: ptr-byte-diff`.")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
