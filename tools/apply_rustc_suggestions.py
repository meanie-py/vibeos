#!/usr/bin/env python3
"""Apply rustc's machine-applicable fixes for NOISE lints, read from cargo's cache.

    python3 tools/apply_rustc_suggestions.py build-i386 build-amd64 build-arm64 \\
        --lint unused_mut --lint unused_parens [--dry-run]

Each fresh unit's `.fingerprint/*/output-lib-*` holds rustc's JSON diagnostics, the same
ones the warnings census reads (see rust_warning_census.py for the freshness rule; a stale
build dir is refused). A suggestion marked `MachineApplicable` is applied only when:

  * EVERY arch whose build compiled that file made the identical suggestion. A `mut` that
    is unused on amd64 can be needed by an i386-only `#[cfg]` arm of the same function, and
    rustc on amd64 never saw that arm. A file compiled for one arch only (a types_i386.rs)
    needs only that arch.
  * the diagnostic is not inside a macro expansion: a fix to a `macro_rules!` body applies
    to every expansion, and the warning only proved one of them.
  * no two accepted edits overlap.
  * the fix compiles on every target: rustc's float `from_bits` / `to_bits` rewrite does
    not on the i386 no-SSE cell (REFUSED_REPLACEMENT).
  * the file is not generated (`@generated` / rust-bindgen header): a regen reverts hand
    edits, so those are counted and left for the generator.

`cargo fix` cannot be used here: the cargo-linked crates build under the CMake build at
the canonical path, per arch, and it would apply one arch's view of a cfg-split file.
"""

from __future__ import annotations

import argparse
import json
import posixpath
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import rust_warning_census as census

REPO = Path(__file__).resolve().parent.parent

Edit = tuple[int, int, str]  # (byte_start, byte_end, replacement)


# rustc offers `f64::from_bits(x)` for a `transmute::<u64, f64>`, without checking the
# target: on the i386 no-SSE cell (`-Z build-std` soft-float json, which also builds
# cnt-rust and ucrt-rust) any fn passing an f64 by value is a hard error, so the "fix" does
# not compile there. The transmute stays.
REFUSED_REPLACEMENT = re.compile(r"\bf(32|64)::(from|to)_bits\b")


def _suggestions(diag: dict) -> list[tuple[str, Edit]]:
    """(file, edit) pairs of one diagnostic's machine-applicable fix, or [] if it has none
    or touches a macro expansion."""
    if any(sp.get("expansion") for sp in diag.get("spans", [])):
        return []
    out = []
    stack = list(diag.get("children", []))
    while stack:
        ch = stack.pop()
        stack.extend(ch.get("children", []))
        for sp in ch.get("spans", []):
            if sp.get("suggestion_applicability") != "MachineApplicable":
                continue
            rep = sp.get("suggested_replacement")
            if rep is None or sp.get("expansion") or REFUSED_REPLACEMENT.search(rep):
                return []
            out.append(
                (sp["file_name"], (sp["byte_start"], sp["byte_end"], sp["suggested_replacement"]))
            )
    return out


def _norm(path: str) -> str:
    """One spelling per file: menuband compiles shell32's island as
    `menuband-rust/src/../../shell32-rust/src/island_amd64.rs`, and two spellings of one
    file would apply the same byte-offset edit to it twice."""
    if path.startswith(census.CANON):
        path = path[len(census.CANON) :]
    return posixpath.normpath(path.removeprefix("sdk/lib/rust/"))


GENERATED = (b"@generated", b"automatically generated by rust-bindgen")


def generated(p: Path) -> bool:
    """A regenerated file loses hand edits; fix its generator instead."""
    with p.open("rb") as fh:
        head = fh.read(512)
    return any(tag in head for tag in GENERATED)


def collect(build_dirs: list[Path], lints: set[str]) -> tuple[dict, dict, dict[str, str]]:
    """({arch: {file: {edit}}}, {arch: {files compiled}}, {arch:crate: why stale})."""
    sugg: dict[str, dict[str, set[Edit]]] = defaultdict(lambda: defaultdict(set))
    compiled: dict[str, set[str]] = defaultdict(set)
    stale_all: dict[str, str] = {}
    for bd in build_dirs:
        repo = bd.resolve().parent
        arch = census.arch_of_build_dir(bd)
        units = census.read_build_dir(bd, repo)
        _, stale = census.coverage(units)
        stale_all.update({f"{arch}:{c}": why for c, why in stale.items()})
        for u in units:
            if u.stale:
                continue
            m = census._FP_HASH.match(u.fpdir.name)
            assert m
            dfile = u.fpdir.parent.parent / "deps" / f"{m['crate'].replace('-', '_')}-{m['hash']}.d"
            compiled[arch].update(_norm(d) for d in census._dep_paths(dfile))
            for out in u.fpdir.glob("output-lib-*"):
                for line in out.read_text(errors="replace").splitlines():
                    try:
                        diag = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    if (diag.get("code") or {}).get("code") not in lints:
                        continue
                    for f, e in _suggestions(diag):
                        sugg[arch][_norm(f)].add(e)
    return sugg, compiled, stale_all


def agreed(sugg: dict, compiled: dict) -> dict[str, list[Edit]]:
    """Edits every arch that compiled the file suggested, without overlaps."""
    files = {f for per in sugg.values() for f in per}
    out = {}
    for f in sorted(files):
        arches = [a for a in compiled if f in compiled[a]]
        if not arches:
            continue
        common = set.intersection(*(sugg[a].get(f, set()) for a in arches))
        kept: list[Edit] = []
        for e in sorted(common):
            if kept and e[0] < kept[-1][1]:
                continue  # overlaps the previous edit
            kept.append(e)
        if kept:
            out[f] = kept
    return out


def apply_edits(b: bytes, edits: list[Edit]) -> bytes:
    """Apply non-overlapping edits back to front. A deletion that would leave a line ending
    in spaces (`(x == 0) as i32 ` after `unused_parens` drops a trailing `)`) takes them too."""
    for s, e, rep in reversed(edits):
        if not rep and b[e : e + 1] in (b"\n", b"\r"):
            while s > 0 and b[s - 1 : s] in (b" ", b"\t"):
                s -= 1
        b = b[:s] + rep.encode() + b[e:]
    return b


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("build_dirs", nargs="+", type=Path)
    ap.add_argument("--lint", action="append", required=True, help="lint to fix (repeatable)")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)

    sugg, compiled, stale = collect(args.build_dirs, set(args.lint))
    if stale:
        print(
            f"STALE: {len(stale)} crate(s) edited since their build; rebuild first:",
            file=sys.stderr,
        )
        for c, why in sorted(stale.items()):
            print(f"   {c}: {why}", file=sys.stderr)
        return 3
    plan = agreed(sugg, compiled)
    root = REPO / "sdk" / "lib" / "rust"
    n = 0
    skipped_generated = 0
    for f, edits in plan.items():
        p = root / f
        if generated(p):
            skipped_generated += len(edits)
            continue
        b = p.read_bytes()
        b = apply_edits(b, edits)
        n += len(edits)
        print(f"{f}: {len(edits)} edit(s)")
        if not args.dry_run:
            p.write_bytes(b)
    offered = sum(len(v) for per in sugg.values() for v in per.values())
    print(
        f"{n} edit(s); {skipped_generated} left in generated files; "
        f"{offered} arch-suggestions read",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
