"""Pins extern_to_use and apply_agent_edits, the fastfat clash-burndown pair."""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent))
import apply_agent_edits as ae
import extern_to_use as e2u

DEFINING = (
    '#[no_mangle]\npub unsafe extern "system" fn FatRaiseStatus(c: *mut u8, s: i32) -> ! {\n}\n'
)
CALLER = (
    "use crate::types::*;\n"
    'extern "system" {\n'
    "    fn FatRaiseStatus(IrpContext: *mut u8,\n        Status: u32);\n"
    "    fn Other(x: u32);\n"
    "}\n"
)


def test_own_function_redeclaration_becomes_a_use_of_the_definition():
    files = {"seh": DEFINING, "allocsup": CALLER}
    changed, report = e2u.convert(files, e2u.find_defs(files, ["FatRaiseStatus"]), e2u.MARK_OWN)
    assert set(changed) == {"allocsup"}  # the defining module is left alone
    out = changed["allocsup"]
    assert "use crate::seh::FatRaiseStatus;" in out
    assert "fn FatRaiseStatus" not in out  # the multi-line decl went, newline included
    assert "    fn Other(x: u32);\n}" in out
    assert report == ["allocsup.rs:3: fn FatRaiseStatus(IrpContext: *mut u8, Status: u32);"]


def test_a_name_defined_twice_or_nowhere_is_refused():
    with pytest.raises(SystemExit):
        e2u.find_defs({"a": DEFINING, "b": DEFINING}, ["FatRaiseStatus"])
    with pytest.raises(SystemExit):
        e2u.find_defs({"a": CALLER}, ["Nowhere"])


def test_external_symbols_go_to_the_named_module():
    changed, _ = e2u.convert(
        {"allocsup": CALLER}, {"Other": "externs"}, e2u.MARK_TO.format(to="externs")
    )
    assert "use crate::externs::Other;" in changed["allocsup"]


def test_agent_edit_applies_only_on_a_unique_match(tmp_path: Path):
    (tmp_path / "a.rs").write_text("let x = 1;\nlet y = 1;\nlet y = 1;\n")
    rows = [
        {"id": "A1", "edit": {"file": "a.rs", "old": "let x = 1;", "new": "let x = 2;"}},
        {"id": "A2", "edit": {"file": "a.rs", "old": "let y = 1;", "new": "let y = 2;"}},
    ]
    p = tmp_path / "out.jsonl"
    p.write_text("\n".join(json.dumps(r) for r in rows))
    ok, skipped = ae.apply(ae.load([p]), tmp_path)
    assert ok == 1
    assert skipped == ["SKIP A2 a.rs: old occurs 2x"]
    assert (tmp_path / "a.rs").read_text().startswith("let x = 2;")


def test_a_bindgen_island_declaration_is_not_a_definition():
    # cdfs: types_<arch>.rs declares `pub fn CdCommonCreate(..);` in an extern block.
    island = 'extern "C" {\n    pub fn FatRaiseStatus(c: *mut u8, s: i32) -> !;\n}\n'
    assert e2u.find_defs({"seh": DEFINING, "types_i386": island}, ["FatRaiseStatus"]) == {
        "FatRaiseStatus": "seh"
    }


def test_a_generated_island_is_never_edited():
    island = (
        "//! Generated by tools/rustconv/gen_driver_types.sh. Do not edit by hand.\n"
        'extern "C" {\n    pub fn Other(x: u32);\n}\n'
    )
    changed, _ = e2u.convert(
        {"allocsup": CALLER, "types_i386": island},
        {"Other": "types"},
        e2u.MARK_TO.format(to="types"),
    )
    assert set(changed) == {"allocsup"}


def test_nested_modules_and_attributed_definitions(tmp_path):
    src = tmp_path / "src"
    (src / "misc").mkdir(parents=True)
    (src / "lib.rs").write_text("pub mod misc;\npub mod caller;\n")
    (src / "misc" / "mod.rs").write_text("pub mod ddemisc;\n")
    (src / "misc" / "ddemisc.rs").write_text(
        '#[no_mangle] pub unsafe extern "C" fn WDML_GetConv(h: u32) -> u32 { h }\n'
    )
    (src / "caller.rs").write_text(
        'use x::y;\nextern "C" {\n    fn WDML_GetConv(h: u64) -> u32;\n}\n'
    )
    files = e2u.module_files(src)
    assert set(files) == {"", "misc", "misc::ddemisc", "caller"}
    home = e2u.find_defs(files, ["WDML_GetConv"])
    assert home == {"WDML_GetConv": "misc::ddemisc"}
    changed, _ = e2u.convert(files, home, e2u.MARK_OWN)
    assert "use crate::misc::ddemisc::WDML_GetConv;" in changed["caller"]
    assert e2u.module_path(src, "misc") == src / "misc" / "mod.rs"


def test_path_mounted_module_and_pub_declaration_keep_their_meaning(tmp_path):
    src = tmp_path / "src"
    (src / "reg").mkdir(parents=True)
    (src / "lib.rs").write_text('#[path = "reg/reg.rs"]\npub mod reg;\npub mod a;\n')
    (src / "reg" / "reg.rs").write_text("pub unsafe fn RegCloseKey(h: u32) -> u32 { h }\n")
    (src / "a.rs").write_text(
        'use x::y;\nextern "C" {\n    pub fn RegCloseKey(h: u64) -> u32;\n}\n'
    )
    files = e2u.module_files(src)
    assert set(files) == {"", "reg", "a"}
    changed, _ = e2u.convert(files, e2u.find_defs(files, ["RegCloseKey"]), e2u.MARK_OWN)
    assert "pub use crate::reg::RegCloseKey;" in changed["a"]


def test_canonical_variant_is_promoted_and_the_others_use_it(tmp_path):
    src = tmp_path / "src"
    src.mkdir()
    (src / "lib.rs").write_text("pub mod a;\npub mod b;\n")
    (src / "a.rs").write_text(
        'use x::y;\nextern "system" {\n'
        "    fn HeapAlloc(h: HANDLE, f: u32, n: SIZE_T) -> LPVOID;\n}\n"
    )
    (src / "b.rs").write_text(
        'use x::y;\nextern "system" {\n    fn HeapAlloc(h: HANDLE, f: u32, n: u32) -> LPVOID;\n}\n'
    )
    changed, _ = e2u.apply_canonical(
        src, [{"name": "HeapAlloc", "canonical": {"module": "a", "line": 3}}]
    )
    assert "    pub fn HeapAlloc(h: HANDLE, f: u32, n: SIZE_T)" in changed["a"]
    assert "use crate::a::HeapAlloc;" in changed["b"] and "fn HeapAlloc" not in changed["b"]


def test_attributes_go_with_their_declaration_and_differing_ones_are_never_merged(tmp_path):
    src = tmp_path / "src"
    src.mkdir()
    (src / "lib.rs").write_text("pub mod a;\npub mod b;\npub mod c;\n")
    keep = '    #[cfg_attr(target_pointer_width = "32", link_name = "GetWindowLongW")]\n'
    (src / "a.rs").write_text(
        'use x::y;\nextern "system" {\n'
        + keep
        + "    fn GetWindowLongPtrW(w: HWND, i: INT) -> LONG_PTR;\n}\n"
    )
    (src / "b.rs").write_text(
        'use x::y;\nextern "system" {\n'
        + keep
        + "    fn GetWindowLongPtrW(w: HWND, i: i32) -> isize;\n}\n"
    )
    (src / "c.rs").write_text(
        'use x::y;\nextern "system" {\n    fn GetWindowLongPtrW(w: HWND, i: i32) -> isize;\n}\n'
    )
    changed, report = e2u.apply_canonical(
        src, [{"name": "GetWindowLongPtrW", "canonical": {"module": "a", "line": 4}}]
    )
    assert "    pub fn GetWindowLongPtrW" in changed["a"] and keep in changed["a"]
    assert "use crate::a::GetWindowLongPtrW;" in changed["b"] and "link_name" not in changed["b"]
    assert "c" not in changed  # no link_name: a different symbol on 32-bit
    assert any(x.startswith("KEPT c.rs") for x in report)


def test_a_declaration_inside_an_inline_module_gets_its_use_there():
    caller = (
        'use x::y;\nmod k32 {\n    extern "system" {\n'
        "        pub fn FatRaiseStatus(c: *mut u8, s: u32);\n    }\n}\n"
    )
    files = {"seh": DEFINING, "winrt": caller}
    changed, _ = e2u.convert(files, e2u.find_defs(files, ["FatRaiseStatus"]), e2u.MARK_OWN)
    out = changed["winrt"]
    assert "mod k32 {\n    pub use crate::seh::FatRaiseStatus;" in out
    assert out.count("use crate::seh::FatRaiseStatus;") == 1


def test_module_walk_follows_an_inline_mod(tmp_path):
    # mspaint's lib.rs: `pub mod mspaint { pub mod cpp_classes; }` is mspaint/cpp_classes.rs.
    src = tmp_path / "src"
    (src / "mspaint").mkdir(parents=True)
    (src / "lib.rs").write_text("pub mod types;\npub mod mspaint {\n    pub mod cpp_classes;\n}\n")
    (src / "types.rs").write_text("")
    (src / "mspaint" / "cpp_classes.rs").write_text("pub static mut X: u32 = 0;\n")
    assert sorted(e2u.module_files(src)) == ["", "mspaint::cpp_classes", "types"]


def test_a_cfg_gated_definition_is_refused():
    # cdrom: `#[cfg(not(target_arch = "x86"))] #[no_mangle] pub unsafe extern "system" fn
    # KeQueryTickCount(..)` -- on i386 it is a kernel export, and a `use` would not resolve.
    files = {
        "ddk_shims": '#[cfg(not(target_arch = "x86"))]\n#[no_mangle]\n'
        'pub unsafe extern "system" fn KeQueryTickCount(c: *mut i64) {}\n',
        "common": 'extern "system" {\n    fn KeQueryTickCount(c: *mut i64);\n}\n',
    }
    try:
        e2u.find_defs(files, ["KeQueryTickCount"])
    except SystemExit as err:
        assert "cfg-gated" in str(err)
    else:
        raise AssertionError("a cfg-gated definition was accepted")
