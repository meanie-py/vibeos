#!/usr/bin/env python3
"""
scan_invented_constants.py — the constants that say, in their own comment, that
nobody looked them up.

THE POINT. `scan_const_contradictions.py` finds "one name, two values, both
ours"; it is blind by construction to a constant that has exactly ONE definition
in the tree and is simply wrong. That population is not hypothetical and it does
not have to be inferred, because the translator labelled it:

    const FAT_MAX_IO_RUNS_ON_STACK: usize = 10; // Guessed value; adjust as needed
    const EA_NEED_EA_FLAG: u32 = 0x80;          // placeholder, actual value unknown
    const FcbGood: u32 = 1;                     // assumed value

One of these has already cost a boot. `fastfat/cachesup.rs` carried
`IRP_CONTEXT_FLAG_DISABLE_DIRTY = 0x100 // placeholder` where `fatstruc.h` says
`0x01`; the guard it gates never fired, and FatSetDirtyBcb -> FatMarkVolume ->
FatSetFatEntry -> FatPrepareWriteVolumeFile recursed until arm64 took a
BUGCHECK 0x50 on a blown kernel stack. The comment announcing the defect was
sitting in the tree the whole time.

HOW THE ORACLE IS SCOPED, and why that matters. Resolving a name against all
~2200 headers at once was tried for `verify_constants.py` and rejected: unrelated
headers collide on short names and the findings were overwhelmingly false
(§9.113b). So the corpus here is narrow and derived per crate: the C module the
crate translates (`fastfat-rust` -> `drivers/filesystems/fastfat`) plus the
shared SDK headers. A name that resolves to two different values inside that
corpus is reported AMBIGUOUS and judged by a human, never guessed at.

Findings, worst first:
    MISMATCH   the C oracle says something else. This is a defect.
    AMBIGUOUS  the scoped corpus holds >1 value for the name.
    UNRESOLVED no oracle found; the label stands and a human must check it.
    (a value that matches its oracle is silently dropped -- and its comment
     should be corrected, since a verified constant is not a placeholder.)

Usage:
    python3 tools/scan_invented_constants.py            # full report
    python3 tools/scan_invented_constants.py --lint     # terse (CLI baseline gate)
    python3 tools/scan_invented_constants.py --crate fastfat-rust

Once a value is verified, REWORD THE COMMENT -- cite the header it came from.
That is what clears the entry; there is no nolint for "I checked it and left the
comment saying I hadn't".  For a value that genuinely has no C oracle (a
Rust-side implementation choice), say so:

    const FOO: u32 = 8; // nolint: invented-constant (Rust-side buffer sizing)

Output is line-number-free so unrelated edits above a declaration never churn
the baseline.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tools.lint_facts import source_facts
from tools.source_walk import source_files, source_walk

REPO = Path(__file__).resolve().parent.parent
RUST_ROOT = REPO / "sdk" / "lib" / "rust"

SKIP_FILE_RE = re.compile(r"(bindgen_[a-z0-9_]+\.rs$|/target/|/\.responses/)")
GENERATED_RE = re.compile(r"automatically generated by rust-bindgen|@generated")
NOLINT_RE = re.compile(r"//\s*nolint(?::\s*invented-constant\b|\s*$|:?\s*\()")

# The self-accusation. Deliberately not "unknown" alone or "TODO" alone: those
# appear on plenty of comments that are about the surrounding code rather than
# about the number.
INVENTED_RE = re.compile(
    r"\b(placeholder|guessed|guess|assumed value|assumed|typical|arbitrary"
    r"|adjust as needed|approximate|dummy value|value unknown|actual value unknown"
    r"|made up|invented|not verified|unverified)\b",
    re.I,
)
# A comment that records the fix is not an accusation any more.
CLEARED_RE = re.compile(r"\b(FIXED|verified|bindgen-correct|nolint)\b", re.I)

CONST_RE = re.compile(
    r"^\s*(?:pub\s*(?:\([^)]*\)\s*)?)?(?:const|static)\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*"
    r"([^=]+?)\s*=\s*(.+?);\s*(?://\s*(.*))?$"
)

RUST_INT_RE = re.compile(
    r"^\s*(-?)\s*(0[xX][0-9A-Fa-f_]+|\d[\d_]*)"
    r"(?:_?(?:u8|u16|u32|u64|usize|i8|i16|i32|i64|isize))?"
    r"(?:\s*as\s+[\w:]+)?\s*$"
)
FOURCC_RE = re.compile(r'u32::from_(le|be)_bytes\(\*b"([^"]{4})"\)')

WIDTH_OF = {
    "u8": 8,
    "i8": 8,
    "u16": 16,
    "i16": 16,
    "u32": 32,
    "i32": 32,
    "u64": 64,
    "i64": 64,
    "usize": 64,
    "isize": 64,
}


def rust_value(raw: str) -> int | None:
    if (fc := FOURCC_RE.search(raw)) is not None:
        return int.from_bytes(fc.group(2).encode(), "little" if fc.group(1) == "le" else "big")
    m = RUST_INT_RE.match(raw)
    if not m:
        return None
    try:
        val = int(m.group(2).replace("_", ""), 0)
    except ValueError:
        return None
    return -val if m.group(1) else val


# ---------------------------------------------------------------- C oracle ---

CAST_RE = re.compile(
    r"\(\s*(?:const\s+)?(?:unsigned\s+|signed\s+)?[A-Za-z_][A-Za-z0-9_]*\s*\**\s*\)"
)
CHAR_RE = re.compile(r"'((?:[^'\\]|\\.){1,4})'")
SAFE_EXPR_RE = re.compile(r"^[\s0-9xXa-fA-F()|&^~<>+*/-]+$")
DEFINE_RE = re.compile(r"^\s*#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)\s+(.+?)\s*$")
ENUM_OPEN_RE = re.compile(r"\benum\b[^{;]*\{")
ENUMERATOR_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)\s*(?:=\s*(.+))?$")


def _strip_comments(text: str) -> str:
    # Newlines are preserved so reported line numbers stay true to the file.
    text = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def _char_literal(s: str) -> int:
    """C multi-character literals are BIG-endian by definition: 'cDwH' is
    ('c'<<24)|('D'<<16)|('w'<<8)|'H'. Getting this backwards is its own recurring
    bug (see the field manual's pool-tag entry), so it is spelled out here."""
    s = s.encode().decode("unicode_escape")
    val = 0
    for ch in s:
        val = (val << 8) | (ord(ch) & 0xFF)
    return val


CTL_CODE_RE = re.compile(r"CTL_CODE\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)")


def eval_c(expr: str, table: dict[str, str], depth: int = 0) -> int | None:
    """Evaluate a C constant expression, resolving named operands from `table`."""
    if depth > 8:
        return None
    expr = expr.strip().rstrip(",")
    # CTL_CODE is the one function-like macro worth teaching this evaluator: the
    # IOCTL numbers it builds are a large slice of the self-labelled population,
    # and an IOCTL is a pure rendezvous constant -- the driver that mismatches it
    # simply never sees the request.
    while (cc := CTL_CODE_RE.search(expr)) is not None:
        args = [a.strip() for a in cc.group(1).split(",")]
        if len(args) != 4:
            return None
        parts = [eval_c(a, table, depth + 1) for a in args]
        if any(x is None for x in parts):
            return None
        dev, func, meth, acc = parts  # type: ignore[misc]
        code = (dev << 16) | (acc << 14) | (func << 2) | meth
        expr = expr[: cc.start()] + str(code) + expr[cc.end() :]
    if not expr or expr.endswith("\\"):
        return None
    expr = CHAR_RE.sub(lambda m: str(_char_literal(m.group(1))), expr)
    # Integer suffixes, then casts. Casts must go after names are resolved would
    # be wrong -- a cast looks exactly like a parenthesised name -- so strip the
    # ones that name a TYPE first, and let unresolved names fail the safety check.
    expr = re.sub(r"\b(0[xX][0-9A-Fa-f]+|\d+)[uUlL]+\b", r"\1", expr)
    for _ in range(4):
        new = CAST_RE.sub(" ", expr)
        if new == expr:
            break
        expr = new
    # The lookbehind matters: a bare `[A-Za-z_]\w*` finds "x0501" inside 0x0501
    # and then fails to resolve it, so EVERY hex constant silently went
    # unresolved -- the scanner reported 0 MISMATCH on a population it could not
    # evaluate at all.
    for name in sorted(
        set(re.findall(r"(?<![0-9A-Za-z_])[A-Za-z_][A-Za-z0-9_]*", expr)), key=len, reverse=True
    ):
        if name not in table:
            return None
        sub = eval_c(table[name], table, depth + 1)
        if sub is None:
            return None
        expr = re.sub(rf"\b{re.escape(name)}\b", f"({sub})", expr)
    if not SAFE_EXPR_RE.match(expr):
        return None
    try:
        # Guarded by SAFE_EXPR_RE above: only digits, hex and arithmetic reach here.
        return int(eval(expr, {"__builtins__": {}}, {}))
    except Exception:
        return None


def harvest(paths: list[Path]) -> dict[str, set[tuple[int, str]]]:
    """name -> {(value, 'file:line')} over a scoped corpus of C sources."""

    def _rel(path: Path) -> str:
        try:
            return str(path.relative_to(REPO))
        except ValueError:
            return str(path)

    return catalog_facts(tuple((_rel(p), p.read_text(errors="ignore")) for p in paths))


@source_facts()
def catalog_facts(contents):
    raw: dict[str, str] = {}
    sites: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for rel, contents_text in contents:
        text = _strip_comments(contents_text)
        for i, line in enumerate(text.splitlines(), 1):
            m = DEFINE_RE.match(line)
            if m and "(" not in m.group(1):
                raw.setdefault(m.group(1), m.group(2))
                sites[m.group(1)].append((m.group(2), f"{rel}:{i}"))
        # enum bodies, including C's implicit numbering
        for m in ENUM_OPEN_RE.finditer(text):
            start = m.end()
            depth, j = 1, start
            while j < len(text) and depth:
                depth += (text[j] == "{") - (text[j] == "}")
                j += 1
            body = text[start : j - 1]
            nxt = 0
            for item in body.split(","):
                em = ENUMERATOR_RE.match(item.strip())
                if not em:
                    nxt += 1
                    continue
                if em.group(2) is None:
                    val: int | None = nxt
                    expr = str(nxt)
                else:
                    expr = em.group(2)
                    # Resolve an EXPLICIT initialiser now, because C's implicit
                    # numbering continues FROM it: `FcbGood = 1, FcbBad,` makes
                    # FcbBad 2, not 1. Getting this wrong reported the correct
                    # `FcbNeedsToBeVerified = 3` as a mismatch against a phantom 2.
                    val = eval_c(expr, raw)
                raw.setdefault(em.group(1), expr)
                sites[em.group(1)].append((expr, rel))
                nxt = (val if val is not None else nxt) + 1

    out: dict[str, set[tuple[int, str]]] = defaultdict(set)
    for name, occurrences in sites.items():
        for expr, where in occurrences:
            v = eval_c(expr, raw)
            if v is not None:
                out[name].add((v, where))
    return dict(out)


def c_dirs_for(crate: str) -> list[Path]:
    """The C module a crate translates. Narrow on purpose: a repo-wide catalog
    collides on short names and its findings are overwhelmingly false."""
    stem = crate.removesuffix("-rust").removesuffix("-sys")
    stem = {"ntkrnl": "ntoskrnl", "rtlk": "rtl", "win32k": "win32ss"}.get(stem, stem)
    # PRUNE during the walk, don't filter after it. `REPO.rglob(stem)` descends into every
    # excluded tree before the `rel.startswith(...)` test can reject it -- including
    # `sdk/lib/rust/target`, which a CONCURRENT cargo build is deleting directories out of.
    # That raced and crashed the scanner with FileNotFoundError deep inside pathlib, which the
    # gate reported as "NEW lint findings" -- a crash misfiled as a verdict. It only became
    # reachable when the source-early partition started running scanners alongside builds
    # rather than after them. Included source I/O errors must still fail loudly:
    # silently skipping unreadable source would shrink verification coverage.
    skip = ("build-", "modules/rostests", "sdk/lib/rust", ".git")
    hits = []
    for parent, dirs, _ in source_walk(REPO, exclude_prefixes=skip):
        hits.extend(parent / name for name in dirs if name == stem)
    return hits


_HEADER_CACHE: list[Path] | None = None


def sdk_headers() -> list[Path]:
    """The public header surface: sdk/include plus every vendored library's public
    root. The vendor/ relocation moved WDF, GL, mbedtls, zlib & co. out of sdk/include
    into `vendor/<lib>/include`; walking sdk/include alone silently dropped them, and
    cdrom-rust's WDF_REMOVE_LOCK_OPTION_ACQUIRE_FOR_IO went UNRESOLVED. Globbing the
    convention rather than listing trees keeps the next move from repeating that."""
    global _HEADER_CACHE
    if _HEADER_CACHE is None:
        roots = [REPO / "sdk" / "include", *sorted((REPO / "vendor").glob("*/include"))]
        _HEADER_CACHE = sorted(h for root in roots for h in source_files(root, "*.h"))
    return _HEADER_CACHE


_ORACLE_CACHE: dict[str, dict[str, set[tuple[int, str]]]] = {}


def oracle_for(crate: str) -> dict[str, set[tuple[int, str]]]:
    if crate not in _ORACLE_CACHE:
        paths = list(sdk_headers())
        for d in c_dirs_for(crate):
            paths += sorted(source_files(d, "*.h")) + sorted(source_files(d, "*.c"))
        _ORACLE_CACHE[crate] = harvest(paths)
    return _ORACLE_CACHE[crate]


# ------------------------------------------------------------------ scan ---


@source_facts()
def invented_facts(text):
    out = []
    for line in text.splitlines():
        if NOLINT_RE.search(line):
            continue
        m = CONST_RE.match(line)
        if not m:
            continue
        comment = m.group(4) or ""
        if not INVENTED_RE.search(comment) or CLEARED_RE.search(comment):
            continue
        val = rust_value(m.group(3))
        if val is None:
            continue
        out.append((m.group(1), val, m.group(2).strip(), comment.strip()))
    return out


def collect() -> list[tuple[str, str, str, int, str, str]]:
    """[(crate, rel, name, value, rust_type, comment)] for self-labelled consts."""
    out = []
    for path in sorted(source_files(RUST_ROOT)):
        if SKIP_FILE_RE.search(str(path)):
            continue
        text = path.read_text(errors="replace")
        if GENERATED_RE.search(text[:800]):
            continue
        rel = str(path.relative_to(REPO))
        crate = Path(rel).relative_to("sdk/lib/rust").parts[0]
        out.extend((crate, rel, *fact) for fact in invented_facts(text))
    return out


def same(rust_val: int, c_val: int, rust_type: str) -> bool:
    """Compare at the declared width, unsigned. `0xC0000052_u32 as i32` and the
    header's `0xC0000052L` are the same 32-bit quantity written two ways."""
    w = WIDTH_OF.get(rust_type.strip().lstrip("_"), 64)
    mask = (1 << w) - 1
    return (rust_val & mask) == (c_val & mask)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lint", action="store_true", help="terse output for the baseline gate")
    ap.add_argument("--crate", help="restrict to one crate")
    args = ap.parse_args()

    findings: list[tuple[str, str, str, str]] = []  # (kind, rel, name, detail)
    for crate, rel, name, val, rtype, _comment in collect():
        if args.crate and crate != args.crate:
            continue
        oracle = oracle_for(crate)
        cands = oracle.get(name, set())
        if not cands:
            # A rustconv habit: the C's `NonPagedPoolNx` is re-declared as
            # `NON_PAGED_POOL_NX` to satisfy Rust's naming lint. Same constant,
            # so fall back to a spelling-insensitive match -- but only when it
            # is UNIQUE, since collapsing case is exactly how a repo-wide
            # catalog manufactures false findings.
            key = name.replace("_", "").lower()
            hits = [v for n, v in oracle.items() if n.replace("_", "").lower() == key]
            if len(hits) == 1:
                cands = hits[0]
        values = {v for v, _ in cands}
        if not values:
            findings.append(("UNRESOLVED", rel, name, f"0x{val & 0xFFFFFFFFFFFFFFFF:X}"))
        elif len(values) > 1:
            shown = ", ".join(sorted(f"0x{v & 0xFFFFFFFFFFFFFFFF:X}" for v in values))
            findings.append(
                ("AMBIGUOUS", rel, name, f"ours 0x{val & 0xFFFFFFFFFFFFFFFF:X} vs {{{shown}}}")
            )
        else:
            cval, where = sorted(cands)[0]
            if not same(val, cval, rtype):
                findings.append(
                    (
                        "MISMATCH",
                        rel,
                        name,
                        f"ours 0x{val & 0xFFFFFFFFFFFFFFFF:X} "
                        f"!= 0x{cval & 0xFFFFFFFFFFFFFFFF:X} ({where})",
                    )
                )

    order = {"MISMATCH": 0, "AMBIGUOUS": 1, "UNRESOLVED": 2}
    findings.sort(key=lambda f: (order[f[0]], f[1], f[2]))
    for kind, rel, name, detail in findings:
        print(f"{kind} {rel}: {name} {detail}")

    if not args.lint:
        counts = defaultdict(int)
        for kind, *_ in findings:
            counts[kind] += 1
        print(
            f"\n{len(findings)} self-labelled constant(s): "
            + ", ".join(f"{counts[k]} {k}" for k in ("MISMATCH", "AMBIGUOUS", "UNRESOLVED"))
        )
        if counts["MISMATCH"]:
            print("MISMATCH is a defect: the C says something else. Fix the value AND the comment.")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
