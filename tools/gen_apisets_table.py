#!/usr/bin/env python3
"""Generate ntdll-rust's api-set table from sdk/lib/apisets/apisets.table.c.

    python3 tools/gen_apisets_table.py          # rewrite ntdll-rust/src/apisets_table.rs
    python3 tools/gen_apisets_table.py --check  # exit 1 if the committed table is stale

The table is committed rather than generated by a build script so ntdll-rust has no
build.rs and its graph reads only its own package: what lets the shared artifact
store build it once for every lane (docs/engineering/immutable-build-artifacts.md).
tools/test_gen_apisets_table.py holds the committed copy to the C.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "sdk/lib/apisets/apisets.table.c"
OUTPUT = REPO / "sdk/lib/rust/ntdll-rust/src/apisets_table.rs"
# APISET_* flag bits (apisets.h / apisetsp.h).
FLAGS = {"APISET_WIN7": 1, "APISET_WIN8": 2, "APISET_WIN81": 4, "APISET_WIN10": 8}


def _flags(expr: str) -> int:
    value = 0
    for token in expr.split("|"):
        token = token.strip()
        if token not in FLAGS:
            raise SystemExit(f"unknown apiset flag token: {token!r}")
        value |= FLAGS[token]
    return value


def _u16(text: str) -> tuple[int, str]:
    data = text.encode("utf-16-le")
    units = [int.from_bytes(data[i : i + 2], "little") for i in range(0, len(data), 2)] + [0]
    return len(units), "[" + ", ".join(f"0x{u:04x}" for u in units) + "]"


def entries(source: str) -> list[tuple[str, str, int]]:
    """Each `{ RTL_CONSTANT_STRING(L"NAME"), RTL_CONSTANT_STRING(L"TARGET"), FLAGS },`
    line; `//`-commented entries do not start with `{`."""
    out = []
    for line in source.splitlines():
        line = line.strip()
        if not line.startswith("{") or "RTL_CONSTANT_STRING" not in line:
            continue
        i1 = line.index('L"') + 2
        n_end = line.index('"', i1)
        name, rest = line[i1:n_end], line[n_end + 1 :]
        i2 = rest.index('L"') + 2
        t_end = rest.index('"', i2)
        target, after = rest[i2:t_end], rest[t_end:]
        segment = after[: after.index("}")]
        out.append((name, target, _flags(segment[segment.index(",") + 1 :])))
    if not out:
        raise SystemExit(f"no apiset entries parsed from {SOURCE}")
    return out


def render(source: str) -> str:
    table = entries(source)
    lines = ["// @generated by tools/gen_apisets_table.py from sdk/lib/apisets/apisets.table.c"]
    for i, (name, target, _) in enumerate(table):
        nl, na = _u16(name)
        tl, ta = _u16(target)
        lines.append(f"static N{i}: [u16; {nl}] = {na};")
        lines.append(f"static T{i}: [u16; {tl}] = {ta};")
    lines.append("")
    lines.append(f"pub(super) static G_APISETS: [RosApiset; {len(table)}] = [")
    for i, (_, _, flags) in enumerate(table):
        lines.append(
            f"    RosApiset {{ name: us(&N{i}), target: us(&T{i}), dw_os_versions: 0x{flags:x} }},"
        )
    lines.append("];")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render(SOURCE.read_text())
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != text:
            print(f"{OUTPUT.relative_to(REPO)} is stale: run python3 tools/gen_apisets_table.py")
            return 1
        return 0
    OUTPUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
