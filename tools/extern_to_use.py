#!/usr/bin/env python3
"""Replace a crate's per-module `extern` redeclarations with `use` of ONE declaration.

    python3 tools/extern_to_use.py sdk/lib/rust/fastfat-rust/src FatRaiseStatus,FatIsFat32
    python3 tools/extern_to_use.py <src> NAME,NAME --to externs [--dry-run]

Translated crates declare the same function in every module that calls it, each with its own
guess at the signature; `clashing_extern_declarations` counts the disagreements and nothing
checks them against the truth. Two cases, one move:

  * the crate DEFINES the function (a `#[no_mangle] pub ... fn` in one module): every other
    module's declaration becomes `use crate::<that module>::<name>;`, so each call is checked
    against the real definition.
  * the function lives outside the crate: write one canonical declaration in a module (e.g.
    `externs.rs`, from the C or the -sys bindgen) and pass `--to externs`.

Then build: the type errors that appear are exactly the call sites that disagreed with the
truth. Run `rustconv crate-repair` for the mechanical ones and read the rest against the C
(fastfat, 2026-10-11: 311 redeclarations, 242 errors, a handful real). Only declarations
starting a line are removed; a one-line `} extern "C" { fn X(..); }` fragment is reported
by the build as a duplicate name and needs a hand edit.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

DEF = (
    r"^\s*(?:#\[[^\]\n]*\]\s*)*pub(?:\(crate\))?\s+(?:unsafe\s+)?"
    r"(?:extern\s+\"[^\"]+\"\s+)?fn\s+{n}\b"
)
MARK_OWN = "// The crate's own functions: the definition is the declaration."
MARK_TO = "// One declaration per external symbol: {to}.rs."


def decl_re(name: str) -> re.Pattern[str]:
    """A bodiless `fn NAME(..) [-> T];` starting a line, with nested parens, and its newline,
    together with the attribute lines right above it (`attrs`): an attribute belongs to the
    declaration, and a `#[link_name]` makes it a different symbol."""
    return re.compile(
        rf"^(?P<attrs>(?:[ \t]*#\[[^\n]*\][ \t]*\n)*)[ \t]*(?P<vis>pub(?:\([^)]*\))?\s+)?"
        rf"fn\s+{name}\s*\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\)"
        rf"\s*(?:->\s*[^;{{]+?)?\s*;[ \t]*\n?",
        re.M,
    )


def _has_body(text: str, at: int) -> bool:
    """The signature starting at `at` reaches a `{` before a `;` at paren depth 0: a
    definition, not a bindgen island's bodiless `pub fn X(..);` in an extern block."""
    depth = 0
    for c in text[at:]:
        if c in "([<":
            depth += 1
        elif c in ")]>":
            depth -= 1
        elif depth <= 0 and c in "{;":
            return c == "{"
    return False


def find_defs(files: dict[str, str], names: list[str]) -> dict[str, str]:
    """name -> the module that defines it. Refuses a name defined zero or several times."""
    out = {}
    for n in names:
        hits = [
            m
            for m, t in files.items()
            if any(_has_body(t, d.end()) for d in re.finditer(DEF.format(n=n), t, re.M))
        ]
        if len(hits) != 1:
            raise SystemExit(f"{n}: defined in {hits or 'no module'}; pass --to <module>")
        out[n] = hits[0]
    return out


def insert_uses(text: str, uses: list[str], mark: str) -> str:
    """After the first top-level `use` statement, or after the leading comments/attributes."""
    m = re.search(r"^use [^;]*;\n", text, re.M)
    at = m.end() if m else re.match(r"(?:(?://[^\n]*|#!\[[^\n]*\]|[ \t]*)\n)*", text).end()
    return text[:at] + mark + "\n" + "\n".join(uses) + "\n" + text[at:]


GENERATED = re.compile(r"Do not edit by hand|automatically generated by rust-bindgen|@generated")


_INLINE_MOD = re.compile(r"^[ \t]*(?:pub(?:\([^)]*\))?\s+)?mod\s+(\w+)\s*\{", re.M)


def _inline_mods_around(text: str, at: int) -> list[str]:
    """Names of the inline `mod x { .. }` blocks enclosing `at`, outermost first. mspaint's
    lib.rs mounts every file inside `pub mod mspaint { pub mod cpp_classes; .. }`, so the
    file is `mspaint/cpp_classes.rs` and the module `crate::mspaint::cpp_classes`."""
    names = []
    for m in _INLINE_MOD.finditer(text, 0, at):
        depth, k = 0, m.end() - 1
        while k < len(text):
            if text[k] == "{":
                depth += 1
            elif text[k] == "}":
                depth -= 1
                if depth == 0:
                    break
            k += 1
        if m.end() <= at < k:
            names.append(m.group(1))
    return names


def _inline_mod_at(text: str, at: int) -> int | None:
    """Offset just past the `{` of the innermost inline `mod x { .. }` enclosing `at`, or
    None at file level. A `use` for a declaration removed from `mod k32 { extern .. }` must
    go inside it: callers spell it `k32::HeapAlloc` (ole32's winrt_string.rs)."""
    best = None
    for m in _INLINE_MOD.finditer(text, 0, at):
        depth, k = 0, m.end() - 1
        while k < len(text):
            if text[k] == "{":
                depth += 1
            elif text[k] == "}":
                depth -= 1
                if depth == 0:
                    break
            k += 1
        if m.end() <= at < k:
            best = m.end()
    return best


def _norm_attrs(attrs: str) -> str:
    return " ".join(attrs.split())


def convert(
    files: dict[str, str],
    home: dict[str, str],
    mark: str,
    attrs_of: dict[str, str] | None = None,
) -> tuple[dict, list[str]]:
    """({module: new text} for changed modules, report lines). A generated module (a
    bindgen island, `types_<arch>.rs`) is never edited: its declarations are the C header's,
    the very signatures the hand-written ones are being replaced by."""
    changed, report = {}, []
    attrs_of = attrs_of or {}
    for mod, text in files.items():
        if GENERATED.search(text[:2048]):
            continue
        new, uses = text, []
        for n, where in home.items():
            if where == mod:
                continue
            r, found, vis, inner = decl_re(n), False, "", None
            want = attrs_of.get(n, "")
            pos = 0
            while m := r.search(new, pos):
                if _norm_attrs(m.group("attrs")) != want:
                    # Same Rust name, different attributes: a `link_name` (or a cfg) can bind a
                    # different symbol on some arch (menuband's GetWindowLongPtrW is
                    # GetWindowLongW on 32-bit). Never merged; left for a human.
                    line = new.count("\n", 0, m.start()) + 1
                    report.append(f"KEPT {mod}.rs:{line}: {n}: attributes differ from the one kept")
                    pos = m.end()
                    continue
                line = new.count("\n", 0, m.start()) + 1
                report.append(f"{mod}.rs:{line}: {' '.join(m.group(0).split())}")
                inner = inner if inner is not None else _inline_mod_at(new, m.start())
                new = new[: m.start()] + new[m.end() :]
                found = True
                # A `pub` declaration may be what other modules import the name through
                # (kernel32: `use crate::proc_getters::CloseHandle`), so the `use` keeps it.
                vis = vis or (m.group("vis") or "").strip()
            if found:
                prefix = f"{vis} " if vis else ""
                line = f"{prefix}use crate::{where + '::' if where else ''}{n};"
                if inner is not None:
                    new = new[:inner] + f"\n    {line}" + new[inner:]
                else:
                    uses.append(line)
        if uses:
            changed[mod] = insert_uses(new, uses, mark)
        elif new != text:
            changed[mod] = new
    return changed, report


def module_key(rel: str) -> str:
    """`windows/rect.rs` -> `windows::rect`; `windows/mod.rs` -> `windows`; `lib.rs` -> ``."""
    parts = rel.removesuffix(".rs").split("/")
    if parts[-1] == "mod" or (len(parts) == 1 and parts[0] in ("lib", "main")):
        parts = parts[:-1]
    return "::".join(parts)


_MOD = re.compile(
    r"^[ \t]*((?:#\[[^\]\n]*\][ \t]*\n?[ \t]*)*)(?:pub\b(?:\([^)]*\))?\s+)?mod\s+(\w+)\s*;", re.M
)
_PATH_ATTR = re.compile(r'#\[path\s*=\s*"([^"]+)"\]')
_PATHS: dict[str, Path] = {}


def module_files(src: Path) -> dict[str, str]:
    """{module path: text}, walking the crate's real `mod` tree from lib.rs/main.rs, so a
    `#[path = "reg/reg.rs"] mod reg;` is `crate::reg` (advapi32), not `crate::reg::reg`. Files
    the tree never reaches are left out. Two cfg'd `mod x;` at different #[path]s (per-arch
    twins) both map to `x`; the later wins, which only matters for generated islands."""
    root = next((src / n for n in ("lib.rs", "main.rs") if (src / n).is_file()), None)
    out: dict[str, str] = {}
    if root is None:
        return out

    def walk(path: Path, key: str, is_dir_owner: bool) -> None:
        if not path.is_file() or (key in out and _PATHS.get(key) == path):
            return
        text = path.read_text()
        out[key] = text
        _PATHS[key] = path
        # Children of lib.rs / mod.rs live beside it; of foo.rs, in foo/.
        base = path.parent if is_dir_owner else path.parent / path.stem
        for m in _MOD.finditer(text):
            name = m.group(2)
            inline = _inline_mods_around(text, m.start(2))
            child_key = "::".join([k for k in [key, *inline] if k] + [name])
            mbase = base.joinpath(*inline)
            attr = _PATH_ATTR.search(m.group(1))
            if attr:
                walk(path.parent / attr.group(1), child_key, attr.group(1).endswith("mod.rs"))
            elif (mbase / f"{name}.rs").is_file():
                walk(mbase / f"{name}.rs", child_key, False)
            else:
                walk(mbase / name / "mod.rs", child_key, True)

    walk(root, "", True)
    return out


def module_path(src: Path, key: str) -> Path:
    """The file a module key came from (recorded by module_files, else by layout)."""
    if key in _PATHS:
        return _PATHS[key]
    for cand in (
        [src / "lib.rs", src / "main.rs"]
        if not key
        else [src / (key.replace("::", "/") + ".rs"), src / key.replace("::", "/") / "mod.rs"]
    ):
        if cand.is_file():
            return cand
    raise SystemExit(f"no file for module `{key}` under {src}")


MARK_CANON = "// One declaration per external symbol: the variant matching the C prototype."


def canonical_attrs(text: str, name: str, line: int) -> str:
    """The normalized attributes on the declaration whose `fn` line is `line`."""
    for m in decl_re(name).finditer(text):
        if text.count("\n", 0, m.start() + len(m.group("attrs"))) + 1 == line:
            return _norm_attrs(m.group("attrs"))
    raise SystemExit(f"{name}: no declaration at line {line}")


def promote(text: str, name: str, line: int) -> str:
    """Make the bodiless declaration of `name` starting at `line` (1-based) `pub`,
    so the crate's other modules can `use` it (and re-export it, where the removed
    declaration was `pub` and other modules imported through it). Refuses if it is not there."""
    for m in decl_re(name).finditer(text):
        fn_at = m.start() + len(m.group("attrs"))
        if text.count("\n", 0, fn_at) + 1 == line:
            if m.group("vis"):
                return text
            at = fn_at + len(text[fn_at : m.end()]) - len(text[fn_at : m.end()].lstrip())
            return text[:at] + "pub " + text[at:]
    raise SystemExit(f"{name}: no declaration at line {line}")


def apply_canonical(src: Path, rows: list[dict]) -> tuple[dict[str, str], list[str]]:
    """Graded rows (`{"name", "canonical": {"module", "line"}}`) -> ({module: new text},
    report): promote each canonical declaration, then replace every other module's
    declaration of that name with a `use` of it. Rows without a canonical are skipped."""
    files = module_files(src)
    report: list[str] = []
    home: dict[str, str] = {}
    attrs: dict[str, str] = {}
    for r in rows:
        c = r.get("canonical")
        if not c:
            report.append(f"SKIP {r['name']}: no OK variant")
            continue
        files[c["module"]] = promote(files[c["module"]], r["name"], int(c["line"]))
        home[r["name"]] = c["module"]
        attrs[r["name"]] = canonical_attrs(files[c["module"]], r["name"], int(c["line"]))
    changed, removed = convert(files, home, MARK_CANON, attrs)
    for mod in {c["module"] for r in rows if (c := r.get("canonical"))}:
        changed.setdefault(mod, files[mod])
    return changed, report + removed


def from_census(root: Path, census: Path, crates: list[str], dry_run: bool) -> int:
    """The crate-defined half of every clash the census names, per crate: each becomes a
    `use` of the definition. The rest (external symbols) are listed for `--canonical`."""
    by: dict[str, set[str]] = {}
    for x in json.loads(census.read_text()):
        if x["lint"] != "clashing_extern_declarations":
            continue
        m = re.search(r"`(\w+)`", x["msg"])
        if m:
            by.setdefault(x["path"].split("/")[0], set()).add(m.group(1))
    for crate in crates or sorted(by):
        src = root / crate / "src"
        files = module_files(src)
        home: dict[str, str] = {}
        ext: list[str] = []
        for n in sorted(by.get(crate, ())):
            try:
                home.update(find_defs(files, [n]))
            except SystemExit:
                ext.append(n)
        changed, report = convert(files, home, MARK_OWN) if home else ({}, [])
        if not dry_run:
            for mod, text in changed.items():
                module_path(src, mod).write_text(text)
        print(f"{crate}: own {len(home)} ({len(report)} decls removed), external {len(ext)}")
        for line in report:
            print(f"  {line}")
        if ext:
            print(f"  external (grade, then --canonical): {','.join(ext)}")
    return 0


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("src", type=Path, help="the crate's src/ directory")
    ap.add_argument("names", nargs="?", default="", help="comma-separated function names")
    ap.add_argument(
        "--canonical",
        type=Path,
        help="graded JSONL ({name, canonical: {module, line}}): promote that variant, use it",
    )
    ap.add_argument("--to", help="module holding the one declaration (external symbols)")
    ap.add_argument(
        "--census",
        type=Path,
        help="`rust_warning_census.py --json` output: take each crate's clashing names from "
        "it; `src` is then sdk/lib/rust, and --crate picks crates (repeatable)",
    )
    ap.add_argument("--crate", action="append", default=[], help="with --census")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args(argv)

    if a.census:
        return from_census(a.src, a.census, a.crate, a.dry_run)

    if a.canonical:
        rows = [json.loads(x) for x in a.canonical.read_text().splitlines() if x.strip()]
        changed, report = apply_canonical(a.src, rows)
        print("\n".join(report))
        if not a.dry_run:
            for mod, text in changed.items():
                module_path(a.src, mod).write_text(text)
        return 0
    files = module_files(a.src)
    names = [n for n in a.names.split(",") if n]
    home = {n: a.to for n in names} if a.to else find_defs(files, names)
    mark = MARK_TO.format(to=a.to) if a.to else MARK_OWN
    changed, report = convert(files, home, mark)
    print("\n".join(report))
    print(f"{len(report)} declaration(s) removed in {len(changed)} module(s)", file=sys.stderr)
    if not a.dry_run:
        for mod, text in changed.items():
            module_path(a.src, mod).write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
