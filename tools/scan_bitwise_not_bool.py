#!/usr/bin/env python3
"""
scan_bitwise_not_bool.py — C's `!x` is LOGICAL not; Rust's `!x` on an integer is BITWISE.

    C:            if (!(flags & DEV_POWER_PROTECTED))
    translated:   if !(flags & 0x10) != 0          <-- always true
    faithful:     if (flags & 0x10) == 0

For any integer `x`, `!x` is zero only when `x` is all-ones, so `!x != 0` is true for
every value a flag test can produce. The condition does not merely read oddly — it is
a CONSTANT, and it compiles clean, types fine, and triggers no rustc lint. Nothing but
reading the C tells you the branch is dead.

Found 2026-07-26, eight sites, and only three were in assertions. The other five were
live control flow:

  * disk-rust `ADJUST_FUA_FLAG` — `DEV_WRITE_CACHE && !DEV_POWER_PROTECTED &&
    !CLASS_SPECIAL_FUA_NOT_SUPPORTED` collapsed to `DEV_WRITE_CACHE` alone, forcing
    Force Unit Access onto power-protected devices and onto devices that had
    explicitly reported FUA unsupported;
  * win32k `rtl_text` — an always-true arm of a `||` disabled the CJK line-break rule
    in word wrapping;
  * kernel32 `DuplicateConsoleHandle` — the DUPLICATE_SAME_ACCESS validation arm;
  * scsiport — only the null half of `ASSERT(Lun && !Lun->Common.IsFDO)` survived.

TWO IDIOMS THIS MUST NOT FLAG, both extremely common and both correct:

  * `x & !MASK != 0` — the unknown-flag test ("any bit set outside MASK?"). Here the
    `!` is genuinely bitwise and genuinely wanted. Detected by the `&`/`|`/`^` before
    the `!` — and note `&&` must NOT be treated as `&`.
  * `offset_of!(T, f) == 0`, `assert!(...)` — a MACRO bang, not an operator. Detected
    by an identifier character before the `!`.

Getting those wrong is not a small matter of noise: the first draft of this scanner
reported 4710 sites, essentially all of them these two idioms, which is indistinguishable
from having no scanner at all.

Also flagged: `!!x`. C uses it to normalise a value to 0/1; in Rust it is two NOTs,
the identity on a bool AND on an integer, so it is never the C. ws2_32's getxyDataEnt
carried `if !!IsEqualGUID(..)` for C's `if (!IsEqualGUID(..))`, an inverted condition
that made every gethostbyname fail WSANO_DATA (2026-10-04).

Usage:
    python3 tools/scan_bitwise_not_bool.py            # report
    python3 tools/scan_bitwise_not_bool.py --lint     # terse (CLI baseline gate)

Exit 1 if any finding.
"""

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tools.source_walk import source_files

REPO = Path(__file__).resolve().parent.parent
RUST_ROOT = REPO / "sdk" / "lib" / "rust"

SKIP_PATH_RE = re.compile(r"(/target/|/\.responses/)")
NOLINT_RE = re.compile(r"//\s*nolint(?::\s*bitwise-not-bool\b|\s*$|:?\s*\()")

# Generated files are identified by CONTENT. The filename cannot decide it: `types_amd64.rs`
# IS bindgen output while `winldr_amd64.rs` is hand-written arch-specific freeldr source,
# and `bindgen_common.rs` is generated but carries no bindgen banner at all.
GEN_MARKERS = (
    "automatically generated by rust-bindgen",
    "@generated",
    "Do not edit manually",
)

# A `!` applied to something that starts a value expression.
UNARY_NOT_RE = re.compile(r"!(?=[A-Za-z_(*])")
# `!!expr` as an operator: not a macro bang (identifier before it) and not `!!!`.
DOUBLE_NOT_RE = re.compile(r"(?<![A-Za-z0-9_!])!!(?=[A-Za-z_(*])")
STRING_RE = re.compile(r'b?"(?:\\.|[^"\\])*"')


def is_generated(text: str) -> bool:
    return any(m in "\n".join(text.split("\n")[:6]) for m in GEN_MARKERS)


def scan_line(line: str) -> bool:
    """True if `line` compares a bitwise-NOT result against 0 at the same paren depth,
    or applies `!!` to a value."""
    if DOUBLE_NOT_RE.search(STRING_RE.sub('""', line)):
        return True
    for m in UNARY_NOT_RE.finditer(line):
        # `foo!(` / `assert!(` — a macro bang, not the not-operator. Judged on the char
        # RIGHT before the `!`: a macro's name touches its bang. Judged after rstrip,
        # `if !Success != 0` read as the macro `if!` and was skipped -- every `if !x != 0`
        # in the tree was invisible, usetup's PrepareCopyPage (setup always quit) among them.
        raw_before = line[: m.start()]
        if raw_before and (raw_before[-1].isalnum() or raw_before[-1] == "_"):
            continue
        before = raw_before.rstrip()
        # `x & !MASK` — the legitimate unknown-flag test. `&&`/`||` are NOT that.
        if before.endswith(("&", "|", "^")) and not before.endswith(("&&", "||")):
            continue
        depth = 0
        j = m.end()
        while j < len(line):
            c = line[j]
            if c in "([{":
                depth += 1
            elif c in ")]}":
                depth -= 1
                if depth < 0:
                    break
            elif depth == 0 and line[j : j + 2] in ("!=", "=="):
                rest = line[j + 2 :].lstrip()
                # `!= 0` only — `!= 0x10` or `!= 01` is a different comparison.
                if rest.startswith("0") and not rest[1:2].isdigit() and rest[:2].lower() != "0x":
                    return True
                break
            elif depth == 0 and (c in "&|" or line[j : j + 2] in ("<<", ">>")):
                # The `!` binds into a wider bitwise expression; not our shape.
                break
            j += 1
    return False


def scan_file(path: Path) -> list[tuple[int, str]]:
    try:
        text = path.read_text(errors="replace")
    except OSError:
        return []
    if is_generated(text):
        return []
    out = []
    for i, line in enumerate(text.split("\n")):
        stripped = line.strip()
        if stripped.startswith("//") or stripped.startswith("*"):
            continue
        if NOLINT_RE.search(line):
            continue
        if scan_line(line):
            out.append((i + 1, stripped[:110]))
    return out


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("-")]
    lint = "--lint" in sys.argv
    roots = [Path(a) for a in args] if args else [RUST_ROOT]

    files: list[Path] = []
    for root in roots:
        if root.is_file():
            files.append(root)
        elif root.is_dir():
            files.extend(source_files(root))

    findings = []
    for f in sorted(set(files)):
        if SKIP_PATH_RE.search(str(f)):
            continue
        for ln, src in scan_file(f):
            try:
                rel = f.relative_to(REPO)
            except ValueError:
                rel = f
            findings.append((str(rel), ln, src))

    for rel, ln, src in findings:
        if lint:
            print(f"{rel}:{ln}: bitwise-not-bool")
        else:
            print(f"{rel}:{ln}: `!x` here is BITWISE not — this comparison is constant")
            print(f"    {src}")

    if not lint:
        print(f"\n{len(findings)} site(s)")
        if findings:
            print("fix: C's `!x` is logical — write `(x & FLAG) == 0`, not `!(x & FLAG) != 0`.")
            print("     if the bitwise complement really is wanted: // nolint: bitwise-not-bool")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
