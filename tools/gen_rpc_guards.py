#!/usr/bin/env python3
"""Generate SEH-guarded wrappers for the client stubs in a widl `<name>_c.h`.

C RPC clients guard each call with `RpcTryExcept` or Wine's `__TRY`/`__EXCEPT`. The
tree builds C under DUMMY_PSEH on every arch, so those blocks compile to nothing: a
call to a dead or refusing server raises (RpcRaiseException), nothing catches it,
and the client process dies (dummy-pseh-verdict.md, "Consequence for RPC clients").

Every such try body is call-shaped, and ntdll's RtlSehTryExcept trampoline catches
exactly that case on all three arches (native SEH on amd64/arm64, a hand-built fs:[0]
frame on i386), but it takes a body CALLBACK, and C has no closures. So this tool
writes the callbacks: for every client prototype `RET f(args)` it emits

    BOOL f_guarded(RPC_GUARD_FILTER filter, DWORD *code, RET *ret, args);

which runs f(args) under the trampoline. It returns TRUE when f returned (and stores
*ret when ret is non-NULL), or FALSE when an exception was caught, with its code in
*code. `filter` is the call site's own __EXCEPT filter; NULL catches everything,
which is what RpcExcept(EXCEPTION_EXECUTE_HANDLER) means. A void stub has no ret.

The build runs this on the freshly generated header (CMake add_custom_command), so a
wrapper cannot drift from the IDL; the guard .c also includes the real header, so a
prototype this parser read wrong is a compile error, never a silent mismatch.

    gen_rpc_guards.py --header epm_c.h --prelude windef.h --prelude rpc.h \\
        --out-c epm_guard.c --out-h epm_guard.h
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

# widl prints every client prototype as `RET __cdecl NAME(\n    T a,\n    T b);`.
_PROTO = re.compile(r"^([A-Za-z_][\w \t\*]*?)[ \t]+__cdecl[ \t]+(\w+)\(\s*(.*?)\);", re.M | re.S)
_ARRAY = re.compile(r"^(.*?)\s*(\w+)\s*\[[^\]]*\]$")
_PLAIN = re.compile(r"^(.*?[\s\*])(\w+)$")


@dataclass
class Param:
    type: str
    name: str


@dataclass
class Proto:
    ret: str
    name: str
    params: list[Param]


def _split_params(text: str) -> list[str]:
    parts, depth, cur = [], 0, []
    for ch in text:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(cur))
            cur = []
        else:
            cur.append(ch)
    parts.append("".join(cur))
    return [" ".join(p.split()) for p in parts if p.strip()]


def _param(text: str) -> Param:
    m = _ARRAY.match(text)
    if m:  # `T name[]` decays to `T *name`, which is what the stub receives
        return Param(m.group(1).strip() + " *", m.group(2))
    m = _PLAIN.match(text)
    if not m or "(" in text:
        raise ValueError(f"unsupported parameter {text!r}")
    return Param(m.group(1).strip(), m.group(2))


def parse_header(text: str) -> list[Proto]:
    """Client prototypes of a widl `_c.h` (server `s_` prototypes are skipped)."""
    out = []
    for m in _PROTO.finditer(text):
        ret, name, params = " ".join(m.group(1).split()), m.group(2), m.group(3).strip()
        plist = [] if params in ("", "void") else [_param(p) for p in _split_params(params)]
        out.append(Proto(ret, name, plist))
    if not out:
        raise ValueError("no `__cdecl` client prototypes found; is this a widl _c.h?")
    return out


def _decl(t: str, name: str) -> str:
    return f"{t}{name}" if t.endswith("*") else f"{t} {name}"


def _signature(p: Proto) -> str:
    # guard_ prefixes keep the wrapper's own names clear of the stub's parameters.
    args = ["RPC_GUARD_FILTER guard_filter", "DWORD *guard_code"]
    if p.ret != "void":
        args.append(_decl(p.ret + " *", "guard_ret"))
    args += [_decl(a.type, a.name) for a in p.params]
    return f"BOOL {p.name}_guarded({', '.join(args)})"


def render(protos: list[Proto], header: str, preludes: list[str], guard_h: str) -> tuple[str, str]:
    banner = f"/* Generated by tools/gen_rpc_guards.py from {header}. Do not edit. */\n"
    macro = re.sub(r"\W", "_", Path(guard_h).name).upper()
    h = [banner, f"#ifndef {macro}\n#define {macro}\n"]
    h.append("/* An __EXCEPT filter: EXCEPTION_EXECUTE_HANDLER catches, CONTINUE_SEARCH passes. */")
    h.append("typedef LONG (WINAPI *RPC_GUARD_FILTER)(EXCEPTION_POINTERS *);\n")
    # Declared here too, so a module's own call-shaped guards (not RPC) can use it.
    h.append("/* ntdll's trampoline (ntoskrnl/sehtry.c): TRUE when Filter took an exception. */")
    h.append(
        "unsigned char __cdecl RtlSehTryExcept(void (__cdecl *Body)(void *), void *BodyContext,\n"
        "                                      long (__cdecl *Filter)(void *, void *),\n"
        "                                      void *FilterContext, long *ExceptionCode);\n"
    )
    h += [_signature(p) + ";" for p in protos]
    h.append(f"\n#endif /* {macro} */\n")

    c = [banner]
    c += [f'#include "{inc}"' if not inc.startswith("<") else f"#include {inc}" for inc in preludes]
    c.append(f'#include "{header}"')
    c.append(f'#include "{Path(guard_h).name}"\n')
    c.append("struct rpc_guard_filter { RPC_GUARD_FILTER filter; };\n")
    c.append("static long __cdecl rpc_guard_filter(void *context, void *pointers)\n{")
    c.append("    RPC_GUARD_FILTER filter = ((struct rpc_guard_filter *)context)->filter;\n")
    c.append("    return filter ? filter(pointers) : EXCEPTION_EXECUTE_HANDLER;\n}\n")
    for p in protos:
        fields = ([_decl(p.ret, "guard_ret") + ";"] if p.ret != "void" else []) + [
            _decl(a.type, a.name) + ";" for a in p.params
        ]
        if not fields:
            fields = ["int unused;"]
        call = f"{p.name}({', '.join('a->' + a.name for a in p.params)})"
        c.append(f"struct {p.name}_args {{ {' '.join(fields)} }};\n")
        c.append(f"static void __cdecl {p.name}_body(void *context)\n{{")
        c.append(f"    struct {p.name}_args *a = context;")
        c.append(f"    {'a->guard_ret = ' if p.ret != 'void' else ''}{call};\n}}\n")
        c.append(_signature(p) + "\n{")
        c.append(f"    struct {p.name}_args a;")
        c.append("    struct rpc_guard_filter f = { guard_filter };")
        c.append("    long caught = 0;\n")
        c.append("    memset(&a, 0, sizeof(a));")
        c += [f"    a.{x.name} = {x.name};" for x in p.params]
        c.append(f"    if (RtlSehTryExcept({p.name}_body, &a, rpc_guard_filter, &f, &caught))")
        c.append("    {\n        if (guard_code) *guard_code = (DWORD)caught;")
        c.append("        return FALSE;\n    }")
        if p.ret != "void":
            c.append("    if (guard_ret) *guard_ret = a.guard_ret;")
        c.append("    return TRUE;\n}\n")
    return "\n".join(h), "\n".join(c)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--header", required=True, help="widl client header (<name>_c.h)")
    ap.add_argument("--prelude", action="append", default=[], help="header the stub needs first")
    ap.add_argument("--out-c", required=True)
    ap.add_argument("--out-h", required=True)
    args = ap.parse_args(argv)
    try:
        protos = parse_header(Path(args.header).read_text())
    except ValueError as e:
        print(f"gen_rpc_guards: {args.header}: {e}", file=sys.stderr)
        return 1
    h, c = render(protos, Path(args.header).name, ["<string.h>", *args.prelude], args.out_h)
    Path(args.out_h).write_text(h)
    Path(args.out_c).write_text(c)
    return 0


if __name__ == "__main__":
    sys.exit(main())
