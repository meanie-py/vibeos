#!/usr/bin/env python3
"""
migrate_debug_assert.py — turn dead `debug_assert!` back into a live C `ASSERT`.

THE GAP. CMake builds the C with `-DDBG=1`, so every C `ASSERT`/`NT_ASSERT` these
were translated from expands to `RtlAssert` and fires loudly. The Rust does not:
`debug_assert!` is gated on `cfg(debug_assertions)`, the workspace
`[profile.release]` never sets `debug-assertions`, and every kernel crate builds
`--release`. So the translated assertion is dead code in the shipping image while
its C original is live — we are strictly weaker than the code we replaced.

That is not theoretical. Field manual §9.135: an assertion forbidding `SegCs == 0`
was walked straight past by a boot that printed `SegCs=0x0`. Live, it would have
caught a blank trap frame AT ITS SOURCE instead of surfacing later as an unhandled
probe raise that bugchecked the box.

WHY NOT JUST FLIP `debug-assertions = true`. Two reasons, and the second is fatal:

  1. `overflow-checks` defaults to FOLLOWING `debug-assertions`, so the flip also
     arms kernel-wide arithmetic panics — a separate and much riskier change that
     the C never had.
  2. A live `debug_assert!` PANICS, and a Rust panic in kernel mode is a SILENT
     HANG: the #[panic_handler] prints `PANIC:<file>:<line>` to debugcon and then
     loops forever. No bugcheck, no dump, no marker. Flipping the flag would
     convert every one of these into the worst of the three assert lowerings (see
     §9.120) all at once.

So we substitute the macro instead. `ntkrnl_sys::ASSERT!` expands to `RtlAssert`,
which is exactly what the C calls under DBG: it PRINTS and RETURNS. Assertions
become visible rather than fatal, which is the whole point — an assert that takes
the box down is not a diagnostic.

WHAT IT REFUSES TO DO. `ASSERT!` builds its message with `concat!`, so the message
must be a literal. An invocation with format ARGUMENTS (`debug_assert!(c, "x {}", y)`)
is reported and left alone rather than silently dropping the interpolation. Same for
anything whose parens do not balance cleanly. Silent partial application is the
failure mode this whole file exists to avoid.

Usage:
    python3 tools/migrate_debug_assert.py                  # report
    python3 tools/migrate_debug_assert.py --apply          # rewrite
    python3 tools/migrate_debug_assert.py --crate ex-rust  # scope to one crate
"""

import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
RUST_ROOT = REPO / "sdk" / "lib" / "rust"

# A generated file is identified by CONTENT, never by name. Both directions of the
# filename guess are wrong here: `types_amd64.rs` IS bindgen output while
# `winldr_amd64.rs` is hand-written arch-specific freeldr source, and
# `bindgen_common.rs` is generated but carries no bindgen banner — it says
# "Do not edit manually" in a `//!` doc header instead. Keying on the name
# over-counted the population by 1472 and under-counted the real one by 80.
GEN_MARKERS = (
    "automatically generated by rust-bindgen",
    "@generated",
    "Do not edit manually",
)

# The leading path must be CONSUMED, not left behind. `\bdebug_assert!` happily matches
# after the `::` in `core::debug_assert!(x)`, and replacing only the tail produces
# `core::ntkrnl_sys::ASSERT!(x)` — 15 files were rewritten that way on the first run.
# The lookbehind stops the same match from firing inside `my_debug_assert!`.
MACRO_RE = re.compile(r"(?<![A-Za-z0-9_])(?:[A-Za-z_]\w*::)*debug_assert(_eq|_ne)?!\s*\(")
SKIP_PATH_RE = re.compile(r"(/target/|/\.responses/)")


def is_generated(text: str) -> bool:
    return any(m in "\n".join(text.split("\n")[:6]) for m in GEN_MARKERS)


def match_paren(text: str, open_idx: int) -> int:
    """Index just past the `)` closing the `(` at open_idx, or -1.

    String/char/comment aware, because an assertion message routinely contains a
    parenthesis and a lifetime tick reads exactly like an unterminated char.
    """
    depth = 0
    i = open_idx
    n = len(text)
    while i < n:
        c = text[i]
        if c == "\\":
            i += 2
            continue
        if c == '"':
            i += 1
            while i < n and text[i] != '"':
                i += 2 if text[i] == "\\" else 1
            i += 1
            continue
        if c == "'":
            # A lifetime (`'a`) is not a char literal. A char literal is 'x' or '\n'.
            if i + 2 < n and (text[i + 1] == "\\" or (i + 2 < n and text[i + 2] == "'")):
                i += 1
                while i < n and text[i] != "'":
                    i += 2 if text[i] == "\\" else 1
                i += 1
            else:
                i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            while i < n and text[i] != "\n":
                i += 1
            continue
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return -1


def split_args(inner: str) -> list[str]:
    """Top-level comma split, honouring (), [], {}, strings and chars."""
    out, buf, depth, i, n = [], [], 0, 0, len(inner)
    while i < n:
        c = inner[i]
        if c == "\\":
            buf.append(inner[i : i + 2])
            i += 2
            continue
        if c == '"':
            j = i + 1
            while j < n and inner[j] != '"':
                j += 2 if inner[j] == "\\" else 1
            buf.append(inner[i : j + 1])
            i = j + 1
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == "," and depth == 0:
            out.append("".join(buf).strip())
            buf = []
            i += 1
            continue
        buf.append(c)
        i += 1
    if "".join(buf).strip():
        out.append("".join(buf).strip())
    return out


LITERAL_MSG_RE = re.compile(r'^(b?"(?:\\.|[^"\\])*")$', re.S)


def convert(text: str) -> tuple[str, int, list[str]]:
    """Rewrite every convertible invocation. Returns (new_text, n_done, skipped)."""
    skipped: list[str] = []
    done = 0
    out = []
    pos = 0
    for m in MACRO_RE.finditer(text):
        if m.start() < pos:
            continue  # inside a region already consumed
        open_idx = m.end() - 1
        close = match_paren(text, open_idx)
        line_no = text.count("\n", 0, m.start()) + 1
        if close < 0:
            skipped.append(f"line {line_no}: unbalanced parens")
            continue
        kind = m.group(1)  # None | '_eq' | '_ne'
        args = split_args(text[open_idx + 1 : close - 1])
        if kind:
            if len(args) < 2:
                skipped.append(f"line {line_no}: debug_assert{kind}! with {len(args)} arg(s)")
                continue
            cond = f"{args[0]} {'==' if kind == '_eq' else '!='} {args[1]}"
            rest = args[2:]
        else:
            if not args:
                skipped.append(f"line {line_no}: debug_assert! with no argument")
                continue
            cond = args[0]
            rest = args[1:]
        if len(rest) > 1:
            # A format string with interpolation. ASSERT! concat!s its message, so
            # converting would silently drop the arguments — refuse instead.
            skipped.append(f"line {line_no}: message has format args ({len(rest)} extra)")
            continue
        if rest and not LITERAL_MSG_RE.match(rest[0]):
            skipped.append(f"line {line_no}: message is not a literal ({rest[0][:40]})")
            continue
        new = f"ntkrnl_sys::ASSERT!({cond}{', ' + rest[0] if rest else ''})"
        out.append(text[pos : m.start()])
        out.append(new)
        pos = close
        done += 1
    out.append(text[pos:])
    return "".join(out), done, skipped


# `RtlAssert` IS NOT ONE FUNCTION, and which one you get is a property of the
# LINK, not of the crate. The kernel's (rtl-diag/src/assert.rs) prints, caps at 20
# and RETURNS -- that behaviour is the entire safety argument for this migration.
# The BOOT LOADER links its own (freeldr-rust/src/debug.rs), which prints and then
# calls DbgBreakPoint(); on arm64 that is a real `brk #0xF000` and it WEDGES THE
# BOOT. i386/amd64 have an empty DbgBreakPoint stub, so the same assertion prints
# and sails on there -- which is why this failed on exactly one arch and sat
# rejected for three weeks.
#
# Filtering by crate name cannot express this: hal-rust is in BOTH links. So
# discover the loader link set instead of hardcoding it -- the loader is whichever
# `*-cargo` binary links freeldr-rust, and its `.rust_lib()`/.rust_staticlib()`
# calls name everything that lands in that binary. The producer has the list; the
# consumer must not carry a literal copy of it.
LOADER_LIB_RE = re.compile(r'\.rust_(?:static)?lib\(\s*"([A-Za-z0-9_-]+)"')


def loader_crates() -> set[str]:
    """Crates linked into a boot loader, where ASSERT! is FATAL on arm64."""
    out: set[str] = set()
    for br in RUST_ROOT.glob("*-cargo/build.rs"):
        try:
            text = br.read_text()
        except OSError:
            continue
        if '.rust_staticlib("freeldr-rust")' not in text:
            continue
        out |= set(LOADER_LIB_RE.findall(text))
    return out


def kernel_crates() -> set[str]:
    """Crates that can reach ntkrnl_sys::ASSERT!. Usermode crates link ntdll's
    RtlAssert instead and need their own macro — a separate change."""
    out = set()
    for ct in RUST_ROOT.glob("*/Cargo.toml"):
        try:
            if "ntkrnl-sys" in ct.read_text():
                out.add(ct.parent.name)
        except OSError:
            pass
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true", help="write the changes")
    ap.add_argument("--crate", help="limit to one crate")
    args = ap.parse_args()

    kern = kernel_crates()
    loaders = kernel_crates() & loader_crates()
    total_done = total_skipped = 0
    touched = 0
    skip_report: list[str] = []

    for p in sorted(RUST_ROOT.rglob("*.rs")):
        if SKIP_PATH_RE.search(str(p)):
            continue
        crate = p.relative_to(RUST_ROOT).parts[0]
        if crate not in kern or (args.crate and crate != args.crate):
            continue
        try:
            text = p.read_text()
        except OSError:
            continue
        if is_generated(text) or not MACRO_RE.search(text):
            continue
        new, done, skipped = convert(text)
        if skipped:
            skip_report += [f"  {p.relative_to(REPO)}:{s}" for s in skipped]
        total_skipped += len(skipped)
        if done:
            total_done += done
            touched += 1
            if args.apply:
                p.write_text(new)

    print(
        f"{'converted' if args.apply else 'convertible'}: {total_done} site(s) "
        f"in {touched} file(s) across {len(kern)} kernel crate(s)"
    )
    if skip_report:
        print(f"\nSKIPPED {total_skipped} (left as debug_assert!, nothing dropped silently):")
        for s in skip_report:
            print(s)
    if loaders:
        print(
            "\nWARNING — these crates also link into a BOOT LOADER, where RtlAssert ends in\n"
            "DbgBreakPoint() (a real `brk #0xF000` on arm64, an empty stub on i386/amd64).\n"
            "A live assertion that FIRES there wedges the arm64 boot instead of printing:\n"
            "    " + ", ".join(sorted(loaders)) + "\n"
            "  Converting them is allowed and currently green, but SMOKE ARM64 before landing —\n"
            "  amd64 and i386 cannot reproduce the failure."
        )
    if not args.apply:
        print("\n(report only — pass --apply to write)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
