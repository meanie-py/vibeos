def parse_params(sig: str) -> list[tuple[str, str]]:
    """Crude C-prototype param split → [(ctype, name)]. Sufficient for
    the sample's shapes (no function pointers / varargs here)."""
    inner = sig[sig.index("(") + 1 : sig.rindex(")")].strip()
    if inner in ("", "void"):
        return []
    out = []
    for part in inner.split(","):
        toks = part.strip().replace("*", " * ").split()
        name = toks[-1]
        ctype = " ".join(toks[:-1])
        out.append((ctype, name))
    return out


# Rust FFI types for the C types the sample uses.
def rs_ty(ctype: str) -> str:
    c = ctype.replace(" ", "")
    return {
        "constchar*": "*const u8",
        "charconst*": "*const u8",  # east-const spelling
        "wchar_tconst*": "*const u16",
        "constwchar_t*": "*const u16",
        "wchar_t**": "*mut *mut u16",
        "char*": "*mut u8",
        "constvoid*": "*const core::ffi::c_void",
        "void*": "*mut core::ffi::c_void",
        "char**": "*mut *mut u8",
        "wchar_t*": "*mut u16",
        "wchar_t": "u16",
        "size_t": "usize",
        "int": "i32",
        "wint_t": "u16",  # Windows wint_t == unsigned short
        "__int64": "i64",
        "unsigned__int64": "u64",
        "long": "i32",  # Win i386 LP32
        "unsignedlong": "u32",
        "unsigned": "u32",
        "unsignedint": "u32",
        "_locale_t": "*mut core::ffi::c_void",  # ignored
    }[c]


_CC = {"__cdecl", "CDECL", "__stdcall", "WINAPI", "NTAPI"}


def ret_ty(sig: str) -> str:
    # "void *memcpy" / "__int64 _atoi64" / "long atol" / "int atoi"
    head = sig.split("(", 1)[0].strip()
    toks = [t for t in head.replace("*", " * ").split() if t not in _CC]
    rtype = "".join(toks[:-1])  # drop the function-name token
    return {
        "size_t": "usize",
        "int": "i32",
        "long": "i32",  # Win i386 LP32: long == 32-bit
        "unsignedlong": "u32",
        "unsignedlonglong": "u64",
        "unsigned__int64": "u64",
        "wint_t": "u16",
        "__int64": "i64",
        "char*": "*mut u8",
        "wchar_t*": "*mut u16",
        "void*": "*mut core::ffi::c_void",
        "void": "()",  # _splitpath/_makepath etc. return nothing
    }[rtype]


# int→str family (itoa.c / itow.c). Each shim is fully self-contained
# (its own param-validation / ERANGE-backfill / byte-count contract),
# so it bypasses the generic slice-reconstruct + return-collapse path.
INT2STR = {
    "int_to_str",  # unchecked narrow: memcpy digits+NUL, no NULL guard
    "int_to_wstr",  # unchecked wide:   NULL-guarded, returns dst (even NULL)
    "s_erange_n",  # _s narrow: bad-param→str[0]=0,EINVAL; too-small→
    #            reverse-backfill+str[0]=0,ERANGE
    "s_einval_n",  # _ui64toa_s: bad-param→EINVAL (no zero); too-small→
    #             EINVAL (no fill)
    "s_erange_w",  # _s wide: as s_erange_n, u16 elements
    "s_einval_w",  # _ui64tow_s: as s_einval_n + the *byte-count* bug
    #             (memcpy ndigits+1 BYTES, not *2)
}


def _mag_prologue(vt: str, v: str, rad: str) -> str:
    """Faithful magnitude+sign derivation per the value's C width:
    sign only when `radix == 10 && value < 0`; otherwise the C
    reinterprets the value's own-width bit pattern as unsigned."""
    if vt == "i64":
        return (
            f"    let neg = {rad} == 10 && {v} < 0;\n"
            f"    let mag = if neg {{ ({v} as i64).unsigned_abs() }} "
            f"else {{ {v} as u64 }};"
        )
    if vt == "i32":
        return (
            f"    let neg = {rad} == 10 && {v} < 0;\n"
            f"    let mag = if neg {{ ({v} as i32).unsigned_abs() as u64 }} "
            f"else {{ {v} as u32 as u64 }};"
        )
    if vt == "u64":
        return f"    let neg = false;\n    let mag = {v};"
    if vt == "u32":
        return f"    let neg = false;\n    let mag = {v} as u64;"
    raise SystemExit(f"int2str: unsupported value type {vt}")


# tcscpy/tcscat/tcsncat — raw unbounded dst (libc `strcpy` trusts the
# caller's buffer; no size param). Self-contained, element-generic via
# the dst pointer width (`*mut u8` narrow / `*mut u16` wide).
STRFAM = {"strcpy_like", "strcat_like", "strncat_like"}


def _strfam_shim(name: str, m: dict, params, rt: str) -> str:
    sp = m["slice_pattern"]
    decl = ", ".join(f"{n}: {rs_ty(t)}" for t, n in params)
    pn = [n for _, n in params]
    dst_ty = rs_ty(params[0][0])
    wide = dst_ty == "*mut u16"
    el = "u16" if wide else "u8"
    cstr = "wcstr_slice" if wide else "cstr_slice"
    rawm = "wraw_mut_slice" if wide else "raw_mut_slice"
    b: list[str] = []
    if sp == "strcpy_like":
        to, fr = pn
        b += [
            f"    let s = {cstr}({fr});",
            "    let m = s.len();",
            f"    let d = {rawm}({to}, m + 1);",
            "    crate::core_rs::string::cpy(d, s);",
            f"    {to}",
        ]
    elif sp == "strcat_like":
        s, ap = pn
        b += [
            f"    let dl = {cstr}({s} as *const {el}).len();",
            f"    let a = {cstr}({ap});",
            "    let m = a.len();",
            f"    let tail = {rawm}({s}.add(dl), m + 1);",
            "    crate::core_rs::string::cat(tail, a);",
            f"    {s}",
        ]
    elif sp == "strncat_like":
        d, src, n = pn
        cstr_b = "wcstr_slice_bounded" if wide else "cstr_slice_bounded"
        b += [
            f"    if {n} == 0 {{ return {d}; }}",
            f"    let dl = {cstr}({d} as *const {el}).len();",
            # src bounded to n — strncat appends min(strlen(src),n); an
            # unbounded scan over-reads a non-terminated src past n.
            f"    let sc = {cstr_b}({src}, {n});",
            f"    let m = if sc.len() < {n} {{ sc.len() }} else {{ {n} }};",
            f"    let tail = {rawm}({d}.add(dl), m + 1);",
            f"    crate::core_rs::string::ncat(tail, sc, {n});",
            f"    {d}",
        ]
    else:
        raise SystemExit(f"{name}: unhandled strfam pattern {sp}")
    misf = m.get("preserved_misfeature", "")
    return (
        f"/// `{m['c_signature']}`\n"
        f"/// preserved misfeature: {misf}\n"
        f"#[no_mangle]\n"
        f'pub unsafe extern "C" fn {name}({decl}) -> {rt} {{\n' + "\n".join(b) + "\n}\n"
    )


# Multibyte ⇄ wide (CP1252 single-byte model). Self-contained shims:
# the genuine .c are thin Rtl* wrappers; cnt-rust folds the Rtl* model
# into core_rs::mbcp and the shim just adapts the C ptr ABI.
MBCP = {"mbtowc", "mbstowcs", "wctomb", "wcstombs", "toupper_mb"}


def _mbcp_shim(name: str, m: dict, params, rt: str) -> str:
    sp = m["slice_pattern"]
    decl = ", ".join(f"{n}: {rs_ty(t)}" for t, n in params)
    pn = [n for _, n in params]
    b: list[str] = []
    if sp == "mbtowc":
        wc, mb, cnt = pn  # wchar*, mbchar(const char*), count
        b += [
            f"    if {mb}.is_null() || {wc}.is_null() {{ return 0; }}",
            f"    let take = if {cnt} < 2 {{ {cnt} }} else {{ 2 }};",
            f"    let s = core::slice::from_raw_parts({mb}, take);",
            "    let r = crate::core_rs::mbcp::mbtowc(s);",
            "    if r.ret == -1 { return -1; }",
            f"    *{wc} = r.wc;",
            "    r.ret",
        ]
    elif sp == "mbstowcs":
        wc, mb, cnt = pn
        b += [
            f"    let s = cstr_slice({mb});",
            f"    if {wc}.is_null() {{ return s.len() as {rt}; }}",
            f"    let n = if s.len() < {cnt} {{ s.len() }} else {{ {cnt} }};",
            f"    let d = core::slice::from_raw_parts_mut({wc}, n);",
            f"    crate::core_rs::mbcp::mbstowcs(d, s, {cnt}) as {rt}",
        ]
    elif sp == "wctomb":
        mb, wc = pn  # mbchar(char*), wchar
        b += [
            f"    if {mb}.is_null() {{ return 0; }}",
            f"    *{mb} = crate::core_rs::mbcp::wctomb({wc});",
            "    1",
        ]
    elif sp == "wcstombs":
        mb, wc, cnt = pn
        b += [
            f"    let s = wcstr_slice({wc});",
            f"    if {mb}.is_null() {{ return s.len() as {rt}; }}",
            f"    let n = if s.len() < {cnt} {{ s.len() }} else {{ {cnt} }};",
            f"    let d = core::slice::from_raw_parts_mut({mb}, n);",
            f"    crate::core_rs::mbcp::wcstombs(d, s, {cnt}) as {rt}",
        ]
    elif sp == "toupper_mb":
        (c,) = pn
        b.append(f"    crate::core_rs::mbcp::toupper_nt_mb({c})")
    else:
        raise SystemExit(f"{name}: unhandled mbcp pattern {sp}")
    misf = m.get("preserved_misfeature", "")
    return (
        f"/// `{m['c_signature']}`\n"
        f"/// preserved misfeature: {misf}\n"
        f"#[no_mangle]\n"
        f'pub unsafe extern "C" fn {name}({decl}) -> {rt} {{\n' + "\n".join(b) + "\n}\n"
    )


# Wave H — ASCII case fold. In-place folders mutate the NUL-terminated
# string and return the pointer; two (_strupr/_wcslwr) NULL-guard
# (manifest `null_guard = true`) → return NULL. Scalars are pure value
# transforms (tolower = ASCII core; towupper = the Rtl/CP1252 upcase
# shared with Wave E2's mbcp::upcase).
CASEMAP = {"case_inplace", "case_tolower", "case_towupper"}


def _casemap_shim(name: str, m: dict, params, rt: str) -> str:
    sp = m["slice_pattern"]
    decl = ", ".join(f"{n}: {rs_ty(t)}" for t, n in params)
    pn = [n for _, n in params]
    b: list[str] = []
    if sp == "case_inplace":
        (p,) = pn
        wide = rs_ty(params[0][0]) == "*mut u16"
        el = "u16" if wide else "u8"
        cstr = "wcstr_slice" if wide else "cstr_slice"
        rawm = "wraw_mut_slice" if wide else "raw_mut_slice"
        cf = m["core_fn"]  # casemap::lower_ascii | casemap::upper_ascii
        if m.get("null_guard", False):
            b.append(f"    if {p}.is_null() {{ return core::ptr::null_mut(); }}")
        b += [
            f"    let n = {cstr}({p} as *const {el}).len();",
            f"    let s = {rawm}({p}, n);",
            f"    crate::core_rs::{cf}(s);",
            f"    {p}",
        ]
    elif sp == "case_tolower":
        (c,) = pn
        b.append(f"    crate::core_rs::casemap::tolower_ascii({c})")
    elif sp == "case_towupper":
        (c,) = pn
        b.append(f"    crate::core_rs::mbcp::upcase({c}) as {rt}")
    else:
        raise SystemExit(f"{name}: unhandled casemap pattern {sp}")
    misf = m.get("preserved_misfeature", "")
    return (
        f"/// `{m['c_signature']}`\n"
        f"/// preserved misfeature: {misf}\n"
        f"#[no_mangle]\n"
        f'pub unsafe extern "C" fn {name}({decl}) -> {rt} {{\n' + "\n".join(b) + "\n}\n"
    )


# Wave I — in-place string mutators. All return the original pointer;
# the slice is bounded by the live content (cstr_slice len), and for
# _strnset further by min(len, (int)sizeMaxFill) — the signed-int cast
# of size_t is the preserved misfeature (huge size_t → negative int →
# fills nothing). NO NULL guards in the C — NULL never fuzzed.
STRMUT = {"mut_reverse", "mut_set", "mut_nset"}


def _strmut_shim(name: str, m: dict, params, rt: str) -> str:
    sp = m["slice_pattern"]
    decl = ", ".join(f"{n}: {rs_ty(t)}" for t, n in params)
    pn = [n for _, n in params]
    wide = rs_ty(params[0][0]) == "*mut u16"
    el = "u16" if wide else "u8"
    cstr = "wcstr_slice" if wide else "cstr_slice"
    rawm = "wraw_mut_slice" if wide else "raw_mut_slice"
    b: list[str] = []
    # `__buf` (not `s`) — _strrev's param is literally named `s`.
    if sp == "mut_reverse":
        (p,) = pn
        b += [
            f"    let __n = {cstr}({p} as *const {el}).len();",
            f"    let __buf = {rawm}({p}, __n);",
            "    crate::core_rs::strmut::reverse(__buf);",
            f"    {p}",
        ]
    elif sp == "mut_set":
        p, fill = pn
        b += [
            f"    let __n = {cstr}({p} as *const {el}).len();",
            f"    let __buf = {rawm}({p}, __n);",
            f"    crate::core_rs::strmut::fill(__buf, {fill} as {el});",
            f"    {p}",
        ]
    elif sp == "mut_nset":
        p, fill, mx = pn
        b += [
            f"    let __n = {cstr}({p} as *const {el}).len();",
            # C: `i < (int)sizeMaxFill` — signed-int cast of size_t.
            f"    let __lim = {mx} as i32;",
            "    let __take = if __lim <= 0 { 0 } else { core::cmp::min(__n, __lim as usize) };",
            f"    let __buf = {rawm}({p}, __take);",
            f"    crate::core_rs::strmut::fill(__buf, {fill} as {el});",
            f"    {p}",
        ]
    else:
        raise SystemExit(f"{name}: unhandled strmut pattern {sp}")
    misf = m.get("preserved_misfeature", "")
    return (
        f"/// `{m['c_signature']}`\n"
        f"/// preserved misfeature: {misf}\n"
        f"#[no_mangle]\n"
        f'pub unsafe extern "C" fn {name}({decl}) -> {rt} {{\n' + "\n".join(b) + "\n}\n"
    )


# Path track — _splitpath/_wsplitpath (_tsplitpath_x.h, non-secure
# !IS_SECAPI + _LIBCNT_) + _makepath/_wmakepath. The C does a SINGLE
# `path[1]==':'` drive detection then `path+=2`; `core_rs::path::split`
# reports ranges into the FULL slice (no sub-slice re-detection). 4
# nullable OUT bufs for split (each skipped if NULL); the synthesized
# 3-elem drive is written iff `drive!=NULL` (the `path+=2` is
# unconditional, baked into split's dir_start). makepath: NULL `path`
# = clean no-op; NULL/empty component skipped (cstr_slice NULL→empty).
PATHFAM = {"splitpath", "makepath"}


def _pathfam_shim(name: str, m: dict, params, rt: str) -> str:
    sp = m["slice_pattern"]
    decl = ", ".join(f"{n}: {rs_ty(t)}" for t, n in params)
    pn = [n for _, n in params]
    wide = "u16" in rs_ty(params[0][0])
    el = "u16" if wide else "u8"
    cstr = "wcstr_slice" if wide else "cstr_slice"
    rawm = "wraw_mut_slice" if wide else "raw_mut_slice"
    nul = "0u16" if wide else "0u8"
    colon = "b':' as u16" if wide else "b':'"
    b: list[str] = []
    if sp == "splitpath":
        path, drive, dir_, fname, ext = pn
        b += [
            f"    let p = {cstr}({path});",
            # C lines 67-70: truncate every non-NULL out to "".
            f"    if !{drive}.is_null() {{ *{drive} = {nul}; }}",
            f"    if !{dir_}.is_null() {{ *{dir_} = {nul}; }}",
            f"    if !{fname}.is_null() {{ *{fname} = {nul}; }}",
            f"    if !{ext}.is_null() {{ *{ext} = {nul}; }}",
            "    if p.is_empty() { return; }",  # C line 91 early ret
            "    let r = crate::core_rs::path::split(p);",
            # drive synthesized [p[0], ':', NUL] iff drive != NULL
            # (C writes the 3 unconditionally given drive!=NULL; the
            # path+=2 is folded into split's dir_start).
            f"    if r.has_drive && !{drive}.is_null() {{",
            f"        *{drive} = p[0];",
            f"        *{drive}.add(1) = {colon};",
            f"        *{drive}.add(2) = {nul};",
            "    }",
            "    for (out, (a, e)) in [",
            f"        ({dir_}, r.dir), ({fname}, r.fname), ({ext}, r.ext),",
            "    ] {",
            "        if !out.is_null() {",
            f"            let d = {rawm}(out, e - a + 1);",
            "            let mut k = 0usize;",
            "            while k < e - a { d[k] = p[a + k]; k += 1; }",
            f"            d[e - a] = {nul};",
            "        }",
            "    }",
        ]
    elif sp == "makepath":
        path, drive, dir_, fname, ext = pn
        b += [
            f"    if {path}.is_null() {{ return; }}",
            f"    let dr = {cstr}({drive} as *const {el});",
            f"    let di = {cstr}({dir_} as *const {el});",
            f"    let fl = {cstr}({fname} as *const {el});",
            f"    let ex = {cstr}({ext} as *const {el});",
            # worst case: drive(2) + dir + sep(1) + fname + dot(1) + ext
            #             + NUL(1)  →  +5 slack
            "    let cap = dr.len() + di.len() + fl.len() + ex.len() + 5;",
            f"    let out = {rawm}({path}, cap);",
            "    crate::core_rs::path::make(out, dr, di, fl, ex);",
        ]
    else:
        raise SystemExit(f"{name}: unhandled pathfam pattern {sp}")
    misf = m.get("preserved_misfeature", "")
    return (
        f"/// `{m['c_signature']}`\n"
        f"/// preserved misfeature: {misf}\n"
        f"#[no_mangle]\n"
        f'pub unsafe extern "C" fn {name}({decl}) -> {rt} {{\n' + "\n".join(b) + "\n}\n"
    )


# Wave STRTOK — strtok/strtok_s/wcstok/wcstok_s. One pure core
# (core_rs::strtok::next_token); the shim owns the raw-pointer walk +
# the non-reentrant saved pointer. `*_static` (strtok/wcstok) keep it
# in a process-global AtomicPtr (faithful to the genuine per-thread
# thread_data_t field — single-threaded-equivalent, the
# _invalid_parameter relaxed-atomic precedent); `*_ctx`
# (strtok_s/wcstok_s) take an explicit `char**`/`wchar_t**`. The Empty
# (no-token) path updates the saved ptr ONLY for strtok_s (`*ctx=str`);
# strtok/wcstok/wcstok_s leave it UNCHANGED (a faithful asymmetry).
STRTOK = {"tok_static", "tok_ctx", "wtok_static", "wtok_ctx"}


def _strtok_shim(name: str, m: dict, params, rt: str) -> str:
    sp = m["slice_pattern"]
    decl = ", ".join(f"{n}: {rs_ty(t)}" for t, n in params)
    pn = [n for _, n in params]
    wide = sp.startswith("w")
    el = "u16" if wide else "u8"
    cstr = "wcstr_slice" if wide else "cstr_slice"
    null = "core::ptr::null_mut()"
    b: list[str] = []
    if sp in ("tok_static", "wtok_static"):
        s_, delim = pn
        b += [
            "    use core::sync::atomic::{AtomicPtr, Ordering};",
            f"    static SAVED: AtomicPtr<{el}> = AtomicPtr::new({null});",
            f"    if {delim}.is_null() {{ return {null}; }}",
            f"    let base = if {s_}.is_null() {{",
            "        let p = SAVED.load(Ordering::Relaxed);",
            f"        if p.is_null() {{ return {null}; }}",
            "        p",
            f"    }} else {{ {s_} }};",
            f"    let n = {cstr}(base as *const {el}).len();",
            "    let s = core::slice::from_raw_parts_mut(base, n);",
            f"    match crate::core_rs::strtok::next_token(s, {cstr}({delim})) {{",
            f"        crate::core_rs::strtok::Tok::Empty {{ .. }} => {null},",
            "        crate::core_rs::strtok::Tok::Found { start, next } => {",
            "            SAVED.store(base.add(next), Ordering::Relaxed);",
            "            base.add(start)",
            "        }",
            "    }",
        ]
    else:  # tok_ctx / wtok_ctx — explicit context pointer
        s_, delim, ctx = pn
        # strtok_s alone updates *ctx on the Empty path (`*ctx=str`);
        # wcstok_s leaves *next_token unchanged (Wine asymmetry).
        empty_arm = (
            f"crate::core_rs::strtok::Tok::Empty {{ stop }} => "
            f"{{ *{ctx} = base.add(stop); {null} }},"
            if sp == "tok_ctx"
            else f"crate::core_rs::strtok::Tok::Empty {{ .. }} => {null},"
        )
        b += [
            f"    if {delim}.is_null() {{ return {null}; }}",
            f"    if {ctx}.is_null() {{ return {null}; }}",
            f"    let base = if {s_}.is_null() {{",
            f"        if (*{ctx}).is_null() {{ return {null}; }}",
            f"        *{ctx}",
            f"    }} else {{ {s_} }};",
            f"    let n = {cstr}(base as *const {el}).len();",
            "    let s = core::slice::from_raw_parts_mut(base, n);",
            f"    match crate::core_rs::strtok::next_token(s, {cstr}({delim})) {{",
            f"        {empty_arm}",
            "        crate::core_rs::strtok::Tok::Found { start, next } => {",
            f"            *{ctx} = base.add(next);",
            "            base.add(start)",
            "        }",
            "    }",
        ]
    misf = m.get("preserved_misfeature", "")
    return (
        f"/// `{m['c_signature']}`\n"
        f"/// preserved misfeature: {misf}\n"
        f"#[no_mangle]\n"
        f'pub unsafe extern "C" fn {name}({decl}) -> {rt} {{\n' + "\n".join(b) + "\n}\n"
    )


def _int2str_shim(name: str, m: dict, params, rt: str) -> str:
    sp = m["slice_pattern"]
    decl = ", ".join(f"{n}: {rs_ty(t)}" for t, n in params)
    v = params[0][1]
    dst = next(n for t, n in params if rs_ty(t).startswith("*mut"))
    rad = params[-1][1]  # radix is always the trailing int
    size = next((n for t, n in params if rs_ty(t) == "usize"), None)
    fr = "crate::core_rs::radix::format_radix"
    mag = _mag_prologue(rs_ty(params[0][0]), v, rad)
    b: list[str] = []

    if sp == "int_to_str":
        b += [
            mag,
            f"    let f = {fr}(mag, {rad} as u32, neg);",
            "    let mut o = 0usize;",
            f"    if f.negative {{ *{dst} = b'-'; o = 1; }}",
            "    let mut i = 0;",
            f"    while i < f.ndigits {{ *{dst}.add(o + i) = f.digits[i]; i += 1; }}",
            f"    *{dst}.add(o + f.ndigits) = 0;",
            f"    {dst}",
        ]
    elif sp == "int_to_wstr":
        b += [
            mag,
            f"    let f = {fr}(mag, {rad} as u32, neg);",
            f"    if !{dst}.is_null() {{",
            "        let mut o = 0usize;",
            f"        if f.negative {{ *{dst} = b'-' as u16; o = 1; }}",
            "        let mut i = 0;",
            f"        while i < f.ndigits {{ *{dst}.add(o + i) = f.digits[i] as u16; i += 1; }}",
            f"        *{dst}.add(o + f.ndigits) = 0;",
            "    }",
            f"    {dst}",
        ]
    elif sp in ("s_erange_n", "s_erange_w"):
        wide = sp == "s_erange_w"
        cast = " as u16" if wide else ""
        minus = "b'-' as u16" if wide else "b'-'"
        b += [
            f"    if {dst}.is_null() || {size} == 0 || {rad} < 2 || {rad} > 36 {{",
            f"        if !{dst}.is_null() && {size} != 0 {{ *{dst} = 0; }}",
            "        return 22;",
            "    }",
            mag,
            f"    let f = {fr}(mag, {rad} as u32, neg);",
            "    let need = f.ndigits + f.negative as usize + 1;",
            f"    if need > {size} {{",
            "        let o = f.negative as usize;",
            f"        let cnt = {size} - o;",
            "        let mut i = 0;",
            "        while i < cnt && i < f.ndigits {",
            f"            *{dst}.add(o + i) = f.digits[f.ndigits - 1 - i]{cast};",
            "            i += 1;",
            "        }",
            f"        *{dst} = 0;",
            "        return 34;",
            "    }",
            "    let mut o = 0usize;",
            f"    if f.negative {{ *{dst} = {minus}; o = 1; }}",
            "    let mut i = 0;",
            f"    while i < f.ndigits {{ *{dst}.add(o + i) = f.digits[i]{cast}; i += 1; }}",
            f"    *{dst}.add(o + f.ndigits) = 0;",
            "    0",
        ]
    elif sp == "s_einval_n":
        b += [
            f"    if {dst}.is_null() || {size} == 0 || {rad} < 2 || {rad} > 36 {{",
            "        return 22;",
            "    }",
            f"    let f = {fr}({v}, {rad} as u32, false);",
            "    let need = f.ndigits + 1;",
            f"    if need > {size} {{ return 22; }}",
            "    let mut i = 0;",
            f"    while i < f.ndigits {{ *{dst}.add(i) = f.digits[i]; i += 1; }}",
            f"    *{dst}.add(f.ndigits) = 0;",
            "    0",
        ]
    elif sp == "s_einval_w":
        # _ui64tow_s byte-count bug: memcpy `ndigits+1` BYTES (NOT
        # * sizeof(wchar_t)) from a u16-LE temp into the wide dst.
        b += [
            f"    if {dst}.is_null() || {size} == 0 || {rad} < 2 || {rad} > 36 {{",
            "        return 22;",
            "    }",
            f"    let f = {fr}({v}, {rad} as u32, false);",
            "    let need = f.ndigits + 1;",
            f"    if need > {size} {{ return 22; }}",
            "    let mut tmp = [0u8; 2 * crate::core_rs::radix::RADIX_DIGITS_MAX + 2];",
            "    let mut t = 0;",
            "    let mut i = 0;",
            "    while i < f.ndigits { tmp[t] = f.digits[i]; t += 2; i += 1; }",
            f"    let db = {dst} as *mut u8;",
            "    let mut i = 0;",
            "    while i < need { *db.add(i) = tmp[i]; i += 1; }",
            "    0",
        ]
    else:
        raise SystemExit(f"{name}: unhandled int2str pattern {sp}")

    misf = m.get("preserved_misfeature", "")
    return (
        f"/// `{m['c_signature']}`\n"
        f"/// preserved misfeature: {misf}\n"
        f"#[no_mangle]\n"
        f'pub unsafe extern "C" fn {name}({decl}) -> {rt} {{\n' + "\n".join(b) + "\n}\n"
    )


# Wave MEM2 — `_memccpy` (copy-until-byte). One bespoke shim: reads
# both dst/src as `count`-length raw slices, runs the pure core, and
# forms `to.add(i+1)` | NULL. The signed-char `t == c` match and the
# NUL-before-c precedence are the core's (mem::ccpy).
MEMCCPY = {"memccpy"}


def _memccpy_shim(name: str, m: dict, params, rt: str) -> str:
    decl = ", ".join(f"{n}: {rs_ty(t)}" for t, n in params)
    to, frm, c, count = [n for _, n in params]
    b = [
        f"    let d = raw_mut_slice({to} as *mut u8, {count});",
        f"    let s = raw_slice({frm} as *const u8, {count});",
        f"    match crate::core_rs::mem::ccpy(d, s, {c}) {{",
        f"        Some(i) => ({to} as *mut u8).add(i) as {rt},",
        "        None => core::ptr::null_mut(),",
        "    }",
    ]
    misf = m.get("preserved_misfeature", "")
    return (
        f"/// `{m['c_signature']}`\n"
        f"/// preserved misfeature: {misf}\n"
        f"#[no_mangle]\n"
        f'pub unsafe extern "C" fn {name}({decl}) -> {rt} {{\n' + "\n".join(b) + "\n}\n"
    )


# Wave RAND — `rand`/`srand`. Non-reentrant hidden LCG state lives in
# the shared `super::RAND_STATE` AtomicU64 (the strtok SAVED-pointer
# precedent); the pure step + seed-install are core_rs::rng.
RANDFAM = {"rand_step", "rand_seed"}


def _rand_shim(name: str, m: dict, params, rt: str) -> str:
    sp = m["slice_pattern"]
    decl = ", ".join(f"{n}: {rs_ty(t)}" for t, n in params)
    if sp == "rand_step":
        b = [
            "    use core::sync::atomic::Ordering;",
            "    let s = super::RAND_STATE.load(Ordering::Relaxed);",
            "    let (ns, r) = crate::core_rs::rng::step(s);",
            "    super::RAND_STATE.store(ns, Ordering::Relaxed);",
            "    r",
        ]
    else:  # rand_seed
        seed = params[0][1]
        b = [
            "    use core::sync::atomic::Ordering;",
            f"    super::RAND_STATE.store(crate::core_rs::rng::seed({seed}), Ordering::Relaxed);",
        ]
    misf = m.get("preserved_misfeature", "")
    return (
        f"/// `{m['c_signature']}`\n"
        f"/// preserved misfeature: {misf}\n"
        f"#[no_mangle]\n"
        f'pub unsafe extern "C" fn {name}({decl}) -> {rt} {{\n' + "\n".join(b) + "\n}\n"
    )


# Wave SORT — `qsort`. Bespoke: the whole Bentley-McIlroy algorithm is
# in `super::qsort_rs` (HELPERS); the shim is a thin ABI adapter. Its C
# signature carries a function-pointer param with embedded commas that
# the crude `parse_params` can't split, so it's dispatched BEFORE
# parse_params with a fixed emitted signature.
SORT = {"sort"}


def _sort_shim(name: str, m: dict, rt: str) -> str:
    misf = m.get("preserved_misfeature", "")
    return (
        f"/// `{m['c_signature']}`\n"
        f"/// preserved misfeature: {misf}\n"
        f"#[no_mangle]\n"
        f'pub unsafe extern "C" fn {name}('
        "base: *mut core::ffi::c_void, num: usize, width: usize, "
        f"cmp: super::CntCmpFn) -> {rt} {{\n"
        "    super::qsort_rs(base as *mut u8, num, width, cmp);\n"
        "}\n"
    )


def shim(name: str, m: dict) -> str:
    sp = m["slice_pattern"]
    rt = ret_ty(m["c_signature"])
    if sp in SORT:
        return _sort_shim(name, m, rt)
    params = parse_params(m["c_signature"])
    rc = m["return_collapse"]
    if sp in MEMCCPY:
        return _memccpy_shim(name, m, params, rt)
    if sp in RANDFAM:
        return _rand_shim(name, m, params, rt)
    if sp in INT2STR:
        return _int2str_shim(name, m, params, rt)
    if sp in MBCP:
        return _mbcp_shim(name, m, params, rt)
    if sp in STRFAM:
        return _strfam_shim(name, m, params, rt)
    if sp in CASEMAP:
        return _casemap_shim(name, m, params, rt)
    if sp in STRMUT:
        return _strmut_shim(name, m, params, rt)
    if sp in PATHFAM:
        return _pathfam_shim(name, m, params, rt)
    if sp in STRTOK:
        return _strtok_shim(name, m, params, rt)
    # `_locale_t` is ignored by every collapse (the `_l` variants
    # delegate with locale unused) — emit it underscore-prefixed so it
    # doesn't trip unused_variables.
    decl_params = ", ".join(
        f"{'_' + n if t.replace(' ', '') == '_locale_t' else n}: {rs_ty(t)}" for t, n in params
    )
    pnames = [n for _, n in params]
    ptrs = [n for t, n in params if rs_ty(t).startswith("*")]
    szp = next((n for t, n in params if rs_ty(t) == "usize"), None)
    # non-ptr non-size scalars (the `c`/`val` arg): i32 narrow, but
    # u16 for the wide `wcschr(.., wchar_t c)` — pass as i32 to the
    # core (find_char takes a C `int`; widening is value-preserving).
    scal = [n for t, n in params if not rs_ty(t).startswith("*") and rs_ty(t) != "usize"]
    body: list[str] = []
    cf = m["core_fn"]

    def core_call(args: str) -> str:
        return f"crate::core_rs::{cf}({args})"

    # ---- slice reconstruction --------------------------------------
    if sp == "nul_in":
        for n in ptrs:  # only pointer args become slices; scalars pass through
            body.append(f"    let {n}_s = cstr_slice({n});")
    elif sp == "wnul_in":  # wide twin: NUL-terminated u16 → &[u16]
        for n in ptrs:
            body.append(f"    let {n}_s = wcstr_slice({n});")
    elif sp == "nul_in_n":  # strncmp: compare <= n, NEVER read past n.
        # Unlike strcmp (nul_in), strncmp's operands may be NON-terminated
        # fixed fields of length >= n; an unbounded scan over-reads into
        # the next page → 0x50. ncmp treats out-of-slice as ZERO, so
        # bounding each operand to n is result-identical and crash-safe.
        for n in ptrs:
            body.append(f"    let {n}_s = cstr_slice_bounded({n}, {szp});")
    elif sp == "wnul_in_n":  # wcsncmp wide twin
        for n in ptrs:
            body.append(f"    let {n}_s = wcstr_slice_bounded({n}, {szp});")
    elif sp == "nul_in_maxlen":
        # strnlen-shape: walk the C string but never past the count
        # param (textbook strnlen must not read beyond maxlen).
        body.append(f"    let {ptrs[0]}_s = cstr_slice_bounded({ptrs[0]}, {szp});")
    elif sp == "wnul_in_maxlen":  # wcsnlen
        body.append(f"    let {ptrs[0]}_s = wcstr_slice_bounded({ptrs[0]}, {szp});")
    elif sp == "dst_fixed_n":
        d, s, _ = pnames
        body.append(f"    let {d}_s = raw_mut_slice({d}, {szp});")
        # src MUST be bounded to n: strncpy copies min(strlen(src),n) and
        # the classic caller passes a NON-NUL-terminated fixed field of
        # length >= n. An unbounded cstr_slice runs off the field into the
        # next (possibly unmapped) page → 0x50. ncpy already does
        # min(src.len(),n) so bounding src is result-identical, just safe.
        body.append(f"    let {s}_s = cstr_slice_bounded({s}, {szp});")
    elif sp == "wdst_fixed_n":  # wcsncpy
        d, s, _ = pnames
        body.append(f"    let {d}_s = wraw_mut_slice({d}, {szp});")
        body.append(f"    let {s}_s = wcstr_slice_bounded({s}, {szp});")
    elif sp == "ptr_len":
        for p in ptrs:
            body.append(f"    let {p}_s = raw_slice({p} as *const u8, {szp});")
    elif sp == "set_raw":
        pass  # raw_fill inline below
    elif sp == "nul_endptr_base":
        np = next(n for t, n in params if rs_ty(t) == "*const u8")
        body.append(f"    let {np}_s = cstr_slice({np});")
    elif sp == "wnul_endptr_base":
        np = next(n for t, n in params if rs_ty(t) == "*const u16")
        body.append(f"    let {np}_s = wcstr_slice({np});")
    elif sp == "mem_raw":
        pass  # raw_move inline below
    else:
        raise SystemExit(f"{name}: unsupported slice_pattern {sp}")

    # First/second slice names. Slices come from POINTER params only
    # (scalars like `int c` pass through untouched).
    s0 = (pnames[0] if sp in ("dst_fixed_n", "wdst_fixed_n") else ptrs[0]) + "_s"
    s1 = ptrs[1] + "_s" if len(ptrs) > 1 else None

    # ---- core call + return collapse -------------------------------
    if rc == "usize":
        body.append(f"    {core_call(s0)} as {rt}")
    elif rc == "usize2":  # span-shape: core(s, set) -> size_t
        body.append(f"    {core_call(f'{s0}, {s1}')} as {rt}")
    elif rc == "i32_passthrough":
        body.append(f"    {core_call(f'{s0}, {s1}')}")
    elif rc == "i32_cmp_n":  # strncmp-shape: core(a, b, n)
        body.append(f"    {core_call(f'{s0}, {s1}, {szp}')}")
    elif rc == "ptr_or_null_from_opt":
        args = f"{s0}, {s1}" if s1 else f"{s0}, {scal[0]} as i32"
        base = pnames[0] if sp == "nul_in" else ptrs[0]
        body.append(f"    match {core_call(args)} {{")
        body.append(f"        Some(i) => {base}.add(i) as {rt},")
        body.append("        None => core::ptr::null_mut(),")
        body.append("    }")
    elif rc == "ret_dst":
        if sp in ("dst_fixed_n", "wdst_fixed_n"):
            d, s, _ = pnames
            body.append(f"    let _ = {core_call(f'{d}_s, {s}_s')};")
            body.append(f"    {d}")
        elif sp == "set_raw":
            d = ptrs[0]
            # memset: an asm fill (raw_fill -> memops.rs), NOT a
            # `core_rs::mem::set` call. memset is a #[no_mangle] C-ABI symbol
            # whose only observable effect is storing through a pointer param
            # — the exact captures(none)/writeonly shape LLVM's dead-store
            # eliminator targets. Compiled from a plain `*x = b` loop it was
            # DCE'd to a guard-only infinite spin in some cgu partitions
            # (observed on the amd64 cmake freeldr link after the per-fn
            # cgu-split: boot hung at RtlZeroMemory(MachVtbl, 0xf0) right after
            # the UEFI banner; a black_box hint only turned the spin into
            # infinite recursion). A volatile byte loop fixed that and cost
            # ~10 instructions a byte; asm stores are as undeletable and run
            # 16 bytes a store. The `set` core stays the plain loop for the
            # difftest + Kani model (core_rs forbids unsafe).
            body.append(f"    raw_fill({d} as *mut u8, {scal[0]} as u8, {szp});")
            body.append(f"    {d}")
        elif sp == "mem_raw":
            d, s, nn = pnames
            body.append(f"    raw_move({d} as *mut u8, {s} as *const u8, {nn});")
            body.append(f"    {d}")
        else:
            raise SystemExit(f"{name}: ret_dst with {sp}")
    elif rc == "i64_trunc_i32":
        body.append(f"    let (v, _of) = {core_call(s0)};")
        body.append(f"    v as i32 as {rt}")
    elif rc == "i64_passthrough":
        body.append(f"    let (v, _of) = {core_call(s0)};")
        body.append(f"    v as {rt}")
    elif rc in ("i64_endptr", "ulong_strtoul"):
        np = next(n for t, n in params if rs_ty(t) == "*const u8")
        ep = next(n for t, n in params if rs_ty(t) == "*mut *mut u8")
        bs = next(n for t, n in params if rs_ty(t) == "i32")
        body.append(f"    let r = crate::core_rs::radix::parse_i64_clamped({np}_s, {bs});")
        body.append(f"    if r.base_ok && !{ep}.is_null() {{")
        body.append(f"        *{ep} = {np}.add(r.end) as *mut u8;")
        body.append("    }")
        if rc == "i64_endptr":
            body.append(f"    r.value as {rt}")
        else:  # ulong_strtoul: asymmetric clamp to [1, ULONG_MAX]
            body.append("    let v = if r.value > 4294967295i64 {")
            body.append("        4294967295i64")
            body.append("    } else if r.value < -4294967295i64 {")
            body.append("        1i64")
            body.append("    } else { r.value };")
            body.append(f"    v as u32 as {rt}")
    elif rc == "wcstoul":
        np = next(n for t, n in params if rs_ty(t) == "*const u16")
        ep = next(n for t, n in params if rs_ty(t) == "*mut *mut u16")
        bs = next(n for t, n in params if rs_ty(t) == "i32")
        body.append(f"    let r = crate::core_rs::radix::parse_ulong_wide({np}_s, {bs});")
        body.append(f"    if !{ep}.is_null() {{")
        body.append(f"        *{ep} = {np}.add(r.end) as *mut u16;")
        body.append("    }")
        body.append(f"    r.value as {rt}")
    elif rc in ("long_bsd", "u64_bsd"):
        # strtol/wcstol/strtoull — BSD parse + endptr. Narrow (*const
        # u8 / char**) or wide (*const u16 / wchar_t**); the core is
        # generic over Cu so the slice type drives it. `as *mut _`
        # lets the endptr cast infer the right inner pointer width.
        core = "parse_long_bsd" if rc == "long_bsd" else "parse_u64_bsd"
        np = next(n for t, n in params if rs_ty(t) in ("*const u8", "*const u16"))
        ep = next(n for t, n in params if rs_ty(t) in ("*mut *mut u8", "*mut *mut u16"))
        bs = next(n for t, n in params if rs_ty(t) == "i32")
        body.append(f"    let r = crate::core_rs::radix::{core}({np}_s, {bs});")
        body.append(f"    if !{ep}.is_null() {{")
        body.append(f"        *{ep} = {np}.add(r.end) as *mut _;")
        body.append("    }")
        body.append(f"    r.value as {rt}")
    elif rc == "wtoi64_w":
        # Wave G2: _wtoi (int trunc), _wtoi64, _wtoi64_l — wide i64
        # wrapping. Picks the *const u16; locale (if any) ignored.
        # `v as {rt}` is (int) truncation for _wtoi (rt=i32) and a
        # no-op for the __int64 forms.
        np = next(n for t, n in params if rs_ty(t) == "*const u16")
        body.append(f"    let (v, _of) = crate::core_rs::radix::parse_i64_wrapping_cu({np}_s);")
        body.append(f"    v as {rt}")
    elif rc == "wtol_w":
        # Wave G2: _wtol — wide decimal u32 wrapping, bit-reinterpreted
        # to `long` (rt=i32). NULL→0 via wcstr_slice empty.
        np = next(n for t, n in params if rs_ty(t) == "*const u16")
        body.append(f"    crate::core_rs::radix::parse_u32_dec_w({np}_s) as {rt}")
    elif rc in ("wcstoi64_w", "wcstoui64_w"):
        # Wave G2: _wcstoi64{,_l} / _wcstoui64{,_l}. NULL nptr → return
        # 0 with NO endptr write (C's MSVCRT_CHECK_PMT under _LIBCNT_).
        # Invalid base → base_ok=false → return 0, no endptr write.
        # Otherwise *endptr = nptr + final-index (written even with no
        # digits — the wide endptr contract). locale ignored.
        core = "parse_i64_clamped_w" if rc == "wcstoi64_w" else "parse_u64_clamped_w"
        np = next(n for t, n in params if rs_ty(t) == "*const u16")
        ep = next(n for t, n in params if rs_ty(t) == "*mut *mut u16")
        bs = next(n for t, n in params if rs_ty(t) == "i32")
        body.append(f"    if {np}.is_null() {{ return 0 as {rt}; }}")
        body.append(f"    let r = crate::core_rs::radix::{core}({np}_s, {bs});")
        body.append(f"    if r.base_ok && !{ep}.is_null() {{")
        body.append(f"        *{ep} = {np}.add(r.end) as *mut _;")
        body.append("    }")
        body.append(f"    r.value as {rt}")
    else:
        raise SystemExit(f"{name}: unsupported return_collapse {rc}")

    misf = m.get("preserved_misfeature", "")
    return (
        f"/// `{m['c_signature']}`\n"
        f"/// preserved misfeature: {misf}\n"
        f"#[no_mangle]\n"
        f'pub unsafe extern "C" fn {name}({decl_params}) -> {rt} {{\n' + "\n".join(body) + "\n}\n"
    )


HELPERS = """//! Hand-written unsafe primitives the generated shims compose. Kept
//! tiny + audited; everything symbol-specific is generated.

/// Hidden LCG state shared by the generated `rand`/`srand` shims —
/// faithful to rand_nt.c's `static unsigned long long next`. An
/// `AtomicU64` (the strtok SAVED-pointer precedent) so the
/// non-reentrant CRT state is single-threaded-equivalent.
pub(crate) static RAND_STATE: core::sync::atomic::AtomicU64 =
    core::sync::atomic::AtomicU64::new(0);

/// NUL-terminated C string → content slice. NULL → empty (faithful to
/// libcntpr's explicit NULL guards in tcslen.h / atoi64.c; harmless
/// for symbols whose fuzz_domain never passes NULL).
#[inline]
pub(crate) unsafe fn cstr_slice<'a>(p: *const u8) -> &'a [u8] {
    if p.is_null() {
        return &[];
    }
    // The scan is asm (memops.rs `str_len8`): this crate gets no LLVM optimisation, so a
    // Rust loop costs ~10 instructions a byte, and asm is also opaque to the host
    // loop-idiom pass that once rewrote the loop into a call to strlen itself.
    core::slice::from_raw_parts(p, str_len8(p))
}

/// `strnlen`-style bounded C-string → content slice: walk to NUL but
/// never past `cap` bytes (textbook strnlen must not read beyond
/// maxlen). NULL → empty (libcntpr tcsnlen.h NULL guard).
#[inline]
pub(crate) unsafe fn cstr_slice_bounded<'a>(p: *const u8, cap: usize) -> &'a [u8] {
    if p.is_null() {
        return &[];
    }
    let mut n = 0usize;
    while n < cap && *p.add(n) != 0 {
        n += 1;
        // see cstr_slice: defeat the host loop-idiom strlen miscompile.
        #[cfg(target_os = "linux")]
        {
            n = core::hint::black_box(n);
        }
    }
    core::slice::from_raw_parts(p, n)
}

/// Wide twin of `cstr_slice`: NUL-terminated `*const u16` → content
/// slice (NUL excluded). NULL → empty.
#[inline]
pub(crate) unsafe fn wcstr_slice<'a>(p: *const u16) -> &'a [u16] {
    if p.is_null() {
        return &[];
    }
    // asm, as cstr_slice's (memops.rs `str_len16`).
    core::slice::from_raw_parts(p, str_len16(p))
}

/// Wide twin of `cstr_slice_bounded` (wcsnlen): NUL or `cap`, NULL→[].
#[inline]
pub(crate) unsafe fn wcstr_slice_bounded<'a>(p: *const u16, cap: usize) -> &'a [u16] {
    if p.is_null() {
        return &[];
    }
    let mut n = 0usize;
    while n < cap && *p.add(n) != 0 {
        n += 1;
    }
    core::slice::from_raw_parts(p, n)
}

#[inline]
pub(crate) unsafe fn raw_slice<'a>(p: *const u8, n: usize) -> &'a [u8] {
    if p.is_null() || n == 0 {
        return &[];
    }
    core::slice::from_raw_parts(p, n)
}

/// Wide twin of `raw_mut_slice` (wcsncpy dst): `*mut u16` × n → &mut.
#[inline]
pub(crate) unsafe fn wraw_mut_slice<'a>(p: *mut u16, n: usize) -> &'a mut [u16] {
    if p.is_null() || n == 0 {
        return &mut [];
    }
    core::slice::from_raw_parts_mut(p, n)
}

#[inline]
pub(crate) unsafe fn raw_mut_slice<'a>(p: *mut u8, n: usize) -> &'a mut [u8] {
    if p.is_null() || n == 0 {
        return &mut [];
    }
    core::slice::from_raw_parts_mut(p, n)
}

/// Overlap-safe raw byte move — the ReactOS `memcpy`/`memmove`
/// algorithm (memcpy.c): forward if disjoint or dst<=src, else
/// backward. This is the one shim that IS the implementation
/// (aliasing raw pointers can't be a safe-slice core); the loops are
/// asm in memops.rs, for the reasons it gives.
#[inline]
pub(crate) unsafe fn raw_move(dst: *mut u8, src: *const u8, n: usize) {
    if dst as usize <= src as usize || dst as usize >= src as usize + n {
        mem_copy_forward(dst, src, n);
    } else {
        mem_copy_backward(dst, src, n);
    }
}

/// `memset`'s fill: `n` bytes of `val` at `dst` (memops.rs). Not a
/// `core_rs::mem::set` call: memset's only effect is the stores, the
/// shape LLVM's dead-store elimination deletes (see gen_cnt.py's
/// set_raw); asm stores cannot be.
#[inline]
pub(crate) unsafe fn raw_fill(dst: *mut u8, val: u8, n: usize) {
    if n != 0 {
        mem_fill(dst, val, n);
    }
}

/// C `qsort` comparator ABI — `int (__cdecl *)(const void*, const void*)`.
pub(crate) type CntCmpFn = unsafe extern "C" fn(
    *const core::ffi::c_void,
    *const core::ffi::c_void,
) -> i32;

#[inline]
unsafe fn q_swap(i: *mut u8, j: *mut u8, es: usize) {
    // The C `swaptype` long-vs-byte choice is a byte-movement
    // optimization only — the resulting memory is identical, so a
    // plain byte swap is result-faithful (incl. equal-key order).
    let mut k = 0;
    while k < es {
        let t = *i.add(k);
        *i.add(k) = *j.add(k);
        *j.add(k) = t;
        k += 1;
    }
}

#[inline]
unsafe fn q_vecswap(i: *mut u8, j: *mut u8, n: usize) {
    let mut k = 0;
    while k < n {
        let t = *i.add(k);
        *i.add(k) = *j.add(k);
        *j.add(k) = t;
        k += 1;
    }
}

#[inline]
unsafe fn q_med3(a: *mut u8, b: *mut u8, c: *mut u8, cmp: CntCmpFn) -> *mut u8 {
    if cmp(a as _, b as _) < 0 {
        if cmp(b as _, c as _) < 0 {
            b
        } else if cmp(a as _, c as _) < 0 {
            c
        } else {
            a
        }
    } else if cmp(b as _, c as _) > 0 {
        b
    } else if cmp(a as _, c as _) < 0 {
        a
    } else {
        c
    }
}

/// Faithful port of ReactOS `stdlib/qsort.c` (Bentley & McIlroy,
/// "Engineering a Sort Function"): median-of-3 (ninther for n>40),
/// insertion sort for n<7 and the no-swap fast path, ties shuffled to
/// the ends then `vecswap`'d to the middle, recurse-left / iterate-
/// right. Unstable; the exact element-swap sequence is replicated so
/// equal-key final order matches byte-for-byte.
pub(crate) unsafe fn qsort_rs(
    mut a: *mut u8,
    mut n: usize,
    es: usize,
    cmp: CntCmpFn,
) {
    let bdiff = |p: *mut u8, q: *mut u8| (p as usize) - (q as usize);
    'outer: loop {
        let mut swap_cnt = 0i32;
        if n < 7 {
            let mut pm = a.add(es);
            let end = a.add(n * es);
            while pm < end {
                let mut pl = pm;
                while pl > a && cmp(pl.sub(es) as _, pl as _) > 0 {
                    q_swap(pl, pl.sub(es), es);
                    pl = pl.sub(es);
                }
                pm = pm.add(es);
            }
            return;
        }
        let mut pm = a.add((n / 2) * es);
        if n > 7 {
            let mut pl = a;
            let mut pn = a.add((n - 1) * es);
            if n > 40 {
                let d = (n / 8) * es;
                pl = q_med3(pl, pl.add(d), pl.add(2 * d), cmp);
                pm = q_med3(pm.sub(d), pm, pm.add(d), cmp);
                pn = q_med3(pn.sub(2 * d), pn.sub(d), pn, cmp);
            }
            pm = q_med3(pl, pm, pn, cmp);
        }
        q_swap(a, pm, es);
        let mut pa = a.add(es);
        let mut pb = pa;
        let mut pc = a.add((n - 1) * es);
        let mut pd = pc;
        loop {
            let mut r: i32;
            while pb <= pc && {
                r = cmp(pb as _, a as _);
                r <= 0
            } {
                if r == 0 {
                    swap_cnt = 1;
                    q_swap(pa, pb, es);
                    pa = pa.add(es);
                }
                pb = pb.add(es);
            }
            while pb <= pc && {
                r = cmp(pc as _, a as _);
                r >= 0
            } {
                if r == 0 {
                    swap_cnt = 1;
                    q_swap(pc, pd, es);
                    pd = pd.sub(es);
                }
                pc = pc.sub(es);
            }
            if pb > pc {
                break;
            }
            q_swap(pb, pc, es);
            swap_cnt = 1;
            pb = pb.add(es);
            pc = pc.sub(es);
        }
        if swap_cnt == 0 {
            let mut pm = a.add(es);
            let end = a.add(n * es);
            while pm < end {
                let mut pl = pm;
                while pl > a && cmp(pl.sub(es) as _, pl as _) > 0 {
                    q_swap(pl, pl.sub(es), es);
                    pl = pl.sub(es);
                }
                pm = pm.add(es);
            }
            return;
        }
        let pn = a.add(n * es);
        let mut r = core::cmp::min(bdiff(pa, a), bdiff(pb, pa));
        q_vecswap(a, pb.sub(r), r);
        r = core::cmp::min(bdiff(pd, pc), bdiff(pn, pd) - es);
        q_vecswap(pb, pn.sub(r), r);
        let r1 = bdiff(pb, pa);
        if r1 > es {
            qsort_rs(a, r1 / es, es, cmp);
        }
        let r2 = bdiff(pd, pc);
        if r2 > es {
            // Iterate rather than recurse (the C `goto loop`).
            a = pn.sub(r2);
            n = r2 / es;
            continue 'outer;
        }
        return;
    }
}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    man = tomllib.loads(MANIFEST.read_text())
    syms = man["symbols"]

    # Per-function module wrapping: each shim lives in its OWN module so
    # rustc emits it into a separate codegen unit / object. This restores the
    # per-function archive-member granularity the C libcntpr had (one .obj per
    # function). Without it every shim lands in a SINGLE cgu object: any
    # reference (a consumer's memset / strtol / _stricmp) extracts the whole
    # object, dragging the kernel-exported CRT (_itow / _wcsicmp / ...) in as
    # local strong defs that then collide with the same symbols the consumer
    # IMPORTS from ntoskrnl / ntdll -> `ld.lld: error: X was replaced`. With
    # one module per fn, a consumer extracts only the objects it actually
    # references locally and imports the rest, exactly like the C version.
    helper_use = (
        "    #[allow(unused_imports)]\n"
        "    use super::super::{cstr_slice, cstr_slice_bounded, raw_fill, raw_move, "
        "raw_mut_slice, raw_slice, wcstr_slice, wcstr_slice_bounded, "
        "wraw_mut_slice};\n"
    )
    shims = [
        AUTOGEN,
        "#![allow(non_snake_case)]  // shims mirror C param names verbatim\n"
        "// One module per shim — keeps each #[no_mangle] export in its own\n"
        "// codegen unit / object (per-function archive granularity). See\n"
        "// tools/gen_cnt.py main() for why (lld 'X was replaced' otherwise).\n\n",
    ]
    for nm in sorted(syms):
        body = shim(nm, syms[nm])
        # Shim bodies reach cabi-level items (helpers, CntCmpFn, qsort_rs,
        # RAND_STATE, ...) via `super::`. Nesting each shim one level deeper
        # (generated::mX) makes cabi `super::super::`, so retarget those paths.
        body = body.replace("super::", "super::super::")
        indented = "\n".join(("    " + ln if ln.strip() else ln) for ln in body.split("\n"))
        shims.append(f"mod m{nm} {{\n{helper_use}\n{indented}\n}}\npub use m{nm}::*;\n")
    generated_rs = "\n".join(shims)

    mod_rs = (
        AUTOGEN
        # Under `cabi-math` alone (the msvcrt.dll math flip — see below) only
        # math.rs compiles, so the shared helpers and RAND_STATE are unused in
        # that configuration; every full-`cabi` build still sees dead code.
        + '#![cfg_attr(not(feature = "cabi"), allow(dead_code))]\n'
        + HELPERS
        # Everything except math.rs is gated on the full `cabi` feature. The
        # narrower `cabi-math` feature (Cargo.toml) compiles ONLY math.rs —
        # it exists so msvcrt-crt-cargo can pull the 66 kernel-proven libm
        # exports into msvcrt.dll WITHOUT the other ~200 #[no_mangle] shims,
        # which would collide with msvcrt-crt-rust's own wrappers in the same
        # staticlib. (The kernel + cnt-difftest builds pass `cabi`, under
        # which all of this is exactly what it always was.)
        # hand-written asm loops under raw_move / raw_fill (memops.rs).
        + "mod memops;\nuse memops::*;\n"
        + '#[cfg(feature = "cabi")]\nmod generated;\n'
        + '#[cfg(feature = "cabi")]\npub use generated::*;\n'
        # hand-written, no differential target (see manual.rs)
        + '#[cfg(feature = "cabi")]\nmod manual;\n'
        + '#[cfg(feature = "cabi")]\npub use manual::*;\n'
        # hand-written printf engine (streamout/wstreamout + the Rust
        # format_float on amd64/arm64); not a gen_cnt family, its
        # differential lives in cnt-difftest's ref_streamout. See
        # streamout.rs.
        + '#[cfg(feature = "cabi")]\nmod streamout;\n'
        + '#[cfg(feature = "cabi")]\npub use streamout::*;\n'
        # hand-written math classification + integer-abs shims (Wave
        # MATH-CLASS); pure IEEE-754 bit ops, no FP arithmetic (i386
        # no-SSE safe). Differential lives in cnt-difftest. See math.rs.
        # Compiled under BOTH `cabi` and `cabi-math` (any gate on the
        # cabi mod itself in lib.rs).
        + "mod math;\npub use math::*;\n"
        # hand-written strtod / wide-string / bsearch-lfind shim modules.
        # (These three were once hand-added to the generated mod.rs — a
        # DO-NOT-EDIT drift that a 2026-07-14 regen silently erased,
        # breaking cnt-difftest. They live in the template now; never
        # hand-edit mod.rs.)
        + '#[cfg(feature = "cabi")]\nmod strtod;\n'
        + '#[cfg(feature = "cabi")]\npub use strtod::*;\n'
        + '#[cfg(feature = "cabi")]\nmod wcs;\n'
        + '#[cfg(feature = "cabi")]\npub use wcs::*;\n'
        + '#[cfg(feature = "cabi")]\nmod search;\n'
        + '#[cfg(feature = "cabi")]\npub use search::*;\n'
    )

    spec = {
        nm: {
            "c_signature": s["c_signature"],
            "family": s["family"],
            "slice_pattern": s["slice_pattern"],
            "return_collapse": s["return_collapse"],
            "reference": s["reference"],
            "fuzz_domain": s["fuzz_domain"],
        }
        for nm, s in sorted(syms.items())
    }
    symbols_json = json.dumps(spec, indent=2) + "\n"

    targets = {
        CABI_DIR / "generated.rs": generated_rs,
        CABI_DIR / "mod.rs": mod_rs,
        SYMBOLS_JSON: symbols_json,
    }

    if args.check:
        bad = 0
        for path, content in targets.items():
            if not path.exists() or path.read_text() != content:
                print(f"FAIL: {path} stale", file=sys.stderr)
                bad += 1
        if bad:
            return 1
        print(f"OK: {len(targets)} generated files match ({len(syms)} symbols)")
        return 0

    for path, content in targets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(REPO)} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
