#!/usr/bin/env python3
"""cnt-rust generator: cnt-manifest.toml → C-ABI shims + harness spec.

Deterministic codegen — no LLM. Emits:
  * sdk/lib/rust/cnt-rust/src/cabi/generated.rs
        #[no_mangle] extern "C" shims = unsafe slice-reconstruct
        (per slice_pattern) + collapse core return (per return_collapse).
  * sdk/lib/rust/cnt-rust/src/cabi/mod.rs   (module + raw helpers)
  * sdk/lib/rust/cnt-difftest/symbols.json  (drives the diff harness)

The shim bodies are uniform per (slice_pattern, return_collapse); the
only per-symbol judgment lives in the manifest (filled by hand for the
sample, by a diff-verified cheap model for the irregular ~30 later).

Usage:
    python3 tools/gen_cnt.py
    python3 tools/gen_cnt.py --check     # fail if regen would differ
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

try:
    import tomllib  # py3.11+
except ModuleNotFoundError:  # pragma: no cover
    import tomli as tomllib  # type: ignore

REPO = Path(__file__).resolve().parent.parent
MANIFEST = REPO / "sdk/lib/rust/cnt-rust/cnt-manifest.toml"
CABI_DIR = REPO / "sdk/lib/rust/cnt-rust/src/cabi"
SYMBOLS_JSON = REPO / "sdk/lib/rust/cnt-difftest/symbols.json"

AUTOGEN = "// @generated by tools/gen_cnt.py from cnt-manifest.toml — DO NOT EDIT\n"


def parse_params(sig: str) -> list[tuple[str, str]]:
    """Crude C-prototype param split → [(ctype, name)]. Sufficient for
    the sample's shapes (no function pointers / varargs here)."""
    inner = sig[sig.index("(") + 1 : sig.rindex(")")].strip()
    if inner in ("", "void"):
        return []
    out = []
    for part in inner.split(","):
        toks = part.strip().replace("*", " * ").split()
        name = toks[-1]
        ctype = " ".join(toks[:-1])
        out.append((ctype, name))
    return out


# Rust FFI types for the C types the sample uses.
def rs_ty(ctype: str) -> str:
    c = ctype.replace(" ", "")
    return {
        "constchar*": "*const u8",
        "charconst*": "*const u8",  # east-const spelling
        "wchar_tconst*": "*const u16",
        "char*": "*mut u8",
        "constvoid*": "*const core::ffi::c_void",
        "void*": "*mut core::ffi::c_void",
        "char**": "*mut *mut u8",
        "wchar_t*": "*mut u16",
        "size_t": "usize",
        "int": "i32",
        "__int64": "i64",
        "unsigned__int64": "u64",
        "long": "i32",  # Win i386 LP32
        "unsignedlong": "u32",
        "_locale_t": "*mut core::ffi::c_void",  # ignored
    }[c]


_CC = {"__cdecl", "CDECL", "__stdcall", "WINAPI", "NTAPI"}


def ret_ty(sig: str) -> str:
    # "void *memcpy" / "__int64 _atoi64" / "long atol" / "int atoi"
    head = sig.split("(", 1)[0].strip()
    toks = [t for t in head.replace("*", " * ").split() if t not in _CC]
    rtype = "".join(toks[:-1])  # drop the function-name token
    return {
        "size_t": "usize",
        "int": "i32",
        "long": "i32",  # Win i386 LP32: long == 32-bit
        "unsignedlong": "u32",
        "__int64": "i64",
        "char*": "*mut u8",
        "wchar_t*": "*mut u16",
        "void*": "*mut core::ffi::c_void",
    }[rtype]


# int→str family (itoa.c / itow.c). Each shim is fully self-contained
# (its own param-validation / ERANGE-backfill / byte-count contract),
# so it bypasses the generic slice-reconstruct + return-collapse path.
INT2STR = {
    "int_to_str",   # unchecked narrow: memcpy digits+NUL, no NULL guard
    "int_to_wstr",  # unchecked wide:   NULL-guarded, returns dst (even NULL)
    "s_erange_n",   # _s narrow: bad-param→str[0]=0,EINVAL; too-small→
                    #            reverse-backfill+str[0]=0,ERANGE
    "s_einval_n",   # _ui64toa_s: bad-param→EINVAL (no zero); too-small→
                    #             EINVAL (no fill)
    "s_erange_w",   # _s wide: as s_erange_n, u16 elements
    "s_einval_w",   # _ui64tow_s: as s_einval_n + the *byte-count* bug
                    #             (memcpy ndigits+1 BYTES, not *2)
}


def _mag_prologue(vt: str, v: str, rad: str) -> str:
    """Faithful magnitude+sign derivation per the value's C width:
    sign only when `radix == 10 && value < 0`; otherwise the C
    reinterprets the value's own-width bit pattern as unsigned."""
    if vt == "i64":
        return (
            f"    let neg = {rad} == 10 && {v} < 0;\n"
            f"    let mag = if neg {{ ({v} as i64).unsigned_abs() }} "
            f"else {{ {v} as u64 }};"
        )
    if vt == "i32":
        return (
            f"    let neg = {rad} == 10 && {v} < 0;\n"
            f"    let mag = if neg {{ ({v} as i32).unsigned_abs() as u64 }} "
            f"else {{ {v} as u32 as u64 }};"
        )
    if vt == "u64":
        return f"    let neg = false;\n    let mag = {v};"
    if vt == "u32":
        return f"    let neg = false;\n    let mag = {v} as u64;"
    raise SystemExit(f"int2str: unsupported value type {vt}")


def _int2str_shim(name: str, m: dict, params, rt: str) -> str:
    sp = m["slice_pattern"]
    decl = ", ".join(f"{n}: {rs_ty(t)}" for t, n in params)
    v = params[0][1]
    dst = next(n for t, n in params if rs_ty(t).startswith("*mut"))
    rad = params[-1][1]  # radix is always the trailing int
    size = next((n for t, n in params if rs_ty(t) == "usize"), None)
    fr = "crate::core_rs::radix::format_radix"
    mag = _mag_prologue(rs_ty(params[0][0]), v, rad)
    b: list[str] = []

    if sp == "int_to_str":
        b += [
            mag,
            f"    let f = {fr}(mag, {rad} as u32, neg);",
            "    let mut o = 0usize;",
            f"    if f.negative {{ *{dst} = b'-'; o = 1; }}",
            "    let mut i = 0;",
            f"    while i < f.ndigits {{ *{dst}.add(o + i) = f.digits[i]; i += 1; }}",
            f"    *{dst}.add(o + f.ndigits) = 0;",
            f"    {dst}",
        ]
    elif sp == "int_to_wstr":
        b += [
            mag,
            f"    let f = {fr}(mag, {rad} as u32, neg);",
            f"    if !{dst}.is_null() {{",
            "        let mut o = 0usize;",
            f"        if f.negative {{ *{dst} = b'-' as u16; o = 1; }}",
            "        let mut i = 0;",
            f"        while i < f.ndigits {{ *{dst}.add(o + i) = f.digits[i] as u16; i += 1; }}",
            f"        *{dst}.add(o + f.ndigits) = 0;",
            "    }",
            f"    {dst}",
        ]
    elif sp in ("s_erange_n", "s_erange_w"):
        wide = sp == "s_erange_w"
        cast = " as u16" if wide else ""
        minus = "b'-' as u16" if wide else "b'-'"
        b += [
            f"    if {dst}.is_null() || {size} == 0 || {rad} < 2 || {rad} > 36 {{",
            f"        if !{dst}.is_null() && {size} != 0 {{ *{dst} = 0; }}",
            "        return 22;",
            "    }",
            mag,
            f"    let f = {fr}(mag, {rad} as u32, neg);",
            "    let need = f.ndigits + f.negative as usize + 1;",
            f"    if need > {size} {{",
            "        let o = f.negative as usize;",
            f"        let cnt = {size} - o;",
            "        let mut i = 0;",
            "        while i < cnt && i < f.ndigits {",
            f"            *{dst}.add(o + i) = f.digits[f.ndigits - 1 - i]{cast};",
            "            i += 1;",
            "        }",
            f"        *{dst} = 0;",
            "        return 34;",
            "    }",
            "    let mut o = 0usize;",
            f"    if f.negative {{ *{dst} = {minus}; o = 1; }}",
            "    let mut i = 0;",
            f"    while i < f.ndigits {{ *{dst}.add(o + i) = f.digits[i]{cast}; i += 1; }}",
            f"    *{dst}.add(o + f.ndigits) = 0;",
            "    0",
        ]
    elif sp == "s_einval_n":
        b += [
            f"    if {dst}.is_null() || {size} == 0 || {rad} < 2 || {rad} > 36 {{",
            "        return 22;",
            "    }",
            f"    let f = {fr}({v}, {rad} as u32, false);",
            "    let need = f.ndigits + 1;",
            f"    if need > {size} {{ return 22; }}",
            "    let mut i = 0;",
            f"    while i < f.ndigits {{ *{dst}.add(i) = f.digits[i]; i += 1; }}",
            f"    *{dst}.add(f.ndigits) = 0;",
            "    0",
        ]
    elif sp == "s_einval_w":
        # _ui64tow_s byte-count bug: memcpy `ndigits+1` BYTES (NOT
        # * sizeof(wchar_t)) from a u16-LE temp into the wide dst.
        b += [
            f"    if {dst}.is_null() || {size} == 0 || {rad} < 2 || {rad} > 36 {{",
            "        return 22;",
            "    }",
            f"    let f = {fr}({v}, {rad} as u32, false);",
            "    let need = f.ndigits + 1;",
            f"    if need > {size} {{ return 22; }}",
            "    let mut tmp = [0u8; 2 * crate::core_rs::radix::RADIX_DIGITS_MAX + 2];",
            "    let mut t = 0;",
            "    let mut i = 0;",
            "    while i < f.ndigits { tmp[t] = f.digits[i]; t += 2; i += 1; }",
            f"    let db = {dst} as *mut u8;",
            "    let mut i = 0;",
            "    while i < need { *db.add(i) = tmp[i]; i += 1; }",
            "    0",
        ]
    else:
        raise SystemExit(f"{name}: unhandled int2str pattern {sp}")

    misf = m.get("preserved_misfeature", "")
    return (
        f"/// `{m['c_signature']}`\n"
        f"/// preserved misfeature: {misf}\n"
        f"#[no_mangle]\n"
        f'pub unsafe extern "C" fn {name}({decl}) -> {rt} {{\n'
        + "\n".join(b)
        + "\n}\n"
    )


def shim(name: str, m: dict) -> str:
    params = parse_params(m["c_signature"])
    sp = m["slice_pattern"]
    rc = m["return_collapse"]
    rt = ret_ty(m["c_signature"])
    if sp in INT2STR:
        return _int2str_shim(name, m, params, rt)
    decl_params = ", ".join(f"{n}: {rs_ty(t)}" for t, n in params)
    pnames = [n for _, n in params]
    ptrs = [n for t, n in params if rs_ty(t).startswith("*")]
    szp = next((n for t, n in params if rs_ty(t) == "usize"), None)
    scal = [n for t, n in params if rs_ty(t) == "i32"]  # c / val
    body: list[str] = []
    cf = m["core_fn"]

    def core_call(args: str) -> str:
        return f"crate::core_rs::{cf}({args})"

    # ---- slice reconstruction --------------------------------------
    if sp == "nul_in":
        for n in ptrs:  # only pointer args become slices; scalars pass through
            body.append(f"    let {n}_s = cstr_slice({n});")
    elif sp == "wnul_in":  # wide twin: NUL-terminated u16 → &[u16]
        for n in ptrs:
            body.append(f"    let {n}_s = wcstr_slice({n});")
    elif sp == "nul_in_maxlen":
        # strnlen-shape: walk the C string but never past the count
        # param (textbook strnlen must not read beyond maxlen).
        body.append(f"    let {ptrs[0]}_s = cstr_slice_bounded({ptrs[0]}, {szp});")
    elif sp == "dst_fixed_n":
        d, s, _ = pnames
        body.append(f"    let {d}_s = raw_mut_slice({d}, {szp});")
        body.append(f"    let {s}_s = cstr_slice({s});")
    elif sp == "ptr_len":
        for p in ptrs:
            body.append(f"    let {p}_s = raw_slice({p} as *const u8, {szp});")
    elif sp == "set_raw":
        d = ptrs[0]
        body.append(f"    let {d}_s = raw_mut_slice({d} as *mut u8, {szp});")
    elif sp == "nul_endptr_base":
        np = next(n for t, n in params if rs_ty(t) == "*const u8")
        body.append(f"    let {np}_s = cstr_slice({np});")
    elif sp == "mem_raw":
        pass  # raw_move inline below
    else:
        raise SystemExit(f"{name}: unsupported slice_pattern {sp}")

    # First/second slice names. Slices come from POINTER params only
    # (scalars like `int c` pass through untouched).
    s0 = (pnames[0] if sp == "dst_fixed_n" else ptrs[0]) + "_s"
    s1 = ptrs[1] + "_s" if len(ptrs) > 1 else None

    # ---- core call + return collapse -------------------------------
    if rc == "usize":
        body.append(f"    {core_call(s0)} as {rt}")
    elif rc == "i32_passthrough":
        body.append(f"    {core_call(f'{s0}, {s1}')}")
    elif rc == "i32_cmp_n":  # strncmp-shape: core(a, b, n)
        body.append(f"    {core_call(f'{s0}, {s1}, {szp}')}")
    elif rc == "ptr_or_null_from_opt":
        args = f"{s0}, {s1}" if s1 else f"{s0}, {scal[0]}"
        base = pnames[0] if sp == "nul_in" else ptrs[0]
        body.append(f"    match {core_call(args)} {{")
        body.append(f"        Some(i) => {base}.add(i) as {rt},")
        body.append("        None => core::ptr::null_mut(),")
        body.append("    }")
    elif rc == "ret_dst":
        if sp == "dst_fixed_n":
            d, s, _ = pnames
            body.append(f"    let _ = {core_call(f'{d}_s, {s}_s')};")
            body.append(f"    {d}")
        elif sp == "set_raw":
            d = ptrs[0]
            body.append(f"    {core_call(f'{d}_s, {scal[0]}')};")
            body.append(f"    {d}")
        elif sp == "mem_raw":
            d, s, nn = pnames
            body.append(f"    raw_move({d} as *mut u8, {s} as *const u8, {nn});")
            body.append(f"    {d}")
        else:
            raise SystemExit(f"{name}: ret_dst with {sp}")
    elif rc == "i64_trunc_i32":
        body.append(f"    let (v, _of) = {core_call(s0)};")
        body.append(f"    v as i32 as {rt}")
    elif rc == "i64_passthrough":
        body.append(f"    let (v, _of) = {core_call(s0)};")
        body.append(f"    v as {rt}")
    elif rc in ("i64_endptr", "ulong_strtoul"):
        np = next(n for t, n in params if rs_ty(t) == "*const u8")
        ep = next(n for t, n in params if rs_ty(t) == "*mut *mut u8")
        bs = next(n for t, n in params if rs_ty(t) == "i32")
        body.append(
            f"    let r = crate::core_rs::radix::parse_i64_clamped({np}_s, {bs});"
        )
        body.append(f"    if r.base_ok && !{ep}.is_null() {{")
        body.append(f"        *{ep} = {np}.add(r.end) as *mut u8;")
        body.append("    }")
        if rc == "i64_endptr":
            body.append(f"    r.value as {rt}")
        else:  # ulong_strtoul: asymmetric clamp to [1, ULONG_MAX]
            body.append("    let v = if r.value > 4294967295i64 {")
            body.append("        4294967295i64")
            body.append("    } else if r.value < -4294967295i64 {")
            body.append("        1i64")
            body.append("    } else { r.value };")
            body.append(f"    v as u32 as {rt}")
    else:
        raise SystemExit(f"{name}: unsupported return_collapse {rc}")

    misf = m.get("preserved_misfeature", "")
    return (
        f"/// `{m['c_signature']}`\n"
        f"/// preserved misfeature: {misf}\n"
        f"#[no_mangle]\n"
        f"pub unsafe extern \"C\" fn {name}({decl_params}) -> {rt} {{\n"
        + "\n".join(body)
        + "\n}\n"
    )


HELPERS = '''//! Hand-written unsafe primitives the generated shims compose. Kept
//! tiny + audited; everything symbol-specific is generated.

/// NUL-terminated C string → content slice. NULL → empty (faithful to
/// libcntpr's explicit NULL guards in tcslen.h / atoi64.c; harmless
/// for symbols whose fuzz_domain never passes NULL).
#[inline]
pub(crate) unsafe fn cstr_slice<'a>(p: *const u8) -> &'a [u8] {
    if p.is_null() {
        return &[];
    }
    let mut n = 0usize;
    while *p.add(n) != 0 {
        n += 1;
    }
    core::slice::from_raw_parts(p, n)
}

/// `strnlen`-style bounded C-string → content slice: walk to NUL but
/// never past `cap` bytes (textbook strnlen must not read beyond
/// maxlen). NULL → empty (libcntpr tcsnlen.h NULL guard).
#[inline]
pub(crate) unsafe fn cstr_slice_bounded<'a>(p: *const u8, cap: usize) -> &'a [u8] {
    if p.is_null() {
        return &[];
    }
    let mut n = 0usize;
    while n < cap && *p.add(n) != 0 {
        n += 1;
    }
    core::slice::from_raw_parts(p, n)
}

/// Wide twin of `cstr_slice`: NUL-terminated `*const u16` → content
/// slice (NUL excluded). NULL → empty.
#[inline]
pub(crate) unsafe fn wcstr_slice<'a>(p: *const u16) -> &'a [u16] {
    if p.is_null() {
        return &[];
    }
    let mut n = 0usize;
    while *p.add(n) != 0 {
        n += 1;
    }
    core::slice::from_raw_parts(p, n)
}

#[inline]
pub(crate) unsafe fn raw_slice<'a>(p: *const u8, n: usize) -> &'a [u8] {
    if p.is_null() || n == 0 {
        return &[];
    }
    core::slice::from_raw_parts(p, n)
}

#[inline]
pub(crate) unsafe fn raw_mut_slice<'a>(p: *mut u8, n: usize) -> &'a mut [u8] {
    if p.is_null() || n == 0 {
        return &mut [];
    }
    core::slice::from_raw_parts_mut(p, n)
}

/// Overlap-safe raw byte move — the ReactOS `memcpy`/`memmove`
/// algorithm verbatim (memcpy.c): forward if disjoint or dst<=src,
/// else backward. This is the one shim that IS the implementation
/// (aliasing raw pointers can't be a safe-slice core).
#[inline]
pub(crate) unsafe fn raw_move(dst: *mut u8, src: *const u8, n: usize) {
    if dst as usize <= src as usize || dst as usize >= src as usize + n {
        let mut i = 0;
        while i < n {
            *dst.add(i) = *src.add(i);
            i += 1;
        }
    } else {
        let mut i = n;
        while i > 0 {
            i -= 1;
            *dst.add(i) = *src.add(i);
        }
    }
}
'''


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    man = tomllib.loads(MANIFEST.read_text())
    syms = man["symbols"]

    shims = [
        AUTOGEN,
        "#[allow(unused_imports)]\n"
        "use super::{cstr_slice, cstr_slice_bounded, raw_move, "
        "raw_mut_slice, raw_slice, wcstr_slice};\n\n",
    ]
    for nm in sorted(syms):
        shims.append(shim(nm, syms[nm]))
        shims.append("")
    generated_rs = "\n".join(shims)

    mod_rs = AUTOGEN + HELPERS + "\nmod generated;\npub use generated::*;\n"

    spec = {
        nm: {
            "c_signature": s["c_signature"],
            "family": s["family"],
            "slice_pattern": s["slice_pattern"],
            "return_collapse": s["return_collapse"],
            "reference": s["reference"],
            "fuzz_domain": s["fuzz_domain"],
        }
        for nm, s in sorted(syms.items())
    }
    symbols_json = json.dumps(spec, indent=2) + "\n"

    targets = {
        CABI_DIR / "generated.rs": generated_rs,
        CABI_DIR / "mod.rs": mod_rs,
        SYMBOLS_JSON: symbols_json,
    }

    if args.check:
        bad = 0
        for path, content in targets.items():
            if not path.exists() or path.read_text() != content:
                print(f"FAIL: {path} stale", file=sys.stderr)
                bad += 1
        if bad:
            return 1
        print(f"OK: {len(targets)} generated files match ({len(syms)} symbols)")
        return 0

    for path, content in targets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(REPO)} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
