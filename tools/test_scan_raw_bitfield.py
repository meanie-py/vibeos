"""scan_raw_bitfield: a C bitfield reached by bit index instead of its name."""

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tools.scan_raw_bitfield import scan_text

SRC = """
unsafe fn f(p: *mut S) {
    (*p)._bitfield_1.set(0, 28, 28);             // finding: a guess at the layout
    if s.u.Flags._bitfield_1.get(0, 1) != 0 {}   // finding
    (*p).set_PageCode(0x1C);                     // right: the named accessor
    // (*p)._bitfield_1.set(0, 1, 1);            right: a comment
    let t = "_bitfield_1.set(0, 1, 1)";          // right: a string
    x._bitfield_2.set(0, 4, 1); // nolint: raw-bitfield (test)
}
impl S {
    pub fn set_Valid(&mut self, val: u8) { self._bitfield_1.set(7usize, 1u8, val as u64) }
}
"""


def test_only_hand_calls_on_a_bitfield_unit():
    assert [line for line, _ in scan_text(SRC)] == [3, 4]


def test_generated_files_are_skipped():
    assert scan_text("/* automatically generated by rust-bindgen */\n" + SRC) == []


def test_tree_is_clean():
    r = subprocess.run(
        [sys.executable, str(Path(__file__).resolve().parent / "scan_raw_bitfield.py"), "--lint"],
        capture_output=True,
        text=True,
    )
    assert r.returncode == 0, r.stdout
