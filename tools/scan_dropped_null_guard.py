#!/usr/bin/env python3
"""
scan_dropped_null_guard.py — the C null-tests an out-parameter before storing through it;
the translation stores through it and never tests it.

    C:            if (FinalUncompressedSize) *FinalUncompressedSize = size;
    translated:   *final_size = size;                        <-- NULL is a crash
    faithful:     if !final_size.is_null() { *final_size = size; }

Optional out-parameters are everywhere in Win32/NT (`PULONG ReturnLength OPTIONAL`), and
the null test is the whole contract: a caller passing NULL is saying "I don't want it".
Dropping it compiles, links, and is correct for every caller that happens to pass a
buffer — so smoke passes, and the first caller that passes NULL faults.

Found 2026-09-26 by `rustconv difftest-contract` (compress.json): `RtlDecompressFragment`
and `RtlCompressBuffer` stored `*final_size` unconditionally where compress.c writes it
only `if (final_size)`, so a NULL FinalUncompressedSize segfaulted where the C returns a
status. (The mirror class — a store the C makes unconditionally and the Rust guards — is
the older field-manual entry; this is the other direction.)

HOW. Per Rust function:
  1. a pointer PARAMETER P (`*mut T`, or a `P…`/`LP…` typedef) is stored through —
     `*P = …`, `*P.add(i) = …`, `(*P).f = …` — and
  2. the Rust body never null-tests P (`is_null`, `null_mut()`, `ARGUMENT_PRESENT`,
     `as usize`, `.as_mut()`/`.as_ref()`, `== 0`), and
  3. the C function of the same name (tools/c_twin.py) DOES null-test the same-named
     parameter: `if (P)`, `if (!P)`, `P != NULL`, `NULL == P`, `P &&`, `P ?`,
     `ARGUMENT_PRESENT(P)`.
Step 3 is what makes this usable: step 1+2 alone is every out-param in the tree, most of
which the C contract declares mandatory. The C saying "this may be NULL" is the oracle.

Coarse by design: one C test anywhere in the function counts, and one Rust test anywhere
exempts. It misses a guard dropped on ONE of several stores; it does not guess.

Usage:
    python3 tools/scan_dropped_null_guard.py            # report with the C evidence
    python3 tools/scan_dropped_null_guard.py --lint     # terse (CLI baseline gate)

Suppress a reviewed site with `// nolint: dropped-null-guard` on the store line.
Exit 1 if any finding.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tools.c_twin import CIndex, Func, affinity, blank_rust, prefer, rust_functions
from tools.source_walk import source_files

REPO = Path(__file__).resolve().parent.parent
RUST_ROOT = REPO / "sdk" / "lib" / "rust"

SKIP_PATH_RE = re.compile(r"(/target/|/\.responses/)")
NOLINT_RE = re.compile(r"//\s*nolint(?::\s*dropped-null-guard\b|\s*$)")
GEN_MARKERS = ("automatically generated by rust-bindgen", "@generated", "Do not edit manually")

# Typedef names that are NOT pointers despite the P/LP prefix shape.
_NOT_PTR = {"PAGE_SIZE", "PFN_NUMBER", "PHYSICAL_ADDRESS", "LPARAM", "PROPID", "PCI_SLOT_NUMBER"}


def split_params(params: str) -> list[tuple[str, str]]:
    out = []
    depth = 0
    cur = ""
    for c in params + ",":
        if c in "<([":
            depth += 1
        elif c in ">)]":
            depth -= 1
        if c == "," and depth == 0:
            if ":" in cur:
                name, ty = cur.split(":", 1)
                name = name.strip()
                name = re.sub(r"^mut\s+", "", name)
                if re.fullmatch(r"[A-Za-z_]\w*", name):
                    out.append((name, ty.strip()))
            cur = ""
        else:
            cur += c
    return out


def is_pointer(ty: str) -> bool:
    t = ty.strip()
    if t.startswith("*"):
        return True
    last = t.split("::")[-1]
    return bool(re.fullmatch(r"(?:P|LP)[A-Z][A-Z0-9_]*", last)) and last not in _NOT_PTR


# Both sides are computed ONCE per function body as name -> first offset / name set:
# compiling a pattern per parameter was most of a 26 s tree scan.
_STORE_RE = re.compile(
    r"(?<![\w)\]])\*\s*(?P<a>[A-Za-z_]\w*)\s*(?:\.\s*(?:add|offset)\s*\([^()]*\)\s*)?=(?!=)"
    r"|\(\s*\*\s*(?P<b>[A-Za-z_]\w*)\s*\)\s*\.\s*\w+(?:\s*\.\s*\w+)*\s*=(?!=)"
)
_TEST_RE = re.compile(
    r"\b(?P<a>[A-Za-z_]\w*)\s*\.\s*(?:is_null|as_mut|as_ref)\s*\("
    # `(IrpContext as *mut u8).is_null()` — a cast before the test.
    r"|\(\s*(?P<b>[A-Za-z_]\w*)\s+as\s+[^;{}()]*\)\s*\.\s*is_null\s*\("
    r"|\b(?P<c>[A-Za-z_]\w*)\s*(?:==|!=)\s*(?:core::ptr::|ptr::)?null"
    r"|null(?:_mut)?\s*(?:::<[^>]*>)?\s*\(\s*\)\s*(?:==|!=)\s*(?P<d>[A-Za-z_]\w*)\b"
    r"|ARGUMENT_PRESENT!?\s*\(\s*(?P<e>[A-Za-z_]\w*)\b"
    r"|\b(?P<f>[A-Za-z_]\w*)\s+as\s+(?:usize|isize|ULONG_PTR|u64|u32)\b"
    # `pFile as *const c_void != core::ptr::null()` — a cast, then the compare.
    r"|\b(?P<i>[A-Za-z_]\w*)\s+as\s+[^;{}()=!]*?(?:==|!=)\s*(?:core::ptr::|ptr::)?null"
    r"|\b(?P<g>[A-Za-z_]\w*)\s*(?:==|!=)\s*0\b"
    r"|NonNull::new\s*\(\s*(?P<h>[A-Za-z_]\w*)\b"
)


def stores(body: str) -> dict[str, int]:
    """Pointer names stored through in `body`, each with its first store offset."""
    out: dict[str, int] = {}
    for m in _STORE_RE.finditer(body):
        out.setdefault(m.group("a") or m.group("b"), m.start())
    return out


def tested(body: str) -> set[str]:
    """Names `body` null-tests, in any of the idioms translations use."""
    return {next(g for g in m.groups() if g) for m in _TEST_RE.finditer(body)}


# P itself, not `*P` / `x.P` / `x->P` (a pointee or a member), and not `P->f` / `P[i]` / `P.f`.
def _bare(v: str) -> str:
    return r"(?<![\w*.>])" + v + r"(?!\s*(?:->|\.|\[)|\w)"


_ASSERT_RE = re.compile(r"\b(?:NT_)?ASSERTM?(?:MSG)?\s*\(")


def _in_assert(body: str, at: int) -> bool:
    """`ASSERT(P != NULL)` says P is MANDATORY — the opposite of an optional out-param."""
    line_start = body.rfind(";", 0, at)
    line_start = max(line_start, body.rfind("{", 0, at), body.rfind("}", 0, at))
    # `at + 1`: the match may START at the assert's own `(` — `ASSERT ( P && Q )`.
    return bool(_ASSERT_RE.search(body, line_start + 1, at + 1))


def c_test(p: str, body: str) -> str | None:
    v = _bare(re.escape(p))
    pat = re.compile(
        r"\bif\s*\(\s*!?\s*" + v + r"\s*\)"
        r"|"
        + v
        + r"\s*(?:==|!=)\s*(?:NULL|0)\b|\bNULL\s*(?:==|!=)\s*"
        + v
        + r"|(?:\(|&&|\|\|)\s*!?\s*"
        + v
        + r"\s*(?:&&|\|\||\?)"
        r"|ARGUMENT_PRESENT\s*\(\s*" + re.escape(p) + r"\s*\)"
    )
    for m in pat.finditer(body):
        if _in_assert(body, m.start()):
            continue
        lo = body.rfind("\n", 0, m.start()) + 1
        hi = body.find("\n", m.end())
        return " ".join(body[lo : hi if hi >= 0 else len(body)].split())[:110]
    return None


def c_derefs(p: str, body: str) -> bool:
    """The C dereferences P itself (`*P`, `P->f`, `P[i]`)."""
    v = re.escape(p)
    return bool(re.search(r"(?<![\w)\]])\*\s*" + v + r"\b|\b" + v + r"\s*(?:->|\[)", body))


def c_param_names(params: str) -> list[str]:
    """Parameter names of a C signature (the last identifier of each comma-split part)."""
    out = []
    for part in _split_top(params):
        part = re.sub(r"\[[^\]]*\]", "", part)
        ids = re.findall(r"[A-Za-z_]\w*", part)
        if ids and ids != ["void"]:
            out.append(ids[-1])
    return out


def _split_top(s: str) -> list[str]:
    parts, depth, cur = [], 0, ""
    for c in s:
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += c
    if cur.strip():
        parts.append(cur)
    return parts


def _norm(n: str) -> str:
    return n.replace("_", "").lower()


def c_name_for(rust_params: list[tuple[str, str]], idx: int, c_params: list[str]) -> str | None:
    """The C parameter the Rust parameter at `idx` translates: by POSITION when the arities
    agree (names get snake_cased — `FinalCompressedSize` -> `final_compressed_size`), else
    by normalized name."""
    if len(rust_params) == len(c_params):
        return c_params[idx]
    want = _norm(rust_params[idx][0])
    for c in c_params:
        if _norm(c) == want:
            return c
    return None


_CALL_RE = re.compile(r"\b([A-Za-z_]\w*)\s*\(")


def c_guard(twin: Func, name: str, index: CIndex, depth: int = 1) -> str | None:
    """Evidence that `twin` null-tests parameter `name`, directly or — one level deep —
    in a callee it hands `name` to unchanged (compress.c's RtlDecompressFragment forwards
    final_size to lznt1_decompress, which is where the `if (final_size)` lives)."""
    ev = c_test(name, twin.body)
    # Only a function that hands P on WITHOUT touching it defers the null contract to its
    # callee; one that dereferences P itself has already treated it as mandatory.
    if ev or depth == 0 or c_derefs(name, twin.body):
        return ev
    for m in _CALL_RE.finditer(twin.body):
        callee = m.group(1)
        if callee in ("if", "while", "for", "switch", "return", "sizeof"):
            continue
        close = _match_paren(twin.body, m.end() - 1)
        if close < 0:
            continue
        args = [a.strip() for a in _split_top(twin.body[m.end() : close])]
        if name not in args:
            continue
        pos = args.index(name)
        for sub in index.in_file(twin.path, callee):
            names = c_param_names(sub.params)
            if len(names) == len(args):
                ev = c_guard(sub, names[pos], index, depth - 1)
                if ev:
                    return f"{callee}(): {ev}"
    return None


def _match_paren(text: str, open_at: int) -> int:
    depth = 0
    for i in range(open_at, len(text)):
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                return i
    return -1


@dataclass
class Site:
    path: Path
    line: int
    fn: str
    param: str
    index: int
    params: list[tuple[str, str]]
    src: str


def candidates(path: Path) -> list[Site]:
    try:
        raw = path.read_text(errors="replace")
    except OSError:
        return []
    if any(g in raw[:2000] for g in GEN_MARKERS):
        return []
    text = blank_rust(raw)
    lines = raw.split("\n")
    out = []
    for f in rust_functions(text, path):
        stored = stores(f.body)
        if not stored:
            continue
        params = split_params(f.params)
        checked: set[str] | None = None
        for i, (name, ty) in enumerate(params):
            at = stored.get(name, -1)
            if at < 0 or not is_pointer(ty):
                continue
            if checked is None:
                checked = tested(f.body)
            if name in checked:
                continue
            ln = text.count("\n", 0, f.body_start + at) + 1
            if NOLINT_RE.search(lines[ln - 1]):
                continue
            out.append(Site(path, ln, f.name, name, i, params, lines[ln - 1].strip()[:110]))
    return out


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("-")]
    lint = "--lint" in sys.argv
    roots = [Path(a) for a in args] if args else [RUST_ROOT]
    files: list[Path] = []
    for root in roots:
        if root.is_file():
            files.append(root)
        elif root.is_dir():
            files.extend(source_files(root))
        else:
            print(f"scan_dropped_null_guard: no such path: {root}", file=sys.stderr)
            return 2
    sites = [
        s for f in sorted(set(files)) if not SKIP_PATH_RE.search(str(f)) for s in candidates(f)
    ]
    index = CIndex()
    index.load({s.fn for s in sites})

    findings: list[tuple[str, Site, str]] = []
    for s in sites:
        twins: list[Func] = prefer(s.path, index.get(s.fn))
        # The BEST twin decides: a same-named function in an unrelated module is not evidence.
        evidence = None
        # A same-named C function sharing no path word with the crate is somebody else's
        # (usbport's KeQuerySystemTime shim is not freeldr's stub) — no evidence either way.
        if twins and affinity(s.path, twins[0]) > 0:
            cname = c_name_for(s.params, s.index, c_param_names(twins[0].params))
            if cname:
                evidence = c_guard(twins[0], cname, index)
        if evidence is None:
            continue
        try:
            rel = s.path.relative_to(REPO)
        except ValueError:
            rel = s.path
        findings.append((str(rel), s, evidence))

    for rel, s, evidence in findings:
        if lint:
            print(f"{rel}:{s.line}: dropped-null-guard {s.fn}({s.param})")
        else:
            print(
                f"{rel}:{s.line}: dropped-null-guard: {s.fn}: "
                f"stores through `{s.param}`, never tests it"
            )
            print(f"    rust: {s.src}")
            print(f"    c:    {evidence}")
    if not lint:
        print(f"\n{len(findings)} site(s)")
        if findings:
            print("fix: guard the store as the C does — `if !P.is_null() { *P = v; }`;")
            print(
                "     if the Rust contract makes P mandatory, mark `// nolint: dropped-null-guard`."
            )
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
