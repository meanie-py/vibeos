use regex::Regex;
use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn valid_stem(stem: &str) -> bool {
    !stem.is_empty() && stem.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_')
}

fn nm_symbols(root: &Path, stem: &str) -> Result<Vec<String>, String> {
    let object = root.join(format!(
        "build-amd64/dll/win32/msvcrt/CMakeFiles/msvcrt_static.dir/{stem}.c.obj"
    ));
    if !object.is_file() {
        return Err(format!(
            "{} not built; fix: ./vibeos-cli build --arch amd64",
            object.display()
        ));
    }
    let object = object
        .canonicalize()
        .map_err(|e| format!("{}: {e}", object.display()))?;
    if !object.starts_with(root) {
        return Err(format!(
            "amd64 object escapes repository root: {}",
            object.display()
        ));
    }
    let nm = root.join(".build-tools/llvm-mingw/bin/llvm-nm");
    let output = Command::new(&nm)
        .arg("--defined-only")
        .arg(&object)
        .output()
        .map_err(|e| format!("failed to run {}: {e}", nm.display()))?;
    if !output.status.success() {
        return Err(format!(
            "{} failed ({}): {}",
            nm.display(),
            output.status,
            String::from_utf8_lossy(&output.stderr).trim()
        ));
    }
    let stdout = String::from_utf8_lossy(&output.stdout);
    let symbols: BTreeSet<String> = stdout
        .lines()
        .filter_map(|line| {
            let fields: Vec<_> = line.split_whitespace().collect();
            (fields.len() == 3 && fields[1] == "T")
                .then(|| fields[2].split('@').next().unwrap_or(fields[2]).to_owned())
        })
        .collect();
    if symbols.is_empty() {
        return Err(format!("{} produced no defined text symbols", nm.display()));
    }
    Ok(symbols.into_iter().collect())
}

fn unrenamable(source: &str, symbols: &[String]) -> BTreeSet<String> {
    let tags = Regex::new(r"\bstruct\s+([A-Za-z_]\w*)").unwrap();
    let undefs = Regex::new(r"(?m)^\s*#\s*undef\s+([A-Za-z_]\w*)").unwrap();
    let tag_names: BTreeSet<_> = tags
        .captures_iter(source)
        .map(|c| c[1].to_owned())
        .collect();
    let undef_names: BTreeSet<_> = undefs
        .captures_iter(source)
        .map(|c| c[1].to_owned())
        .collect();
    symbols
        .iter()
        .filter(|s| tag_names.contains(*s) || undef_names.contains(*s))
        .cloned()
        .collect()
}

fn definition_regex(name: &str) -> Regex {
    let pattern = format!(
        r"(?ms)^(?P<ret>[A-Za-z_][^;{{}}()\n]*?)\s*(?:\b(?P<cc>CDECL|WINAPIV|WINAPI|__cdecl)\s+)?(?P<name>{})\s*\((?P<params>[^;{{}}]*?)\)\s*\{{",
        regex::escape(name)
    );
    Regex::new(&pattern).unwrap()
}

fn prototypes(
    source: &str,
    symbols: &[String],
    colliding: &BTreeSet<String>,
) -> (Vec<String>, Vec<String>) {
    let mut found = Vec::new();
    let mut missing = Vec::new();
    for symbol in symbols {
        let re = definition_regex(symbol);
        let Some(c) = re.captures_iter(source).find(|c| {
            // Rust regex has no lookbehind. Check the exact byte preceding the
            // symbol so `_stat` cannot match `msvcrt_stat64_to_stat`'s suffix.
            let start = c.name("name").unwrap().start();
            start == 0 || !matches!(source.as_bytes()[start - 1], b'a'..=b'z' | b'A'..=b'Z' | b'0'..=b'9' | b'_')
        }) else {
            missing.push(symbol.clone());
            continue;
        };
        let tidy = |s: &str| s.split_whitespace().collect::<Vec<_>>().join(" ");
        let ret = tidy(&c["ret"]);
        let cc = c
            .name("cc")
            .map(|v| format!("{} ", v.as_str()))
            .unwrap_or_default();
        let params = match tidy(&c["params"]).as_str() {
            "" => "void".to_owned(),
            p => p.to_owned(),
        };
        let label = if colliding.contains(symbol) {
            format!(" __asm__(\"ref_{symbol}\")")
        } else {
            String::new()
        };
        found.push(format!("{ret} {cc}{symbol}({params}){label};"));
    }
    (found, missing)
}

fn render_header(stem: &str, protos: &[String], missing: &[String]) -> String {
    let guard = format!("MSVCRT_DIFFTEST_{}_PROTOS_H", stem.to_ascii_uppercase());
    let mut out = vec![
        format!("/* GENERATED by tools/gen_msvcrt_ref_protos.py from {stem}.c — DO NOT EDIT."),
        " *".into(),
        format!(" * A prototype for every function {stem}.c defines, in the source's own"),
        " * spelling, to be included AFTER build.rs's rename wall so each one is".into(),
        " * renamed alongside the definition it describes.".into(),
        " *".into(),
        " * Without these, every call placed above its definition falls to C's".into(),
        " * implicit-declaration rule and becomes `int()` — a 64-bit return silently".into(),
        " * truncated to 32 bits, in code that compiles and links.  The harness's".into(),
        " * -Werror=implicit-function-declaration is what makes that loud; this file".into(),
        " * is what answers it.".into(),
        " *".into(),
        format!(" * Regenerate:  python3 tools/gen_msvcrt_ref_protos.py {stem}.c"),
        " */".into(),
        format!("#ifndef {guard}"),
        format!("#define {guard}"),
        "".into(),
    ];
    out.extend(protos.iter().cloned());
    if !missing.is_empty() {
        out.extend([
            "".into(),
            "/* Symbols whose definition this generator could not parse.  Listed,".into(),
            " * not silently dropped — each is a prototype the reference TU is".into(),
            " * missing, so if the build then complains about an implicit".into(),
            " * declaration, the name will be here. */".into(),
        ]);
        out.extend(missing.iter().map(|m| format!("/*   UNPARSED: {m} */")));
    }
    out.extend(["".into(), format!("#endif /* {guard} */"), "".into()]);
    out.join("\n")
}

fn render_skiplist(stem: &str, colliding: &BTreeSet<String>) -> String {
    let mut lines = vec![
        format!("# GENERATED by tools/gen_msvcrt_ref_protos.py from {stem}.c — DO NOT EDIT."),
        "#".into(),
        "# Symbols a `#define <n> ref_<n>` rename wall cannot rename: either the".into(),
        "# name is also a struct tag (the wall would rewrite the TYPE), or the TU".into(),
        "# `#undef`s it (which silently DELETES the rename). See unrenamable().".into(),
        format!("# msvcrt_{stem}_protos.h carries their rename as an asm label instead;"),
        "# build.rs must skip exactly these when emitting the wall.".into(),
    ];
    lines.extend(colliding.iter().cloned());
    lines.push(String::new());
    lines.join("\n")
}

/// Derive the prototype header and rename skiplist from the local amd64 object.
pub fn generate(root: &Path, stem: &str) -> Result<Vec<(PathBuf, String)>, String> {
    if !valid_stem(stem) {
        return Err(format!("invalid msvcrt source stem: {stem:?}"));
    }
    let root = root
        .canonicalize()
        .map_err(|e| format!("invalid repository root {}: {e}", root.display()))?;
    let source_path = root.join("dll/win32/msvcrt").join(format!("{stem}.c"));
    if !source_path.is_file() {
        return Err(format!("no such source: dll/win32/msvcrt/{stem}.c"));
    }
    let source_real = source_path
        .canonicalize()
        .map_err(|e| format!("{}: {e}", source_path.display()))?;
    if !source_real.starts_with(&root) {
        return Err("msvcrt source escapes repository root".into());
    }
    let source =
        fs::read_to_string(&source_real).map_err(|e| format!("{}: {e}", source_real.display()))?;
    let symbols = nm_symbols(&root, stem)?;
    let colliding = unrenamable(&source, &symbols);
    let (protos, missing) = prototypes(&source, &symbols, &colliding);
    let out = root.join("sdk/lib/rust/msvcrt-difftest/refstub");
    Ok(vec![
        (
            out.join(format!("msvcrt_{stem}_protos.h")),
            render_header(stem, &protos, &missing),
        ),
        (
            out.join(format!("msvcrt_{stem}_no_rename.txt")),
            render_skiplist(stem, &colliding),
        ),
    ])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pointer_returns_and_variadic_conventions() {
        let (got, missing) = prototypes(
            "void *ptr(void) {}\nint WINAPIV var(int x, ...) {}\n",
            &["ptr".into(), "var".into()],
            &BTreeSet::new(),
        );
        assert!(missing.is_empty());
        assert_eq!(got, ["void * ptr(void);", "int WINAPIV var(int x, ...);"]);
    }

    #[test]
    fn convention_and_name_may_start_separate_lines() {
        let (got, missing) = prototypes(
            "int\nWINAPIV\nvar(int x, ...) {}\n",
            &["var".into()],
            &BTreeSet::new(),
        );
        assert!(missing.is_empty());
        assert_eq!(got, ["int WINAPIV var(int x, ...);"]);
    }

    #[test]
    fn stat_does_not_match_stat64_to_stat_tail() {
        let src = "struct _stat { int x; };\nint msvcrt_stat64_to_stat(int x) { return x; }\nint _stat(void) { return 0; }\n";
        let (got, missing) = prototypes(src, &["_stat".into()], &BTreeSet::new());
        assert!(missing.is_empty());
        assert_eq!(got, ["int _stat(void);"]);
    }
}
