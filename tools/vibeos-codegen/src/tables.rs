use regex::Regex;
use std::collections::{BTreeSet, HashMap};

/// Preserve deliberate shipping divergences from the inherited C table. These were
/// previously hand-edited into generated Rust (501abe55d05 / 9495f2330ac), so the
/// old generator silently erased them. Explicit source overrides still use the
/// literal extractor; the checkout recipe uses this function.
pub fn rtl_error_tables(source: &str, winerror: &str, ntstatus: &str) -> Result<String, String> {
    if !Regex::new(r"(?m)^#define\s+ERROR_NOT_SAME_OBJECT\s+1656\s*$")
        .unwrap()
        .is_match(winerror)
        || !Regex::new(r"(?m)^#define\s+STATUS_NOT_SAME_OBJECT\s+\(\(NTSTATUS\)0xC00001AC\)")
            .unwrap()
            .is_match(ntstatus)
    {
        return Err("STATUS_NOT_SAME_OBJECT override needs review: SDK values changed".into());
    }
    let mut out = error_tables(source)?;
    if out.contains("pub static table_c00001ac:") {
        return Err(
            "STATUS_NOT_SAME_OBJECT now exists in C; review/remove the Rust generator override"
                .into(),
        );
    }
    let replacements = [
        ("    STATUS_ILLEGAL_INSTRUCTION,\n".to_string(), "    STATUS_ILLEGAL_INSTRUCTION, // c000001d: passes through, like c0000025 (upstream e9a67ff1bd5)\n".to_string()),
        ("pub static table_c0000202:".to_string(), "/// STATUS_NOT_SAME_OBJECT (NtCompareObjects, Windows 10) -> ERROR_NOT_SAME_OBJECT. Windows\n/// maps it; the inherited table stopped at 0xc000019c, so CompareObjectHandles reported\n/// ERROR_MR_MID_NOT_FOUND (317) for two different objects.\npub static table_c00001ac: [DWORD; 1] = [1656];\n\npub static table_c0000202:".to_string()),
        ("    error_table { start: 0xc0000202,".to_string(), "    error_table { start: 0xc00001ac, end: 0xc00001ad, table: table_c00001ac.as_ptr() },\n    error_table { start: 0xc0000202,".to_string()),
    ];
    for (before, after) in replacements {
        if out.matches(&before).count() != 1 {
            return Err(format!(
                "RTL source changed; review generator override at {before:?}"
            ));
        }
        out = out.replacen(&before, &after, 1);
    }
    let dispatch = Regex::new(r"pub static ERROR_TABLE: \[error_table; (\d+)\]").unwrap();
    let captures = dispatch
        .captures(&out)
        .ok_or("missing rendered RTL dispatch")?;
    let count: usize = captures[1]
        .parse()
        .map_err(|_| "invalid RTL dispatch length")?;
    out = dispatch
        .replace(
            &out,
            format!("pub static ERROR_TABLE: [error_table; {}]", count + 1),
        )
        .into_owned();
    Ok(out)
}

/// Reproduce `gen_error_tables.py` from the contents of rtl/error.c.
pub fn error_tables(source: &str) -> Result<String, String> {
    let comments = Regex::new(r"(?s)/\*.*?\*/").unwrap();
    let c = comments.replace_all(source, "");
    let table_re = Regex::new(
        r"(?s)static\s+const\s+DWORD\s+(table_[0-9a-fA-F]+)\s*\[(\d+)\]\s*=\s*\{(.*?)\}\s*;",
    )
    .unwrap();
    let mut lines = vec![
        "//! AUTO-GENERATED by tools/gen_error_tables.py from sdk/lib/rtl/error.c".to_string(),
        "//! — the NTSTATUS->DOS code tables (pure data). Element names resolve".to_string(),
        "//! via crate::winerr::*; the dispatch struct is defined in lib.rs.".to_string(),
        "//! DO NOT edit by hand; re-run the generator if error.c changes.".to_string(),
        "#![allow(dead_code)]".to_string(),
        "use crate::winerr::*;".to_string(),
        "use crate::{error_table, DWORD};".to_string(),
        String::new(),
    ];
    for cap in table_re.captures_iter(&c) {
        let name = &cap[1];
        let n: usize = cap[2]
            .parse()
            .map_err(|_| format!("{name}: invalid declared count"))?;
        let items: Vec<&str> = cap[3]
            .split(',')
            .map(str::trim)
            .filter(|s| !s.is_empty())
            .collect();
        if items.len() != n {
            return Err(format!(
                "{name}: declared [{n}] but found {} entries",
                items.len()
            ));
        }
        lines.push(format!("pub static {name}: [DWORD; {n}] = ["));
        for item in items {
            lines.push(format!("    {item},"));
        }
        lines.push("];".to_string());
        lines.push(String::new());
    }
    let dispatch_re = Regex::new(r"(?s)error_table\s*\[\s*\]\s*=\s*\{(.*?)\}\s*;").unwrap();
    let disp = dispatch_re
        .captures(&c)
        .ok_or_else(|| "could not find error_table[] dispatch array".to_string())?;
    let entry_re = Regex::new(
        r"\{\s*([0-9a-fA-Fx]+)\s*,\s*([0-9a-fA-Fx]+)\s*,\s*(table_[0-9a-fA-F]+|NULL)\s*\}",
    )
    .unwrap();
    let entries: Vec<_> = entry_re.captures_iter(&disp[1]).collect();
    lines.push(format!(
        "pub static ERROR_TABLE: [error_table; {}] = [",
        entries.len()
    ));
    for e in &entries {
        let (start, end, tbl) = (&e[1], &e[2], &e[3]);
        if tbl == "NULL" {
            lines.push(format!(
                "    error_table {{ start: {start}, end: {end}, table: core::ptr::null() }},"
            ));
        } else {
            lines.push(format!(
                "    error_table {{ start: {start}, end: {end}, table: {tbl}.as_ptr() }},"
            ));
        }
    }
    lines.push("];".to_string());
    Ok(lines.join("\n") + "\n")
}

/// Reproduce `gen_winerror_consts.py`; `headers` are header file contents in search order.
pub fn winerror_consts(source: &str, headers: &[String]) -> Result<String, String> {
    let cut_re = Regex::new(r"#\[no_mangle\]").unwrap();
    let region = &source[..cut_re
        .find(source)
        .map(|m| m.start())
        .unwrap_or(source.len())];
    let block_comments = Regex::new(r"(?s)/\*.*?\*/").unwrap();
    let no_block = block_comments.replace_all(region, "");
    let line_comments = Regex::new(r"//.*").unwrap();
    let no_comments = line_comments.replace_all(&no_block, "");
    let ident_re = Regex::new(r"\b([A-Z][A-Z0-9_]{3,})\b").unwrap();
    let own: BTreeSet<&str> = [
        "DWORD",
        "ULONG",
        "NTSTATUS",
        "PULONG",
        "PVOID",
        "BOOLEAN",
        "HANDLE",
        "PTEB",
        "TEB",
        "PWSTR",
        "USHORT",
        "UCHAR",
        "LONG",
        "ERROR_TABLE",
    ]
    .into_iter()
    .collect();
    let referenced: BTreeSet<String> = ident_re
        .captures_iter(&no_comments)
        .map(|c| c[1].to_string())
        .filter(|s| !own.contains(s.as_str()))
        .collect();

    let simple = Regex::new(
        r"(?m)^#define\s+([A-Z][A-Z0-9_]+)\s+\(?(-?\d+|0[xX][0-9a-fA-F]+)L?\)?\s*(?://|/\*|$)",
    )
    .unwrap();
    let hresult = Regex::new(
        r"(?m)^#define\s+([A-Z][A-Z0-9_]+)\s+_HRESULT_TYPEDEF_\((0[xX][0-9a-fA-F]+)L?\)",
    )
    .unwrap();
    let status =
        Regex::new(r"(?m)^#define\s+([A-Z][A-Z0-9_]+)\s+\(\(NTSTATUS\)(0[xX][0-9a-fA-F]+)L?\)")
            .unwrap();
    let mut defs: HashMap<String, String> = HashMap::new();
    for header in headers {
        for captures in simple.captures_iter(header) {
            defs.entry(captures[1].to_string())
                .or_insert_with(|| captures[2].to_string());
        }
        for captures in hresult.captures_iter(header) {
            defs.entry(captures[1].to_string())
                .or_insert_with(|| captures[2].to_string());
        }
        for captures in status.captures_iter(header) {
            defs.entry(captures[1].to_string())
                .or_insert_with(|| captures[2].to_string());
        }
    }
    let missing: Vec<_> = referenced
        .iter()
        .filter(|n| !defs.contains_key(*n))
        .cloned()
        .collect();
    if !missing.is_empty() {
        return Err(format!(
            "UNRESOLVED constants (not in given headers): {}",
            missing.join(", ")
        ));
    }
    let mut lines = vec![
        "//! AUTO-GENERATED by tools/gen_winerror_consts.py from the SDK headers".to_string(),
        "//! (winerror.h + ntstatus.h) — the Win32 ERROR_* / NT STATUS_* codes".to_string(),
        "//! referenced by the NTSTATUS->DOS error tables in rtl/error.c, all as".to_string(),
        "//! DWORD (the table element type). DO NOT edit by hand; re-run the".to_string(),
        "//! generator if the referenced set changes.".to_string(),
        "#![allow(dead_code)]".to_string(),
        "use crate::DWORD;".to_string(),
        String::new(),
    ];
    for name in referenced {
        let value = &defs[&name];
        let rendered = if value.to_ascii_lowercase().starts_with("0x") {
            let number = u64::from_str_radix(&value[2..], 16)
                .map_err(|_| format!("invalid hex constant for {name}: {value}"))?;
            format!("0x{number:08x}")
        } else {
            value.clone()
        };
        lines.push(format!("pub const {name}: DWORD = {rendered};"));
    }
    Ok(lines.join("\n") + "\n")
}

/// Reproduce the neutral-LCID table generator from the supplied C source.
pub fn lcid(source: &str) -> Result<String, String> {
    let case_re =
        Regex::new(r"case\s+(0x[0-9A-Fa-f]+)\s*:\s*return\s+(0x[0-9A-Fa-f]+)\s*;\s*//\s*(.*)$")
            .unwrap();
    let mut rows: Vec<(u64, u64, String)> = Vec::new();
    for line in source.lines() {
        if let Some(c) = case_re.captures(line) {
            let parse = |s: &str| {
                u64::from_str_radix(&s[2..], 16).map_err(|_| format!("malformed LCID row: {line}"))
            };
            rows.push((parse(&c[1])?, parse(&c[2])?, c[3].trim().to_string()));
        }
    }
    if rows.is_empty() {
        return Err("error: no `case 0x..: return 0x..;` rows found".to_string());
    }
    let mut lines = vec![
        "// @generated by tools/gen_kernel32_vista_lcid_table.py — DO NOT EDIT.".to_string(),
        "// Source: dll/win32/kernel32/kernel32_vista/LocaleNameToLCID.c (neutral-LCID switch)."
            .to_string(),
        "//! Verbatim extraction of the special neutral-LCID remap table.".to_string(),
        String::new(),
        "/// Map a special neutral LCID (SubLangId >= 0x18) to its default locale.".to_string(),
        "/// Returns `None` for an unhandled neutral LCID (the C `ASSERT(FALSE)` path)."
            .to_string(),
        "#[inline]".to_string(),
        "pub fn neutral_lcid_remap(lcid: u32) -> Option<u32> {".to_string(),
        "    match lcid {".to_string(),
    ];
    for (lcid, ret, comment) in rows {
        lines.push(format!(
            "        0x{lcid:05X} => Some(0x{ret:05X}), // {comment}"
        ));
    }
    lines.extend([
        "        _ => None,".to_string(),
        "    }".to_string(),
        "}".to_string(),
        String::new(),
    ]);
    Ok(lines.join("\n"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shipping_rtl_override_survives_regeneration_and_rejects_sdk_drift() {
        let source = "static const DWORD table_c0000001[1] = { STATUS_ILLEGAL_INSTRUCTION };\nstatic const DWORD table_c0000202[1] = { ERROR_OTHER };\nerror_table[] = {{0xc0000001,0xc0000002,table_c0000001},{0xc0000202,0xc0000203,table_c0000202},{0,0,NULL}};";
        let winerror = "#define ERROR_NOT_SAME_OBJECT 1656\n";
        let ntstatus = "#define STATUS_NOT_SAME_OBJECT ((NTSTATUS)0xC00001AC)\n";
        let out = rtl_error_tables(source, winerror, ntstatus).unwrap();
        assert!(out.contains("pub static table_c00001ac: [DWORD; 1] = [1656];"));
        assert!(out.contains("start: 0xc00001ac, end: 0xc00001ad, table: table_c00001ac.as_ptr()"));
        assert!(out.contains("ERROR_TABLE: [error_table; 4]"));
        assert!(out.contains("upstream e9a67ff1bd5"));
        assert!(rtl_error_tables(source, &winerror.replace("1656", "1657"), ntstatus).is_err());
        assert!(rtl_error_tables(
            &source.replace("table_c0000202", "table_c00001ac"),
            winerror,
            ntstatus
        )
        .is_err());
    }

    #[test]
    fn error_tables_requires_dispatch() {
        assert_eq!(
            error_tables("static const DWORD table_1[1] = { 1 };"),
            Err("could not find error_table[] dispatch array".into())
        );
    }

    #[test]
    fn error_tables_checks_declared_count() {
        let src = "static const DWORD table_1[2] = { 1 }; error_table[] = {};";
        assert_eq!(
            error_tables(src),
            Err("table_1: declared [2] but found 1 entries".into())
        );
    }

    #[test]
    fn winerror_filters_comments_and_resolves_constants() {
        let source = "/* ERROR_FAKE */\nERROR_REAL, // STATUS_FAKE\n#[no_mangle]\nERROR_LATE";
        let headers = vec!["#define ERROR_REAL 0xAB\n#define ERROR_LATE 2".to_string()];
        let out = winerror_consts(source, &headers).unwrap();
        assert!(out.contains("pub const ERROR_REAL: DWORD = 0x000000ab;"));
        assert!(!out.contains("FAKE"));
        assert!(!out.contains("ERROR_LATE"));
    }

    #[test]
    fn winerror_reports_unresolved_constants() {
        assert_eq!(
            winerror_consts("ERROR_MISS", &[]),
            Err("UNRESOLVED constants (not in given headers): ERROR_MISS".into())
        );
    }

    #[test]
    fn lcid_rejects_empty_or_malformed_rows() {
        assert!(lcid("case 0x1: return nope; // bad").is_err());
        assert!(lcid("switch (x) {} ")
            .unwrap_err()
            .contains("no `case 0x..: return 0x..;` rows"));
    }
}
