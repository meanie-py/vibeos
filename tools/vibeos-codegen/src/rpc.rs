//! Text-oriented port of tools/gen_rpc_guards.py.
use regex::Regex;
use std::path::Path;

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Param {
    pub ty: String,
    pub name: String,
}
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Proto {
    pub ret: String,
    pub name: String,
    pub params: Vec<Param>,
}
fn split_params(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let (mut d, mut start) = (0i32, 0usize);
    for (i, c) in s.char_indices() {
        if c == '(' || c == '[' {
            d += 1
        } else if c == ')' || c == ']' {
            d -= 1
        }
        if c == ',' && d == 0 {
            let p = s[start..i].split_whitespace().collect::<Vec<_>>().join(" ");
            if !p.is_empty() {
                out.push(p)
            }
            start = i + 1
        }
    }
    let p = s[start..].split_whitespace().collect::<Vec<_>>().join(" ");
    if !p.is_empty() {
        out.push(p)
    }
    out
}
fn param(s: &str) -> Result<Param, String> {
    let ar = Regex::new(r"^(.*?)\s*(\w+)\s*\[[^\]]*\]$").unwrap();
    if let Some(m) = ar.captures(s) {
        return Ok(Param {
            ty: format!("{} *", m[1].trim()),
            name: m[2].into(),
        });
    }
    let plain = Regex::new(r"^(.*?[\s\*])(\w+)$").unwrap();
    if s.contains('(') {
        return Err(format!("unsupported parameter {s:?}"));
    }
    if let Some(m) = plain.captures(s) {
        return Ok(Param {
            ty: m[1].trim().into(),
            name: m[2].into(),
        });
    }
    Err(format!("unsupported parameter {s:?}"))
}
pub fn parse_header(text: &str) -> Result<Vec<Proto>, String> {
    let re =
        Regex::new(r"(?ms)^([A-Za-z_][\w \t\*]*?)[ \t]+__cdecl[ \t]+(\w+)\(\s*(.*?)\);").unwrap();
    let mut out = Vec::new();
    for m in re.captures_iter(text) {
        let raw = m[3].trim();
        let params = if raw.is_empty() || raw == "void" {
            Vec::new()
        } else {
            split_params(raw)
                .iter()
                .map(|p| param(p))
                .collect::<Result<Vec<_>, _>>()?
        };
        out.push(Proto {
            ret: m[1].split_whitespace().collect::<Vec<_>>().join(" "),
            name: m[2].into(),
            params,
        })
    }
    if out.is_empty() {
        return Err("no `__cdecl` client prototypes found; is this a widl _c.h?".into());
    }
    Ok(out)
}
fn decl(t: &str, n: &str) -> String {
    if t.ends_with('*') {
        format!("{t}{n}")
    } else {
        format!("{t} {n}")
    }
}
pub fn signature(p: &Proto) -> String {
    let mut a = vec![
        "RPC_GUARD_FILTER guard_filter".into(),
        "DWORD *guard_code".into(),
    ];
    if p.ret != "void" {
        a.push(decl(&format!("{} *", p.ret), "guard_ret"))
    }
    a.extend(p.params.iter().map(|x| decl(&x.ty, &x.name)));
    format!("BOOL {}_guarded({})", p.name, a.join(", "))
}
pub fn render(
    protos: &[Proto],
    header: &str,
    preludes: &[String],
    guard_h: &str,
) -> (String, String) {
    let banner =
        format!("/* Generated by tools/gen_rpc_guards.py from {header}. Do not edit. */\n");
    let gh = Path::new(guard_h)
        .file_name()
        .unwrap_or_default()
        .to_string_lossy();
    let macro_name = gh
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect::<String>()
        .to_uppercase();
    let mut h=vec![banner.clone(),format!("#ifndef {macro_name}\n#define {macro_name}\n"),"/* An __EXCEPT filter: EXCEPTION_EXECUTE_HANDLER catches, CONTINUE_SEARCH passes. */".into(),"typedef LONG (WINAPI *RPC_GUARD_FILTER)(EXCEPTION_POINTERS *);\n".into(),"/* ntdll's trampoline (ntoskrnl/sehtry.c): TRUE when Filter took an exception. */".into(),"unsigned char __cdecl RtlSehTryExcept(void (__cdecl *Body)(void *), void *BodyContext,\n                                      long (__cdecl *Filter)(void *, void *),\n                                      void *FilterContext, long *ExceptionCode);\n".into()];
    h.extend(protos.iter().map(|p| format!("{};", signature(p))));
    h.push(format!("\n#endif /* {macro_name} */\n"));
    let hout = h.join("\n");
    let mut c = vec![banner];
    for inc in std::iter::once("<string.h>".to_owned()).chain(preludes.iter().cloned()) {
        c.push(if inc.starts_with('<') {
            format!("#include {inc}")
        } else {
            format!("#include \"{inc}\"")
        })
    }
    c.push(format!("#include \"{header}\""));
    c.push(format!("#include \"{gh}\"\n"));
    c.push("struct rpc_guard_filter { RPC_GUARD_FILTER filter; };\n".into());
    c.push("static long __cdecl rpc_guard_filter(void *context, void *pointers)\n{".into());
    c.push("    RPC_GUARD_FILTER filter = ((struct rpc_guard_filter *)context)->filter;\n".into());
    c.push("    return filter ? filter(pointers) : EXCEPTION_EXECUTE_HANDLER;\n}\n".into());
    for p in protos {
        let mut fields = Vec::new();
        if p.ret != "void" {
            fields.push(format!("{};", decl(&p.ret, "guard_ret")))
        }
        fields.extend(
            p.params
                .iter()
                .map(|x| format!("{};", decl(&x.ty, &x.name))),
        );
        if fields.is_empty() {
            fields.push("int unused;".into())
        }
        let call = format!(
            "{}({})",
            p.name,
            p.params
                .iter()
                .map(|a| format!("a->{}", a.name))
                .collect::<Vec<_>>()
                .join(", ")
        );
        c.push(format!(
            "struct {}_args {{ {} }};\n",
            p.name,
            fields.join(" ")
        ));
        c.push(format!(
            "static void __cdecl {}_body(void *context)\n{{",
            p.name
        ));
        c.push(format!("    struct {}_args *a = context;", p.name));
        c.push(format!(
            "    {}{};\n}}\n",
            if p.ret != "void" {
                "a->guard_ret = "
            } else {
                ""
            },
            call
        ));
        c.push(format!("{}\n{{", signature(p)));
        c.push(format!("    struct {}_args a;", p.name));
        c.push("    struct rpc_guard_filter f = { guard_filter };".into());
        c.push("    long caught = 0;\n".into());
        c.push("    memset(&a, 0, sizeof(a));".into());
        c.extend(
            p.params
                .iter()
                .map(|x| format!("    a.{} = {};", x.name, x.name)),
        );
        c.push(format!(
            "    if (RtlSehTryExcept({}_body, &a, rpc_guard_filter, &f, &caught))",
            p.name
        ));
        c.push("    {\n        if (guard_code) *guard_code = (DWORD)caught;".into());
        c.push("        return FALSE;\n    }".into());
        if p.ret != "void" {
            c.push("    if (guard_ret) *guard_ret = a.guard_ret;".into())
        }
        c.push("    return TRUE;\n}\n".into());
    }
    (hout, c.join("\n"))
}

#[cfg(test)]
mod tests {
    use super::*;
    const HEADER:&str="\nUINT __cdecl remote_GetProperty(\n MSIHANDLE hinst, LPCWSTR property, LPWSTR *value, DWORD *size);\nvoid __cdecl ept_insert(handle_t h, unsigned32 num_ents, ept_entry_t entries[], boolean32 replace, error_status_t *status);\nLANGID __cdecl remote_GetLanguage(MSIHANDLE hinst);\nDWORD __cdecl PNP_GetVersion(void);\n";
    #[test]
    fn client_array_void_and_output_contract() {
        let ps = parse_header(HEADER).unwrap();
        assert_eq!(ps.len(), 4);
        let e = ps.iter().find(|p| p.name == "ept_insert").unwrap();
        assert_eq!(
            (e.params[2].ty.as_str(), e.params[2].name.as_str()),
            ("ept_entry_t *", "entries")
        );
        let (h, c) = render(&ps, "x_c.h", &["<string.h>".into()], "x_guard.h");
        assert!(h.contains("BOOL ept_insert_guarded(RPC_GUARD_FILTER guard_filter, DWORD *guard_code, handle_t h, unsigned32 num_ents, ept_entry_t *entries, boolean32 replace, error_status_t *status);"));
        assert!(c.contains("    ept_insert(a->h, a->num_ents, a->entries, a->replace, a->status);"));
        assert!(c.contains("struct PNP_GetVersion_args { DWORD guard_ret; };"));
        assert!(h.contains("#include") == false);
        assert!(c.contains("#include \"x_c.h\""));
    }
    #[test]
    fn refuses_no_prototypes_and_function_pointer_params() {
        assert!(parse_header("int foo(void);").is_err());
        assert!(parse_header("void __cdecl f(void (*cb)(int));").is_err());
    }
}
