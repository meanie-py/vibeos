//! Rust port of `tools/gen_global_barrier.py`.

use regex::Regex;
use std::collections::HashSet;
use std::fs;
use std::path::Path;

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Global {
    pub name: String,
    pub typ: String,
    pub file: String,
}

const ARCH_MODULES: &[(&str, Option<&str>)] = &[
    ("amd64", Some("#[cfg(target_arch = \"x86_64\")]")),
    ("arm64", Some("#[cfg(target_arch = \"aarch64\")]")),
    ("arm", Some("#[cfg(target_arch = \"aarch64\")]")),
    ("i386", Some("#[cfg(target_arch = \"x86\")]")),
    ("kd64", None),
];
const SKIP_MODULES: &[&str] = &["kd64"];
const SKIP_GLOBALS: &[&str] = &[
    "MiHighestUserPpe",
    "MiHighestUserPxe",
    "ADMIN_DEVICE_NAME",
    "ADMIN_DOS_DEVICE_NAME",
    "GUID_OBJECT_NAME",
    "PREFIX",
    "KEY_PRODUCT",
    "LANMAN_PRODUCT",
    "SERVER_PRODUCT",
    "VALUE_NT_PRODUCT",
    "WORKSTATION_PRODUCT",
    "SERVICE_DEVICE_NAME",
    "SERVICE_DOS_DEVICE_NAME",
    "ExpCritSecOutOfMemoryEvent",
    "ObpDosDevicesShortNamePrefix",
    "ObpDosDevicesShortNameRoot",
    "RotBarSelection",
    "PltRotBarStatus",
    "InbvProgressState",
    "InbvProgressIndicator",
];

fn excluded_path(file: &str) -> bool {
    file.contains(".bak") || file.contains("old_translations")
}

pub fn find_globals(src_dir: &Path) -> Result<Vec<Global>, String> {
    let pattern = Regex::new(r"pub\s+static\s+mut\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*([^=;]+?)\s*=")
        .map_err(|e| format!("compile global pattern: {e}"))?;
    let mut files = crate::source_walk::files(src_dir)?;
    files.retain(|p| p.extension().is_some_and(|e| e == "rs"));
    files.sort();
    let mut globals = Vec::new();
    let mut seen = HashSet::new();
    for path in files {
        let rel = path
            .strip_prefix(src_dir)
            .map_err(|e| format!("{} is not under {}: {e}", path.display(), src_dir.display()))?;
        let file = rel.to_string_lossy().replace('\\', "/");
        if excluded_path(&file) || path.file_name().is_some_and(|n| n == "global_barrier.rs") {
            continue;
        }
        let source =
            fs::read_to_string(&path).map_err(|e| format!("read {}: {e}", path.display()))?;
        for caps in pattern.captures_iter(&source) {
            let name = caps[1].to_owned();
            if SKIP_GLOBALS.contains(&name.as_str()) || !seen.insert(name.clone()) {
                continue;
            }
            globals.push(Global {
                name,
                typ: caps[2].trim().to_owned(),
                file: file.clone(),
            });
        }
    }
    Ok(globals)
}

fn module_path(file: &str) -> String {
    format!("{}::", file.replace(".rs", "").replace('/', "::"))
}

fn cfg_for_file(file: &str) -> Option<&'static str> {
    for part in file.split('/') {
        if SKIP_MODULES.contains(&part) {
            return Some("SKIP");
        }
        if let Some((_, cfg)) = ARCH_MODULES.iter().find(|(module, _)| *module == part) {
            return *cfg;
        }
    }
    None
}

pub fn render(globals: &[Global]) -> String {
    let mut lines = vec![
        "//! Auto-generated write barrier for all pub static mut globals.".to_owned(),
        "//!".into(),
        "//! This function is NEVER CALLED — its purpose is to prevent LLVM from".into(),
        "//! constant-folding globals that are initialized to 0 but written from C.".into(),
        "//! With codegen-units=1, LLVM can see the entire Rust crate and may prove".into(),
        "//! a global is \"never written\" (because writes happen in C code LLVM cannot".into(),
        "//! see). This function provides a visible write site that LLVM cannot".into(),
        "//! eliminate (the function is #[no_mangle], so it could be called externally).".into(),
        "//!".into(),
        "//! Generated by: python3 tools/gen_global_barrier.py".into(),
        format!("//! Globals covered: {}", globals.len()),
        "//!".into(),
        "//! DO NOT EDIT — regenerate with the command above.".into(),
        "".into(),
        "#[allow(unused_unsafe)]".into(),
        "#[allow(dead_code)]".into(),
        "".into(),
        "/// Write barrier — touches every pub static mut global.".into(),
        "/// NEVER CALLED. Exists solely to prevent LLVM constant-folding.".into(),
        "#[no_mangle]".into(),
        "#[inline(never)]".into(),
        "pub unsafe extern \"C\" fn _global_write_barrier(seed: usize) {".into(),
        "    // The seed parameter is opaque to LLVM — it cannot prove what".into(),
        "    // value is written, so it cannot constant-fold any global.".into(),
        "    let s = seed as u8;".into(),
    ];
    let (mut current_file, mut current_cfg): (Option<&str>, Option<&str>) = (None, None);
    for global in globals {
        let cfg = cfg_for_file(&global.file);
        if cfg == Some("SKIP") {
            continue;
        }
        if Some(global.file.as_str()) != current_file {
            if current_cfg.is_some() && current_cfg != cfg {
                lines.push("    }".into());
                current_cfg = None;
            }
            current_file = Some(&global.file);
            lines.push(format!("    // {}", global.file));
            if cfg.is_some() && cfg != current_cfg {
                lines.push(format!("    {}", cfg.unwrap()));
                lines.push("    {".into());
                current_cfg = cfg;
            } else if cfg.is_none() && current_cfg.is_some() {
                current_cfg = None;
            }
        }
        let indent = if current_cfg.is_some() {
            "        "
        } else {
            "    "
        };
        let path = format!("crate::{}{}", module_path(&global.file), global.name);
        lines.push(format!(
            "{indent}let p = core::ptr::addr_of_mut!({path}) as *mut u8;"
        ));
        lines.push(format!(
            "{indent}core::ptr::write_volatile(p, core::ptr::read_volatile(p) ^ s);"
        ));
    }
    if current_cfg.is_some() {
        lines.push("    }".into());
    }
    lines.push("}".into());
    lines.push(String::new());
    lines.join("\n")
}

pub fn generate(root: &Path) -> Result<String, String> {
    let src_dir = root.join("sdk/lib/rust/ntoskrnl-rust/src");
    if !src_dir.is_dir() {
        return Err(format!(
            "{} not found. Run from vibeos/ root.",
            src_dir.display()
        ));
    }
    find_globals(&src_dir).map(|globals| render(&globals))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;
    use std::time::{SystemTime, UNIX_EPOCH};

    struct Temp(PathBuf);
    impl Temp {
        fn new() -> Self {
            let n = SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .unwrap()
                .as_nanos();
            let path =
                std::env::temp_dir().join(format!("barrier-codegen-{}-{n}", std::process::id()));
            fs::create_dir_all(&path).unwrap();
            Self(path)
        }
        fn put(&self, file: &str, text: &str) {
            let path = self.0.join(file);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, text).unwrap();
        }
    }
    impl Drop for Temp {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    #[test]
    fn finds_sorted_deduped_globals_and_honors_skips_and_pruning() {
        let t = Temp::new();
        t.put(
            "b.rs",
            "pub static mut Z: u32 = 0; pub static mut Dup: u8 = 0;",
        );
        t.put("a.rs", "pub static mut A: *mut c_void = 0; pub static mut Dup: u16 = 0; pub static mut PREFIX: u8 = 0;");
        t.put("kd64/data.rs", "pub static mut KeptCount: u32 = 0;");
        t.put("old_translations/old.rs", "pub static mut Old: u32 = 0;");
        t.put("old_translations_copy.rs", "pub static mut Copy: u32 = 0;");
        t.put("x.bak.rs", "pub static mut Backup: u32 = 0;");
        t.put("build-test/generated.rs", "pub static mut Built: u32 = 0;");
        let got = find_globals(&t.0).unwrap();
        assert_eq!(
            got.iter().map(|g| g.name.as_str()).collect::<Vec<_>>(),
            ["A", "Dup", "Z", "KeptCount"]
        );
        assert_eq!(got[1].typ, "u16");
        let rendered = render(&got);
        assert!(rendered.contains("Globals covered: 4")); // kd64 remains in the legacy count.
        assert!(!rendered.contains("KeptCount"));
    }

    #[test]
    fn render_preserves_architecture_blocks_and_module_paths() {
        let gs = [
            Global {
                name: "A".into(),
                typ: "u32".into(),
                file: "plain/one.rs".into(),
            },
            Global {
                name: "B".into(),
                typ: "u32".into(),
                file: "amd64/two.rs".into(),
            },
            Global {
                name: "C".into(),
                typ: "u32".into(),
                file: "amd64/three.rs".into(),
            },
            Global {
                name: "D".into(),
                typ: "u32".into(),
                file: "arm/four.rs".into(),
            },
            Global {
                name: "E".into(),
                typ: "u32".into(),
                file: "i386/five.rs".into(),
            },
        ];
        let out = render(&gs);
        assert!(out.contains("crate::plain::one::A"));
        assert!(out.contains("#[cfg(target_arch = \"x86_64\")]\n    {\n        let p = core::ptr::addr_of_mut!(crate::amd64::two::B)"));
        assert!(out.contains("#[cfg(target_arch = \"aarch64\")]"));
        assert!(out.contains("#[cfg(target_arch = \"x86\")]"));
    }
}
