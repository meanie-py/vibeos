mod generic;
mod signature;
use std::path::{Path, PathBuf};
use toml::Value;
const AUTOGEN: &str = "// @generated by tools/gen_cnt.py from cnt-manifest.toml — DO NOT EDIT\n";
const HEADER:&str="#![allow(non_snake_case)]  // shims mirror C param names verbatim\n// One module per shim — keeps each #[no_mangle] export in its own\n// codegen unit / object (per-function archive granularity). See\n// tools/gen_cnt.py main() for why (lld 'X was replaced' otherwise).\n\n";
const HELPER_USE:&str="    #[allow(unused_imports)]\n    use super::super::{cstr_slice, cstr_slice_bounded, raw_fill, raw_move, raw_mut_slice, raw_slice, wcstr_slice, wcstr_slice_bounded, wraw_mut_slice};\n";
const PATHS: [&str; 3] = [
    "sdk/lib/rust/cnt-rust/src/cabi/generated.rs",
    "sdk/lib/rust/cnt-rust/src/cabi/mod.rs",
    "sdk/lib/rust/cnt-difftest/symbols.json",
];
fn field<'a>(v: &'a Value, k: &str) -> Result<&'a str, String> {
    v.get(k)
        .and_then(Value::as_str)
        .ok_or_else(|| format!("missing or invalid {k}"))
}
fn quote(s: &str) -> String {
    let raw = serde_json::to_string(s).expect("serializing string");
    let mut out = String::new();
    for c in raw.chars() {
        if (c as u32) >= 0x7f {
            for u in c.encode_utf16(&mut [0; 2]).iter() {
                out.push_str(&format!("\\u{u:04x}"));
            }
        } else {
            out.push(c);
        }
    }
    out
}
fn json(v: &Value, level: usize) -> Result<String, String> {
    match v {
        Value::String(s) => Ok(quote(s)),
        Value::Integer(i) => Ok(i.to_string()),
        Value::Boolean(b) => Ok(b.to_string()),
        Value::Array(a) => {
            if a.is_empty() {
                return Ok("[]".into());
            }
            let indent = "  ".repeat(level + 1);
            let end = "  ".repeat(level);
            let vals = a
                .iter()
                .map(|v| Ok(format!("{indent}{}", json(v, level + 1)?)))
                .collect::<Result<Vec<_>, String>>()?;
            Ok(format!("[\n{}\n{end}]", vals.join(",\n")))
        }
        Value::Table(t) => {
            if t.is_empty() {
                return Ok("{}".into());
            }
            let indent = "  ".repeat(level + 1);
            let end = "  ".repeat(level);
            let vals = t
                .iter()
                .map(|(k, v)| Ok(format!("{indent}{}: {}", quote(k), json(v, level + 1)?)))
                .collect::<Result<Vec<_>, String>>()?;
            Ok(format!("{{\n{}\n{end}}}", vals.join(",\n")))
        }
        _ => Err("unsupported fuzz_domain value".into()),
    }
}
fn shim(name: &str, m: &Value) -> Result<String, String> {
    let sp = field(m, "slice_pattern")?;
    let sig = field(m, "c_signature")?;
    let rt = signature::ret_ty(sig)?;
    if sp == "sort" {
        let misf = m
            .get("preserved_misfeature")
            .and_then(Value::as_str)
            .unwrap_or("");
        return Ok(format!("/// `{sig}`\n/// preserved misfeature: {misf}\n#[no_mangle]\npub unsafe extern \"C\" fn {name}(base: *mut core::ffi::c_void, num: usize, width: usize, cmp: super::CntCmpFn) -> {rt} {{\n    super::qsort_rs(base as *mut u8, num, width, cmp);\n}}\n"));
    }
    let params = signature::parse_params(sig)?;
    // `fast_path`: the export calls a hand-written body in cabi/memops.rs with its own
    // arguments. `core_fn` stays the contract (cnt-difftest grades the export against the C);
    // this is for hot rows whose slice form costs ~10x the C under no LLVM passes.
    if let Some(fast) = m.get("fast_path").and_then(Value::as_str) {
        let misf = m
            .get("preserved_misfeature")
            .and_then(Value::as_str)
            .unwrap_or("");
        let decl = params
            .iter()
            .map(|(t, n)| Ok(format!("{n}: {}", signature::rs_ty(t)?)))
            .collect::<Result<Vec<_>, String>>()?
            .join(", ");
        let args = params
            .iter()
            .map(|(_, n)| n.as_str())
            .collect::<Vec<_>>()
            .join(", ");
        return Ok(format!("/// `{sig}`\n/// preserved misfeature: {misf}\n/// body: memops.rs `{fast}`, the `core_fn` contract as an asm scan\n#[no_mangle]\npub unsafe extern \"C\" fn {name}({decl}) -> {rt} {{\n    super::{fast}({args})\n}}\n"));
    }
    match families::render(name, m, &params, rt)? {
        Some(s) => Ok(s),
        None => generic::render(name, m, &params, rt),
    }
}
pub fn render(manifest: &str) -> Result<Vec<(String, String)>, String> {
    let root: Value = manifest.parse::<Value>().map_err(|e| e.to_string())?;
    let syms = root
        .get("symbols")
        .and_then(Value::as_table)
        .ok_or("missing symbols table")?;
    let mut generated = vec![AUTOGEN.to_owned(), HEADER.to_owned()];
    let mut spec = Vec::new();
    for (name, m) in syms {
        let body = shim(name, m)?.replace("super::", "super::super::");
        let indented = body
            .split('\n')
            .map(|line| {
                if line.trim().is_empty() {
                    line.to_owned()
                } else {
                    format!("    {line}")
                }
            })
            .collect::<Vec<_>>()
            .join("\n");
        generated.push(format!(
            "mod m{name} {{\n{HELPER_USE}\n{indented}\n}}\npub use m{name}::*;\n"
        ));
        let mut fields = Vec::new();
        for key in [
            "c_signature",
            "family",
            "slice_pattern",
            "return_collapse",
            "reference",
            "fuzz_domain",
        ] {
            let value = m.get(key).ok_or_else(|| format!("{name}: missing {key}"))?;
            fields.push(format!("    {}: {}", quote(key), json(value, 2)?));
        }
        spec.push(format!(
            "  {}: {{\n{}\n  }}",
            quote(name),
            fields.join(",\n")
        ));
    }
    let spec = if spec.is_empty() {
        "{}\n".to_owned()
    } else {
        format!("{{\n{}\n}}\n", spec.join(",\n"))
    };
    let mod_rs = format!(
        "{AUTOGEN}#![cfg_attr(not(feature = \"cabi\"), allow(dead_code))]\n{}{}",
        include_str!("helpers.txt"),
        include_str!("mod_tail.txt")
    );
    Ok(vec![
        (PATHS[0].into(), generated.join("\n")),
        (PATHS[1].into(), mod_rs),
        (PATHS[2].into(), spec),
    ])
}
pub fn generate(root: &Path) -> Result<Vec<(PathBuf, String)>, String> {
    let path = root.join("sdk/lib/rust/cnt-rust/cnt-manifest.toml");
    let manifest =
        std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    Ok(render(&manifest)?
        .into_iter()
        .map(|(p, s)| (root.join(p), s))
        .collect())
}

#[cfg(test)]
mod tests {
    use super::*;
    fn fixture(pattern: &str, signature: &str, collapse: &str, core: &str) -> String {
        format!("[symbols.custom]\nc_signature = {signature:?}\nfamily = \"test\"\nslice_pattern = {pattern:?}\nreturn_collapse = {collapse:?}\ncore_fn = {core:?}\nreference = \"test.c\"\nfuzz_domain = [\"±\"]\n")
    }
    #[test]
    fn custom_symbol_uses_its_parameters_and_python_json_escaping() {
        let outputs = render(&fixture(
            "strcpy_like",
            "char *custom(char *destination, const char *source)",
            "ret_dst",
            "string::cpy",
        ))
        .unwrap();
        assert!(outputs[0].1.contains(
            "pub unsafe extern \"C\" fn custom(destination: *mut u8, source: *const u8)"
        ));
        assert!(outputs[0].1.contains("let s = cstr_slice(source);"));
        assert!(outputs[0]
            .1
            .contains("let d = raw_mut_slice(destination, m + 1);"));
        assert!(outputs[2].1.contains("\\u00b1"));
    }
    #[test]
    fn generic_bounded_compare_uses_manifest_names() {
        let outputs = render(&fixture(
            "nul_in_n",
            "int custom(const char *left, const char *right, size_t limit)",
            "i32_cmp_n",
            "string::ncmp",
        ))
        .unwrap();
        assert!(outputs[0]
            .1
            .contains("let left_s = cstr_slice_bounded(left, limit);"));
        assert!(outputs[0]
            .1
            .contains("crate::core_rs::string::ncmp(left_s, right_s, limit)"));
    }
    #[test]
    fn unsupported_patterns_and_types_fail() {
        assert!(render(&fixture(
            "unknown",
            "int custom(const char *s)",
            "usize",
            "string::len_of"
        ))
        .is_err());
        assert!(render(&fixture(
            "nul_in",
            "int custom(float s)",
            "usize",
            "string::len_of"
        ))
        .is_err());
        assert!(render(&fixture(
            "nul_in",
            "int custom(const char *s)",
            "unknown",
            "string::len_of"
        ))
        .is_err());
    }
}
