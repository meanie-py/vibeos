pub fn rc_parts(cmd: &str) -> Result<RcParts> {
    let t = tokens(cmd)?;
    if t.len() < 7 || t[1..4] != ["-O", "coff", "--codepage=65001"] {
        return Err(fail(format!("not cmake's windres rule: {}", short(&t, 5))));
    }
    let (mut i, mut includes) = (4, Vec::new());
    while t.get(i).is_some_and(|s| s == "-I") {
        includes.push(
            t.get(i + 1)
                .ok_or_else(|| fail("windres -I missing value"))?
                .clone(),
        );
        i += 2;
    }
    if includes
        .last()
        .is_none_or(|s| !s.ends_with("/sdk/include/crt"))
    {
        return Err(fail(format!(
            "windres command without CMAKE_RC_FLAGS' -I crt: {}",
            t[t.len() - 2]
        )));
    }
    let k = (i..t.len())
        .find(|&j| t[j] == "-DRC_INVOKED")
        .ok_or_else(|| fail("windres missing -DRC_INVOKED"))?;
    let mut flags = vec!["-I".into(), includes.pop().unwrap()];
    flags.extend_from_slice(&t[i..k]);
    let mut j = k + 3;
    if j > t.len() - 2 {
        return Err(fail("windres missing RC defines or source"));
    }
    while j < t.len() - 2 && t[j].starts_with("-DLANGUAGE_") {
        j += 1
    }
    let defines = t[j..t.len() - 2].to_vec();
    if !sorted(&defines) {
        return Err(fail(format!(
            "{}: <DEFINES> not sorted, the rule this models",
            t[t.len() - 2]
        )));
    }
    Ok(RcParts {
        windres: t[0].clone(),
        includes,
        flags,
        defs: t[k..j].to_vec(),
        defines,
        src: t[t.len() - 2].clone(),
    })
}
pub fn rc_enc(path: &str, arch: &str) -> Result<String> {
    let b = format!("{CANON}/build-{arch}");
    if path == b || path.starts_with(&(b.clone() + "/")) {
        Ok(format!("@build{}", &path[b.len()..]))
    } else if let Some(p) = path.strip_prefix("/tmp/vibeos/") {
        Ok(p.into())
    } else {
        Err(fail(format!("windres include outside the tree: {path}")))
    }
}
pub fn rc_dec(tok: &str, arch: &str) -> String {
    if tok == "@build" || tok.starts_with("@build/") {
        format!("{CANON}/build-{arch}{}", &tok[6..])
    } else {
        format!("{CANON}/{tok}")
    }
}
pub fn flag_enc(tok: &str, arch: &str) -> String {
    tok.replace(&format!("{CANON}/build-{arch}"), "{BUILD}")
        .replace(CANON, "{REPO}")
}
pub fn flag_dec(tok: &str, arch: &str) -> String {
    tok.replace("{BUILD}", &format!("{CANON}/build-{arch}"))
        .replace("{REPO}", CANON)
}
impl RcTemplate {
    pub fn text(&self, arch: &str) -> String {
        let mut out=vec![format!("# cmake's windres rule, the part every module shares ({arch}). Generated by"),"# python3 tools/cargo_cell_gen.py --rc-template from build-<arch>/compile_commands.json;".into(),"# reactos-link's Linker::rc adds the module's own includes, flags and defines.".into()];
        for (name, toks) in [
            ("windres", vec![self.windres.clone()]),
            ("std", self.std.clone()),
            ("flags", self.flags.clone()),
            ("defs", self.defs.clone()),
            ("defines", self.defines.clone()),
        ] {
            out.push(format!("[{name}]"));
            out.extend(toks)
        }
        out.join("\n") + "\n"
    }
}
impl CTemplate {
    pub fn text(&self, arch: &str) -> String {
        self.text_for(arch, "C")
    }
    pub fn text_for(&self, arch: &str, rule: &str) -> String {
        let mut out=vec![format!("# cmake's {rule} rule, the part every {rule} compile in the tree shares ({arch}). Generated"),"# by python3 tools/cargo_cell_gen.py --c-template from build-<arch>/compile_commands.json;".into(),"# reactos-link's Linker::c_compiled adds the library's own includes, flags and defines.".into()];
        for (name, toks) in [
            ("cc", vec![self.cc.clone()]),
            ("target", vec![self.target.clone()]),
            ("std", self.std.clone()),
            ("core", self.core.clone()),
            ("defines", self.defines.clone()),
        ] {
            out.push(format!("[{name}]"));
            out.extend(toks)
        }
        out.join("\n") + "\n"
    }
}
pub fn with_marker(seq: &[String], run: &[String], marker: &str) -> Option<Vec<String>> {
    if run.len() > seq.len() {
        return None;
    }
    for i in 0..=seq.len() - run.len() {
        if seq[i..i + run.len()] == *run {
            let mut out = seq[..i].to_vec();
            out.push(marker.into());
            out.extend_from_slice(&seq[i + run.len()..]);
            return Some(out);
        }
    }
    None
}
