const CANON: &str = "/tmp/vibeos";
fn tokens(cmd: &str) -> Result<Vec<String>> {
    shlex::split(cmd).ok_or_else(|| Error::new("invalid shell quoting in compile command"))
}
fn fail(s: impl Into<String>) -> Error {
    Error::new(s)
}
fn short(t: &[String], n: usize) -> String {
    t.iter().take(n).cloned().collect::<Vec<_>>().join(" ")
}
fn sorted(v: &[String]) -> bool {
    v.windows(2).all(|p| p[0] <= p[1])
}
fn remove_common(
    whole: &[String],
    common: &[String],
    src: &str,
    what: &str,
) -> Result<Vec<String>> {
    let mut left = whole.to_vec();
    for d in common {
        let Some(i) = left.iter().position(|x| x == d) else {
            return Err(fail(format!("{src}: lacks the global {what}{d}")));
        };
        left.remove(i);
    }
    Ok(left)
}
fn expand(s: &str) -> String {
    s.replace("{REPO}", CANON)
}
