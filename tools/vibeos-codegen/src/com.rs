//! Text-oriented port of tools/gen_commacros.py.
use regex::Regex;
use std::collections::BTreeSet;

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Method {
    pub name: String,
    pub args: Vec<(String, String)>,
    pub ret: Option<String>,
}
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Interface {
    pub name: String,
    pub methods: Vec<Method>,
}

fn arrow_gt(s: &str, i: usize) -> bool {
    i > 0 && s.as_bytes()[i] == b'>' && s.as_bytes()[i - 1] == b'-'
}
fn matching(s: &str, start: usize) -> Result<usize, String> {
    let b = s.as_bytes();
    let open = *b.get(start).ok_or("delimiter index out of range")?;
    let close = match open {
        b'(' => b')',
        b'<' => b'>',
        b'{' => b'}',
        b'[' => b']',
        _ => return Err(format!("not an opener at {start}")),
    };
    let mut depth = 0i32;
    let mut i = start;
    while i < b.len() {
        if b[i] == b'>' && arrow_gt(s, i) {
            i += 1;
            continue;
        }
        if b[i] == open {
            depth += 1;
        } else if b[i] == close {
            depth -= 1;
            if depth == 0 {
                return Ok(i);
            }
        }
        i += 1;
    }
    Err(format!("unbalanced '{}' at {start}", open as char))
}
fn split_top(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut d = 0i32;
    let mut start = 0;
    for (i, c) in s.char_indices() {
        if "(<[{".contains(c) {
            d += 1;
        } else if ")>]}".contains(c) && !(c == '>' && arrow_gt(s, i)) {
            d -= 1;
        }
        if c == ',' && d == 0 {
            let x = s[start..i].trim();
            if !x.is_empty() {
                out.push(x.to_owned())
            }
            start = i + 1;
        }
    }
    let x = s[start..].trim();
    if !x.is_empty() {
        out.push(x.to_owned())
    }
    out
}

pub fn parse_vtbls(src: &str) -> Result<Vec<Interface>, String> {
    let vr = Regex::new(r"pub struct (I[A-Za-z0-9_]*)Vtbl\s*\{").unwrap();
    let fr =
        Regex::new(r"pub\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*::core::option::Option\s*<").unwrap();
    let mut out = Vec::new();
    for vm in vr.captures_iter(src) {
        let whole = vm.get(0).unwrap();
        let iface = vm[1].to_owned();
        let op = src[whole.start()..whole.end()].rfind('{').unwrap() + whole.start();
        let end = matching(src, op)?;
        let body = &src[op + 1..end];
        let mut methods = Vec::new();
        for fm in fr.captures_iter(body) {
            let name = fm[1].to_owned();
            let pos = fm.get(0).unwrap().end();
            let rel = pos - 1;
            let pe = matching(body, rel)?;
            let payload = &body[rel + 1..pe];
            let Some(fi) = payload.find("fn") else {
                continue;
            };
            let po = payload[fi..]
                .find('(')
                .ok_or("function pointer missing arguments")?
                + fi;
            let pc = matching(payload, po)?;
            let tail = payload[pc + 1..].trim();
            let ret = tail
                .strip_prefix("->")
                .map(|x| x.trim().trim_end_matches(',').trim().to_owned());
            let mut args = Vec::new();
            for a in split_top(&payload[po + 1..pc]) {
                if let Some((n, t)) = a.split_once(':') {
                    args.push((n.trim().to_owned(), t.trim().to_owned()));
                }
            }
            if args.is_empty() {
                continue;
            }
            methods.push(Method {
                name,
                args: args.into_iter().skip(1).collect(),
                ret,
            });
        }
        if !methods.is_empty() {
            out.push(Interface {
                name: iface,
                methods,
            });
        }
    }
    Ok(out)
}
pub fn render(interfaces: &[Interface], only: Option<&str>) -> Result<String, String> {
    if interfaces.is_empty() {
        return Err("no I*Vtbl structs parsed — did the bindgen format change?".into());
    }
    let wanted: Option<BTreeSet<String>> = only.map(|s| {
        s.split(',')
            .map(str::trim)
            .filter(|x| !x.is_empty())
            .map(str::to_owned)
            .collect()
    });
    if let Some(w) = &wanted {
        let have: BTreeSet<_> = interfaces.iter().map(|x| x.name.clone()).collect();
        let missing: Vec<_> = w.difference(&have).cloned().collect();
        if !missing.is_empty() {
            return Err(format!("interfaces not in bindgen: {:?}", missing));
        }
    }
    let mut lines = vec![
        "//! GENERATED by tools/gen_commacros.py from com-sys bindgen — do not hand-edit.",
        "//! COBJMACROS-shaped call helpers (`IFoo_Method(p, ...)`), the role the C macros",
        "//! from the COBJMACROS headers played for the wine sources. Bodies call straight",
        "//! through the vtbl slot; the fn-pointer type carries the per-arch calling",
        "//! convention (com-sys bindgen: stdcall on i386, C on amd64/arm64), so this file",
        "//! is ABI-correct on all three targets without a single cfg.",
        "//! `unwrap_unchecked` on the Option<fn> keeps C semantics exactly (a NULL slot",
        "//! faults at the call, same as C).",
        "#![allow(clippy::all)]",
        "use crate::prelude::*;",
        "",
    ]
    .into_iter()
    .map(str::to_owned)
    .collect::<Vec<_>>();
    let mut sorted = interfaces.to_vec();
    sorted.sort_by(|a, b| a.name.cmp(&b.name));
    let mut nfn = 0;
    let mut nalias = 0;
    let mut nif = 0;
    for it in sorted {
        if wanted.as_ref().is_some_and(|w| !w.contains(&it.name)) {
            continue;
        }
        nif += 1;
        lines.push(format!("// ---- {} ----", it.name));
        let names: BTreeSet<_> = it.methods.iter().map(|m| m.name.clone()).collect();
        for m in &it.methods {
            nfn += 1;
            emit(
                &mut lines,
                &it.name,
                &m.name,
                &m.name,
                &m.args,
                m.ret.as_deref(),
            );
            if matches!(m.name.chars().last(), Some('A' | 'W')) && m.name.len() > 1 {
                let base = &m.name[..m.name.len() - 1];
                let sibling = format!("{}{}", base, if m.name.ends_with('A') { 'W' } else { 'A' });
                if !names.contains(base) && !names.contains(&sibling) {
                    nalias += 1;
                    lines.push("// alias: C call sites use the unsuffixed COBJMACRO name".into());
                    emit(
                        &mut lines,
                        &it.name,
                        base,
                        &m.name,
                        &m.args,
                        m.ret.as_deref(),
                    );
                }
            }
        }
        lines.push(String::new());
    }
    while lines.last().is_some_and(String::is_empty) {
        lines.pop();
    }
    let mut result = lines.join("\n");
    result.push('\n');
    let _ = (nfn, nalias, nif);
    Ok(result)
}
fn emit(
    l: &mut Vec<String>,
    iface: &str,
    name: &str,
    slot: &str,
    args: &[(String, String)],
    ret: Option<&str>,
) {
    let more = args
        .iter()
        .map(|(a, t)| format!("{a}: {t}"))
        .collect::<Vec<_>>()
        .join(", ");
    let params = format!(
        "This: *mut {iface}{}",
        if more.is_empty() {
            String::new()
        } else {
            format!(", {more}")
        }
    );
    let call = std::iter::once("This".to_owned())
        .chain(args.iter().map(|x| x.0.clone()))
        .collect::<Vec<_>>()
        .join(", ");
    l.push("#[inline]".into());
    l.push(format!(
        "pub unsafe fn {iface}_{name}({params}){} {{",
        ret.map(|x| format!(" -> {x}")).unwrap_or_default()
    ));
    l.push(format!(
        "    ((*(*This).lpVtbl).{slot}.unwrap_unchecked())({call})"
    ));
    l.push("}".into());
}
pub fn generate(src: &str, only: Option<&str>) -> Result<String, String> {
    render(&parse_vtbls(src)?, only)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn nested_callback_arrow_and_alias() {
        let s = r#"pub struct IFooVtbl { pub Draw: ::core::option::Option<unsafe extern "C" fn(This: *mut IFoo, cb: Option<unsafe extern "C" fn(i32) -> HRESULT>, x: i32) -> HRESULT>, }"#;
        let x = generate(s, None).unwrap();
        assert!(x.contains("cb: Option<unsafe extern \"C\" fn(i32) -> HRESULT>"));
        assert!(x.contains(") -> HRESULT {"));
    }
    #[test]
    fn refuses_missing_filter() {
        let s="pub struct IFooVtbl { pub X: ::core::option::Option<unsafe extern \"C\" fn(This: *mut IFoo)> }";
        assert!(generate(s, Some("INope"))
            .unwrap_err()
            .contains("not in bindgen"));
    }
}
