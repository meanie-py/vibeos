//! Stage-1 Rust output: the same thunk table `emit_c` writes, as a committed module of
//! `wow64-rust`. The C table was a build-time `#include`; the Rust one is checked in
//! (`sdk/lib/rust/wow64-rust/src/wow64/gen/`) so a plain `cargo check` of the crate
//! sees it, and the build fails loud on drift instead of regenerating it silently.
use super::{arg_kind, Syscall};

/// The committed outputs, keyed by the `AUDIT_TABLES` row that supplies their inputs.
pub const RUST_TABLES: &[(&str, &str, &str)] = &[
    (
        "ntdll",
        "Wow64Thunk",
        "sdk/lib/rust/wow64-rust/src/wow64/gen/wow64_thunks.rs",
    ),
    (
        "win32k",
        "Wow64Win32kThunk",
        "sdk/lib/rust/wow64-rust/src/wow64/gen/wow64_win32k_thunks.rs",
    ),
];

/// The Rust spelling of one `.spec` token: (parameter type, widening helper).
fn rust_kind(token: &str) -> Option<(&'static str, &'static str)> {
    Some(match token {
        "long" => ("usize", "long"),
        "s_long" => ("isize", "s_long"),
        "word" => ("usize", "word"),
        "ptr" | "str" | "wstr" => ("*mut c_void", "ptr"),
        "int64" => ("u64", "int64"),
        "double" => ("f64", "double"),
        _ => return None,
    })
}

/// Emit the Rust table. `table` names the `AUDIT_TABLES` row; the text carries no paths,
/// so it is byte-identical whichever checkout (or canonical mount) generated it.
pub fn emit_rs(syscalls: &[Syscall], table: &str, symbol_prefix: &str) -> Result<String, String> {
    let n_manual = syscalls.iter().filter(|s| s.needs_manual()).count();
    let mut b = Vec::new();
    b.push(format!(
        "//! @generated by `tools/codegen wow64-thunks --emit-rs` from the `{table}` table — DO NOT EDIT.\n\
         //! Regenerate: tools/codegen wow64-thunks --emit-rs   (the build runs it with --check)\n\
         //!\n\
         //! Index == REAL service number (the service list's order, which is what guest EAX\n\
         //! carries); the .spec contributes argument types only. Each thunk reads the guest's\n\
         //! 32-bit argument dwords and calls the real 64-bit export. Single-dword arguments are\n\
         //! sign-extended, which keeps guest VAs and negative pseudo-handles (-1, -2) correct.\n\
         //! Entries left `None` need a deep marshaller (`Wow64ManualDispatch`).\n\
         //! Count: {} auto, {n_manual} manual. Identical for amd64 and arm64 (the generator\n\
         //! refuses to write it otherwise).\n",
        syscalls.len() - n_manual
    ));
    b.push(
        "// The exports are declared with the table's generic argument types, as the C did in\n\
         // its own translation unit, so they may differ from a typed declaration elsewhere.\n\
         #![allow(clashing_extern_declarations)]\n\
         \n\
         use core::ffi::{c_char, c_void};\n\
         \n\
         pub type WOW64_THUNK = unsafe extern \"C\" fn(a: *mut u32) -> i32;\n\
         \n\
         #[repr(C)]\n\
         pub struct WOW64_THUNK_ENTRY {\n    \
             /// Export name, for the manual dispatcher and the trace.\n    \
             pub Name: *const c_char,\n    \
             /// The marshaller, or `None` for a syscall that needs a hand-written one.\n    \
             pub Thunk: Option<WOW64_THUNK>,\n    \
             /// Guest argument dwords consumed.\n    \
             pub Slots: u8,\n\
         }\n\
         // SAFETY: an immutable table of 'static C strings and function pointers.\n\
         unsafe impl Sync for WOW64_THUNK_ENTRY {}\n\
         \n\
         // One widening per .spec token.\n\
         #[inline(always)]\n\
         unsafe fn long(a: *mut u32, s: usize) -> usize { *a.add(s) as i32 as isize as usize }\n\
         #[inline(always)]\n\
         unsafe fn s_long(a: *mut u32, s: usize) -> isize { *a.add(s) as i32 as isize }\n\
         #[inline(always)]\n\
         unsafe fn word(a: *mut u32, s: usize) -> usize { *a.add(s) as u16 as usize }\n\
         #[inline(always)]\n\
         unsafe fn ptr(a: *mut u32, s: usize) -> *mut c_void { *a.add(s) as i32 as isize as *mut c_void }\n\
         #[inline(always)]\n\
         unsafe fn int64(a: *mut u32, s: usize) -> u64 { *a.add(s) as u64 | (*a.add(s + 1) as u64) << 32 }\n\
         #[inline(always)]\n\
         unsafe fn double(a: *mut u32, s: usize) -> f64 { f64::from_bits(int64(a, s)) }\n"
            .to_owned(),
    );
    for sc in syscalls {
        if sc.needs_manual() {
            b.push(format!(
                "// {}: WOW64_NEEDS_MANUAL — {}. Table entry left None.\n",
                sc.name, sc.manual_reason
            ));
            continue;
        }
        let (mut params, mut args, mut slot) = (Vec::new(), Vec::new(), 0);
        for tok in &sc.args {
            let k = arg_kind(tok)
                .ok_or_else(|| format!("{}: unknown auto argument '{tok}'", sc.name))?;
            let (ty, helper) = rust_kind(tok)
                .ok_or_else(|| format!("{}: manual argument '{tok}' in auto thunk", sc.name))?;
            params.push(format!("_: {ty}"));
            args.push(format!("{helper}(a, {slot})"));
            slot += k.dwords;
        }
        b.push(format!(
            "unsafe extern \"system\" {{\n    fn {n}({p}) -> i32;\n}}\n\
             unsafe extern \"C\" fn wow64_thunk_{n}(a: *mut u32) -> i32 {{\n    {n}({a})\n}}\n",
            n = sc.name,
            p = params.join(", "),
            a = args.join(", ")
        ));
    }
    b.push(format!(
        "pub static {symbol_prefix}Table: [WOW64_THUNK_ENTRY; {}] = [",
        syscalls.len()
    ));
    for sc in syscalls {
        let slots: u8 = sc
            .slots
            .try_into()
            .map_err(|_| format!("{}: {} argument dwords overflow the u8 Slots", sc.name, sc.slots))?;
        if sc.needs_manual() {
            b.push(format!(
                "    WOW64_THUNK_ENTRY {{ Name: c\"{}\".as_ptr(), Thunk: None, Slots: {slots} }}, // [{}] MANUAL: {}",
                sc.name, sc.ordinal, sc.manual_reason
            ));
        } else {
            b.push(format!(
                "    WOW64_THUNK_ENTRY {{ Name: c\"{n}\".as_ptr(), Thunk: Some(wow64_thunk_{n}), Slots: {slots} }}, // [{}]",
                sc.ordinal,
                n = sc.name
            ));
        }
    }
    b.push("];".into());
    b.push(String::new());
    b.push(format!(
        "pub const {symbol_prefix}Count: u32 = {};",
        syscalls.len()
    ));
    b.push(String::new());
    Ok(b.join("\n"))
}
