use regex::Regex;
use std::collections::HashSet;
use std::fmt::Write;

pub fn apisets(source: &str) -> Result<String, String> {
    let mut entries = Vec::new();
    for line in source.lines().map(str::trim) {
        if !line.starts_with('{') || !line.contains("RTL_CONSTANT_STRING") {
            continue;
        }
        let string = |s: &str| -> Result<(String, String), String> {
            let (_, rest) = s.split_once("L\"").ok_or("missing wide string")?;
            let (value, rest) = rest.split_once('"').ok_or("unterminated wide string")?;
            Ok((value.into(), rest.into()))
        };
        let (name, rest) = string(line)?;
        let (target, rest) = string(&rest)?;
        let flags = rest
            .split_once('}')
            .ok_or("missing apiset closing brace")?
            .0;
        let flags = flags.split_once(',').ok_or("missing apiset flags")?.1;
        let mut value = 0u8;
        for token in flags.split('|').map(str::trim) {
            value |= match token {
                "APISET_WIN7" => 1,
                "APISET_WIN8" => 2,
                "APISET_WIN81" => 4,
                "APISET_WIN10" => 8,
                _ => return Err(format!("unknown apiset flag token: {token:?}")),
            };
        }
        entries.push((name, target, value));
    }
    if entries.is_empty() {
        return Err("no apiset entries parsed".into());
    }
    let mut out =
        "// @generated by tools/gen_apisets_table.py from sdk/lib/apisets/apisets.table.c\n"
            .to_string();
    for (i, (name, target, _)) in entries.iter().enumerate() {
        for (prefix, value) in [("N", name), ("T", target)] {
            let units: Vec<_> = value.encode_utf16().chain(Some(0)).collect();
            let values = units
                .iter()
                .map(|u| format!("0x{u:04x}"))
                .collect::<Vec<_>>()
                .join(", ");
            writeln!(
                out,
                "static {prefix}{i}: [u16; {}] = [{values}];",
                units.len()
            )
            .unwrap();
        }
    }
    writeln!(
        out,
        "\npub(super) static G_APISETS: [RosApiset; {}] = [",
        entries.len()
    )
    .unwrap();
    for (i, (_, _, flags)) in entries.iter().enumerate() {
        writeln!(
            out,
            "    RosApiset {{ name: us(&N{i}), target: us(&T{i}), dw_os_versions: 0x{flags:x} }},"
        )
        .unwrap();
    }
    out.push_str("];\n");
    Ok(out)
}

pub fn ssdt(source: &str) -> Result<String, String> {
    let re = Regex::new(r"^\s*SVC_\(\s*(\w+)\s*,\s*(\d+)\s*\)\s*$").unwrap();
    let mut entries = Vec::new();
    for (i, line) in source.lines().enumerate() {
        let line = line.split("//").next().unwrap().trim_end();
        if line.trim().is_empty() {
            continue;
        }
        let c = re
            .captures(line)
            .ok_or_else(|| format!("sysfuncs.h:{}: unparsed line: {line:?}", i + 1))?;
        let argc: usize = c[2].parse().map_err(|_| "invalid syscall argument count")?;
        // Every supported ABI fits this count in MainSSPT's u8 even at 8 bytes/arg.
        if argc > 31 {
            return Err(format!("{}: argument byte count overflows MainSSPT", &c[1]));
        }
        entries.push((c[1].to_owned(), argc));
    }
    if entries.is_empty() {
        return Err("no syscalls parsed".into());
    }
    let n = entries.len();
    let mut out = include_str!("ssdt_prefix.txt").to_owned();
    out.push_str("extern \"system\" {\n");
    for (name, argc) in &entries {
        let args = vec!["_: usize"; *argc].join(", ");
        writeln!(out, "    pub fn Nt{name}({args});").unwrap();
    }
    out.push_str("}\n\n// `static mut` (not `static`) so consumers can `addr_of_mut!` to match\n// the original C `ULONG_PTR MainSSDT[]` declaration.\n#[no_mangle]\n");
    writeln!(out, "pub static mut MainSSDT: [SSDTEntry; {n}] = [").unwrap();
    for (name, _) in &entries {
        writeln!(out, "    Nt{name} as SSDTEntry,").unwrap();
    }
    out.push_str("];\n\n// `argcount * sizeof(void*)` per entry — pointer size differs per arch\n// so the multiplier is computed at const-eval time.\n#[no_mangle]\n");
    writeln!(out, "pub static mut MainSSPT: [u8; {n}] = [").unwrap();
    for (_, argc) in &entries {
        writeln!(out, "    ({argc} * core::mem::size_of::<usize>()) as u8,").unwrap();
    }
    writeln!(
        out,
        "];\n\n#[no_mangle]\npub static mut MainNumberOfSysCalls: u32 = {n};"
    )
    .unwrap();
    Ok(out)
}

pub fn nls(source: &str, filename: &str) -> Result<String, String> {
    let declarations = Regex::new(
        r"const\s+(unsigned\s+int|WCHAR)\s+(?:DECLSPEC_HIDDEN\s+)?(\w+)\s*\[\s*(\d+)\s*\]\s*=\s*\{",
    )
    .unwrap();
    let comments = Regex::new(r"(?s)/\*.*?\*/").unwrap();
    let mut lines = vec![
        format!("//! Auto-generated from winnls/string/{filename} by tools/gen_nls_data_tables.py — DO NOT EDIT."),
        format!("//! Pure Unicode data tables ({filename} is generated, zero logic). The C consumers"),
        "//! (sortkey.c / k32.h tolowerW/toupperW) link these #[no_mangle] symbols directly.".into(),
        "#![allow(non_upper_case_globals)]".into(), String::new(),
    ];
    let mut count = 0;
    for c in declarations.captures_iter(source) {
        let (ty, width, max) = if &c[1] == "WCHAR" {
            ("u16", 4, u16::MAX as u64)
        } else {
            ("u32", 8, u32::MAX as u64)
        };
        let n: usize = c[3].parse().map_err(|_| "invalid NLS array length")?;
        let begin = c.get(0).unwrap().end();
        let rest = &source[begin..];
        let end = rest.find('}').ok_or("unbalanced NLS braces")?;
        let body = comments.replace_all(&rest[..end], " ");
        let mut values = Vec::new();
        for token in body.split(',').map(str::trim).filter(|s| !s.is_empty()) {
            let value = number(token)?;
            if value > max {
                return Err(format!("{filename}:{}: value out of {ty} range", &c[2]));
            }
            values.push(value);
        }
        if values.len() != n {
            return Err(format!(
                "{filename}:{}: parsed {} values but declaration says [{n}]",
                &c[2],
                values.len()
            ));
        }
        lines.extend([
            "#[no_mangle]".into(),
            "#[used]".into(),
            format!("pub static {}: [{ty}; {n}] = [", &c[2]),
        ]);
        for row in values.chunks(12) {
            let row = row
                .iter()
                .map(|v| format!("0x{v:0width$x}"))
                .collect::<Vec<_>>()
                .join(", ");
            lines.push(format!("    {row},"));
        }
        lines.extend(["];".into(), String::new()]);
        count += 1;
    }
    if count == 0 {
        return Err(format!("no NLS arrays found in {filename}"));
    }
    Ok(lines.join("\n"))
}

fn number(token: &str) -> Result<u64, String> {
    let result = if token.starts_with("0x") || token.starts_with("0X") {
        u64::from_str_radix(&token[2..], 16)
    } else {
        token.parse()
    };
    result.map_err(|_| format!("invalid integer literal: {token:?}"))
}

pub const ERRLIST_BEGIN: &str =
    "// ---- @generated by tools/gen_msvcrt_errlist.py — do not hand-edit ----";
pub const ERRLIST_END: &str = "// ---- end @generated ----";

fn c_bytes(literal: &str) -> Result<Vec<u8>, String> {
    let mut bytes = literal.bytes().peekable();
    let mut out = Vec::new();
    while let Some(b) = bytes.next() {
        if b != b'\\' {
            out.push(b);
            continue;
        }
        let escaped = bytes.next().ok_or("trailing backslash in C literal")?;
        out.push(match escaped {
            b'\\' | b'\'' | b'"' => escaped,
            b'a' => 7,
            b'b' => 8,
            b'f' => 12,
            b'n' => 10,
            b'r' => 13,
            b't' => 9,
            b'v' => 11,
            b'x' => {
                let digits = [
                    bytes.next().ok_or("short hex escape")?,
                    bytes.next().ok_or("short hex escape")?,
                ];
                u8::from_str_radix(
                    std::str::from_utf8(&digits).map_err(|_| "invalid hex escape")?,
                    16,
                )
                .map_err(|_| "invalid hex escape")?
            }
            b'0'..=b'7' => {
                let mut value = (escaped - b'0') as u16;
                for _ in 0..2 {
                    match bytes.peek() {
                        Some(b'0'..=b'7') => {
                            value = value * 8 + (bytes.next().unwrap() - b'0') as u16
                        }
                        _ => break,
                    }
                }
                u8::try_from(value).map_err(|_| "octal escape does not fit a byte")?
            }
            _ => return Err(format!("unsupported C escape: \\{}", escaped as char)),
        });
    }
    out.push(0);
    Ok(out)
}

pub fn errlist(source: &str) -> Result<String, String> {
    let strings = Regex::new(r#"static char (str_\w+)\[\]\s*=\s*"((?:[^"\\]|\\.)*)";"#).unwrap();
    let strings: Vec<_> = strings.captures_iter(source).collect();
    if strings.is_empty() {
        return Err("no `static char str_*[]` found".into());
    }
    let table = Regex::new(r"(?s)char \*MSVCRT__sys_errlist\[\]\s*=\s*\{(.*?)\};").unwrap();
    let table = table
        .captures(source)
        .ok_or("MSVCRT__sys_errlist not found")?;
    let order: Vec<_> = table[1]
        .trim()
        .lines()
        .map(str::trim)
        .filter(|s| !s.trim_matches([' ', ',']).is_empty())
        .map(|s| s.trim_end_matches(','))
        .collect();
    let defined: HashSet<_> = strings.iter().map(|s| &s[1]).collect();
    if order.is_empty() {
        return Err("MSVCRT__sys_errlist is empty".into());
    }
    for name in &order {
        if !defined.contains(name) {
            return Err(format!("errlist references undefined string {name}"));
        }
    }
    let mut out = format!("{ERRLIST_BEGIN}\n// Content, sizes and table order all come from dll/win32/msvcrt/errno.c. See the\n// generator's docstring for why a transcription of this particular block is unsafe.\n");
    for s in strings {
        let bytes = c_bytes(&s[2])?;
        let body = bytes
            .iter()
            .map(|b| {
                if (32..127).contains(b) && ![b'"', b'\\'].contains(b) {
                    (*b as char).to_string()
                } else {
                    format!("\\x{b:02x}")
                }
            })
            .collect::<String>();
        writeln!(
            out,
            "pub static mut {}: [u8; {}] = *b\"{body}\";",
            &s[1],
            bytes.len()
        )
        .unwrap();
    }
    writeln!(
        out,
        "\n#[no_mangle]\npub static mut MSVCRT__sys_errlist: [*mut c_char; {}] = [",
        order.len()
    )
    .unwrap();
    for name in &order {
        writeln!(out, "    core::ptr::addr_of_mut!({name}) as *mut c_char,").unwrap();
    }
    writeln!(out, "];\n\n// ARRAY_SIZE(MSVCRT__sys_errlist) - 1 in the C. Every entry point clamps `err`\n// against it, so a table one entry short silently rewrites the clamp.\n#[no_mangle]\npub static mut MSVCRT__sys_nerr: c_uint = {};\n{ERRLIST_END}", order.len()-1).unwrap();
    out.pop(); // The block itself has no final newline; retain the caller's tail.
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn apisets_skip_disabled_and_encode_surrogates_with_nul() {
        let text = "{ RTL_CONSTANT_STRING(L\"api-😀\"), RTL_CONSTANT_STRING(L\"k.dll\"), APISET_WIN7 | APISET_WIN10 },\n// { RTL_CONSTANT_STRING(L\"disabled\"), RTL_CONSTANT_STRING(L\"x\"), APISET_WIN8 },";
        let out = apisets(text).unwrap();
        assert!(out.contains("0xd83d, 0xde00, 0x0000]"));
        assert!(out.contains("dw_os_versions: 0x9"));
        assert!(!out.contains("N1"));
        assert!(apisets(&text.replace("APISET_WIN10", "APISET_UNKNOWN")).is_err());
    }
    #[test]
    fn ssdt_preserves_order_and_pointer_sized_arguments() {
        let out = ssdt("SVC_(First, 0) // comment\nSVC_(Second, 2)\n").unwrap();
        assert!(out.contains("pub fn NtSecond(_: usize, _: usize);"));
        assert!(out.contains("    (2 * core::mem::size_of::<usize>()) as u8,"));
        assert!(out.contains("[SSDTEntry; 2] = [\n    NtFirst as SSDTEntry,\n    NtSecond"));
        assert!(ssdt("SVC_(First, nope)").is_err());
        assert!(ssdt("").is_err());
    }
    #[test]
    fn nls_checks_lengths_range_and_qualifiers() {
        let out = nls(
            "const WCHAR DECLSPEC_HIDDEN test[2] = { /* 99 */ 0x41, 0, };",
            "test.c",
        )
        .unwrap();
        assert!(out.contains("#[used]\npub static test: [u16; 2] = [\n    0x0041, 0x0000,"));
        for source in [
            "const WCHAR test[1] = { 65536 };",
            "const WCHAR test[2] = { 1 };",
            "const WCHAR test[1] = {-1};",
        ] {
            assert!(nls(source, "test.c").is_err());
        }
    }
    #[test]
    fn errlist_terminates_strings_and_preserves_order() {
        let out = errlist("static char str_A[] = \"hi\\n\";\nstatic char str_B[] = \"x\";\nchar *MSVCRT__sys_errlist[] = {\nstr_B,\nstr_A,\n};").unwrap();
        assert!(out.contains("str_A: [u8; 4] = *b\"hi\\x0a\\x00\""));
        assert!(out.contains("MSVCRT__sys_nerr: c_uint = 1;"));
        assert!(
            out.find("addr_of_mut!(str_B)").unwrap() < out.find("addr_of_mut!(str_A)").unwrap()
        );
        assert_eq!(c_bytes(r#"\101\x42\\\""#).unwrap(), b"AB\\\"\0");
        assert!(
            errlist("static char str_A[] = \"x\"; char *MSVCRT__sys_errlist[] = {unknown};")
                .is_err()
        );
    }
}
