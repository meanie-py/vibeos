#!/usr/bin/env python3
"""Derive msvcrt's error-string table for `msvcrt-crt-rust/src/msvcrt/errno.rs`.

WHY THIS IS GENERATED
---------------------
`errno.c`'s 40 error strings and the 44-entry `MSVCRT__sys_errlist` that indexes them are
pure data, and a translated copy of pure data is a transcription — the one job an LLM has
no advantage at and a specific way of getting subtly wrong:

    static char str_ENOTTY[] = "Inappropriate ioctl for device";   /* C: sizeof == 31 */
    pub static mut str_ENOTTY: [u8; 30] = *b"Inappropriate ioctl for device";  /* NO NUL */

C sizes a `char[]` from a string literal to *include* the terminator; a Rust byte-array
literal does not, and neither the type system nor any lint notices. `strerror` does
`strcpy(buf, MSVCRT__sys_errlist[err])` and `perror` does `strlen` on the same pointer, so
an unterminated entry reads off the end of the static. Two of the 40 came back that way,
and eleven more were padded with surplus NULs — harmless, but equally unverified.

Sealing does not cover this. `--seal-facts` protects CONSTANTS; a string literal is not
one, so the model retypes the text and invents the length. Deriving both from the C is the
only thing that makes the table's content a fact rather than a claim.

The index is also load-bearing beyond the strings: `MSVCRT__sys_nerr` is
`ARRAY_SIZE(...) - 1` and every entry point clamps `err` against it, so a table one short
silently rewrites the clamp.

USAGE
-----
    python3 tools/gen_msvcrt_errlist.py            # rewrite the block in errno.rs
    python3 tools/gen_msvcrt_errlist.py --check    # exit 1 if errno.rs is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
C_SRC = REPO / "dll/win32/msvcrt/errno.c"
RS_DST = REPO / "sdk/lib/rust/msvcrt-crt-rust/src/msvcrt/errno.rs"

BEGIN = "// ---- @generated by tools/gen_msvcrt_errlist.py — do not hand-edit ----"
END = "// ---- end @generated ----"


def _rust_byte_literal(c_literal: str) -> tuple[str, int]:
    """A C string literal -> (Rust `b"..."` body, byte length INCLUDING the NUL)."""
    raw = c_literal.encode().decode("unicode_escape").encode("latin-1") + b"\0"
    body = "".join(chr(b) if 32 <= b < 127 and chr(b) not in '"\\' else f"\\x{b:02x}" for b in raw)
    return body, len(raw)


def render(c_text: str) -> str:
    strings = re.findall(r'static char (str_\w+)\[\]\s*=\s*"((?:[^"\\]|\\.)*)";', c_text)
    if not strings:
        sys.exit(f'{C_SRC}: no `static char str_*[] = "...";` found — did the file move?')

    table = re.search(r"char \*MSVCRT__sys_errlist\[\]\s*=\s*\{(.*?)\};", c_text, re.S)
    if not table:
        sys.exit(f"{C_SRC}: MSVCRT__sys_errlist not found")
    order = [ln.strip().rstrip(",") for ln in table.group(1).strip().splitlines() if ln.strip(" ,")]

    defined = {name for name, _ in strings}
    unknown = [n for n in order if n not in defined]
    if unknown:
        sys.exit(f"{C_SRC}: errlist references undefined strings {unknown}")

    out = [
        BEGIN,
        "// Content, sizes and table order all come from dll/win32/msvcrt/errno.c. See the",
        "// generator's docstring for why a transcription of this particular block is unsafe.",
    ]
    for name, lit in strings:
        body, n = _rust_byte_literal(lit)
        out.append(f'pub static mut {name}: [u8; {n}] = *b"{body}";')
    out += [
        "",
        "#[no_mangle]",
        f"pub static mut MSVCRT__sys_errlist: [*mut c_char; {len(order)}] = [",
    ]
    out += [f"    core::ptr::addr_of_mut!({n}) as *mut c_char," for n in order]
    out += [
        "];",
        "",
        "// ARRAY_SIZE(MSVCRT__sys_errlist) - 1 in the C. Every entry point clamps `err`",
        "// against it, so a table one entry short silently rewrites the clamp.",
        "#[no_mangle]",
        f"pub static mut MSVCRT__sys_nerr: c_uint = {len(order) - 1};",
        END,
    ]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="exit 1 if errno.rs is stale")
    args = ap.parse_args()

    block = render(C_SRC.read_text(errors="replace"))
    rs = RS_DST.read_text(errors="replace")
    if BEGIN not in rs or END not in rs:
        sys.exit(f"{RS_DST}: generated-block markers not found — restore {BEGIN!r} .. {END!r}")
    new = re.sub(
        re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, rs, count=1, flags=re.S
    )
    if args.check:
        if new != rs:
            print(f"STALE: {RS_DST.relative_to(REPO)}", file=sys.stderr)
            print("fix: python3 tools/gen_msvcrt_errlist.py", file=sys.stderr)
            return 1
        print(f"ok: {RS_DST.relative_to(REPO)} matches errno.c")
        return 0
    if new != rs:
        RS_DST.write_text(new)
        print(f"wrote {RS_DST.relative_to(REPO)}")
    else:
        print(f"unchanged: {RS_DST.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
