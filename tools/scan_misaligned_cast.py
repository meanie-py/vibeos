#!/usr/bin/env python3
"""
scan_misaligned_cast.py — a byte buffer cast to a wider pointer and dereferenced, with no
`read_unaligned` / `write_unaligned`.

    C:            Count = (ULONG *)(Buffer + Pad);   Count[0] = ...;
    translated:   Count = Buffer.as_mut_ptr().add(Pad as usize) as *mut u32;
                  *Count.offset(0) = ...;                          <-- UB when Pad % 4 != 0
    faithful:     Count.write_unaligned(...)   (same bytes, defined behaviour)

A `[u8; N]` has alignment 1, so a `*mut u32` into it is misaligned whenever the offset is
not a multiple of 4 — and possibly even at offset 0, since nothing aligns the array itself.
In C that is UB the compilers we target tolerate; in Rust a misaligned deref is UB LLVM is
entitled to exploit (it may emit an aligned vector store, or assume the low bits are zero),
and debug builds panic on it. The bytes written are identical either way, which is why
nothing but a sanitizer or a reviewer finds it.

Found 2026-09-26 by `rustconv difftest-contract` (sha1.json): cryptlib `A_SHAFinal` stored
the length words through `Buffer + Pad` over a `[u8; 72]`. UBSan flagged the genuine C at
the same line, which is the tell that this class is INHERITED: the translation faithfully
kept a C bug, and "exceed the C" (AGENTS.md) means the Rust does it right.

WHAT IS FLAGGED. A cast `<base> as *mut T` / `*const T` where T is wider than a byte and
the base is derived from a BYTE ARRAY (`[u8; N]`, `[UCHAR; N]`, `[BYTE; N]`, `[c_char; N]`,
a local or a struct field, via `.as_ptr()` / `.as_mut_ptr()` / `&buf[i]`), and the result
is DEREFERENCED — directly (`*(… as *mut u32) = x`) or through the variable it is stored in
(`*Count.offset(0) = x`, `(*Hdr).f`, `Count.write(x)`). A pointer that is only passed on
(memcpy, a callee) is not dereferenced here and is not flagged.

WHAT IS DELIBERATELY NOT FLAGGED. A cast of a byte POINTER (`PUCHAR`, `*mut u8` params):
the C contract often guarantees alignment there (pool allocations, packed descriptors read
through `#[repr(packed)]` structs), and that population is a separate, much larger review
— a pointer carries a caller's promise, an array carries none. `--pointers` reports it.

Usage:
    python3 tools/scan_misaligned_cast.py            # report
    python3 tools/scan_misaligned_cast.py --lint     # terse (CLI baseline gate)
    python3 tools/scan_misaligned_cast.py --pointers # also byte POINTER bases (review)

Suppress a reviewed site with `// nolint: misaligned-cast` on the cast line (e.g. the array
sits in a `#[repr(align(4))]` wrapper or a union with a `u32`, so it is aligned by type).
Exit 1 if any finding.
"""

from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tools.c_twin import blank_rust, enclosing, rust_functions
from tools.scan_ptr_byte_diff import BYTE_ELEM, BYTE_PTR, WIDE_ELEM, WIDE_PTR, _decl
from tools.source_walk import source_files

REPO = Path(__file__).resolve().parent.parent
RUST_ROOT = REPO / "sdk" / "lib" / "rust"

SKIP_PATH_RE = re.compile(r"(/target/|/\.responses/)")
NOLINT_RE = re.compile(r"//\s*nolint(?::\s*misaligned-cast\b|\s*$)")
GEN_MARKERS = ("automatically generated by rust-bindgen", "@generated", "Do not edit manually")

# The widened target: `as *mut u32`, `as *const ULONG`, `as PULONG`.
CAST_RE = re.compile(
    r"\bas\s+(?:\*\s*(?P<mut>mut|const)\s+(?P<elem>[A-Za-z_][\w:]*)|(?P<ptr>[A-Z][A-Z0-9_]*)\b)"
)
PREFILTER_RE = re.compile(r"\bas\s+(?:\*\s*(?:mut|const)\s+[A-Za-z_]|P[A-Z]|LP[A-Z])")


def _last(t: str) -> str:
    return t.split("::")[-1]


def wide_target(m: re.Match[str]) -> str | None:
    """The element type name if the cast target is a scalar pointer wider than a byte."""
    if m.group("elem"):
        e = _last(m.group("elem"))
        return e if e in WIDE_ELEM else None
    p = m.group("ptr")
    return p if p in WIDE_PTR else None


def _cast_operand(text: str, as_at: int) -> tuple[str, int]:
    """The expression `as` applies to (postfix chain, or a parenthesised group)."""
    j = as_at
    while j > 0 and text[j - 1] in " \t\n":
        j -= 1
    end = j
    while j > 0:
        c = text[j - 1]
        if c == ")" or c == "]":
            depth = 0
            k = j - 1
            while k >= 0:
                if text[k] in ")]":
                    depth += 1
                elif text[k] in "([":
                    depth -= 1
                    if depth == 0:
                        break
                k -= 1
            j = k
            continue
        if c.isalnum() or c in "_.!":
            j -= 1
            continue
        if c in "*&" and j >= 2 and text[j - 2] == "(":
            # `(*ctx).Buffer` / `(&mut x)` inside a group already walked; stop here.
            break
        break
    return text[j:end], j


# `.as_mut_ptr()` / `.as_ptr()` on NAME, or `&buf[..]` / `&mut buf[..]`, or addr_of!(buf[..]).
_ARRAY_BASE = re.compile(
    r"(?:(?P<a>[A-Za-z_]\w*)\s*\.\s*as_(?:mut_)?ptr\s*\(\s*\))"
    r"|(?:&\s*(?:mut\s+)?(?:\(\*\s*\w+\s*\)\s*\.\s*)?(?P<b>[A-Za-z_]\w*)\s*\[)"
    r"|(?:addr_of(?:_mut)?!\s*\(\s*(?:\(\*\s*\w+\s*\)\s*\.\s*)?(?P<c>[A-Za-z_]\w*)\s*\[)"
)
_BYTE_ARRAY_TY = re.compile(r"^\[\s*(?:[\w:]+::)?(?P<e>\w+)\s*;")


def base_kind(operand: str, scope: str, file_text: str) -> tuple[str | None, str]:
    """('array'|'pointer'|None, base name) for the byte buffer the operand is derived from."""
    m = _ARRAY_BASE.search(operand)
    if m:
        name = m.group("a") or m.group("b") or m.group("c")
        ty = _decl(scope, name) or _decl(file_text, name)
        if ty:
            am = _BYTE_ARRAY_TY.match(ty.strip())
            if am and _last(am.group("e")) in BYTE_ELEM - {"c_void", "VOID"}:
                return "array", name
        return None, name
    # A bare byte pointer, possibly offset: `p.add(n)`, `(p as *mut u8).offset(k)`.
    head = re.match(r"\(?\s*([A-Za-z_]\w*)", operand)
    if not head:
        return None, ""
    name = head.group(1)
    ty = _decl(scope, name) or _decl(file_text, name)
    if ty is None:
        return None, name
    ty = ty.strip()
    pm = re.match(r"\*\s*(?:mut|const)\s+([\w:]+)$", ty)
    if (pm and _last(pm.group(1)) in BYTE_ELEM - {"c_void", "VOID"}) or _last(ty) in (
        BYTE_PTR - {"PVOID", "LPVOID", "PCVOID", "LPCVOID", "HANDLE"}
    ):
        return "pointer", name
    return None, name


def _deref_direct(text: str, start: int, end: int) -> bool:
    """`*(<cast>)`, `*(<cast>).add(i)`, `(<cast>).write(x)` / `.read()` around the cast."""
    before = text[max(0, start - 40) : start]
    after = text[end : end + 60]
    opened = re.search(r"\*\s*\(\s*\(?\s*$", before)
    if opened and re.match(
        r"\s*\)\s*(?:\.\s*(?:add|offset|sub|wrapping_add)\s*\([^()]*\)\s*\)?)?\s*(?:[^.\w(=]|=[^=]|$)",
        after,
    ):
        return True
    return bool(
        re.search(r"\(\s*$", before) and re.match(r"\s*\)\s*\.\s*(?:write|read)\s*\(", after)
    )


def _deref_of(var: str, body: str) -> int:
    """Offset in `body` of a dereference of pointer variable `var`, or -1."""
    v = re.escape(var)
    pat = re.compile(
        r"\*\s*\(?\s*" + v + r"\b(?!\s*as\b)"
        r"(?:\s*\.\s*(?:add|offset|sub|wrapping_add)\s*\([^()]*(?:\([^()]*\))*[^()]*\))?"
        r"|\(\s*\*\s*" + v + r"\s*\)"
        r"|\b" + v + r"\s*\.\s*(?:write|read)\s*\("
    )
    for m in pat.finditer(body):
        # `*mut var` is a type, and `a * var` is multiplication.
        pre = body[max(0, m.start() - 12) : m.start()]
        if re.search(r"(?:\bmut|\bconst)\s*$", pre):
            continue
        if m.group(0).startswith("*") and re.search(r"[\w)\]]\s*$", pre):
            continue
        return m.start()
    return -1


_ASSIGN_RE = re.compile(r"(?:\blet\s+(?:mut\s+)?)?(?P<v>[A-Za-z_]\w*)\s*(?::\s*[^=;]+)?=\s*$")


@dataclass
class Site:
    path: Path
    line: int
    fn: str
    kind: str
    base: str
    elem: str
    via: str
    src: str


def scan_file(path: Path, pointers: bool) -> list[Site]:
    try:
        raw = path.read_text(errors="replace")
    except OSError:
        return []
    if any(g in raw[:2000] for g in GEN_MARKERS) or not PREFILTER_RE.search(raw):
        return []
    text = blank_rust(raw)
    lines = raw.split("\n")
    funcs = rust_functions(text, path)
    out: list[Site] = []
    for m in CAST_RE.finditer(text):
        elem = wide_target(m)
        if elem is None:
            continue
        operand, op_start = _cast_operand(text, m.start())
        if not operand:
            continue
        owner = enclosing(funcs, m.start())
        scope = (owner.params + owner.body) if owner else text
        kind, base = base_kind(operand, scope, text)
        if kind is None or (kind == "pointer" and not pointers):
            continue
        ln = text.count("\n", 0, m.start()) + 1
        if NOLINT_RE.search(lines[ln - 1]):
            continue
        via = ""
        if _deref_direct(text, op_start, m.end()):
            via = "direct"
        else:
            # `V = <cast>;` — follow V to a dereference in the same function.
            lhs = _ASSIGN_RE.search(text, max(0, op_start - 120), op_start)
            if lhs and owner is not None and text[m.end() :].lstrip().startswith(";"):
                var = lhs.group("v")
                rel = m.end() - owner.body_start
                at = _deref_of(var, owner.body[rel:])
                if at >= 0:
                    tail = owner.body[rel + at : rel + at + 80]
                    if "unaligned" not in tail.split(";")[0]:
                        via = var
        if not via:
            continue
        out.append(
            Site(
                path,
                ln,
                owner.name if owner else "",
                kind,
                base,
                elem,
                via,
                lines[ln - 1].strip()[:110],
            )
        )
    return out


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("-")]
    lint = "--lint" in sys.argv
    pointers = "--pointers" in sys.argv
    roots = [Path(a) for a in args] if args else [RUST_ROOT]
    files: list[Path] = []
    for root in roots:
        if root.is_file():
            files.append(root)
        elif root.is_dir():
            files.extend(source_files(root))
        else:
            print(f"scan_misaligned_cast: no such path: {root}", file=sys.stderr)
            return 2
    sites = [
        s
        for f in sorted(set(files))
        if not SKIP_PATH_RE.search(str(f))
        for s in scan_file(f, pointers)
    ]
    for s in sites:
        try:
            rel = s.path.relative_to(REPO)
        except ValueError:
            rel = s.path
        tag = "misaligned-cast" if s.kind == "array" else "misaligned-cast-pointer"
        if lint:
            print(f"{rel}:{s.line}: {tag} {s.fn}({s.base} as *{s.elem})")
        else:
            how = "dereferenced here" if s.via == "direct" else f"dereferenced through `{s.via}`"
            print(
                f"{rel}:{s.line}: {tag}: {s.fn}: byte {s.kind} `{s.base}` cast to *{s.elem}, {how}"
            )
            print(f"    {s.src}")
    if not lint:
        print(f"\n{len(sites)} site(s)")
        if sites:
            print("fix: `p.write_unaligned(v)` / `p.read_unaligned()` — the bytes are identical;")
            print(
                "     if the buffer is aligned by type, say how and mark"
                " `// nolint: misaligned-cast`."
            )
    return 1 if sites else 0


if __name__ == "__main__":
    sys.exit(main())
