#!/usr/bin/env python3
"""
scan_const_contradictions.py — one name, two values, both ours.

THE POINT (field manual §9.113/§9.113a). Translated files each re-declare their
own private copy of a shared C constant, and the LLM invented the number for a
lot of them: 61 wrong bugcheck codes, then 18 more named constants including a
real behavioral bug (mm/section.rs and mm/section_pe.rs disagreed on
STATUS_ROS_EXEFMT_UNKNOWN_FORMAT, so a producer/consumer status comparison could
never match).

Three of those were provable with NO oracle at all — the same name simply carried
two different values in our own tree, so one of them had to be wrong:

    IO_ERR_NOT_READY                 0xC0040002  vs  0xC004000F
    IO_WARNING_IO_OPERATION_RETRIED  0x80040032  vs  0x80040099
    STATUS_ROS_EXEFMT_UNKNOWN_FORMAT 0xC000FFFE  vs  0xA0100001

That is what this scanner automates. It needs no C header, so it covers every
constant family — including the ones `verify_constants.py`'s curated catalog does
not know about, which is exactly how the 18 hid. (A catalog that sweeps ALL 2216
headers was tried and rejected: name collisions across unrelated headers produced
486 findings that were overwhelmingly false. See §9.113b.)

WHY THE DISEASE IS THE DUPLICATION, NOT THE VALUE. A constant declared once and
imported cannot disagree with itself. Every entry here is a private copy that
should eventually be a single shared definition (`ntkrnl_sys::bugcodes` is the
worked example). The baseline is therefore also the work queue.

Not every hit is a bug — a driver may legitimately define its own TRACE_FLAG_*
scale, and per-arch values are real. Arch-suffixed paths are bucketed so
i386/amd64/arm64 variants of one name do not flag each other; what remains is
"two files that should agree, and don't".

Usage:
    python3 tools/scan_const_contradictions.py            # full report
    python3 tools/scan_const_contradictions.py --lint     # terse (CLI baseline gate)
    python3 tools/scan_const_contradictions.py --vs-island  # hand copy vs EVERY bindgen value

Suppress a verified-legitimate divergence on the declaring line:

    const TRACE_FLAG_INIT: u32 = 0x10; // nolint: const-contradiction (driver-local scale)

Output is line-number-free (`<file>: <NAME> = <hex>`) so unrelated edits above a
declaration never churn the baseline — only a genuinely new or changed copy does.
"""

from __future__ import annotations

import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tools.source_walk import source_files

REPO = Path(__file__).resolve().parent.parent
RUST_ROOT = REPO / "sdk" / "lib" / "rust"

SKIP_FILE_RE = re.compile(r"(bindgen_[a-z0-9_]+\.rs$|/target/|/\.responses/)")
GENERATED_RE = re.compile(r"automatically generated by rust-bindgen|@generated")
NOLINT_RE = re.compile(r"//\s*nolint(?::\s*const-contradiction\b|\s*$|:?\s*\()")

# [pub[(…)]] const|static NAME: TYPE = [!]VALUE;  — integer literals plus a
# leading bitwise-NOT, with optional _ separators, a u32/i32/usize-style suffix,
# and an optional `as T` cast.
#
# Both extensions are scars. `static` was excluded, and `mm/rmap.rs` parked a
# 32-bit-truncated `static RMAP_SEGMENT_MASK: ULONG_PTR = 0xFFFFFF00;` where the
# C header says `~((ULONG_PTR)0xff)`. `!LITERAL` was excluded because the value
# was fed straight to `int(raw, 0)`, which raises on "!0xff" — so a *mask*
# constant, the one shape where a wrong value is invisible at the use site, was
# structurally unscannable. RMAP_SEGMENT_MASK had five private copies spelled
# `!0xff` / `!0xFFF` / `!1usize` / `0xFFFFFF00`; only the plain literal parsed,
# and one surviving value cannot contradict itself.
# The value is an integer literal OR a FourCC byte-string. The byte-string form
# was invisible here until 2026-09-04, and it is the LARGEST duplicated-constant
# family in the tree: pool tags. freeldr spelled ONE constant two ways --
# hwdisk.rs `from_le_bytes(*b"cDwH")` (0x48774463) against uefidisk.rs
# `from_be_bytes(*b"cDwH")` (0x63447748, the value C's 'cDwH' actually has) --
# and this scanner, whose entire job is "one name, two values, both ours", could
# not see either. The mismatch wedged the arm64 boot in FrLdrHeapFreeEx's
# tag-check. Both spellings stay legal: `from_le_bytes(*b"HwDc")` and
# `from_be_bytes(*b"cDwH")` are the same number, so compare the VALUE, never the
# spelling.
# The value may also be a pointer-typed flag: `(-2isize) as *mut IRP`, `0x02 as PIRP`. Those
# were invisible here, and fastfat carried FSRTL_CACHE_TOP_LEVEL_IRP four ways (-2, 2, -1,
# 1): each Acquire/Release pair set one value and tested another, a bogus top-level IRP
# leaked, and FatCommonWrite dereferenced it (BUGCHECK 0x23 on arm64).
_INT_LIT = r"(?:0[xX][0-9A-Fa-f_]+|\d[\d_]*)(?:_?(?:u8|u16|u32|u64|usize|i8|i16|i32|i64|isize))?"
CONST_RE = re.compile(
    r"^\s*(?:pub\s*(?:\([^)]*\)\s*)?)?(?:const|static)\s+([A-Z_][A-Z0-9_]*)\s*:\s*[^=]+=\s*"
    r"(!?\s*"
    + _INT_LIT
    + r"|\(\s*-?\s*"
    + _INT_LIT
    + r"\s*\)|-\s*"
    + _INT_LIT
    + r"|u32::from_(?:le|be)_bytes\(\*b\"[^\"]{4}\"\))\s*"
    r"(?:as\s+(?:\*\s*(?:mut|const)\s+)?[\w:]+\s*)*;"
)
_SUFFIX_RE = re.compile(r"_?(?:u8|u16|u32|u64|usize|i8|i16|i32|i64|isize)$")

FOURCC_RE = re.compile(r'u32::from_(le|be)_bytes\(\*b"([^"]{4})"\)')


def parse_value(raw: str) -> int | None:
    """`0x10` -> 16; `!0xff` -> ~255. None when it is not an integer we can read.

    NOT values keep Python's arbitrary-precision `~` (so `!0xff` is -256) rather
    than being widened to some assumed pointer size: the whole point is to
    compare our copies against each other, and picking a width here would make
    `!0xff` and a spelled-out `0xFFFFFF00` collide on 32-bit and not on 64-bit.
    """
    if (fc := FOURCC_RE.search(raw)) is not None:
        return int.from_bytes(fc.group(2).encode(), "little" if fc.group(1) == "le" else "big")
    raw = raw.replace(" ", "").strip("()")
    raw = _SUFFIX_RE.sub("", raw).replace("_", "")
    invert = raw.startswith("!")
    if invert:
        raw = raw[1:]
    try:
        val = int(raw, 0)
    except ValueError:
        return None
    return ~val if invert else val


def render_value(val: int) -> str:
    """Canonical display: `!0xFF` for NOT values, `0xFF` otherwise."""
    return f"!0x{~val:X}" if val < 0 else f"0x{val:X}"


ARCH_RE = re.compile(r"(?:^|[/_])(arm64|aarch64|amd64|x86_64|i386|x86)(?:[/_.]|$)")


def arch_of(rel: str) -> str:
    """Bucket a path by target arch so per-arch values don't flag each other."""
    m = ARCH_RE.search(rel)
    if not m:
        return "common"
    a = m.group(1)
    return {"aarch64": "arm64", "x86_64": "amd64", "x86": "i386"}.get(a, a)


# Any identifier, for the island comparison only. Enum members are CamelCase
# (`UserThreadUseActiveDesktop`, `DelayedWorkQueue`), and CONST_RE's ALL_CAPS rule hid every
# hand copy of one: winsrv's USERTHREADINFOCLASS (0..3 for 7/9/5/6) broke every ExitWindowsEx,
# and 59 more sat in dbgk, ex, po, pnpmgr, cc, inbv, ... The cross-crate contradiction check
# keeps ALL_CAPS: across crates a CamelCase name is too often a different local thing.
ANY_CONST_RE = re.compile(
    CONST_RE.pattern.replace("([A-Z_][A-Z0-9_]*)", "([A-Za-z_][A-Za-z0-9_]*)", 1)
)


def collect(any_case: bool = False) -> dict[str, list[tuple[str, int, str]]]:
    """name -> [(rel_path, value, arch)]"""
    const_re = ANY_CONST_RE if any_case else CONST_RE
    decls: dict[str, list[tuple[str, int, str]]] = defaultdict(list)
    for path in sorted(source_files(RUST_ROOT)):
        sp = str(path)
        if SKIP_FILE_RE.search(sp):
            continue
        try:
            text = path.read_text(errors="replace")
        except OSError:
            continue
        # Generated bindings are correct BY CONSTRUCTION — bindgen copies the
        # value straight out of the C header, so it cannot be an invented number.
        # They also legitimately disagree across crates: uniata's private
        # uata_ctl.h defines ATA_FLAGS_DATA_IN as 0x04 while ntddscsi.h uses
        # (1<<1), and both bindings are right. Only hand/LLM-written
        # declarations are in scope here.
        if GENERATED_RE.search(text[:800]):
            continue
        rel = str(path.relative_to(REPO))
        lines = text.splitlines()
        for idx, line in enumerate(lines):
            if NOLINT_RE.search(line):
                continue
            m = const_re.match(line)
            if not m:
                continue
            # `#[cfg(...)]`-gated declarations legitimately come in mutually
            # exclusive pairs (`_MI_PAGING_LEVELS` is 2 or 4 by pointer width).
            # Only one is ever compiled, so they are not a contradiction — the
            # arch-path bucketing above cannot see these because both live in
            # one file. Look back past doc comments/attributes for a cfg.
            gated = False
            for back in range(1, 4):
                if idx - back < 0:
                    break
                prev = lines[idx - back].strip()
                if prev.startswith("#[cfg("):
                    gated = True
                    break
                if not (prev.startswith("//") or prev.startswith("#[")):
                    break
            if gated:
                continue
            val = parse_value(m.group(2))
            if val is None:
                continue
            decls[m.group(1)].append((rel, val, arch_of(rel)))
    return decls


MASK32 = 0xFFFFFFFF
MASK64 = 0xFFFFFFFFFFFFFFFF


def disagrees(vals: set[int]) -> bool:
    """True only when the values differ as 32-bit AND as 64-bit quantities.

    `!0x0` and `0xFFFFFFFF` are one 32-bit mask spelled two ways; a NOT carries
    no width of its own, so judging it at a single width invents contradictions
    (EXCEPTION_CHAIN_END, SP_UNINITIALIZED_VALUE). Requiring disagreement at both
    widths keeps the real ones — `!0xff` vs `!1usize` differ either way — at the
    cost of forgiving a spelled-out literal that matches the NOT at 32 bits.
    """
    # A 16-bit quantity spelled both ways: VARIANT_TRUE is `-1` and `0xFFFF`, WEOF is `!0`
    # and `0xFFFF`. Only when every spelled-out value fits in 16 bits, so a real
    # 0x10000-vs-0 disagreement is never forgiven.
    sixteen = all(v <= 0xFFFF for v in vals if v >= 0) and any(v < 0 for v in vals)
    if sixteen and len({v & 0xFFFF for v in vals}) == 1:
        return False
    return len({v & MASK32 for v in vals}) > 1 and len({v & MASK64 for v in vals}) > 1


def contradictions(decls) -> list[tuple[str, str, int]]:
    """[(name, file, value)] for names that disagree WITHIN an arch bucket."""
    out = []
    for name, sites in decls.items():
        by_arch: dict[str, set] = defaultdict(set)
        for _rel, val, arch in sites:
            by_arch[arch].add(val)
        # A name is contradictory if any single arch bucket holds >1 value.
        # (common-vs-arm64 divergence is a legitimate per-arch override.)
        if not any(disagrees(v) for v in by_arch.values()):
            continue
        bad_arches = {a for a, v in by_arch.items() if disagrees(v)}
        for rel, val, arch in sites:
            if arch in bad_arches:
                out.append((name, rel, val))
    return sorted(set(out))


def _crate_of(rel: str) -> str:
    parts = rel.split("/")
    return parts[3] if len(parts) > 3 and parts[:3] == ["sdk", "lib", "rust"] else rel


def within_crate(decls) -> list[tuple[str, str, int]]:
    """[(name, file, value)] for a name with two values inside ONE crate (same arch bucket).

    Across crates a name can legitimately mean two things; inside one crate, one of the two
    copies is wrong. The cross-crate list is a large, mixed triage queue that only gates NEW
    rows, and userenv's IDS_PROFILEPATH (0 and 1 in one crate) sat in it while it stopped GUI
    setup on every install. This half is gated against a short reviewed baseline instead.
    """
    out = []
    for name, sites in decls.items():
        by_bucket: dict[tuple[str, str], set] = defaultdict(set)
        for rel, val, arch in sites:
            by_bucket[(_crate_of(rel), arch)].add(val)
        bad = {k for k, v in by_bucket.items() if disagrees(v)}
        for rel, val, arch in sites:
            if (_crate_of(rel), arch) in bad:
                out.append((name, rel, val))
    return sorted(set(out))


# `pub const NAME: T = VALUE;` as bindgen writes it -- the island's transcript of a C header.
ISLAND_FILE_RE = re.compile(r"(?:^|/)(?:hal_)?bindgen_[a-z0-9_]+\.rs$")
ISLAND_CONST_RE = re.compile(
    r"^\s*pub const ([A-Za-z_][A-Za-z0-9_]*)\s*:\s*([^=]+?)\s*="
    r"\s*(-?(?:0[xX][0-9A-Fa-f_]+|\d[\d_]*))\s*;"
)


def island_values() -> dict[str, set[int]]:
    """name -> every value the bindgen islands give it (all crates, all arches)."""
    out: dict[str, set[int]] = defaultdict(set)
    for path in sorted(source_files(RUST_ROOT)):
        if "/target/" in str(path) or not ISLAND_FILE_RE.search(str(path)):
            continue
        for line in path.read_text(errors="replace").splitlines():
            m = ISLAND_CONST_RE.match(line)
            if m:
                try:
                    val = int(m.group(3).replace("_", ""), 0)
                except ValueError:
                    continue
                out[m.group(1)].add(val)
                # An enum member is `<EnumType>_<Member>: <EnumType>`; a hand copy is named by
                # the bare member, as the C spells it. fastfat's `MmFlushForWrite = 2` (it is 1)
                # was invisible until the member was indexed too.
                enum_type = m.group(2).strip()
                if m.group(1).startswith(enum_type + "_"):
                    out[m.group(1)[len(enum_type) + 1 :]].add(val)
    return out


def island_disagreements(decls, island) -> list[tuple[str, str, int]]:
    """[(name, file, value)]: a hand copy whose value is NONE of the islands' values.

    The contradiction check above needs TWO hand copies to disagree, so a single invented
    copy of a header constant is invisible to it -- and bindgen islands are skipped as
    inputs because they can differ across crates. fsrtl's filelock.rs carried exactly that:
    the only hand copy of _RTL_GENERIC_COMPARE_RESULTS_GenericEqual/GreaterThan, with the
    two values SWAPPED against every island. Overlapping lock ranges compared as "greater",
    RtlDeleteElementGenericTable never found a lock, FsRtlUninitializeFileLock spun forever
    holding fastfat's volume resource, and every later open on C: hung. Matching ANY island
    value keeps the cross-crate case (uniata's private ATA_FLAGS_DATA_IN) quiet; what is
    left disagrees with every C header we transcribe."""
    out = []
    for name, sites in decls.items():
        vals = island.get(name)
        if not vals:
            continue
        for rel, val, _arch in sites:
            if not any(
                (val & MASK32) == (v & MASK32) or (val & MASK64) == (v & MASK64) for v in vals
            ):
                out.append((name, rel, val))
    return sorted(set(out))


def main() -> int:
    lint = "--lint" in sys.argv
    decls = collect()
    if "--vs-island" in sys.argv:
        for name, rel, val in island_disagreements(collect(any_case=True), island_values()):
            print(f"{rel}: {name} = {render_value(val)} [VS_ISLAND]")
        return 0
    if "--within-crate" in sys.argv:
        for name, rel, val in within_crate(decls):
            print(f"{rel}: {name} = {render_value(val)} [WITHIN_CRATE]")
        return 0
    hits = contradictions(decls)

    names = sorted({h[0] for h in hits})
    for name, rel, val in hits:
        print(f"{rel}: {name} = {render_value(val)}")

    if not lint:
        print(f"\n{len(hits)} declaration(s) across {len(names)} contradictory name(s)")
        if hits:
            print(
                "each name has two values in one arch bucket — at most one can be right.\n"
                "fix: resolve against the C header, then hoist to ONE shared definition\n"
                "     (see ntkrnl_sys::bugcodes); suppress a legitimate driver-local\n"
                "     scale with // nolint: const-contradiction (reason)"
            )
    return 1 if hits else 0


if __name__ == "__main__":
    sys.exit(main())
