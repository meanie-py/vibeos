#!/usr/bin/env python3
"""Deterministically extract the NTSTATUS->DOS data tables from rtl/error.c
into a Rust module. The tables are pure data (hundreds of DWORD entries); an
LLM transcription silently drops/miscounts entries (observed), so we generate
them straight from the C source instead. The element identifiers resolve via
`crate::winerr::*` (see gen_winerror_consts.py); the dispatch struct
`error_table` is defined in lib.rs.

Usage: gen_error_tables.py <error.c> <out_tables.rs>
"""
import re, sys

cpath, out = sys.argv[1], sys.argv[2]
c = open(cpath).read()
# strip /* ... */ comments (tables are heavily commented)
c = re.sub(r'/\*.*?\*/', '', c, flags=re.S)

lines = ["//! AUTO-GENERATED by tools/gen_error_tables.py from sdk/lib/rtl/error.c",
         "//! — the NTSTATUS->DOS code tables (pure data). Element names resolve",
         "//! via crate::winerr::*; the dispatch struct is defined in lib.rs.",
         "//! DO NOT edit by hand; re-run the generator if error.c changes.",
         "#![allow(dead_code)]",
         "use crate::winerr::*;",
         "use crate::{error_table, DWORD};",
         ""]

# 1) the value tables: static const DWORD table_X[N] = { ... };
n_tables = 0
for m in re.finditer(r'static\s+const\s+DWORD\s+(table_[0-9a-fA-F]+)\s*\[(\d+)\]\s*=\s*\{(.*?)\}\s*;', c, re.S):
    name, n, body = m.group(1), int(m.group(2)), m.group(3)
    items = [e.strip() for e in body.split(',')]
    items = [e for e in items if e]  # drop trailing empty after last comma
    if len(items) != n:
        sys.exit(f"{name}: declared [{n}] but found {len(items)} entries")
    lines.append(f"pub static {name}: [DWORD; {n}] = [")
    for e in items:
        lines.append(f"    {e},")
    lines.append("];")
    lines.append("")
    n_tables += 1

# 2) the dispatch array: static const struct {...} error_table[] = { {s,e,tbl}, ... };
disp = re.search(r'error_table\s*\[\s*\]\s*=\s*\{(.*?)\}\s*;', c, re.S)
if not disp:
    sys.exit("could not find error_table[] dispatch array")
entries = re.findall(r'\{\s*([0-9a-fA-Fx]+)\s*,\s*([0-9a-fA-Fx]+)\s*,\s*(table_[0-9a-fA-F]+|NULL)\s*\}', disp.group(1))
lines.append(f"pub static ERROR_TABLE: [error_table; {len(entries)}] = [")
for start, end, tbl in entries:
    if tbl == "NULL":
        lines.append(f"    error_table {{ start: {start}, end: {end}, table: core::ptr::null() }},")
    else:
        lines.append(f"    error_table {{ start: {start}, end: {end}, table: {tbl}.as_ptr() }},")
lines.append("];")
open(out, "w").write("\n".join(lines) + "\n")
print(f"emitted {n_tables} tables + dispatch[{len(entries)}] -> {out}")
