#!/usr/bin/env python3
"""Deterministically extract the Win32 ERROR_*/SEC_*/RPC_* and NTSTATUS
STATUS_* constants that a banked rtl translation references, resolving each
against the SDK headers, and emit a Rust consts module (all typed `DWORD`).

LLMs are bad at transcribing hundreds of numeric codes verbatim — this is a
header-driven pass instead. Re-run if the referenced set changes.

Usage:
  gen_winerror_consts.py <input.rs> <out.rs> <winerror.h> [ntstatus.h ...]
"""

import re
import sys
from pathlib import Path

inp, out = sys.argv[1], sys.argv[2]
headers = sys.argv[3:]
src = Path(inp).read_text()

# Only scan the data-table region (before the first translated function) so we
# pick up table-value constants of every family (ERROR_/STATUS_/STG_E_/SCARD_/
# RPC_/SEC_/…) without grabbing the NTSTATUS-typed STATUS_* the functions
# return. Identifiers that are our own tokens (DWORD, the table_* statics) are
# excluded; everything else must resolve in the headers.
cut = re.search(r"#\[no_mangle\]", src)
region = src[: cut.start()] if cut else src
region = re.sub(r"/\*.*?\*/", "", region, flags=re.S)  # block comments
region = re.sub(r"//.*", "", region)  # line comments
own = {
    "DWORD",
    "ULONG",
    "NTSTATUS",
    "PULONG",
    "PVOID",
    "BOOLEAN",
    "HANDLE",
    "PTEB",
    "TEB",
    "PWSTR",
    "USHORT",
    "UCHAR",
    "LONG",
}
referenced = sorted({i for i in re.findall(r"\b([A-Z][A-Z0-9_]{3,})\b", region) if i not in own})

# Resolve across all given headers. Forms seen:
#   #define NAME 123 / 0xABC / (0xABC)
#   #define NAME _HRESULT_TYPEDEF_(0x........)      (winerror.h)
#   #define NAME ((NTSTATUS)0x........L)            (ntstatus.h)
defs = {}
for h in headers:
    text = Path(h).read_text()
    for m in re.finditer(
        r"^#define\s+([A-Z][A-Z0-9_]+)\s+\(?(-?\d+|0[xX][0-9a-fA-F]+)L?\)?\s*(?://|/\*|$)",
        text,
        re.M,
    ):
        defs.setdefault(m.group(1), m.group(2))
    for m in re.finditer(
        r"^#define\s+([A-Z][A-Z0-9_]+)\s+_HRESULT_TYPEDEF_\((0[xX][0-9a-fA-F]+)L?\)", text, re.M
    ):
        defs.setdefault(m.group(1), m.group(2))
    for m in re.finditer(
        r"^#define\s+([A-Z][A-Z0-9_]+)\s+\(\(NTSTATUS\)(0[xX][0-9a-fA-F]+)L?\)", text, re.M
    ):
        defs.setdefault(m.group(1), m.group(2))

missing = [c for c in referenced if c not in defs]
if missing:
    sys.exit("UNRESOLVED constants (not in given headers): " + ", ".join(missing))

lines = [
    "//! AUTO-GENERATED by tools/gen_winerror_consts.py from the SDK headers",
    "//! (winerror.h + ntstatus.h) — the Win32 ERROR_* / NT STATUS_* codes",
    "//! referenced by the NTSTATUS->DOS error tables in rtl/error.c, all as",
    "//! DWORD (the table element type). DO NOT edit by hand; re-run the",
    "//! generator if the referenced set changes.",
    "#![allow(dead_code)]",
    "use crate::DWORD;",
    "",
]
for name in referenced:
    v = defs[name]
    val = f"0x{int(v, 16):08x}" if v.lower().startswith("0x") else v
    lines.append(f"pub const {name}: DWORD = {val};")
Path(out).write_text("\n".join(lines) + "\n")
print(f"emitted {len(referenced)} consts -> {out}")
