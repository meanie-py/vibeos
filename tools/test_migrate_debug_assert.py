#!/usr/bin/env python3
"""Controls for migrate_debug_assert.py — a WRITE-CAPABLE tool that rewrote 454 sites.

The failure modes that matter here are silent: a rewrite that drops an assertion
message, mangles a path-qualified invocation, or quietly skips a form it does not
understand all produce a tree that still compiles. Every case below was either a real
defect caught on the first run or a form the tool must refuse rather than guess at.
"""

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from migrate_debug_assert import convert, is_generated, split_args  # noqa: E402


def one(src):
    out, n, skipped = convert(src)
    return out, n, skipped


# --- the plain forms -------------------------------------------------------


def test_plain_predicate():
    out, n, _ = one("debug_assert!(x > 0);")
    assert n == 1 and out == "ntkrnl_sys::ASSERT!(x > 0);"


def test_eq_and_ne_become_comparisons():
    assert one("debug_assert_eq!(a, b);")[0] == "ntkrnl_sys::ASSERT!(a == b);"
    assert one("debug_assert_ne!(a, b);")[0] == "ntkrnl_sys::ASSERT!(a != b);"


def test_literal_message_is_preserved():
    out, n, _ = one('debug_assert!(c, "boom");')
    assert n == 1 and '"boom"' in out


def test_eq_with_message():
    out, _, _ = one('debug_assert_eq!(a, b, "why");')
    assert out == 'ntkrnl_sys::ASSERT!(a == b, "why");'


# --- the parsing traps -----------------------------------------------------


def test_comma_inside_a_call_does_not_split_args():
    """`foo(a, b)` is ONE argument. Splitting on it would produce `foo(a == b)`."""
    out, n, _ = one("debug_assert!(foo(a, b) == 1);")
    assert n == 1 and out == "ntkrnl_sys::ASSERT!(foo(a, b) == 1);"


def test_paren_inside_a_message_does_not_end_the_invocation():
    out, n, _ = one('debug_assert!(x, "oops (see docs)");')
    assert n == 1 and '"oops (see docs)"' in out


def test_turbofish_generics_survive():
    out, n, _ = one("debug_assert!(size_of::<T>() == 4);")
    assert n == 1 and "size_of::<T>() == 4" in out


def test_multiline_invocation():
    out, n, _ = one("debug_assert!(\n    a == b\n);")
    assert n == 1 and "ntkrnl_sys::ASSERT!(a == b)" in out


def test_two_on_one_line():
    assert one("debug_assert!(a); debug_assert!(b);")[1] == 2


# --- the regression that shipped on the first run --------------------------


def test_path_qualified_prefix_is_CONSUMED_not_left_behind():
    """`core::debug_assert!(x)` must not become `core::ntkrnl_sys::ASSERT!(x)`.

    `\\bdebug_assert` matches happily after the `::`, and rewriting only the tail
    produced that exact garbage in 15 files before the lookbehind went in.
    """
    for src in ("core::debug_assert!(false);", "std::debug_assert_eq!(a, b);"):
        out, n, _ = one(src)
        assert n == 1, src
        assert "::ntkrnl_sys::ASSERT!" not in out, out
        assert out.startswith("ntkrnl_sys::ASSERT!"), out


def test_a_different_macro_ending_in_the_same_name_is_untouched():
    """The negative control for the fix above — consuming a path prefix must not
    turn into consuming an identifier prefix."""
    out, n, _ = one("my_debug_assert!(x);")
    assert n == 0 and out == "my_debug_assert!(x);"


# --- what it must REFUSE rather than guess ---------------------------------


def test_format_args_are_refused_not_silently_dropped():
    """ASSERT! concat!s its message, so interpolation cannot survive. Converting
    anyway would silently discard `v` — the site must be left alone and reported."""
    out, n, skipped = one('debug_assert!(x, "v={}", v);')
    assert n == 0 and out == 'debug_assert!(x, "v={}", v);'
    assert skipped and "format args" in skipped[0]


def test_non_literal_message_is_refused():
    out, n, skipped = one("debug_assert!(x, msg_var);")
    assert n == 0 and skipped and "not a literal" in skipped[0]


# --- generated-file detection ----------------------------------------------


def test_generated_files_are_detected_by_CONTENT_not_name():
    """`types_amd64.rs` IS bindgen output; `winldr_amd64.rs` is hand-written freeldr
    source; `bindgen_common.rs` is generated but carries no bindgen banner. The name
    decides none of them."""
    assert is_generated("/* automatically generated by rust-bindgen 0.72.1 */\n")
    assert is_generated("// @generated by tools/rustconv/gen_driver_types.sh\n")
    assert is_generated("//! Shared helpers.\n//!\n//! Do not edit manually.\n")
    assert not is_generated("use ntkrnl_sys::base::*;\nfn main() {}\n")


def test_split_args_honours_nesting():
    assert split_args("a, b") == ["a", "b"]
    assert split_args("foo(a, b), c") == ["foo(a, b)", "c"]
    assert split_args('x, "a, b"') == ["x", '"a, b"']
