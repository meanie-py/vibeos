#!/usr/bin/env python3
"""Generate _global_write_barrier() function for ntoskrnl-rust.

Creates a #[no_mangle] function that writes to every pub static mut global.
LLVM can't prove this function is never called (it's externally visible),
so it must assume every global CAN be written, preventing constant-folding
of initial values.

This is the fix for CGU=1 LLVM miscompilation where LLVM constant-folds
globals that are initialized to 0 and appear (to LLVM) to never be written
(because the actual writes happen in C code that LLVM can't see).

Usage:
    python3 tools/gen_global_barrier.py > sdk/lib/rust/ntoskrnl-rust/src/global_barrier.rs
"""

import re
import sys
from pathlib import Path


def find_globals(src_dir: Path) -> list[tuple[str, str, str]]:
    """Find all pub static mut definitions. Returns [(name, type, file), ...]."""
    globals = []
    seen = set()

    for rs_file in sorted(src_dir.rglob("*.rs")):
        if ".bak" in str(rs_file) or "old_translations" in str(rs_file):
            continue
        if rs_file.name == "global_barrier.rs":
            continue

        try:
            source = rs_file.read_text()
        except Exception:
            continue

        for match in re.finditer(
            r"pub\s+static\s+mut\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*([^=;]+?)\s*=",
            source,
        ):
            name = match.group(1)
            typ = match.group(2).strip()
            if name not in seen and name not in SKIP_GLOBALS:
                seen.add(name)
                rel_path = str(rs_file.relative_to(src_dir))
                globals.append((name, typ, rel_path))

    return globals


def generate(globals: list[tuple[str, str, str]]) -> str:
    """Generate the global_barrier.rs source."""
    lines = [
        "//! Auto-generated write barrier for all pub static mut globals.",
        "//!",
        "//! This function is NEVER CALLED — its purpose is to prevent LLVM from",
        "//! constant-folding globals that are initialized to 0 but written from C.",
        "//! With codegen-units=1, LLVM can see the entire Rust crate and may prove",
        '//! a global is "never written" (because writes happen in C code LLVM cannot',
        "//! see). This function provides a visible write site that LLVM cannot",
        "//! eliminate (the function is #[no_mangle], so it could be called externally).",
        "//!",
        "//! Generated by: python3 tools/gen_global_barrier.py",
        f"//! Globals covered: {len(globals)}",
        "//!",
        "//! DO NOT EDIT — regenerate with the command above.",
        "",
        "#[allow(unused_unsafe)]",
        "#[allow(dead_code)]",
        "",
        "/// Write barrier — touches every pub static mut global.",
        "/// NEVER CALLED. Exists solely to prevent LLVM constant-folding.",
        "#[no_mangle]",
        "#[inline(never)]",
        'pub unsafe extern "C" fn _global_write_barrier(seed: usize) {',
        "    // The seed parameter is opaque to LLVM — it cannot prove what",
        "    // value is written, so it cannot constant-fold any global.",
        "    let s = seed as u8;",
    ]

    # Group by source file for readability
    current_file = None
    current_cfg = None
    for name, _typ, file in globals:
        cfg = _cfg_for_file(file)
        if cfg == "SKIP":
            continue

        if file != current_file:
            # Close previous cfg block if needed
            if current_cfg and current_cfg != cfg:
                lines.append("    }")
                current_cfg = None

            current_file = file
            lines.append(f"    // {file}")

            # Open new cfg block if needed
            if cfg and cfg != current_cfg:
                lines.append(f"    {cfg}")
                lines.append("    {")
                current_cfg = cfg
            elif not cfg and current_cfg:
                current_cfg = None

        # Write a seed-dependent value: XOR the first byte of the global
        # with the seed parameter. LLVM cannot prove what value is written
        # because the seed comes from an external caller.
        indent = "        " if current_cfg else "    "
        path = f"crate::{_module_path(file)}{name}"
        lines.append(f"{indent}let p = core::ptr::addr_of_mut!({path}) as *mut u8;")
        lines.append(f"{indent}core::ptr::write_volatile(p, core::ptr::read_volatile(p) ^ s);")

    # Close any open cfg block
    if current_cfg:
        lines.append("    }")

    lines.append("}")
    lines.append("")
    return "\n".join(lines)


# Modules that are cfg-gated or not compiled on all architectures
ARCH_MODULES = {
    "amd64": '#[cfg(target_arch = "x86_64")]',
    "arm64": '#[cfg(target_arch = "aarch64")]',
    "arm": '#[cfg(target_arch = "aarch64")]',
    "i386": '#[cfg(target_arch = "x86")]',
    "kd64": None,  # KD64 compiled from C — Rust module not available
}


def _module_path(file: str) -> str:
    """Convert file path to Rust module path prefix.

    e.g., 'kd64/kddata.rs' -> 'kd64::kddata::'
          'ex/init.rs' -> 'ex::init::'
    """
    parts = file.replace(".rs", "").split("/")
    return "::".join(parts) + "::"


# Modules to skip entirely (compiled from C, Rust module not available)
SKIP_MODULES = {"kd64"}

# Individual globals to skip (cfg-gated per arch, constants, or not actual static mut)
SKIP_GLOBALS = {
    # 64-bit only (paging levels > 2)
    "MiHighestUserPpe",
    "MiHighestUserPxe",
    # Constants incorrectly matched as static mut
    "ADMIN_DEVICE_NAME",
    "ADMIN_DOS_DEVICE_NAME",
    "GUID_OBJECT_NAME",
    "PREFIX",
    "KEY_PRODUCT",
    "LANMAN_PRODUCT",
    "SERVER_PRODUCT",
    "VALUE_NT_PRODUCT",
    "WORKSTATION_PRODUCT",
    "SERVICE_DEVICE_NAME",
    "SERVICE_DOS_DEVICE_NAME",
    # Globals with private types (can't access cross-module)
    "ExpCritSecOutOfMemoryEvent",
    "ObpDosDevicesShortNamePrefix",
    "ObpDosDevicesShortNameRoot",
    "RotBarSelection",
    "PltRotBarStatus",
    "InbvProgressState",
    "InbvProgressIndicator",
}


def _cfg_for_file(file: str) -> str | None:
    """Return cfg guard if file is in an arch-specific module, else None."""
    parts = file.split("/")
    # Check all path components for arch-specific modules
    for part in parts:
        if part in SKIP_MODULES:
            return "SKIP"
        if part in ARCH_MODULES:
            return ARCH_MODULES[part]
    return None


def main():
    src_dir = Path("sdk/lib/rust/ntoskrnl-rust/src")
    if not src_dir.exists():
        print(f"ERROR: {src_dir} not found. Run from vibeos/ root.", file=sys.stderr)
        sys.exit(1)

    globals = find_globals(src_dir)
    print(f"Found {len(globals)} globals", file=sys.stderr)

    output = generate(globals)
    sys.stdout.write(output)


if __name__ == "__main__":
    main()
