#!/usr/bin/env python3
"""Extract the neutral-LCID remap table from kernel32_vista/LocaleNameToLCID.c
and emit it verbatim as Rust, so the 30 hex->hex special cases are never
hand-transcribed (a single wrong hex digit silently breaks a locale).

Usage:
    gen_kernel32_vista_lcid_table.py            # write the .rs
    gen_kernel32_vista_lcid_table.py --check    # verify the .rs is in sync (CI)
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "dll/win32/kernel32/kernel32_vista/LocaleNameToLCID.c"
OUT = ROOT / "sdk/lib/rust/kernel32-vista-rust/src/localenametolcid_table.rs"

# Match:  case 0x0742C: return 0x0082C; // "az-Cyrl" -> "az-Cyrl-AZ"
CASE_RE = re.compile(r"case\s+(0x[0-9A-Fa-f]+)\s*:\s*return\s+(0x[0-9A-Fa-f]+)\s*;\s*//\s*(.*)$")


def extract():
    rows = []
    for line in SRC.read_text().splitlines():
        m = CASE_RE.search(line)
        if m:
            lcid = int(m.group(1), 16)
            ret = int(m.group(2), 16)
            comment = m.group(3).strip()
            rows.append((lcid, ret, comment))
    if not rows:
        sys.exit("error: no `case 0x..: return 0x..;` rows found in " + str(SRC))
    return rows


def render(rows):
    lines = [
        "// @generated by tools/gen_kernel32_vista_lcid_table.py — DO NOT EDIT.",
        "// Source: dll/win32/kernel32/kernel32_vista/LocaleNameToLCID.c (neutral-LCID switch).",
        "//! Verbatim extraction of the special neutral-LCID remap table.",
        "",
        "/// Map a special neutral LCID (SubLangId >= 0x18) to its default locale.",
        "/// Returns `None` for an unhandled neutral LCID (the C `ASSERT(FALSE)` path).",
        "#[inline]",
        "pub fn neutral_lcid_remap(lcid: u32) -> Option<u32> {",
        "    match lcid {",
    ]
    for lcid, ret, comment in rows:
        lines.append(f"        0x{lcid:05X} => Some(0x{ret:05X}), // {comment}")
    lines += [
        "        _ => None,",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    rows = extract()
    text = render(rows)
    check = "--check" in sys.argv
    if check:
        if not OUT.exists():
            sys.exit(f"error: {OUT} missing — run without --check")
        if OUT.read_text() != text:
            sys.exit(f"error: {OUT} out of sync with {SRC.name} — re-run the generator")
        print(f"ok: {OUT.name} in sync ({len(rows)} entries)")
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text)
        print(f"wrote {OUT} ({len(rows)} entries)")


if __name__ == "__main__":
    main()
