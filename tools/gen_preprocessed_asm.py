#!/usr/bin/env python3
"""Pre-process the 6 remaining ntoskrnl i386 asm files via `clang -E`.

The output `.s` files are checked in next to the corresponding Rust
wrappers under `sdk/lib/rust/ntoskrnl-rust/src/{ke,ex,rtl}/...`. The
wrappers do `core::arch::global_asm!(include_str!("X.s"))` so the asm
becomes a first-class part of the kernel-rust build — no cc-rs `compile_asm()`
on source-tree `.S` files, no kernel `-I` chain (drops `ntoskrnl/include`
and `sdk/include/asm` from `KERNEL_INCLUDES`).

Out-of-band — re-run when an asm source, `asm.inc`, `asmmacro.S`,
`syscalls.inc`, or `sysfuncs.h` changes. Output is GAS assembly with all
`#include`/`#define` preprocessor directives expanded; GAS `.macro` /
`.endm` blocks remain (the Rust integrated assembler handles those).

Usage:
    python3 tools/gen_preprocessed_asm.py
    python3 tools/gen_preprocessed_asm.py --check
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LLVM_MINGW = REPO / ".build-tools/llvm-mingw"
CLANG = LLVM_MINGW / "bin/i686-w64-mingw32-clang"

# Mirrors KERNEL_DEFINES + asm-side defines from build.rs.
ASM_DEFINES = [
    ("__ASM__", None),
    ("DBG", "1"),
    ("KDBG", None),
    ("NTDDI_VERSION", "0x05020400"),
    ("WINVER", "0x502"),
    ("_M_IX86", None),
    ("_NTOSKRNL_", None),
    ("_NTSYSTEM_", None),
    ("_USE_DUMMY_PSEH", "1"),
    ("_WIN32_WINNT", "0x502"),
    ("_X86_", None),
    ("__REACTOS__", None),
    ("__i386__", None),
    ("i386", None),
]

# Each entry: (source, dest). Source paths are relative to repo root;
# dest paths land in `sdk/lib/rust/ntoskrnl-rust/src/...` next to the
# Rust wrapper that will `include_str!` them.
SOURCES = [
    ("ntoskrnl/ex/zw.S",                    "sdk/lib/rust/ntoskrnl-cargo/data/asm/zw-i386.s"),
    ("ntoskrnl/ex/i386/fastinterlck_asm.S", "sdk/lib/rust/ntoskrnl-cargo/data/asm/fastinterlck-i386.s"),
    ("ntoskrnl/ex/i386/ioport.S",           "sdk/lib/rust/ntoskrnl-cargo/data/asm/ioport-i386.s"),
    ("ntoskrnl/ke/i386/ctxswitch.S",        "sdk/lib/rust/ntoskrnl-cargo/data/asm/ctxswitch-i386.s"),
    ("ntoskrnl/ke/i386/trap.s",             "sdk/lib/rust/ntoskrnl-cargo/data/asm/trap-i386.s"),
    ("ntoskrnl/ke/i386/usercall_asm.S",     "sdk/lib/rust/ntoskrnl-cargo/data/asm/usercall-i386.s"),
]


def build_command(source: Path, ks386_inc_dir: Path, mc_gen_dir: Path) -> list[str]:
    cmd = [
        str(CLANG),
        "--target=i686-w64-mingw32",
        "-E",
        "-x", "assembler-with-cpp",
        "-nostdinc",
        "-isystem", str(REPO / "sdk/include/crt"),
        "-isystem", str(LLVM_MINGW / "lib/clang/19/include"),
    ]
    for name, value in ASM_DEFINES:
        cmd.append(f"-D{name}={value}" if value is not None else f"-D{name}")
    # Asm needs sdk/include/asm (asm.inc, syscalls.inc), generated
    # ks386.inc dir, ntoskrnl/include (asmmacro.S, sysfuncs.h),
    # and mc-gen for any indirect includes.
    cmd.extend([
        "-I", str(REPO / "sdk/include/asm"),
        "-I", str(ks386_inc_dir),
        "-I", str(REPO / "ntoskrnl/include"),
        "-I", str(mc_gen_dir),
    ])
    cmd.append(str(source))
    return cmd


def find_cargo_dirs() -> tuple[Path, Path]:
    """Locate the cargo PoC's OUT_DIR for ks386 + mc-gen.

    These get generated by build.rs at first run; if absent, the user
    must build the cargo PoC at least once before regen."""
    target = REPO / "sdk/lib/rust/target/i686-kernel/release/build"
    matches = list(target.glob("ntoskrnl-cargo-*/out"))
    if not matches:
        raise SystemExit(
            f"missing cargo PoC OUT_DIR under {target}\n"
            f"  Run `bash sdk/lib/rust/ntoskrnl-cargo/build-and-test.sh` once first."
        )
    out = matches[0]
    return out / "asm-gen", out / "mc-gen"


def regen_one(source: Path, dest: Path, ks386_inc_dir: Path, mc_gen_dir: Path) -> bytes:
    cmd = build_command(source, ks386_inc_dir, mc_gen_dir)
    proc = subprocess.run(cmd, capture_output=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr.decode("utf-8", "replace"))
        raise RuntimeError(f"clang -E failed for {source} (exit {proc.returncode})")
    # Strip line markers (`# 1 "..."`) — they reference repo-relative paths
    # that change per checkout. Keeps the checked-in file deterministic.
    out_lines = []
    for line in proc.stdout.splitlines():
        if line.startswith(b"# ") and (b"\"" in line):
            continue
        out_lines.append(line)
    return b"\n".join(out_lines) + b"\n"


def normalize_leading(b: bytes) -> bytes:
    """Strip leading blank lines so files start identically."""
    return b.lstrip(b"\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify checked-in files match a fresh regen")
    args = ap.parse_args()

    if not CLANG.exists():
        raise SystemExit(f"missing {CLANG}")
    ks386_inc_dir, mc_gen_dir = find_cargo_dirs()

    # Pre-process every source. The .s files are self-contained (all
    # `#include`s expanded), so they compile via cc-rs without the kernel
    # `-I` chain — each as its own translation unit, GAS `.macro`
    # definitions are per-TU and don't conflict across files.
    failures = 0
    targets: list[tuple[str, bytes]] = []
    for src_rel, dst_rel in SOURCES:
        src = REPO / src_rel
        if not src.exists():
            raise SystemExit(f"missing source {src}")
        body = normalize_leading(regen_one(src, REPO / dst_rel, ks386_inc_dir, mc_gen_dir))
        targets.append((dst_rel, body))

    for dst_rel, fresh in targets:
        dst = REPO / dst_rel
        if args.check:
            if not dst.exists():
                print(f"FAIL: {dst_rel} does not exist", file=sys.stderr)
                failures += 1
                continue
            existing = dst.read_bytes()
            if existing != fresh:
                print(f"FAIL: {dst_rel} differs from fresh regen", file=sys.stderr)
                failures += 1
                continue
            print(f"OK:   {dst_rel} ({len(fresh)} bytes)")
        else:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes(fresh)
            print(f"wrote {dst_rel} ({len(fresh)} bytes)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
