"""Exercise the shipping generator CLI, including failures that must never write."""

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]


def run(*args, cwd=None):
    return subprocess.run(
        [str(REPO / "tools/codegen"), *map(str, args)],
        cwd=cwd,
        capture_output=True,
        text=True,
        timeout=120,
    )


def test_all_committed_outputs_match():
    result = run("--all", "--check")
    assert result.returncode == 0, result.stderr
    assert "11 generated outputs match" in result.stderr


def test_write_then_check_and_missing_or_stale_output(tmp_path):
    target = tmp_path / "table with spaces.rs"
    assert run("apisets-table", "--output", target, "--check").returncode == 1
    assert not target.exists()
    result = run("apisets-table", "--output", target, cwd=tmp_path)
    assert result.returncode == 0, result.stderr
    before = target.stat().st_mtime_ns
    assert run("apisets-table", "--output", target).returncode == 0
    assert target.stat().st_mtime_ns == before
    target.write_text("stale")
    assert run("apisets-table", "--output", target, "--check").returncode == 1
    assert target.read_text() == "stale"


@pytest.mark.parametrize(
    "args",
    [
        ["unknown"],
        ["apisets-table", "--check", "--stdout"],
        ["--all", "--stdout"],
        ["nls", "--stdout"],
        ["ssdt", "--input"],
        ["apisets-table", "--header", "missing.h"],
    ],
)
def test_invalid_invocations_fail(args):
    result = run(*args)
    assert result.returncode == 2, result.stdout + result.stderr


def test_bad_source_leaves_existing_output_untouched(tmp_path):
    source = tmp_path / "bad.c"
    target = tmp_path / "output.rs"
    source.write_text("unparseable")
    target.write_text("precious contents")
    assert run("ssdt", "--input", source, "--output", target).returncode == 2
    assert target.read_text() == "precious contents"
    assert list(tmp_path.glob("*.tmp")) == []


def test_generated_block_preserves_code_outside_markers(tmp_path):
    target = tmp_path / "errno.rs"
    begin = "// ---- @generated by tools/gen_msvcrt_errlist.py — do not hand-edit ----"
    end = "// ---- end @generated ----"
    target.write_text(f"prefix\n{begin}\nold\n{end}\nsuffix\n")
    result = run("msvcrt-errlist", "--output", target)
    assert result.returncode == 0, result.stderr
    text = target.read_text()
    assert text.startswith(f"prefix\n{begin}\n")
    assert text.endswith(f"{end}\nsuffix\n")
    assert "MSVCRT__sys_nerr: c_uint = 43;" in text


def test_legacy_entrypoints_execute_native_generator(tmp_path):
    for script in ["gen_apisets_table.py", "gen_bugcodes.py", "gen_bugcodes_h.py"]:
        result = subprocess.run(
            [sys.executable, str(REPO / "tools" / script), "--check"],
            cwd=tmp_path,
            capture_output=True,
            text=True,
        )
        assert result.returncode == 0, result.stdout + result.stderr
    target = tmp_path / "tables.rs"
    source = REPO / "sdk/lib/rtl/error.c"
    result = subprocess.run(
        [sys.executable, str(REPO / "tools/gen_error_tables.py"), str(source), str(target)],
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    native = run("error-tables", "--stdout")
    assert native.returncode == 0, native.stderr
    assert target.read_text() == native.stdout


def test_host_tool_cleans_inherited_cross_build_environment(tmp_path):
    result = subprocess.run(
        [str(REPO / "tools/codegen"), "bugcodes-h", "--check"],
        cwd=tmp_path,
        env={
            **os.environ,
            "RUSTUP_TOOLCHAIN": "uninstalled-codegen-test-toolchain",
            "RUSTFLAGS": "--invalid-cross-build-option",
            "CARGO_BUILD_TARGET": "invalid-cross-build-target",
            "RUSTC_WRAPPER": "/missing/cross-build-wrapper",
            "RUSTC": "/missing/cross-build-compiler",
            "CARGO_BUILD_RUSTC": "/missing/cargo-cross-build-compiler",
        },
        capture_output=True,
        text=True,
        timeout=120,
    )
    assert result.returncode == 0, result.stdout + result.stderr


def test_output_symlinks_are_rejected(tmp_path):
    target = tmp_path / "real.rs"
    target.write_text("precious")
    link = tmp_path / "linked.rs"
    link.symlink_to(target)
    result = run("apisets-table", "--output", link)
    assert result.returncode == 2, result.stderr
    assert target.read_text() == "precious"
    assert link.is_symlink()


def test_stdout_contains_only_generated_bytes():
    result = run("bugcodes-h", "--stdout")
    assert result.returncode == 0, result.stderr
    assert (
        result.stdout
        == (REPO / "sdk/lib/rust/reactos-link/committed-headers/bugcodes.h").read_text()
    )


def test_all_renders_before_any_write(tmp_path):
    # Render the first three recipes, then fail at missing RTL input. Even valid
    # earlier results must stay unwritten when a later recipe cannot run.
    for relative in [
        "sdk/lib/apisets/apisets.table.c",
        "sdk/include/reactos/mc/bugcodes.mc",
        "sdk/lib/rust/reactos-link/committed-headers/bugcodes.h",
    ]:
        target = tmp_path / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(REPO / relative, target)
    target = tmp_path / "sdk/lib/rust/ntdll-rust/src/apisets_table.rs"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("do not replace before every recipe renders")
    result = run("--root", tmp_path, "--all")
    assert result.returncode == 2, result.stderr
    assert "sdk/lib/rtl/error.c" in result.stderr
    assert target.read_text() == "do not replace before every recipe renders"
