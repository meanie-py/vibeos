#!/usr/bin/env python3
"""Generate the Rust apiset table from the checked-in C table.

`sdk/lib/apisets/apisets.table.c` is an autogenerated (but checked-in) C array
of `ROS_APISET { UNICODE_STRING Name; UNICODE_STRING Target; DWORD flags }`
built with `RTL_CONSTANT_STRING(L"...")`. The cargo-driven ntdll links this as
the `libapisets.a` reuse-`.a`; this script translates the *data table* to a Rust
static so the resolver (`ntdll-rust/src/apisets.rs`) can own it and cmake's
libapisets.a can be dropped. The 92-LOC resolver is hand-translated; only the
~624-entry table is mechanically generated here.

Output: `sdk/lib/rust/ntdll-rust/src/apisets_table.rs` (checked in; re-run when
apisets.table.c changes). `--check` verifies it matches a fresh generation.

Usage:
    python3 tools/gen_apisets_rs.py [--check]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "sdk/lib/apisets/apisets.table.c"
DST = REPO / "sdk/lib/rust/ntdll-rust/src/apisets_table.rs"

# APISET_* flag bits (apisets.h).
FLAGS = {"APISET_WIN7": 1, "APISET_WIN8": 2, "APISET_WIN81": 4, "APISET_WIN10": 8}

ENTRY_RE = re.compile(
    r'\{\s*RTL_CONSTANT_STRING\(L"([^"]*)"\)\s*,\s*'
    r'RTL_CONSTANT_STRING\(L"([^"]*)"\)\s*,\s*([^}]+?)\s*\}'
)


def parse_flags(expr: str) -> int:
    val = 0
    for tok in expr.split("|"):
        tok = tok.strip()
        if tok not in FLAGS:
            raise SystemExit(f"unknown apiset flag token: {tok!r}")
        val |= FLAGS[tok]
    return val


def u16_array(s: str) -> str:
    # UTF-16LE code units + NUL terminator, as a Rust [u16; N] initializer.
    units = [ord(c) for c in s]
    if any(u > 0xFFFF for u in units):
        raise SystemExit(f"non-BMP char in apiset string: {s!r}")
    units.append(0)
    body = ", ".join(f"0x{u:04x}" for u in units)
    return f"[{body}]"


def generate() -> str:
    text = SRC.read_text(encoding="utf-8")
    entries = ENTRY_RE.findall(text)
    if not entries:
        raise SystemExit(f"no entries parsed from {SRC}")

    out: list[str] = []
    out.append("// @generated by tools/gen_apisets_rs.py from")
    out.append("// sdk/lib/apisets/apisets.table.c — DO NOT EDIT. Re-run the")
    out.append("// generator (and `--check` in CI) when the C table changes.")
    out.append("//")
    out.append("// The g_Apisets table (sorted by Name, case-insensitive) consumed by")
    out.append("// the binary-search resolver in apisets.rs.")
    out.append("#![allow(clippy::all)]")
    out.append("")
    out.append("use super::apisets::{us, RosApiset};")
    out.append("")

    # Per-entry name/target u16 statics, then the table referencing them.
    for i, (name, target, _flags) in enumerate(entries):
        out.append(f"static N{i}: [u16; {len(name) + 1}] = {u16_array(name)};")
        out.append(f"static T{i}: [u16; {len(target) + 1}] = {u16_array(target)};")
    out.append("")
    out.append(f"pub(super) static G_APISETS: [RosApiset; {len(entries)}] = [")
    for i, (_name, _target, flags) in enumerate(entries):
        f = parse_flags(flags)
        out.append(f"    RosApiset {{ name: us(&N{i}), target: us(&T{i}), dw_os_versions: 0x{f:x} }},")
    out.append("];")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify checked-in file is up to date")
    args = ap.parse_args()
    fresh = generate()
    if args.check:
        cur = DST.read_text(encoding="utf-8") if DST.exists() else ""
        if cur != fresh:
            print(f"FAIL: {DST.relative_to(REPO)} differs from a fresh generation", file=sys.stderr)
            return 1
        print(f"OK:   {DST.relative_to(REPO)} up to date ({len(fresh)} bytes)")
        return 0
    DST.write_text(fresh, encoding="utf-8")
    n = fresh.count("RosApiset {")
    print(f"wrote {DST.relative_to(REPO)} ({n} apisets, {len(fresh)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
