#!/bin/bash
# Generate the focused ACPICA FFI substrate (acpica-sys) for all 3 arches.
#
# acpica-sys covers the public ACPICA interface the ReactOS `acpi` driver glue
# needs: the ACPI_* types, the 57 outbound Acpi* API fns (acpixf.h), and the
# AcpiOs* OSL callback typedefs (acpiosxf.h) so the Rust #[no_mangle] OSL impls
# (acpi-rust) match. ACPICA itself stays C (FFI-to-blob). Allowlisted to
# (ACPI_.*|Acpi.*|AE_.*) so it doesn't drift into a second copy of the kernel
# surface — the kernel types the glue touches come from ntkrnl-sys, cast at the
# boundary. Per-arch (pointer widths / table packing differ).
#
# Built with the same defines as the `acpica` cmake target
# (ACPI_USE_LOCAL_CACHE; ACPI_USE_SYSTEM_INTTYPES) + acpi.h's __REACTOS__ path
# (pulls ntddk.h). Prereq: cargo install bindgen-cli. Build dirs must exist
# (generated headers like ntddk.h live under build-<arch>/sdk/include).
set -e
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SRC="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
TC="$SRC/.build-tools/llvm-mingw"
OUT_DIR="$SCRIPT_DIR/src"
WRAPPER="$SCRIPT_DIR/wrapper_acpica.h"
ACPI_DIR="$SRC/drivers/bus/acpi"

COMMON_FLAGS=(
    --use-core --no-layout-tests --no-doc-comments
    --allowlist-type     '(ACPI_.*|acpi_.*)'
    --allowlist-function '(Acpi.*)'
    --allowlist-var      '(ACPI_.*|AE_.*)'
)

run_bindgen() {
    local ARCH=$1 TARGET=$2; shift 2
    local EXTRA=("$@")
    local BUILD_DIR="$SRC/build-${ARCH}"
    local RAW="/tmp/acpica_${ARCH}_raw.rs"
    local FINAL="$OUT_DIR/bindgen_${ARCH}.rs"
    echo "=== acpica-sys ${ARCH} (${TARGET}) ==="
    bindgen "$WRAPPER" "${COMMON_FLAGS[@]}" -o "$RAW" -- \
        -ferror-limit=0 -Wno-everything \
        -DACPI_USE_LOCAL_CACHE -DACPI_USE_SYSTEM_INTTYPES \
        -D__REACTOS__ -D_USE_DUMMY_PSEH=1 \
        "${EXTRA[@]}" \
        -DDBG=1 -DWINVER=0x502 -D_WIN32_WINNT=0x502 \
        -I"${ACPI_DIR}/include" \
        -I"${SRC}/vendor/acpica/include" \
        -I"${BUILD_DIR}/ntoskrnl" \
        -I"${SRC}/ntoskrnl" \
        -I"${SRC}/sdk/include" \
        -I"${SRC}/sdk/include/ddk" \
        -I"${SRC}/sdk/include/ndk" \
        -I"${SRC}/sdk/include/psdk" \
        -I"${SRC}/sdk/include/xdk" \
        -I"${SRC}/sdk/include/reactos" -I"${SRC}/sdk/include/reactos/subsys" \
        -I"${SRC}/sdk/include/reactos/libs" \
        -I"${SRC}/sdk/include/reactos/drivers" \
        -I"${SRC}/sdk/include/vcruntime" \
        -I"${SRC}/sdk/include/winrt" \
        -I"${BUILD_DIR}/sdk/include" \
        -I"${BUILD_DIR}/sdk/include/psdk" \
        -I"${BUILD_DIR}/sdk/include/ddk" \
        -I"${BUILD_DIR}/sdk/include/dxsdk" \
        -I"${BUILD_DIR}/sdk/include/reactos" \
        -I"${BUILD_DIR}/sdk/include/reactos/mc" \
        -I"${SRC}/sdk/include/dxsdk" \
        -I"${SRC}/sdk/lib/pseh/include" \
        -I"${SRC}" \
        -I"${SRC}/ntoskrnl/include" \
        -I"${BUILD_DIR}/ntoskrnl/include" \
        -I"${BUILD_DIR}/ntoskrnl/include/internal" \
        -isystem "${SRC}/sdk/include/crt" \
        -isystem "${TC}/lib/clang/19/include" \
        --target="${TARGET}"
    {
        echo "// AUTO-GENERATED by acpica-sys/generate_bindings.sh — do not edit by hand."
        echo "// Public ACPICA FFI surface for the ReactOS acpi driver glue translation."
        echo "#![allow(non_snake_case, non_camel_case_types, non_upper_case_globals, dead_code, unused_imports)]"
        cat "$RAW"
    } > "$FINAL"
    # Same-size int transmutes (bitfield accessors) -> casts, so the generated
    # module stays clean under `unnecessary_transmutes` (rustc >= 1.92).
    python3 "$(dirname "$0")/fix_transmutes.py" "$FINAL"
    echo "  -> $FINAL ($(wc -l < "$FINAL") lines)"
}

run_bindgen arm64 aarch64-pc-windows-gnu -D_WIN64 -DWIN64 -D_M_ARM64 -D__aarch64__ -D__arm64__ -D_ARM64_
# amd64: -UWIN32. The *-windows-gnu target predefines WIN32, which sends acenv.h to
# acwin.h (ACPI_MACHINE_WIDTH 32) before it reaches the WIN64 branch; the real amd64
# compile defines no WIN32 and gets acwin64.h, i.e. a 64-bit ACPI_SIZE. Generated
# without this, every ACPI_BUFFER the Rust built had a 4-byte Length over a field
# ACPICA reads as 8, so ACPI_ALLOCATE_BUFFER arrived with garbage in its high half
# (AE_BAD_PARAMETER). arm64 and i386 really are 32-wide (their compiles define WIN32).
# Check against the real flags with `-E -dM` on an acpica TU from compile_commands.json.
run_bindgen amd64 x86_64-pc-windows-gnu  -UWIN32 -D_WIN64 -DWIN64 -D_M_AMD64 -D__x86_64__ -D_AMD64_
run_bindgen i386  i686-pc-windows-gnu    -D_M_IX86 -D__i386__ -D_X86_
echo "=== done ==="

# Spell ABI-identical callback slots `extern "system"` across the three islands this run just
# wrote, projecting per symbol from the i386 witness (the only arch that still records which
# callbacks are stdcall). Without this the slots keep the arch's literal convention, a
# translated `extern "system"` callback will not unify with them, and the standing workaround
# is a transmute that erases the whole fn type. Idempotent — safe to re-run.
#
# This lives in EVERY generator on purpose: normalization that only some of them apply is
# normalization that the next regeneration of any other crate silently undoes.
_isl_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
python3 "${_isl_dir}/../../../../tools/rustconv/normalize_island_abi.py" --apply "${_isl_dir}"
