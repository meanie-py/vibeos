// ---- file-scope preamble (translated) ----
// (no translatable declarations)
#[no_mangle]
pub unsafe extern "C" fn PortCreatePdo(
    FdoDeviceExtension: PFDO_DEVICE_EXTENSION,
    Bus: ULONG,
    Target: ULONG,
    Lun: ULONG,
    PdoDeviceExtension: *mut PPDO_DEVICE_EXTENSION,
) -> NTSTATUS {
    const FILE_DEVICE_MASS_STORAGE: u32 = 0x0000002d;

    let mut DeviceExtension: PPDO_DEVICE_EXTENSION = core::ptr::null_mut();
    let mut Pdo: PDEVICE_OBJECT = core::ptr::null_mut();
    let mut LockHandle: KLOCK_QUEUE_HANDLE = core::mem::zeroed();
    let mut Status: NTSTATUS;

    /* Create the port device */
    Status = IoCreateDevice(
        (*(*FdoDeviceExtension).Device).DriverObject,
        core::mem::size_of::<PDO_DEVICE_EXTENSION>() as ULONG,
        core::ptr::null_mut(),
        FILE_DEVICE_MASS_STORAGE,
        (FILE_DEVICE_SECURE_OPEN | FILE_AUTOGENERATED_DEVICE_NAME) as ULONG,
        0,
        core::ptr::addr_of_mut!(Pdo),
    );
    if !NT_SUCCESS(Status) {
        DbgPrint(
            b"IoCreateDevice() failed (Status 0x%lX)\n\0".as_ptr() as PCSTR,
            Status,
        );
        return Status;
    }

    /* Initialize the device */
    (*Pdo).Flags |= DO_DIRECT_IO as u32;
    (*Pdo).Flags |= DO_POWER_PAGABLE as u32;

    DeviceExtension = (*Pdo).DeviceExtension as PPDO_DEVICE_EXTENSION;
    RtlZeroMemory(
        DeviceExtension as *mut core::ffi::c_void,
        core::mem::size_of::<PDO_DEVICE_EXTENSION>(),
    );

    (*DeviceExtension).ExtensionType = EXTENSION_TYPE_PdoExtension;

    (*DeviceExtension).Device = Pdo;
    (*DeviceExtension).FdoExtension = FdoDeviceExtension;
    (*DeviceExtension).PnpState = dsStopped;

    /* Add the PDO to the PDO list*/
    KeAcquireInStackQueuedSpinLock(
        core::ptr::addr_of_mut!((*FdoDeviceExtension).PdoListLock),
        core::ptr::addr_of_mut!(LockHandle),
    );
    InsertHeadList(
        core::ptr::addr_of_mut!((*FdoDeviceExtension).PdoListHead),
        core::ptr::addr_of_mut!((*DeviceExtension).PdoListEntry),
    );
    (*FdoDeviceExtension).PdoCount = (*FdoDeviceExtension).PdoCount.wrapping_add(1);
    KeReleaseInStackQueuedSpinLock(core::ptr::addr_of_mut!(LockHandle));

    (*DeviceExtension).Bus = Bus;
    (*DeviceExtension).Target = Target;
    (*DeviceExtension).Lun = Lun;

    // FIXME: More initialization

    /* The device has been initialized */
    (*Pdo).Flags &= !DO_DEVICE_INITIALIZING as u32;

    *PdoDeviceExtension = DeviceExtension;

    return STATUS_SUCCESS;
}
#[no_mangle]
pub unsafe extern "C" fn PortDeletePdo(PdoExtension: PPDO_DEVICE_EXTENSION) -> NTSTATUS {
    let mut LockHandle: KLOCK_QUEUE_HANDLE = core::mem::zeroed();

    KeAcquireInStackQueuedSpinLock(
        core::ptr::addr_of_mut!((*(*PdoExtension).FdoExtension).PdoListLock),
        core::ptr::addr_of_mut!(LockHandle),
    );
    RemoveEntryList(core::ptr::addr_of_mut!((*PdoExtension).PdoListEntry));
    (*(*PdoExtension).FdoExtension).PdoCount =
        (*(*PdoExtension).FdoExtension).PdoCount.wrapping_sub(1);
    KeReleaseInStackQueuedSpinLock(core::ptr::addr_of_mut!(LockHandle));

    if !(*PdoExtension).InquiryBuffer.is_null() {
        ExFreePoolWithTag(
            (*PdoExtension).InquiryBuffer as PVOID,
            TAG_INQUIRY_DATA as ULONG,
        );
        (*PdoExtension).InquiryBuffer = core::ptr::null_mut();
    }

    // FIXME: More uninitialization

    IoDeleteDevice((*PdoExtension).Device);

    return STATUS_SUCCESS;
}

#[no_mangle]
pub unsafe extern "system" fn PortPdoScsi(
    mut DeviceObject: PDEVICE_OBJECT,
    mut Irp: PIRP,
) -> NTSTATUS {
    if DbgPrint(
        b"(%s:%d) PortPdoScsi(%p %p)\n\0" as *const u8 as PCSTR,
        b"pdo.c\0" as *const u8 as *const core::ffi::c_char,
        124 as core::ffi::c_int,
        DeviceObject,
        Irp,
    ) != 0
    {
        DbgPrint(
            b"(%s:%d) DbgPrint() failed!\n\0" as *const u8 as PCSTR,
            b"pdo.c\0" as *const u8 as *const core::ffi::c_char,
            124 as core::ffi::c_int,
        );
    }
    (*Irp).IoStatus.Information = 0 as _;
    (*Irp).IoStatus.__bindgen_anon_1.Status = STATUS_SUCCESS;
    IoCompleteRequest(Irp, IO_NO_INCREMENT as CCHAR);
    return STATUS_SUCCESS;
}

