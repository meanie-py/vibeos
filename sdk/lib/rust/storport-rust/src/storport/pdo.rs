unsafe extern "C" fn PdoHandleQueryDeviceText(
    PdoExtension: PPDO_DEVICE_EXTENSION,
    Irp: PIRP,
) -> NTSTATUS {
    let mut IoStack: PIO_STACK_LOCATION;
    let mut Status: NTSTATUS;
    let mut Buffer: PWCHAR;
    let mut CharCount: size_t;

    IoStack = IoGetCurrentIrpStackLocation(Irp);
    'sw: {
        match (*IoStack).Parameters.QueryDeviceText.DeviceTextType as u32 {
            DeviceTextDescription => {
                let mut InquiryData: PINQUIRYDATA;
                let mut DeviceType: PCSTR;
                let mut Offset: ULONG;
                let mut LocalBuffer = [0 as CHAR; (RTL_FIELD_SIZE!(INQUIRYDATA, VendorId)
                    + (core::mem::size_of::<[u8; 2]>() - 1 as usize)
                    + RTL_FIELD_SIZE!(INQUIRYDATA, ProductId)
                    + core::mem::size_of_val(&ANSI_NULL))];

                InquiryData = (*PdoExtension).InquiryBuffer;
                DeviceType = GetDeviceType(InquiryData);

                CharCount = (RTL_FIELD_SIZE!(INQUIRYDATA, VendorId)
                    + (core::mem::size_of::<[u8; 2]>() - 1 as usize)
                    + RTL_FIELD_SIZE!(INQUIRYDATA, ProductId)
                    + (core::mem::size_of::<[u8; 7]>() - 1 as usize)
                    + strlen(DeviceType as *const i8) as usize
                    + (core::mem::size_of::<[u8; 9]>() - 1 as usize)
                    + core::mem::size_of_val(&ANSI_NULL)) as size_t;

                Buffer = ExAllocatePoolUninitialized(
                    PagedPool,
                    ((CharCount as SIZE_T).wrapping_mul(core::mem::size_of::<WCHAR>() as SIZE_T)) as _,
                    TAG_DEVICE_TEXT,
                ) as PWCHAR;
                if Buffer.is_null() {
                    Status = STATUS_INSUFFICIENT_RESOURCES;
                    break 'sw;
                }

                /* Combine VendorId and ProductId, separated by a space */
                Offset = 0;
                Offset = Offset.wrapping_add(CopyField(
                    &raw mut (*InquiryData).VendorId as PUCHAR,
                    (&raw mut LocalBuffer as *mut CHAR).offset(Offset as isize) as PCHAR,
                    RTL_FIELD_SIZE!(INQUIRYDATA, VendorId) as ULONG,
                    b' ' as CHAR,
                    TRUE as BOOLEAN,
                ));
                let idx1 = Offset;
                Offset = Offset.wrapping_add(1);
                LocalBuffer[idx1 as usize] = b' ' as CHAR;
                Offset = Offset.wrapping_add(CopyField(
                    &raw mut (*InquiryData).ProductId as PUCHAR,
                    (&raw mut LocalBuffer as *mut CHAR).offset(Offset as isize) as PCHAR,
                    RTL_FIELD_SIZE!(INQUIRYDATA, ProductId) as ULONG,
                    b' ' as CHAR,
                    TRUE as BOOLEAN,
                ));
                let idx2 = Offset;
                Offset = Offset.wrapping_add(1);
                LocalBuffer[idx2 as usize] = ANSI_NULL as CHAR;

                Status = RtlStringCchPrintfExW!(
                    Buffer as NTSTRSAFE_PWSTR,
                    CharCount,
                    core::ptr::null_mut::<NTSTRSAFE_PWSTR>(),
                    core::ptr::null_mut::<size_t>(),
                    0 as STRSAFE_DWORD,
                    RUSTCONV_WSTR_631230CF15FA.as_ptr() as NTSTRSAFE_PCWSTR,
                    &raw mut LocalBuffer as *mut CHAR,
                    DeviceType,
                );
                ASSERT!(NT_SUCCESS!(Status));

                DPRINT!(b"TextDescription: '%S'\n\0".as_ptr() as *const i8, Buffer);
                break 'sw;
            }

            DeviceTextLocationInformation => {
                CharCount = core::mem::size_of::<[CHAR; 39]>() as usize as size_t;

                Buffer = ExAllocatePoolUninitialized(
                    PagedPool,
                    ((CharCount as SIZE_T).wrapping_mul(core::mem::size_of::<WCHAR>() as SIZE_T)) as _,
                    TAG_DEVICE_TEXT,
                ) as PWCHAR;
                if Buffer.is_null() {
                    Status = STATUS_INSUFFICIENT_RESOURCES;
                    break 'sw;
                }

                Status = RtlStringCchPrintfExW!(
                    Buffer as NTSTRSAFE_PWSTR,
                    CharCount,
                    core::ptr::null_mut::<NTSTRSAFE_PWSTR>(),
                    core::ptr::null_mut::<size_t>(),
                    0 as STRSAFE_DWORD,
                    RUSTCONV_WSTR_01C3B6A20099.as_ptr() as NTSTRSAFE_PCWSTR,
                    (*PdoExtension).Bus,
                    (*PdoExtension).Target,
                    (*PdoExtension).Lun,
                );
                ASSERT!(NT_SUCCESS!(Status));

                DPRINT!(b"TextLocationInformation: '%S'\n\0".as_ptr() as *const i8, Buffer);
                break 'sw;
            }

            _ => {
                Buffer = core::ptr::null_mut::<WCHAR>();
                Status = (*Irp).IoStatus.__bindgen_anon_1.Status;
                break 'sw;
            }
        }
    }

    (*Irp).IoStatus.Information = Buffer as ULONG_PTR;
    return Status;
}

unsafe extern "C" fn PdoHandleDeviceRelations(
    PdoExtension: PPDO_DEVICE_EXTENSION,
    Irp: PIRP,
) -> NTSTATUS {
    let mut deviceRelations: PDEVICE_RELATIONS;
    let ioStack: PIO_STACK_LOCATION = IoGetCurrentIrpStackLocation(Irp);

    // check if relation type is BusRelations
    if (*ioStack).Parameters.QueryDeviceRelations.Type as ::core::ffi::c_uint
        != TargetDeviceRelation as ::core::ffi::c_uint
    {
        // PDO handles only target device relation
        return (*Irp).IoStatus.__bindgen_anon_1.Status;
    }

    deviceRelations = ExAllocatePoolWithTag(
        PagedPool,
        core::mem::size_of::<_DEVICE_RELATIONS>() as SIZE_T,
        TAG_DEVICE_RELATION as ULONG,
    ) as PDEVICE_RELATIONS;
    if deviceRelations.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }

    // initialize device relations
    (*deviceRelations).Count = 1 as ULONG;
    (*deviceRelations).Objects[0 as usize] = (*PdoExtension).Device;
    ObReferenceObject((*PdoExtension).Device as PVOID);

    (*Irp).IoStatus.Information = deviceRelations as ULONG_PTR;
    return STATUS_SUCCESS;
}

#[no_mangle]
pub unsafe extern "system" fn PortPdoPnp(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS {
    let mut Status: NTSTATUS;
    let mut Stack: PIO_STACK_LOCATION;
    let mut DeviceExtension: PPDO_DEVICE_EXTENSION;

    DPRINT1!("PortPdoPnp(%p %p)\n", DeviceObject, Irp);

    DeviceExtension = (*DeviceObject).DeviceExtension as PPDO_DEVICE_EXTENSION;
    ASSERT!((*DeviceExtension).ExtensionType == EXTENSION_TYPE_PdoExtension);

    Stack = IoGetCurrentIrpStackLocation(Irp);

    match (*Stack).MinorFunction {
        IRP_MN_START_DEVICE => {
            // RegistryInitLunKey(lunExt);
            (*DeviceExtension).PnpState = dsStarted;
            Status = STATUS_SUCCESS;
        }
        IRP_MN_REMOVE_DEVICE | IRP_MN_SURPRISE_REMOVAL => {
            (*DeviceExtension).PnpState = if (*Stack).MinorFunction == IRP_MN_REMOVE_DEVICE {
                dsRemoved
            } else {
                dsSurpriseRemoved
            };
            Status = STATUS_SUCCESS;
        }
        IRP_MN_QUERY_CAPABILITIES | IRP_MN_QUERY_REMOVE_DEVICE | IRP_MN_QUERY_STOP_DEVICE => {
            Status = STATUS_SUCCESS;
        }
        IRP_MN_QUERY_DEVICE_RELATIONS => {
            Status = PdoHandleDeviceRelations(DeviceExtension, Irp);
        }
        IRP_MN_QUERY_DEVICE_TEXT => {
            Status = PdoHandleQueryDeviceText(DeviceExtension, Irp);
        }
        IRP_MN_QUERY_ID => {
            DPRINT!(
                "IRP_MN_QUERY_ID IdType %s\n",
                DbgGetDeviceIDString((*Stack).Parameters.QueryId.IdType)
            );

            if (*Stack).Parameters.QueryId.IdType == BusQueryDeviceID {
                Status = PdoHandleQueryDeviceId(DeviceExtension, Irp);
            } else if (*Stack).Parameters.QueryId.IdType == BusQueryHardwareIDs {
                Status = PdoHandleQueryHardwareId(DeviceExtension, Irp);
            } else if (*Stack).Parameters.QueryId.IdType == BusQueryInstanceID {
                Status = PdoHandleQueryInstanceId(DeviceExtension, Irp);
            } else if (*Stack).Parameters.QueryId.IdType == BusQueryCompatibleIDs {
                Status = PdoHandleQueryCompatibleId(DeviceExtension, Irp);
            } else {
                // fallthrough to default
                // do nothing
                Status = (*Irp).IoStatus.__bindgen_anon_1.Status;
            }
        }
        _ => {
            // do nothing
            Status = (*Irp).IoStatus.__bindgen_anon_1.Status;
        }
    }

    if Status != STATUS_PENDING {
        (*Irp).IoStatus.__bindgen_anon_1.Status = Status;
        IoCompleteRequest(Irp, (IO_NO_INCREMENT as i8));
    }

    return Status;
}
