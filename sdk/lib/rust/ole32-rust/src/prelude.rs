//! Shared import surface for the rustconv-translated `ring` modules (ifs,
//! hglobalstream, bindctx, errorinfo, monikers, ole2, clipboard, usrmarshal, …).
//!
//! Each raw translation lands with `use ntdll_sys::nt::*;` plus a per-file
//! `extern "C"` block that hand-declares everything it calls. At integration the
//! header line is swapped for `use crate::prelude::*;` and those blocks are
//! stripped, because they are wrong in two ways that matter:
//!
//!   1. Win32 APIs declared `extern "C"` break i386 (WINAPI is stdcall → `_Foo@N`).
//!      → `crate::win32` re-declares them `extern "system"`.
//!   2. COBJMACRO helpers (`IMalloc_Free`, …) declared as extern *symbols* link to
//!      nothing — in C they were macros, not functions.
//!      → `crate::commacros_gen` (generated by tools/gen_commacros.py from com-sys)
//!        provides them as real inline vtbl calls.
//!
//! What the modules DO keep as `extern` decls: the IID_*/CLSID_* data statics.
//! Those are genuine link-time symbols (uuid.lib + ole32's own guid.c) — see the
//! note in winemacros.rs about why we must not redefine them.
//!
//! com-sys (bindgen over the real SDK COM headers) supplies the interfaces and
//! data types with exact per-arch layouts and calling conventions.
//!
//! NOTE: compobj/marshal do NOT use this prelude — they predate it and carry their
//! own hand-rolled surface. Collapsing them onto com-sys is a queued cleanup.
pub use com_sys::*;

// Base aliases com-sys doesn't re-export under the names the translations use.
