// fdo.c — Rust translation of drivers/bus/pci/fdo.c (PCI device object dispatch
// routines: bus enumeration + PnP/Power IRP dispatch for the functional device
// object). Faithful transliteration; no SEH in this driver. C kept on disk per
// the never-delete rule.
//
// Substrate notes:
//   * `IoCompleteRequest`/`IoCallDriver`/`PoCallDriver`/`PoStartNextPowerIrp`/
//     `ExInterlockedInsertTailList` come from `ntkrnl_sys::driver_ddk` (macros /
//     fastcall thunks bindgen does not emit under these names).
//   * `IoGetCurrentIrpStackLocation`/`IoSkipCurrentIrpStackLocation`/
//     `ObReferenceObject` are inline DDK helpers → `ntkrnl_sys::inline::tier1`.
//   * `InitializeListHead` is `ntkrnl_sys::base`.
//   * Cross-file callees (the PciCreate*String builders) live in pci.c-now-pci.rs;
//     declared in an `extern "system" {}` block with the pci.h signatures.
//   * `PCI_COMMON_CONFIG` is OPAQUE in bindgen (`[UCHAR; 192]`), so the C field
//     reads `PciConfig.VendorID`/`.DeviceID`/`.HeaderType`/`.BaseClass`/`.SubClass`
//     are done by overlaying `PCI_COMMON_HEADER` over the start of the buffer
//     (`as *const PCI_COMMON_HEADER`). See TODO note in the summary.

