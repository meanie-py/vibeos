unsafe fn FdoLocateChildDevice(
    Device: *mut PPCI_DEVICE,
    DeviceExtension: PFDO_DEVICE_EXTENSION,
    SlotNumber: PCI_SLOT_NUMBER,
    PciConfig: *const PCI_COMMON_CONFIG,
) -> NTSTATUS {
    let mut current_entry = (*DeviceExtension).DeviceListHead.Flink;
    let list_head = &mut (*DeviceExtension).DeviceListHead as *mut _;

    while current_entry != list_head {
        // CONTAINING_RECORD(CurrentEntry, PCI_DEVICE, ListEntry)
        let current_device = (current_entry as *mut u8)
            .sub(offset_of!(PCI_DEVICE, ListEntry)) as PPCI_DEVICE;

        let cfg_hdr = pci_hdr(PciConfig);
        let cur_hdr = pci_hdr(&(*current_device).PciConfig as *const PCI_COMMON_CONFIG);

        // If both vendor ID and device ID match, it is the same device.
        if (*cfg_hdr).VendorID == (*cur_hdr).VendorID
            && (*cfg_hdr).DeviceID == (*cur_hdr).DeviceID
            && SlotNumber.u.AsULONG == (*current_device).SlotNumber.u.AsULONG
        {
            *Device = current_device;
            return STATUS_SUCCESS;
        }

        current_entry = (*current_entry).Flink;
    }

    *Device = core::ptr::null_mut();
    STATUS_UNSUCCESSFUL
}

unsafe fn PciIsDebuggingDevice(Bus: ULONG, SlotNumber: PCI_SLOT_NUMBER) -> bool {
    if HasDebuggingDevice == 0 {
        return false;
    }

    // Raw-pointer walk over the `static mut PciDebuggingDevice` array (avoids
    // taking a reference to a static mut — static_mut_refs lint).
    let base = core::ptr::addr_of!(PciDebuggingDevice) as *const crate::shared::PCI_TYPE1_CFG_CYCLE_BITS;
    // RTL_NUMBER_OF(PciDebuggingDevice) == 2 (shared::PciDebuggingDevice: [_; 2]).
    let count = 2usize;
    for i in 0..count {
        let dbg = &*base.add(i);
        if dbg.InUse() != 0
            && dbg.BusNumber() == Bus
            && dbg.DeviceNumber() == SlotNumber.u.bits.DeviceNumber()
            && dbg.FunctionNumber() == SlotNumber.u.bits.FunctionNumber()
        {
            return true;
        }
    }

    false
}

unsafe fn FdoEnumerateDevices(DeviceObject: PDEVICE_OBJECT) -> NTSTATUS {
    let device_extension = (*DeviceObject).DeviceExtension as PFDO_DEVICE_EXTENSION;

    (*device_extension).DeviceListCount = 0;

    let mut pci_config: PCI_COMMON_CONFIG = core::mem::zeroed();
    let mut slot_number: PCI_SLOT_NUMBER = core::mem::zeroed();

    // Enumerate devices on the PCI bus.
    slot_number.u.AsULONG = 0;
    for device_number in 0..PCI_MAX_DEVICES {
        slot_number.u.bits.set_DeviceNumber(device_number);
        for function_number in 0..PCI_MAX_FUNCTION {
            slot_number.u.bits.set_FunctionNumber(function_number);

            core::ptr::write_bytes(
                &mut pci_config as *mut PCI_COMMON_CONFIG,
                0,
                1,
            );

            let size = HalGetBusData(
                PCI_CONFIGURATION,
                (*device_extension).BusNumber,
                slot_number.u.AsULONG,
                &mut pci_config as *mut PCI_COMMON_CONFIG as *mut core::ffi::c_void,
                PCI_COMMON_HDR_LENGTH,
            );

            let cfg_hdr = pci_hdr(&pci_config as *const PCI_COMMON_CONFIG);

            if size != PCI_COMMON_HDR_LENGTH
                || (*cfg_hdr).VendorID == PCI_INVALID_VENDORID
                || (*cfg_hdr).VendorID == 0
            {
                if function_number == 0 {
                    break;
                } else {
                    continue;
                }
            }

            // arm64/QEMU-virt: ArmVirt EDK2 never writes the PCI Interrupt Line
            // register (it stays 0), but the virt board's GPEX INTx routing is
            // fixed: INTA..INTD -> GIC INTIDs 35..38, standard bridge swizzle
            // by device number ((slot + pin) % 4, pin 0-based). Synthesize the
            // line here so the PDO's boot config carries a real, translatable
            // vector (HalGetInterruptVector on arm64 is INTID passthrough).
            // Without this the interrupt requirement is unconstrained (0..0xFF),
            // the arbiter picks 0, and resource translation fails 0xC0000001.
            #[cfg(target_arch = "aarch64")]
            {
                let hdr_type = pci_config.Header.HeaderType;
                if (hdr_type & 0x7F) == 0 {
                    let pin = pci_config.Header.u.type0.InterruptPin; // 1-based, INTA=1
                    let line = pci_config.Header.u.type0.InterruptLine;
                    if pin >= 1 && pin <= 4 && (line == 0 || line == 0xFF) {
                        let mut synthesized: u8 =
                            35 + ((device_number as u8 + (pin - 1)) % 4);
                        pci_config.Header.u.type0.InterruptLine = synthesized;
                        // Persist to config space (offset 0x3C is a scratch
                        // register) — PdoQueryResources RE-READS live config,
                        // so patching only our cached copy is not enough.
                        HalSetBusDataByOffset(
                            PCI_CONFIGURATION,
                            (*device_extension).BusNumber,
                            slot_number.u.AsULONG,
                            &mut synthesized as *mut u8 as *mut core::ffi::c_void,
                            0x3C, // FIELD_OFFSET(PCI_COMMON_HEADER, u.type0.InterruptLine)
                            1,
                        );
                    }
                }
            }

            // xHCI early quiesce: mask the controller's INTx (COMMAND bit 10,
            // Interrupt Disable) until its driver has reset it. Firmware can hand
            // over an xHCI still asserting its level-triggered line (UEFI's own
            // USB stack ran it), and usbport connects the interrupt before it
            // starts the miniport, so an unmaskable line storms the CPU before
            // anyone can quiet the controller. usbxhci clears the bit after its
            // reset. Linux does the equivalent in quirk_usb_handoff_xhci.
            // PdoStartDevice ORs its enables into this cached Command, so the
            // bit survives device start.
            if pci_config.Header.BaseClass == PCI_CLASS_SERIAL_BUS_CTLR
                && pci_config.Header.SubClass == 0x03
                && pci_config.Header.ProgIf == 0x30
            {
                let mut command: u16 = pci_config.Header.Command | 0x0400;
                pci_config.Header.Command = command;
                HalSetBusDataByOffset(
                    PCI_CONFIGURATION,
                    (*device_extension).BusNumber,
                    slot_number.u.AsULONG,
                    &mut command as *mut u16 as *mut core::ffi::c_void,
                    0x04, // FIELD_OFFSET(PCI_COMMON_HEADER, Command)
                    2,
                );
            }

            let mut device: PPCI_DEVICE = core::ptr::null_mut();
            let status =
                FdoLocateChildDevice(&mut device, device_extension, slot_number, &pci_config);
            if !nt_success(status) {
                device = ExAllocatePoolWithTag(
                    PCI_CONFIGURATION_POOL_NONPAGED,
                    core::mem::size_of::<PCI_DEVICE>() as _,
                    TAG_PCI,
                ) as PPCI_DEVICE;
                if device.is_null() {
                    /* FIXME: Cleanup resources for already discovered devices */
                    return STATUS_INSUFFICIENT_RESOURCES;
                }

                core::ptr::write_bytes(device, 0, 1);

                (*device).BusNumber = (*device_extension).BusNumber;

                if PciIsDebuggingDevice((*device_extension).BusNumber, slot_number) {
                    (*device).IsDebuggingDevice = 1; // TRUE

                    /*
                     * ReactOS-specific: apply a hack to prevent driver
                     * installation for the debugging device. Nothing to do for
                     * IEEE 1394 devices; NT5.1/5.2 support 1394 debugging.
                     * FIXME: set CM_PROB_USED_BY_DEBUGGER instead.
                     */
                    if (*cfg_hdr).BaseClass != PCI_CLASS_SERIAL_BUS_CTLR
                        || (*cfg_hdr).SubClass != PCI_SUBCLASS_SB_IEEE1394
                    {
                        // PciConfig.VendorID = 0xDEAD; PciConfig.DeviceID = 0xBEEF;
                        let cfg_hdr_mut =
                            &mut pci_config as *mut PCI_COMMON_CONFIG as *mut PCI_COMMON_HEADER;
                        (*cfg_hdr_mut).VendorID = 0xDEAD;
                        (*cfg_hdr_mut).DeviceID = 0xBEEF;
                    }
                }

                // RtlCopyMemory(&Device->SlotNumber, &SlotNumber, sizeof(PCI_SLOT_NUMBER));
                (*device).SlotNumber = slot_number;

                // RtlCopyMemory(&Device->PciConfig, &PciConfig, sizeof(PCI_COMMON_CONFIG));
                (*device).PciConfig = pci_config;

                ExInterlockedInsertTailList(
                    &mut (*device_extension).DeviceListHead,
                    &mut (*device).ListEntry,
                    &mut (*device_extension).DeviceListLock,
                );
            }

            (*device_extension).DeviceListCount += 1;

            // Skip to next device if the current one is not multifunction.
            if function_number == 0 && ((*cfg_hdr).HeaderType & 0x80) == 0 {
                break;
            }
        }
    }

    STATUS_SUCCESS
}

unsafe fn FdoQueryBusRelations(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
    _IrpSp: PIO_STACK_LOCATION,
) -> NTSTATUS {
    let mut pdo_device_extension: PPDO_DEVICE_EXTENSION = core::ptr::null_mut();

    let mut error_status: NTSTATUS = STATUS_INSUFFICIENT_RESOURCES;
    let mut status: NTSTATUS = STATUS_SUCCESS;
    let mut error_occurred = false;

    FdoEnumerateDevices(DeviceObject);

    let device_extension = (*DeviceObject).DeviceExtension as PFDO_DEVICE_EXTENSION;

    if (*Irp).IoStatus.Information != 0 {
        /* FIXME: Another bus driver already created a DEVICE_RELATIONS structure
                  so we must merge this structure with our own */
        DPRINT1!("FIXME: leaking old bus relations\n");
    }

    // Size = sizeof(DEVICE_RELATIONS) + sizeof(Relations->Objects) * (Count - 1)
    // Objects is PDEVICE_OBJECT[1].
    let size = core::mem::size_of::<DEVICE_RELATIONS>()
        + core::mem::size_of::<PDEVICE_OBJECT>()
            * ((*device_extension).DeviceListCount as usize - 1);

    let relations =
        ExAllocatePoolWithTag(PCI_CONFIGURATION_POOL_PAGED, size as _, TAG_PCI) as *mut DEVICE_RELATIONS;
    if relations.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }

    (*relations).Count = (*device_extension).DeviceListCount;

    let mut i: usize = 0;
    let mut current_entry = (*device_extension).DeviceListHead.Flink;
    let list_head = &mut (*device_extension).DeviceListHead as *mut _;

    while current_entry != list_head {
        let device = (current_entry as *mut u8)
            .sub(offset_of!(PCI_DEVICE, ListEntry)) as PPCI_DEVICE;

        pdo_device_extension = core::ptr::null_mut();

        if (*device).Pdo.is_null() {
            // Create a PDO for the device as it does not already have one.
            status = IoCreateDevice(
                (*DeviceObject).DriverObject,
                core::mem::size_of::<crate::shared::PDO_DEVICE_EXTENSION>() as ULONG,
                core::ptr::null_mut(),
                FILE_DEVICE_CONTROLLER,
                FILE_AUTOGENERATED_DEVICE_NAME,
                0, // FALSE
                &mut (*device).Pdo,
            );
            if !nt_success(status) {
                error_status = status;
                error_occurred = true;
                break;
            }

            (*(*device).Pdo).Flags &= !DO_DEVICE_INITIALIZING;
            // (*device).Pdo->Flags |= DO_POWER_PAGABLE; (left commented in C)

            pdo_device_extension =
                (*(*device).Pdo).DeviceExtension as PPDO_DEVICE_EXTENSION;

            core::ptr::write_bytes(pdo_device_extension, 0, 1);

            (*pdo_device_extension).Common.IsFDO = 0; // FALSE
            (*pdo_device_extension).Common.DeviceObject = (*device).Pdo;
            (*pdo_device_extension).Common.DevicePowerState = POWER_DEVICE_D0;
            (*pdo_device_extension).Fdo = DeviceObject;
            (*pdo_device_extension).PciDevice = device;

            // Add Device ID string.
            status = PciCreateDeviceIDString(&mut (*pdo_device_extension).DeviceID, device);
            if !nt_success(status) {
                error_status = status;
                error_occurred = true;
                break;
            }

            // Add Instance ID string.
            status =
                PciCreateInstanceIDString(&mut (*pdo_device_extension).InstanceID, device);
            if !nt_success(status) {
                error_status = status;
                error_occurred = true;
                break;
            }

            // Add Hardware IDs string.
            status =
                PciCreateHardwareIDsString(&mut (*pdo_device_extension).HardwareIDs, device);
            if !nt_success(status) {
                error_status = status;
                error_occurred = true;
                break;
            }

            // Add Compatible IDs string.
            status = PciCreateCompatibleIDsString(
                &mut (*pdo_device_extension).CompatibleIDs,
                device,
            );
            if !nt_success(status) {
                error_status = status;
                error_occurred = true;
                break;
            }

            // Add device description string.
            status = PciCreateDeviceDescriptionString(
                &mut (*pdo_device_extension).DeviceDescription,
                device,
            );
            if !nt_success(status) {
                error_status = status;
                error_occurred = true;
                break;
            }

            // Add device location string.
            status = PciCreateDeviceLocationString(
                &mut (*pdo_device_extension).DeviceLocation,
                device,
            );
            if !nt_success(status) {
                error_status = status;
                error_occurred = true;
                break;
            }
        }

        // Reference the PDO; the PnP manager dereferences it when done.
        ObReferenceObject((*device).Pdo as *mut core::ffi::c_void);

        // Relations->Objects[i] = Device->Pdo;  (flexible array — pointer arith)
        let objects = core::ptr::addr_of_mut!((*relations).Objects) as *mut PDEVICE_OBJECT;
        objects.add(i).write((*device).Pdo);

        i += 1;
        current_entry = (*current_entry).Flink;
    }

    if error_occurred {
        /* FIXME: Cleanup all new PDOs created in this call. */
        /* FIXME: Should IoAttachDeviceToDeviceStack() be undone? */
        if !pdo_device_extension.is_null() {
            RtlFreeUnicodeString(&mut (*pdo_device_extension).DeviceID);
            RtlFreeUnicodeString(&mut (*pdo_device_extension).InstanceID);
            RtlFreeUnicodeString(&mut (*pdo_device_extension).HardwareIDs);
            RtlFreeUnicodeString(&mut (*pdo_device_extension).CompatibleIDs);
            RtlFreeUnicodeString(&mut (*pdo_device_extension).DeviceDescription);
            RtlFreeUnicodeString(&mut (*pdo_device_extension).DeviceLocation);
        }

        ExFreePoolWithTag(relations as *mut core::ffi::c_void, TAG_PCI);
        return error_status;
    }

    (*Irp).IoStatus.Information = relations as ULONG_PTR;

    status
}

unsafe fn FdoStartDevice(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS {
    let device_extension = (*DeviceObject).DeviceExtension as PFDO_DEVICE_EXTENSION;

    let allocated_resources: PCM_RESOURCE_LIST = (*IoGetCurrentIrpStackLocation(Irp))
        .Parameters
        .StartDevice
        .AllocatedResources;
    if allocated_resources.is_null() || (*allocated_resources).Count < 1 {
        // A statically root-enumerated host bridge (arm64: hivesys_arm64.inf
        // seeds Enum\Root\*PNP0A03 — no ACPI, so no _CRS bus-number resource)
        // arrives with no resource list at all. Default to bus 0 instead of
        // failing: config access goes through HalGetBusData (ECAM on arm64),
        // which needs only the bus number. x86 always gets resources from
        // acpi.sys, so this branch never runs there.
        ntkrnl_sys::driver_ddk::DbgPrint(
            b"[PCI] FdoStartDevice: no bus-number resource (root-seeded bridge?) - defaulting to bus 0\n\0"
                .as_ptr() as *const i8,
        );
        ntkrnl_sys::ASSERT!((*device_extension).State == dsStopped);
        (*device_extension).BusNumber = 0;
    } else {
        // AllocatedResources->List[0] — List is CM_FULL_RESOURCE_DESCRIPTOR[1].
        let list0 = core::ptr::addr_of_mut!((*allocated_resources).List)
            as *mut ntkrnl_sys::ddk::CM_FULL_RESOURCE_DESCRIPTOR;
        let partial_list = core::ptr::addr_of_mut!((*list0).PartialResourceList);

        if (*partial_list).Version != 1 || (*partial_list).Revision != 1 {
            return STATUS_REVISION_MISMATCH;
        }

        ntkrnl_sys::ASSERT!((*device_extension).State == dsStopped);

        // By default, use the bus number in the resource list header.
        (*device_extension).BusNumber = (*list0).BusNumber;

        let mut found_bus_number = false;
        for i in 0..(*partial_list).Count {
            // ResourceDescriptor = &...PartialDescriptors[i]  ([T; 1] — pointer arith)
            let descriptors = core::ptr::addr_of_mut!((*partial_list).PartialDescriptors)
                as *mut ntkrnl_sys::ddk::CM_PARTIAL_RESOURCE_DESCRIPTOR;
            let resource_descriptor = descriptors.add(i as usize);

            match (*resource_descriptor).Type {
                x if x == CmResourceTypeBusNumber => {
                    let bus = (*resource_descriptor).u.BusNumber;
                    if found_bus_number || bus.Length < 1 {
                        return STATUS_INVALID_PARAMETER;
                    }

                    // Use this one instead.
                    ntkrnl_sys::ASSERT!((*list0).BusNumber == bus.Start);
                    (*device_extension).BusNumber = bus.Start;
                    found_bus_number = true;
                }
                _ => {
                    // DPRINT("Unknown resource descriptor type 0x%x\n", ...);
                }
            }
        }
    }

    InitializeListHead(&mut (*device_extension).DeviceListHead);
    // KSPIN_LOCK (ddk ULONG) vs the inline's *mut ULONG_PTR (usize) — same width
    // per arch, distinct nominal types; cast at the boundary.
    KeInitializeSpinLock((&mut (*device_extension).DeviceListLock as *mut _) as *mut usize);
    (*device_extension).DeviceListCount = 0;
    (*device_extension).State = dsStarted;

    crate::irqroute::fdo_query_routing(DeviceObject);

    ExInterlockedInsertTailList(
        &mut (*DriverExtension).BusListHead,
        &mut (*device_extension).ListEntry,
        &mut (*DriverExtension).BusListLock,
    );

    (*Irp).IoStatus.Information = 0;

    STATUS_SUCCESS
}

