/// FUNCTION: Handle Plug and Play IRPs for the PCI device object.
#[no_mangle]
pub unsafe extern "system" fn FdoPnpControl(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS {
    let device_extension = (*DeviceObject).DeviceExtension as PFDO_DEVICE_EXTENSION;

    let mut status: NTSTATUS = (*Irp).IoStatus.__bindgen_anon_1.Status;

    let irp_sp = IoGetCurrentIrpStackLocation(Irp);
    match (*irp_sp).MinorFunction {
        // #if 0 cases (CANCEL_REMOVE/CANCEL_STOP/DEVICE_USAGE_NOTIFICATION/
        // FILTER_RESOURCE_REQUIREMENTS-as-NOT_IMPLEMENTED, QUERY_PNP_DEVICE_STATE,
        // QUERY_REMOVE_DEVICE, SURPRISE_REMOVAL) are disabled in C — dropped.
        IRP_MN_QUERY_DEVICE_RELATIONS => {
            if (*irp_sp).Parameters.QueryDeviceRelations.Type as ULONG != BUS_RELATIONS {
                // break — fall through to forward-down-the-stack tail.
            } else {
                status = FdoQueryBusRelations(DeviceObject, Irp, irp_sp);
                (*Irp).IoStatus.__bindgen_anon_1.Status = status;
                IoCompleteRequest(Irp, IO_NO_INCREMENT);
                return status;
            }
        }

        IRP_MN_START_DEVICE => {
            status = STATUS_UNSUCCESSFUL;

            if IoForwardIrpSynchronously((*device_extension).Ldo, Irp) != 0 {
                status = (*Irp).IoStatus.__bindgen_anon_1.Status;
                if nt_success(status) {
                    status = FdoStartDevice(DeviceObject, Irp);
                }
            }

            (*Irp).IoStatus.__bindgen_anon_1.Status = status;
            IoCompleteRequest(Irp, IO_NO_INCREMENT);
            return status;
        }

        IRP_MN_QUERY_STOP_DEVICE => {
            // We don't support stopping yet.
            status = STATUS_UNSUCCESSFUL;
            (*Irp).IoStatus.__bindgen_anon_1.Status = status;
            IoCompleteRequest(Irp, IO_NO_INCREMENT);
            return status;
        }

        IRP_MN_STOP_DEVICE => {
            // We can't fail this one so we fail the preceding QUERY_STOP. break.
        }

        IRP_MN_FILTER_RESOURCE_REQUIREMENTS => {
            // break.
        }

        IRP_MN_REMOVE_DEVICE => {
            // Detach the device object from the device stack.
            IoDetachDevice((*device_extension).Ldo);
            // Delete the device object.
            IoDeleteDevice(DeviceObject);
            // Return success.
            status = STATUS_SUCCESS;
        }

        IRP_MN_QUERY_CAPABILITIES | IRP_MN_QUERY_PNP_DEVICE_STATE => {
            // Don't print the warning, too much noise. break.
        }

        _ => {
            DPRINT1!("Unknown PNP minor function 0x%x\n", (*irp_sp).MinorFunction as core::ffi::c_uint);
        }
    }

    (*Irp).IoStatus.__bindgen_anon_1.Status = status;
    IoSkipCurrentIrpStackLocation(Irp);
    status = IoCallDriver((*device_extension).Ldo, Irp);

    status
}

/// FUNCTION: Handle power management IRPs for the PCI device object.
#[no_mangle]
pub unsafe extern "system" fn FdoPowerControl(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
) -> NTSTATUS {
    let device_extension = (*DeviceObject).DeviceExtension as PFDO_DEVICE_EXTENSION;

    PoStartNextPowerIrp(Irp);
    IoSkipCurrentIrpStackLocation(Irp);
    PoCallDriver((*device_extension).Ldo, Irp)
}

