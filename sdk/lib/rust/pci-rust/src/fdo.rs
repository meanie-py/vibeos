const PCI_MAX_DEVICES: ULONG = 32;
const PCI_MAX_FUNCTION: ULONG = 8;
const PCI_COMMON_HDR_LENGTH: ULONG = 64; // FIELD_OFFSET(PCI_COMMON_CONFIG, DeviceSpecific)
const PCI_INVALID_VENDORID: u16 = 0xFFFF;
const PCI_CLASS_SERIAL_BUS_CTLR: u8 = 0x0c;
const PCI_SUBCLASS_SB_IEEE1394: u8 = 0x00;

const FILE_DEVICE_CONTROLLER: ULONG = 0x00000004;
const CmResourceTypeBusNumber: u8 = 6;

// IRP_MN_* not present in driver_ddk (PnP minor codes).
const IRP_MN_QUERY_CAPABILITIES: u8 = 0x09;
const IRP_MN_FILTER_RESOURCE_REQUIREMENTS: u8 = 0x0D;
const IRP_MN_QUERY_PNP_DEVICE_STATE: u8 = 0x14;

// DEVICE_OBJECT.Flags (xdk/iotypes.h).
const DO_DEVICE_INITIALIZING: ULONG = 0x00000080;

// DEVICE_RELATION_TYPE::BusRelations (bindgen enum value 0, c_uint).
const BUS_RELATIONS: u32 = 0;

// BUS_DATA_TYPE::PCIConfiguration (bindgen enum value 4, c_int).
const PCI_CONFIGURATION: i32 = 4;

// DEVICE_POWER_STATE::PowerDeviceD0 (bindgen enum value 1, c_uint).
const POWER_DEVICE_D0: u32 = 1;

// NTSTATUS codes.
const STATUS_SUCCESS: NTSTATUS = 0;
const STATUS_UNSUCCESSFUL: NTSTATUS = 0xC0000001_u32 as i32;
const STATUS_INSUFFICIENT_RESOURCES: NTSTATUS = 0xC000009A_u32 as i32;
const STATUS_REVISION_MISMATCH: NTSTATUS = 0xC0000059_u32 as i32;
const STATUS_INVALID_PARAMETER: NTSTATUS = 0xC000000D_u32 as i32;

const IO_NO_INCREMENT: i8 = 0;

#[inline]
fn nt_success(status: NTSTATUS) -> bool {
    status >= 0
}

// Overlay the (opaque) PCI_COMMON_CONFIG buffer with the real PCI_COMMON_HEADER
// layout so the C field reads (VendorID/DeviceID/HeaderType/BaseClass/SubClass)
// resolve. The header occupies the first 64 bytes of the 192/256-byte config.
#[inline]
unsafe fn pci_hdr(config: *const PCI_COMMON_CONFIG) -> *const PCI_COMMON_HEADER {
    config as *const PCI_COMMON_HEADER
}

