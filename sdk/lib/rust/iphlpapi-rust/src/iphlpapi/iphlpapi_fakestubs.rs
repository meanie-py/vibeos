//! `iphlpapi_fakestubs.c` — the 16 `Pf*` packet-filter exports.
//!
//! HAND-WRITTEN, not LLM-translated, deliberately: all 16 C bodies are byte-identical
//! (`UNIMPLEMENTED; return ERROR_CALL_NOT_IMPLEMENTED;`), so a paid per-function pass buys
//! nothing over transcribing the signatures exactly. (The first two below ARE the machine
//! translation's output, kept verbatim — they agree with the hand transcription.)
//!
//! WHY THIS FILE EXISTS UPSTREAM (CORE-8462 / CORE-15665): iphlpapi.spec exports these with
//! the i386 stdcall decoration written out LITERALLY —
//!     @ stdcall _PfAddFiltersToInterface@24()
//! — because autogenerated stubs would lose the decoration, so real WINAPI definitions have
//! to exist to supply those decorated symbols. `extern "system"` reproduces exactly what the
//! C compiler emitted per arch: `_Name@N` on i386, the plain name on amd64/arm64. Every arg
//! count below was checked against its spec `@N` (PfSetLogBuffer 7 args → @28,
//! PfDeleteLog VOID → @0, PfCreateInterface 6 → @24, ...).
//!
//! SCANNER NOTE — this file cost a near-miss worth recording: 14 of the 16 are invisible to
//! the rustconv scanner, because they are declared via `PFAPIENTRY`, a macro expanding to
//! `EXTERNCDECL DWORD PFEXPORT WINAPI` — return type AND calling convention in one token the
//! parser cannot see through. A `translate` run therefore emitted 2/16 and exited 0. The
//! spec cross-check built to catch exactly that was itself defeated, because it compared the
//! PRE-DECORATED spec names (`_PfDeleteLog@0`) against the undecorated C definitions and
//! found no overlap. Both are fixed: `_exports_lost_to_unextracted` now also tries the
//! undecorated form and hard-fails (rustconv/__main__.py).
use crate::prelude::*;

/// `UNIMPLEMENTED` (reactos/debug.h) is `__NOTICE(WARNING, "is UNIMPLEMENTED!\n")` — a
/// DbgPrint that FALLS THROUGH; it neither blocks nor returns. Kept as a macro and never an
/// out-of-line no-op fn: an out-of-line no-op is an optimization barrier that uncloaks
/// latent ABI mismatches into `ud2` (field manual §9.65). Compare the dhcpcsvc bug where the
/// same macro was translated as `loop {}` and hung the caller forever.
macro_rules! UNIMPLEMENTED {
    () => {};
}

