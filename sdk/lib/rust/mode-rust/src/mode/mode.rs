    let mut buffer: [WCHAR; 250] = [0; 250];
    let mut szPortName: [WCHAR; MAX_PORTNAME_LEN] = [0; MAX_PORTNAME_LEN];

    _swprintf(
        core::ptr::addr_of_mut!(szPortName) as *mut WCHAR,
        RUSTCONV_WSTR_6E5848CFDF88.as_ptr(),
        nPortNum,
    );

    ConPuts(StdOut, RUSTCONV_WSTR_075DE2B906DB.as_ptr());
    UnderlinedResPrintf(
        StdOut,
        IDS_DEVICE_STATUS_HEADER,
        core::ptr::addr_of_mut!(szPortName) as *mut WCHAR,
    );
    ConPuts(StdOut, RUSTCONV_WSTR_075DE2B906DB.as_ptr());

    if QueryDosDeviceW(
        core::ptr::addr_of_mut!(szPortName) as *mut WCHAR,
        core::ptr::addr_of_mut!(buffer) as *mut WCHAR,
        ARRAYSIZE!(buffer),
    ) != 0
    {
        let mut ptr: PWSTR = wcsrchr(
            core::ptr::addr_of_mut!(buffer) as *mut WCHAR,
            0x005Cu16,
        ) as PWSTR;
        if !ptr.is_null() {
            ptr = ptr.add(1);
            if _wcsicmp(
                core::ptr::addr_of_mut!(szPortName) as *mut WCHAR,
                ptr as *const WCHAR,
            ) == 0
            {
                ConResPuts(StdOut, IDS_PRINTER_OUTPUT_NOT_REROUTED);
            } else {
                ConResPrintf(StdOut, IDS_PRINTER_OUTPUT_REROUTED_SERIAL, ptr);
            }

            return 0;
        } else {
            ConResPrintf(
                StdErr,
                IDS_ERROR_QUERY_DEVICES_FORM,
                core::ptr::addr_of_mut!(szPortName) as *mut WCHAR,
                core::ptr::addr_of_mut!(buffer) as *mut WCHAR,
            );
        }
    } else {
        ConPrintf(
            StdErr,
            RUSTCONV_WSTR_EE1D44D5055F.as_ptr(),
            core::ptr::addr_of_mut!(szPortName) as *mut WCHAR,
            GetLastError(),
        );
    }
    ConPuts(StdOut, RUSTCONV_WSTR_075DE2B906DB.as_ptr());

    return 1;
