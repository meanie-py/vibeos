    _swprintf(
        addr_of_mut!(szPortName) as *mut WCHAR,
        RUSTCONV_WSTR_527F599AE3B6.as_ptr(),
        nPortNum,
    );

    ConPuts(core::ptr::addr_of_mut!(csStdOut), RUSTCONV_WSTR_075DE2B906DB.as_ptr());
    UnderlinedResPrintf(
        core::ptr::addr_of_mut!(csStdOut),
        IDS_DEVICE_STATUS_HEADER,
        addr_of_mut!(szPortName) as *mut WCHAR,
    );
