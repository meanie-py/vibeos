//! samsrv constants the translations reference: resource string IDs, SAM/domain
//! access bits (ntsam.h), and the few NTSTATUS codes absent from ntdll_sys::nt.
//! Grown from the C headers during integration (mirror lsasrv-rust/src/consts.rs).
//! Values verified against sdk/include/ddk/ntsam.h, sdk/include/.../winnt.h,
//! dll/win32/samsrv/{samsrv.h,resources.h}, ntsecapi.h and ntstatus.h.
#![allow(non_upper_case_globals, dead_code)]

use ntdll_sys::nt::{ACCESS_MASK, NTSTATUS, ULONG};
// Standard rights (winnt.h) used to compose the SAM access masks — private use
// of ntdll_sys::nt's definitions (re-defining them here collides with the
// prelude's `ntdll_sys::nt::*` glob → E0659).
use ntdll_sys::nt::{
    STANDARD_RIGHTS_EXECUTE, STANDARD_RIGHTS_READ, STANDARD_RIGHTS_REQUIRED, STANDARD_RIGHTS_WRITE,
};

// ---- SAM server access bits (ntsam.h) ----
pub const SAM_SERVER_CONNECT: ACCESS_MASK = 0x00000001;
pub const SAM_SERVER_SHUTDOWN: ACCESS_MASK = 0x00000002;
pub const SAM_SERVER_INITIALIZE: ACCESS_MASK = 0x00000004;
pub const SAM_SERVER_CREATE_DOMAIN: ACCESS_MASK = 0x00000008;
pub const SAM_SERVER_ENUMERATE_DOMAINS: ACCESS_MASK = 0x00000010;
pub const SAM_SERVER_LOOKUP_DOMAIN: ACCESS_MASK = 0x00000020;
pub const SAM_SERVER_ALL_ACCESS: ACCESS_MASK = STANDARD_RIGHTS_REQUIRED
    | SAM_SERVER_CONNECT
    | SAM_SERVER_SHUTDOWN
    | SAM_SERVER_INITIALIZE
    | SAM_SERVER_CREATE_DOMAIN
    | SAM_SERVER_ENUMERATE_DOMAINS
    | SAM_SERVER_LOOKUP_DOMAIN;

// ---- Domain access bits (ntsam.h) ----
pub const DOMAIN_READ_PASSWORD_PARAMETERS: ACCESS_MASK = 0x00000001;
pub const DOMAIN_WRITE_PASSWORD_PARAMS: ACCESS_MASK = 0x00000002;
pub const DOMAIN_READ_OTHER_PARAMETERS: ACCESS_MASK = 0x00000004;
pub const DOMAIN_WRITE_OTHER_PARAMETERS: ACCESS_MASK = 0x00000008;
pub const DOMAIN_CREATE_USER: ACCESS_MASK = 0x00000010;
pub const DOMAIN_CREATE_GROUP: ACCESS_MASK = 0x00000020;
pub const DOMAIN_CREATE_ALIAS: ACCESS_MASK = 0x00000040;
pub const DOMAIN_GET_ALIAS_MEMBERSHIP: ACCESS_MASK = 0x00000080;
pub const DOMAIN_LIST_ACCOUNTS: ACCESS_MASK = 0x00000100;
pub const DOMAIN_LOOKUP: ACCESS_MASK = 0x00000200;
pub const DOMAIN_ADMINISTER_SERVER: ACCESS_MASK = 0x00000400;
pub const DOMAIN_READ: ACCESS_MASK =
    STANDARD_RIGHTS_READ | DOMAIN_READ_OTHER_PARAMETERS | DOMAIN_GET_ALIAS_MEMBERSHIP;
pub const DOMAIN_EXECUTE: ACCESS_MASK = STANDARD_RIGHTS_EXECUTE
    | DOMAIN_READ_PASSWORD_PARAMETERS
    | DOMAIN_LIST_ACCOUNTS
    | DOMAIN_LOOKUP;

// ---- Group access bits (ntsam.h) ----
pub const GROUP_READ_INFORMATION: ACCESS_MASK = 0x00000001;
pub const GROUP_WRITE_ACCOUNT: ACCESS_MASK = 0x00000002;
pub const GROUP_ADD_MEMBER: ACCESS_MASK = 0x00000004;
pub const GROUP_REMOVE_MEMBER: ACCESS_MASK = 0x00000008;
pub const GROUP_LIST_MEMBERS: ACCESS_MASK = 0x00000010;
pub const GROUP_ALL_ACCESS: ACCESS_MASK = STANDARD_RIGHTS_REQUIRED
    | GROUP_READ_INFORMATION
    | GROUP_WRITE_ACCOUNT
    | GROUP_ADD_MEMBER
    | GROUP_REMOVE_MEMBER
    | GROUP_LIST_MEMBERS;

// ---- Alias access bits (ntsam.h) ----
pub const ALIAS_ADD_MEMBER: ACCESS_MASK = 0x00000001;
