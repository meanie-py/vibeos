pub const ALIAS_LIST_MEMBERS: ACCESS_MASK = 0x00000004;
pub const ALIAS_READ_INFORMATION: ACCESS_MASK = 0x00000008;
pub const ALIAS_WRITE_ACCOUNT: ACCESS_MASK = 0x00000010;
pub const ALIAS_ALL_ACCESS: ACCESS_MASK = STANDARD_RIGHTS_REQUIRED
    | ALIAS_ADD_MEMBER
    | ALIAS_REMOVE_MEMBER
    | ALIAS_LIST_MEMBERS
    | ALIAS_READ_INFORMATION
    | ALIAS_WRITE_ACCOUNT;

