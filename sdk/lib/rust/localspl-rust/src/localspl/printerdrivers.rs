#[no_mangle]
pub unsafe extern "system" fn LocalEnumPrinterDrivers(pName: PWSTR, pEnvironment: PWSTR, Level: DWORD, pDriverInfo: PBYTE, cbBuf: DWORD, pcbNeeded: PDWORD, pcReturned: PDWORD) -> BOOL {
    let mut pDriverInfo = pDriverInfo;
    let mut dwErrorCode: DWORD;
    let mut pNode: PSKIPLIST_NODE;
    let mut pEnd: PBYTE;
    let mut pPrinter: PLOCAL_PRINTER;

    // Only support 8 levels and not 7
    if Level < 1 || Level == 7 || Level > 8
    {
        // The caller supplied an invalid level.
        dwErrorCode = ERROR_INVALID_LEVEL;
    } else {
        // Count the required buffer size.
        *pcbNeeded = 0;

        // Count the required buffer size and the number of printers.
        pNode = PrinterList.Head.Next[0 as usize] as PSKIPLIST_NODE;
        while !pNode.is_null() {
            pPrinter = (*pNode).Element as PLOCAL_PRINTER;

            pfnPrinterDriverLevels[Level as usize].unwrap_unchecked()(pPrinter, core::ptr::null_mut(), core::ptr::null_mut(), pcbNeeded);

            pNode = (*pNode).Next[0 as usize] as PSKIPLIST_NODE;
        }

        // Check if the supplied buffer is large enough.
        if cbBuf < *pcbNeeded {
            dwErrorCode = ERROR_INSUFFICIENT_BUFFER;
        } else {
            // Copy over the Printer information.
            pEnd = pDriverInfo.offset(*pcbNeeded as isize) as *mut BYTE as PBYTE;

            pNode = PrinterList.Head.Next[0 as usize] as PSKIPLIST_NODE;
            while !pNode.is_null() {
                pPrinter = (*pNode).Element as PLOCAL_PRINTER;

                pfnPrinterDriverLevels[Level as usize].unwrap_unchecked()(
                    pPrinter,
                    core::ptr::addr_of_mut!(pDriverInfo) as PVOID,
                    core::ptr::addr_of_mut!(pEnd),
                    core::ptr::null_mut(),
                );
                *pcReturned = (*pcReturned).wrapping_add(1);

                pNode = (*pNode).Next[0 as usize] as PSKIPLIST_NODE;
            }

            dwErrorCode = ERROR_SUCCESS;
        }
    }

    SetLastError(dwErrorCode);
    return (dwErrorCode == ERROR_SUCCESS) as BOOL;
}

unsafe extern "C" fn multi_sz_lenW(str: *const WCHAR) -> ::core::ffi::c_int {
    let mut ptr: *const WCHAR = str;
    if str.is_null() {
        return 0;
    }
    loop {
        ptr = ptr.offset((lstrlenW(ptr as LPCWSTR) + 1) as isize);
        if !(*ptr != 0) {
            break;
        }
    }
    return (((ptr.offset_from(str) as ::core::ffi::c_longlong) + 1 as ::core::ffi::c_longlong)
        as usize)
        .wrapping_mul(::core::mem::size_of::<WCHAR>()) as ::core::ffi::c_int;
}
