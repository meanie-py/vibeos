//! DirectDraw driver-info GUID data for dxg.sys.
//!
//! In C these were materialized by `DEFINE_GUID` in main.c's TU (which includes
//! <initguid.h> before <ddrawi.h>), so the `_GUID_*` data symbols lived in dxg.sys.
//! With main.c flipped to Rust, provide the same data here: win32k-sys only DECLARES
//! these as `extern static GUID;`, so these `#[no_mangle]` definitions satisfy the
//! link. Values verbatim from sdk/include/.../ddrawi.h + dxg's DEFINE_GUIDs.
#![allow(non_upper_case_globals)]

use win32k_sys::win32k::GUID;

macro_rules! dxg_guid {
    ($name:ident, $d1:expr, $d2:expr, $d3:expr, [$($d4:expr),*]) => {
        #[no_mangle]
        pub static $name: GUID = GUID { Data1: $d1, Data2: $d2, Data3: $d3, Data4: [$($d4),*] };
    };
}

