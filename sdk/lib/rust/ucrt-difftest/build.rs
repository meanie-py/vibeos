// Compile the GENUINE Microsoft UCRT reference TUs for the host, with their
// public symbols renamed to `ref_<name>`, so a test binary can hold both the
// real C and our Rust at once and compare them.
//
// Nothing is transcribed, and nothing depends on the live tree: the reference
// is Microsoft's C as it sat at REFERENCE_REV, extracted from git history with
// `git archive`. It used to be read from `sdk/lib/ucrt`, skipping whatever a
// takeover had deleted -- which meant the oracle shrank with every batch and hit
// zero the day the last TU went (the stdlib takeover). The history does not go
// away, so neither does the oracle. If git cannot produce the tree, the build
// FAILS: a harness that silently graded nothing is what this exists to prevent.
//
// See Cargo.toml for the header hacks and for what Tier 1 / Tier 2 mean.

/// The last commit whose `sdk/lib/ucrt` holds every TU in REFS (the one before
/// the string takeover deleted `string/strcat.c`). An ancestor of master.
const REFERENCE_REV: &str = "af738a3b14e77b84c536c73f2ea48fa9ba5ce754";

use std::path::PathBuf;

/// One reference TU and the public symbols it owns.
///
/// Symbols are listed explicitly rather than discovered, because a rename that
/// silently misses one leaves the C body exporting its REAL name, which then
/// collides with (or worse, quietly substitutes for) the Rust under test. An
/// explicit list makes that a link error instead of a wrong verdict.
const REFS: &[(&str, &[&str])] = &[
    // NOT HERE, DELIBERATELY: `labs` and `ldiv`. Windows `long` is 32 bits and
    // the HOST's is 64, so a reference TU compiled here takes and returns a
    // different-width value than the ucrtbase one does. The comparison would
    // run, and be meaningless. Any UCRT function whose signature mentions
    // `long` is ungradeable by a host harness without an explicit shim, and
    // omitting them is how that stays visible instead of becoming a quiet
    // wrong verdict. (`long long` and `int` are the same width on both, so
    // llabs/lldiv/div are fine.)
    //
    // One symbol per TU for most of these -- verified with nm against the
    // built objects rather than assumed from the filename. The first draft
    // listed labs/llabs under abs.cpp and the link caught it immediately,
    // which is the point of enumerating rather than discovering.
    ("stdlib/abs.cpp", &["abs", "_abs64"]),
    ("stdlib/llabs.cpp", &["llabs"]),
    ("stdlib/div.cpp", &["div"]),
    ("stdlib/lldiv.cpp", &["lldiv"]),
    ("stdlib/imaxabs.cpp", &["imaxabs"]),
    ("string/strcat.c", &["strcat", "strcpy"]),
];
fn main() {
    let repo = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../../..")
        .canonicalize()
        .expect("repo root");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let stub = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("refstub");

    println!("cargo:rerun-if-changed=refstub");
    println!("cargo:rerun-if-changed=build.rs");
    // Kept for the tests' existing gates; with the reference read from history,
    // both are now constant (the reference is always there).
    println!("cargo::rustc-check-cfg=cfg(no_ucrt_reference)");
    println!("cargo::rustc-check-cfg=cfg(ucrt_ref_strcat)");
    println!("cargo:rustc-cfg=ucrt_ref_strcat");

    let tree = out.join("ucrt-ref");
    let _ = std::fs::remove_dir_all(&tree);
    std::fs::create_dir_all(&tree).expect("create ucrt-ref");
    let archive = std::process::Command::new("git")
        .arg("-C")
        .arg(&repo)
        .args(["archive", "--format=tar", REFERENCE_REV, "sdk/lib/ucrt"])
        .output()
        .expect("run git archive (the reference UCRT comes from git history)");
    assert!(
        archive.status.success(),
        "git archive {REFERENCE_REV} sdk/lib/ucrt failed: {}",
        String::from_utf8_lossy(&archive.stderr)
    );
    let tar_path = out.join("ucrt-ref.tar");
    std::fs::write(&tar_path, &archive.stdout).expect("write ucrt-ref.tar");
    let untar = std::process::Command::new("tar")
        .arg("-xf")
        .arg(&tar_path)
        .arg("-C")
        .arg(&tree)
        .status()
        .expect("run tar");
    assert!(untar.success(), "extracting the reference UCRT failed");
    let ucrt = tree.join("sdk/lib/ucrt");

    let mut renames: Vec<&str> = Vec::new();
    for (rel, syms) in REFS {
        assert!(
            ucrt.join(rel).is_file(),
            "{rel} is not in {REFERENCE_REV}; REFS and REFERENCE_REV disagree"
        );
        renames.extend(syms.iter().copied());
    }

    // ONE rename header for all TUs, not one per TU: a `cc::Build` applies
    // every `-include` to every file, so per-TU preludes would cross-apply
    // anyway -- better to make that explicit and auditable in one file.
    let prelude = out.join("ref_prelude.h");
    let mut text = String::from("/* generated by build.rs - do not edit */\n");
    for sym in &renames {
        text.push_str(&format!("#define {sym} ref_{}\n", sym.trim_start_matches('_')));
    }
    std::fs::write(&prelude, text).expect("write prelude");

    let mut build = cc::Build::new();
    build
        .cpp(true)
        .flag_if_supported("-std=gnu++17")
        .warnings(false)
        .include(&stub)
        .include(repo.join("sdk/include/ucrt"))
        .include(repo.join("sdk/include/psdk"))
        .include(ucrt.join("inc"))
        .include(repo.join("sdk/lib/vcruntime/inc"))
        .include(repo.join("sdk/lib/pseh/include"))
        // AFTER everything, so the UCRT/host copies of stddef, stdarg and
        // intrin that refstub shadows keep winning, while genuinely missing
        // headers (vcruntime_startup.h, vcruntime_string.h) still resolve.
        .flag(format!("-idirafter{}", repo.join("sdk/include/vcruntime").display()))
        .flag(format!("-include{}", prelude.display()));

    for (rel, _) in REFS {
        build.file(ucrt.join(rel));
    }
    build.compile("ucrt_ref");
}
