#[no_mangle]
pub unsafe extern "C" fn IntFillImeSpaceCHSorCHT(mut pEntry: PCONENTRY, mut pDisplay: PIMEDISPLAY, mut cch: UINT) -> UINT {
    let maxX: UINT = max!((*pEntry).ScreenSize.X as ::core::ffi::c_int, IMEDISPLAY_MAX_X as ::core::ffi::c_int) as UINT;

    let mut currentWidth: UINT = IntGetCharInfoWidth(core::ptr::addr_of_mut!((*pDisplay).CharInfo) as PCHAR_INFO, cch);
    let mut index: UINT = cch;
    while currentWidth > maxX && index > 0 as UINT {
        index = index.wrapping_sub(1);
        let wch: WCHAR = (*pDisplay).CharInfo[index as usize].Char.UnicodeChar;
        currentWidth = currentWidth.wrapping_sub(IntGetCharDisplayWidth(wch));
    }

    let remainingSpace: UINT = maxX.wrapping_sub(currentWidth);
    let ichFinal: UINT = index.wrapping_add(remainingSpace);

    if remainingSpace > 0 as UINT {
        let mut ich: UINT = index;
        while ich < ichFinal {
            let pChar: PCHAR_INFO = core::ptr::addr_of_mut!((*pDisplay).CharInfo[ich as usize]);
            (*pChar).Char.UnicodeChar = 0x0020u16;

            if ich < cch {
                (*pChar).Attributes = (*pDisplay).CharInfo[ich as usize].Attributes;
            } else {
                (*pChar).Attributes = _FOREGROUND_WHITE as WORD;
            }
            ich = ich.wrapping_add(1);
        }
    }

    return ichFinal;
}
