#[no_mangle]
pub unsafe extern "C" fn IntFillImeDisplayJPN(mut pEntry: PCONENTRY, mut pDisplay: PIMEDISPLAY) -> BOOL {
    let mut pChar: PCHAR_INFO = core::ptr::addr_of_mut!((*pDisplay).CharInfo) as PCHAR_INFO;
    let mut dwConversion: DWORD = (*pEntry).dwConversion;
    let mut dwSentence: DWORD = (*pEntry).dwSentence;
    let mut cch: UINT = 0;
    let mut wchSentence: WCHAR = 0x0020u16;

    'skip: {
        if (*pEntry).bOpened == 0 {
            break 'skip;
        }

        // Determines the input character type (full-width/half-width, hiragana/katakana/alphanumeric)
        if (dwConversion & IME_CMODE_FULLSHAPE) != 0 {
            // Full-width (全角)
            if (dwConversion & IME_CMODE_NATIVE) != 0 {
                if (dwConversion & IME_CMODE_KATAKANA) != 0 {
                    IntCopyUnicodeToCharInfo(core::ptr::addr_of_mut!(pChar), RUSTCONV_WSTR_28270251650C.as_ptr()); // L"全カ"
                } else {
                    IntCopyUnicodeToCharInfo(core::ptr::addr_of_mut!(pChar), RUSTCONV_WSTR_0F1734C600BA.as_ptr()); // L"全あ"
                }
            } else {
                IntCopyUnicodeToCharInfo(core::ptr::addr_of_mut!(pChar), RUSTCONV_WSTR_B020151A5139.as_ptr()); // L"全Ａ"
            }
            cch = 2;
        } else {
            // Half-width (半角)
            if (dwConversion & IME_CMODE_NATIVE) != 0 {
                if (dwConversion & IME_CMODE_KATAKANA) != 0 {
                    IntCopyUnicodeToCharInfo(core::ptr::addr_of_mut!(pChar), RUSTCONV_WSTR_5617AF86A73D.as_ptr()); // L"半ｶ "
                } else {
                    IntCopyUnicodeToCharInfo(core::ptr::addr_of_mut!(pChar), RUSTCONV_WSTR_D3C58703A4B1.as_ptr()); // L"半ｱ "
                }
            } else {
                IntCopyUnicodeToCharInfo(core::ptr::addr_of_mut!(pChar), RUSTCONV_WSTR_F5D65F2F7A0C.as_ptr()); // L"半A "
            }
            cch = 3;
        }

        // Determine phrase conversion mode (compound phrase, simple phrase, automatic, multi-phrase)
        if (dwSentence & IME_SMODE_PLAURALCLAUSE) != 0 {
            wchSentence = 0x8907u16; // L'複'
        } else if (dwSentence & IME_SMODE_SINGLECONVERT) != 0 {
            wchSentence = 0x5358u16; // L'単'
        } else if (dwSentence & IME_SMODE_AUTOMATIC) != 0 {
            wchSentence = 0x81EAu16; // L'自'
        } else if (dwSentence & IME_SMODE_PHRASEPREDICT) != 0 {
            wchSentence = 0x9023u16; // L'連'
        }

        let fresh16 = cch;
        cch = cch.wrapping_add(1);
        (*pDisplay).CharInfo[fresh16 as usize].Char.UnicodeChar = wchSentence;
        pChar = pChar.offset(1);

        // Input method (kana input / romaji input) detection
        if ((GetKeyState((VK_KANA as i32)) as i32) & 1) != 0 {
            IntCopyUnicodeToCharInfo(core::ptr::addr_of_mut!(pChar), RUSTCONV_WSTR_5ADAA7813DC0.as_ptr()); // L"ｶﾅ  "
            cch = cch.wrapping_add(4);
        } else if (dwConversion & IME_CMODE_ROMAN) != 0 {
            IntCopyUnicodeToCharInfo(core::ptr::addr_of_mut!(pChar), RUSTCONV_WSTR_C4FFCC060096.as_ptr()); // L"ﾛｰﾏ "
            cch = cch.wrapping_add(4);
        }
    }

    // DoSetAttributes:
    let mut ich: UINT = 0;
    while ich < cch {
        (*pDisplay).CharInfo[ich as usize].Attributes = (_FOREGROUND_WHITE as u16);
        ich = ich.wrapping_add(1);
    }

    (*pDisplay).uCharInfoLen = cch;
    (*pDisplay).bFlag = (TRUE as i32);
    return (TRUE) as BOOL;
}
