#[no_mangle]
pub unsafe extern "C" fn IntCloseCandsCHT(
    hwnd: HWND,
    hIMC: HIMC,
    pEntry: PCONENTRY,
    dwCandidates: DWORD,
) -> BOOL {
    let mut pDisplay: PIMEDISPLAY = LocalAlloc(
        LPTR as UINT,
        core::mem::size_of::<IMEDISPLAY>() as SIZE_T,
    ) as PIMEDISPLAY;
    if pDisplay.is_null() {
        return (FALSE) as BOOL;
    }

    let mut apCandList: *mut *mut PCANDIDATELIST =
        core::ptr::addr_of_mut!((*pEntry).apCandList) as *mut *mut PCANDIDATELIST;
    let mut iCand: DWORD = 0 as DWORD;
    while iCand < MAX_CANDLIST as DWORD {
        if (dwCandidates & ((1 as DWORD) << iCand)) != 0
            && !(*apCandList.offset(iCand as isize)).is_null()
        {
            LocalFree(*apCandList.offset(iCand as isize) as HLOCAL);
            *apCandList.offset(iCand as isize) = core::ptr::null_mut();
            (*pEntry).acbCandList[iCand as usize] = 0 as DWORD;
        }
        iCand = iCand.wrapping_add(1);
    }

    let mut CopyData: COPYDATASTRUCT = core::mem::zeroed();
    CopyData.dwData = MAGIC_SEND_IMEDISPLAY as _;
    CopyData.cbData = core::mem::size_of::<IMEDISPLAY>() as DWORD;
    CopyData.lpData = pDisplay as *mut core::ffi::c_void;
    if IntFillImeDisplayCHT(pEntry, pDisplay) != 0 {
        IntSendDataToConsole(
            (*pEntry).hwndConsole,
            hwnd,
            core::ptr::addr_of_mut!(CopyData),
        );
    }

    LocalFree(pDisplay as HLOCAL);
    return (TRUE) as BOOL;
}
