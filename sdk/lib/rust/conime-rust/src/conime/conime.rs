#[no_mangle]
pub unsafe extern "C" fn ConIme_OnGo(hwnd: HWND, hConsole: HANDLE, hKL: HKL, iDirection: INT) -> BOOL {
    let mut pEntry: PCONENTRY = IntFindConsoleEntry(hConsole);
    if pEntry.is_null() {
        return (FALSE) as BOOL; // Deny
    }

    let mut wTargetLang: LANGID = 0;
    match ((*pEntry).nOutputCodePage as ::core::ffi::c_int) as u32 {
        CP_CHINESE_SIMPLIFIED => {
            wTargetLang = (LANGID_CHINESE_SIMPLIFIED as u16);
        }
        CP_CHINESE_TRADITIONAL => {
            wTargetLang = (LANGID_CHINESE_TRADITIONAL as u16);
        }
        CP_JAPANESE => {
            wTargetLang = (LANGID_JAPANESE as u16);
        }
        CP_KOREAN => {
            wTargetLang = (LANGID_KOREAN as u16);
        }
        _ => {
            return (TRUE) as BOOL; // Allow
        }
    }

    if ((IS_IME_HKL!(hKL)) == 0) || LOWORD!(hKL) == wTargetLang {
        return (TRUE) as BOOL; // Allow
    }

    if iDirection == 0 {
        return (FALSE) as BOOL; // Deny
    }

    // Get keyboard list
    let mut cKLs: INT = GetKeyboardLayoutList(0, core::ptr::null_mut()) as INT;
    if cKLs <= 0 {
        return (FALSE) as BOOL; // Deny
    }
    let mut phKLs: *mut HKL = LocalAlloc(
        LPTR,
        (cKLs as SIZE_T).wrapping_mul(core::mem::size_of::<HKL>() as SIZE_T),
    ) as *mut HKL;
    if phKLs.is_null() {
        return (FALSE) as BOOL; // Deny
    }
    GetKeyboardLayoutList(cKLs, phKLs);

    // Get current keyboard
    let mut iCurrent: INT = 0;
    while iCurrent < cKLs {
        if (*pEntry).hKL == *phKLs.offset(iCurrent as isize) {
            break;
        }
        iCurrent += 1;
    }

    if iCurrent < cKLs {
        let mut iAttempt: INT = 0;
        let mut iNext: INT = iCurrent;
        while iAttempt < cKLs {
            iNext += iDirection;

            if iNext < 0 {
                iNext = cKLs - 1;
            } else if iNext >= cKLs {
                iNext = 0;
            }

            let mut hKL: HKL = *phKLs.offset(iNext as isize);
            let mut wLangId: LANGID = LOWORD!(hKL);
            if ((IS_IME_HKL!(hKL)) == 0) || wLangId == wTargetLang {
                PostMessageW(
                    (*pEntry).hwndConsole,
                    WM_USER + 0x0F,
                    hKL as WPARAM,
                    0 as LPARAM,
                );
                break;
            }
            iAttempt += 1;
        }
    }

    LocalFree(phKLs as HLOCAL);
    return (FALSE) as BOOL; // Deny
}
