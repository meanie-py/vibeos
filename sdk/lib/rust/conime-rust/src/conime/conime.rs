#[no_mangle]
pub unsafe extern "C" fn IntFindConsoleEntry(hConsole: HANDLE) -> PCONENTRY {
    EnterCriticalSection(core::ptr::addr_of_mut!(g_csLock));

    if g_hConsole.is_null() {
        IntSetCurrentConsole(hConsole);
    }

    let mut pFound: PCONENTRY = core::ptr::null_mut();
    let mut iEntry: UINT = 1;
    while iEntry < g_cEntries {
        let pEntry: PCONENTRY = *g_ppEntries.add(iEntry as usize);
        if !pEntry.is_null() && (*pEntry).hConsole == hConsole && (*pEntry).bWndEnabled == 0 {
            pFound = pEntry;
            break;
        }
        iEntry = iEntry.wrapping_add(1);
    }

    LeaveCriticalSection(core::ptr::addr_of_mut!(g_csLock));

    return pFound;
}
