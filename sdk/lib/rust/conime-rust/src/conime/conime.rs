#[no_mangle]
pub unsafe extern "C" fn ConIme_OnRoute(
    mut hwnd: HWND,
    mut uMsg: UINT,
    mut wParam: WPARAM,
    mut lParam: LPARAM,
) -> LRESULT {
    let mut wch: WPARAM = wParam;
    if (HIWORD!(wParam) as WPARAM) != 0 {
        if uMsg == WM_ROUTE_KEYDOWN || uMsg == WM_ROUTE_KEYUP ||
            uMsg == WM_ROUTE_SYSKEYDOWN || uMsg == WM_ROUTE_SYSKEYUP
        {
            wch = (UNICODE_NULL) as _;
        } else if (HIWORD!(wParam) as WPARAM) <= 0xFF {
            wch = HIWORD!(wParam) as WPARAM;
        } else {
            let mut wsz: [WCHAR; 2] = [HIWORD!(wParam) as WCHAR, 0];
            let mut ach: CHAR = 0;
            WideCharToMultiByte(
                CP_ACP,
                0,
                core::ptr::addr_of_mut!(wsz) as *mut WCHAR as LPCWSTR,
                1,
                core::ptr::addr_of_mut!(ach),
                1,
                core::ptr::null_mut(),
                core::ptr::null_mut(),
            );
            wch = ach as WPARAM;
        }
    }

    let mut vkey: UINT = 0;
    let mut uKeyMsg: UINT = (if ((HIWORD!(lParam) as UINT) & KF_UP) != 0 {
        WM_KEYUP
    } else {
        WM_KEYDOWN
    }) as UINT;
    let mut ret: LRESULT = ImmCallImeConsoleIME(
        hwnd,
        uKeyMsg,
        wParam,
        lParam,
        core::ptr::addr_of_mut!(vkey),
    ) as LRESULT;

    if (ret & (IPHK_HOTKEY as LRESULT)) == 0 {
        if (ret & (IPHK_PROCESSBYIME as LRESULT)) != 0 {
            return ImmTranslateMessage(hwnd, uKeyMsg, wParam, lParam) as LRESULT;
        } else if (ret & (IPHK_CHECKCTRL as LRESULT)) != 0
            || uMsg == WM_ROUTE_CHAR
            || uMsg == WM_ROUTE_SYSCHAR
        {
            return ConIme_OnKeyChar(
                hwnd,
                uMsg.wrapping_sub(WM_ROUTE),
                wch,
                lParam,
            ) as LRESULT;
        } else {
            return ConIme_OnKeyChar(
                hwnd,
                uMsg.wrapping_sub(WM_ROUTE),
                wParam as UINT as WPARAM,
                lParam,
            ) as LRESULT;
        }
    }

    return ret;
}
