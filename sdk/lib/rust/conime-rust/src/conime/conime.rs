#[no_mangle]
pub unsafe extern "C" fn ConIme_OnEnable() {
    EnterCriticalSection(core::ptr::addr_of_mut!(g_csLock));
    let mut iEntry: UINT = 1;
    while iEntry < g_cEntries {
        let pEntry: PCONENTRY = *g_ppEntries.offset(iEntry as isize);
        if !pEntry.is_null() && !(*pEntry).hConsole.is_null() {
            // Enable the console window and bring it to the front
            if (*pEntry).bConsoleEnabled == 0 && IsWindowEnabled((*pEntry).hwndConsole) == 0 {
                EnableWindow((*pEntry).hwndConsole, (TRUE) as BOOL);
                (*pEntry).bConsoleEnabled = (TRUE as i32);
                if (*pEntry).bWndEnabled == 0 {
                    SetForegroundWindow((*pEntry).hwndConsole);
                }
            }
        }
        iEntry = iEntry.wrapping_add(1);
    }
    LeaveCriticalSection(core::ptr::addr_of_mut!(g_csLock));
}
#[no_mangle]
pub unsafe extern "C" fn ConIme_OnDisable() {
    let pEntry: PCONENTRY = IntFindConsoleEntry(g_hConsole);
    if !pEntry.is_null() && !(*pEntry).hConsole.is_null() {
        (*pEntry).bConsoleEnabled = (FALSE as i32);
        EnableWindow((*pEntry).hwndConsole, (FALSE) as BOOL);
        g_bDisabled = (TRUE as i32);
    }
}
#[no_mangle]
pub unsafe extern "C" fn ConIme_OnImeStartComposition(hwnd: HWND) {
    TRACE!("WM_IME_STARTCOMPOSITION\n");
    let mut pEntry: PCONENTRY = IntFindConsoleEntry(g_hConsole);
    if !pEntry.is_null() {
        (*pEntry).bInComposition = TRUE as BOOL;
    }
}
#[no_mangle]
pub unsafe extern "C" fn ConIme_OnImeEndComposition(hWnd: HWND) {
    TRACE!("WM_IME_ENDCOMPOSITION\n");

    // Find the currently active console entry
    let mut pEntry: PCONENTRY = IntFindConsoleEntry(g_hConsole);
    if pEntry.is_null() {
        return;
    }

    (*pEntry).bInComposition = (FALSE as i32);

    // Free composition string info
    if !(*pEntry).pCompStr.is_null() {
        LocalFree((*pEntry).pCompStr as HLOCAL);
        (*pEntry).pCompStr = core::ptr::null_mut();
    }
}
#[no_mangle]
pub unsafe extern "C" fn ConIme_OnChangeKeyboard(mut hwnd: HWND, mut hConsole: HANDLE, mut hNewKL: HKL) {
    let mut pEntry: PCONENTRY = IntFindConsoleEntry(hConsole);
    if pEntry.is_null() {
        pEntry = IntFindConsoleEntry(g_hConsole);
    }
    if pEntry.is_null() || (*pEntry).pKLInfo.is_null() {
        return;
    }

    let mut hOldKL: HKL = (*pEntry).hKL;

    if ((IS_IME_HKL!(hOldKL)) != 0) {
        let mut iKL: INT;
        let mut pKLInfo: PKLINFO = (*pEntry).pKLInfo;

        iKL = 0 as INT;
        while iKL < (*pEntry).cKLs {
            if (*pKLInfo.offset(iKL as isize)).hKL.is_null()
                || (*pKLInfo.offset(iKL as isize)).hKL == hOldKL
            {
                break;
            }
            iKL += 1;
        }

        if iKL >= (*pEntry).cKLs {
            let mut newCount: INT = (*pEntry).cKLs + 1 as INT;
            let mut phNewKLs: PKLINFO = LocalAlloc(
                LPTR as UINT,
                (newCount as SIZE_T).wrapping_mul(core::mem::size_of::<KLINFO>() as SIZE_T),
            ) as PKLINFO;
            if phNewKLs.is_null() {
                return;
            }

            CopyMemory!(
                phNewKLs as *mut core::ffi::c_void,
                (*pEntry).pKLInfo as *const core::ffi::c_void,
                ((*pEntry).cKLs as usize).wrapping_mul(core::mem::size_of::<KLINFO>()),
            );
            LocalFree((*pEntry).pKLInfo as HLOCAL);
            (*pEntry).pKLInfo = phNewKLs;
            (*pEntry).cKLs = newCount;
        }

        (*(*pEntry).pKLInfo.offset(iKL as isize)).hKL = hOldKL;

        let mut dwConversion: DWORD = (*pEntry).dwConversion
            | (if (*pEntry).bOpened != 0 {
                _IME_CMODE_OPEN
            } else {
                0
            }) as DWORD;
        (*(*pEntry).pKLInfo.offset(iKL as isize)).dwConversion = dwConversion;
    }

    ActivateKeyboardLayout(hNewKL, 0 as UINT);
    (*pEntry).hKL = hNewKL;

    IntGetImeLayoutText(pEntry);
    ConIme_SendImeStatus(hwnd);
    (*pEntry).dwImeProp = ImmGetProperty((*pEntry).hKL, IGP_PROPERTY as DWORD);

    let mut pDisplay: PIMEDISPLAY = LocalAlloc(
        LPTR as UINT,
        core::mem::size_of::<IMEDISPLAY>() as SIZE_T,
    ) as PIMEDISPLAY;
    if pDisplay.is_null() {
        return;
    }

    let mut CopyData: COPYDATASTRUCT = core::mem::zeroed();
    CopyData.dwData = MAGIC_SEND_IMEDISPLAY as ULONG_PTR;
    CopyData.cbData = core::mem::size_of::<IMEDISPLAY>() as DWORD;
    CopyData.lpData = pDisplay as PVOID;

    if ((IS_IME_HKL!(hNewKL)) != 0) {
        let mut iKL_0: INT = 0 as INT;
        while iKL_0 < (*pEntry).cKLs {
            if (*(*pEntry).pKLInfo.offset(iKL_0 as isize)).hKL != hNewKL {
                iKL_0 += 1;
                continue;
            }

            IntSetImeState(
                hwnd,
                hConsole,
                (*(*pEntry).pKLInfo.offset(iKL_0 as isize)).dwConversion,
            );
            ConIme_SendImeStatus(hwnd);

            if IntFillImeDisplay(pEntry, pDisplay) != 0 {
                IntSendDataToConsole((*pEntry).hwndConsole, hwnd, &raw mut CopyData);
            }

            break;
        }
    } else {
        IntSetImeState(
            hwnd,
            hConsole,
            (*pEntry).dwConversion & !(_IME_CMODE_OPEN as DWORD),
        );
        (*pDisplay).uCharInfoLen = 0 as UINT;
        (*pDisplay).bFlag = TRUE as BOOL;
        IntSendDataToConsole((*pEntry).hwndConsole, hwnd, &raw mut CopyData);
    }

    LocalFree(pDisplay as HLOCAL);
}
#[no_mangle]
pub unsafe extern "C" fn ConIme_OnUser(hWnd: HWND, uMsg: UINT, wParam: WPARAM, lParam: LPARAM) -> LRESULT {
    match uMsg {
        WM_USER_INIT => {
            return ConIme_OnInit(hWnd, wParam as HANDLE, lParam as HWND) as LRESULT;
        }
        WM_USER_UNINIT => {
            return ConIme_OnUnInit(hWnd, wParam as HANDLE) as LRESULT;
        }
        WM_USER_SWITCHIME => {
            return ConIme_OnSwitchIme(hWnd, wParam as HANDLE, lParam as HKL) as LRESULT;
        }
        WM_USER_DEACTIVATE => {
            return ConIme_OnDeactivate(hWnd, wParam as HANDLE) as LRESULT;
        }
        WM_USER_SIMHOTKEY => {
            return ConIme_SimulateHotKey(hWnd, wParam, lParam) as LRESULT;
        }
        WM_USER_GETIMESTATE => {
            return IntGetImeState(hWnd, wParam as HANDLE) as LRESULT;
        }
        WM_USER_SETIMESTATE => {
            return IntSetImeState(hWnd, wParam as HANDLE, lParam as DWORD) as LRESULT;
        }
        WM_USER_SETSCREENSIZE => {
            let mut coord: COORD = _COORD {
                X: LOWORD!(lParam) as SHORT,
                Y: HIWORD!(lParam) as SHORT,
            };
            return ConIme_SetScreenSize(hWnd, wParam as HANDLE, coord) as LRESULT;
        }
        WM_USER_SENDIMESTATUS => {
            return ConIme_SendImeStatus(hWnd) as LRESULT;
        }
        WM_USER_CHANGEKEYBOARD => {
            ConIme_OnChangeKeyboard(hWnd, wParam as HANDLE, lParam as HKL);
            return (TRUE) as LRESULT;
        }
        WM_USER_SETCODEPAGE => {
            return ConIme_SetCodePage(
                hWnd,
                wParam as HANDLE,
                LOWORD!(lParam) as BOOL,
                HIWORD!(lParam) as WORD,
            ) as LRESULT;
        }
        WM_USER_GO => {
            return ConIme_OnGo(
                hWnd,
                wParam as HANDLE,
                lParam as HKL,
                (0) as INT,
            ) as LRESULT;
        }
        WM_USER_GONEXT => {
            return ConIme_OnGo(
                hWnd,
                wParam as HANDLE,
                lParam as HKL,
                (1) as INT,
            ) as LRESULT;
        }
        WM_USER_GOBACK => {
            return ConIme_OnGo(
                hWnd,
                wParam as HANDLE,
                lParam as HKL,
                -((1) as INT),
            ) as LRESULT;
        }
        _ => {
            ERR!("Unknown uMsg %u\n", uMsg);
            return (FALSE) as LRESULT;
        }
    }
}
#[no_mangle]
pub unsafe extern "C" fn ConIme_OnInputLangChangeRequest(hWnd: HWND, wParam: WPARAM, lParam: LPARAM) -> LRESULT {
    TRACE!("(%p, %p, %p)\n", hWnd, wParam, lParam);

    let pEntry: PCONENTRY = IntFindConsoleEntry(g_hConsole);
    if pEntry.is_null() {
        return FALSE as LRESULT;
    }

    // Forward messages to the console window
    PostMessageW((*pEntry).hwndConsole, WM_INPUTLANGCHANGEREQUEST as UINT, wParam, lParam);
    return TRUE as LRESULT;
}

#[no_mangle]
pub unsafe extern "system" fn ConIme_WndProc(hWnd: HWND, uMsg: UINT, wParam: WPARAM, lParam: LPARAM) -> LRESULT {
    match uMsg {
        WM_CREATE => {
            return (if ConIme_OnCreate(hWnd) != 0 { 0 } else { -1 }) as LRESULT;
        }
        WM_DESTROY => {
            ConIme_OnEnd(hWnd, uMsg);
            PostQuitMessage(0);
        }
        WM_CLOSE => {
            DestroyWindow(hWnd);
        }
        WM_QUERYENDSESSION => {
            return TRUE as LRESULT;
        }
        WM_ENDSESSION => {
            ConIme_OnEnd(hWnd, uMsg);
        }
        WM_INPUTLANGCHANGE => {
            ConIme_OnInputLangChange(hWnd, wParam, lParam as HKL);
            return TRUE as LRESULT;
        }
        WM_INPUTLANGCHANGEREQUEST => {
            if ConIme_OnInputLangChangeRequest(hWnd, wParam, lParam) != 0 {
                return TRUE as LRESULT;
            }
            return DefWindowProcW(hWnd, uMsg, wParam, lParam);
        }
        WM_ENABLE => {
            if wParam != 0 {
                ConIme_OnEnable();
            } else {
                ConIme_OnDisable();
            }
            return DefWindowProcW(hWnd, uMsg, wParam, lParam);
        }
        WM_IME_STARTCOMPOSITION => {
            ConIme_OnImeStartComposition(hWnd);
            return TRUE as LRESULT;
        }
        WM_IME_ENDCOMPOSITION => {
            ConIme_OnImeEndComposition(hWnd);
            return TRUE as LRESULT;
        }
        WM_IME_COMPOSITION => {
            ConIme_OnImeComposition(hWnd, wParam, lParam);
            return TRUE as LRESULT;
        }
        WM_KEYDOWN
        | WM_KEYUP
        | WM_CHAR
        | WM_DEADCHAR
        | WM_SYSKEYDOWN
        | WM_SYSKEYUP
        | WM_SYSCHAR
        | WM_SYSDEADCHAR => {
            ConIme_OnKeyChar(hWnd, uMsg, wParam, lParam);
            return TRUE as LRESULT;
        }
        WM_IME_SETCONTEXT => {
            return DefWindowProcW(hWnd, uMsg, wParam, lParam & (!ISC_SHOWUIALL) as LPARAM);
        }
        WM_IME_NOTIFY => {
            if ConIme_OnImeNotify(hWnd, wParam, lParam) == 0 {
                return DefWindowProcW(hWnd, uMsg, wParam, lParam);
            }
            return TRUE as LRESULT;
        }
        WM_IME_COMPOSITIONFULL => {
            return TRUE as LRESULT;
        }
        WM_IME_SYSTEM => {
            if wParam == (IMS_CONSOLEIME_1A as _) || wParam == (IMS_CONSOLEIME_1B as _) {
                ConIme_OnImeSystem(hWnd, wParam, lParam);
                return TRUE as LRESULT;
            }
            return DefWindowProcW(hWnd, uMsg, wParam, lParam);
        }
        _ => {
            if WM_USER_INIT <= uMsg && uMsg <= WM_USER_GOBACK {
                return ConIme_OnUser(hWnd, uMsg, wParam, lParam);
            }
            if WM_ROUTE_KEYDOWN <= uMsg && uMsg <= WM_ROUTE_SYSDEADCHAR {
                ConIme_OnRoute(hWnd, uMsg, wParam, lParam);
                return TRUE as LRESULT;
            }
            return DefWindowProcW(hWnd, uMsg, wParam, lParam);
        }
    }

    return 0 as LRESULT;
}
#[no_mangle]
pub unsafe extern "C" fn IntIsConImeOnSystemProcessEnabled() -> BOOL {
    let mut bIsConImeOnSystemProcessEnabled: BOOL = (FALSE as i32);

    let mut hKey: HKEY = ::core::ptr::null_mut::<HKEY__>();
    let mut error: LSTATUS = RegOpenKeyExW(
        HKEY_LOCAL_MACHINE,
        RUSTCONV_WSTR_AAA57AE6E61A.as_ptr(),
        0,
        KEY_QUERY_VALUE,
        &raw mut hKey,
    );
    if error == (ERROR_SUCCESS as i32) {
        let mut dwValue: DWORD = FALSE;
        let mut cbValue: DWORD = ::core::mem::size_of::<DWORD>() as DWORD;
        error = RegQueryValueExW(
            hKey,
            RUSTCONV_WSTR_4B1548C6044F.as_ptr(),
            ::core::ptr::null_mut::<DWORD>(),
            ::core::ptr::null_mut::<DWORD>(),
            &raw mut dwValue as PBYTE,
            &raw mut cbValue,
        );
        if error == (ERROR_SUCCESS as i32) {
            bIsConImeOnSystemProcessEnabled = (dwValue != 0) as ::core::ffi::c_int as BOOL;
        }
        RegCloseKey(hKey);
    }

    return bIsConImeOnSystemProcessEnabled;
}
#[no_mangle]
pub unsafe extern "C" fn ConIme_InitInstance(mut hInstance: HINSTANCE) -> BOOL {
    let mut bIsConImeOnSystemProcessEnabled: BOOL = IntIsConImeOnSystemProcessEnabled();
    if bIsConImeOnSystemProcessEnabled == 0 && IntIsLogOnSession() != 0 {
        return (FALSE) as BOOL;
    }

    let cEntries: UINT = 10;
    g_ppEntries = LocalAlloc(
        LPTR,
        (cEntries as SIZE_T) * (core::mem::size_of::<PCONENTRY>() as SIZE_T),
    ) as *mut PCONENTRY;
    if g_ppEntries.is_null() {
        return (FALSE) as BOOL;
    }

    InitializeCriticalSection(&raw mut g_csLock);

    g_cEntries = cEntries;

    // Open a startup synchronization event
    let mut hStartUpEvent: HANDLE = OpenEventW(
        EVENT_MODIFY_STATE,
        (FALSE) as BOOL,
        RUSTCONV_WSTR_664EA17994F8.as_ptr(),
    );
    if hStartUpEvent.is_null() {
        DeleteCriticalSection(&raw mut g_csLock);
        return (FALSE) as BOOL;
    }

    let mut x: INT = 0;
    let mut y: INT = 0;
    let mut cx: INT = 0;
    let mut cy: INT = 0;
    let mut cxScreen: INT = 0;
    let mut cyMenu: INT = 0;
    let mut hWnd: HWND = core::ptr::null_mut();

    // Register window class
    let mut wc: WNDCLASSEXW = core::mem::zeroed();
    wc.cbSize = core::mem::size_of::<WNDCLASSEXW>() as UINT;
    wc.lpfnWndProc =
        Some(ConIme_WndProc);
    wc.hInstance = hInstance;
    wc.hIcon = LoadIconW(hInstance, MAKEINTRESOURCEW!(IDI_MAINICON));
    wc.hCursor = LoadCursorW(core::ptr::null_mut(), IDC_ARROW as LPCWSTR);
    wc.hbrBackground = GetStockObject((BLACK_BRUSH as i32)) as HBRUSH;
    wc.lpszClassName = RUSTCONV_WSTR_C651008EF7B7.as_ptr();
    let mut atom: ATOM = RegisterClassExW(&raw mut wc);

    'cleanup1: {
        if atom == 0 {
            break 'cleanup1;
        }

        // Create main window
        cxScreen = GetSystemMetrics((SM_CXSCREEN as i32)) as INT;
        cyMenu = GetSystemMetrics((SM_CYMENU as i32)) as INT;
        x = cxScreen - (cxScreen / 3);
        y = cyMenu;
        cx = cxScreen / 3;
        cy = 10 * cyMenu;
        hWnd = CreateWindowW!(
            RUSTCONV_WSTR_C651008EF7B7.as_ptr(),
            RUSTCONV_WSTR_96A296D224F2.as_ptr(),
            WS_OVERLAPPEDWINDOW,
            x,
            y,
            cx,
            cy,
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            hInstance,
            core::ptr::null_mut(),
        );

        'cleanup2: {
            if hWnd.is_null() {
                break 'cleanup2;
            }

            // Console IME registration and threaded input synchronization
            if RegisterConsoleIME(hWnd, &raw mut g_dwAttachToThreadId) != 0
                && AttachThreadInput(
                    GetCurrentThreadId(),
                    g_dwAttachToThreadId,
                    (TRUE) as BOOL,
                ) != 0
            {
                SetEvent(hStartUpEvent);
                CloseHandle(hStartUpEvent);
                return (TRUE) as BOOL; // Success
            }

            if g_dwAttachToThreadId != 0 {
                UnregisterConsoleIME();
            }

            if !hWnd.is_null() {
                DestroyWindow(hWnd);
            }
        }

        // Cleanup2:
        if atom != 0 {
            UnregisterClassW(RUSTCONV_WSTR_C651008EF7B7.as_ptr(), hInstance);
        }
    }

    // Cleanup1:
    if !hStartUpEvent.is_null() {
        SetEvent(hStartUpEvent); // Set to release the waiting side even if it fails
        CloseHandle(hStartUpEvent);
    }

    DeleteCriticalSection(&raw mut g_csLock);
    return (FALSE) as BOOL; // Failed
}

#[no_mangle]
pub unsafe extern "system" fn wWinMain(
    hInstance: HINSTANCE,
    hPrevInstance: HINSTANCE,
    lpCmdLine: PWSTR,
    nCmdShow: INT,
) -> INT {
    let mut szSysDir: [WCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    if GetSystemDirectoryW(
        core::ptr::addr_of_mut!(szSysDir) as LPWSTR,
        _countof!(szSysDir) as UINT,
    ) != 0
    {
        SetCurrentDirectoryW(core::ptr::addr_of_mut!(szSysDir) as *mut WCHAR as LPCWSTR);
    }

    ImmDisableTextFrameService(0xFFFFFFFF as DWORD);

    if ConIme_InitInstance(hInstance) == 0 {
        ERR!("ConIme_InitInstance failed\n");
        IntFreeConsoleEntries();
        return 0 as INT;
    }

    let mut msg: MSG = tagMSG {
        hwnd: core::ptr::null_mut::<HWND__>(),
        message: 0,
        wParam: 0,
        lParam: 0,
        time: 0,
        pt: tagPOINT { x: 0, y: 0 },
    };
    // _SEH2_TRY: a Rust message loop raises no SEH exception; the handler below is kept.
    let mut _SEH2_Volatile0_local: i32 = 0;
    {
        // Main loop
        while GetMessageW(
            core::ptr::addr_of_mut!(msg),
            core::ptr::null_mut::<HWND__>(),
            0 as UINT,
            0 as UINT,
        ) != 0
        {
            TranslateMessage(core::ptr::addr_of_mut!(msg));
            DispatchMessageW(core::ptr::addr_of_mut!(msg));
        }
    }
    // _SEH2_EXCEPT(EXCEPTION_EXECUTE_HANDLER)
    if _SEH2_Volatile0_local != 0 {
        ERR!("Exception\n");
        msg.wParam = (-(1 as i32)) as WPARAM;
    }

    IntFreeConsoleEntries();
    DeleteCriticalSection(core::ptr::addr_of_mut!(g_csLock));

    msg.wParam as INT
}
