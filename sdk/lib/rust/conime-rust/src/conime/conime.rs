    let mut width: UINT = 0 as UINT;

    let mut pLayoutSrc: PWCHAR = core::ptr::addr_of_mut!((*pEntry).szLayoutText) as PWCHAR;
    while *pLayoutSrc != 0 {
        let wch: WCHAR = *pLayoutSrc;
        if wch == 0x8F93 as WCHAR {
            break;
        }

        let idx = cch;
        cch = cch.wrapping_add(1);
        (*pDisplay).CharInfo[idx as usize].Char.UnicodeChar = wch;

        width = width.wrapping_add(
            (IntIsDoubleWidthChar(wch) + 1) as UINT,
        );
        if width >= 9 as UINT {
            cch = cch.wrapping_add(1);
            pLayoutSrc = pLayoutSrc.offset(1);
            break;
        } else {
            pLayoutSrc = pLayoutSrc.offset(1);
        }
    }

    let paddingCount: INT = (9 as UINT).wrapping_sub(width) as INT;
    let mut i: INT = 0 as INT;
    while i < paddingCount {
        let idx = cch;
        cch = cch.wrapping_add(1);
        (*pDisplay).CharInfo[idx as usize].Char.UnicodeChar = 0x0020u16;
        i += 1;
    }

    let modeChar: WCHAR;
    if (dwConversion & IME_CMODE_FULLSHAPE as DWORD) != 0 {
        modeChar = 0x5168 as WCHAR;
    } else {
        modeChar = 0x534A as WCHAR;
    }

    let idx = cch;
    cch = cch.wrapping_add(1);
    (*pDisplay).CharInfo[idx as usize].Char.UnicodeChar = modeChar;

    let idx = cch;
    cch = cch.wrapping_add(1);
    (*pDisplay).CharInfo[idx as usize].Char.UnicodeChar = 0x003Au16;

    let mut ich: UINT = 0 as UINT;
    while ich < cch {
        (*pDisplay).CharInfo[ich as usize].Attributes = _FOREGROUND_WHITE as WORD;
        ich = ich.wrapping_add(1);
    }

