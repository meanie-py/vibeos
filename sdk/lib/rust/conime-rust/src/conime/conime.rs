#[no_mangle]
pub unsafe extern "C" fn IntFormatCandLineJPNorKOR(
    mut pCandList: PCANDIDATELIST,
    mut pszCandStrDest: PWSTR,
    mut pbAttrsDest: PBYTE,
    mut width: UINT,
    mut labelWidth: UINT,
    mut pEntry: PCONENTRY,
    mut bIsCode: BOOL,
) -> UINT {
    if (*pCandList).dwSelection >= (*pCandList).dwCount {
        (*pCandList).dwSelection = 0 as DWORD;
    }

    let mut pageIndex: UINT = 0;
    pageIndex = (*pEntry).dwCandIndexMax as UINT;
    while pageIndex > 0 as UINT {
        if (*pCandList).dwSelection >= *(*pEntry).pdwCandPageStart.offset(pageIndex as isize) {
            break;
        }
        pageIndex = pageIndex.wrapping_sub(1);
    }

    ZeroMemory!(pbAttrsDest as *mut ::core::ffi::c_void, width as usize);

    let mut pszCurrentPos: PWSTR = pszCandStrDest;
    let mut pbCurrentAttr: PBYTE = pbAttrsDest;
    let mut currentX: UINT = 0 as UINT;
    let mut candNum: UINT = 1 as UINT;

    if bIsCode != 0 {
        let mut szCharCode: [WCHAR; 8] = [0 as WCHAR; 8];
        let mut asz: [CHAR; 2] = [0 as CHAR; 2];

        let mut pwchCand: PCWCH = (pCandList as PBYTE).offset(
            *(&raw mut (*pCandList).dwOffset as *mut DWORD)
                .offset((*pCandList).dwSelection as isize) as isize,
        ) as PCWCH;
        WideCharToMultiByte(
            CP_OEMCP as UINT,
            0 as DWORD,
            pwchCand as LPCWSTR,
            1 as ::core::ffi::c_int,
            &raw mut asz as LPSTR,
            _countof!(asz) as ::core::ffi::c_int,
            ::core::ptr::null::<CHAR>(),
            ::core::ptr::null_mut::<BOOL>(),
        );

        StringCchPrintfW!(
            &raw mut szCharCode as *mut WCHAR,
            _countof!(szCharCode) as size_t,
            RUSTCONV_WSTR_12D6B9570DB7.as_ptr(),
            MAKEWORD!(
                asz[0 as usize] as u8,
                asz[1 as usize] as u8,
            ) as ::core::ffi::c_int,
        );

        let cchCode: size_t = wcslen(&raw mut szCharCode as *mut WCHAR) as size_t;
        StringCchCopyW(
            pszCurrentPos as STRSAFE_LPWSTR,
            cchCode.wrapping_add(1 as size_t),
            &raw mut szCharCode as *mut WCHAR as STRSAFE_LPCWSTR,
        );

        currentX = cchCode as UINT;
        pszCurrentPos = pszCurrentPos.offset(cchCode as isize);
        pbCurrentAttr = pbCurrentAttr.offset(cchCode as isize);
    }

    let iStart: DWORD = *(*pEntry).pdwCandPageStart.offset(pageIndex as isize);
    let iEnd: DWORD = *(*pEntry)
        .pdwCandPageStart
        .offset(pageIndex.wrapping_add(1 as UINT) as isize);
    let mut i: DWORD = iStart;
    while i < iEnd {
        let pszSrc: *const WCHAR = (pCandList as PBYTE)
            .offset(*(&raw mut (*pCandList).dwOffset as *mut DWORD).offset(i as isize) as isize)
            as *const WCHAR;
        let mut cchSrc: size_t = wcslen(pszSrc) as size_t;
        let mut strWidth: UINT = IntGetStringWidth(pszSrc as PCWSTR) as UINT;
        let mut bTruncated: BOOL = FALSE as BOOL;

        if currentX.wrapping_add(strWidth).wrapping_add(3 as UINT)
            > width.wrapping_sub(labelWidth)
        {
            let mut tmpW: UINT = 0 as UINT;
            let mut ichSrc: UINT = 0 as UINT;
            ichSrc = 0 as UINT;
            while (ichSrc as size_t) < cchSrc {
                tmpW = tmpW.wrapping_add(
                    (IntIsDoubleWidthChar(*pszSrc.offset(ichSrc as isize)) as ::core::ffi::c_int
                        + 1 as ::core::ffi::c_int) as UINT,
                );
                if currentX.wrapping_add(tmpW)
                    > width
                        .wrapping_sub(labelWidth)
                        .wrapping_sub(3 as UINT)
                {
                    break;
                }
                ichSrc = ichSrc.wrapping_add(1);
            }
            cchSrc = (if ichSrc > 0 as UINT {
                ichSrc.wrapping_sub(1 as UINT)
            } else {
                0 as UINT
            }) as size_t;
            strWidth = tmpW;
            bTruncated = TRUE as BOOL;
        }

        if currentX
            .wrapping_add(strWidth)
            .wrapping_add(labelWidth)
            .wrapping_add(3 as UINT)
            > width
        {
            break;
        }

        if i == (*pCandList).dwSelection {
            FillMemory!(
                pbCurrentAttr as *mut ::core::ffi::c_void,
                cchSrc.wrapping_add(2 as size_t),
                FOREGROUND_BLUE as ::core::ffi::c_int,
            );
        }

        *pszCurrentPos = (0x0030u16 as UINT).wrapping_add(candNum) as WCHAR;
        pszCurrentPos = pszCurrentPos.offset(1);
        *pszCurrentPos = 0x003Au16;
        pszCurrentPos = pszCurrentPos.offset(1);
        CopyMemory!(
            pszCurrentPos as *mut ::core::ffi::c_void,
            pszSrc as *const ::core::ffi::c_void,
            cchSrc.wrapping_mul(::core::mem::size_of::<WCHAR>() as size_t),
        );
        pszCurrentPos = pszCurrentPos.offset(cchSrc as isize);
        *pszCurrentPos = 0x0020u16;
        pszCurrentPos = pszCurrentPos.offset(1);

        currentX = currentX.wrapping_add(strWidth.wrapping_add(3 as UINT));
        pbCurrentAttr = pbCurrentAttr.offset(cchSrc.wrapping_add(3 as size_t) as isize);
        candNum = candNum.wrapping_add(1);

        if bTruncated != 0 {
            break;
        }
        i = i.wrapping_add(1);
    }

    *pszCurrentPos = UNICODE_NULL as WCHAR;

    let totalWidth: UINT = IntGetStringWidth(pszCandStrDest as PCWSTR) as UINT;
    let usableWidth: UINT = width.wrapping_sub(labelWidth);

    if totalWidth <= usableWidth {
        if bIsCode != 0 {
            if totalWidth < width {
                let pad: UINT = width.wrapping_sub(totalWidth);
                core::slice::from_raw_parts_mut(pszCurrentPos as *mut u16, pad as usize).fill(0x0020); // wmemset (wchar.h inline)
                pszCurrentPos = pszCurrentPos.offset(pad as isize);
            }
        } else {
            if totalWidth < usableWidth {
                let pad_0: UINT = usableWidth.wrapping_sub(totalWidth);
                core::slice::from_raw_parts_mut(pszCurrentPos as *mut u16, pad_0 as usize).fill(0x0020); // wmemset (wchar.h inline)
                pszCurrentPos = pszCurrentPos.offset(pad_0 as isize);
            }

            let halfLabel: UINT = labelWidth
                .wrapping_sub(1 as UINT)
                .wrapping_div(2 as UINT);

            IntFormatNumber(
                pszCurrentPos,
                (*pCandList).dwSelection.wrapping_add(1 as DWORD) as UINT,
                halfLabel,
            );
            pszCurrentPos = pszCurrentPos.offset(halfLabel as isize);

            *pszCurrentPos = 0x002Fu16;
            pszCurrentPos = pszCurrentPos.offset(1);

            IntFormatNumber(pszCurrentPos, (*pCandList).dwCount as UINT, halfLabel);
            pszCurrentPos = pszCurrentPos.offset(halfLabel as isize);
        }

        *pszCurrentPos = UNICODE_NULL as WCHAR;
    }

    return pageIndex;
}
