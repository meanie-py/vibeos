pub unsafe extern "C" fn IntFillImeModeCHT(pEntry: PCONENTRY, pDisplay: PIMEDISPLAY, mut cch: INT) -> UINT {
    let mut pLayoutSrc: PWCHAR = core::ptr::addr_of_mut!((*pEntry).szLayoutText) as PWCHAR;

    let mut width: UINT;
    width = 0 as UINT;
    while *pLayoutSrc != 0 && width < (5 as UINT).wrapping_sub(1 as UINT) {
        let wch: WCHAR = *pLayoutSrc;
        pLayoutSrc = pLayoutSrc.offset(1);
        (*pDisplay).CharInfo[cch as usize].Char.UnicodeChar = wch;
        cch = cch + 1;
        width = width.wrapping_add((IntIsDoubleWidthChar(wch) as UINT).wrapping_add(1 as UINT));
    }

    let paddingCount: INT = (5 as UINT).wrapping_sub(width) as INT;
    let mut i: INT = 0 as INT;
    while i < paddingCount {
        (*pDisplay).CharInfo[cch as usize].Char.UnicodeChar = 0x0020u16;
        cch = cch + 1;
        i += 1;
    }

    let modeChar: WCHAR;
    if (*pEntry).dwConversion & (IME_CMODE_FULLSHAPE as DWORD) != 0 {
        modeChar = 0x5168 as WCHAR;
    } else {
        modeChar = 0x534A as WCHAR;
    }

    (*pDisplay).CharInfo[cch as usize].Char.UnicodeChar = modeChar;
    cch = cch + 1;
    (*pDisplay).CharInfo[cch as usize].Char.UnicodeChar = 0x0020u16;
    cch = cch + 1;
    (*pDisplay).CharInfo[cch as usize].Char.UnicodeChar = 0x003Au16;
    cch = cch + 1;

    let mut i_0: UINT = 0 as UINT;
    while i_0 < cch as UINT {
        (*pDisplay).CharInfo[i_0 as usize].Attributes = _FOREGROUND_WHITE as WORD;
        i_0 = i_0.wrapping_add(1);
    }

    return cch as UINT;
}
