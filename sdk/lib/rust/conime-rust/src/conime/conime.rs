pub unsafe extern "C" fn ConIme_OnEnd(mut hwnd: HWND, mut uMsg: UINT) {
    ImmAssociateContext(hwnd, g_hOldIMC);
    IntFreeConsoleEntries();
    if g_dwAttachToThreadId != 0 && (uMsg != WM_ENDSESSION as UINT || g_bIsLogOnSession == 0) {
        AttachThreadInput(GetCurrentThreadId(), g_dwAttachToThreadId, (FALSE) as BOOL);
        UnregisterConsoleIME();
        g_dwAttachToThreadId = 0;
    }
}
#[no_mangle]
pub unsafe extern "C" fn IntGrowEntries() -> BOOL {
    let mut cGrow: size_t = 5 as size_t;
    let mut cNewCount: size_t = (g_cEntries as size_t).wrapping_add(cGrow);
    let mut cbOld: size_t =
        (::core::mem::size_of::<PCONENTRY>() as size_t).wrapping_mul(g_cEntries as size_t);
    let mut cbNew: size_t = (::core::mem::size_of::<PCONENTRY>() as size_t).wrapping_mul(cNewCount);
    let mut ppEntries: *mut PCONENTRY =
        LocalAlloc(LPTR as UINT, cbNew as SIZE_T) as *mut PCONENTRY;
    if ppEntries.is_null() {
        return (FALSE) as BOOL;
    }
    CopyMemory!(
        ppEntries as *mut ::core::ffi::c_void,
        g_ppEntries as *const ::core::ffi::c_void,
        cbOld,
    );
    let mut ppOldEntries: *mut PCONENTRY = g_ppEntries;
    g_ppEntries = ppEntries;
    g_cEntries = cNewCount as UINT;
    LocalFree(ppOldEntries as HLOCAL);
    return (TRUE) as BOOL;
}
#[no_mangle]
pub unsafe extern "C" fn ConIme_UnInitEntry(hwnd: HWND, pEntry: PCONENTRY) -> BOOL {
    if (*pEntry).bConsoleEnabled == 0 {
        (*pEntry).bWndEnabled = TRUE as BOOL;
        return TRUE as BOOL;
    }
    (*pEntry).hConsole = core::ptr::null_mut();
    (*pEntry).ScreenSize.X = 0 as SHORT;
    (*pEntry).nOutputCodePage = CP_ACP as WORD;
    (*pEntry).nCodePage = (*pEntry).nOutputCodePage;
    (*pEntry).hKL = core::ptr::null_mut();
    ImmDestroyContext((*pEntry).hNewIMC);

    // Free composition string info
    if !(*pEntry).pCompStr.is_null() {
        LocalFree((*pEntry).pCompStr as HLOCAL);
        (*pEntry).pCompStr = core::ptr::null_mut();
    }

    // Free candidate list
    let mut iList: UINT = 0 as UINT;
    while (iList as usize) < (_countof!((*pEntry).apCandList) as usize) {
        if !(*pEntry).apCandList[iList as usize].is_null() {
            LocalFree((*pEntry).apCandList[iList as usize] as HLOCAL);
            (*pEntry).apCandList[iList as usize] = core::ptr::null_mut();
        }
        iList = iList.wrapping_add(1);
    }

    // Free candidate separators
    if !(*pEntry).pdwCandPageStart.is_null() {
        LocalFree((*pEntry).pdwCandPageStart as HLOCAL);
        (*pEntry).pdwCandPageStart = core::ptr::null_mut();
    }

    // Free keyboard list info
    if !(*pEntry).pKLInfo.is_null() {
        LocalFree((*pEntry).pKLInfo as HLOCAL);
        (*pEntry).pKLInfo = core::ptr::null_mut();
    }

    (*pEntry).bConsoleEnabled = FALSE as BOOL;
    (*pEntry).bWndEnabled = FALSE as BOOL;
    return TRUE as BOOL;
}
