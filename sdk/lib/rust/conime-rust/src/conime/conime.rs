#[no_mangle]
pub unsafe extern "C" fn IntFormatNumber(pszBuffer: PWSTR, mut value: UINT, width: UINT) {
    let mut divisor: UINT = 1;
    if width > 1 {
        let mut tempWidth: UINT = width.wrapping_sub(1);
        loop {
            divisor = divisor.wrapping_mul(10);
            tempWidth = tempWidth.wrapping_sub(1);
            if tempWidth == 0 {
                break;
            }
        }
    }

    let mut i: UINT = divisor;
    let mut ich: UINT = 0;
    while i > 0 {
        'body: {
            let digit: UINT = value / i;
            value %= i;

            if digit == 0 && ich > 0 {
                let prevChar: WCHAR = *pszBuffer.add(ich.wrapping_sub(1) as usize);
                if prevChar == 0x0020u16 || prevChar == 0x002Fu16 {
                    *pszBuffer.add(ich as usize) = 0x0020u16;
                    break 'body;
                }
            }

            *pszBuffer.add(ich as usize) =
                ((0x0030u16 as UINT).wrapping_add(digit)) as WCHAR;
        }
        i = i / 10;
        ich = ich.wrapping_add(1);
    }
}
#[no_mangle]
pub unsafe extern "C" fn IntIsDoubleWidthChar(wch: WCHAR) -> BOOL {
    // Characters from SPACE (0x20) to TILDE (0x7E) are always single-width
    if 0x0020 <= wch && wch <= 0x007E {
        return (FALSE) as BOOL;
    }

    // East Asian scripts (Full-width blocks)
    if (0x3041 <= wch && wch <= 0x3094) || // Hiragana
        (0x30A1 <= wch && wch <= 0x30F6) || // Katakana
        (0x3105 <= wch && wch <= 0x312C) || // Bopomofo
        (0x3131 <= wch && wch <= 0x318E) || // Hangul Compatibility Jamo
        (0xAC00 <= wch && wch <= 0xD7A3) || // Hangul Syllables
        (0xFF01 <= wch && wch <= 0xFF5E)    // Full-width Forms
    {
        return (TRUE) as BOOL;
    }

    // Half-width East Asian blocks
    if (0xFF61 <= wch && wch <= 0xFF9F) || // Half-width Katakana
        (0xFFA0 <= wch && wch <= 0xFFBE) || // Half-width Hangul
        (0xFFC2 <= wch && wch <= 0xFFC7) || // Specific Half-width Jamo variants
        (0xFFCA <= wch && wch <= 0xFFCF) ||
        (0xFFD2 <= wch && wch <= 0xFFD7) ||
        (0xFFDA <= wch && wch <= 0xFFDC)
    {
        return (FALSE) as BOOL;
    }

    // CJK Ideographs and supplemental Full-width symbols
    if (0xFFE0 <= wch && wch <= 0xFFE6) || // Full-width currency/symbols
        (0x4E00 <= wch && wch <= 0x9FA5) || // CJK Unified Ideographs
        (0xF900 <= wch && wch <= 0xFA2D)    // CJK Compatibility Ideographs
    {
        return (TRUE) as BOOL;
    }

    // Fallback for undefined ranges
    let mut cbMultiByte: ULONG = 0;
    let Status: NTSTATUS = RtlUnicodeToMultiByteSize(
        core::ptr::addr_of_mut!(cbMultiByte),
        core::ptr::addr_of!(wch) as PCWCH,
        core::mem::size_of::<WCHAR>() as ULONG,
    );
    if NT_SUCCESS!(Status) {
        return (cbMultiByte == 2) as BOOL;
    }

    return (FALSE) as BOOL;
}
#[no_mangle]
pub unsafe extern "C" fn IntGetStringWidth(mut pch: PCWSTR) -> INT {
    let mut cch: INT = 0;
    while *pch != 0 {
        let fresh = *pch;
        pch = pch.add(1);
        cch += IntIsDoubleWidthChar(fresh) as INT + 1;
    }
    return cch;
}
#[no_mangle]
pub unsafe extern "C" fn IntSendDataToConsole(hwndConsole: HWND, hwndSender: HWND, pCopyData: PCOPYDATASTRUCT) -> BOOL {
    if hwndConsole.is_null() || IsWindow(hwndConsole) == 0 {
        ERR!("%p is null or invalid window\n", hwndConsole);
        return (FALSE) as BOOL;
    }

    let mut result: DWORD_PTR = 0;
    if SendMessageTimeoutW(
        hwndConsole,
        WM_COPYDATA,
        hwndSender as WPARAM,
        pCopyData as LPARAM,
        SMTO_ABORTIFHUNG,
        3000,
        core::ptr::addr_of_mut!(result),
    ) == 0
    {
        ERR!("SendMessageTimeoutW(%p) failed\n", hwndConsole);
        return (FALSE) as BOOL;
    }

    return (TRUE) as BOOL;
}
#[no_mangle]
pub unsafe extern "C" fn IntIsLogOnSession() -> BOOL {
    let mut Status: NTSTATUS = 0;
    let mut hToken: HANDLE = core::ptr::null_mut();
    let mut returnLength: ULONG = 0;
    let mut tokenStats: TOKEN_STATISTICS = core::mem::zeroed();
    // setypes.h: #define SYSTEM_LUID {0x3e7, 0x0}
    static systemLuid: LUID = LUID { LowPart: 0x3e7, HighPart: 0 };

    Status = NtOpenProcessToken(
        INVALID_HANDLE_VALUE,
        TOKEN_QUERY,
        core::ptr::addr_of_mut!(hToken),
    );
    if !NT_SUCCESS!(Status) {
        return g_bIsLogOnSession;
    }

    Status = NtQueryInformationToken(
        hToken,
        TokenStatistics,
        core::ptr::addr_of_mut!(tokenStats) as PVOID,
        core::mem::size_of::<TOKEN_STATISTICS>() as ULONG,
        core::ptr::addr_of_mut!(returnLength),
    );
    NtClose(hToken);

    if !NT_SUCCESS!(Status) {
        return g_bIsLogOnSession;
    }

    g_bIsLogOnSession = RtlEqualMemory!(
        core::ptr::addr_of!(tokenStats.AuthenticationId) as *const core::ffi::c_void,
        core::ptr::addr_of!(systemLuid) as *const core::ffi::c_void,
        core::mem::size_of::<LUID>(),
    ) as BOOL;
    return g_bIsLogOnSession;
}
#[no_mangle]
pub unsafe extern "C" fn IntFreeConsoleEntries() {
    EnterCriticalSection(core::ptr::addr_of_mut!(g_csLock));

    if !g_ppEntries.is_null() {
        let mut iEntry: UINT = 1;
        while iEntry < g_cEntries {
            'entry: {
                let pEntry: PCONENTRY = *g_ppEntries.offset(iEntry as isize);
                if pEntry.is_null() {
                    break 'entry;
                }

                if (*pEntry).hConsole.is_null() {
                    LocalFree(pEntry as HLOCAL);
                    break 'entry;
                }

                if (*pEntry).bOpened != 0 {
                    (*pEntry).bOpened = (FALSE as i32);
                    ImmSetOpenStatus((*pEntry).hNewIMC, (FALSE) as BOOL);
                }

                if !(*pEntry).hNewIMC.is_null() {
                    ImmDestroyContext((*pEntry).hNewIMC);
                }

                if !(*pEntry).pCompStr.is_null() {
                    LocalFree((*pEntry).pCompStr as HLOCAL);
                    (*pEntry).pCompStr = ::core::ptr::null_mut::<tagCOMPSTRINFO>();
                }

                let mut iList: UINT = 0;
                while iList < MAX_CANDLIST {
                    'cand: {
                        if (*pEntry).apCandList[iList as usize].is_null() {
                            break 'cand;
                        }
                        LocalFree((*pEntry).apCandList[iList as usize] as HLOCAL);
                        (*pEntry).apCandList[iList as usize] =
                            ::core::ptr::null_mut::<tagCANDIDATELIST>();
                        (*pEntry).acbCandList[iList as usize] = 0;
                    }
                    iList = iList.wrapping_add(1);
                }

                if !(*pEntry).pdwCandPageStart.is_null() {
                    LocalFree((*pEntry).pdwCandPageStart as HLOCAL);
                    (*pEntry).pdwCandPageStart = ::core::ptr::null_mut::<DWORD>();
                    (*pEntry).cbCandPageData = 0;
                }

                if !(*pEntry).pKLInfo.is_null() {
                    LocalFree((*pEntry).pKLInfo as HLOCAL);
                    (*pEntry).pKLInfo = ::core::ptr::null_mut::<tagKLINFO>();
                }

                LocalFree(pEntry as HLOCAL);
            }
            iEntry = iEntry.wrapping_add(1);
        }

        LocalFree(g_ppEntries as HLOCAL);
        g_ppEntries = ::core::ptr::null_mut::<PCONENTRY>();
        g_cEntries = 0;
    }

    LeaveCriticalSection(core::ptr::addr_of_mut!(g_csLock));
}

