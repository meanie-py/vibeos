#[no_mangle]
pub unsafe extern "C" fn IntFillImeCandidatesCHS(
    mut pEntry: PCONENTRY,
    mut pDisplay: PIMEDISPLAY,
    mut cch: UINT,
) -> UINT {
    let mut pCompStr: PCOMPSTRINFO = (*pEntry).pCompStr;

    if (*pEntry).pCandInfo.is_null() {
        return cch;
    }

    let mut displayCols: UINT = 0 as UINT;
    let mut strPosByte: DWORD = 0 as DWORD;

    if (*pCompStr).dwCompStrLen > 0 as DWORD {
        let mut pszComp: PWCHAR =
            pCompStr.offset(1 as isize) as *mut tagCOMPSTRINFO as PWCHAR;
        let mut cbCompStr: size_t = ((*pCompStr).dwCompStrLen as size_t)
            .wrapping_add(core::mem::size_of_val(&UNICODE_NULL) as size_t);
        let mut pbAttrs: PBYTE = (pszComp as PBYTE).offset(cbCompStr as isize);

        while displayCols < 10 as UINT {
            (*pDisplay).CharInfo[cch as usize].Char.UnicodeChar = *pszComp;
            (*pDisplay).CharInfo[cch as usize].Attributes =
                (*pCompStr).awAttrColor[*pbAttrs as usize];
            cch = cch.wrapping_add(1);

            strPosByte = strPosByte.wrapping_add(core::mem::size_of_val(&UNICODE_NULL) as DWORD);
            displayCols = displayCols.wrapping_add(
                (IntIsDoubleWidthChar(*pszComp) + 1 as BOOL) as UINT,
            );
            pszComp = pszComp.offset(1);
            pbAttrs = pbAttrs.offset(1);

            if strPosByte >= (*pCompStr).dwCompStrLen {
                break;
            }
        }
    }

    let mut padCount: INT = (10 as UINT).wrapping_sub(displayCols) as INT;
    let mut i: INT = 0 as INT;
    while i < padCount {
        let fresh24 = cch;
        cch = cch.wrapping_add(1);
        (*pDisplay).CharInfo[fresh24 as usize].Char.UnicodeChar = 0x0020u16;
        i += 1;
    }

    let fresh25 = cch;
    cch = cch.wrapping_add(1);
    (*pDisplay).CharInfo[fresh25 as usize].Char.UnicodeChar = 0x003Au16;

    let mut pCandInfo: PCANDINFO = (*pEntry).pCandInfo;
    let mut pbCandAttrs: PBYTE = (pCandInfo as PBYTE).offset((*pCandInfo).dwAttrsOffset as isize);

    let mut pszCand: PWCHAR = core::ptr::addr_of_mut!((*pCandInfo).szCandStr) as PWCHAR;
    while *pszCand != 0 {
        (*pDisplay).CharInfo[cch as usize].Char.UnicodeChar = *pszCand;
        (*pDisplay).CharInfo[cch as usize].Attributes =
            (*pCompStr).awAttrColor[*pbCandAttrs as usize];
        cch = cch.wrapping_add(1);
        pbCandAttrs = pbCandAttrs.offset(1);
        pszCand = pszCand.offset(1);
    }

    return cch;
}
