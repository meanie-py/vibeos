#[no_mangle]
pub unsafe extern "C" fn ConIme_InitEntry(mut hwnd: HWND, mut hConsole: HANDLE, mut hwndConsole: HWND) -> BOOL {
    let mut pEntry: PCONENTRY = core::ptr::null_mut();
    let mut iEntry: UINT = 1;
    loop {
        while iEntry >= g_cEntries {
            if IntGrowEntries() == 0 {
                return (FALSE) as BOOL;
            }
        }
        pEntry = *g_ppEntries.offset(iEntry as isize);
        if pEntry.is_null() {
            pEntry = LocalAlloc(LPTR as UINT, core::mem::size_of::<CONENTRY>() as SIZE_T) as PCONENTRY;
            if pEntry.is_null() {
                return (FALSE) as BOOL;
            }
            *g_ppEntries.offset(iEntry as isize) = pEntry;
        }
        if (*pEntry).hConsole.is_null() {
            break;
        }
        if (*pEntry).bWndEnabled != 0 && (*pEntry).bConsoleEnabled != 0 {
            ConIme_UnInitEntry(hwnd, pEntry);
        }
        if (*pEntry).hConsole.is_null() {
            break;
        }
        iEntry = iEntry.wrapping_add(1);
    }
    core::ptr::write_bytes(pEntry, 0, 1);
    (*pEntry).pKLInfo = LocalAlloc(LPTR as UINT, core::mem::size_of::<KLINFO>() as SIZE_T) as PKLINFO;
    let mut pKLInfo: PKLINFO = (*pEntry).pKLInfo;
    if (*pEntry).pKLInfo.is_null() {
        return (FALSE) as BOOL;
    }
    (*pKLInfo).hKL = core::ptr::null_mut();
    (*pKLInfo).dwConversion = 0;
    (*pEntry).cKLs = 1;
    let mut hIMC: HIMC = ImmCreateContext();
    if hIMC.is_null() {
        LocalFree(pKLInfo as HLOCAL);
        (*pEntry).pKLInfo = core::ptr::null_mut();
        return (FALSE) as BOOL;
    }
    (*pEntry).hNewIMC = hIMC;
    (*pEntry).hConsole = hConsole;
    (*pEntry).hwndConsole = hwndConsole;
    (*pEntry).bConsoleEnabled = (TRUE as i32);
    (*pEntry).ScreenSize.X = 80;
    (*pEntry).awAttrColor[0 as usize] = (COMMON_LVB_UNDERSCORE | 0x7) as WORD;
    (*pEntry).awAttrColor[1 as usize] = (BACKGROUND_BLUE | _FOREGROUND_WHITE) as WORD;
    (*pEntry).awAttrColor[2 as usize] = (COMMON_LVB_UNDERSCORE | _FOREGROUND_WHITE) as WORD;
    (*pEntry).awAttrColor[3 as usize] = (COMMON_LVB_UNDERSCORE | _BACKGROUND_WHITE | FOREGROUND_BLUE) as WORD;
    (*pEntry).awAttrColor[4 as usize] = (COMMON_LVB_UNDERSCORE | FOREGROUND_RED) as WORD;
    (*pEntry).awAttrColor[5 as usize] = (COMMON_LVB_UNDERSCORE | FOREGROUND_RED) as WORD;
    (*pEntry).awAttrColor[6 as usize] = (COMMON_LVB_UNDERSCORE | FOREGROUND_RED) as WORD;
    (*pEntry).awAttrColor[7 as usize] = (COMMON_LVB_UNDERSCORE | FOREGROUND_RED) as WORD;
    IntGetImeLayoutText(pEntry);
    return (TRUE) as BOOL;
}
