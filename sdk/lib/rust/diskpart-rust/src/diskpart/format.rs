unsafe extern "C" fn GetFsModule(
    mut pszFileSystem: PWSTR,
    mut phModule: *mut HMODULE,
) -> BOOL {
    let mut szDllNameBuffer: [u16; 32] = [0; 32];
    let mut hKey: HKEY = core::ptr::null_mut();
    let mut dwLength: u32 = 0;
    let mut dwErr: u32 = 0;

    *phModule = core::ptr::null_mut();

    dwErr = (RegOpenKeyExW(
        HKEY_LOCAL_MACHINE,
        RUSTCONV_WSTR_9545D47ABA0B.as_ptr(),
        0,
        KEY_READ,
        &mut hKey,
    )) as u32;
    if dwErr != ERROR_SUCCESS {
        DPRINT1!("Failed to open!\n");
        return FALSE;
    }

    dwLength = core::mem::size_of::<[u16; 32]>() as u32;
    dwErr = (RegQueryValueExW(
        hKey,
        pszFileSystem,
        core::ptr::null_mut(),
        core::ptr::null_mut(),
        szDllNameBuffer.as_mut_ptr() as PBYTE,
        &mut dwLength,
    )) as u32;

    RegCloseKey(hKey);

    if dwErr != ERROR_SUCCESS {
        DPRINT1!("Failed to query!\n");
        return FALSE;
    }

    *phModule = LoadLibraryW(szDllNameBuffer.as_mut_ptr());
    if (*phModule).is_null() {
        DPRINT1!("Failed to load!\n");
        return FALSE;
    }

    return TRUE;
}

#[no_mangle]
pub unsafe extern "system" fn FormatCallback(
    Command: CALLBACKCOMMAND,
    Size: ULONG,
    Argument: PVOID,
) -> BOOLEAN {
    let mut percent: PDWORD;

    match Command {
        CALLBACKCOMMAND_PROGRESS => {
            percent = Argument as PDWORD;
            ConResPrintf(StdOut, (IDS_FORMAT_PROGRESS) as u32, *percent);
        }

        CALLBACKCOMMAND_DONE => {}

        _ => {
            DPRINT1!("Callback (%u %lu %p)\n", Command, Size, Argument);
        }
    }

    return (TRUE) as BOOLEAN;
}
