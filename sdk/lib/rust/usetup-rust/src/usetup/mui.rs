unsafe extern "C" fn FindLanguageIndex() -> ULONG {
    let mut lngIndex: ULONG = 0;
    if SelectedLanguageId.is_null() {
        return 0;
    }
    while !ResourceList[lngIndex as usize].MuiPages.is_null() {
        if _wcsicmp(
            ResourceList[lngIndex as usize].LanguageID as *const wchar_t,
            SelectedLanguageId as *const wchar_t,
        ) == 0
        {
            return lngIndex;
        }
        lngIndex = lngIndex.wrapping_add(1);
    }
    return 0;
}

unsafe extern "C" fn FindMUIEntriesOfPage(mut PageNumber: ULONG) -> *const MUI_ENTRY {
    let mut muiIndex: ULONG = 0;
    let mut lngIndex: ULONG;
    let mut Pages: *const MUI_PAGE = core::ptr::null();

    lngIndex = max(FindLanguageIndex(), 0);
    Pages = ResourceList[lngIndex as usize].MuiPages;

    while !(*Pages.offset(muiIndex as isize)).MuiEntry.is_null() {
        if ((*Pages.offset(muiIndex as isize)).Number) as u32 == PageNumber {
            return (*Pages.offset(muiIndex as isize)).MuiEntry;
        }
        muiIndex = muiIndex.wrapping_add(1);
    }

    return core::ptr::null();
}

unsafe extern "C" fn FindMUIErrorEntries() -> *const MUI_ERROR {
    let mut lngIndex: ULONG = max(FindLanguageIndex(), 0);
    return ResourceList[lngIndex as usize].MuiErrors;
}

unsafe extern "C" fn FindMUIStringEntries() -> *const MUI_STRING {
    let mut lngIndex: ULONG = max(FindLanguageIndex(), 0);
    return ResourceList[lngIndex as usize].MuiStrings;
}
#[no_mangle]
pub unsafe extern "C" fn MUIClearPage(page: ULONG) {
    let mut entry: *const MUI_ENTRY;
    let mut index: ULONG;

    entry = FindMUIEntriesOfPage(page);
    if entry.is_null() {
        PopupError(
            b"Error: Failed to find translated page\0".as_ptr() as *const i8,
            core::ptr::null(),
            core::ptr::null_mut(),
            POPUP_WAIT_NONE,
        );
        return;
    }

    index = 0;
    while !(*entry.offset(index as isize)).Buffer.is_null() {
        CONSOLE_ClearStyledText(
            (*entry.offset(index as isize)).X,
            (*entry.offset(index as isize)).Y,
            ((*entry.offset(index as isize)).Flags) as INT,
            (strlen((*entry.offset(index as isize)).Buffer) as USHORT) as SHORT,
        );
        index = index.wrapping_add(1);
    }
}
#[no_mangle]
pub unsafe extern "C" fn MUIDisplayPage(page: u32) {
    let mut entry: *const MUI_ENTRY = core::ptr::null();
    let mut index: u32;

    entry = FindMUIEntriesOfPage(page);
    if entry.is_null() {
        PopupError(
            b"Error: Failed to find translated page\0".as_ptr() as *const i8,
            core::ptr::null(),
            core::ptr::null_mut(),
            POPUP_WAIT_NONE,
        );
        return;
    }

    index = 0;
    while !(*entry.add(index as usize)).Buffer.is_null() {
        CONSOLE_SetStyledText(
            (*entry.add(index as usize)).X,
            (*entry.add(index as usize)).Y,
            ((*entry.add(index as usize)).Flags) as INT,
            (*entry.add(index as usize)).Buffer,
        );

        index = index.wrapping_add(1);
    }
}
#[no_mangle]
pub unsafe extern "C" fn MUIDisplayErrorV(
    ErrorNum: ULONG,
    Ir: PINPUT_RECORD,
    WaitEvent: ULONG,
    args: va_list,
) {
    let entry: *const MUI_ERROR;
    let mut Buffer: [CHAR; 2048] = [0; 2048];

    if ErrorNum >= ERROR_LAST_ERROR_CODE {
        PopupError(
            b"Invalid error number provided\0".as_ptr() as PCSTR,
            b"Press ENTER to continue\0".as_ptr() as PCSTR,
            Ir,
            POPUP_WAIT_ENTER,
        );
        return;
    }

    entry = FindMUIErrorEntries();
    if entry.is_null() {
        PopupError(
            b"Error: Failed to find translated error message\0".as_ptr() as PCSTR,
            core::ptr::null(),
            core::ptr::null_mut(),
            POPUP_WAIT_NONE,
        );
        return;
    }

    vsprintf(
        Buffer.as_mut_ptr() as *mut i8,
        (*entry.add(ErrorNum as usize)).ErrorText as *const i8,
        args,
    );

    PopupError(
        Buffer.as_ptr() as PCSTR,
        (*entry.add(ErrorNum as usize)).ErrorStatus as PCSTR,
        Ir,
        WaitEvent,
    );
}

