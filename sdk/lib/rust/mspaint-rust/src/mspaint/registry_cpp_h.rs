    pub unsafe fn SetMostRecentFile(&mut self, szPathName: LPCWSTR) {
        let this_: *mut Self = self;
        // Register the file to the user's 'Recent' folder
        if !szPathName.is_null() && *szPathName.offset(0 as isize) != 0 {
            SHAddToRecentDocs(SHARD_PATHW, (szPathName).cast());
        }
    
        // If szPathName is present in strFiles, move it to the top of the list
        let mut i: i32 = (MAX_RECENT_FILES - 1) as i32;
        let mut iFound: i32 = -1;
        while i > 0 {
            if iFound < 0
                && (*this_).strFiles[i as usize].CompareNoCase(szPathName) == 0
            {
                iFound = i;
            }
    
            if iFound >= 0 {
                // ATL's Swap(a, b).
                core::ptr::swap(
                    core::ptr::addr_of_mut!((*this_).strFiles[i as usize]),
                    core::ptr::addr_of_mut!((*this_).strFiles[(i - 1) as usize]),
                );
            }
            i -= 1;
        }
    
        // If szPathName is not the first item in strFiles, insert it at the top of the list
        if (*this_).strFiles[0 as usize].CompareNoCase(szPathName) != 0 {
            let mut i: i32 = (MAX_RECENT_FILES - 1) as i32;
            while i > 0 {
                (*this_).strFiles[i as usize] = (*this_).strFiles[(i - 1) as usize].clone();
                i -= 1;
            }
    
            (*this_).strFiles[0 as usize] = CStringW::from_ptr(szPathName);
        }
    }
