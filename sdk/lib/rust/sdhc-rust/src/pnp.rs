//! The device stacks: our FDO on the HAL's `ACPI\BRCME88C` PDO, and one child
//! PDO for the card, which disk.sys attaches to through `GenDisk`.
//!
//!   disk.sys FDO (+ partmgr)          classpnp sends SRBs and storage IOCTLs
//!   our disk PDO                      ── queued to the worker thread ──┐
//!   our FDO                           IRP_MN_START_DEVICE: init the card│
//!   HAL PDO (ACPI\BRCME88C)                                             │
//!                                     worker: one SRB at a time, PIO ◄─┘
//!
//! One controller per machine (the Pi 4 has one card slot), so the state is
//! static. The card is initialised once, at START; it is never stopped or
//! removed (the slot has no card-detect line, so a swap cannot be seen).

