static FDO: AtomicPtr<DEVICE_OBJECT> = AtomicPtr::new(null_mut());
static LOWER: AtomicPtr<DEVICE_OBJECT> = AtomicPtr::new(null_mut());
static DISK: AtomicPtr<DEVICE_OBJECT> = AtomicPtr::new(null_mut());
static CLAIMED: AtomicBool = AtomicBool::new(false);
/// Written once in START, before DISK is published; read-only afterwards.
static mut HOST: Option<Host> = None;
static mut IDENT: Ident = Ident { product: [0; 5], revision: [0; 3], serial: 0 };
/// SRBs waiting for the worker, linked through Irp->Tail.Overlay.ListEntry.
static mut QUEUE: LIST_ENTRY = unsafe { core::mem::zeroed() };
static mut QUEUE_LOCK: ntkrnl_sys::ke::KSPIN_LOCK = 0;
static mut QUEUE_EVENT: KEVENT = unsafe { core::mem::zeroed() };

unsafe fn status_of(irp: PIRP) -> NTSTATUS {
    (*irp).IoStatus.__bindgen_anon_1.Status
}

unsafe fn complete(irp: PIRP, status: NTSTATUS, information: usize) -> NTSTATUS {
    (*irp).IoStatus.__bindgen_anon_1.Status = status;
    (*irp).IoStatus.Information = information as _;
    IoCompleteRequest(irp, 0);
    status
}

unsafe fn pass_down(irp: PIRP) -> NTSTATUS {
    IoSkipCurrentIrpStackLocation(irp);
    IoCallDriver(LOWER.load(Ordering::Acquire), irp)
}

pub unsafe extern "system" fn add_device(driver: PDRIVER_OBJECT, pdo: PDEVICE_OBJECT) -> NTSTATUS {
    if !FDO.load(Ordering::Acquire).is_null() {
        sdprint!("a second SD host was ignored\n");
        return STATUS_NO_SUCH_DEVICE;
    }
    let mut fdo: PDEVICE_OBJECT = null_mut();
    let status = IoCreateDevice(driver, 0, null_mut(), FILE_DEVICE_CONTROLLER, FILE_DEVICE_SECURE_OPEN, 0, &mut fdo);
    if status < 0 {
        sdprint!("IoCreateDevice (host) failed {:#010x}\n", status as u32);
        return status;
    }
    let lower = ntkrnl_sys::ddk::IoAttachDeviceToDeviceStack(fdo, pdo);
    if lower.is_null() {
        ntkrnl_sys::ddk::IoDeleteDevice(fdo);
        return STATUS_NO_SUCH_DEVICE;
    }
    LOWER.store(lower, Ordering::Release);
    FDO.store(fdo, Ordering::Release);
    (*fdo).Flags &= !DO_DEVICE_INITIALIZING;
    STATUS_SUCCESS
}

pub unsafe extern "system" fn dispatch(device: PDEVICE_OBJECT, irp: PIRP) -> NTSTATUS {
    if device == FDO.load(Ordering::Acquire) {
        fdo_dispatch(irp)
    } else if !device.is_null() && device == DISK.load(Ordering::Acquire) {
        disk_dispatch(device, irp)
    } else {
        complete(irp, STATUS_INVALID_DEVICE_REQUEST, 0)
    }
}

