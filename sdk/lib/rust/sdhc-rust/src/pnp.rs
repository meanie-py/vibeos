// The start-time self-test
// ---------------------------------------------------------------------------

/// Read the partition table and a timed run of sectors, then prove the write
/// path on the last sectors of the card, but only where no MBR partition
/// reaches: save them, write a pattern, read it back, restore, verify. All
/// four transfer commands run (multi- and single-block, read and write).
unsafe fn self_test(host: &Host) {
    const RUN: usize = 64 * 1024;
    const PROBE: usize = 8;
    let buf = ExAllocatePoolWithTag(NON_PAGED_POOL as _, (RUN + 3 * PROBE * SECTOR) as _, SDHC_POOL_TAG) as *mut u8;
    if buf.is_null() {
        sdprint!("self-test: no memory\n");
        return;
    }
    let mbr = core::slice::from_raw_parts_mut(buf, SECTOR);
    if let Err(e) = host.read(0, 1, buf) {
        sdprint!("self-test: reading the MBR failed: {:?}\n", e);
        ExFreePoolWithTag(buf.cast(), SDHC_POOL_TAG);
        return;
    }
    let signed = mbr[510] == 0x55 && mbr[511] == 0xAA;
    let mut end = 0u64;
    let mut gpt = false;
    for i in 0..4 {
        let e = &mbr[446 + 16 * i..462 + 16 * i];
        let kind = e[4];
        let first = u32::from_le_bytes([e[8], e[9], e[10], e[11]]) as u64;
        let count = u32::from_le_bytes([e[12], e[13], e[14], e[15]]) as u64;
        if kind == 0 {
            continue;
        }
        gpt |= kind == 0xEE;
        end = end.max(first + count);
        sdprint!("self-test: partition {} type {:#04x} at LBA {}, {} sectors\n", i + 1, kind, first, count);
    }
    if !signed {
        sdprint!("self-test: sector 0 holds no MBR signature\n");
    }

    let t0 = now_us();
    let sectors = RUN / SECTOR;
    let mut lba = 0;
    let mut ok = true;
    while lba < 2048 && ok {
        ok = host.read(lba as u64, sectors as u16, buf).is_ok();
        lba += sectors;
    }
    let us = elapsed_us(t0).max(1);
    sdprint!("self-test: read {} KiB in {} ms ({} KiB/s){}\n", lba / 2, us / 1000, lba as u64 * 512 * 1_000_000 / 1024 / us, if ok { "" } else { " - FAILED" });

    let probe = host.card.blocks.saturating_sub(PROBE as u64);
    if !WRITE_SELF_TEST {
        ExFreePoolWithTag(buf.cast(), SDHC_POOL_TAG);
        return;
    }
    if !signed || gpt || probe < end || probe == 0 {
        sdprint!("self-test: no sectors outside the partitions; write path not tested\n");
        ExFreePoolWithTag(buf.cast(), SDHC_POOL_TAG);
        return;
    }
    let saved = buf.add(RUN);
    let pattern = saved.add(PROBE * SECTOR);
    let back = pattern.add(PROBE * SECTOR);
    for i in 0..PROBE * SECTOR {
        *pattern.add(i) = (i as u32 ^ (i as u32 >> 9) * 0x9E ^ host.card.serial) as u8;
    }
    let same = |a: *const u8, b: *const u8| {
        core::slice::from_raw_parts(a, PROBE * SECTOR) == core::slice::from_raw_parts(b, PROBE * SECTOR)
    };
    let verdict = (|| {
        host.read(probe, PROBE as u16, saved).map_err(|e| ("save", e))?;
        host.write(probe, PROBE as u16, pattern).map_err(|e| ("write (multi)", e))?;
        for i in 0..PROBE {
            host.read(probe + i as u64, 1, back.add(i * SECTOR)).map_err(|e| ("read back (single)", e))?;
        }
        let matched = same(pattern, back);
        for i in 0..PROBE {
            host.write(probe + i as u64, 1, saved.add(i * SECTOR)).map_err(|e| ("restore (single)", e))?;
        }
        host.read(probe, PROBE as u16, back).map_err(|e| ("verify (multi)", e))?;
        Ok((matched, same(saved, back)))
    })();
    match verdict {
        Ok((true, true)) => sdprint!("self-test: write path OK at LBA {} ({} sectors, restored)\n", probe, PROBE),
        Ok((matched, restored)) => sdprint!(
            "self-test: write path FAILED at LBA {}: pattern {} , restore {}\n",
            probe,
            if matched { "read back" } else { "MISMATCHED" },
            if restored { "verified" } else { "MISMATCHED" }
        ),
        Err((step, e)) => sdprint!("self-test: write path FAILED at LBA {}: {} failed: {:?}\n", probe, step, e),
    }
    ExFreePoolWithTag(buf.cast(), SDHC_POOL_TAG);
}

