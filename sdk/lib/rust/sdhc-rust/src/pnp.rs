unsafe fn fdo_dispatch(irp: PIRP) -> NTSTATUS {
    let io = IoGetCurrentIrpStackLocation(irp);
    match ((*io).MajorFunction, (*io).MinorFunction) {
        (IRP_MJ_PNP, IRP_MN_START_DEVICE) => {
            let status = if IoForwardIrpSynchronously(LOWER.load(Ordering::Acquire), irp) == 0 {
                STATUS_NO_SUCH_DEVICE
            } else if status_of(irp) < 0 {
                status_of(irp)
            } else {
                start(io)
            };
            complete(irp, status, 0)
        }
        (IRP_MJ_PNP, IRP_MN_QUERY_DEVICE_RELATIONS)
            if (*io).Parameters.QueryDeviceRelations.Type as i32 == BUS_RELATIONS =>
        {
            let disk = DISK.load(Ordering::Acquire);
            if !disk.is_null() {
                let prior = (*irp).IoStatus.Information as PDEVICE_RELATIONS;
                let mut out: PVOID = null_mut();
                let status = relations(prior, disk, &mut out);
                if status < 0 {
                    return complete(irp, status, 0);
                }
                (*irp).IoStatus.__bindgen_anon_1.Status = STATUS_SUCCESS;
                (*irp).IoStatus.Information = out as _;
            }
            pass_down(irp)
        }
        (IRP_MJ_PNP, minor) => {
            if minor == IRP_MN_REMOVE_DEVICE {
                // The card stays initialised for the life of the system.
                sdprint!("SD host removal is not supported\n");
            }
            pass_down(irp)
        }
        (IRP_MJ_POWER, _) => {
            PoStartNextPowerIrp(irp);
            IoSkipCurrentIrpStackLocation(irp);
            PoCallDriver(LOWER.load(Ordering::Acquire), irp)
        }
        (IRP_MJ_CREATE | IRP_MJ_CLOSE, _) => complete(irp, STATUS_SUCCESS, 0),
        _ => pass_down(irp),
    }
}

/// A DEVICE_RELATIONS holding `prior`'s objects and `extra` (referenced).
unsafe fn relations(prior: PDEVICE_RELATIONS, extra: PDEVICE_OBJECT, out: *mut PVOID) -> NTSTATUS {
    let n = if prior.is_null() { 0 } else { (*prior).Count as usize };
    let header = offset_of!(ntkrnl_sys::ddk::DEVICE_RELATIONS, Objects);
    let size = header + (n + 1) * core::mem::size_of::<PDEVICE_OBJECT>();
    let r = ExAllocatePoolWithTag(PAGED_POOL as _, size as _, SDHC_POOL_TAG) as PDEVICE_RELATIONS;
    if r.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    let objects = (*r).Objects.as_mut_ptr();
    if n > 0 {
        core::ptr::copy_nonoverlapping((*prior).Objects.as_ptr(), objects, n);
        ExFreePoolWithTag(prior as PVOID, 0);
    }
    ObReferenceObject(extra as PVOID);
    *objects.add(n) = extra;
    (*r).Count = (n + 1) as ULONG;
    *out = r as PVOID;
    STATUS_SUCCESS
}

/// Map the registers, bring the card up, and publish the disk.
unsafe fn start(io: PIO_STACK_LOCATION) -> NTSTATUS {
    let list = (*io).Parameters.StartDevice.AllocatedResourcesTranslated;
    if list.is_null() || (*list).Count == 0 {
        sdprint!("START_DEVICE carried no resources\n");
        return STATUS_DEVICE_CONFIGURATION_ERROR;
    }
    let partial = &(*(*list).List.as_ptr()).PartialResourceList;
    let descs = core::slice::from_raw_parts(partial.PartialDescriptors.as_ptr(), partial.Count as usize);
    let Some(mem) = descs.iter().find(|d| d.Type == CM_RESOURCE_TYPE_MEMORY) else {
        sdprint!("START_DEVICE carried no register window\n");
        return STATUS_DEVICE_CONFIGURATION_ERROR;
    };
    let mut pa: PHYSICAL_ADDRESS = core::mem::zeroed();
    pa.QuadPart = mem.u.Memory.Start.QuadPart;
    let len = mem.u.Memory.Length;
    let regs = MmMapIoSpace(pa, len as _, _MEMORY_CACHING_TYPE_MmNonCached) as *mut u8;
    if regs.is_null() {
        sdprint!("could not map the registers at {:#x}\n", pa.QuadPart);
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    sdprint!("host started, regs {:#x}+{:#x}\n", pa.QuadPart, len);
    // Nothing may signal until a waiter arms it (irq.rs); the firmware can leave
    // signals enabled with status latched.
    crate::irq::quiet(regs);
    match descs.iter().find(|d| d.Type == CM_RESOURCE_TYPE_INTERRUPT) {
        Some(int) => {
            let i = int.u.Interrupt;
            crate::irq::connect(
                regs,
                i.Vector,
                i.Level as u8,
                i.Affinity as _,
                int.Flags & CM_RESOURCE_INTERRUPT_LATCHED != 0,
                int.ShareDisposition == CM_RESOURCE_SHARE_SHARED,
            );
        }
        None => sdprint!("no interrupt resource: polling\n"),
    }

    let mut host = Host::new(regs);
    let t0 = now_us();
    if let Err(e) = host.init() {
        // No card (or one we cannot drive): the host stays started, with no disk.
        sdprint!("no usable card: {:?}\n", e);
        return STATUS_SUCCESS;
    }
    let c = host.card;
    sdprint!(
        "card: {} '{}' rev {}.{} serial {:08x}, {} sectors ({} MiB), RCA {:#06x}, {} kHz 4-bit, ready in {} ms\n",
        if c.high_capacity { "SDHC/SDXC" } else { "SDSC" },
        core::str::from_utf8(&c.name).unwrap_or("?"),
        c.revision >> 4,
        c.revision & 0xF,
        c.serial,
        c.blocks,
        c.blocks / 2048,
        c.rca,
        c.clock_hz / 1000,
        elapsed_us(t0) / 1000
    );
    IDENT = Ident::of(&host);
    self_test(&host);
    HOST = Some(host);

    InitializeListHead(&raw mut QUEUE);
    KeInitializeEvent(&raw mut QUEUE_EVENT, SYNCHRONIZATION_EVENT as _, 0);
    let mut thread: HANDLE = null_mut();
    let status =
        PsCreateSystemThread(&mut thread, THREAD_ALL_ACCESS, null_mut(), null_mut(), null_mut(), Some(worker), null_mut());
    if status < 0 {
        sdprint!("PsCreateSystemThread failed {:#010x}\n", status as u32);
        return STATUS_SUCCESS;
    }
    ZwClose(thread);

    let fdo = FDO.load(Ordering::Acquire);
    let mut disk: PDEVICE_OBJECT = null_mut();
    let status = IoCreateDevice(
        (*fdo).DriverObject,
        0,
        null_mut(),
        FILE_DEVICE_MASS_STORAGE,
        FILE_AUTOGENERATED_DEVICE_NAME | FILE_DEVICE_SECURE_OPEN,
        0,
        &mut disk,
    );
    if status < 0 {
        sdprint!("IoCreateDevice (disk) failed {:#010x}\n", status as u32);
        return STATUS_SUCCESS;
    }
    (*disk).Flags |= DO_DIRECT_IO;
    (*disk).Flags &= !DO_DEVICE_INITIALIZING;
    DISK.store(disk, Ordering::Release);
    sdprint!("disk published ({})\n", if WRITE_ENABLED { "read/write" } else { "read-only" });
    STATUS_SUCCESS
}

