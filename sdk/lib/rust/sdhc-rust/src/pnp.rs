unsafe fn disk_dispatch(device: PDEVICE_OBJECT, irp: PIRP) -> NTSTATUS {
    let io = IoGetCurrentIrpStackLocation(irp);
    match (*io).MajorFunction {
        IRP_MJ_SCSI => {
            let srb = (*io).Parameters.Scsi.Srb as *mut Srb;
            match (*srb).Function {
                scsi::SRB_FUNCTION_EXECUTE_SCSI => {
                    if TRACE {
                        let c = (*srb).Cdb;
                        sdprint!(
                            "trace: srb {:p} op {:#04x} cdb {:02x?} len {} flags {:#x} tid {:p} mdl {:p} buf {:p}\n",
                            srb,
                            c[0],
                            &c[..(*srb).CdbLength.min(16) as usize],
                            (*srb).DataTransferLength,
                            (*srb).SrbFlags,
                            ntkrnl_sys::ddk::PsGetCurrentThreadId(),
                            (*irp).MdlAddress,
                            (*srb).DataBuffer
                        );
                    }
                    IoMarkIrpPending(irp);
                    (*srb).SrbStatus = scsi::SRB_STATUS_PENDING;
                    {
                        let _g = ntkrnl_sys::guards::SpinLockGuard::acquire(&raw mut QUEUE_LOCK);
                        InsertTailList(&raw mut QUEUE, &raw mut (*irp).Tail.Overlay.__bindgen_anon_2.ListEntry);
                    }
                    KeSetEvent(&raw mut QUEUE_EVENT, 0, 0);
                    STATUS_PENDING
                }
                scsi::SRB_FUNCTION_CLAIM_DEVICE => {
                    if CLAIMED.swap(true, Ordering::AcqRel) {
                        (*srb).SrbStatus = scsi::SRB_STATUS_BUSY;
                        return complete(irp, STATUS_DEVICE_BUSY, 0);
                    }
                    (*srb).DataBuffer = device.cast();
                    (*srb).SrbStatus = scsi::SRB_STATUS_SUCCESS;
                    complete(irp, STATUS_SUCCESS, 0)
                }
                scsi::SRB_FUNCTION_RELEASE_DEVICE => {
                    CLAIMED.store(false, Ordering::Release);
                    (*srb).SrbStatus = scsi::SRB_STATUS_SUCCESS;
                    complete(irp, STATUS_SUCCESS, 0)
                }
                // One request at a time, completed in order, and no write
                // cache: nothing to release, flush or lock.
                scsi::SRB_FUNCTION_RELEASE_QUEUE
                | scsi::SRB_FUNCTION_FLUSH_QUEUE
                | scsi::SRB_FUNCTION_LOCK_QUEUE
                | scsi::SRB_FUNCTION_UNLOCK_QUEUE
                | scsi::SRB_FUNCTION_FLUSH
                | scsi::SRB_FUNCTION_SHUTDOWN => {
                    (*srb).SrbStatus = scsi::SRB_STATUS_SUCCESS;
                    complete(irp, STATUS_SUCCESS, 0)
                }
                f => {
                    sdprint!("SRB function {:#04x} not supported\n", f);
                    (*srb).SrbStatus = scsi::SRB_STATUS_INVALID_REQUEST;
                    complete(irp, scsi::STATUS_NOT_SUPPORTED, 0)
                }
            }
        }
        IRP_MJ_DEVICE_CONTROL => {
            let p = (*io).Parameters.DeviceIoControl;
            if TRACE {
                sdprint!("trace: ioctl {:#010x} out {} tid {:p}\n", p.IoControlCode, p.OutputBufferLength, ntkrnl_sys::ddk::PsGetCurrentThreadId());
            }
            let (status, n) = scsi::device_control(
                &*(&raw const IDENT),
                irp,
                p.IoControlCode,
                p.InputBufferLength as usize,
                p.OutputBufferLength as usize,
            );
            complete(irp, status, n)
        }
        IRP_MJ_PNP => disk_pnp(device, irp, io),
        IRP_MJ_POWER => {
            PoStartNextPowerIrp(irp);
            complete(irp, STATUS_SUCCESS, 0)
        }
        IRP_MJ_CREATE | IRP_MJ_CLOSE => complete(irp, STATUS_SUCCESS, 0),
        _ => {
            let status = status_of(irp);
            complete(irp, status, (*irp).IoStatus.Information as usize)
        }
    }
}

/// A multi-sz of `parts` in paged pool, for IRP_MN_QUERY_ID / DEVICE_TEXT.
unsafe fn wide_multi_sz(parts: &[&[u8]], multi: bool) -> PVOID {
    let chars: usize = parts.iter().map(|p| p.len() + 1).sum::<usize>() + multi as usize;
    let p = ExAllocatePoolWithTag(PAGED_POOL as _, (chars * 2) as _, SDHC_POOL_TAG) as *mut u16;
    if p.is_null() {
        return null_mut();
    }
    let mut at = 0;
    for part in parts {
        for &b in *part {
            *p.add(at) = b as u16;
            at += 1;
        }
        *p.add(at) = 0;
        at += 1;
    }
    if multi {
        *p.add(at) = 0;
    }
    p.cast()
}

unsafe fn disk_pnp(device: PDEVICE_OBJECT, irp: PIRP, io: PIO_STACK_LOCATION) -> NTSTATUS {
    let ident = &*(&raw const IDENT);
    match (*io).MinorFunction {
        IRP_MN_START_DEVICE
        | IRP_MN_QUERY_REMOVE_DEVICE
        | IRP_MN_CANCEL_REMOVE_DEVICE
        | IRP_MN_STOP_DEVICE
        | IRP_MN_QUERY_STOP_DEVICE
        | IRP_MN_CANCEL_STOP_DEVICE
        | IRP_MN_SURPRISE_REMOVAL
        | IRP_MN_DEVICE_USAGE_NOTIFICATION
        // The disk lives as long as the host: a removal leaves it in place.
        | IRP_MN_REMOVE_DEVICE => complete(irp, STATUS_SUCCESS, 0),
        IRP_MN_QUERY_ID => {
            // SD\Disk&Prod_<CID name>&Rev_<n.m>, then less specific, then GenDisk,
            // which the critical device database maps to disk.sys.
            let mut full = [0u8; 40];
            let head: &[u8] = b"SD\\Disk&Prod_";
            let mut n = 0;
            for s in [head, &ident.product, b"&Rev_", &ident.revision] {
                full[n..n + s.len()].copy_from_slice(s);
                n += s.len();
            }
            let full = &full[..n];
            let product = &full[..head.len() + ident.product.len()];
            let mut instance = [0u8; 8];
            for (i, c) in instance.iter_mut().enumerate() {
                *c = b"0123456789ABCDEF"[(ident.serial >> (28 - 4 * i)) as usize & 0xF];
            }
            let ids = match (*io).Parameters.QueryId.IdType as i32 {
                BUS_QUERY_DEVICE_ID => wide_multi_sz(&[full], false),
                BUS_QUERY_HARDWARE_IDS => wide_multi_sz(&[full, product, b"SD\\Disk", b"GenDisk"], true),
                BUS_QUERY_COMPATIBLE_IDS => wide_multi_sz(&[b"SD\\Disk", b"GenDisk"], true),
                BUS_QUERY_INSTANCE_ID => wide_multi_sz(&[&instance], false),
                _ => return complete(irp, status_of(irp), (*irp).IoStatus.Information as usize),
            };
            if ids.is_null() {
                return complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0);
            }
            complete(irp, STATUS_SUCCESS, ids as usize)
        }
        IRP_MN_QUERY_DEVICE_TEXT
            if (*io).Parameters.QueryDeviceText.DeviceTextType as i32 == DEVICE_TEXT_DESCRIPTION =>
        {
            let text = wide_multi_sz(&[b"SD Memory Card"], false);
            if text.is_null() {
                return complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0);
            }
            complete(irp, STATUS_SUCCESS, text as usize)
        }
        IRP_MN_QUERY_CAPABILITIES => {
            let caps = &mut *(*io).Parameters.DeviceCapabilities.Capabilities;
            caps.set_Removable(0);
            caps.set_UniqueID(0);
            caps.set_SilentInstall(1);
            caps.set_RawDeviceOK(0);
            caps.set_SurpriseRemovalOK(0);
            caps.Address = 0;
            caps.UINumber = 0;
            for (i, s) in caps.DeviceState.iter_mut().enumerate() {
                *s = if i == POWER_SYSTEM_WORKING { POWER_DEVICE_D0 } else { POWER_DEVICE_D3 } as _;
            }
            complete(irp, STATUS_SUCCESS, 0)
        }
        IRP_MN_QUERY_DEVICE_RELATIONS
            if (*io).Parameters.QueryDeviceRelations.Type as i32 == TARGET_DEVICE_RELATION =>
        {
            let mut out: PVOID = null_mut();
            let status = relations(null_mut(), device, &mut out);
            complete(irp, status, out as usize)
        }
        // Resources, bus information, device state, ...: nothing to add.
        _ => complete(irp, status_of(irp), (*irp).IoStatus.Information as usize),
    }
}

// ---------------------------------------------------------------------------
// The worker: every SRB that moves data runs here, at PASSIVE_LEVEL, in order
// ---------------------------------------------------------------------------

unsafe extern "system" fn worker(_context: PVOID) {
    loop {
        // A timed wait, so an io: window still open when the card goes quiet
        // is reported then, not left until the next request.
        let mut idle: ntkrnl_sys::ddk::LARGE_INTEGER = core::mem::zeroed();
        idle.QuadPart = -(IDLE_FLUSH_MS * 10_000);
        if KeWaitForSingleObject((&raw mut QUEUE_EVENT).cast(), 0, 0, 0, &mut idle) == STATUS_TIMEOUT {
            io_flush(now_us());
            continue;
        }
        loop {
            let entry = {
                let _g = ntkrnl_sys::guards::SpinLockGuard::acquire(&raw mut QUEUE_LOCK);
                if IsListEmpty(&raw const QUEUE) { null_mut() } else { RemoveHeadList(&raw mut QUEUE) }
            };
            if entry.is_null() {
                break;
            }
            let irp = (entry as *mut u8).sub(offset_of!(IRP, Tail.Overlay.__bindgen_anon_2.ListEntry)) as PIRP;
            execute(irp);
        }
    }
}

unsafe fn execute(irp: PIRP) {
    let io = IoGetCurrentIrpStackLocation(irp);
    let srb = (*io).Parameters.Scsi.Srb as *mut Srb;
    let mut data = (*srb).DataBuffer as *mut u8;
    let mdl = (*irp).MdlAddress;
    if (*srb).DataTransferLength != 0 && !mdl.is_null() {
        // DataBuffer is an address in the MDL's range; reach it through the
        // system mapping, since the worker is not in the requester's context.
        let system = MmGetSystemAddressForMdlSafe(mdl, NORMAL_PAGE_PRIORITY) as *mut u8;
        if system.is_null() {
            (*srb).SrbStatus = scsi::SRB_STATUS_ERROR;
            complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0);
            return;
        }
        let va = ((*mdl).StartVa as usize) + (*mdl).ByteOffset as usize;
        data = system.add(data as usize - va);
    }
    // The disk is published only after HOST is set, so this cannot miss; if
    // it ever does, fail the request rather than the machine.
    let Some(host) = (*(&raw const HOST)).as_ref() else {
        sdprint!("an SRB reached the disk before the card was up\n");
        (*srb).SrbStatus = scsi::SRB_STATUS_ERROR;
        complete(irp, STATUS_DEVICE_CONFIGURATION_ERROR, 0);
        return;
    };
    let status = scsi::execute(host, &*(&raw const IDENT), WRITE_ENABLED, srb, data);
    let n = if status >= 0 { (*srb).DataTransferLength as usize } else { 0 };
    io_rate(&*srb, n);
    if TRACE {
        sdprint!("trace: done srb {:p} op {:#04x} srb {:#04x} status {:#010x} n {}\n", srb, (*srb).Cdb[0], (*srb).SrbStatus, status as u32, n);
    }
    (*irp).IoStatus.__bindgen_anon_1.Status = status;
    (*irp).IoStatus.Information = n as _;
    // Complete at DISPATCH_LEVEL, the context a port driver completes SRBs in
    // (from its DPC), so classpnp's completion routines see what they would
    // under storport or usbstor.
    let _dpc = ntkrnl_sys::guards::IrqlGuard::raise_to_dpc();
    IoCompleteRequest(irp, 1); // IO_DISK_INCREMENT
}

/// One `[SDHC] io:` line at most every IO_RATE_US while the card is busy:
/// requests, sectors and the mean request size, so a slow volume operation
/// shows as a rate rather than as a silent hang. Called only from the worker.
const IO_RATE_US: u64 = 5_000_000;
const IDLE_FLUSH_MS: i64 = 1_000;
const STATUS_TIMEOUT: NTSTATUS = 0x0000_0102;
static mut IO_WINDOW: (u64, u64, u64, u64) = (0, 0, 0, 0); // start, requests, read, written

unsafe fn io_rate(srb: &Srb, bytes: usize) {
    let w = &mut *(&raw mut IO_WINDOW);
    let now = now_us();
    if w.0 == 0 {
        w.0 = now;
    }
    match srb.Cdb[0] {
        0x08 | 0x28 | 0xA8 | 0x88 => w.2 += (bytes / SECTOR) as u64,
        0x0A | 0x2A | 0xAA | 0x8A => w.3 += (bytes / SECTOR) as u64,
        _ => return,
    }
    w.1 += 1;
    if now.wrapping_sub(w.0) >= IO_RATE_US {
        io_flush(now);
    }
}

/// Report and close the io: window, if anything happened in it.
unsafe fn io_flush(now: u64) {
    let w = &mut *(&raw mut IO_WINDOW);
    if w.1 != 0 {
        sdprint!(
            "io: {} requests in {} ms, {} sectors read, {} written ({} sectors per request)\n",
            w.1,
            now.wrapping_sub(w.0) / 1000,
            w.2,
            w.3,
            (w.2 + w.3) / w.1
        );
    }
    *w = (0, 0, 0, 0);
}
