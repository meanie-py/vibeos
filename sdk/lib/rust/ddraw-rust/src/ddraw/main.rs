unsafe extern "C" fn CF_CreateDirectDraw(mut UnkOuter: *mut IUnknown, iid: *const IID, mut obj: *mut *mut ::core::ffi::c_void) -> HRESULT {
    let mut hr: HRESULT;

    wined3d_mutex_lock();
    hr = DDRAW_Create(core::ptr::null_mut(), obj, UnkOuter, iid);
    wined3d_mutex_unlock();

    return hr;
}

unsafe extern "C" fn CF_CreateDirectDrawClipper(UnkOuter: *mut IUnknown, riid: *const IID, obj: *mut *mut ::core::ffi::c_void) -> HRESULT {
    let mut hr: HRESULT;
    let mut Clip: *mut IDirectDrawClipper = core::ptr::null_mut();

    wined3d_mutex_lock();
    hr = DirectDrawCreateClipper(0, core::ptr::addr_of_mut!(Clip), UnkOuter);
    if hr != DD_OK {
        wined3d_mutex_unlock();
        return hr;
    }

    hr = IDirectDrawClipper_QueryInterface(Clip, riid, obj);
    IDirectDrawClipper_Release(Clip);

    wined3d_mutex_unlock();

    return hr;
}

unsafe extern "C" fn impl_from_IClassFactory(iface: *mut IClassFactory) -> *mut ddraw_class_factory {
    return (iface as *mut u8).sub(core::mem::offset_of!(ddraw_class_factory, IClassFactory_iface)) as *mut ddraw_class_factory;
}
unsafe extern "system" fn ddraw_class_factory_QueryInterface(iface: *mut IClassFactory, riid: *const IID, out: *mut *mut core::ffi::c_void) -> HRESULT {
    if IsEqualGUID!(riid, core::ptr::addr_of!(IID_IUnknown))
        || IsEqualGUID!(riid, core::ptr::addr_of!(IID_IClassFactory))
    {
        IClassFactory_AddRef(iface);
        *out = iface as *mut core::ffi::c_void;
        return S_OK;
    }

    WARN!("%s not implemented, returning E_NOINTERFACE.\n", debugstr_guid(riid));

    return E_NOINTERFACE;
}
unsafe extern "system" fn ddraw_class_factory_AddRef(iface: *mut IClassFactory) -> ULONG {
    let factory: *mut ddraw_class_factory = impl_from_IClassFactory(iface);
    let ref_0: ULONG = InterlockedIncrement(core::ptr::addr_of_mut!((*factory).ref_) as *mut core::ffi::c_long) as ULONG;

    TRACE!("%p increasing refcount to %lu.\n", factory, ref_0);

    return ref_0;
}

