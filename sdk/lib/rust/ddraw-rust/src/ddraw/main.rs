#[no_mangle]
pub unsafe extern "system" fn DirectDrawEnumerateExA(
    callback: LPDDENUMCALLBACKEXA,
    context: *mut core::ffi::c_void,
    flags: DWORD,
) -> HRESULT {
    let mut wined3d: *mut wined3d = core::ptr::null_mut();

    WINE_TRACE!("callback %p, context %p, flags %#lx.\n", callback, context, flags);

    if flags & !(DDENUM_ATTACHEDSECONDARYDEVICES | DDENUM_DETACHEDSECONDARYDEVICES | DDENUM_NONDISPLAYDEVICES) != 0 {
        return DDERR_INVALIDPARAMS;
    }

    if flags & !DDENUM_ATTACHEDSECONDARYDEVICES != 0 {
        WINE_FIXME!("flags %#lx not handled\n", flags & !DDENUM_ATTACHEDSECONDARYDEVICES);
    }

    WINE_TRACE!("Enumerating ddraw interfaces\n");

    wined3d = wined3d_create(DDRAW_WINED3D_FLAGS);
    if wined3d.is_null() {
        wined3d = wined3d_create(DDRAW_WINED3D_FLAGS | WINED3D_NO3D);
        if wined3d.is_null() {
            WINE_WARN!("Failed to create a wined3d object.\n");
            return E_FAIL;
        }
        WINE_WARN!("Created a wined3d object without 3D support.\n");
    }

    // __TRY .. __EXCEPT_PAGE_FAULT: DUMMY_PSEH compiled the handler out of the C;
    // page_fault_try makes it real (comctl32's is_valid, the same idiom).
    if ntdll_sys::seh::page_fault_try(|| {
        static mut driver_desc: [CHAR; 15] =
            unsafe { ::core::mem::transmute::<[u8; 15], [CHAR; 15]>(*b"DirectDraw HAL\0") };
        static mut driver_name: [CHAR; 8] =
            unsafe { ::core::mem::transmute::<[u8; 8], [CHAR; 8]>(*b"display\0") };
        let mut cont_enum: BOOL = 0;

        WINE_TRACE!("Default interface: DirectDraw HAL\n");

        cont_enum = (callback.unwrap_unchecked())(
            core::ptr::null_mut::<GUID>(),
            core::ptr::addr_of_mut!(driver_desc) as LPSTR,
            core::ptr::addr_of_mut!(driver_name) as LPSTR,
            context as LPVOID,
            core::ptr::null_mut(),
        );

        if cont_enum != 0 && flags & DDENUM_ATTACHEDSECONDARYDEVICES != 0 {
            ddraw_enumerate_secondary_devices(wined3d, callback, context);
        }

    })
    .is_none()
    {
        wined3d_decref(wined3d);
        return DDERR_INVALIDPARAMS;
    }

    wined3d_decref(wined3d);
    WINE_TRACE!("End of enumeration\n");

    return DD_OK;
}

