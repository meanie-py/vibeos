#[repr(C)]
pub struct callback_info {
    pub callback: LPDDENUMCALLBACKA,
    pub context: *mut core::ffi::c_void,
}

// HRESULT WINAPI (x2): stray function prototype fragments, no declaration emitted.
// static const IClassFactoryVtbl IClassFactory_Vtbl: COM vtable, generated by vtbl_gen.py, skipped.

unsafe extern "system" fn enum_callback(
    guid: *mut GUID,
    description: *mut i8,
    driver_name: *mut i8,
    context: *mut core::ffi::c_void,
    monitor: HMONITOR,
) -> i32 {
    let _ = monitor;
    let info: *const callback_info = context as *const callback_info;
    return ((*info).callback.unwrap_unchecked())(
        guid,
        description,
        driver_name,
        (*info).context,
    );
}

unsafe extern "C" fn ddraw_enumerate_secondary_devices(
    mut wined3d: *mut wined3d,
    mut callback: LPDDENUMCALLBACKEXA,
    mut context: *mut ::core::ffi::c_void,
) {
    let mut adapter_id: wined3d_adapter_identifier = ::core::mem::zeroed();
    let mut wined3d_adapter: *mut wined3d_adapter = ::core::ptr::null_mut::<wined3d_adapter>();
    let mut output_desc: wined3d_output_desc = ::core::mem::zeroed();
    let mut wined3d_output: *mut wined3d_output = ::core::ptr::null_mut::<wined3d_output>();
    let mut interface_count: ::core::ffi::c_uint = 0;
    let mut adapter_idx: ::core::ffi::c_uint = 0;
    let mut output_idx: ::core::ffi::c_uint;
    let mut cont_enum: BOOL = (TRUE as i32);
    let mut hr: HRESULT;

    while cont_enum != 0 && {
        wined3d_adapter = wined3d_get_adapter(wined3d, adapter_idx);
        !wined3d_adapter.is_null()
    } {
        let mut device_name: [::core::ffi::c_char; 512] =
            [0; 512];
        let mut description: [::core::ffi::c_char; 512] =
            [0; 512];

        /* The Battle.net System Checker expects the GetAdapterIdentifier DeviceName to match the
         * Driver Name, so obtain the DeviceName and GUID from D3D. */
        memset(
            &raw mut adapter_id as *mut ::core::ffi::c_void,
            0x0 as ::core::ffi::c_int,
            ::core::mem::size_of::<wined3d_adapter_identifier>() as size_t,
        );
        adapter_id.description = description.as_mut_ptr();
        adapter_id.description_size =
            ::core::mem::size_of::<[::core::ffi::c_char; 512]>()
                as ::core::ffi::c_uint;

        wined3d_mutex_lock();
        hr = wined3d_adapter_get_identifier(
            wined3d_adapter,
            0x0 as uint32_t,
            &raw mut adapter_id,
        );
        if hr < 0 {
            WARN!("Failed to get adapter identifier, hr %#lx.\n", hr);
            wined3d_mutex_unlock();
            break;
        }
        wined3d_mutex_unlock();

        output_idx = 0 as ::core::ffi::c_uint;
        while cont_enum != 0 && {
            wined3d_output = wined3d_adapter_get_output(wined3d_adapter, output_idx);
            !wined3d_output.is_null()
        } {
            wined3d_mutex_lock();
            hr = wined3d_output_get_desc(wined3d_output, &raw mut output_desc);
            if hr < 0 {
                WARN!("Failed to get output description, hr %#lx.\n", hr);
                wined3d_mutex_unlock();
                break;
            }
            wined3d_mutex_unlock();

            WideCharToMultiByte(
                CP_ACP as UINT,
                0 as DWORD,
                &raw mut output_desc.device_name as *mut WCHAR as LPCWSTR,
                -(1 as ::core::ffi::c_int),
                device_name.as_mut_ptr() as LPSTR,
                ::core::mem::size_of::<[::core::ffi::c_char; 512]>()
                    as ::core::ffi::c_int,
                ::core::ptr::null::<CHAR>(),
                ::core::ptr::null_mut::<BOOL>(),
            );
            TRACE!(
                "Interface %u: %s\n",
                interface_count,
                wine_dbgstr_guid(&raw mut adapter_id.device_identifier),
            );
            interface_count = interface_count.wrapping_add(1);
            cont_enum = (callback.unwrap_unchecked())(
                &raw mut adapter_id.device_identifier,
                adapter_id.description as LPSTR,
                device_name.as_mut_ptr() as LPSTR,
                context as LPVOID,
                output_desc.monitor,
            );
            output_idx = output_idx.wrapping_add(1);
        }

        if hr < 0 {
            break;
        }

        adapter_idx = adapter_idx.wrapping_add(1);
    }
}
#[no_mangle]
pub unsafe extern "C" fn ddraw_handle_table_init(t: *mut ddraw_handle_table, initial_size: UINT) -> BOOL {
    (*t).entries = calloc(
        (initial_size as size_t) as _,
        (core::mem::size_of::<ddraw_handle_entry>() as size_t) as _,
    ) as *mut ddraw_handle_entry;
    if (*t).entries.is_null() {
        ERR!("Failed to allocate handle table memory.\n");
        return (FALSE) as BOOL;
    }
    (*t).free_entries = core::ptr::null_mut::<ddraw_handle_entry>();
    (*t).table_size = initial_size;
    (*t).entry_count = 0;

    return (TRUE) as BOOL;
}
#[no_mangle]
pub unsafe extern "C" fn ddraw_handle_table_destroy(t: *mut ddraw_handle_table) {
    free((*t).entries as *mut core::ffi::c_void);
    memset(t as *mut core::ffi::c_void, 0, core::mem::size_of::<ddraw_handle_table>() as usize);
}
#[no_mangle]
pub unsafe extern "C" fn ddraw_allocate_handle(
    mut t: *mut ddraw_handle_table,
    mut object: *mut ::core::ffi::c_void,
    mut type_0: ddraw_handle_type,
) -> DWORD {
    let mut entry: *mut ddraw_handle_entry = ::core::ptr::null_mut::<ddraw_handle_entry>();
    if t.is_null() {
        t = &raw mut global_handle_table;
    }
    if !(*t).free_entries.is_null() {
        let mut idx: DWORD = (*t).free_entries.offset_from((*t).entries) as DWORD;
        entry = (*t).free_entries;
        if (*entry).type_ as ::core::ffi::c_uint != DDRAW_HANDLE_FREE as ::core::ffi::c_uint {
            ERR!(
                "Handle %#lx (%p) is in the free list, but has type %#x.\n",
                idx,
                (*entry).object,
                (*entry).type_ as ::core::ffi::c_uint
            );
            return (DDRAW_INVALID_HANDLE) as DWORD;
        }
        (*t).free_entries = (*entry).object as *mut ddraw_handle_entry;
        (*entry).object = object;
        (*entry).type_ = type_0;
        return idx;
    }
    if !((*t).entry_count < (*t).table_size) {
        let mut new_size: UINT = (*t).table_size.wrapping_add((*t).table_size >> 1);
        let mut new_entries: *mut ddraw_handle_entry = ::core::ptr::null_mut::<ddraw_handle_entry>();
        new_entries = realloc(
            (*t).entries as *mut ::core::ffi::c_void,
            (new_size as usize).wrapping_mul(::core::mem::size_of::<ddraw_handle_entry>() as usize),
        ) as *mut ddraw_handle_entry;
        if new_entries.is_null() {
            ERR!("Failed to grow the handle table.\n");
            return (DDRAW_INVALID_HANDLE) as DWORD;
        }
        (*t).entries = new_entries;
        (*t).table_size = new_size;
    }
    entry = (*t).entries.offset((*t).entry_count as isize) as *mut ddraw_handle_entry;
    (*entry).object = object;
    (*entry).type_ = type_0;
    let fresh = (*t).entry_count;
    (*t).entry_count = (*t).entry_count.wrapping_add(1);
    return fresh;
}
#[no_mangle]
pub unsafe extern "C" fn ddraw_free_handle(
    mut t: *mut ddraw_handle_table,
    mut handle: DWORD,
    mut type_0: ddraw_handle_type,
) -> *mut core::ffi::c_void {
    let mut entry: *mut ddraw_handle_entry = core::ptr::null_mut();
    let mut object: *mut core::ffi::c_void = core::ptr::null_mut();

    if t.is_null() {
        t = core::ptr::addr_of_mut!(global_handle_table);
    }

    if handle == (DDRAW_INVALID_HANDLE) as u32 || handle >= (*t).entry_count {
        WARN!("Invalid handle %#lx passed.\n", handle);
        return core::ptr::null_mut();
    }

    entry = (*t).entries.offset(handle as isize) as *mut ddraw_handle_entry;
    if (*entry).type_ as core::ffi::c_uint != type_0 as core::ffi::c_uint {
        WARN!(
            "Handle %#lx (%p) is not of type %#x.\n",
            handle,
            (*entry).object,
            type_0 as core::ffi::c_uint
        );
        return core::ptr::null_mut();
    }

    object = (*entry).object;
    (*entry).object = (*t).free_entries as *mut core::ffi::c_void;
    (*entry).type_ = DDRAW_HANDLE_FREE;
    (*t).free_entries = entry;

    return object;
}
#[no_mangle]
pub unsafe extern "C" fn ddraw_get_object(mut t: *mut ddraw_handle_table, handle: DWORD, type_: ddraw_handle_type) -> *mut core::ffi::c_void {
    let mut entry: *mut ddraw_handle_entry;

    if t.is_null() {
        t = core::ptr::addr_of_mut!(global_handle_table);
    }

    if handle == (DDRAW_INVALID_HANDLE) as u32 || handle >= (*t).entry_count {
        WARN!("Invalid handle %#lx passed.\n", handle);
        return core::ptr::null_mut();
    }

    entry = (*t).entries.offset(handle as isize);
    if (*entry).type_ != type_ {
        WARN!("Handle %#lx (%p) is not of type %#x.\n", handle, (*entry).object, type_);
        return core::ptr::null_mut();
    }

    return (*entry).object;
}

#[no_mangle]
pub unsafe extern "system" fn GetSurfaceFromDC(
    mut dc: HDC,
    mut surface: *mut *mut IDirectDrawSurface4,
    mut device_dc: *mut HDC,
) -> HRESULT {
    let mut ddraw: *mut ddraw = core::ptr::null_mut::<ddraw>();
    WINE_TRACE!("dc %p, surface %p, device_dc %p.\n", dc, surface, device_dc);
    if surface.is_null() {
        return E_INVALIDARG;
    }
    if device_dc.is_null() {
        *surface = core::ptr::null_mut::<IDirectDrawSurface4>();
        return E_INVALIDARG;
    }
    wined3d_mutex_lock();
    ddraw = (global_ddraw_list.next as *mut core::ffi::c_char).offset(
        -(core::mem::offset_of!(ddraw, ddraw_list_entry) as core::ffi::c_ulonglong as isize),
    ) as *mut ddraw;
    while &raw mut (*ddraw).ddraw_list_entry != &raw mut global_ddraw_list {
        if IDirectDraw4_GetSurfaceFromDC(
            &raw mut (*ddraw).IDirectDraw4_iface,
            dc,
            surface as *mut LPDIRECTDRAWSURFACE4,
        ) < 0
        {
            ddraw = ((*ddraw).ddraw_list_entry.next as *mut core::ffi::c_char).offset(
                -(core::mem::offset_of!(ddraw, ddraw_list_entry) as core::ffi::c_ulonglong
                    as isize),
            ) as *mut ddraw;
        } else {
            *device_dc = core::ptr::null_mut::<HDC__>();
            wined3d_mutex_unlock();
            return DD_OK;
        }
    }
    wined3d_mutex_unlock();
    *surface = core::ptr::null_mut::<IDirectDrawSurface4>();
    *device_dc = core::ptr::null_mut::<HDC__>();
    return DDERR_NOTFOUND;
}

unsafe extern "C" fn DDRAW_Create(
    guid: *const GUID,
    out: *mut *mut ::core::ffi::c_void,
    outer_unknown: *mut IUnknown,
    iid: *const IID,
) -> HRESULT {
    let mut device_type: wined3d_device_type = 0 as wined3d_device_type;
    let mut ddraw: *mut ddraw = core::ptr::null_mut::<ddraw>();
    let mut flags: DWORD = 0;
    let mut hr: HRESULT = 0;

    TRACE!(
        "driver_guid %s, ddraw %p, outer_unknown %p, interface_iid %s.\n",
        debugstr_guid(guid),
        out,
        outer_unknown,
        debugstr_guid(iid)
    );

    *out = core::ptr::null_mut();

    if guid == DDCREATE_EMULATIONONLY as *mut GUID as *const GUID {
        device_type = WINED3D_DEVICE_TYPE_REF as wined3d_device_type;
    } else if guid == DDCREATE_HARDWAREONLY as *mut GUID as *const GUID {
        device_type = WINED3D_DEVICE_TYPE_HAL as wined3d_device_type;
    } else {
        device_type = WINED3D_DEVICE_TYPE_HAL as wined3d_device_type;
    }

    /* DDraw doesn't support aggregation, according to msdn */
    if !outer_unknown.is_null() {
        return CLASS_E_NOAGGREGATION;
    }

    if IsEqualGUID!(iid, core::ptr::addr_of!(IID_IDirectDraw7)) == false {
        flags = WINED3D_LEGACY_FFP_LIGHTING;
    }

    ddraw = calloc(
        1,
        (core::mem::size_of::<ddraw>() as size_t) as _,
    ) as *mut ddraw;
    if ddraw.is_null() {
        ERR!("Out of memory when creating DirectDraw.\n");
        return E_OUTOFMEMORY;
    }

    hr = ddraw_init(ddraw, flags, device_type);
    if hr < 0 {
        WARN!("Failed to initialize ddraw object, hr %#lx.\n", hr);
        free(ddraw as *mut ::core::ffi::c_void);
        return hr;
    }

    hr = IDirectDraw7_QueryInterface(
        core::ptr::addr_of_mut!((*ddraw).IDirectDraw7_iface),
        iid,
        out,
    );
    IDirectDraw7_Release(core::ptr::addr_of_mut!((*ddraw).IDirectDraw7_iface));
    if hr >= 0 {
        list_add_head(
            core::ptr::addr_of_mut!(global_ddraw_list),
            core::ptr::addr_of_mut!((*ddraw).ddraw_list_entry),
        );
    } else {
        WARN!(
            "Failed to query interface %s from ddraw object %p.\n",
            debugstr_guid(iid),
            ddraw
        );
    }

    return hr;
}

#[no_mangle]
pub unsafe extern "system" fn DirectDrawCreate(
    driver_guid: *mut GUID,
    ddraw: *mut *mut IDirectDraw,
    outer: *mut IUnknown,
) -> HRESULT {
    let mut hr: HRESULT = 0;
    WINE_TRACE!("driver_guid %s, ddraw %p, outer %p.\n", debugstr_guid(driver_guid), ddraw, outer);
    wined3d_mutex_lock();
    hr = DDRAW_Create(
        driver_guid,
        ddraw as *mut *mut ::core::ffi::c_void,
        outer,
        core::ptr::addr_of!(IID_IDirectDraw),
    );
    wined3d_mutex_unlock();

    if hr >= 0 {
        hr = IDirectDraw_Initialize(*ddraw, driver_guid);
        if hr < 0 {
            IDirectDraw_Release(*ddraw);
        }
    }

    return hr;
}

#[no_mangle]
pub unsafe extern "system" fn DirectDrawCreateEx(
    driver_guid: *mut GUID,
    ddraw: *mut *mut core::ffi::c_void,
    interface_iid: *const GUID,
    outer: *mut IUnknown,
) -> HRESULT {
    let mut hr: HRESULT = 0;

    if IsEqualGUID!(interface_iid, core::ptr::addr_of!(IID_IDirectDraw7)) == false {
        return DDERR_INVALIDPARAMS;
    }

    wined3d_mutex_lock();
    hr = DDRAW_Create(driver_guid, ddraw, outer, interface_iid);
    wined3d_mutex_unlock();

    if hr >= 0 {
        let mut ddraw7: *mut IDirectDraw7 = *(ddraw as *mut *mut IDirectDraw7);
        hr = IDirectDraw7_Initialize(ddraw7, driver_guid);
        if hr < 0 {
            IDirectDraw7_Release(ddraw7);
        }
    }

    return hr;
}

