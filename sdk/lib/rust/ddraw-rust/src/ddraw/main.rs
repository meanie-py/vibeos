    while (i as usize) < (ARRAY_SIZE!(object_creation) as usize) {
        if IsEqualGUID!(object_creation[i as usize].clsid, rclsid) != false {
            break;
        }
        i = i.wrapping_add(1);
    }
    if i as usize == (ARRAY_SIZE!(object_creation) as usize) {
        WINE_FIXME!("%s: no class found.\n", debugstr_guid(rclsid as *const _GUID));
        return CLASS_E_CLASSNOTAVAILABLE;
    }
    factory = calloc(
        1,
        (core::mem::size_of::<ddraw_class_factory>() as usize) as _,
    ) as *mut ddraw_class_factory;
