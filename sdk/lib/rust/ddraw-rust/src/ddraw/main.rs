pub unsafe extern "system" fn DllMain(inst: HINSTANCE, reason: DWORD, reserved: *mut core::ffi::c_void) -> BOOL {
    'sw: {
        match reason {
            DLL_PROCESS_ATTACH => {
                static mut ddraw_self: HMODULE = core::ptr::null_mut();
                let mut hkey: HKEY = core::ptr::null_mut();
                let mut wc: WNDCLASSA = core::mem::zeroed();

                wc.style = CS_HREDRAW | CS_VREDRAW;
                wc.lpfnWndProc = Some(DefWindowProcA);
                wc.cbClsExtra = 0;
                wc.cbWndExtra = 0;
                wc.hInstance = inst;
                wc.hIcon = core::ptr::null_mut();
                wc.hCursor = core::ptr::null_mut();
                wc.hbrBackground = GetStockObject((BLACK_BRUSH as i32)) as HBRUSH;
                wc.lpszMenuName = core::ptr::null_mut();
                wc.lpszClassName = (DDRAW_WINDOW_CLASS_NAME).as_ptr();
                if RegisterClassA(&raw mut wc) == 0 {
                    ERR!("Failed to register ddraw window class, last error %#lx.\n", GetLastError());
                    return (FALSE) as BOOL;
                }

                if ddraw_handle_table_init(&raw mut global_handle_table, 64) == 0 {
                    UnregisterClassA((DDRAW_WINDOW_CLASS_NAME).as_ptr(), inst);
                    return (FALSE) as BOOL;
                }

                if RegOpenKeyA(HKEY_LOCAL_MACHINE, b"Software\\Microsoft\\DirectDraw\0".as_ptr() as LPCSTR, &raw mut hkey) == 0 {
                    let mut type_: DWORD = 0;
                    let mut data: DWORD = 0;
                    let mut size: DWORD = 0;

                    size = core::mem::size_of::<DWORD>() as DWORD;
                    if RegQueryValueExA(hkey, b"ForceRefreshRate\0".as_ptr() as LPCSTR, core::ptr::null_mut(), &raw mut type_, &raw mut data as *mut BYTE, &raw mut size) == 0 && type_ == REG_DWORD {
                        force_refresh_rate = data;
                    }
                    RegCloseKey(hkey);
                }

                if GetModuleHandleExW(GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS | GET_MODULE_HANDLE_EX_FLAG_PIN, &raw mut ddraw_self as LPCWSTR, &raw mut ddraw_self) == 0 {
                    ERR!("Failed to get own module handle.\n");
                }

                instance = inst;
                DisableThreadLibraryCalls(inst);
            }

            DLL_PROCESS_DETACH => {
                if WARN_ON!(__wine_dbch_ddraw) != 0 {
                    let mut ddraw: *mut ddraw = core::ptr::null_mut();
                    let mut i: UINT = 0;

                    ddraw = ((global_ddraw_list.next as *mut u8).offset(-(core::mem::offset_of!(ddraw, ddraw_list_entry) as isize))) as *mut ddraw;
                    while &raw mut (*ddraw).ddraw_list_entry != &raw mut global_ddraw_list {
                        let mut surface: *mut ddraw_surface = core::ptr::null_mut();

                        WARN!("DirectDraw object %p has reference counts {%lu, %lu, %lu, %lu, %lu}.\n", ddraw, (*ddraw).ref7, (*ddraw).ref4, (*ddraw).ref3, (*ddraw).ref2, (*ddraw).ref1);

                        if list_empty(&raw mut (*ddraw).d3ddevice_list) == 0 {
                            WARN!("DirectDraw object %p has Direct3D device(s) attached.\n", ddraw);
                        }

                        surface = ((*ddraw).surface_list.next as *mut u8).offset(-(core::mem::offset_of!(ddraw_surface, surface_list_entry) as isize)) as *mut ddraw_surface;
                        while &raw mut (*surface).surface_list_entry != &raw mut (*ddraw).surface_list {
                            WARN!("Surface %p has reference counts {%lu, %lu, %lu, %lu, %lu, %lu}.\n", surface, (*surface).ref7, (*surface).ref4, (*surface).ref3, (*surface).ref2, (*surface).ref1, (*surface).gamma_count);

                            surface = ((*surface).surface_list_entry.next as *mut u8).offset(-(core::mem::offset_of!(ddraw_surface, surface_list_entry) as isize)) as *mut ddraw_surface;
                        }

                        ddraw = ((*ddraw).ddraw_list_entry.next as *mut u8).offset(-(core::mem::offset_of!(ddraw, ddraw_list_entry) as isize)) as *mut ddraw;
                    }

                    i = 0;
                    while i < global_handle_table.entry_count {
                        let mut entry: *mut ddraw_handle_entry = global_handle_table.entries.offset(i as isize);

                        match (*entry).type_ {
                            DDRAW_HANDLE_FREE => {}
                            DDRAW_HANDLE_MATERIAL => {
                                WARN!("Material handle %#x (%p) not unset properly.\n", i + 1, (*entry).object);
                            }
                            DDRAW_HANDLE_SURFACE => {
                                WARN!("Texture handle %#x (%p) not unset properly.\n", i + 1, (*entry).object);
                            }
                            DDRAW_HANDLE_MATRIX => {
                                WARN!("Leftover matrix handle %#x (%p), deleting.\n", i + 1, (*entry).object);
                            }
                            _ => {
                                WARN!("Handle %#x (%p) has unknown type %#x.\n", i + 1, (*entry).object, (*entry).type_);
                            }
                        }
                        i = i.wrapping_add(1);
                    }
                    ddraw_handle_table_destroy(&raw mut global_handle_table);
                }

                if !reserved.is_null() {
                    break 'sw;
                }
                UnregisterClassA((DDRAW_WINDOW_CLASS_NAME).as_ptr(), inst);
            }

            _ => {}
        }
    }
    return (TRUE) as BOOL;
}

