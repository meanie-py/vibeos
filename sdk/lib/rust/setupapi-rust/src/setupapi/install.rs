unsafe extern "C" fn Concatenate(
    DirId: ::core::ffi::c_int,
    SubDirPart: LPCWSTR,
    NamePart: LPCWSTR,
    pFullName: *mut LPWSTR,
) -> BOOL {
    let mut dwRequired: DWORD = 0 as DWORD;
    let mut Dir: LPCWSTR;
    let mut FullName: LPWSTR;

    *pFullName = core::ptr::null_mut();

    Dir = DIRID_get_string(DirId) as LPCWSTR;
    if !Dir.is_null() && *Dir != 0 {
        dwRequired = dwRequired.wrapping_add(
            (wcslen(Dir as *const wchar_t) + 1 as usize) as DWORD,
        );
    } else {
        Dir = core::ptr::null();
    }
    if !SubDirPart.is_null() {
        dwRequired = dwRequired.wrapping_add(
            (wcslen(SubDirPart as *const wchar_t) + 1 as usize) as DWORD,
        );
    }
    if !NamePart.is_null() {
        dwRequired = dwRequired.wrapping_add(
            wcslen(NamePart as *const wchar_t) as DWORD,
        );
    }
    dwRequired = (dwRequired as usize)
        .wrapping_mul(core::mem::size_of_val(&UNICODE_NULL))
        .wrapping_add(core::mem::size_of_val(&UNICODE_NULL)) as DWORD;

    FullName = MyMalloc(dwRequired) as LPWSTR;
    if FullName.is_null() {
        SetLastError(ERROR_NOT_ENOUGH_MEMORY as DWORD);
        return (FALSE) as BOOL;
    }
    *FullName.offset(0 as isize) = UNICODE_NULL;

    if !Dir.is_null() {
        wcscat(FullName as *mut wchar_t, Dir as *const wchar_t);
        if *FullName.offset(
            wcslen(FullName as *const wchar_t).wrapping_sub(1 as usize) as isize,
        ) as ::core::ffi::c_int
            != '\\' as i32
        {
            wcscat(FullName as *mut wchar_t, &raw const BackSlash as *const wchar_t);
        }
    }
    if !SubDirPart.is_null() {
        wcscat(FullName as *mut wchar_t, SubDirPart as *const wchar_t);
        if *FullName.offset(
            wcslen(FullName as *const wchar_t).wrapping_sub(1 as usize) as isize,
        ) as ::core::ffi::c_int
            != '\\' as i32
        {
            wcscat(FullName as *mut wchar_t, &raw const BackSlash as *const wchar_t);
        }
    }
    if !NamePart.is_null() {
        wcscat(FullName as *mut wchar_t, NamePart as *const wchar_t);
    }

    *pFullName = FullName;
    return (TRUE) as BOOL;
}

unsafe extern "C" fn profile_items_callback(
    hInf: HINF,
    SectionName: PCWSTR,
    Arg: PVOID,
) -> BOOL {
    let mut Context: INFCONTEXT = core::mem::zeroed();
    let mut LinkSubDir: LPWSTR = core::ptr::null_mut();
    let mut LinkName: LPWSTR = core::ptr::null_mut();
    let mut LinkAttributes: INT = 0;
    let mut LinkFolder: INT = 0;
    let mut FileDirId: INT = 0;
    let mut CSIDL: INT = (CSIDL_COMMON_PROGRAMS as i32);
    let mut FileSubDir: LPWSTR = core::ptr::null_mut();
    let mut DirId: INT = 0;
    let mut SubDirPart: LPWSTR = core::ptr::null_mut();
    let mut NamePart: LPWSTR = core::ptr::null_mut();
    let mut FullLinkName: LPWSTR = core::ptr::null_mut();
    let mut FullFileName: LPWSTR = core::ptr::null_mut();
    let mut FullWorkingDir: LPWSTR = core::ptr::null_mut();
    let mut FullIconName: LPWSTR = core::ptr::null_mut();
    let mut IconIdx: INT = 0;
    let mut lpHotKey: LPWSTR = core::ptr::null_mut();
    let mut lpInfoTip: LPWSTR = core::ptr::null_mut();
    let mut DisplayName: LPWSTR = core::ptr::null_mut();
    let mut DisplayResId: INT = 0;
    let mut ret: BOOL = (FALSE as i32);
    let mut Index: DWORD;
    let mut Required: DWORD;

    let mut psl: *mut IShellLinkW = core::ptr::null_mut();
    let mut ppf: *mut IPersistFile = core::ptr::null_mut();
    let mut hOle32: HMODULE = core::ptr::null_mut();
    let mut pCoInitialize: COINITIALIZE = None;
    let mut pCoCreateInstance: COCREATEINSTANCE = None;
    let mut pCoUninitialize: COUNINITIALIZE = None;
    let mut hr: HRESULT;

    if (*__wine_dbch___default).flags as ::core::ffi::c_int
        & (1 as ::core::ffi::c_int) << __WINE_DBCL_TRACE as ::core::ffi::c_int
        != 0
    {
        TRACE!(
            "hInf %p, SectionName %s, Arg %p\n",
            hInf,
            debugstr_w(SectionName as *const WCHAR),
            Arg,
        );
    }

    'body: {
        /* Read 'Name' entry */
        if SetupFindFirstLineW(hInf, SectionName, core::ptr::addr_of!(Name) as PCWSTR, core::ptr::addr_of_mut!(Context)) == 0 {
            break 'body;
        }
        if GetStringField(core::ptr::addr_of_mut!(Context), 1, core::ptr::addr_of_mut!(LinkName)) == 0 {
            break 'body;
        }
        if SetupGetFieldCount(core::ptr::addr_of_mut!(Context)) >= 2 {
            if SetupGetIntField(core::ptr::addr_of_mut!(Context), 2, core::ptr::addr_of_mut!(LinkAttributes)) == 0 {
                break 'body;
            }
        }
        if SetupGetFieldCount(core::ptr::addr_of_mut!(Context)) >= 3 {
            if SetupGetIntField(core::ptr::addr_of_mut!(Context), 3, core::ptr::addr_of_mut!(LinkFolder)) == 0 {
                break 'body;
            }
        }

        /* Read 'CmdLine' entry */
        if SetupFindFirstLineW(hInf, SectionName, core::ptr::addr_of!(CmdLine) as PCWSTR, core::ptr::addr_of_mut!(Context)) == 0 {
            break 'body;
        }
        Index = 1;
        let fresh_a = Index;
        Index = Index.wrapping_add(1);
        if SetupGetIntField(core::ptr::addr_of_mut!(Context), fresh_a, core::ptr::addr_of_mut!(FileDirId)) == 0 {
            break 'body;
        }
        if SetupGetFieldCount(core::ptr::addr_of_mut!(Context)) >= 3 {
            let fresh_b = Index;
            Index = Index.wrapping_add(1);
            if GetStringField(core::ptr::addr_of_mut!(Context), fresh_b, core::ptr::addr_of_mut!(FileSubDir)) == 0 {
                break 'body;
            }
        }
        let fresh_c = Index;
        Index = Index.wrapping_add(1);
        if GetStringField(core::ptr::addr_of_mut!(Context), fresh_c, core::ptr::addr_of_mut!(NamePart)) == 0 {
            break 'body;
        }
        if Concatenate(FileDirId, FileSubDir as LPCWSTR, NamePart as LPCWSTR, core::ptr::addr_of_mut!(FullFileName)) == 0 {
            break 'body;
        }
        MyFree(NamePart as PVOID);
        NamePart = core::ptr::null_mut();

        /* Read 'SubDir' entry */
        if ((LinkAttributes & (FLG_PROFITEM_GROUP as INT)) == 0)
            && SetupFindFirstLineW(hInf, SectionName, core::ptr::addr_of!(SubDir) as PCWSTR, core::ptr::addr_of_mut!(Context)) != 0
        {
            if GetStringField(core::ptr::addr_of_mut!(Context), 1, core::ptr::addr_of_mut!(LinkSubDir)) == 0 {
                break 'body;
            }
        }

        /* Read 'WorkingDir' entry */
        if SetupFindFirstLineW(hInf, SectionName, core::ptr::addr_of!(WorkingDir) as PCWSTR, core::ptr::addr_of_mut!(Context)) != 0 {
            if SetupGetIntField(core::ptr::addr_of_mut!(Context), 1, core::ptr::addr_of_mut!(DirId)) == 0 {
                break 'body;
            }
            if SetupGetFieldCount(core::ptr::addr_of_mut!(Context)) >= 2 {
                if GetStringField(core::ptr::addr_of_mut!(Context), 2, core::ptr::addr_of_mut!(SubDirPart)) == 0 {
                    break 'body;
                }
            }
            if Concatenate(DirId, SubDirPart as LPCWSTR, core::ptr::null::<WCHAR>(), core::ptr::addr_of_mut!(FullWorkingDir)) == 0 {
                break 'body;
            }
            MyFree(SubDirPart as PVOID);
            SubDirPart = core::ptr::null_mut();
        } else {
            if Concatenate(FileDirId, FileSubDir as LPCWSTR, core::ptr::null::<WCHAR>(), core::ptr::addr_of_mut!(FullWorkingDir)) == 0 {
                break 'body;
            }
        }

        /* Read 'IconPath' entry */
        if SetupFindFirstLineW(hInf, SectionName, core::ptr::addr_of!(IconPath) as PCWSTR, core::ptr::addr_of_mut!(Context)) != 0 {
            Index = 1;
            let fresh_d = Index;
            Index = Index.wrapping_add(1);
            if SetupGetIntField(core::ptr::addr_of_mut!(Context), fresh_d, core::ptr::addr_of_mut!(DirId)) == 0 {
                break 'body;
            }
            if SetupGetFieldCount(core::ptr::addr_of_mut!(Context)) >= 3 {
                let fresh_e = Index;
                Index = Index.wrapping_add(1);
                if GetStringField(core::ptr::addr_of_mut!(Context), fresh_e, core::ptr::addr_of_mut!(SubDirPart)) == 0 {
                    break 'body;
                }
            }
            if GetStringField(core::ptr::addr_of_mut!(Context), Index, core::ptr::addr_of_mut!(NamePart)) == 0 {
                break 'body;
            }
            if Concatenate(DirId, SubDirPart as LPCWSTR, NamePart as LPCWSTR, core::ptr::addr_of_mut!(FullIconName)) == 0 {
                break 'body;
            }
            MyFree(SubDirPart as PVOID);
            MyFree(NamePart as PVOID);
            SubDirPart = core::ptr::null_mut();
            NamePart = core::ptr::null_mut();
        } else {
            FullIconName = pSetupDuplicateString(FullFileName as PCWSTR) as LPWSTR;
            if FullIconName.is_null() {
                break 'body;
            }
        }

        /* Read 'IconIndex' entry */
        if SetupFindFirstLineW(hInf, SectionName, core::ptr::addr_of!(IconIndex) as PCWSTR, core::ptr::addr_of_mut!(Context)) != 0 {
            if SetupGetIntField(core::ptr::addr_of_mut!(Context), 1, core::ptr::addr_of_mut!(IconIdx)) == 0 {
                break 'body;
            }
        }

        /* Read 'HotKey' and 'InfoTip' entries */
        GetLineText(hInf, SectionName, core::ptr::addr_of!(HotKey) as PCWSTR, core::ptr::addr_of_mut!(lpHotKey));
        GetLineText(hInf, SectionName, core::ptr::addr_of!(InfoTip) as PCWSTR, core::ptr::addr_of_mut!(lpInfoTip));

        /* Read 'DisplayResource' entry */
        if SetupFindFirstLineW(hInf, SectionName, core::ptr::addr_of!(DisplayResource) as PCWSTR, core::ptr::addr_of_mut!(Context)) != 0 {
            if GetStringField(core::ptr::addr_of_mut!(Context), 1, core::ptr::addr_of_mut!(DisplayName)) == 0 {
                break 'body;
            }
            if SetupGetIntField(core::ptr::addr_of_mut!(Context), 2, core::ptr::addr_of_mut!(DisplayResId)) == 0 {
                break 'body;
            }
        }

        /* Some debug */
        if (*__wine_dbch___default).flags as ::core::ffi::c_int
            & (1 as ::core::ffi::c_int) << __WINE_DBCL_TRACE as ::core::ffi::c_int
            != 0
        {
            TRACE!(
                "Link is %s\\%s, attributes 0x%x\n",
                debugstr_w(LinkSubDir as *const WCHAR),
                debugstr_w(LinkName as *const WCHAR),
                LinkAttributes,
            );
        }
        if (*__wine_dbch___default).flags as ::core::ffi::c_int
            & (1 as ::core::ffi::c_int) << __WINE_DBCL_TRACE as ::core::ffi::c_int
            != 0
        {
            TRACE!(
                "File is %s\n",
                debugstr_w(FullFileName as *const WCHAR),
            );
        }
        if (*__wine_dbch___default).flags as ::core::ffi::c_int
            & (1 as ::core::ffi::c_int) << __WINE_DBCL_TRACE as ::core::ffi::c_int
            != 0
        {
            TRACE!(
                "Working dir %s\n",
                debugstr_w(FullWorkingDir as *const WCHAR),
            );
        }
        if (*__wine_dbch___default).flags as ::core::ffi::c_int
            & (1 as ::core::ffi::c_int) << __WINE_DBCL_TRACE as ::core::ffi::c_int
            != 0
        {
            TRACE!(
                "Icon is %s, %d\n",
                debugstr_w(FullIconName as *const WCHAR),
                IconIdx,
            );
        }
        if (*__wine_dbch___default).flags as ::core::ffi::c_int
            & (1 as ::core::ffi::c_int) << __WINE_DBCL_TRACE as ::core::ffi::c_int
            != 0
        {
            TRACE!(
                "Hotkey %s\n",
                debugstr_w(lpHotKey as *const WCHAR),
            );
        }
        if (*__wine_dbch___default).flags as ::core::ffi::c_int
            & (1 as ::core::ffi::c_int) << __WINE_DBCL_TRACE as ::core::ffi::c_int
            != 0
        {
            TRACE!(
                "InfoTip %s\n",
                debugstr_w(lpInfoTip as *const WCHAR),
            );
        }
        if (*__wine_dbch___default).flags as ::core::ffi::c_int
            & (1 as ::core::ffi::c_int) << __WINE_DBCL_TRACE as ::core::ffi::c_int
            != 0
        {
            TRACE!(
                "Display %s, %d\n",
                DisplayName,
                DisplayResId,
            );
        }

        /* Load ole32.dll */
        hOle32 = LoadLibraryA(b"ole32.dll\0".as_ptr() as LPCSTR) as HMODULE;
        if hOle32.is_null() {
            break 'body;
        }
        pCoInitialize = core::mem::transmute::<FARPROC, COINITIALIZE>(
            GetProcAddress(hOle32 as HINSTANCE, b"CoInitialize\0".as_ptr() as LPCSTR),
        );
        if pCoInitialize.is_none() {
            break 'body;
        }
        pCoCreateInstance = core::mem::transmute::<FARPROC, COCREATEINSTANCE>(
            GetProcAddress(hOle32 as HINSTANCE, b"CoCreateInstance\0".as_ptr() as LPCSTR),
        );
        if pCoCreateInstance.is_none() {
            break 'body;
        }
        pCoUninitialize = core::mem::transmute::<FARPROC, COUNINITIALIZE>(
            GetProcAddress(hOle32 as HINSTANCE, b"CoUninitialize\0".as_ptr() as LPCSTR),
        );
        if pCoUninitialize.is_none() {
            break 'body;
        }

        /* Create shortcut */
        hr = (pCoInitialize.unwrap_unchecked())(core::ptr::null_mut());
        if !(hr >= 0) {
            if HRESULT_FACILITY(hr) == FACILITY_WIN32 {
                SetLastError(HRESULT_CODE(hr));
            } else {
                SetLastError(E_FAIL as DWORD);
            }
            break 'body;
        }
        hr = (pCoCreateInstance.unwrap_unchecked())(
            core::ptr::addr_of!(CLSID_ShellLink),
            core::ptr::null_mut(),
            CLSCTX_INPROC_SERVER,
            core::ptr::addr_of!(IID_IShellLinkW),
            core::ptr::addr_of_mut!(psl) as *mut LPVOID,
        );
        if hr >= 0 {
            /* Fill link properties */
            hr = IShellLinkW_SetPath(psl, FullFileName);
            if hr >= 0 {
                hr = IShellLinkW_SetArguments(psl, RUSTCONV_WSTR_96A296D224F2.as_ptr());
            }
            if hr >= 0 {
                hr = IShellLinkW_SetWorkingDirectory(psl, FullWorkingDir);
            }
            if hr >= 0 {
                hr = IShellLinkW_SetIconLocation(psl, FullIconName, IconIdx);
            }
            if (hr >= 0) && !lpHotKey.is_null() {
                FIXME!(
                    "Need to store hotkey %s in shell link\n",
                    debugstr_w(lpHotKey as *const WCHAR),
                );
            }
            if (hr >= 0) && !lpInfoTip.is_null() {
                hr = IShellLinkW_SetDescription(psl, lpInfoTip);
            }
            if (hr >= 0) && !DisplayName.is_null() {
                FIXME!(
                    "Need to store display name %s, %d in shell link\n",
                    debugstr_w(DisplayName as *const WCHAR),
                    DisplayResId,
                );
            }
            if hr >= 0 {
                hr = IShellLinkW_QueryInterface(
                    psl,
                    core::ptr::addr_of!(IID_IPersistFile),
                    core::ptr::addr_of_mut!(ppf) as *mut LPVOID,
                );
                if hr >= 0 {
                    Required = ((MAX_PATH as usize
                        + 1 as usize
                        + (if !LinkSubDir.is_null() {
                            wcslen(LinkSubDir as *const WCHAR) as usize
                        } else {
                            0 as usize
                        })
                        + (if !LinkName.is_null() {
                            wcslen(LinkName as *const WCHAR) as usize
                        } else {
                            0 as usize
                        }))
                        * core::mem::size_of::<WCHAR>()) as DWORD;
                    FullLinkName = MyMalloc(Required) as LPWSTR;
                    if FullLinkName.is_null() {
                        hr = E_OUTOFMEMORY;
                    } else {
                        if ((LinkAttributes as u32) & (FLG_PROFITEM_DELETE | FLG_PROFITEM_GROUP)) != 0 {
                            FIXME!("Need to handle FLG_PROFITEM_DELETE and FLG_PROFITEM_GROUP\n");
                        }
                        if (LinkAttributes & (FLG_PROFITEM_CSIDL as INT)) != 0 {
                            CSIDL = LinkFolder;
                        } else if (LinkAttributes & (FLG_PROFITEM_CURRENTUSER as INT)) != 0 {
                            CSIDL = (CSIDL_PROGRAMS as i32);
                        }

                        if SHGetSpecialFolderPathW(
                            core::ptr::null_mut(),
                            FullLinkName,
                            CSIDL,
                            (TRUE) as BOOL,
                        ) != 0
                        {
                            if *FullLinkName.offset(
                                (wcslen(FullLinkName as *const WCHAR) as usize)
                                    .wrapping_sub(1 as usize) as isize,
                            ) != '\\' as WCHAR
                            {
                                wcscat(FullLinkName, core::ptr::addr_of!(BackSlash) as *const WCHAR);
                            }
                            if !LinkSubDir.is_null() {
                                wcscat(FullLinkName, LinkSubDir as *const WCHAR);
                                if *FullLinkName.offset(
                                    (wcslen(FullLinkName as *const WCHAR) as usize)
                                        .wrapping_sub(1 as usize) as isize,
                                ) != '\\' as WCHAR
                                {
                                    wcscat(FullLinkName, core::ptr::addr_of!(BackSlash) as *const WCHAR);
                                }
                            }
                            if !LinkName.is_null() {
                                wcscat(FullLinkName, LinkName as *const WCHAR);
                                wcscat(FullLinkName, core::ptr::addr_of!(DotLnk) as *const WCHAR);
                            }
                            hr = IPersistFile_Save(ppf, FullLinkName, TRUE as BOOL);
                        } else {
                            hr = HRESULT_FROM_WIN32!(GetLastError());
                        }
                    }
                    IPersistFile_Release(ppf);
                }
            }
            IShellLinkW_Release(psl);
        }
        (pCoUninitialize.unwrap_unchecked())();
        if hr >= 0 {
            ret = (TRUE as i32);
        } else {
            if HRESULT_FACILITY(hr) == FACILITY_WIN32 {
                SetLastError(HRESULT_CODE(hr));
            } else {
                SetLastError(E_FAIL as DWORD);
            }
        }
    }

    // cleanup:
    MyFree(LinkSubDir as PVOID);
    MyFree(LinkName as PVOID);
    MyFree(FileSubDir as PVOID);
    MyFree(SubDirPart as PVOID);
    MyFree(NamePart as PVOID);
    MyFree(FullFileName as PVOID);
    MyFree(FullWorkingDir as PVOID);
    MyFree(FullIconName as PVOID);
    MyFree(FullLinkName as PVOID);
    MyFree(lpHotKey as PVOID);
    MyFree(lpInfoTip as PVOID);
    MyFree(DisplayName as PVOID);
    if !hOle32.is_null() {
        FreeLibrary(hOle32);
    }

    if (*__wine_dbch___default).flags as ::core::ffi::c_int
        & (1 as ::core::ffi::c_int) << __WINE_DBCL_TRACE as ::core::ffi::c_int
        != 0
    {
        TRACE!(
            "Returning %d\n",
            ret,
        );
    }
    return ret;
}

