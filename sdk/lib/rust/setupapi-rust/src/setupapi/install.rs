unsafe extern "C" fn needs_callback(hinf: HINF, field: PCWSTR, arg: *mut core::ffi::c_void) -> BOOL {
    let info: *mut needs_callback_info = arg as *mut needs_callback_info;
    match (*info).r#type {
        0 => {
            return SetupInstallFromInfSectionW(
                (*info).owner,
                *(hinf as *mut HINF),
                field,
                (*info).flags,
                (*info).key_root,
                (*info).src_root as PCWSTR,
                (*info).copy_flags,
                core::mem::transmute::<PVOID, PSP_FILE_CALLBACK_W>((*info).callback),
                (*info).context,
                (*info).devinfo,
                (*info).devinfo_data,
            );
        }
        1 => {
            return SetupInstallServicesFromInfSectionExW(
                *(hinf as *mut HINF),
                field,
                (*info).flags as DWORD,
                (*info).devinfo,
                (*info).devinfo_data,
                (*info).reserved1,
                (*info).reserved2,
            );
        }
        _ => {
            ERR!("Unknown info type %u\n", (*info).r#type);
            return (FALSE) as BOOL;
        }
    }
}

#[no_mangle]
pub unsafe extern "system" fn SetupInstallFromInfSectionW(
    owner: HWND,
    hinf: HINF,
    section: PCWSTR,
    flags: UINT,
    key_root: HKEY,
    src_root: PCWSTR,
    copy_flags: UINT,
    callback: PSP_FILE_CALLBACK_W,
    context: PVOID,
    devinfo: HDEVINFO,
    devinfo_data: PSP_DEVINFO_DATA,
) -> BOOL {
    let mut needs_info: needs_callback_info = core::mem::zeroed();

    /* Parse 'Include' and 'Needs' directives */
    iterate_section_fields(
        hinf,
        section,
        core::ptr::addr_of!(Include) as PCWSTR,
        Some(
            include_callback
                as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
        ),
        core::ptr::null_mut(),
    );
    needs_info.r#type = 0 as UINT;
    needs_info.owner = owner;
    needs_info.flags = flags;
    needs_info.key_root = key_root;
    needs_info.src_root = src_root as LPCWSTR;
    needs_info.copy_flags = copy_flags;
    needs_info.callback = core::mem::transmute::<PSP_FILE_CALLBACK_W, PVOID>(callback);
    needs_info.context = context;
    needs_info.devinfo = devinfo;
    needs_info.devinfo_data = devinfo_data;
    iterate_section_fields(
        hinf,
        section,
        core::ptr::addr_of!(Needs) as PCWSTR,
        Some(
            needs_callback as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
        ),
        core::ptr::addr_of_mut!(needs_info) as *mut core::ffi::c_void,
    );

    if flags & SPINST_FILES as UINT != 0 {
        let mut install_params: SP_DEVINSTALL_PARAMS_W = core::mem::zeroed();
        let mut info: files_callback_info = core::mem::zeroed();
        let mut queue: HSPFILEQ = NULL;
        let mut use_custom_queue: BOOL = 0;
        let mut ret: BOOL = 0;

        install_params.cbSize = core::mem::size_of::<SP_DEVINSTALL_PARAMS>() as DWORD;
        use_custom_queue = (SetupDiGetDeviceInstallParamsW(
            devinfo,
            devinfo_data,
            core::ptr::addr_of_mut!(install_params),
        ) != 0
            && install_params.Flags & DI_NOVCP as DWORD != 0)
            as core::ffi::c_int as BOOL;
        if use_custom_queue == 0 && {
            queue = SetupOpenFileQueue();
            queue == (INVALID_HANDLE_VALUE as HSPFILEQ)
        } {
            return (FALSE) as BOOL;
        }
        info.queue = (if use_custom_queue != 0 {
            install_params.FileQueue as *mut core::ffi::c_void
        } else {
            queue as *mut core::ffi::c_void
        }) as HSPFILEQ;
        info.src_root = src_root;
        info.copy_flags = copy_flags;
        info.layout = hinf;
        ret = (iterate_section_fields(
            hinf,
            section,
            core::ptr::addr_of!(CopyFiles) as PCWSTR,
            Some(
                copy_files_callback
                    as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
            ),
            core::ptr::addr_of_mut!(info) as *mut core::ffi::c_void,
        ) != 0
            && iterate_section_fields(
                hinf,
                section,
                core::ptr::addr_of!(DelFiles) as PCWSTR,
                Some(
                    delete_files_callback
                        as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
                ),
                core::ptr::addr_of_mut!(info) as *mut core::ffi::c_void,
            ) != 0
            && iterate_section_fields(
                hinf,
                section,
                core::ptr::addr_of!(RenFiles) as PCWSTR,
                Some(
                    rename_files_callback
                        as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
                ),
                core::ptr::addr_of_mut!(info) as *mut core::ffi::c_void,
            ) != 0) as core::ffi::c_int as BOOL;
        if use_custom_queue == 0 {
            if ret != 0 {
                ret = SetupCommitFileQueueW(owner, queue, callback, context);
            }
            SetupCloseFileQueue(queue);
        }
        if ret == 0 {
            return (FALSE) as BOOL;
        }
    }
    if flags & SPINST_INIFILES as UINT != 0 {
        if iterate_section_fields(
            hinf,
            section,
            core::ptr::addr_of!(UpdateInis) as PCWSTR,
            Some(
                update_ini_callback
                    as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
            ),
            core::ptr::null_mut(),
        ) == 0
            || iterate_section_fields(
                hinf,
                section,
                core::ptr::addr_of!(UpdateIniFields) as PCWSTR,
                Some(
                    update_ini_fields_callback
                        as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
                ),
                core::ptr::null_mut(),
            ) == 0
        {
            return (FALSE) as BOOL;
        }
    }
    if flags & SPINST_INI2REG as UINT != 0 {
        if iterate_section_fields(
            hinf,
            section,
            core::ptr::addr_of!(Ini2Reg) as PCWSTR,
            Some(
                ini2reg_callback
                    as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
            ),
            core::ptr::null_mut(),
        ) == 0
        {
            return (FALSE) as BOOL;
        }
    }
    if flags & SPINST_LOGCONFIG as UINT != 0 {
        if iterate_section_fields(
            hinf,
            section,
            core::ptr::addr_of!(LogConf) as PCWSTR,
            Some(
                logconf_callback
                    as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
            ),
            core::ptr::null_mut(),
        ) == 0
        {
            return (FALSE) as BOOL;
        }
    }
    if flags & SPINST_REGSVR as UINT != 0 {
        let mut info_0: register_dll_info = core::mem::zeroed();

        info_0.unregister = FALSE as BOOL;
        if flags & SPINST_REGISTERCALLBACKAWARE as UINT != 0 {
            info_0.callback = callback;
            info_0.callback_context = context;
        } else {
            info_0.callback = core::mem::zeroed();
        }

        if iterate_section_fields(
            hinf,
            section,
            core::ptr::addr_of!(RegisterDlls) as PCWSTR,
            Some(
                register_dlls_callback
                    as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
            ),
            core::ptr::addr_of_mut!(info_0) as *mut core::ffi::c_void,
        ) == 0
        {
            return (FALSE) as BOOL;
        }

    }
    if flags & SPINST_UNREGSVR as UINT != 0 {
        let mut info_1: register_dll_info = core::mem::zeroed();

        info_1.unregister = TRUE as BOOL;
        if flags & SPINST_REGISTERCALLBACKAWARE as UINT != 0 {
            info_1.callback = callback;
            info_1.callback_context = context;
        } else {
            info_1.callback = core::mem::zeroed();
        }

        if iterate_section_fields(
            hinf,
            section,
            core::ptr::addr_of!(UnregisterDlls) as PCWSTR,
            Some(
                register_dlls_callback
                    as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
            ),
            core::ptr::addr_of_mut!(info_1) as *mut core::ffi::c_void,
        ) == 0
        {
            return FALSE as BOOL;
        }
    }
    if flags & SPINST_REGISTRY as UINT != 0 {
        let mut info_2: registry_callback_info = core::mem::zeroed();

        info_2.default_root = key_root;
        info_2.delete = TRUE as BOOL;
        if iterate_section_fields(
            hinf,
            section,
            core::ptr::addr_of!(DelReg) as PCWSTR,
            Some(
                registry_callback
                    as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
            ),
            core::ptr::addr_of_mut!(info_2) as *mut core::ffi::c_void,
        ) == 0
        {
            return FALSE as BOOL;
        }
        info_2.delete = FALSE as BOOL;
        if iterate_section_fields(
            hinf,
            section,
            core::ptr::addr_of!(AddReg) as PCWSTR,
            Some(
                registry_callback
                    as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
            ),
            core::ptr::addr_of_mut!(info_2) as *mut core::ffi::c_void,
        ) == 0
        {
            return FALSE as BOOL;
        }
    }
    if flags & SPINST_BITREG as UINT != 0 {
        if iterate_section_fields(
            hinf,
            section,
            core::ptr::addr_of!(BitReg) as PCWSTR,
            Some(
                bitreg_callback
                    as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
            ),
            core::ptr::null_mut(),
        ) == 0
        {
            return FALSE as BOOL;
        }
    }
    if flags & SPINST_PROFILEITEMS as UINT != 0 {
        if iterate_section_fields(
            hinf,
            section,
            core::ptr::addr_of!(ProfileItems) as PCWSTR,
            Some(
                profile_items_callback
                    as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
            ),
            core::ptr::null_mut(),
        ) == 0
        {
            return FALSE as BOOL;
        }
    }
    if flags & SPINST_COPYINF as UINT != 0 {
        if iterate_section_fields(
            hinf,
            section,
            core::ptr::addr_of!(CopyINF) as PCWSTR,
            Some(
                copy_inf_callback
                    as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL,
            ),
            core::ptr::null_mut(),
        ) == 0
        {
            return FALSE as BOOL;
        }
    }

    return TRUE as BOOL;
}

#[no_mangle]
pub unsafe extern "system" fn InstallHinfSectionW(
    hwnd: HWND,
    handle: HINSTANCE,
    cmdline: LPCWSTR,
    show: INT,
) {
    let mut ret: BOOL = (FALSE as i32);
    let mut s: *mut WCHAR = core::ptr::null_mut();
    let mut path: *mut WCHAR = core::ptr::null_mut();
    let mut section: [WCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut callback_context: *mut core::ffi::c_void = core::ptr::null_mut();
    let mut SectionNameLength: DWORD = 0;
    let mut mode: UINT = 0;
    let mut hinf: HINF = INVALID_HANDLE_VALUE;
    let mut bRebootRequired: BOOL = (FALSE as i32);

    'cleanup: {
        lstrcpynW(section.as_mut_ptr(), cmdline, (MAX_PATH as i32));

        s = strchrW(section.as_mut_ptr(), (' ' as u16) as WCHAR);
        if s.is_null() {
            break 'cleanup;
        }
        let fresh0 = s;
        s = s.add(1);
        *fresh0 = 0 as WCHAR;
        while *s == (' ' as u16) as WCHAR {
            s = s.add(1);
        }
        mode = atoiW(s) as UINT;

        /* quoted paths are not allowed on native, the rest of the command line is taken as the path */
        s = strchrW(s, (' ' as u16) as WCHAR);
        if s.is_null() {
            break 'cleanup;
        }
        while *s == (' ' as u16) as WCHAR {
            s = s.add(1);
        }
        path = s;

        if mode & 0x80 != 0 {
            /* default path of the installation not changed */
            mode &= !0x80;
        }

        hinf = SetupOpenInfFileW(path, core::ptr::null(), INF_STYLE_WIN4, core::ptr::null_mut());
        if hinf == INVALID_HANDLE_VALUE {
            WARN!(
                "SetupOpenInfFileW(%s) failed (Error %u)\n",
                path,
                GetLastError()
            );
            break 'cleanup;
        }

        ret = SetupDiGetActualSectionToInstallW(
            hinf,
            section.as_mut_ptr(),
            section.as_mut_ptr(),
            (core::mem::size_of::<[WCHAR; (MAX_PATH) as _]>()
                / core::mem::size_of_val(&section[0])) as DWORD,
            core::ptr::addr_of_mut!(SectionNameLength),
            core::ptr::null_mut(),
        );
        if ret == 0 {
            WARN!(
                "SetupDiGetActualSectionToInstallW() failed (Error %u)\n",
                GetLastError()
            );
            break 'cleanup;
        }
        if (SectionNameLength as usize)
            > (MAX_PATH as usize)
                .wrapping_sub(strlenW(core::ptr::addr_of!(DotServices) as *const WCHAR) as usize)
        {
            WARN!("Section name '%s' too long\n", section.as_mut_ptr());
            break 'cleanup;
        }

        /* Copy files and add registry entries */
        callback_context = SetupInitDefaultQueueCallback(hwnd) as *mut core::ffi::c_void;
        ret = SetupInstallFromInfSectionW(
            hwnd,
            hinf,
            section.as_mut_ptr(),
            SPINST_ALL,
            core::ptr::null_mut(),
            core::ptr::null(),
            SP_COPY_NEWER | SP_COPY_IN_USE_NEEDS_REBOOT,
            Some(SetupDefaultQueueCallbackW),
            callback_context as PVOID,
            core::ptr::null_mut(),
            core::ptr::null_mut(),
        );
        if ret == 0 {
            WARN!(
                "SetupInstallFromInfSectionW() failed (Error %u)\n",
                GetLastError()
            );
            break 'cleanup;
        }
        /* FIXME: need to check if some files were in use and need reboot
         * bReboot = ...;
         */

        /* Install services */
        wcscat(section.as_mut_ptr(), core::ptr::addr_of!(DotServices) as *const WCHAR);
        ret = SetupInstallServicesFromInfSectionW(hinf, section.as_mut_ptr(), 0);
        if ret == 0 && GetLastError() == ERROR_SECTION_NOT_FOUND {
            ret = (TRUE as i32);
        }
        if ret == 0 {
            WARN!(
                "SetupInstallServicesFromInfSectionW() failed (Error %u)\n",
                GetLastError()
            );
            break 'cleanup;
        } else if GetLastError() == ERROR_SUCCESS_REBOOT_REQUIRED {
            bRebootRequired = (TRUE as i32);
        }

        /* Check if we need to reboot */
        match mode {
            0 => {
                /* Never reboot */
            }
            1 => {
                /* Always reboot */
                ExitWindowsEx(
                    EWX_REBOOT,
                    SHTDN_REASON_MAJOR_APPLICATION | SHTDN_REASON_MINOR_INSTALLATION | SHTDN_REASON_FLAG_PLANNED,
                );
            }
            2 => {
                /* Query user before rebooting */
                SetupPromptReboot(core::ptr::null_mut(), hwnd, (FALSE) as BOOL);
            }
            3 => {
                /* Reboot if necessary */
                if bRebootRequired != 0 {
                    ExitWindowsEx(
                        EWX_REBOOT,
                        SHTDN_REASON_MAJOR_APPLICATION | SHTDN_REASON_MINOR_INSTALLATION | SHTDN_REASON_FLAG_PLANNED,
                    );
                }
            }
            4 => {
                /* If necessary, query user before rebooting */
                if bRebootRequired != 0 {
                    SetupPromptReboot(core::ptr::null_mut(), hwnd, (FALSE) as BOOL);
                }
            }
            _ => {}
        }
    }

    if !callback_context.is_null() {
        SetupTermDefaultQueueCallback(callback_context as PVOID);
    }
    if hinf != INVALID_HANDLE_VALUE {
        SetupCloseInfFile(hinf);
    }

    // TODO: Localize the error string.
    {}
}

