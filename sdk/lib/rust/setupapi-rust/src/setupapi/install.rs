unsafe extern "C" fn iterate_section_fields(
    hinf: HINF,
    section: PCWSTR,
    key: PCWSTR,
    callback: iterate_fields_func,
    arg: *mut core::ffi::c_void,
) -> BOOL {
    let mut static_buffer: [WCHAR; 200] = [0; 200];
    let mut buffer: *mut WCHAR = core::ptr::addr_of_mut!(static_buffer) as *mut WCHAR;
    let mut size: DWORD = (core::mem::size_of::<[WCHAR; 200]>()
        / core::mem::size_of::<WCHAR>()) as DWORD;
    let mut context: INFCONTEXT = core::mem::zeroed();
    let mut ret: BOOL = (FALSE as i32);

    let mut ok: BOOL = SetupFindFirstLineW(hinf, section, key, core::ptr::addr_of_mut!(context));
    'done: {
        while ok != 0 {
            let mut i: UINT;
            let count: UINT = SetupGetFieldCount(core::ptr::addr_of_mut!(context));
            i = 1;
            while i <= count {
                buffer = get_field_string(
                    core::ptr::addr_of_mut!(context),
                    i,
                    buffer,
                    core::ptr::addr_of_mut!(static_buffer) as *mut WCHAR,
                    core::ptr::addr_of_mut!(size),
                );
                if buffer.is_null() {
                    break 'done;
                }
                if (callback.unwrap_unchecked())(hinf, buffer, arg) == 0 {
                    WARN!(
                        "callback failed for %s %s err %d\n",
                        debugstr_w(section),
                        debugstr_w(buffer),
                        GetLastError()
                    );
                    break 'done;
                }
                i = i.wrapping_add(1);
            }
            ok = SetupFindNextMatchLineW(
                core::ptr::addr_of_mut!(context),
                key,
                core::ptr::addr_of_mut!(context),
            );
        }
        ret = (TRUE as i32);
    }
    if buffer != core::ptr::addr_of_mut!(static_buffer) as *mut WCHAR {
        HeapFree(
            GetProcessHeap(),
            0,
            buffer as PVOID,
        );
    }
    return ret;
}
