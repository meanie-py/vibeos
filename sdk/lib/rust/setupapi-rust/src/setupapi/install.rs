unsafe extern "C" fn GetLineText(hinf: HINF, section_name: PCWSTR, key_name: PCWSTR, value: *mut PWSTR) -> BOOL {
    let mut required: DWORD = 0;
    let mut buf: PWSTR = core::ptr::null_mut();

    *value = core::ptr::null_mut();

    if SetupGetLineTextW(
        core::ptr::null_mut(),
        hinf,
        section_name,
        key_name,
        core::ptr::null_mut(),
        0 as DWORD,
        core::ptr::addr_of_mut!(required),
    ) == 0
        && GetLastError() != ERROR_INSUFFICIENT_BUFFER as DWORD
    {
        return (FALSE) as BOOL;
    }

    buf = HeapAlloc(
        GetProcessHeap(),
        0 as DWORD,
        (required as SIZE_T).wrapping_mul(core::mem::size_of::<WCHAR>() as SIZE_T),
    ) as PWSTR;
    if buf.is_null() {
        SetLastError(ERROR_NOT_ENOUGH_MEMORY as DWORD);
        return (FALSE) as BOOL;
    }

    if SetupGetLineTextW(
        core::ptr::null_mut(),
        hinf,
        section_name,
        key_name,
        buf,
        required,
        core::ptr::addr_of_mut!(required),
    ) == 0
    {
        HeapFree(
            GetProcessHeap(),
            0 as DWORD,
            buf as PVOID,
        );
        return (FALSE) as BOOL;
    }

    *value = buf;
    return (TRUE) as BOOL;
}

unsafe extern "C" fn GetIntField(
    mut hinf: HINF,
    mut section_name: PCWSTR,
    mut key_name: PCWSTR,
    mut value: *mut INT,
) -> BOOL {
    let mut buffer: LPWSTR = core::ptr::null_mut::<WCHAR>();
    let mut end: LPWSTR = core::ptr::null_mut::<WCHAR>();
    let mut res: INT = 0;

    if GetLineText(hinf, section_name, key_name, core::ptr::addr_of_mut!(buffer)) == 0 {
        return (FALSE) as BOOL;
    }

    res = wcstol(
        buffer as *const WCHAR,
        core::ptr::addr_of_mut!(end),
        0 as ::core::ffi::c_int,
    ) as INT;

    if end != buffer && *end == 0 {
        HeapFree(
            GetProcessHeap(),
            0 as DWORD,
            buffer as PVOID,
        );
        *value = res;
        return (TRUE) as BOOL;
    } else {
        HeapFree(
            GetProcessHeap(),
            0 as DWORD,
            buffer as PVOID,
        );
        SetLastError(ERROR_INVALID_DATA as DWORD);
        return (FALSE) as BOOL;
    }
}
#[no_mangle]
pub unsafe extern "C" fn GetStringField(context: PINFCONTEXT, index: DWORD, value: *mut PWSTR) -> BOOL {
    let mut RequiredSize: DWORD = 0;
    let mut ret: BOOL;
    ret = SetupGetStringFieldW(
        context,
        index,
        core::ptr::null_mut::<WCHAR>(),
        0 as DWORD,
        core::ptr::addr_of_mut!(RequiredSize),
    );
    if ret == 0 {
        return (FALSE) as BOOL;
    } else if RequiredSize == 0 as DWORD {
        *value = core::ptr::null_mut::<WCHAR>();
        return (TRUE) as BOOL;
    }

    /* We got the needed size for the buffer */
    *value = MyMalloc(
        (RequiredSize as usize).wrapping_mul(core::mem::size_of::<WCHAR>()) as DWORD,
    ) as PWSTR;
    if (*value).is_null() {
        SetLastError(ERROR_NOT_ENOUGH_MEMORY as DWORD);
        return (FALSE) as BOOL;
    }
    ret = SetupGetStringFieldW(
        context,
        index,
        *value,
        RequiredSize,
        core::ptr::null_mut::<DWORD>(),
    );
    if ret == 0 {
        MyFree(*value as PVOID);
    }

    return ret;
}

unsafe extern "C" fn FixupServiceBinaryPath(
    mut ServiceType: DWORD,
    mut ServiceBinary: *mut LPWSTR,
) {
    let mut Buffer: LPWSTR;
    let mut ReactOSDir: [WCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut RosDirLength: DWORD;
    let mut ServiceLength: DWORD;
    let mut Win32Length: DWORD;

    GetWindowsDirectoryW(ReactOSDir.as_mut_ptr(), MAX_PATH);
    RosDirLength = strlenW(ReactOSDir.as_ptr()) as DWORD;
    ServiceLength = strlenW(*ServiceBinary as *const WCHAR) as DWORD;

    if ServiceLength < RosDirLength {
        return;
    }

    if wcsnicmp(
        *ServiceBinary as *const WCHAR,
        ReactOSDir.as_ptr(),
        RosDirLength as usize,
    ) == 0
    {
        MoveMemory!(
            *ServiceBinary as *mut core::ffi::c_void,
            (*ServiceBinary).add(RosDirLength as usize + 1) as *const core::ffi::c_void,
            (ServiceLength - RosDirLength) as usize * core::mem::size_of::<WCHAR>(),
        );

        if ServiceType & SERVICE_WIN32 != 0 {
            Win32Length = ((ServiceLength - RosDirLength) as usize * core::mem::size_of::<WCHAR>()
                - core::mem::size_of::<WCHAR>() /* sizeof(L'\\') */
                + core::mem::size_of::<[WCHAR; 14]>() /* sizeof(L"%SystemRoot%\\") */) as DWORD;
            Buffer = MyMalloc(Win32Length) as LPWSTR;

            wcscpy(Buffer, RUSTCONV_WSTR_ED82D57B6831.as_ptr());
            wcscat(Buffer, *ServiceBinary);
            MyFree((*ServiceBinary).cast());

            *ServiceBinary = Buffer;
        }
    }
}

unsafe extern "C" fn InstallOneService(
    list: *mut DeviceInfoSet,
    hInf: HINF,
    ServiceSection: LPCWSTR,
    ServiceName: LPCWSTR,
    ServiceFlags: UINT,
) -> BOOL {
    let mut hSCManager: SC_HANDLE = core::ptr::null_mut();
    let mut hService: SC_HANDLE = core::ptr::null_mut();
    let mut GroupOrder: LPDWORD = core::ptr::null_mut();
    let mut ServiceConfig: LPQUERY_SERVICE_CONFIGW = core::ptr::null_mut();
    let mut hServicesKey: HKEY = core::ptr::null_mut();
    let mut hServiceKey: HKEY = core::ptr::null_mut();
    let mut rc: LONG = 0;
    let mut ret: BOOL = FALSE as BOOL;

    let mut hGroupOrderListKey: HKEY = core::ptr::null_mut();
    let mut ServiceBinary: LPWSTR = core::ptr::null_mut();
    let mut LoadOrderGroup: LPWSTR = core::ptr::null_mut();
    let mut DisplayName: LPWSTR = core::ptr::null_mut();
    let mut Description: LPWSTR = core::ptr::null_mut();
    let mut Dependencies: LPWSTR = core::ptr::null_mut();
    let mut StartName: LPWSTR = core::ptr::null_mut();
    let mut SecurityDescriptor: LPWSTR = core::ptr::null_mut();
    let mut sd: PSECURITY_DESCRIPTOR = core::ptr::null_mut();
    let mut ServiceType: INT = 0;
    let mut StartType: INT = 0;
    let mut ErrorControl: INT = 0;
    let mut dwRegType: DWORD = 0;
    let mut tagId: DWORD = (-(1 as ::core::ffi::c_int)) as DWORD;
    let mut useTag: BOOL = 0;

    'cleanup: {
        if GetIntField(
            hInf,
            ServiceSection,
            core::ptr::addr_of!(ServiceTypeKey) as PCWSTR,
            core::ptr::addr_of_mut!(ServiceType),
        ) == 0
        {
            SetLastError(ERROR_BAD_SERVICE_INSTALLSECT as DWORD);
            break 'cleanup;
        }
        if GetIntField(
            hInf,
            ServiceSection,
            core::ptr::addr_of!(StartTypeKey) as PCWSTR,
            core::ptr::addr_of_mut!(StartType),
        ) == 0
        {
            SetLastError(ERROR_BAD_SERVICE_INSTALLSECT as DWORD);
            break 'cleanup;
        }
        if GetIntField(
            hInf,
            ServiceSection,
            core::ptr::addr_of!(ErrorControlKey) as PCWSTR,
            core::ptr::addr_of_mut!(ErrorControl),
        ) == 0
        {
            SetLastError(ERROR_BAD_SERVICE_INSTALLSECT as DWORD);
            break 'cleanup;
        }
        useTag = ((ServiceType == SERVICE_BOOT_START as INT)
            || (ServiceType == SERVICE_SYSTEM_START as INT)) as BOOL;

        hSCManager = OpenSCManagerW(
            core::ptr::null(),
            SERVICES_ACTIVE_DATABASE.as_ptr(),
            SC_MANAGER_CREATE_SERVICE as DWORD,
        );
        if hSCManager.is_null() {
            break 'cleanup;
        }

        if GetLineText(
            hInf,
            ServiceSection,
            core::ptr::addr_of!(ServiceBinaryKey) as PCWSTR,
            core::ptr::addr_of_mut!(ServiceBinary),
        ) == 0
        {
            SetLastError(ERROR_BAD_SERVICE_INSTALLSECT as DWORD);
            break 'cleanup;
        }

        /* Adjust binary path according to the service type */
        FixupServiceBinaryPath(ServiceType as DWORD, core::ptr::addr_of_mut!(ServiceBinary));

        /* Don't check return value, as these fields are optional and
         * GetLineText initialize output parameter even on failure */
        GetLineText(
            hInf,
            ServiceSection,
            core::ptr::addr_of!(LoadOrderGroupKey) as PCWSTR,
            core::ptr::addr_of_mut!(LoadOrderGroup),
        );
        GetLineText(
            hInf,
            ServiceSection,
            core::ptr::addr_of!(DisplayNameKey) as PCWSTR,
            core::ptr::addr_of_mut!(DisplayName),
        );
        GetLineText(
            hInf,
            ServiceSection,
            core::ptr::addr_of!(DescriptionKey) as PCWSTR,
            core::ptr::addr_of_mut!(Description),
        );
        GetLineText(
            hInf,
            ServiceSection,
            core::ptr::addr_of!(DependenciesKey) as PCWSTR,
            core::ptr::addr_of_mut!(Dependencies),
        );
        GetLineText(
            hInf,
            ServiceSection,
            core::ptr::addr_of!(StartNameKey) as PCWSTR,
            core::ptr::addr_of_mut!(StartName),
        );

        /* If there is no group, we must not request a tag */
        if LoadOrderGroup.is_null() || *LoadOrderGroup == 0 {
            useTag = FALSE as BOOL;
        }

        hService = OpenServiceW(
            hSCManager,
            ServiceName,
            (DELETE | SERVICE_QUERY_CONFIG | SERVICE_CHANGE_CONFIG
                | WRITE_DAC) as DWORD,
        );
        if hService.is_null() && GetLastError() != ERROR_SERVICE_DOES_NOT_EXIST as DWORD {
            break 'cleanup;
        }

        if !hService.is_null() && (ServiceFlags & (SPSVCINST_DELETEEVENTLOGENTRY as UINT)) != 0 {
            ret = DeleteService(hService);
            if ret == 0 && GetLastError() != ERROR_SERVICE_MARKED_FOR_DELETE as DWORD {
                break 'cleanup;
            }
        }

        if hService.is_null() {
            /* Create new service */
            hService = CreateServiceW(
                hSCManager,
                ServiceName,
                DisplayName as LPCWSTR,
                WRITE_DAC as DWORD,
                ServiceType as DWORD,
                StartType as DWORD,
                ErrorControl as DWORD,
                ServiceBinary as LPCWSTR,
                LoadOrderGroup as LPCWSTR,
                if useTag != 0 {
                    core::ptr::addr_of_mut!(tagId)
                } else {
                    core::ptr::null_mut()
                },
                Dependencies as LPCWSTR,
                StartName as LPCWSTR,
                core::ptr::null(),
            );
            if hService.is_null() {
                break 'cleanup;
            }
        } else {
            let mut bufferSize: DWORD = 0;
            /* Read current configuration */
            if QueryServiceConfigW(
                hService,
                core::ptr::null_mut(),
                0 as DWORD,
                core::ptr::addr_of_mut!(bufferSize),
            ) == 0
            {
                if GetLastError() != ERROR_INSUFFICIENT_BUFFER as DWORD {
                    break 'cleanup;
                }
                ServiceConfig = MyMalloc(bufferSize) as LPQUERY_SERVICE_CONFIGW;
                if ServiceConfig.is_null() {
                    SetLastError(ERROR_NOT_ENOUGH_MEMORY as DWORD);
                    break 'cleanup;
                }
                if QueryServiceConfigW(
                    hService,
                    ServiceConfig,
                    bufferSize,
                    core::ptr::addr_of_mut!(bufferSize),
                ) == 0
                {
                    break 'cleanup;
                }
            }
            tagId = (*ServiceConfig).dwTagId;

            /* Update configuration */
            ret = ChangeServiceConfigW(
                hService,
                ServiceType as DWORD,
                (if (ServiceFlags & (SPSVCINST_NOCLOBBER_STARTTYPE as UINT)) != 0 {
                    SERVICE_NO_CHANGE as DWORD
                } else {
                    StartType as DWORD
                }),
                (if (ServiceFlags & (SPSVCINST_NOCLOBBER_ERRORCONTROL as UINT)) != 0 {
                    SERVICE_NO_CHANGE as DWORD
                } else {
                    ErrorControl as DWORD
                }),
                ServiceBinary as LPCWSTR,
                (if (ServiceFlags & (SPSVCINST_NOCLOBBER_LOADORDERGROUP as UINT)) != 0
                    && !(*ServiceConfig).lpLoadOrderGroup.is_null()
                {
                    core::ptr::null_mut()
                } else {
                    LoadOrderGroup
                }) as LPCWSTR,
                if useTag != 0 {
                    core::ptr::addr_of_mut!(tagId)
                } else {
                    core::ptr::null_mut()
                },
                (if (ServiceFlags & (SPSVCINST_NOCLOBBER_DEPENDENCIES as UINT)) != 0
                    && !(*ServiceConfig).lpDependencies.is_null()
                {
                    core::ptr::null_mut()
                } else {
                    Dependencies
                }) as LPCWSTR,
                StartName as LPCWSTR,
                core::ptr::null(),
                (if (ServiceFlags & (SPSVCINST_NOCLOBBER_DISPLAYNAME as UINT)) != 0
                    && !(*ServiceConfig).lpDisplayName.is_null()
                {
                    core::ptr::null_mut()
                } else {
                    DisplayName
                }) as LPCWSTR,
            );
            if ret == 0 {
                break 'cleanup;
            }
        }

        /* Set security */
        if GetLineText(
            hInf,
            ServiceSection,
            core::ptr::addr_of!(SecurityKey) as PCWSTR,
            core::ptr::addr_of_mut!(SecurityDescriptor),
        ) != 0
        {
            ret = ConvertStringSecurityDescriptorToSecurityDescriptorW(
                SecurityDescriptor as LPCWSTR,
                SDDL_REVISION_1 as DWORD,
                core::ptr::addr_of_mut!(sd),
                core::ptr::null_mut(),
            );
            if ret == 0 {
                break 'cleanup;
            }
            ret = SetServiceObjectSecurity(
                hService,
                DACL_SECURITY_INFORMATION as SECURITY_INFORMATION,
                sd,
            );
            if ret == 0 {
                break 'cleanup;
            }
        }

        /* FIXME: use Description and SPSVCINST_NOCLOBBER_DESCRIPTION */

        if useTag != 0 {
            /* Add the tag to SYSTEM\CurrentControlSet\Control\GroupOrderList key */
            let mut lpLoadOrderGroup: LPCWSTR = core::ptr::null();
            let mut bufferSize: DWORD = 0;

            lpLoadOrderGroup = LoadOrderGroup as LPCWSTR;
            if (ServiceFlags & (SPSVCINST_NOCLOBBER_LOADORDERGROUP as UINT)) != 0
                && !ServiceConfig.is_null()
                && !(*ServiceConfig).lpLoadOrderGroup.is_null()
            {
                lpLoadOrderGroup = (*ServiceConfig).lpLoadOrderGroup as LPCWSTR;
            }

            rc = RegOpenKeyW(
                if !list.is_null() {
                    (*list).HKLM
                } else {
                    HKEY_LOCAL_MACHINE
                },
                core::ptr::addr_of!(GroupOrderListKey) as LPCWSTR,
                core::ptr::addr_of_mut!(hGroupOrderListKey),
            );
            if rc != ERROR_SUCCESS as LONG {
                SetLastError(rc as DWORD);
                break 'cleanup;
            }
            rc = RegQueryValueExW(
                hGroupOrderListKey,
                lpLoadOrderGroup,
                core::ptr::null_mut(),
                core::ptr::addr_of_mut!(dwRegType),
                core::ptr::null_mut(),
                core::ptr::addr_of_mut!(bufferSize),
            );
            if rc == ERROR_FILE_NOT_FOUND as LONG {
                bufferSize = core::mem::size_of::<DWORD>() as DWORD;
            } else if rc != ERROR_SUCCESS as LONG {
                SetLastError(rc as DWORD);
                break 'cleanup;
            } else if dwRegType != REG_BINARY as DWORD
                || bufferSize == 0 as DWORD
                || bufferSize % (core::mem::size_of::<DWORD>() as DWORD)
                    != 0 as DWORD
            {
                SetLastError(ERROR_GEN_FAILURE as DWORD);
                break 'cleanup;
            }
            /* Allocate buffer to store existing data + the new tag */
            GroupOrder = MyMalloc(
                bufferSize + core::mem::size_of::<DWORD>() as DWORD,
            ) as LPDWORD;
            if GroupOrder.is_null() {
                SetLastError(ERROR_NOT_ENOUGH_MEMORY as DWORD);
                break 'cleanup;
            }
            if rc == ERROR_SUCCESS as LONG {
                /* Read existing data */
                rc = RegQueryValueExW(
                    hGroupOrderListKey,
                    lpLoadOrderGroup,
                    core::ptr::null_mut(),
                    core::ptr::null_mut(),
                    GroupOrder as *mut BYTE,
                    core::ptr::addr_of_mut!(bufferSize),
                );
                if rc != ERROR_SUCCESS as LONG {
                    SetLastError(rc as DWORD);
                    break 'cleanup;
                }
                if (ServiceFlags & (SPSVCINST_TAGTOFRONT as UINT)) != 0 {
                    memmove(
                        GroupOrder.offset(2 as isize) as *mut ::core::ffi::c_void,
                        GroupOrder.offset(1 as isize) as *const ::core::ffi::c_void,
                        (bufferSize - core::mem::size_of::<DWORD>() as DWORD) as usize,
                    );
                }
            } else {
                *GroupOrder.offset(0 as isize) = 0 as DWORD;
            }
            *GroupOrder.offset(0 as isize) =
                (*GroupOrder.offset(0 as isize)).wrapping_add(1);
            if (ServiceFlags & (SPSVCINST_TAGTOFRONT as UINT)) != 0 {
                *GroupOrder.offset(1 as isize) = tagId;
            } else {
                *GroupOrder.offset(
                    (bufferSize / (core::mem::size_of::<DWORD>() as DWORD)) as isize,
                ) = tagId;
            }

            rc = RegSetValueExW(
                hGroupOrderListKey,
                lpLoadOrderGroup,
                0 as DWORD,
                REG_BINARY as DWORD,
                GroupOrder as *mut BYTE,
                bufferSize + core::mem::size_of::<DWORD>() as DWORD,
            );
            if rc != ERROR_SUCCESS as LONG {
                SetLastError(rc as DWORD);
                break 'cleanup;
            }
        }

        /* Handle AddReg and DelReg */
        rc = RegOpenKeyExW(
            if !list.is_null() {
                (*list).HKLM
            } else {
                HKEY_LOCAL_MACHINE
            },
            REGSTR_PATH_SERVICES,
            0 as DWORD,
            READ_CONTROL as REGSAM,
            core::ptr::addr_of_mut!(hServicesKey),
        );
        if rc != ERROR_SUCCESS as LONG {
            SetLastError(rc as DWORD);
            break 'cleanup;
        }
        rc = RegOpenKeyExW(
            hServicesKey,
            ServiceName,
            0 as DWORD,
            (KEY_READ | KEY_WRITE) as REGSAM,
            core::ptr::addr_of_mut!(hServiceKey),
        );
        RegCloseKey(hServicesKey);
        if rc != ERROR_SUCCESS as LONG {
            SetLastError(rc as DWORD);
            break 'cleanup;
        }

        ret = SetupInstallFromInfSectionW(
            core::ptr::null_mut(),
            hInf,
            ServiceSection,
            SPINST_REGISTRY as UINT,
            hServiceKey,
            core::ptr::null(),
            0 as UINT,
            None,
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            core::ptr::null_mut(),
        );
        RegCloseKey(hServiceKey);
    }

    if !hSCManager.is_null() {
        CloseServiceHandle(hSCManager);
    }
    if !hService.is_null() {
        CloseServiceHandle(hService);
    }
    if !hGroupOrderListKey.is_null() {
        RegCloseKey(hGroupOrderListKey);
    }
    if !sd.is_null() {
        LocalFree(sd as HLOCAL);
    }
    MyFree(ServiceConfig as PVOID);
    MyFree(ServiceBinary as PVOID);
    MyFree(LoadOrderGroup as PVOID);
    MyFree(DisplayName as PVOID);
    MyFree(Description as PVOID);
    MyFree(Dependencies as PVOID);
    MyFree(SecurityDescriptor as PVOID);
    MyFree(GroupOrder as PVOID);
    MyFree(StartName as PVOID);

    return ret;
}

#[no_mangle]
pub unsafe extern "system" fn SetupInstallServicesFromInfSectionExW(
    InfHandle: HINF,
    SectionName: PCWSTR,
    mut Flags: DWORD,
    DeviceInfoSet: HDEVINFO,
    DeviceInfoData: PSP_DEVINFO_DATA,
    Reserved1: PVOID,
    Reserved2: PVOID,
) -> BOOL {
    let mut list: *mut DeviceInfoSet = core::ptr::null_mut();
    let mut ret: BOOL = (FALSE as i32);

    /* FIXME: SPSVCINST_ASSOCSERVICE is not fully supported */
    const SupportedFlags: DWORD =
        SPSVCINST_TAGTOFRONT | SPSVCINST_DELETEEVENTLOGENTRY | SPSVCINST_NOCLOBBER_DISPLAYNAME |
        SPSVCINST_NOCLOBBER_STARTTYPE | SPSVCINST_NOCLOBBER_ERRORCONTROL |
        SPSVCINST_NOCLOBBER_LOADORDERGROUP | SPSVCINST_NOCLOBBER_DEPENDENCIES |
        SPSVCINST_STOPSERVICE;

    if DeviceInfoSet.is_null() || DeviceInfoSet == INVALID_HANDLE_VALUE {
        list = core::ptr::null_mut();
    } else {
        list = DeviceInfoSet as *mut DeviceInfoSet;
    }

    'done: {
        if (Flags & !SupportedFlags) != 0 {
            TRACE!("Unknown flags: 0x%08lx\n", Flags & !SupportedFlags);
            SetLastError(ERROR_INVALID_FLAGS);
        } else if SectionName.is_null() || !Reserved1.is_null() || !Reserved2.is_null() {
            SetLastError(ERROR_INVALID_PARAMETER);
        } else if !list.is_null() && (*list).magic != SETUP_DEVICE_INFO_SET_MAGIC {
            SetLastError(ERROR_INVALID_HANDLE);
        } else if !DeviceInfoData.is_null()
            && (*DeviceInfoData).cbSize as usize != core::mem::size_of::<SP_DEVINFO_DATA>() as usize
        {
            SetLastError(ERROR_INVALID_USER_BUFFER);
        } else {
            let mut needs_info: needs_callback_info = core::mem::zeroed();
            let mut ServiceName: LPWSTR = core::ptr::null_mut();
            let mut ServiceSection: LPWSTR = core::ptr::null_mut();
            let mut ServiceFlags: INT = 0;
            let mut ContextService: INFCONTEXT = core::mem::zeroed();
            let mut bNeedReboot: BOOL = (FALSE as i32);

            /* Parse 'Include' and 'Needs' directives */
            iterate_section_fields(
                InfHandle,
                SectionName,
                core::ptr::addr_of!(Include) as PCWSTR,
                Some(include_callback as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL),
                core::ptr::null_mut(),
            );
            needs_info.r#type = 1;
            needs_info.flags = Flags as UINT;
            needs_info.devinfo = DeviceInfoSet;
            needs_info.devinfo_data = DeviceInfoData;
            needs_info.reserved1 = Reserved1;
            needs_info.reserved2 = Reserved2;
            iterate_section_fields(
                InfHandle,
                SectionName,
                core::ptr::addr_of!(Needs) as PCWSTR,
                Some(needs_callback as unsafe extern "C" fn(HINF, PCWSTR, *mut core::ffi::c_void) -> BOOL),
                core::ptr::addr_of_mut!(needs_info) as *mut core::ffi::c_void,
            );

            if (Flags & SPSVCINST_STOPSERVICE) != 0 {
                /* This may lead to require a reboot */
                /* bNeedReboot = TRUE; */
                Flags &= !SPSVCINST_STOPSERVICE;
            }

            ret = SetupFindFirstLineW(
                InfHandle,
                SectionName,
                core::ptr::null(),
                core::ptr::addr_of_mut!(ContextService),
            );
            if ret == 0 {
                SetLastError(ERROR_SECTION_NOT_FOUND);
                break 'done;
            }

            ret = SetupFindFirstLineW(
                InfHandle,
                SectionName,
                core::ptr::addr_of!(AddService) as PCWSTR,
                core::ptr::addr_of_mut!(ContextService),
            );
            while ret != 0 {
                if GetStringField(
                    core::ptr::addr_of_mut!(ContextService),
                    1,
                    core::ptr::addr_of_mut!(ServiceName),
                ) == 0
                {
                    break 'done;
                }

                ret = SetupGetIntField(
                    core::ptr::addr_of_mut!(ContextService),
                    2, /* Field index */
                    core::ptr::addr_of_mut!(ServiceFlags),
                );
                if ret == 0 {
                    /* The field may be empty. Ignore the error */
                    ServiceFlags = 0;
                }

                if GetStringField(
                    core::ptr::addr_of_mut!(ContextService),
                    3,
                    core::ptr::addr_of_mut!(ServiceSection),
                ) == 0
                {
                    break 'done;
                }

                ret = InstallOneService(
                    list,
                    InfHandle,
                    ServiceSection as LPCWSTR,
                    ServiceName as LPCWSTR,
                    (((ServiceFlags & !(SPSVCINST_ASSOCSERVICE as INT)) as DWORD) | Flags) as UINT,
                );
                if ret == 0 {
                    break 'done;
                }

                if !list.is_null() && (ServiceFlags & SPSVCINST_ASSOCSERVICE as INT) != 0 {
                    ret = SetupDiSetDeviceRegistryPropertyW(
                        DeviceInfoSet,
                        DeviceInfoData,
                        SPDRP_SERVICE,
                        ServiceName as LPBYTE,
                        ((strlenW(ServiceName as PCWSTR) as usize + 1 as usize)
                            * core::mem::size_of::<WCHAR>()) as DWORD,
                    );
                    if ret == 0 {
                        break 'done;
                    }
                }

                HeapFree(GetProcessHeap(), 0, ServiceName as PVOID);
                HeapFree(GetProcessHeap(), 0, ServiceSection as PVOID);
                ServiceSection = core::ptr::null_mut();
                ServiceName = ServiceSection;
                ret = SetupFindNextMatchLineW(
                    core::ptr::addr_of_mut!(ContextService),
                    core::ptr::addr_of!(AddService) as PCWSTR,
                    core::ptr::addr_of_mut!(ContextService),
                );
            }

            if bNeedReboot != 0 {
                SetLastError(ERROR_SUCCESS_REBOOT_REQUIRED);
            } else {
                SetLastError(ERROR_SUCCESS);
            }
            ret = (TRUE as i32);
        }
    }
    TRACE!("Returning %d\n", ret);
    return ret;
}

#[no_mangle]
pub unsafe extern "system" fn SetupCopyOEMInfA(
    mut SourceInfFileName: PCSTR,
    mut OEMSourceMediaLocation: PCSTR,
    mut OEMSourceMediaType: DWORD,
    mut CopyStyle: DWORD,
    mut DestinationInfFileName: PSTR,
    mut DestinationInfFileNameSize: DWORD,
    mut RequiredSize: PDWORD,
    mut DestinationInfFileNameComponent: *mut PSTR,
) -> BOOL {
    let mut SourceInfFileNameW: PWSTR = core::ptr::null_mut::<WCHAR>();
    let mut OEMSourceMediaLocationW: PWSTR = core::ptr::null_mut::<WCHAR>();
    let mut DestinationInfFileNameW: PWSTR = core::ptr::null_mut::<WCHAR>();
    let mut DestinationInfFileNameComponentW: PWSTR = core::ptr::null_mut::<WCHAR>();
    let mut ret: BOOL = (FALSE as i32);
    let mut size: DWORD = 0;

    if (*__wine_dbch___default).flags as ::core::ffi::c_int
        & (1 as ::core::ffi::c_int) << __WINE_DBCL_TRACE as ::core::ffi::c_int
        != 0
    {
        let __dbch: *mut __wine_debug_channel = __wine_dbch___default;
        let __dbcl: __wine_debug_class = __WINE_DBCL_TRACE;
        ros_dbg_log(
            __dbcl,
            __dbch,
            b"dll/win32/setupapi/install.c\0"
                as *const u8 as *const ::core::ffi::c_char,
            b"SetupCopyOEMInfA\0" as *const u8 as *const ::core::ffi::c_char,
            2286 as ::core::ffi::c_int,
            b"%s %s 0x%lx 0x%lx %p 0%lu %p %p\n\0" as *const u8 as *const ::core::ffi::c_char,
            SourceInfFileName,
            OEMSourceMediaLocation,
            OEMSourceMediaType,
            CopyStyle,
            DestinationInfFileName,
            DestinationInfFileNameSize,
            RequiredSize,
            DestinationInfFileNameComponent,
        );
    }

    'cleanup: {
        if DestinationInfFileName.is_null() && DestinationInfFileNameSize > 0 {
            SetLastError(ERROR_INVALID_PARAMETER);
        } else if {
            SourceInfFileNameW = pSetupMultiByteToUnicode(SourceInfFileName, CP_ACP);
            SourceInfFileNameW.is_null()
        } {
            SetLastError(ERROR_INVALID_PARAMETER);
        } else if OEMSourceMediaType != SPOST_NONE && {
            OEMSourceMediaLocationW =
                pSetupMultiByteToUnicode(OEMSourceMediaLocation, CP_ACP);
            OEMSourceMediaLocationW.is_null()
        } {
            SetLastError(ERROR_INVALID_PARAMETER);
        } else {
            if DestinationInfFileNameSize != 0 {
                DestinationInfFileNameW = MyMalloc(
                    (DestinationInfFileNameSize as usize)
                        .wrapping_mul(::core::mem::size_of::<WCHAR>() as usize)
                        as DWORD,
                ) as PWSTR;
                if DestinationInfFileNameW.is_null() {
                    SetLastError(ERROR_NOT_ENOUGH_MEMORY);
                    break 'cleanup;
                }
            }

            ret = SetupCopyOEMInfW(
                SourceInfFileNameW as PCWSTR,
                OEMSourceMediaLocationW as PCWSTR,
                OEMSourceMediaType,
                CopyStyle,
                DestinationInfFileNameW,
                DestinationInfFileNameSize,
                core::ptr::addr_of_mut!(size),
                if !DestinationInfFileNameComponent.is_null() {
                    core::ptr::addr_of_mut!(DestinationInfFileNameComponentW)
                } else {
                    core::ptr::null_mut::<PWSTR>()
                },
            );
            if ret == 0 {
                if !RequiredSize.is_null() {
                    *RequiredSize = size;
                }
                break 'cleanup;
            }

            if DestinationInfFileNameSize != 0 {
                if WideCharToMultiByte(
                    CP_ACP,
                    0,
                    DestinationInfFileNameW as LPCWSTR,
                    -1,
                    DestinationInfFileName as LPSTR,
                    DestinationInfFileNameSize as ::core::ffi::c_int,
                    core::ptr::null::<CHAR>(),
                    core::ptr::null_mut::<BOOL>(),
                ) == 0
                {
                    *DestinationInfFileName.offset(0 as isize) =
                        '\0' as i32 as CHAR;
                    break 'cleanup;
                }
            }
            if !DestinationInfFileNameComponent.is_null() {
                if !DestinationInfFileNameComponentW.is_null() {
                    *DestinationInfFileNameComponent = DestinationInfFileName
                        .offset(
                            DestinationInfFileNameComponentW.offset_from(DestinationInfFileNameW)
                                as ::core::ffi::c_longlong as isize,
                        )
                        as *mut CHAR
                        as PSTR;
                } else {
                    *DestinationInfFileNameComponent = core::ptr::null_mut::<CHAR>();
                }
            }
            ret = (TRUE as i32);
        }
    }

    MyFree(SourceInfFileNameW as PVOID);
    MyFree(OEMSourceMediaLocationW as PVOID);
    MyFree(DestinationInfFileNameW as PVOID);

    if (*__wine_dbch___default).flags as ::core::ffi::c_int
        & (1 as ::core::ffi::c_int) << __WINE_DBCL_TRACE as ::core::ffi::c_int
        != 0
    {
        let __dbch_0: *mut __wine_debug_channel = __wine_dbch___default;
        let __dbcl_0: __wine_debug_class = __WINE_DBCL_TRACE;
        ros_dbg_log(
            __dbcl_0,
            __dbch_0,
            b"dll/win32/setupapi/install.c\0"
                as *const u8 as *const ::core::ffi::c_char,
            b"SetupCopyOEMInfA\0" as *const u8 as *const ::core::ffi::c_char,
            2344 as ::core::ffi::c_int,
            b"Returning %d\n\0" as *const u8 as *const ::core::ffi::c_char,
            ret,
        );
    }

    if ret != 0 {
        SetLastError(ERROR_SUCCESS);
    }
    return ret;
}

unsafe extern "C" fn compare_files(file1: HANDLE, file2: HANDLE) -> ::core::ffi::c_int {
    let mut buffer1: [::core::ffi::c_char; 2048] = [0; 2048];
    let mut buffer2: [::core::ffi::c_char; 2048] = [0; 2048];
    let mut size1: DWORD = 0;
    let mut size2: DWORD = 0;
    while ReadFile(
        file1,
        core::ptr::addr_of_mut!(buffer1) as *mut ::core::ffi::c_char as PVOID,
        ::core::mem::size_of::<[::core::ffi::c_char; 2048]>() as DWORD,
        core::ptr::addr_of_mut!(size1),
        ::core::ptr::null_mut::<_OVERLAPPED>(),
    ) != 0
        && ReadFile(
            file2,
            core::ptr::addr_of_mut!(buffer2) as *mut ::core::ffi::c_char as PVOID,
            ::core::mem::size_of::<[::core::ffi::c_char; 2048]>() as DWORD,
            core::ptr::addr_of_mut!(size2),
            ::core::ptr::null_mut::<_OVERLAPPED>(),
        ) != 0
    {
        let mut ret: ::core::ffi::c_int = 0;
        if size1 != size2 {
            return if size1 > size2 {
                1
            } else {
                -(1)
            };
        }
        if size1 == 0 {
            return 0;
        }
        ret = memcmp(
            core::ptr::addr_of_mut!(buffer1) as *mut ::core::ffi::c_char as *const ::core::ffi::c_void,
            core::ptr::addr_of_mut!(buffer2) as *mut ::core::ffi::c_char as *const ::core::ffi::c_void,
            size1 as size_t,
        );
        if ret != 0 {
            return ret;
        }
    }
    return 0;
}

#[no_mangle]
pub unsafe extern "system" fn SetupCopyOEMInfW(
    SourceInfFileName: PCWSTR,
    OEMSourceMediaLocation: PCWSTR,
    OEMSourceMediaType: DWORD,
    CopyStyle: DWORD,
    DestinationInfFileName: PWSTR,
    DestinationInfFileNameSize: DWORD,
    RequiredSize: PDWORD,
    DestinationInfFileNameComponent: *mut PWSTR,
) -> BOOL {
    let mut ret: BOOL = (FALSE as i32);

    if SourceInfFileName.is_null() {
        SetLastError(ERROR_INVALID_PARAMETER);
    } else if OEMSourceMediaType != SPOST_NONE && OEMSourceMediaType != SPOST_PATH && OEMSourceMediaType != SPOST_URL {
        SetLastError(ERROR_INVALID_PARAMETER);
    } else if (CopyStyle & !(SP_COPY_DELETESOURCE | SP_COPY_REPLACEONLY | SP_COPY_NOOVERWRITE | SP_COPY_OEMINF_CATALOG_ONLY)) != 0 {
        SetLastError(ERROR_INVALID_FLAGS);
    } else if DestinationInfFileName.is_null() && DestinationInfFileNameSize > 0 {
        SetLastError(ERROR_INVALID_PARAMETER);
    } else if (CopyStyle & SP_COPY_OEMINF_CATALOG_ONLY) != 0 {
        SetLastError(ERROR_CALL_NOT_IMPLEMENTED);
    } else {
        let mut hSearch: HANDLE = INVALID_HANDLE_VALUE;
        let mut FindFileData: WIN32_FIND_DATAW = core::mem::zeroed();
        let mut AlreadyExists: BOOL = 0;
        let mut NextFreeNumber: DWORD = 0;
        let mut len: SIZE_T = 0;
        let mut pFullFileName: LPWSTR = core::ptr::null_mut();
        let mut pFileName: LPWSTR = core::ptr::null_mut();
        let mut hSourceFile: HANDLE = INVALID_HANDLE_VALUE;

        if OEMSourceMediaType == SPOST_PATH || OEMSourceMediaType == SPOST_URL {
            FIXME!("OEMSourceMediaType 0x%lx ignored\n", OEMSourceMediaType);
        }

        /* Check if source file exists, and open it */
        if !strchrW(SourceInfFileName, '\\' as u16).is_null() || !strchrW(SourceInfFileName, '/' as u16).is_null() {
            let mut path: *mut WCHAR = core::ptr::null_mut();

            len = GetFullPathNameW(SourceInfFileName, 0, core::ptr::null_mut(), core::ptr::null_mut()) as SIZE_T;
            if len == 0 {
                return (FALSE) as BOOL;
            }
            path = MyMalloc((len * core::mem::size_of::<WCHAR>() as SIZE_T) as DWORD) as *mut WCHAR;
            if path.is_null() {
                SetLastError(ERROR_NOT_ENOUGH_MEMORY);
                return (FALSE) as BOOL;
            }
            GetFullPathNameW(SourceInfFileName, len as DWORD, path as LPWSTR, core::ptr::null_mut());
            hSourceFile = CreateFileW(
                path as LPCWSTR, FILE_READ_DATA | FILE_READ_ATTRIBUTES,
                FILE_SHARE_READ | FILE_SHARE_WRITE | FILE_SHARE_DELETE,
                core::ptr::null_mut(), OPEN_EXISTING, 0, core::ptr::null_mut());
            MyFree(path as PVOID);
        } else {
            /* try Windows directory */
            let mut path: *mut WCHAR = core::ptr::null_mut();
            let mut p: *mut WCHAR = core::ptr::null_mut();
            static Inf: [u16; 6] = [0x005Cu16, 0x0069, 0x006E, 0x0066, 0x005C, 0x0000];
            static System32: [u16; 11] = [
    0x005Cu16, 0x0073, 0x0079, 0x0073, 0x0074, 0x0065, 0x006D, 0x0033, 0x0032, 0x005C,
    0x0000,
];

            len = (GetWindowsDirectoryW(core::ptr::null_mut(), 0) as SIZE_T)
                + (strlenW(SourceInfFileName) as SIZE_T)
                + (12 as SIZE_T);
            path = MyMalloc((len * core::mem::size_of::<WCHAR>() as SIZE_T) as DWORD) as *mut WCHAR;
            if path.is_null() {
                SetLastError(ERROR_NOT_ENOUGH_MEMORY);
                return (FALSE) as BOOL;
            }
            GetWindowsDirectoryW(path as LPWSTR, len as UINT);
            p = path.add(strlenW(path) as usize);
            strcpyW(p, core::ptr::addr_of!(Inf) as PCWSTR);
            strcatW(p, SourceInfFileName);
            hSourceFile = CreateFileW(
                path as LPCWSTR, FILE_READ_DATA | FILE_READ_ATTRIBUTES,
                FILE_SHARE_READ | FILE_SHARE_WRITE | FILE_SHARE_DELETE,
                core::ptr::null_mut(), OPEN_EXISTING, 0, core::ptr::null_mut());
            if hSourceFile == INVALID_HANDLE_VALUE {
                strcpyW(p, core::ptr::addr_of!(System32) as PCWSTR);
                strcatW(p, SourceInfFileName);
                hSourceFile = CreateFileW(
                    path as LPCWSTR, FILE_READ_DATA | FILE_READ_ATTRIBUTES,
                    FILE_SHARE_READ | FILE_SHARE_WRITE | FILE_SHARE_DELETE,
                    core::ptr::null_mut(), OPEN_EXISTING, 0, core::ptr::null_mut());
            }
            MyFree(path as PVOID);
        }
        if hSourceFile == INVALID_HANDLE_VALUE {
            SetLastError(ERROR_FILE_NOT_FOUND);
            // goto cleanup -- handled by skipping to the cleanup tail below
        } else {
            'cleanup: {
                /* Prepare .inf file specification */
                len = (MAX_PATH as SIZE_T)
                    + (1 as SIZE_T)
                    + (strlenW(core::ptr::addr_of!(InfDirectory) as PCWSTR) as SIZE_T)
                    + (13 as SIZE_T);
                pFullFileName = MyMalloc((len * core::mem::size_of::<WCHAR>() as SIZE_T) as DWORD) as LPWSTR;
                if pFullFileName.is_null() {
                    SetLastError(ERROR_NOT_ENOUGH_MEMORY);
                    break 'cleanup;
                }
                len = GetSystemWindowsDirectoryW(pFullFileName, MAX_PATH) as SIZE_T;
                if len == 0 || len > (MAX_PATH as SIZE_T) {
                    break 'cleanup;
                }
                if *pFullFileName.add(strlenW(pFullFileName) as usize - 1 as usize) != '\\' as u16 {
                    strcatW(pFullFileName, core::ptr::addr_of!(BackSlash) as PCWSTR);
                }
                strcatW(pFullFileName, core::ptr::addr_of!(InfDirectory) as PCWSTR);
                pFileName = pFullFileName.add(strlenW(pFullFileName) as usize);

                /* Search if the specified .inf file already exists in %WINDIR%\Inf */
                AlreadyExists = (FALSE as i32);
                strcpyW(pFileName, core::ptr::addr_of!(OemFileMask) as PCWSTR);
                hSearch = FindFirstFileW(pFullFileName as LPCWSTR, core::ptr::addr_of_mut!(FindFileData));
                if hSearch != INVALID_HANDLE_VALUE {
                    let mut SourceFileSize: LARGE_INTEGER = core::mem::zeroed();

                    if GetFileSizeEx(hSourceFile, core::ptr::addr_of_mut!(SourceFileSize)) != 0 {
                        loop {
                            let mut DestFileSize: LARGE_INTEGER = core::mem::zeroed();
                            let mut hDestFile: HANDLE;

                            strcpyW(pFileName, core::ptr::addr_of_mut!(FindFileData.cFileName) as PCWSTR);
                            hDestFile = CreateFileW(
                                pFullFileName as LPCWSTR, FILE_READ_DATA | FILE_READ_ATTRIBUTES,
                                FILE_SHARE_READ | FILE_SHARE_WRITE | FILE_SHARE_DELETE,
                                core::ptr::null_mut(), OPEN_EXISTING, 0, core::ptr::null_mut());
                            if hDestFile != INVALID_HANDLE_VALUE {
                                if GetFileSizeEx(hDestFile, core::ptr::addr_of_mut!(DestFileSize)) != 0
                                    && DestFileSize.QuadPart == SourceFileSize.QuadPart
                                    && compare_files(hSourceFile, hDestFile) == 0
                                {
                                    AlreadyExists = (TRUE as i32);
                                }
                            }
                            if !(AlreadyExists == 0 && FindNextFileW(hSearch, core::ptr::addr_of_mut!(FindFileData)) != 0) {
                                break;
                            }
                        }
                    }
                    FindClose(hSearch);
                    hSearch = INVALID_HANDLE_VALUE;
                }

                if AlreadyExists == 0 && (CopyStyle & SP_COPY_REPLACEONLY) != 0 {
                    /* FIXME: set DestinationInfFileName, RequiredSize, DestinationInfFileNameComponent */
                    SetLastError(ERROR_FILE_NOT_FOUND);
                    break 'cleanup;
                } else if AlreadyExists != 0 && (CopyStyle & SP_COPY_NOOVERWRITE) != 0 {
                    let mut Size: DWORD = (strlenW(pFileName) + 1) as DWORD;

                    if !RequiredSize.is_null() {
                        *RequiredSize = Size;
                    }
                    if DestinationInfFileNameSize == 0 {
                        SetLastError(ERROR_FILE_EXISTS);
                    } else if DestinationInfFileNameSize < Size {
                        SetLastError(ERROR_INSUFFICIENT_BUFFER);
                    } else {
                        SetLastError(ERROR_FILE_EXISTS);
                        strcpyW(DestinationInfFileName, pFileName);
                    }
                    break 'cleanup;
                }

                /* Search the number to give to OEM??.INF */
                strcpyW(pFileName, core::ptr::addr_of!(OemFileMask) as PCWSTR);
                hSearch = FindFirstFileW(pFullFileName as LPCWSTR, core::ptr::addr_of_mut!(FindFileData));
                if hSearch == INVALID_HANDLE_VALUE {
                    if GetLastError() != ERROR_FILE_NOT_FOUND {
                        break 'cleanup;
                    }
                } else {
                    loop {
                        let mut CurrentNumber: DWORD = 0;
                        if swscanf(
                            core::ptr::addr_of_mut!(FindFileData.cFileName) as PCWSTR,
                            core::ptr::addr_of!(OemFileSpecification) as PCWSTR,
                            core::ptr::addr_of_mut!(CurrentNumber)) == 1
                            && CurrentNumber <= 99999
                        {
                            if CurrentNumber >= NextFreeNumber {
                                NextFreeNumber = CurrentNumber + 1;
                            }
                        }
                        if !(FindNextFileW(hSearch, core::ptr::addr_of_mut!(FindFileData)) != 0) {
                            break;
                        }
                    }
                }

                if NextFreeNumber > 99999 {
                    ERR!("Too much custom .inf files\n");
                    SetLastError(ERROR_GEN_FAILURE);
                    break 'cleanup;
                }

                /* Create the full path: %WINDIR%\Inf\OEM{XXXXX}.inf */
                sprintfW(pFileName, core::ptr::addr_of!(OemFileSpecification) as PCWSTR, NextFreeNumber);

                if CopyFileW(SourceInfFileName, pFullFileName as LPCWSTR, (TRUE) as BOOL) == 0 {
                    break 'cleanup;
                }

                len = (strlenW(pFullFileName) + 1) as SIZE_T;
                if !RequiredSize.is_null() {
                    *RequiredSize = len as DWORD;
                }
                if !DestinationInfFileName.is_null() {
                    if (DestinationInfFileNameSize as SIZE_T) >= len {
                        strcpyW(DestinationInfFileName, pFullFileName as PCWSTR);
                        if !DestinationInfFileNameComponent.is_null() {
                            *DestinationInfFileNameComponent =
                                DestinationInfFileName.add(pFileName.offset_from(pFullFileName) as usize);
                        }
                    } else {
                        SetLastError(ERROR_INSUFFICIENT_BUFFER);
                        break 'cleanup;
                    }
                }

                if (CopyStyle & SP_COPY_DELETESOURCE) != 0 {
                    if DeleteFileW(SourceInfFileName) == 0 {
                        break 'cleanup;
                    }
                }

                ret = (TRUE as i32);
            }
            // cleanup:
            if hSourceFile != INVALID_HANDLE_VALUE {
                CloseHandle(hSourceFile);
            }
            if hSearch != INVALID_HANDLE_VALUE {
                FindClose(hSearch);
            }
            MyFree(pFullFileName as PVOID);
        }
    }

    if ret != 0 {
        SetLastError(ERROR_SUCCESS);
    }
    return ret;
}
