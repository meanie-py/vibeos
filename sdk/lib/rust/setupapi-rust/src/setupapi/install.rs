unsafe extern "C" fn get_root_key(name: *const WCHAR, def_root: HKEY) -> HKEY {
    static HKCR: [u16; 5] = [0x0048u16, 0x004B, 0x0043, 0x0052, 0x0000];
    static HKCU: [u16; 5] = [0x0048u16, 0x004B, 0x0043, 0x0055, 0x0000];
    static HKLM: [u16; 5] = [0x0048u16, 0x004B, 0x004C, 0x004D, 0x0000];
    static HKU: [u16; 4] = [0x0048u16, 0x004B, 0x0055, 0x0000];
    static HKR: [u16; 4] = [0x0048u16, 0x004B, 0x0052, 0x0000];

    if strcmpiW(name, HKCR.as_ptr()) == 0 {
        return HKEY_CLASSES_ROOT;
    }
    if strcmpiW(name, HKCU.as_ptr()) == 0 {
        return HKEY_CURRENT_USER;
    }
    if strcmpiW(name, HKLM.as_ptr()) == 0 {
        return HKEY_LOCAL_MACHINE;
    }
    if strcmpiW(name, HKU.as_ptr()) == 0 {
        return HKEY_USERS;
    }
    if strcmpiW(name, HKR.as_ptr()) == 0 {
        return def_root;
    }
    return core::ptr::null_mut();
}

unsafe extern "C" fn append_multi_sz_value(
    hkey: HKEY,
    value: *const WCHAR,
    mut strings: *const WCHAR,
    str_size: DWORD,
) {
    let mut size: DWORD = 0;
    let mut type_: DWORD = 0;
    let mut total: DWORD = 0;
    let mut buffer: *mut WCHAR = core::ptr::null_mut();
    let mut p: *mut WCHAR = core::ptr::null_mut();

    if RegQueryValueExW(
        hkey,
        value,
        core::ptr::null_mut(),
        core::ptr::addr_of_mut!(type_),
        core::ptr::null_mut(),
        core::ptr::addr_of_mut!(size),
    ) != 0
    {
        return;
    }
    if type_ != REG_MULTI_SZ as DWORD {
        return;
    }

    size = size.wrapping_add(str_size.wrapping_mul(core::mem::size_of::<WCHAR>() as DWORD));
    buffer = HeapAlloc(
        GetProcessHeap(),
        0 as DWORD,
        (size) as SIZE_T,
    ) as *mut WCHAR;
    if buffer.is_null() {
        return;
    }

    'done: {
        if RegQueryValueExW(
            hkey,
            value,
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            buffer as *mut BYTE,
            core::ptr::addr_of_mut!(size),
        ) != 0
        {
            break 'done;
        }

        /* compare each string against all the existing ones */
        total = size;
        while *strings != 0 {
            let mut len: i32 = strlenW(strings) as i32 + 1 as i32;

            p = buffer;
            while *p != 0 {
                if strcmpiW(p, strings) == 0 {
                    break;
                }
                p = p.offset(strlenW(p) as isize + 1 as isize);
            }

            if *p == 0 {
                /* not found, need to append it */
                memcpy(
                    p as *mut core::ffi::c_void,
                    strings as *const core::ffi::c_void,
                    (len as usize).wrapping_mul(core::mem::size_of::<WCHAR>()),
                );
                *p.offset(len as isize) = 0 as WCHAR;
                total = total.wrapping_add(
                    (len as usize).wrapping_mul(core::mem::size_of::<WCHAR>()) as DWORD,
                );
            }
            strings = strings.offset(len as isize);
        }

        if total != size {
            RegSetValueExW(
                hkey,
                value,
                0 as DWORD,
                REG_MULTI_SZ as DWORD,
                buffer as *mut BYTE,
                total.wrapping_add(core::mem::size_of::<WCHAR>() as DWORD),
            );
        }
    }

    HeapFree(
        GetProcessHeap(),
        0 as DWORD,
        buffer as PVOID,
    );
}

unsafe extern "C" fn delete_multi_sz_value(hkey: HKEY, value: *const WCHAR, string: *const WCHAR) {
    let mut size: DWORD = 0;
    let mut type_: DWORD = 0;
    let mut buffer: *mut WCHAR = core::ptr::null_mut();
    let mut src: *mut WCHAR = core::ptr::null_mut();
    let mut dst: *mut WCHAR = core::ptr::null_mut();

    if RegQueryValueExW(
        hkey,
        value as LPCWSTR,
        core::ptr::null_mut(),
        core::ptr::addr_of_mut!(type_),
        core::ptr::null_mut(),
        core::ptr::addr_of_mut!(size),
    ) != 0
    {
        return;
    }
    if type_ != REG_MULTI_SZ {
        return;
    }
    /* allocate double the size, one for value before and one for after */
    buffer = HeapAlloc(
        GetProcessHeap(),
        0,
        size.wrapping_mul(2) as SIZE_T,
    ) as *mut WCHAR;
    if buffer.is_null() {
        return;
    }
    'done: {
        if RegQueryValueExW(
            hkey,
            value as LPCWSTR,
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            buffer as LPBYTE,
            core::ptr::addr_of_mut!(size),
        ) != 0
        {
            break 'done;
        }
        src = buffer;
        dst = buffer.add(size as usize);
        while *src != 0 {
            let mut len: i32 = strlenW(src) as i32 + 1;
            if strcmpiW(src, string) != 0 {
                memcpy(
                    dst as *mut core::ffi::c_void,
                    src as *const core::ffi::c_void,
                    (len as usize) * core::mem::size_of::<WCHAR>(),
                );
                dst = dst.offset(len as isize);
            }
            src = src.offset(len as isize);
        }
        *dst = 0;
        dst = dst.add(1);
        if dst != buffer.add((2 as usize) * (size as usize)) {
            /* did we remove something? */
            RegSetValueExW(
                hkey,
                value as LPCWSTR,
                0,
                REG_MULTI_SZ,
                buffer.add(size as usize) as LPBYTE,
                dst.offset_from(buffer.add(size as usize)) as DWORD,
            );
        }
    }
    HeapFree(
        GetProcessHeap(),
        0,
        buffer as PVOID,
    );
}

unsafe extern "C" fn do_reg_operation(
    mut hkey: HKEY,
    mut value: *const WCHAR,
    mut context: *mut INFCONTEXT,
    mut flags: INT,
) -> BOOL {
    let mut type_0: DWORD = 0;
    let mut size: DWORD = 0;

    if (flags & (FLG_ADDREG_DELREG_BIT | (FLG_ADDREG_DELVAL as i32))) != 0 {
        if *value != 0 && (flags & FLG_DELREG_KEYONLY_COMMON) == 0 {
            if (flags & FLG_DELREG_MULTI_SZ_DELSTRING) == FLG_DELREG_MULTI_SZ_DELSTRING {
                let mut str: *mut WCHAR = core::ptr::null_mut::<WCHAR>();
                if SetupGetStringFieldW(
                    context,
                    5,
                    core::ptr::null_mut::<WCHAR>(),
                    0,
                    &raw mut size,
                ) == 0
                    || size == 0
                {
                    return (TRUE) as BOOL;
                }
                str = HeapAlloc(
                    GetProcessHeap(),
                    0,
                    (size as SIZE_T).wrapping_mul(::core::mem::size_of::<WCHAR>() as SIZE_T),
                ) as *mut WCHAR;
                if str.is_null() {
                    return (FALSE) as BOOL;
                }
                SetupGetStringFieldW(
                    context,
                    5,
                    str as PWSTR,
                    size,
                    core::ptr::null_mut::<DWORD>(),
                );
                delete_multi_sz_value(hkey, value, str);
                HeapFree(GetProcessHeap(), 0, str as PVOID);
            } else {
                RegDeleteValueW(hkey, value as LPCWSTR);
            }
        } else {
            NtDeleteKey(hkey as HANDLE);
        }
        return (TRUE) as BOOL;
    }

    if ((flags as u32) & (FLG_ADDREG_KEYONLY | (FLG_ADDREG_KEYONLY_COMMON as u32))) != 0 {
        return (TRUE) as BOOL;
    }

    if ((flags as u32) & (FLG_ADDREG_NOCLOBBER | FLG_ADDREG_OVERWRITEONLY)) != 0 {
        let mut exists: BOOL = (RegQueryValueExW(
            hkey,
            value as LPCWSTR,
            core::ptr::null_mut::<DWORD>(),
            core::ptr::null_mut::<DWORD>(),
            core::ptr::null_mut::<BYTE>(),
            core::ptr::null_mut::<DWORD>(),
        ) == 0) as BOOL;
        if exists != 0 && (flags & (FLG_ADDREG_NOCLOBBER as INT)) != 0 {
            return (TRUE) as BOOL;
        }
        if exists == 0 && (flags & (FLG_ADDREG_OVERWRITEONLY as INT)) != 0 {
            return (TRUE) as BOOL;
        }
    }

    match (flags as u32) & FLG_ADDREG_TYPE_MASK {
        FLG_ADDREG_TYPE_SZ => {
            type_0 = REG_SZ as DWORD;
        }
        FLG_ADDREG_TYPE_MULTI_SZ => {
            type_0 = REG_MULTI_SZ as DWORD;
        }
        FLG_ADDREG_TYPE_EXPAND_SZ => {
            type_0 = REG_EXPAND_SZ as DWORD;
        }
        FLG_ADDREG_TYPE_BINARY => {
            type_0 = REG_BINARY as DWORD;
        }
        FLG_ADDREG_TYPE_DWORD => {
            type_0 = REG_DWORD as DWORD;
        }
        FLG_ADDREG_TYPE_NONE => {
            type_0 = REG_NONE as DWORD;
        }
        _ => {
            type_0 = (flags >> 16) as DWORD;
        }
    }

    if (flags & (FLG_ADDREG_BINVALUETYPE as INT)) == 0
        || (type_0 == REG_DWORD && SetupGetFieldCount(context) == 5)
    {
        static mut empty: WCHAR = 0;
        let mut str_0: *mut WCHAR = core::ptr::null_mut::<WCHAR>();

        if type_0 == REG_MULTI_SZ {
            if SetupGetMultiSzFieldW(
                context,
                5,
                core::ptr::null_mut::<WCHAR>(),
                0,
                &raw mut size,
            ) == 0
            {
                size = 0;
            }
            if size != 0 {
                str_0 = HeapAlloc(
                    GetProcessHeap(),
                    0,
                    (size as SIZE_T).wrapping_mul(::core::mem::size_of::<WCHAR>() as SIZE_T),
                ) as *mut WCHAR;
                if str_0.is_null() {
                    return FALSE as BOOL;
                }
                SetupGetMultiSzFieldW(
                    context,
                    5,
                    str_0 as PWSTR,
                    size,
                    core::ptr::null_mut::<DWORD>(),
                );
            }
            if (flags & (FLG_ADDREG_APPEND as INT)) != 0 {
                if str_0.is_null() {
                    return TRUE as BOOL;
                }
                append_multi_sz_value(hkey, value as LPCWSTR, str_0, size);
                HeapFree(GetProcessHeap(), 0, str_0 as PVOID);
                return TRUE as BOOL;
            }
        } else {
            if SetupGetStringFieldW(
                context,
                5,
                core::ptr::null_mut::<WCHAR>(),
                0,
                &raw mut size,
            ) == 0
            {
                size = 0;
            }
            if size != 0 {
                str_0 = HeapAlloc(
                    GetProcessHeap(),
                    0,
                    (size as SIZE_T).wrapping_mul(::core::mem::size_of::<WCHAR>() as SIZE_T),
                ) as *mut WCHAR;
                if str_0.is_null() {
                    return FALSE as BOOL;
                }
                SetupGetStringFieldW(
                    context,
                    5,
                    str_0 as PWSTR,
                    size,
                    core::ptr::null_mut::<DWORD>(),
                );
            }
        }

        if type_0 == REG_DWORD {
            let mut dw: DWORD = if !str_0.is_null() {
                strtoulW(str_0, core::ptr::null_mut::<*mut WCHAR>(), 0) as DWORD
            } else {
                0
            };
            if ((*__wine_dbch___default).flags as ::core::ffi::c_int
                & ((1 as ::core::ffi::c_int) << (__WINE_DBCL_TRACE as ::core::ffi::c_int)))
                != 0
            {
                let __dbch: *mut __wine_debug_channel = __wine_dbch___default;
                let __dbcl: __wine_debug_class = __WINE_DBCL_TRACE;
                ros_dbg_log(
                    __dbcl,
                    __dbch,
                    b"dll/win32/setupapi/install.c\0"
                        as *const u8 as *const ::core::ffi::c_char,
                    b"do_reg_operation\0" as *const u8 as *const ::core::ffi::c_char,
                    387 as ::core::ffi::c_int,
                    b"setting dword %s to %x\n\0" as *const u8 as *const ::core::ffi::c_char,
                    debugstr_w(value),
                    dw,
                );
            }
            RegSetValueExW(
                hkey,
                value as LPCWSTR,
                0,
                type_0,
                &raw mut dw as *mut BYTE,
                ::core::mem::size_of::<DWORD>() as DWORD,
            );
        } else {
            if ((*__wine_dbch___default).flags as ::core::ffi::c_int
                & ((1 as ::core::ffi::c_int) << (__WINE_DBCL_TRACE as ::core::ffi::c_int)))
                != 0
            {
                let __dbch_0: *mut __wine_debug_channel = __wine_dbch___default;
                let __dbcl_0: __wine_debug_class = __WINE_DBCL_TRACE;
                ros_dbg_log(
                    __dbcl_0,
                    __dbch_0,
                    b"dll/win32/setupapi/install.c\0"
                        as *const u8 as *const ::core::ffi::c_char,
                    b"do_reg_operation\0" as *const u8 as *const ::core::ffi::c_char,
                    392 as ::core::ffi::c_int,
                    b"setting value %s to %s\n\0" as *const u8 as *const ::core::ffi::c_char,
                    debugstr_w(value),
                    debugstr_w(str_0),
                );
            }
            if !str_0.is_null() {
                RegSetValueExW(
                    hkey,
                    value as LPCWSTR,
                    0,
                    type_0,
                    str_0 as *mut BYTE,
                    (size as usize).wrapping_mul(::core::mem::size_of::<WCHAR>() as usize) as DWORD,
                );
            } else {
                RegSetValueExW(
                    hkey,
                    value as LPCWSTR,
                    0,
                    type_0,
                    &raw const empty as *const BYTE,
                    ::core::mem::size_of::<WCHAR>() as DWORD,
                );
            }
        }
        HeapFree(GetProcessHeap(), 0, str_0 as PVOID);
        return TRUE as BOOL;
    } else {
        let mut data: *mut BYTE = core::ptr::null_mut::<BYTE>();

        if SetupGetBinaryField(
            context,
            5,
            core::ptr::null_mut::<BYTE>(),
            0,
            &raw mut size,
        ) == 0
        {
            size = 0;
        }
        if size != 0 {
            data = HeapAlloc(GetProcessHeap(), 0, size as SIZE_T) as *mut BYTE;
            if data.is_null() {
                return FALSE as BOOL;
            }
            if ((*__wine_dbch___default).flags as ::core::ffi::c_int
                & ((1 as ::core::ffi::c_int) << (__WINE_DBCL_TRACE as ::core::ffi::c_int)))
                != 0
            {
                let __dbch_1: *mut __wine_debug_channel = __wine_dbch___default;
                let __dbcl_1: __wine_debug_class = __WINE_DBCL_TRACE;
                ros_dbg_log(
                    __dbcl_1,
                    __dbch_1,
                    b"dll/win32/setupapi/install.c\0"
                        as *const u8 as *const ::core::ffi::c_char,
                    b"do_reg_operation\0" as *const u8 as *const ::core::ffi::c_char,
                    407 as ::core::ffi::c_int,
                    b"setting binary data %s len %d\n\0" as *const u8 as *const ::core::ffi::c_char,
                    debugstr_w(value),
                    size,
                );
            }
            SetupGetBinaryField(
                context,
                5,
                data as PBYTE,
                size,
                core::ptr::null_mut::<DWORD>(),
            );
        }
        RegSetValueExW(hkey, value as LPCWSTR, 0, type_0, data, size);
        HeapFree(GetProcessHeap(), 0, data as PVOID);
        return TRUE as BOOL;
    }
}

unsafe extern "C" fn registry_callback(
    mut hinf: HINF,
    mut field: PCWSTR,
    mut arg: *mut core::ffi::c_void,
) -> BOOL {
    let mut info: *mut registry_callback_info = arg as *mut registry_callback_info;
    let mut security_key: LPWSTR = core::ptr::null_mut();
    let mut security_descriptor: LPWSTR = core::ptr::null_mut();
    let mut context: INFCONTEXT = core::mem::zeroed();
    let mut security_context: INFCONTEXT = core::mem::zeroed();
    let mut sd: PSECURITY_DESCRIPTOR = core::ptr::null_mut();
    let mut security_attributes: SECURITY_ATTRIBUTES = SECURITY_ATTRIBUTES {
        nLength: 0,
        lpSecurityDescriptor: core::ptr::null_mut(),
        bInheritHandle: 0,
    };
    let mut root_key: HKEY = core::ptr::null_mut();
    let mut hkey: HKEY = core::ptr::null_mut();
    let mut required: DWORD = 0;

    let mut ok: BOOL = SetupFindFirstLineW(
        hinf,
        field,
        core::ptr::null(),
        core::ptr::addr_of_mut!(context),
    );
    if ok == 0 {
        return (TRUE) as BOOL;
    }

    /* Check for .Security section */
    security_key = MyMalloc(
        ((strlenW(field) as DWORD)
            + (strlenW(core::ptr::addr_of!(DotSecurity) as PCWSTR) as DWORD))
            * (core::mem::size_of::<WCHAR>() as DWORD)
            + (core::mem::size_of_val(&UNICODE_NULL) as DWORD),
    ) as LPWSTR;
    if security_key.is_null() {
        SetLastError(ERROR_NOT_ENOUGH_MEMORY);
        return (FALSE) as BOOL;
    }
    strcpyW(security_key, field);
    strcatW(security_key, core::ptr::addr_of!(DotSecurity) as PCWSTR);
    ok = SetupFindFirstLineW(
        hinf,
        security_key as PCWSTR,
        core::ptr::null(),
        core::ptr::addr_of_mut!(security_context),
    );
    MyFree(security_key as PVOID);
    if ok != 0 {
        if SetupGetLineTextW(
            core::ptr::addr_of_mut!(security_context),
            core::ptr::null_mut(),
            core::ptr::null(),
            core::ptr::null(),
            core::ptr::null_mut(),
            0 as DWORD,
            core::ptr::addr_of_mut!(required),
        ) == 0
        {
            return (FALSE) as BOOL;
        }
        security_descriptor = MyMalloc(
            (required as usize).wrapping_mul(core::mem::size_of::<WCHAR>()) as DWORD,
        ) as LPWSTR;
        if security_descriptor.is_null() {
            SetLastError(ERROR_NOT_ENOUGH_MEMORY);
            return (FALSE) as BOOL;
        }
        if SetupGetLineTextW(
            core::ptr::addr_of_mut!(security_context),
            core::ptr::null_mut(),
            core::ptr::null(),
            core::ptr::null(),
            security_descriptor as PWSTR,
            required,
            core::ptr::null_mut(),
        ) == 0
        {
            return (FALSE) as BOOL;
        }
        ok = ConvertStringSecurityDescriptorToSecurityDescriptorW(
            security_descriptor as LPCWSTR,
            SDDL_REVISION_1 as DWORD,
            core::ptr::addr_of_mut!(sd),
            core::ptr::null_mut(),
        );
        MyFree(security_descriptor as PVOID);
        if ok == 0 {
            return (FALSE) as BOOL;
        }
        security_attributes.nLength =
            core::mem::size_of::<SECURITY_ATTRIBUTES>() as DWORD;
        security_attributes.lpSecurityDescriptor = sd as LPVOID;
    }

    ok = (TRUE as i32);
    while ok != 0 {
        'body: {
            let mut buffer: [WCHAR; (MAX_INF_STRING_LENGTH) as _] = [0; (MAX_INF_STRING_LENGTH) as _];
            let mut flags: INT = 0;

            /* get root */
            if SetupGetStringFieldW(
                core::ptr::addr_of_mut!(context),
                1 as DWORD,
                addr_of_mut!(buffer) as PWSTR,
                ((core::mem::size_of::<[WCHAR; (MAX_INF_STRING_LENGTH) as _]>())
                    / core::mem::size_of::<WCHAR>()) as DWORD,
                core::ptr::null_mut(),
            ) == 0
            {
                break 'body;
            }
            root_key = get_root_key(
                addr_of_mut!(buffer) as *mut WCHAR,
                (*info).default_root,
            );
            if root_key.is_null() {
                break 'body;
            }

            /* get key */
            if SetupGetStringFieldW(
                core::ptr::addr_of_mut!(context),
                2 as DWORD,
                addr_of_mut!(buffer) as PWSTR,
                ((core::mem::size_of::<[WCHAR; (MAX_INF_STRING_LENGTH) as _]>())
                    / core::mem::size_of::<WCHAR>()) as DWORD,
                core::ptr::null_mut(),
            ) == 0
            {
                *(addr_of_mut!(buffer) as *mut WCHAR) = 0 as WCHAR;
            }

            /* get flags */
            if SetupGetIntField(
                core::ptr::addr_of_mut!(context),
                4 as DWORD,
                core::ptr::addr_of_mut!(flags),
            ) == 0
            {
                flags = 0 as INT;
            }

            if (*info).delete == 0 {
                if flags & FLG_ADDREG_DELREG_BIT != 0 {
                    break 'body; /* ignore this entry */
                }
            } else {
                if flags == 0 {
                    flags = FLG_ADDREG_DELREG_BIT as INT;
                } else if flags & FLG_ADDREG_DELREG_BIT == 0 {
                    break 'body; /* ignore this entry */
                }
            }

            if (*info).delete != 0 || flags & (FLG_ADDREG_OVERWRITEONLY as INT) != 0 {
                if RegOpenKeyW(
                    root_key,
                    addr_of_mut!(buffer) as *mut WCHAR as LPCWSTR,
                    core::ptr::addr_of_mut!(hkey),
                ) != 0
                {
                    break 'body; /* ignore if it doesn't exist */
                }
            } else if RegCreateKeyExW(
                root_key,
                addr_of_mut!(buffer) as *mut WCHAR as LPCWSTR,
                0 as DWORD,
                core::ptr::null_mut(),
                0 as DWORD,
                MAXIMUM_ALLOWED as REGSAM,
                if !sd.is_null() {
                    core::ptr::addr_of_mut!(security_attributes)
                } else {
                    core::ptr::null_mut()
                },
                core::ptr::addr_of_mut!(hkey),
                core::ptr::null_mut(),
            ) != 0
            {
                ERR!(
                    "could not create key %p %s\n",
                    root_key,
                    debugstr_w(addr_of_mut!(buffer) as *mut WCHAR)
                );
                break 'body;
            }

            /* get value name */
            if SetupGetStringFieldW(
                core::ptr::addr_of_mut!(context),
                3 as DWORD,
                addr_of_mut!(buffer) as PWSTR,
                ((core::mem::size_of::<[WCHAR; (MAX_INF_STRING_LENGTH) as _]>())
                    / core::mem::size_of::<WCHAR>()) as DWORD,
                core::ptr::null_mut(),
            ) == 0
            {
                *(addr_of_mut!(buffer) as *mut WCHAR) = 0 as WCHAR;
            }

            /* and now do it */
            if do_reg_operation(
                hkey,
                addr_of_mut!(buffer) as *mut WCHAR,
                core::ptr::addr_of_mut!(context),
                flags,
            ) == 0
            {
                if hkey != root_key {
                    RegCloseKey(hkey);
                }
                if !sd.is_null() {
                    LocalFree(sd as HLOCAL);
                }
                return FALSE as BOOL;
            }
            if hkey != root_key {
                RegCloseKey(hkey);
            }
        }
        ok = SetupFindNextLine(
            core::ptr::addr_of_mut!(context),
            core::ptr::addr_of_mut!(context),
        );
    }
    if !sd.is_null() {
        LocalFree(sd as HLOCAL);
    }
    return TRUE as BOOL;
}

unsafe extern "C" fn do_register_dll(
    info: *const register_dll_info,
    path: *const WCHAR,
    flags: INT,
    timeout: INT,
    mut args: *const WCHAR,
) -> BOOL {
    let mut module: HMODULE = core::ptr::null_mut();
    let mut res: HRESULT = 0;
    let mut status: SP_REGISTER_CONTROL_STATUSW = SP_REGISTER_CONTROL_STATUSW {
        cbSize: 0,
        FileName: core::ptr::null(),
        Win32Error: 0,
        FailureCode: 0,
    };
    let mut nt: *mut IMAGE_NT_HEADERS = core::ptr::null_mut();

    status.cbSize = core::mem::size_of::<SP_REGISTER_CONTROL_STATUSW>() as DWORD;
    status.FileName = path as PCWSTR;
    status.FailureCode = SPREG_SUCCESS;
    status.Win32Error = ERROR_SUCCESS;

    if (*info).callback.is_some() {
        match (*info).callback.unwrap_unchecked()(
            (*info).callback_context,
            SPFILENOTIFY_STARTREGISTRATION,
            core::ptr::addr_of_mut!(status) as UINT_PTR,
            (((*info).unregister == 0) as BOOL) as UINT_PTR,
        ) {
            FILEOP_ABORT => {
                SetLastError(ERROR_OPERATION_ABORTED);
                return (FALSE) as BOOL;
            }
            FILEOP_SKIP => return (TRUE as i32),
            FILEOP_DOIT => {}
            _ => {}
        }
    }

    module = LoadLibraryExW(path, core::ptr::null_mut(), LOAD_WITH_ALTERED_SEARCH_PATH) as HMODULE;

    'done: {
        if module.is_null() {
            WARN!("could not load %s\n", debugstr_w(path));
            status.FailureCode = SPREG_LOADLIBRARY;
            status.Win32Error = GetLastError();
            break 'done;
        }

        nt = RtlImageNtHeader(module as PVOID) as *mut IMAGE_NT_HEADERS;
        if !nt.is_null() && (((*nt).FileHeader.Characteristics as INT) & (IMAGE_FILE_DLL as i32)) == 0 {
            /* file is an executable, not a dll */
            let mut startup: STARTUPINFOW = core::mem::zeroed();
            let mut info: PROCESS_INFORMATION = core::mem::zeroed();
            let mut cmd_line: *mut WCHAR = core::ptr::null_mut();
            let mut res: BOOL = 0;
            static format: [u16; 8] = [0x0022u16, 0x0025, 0x0073, 0x0022, 0x0020, 0x0025, 0x0073, 0x0000];
            static default_args: [u16; 11] = [
    0x002Fu16, 0x0052, 0x0065, 0x0067, 0x0053, 0x0065, 0x0072, 0x0076, 0x0065, 0x0072,
    0x0000,
];

            FreeLibrary(module);
            module = core::ptr::null_mut();
            if args.is_null() {
                args = core::ptr::addr_of!(default_args) as *const WCHAR;
            }
            cmd_line = HeapAlloc(
                GetProcessHeap(),
                0,
                (((strlenW(path) + strlenW(args) + 4) as usize)
                    * core::mem::size_of::<WCHAR>()) as SIZE_T,
            ) as *mut WCHAR;
            sprintfW(
                cmd_line,
                core::ptr::addr_of!(format) as *const WCHAR,
                path,
                args,
            );
            memset(
                core::ptr::addr_of_mut!(startup) as *mut core::ffi::c_void,
                0,
                core::mem::size_of::<STARTUPINFOW>(),
            );
            startup.cb = core::mem::size_of::<STARTUPINFOW>() as DWORD;

            res = CreateProcessW(
                core::ptr::null(),
                cmd_line as LPWSTR,
                core::ptr::null_mut(),
                core::ptr::null_mut(),
                (FALSE) as BOOL,
                0,
                core::ptr::null_mut(),
                core::ptr::null(),
                core::ptr::addr_of_mut!(startup),
                core::ptr::addr_of_mut!(info),
            );
            HeapFree(
                GetProcessHeap(),
                0,
                cmd_line as PVOID,
            );
            if res == 0 {
                status.FailureCode = SPREG_LOADLIBRARY;
                status.Win32Error = GetLastError();
                break 'done;
            }
            CloseHandle(info.hThread);

            if WaitForSingleObject(
                info.hProcess,
                (timeout * 1000) as DWORD,
            ) == WAIT_TIMEOUT
            {
                /* timed out, kill the process */
                TerminateProcess(info.hProcess, 1);
                status.FailureCode = SPREG_TIMEOUT;
                status.Win32Error = ERROR_TIMEOUT;
            }
            CloseHandle(info.hProcess);
            break 'done;
        }

        if (flags & (FLG_REGSVR_DLLREGISTER as INT)) != 0 {
            let entry_point: *const core::ffi::c_char = if (*info).unregister != 0 {
                b"DllUnregisterServer\0" as *const u8 as *const core::ffi::c_char
            } else {
                b"DllRegisterServer\0" as *const u8 as *const core::ffi::c_char
            };
            let mut func: Option<unsafe extern "system" fn() -> HRESULT> =
                ::core::mem::transmute::<
                    *mut core::ffi::c_void,
                    Option<unsafe extern "system" fn() -> HRESULT>,
                >(::core::mem::transmute::<FARPROC, *mut core::ffi::c_void>(
                    GetProcAddress(module as HINSTANCE, entry_point as LPCSTR),
                ));

            if func.is_none() {
                status.FailureCode = SPREG_GETPROCADDR;
                status.Win32Error = GetLastError();
                break 'done;
            }

            res = (func.unwrap_unchecked())();

            if res < 0 {
                WARN!(
                    "calling %s in %s returned error %x\n",
                    entry_point,
                    debugstr_w(path),
                    res
                );
                status.FailureCode = SPREG_REGSVR;
                status.Win32Error = res as DWORD;
                break 'done;
            }
        }

        if (flags & (FLG_REGSVR_DLLINSTALL as INT)) != 0 {
            let mut func: Option<
                unsafe extern "system" fn(BOOL, LPCWSTR) -> HRESULT,
            > = ::core::mem::transmute::<
                *mut core::ffi::c_void,
                Option<
                    unsafe extern "system" fn(BOOL, LPCWSTR) -> HRESULT,
                >,
            >(::core::mem::transmute::<FARPROC, *mut core::ffi::c_void>(
                GetProcAddress(module as HINSTANCE, b"DllInstall\0" as *const u8 as LPCSTR),
            ));

            if func.is_none() {
                status.FailureCode = SPREG_GETPROCADDR;
                status.Win32Error = GetLastError();
                break 'done;
            }

            res = (func.unwrap_unchecked())(((*info).unregister == 0) as BOOL, args as LPCWSTR);

            if res < 0 {
                WARN!(
                    "calling DllInstall in %s returned error %x\n",
                    debugstr_w(path),
                    res
                );
                status.FailureCode = SPREG_REGSVR;
                status.Win32Error = res as DWORD;
                break 'done;
            }
        }
    }

    if !module.is_null() {
        FreeLibrary(module);
    }
    if (*info).callback.is_some() {
        (*info).callback.unwrap_unchecked()(
            (*info).callback_context,
            SPFILENOTIFY_ENDREGISTRATION,
            core::ptr::addr_of_mut!(status) as UINT_PTR,
            (((*info).unregister == 0) as BOOL) as UINT_PTR,
        );
    }
    return (TRUE) as BOOL;
}

unsafe extern "C" fn register_dlls_callback(hinf: HINF, field: PCWSTR, arg: *mut core::ffi::c_void) -> BOOL {
    let info: *mut register_dll_info = arg as *mut register_dll_info;
    let mut context: INFCONTEXT = core::mem::zeroed();
    let mut ret: BOOL = (TRUE as i32);
    let mut ok: BOOL = SetupFindFirstLineW(hinf, field, core::ptr::null_mut(), core::ptr::addr_of_mut!(context));

    'lp: while ok != 0 {
        'next: {
            let mut path: PWSTR;
            let mut args: PWSTR;
            let mut p: PWSTR;
            let mut buffer: [WCHAR; (MAX_INF_STRING_LENGTH) as _] = [0 as WCHAR; (MAX_INF_STRING_LENGTH) as _];
            let mut flags: INT = core::mem::zeroed();
            let mut timeout: INT = core::mem::zeroed();

            /* get directory */
            path = PARSER_get_dest_dir(core::ptr::addr_of_mut!(context)) as PWSTR;
            if path.is_null() {
                break 'next;
            }

            'done: {
                /* get dll name */
                if SetupGetStringFieldW(
                    core::ptr::addr_of_mut!(context),
                    3 as DWORD,
                    core::ptr::addr_of_mut!(buffer) as PWSTR,
                    (core::mem::size_of::<[WCHAR; (MAX_INF_STRING_LENGTH) as _]>() / core::mem::size_of::<WCHAR>()) as DWORD,
                    core::ptr::null_mut(),
                ) == 0
                {
                    break 'done;
                }
                p = HeapReAlloc(
                    GetProcessHeap(),
                    0 as DWORD,
                    path as LPVOID,
                    ((strlenW(path) as SIZE_T
                        + strlenW(core::ptr::addr_of_mut!(buffer) as PWSTR) as SIZE_T
                        + 2 as SIZE_T)
                        * core::mem::size_of::<WCHAR>() as SIZE_T),
                ) as PWSTR;
                if p.is_null() {
                    break 'done;
                }
                path = p;
                p = p.offset(strlenW(p) as isize);
                if p == path || *p.offset(-(1 as isize)) != '\\' as WCHAR {
                    *p = '\\' as WCHAR;
                    p = p.offset(1);
                }
                strcpyW(p, core::ptr::addr_of_mut!(buffer) as PWSTR);

                /* get flags */
                if SetupGetIntField(
                    core::ptr::addr_of_mut!(context),
                    4 as DWORD,
                    core::ptr::addr_of_mut!(flags),
                ) == 0
                {
                    flags = 0 as INT;
                }

                /* get timeout */
                {
                    /* "11,,cmd.exe,,,/K dir" means default timeout, not a timeout of zero */
                    if SetupGetIntField(
                        core::ptr::addr_of_mut!(context),
                        5 as DWORD,
                        core::ptr::addr_of_mut!(timeout),
                    ) == 0
                        || timeout == 0 as INT
                    {
                        timeout = 60 as INT;
                    }
                }

                /* get command line */
                args = core::ptr::null_mut();
                if SetupGetStringFieldW(
                    core::ptr::addr_of_mut!(context),
                    6 as DWORD,
                    core::ptr::addr_of_mut!(buffer) as PWSTR,
                    (core::mem::size_of::<[WCHAR; (MAX_INF_STRING_LENGTH) as _]>() / core::mem::size_of::<WCHAR>()) as DWORD,
                    core::ptr::null_mut(),
                ) != 0
                {
                    args = core::ptr::addr_of_mut!(buffer) as PWSTR;
                }

                ret = do_register_dll(info, path, flags, timeout, args);
            }

            HeapFree(
                GetProcessHeap(),
                0 as DWORD,
                path as LPVOID,
            );
            if ret == 0 {
                break 'lp;
            }
        }
        ok = SetupFindNextLine(
            core::ptr::addr_of_mut!(context),
            core::ptr::addr_of_mut!(context),
        );
    }
    return ret;
}

unsafe extern "C" fn update_ini_callback(hinf: HINF, field: PCWSTR, arg: *mut core::ffi::c_void) -> BOOL {
    let _ = arg;
    let mut context: INFCONTEXT = core::mem::zeroed();

    let mut ok: BOOL = SetupFindFirstLineW(hinf, field, core::ptr::null(), &raw mut context);

    while ok != 0 {
        'body: {
            let mut buffer: [WCHAR; (MAX_INF_STRING_LENGTH) as _] = [0; (MAX_INF_STRING_LENGTH) as _];
            let mut filename: [WCHAR; (MAX_INF_STRING_LENGTH) as _] = [0; (MAX_INF_STRING_LENGTH) as _];
            let mut section: [WCHAR; (MAX_INF_STRING_LENGTH) as _] = [0; (MAX_INF_STRING_LENGTH) as _];
            let mut entry: [WCHAR; (MAX_INF_STRING_LENGTH) as _] = [0; (MAX_INF_STRING_LENGTH) as _];
            let mut string: [WCHAR; (MAX_INF_STRING_LENGTH) as _] = [0; (MAX_INF_STRING_LENGTH) as _];
            let mut divider: LPWSTR = core::ptr::null_mut::<WCHAR>();

            if SetupGetStringFieldW(
                &raw mut context,
                1 as DWORD,
                &raw mut filename as PWSTR,
                (core::mem::size_of::<[WCHAR; (MAX_INF_STRING_LENGTH) as _]>()
                    / core::mem::size_of::<WCHAR>()) as DWORD,
                core::ptr::null_mut::<DWORD>(),
            ) == 0
            {
                break 'body;
            }

            if SetupGetStringFieldW(
                &raw mut context,
                2 as DWORD,
                &raw mut section as PWSTR,
                (core::mem::size_of::<[WCHAR; (MAX_INF_STRING_LENGTH) as _]>()
                    / core::mem::size_of::<WCHAR>()) as DWORD,
                core::ptr::null_mut::<DWORD>(),
            ) == 0
            {
                break 'body;
            }

            if SetupGetStringFieldW(
                &raw mut context,
                4 as DWORD,
                &raw mut buffer as PWSTR,
                (core::mem::size_of::<[WCHAR; (MAX_INF_STRING_LENGTH) as _]>()
                    / core::mem::size_of::<WCHAR>()) as DWORD,
                core::ptr::null_mut::<DWORD>(),
            ) == 0
            {
                break 'body;
            }

            divider = strchrW(&raw mut buffer as PWSTR, '=' as WCHAR);
            if !divider.is_null() {
                *divider = 0 as WCHAR;
                strcpyW(&raw mut entry as PWSTR, &raw mut buffer as PWSTR);
                divider = divider.add(1);
                strcpyW(&raw mut string as PWSTR, divider);
            } else {
                strcpyW(&raw mut entry as PWSTR, &raw mut buffer as PWSTR);
                string[0 as usize] = 0 as WCHAR;
            }

            WritePrivateProfileStringW(
                &raw mut section as *mut WCHAR as LPCWSTR,
                &raw mut entry as *mut WCHAR as LPCWSTR,
                &raw mut string as *mut WCHAR as LPCWSTR,
                &raw mut filename as *mut WCHAR as LPCWSTR,
            );
        }
        ok = SetupFindNextLine(&raw mut context, &raw mut context);
    }
    return TRUE as BOOL;
}

