#!/bin/bash
# Generate the focused USB FFI substrate (hid-sys) for all 3 arches.
#
# hid-sys covers ONLY the HID parser DDK types the usbd.sys translation needs —
# URB + USB descriptors (usb.h/usb100.h via usbdi.h) + USBD info structs
# (usbdlib.h) — which are absent from ntkrnl-sys (that crate is ntoskrnl.h-only).
# Allowlisted to USB_*/USBD_*/_URB* so it stays small and won't drift into a
# second copy of the kernel surface. Per-arch (URB/pointer widths differ).
#
# Prereq: cargo install bindgen-cli. Build dirs must exist (generated headers
# like ntddk.h live under build-<arch>/sdk/include). Run from anywhere.
set -e
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SRC="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
TC="$SRC/.build-tools/llvm-mingw"
OUT_DIR="$SCRIPT_DIR/src"
WRAPPER="$SCRIPT_DIR/wrapper_parser_h.h"

COMMON_FLAGS=(
    --use-core --no-layout-tests --no-doc-comments
    --raw-line "use hid_sys::*;"
    --allowlist-type 'P?(GLOBAL_ITEM_STATE|HID_COLLECTION|HID_PARSER_CONTEXT|HID_REPORT|HID_REPORT_ITEM|ITEM_PREFIX|LOCAL_ITEM_STATE|LONG_ITEM|MAIN_ITEM_DATA|SHORT_ITEM|USAGE_VALUE)'
    --blocklist-type '(HIDP_.*|HIDD_.*|^USAGE$|^PUSAGE$|^USAGE_AND_PAGE$)'
)

run_bindgen() {
    local ARCH=$1 TARGET=$2; shift 2
    local EXTRA=("$@")
    local BUILD_DIR="$SRC/build-${ARCH}"
    local RAW="/tmp/parserh_${ARCH}_raw.rs"
    local FINAL="$OUT_DIR/parser_h_${ARCH}.rs"
    echo "=== hid-sys ${ARCH} (${TARGET}) ==="
    bindgen "$WRAPPER" "${COMMON_FLAGS[@]}" -o "$RAW" -- \
        -ferror-limit=0 -Wno-everything \
        -D_NTOSKRNL_ -D_NTSYSTEM_ -D__REACTOS__ -D_USE_DUMMY_PSEH=1 \
        "${EXTRA[@]}" \
        -DDBG=1 -DWINVER=0x502 -D_WIN32_WINNT=0x502 \
        -I"${BUILD_DIR}/ntoskrnl" \
        -I"${SRC}/ntoskrnl" \
        -I"${SRC}/sdk/lib/drivers/hidparser" \
        -I"${SRC}/sdk/include" \
        -I"${SRC}/sdk/include/ddk" \
        -I"${SRC}/sdk/include/ndk" \
        -I"${SRC}/sdk/include/psdk" \
        -I"${SRC}/sdk/include/xdk" \
        -I"${SRC}/sdk/include/reactos" \
        -I"${SRC}/sdk/include/reactos/libs" \
        -I"${SRC}/sdk/include/reactos/drivers" \
        -I"${SRC}/sdk/include/vcruntime" \
        -I"${SRC}/sdk/include/winrt" \
        -I"${BUILD_DIR}/sdk/include" \
        -I"${BUILD_DIR}/sdk/include/psdk" \
        -I"${BUILD_DIR}/sdk/include/ddk" \
        -I"${BUILD_DIR}/sdk/include/dxsdk" \
        -I"${BUILD_DIR}/sdk/include/reactos" \
        -I"${BUILD_DIR}/sdk/include/reactos/mc" \
        -I"${SRC}/sdk/include/dxsdk" \
        -I"${SRC}/sdk/lib/pseh/include" \
        -I"${SRC}" \
        -I"${SRC}/sdk/lib/drivers/arbiter" \
        -I"${SRC}/sdk/lib/cmlib" \
        -I"${SRC}/ntoskrnl/include" \
        -I"${BUILD_DIR}/ntoskrnl/include" \
        -I"${BUILD_DIR}/ntoskrnl/include/internal" \
        -isystem "${SRC}/sdk/include/crt" \
        -isystem "${TC}/lib/clang/19/include" \
        --target="${TARGET}"
    # Header banner + no_std-friendly prelude (bindgen --use-core already uses core::).
    {
        echo "// AUTO-GENERATED by hid-sys/generate_bindings.sh — do not edit by hand."
        echo "// Focused HID parser DDK substrate (HIDP parser caps + report types) for usbd.sys."
        echo "#![allow(non_snake_case, non_camel_case_types, non_upper_case_globals, dead_code)]"
        cat "$RAW"
    } > "$FINAL"
    echo "  -> $FINAL ($(wc -l < "$FINAL") lines)"
}

run_bindgen arm64 aarch64-pc-windows-gnu -D_WIN64 -D_M_ARM64 -D__aarch64__ -D__arm64__ -D_ARM64_
run_bindgen amd64 x86_64-pc-windows-gnu  -D_WIN64 -D_M_AMD64 -D__x86_64__ -D_AMD64_
run_bindgen i386  i686-pc-windows-gnu    -D_M_IX86 -D__i386__ -D_X86_
echo "=== done ==="
