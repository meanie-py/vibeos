// The island's enum values (SmallIcons=0, LargeIcons=1, List=2, Detail=3). The translation
// had guessed them "from enum declaration order" and swapped Small and Large, so a Large
// Icons view was saved as "SmallIcon".
#[allow(non_upper_case_globals)]
const ListView_LargeIcons: LISTVIEW_MODE = _LISTVIEW_MODE_ListView_LargeIcons;
#[allow(non_upper_case_globals)]
const ListView_SmallIcons: LISTVIEW_MODE = _LISTVIEW_MODE_ListView_SmallIcons;
#[allow(non_upper_case_globals)]
const ListView_List: LISTVIEW_MODE = _LISTVIEW_MODE_ListView_List;
#[allow(non_upper_case_globals)]
const ListView_Detail: LISTVIEW_MODE = _LISTVIEW_MODE_ListView_Detail;

#[no_mangle]
pub unsafe extern "C" fn ViewModeToCmdId(ListViewMode: LISTVIEW_MODE) -> UINT {
    let mut CmdId: UINT;

    if ListViewMode == ListView_SmallIcons {
        CmdId = IDM_VIEW_SMALL_ICONS;
    } else if ListViewMode == ListView_LargeIcons {
        CmdId = IDM_VIEW_LARGE_ICONS;
    } else if ListViewMode == ListView_List {
        CmdId = IDM_VIEW_LIST;
    } else {
        // default: falls through to ListView_Detail
        CmdId = IDM_VIEW_DETAILS;
    }

    return CmdId;
}
#[no_mangle]
pub unsafe extern "C" fn CmdIdToViewMode(CmdId: UINT) -> LISTVIEW_MODE {
    let mut ListViewMode: LISTVIEW_MODE;

    match CmdId {
        IDM_VIEW_SMALL_ICONS => {
            ListViewMode = ListView_SmallIcons;
        }

        IDM_VIEW_LARGE_ICONS => {
            ListViewMode = ListView_LargeIcons;
        }

        IDM_VIEW_LIST => {
            ListViewMode = ListView_List;
        }

        IDM_VIEW_DETAILS => {
            ListViewMode = ListView_Detail;
        }

        _ => {
            ListViewMode = ListView_Detail;
        }
    }

    return ListViewMode;
}
