    pub unsafe fn Rename(&mut self, pszwDuplicateName: LPCWSTR) -> HRESULT {
        let this_: *mut Self = self;
        let mut szName: [u16; 140] = core::mem::zeroed();
        let mut pStr: LPWSTR = core::ptr::null_mut();
        let mut dwSize: DWORD = core::mem::zeroed();
        let mut hKey: HKEY = core::mem::zeroed();
        let mut hr: HRESULT = core::mem::zeroed();

        if pszwDuplicateName.is_null() || wcslen(pszwDuplicateName) == 0 {
            return S_OK;
        }

        if !(*this_).m_Props.pszwName.is_null() {
            CoTaskMemFree((*this_).m_Props.pszwName as *mut core::ffi::c_void);
            (*this_).m_Props.pszwName = core::ptr::null_mut();
        }

        dwSize = ((wcslen(pszwDuplicateName) as DWORD) + 1) * (core::mem::size_of::<u16>() as DWORD);
        (*this_).m_Props.pszwName = CoTaskMemAlloc((dwSize) as SIZE_T) as PWSTR;
        if (*this_).m_Props.pszwName.is_null() {
            return E_OUTOFMEMORY;
        }

        wcscpy((*this_).m_Props.pszwName, pszwDuplicateName);

        hr = StringFromCLSID(core::ptr::addr_of!((*this_).m_Props.guidId) as *const CLSID, &mut pStr);
        if (hr) >= 0 {
            wcscpy(szName.as_mut_ptr(), CPP_COM_WSTR_C560181AF982.as_ptr());
            wcscat(szName.as_mut_ptr(), pStr);
            wcscat(szName.as_mut_ptr(), CPP_COM_WSTR_636AA582CA19.as_ptr());

            if RegOpenKeyExW(HKEY_LOCAL_MACHINE, szName.as_ptr(), 0, KEY_WRITE, &mut hKey) == (ERROR_SUCCESS as i32) {
                RegSetValueExW(hKey, CPP_COM_WSTR_76E480513E2C.as_ptr(), 0, REG_SZ, (*this_).m_Props.pszwName as LPBYTE, dwSize);
                RegCloseKey(hKey);
            }

            CoTaskMemFree(pStr as *mut core::ffi::c_void);
        }

        return hr;
    }
