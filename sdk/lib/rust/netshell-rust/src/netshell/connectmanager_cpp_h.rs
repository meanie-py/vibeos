    pub unsafe fn Disconnect(&mut self) -> HRESULT {
        let this_: *mut Self = self;
        let mut hKey: HKEY = core::ptr::null_mut();
        let mut pProperties: *mut NETCON_PROPERTIES = core::ptr::null_mut();
        let mut pDisplayName: LPOLESTR = core::ptr::null_mut();
        let mut szPath: [WCHAR; 200] = [0; 200];
        let mut dwSize: DWORD = 0;
        let mut dwType: DWORD = 0;
        let mut pPnp: LPWSTR = core::ptr::null_mut();
        let mut hInfo: HDEVINFO = core::ptr::null_mut();
        let mut DevInfo: SP_DEVINFO_DATA = core::mem::zeroed();
        let mut PropChangeParams: SP_PROPCHANGE_PARAMS = core::mem::zeroed();
        let mut hr: HRESULT = 0;

        hr = (*this_).GetProperties(core::ptr::addr_of_mut!(pProperties));
        if FAILED_UNEXPECTEDLY!(hr) != false {
            return hr;
        }

        hInfo = SetupDiGetClassDevsW(core::ptr::addr_of!(GUID_DEVCLASS_NET), core::ptr::null_mut(), core::ptr::null_mut(), DIGCF_PRESENT);
        if hInfo.is_null() {
            NcFreeNetconProperties(pProperties);
            return E_FAIL;
        }

        if StringFromCLSID(&(*pProperties).guidId, core::ptr::addr_of_mut!(pDisplayName)) < 0 {
            NcFreeNetconProperties(pProperties);
            SetupDiDestroyDeviceInfoList(hInfo);
            return E_FAIL;
        }
        NcFreeNetconProperties(pProperties);

        if FindNetworkAdapter(hInfo, core::ptr::addr_of_mut!(DevInfo), pDisplayName) != 0 {
            PropChangeParams.ClassInstallHeader.cbSize = core::mem::size_of::<SP_CLASSINSTALL_HEADER>() as u32;
            PropChangeParams.ClassInstallHeader.InstallFunction = DIF_PROPERTYCHANGE;
            PropChangeParams.StateChange = DICS_DISABLE;
            PropChangeParams.Scope = DICS_FLAG_CONFIGSPECIFIC;
            PropChangeParams.HwProfile = 0;

            if SetupDiSetClassInstallParams(hInfo, core::ptr::addr_of_mut!(DevInfo), core::ptr::addr_of_mut!(PropChangeParams.ClassInstallHeader), core::mem::size_of::<SP_PROPCHANGE_PARAMS>() as u32) == 0
                || SetupDiCallClassInstaller(DIF_PROPERTYCHANGE, hInfo, core::ptr::addr_of_mut!(DevInfo)) == 0
            {
                hr = HRESULT_FROM_WIN32!(GetLastError());
            }
        }
        SetupDiDestroyDeviceInfoList(hInfo);

        _swprintf(szPath.as_mut_ptr(), CPP_COM_WSTR_285242FC4F38.as_ptr(), pDisplayName);
        CoTaskMemFree((pDisplayName).cast());

        if FAILED_UNEXPECTEDLY!(hr) != false {
            return hr;
        }

        if RegOpenKeyExW(HKEY_LOCAL_MACHINE, szPath.as_ptr(), 0, KEY_READ, core::ptr::addr_of_mut!(hKey)) != (ERROR_SUCCESS as i32) {
            return E_FAIL;
        }

        dwSize = 0;
        if RegQueryValueExW(hKey, CPP_COM_WSTR_60A4C823C9C0.as_ptr(), core::ptr::null_mut(), core::ptr::addr_of_mut!(dwType), core::ptr::null_mut(), core::ptr::addr_of_mut!(dwSize)) != (ERROR_SUCCESS as i32) || dwType != REG_SZ {
            RegCloseKey(hKey);
            return E_FAIL;
        }

        pPnp = CoTaskMemAlloc((dwSize) as SIZE_T) as PWSTR;
        if pPnp.is_null() {
            RegCloseKey(hKey);
            return E_FAIL;
        }

        if RegQueryValueExW(hKey, CPP_COM_WSTR_60A4C823C9C0.as_ptr(), core::ptr::null_mut(), core::ptr::addr_of_mut!(dwType), pPnp as LPBYTE, core::ptr::addr_of_mut!(dwSize)) != (ERROR_SUCCESS as i32) {
            CoTaskMemFree((pPnp).cast());
            RegCloseKey(hKey);
            return E_FAIL;
        }
        RegCloseKey(hKey);

        _swprintf(szPath.as_mut_ptr(), CPP_COM_WSTR_9771C6C22DBB.as_ptr(), pPnp);
        CoTaskMemFree((pPnp).cast());

        if RegCreateKeyExW(HKEY_LOCAL_MACHINE, szPath.as_ptr(), 0, core::ptr::null_mut(), 0, KEY_WRITE, core::ptr::null_mut(), core::ptr::addr_of_mut!(hKey), core::ptr::null_mut()) != (ERROR_SUCCESS as i32) {
            return E_FAIL;
        }

        dwSize = 1;
        RegSetValueExW(hKey, CPP_COM_WSTR_3BA62E0D9245.as_ptr(), 0, REG_DWORD, core::ptr::addr_of_mut!(dwSize) as LPBYTE, core::mem::size_of::<DWORD>() as DWORD);
        RegCloseKey(hKey);

        return S_OK;
    }
