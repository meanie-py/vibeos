    pub unsafe fn GetProperties(&mut self, ppProps: *mut *mut NETCON_PROPERTIES) -> HRESULT {
        let this_: *mut Self = self;
        let mut IfEntry: MIB_IFROW = core::mem::zeroed();
        let mut hKey: HKEY = core::ptr::null_mut();
        let mut pStr: LPWSTR = core::ptr::null_mut();
        let mut szName: [u16; 140] = [0; 140];
        let mut dwShowIcon: DWORD = 0;
        let mut dwNotifyDisconnect: DWORD = 0;
        let mut dwType: DWORD = 0;
        let mut dwSize: DWORD = 0;
        let mut pProperties: *mut NETCON_PROPERTIES;
        let mut hr: HRESULT;

        if ppProps.is_null() {
            return E_POINTER;
        }

        pProperties = CoTaskMemAlloc((core::mem::size_of::<NETCON_PROPERTIES>()) as SIZE_T) as *mut NETCON_PROPERTIES;
        if pProperties.is_null() {
            return E_OUTOFMEMORY;
        }

        CopyMemory!(
            pProperties as *mut core::ffi::c_void,
            core::ptr::addr_of!((*this_).m_Props) as *const core::ffi::c_void,
            core::mem::size_of::<NETCON_PROPERTIES>(),
        );
        (*pProperties).pszwName = core::ptr::null_mut();

        if !(*this_).m_Props.pszwDeviceName.is_null() {
            (*pProperties).pszwDeviceName = CoTaskMemAlloc(
                ((wcslen((*this_).m_Props.pszwDeviceName) + 1)
                    * core::mem::size_of::<WCHAR>()) as SIZE_T,
            ) as LPWSTR;
            if !(*pProperties).pszwDeviceName.is_null() {
                wcscpy((*pProperties).pszwDeviceName, (*this_).m_Props.pszwDeviceName);
            }
        }

        *ppProps = pProperties;

        /* get updated adapter characteristics */
        ZeroMemory!(
            core::ptr::addr_of_mut!(IfEntry) as *mut core::ffi::c_void,
            core::mem::size_of::<MIB_IFROW>(),
        );
        IfEntry.dwIndex = (*this_).m_dwAdapterIndex;
        if GetIfEntry(core::ptr::addr_of_mut!(IfEntry)) != NO_ERROR {
            return NOERROR;
        }

        NormalizeOperStatus(core::ptr::addr_of_mut!(IfEntry), pProperties);

        hr = StringFromCLSID(&(*this_).m_Props.guidId, core::ptr::addr_of_mut!(pStr));
        if hr >= 0 {
            wcscpy(szName.as_mut_ptr(), CPP_COM_WSTR_C560181AF982.as_ptr());
            wcscat(szName.as_mut_ptr(), pStr);
            wcscat(szName.as_mut_ptr(), CPP_COM_WSTR_636AA582CA19.as_ptr());

            if RegOpenKeyExW(
                HKEY_LOCAL_MACHINE,
                szName.as_ptr(),
                0,
                KEY_READ,
                core::ptr::addr_of_mut!(hKey),
            ) == (ERROR_SUCCESS as i32)
            {
                dwSize = core::mem::size_of::<DWORD>() as DWORD;
                if RegQueryValueExW(
                    hKey,
                    CPP_COM_WSTR_B25B3C7B5934.as_ptr(),
                    core::ptr::null_mut(),
                    core::ptr::addr_of_mut!(dwType),
                    core::ptr::addr_of_mut!(dwShowIcon) as LPBYTE,
                    core::ptr::addr_of_mut!(dwSize),
                ) == (ERROR_SUCCESS as i32)
                    && dwType == REG_DWORD
                {
                    if dwShowIcon != 0 {
                        (*pProperties).dwCharacter |= NCCF_SHOW_ICON;
                    } else {
                        (*pProperties).dwCharacter &= !NCCF_SHOW_ICON;
                    }
                }

                dwSize = core::mem::size_of::<DWORD>() as DWORD;
                if RegQueryValueExW(
                    hKey,
                    CPP_COM_WSTR_B6B73CAE481D.as_ptr(),
                    core::ptr::null_mut(),
                    core::ptr::addr_of_mut!(dwType),
                    core::ptr::addr_of_mut!(dwNotifyDisconnect) as LPBYTE,
                    core::ptr::addr_of_mut!(dwSize),
                ) == (ERROR_SUCCESS as i32)
                    && dwType == REG_DWORD
                {
                    if dwNotifyDisconnect != 0 {
                        (*pProperties).dwCharacter |= NCCF_NOTIFY_DISCONNECTED;
                    } else {
                        (*pProperties).dwCharacter &= !NCCF_NOTIFY_DISCONNECTED;
                    }
                }

                dwSize = core::mem::size_of::<[u16; 140]>() as DWORD;
                if RegQueryValueExW(
                    hKey,
                    CPP_COM_WSTR_76E480513E2C.as_ptr(),
                    core::ptr::null_mut(),
                    core::ptr::addr_of_mut!(dwType),
                    szName.as_mut_ptr() as LPBYTE,
                    core::ptr::addr_of_mut!(dwSize),
                ) == (ERROR_SUCCESS as i32)
                {
                    /* use updated name */
                    dwSize = (wcslen(szName.as_ptr()) + 1) as DWORD;
                    (*pProperties).pszwName = CoTaskMemAlloc(
                        ((dwSize as usize) * core::mem::size_of::<WCHAR>()) as SIZE_T,
                    ) as PWSTR;
                    if !(*pProperties).pszwName.is_null() {
                        CopyMemory!(
                            (*pProperties).pszwName as *mut core::ffi::c_void,
                            szName.as_ptr() as *const core::ffi::c_void,
                            (dwSize as usize) * core::mem::size_of::<WCHAR>(),
                        );
                    }
                } else {
                    /* use cached name */
                    if !(*this_).m_Props.pszwName.is_null() {
                        (*pProperties).pszwName = CoTaskMemAlloc(
                            ((wcslen((*this_).m_Props.pszwName) + 1)
                                * core::mem::size_of::<WCHAR>()) as SIZE_T,
                        ) as PWSTR;
                        if !(*pProperties).pszwName.is_null() {
                            wcscpy((*pProperties).pszwName, (*this_).m_Props.pszwName);
                        }
                    }
                }
                RegCloseKey(hKey);
            }
            CoTaskMemFree(pStr as LPVOID);
        }

        /* Enable 'Rename' and 'Delete' for Adminstrators only */
        if IsUserAdmin() != 0 {
            (*pProperties).dwCharacter |= NCCF_ALLOW_RENAME;

            /* Virtual network interfaces can be deleted */
            if IfEntry.dwType == IF_TYPE_TUNNEL {
                (*pProperties).dwCharacter |= NCCF_ALLOW_REMOVAL;
            }
        } else {
            (*pProperties).dwCharacter &= !(NCCF_ALLOW_RENAME | NCCF_ALLOW_REMOVAL);
        }

        return S_OK;
    }
