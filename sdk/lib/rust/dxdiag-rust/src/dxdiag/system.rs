pub unsafe extern "C" fn GetRegValue(mut hBaseKey: HKEY, mut SubKey: LPWSTR, mut ValueName: LPWSTR, mut Type: DWORD, mut Result: LPWSTR, mut Size: DWORD) -> BOOL {
    let mut hKey: HKEY = core::ptr::null_mut();
    let mut res: LONG = 0;
    let mut dwType: DWORD = 0;
    let mut dwSize: DWORD = 0;

    if RegOpenKeyExW(
        hBaseKey,
        SubKey as LPCWSTR,
        0 as DWORD,
        KEY_QUERY_VALUE as REGSAM,
        core::ptr::addr_of_mut!(hKey),
    ) as LONG != ERROR_SUCCESS as LONG
    {
        return FALSE as BOOL;
    }

    dwSize = Size;
    res = RegQueryValueExW(
        hKey,
        ValueName as LPCWSTR,
        core::ptr::null_mut::<DWORD>(),
        core::ptr::addr_of_mut!(dwType),
        Result as LPBYTE,
        core::ptr::addr_of_mut!(dwSize),
    ) as LONG;
    RegCloseKey(hKey);

    if res != ERROR_SUCCESS as LONG {
        return FALSE as BOOL;
    }

    if dwType != Type {
        return FALSE as BOOL;
    }

    if Size as usize == core::mem::size_of::<DWORD>() as usize {
        return TRUE as BOOL;
    }

    *Result.offset(
        (Size as usize)
            .wrapping_div(core::mem::size_of::<WCHAR>() as usize)
            .wrapping_sub(1 as usize) as isize,
    ) = 0x0000u16;
    return TRUE as BOOL;
}

