unsafe extern "C" fn GetItemPartition(hTreeList: HWND, hItem: HTLITEM) -> PPARTITEM {
    let hParentItem: HTLITEM = TreeList_GetParent!(hTreeList, hItem);
    /* May or may not be a PPARTITEM: this is a PPARTITEM only when hParentItem != NULL */
    let PartItem: PPARTITEM = TreeListGetItemData(hTreeList, hItem) as PPARTITEM;
    if hParentItem.is_null() || PartItem.is_null() {
        return core::ptr::null_mut();
    }
    return PartItem;
}

unsafe extern "C" fn GetSelectedPartition(
    mut hTreeList: HWND,
    mut phItem: *mut HTLITEM,
) -> PPARTITEM {
    let mut PartItem: PPARTITEM = core::ptr::null_mut();
    let mut hItem: HTLITEM = TreeList_GetSelection!(hTreeList);
    if !hItem.is_null() {
        PartItem = GetItemPartition(hTreeList, hItem);
        if !PartItem.is_null() && !phItem.is_null() {
            *phItem = hItem;
        }
    }
    return PartItem;
}

unsafe extern "C" fn FindPartitionItem(
    hTreeList: HWND,
    PartEntry: PPARTENTRY,
    phItem: *mut HTLITEM,
) -> PPARTITEM {
    let mut PartItem: PPARTITEM = core::ptr::null_mut();

    /* Enumerate every cached data in the TreeList, and for each, check
     * whether its corresponding PPARTENTRY is the one we are looking for */
    let mut hItem: HTLITEM = TVI_ROOT;
    loop { // nolint: dowhile-continue (the C is a while: its condition is the first statement, so continue re-tests it)
        hItem = TreeList_GetNextItem!(hTreeList, hItem, TVGN_NEXTITEM);
        if hItem.is_null() {
            break;
        }
        PartItem = GetItemPartition(hTreeList, hItem);
        if PartItem.is_null() {
            continue;
        }

        /* Return the first valid partition item (if PartEntry == NULL),
         * or the one that matches the given partition entry */
        if PartEntry.is_null() || ((*PartItem).PartEntry == PartEntry) {
            break; /* Found it */
        }
        /* Not yet found */
    }
    if !phItem.is_null() {
        *phItem = hItem;
    }
    return if !hItem.is_null() {
        PartItem
    } else {
        core::ptr::null_mut()
    };
}
#[no_mangle]
pub unsafe extern "C" fn FindVolCreateInTreeByVolume(hTreeList: HWND, Volume: PVOLENTRY) -> PVOL_CREATE_INFO {
    let mut hItem: HTLITEM = TVI_ROOT;
    loop {
        hItem = TreeList_GetNextItem!(hTreeList, hItem, TVGN_NEXTITEM);
        if hItem.is_null() {
            break;
        }
        let mut PartItem: PPARTITEM = GetItemPartition(hTreeList, hItem);
        if PartItem.is_null() || (*PartItem).VolCreate.is_null() {
            continue;
        }
        if (*PartItem).Volume == Volume {
            return (*PartItem).VolCreate;
        }
    }
    return core::ptr::null_mut();
}
#[no_mangle]
pub unsafe extern "C" fn GetPartitionTypeString(
    PartEntry: PPARTENTRY,
    strBuffer: PSTR,
    cchBuffer: ULONG,
) {
    if (*PartEntry).PartitionType as ::core::ffi::c_int == (PARTITION_ENTRY_UNUSED as i32) {
        StringCchCopyA(
            strBuffer,
            (cchBuffer) as _,
            b"Unused\0".as_ptr() as PCSTR,
        );
    } else if IsContainerPartition!((*PartEntry).PartitionType) {
        StringCchCopyA(
            strBuffer,
            (cchBuffer) as _,
            b"Extended Partition\0".as_ptr() as PCSTR,
        );
    } else {
        /* Do the table lookup */
        let mut Description: PCSTR = LookupPartitionTypeString(
            (*(*PartEntry).DiskEntry).DiskStyle,
            core::ptr::addr_of_mut!((*PartEntry).PartitionType) as PVOID,
        );
        if !Description.is_null() {
            StringCchCopyA(
                strBuffer,
                (cchBuffer) as _,
                Description,
            );
            return;
        }

        /* We are here because the partition type is unknown */
        if cchBuffer > 0 {
            *strBuffer = b'\0' as CHAR;
        }
    }

    if (cchBuffer > 0) && (*strBuffer as ::core::ffi::c_int == '\0' as ::core::ffi::c_int) {
        StringCchPrintfA!(
            strBuffer,
            cchBuffer,
            b"Type 0x%02x\0".as_ptr() as PCSTR,
            (*PartEntry).PartitionType as ::core::ffi::c_int,
        );
    }
}

unsafe extern "C" fn PrettifySize1(Size: PULONGLONG, Unit: *mut PCWSTR) {
    let mut DiskSize: ULONGLONG = *Size;

    if DiskSize >= 10 * GB /* 10 GB */ {
        DiskSize = RoundingDivide(DiskSize, GB);
        *Unit = RUSTCONV_WSTR_091377C39548.as_ptr(); // MUIGetString(STRING_GB);
    } else {
        DiskSize = RoundingDivide(DiskSize, MB);
        if DiskSize == 0 {
            DiskSize = 1;
        }
        *Unit = RUSTCONV_WSTR_6096F1180D1E.as_ptr(); // MUIGetString(STRING_MB);
    }

    *Size = DiskSize;
}

unsafe extern "C" fn PrettifySize2(Size: PULONGLONG, Unit: *mut PCWSTR) {
    let mut PartSize: ULONGLONG = *Size;

    if PartSize >= (10 as ULONGLONG) * (MB as ULONGLONG) /* 10 MB */ {
        PartSize = RoundingDivide(PartSize, MB as ULONGLONG);
        *Unit = RUSTCONV_WSTR_6096F1180D1E.as_ptr(); // MUIGetString(STRING_MB);
    } else {
        PartSize = RoundingDivide(PartSize, KB as ULONGLONG);
        *Unit = RUSTCONV_WSTR_B00670AF8E90.as_ptr(); // MUIGetString(STRING_KB);
    }

    *Size = PartSize;
}

unsafe extern "C" fn PrintPartitionData(
    hWndList: HWND,
    htiParent: HTLITEM,
    hInsertAfter: HTLITEM,
    PartEntry: PPARTENTRY,
) -> HTLITEM {
    let DiskEntry: PDISKENTRY = (*PartEntry).DiskEntry as PDISKENTRY;
    let VolInfo: PVOLINFO = if !(*PartEntry).Volume.is_null() {
        &raw mut (*(*PartEntry).Volume).Info
    } else {
        core::ptr::null_mut()
    };
    let mut PartItem: PPARTITEM = core::ptr::null_mut();
    let mut PartSize: ULONGLONG = 0;
    let mut htiPart: HTLITEM = core::ptr::null_mut();
    let mut PartTypeString: [CHAR; 32] = [0; 32];
    let mut PartType: PCHAR = &raw mut PartTypeString as PCHAR;
    let mut LineBuffer: [WCHAR; 128] = [0; 128];

    /* Volume name */
    if (*PartEntry).IsPartitioned as ::core::ffi::c_int == (FALSE as i32) {
        /* Unpartitioned space: Just display the description */
        StringCchPrintfW!(
            &raw mut LineBuffer as LPWSTR,
            ARRAYSIZE!(LineBuffer) as size_t,
            RUSTCONV_WSTR_8F07DFE8A197.as_ptr(),
        );
    } else if ((*DiskEntry).DiskStyle as ::core::ffi::c_int) as u32 == PARTITION_STYLE_MBR
        && IsContainerPartition!((*PartEntry).PartitionType) != false
    {
        /* Extended partition container: Just display the partition's type */
        StringCchPrintfW!(
            &raw mut LineBuffer as LPWSTR,
            ARRAYSIZE!(LineBuffer) as size_t,
            RUSTCONV_WSTR_F64728D9CDAD.as_ptr(),
        );
    } else {
        /* Drive letter and partition number */
        StringCchPrintfW!(
            &raw mut LineBuffer as LPWSTR,
            ARRAYSIZE!(LineBuffer) as size_t,
            RUSTCONV_WSTR_A23C8B3B2F82.as_ptr(),
            if !VolInfo.is_null() && *(&raw mut (*VolInfo).VolumeLabel as *mut WCHAR) as ::core::ffi::c_int != 0 {
                &raw mut (*VolInfo).VolumeLabel as *mut WCHAR as *const WCHAR
            } else {
                RUSTCONV_WSTR_390B38887995.as_ptr()
            },
            if !(!VolInfo.is_null() && (*VolInfo).DriveLetter as ::core::ffi::c_int != 0) {
                0x002Du16 as ::core::ffi::c_int
            } else {
                (*VolInfo).DriveLetter as ::core::ffi::c_int
            },
            if !(!VolInfo.is_null() && (*VolInfo).DriveLetter as ::core::ffi::c_int != 0) {
                0x002Du16 as ::core::ffi::c_int
            } else {
                0x003Au16 as ::core::ffi::c_int
            },
        );
    }

    /* Allocate and initialize a partition-info structure */
    PartItem = LocalAlloc(
        LPTR,
        core::mem::size_of::<_PARTITEM>() as SIZE_T,
    ) as PPARTITEM;
    if PartItem.is_null() {
        DPRINT1!("Failed to allocate partition-info structure\n");
        // We'll store a NULL pointer?!
    }

    (*PartItem).PartEntry = PartEntry;
    (*PartItem).Volume = (*PartEntry).Volume;

    htiPart = TreeListAddItem(
        hWndList,
        htiParent,
        hInsertAfter,
        &raw mut LineBuffer as *mut WCHAR as LPCWSTR,
        1,
        1,
        PartItem as LPARAM,
    );

    *(&raw mut LineBuffer as *mut WCHAR) = 0;
    if (*PartEntry).IsPartitioned != 0 {
        PartTypeString[0 as usize] = '\0' as i32 as CHAR;

        /*
         * If the volume's file system is recognized, display the volume label
         * (if any) and the file system name. Otherwise, display the partition
         * type if it's not a new partition.
         */
        if !VolInfo.is_null()
            && *(&raw mut (*VolInfo).FileSystem as *mut WCHAR) as ::core::ffi::c_int != 0
            && _wcsicmp(
                &raw mut (*VolInfo).FileSystem as *mut WCHAR,
                RUSTCONV_WSTR_903B52F937BA.as_ptr(),
            ) != 0
        {
            // TODO: Group this part together with the similar one
            // from below once the strings are in the same encoding...
            if (*PartEntry).New != 0 {
                StringCchPrintfA!(
                    &raw mut PartTypeString as STRSAFE_LPSTR,
                    ARRAYSIZE!(PartTypeString) as size_t,
                    b"New (%S)\0".as_ptr() as PCSTR,
                    &raw mut (*VolInfo).FileSystem as *mut WCHAR,
                );
            } else {
                StringCchPrintfA!(
                    &raw mut PartTypeString as STRSAFE_LPSTR,
                    ARRAYSIZE!(PartTypeString) as size_t,
                    b"%S\0".as_ptr() as PCSTR,
                    &raw mut (*VolInfo).FileSystem as *mut WCHAR,
                );
            }
            PartType = &raw mut PartTypeString as PCHAR;
        } else if (*PartEntry).New != 0 {
            /* Use this description if the partition is new and not planned for formatting */
            PartType = b"New (Unformatted)\0".as_ptr() as PCHAR; // MUIGetString(STRING_UNFORMATTED);
        } else {
            /* If the partition is not new but its file system is not recognized
             * (or is not formatted), use the partition type description. */
            GetPartitionTypeString(
                PartEntry,
                &raw mut PartTypeString as PSTR,
                ARRAYSIZE!(PartTypeString) as ULONG,
            );
            PartType = &raw mut PartTypeString as PCHAR;
        }

        StringCchPrintfW!(
            &raw mut LineBuffer as LPWSTR,
            ARRAYSIZE!(LineBuffer) as size_t,
            RUSTCONV_WSTR_BE193C67CE83.as_ptr(),
            PartType,
        );
    }
    TreeList_SetItemText!(
        hWndList,
        htiPart,
        1,
        &raw mut LineBuffer as *mut WCHAR as LPCWSTR,
    );

    /* Format the partition size */
    PartSize = GetPartEntrySizeInBytes!(PartEntry);
    if StrFormatByteSizeW(
        PartSize as LONGLONG,
        &raw mut LineBuffer as LPWSTR,
        ARRAYSIZE!(LineBuffer) as UINT,
    )
    .is_null()
    {
        /* We failed for whatever reason, do the hardcoded way */
        let mut Unit: PCWSTR = core::ptr::null();
        PrettifySize2(&raw mut PartSize, &raw mut Unit);
        StringCchPrintfW!(
            &raw mut LineBuffer as LPWSTR,
            ARRAYSIZE!(LineBuffer) as size_t,
            RUSTCONV_WSTR_427BCCFF58F8.as_ptr(),
            PartSize,
            Unit,
        );
    }
    TreeList_SetItemText!(
        hWndList,
        htiPart,
        2,
        &raw mut LineBuffer as *mut WCHAR as LPCWSTR,
    );

    /* Volume status */
    *(&raw mut LineBuffer as *mut WCHAR) = 0;
    if (*PartEntry).IsPartitioned != 0 {
        StringCchPrintfW!(
            &raw mut LineBuffer as LPWSTR,
            ARRAYSIZE!(LineBuffer) as size_t,
            // MUIGetString(STRING_HDDINFOUNK5),
            if (*PartEntry).BootIndicator as ::core::ffi::c_int != 0 {
                RUSTCONV_WSTR_7D30E0F4123F.as_ptr()
            } else {
                RUSTCONV_WSTR_96A296D224F2.as_ptr()
            },
        );
    }
    TreeList_SetItemText!(
        hWndList,
        htiPart,
        3,
        &raw mut LineBuffer as *mut WCHAR as LPCWSTR,
    );

    /* If this is the single extended partition of an MBR disk,
     * recursively display its logical partitions */
    if PartEntry == (*DiskEntry).ExtendedPartition {
        let mut LogicalEntry: PLIST_ENTRY = core::ptr::null_mut();

        LogicalEntry = (*DiskEntry).LogicalPartListHead.Flink as PLIST_ENTRY;
        while LogicalEntry != &raw mut (*DiskEntry).LogicalPartListHead as PLIST_ENTRY {
            let mut LogicalPartEntry: PPARTENTRY =
                CONTAINING_RECORD!(LogicalEntry, PARTENTRY, ListEntry);
            PrintPartitionData(
                hWndList,
                htiPart,
                core::ptr::null_mut(),
                LogicalPartEntry,
            );
            LogicalEntry = (*LogicalEntry).Flink as PLIST_ENTRY;
        }

        /* Expand the extended partition node */
        TreeList_Expand!(hWndList, htiPart, TVE_EXPAND);
    }

    return htiPart;
}

unsafe extern "C" fn DeleteTreeItem(hWndList: HWND, ptlItem: *mut TLITEMW) {
    /* Code below is equivalent to: PartItem = GetItemPartition(hWndList, ptlItem->hItem);
     * except that we already have the data structure in ptlItem->lParam, so there is
     * no need to call extra helpers as GetItemPartition() does. */
    let hParentItem: HTLITEM = TreeList_GetParent!(hWndList, (*ptlItem).hItem);
    /* May or may not be a PPARTITEM: this is a PPARTITEM only when hParentItem != NULL */
    let PartItem: PPARTITEM = (*ptlItem).lParam as PPARTITEM;
    if hParentItem.is_null() || PartItem.is_null() {
        return;
    }

    if !(*PartItem).VolCreate.is_null() {
        LocalFree((*PartItem).VolCreate as HLOCAL);
    }
    LocalFree(PartItem as HLOCAL);
}

unsafe extern "C" fn PrintDiskData(
    hWndList: HWND,
    hInsertAfter: HTLITEM,
    DiskEntry: PDISKENTRY,
) {
    let mut Success: BOOL = 0;
    let mut hDevice: HANDLE = core::ptr::null_mut();
    let mut DiskName: PCHAR = core::ptr::null_mut();
    let mut Length: ULONG = 0;
    let mut PrimaryEntry: PLIST_ENTRY = core::ptr::null_mut();
    let mut DiskSize: ULONGLONG = 0;
    let mut htiDisk: HTLITEM = core::ptr::null_mut();
    let mut LineBuffer: [WCHAR; 128] = [0; 128];
    let mut outBuf: [UCHAR; 512] = [0; 512];

    StringCchPrintfW!(
        core::ptr::addr_of_mut!(LineBuffer) as *mut WCHAR,
        ARRAYSIZE!(LineBuffer),
        RUSTCONV_WSTR_9E5AAD2088A8.as_ptr(),
        (*DiskEntry).DiskNumber,
    );

    hDevice = CreateFileW(
        core::ptr::addr_of_mut!(LineBuffer) as LPCWSTR,
        GENERIC_READ,
        FILE_SHARE_READ | FILE_SHARE_WRITE,
        core::ptr::null_mut(),
        OPEN_EXISTING,
        0,
        core::ptr::null_mut(),
    );
    if hDevice != INVALID_HANDLE_VALUE {
        let mut Query: STORAGE_PROPERTY_QUERY = core::mem::zeroed();

        Query.PropertyId = StorageDeviceProperty;
        Query.QueryType = PropertyStandardQuery;

        Success = DeviceIoControl(
            hDevice,
            IOCTL_STORAGE_QUERY_PROPERTY,
            core::ptr::addr_of_mut!(Query) as LPVOID,
            core::mem::size_of::<STORAGE_PROPERTY_QUERY>() as DWORD,
            core::ptr::addr_of_mut!(outBuf) as LPVOID,
            core::mem::size_of::<[UCHAR; 512]>() as DWORD,
            core::ptr::addr_of_mut!(Length),
            core::ptr::null_mut(),
        );
        if Success != 0 {
            let mut devDesc: PSTORAGE_DEVICE_DESCRIPTOR =
                core::ptr::addr_of_mut!(outBuf) as *mut UCHAR as PSTORAGE_DEVICE_DESCRIPTOR;
            if (*devDesc).ProductIdOffset != 0 {
                DiskName = (core::ptr::addr_of_mut!(outBuf) as *mut UCHAR)
                    .offset((*devDesc).ProductIdOffset as isize) as *mut UCHAR as PCHAR;
                Length = Length.wrapping_sub((*devDesc).ProductIdOffset);
                *DiskName.offset(
                    min!(
                        Length as usize,
                        strlen(DiskName as *const i8),
                    ) as isize,
                ) = 0 as CHAR;
                // ( i = devDesc->ProductIdOffset; p[i] != 0 && i < Length; i++ )
            }
        }

        CloseHandle(hDevice);
    }

    if !DiskName.is_null() && *DiskName != 0 {
        if (*DiskEntry).DriverName.Length > 0 {
            StringCchPrintfW!(
                core::ptr::addr_of_mut!(LineBuffer) as *mut WCHAR,
                ARRAYSIZE!(LineBuffer),
                RUSTCONV_WSTR_6ED1DBBC34B3.as_ptr(),
                (*DiskEntry).DiskNumber,
                DiskName,
                (*DiskEntry).Port as core::ffi::c_uint,
                (*DiskEntry).Bus as core::ffi::c_uint,
                (*DiskEntry).Id as core::ffi::c_uint,
                core::ptr::addr_of_mut!((*DiskEntry).DriverName),
            );
        } else {
            StringCchPrintfW!(
                core::ptr::addr_of_mut!(LineBuffer) as *mut WCHAR,
                ARRAYSIZE!(LineBuffer),
                RUSTCONV_WSTR_054CA170D3D8.as_ptr(),
                (*DiskEntry).DiskNumber,
                DiskName,
                (*DiskEntry).Port as core::ffi::c_uint,
                (*DiskEntry).Bus as core::ffi::c_uint,
                (*DiskEntry).Id as core::ffi::c_uint,
            );
        }
    } else {
        if (*DiskEntry).DriverName.Length > 0 {
            StringCchPrintfW!(
                core::ptr::addr_of_mut!(LineBuffer) as *mut WCHAR,
                ARRAYSIZE!(LineBuffer),
                RUSTCONV_WSTR_6409B0906A18.as_ptr(),
                (*DiskEntry).DiskNumber,
                (*DiskEntry).Port as core::ffi::c_uint,
                (*DiskEntry).Bus as core::ffi::c_uint,
                (*DiskEntry).Id as core::ffi::c_uint,
                core::ptr::addr_of_mut!((*DiskEntry).DriverName),
            );
        } else {
            StringCchPrintfW!(
                core::ptr::addr_of_mut!(LineBuffer) as *mut WCHAR,
                ARRAYSIZE!(LineBuffer),
                RUSTCONV_WSTR_609E7F0715BE.as_ptr(),
                (*DiskEntry).DiskNumber,
                (*DiskEntry).Port as core::ffi::c_uint,
                (*DiskEntry).Bus as core::ffi::c_uint,
                (*DiskEntry).Id as core::ffi::c_uint,
            );
        }
    }

    htiDisk = TreeListAddItem(
        hWndList,
        core::ptr::null_mut(),
        hInsertAfter,
        core::ptr::addr_of_mut!(LineBuffer) as *mut WCHAR as LPCWSTR,
        0,
        0,
        DiskEntry as LPARAM,
    );

    /* Disk type: MBR, GPT or RAW (Uninitialized) */
    TreeList_SetItemText!(
        hWndList,
        htiDisk,
        1,
        if (*DiskEntry).DiskStyle == PARTITION_STYLE_MBR {
            RUSTCONV_WSTR_DD8FED8124A3.as_ptr()
        } else if (*DiskEntry).DiskStyle == PARTITION_STYLE_GPT {
            RUSTCONV_WSTR_E066D47523FF.as_ptr()
        } else {
            RUSTCONV_WSTR_903B52F937BA.as_ptr()
        },
    );

    /* Format the disk size */
    DiskSize = GetDiskSizeInBytes!(DiskEntry);
    if StrFormatByteSizeW(
        (DiskSize) as LONGLONG,
        core::ptr::addr_of_mut!(LineBuffer) as *mut WCHAR,
        ARRAYSIZE!(LineBuffer),
    )
    .is_null()
    {
        /* We failed for whatever reason, do the hardcoded way */
        let mut Unit: PCWSTR = core::ptr::null();
        PrettifySize1(
            core::ptr::addr_of_mut!(DiskSize),
            core::ptr::addr_of_mut!(Unit),
        );
        StringCchPrintfW!(
            core::ptr::addr_of_mut!(LineBuffer) as *mut WCHAR,
            ARRAYSIZE!(LineBuffer),
            RUSTCONV_WSTR_427BCCFF58F8.as_ptr(),
            DiskSize,
            Unit,
        );
    }
    TreeList_SetItemText!(
        hWndList,
        htiDisk,
        2,
        core::ptr::addr_of_mut!(LineBuffer) as *mut WCHAR,
    );

    /* Print partition lines */
    PrimaryEntry = (*DiskEntry).PrimaryPartListHead.Flink;
    while PrimaryEntry != core::ptr::addr_of_mut!((*DiskEntry).PrimaryPartListHead) {
        /* If this is an extended partition, recursively print the logical partitions */
        let mut PartEntry: PPARTENTRY =
            CONTAINING_RECORD!(PrimaryEntry, PARTENTRY, ListEntry);
        PrintPartitionData(hWndList, htiDisk, core::ptr::null_mut(), PartEntry);
        PrimaryEntry = (*PrimaryEntry).Flink;
    }

    /* Expand the disk node */
    TreeList_Expand!(hWndList, htiDisk, TVE_EXPAND);
}

unsafe extern "C" fn InitPartitionList(hInstance: HINSTANCE, hWndList: HWND) {
    let dwStyle: DWORD = TVS_HASBUTTONS | /*TVS_HASLINES | TVS_LINESATROOT |*/ TVS_SHOWSELALWAYS | TVS_FULLROWSELECT;
    let dwExStyle: DWORD = TVS_EX_FULLROWMARK /* | TVS_EX_FULLROWITEMS*/;
    let mut hSmall: HIMAGELIST;

    /* Set the TreeList styles and fixup the item selection color */
    TreeList_SetStyle!(hWndList, TreeList_GetStyle!(hWndList) | dwStyle);
    // TreeList_SetStyleEx(hWndList, dwStyle, dwStyle);
    TreeList_SetExtendedStyle!(hWndList, dwExStyle);
    TreeList_SetColor!(hWndList, TVC_MARK, GetSysColor((COLOR_HIGHLIGHT as i32)));

    /* Initialize its columns */
    CreateTreeListColumns(
        hInstance,
        hWndList,
        core::ptr::addr_of!(column_ids) as *const UINT,
        core::ptr::addr_of!(column_widths) as *const INT,
        core::ptr::addr_of!(column_alignment) as *const INT,
        (MAX_LIST_COLUMNS) as UINT,
    );

    /* Create the ImageList */
    hSmall = ImageList_Create(
        GetSystemMetrics((SM_CXSMICON as i32)),
        GetSystemMetrics((SM_CYSMICON as i32)),
        ILC_COLOR32 | ILC_MASK, // ILC_COLOR24
        1,
        1,
    );

    /* Add event type icons to the ImageList */
    ImageList_AddIcon!(hSmall, LoadIconW(hInstance, MAKEINTRESOURCEW!(IDI_DISKDRIVE)));
    ImageList_AddIcon!(hSmall, LoadIconW(hInstance, MAKEINTRESOURCEW!(IDI_PARTITION)));

    /* Assign the ImageList to the List View */
    TreeList_SetImageList!(hWndList, hSmall, TVSIL_NORMAL);
}

unsafe extern "C" fn DrawPartitionList(hWndList: HWND, List: PPARTLIST) {
    let mut Entry: PLIST_ENTRY;

    /* Clear the list first */
    TreeList_DeleteAllItems!(hWndList);

    /* Insert all the detected disks and partitions */
    Entry = (*List).DiskListHead.Flink;
    while Entry != core::ptr::addr_of_mut!((*List).DiskListHead) {
        /* Print disk entry */
        let DiskEntry: PDISKENTRY = CONTAINING_RECORD!(Entry, DISKENTRY, ListEntry);
        PrintDiskData(hWndList, core::ptr::null_mut(), DiskEntry);
        Entry = (*Entry).Flink;
    }

    /* Select the first usable partition/empty space */
    {
        let mut hItem: HTLITEM = core::ptr::null_mut();
        if FindPartitionItem(hWndList, core::ptr::null_mut(), core::ptr::addr_of_mut!(hItem))
            .is_null()
        {
            hItem = 1 as HTLITEM; // If none, select the first item, whatever it is.
        }
        TreeList_SelectItem!(hWndList, hItem);
    }
}

unsafe extern "C" fn CleanupPartitionList(hWndList: HWND) {
    let hSmall: HIMAGELIST;

    /* Cleanup all the items. Their cached data will be automatically deleted
     * on response to the TVN_DELETEITEM notification sent by the TreeList
     * by DeleteTreeItem() */
    TreeList_DeleteAllItems!(hWndList);

    /* And cleanup the imagelist */
    hSmall = TreeList_GetImageList!(hWndList, TVSIL_NORMAL);
    TreeList_SetImageList!(hWndList, NULL, TVSIL_NORMAL);
    ImageList_Destroy(hSmall);
}

unsafe extern "C" fn DoCreatePartition(
    mut hList: HWND,
    mut List: PPARTLIST,
    mut phItem: *mut HTLITEM,
    mut pPartItem: *mut PPARTITEM,
    mut SizeBytes: ULONGLONG,
    mut PartitionInfo: ULONG_PTR,
) -> BOOLEAN {
    let mut PartItem: PPARTITEM = core::ptr::null_mut();
    let mut PartEntry: PPARTENTRY = core::ptr::null_mut();
    let mut hParentItem: HTLITEM = core::ptr::null_mut();
    let mut hInsertAfter: HTLITEM = core::ptr::null_mut();
    let mut NextPart: PPARTENTRY = core::ptr::null_mut();
    let mut Success: BOOLEAN = 0;

    PartItem = if !pPartItem.is_null() {
        *pPartItem
    } else {
        GetItemPartition(hList, *phItem)
    };
    if PartItem.is_null() {
        /* We must have a disk region... */
        ASSERT!(FALSE);
        return (FALSE) as BOOLEAN;
    }
    PartEntry = (*PartItem).PartEntry;

    Success = CreatePartition(List, PartEntry, SizeBytes, PartitionInfo);
    if Success == 0 {
        return Success;
    }

    /* Retrieve the parent item (disk or MBR extended partition) */
    hParentItem = TreeList_GetParent!(hList, *phItem);
    hInsertAfter = TreeList_GetPrevSibling!(hList, *phItem);
    if hInsertAfter.is_null() {
        hInsertAfter = TVI_FIRST;
    }

    /*
     * The current entry has been recreated and maybe split
     * in two: new partition and remaining unused space.
     * Thus, recreate the current entry.
     *
     * NOTE: Since we create a partition we don't care
     * about its previous PartItem, so it can be deleted.
     */
    {
        /* Cache out the original item's volume create info */
        let mut VolCreate: PVOL_CREATE_INFO = (*PartItem).VolCreate;
        (*PartItem).VolCreate = core::ptr::null_mut();

        /* Remove the current item */
        TreeList_DeleteItem!(hList, *phItem);

        /* Recreate the entry */
        *phItem = PrintPartitionData(hList, hParentItem, hInsertAfter, PartEntry);

        /* Retrieve the new PartItem and restore the volume create
         * information associated to the newly-created partition */
        PartItem = GetItemPartition(hList, *phItem);
        ASSERT!(PartItem);

        /* Update the volume associated to the create information */
        if !VolCreate.is_null() {
            (*VolCreate).Volume = (*PartItem).Volume;
        }

        /* Restore the volume create information */
        (*PartItem).VolCreate = VolCreate;

        if !pPartItem.is_null() {
            *pPartItem = PartItem;
        }
    }

    /* Add also the following unused space, if any */
    // NextPart = GetAdjDiskRegion(NULL, PartEntry, ENUM_REGION_NEXT);
    NextPart = GetAdjUnpartitionedEntry(PartEntry, (TRUE) as BOOLEAN);
    if !NextPart.is_null() {
        PrintPartitionData(hList, hParentItem, *phItem, NextPart);
    }

    /* Select the created partition */
    TreeList_SelectItem!(hList, *phItem);

    return (TRUE) as BOOLEAN;
}

unsafe extern "C" fn DoDeletePartition(
    hList: HWND,
    List: PPARTLIST,
    phItem: *mut HTLITEM,
    PartItem: PPARTITEM,
) -> BOOLEAN {
    let mut PartEntry: PPARTENTRY = (*PartItem).PartEntry;
    let mut PrevPart: PPARTENTRY;
    let mut NextPart: PPARTENTRY;
    let mut PrevIsPartitioned: BOOLEAN;
    let mut NextIsPartitioned: BOOLEAN;
    let mut Success: BOOLEAN;

    let mut hParentItem: HTLITEM;
    let mut hInsertAfter: HTLITEM;
    let mut hAdjItem: HTLITEM;
    let mut AdjPartItem: PPARTITEM;

    PrevPart = GetAdjUnpartitionedEntry(PartEntry, (FALSE) as BOOLEAN);
    NextPart = GetAdjUnpartitionedEntry(PartEntry, (TRUE) as BOOLEAN);

    PrevIsPartitioned = (!PrevPart.is_null() && (*PrevPart).IsPartitioned != 0) as BOOLEAN;
    NextIsPartitioned = (!NextPart.is_null() && (*NextPart).IsPartitioned != 0) as BOOLEAN;

    ASSERT!((*PartEntry).IsPartitioned != 0); // The current partition must be partitioned.
    Success = DeletePartition(
        List,
        PartEntry,
        core::ptr::addr_of_mut!(PartEntry),
    );
    if Success == 0 {
        return Success;
    }

    /* Retrieve the parent item (disk or MBR extended partition) */
    hParentItem = TreeList_GetParent!(hList, *phItem);

    /* If previous sibling isn't partitioned, remove it */
    if !PrevPart.is_null() && PrevIsPartitioned == 0 {
        hAdjItem = TreeList_GetPrevSibling!(hList, *phItem);
        ASSERT!(!hAdjItem.is_null()); // TODO: Investigate
        if !hAdjItem.is_null() {
            AdjPartItem = GetItemPartition(hList, hAdjItem);
            ASSERT!(!AdjPartItem.is_null() && ((*AdjPartItem).PartEntry == PrevPart));
            AdjPartItem = core::ptr::null_mut();
            TreeList_DeleteItem!(hList, hAdjItem);
        }
    }
    /* If next sibling isn't partitioned, remove it */
    if !NextPart.is_null() && NextIsPartitioned == 0 {
        hAdjItem = TreeList_GetNextSibling!(hList, *phItem);
        ASSERT!(!hAdjItem.is_null()); // TODO: Investigate
        if !hAdjItem.is_null() {
            AdjPartItem = GetItemPartition(hList, hAdjItem);
            ASSERT!(!AdjPartItem.is_null() && ((*AdjPartItem).PartEntry == NextPart));
            AdjPartItem = core::ptr::null_mut();
            TreeList_DeleteItem!(hList, hAdjItem);
        }
    }

    /* We are going to insert the updated entry after
     * either, the original previous sibling (if it is
     * partitioned), or the second-previous sibling
     * (if the first one was already removed, see above) */
    hInsertAfter = TreeList_GetPrevSibling!(hList, *phItem);
    if hInsertAfter.is_null() {
        hInsertAfter = TVI_FIRST;
    }

    /* Remove the current item */
    TreeList_DeleteItem!(hList, *phItem);

    /* Add back the "new" unpartitioned space */
    *phItem = PrintPartitionData(hList, hParentItem, hInsertAfter, PartEntry);

    /* Select the unpartitioned space */
    TreeList_SelectItem!(hList, *phItem);

    return (TRUE) as BOOLEAN;
}

unsafe extern "C" fn SelectInstallPartition(
    mut pSetupData: PSETUPDATA,
    mut hwndDlg: HWND,
    mut CurrentPartition: PPARTENTRY,
) -> BOOLEAN {
    let mut hList: HWND = core::ptr::null_mut();
    let mut hItem: HTREEITEM = core::ptr::null_mut();
    let mut PartItem: PPARTITEM = core::ptr::null_mut();
    let mut PartEntry: PPARTENTRY = core::ptr::null_mut();

    hList = GetDlgItem(hwndDlg, (IDC_PARTITION as i32));
    if !CurrentPartition.is_null() {
        PartItem = FindPartitionItem(hList, CurrentPartition, &raw mut hItem);
        if !hItem.is_null() {
            TreeList_SelectItem!(hList, hItem);
        }
    } else {
        PartItem = GetSelectedPartition(hList, &raw mut hItem);
    }
    if PartItem.is_null() {
        return (FALSE) as BOOLEAN; // Fail
    }
    PartEntry = (*PartItem).PartEntry;
    ASSERT!(!PartEntry.is_null());

    /*
     * Check whether the user wants to install ReactOS on a disk that
     * is not recognized by the computer's firmware and if so, display
     * a warning since such disks may not be bootable.
     */
    if (*(*PartEntry).DiskEntry).MediaType == FixedMedia
        && (*(*PartEntry).DiskEntry).BiosFound == 0
    {
        let mut nRet: INT = 0;

        nRet = DisplayMessage(
            hwndDlg,
            MB_ICONWARNING | MB_OKCANCEL,
            RUSTCONV_WSTR_D0AB4CA95EC4.as_ptr(),
            RUSTCONV_WSTR_CFAE7E5322EC.as_ptr(),
        );
        if nRet != (IDOK as i32) {
            return (FALSE) as BOOLEAN; // Fail
        }
    }

    /* If this is an empty region, auto-create the partition if conditions are OK */
    if (*PartEntry).IsPartitioned == 0 {
        let mut Error: ULONG = 0;

        Error = PartitionCreateChecks(PartEntry, 0, 0);
        if Error != NOT_AN_ERROR {
            // MUIDisplayError(Error, Ir, POPUP_WAIT_ANY_KEY);
            DisplayMessage(
                hwndDlg,
                MB_ICONERROR | MB_OK,
                core::ptr::null(),
                RUSTCONV_WSTR_DEC14CA7236F.as_ptr(),
            );
            return (FALSE) as BOOLEAN; // Fail
        }

        /* Automatically create the partition on the whole empty space;
         * it will be formatted later with default parameters */
        if DoCreatePartition(
            hList,
            (*pSetupData).PartitionList,
            &raw mut hItem,
            &raw mut PartItem,
            0,
            0,
        ) == 0
        {
            DisplayError(
                GetParent(hwndDlg),
                IDS_ERROR_CREATE_PARTITION_TITLE,
                IDS_ERROR_CREATE_PARTITION,
            );
            return (FALSE) as BOOLEAN; // Fail
        }
        /* Update PartEntry */
        PartEntry = (*PartItem).PartEntry;
    }

    ASSERT!((*PartEntry).IsPartitioned != 0);
    // ASSERT(PartEntry != PartEntry->DiskEntry->ExtendedPartition);
    ASSERT!(!IsContainerPartition!((*PartEntry).PartitionType));
    ASSERT!(!(*PartEntry).Volume.is_null());

    /* Force formatting only if the partition doesn't have a volume (may or may not be formatted) */
    if !(*PartEntry).Volume.is_null()
        && (((*(*PartEntry).Volume).FormatState == Formatted)
            || (!(*PartItem).VolCreate.is_null()
                && (*(*PartItem).VolCreate).FileSystemName[0] != 0))
        && !((*pSetupData).bUnattend != 0 && (*pSetupData).USetupData.FormatPartition != 0)
    {
        /*NOTHING*/
    } else {
        /* Request formatting of the selected region if it's not already formatted */
        let mut ret: INT_PTR = 0;
        let mut PartCreateCtx: PARTCREATE_CTX = core::mem::zeroed();

        /* In unattended setup, try auto-formatting if required,
         * otherwise show the dialog to ask the user what to do */
        if (*pSetupData).bUnattend != 0 && (*pSetupData).USetupData.FormatPartition != 0 {
            PartCreateCtx.set_AutoFormat(TRUE as BOOLEAN);
        }

        /* Show the formatting dialog. In unattended setup, auto-format with
         * "default" filesystem, or popup the dialog asking the user what to do. */
        PartCreateCtx.PartItem = PartItem;
        ret = DialogBoxParamW(
            (*pSetupData).hInstance,
            MAKEINTRESOURCEW!(IDD_FORMAT),
            hwndDlg,
            Some(FormatDlgProc),
            &raw mut PartCreateCtx as LPARAM,
        );

        /* If the user refuses to format the partition, fail */
        if ret != IDOK as INT_PTR {
            return (FALSE) as BOOLEAN;
        }

        /* The partition will be formatted */
    }

    /* The install partition has been found */
    ASSERT!(
        (!(*PartEntry).Volume.is_null() && (*(*PartEntry).Volume).FormatState == Formatted)
            || (!(*PartItem).VolCreate.is_null()
                && (*(*PartItem).VolCreate).FileSystemName[0] != 0)
    );
    InstallPartition = PartEntry;
    return (TRUE) as BOOLEAN;
}

#[no_mangle]
pub unsafe extern "system" fn DriveDlgProc(hwndDlg: HWND, uMsg: UINT, wParam: WPARAM, lParam: LPARAM) -> INT_PTR {
    let mut pSetupData: PSETUPDATA = core::ptr::null_mut();
    let mut hList: HWND = core::ptr::null_mut();

    /* Retrieve pointer to the global setup data */
    pSetupData = GetWindowLongPtrW(hwndDlg, DWLP_USER) as PSETUPDATA;

    'sw: {
        match uMsg {
            WM_INITDIALOG => {
                /* Save pointer to the global setup data */
                pSetupData = (*(lParam as LPPROPSHEETPAGEW)).lParam as PSETUPDATA;
                SetWindowLongPtrW(hwndDlg, DWLP_USER, pSetupData as LONG_PTR);

                /* Initially hide and disable all partitioning buttons */
                ShowDlgItem!(hwndDlg, (IDC_INITDISK as i32), (SW_HIDE as i32));
                EnableDlgItem!(hwndDlg, (IDC_INITDISK as i32), (FALSE as i32));
                ShowDlgItem!(hwndDlg, (IDC_PARTCREATE as i32), (SW_HIDE as i32));
                EnableDlgItem!(hwndDlg, (IDC_PARTCREATE as i32), (FALSE as i32));
                ShowDlgItem!(hwndDlg, (IDC_PARTFORMAT as i32), (SW_HIDE as i32));
                EnableDlgItem!(hwndDlg, (IDC_PARTFORMAT as i32), (FALSE as i32));
                ShowDlgItem!(hwndDlg, (IDC_PARTDELETE as i32), (SW_HIDE as i32));
                EnableDlgItem!(hwndDlg, (IDC_PARTDELETE as i32), (FALSE as i32));

                /* Initialize the partitions list */
                hList = GetDlgItem(hwndDlg, (IDC_PARTITION as i32));
                UiContext.hPartList = hList;
                InitPartitionList((*pSetupData).hInstance, hList);
                DrawPartitionList(hList, (*pSetupData).PartitionList);
                break 'sw;
            }

            WM_DESTROY => {
                hList = GetDlgItem(hwndDlg, (IDC_PARTITION as i32));
                ASSERT!(UiContext.hPartList == hList);
                UiContext.hPartList = core::ptr::null_mut();
                CleanupPartitionList(hList);
                return (TRUE) as INT_PTR;
            }

            WM_COMMAND => {
                if HIWORD!(wParam) == (BN_CLICKED as u16) {
                    match (LOWORD!(wParam)) as u32 {
                        IDC_PARTMOREOPTS => {
                            DialogBoxParamW(
                                (*pSetupData).hInstance,
                                MAKEINTRESOURCEW!(IDD_ADVINSTOPTS),
                                hwndDlg,
                                Some(MoreOptDlgProc),
                                pSetupData as LPARAM,
                            );
                            return (TRUE) as INT_PTR;
                        }

                        IDC_INITDISK => {
                            // TODO: Implement disk partitioning initialization
                            return (TRUE) as INT_PTR;
                        }

                        IDC_PARTCREATE => {
                            let mut hItem: HTLITEM = core::ptr::null_mut();
                            let mut PartItem: PPARTITEM = core::ptr::null_mut();
                            let mut PartEntry: PPARTENTRY = core::ptr::null_mut();
                            let mut PartSize: ULONGLONG = 0;
                            let mut MaxPartSize: ULONGLONG = 0;
                            let mut MaxSizeMB: ULONG = 0;
                            let mut ret: INT_PTR = 0;
                            let mut PartCreateCtx: PARTCREATE_CTX = core::mem::zeroed();

                            hList = GetDlgItem(hwndDlg, (IDC_PARTITION as i32));
                            PartItem = GetSelectedPartition(hList, core::ptr::addr_of_mut!(hItem));
                            if PartItem.is_null() {
                                /* If the button was clicked, an empty disk
                                 * region should have been selected first */
                                ASSERT!(FALSE);
                                break 'sw;
                            }
                            PartEntry = (*PartItem).PartEntry;
                            if (*PartEntry).IsPartitioned != 0 {
                                /* Don't create a partition when one already exists */
                                ASSERT!(FALSE);
                                break 'sw;
                            }
                            ASSERT!(!(*PartEntry).Volume.is_null());

                            /* Get the partition info stored in the TreeList */
                            PartCreateCtx.PartItem = PartItem;

                            /* Retrieve the maximum size in MB (rounded up) the partition can have */
                            MaxPartSize = GetPartEntrySizeInBytes!(PartEntry);
                            MaxSizeMB = RoundingDivide(MaxPartSize, MB) as ULONG;
                            PartCreateCtx.MaxSizeMB = MaxSizeMB;

                            /* Don't force formatting by default */
                            PartCreateCtx.set_ForceFormat(FALSE as BOOLEAN);

                            /* Show the partitioning dialog */
                            ret = DialogBoxParamW(
                                (*pSetupData).hInstance,
                                MAKEINTRESOURCEW!(IDD_PARTITION),
                                hwndDlg,
                                Some(PartitionDlgProc),
                                core::ptr::addr_of_mut!(PartCreateCtx) as LPARAM,
                            );
                            if ret != IDOK as INT_PTR {
                                break 'sw;
                            }

                            /*
                             * If the input size, given in MB, specifies the maximum partition
                             * size, it may slightly under- or over-estimate the latter due to
                             * rounding error. In this case, use all of the unpartitioned space.
                             * Otherwise, directly convert the size to bytes.
                             */
                            PartSize = PartCreateCtx.PartSizeMB as ULONGLONG;
                            if PartSize == MaxSizeMB as ULONGLONG {
                                PartSize = MaxPartSize;
                            } else {
                                // if (PartSize < MaxSizeMB)
                                PartSize = PartSize.wrapping_mul(MB as ULONGLONG);
                            }

                            ASSERT!(PartSize <= MaxPartSize);

                            if DoCreatePartition(
                                hList,
                                (*pSetupData).PartitionList,
                                core::ptr::addr_of_mut!(hItem),
                                core::ptr::addr_of_mut!(PartItem),
                                PartSize,
                                (if PartCreateCtx.MBRExtPart == 0 {
                                    0
                                } else {
                                    PARTITION_EXTENDED
                                }) as ULONG_PTR,
                            ) == 0
                            {
                                DisplayError(
                                    GetParent(hwndDlg),
                                    IDS_ERROR_CREATE_PARTITION_TITLE,
                                    IDS_ERROR_CREATE_PARTITION,
                                );
                            }
                            break 'sw;
                        }

                        IDC_PARTFORMAT => {
                            let mut PartItem: PPARTITEM = core::ptr::null_mut();
                            let mut PartEntry: PPARTENTRY = core::ptr::null_mut();
                            let mut ret: INT_PTR = 0;
                            let mut PartCreateCtx: PARTCREATE_CTX = core::mem::zeroed();

                            hList = GetDlgItem(hwndDlg, (IDC_PARTITION as i32));
                            PartItem = GetSelectedPartition(hList, core::ptr::null_mut());
                            if PartItem.is_null() {
                                /* If the button was clicked, an empty disk
                                 * region should have been selected first */
                                ASSERT!(FALSE);
                                break 'sw;
                            }
                            PartEntry = (*PartItem).PartEntry;
                            if (*PartEntry).Volume.is_null() {
                                /* Don't format an unformattable partition */
                                ASSERT!(FALSE);
                                break 'sw;
                            }

                            /* Show the formatting dialog */
                            PartCreateCtx.PartItem = PartItem;
                            ret = DialogBoxParamW(
                                (*pSetupData).hInstance,
                                MAKEINTRESOURCEW!(IDD_FORMAT),
                                hwndDlg,
                                Some(FormatDlgProc),
                                core::ptr::addr_of_mut!(PartCreateCtx) as LPARAM,
                            );
                            DBG_UNREFERENCED_PARAMETER!(ret);
                            break 'sw;
                        }

                        IDC_PARTDELETE => {
                            let mut hItem: HTLITEM = core::ptr::null_mut();
                            let mut PartItem: PPARTITEM = core::ptr::null_mut();
                            let mut PartEntry: PPARTENTRY = core::ptr::null_mut();
                            let mut uIDWarnMsg: UINT = 0;

                            hList = GetDlgItem(hwndDlg, (IDC_PARTITION as i32));
                            PartItem = GetSelectedPartition(hList, core::ptr::addr_of_mut!(hItem));
                            if PartItem.is_null() {
                                /* If the button was clicked, a partition
                                 * should have been selected first */
                                ASSERT!(FALSE);
                                break 'sw;
                            }
                            PartEntry = (*PartItem).PartEntry;
                            if (*PartEntry).IsPartitioned == 0 {
                                /* Don't delete an unpartitioned disk region */
                                ASSERT!(FALSE);
                                break 'sw;
                            }

                            /* Choose the correct warning message to display:
                             * MBR-extended (container) vs. standard partition */
                            if PartEntry == (*(*PartEntry).DiskEntry).ExtendedPartition {
                                uIDWarnMsg = IDS_WARN_DELETE_MBR_EXTENDED_PARTITION;
                            } else {
                                uIDWarnMsg = IDS_WARN_DELETE_PARTITION;
                            }

                            /* If the user really wants to delete the partition... */
                            if DisplayMessage(
                                GetParent(hwndDlg),
                                MB_ICONWARNING | MB_YESNO | MB_DEFBUTTON2,
                                MAKEINTRESOURCEW!(IDS_WARN_DELETE_PARTITION_TITLE),
                                MAKEINTRESOURCEW!(uIDWarnMsg),
                            ) == (IDYES as i32)
                            {
                                /* ... make it so! */
                                if DoDeletePartition(
                                    hList,
                                    (*pSetupData).PartitionList,
                                    core::ptr::addr_of_mut!(hItem),
                                    PartItem,
                                ) == 0
                                {
                                    DisplayMessage(
                                        hwndDlg,
                                        MB_ICONERROR | MB_OK,
                                        core::ptr::null_mut(),
                                        RUSTCONV_WSTR_A576263ACBFE.as_ptr(),
                                    );
                                }
                            }
                            break 'sw;
                        }

                        _ => {}
                    }
                }
                break 'sw;
            }

            WM_NOTIFY => {
                let lpnm: LPNMHDR = lParam as LPNMHDR;

                if (*lpnm).idFrom == IDC_PARTITION as UINT_PTR {
                    'nsw1: {
                        match (((*lpnm).code) as i32) as u32 {
                            NM_RETURN => {
                                /* If the currently selected item is a partition (and so, if
                                 * the wizard "Next" button is enabled), pressing "Next" will
                                 * attempt to select an install partition and go to the next
                                 * page if successful. */
                                let hWndParent: HWND = GetParent(hwndDlg);
                                if IsWindowEnabled(GetDlgItem(hWndParent, (ID_WIZNEXT as i32))) != 0 {
                                    PropSheet_PressButton!(hWndParent, PSBTN_NEXT);
                                }
                                break 'nsw1;
                            }

                            __c if __c == TVN_KEYDOWN as u32 => {
                                if (*(lParam as LPTV_KEYDOWN_EX)).wVKey == (VK_DELETE as u16) {
                                    /* Send the delete command only if IDC_PARTDELETE is
                                     * enabled (i.e. the selected item IS a partition) */
                                    if IsWindowEnabled(GetDlgItem(hwndDlg, (IDC_PARTDELETE as i32))) != 0 {
                                        PostMessageW(
                                            hwndDlg,
                                            WM_COMMAND,
                                            MAKEWPARAM!(IDC_PARTDELETE, BN_CLICKED),
                                            0,
                                        );
                                    }
                                }
                                break 'nsw1;
                            }

                            _ => {}
                        }
                    }
                }

                // On Vista+ we can use TVN_ITEMCHANGED instead, with NMTVITEMCHANGE* pointer
                if (*lpnm).idFrom == IDC_PARTITION as UINT_PTR && (*lpnm).code == TVN_SELCHANGED as UINT {
                    let pnmv: LPNMTREEVIEW = lParam as LPNMTREEVIEW;

                    /* Check whether the item has been (de)selected */
                    if (((*pnmv).itemOld.mask | (*pnmv).itemNew.mask) & (TVIF_STATE as UINT)) == 0
                        || (((*pnmv).itemOld.state ^ (*pnmv).itemNew.state) & (TVIS_SELECTED as UINT)) == 0
                    {
                        break 'sw;
                    }

                    'after_d: {
                        'd: {
                            if ((*pnmv).itemNew.state & (TVIS_SELECTED as UINT)) != 0 {
                                let hParentItem: HTLITEM = TreeList_GetParent!((*lpnm).hwndFrom, (*pnmv).itemNew.hItem);
                                /* May or may not be a PPARTENTRY: this is a PPARTENTRY only when hParentItem != NULL */

                                if hParentItem.is_null() {
                                    /* Hard disk */
                                    let DiskEntry: PDISKENTRY = (*pnmv).itemNew.lParam as PDISKENTRY;
                                    ASSERT!(!DiskEntry.is_null());

                                    /* Show the "Initialize" disk button and hide and disable the others */
                                    ShowDlgItem!(hwndDlg, (IDC_INITDISK as i32), (SW_SHOW as i32));

                                    EnableDlgItem!(hwndDlg, (IDC_INITDISK as i32), (FALSE as i32));

                                    ShowDlgItem!(hwndDlg, (IDC_PARTCREATE as i32), (SW_HIDE as i32));
                                    EnableDlgItem!(hwndDlg, (IDC_PARTCREATE as i32), (FALSE as i32));

                                    ShowDlgItem!(hwndDlg, (IDC_PARTFORMAT as i32), (SW_HIDE as i32));
                                    EnableDlgItem!(hwndDlg, (IDC_PARTFORMAT as i32), (FALSE as i32));

                                    ShowDlgItem!(hwndDlg, (IDC_PARTDELETE as i32), (SW_HIDE as i32));
                                    EnableDlgItem!(hwndDlg, (IDC_PARTDELETE as i32), (FALSE as i32));

                                    /* Disable the "Next" button */
                                    // goto DisableWizNext;
                                    break 'd;
                                } else {
                                    /* Partition or unpartitioned space */
                                    let PartItem: PPARTITEM = (*pnmv).itemNew.lParam as PPARTITEM;
                                    let mut PartEntry: PPARTENTRY = core::ptr::null_mut();
                                    let mut CanBePartitioned: BOOL = 0;
                                    ASSERT!(!PartItem.is_null());
                                    PartEntry = (*PartItem).PartEntry;
                                    ASSERT!(!PartEntry.is_null());

                                    /* Hide and disable the "Initialize" disk button */
                                    ShowDlgItem!(hwndDlg, (IDC_INITDISK as i32), (SW_HIDE as i32));
                                    EnableDlgItem!(hwndDlg, (IDC_INITDISK as i32), (FALSE as i32));

                                    /* Check whether the selected disk region is not partitioned, and
                                     * can be partitioned according to the disk's partitioning scheme */
                                    CanBePartitioned = (((*PartEntry).IsPartitioned == 0)
                                        && (PartitionCreateChecks(PartEntry, 0, 0) == NOT_AN_ERROR))
                                        as BOOL;

                                    if (*PartEntry).IsPartitioned == 0 {
                                        /* Show the "Create" partition button, but enable it
                                         * only if the selected disk region can be partitioned */
                                        ShowDlgItem!(hwndDlg, (IDC_PARTCREATE as i32), (SW_SHOW as i32));
                                        EnableDlgItem!(hwndDlg, (IDC_PARTCREATE as i32), CanBePartitioned);

                                        /* Hide and disable the "Format" button */
                                        ShowDlgItem!(hwndDlg, (IDC_PARTFORMAT as i32), (SW_HIDE as i32));
                                        EnableDlgItem!(hwndDlg, (IDC_PARTFORMAT as i32), (FALSE as i32));
                                    } else {
                                        /* Hide and disable the "Create" partition button */
                                        ShowDlgItem!(hwndDlg, (IDC_PARTCREATE as i32), (SW_HIDE as i32));
                                        EnableDlgItem!(hwndDlg, (IDC_PARTCREATE as i32), (FALSE as i32));

                                        /* Show the "Format" button, but enable it only
                                         * if a formattable volume is present */
                                        ShowDlgItem!(hwndDlg, (IDC_PARTFORMAT as i32), (SW_SHOW as i32));
                                        EnableDlgItem!(hwndDlg, (IDC_PARTFORMAT as i32), (!(*PartEntry).Volume.is_null()) as BOOL);
                                    }

                                    /* Show the "Delete" partition button, but enable it
                                     * only if the disk region is partitioned */
                                    ShowDlgItem!(hwndDlg, (IDC_PARTDELETE as i32), (SW_SHOW as i32));
                                    EnableDlgItem!(hwndDlg, (IDC_PARTDELETE as i32), (*PartEntry).IsPartitioned as BOOL);

                                    /*
                                     * Enable the "Next" button if:
                                     *
                                     * 1. the selected disk region is partitioned:
                                     *    it can either have a volume attached (and be either
                                     *    formatted or ready to be formatted),
                                     *    or it's not yet formatted (the installer will prompt
                                     *    for formatting parameters).
                                     *
                                     * 2. Or, the selected disk region is not partitioned, but
                                     *    can be partitioned according to the disk's partitioning
                                     *    scheme (the installer will auto-partition the region
                                     *    and prompt for formatting parameters).
                                     *
                                     * In all other cases, the "Next" button is disabled.
                                     */

                                    // TODO: In the future: first test needs to be augmented with:
                                    // (... && PartEntry->Volume->IsSimpleVolume)
                                    if ((((*PartEntry).IsPartitioned != 0) && !(*PartEntry).Volume.is_null())) || CanBePartitioned != 0 {
                                        // ASSERT(PartEntry != PartEntry->DiskEntry->ExtendedPartition);
                                        ASSERT!(IsContainerPartition!((*PartEntry).PartitionType) == false);
                                        PropSheet_SetWizButtons!(
                                            GetParent(hwndDlg),
                                            PSWIZB_BACK | PSWIZB_NEXT,
                                        );
                                        break 'after_d;
                                    } else {
                                        // goto DisableWizNext;
                                        break 'd;
                                    }
                                }
                            }
                        }

                        /* DisableWizNext: Keep the "Next" button disabled. It will be enabled
                         * only when the user selects a valid partition. */
                        PropSheet_SetWizButtons!(GetParent(hwndDlg), PSWIZB_BACK);
                    }

                    break 'sw;
                }

                if (*lpnm).idFrom == IDC_PARTITION as UINT_PTR && (*lpnm).code == TVN_DELETEITEM as UINT {
                    /* Deleting an item from the partition list */
                    let pnmv: LPNMTREEVIEW = lParam as LPNMTREEVIEW;
                    DeleteTreeItem((*lpnm).hwndFrom, core::ptr::addr_of_mut!((*pnmv).itemOld) as *mut TLITEMW);
                    break 'sw;
                }

                match ((*lpnm).code) as i32 {
                    PSN_SETACTIVE => {
                        /* Keep the "Next" button disabled. It will be enabled
                         * only when the user selects a valid partition. */
                        PropSheet_SetWizButtons!(GetParent(hwndDlg), PSWIZB_BACK);

                        /* In unattended mode, switch directly to the next page.
                         * TODO: *UNLESS* there are inconsistencies in the data,
                         * in which case we should stay on the page! */
                        if (*pSetupData).bUnattend != 0 {
                            'dowhile: loop {
                                let mut CurrentPartition: PPARTENTRY = core::ptr::null_mut();

                                'cip: {
                                    /* If DestinationDiskNumber or DestinationPartitionNumber are invalid
                                     * (see below), don't select the partition and show the list instead */
                                    if (*pSetupData).USetupData.DestinationDiskNumber == -(1 as LONG)
                                        || (*pSetupData).USetupData.DestinationPartitionNumber == -(1 as LONG)
                                    {
                                        break 'dowhile;
                                    }

                                    /* Determine the selected installation disk & partition */
                                    CurrentPartition = SelectPartition(
                                        (*pSetupData).PartitionList,
                                        (*pSetupData).USetupData.DestinationDiskNumber as ULONG,
                                        (*pSetupData).USetupData.DestinationPartitionNumber as ULONG,
                                    );

                                    /* Now reset DestinationDiskNumber and DestinationPartitionNumber
                                     * to *invalid* values, so that if the corresponding partition is
                                     * determined to be invalid by the code below or in CreateInstallPartition,
                                     * we don't reselect it when SelectPartitionPage() is called again */
                                    (*pSetupData).USetupData.DestinationDiskNumber = -(1 as LONG);
                                    (*pSetupData).USetupData.DestinationPartitionNumber = -(1 as LONG);

                                    // FIXME: Here and in the AutoPartition case below, the CurrentPartition
                                    // may actually be unsuitable (MBR-extended, non-simple volume...).
                                    // More checks need to be made here!
                                    //
                                    // NOTE: We don't check for CurrentPartition->Volume in case
                                    // the partition doesn't contain a recognized volume/none exists.
                                    // We also don't check whether IsPartitioned is TRUE, because if
                                    // the partition is still empty space, we'll try to partition it.
                                    if !CurrentPartition.is_null()
                                        && IsContainerPartition!((*CurrentPartition).PartitionType) == false
                                    {
                                        // goto CreateInstallPartition;
                                        break 'cip;
                                    }

                                    if (*pSetupData).USetupData.AutoPartition != 0 {
                                        /* Use whatever selected partition (or the first one) in the list */
                                        let mut PartItem: PPARTITEM = core::ptr::null_mut();
                                        hList = GetDlgItem(hwndDlg, (IDC_PARTITION as i32));
                                        PartItem = GetSelectedPartition(hList, core::ptr::null_mut());
                                        if PartItem.is_null() {
                                            PartItem = FindPartitionItem(hList, core::ptr::null_mut(), core::ptr::null_mut());
                                        }
                                        if !PartItem.is_null() {
                                            CurrentPartition = (*PartItem).PartEntry;
                                        }

                                        // TODO: Do more checks, and loop until we find a valid partition.
                                        // goto CreateInstallPartition;
                                        break 'cip;
                                    }
                                    break 'dowhile;
                                }

                                /* CreateInstallPartition: Select the install partition and if success,
                                 * proceed with the installation */
                                if SelectInstallPartition(pSetupData, hwndDlg, CurrentPartition) != 0 {
                                    SetWindowLongPtrW(hwndDlg, DWLP_MSGRESULT, -(1 as LONG_PTR));
                                    return (TRUE) as INT_PTR;
                                }
                                /* Halt the installation and display the page */

                                if (0) == 0 {
                                    break 'dowhile;
                                }
                            }
                        }
                        break 'sw;
                    }

                    PSN_QUERYINITIALFOCUS => {
                        /* Reselect the currently selected item, so as to refresh the UI buttons */
                        let mut hItem: HTLITEM = core::ptr::null_mut();
                        hList = GetDlgItem(hwndDlg, (IDC_PARTITION as i32));
                        hItem = TreeList_GetSelection!(hList);
                        if !hItem.is_null() {
                            /* Don't use TreeList_SelectItem() directly. Instead,
                             * deselect first the item before reselecting it, so as to
                             * invalidate its cached state and have the TVN_SELCHANGED
                             * notification sent. */
                            TreeList_SetItemState!(hList, hItem, 0, TVIS_SELECTED);
                            TreeList_SetItemState!(hList, hItem, TVIS_SELECTED, TVIS_SELECTED);
                        }

                        /* Focus on the partition list */
                        SetWindowLongPtrW(hwndDlg, DWLP_MSGRESULT, hList as LONG_PTR);
                        return (TRUE) as INT_PTR;
                    }

                    PSN_QUERYCANCEL => {
                        if DisplayMessage(
                            GetParent(hwndDlg),
                            MB_ICONQUESTION | MB_YESNO | MB_DEFBUTTON2,
                            MAKEINTRESOURCEW!(IDS_ABORTSETUP2),
                            MAKEINTRESOURCEW!(IDS_ABORTSETUP),
                        ) == (IDYES as i32)
                        {
                            /* Go to the Abort page */
                            PropSheet_SetCurSelByID!(GetParent(hwndDlg), IDD_ABORTPAGE);
                        }

                        /* Do not close the wizard too soon */
                        SetWindowLongPtrW(hwndDlg, DWLP_MSGRESULT, (TRUE) as LONG_PTR);
                        return (TRUE) as INT_PTR;
                    }

                    PSN_WIZNEXT => {
                        /* Select the install partition and if success, go to the next page */
                        if SelectInstallPartition(pSetupData, hwndDlg, core::ptr::null_mut()) != 0 {
                            break 'sw;
                        }
                        /* Failed, stay on the page */
                        SetWindowLongPtrW(hwndDlg, DWLP_MSGRESULT, -(1 as LONG_PTR));
                        return (TRUE) as INT_PTR;
                    }

                    _ => {}
                }
                break 'sw;
            }

            _ => {}
        }
    }

    return (FALSE) as INT_PTR;
}
