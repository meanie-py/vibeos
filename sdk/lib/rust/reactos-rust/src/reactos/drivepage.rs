unsafe extern "C" fn DoSanitizeText(pszSanitized: PWSTR) -> BOOL {
    let mut pch1: PWCHAR = core::ptr::null_mut();
    let mut pch2: PWCHAR = core::ptr::null_mut();
    let mut bSanitized: BOOL = (FALSE as i32);

    pch1 = pszSanitized as PWCHAR;
    pch2 = pszSanitized as PWCHAR;
    while *pch1 != 0 {
        /* Skip any invalid character found */
        if !IS_VALID_INSTALL_PATH_CHAR!(*pch1) {
            bSanitized = (TRUE as i32);
        } else {
            /* Copy over the valid ones */
            *pch2 = *pch1;
            pch2 = pch2.offset(1);
        }
        pch1 = pch1.offset(1);
    }
    *pch2 = 0;

    return bSanitized;
}

unsafe extern "C" fn DoSanitizeClipboard(hWnd: HWND) -> BOOL {
    let mut hData: HGLOBAL;
    let mut pszText: LPWSTR;
    let mut pszSanitized: LPWSTR;
    let mut bSanitized: BOOL;

    /* Protect read-only edit control from modification */
    if GetWindowLongPtrW(hWnd, GWL_STYLE as core::ffi::c_int) & ES_READONLY as LONG_PTR != 0 {
        return FALSE as BOOL;
    }

    if OpenClipboard(hWnd) == 0 {
        return FALSE as BOOL;
    }

    hData = GetClipboardData(CF_UNICODETEXT as UINT) as HGLOBAL;
    pszText = GlobalLock(hData) as LPWSTR;
    if pszText.is_null() {
        CloseClipboard();
        return FALSE as BOOL;
    }

    pszSanitized = _wcsdup(pszText as *const WCHAR) as LPWSTR;
    GlobalUnlock(hData);
    bSanitized = (!pszSanitized.is_null() && DoSanitizeText(pszSanitized as PWSTR) != 0) as core::ffi::c_int as BOOL;
    if bSanitized != 0 {
        /* Update clipboard text */
        let cbData: SIZE_T = (wcslen(pszSanitized as *const WCHAR) as SIZE_T)
            .wrapping_add(1 as SIZE_T)
            .wrapping_mul(core::mem::size_of::<WCHAR>() as SIZE_T);
        hData = GlobalAlloc((GMEM_MOVEABLE | GMEM_SHARE) as UINT, cbData) as HGLOBAL;
        pszText = GlobalLock(hData) as LPWSTR;
        if !pszText.is_null() {
            CopyMemory!(pszText as *mut core::ffi::c_void, pszSanitized as *const core::ffi::c_void, cbData as usize);
            GlobalUnlock(hData);
            SetClipboardData(CF_UNICODETEXT as UINT, hData as HANDLE);
        }
    }
    free(pszSanitized as *mut core::ffi::c_void);

    CloseClipboard();
    return bSanitized;
}

unsafe extern "C" fn ShowErrorTip(mut hEdit: HWND) {
    let mut balloon: EDITBALLOONTIP = core::mem::zeroed();
    let mut szTitle: [WCHAR; 512] = [0; 512];
    let mut szText: [WCHAR; 512] = [0; 512];

    /* Load the resources */
    LoadStringW(
        SetupData.hInstance,
        IDS_ERROR_INVALID_INSTALLDIR_CHAR_TITLE as UINT,
        core::ptr::addr_of_mut!(szTitle) as LPWSTR,
        _countof!(szTitle) as core::ffi::c_int,
    );
    LoadStringW(
        SetupData.hInstance,
        IDS_ERROR_INVALID_INSTALLDIR_CHAR as UINT,
        core::ptr::addr_of_mut!(szText) as LPWSTR,
        _countof!(szText) as core::ffi::c_int,
    );

    /* Show a warning balloon */
    balloon.cbStruct = core::mem::size_of::<EDITBALLOONTIP>() as DWORD;
    balloon.pszTitle = core::ptr::addr_of_mut!(szTitle) as *mut WCHAR as LPCWSTR;
    balloon.pszText = core::ptr::addr_of_mut!(szText) as *mut WCHAR as LPCWSTR;
    balloon.ttiIcon = TTI_ERROR as INT;

    MessageBeep(MB_ICONERROR as UINT);
    Edit_ShowBalloonTip!(hEdit, core::ptr::addr_of_mut!(balloon));

    // NOTE: There is no need to hide it when other keys are pressed;
    // the EDIT control will deal with that itself.
}

unsafe extern "system" fn InstallDirEditProc(
    mut hWnd: HWND,
    mut uMsg: UINT,
    mut wParam: WPARAM,
    mut lParam: LPARAM,
) -> LRESULT {
    let mut orgEditProc: WNDPROC = ::core::mem::transmute::<isize, WNDPROC>(
        GetWindowLongPtrW(hWnd, GWLP_USERDATA) as isize,
    );

    'sw: {
        let mut run_block: bool = false;
        match uMsg {
            WM_UNICHAR => {
                if wParam == UNICODE_NOCHAR as WPARAM {
                    return TRUE as LRESULT;
                }
                run_block = true;
            }
            WM_IME_CHAR | WM_CHAR => {
                run_block = true;
            }
            WM_PASTE => {
                /* Verify the text being pasted; if it was sanitized, show an error */
                if DoSanitizeClipboard(hWnd) != 0 {
                    ShowErrorTip(hWnd);
                }
                break 'sw;
            }
            _ => {
                break 'sw;
            }
        }

        if run_block {
            let mut wch: WCHAR = wParam as WCHAR;

            /* Let the EDIT control deal with Control characters.
             * It won't emit them as raw data in the text. */
            if wParam < ' ' as WPARAM {
                break 'sw;
            }

            /* Ignore Ctrl-Backspace */
            if wParam == 0x7F as WPARAM {
                return 0 as LRESULT;
            }

            /* Protect read-only edit control from modification */
            if (GetWindowLongPtrW(hWnd, GWL_STYLE) & ES_READONLY as LONG_PTR) != 0 {
                break 'sw;
            }

            if uMsg == WM_IME_CHAR as UINT {
                if IsWindowUnicode(hWnd) == 0
                    && (HIBYTE!(wch) as i32) != (0 as i32)
                {
                    let mut data: [CHAR; 2] = [HIBYTE!(wch) as CHAR, LOBYTE!(wch) as CHAR];
                    MultiByteToWideChar(
                        CP_ACP as UINT,
                        0 as DWORD,
                        core::ptr::addr_of_mut!(data) as *mut CHAR as LPCSTR,
                        2 as ::core::ffi::c_int,
                        core::ptr::addr_of_mut!(wch),
                        1 as ::core::ffi::c_int,
                    );
                }
            }

            /* Show an error and ignore input character if it's invalid */
            if !IS_VALID_INSTALL_PATH_CHAR!(wch) {
                ShowErrorTip(hWnd);
                return 0 as LRESULT;
            }
        }
    }

    return CallWindowProcW(orgEditProc, hWnd, uMsg, wParam, lParam);
}

unsafe extern "system" fn MoreOptDlgProc(
    hDlg: HWND,
    uMsg: UINT,
    wParam: WPARAM,
    lParam: LPARAM,
) -> INT_PTR {
    let mut pSetupData: PSETUPDATA = core::ptr::null_mut();

    /* Retrieve pointer to the global setup data */
    pSetupData = GetWindowLongPtrW(hDlg, DWLP_USER) as PSETUPDATA;

    match uMsg {
        WM_INITDIALOG => {
            let mut hEdit: HWND = core::ptr::null_mut();
            let mut orgEditProc: WNDPROC = None;
            let mut bIsBIOS: BOOL = 0;
            let mut uID: UINT = 0;
            let mut iItem: INT = 0;
            let mut iCurrent: INT = CB_ERR;
            let mut iDefault: INT = 0;
            let mut szText: [WCHAR; 50] = [0; 50];

            /* Save pointer to the global setup data */
            pSetupData = lParam as PSETUPDATA;
            SetWindowLongPtrW(hDlg, DWLP_USER, pSetupData as LONG_PTR);

            /* Subclass the install-dir edit control */
            hEdit = GetDlgItem(hDlg, (IDC_PATH as i32));
            orgEditProc = core::mem::transmute::<LONG_PTR, WNDPROC>(
                GetWindowLongPtrW(hEdit, GWLP_WNDPROC),
            );
            SetWindowLongPtrW(
                hEdit,
                GWLP_USERDATA,
                core::mem::transmute::<WNDPROC, LONG_PTR>(orgEditProc),
            );
            SetWindowLongPtrW(
                hEdit,
                GWLP_WNDPROC,
                (InstallDirEditProc as usize) as LONG_PTR,
            );

            /* Set the current installation directory */
            SetWindowTextW(
                hEdit,
                core::ptr::addr_of_mut!((*pSetupData).USetupData.InstallationDirectory) as *mut WCHAR as LPCWSTR,
            );

            /* Initialize the list of available bootloader locations */
            bIsBIOS = (((*pSetupData).USetupData.ArchType == ARCH_PcAT)
                || ((*pSetupData).USetupData.ArchType == ARCH_NEC98x86)) as BOOL;
            uID = IDS_BOOTLOADER_NOINST;
            while uID <= IDS_BOOTLOADER_VBRONLY {
                if !((bIsBIOS != 0 && (uID == IDS_BOOTLOADER_SYSTEM))
                    || (bIsBIOS == 0 && (uID == IDS_BOOTLOADER_MBRVBR || uID == IDS_BOOTLOADER_VBRONLY)))
                {
                    LoadStringW(
                        (*pSetupData).hInstance,
                        uID,
                        core::ptr::addr_of_mut!(szText) as *mut WCHAR as LPWSTR,
                        ARRAYSIZE!(szText) as INT,
                    );
                    iItem = SendDlgItemMessageW(
                        hDlg,
                        (IDC_INSTFREELDR as i32),
                        CB_ADDSTRING,
                        0,
                        core::ptr::addr_of_mut!(szText) as *mut WCHAR as LPARAM,
                    ) as INT;
                    if iItem != CB_ERR && iItem != CB_ERRSPACE {
                        let mut uBldrLoc: UINT = uID.wrapping_sub(IDS_BOOTLOADER_NOINST).wrapping_sub(
                            (if bIsBIOS != 0 && uID >= IDS_BOOTLOADER_SYSTEM {
                                1
                            } else {
                                0
                            }) as UINT,
                        );
                        SendDlgItemMessageW(
                            hDlg,
                            (IDC_INSTFREELDR as i32),
                            CB_SETITEMDATA,
                            iItem as WPARAM,
                            uBldrLoc as LPARAM,
                        );

                        /* Find the index of the current and default locations */
                        if (uBldrLoc as ::core::ffi::c_ulong)
                            == ((*pSetupData).USetupData.BootLoaderLocation as ::core::ffi::c_ulong)
                        {
                            iCurrent = iItem;
                        }
                        if uBldrLoc == (IDS_BOOTLOADER_SYSTEM - IDS_BOOTLOADER_NOINST) as UINT {
                            iDefault = iItem;
                        }
                    }
                }
                uID = uID.wrapping_add(1);
            }
            /* Select the current location or fall back to the default one */
            if iCurrent == CB_ERR {
                iCurrent = iDefault;
            }
            SendDlgItemMessageW(
                hDlg,
                (IDC_INSTFREELDR as i32),
                CB_SETCURSEL,
                iCurrent as WPARAM,
                0 as LPARAM,
            );

            return TRUE as INT_PTR;
        }

        WM_DESTROY => {
            /* Unsubclass the edit control */
            let mut hEdit_0: HWND = GetDlgItem(hDlg, (IDC_PATH as i32));
            let mut orgEditProc_0: WNDPROC = core::mem::transmute::<LONG_PTR, WNDPROC>(
                GetWindowLongPtrW(hEdit_0, GWLP_USERDATA),
            );
            if orgEditProc_0.is_some() {
                SetWindowLongPtrW(
                    hEdit_0,
                    GWLP_WNDPROC,
                    core::mem::transmute::<WNDPROC, LONG_PTR>(orgEditProc_0),
                );
            }
            (); // break
        }

        WM_COMMAND => {
            if HIWORD!(wParam) == (BN_CLICKED as u16) {
                let mut at: u8 = match (LOWORD!(wParam)) as u32 {
                    IDOK => 0,
                    IDCANCEL => 1,
                    _ => 2,
                };
                loop {
                    match at {
                        0 => {
                            let mut hEdit_1: HWND = core::ptr::null_mut();
                            let mut bIsValid: BOOL = 0;
                            let mut InstallDir: [WCHAR; (MAX_PATH) as _] =
                                [0; (MAX_PATH) as _];
                            let mut iItem_0: INT = 0;
                            let mut uBldrLoc_0: UINT = (CB_ERR) as u32;

                            /*
                             * Retrieve the installation path and verify its validity.
                             * Check for the validity of the installation directory and
                             * pop up an error if this is not the case.
                             */
                            hEdit_1 = GetDlgItem(hDlg, (IDC_PATH as i32));
                            bIsValid = (((GetWindowTextLengthW(hEdit_1)) as usize)
                                < (_countof!(InstallDir) as usize)) as BOOL; // && IsValidInstallDirectory(InstallDir);
                            GetWindowTextW(
                                hEdit_1,
                                core::ptr::addr_of_mut!(InstallDir) as *mut WCHAR as LPWSTR,
                                _countof!(InstallDir) as INT,
                            );
                            bIsValid = (bIsValid != 0
                                && IsValidInstallDirectory(
                                    core::ptr::addr_of_mut!(InstallDir) as *mut WCHAR as PCWSTR,
                                ) != 0) as BOOL;

                            if bIsValid == 0 {
                                // ERROR_DIRECTORY_NAME
                                DisplayError(
                                    hDlg,
                                    IDS_ERROR_DIRECTORY_NAME_TITLE,
                                    IDS_ERROR_DIRECTORY_NAME,
                                );
                                break; // Go back to the dialog.
                            }

                            StringCchCopyW(
                                core::ptr::addr_of_mut!((*pSetupData).USetupData.InstallationDirectory)
                                    as STRSAFE_LPWSTR,
                                _countof!((*pSetupData).USetupData.InstallationDirectory) as size_t,
                                core::ptr::addr_of_mut!(InstallDir) as *mut WCHAR as STRSAFE_LPCWSTR,
                            );

                            /* Retrieve the bootloader location */
                            iItem_0 = SendDlgItemMessageW(
                                hDlg,
                                (IDC_INSTFREELDR as i32),
                                CB_GETCURSEL,
                                0 as WPARAM,
                                0 as LPARAM,
                            ) as INT;
                            if iItem_0 != CB_ERR {
                                uBldrLoc_0 = SendDlgItemMessageW(
                                    hDlg,
                                    (IDC_INSTFREELDR as i32),
                                    CB_GETITEMDATA,
                                    iItem_0 as WPARAM,
                                    0 as LPARAM,
                                ) as UINT;
                            }
                            if uBldrLoc_0 == CB_ERR as UINT {
                                // Default location: System partition / MBR & VBR
                                uBldrLoc_0 = (IDS_BOOTLOADER_SYSTEM - IDS_BOOTLOADER_NOINST) as UINT;
                            }
                            uBldrLoc_0 = min!(
                                max!(uBldrLoc_0, 0 as UINT),
                                3 as UINT,
                            );
                            (*pSetupData).USetupData.BootLoaderLocation = uBldrLoc_0 as LONG;

                            // __fallthrough
                            at = 1;
                            continue;
                        }
                        1 => {
                            EndDialog(hDlg, LOWORD!(wParam) as INT_PTR);
                            return TRUE as INT_PTR;
                        }
                        _ => break,
                    }
                }
            }
            (); // break
        }

        _ => {}
    }

    return FALSE as INT_PTR;
}

unsafe extern "system" fn FormatDlgProcWorker(
    PartCreateCtx: PPARTCREATE_CTX,
    hDlg: HWND,
    uMsg: UINT,
    wParam: WPARAM,
    lParam: LPARAM,
) -> INT_PTR {
    match uMsg {
        WM_INITDIALOG => {
            let mut Index: ULONG = 0 as ULONG;
            let mut iItem: INT = 0;
            let mut FileSystem: PCWSTR = core::ptr::null();
            let mut DefaultFs: PCWSTR = core::ptr::null();
            let mut Volume: PVOLENTRY = core::ptr::null_mut();
            let mut VolCreate: PVOL_CREATE_INFO = core::ptr::null_mut();

            /* List the well-known file systems. We use the same strings
             * for the displayed FS names and their actual ones. */
            loop {
                let fresh = Index;
                Index = Index.wrapping_add(1);
                if !(GetRegisteredFileSystems(fresh, core::ptr::addr_of_mut!(FileSystem)) != 0) {
                    break;
                }
                iItem = SendDlgItemMessageW(
                    hDlg,
                    IDC_FSTYPE as ::core::ffi::c_int,
                    CB_INSERTSTRING as UINT,
                    -(1 as ::core::ffi::c_int) as WPARAM,
                    FileSystem as LPARAM,
                ) as INT;
                if iItem != CB_ERR && iItem != CB_ERRSPACE {
                    SendDlgItemMessageW(
                        hDlg,
                        IDC_FSTYPE as ::core::ffi::c_int,
                        CB_SETITEMDATA as UINT,
                        iItem as WPARAM,
                        FileSystem as LPARAM,
                    );
                }
            }

            /* Add the 'Do not format' entry if needed */
            if (*PartCreateCtx).ForceFormat() == 0 {
                let mut szText: [WCHAR; 50] = [0; 50];

                LoadStringW(
                    SetupData.hInstance,
                    IDS_VOLUME_NOFORMAT as UINT,
                    core::ptr::addr_of_mut!(szText) as *mut WCHAR as LPWSTR,
                    _countof!(szText) as ::core::ffi::c_int,
                );
                iItem = SendDlgItemMessageW(
                    hDlg,
                    IDC_FSTYPE as ::core::ffi::c_int,
                    CB_INSERTSTRING as UINT,
                    0 as WPARAM,
                    core::ptr::addr_of_mut!(szText) as *mut WCHAR as LPARAM,
                ) as INT;
                if iItem != CB_ERR && iItem != CB_ERRSPACE {
                    SendDlgItemMessageW(
                        hDlg,
                        IDC_FSTYPE as ::core::ffi::c_int,
                        CB_SETITEMDATA as UINT,
                        iItem as WPARAM,
                        core::ptr::null_mut::<u8>() as LPARAM,
                    );
                }
            }

            if SetupData.bUnattend != 0 {
                /* In unattended mode, preselect the file system */
                match SetupData.USetupData.FsType {
                    /* 1 is for BtrFS */
                    1 => {
                        DefaultFs = RUSTCONV_WSTR_BE0DEB469A7B.as_ptr();
                    }

                    /* If we don't understand input, default to FAT */
                    _ => {
                        DefaultFs = RUSTCONV_WSTR_A953DDDD78B1.as_ptr();
                    }
                }
            } else {
                /* By default select the "FAT" file system */
                DefaultFs = RUSTCONV_WSTR_A953DDDD78B1.as_ptr();
            }

            /* Retrieve the selected volume and create information */
            ASSERT!(
                (*(*PartCreateCtx).PartItem).Volume
                    == (*(*(*PartCreateCtx).PartItem).PartEntry).Volume
            );
            Volume = (*(*(*PartCreateCtx).PartItem).PartEntry).Volume;
            VolCreate = (*(*PartCreateCtx).PartItem).VolCreate;

            /* Select the existing file system in the list if any,
             * otherwise use the "DefaultFs" */
            if !VolCreate.is_null()
                && *(core::ptr::addr_of_mut!((*VolCreate).FileSystemName) as *mut WCHAR) != 0
            {
                FileSystem = core::ptr::addr_of_mut!((*VolCreate).FileSystemName) as *mut WCHAR as PCWSTR;
            } else if SetupData.bUnattend == 0
                && !Volume.is_null()
                && *(core::ptr::addr_of_mut!((*Volume).Info.FileSystem) as *mut WCHAR) != 0
            {
                FileSystem = core::ptr::addr_of_mut!((*Volume).Info.FileSystem) as *mut WCHAR as PCWSTR;
            } else {
                FileSystem = DefaultFs;
            }

            iItem = SendDlgItemMessageW(
                hDlg,
                IDC_FSTYPE as ::core::ffi::c_int,
                CB_FINDSTRINGEXACT as UINT,
                0 as WPARAM,
                FileSystem as LPARAM,
            ) as INT;
            if iItem == CB_ERR {
                iItem = 0;
            }
            SendDlgItemMessageW(
                hDlg,
                IDC_FSTYPE as ::core::ffi::c_int,
                CB_SETCURSEL as UINT,
                iItem as WPARAM,
                0 as LPARAM,
            );

            /* Check the quick-format option by default as it speeds up formatting */
            if VolCreate.is_null() || (*VolCreate).QuickFormat as ::core::ffi::c_int != 0 {
                CheckDlgButton(
                    hDlg,
                    IDC_CHECK_QUICKFMT as ::core::ffi::c_int,
                    BST_CHECKED as UINT,
                );
            } else {
                CheckDlgButton(
                    hDlg,
                    IDC_CHECK_QUICKFMT as ::core::ffi::c_int,
                    BST_UNCHECKED as UINT,
                );
            }

            return TRUE as INT_PTR;
        }

        WM_COMMAND => {
            //
            // NOTE:
            // - CBN_SELCHANGE sent everytime a combobox list item is selected,
            //   *even if* the list is opened.
            // - CBN_SELENDOK sent only when user finished to select an item
            //   by clicking on it (if the list is opened), or selection changed
            //   (when the list is closed but selection is done with arrow keys).
            //
            if (HIWORD!(wParam) == (CBN_SELCHANGE as u16) /*|| HIWORD(wParam) == CBN_SELENDOK*/)
                && (LOWORD!(wParam) == (IDC_FSTYPE as u16))
            {
                // HWND hWndList = GetDlgItem(hDlg, IDC_FSTYPE);
                let mut FileSystem_0: PCWSTR = core::ptr::null();
                let mut iItem_0: INT = 0;

                /* Retrieve the selected file system. Use the
                 * item data instead of the displayed string. */
                iItem_0 = SendDlgItemMessageW(
                    hDlg,
                    IDC_FSTYPE as ::core::ffi::c_int,
                    CB_GETCURSEL as UINT,
                    0 as WPARAM,
                    0 as LPARAM,
                ) as INT;
                if iItem_0 == CB_ERR {
                    iItem_0 = 0; // Default entry
                }
                FileSystem_0 = SendDlgItemMessageW(
                    hDlg,
                    IDC_FSTYPE as ::core::ffi::c_int,
                    CB_GETITEMDATA as UINT,
                    iItem_0 as WPARAM,
                    0 as LPARAM,
                ) as PCWSTR;
                if FileSystem_0 == CB_ERR as isize as PCWSTR {
                    FileSystem_0 = core::ptr::null(); // Default data
                }

                /* Enable or disable formatting options,
                 * depending on whether we need to format */
                EnableDlgItem!(
                    hDlg,
                    IDC_CHECK_QUICKFMT as ::core::ffi::c_int,
                    (!FileSystem_0.is_null() && *FileSystem_0 != 0) as ::core::ffi::c_int,
                );
                return TRUE as INT_PTR;
            }

            if (HIWORD!(wParam) == (BN_CLICKED as u16))
                && (LOWORD!(wParam) == (IDOK as u16))
            {
                let mut PartItem: PPARTITEM = (*PartCreateCtx).PartItem;
                let mut VolCreate_0: PVOL_CREATE_INFO = core::ptr::null_mut();
                let mut FileSystem_1: PCWSTR = core::ptr::null();
                let mut iItem_1: INT = 0;

                /*
                 * Retrieve the formatting options
                 */

                /* Retrieve the selected file system. Use the
                 * item data instead of the displayed string. */
                iItem_1 = SendDlgItemMessageW(
                    hDlg,
                    IDC_FSTYPE as ::core::ffi::c_int,
                    CB_GETCURSEL as UINT,
                    0 as WPARAM,
                    0 as LPARAM,
                ) as INT;
                if iItem_1 == CB_ERR {
                    iItem_1 = 0; // Default entry
                }
                FileSystem_1 = SendDlgItemMessageW(
                    hDlg,
                    IDC_FSTYPE as ::core::ffi::c_int,
                    CB_GETITEMDATA as UINT,
                    iItem_1 as WPARAM,
                    0 as LPARAM,
                ) as PCWSTR;
                if FileSystem_1 == CB_ERR as isize as PCWSTR {
                    FileSystem_1 = core::ptr::null(); // Default data
                }

                VolCreate_0 = (*PartItem).VolCreate;

                /* Check if we need to format */
                if FileSystem_1.is_null() || *FileSystem_1 == 0 {
                    /* We don't format. If there is an existing
                     * volume-create structure, free it. */
                    if !VolCreate_0.is_null() {
                        LocalFree(VolCreate_0 as HLOCAL);
                    }
                    (*PartItem).VolCreate = core::ptr::null_mut();

                    /* And return */
                    return TRUE as INT_PTR;
                }

                /* We will format: allocate and initialize
                 * a volume-create structure if needed */
                if VolCreate_0.is_null() {
                    VolCreate_0 = LocalAlloc(
                        LPTR as UINT,
                        core::mem::size_of::<_VOL_CREATE_INFO>() as SIZE_T,
                    ) as PVOL_CREATE_INFO;
                }
                if VolCreate_0.is_null() {
                    DPRINT1!("Failed to allocate volume-create structure\n");
                    return TRUE as INT_PTR;
                }

                /* Cached input information that will be set to
                 * the FORMAT_VOLUME_INFO structure given to the
                 * 'FSVOLNOTIFY_STARTFORMAT' step */
                // TODO: Think about which values could be defaulted...
                StringCchCopyW(
                    core::ptr::addr_of_mut!((*VolCreate_0).FileSystemName) as *mut WCHAR as STRSAFE_LPWSTR,
                    (_countof!((*VolCreate_0).FileSystemName)) as _,
                    FileSystem_1 as STRSAFE_LPCWSTR,
                );
                (*VolCreate_0).MediaFlag = FMIFS_HARDDISK;
                (*VolCreate_0).Label = core::ptr::null_mut();
                (*VolCreate_0).QuickFormat = (IsDlgButtonChecked(
                    hDlg,
                    IDC_CHECK_QUICKFMT as ::core::ffi::c_int,
                ) == BST_CHECKED as UINT)
                    as ::core::ffi::c_int as BOOLEAN;
                (*VolCreate_0).ClusterSize = 0;

                /* Set the volume associated to the new create information */
                (*VolCreate_0).Volume = (*PartItem).Volume;

                /* Associate the new, or update the volume create information */
                (*PartItem).VolCreate = VolCreate_0;
                return TRUE as INT_PTR;
            }
        }

        _ => {}
    }

    return FALSE as INT_PTR;
}

unsafe extern "system" fn FormatDlgProc(
    hDlg: HWND,
    uMsg: UINT,
    wParam: WPARAM,
    lParam: LPARAM,
) -> INT_PTR {
    let mut PartCreateCtx: PPARTCREATE_CTX = core::ptr::null_mut();

    /* Retrieve dialog context pointer */
    PartCreateCtx = GetWindowLongPtrW(hDlg, DWLP_USER as ::core::ffi::c_int) as PPARTCREATE_CTX;

    match uMsg {
        WM_INITDIALOG => {
            /* Save dialog context pointer */
            PartCreateCtx = lParam as PPARTCREATE_CTX;
            SetWindowLongPtrW(
                hDlg,
                DWLP_USER as ::core::ffi::c_int,
                PartCreateCtx as LONG_PTR,
            );

            /* We actually want to format, so set the flag */
            (*PartCreateCtx).set_ForceFormat(TRUE as BOOLEAN as BOOLEAN);

            /* In auto-format mode, hide the dialog and simulate press on OK.
             * The file system is preselected by FormatDlgProcWorker(). */
            if (*PartCreateCtx).AutoFormat() != 0 {
                /* Win32 NOTE: No need to first invoke the helper dialog procedure,
                 * before posting our messages. The posted messages are dealt with
                 * *ONLY* after any messages potentially sent to ourselves by the
                 * helper dialog procedure. */
                //INT_PTR ret = FormatDlgProcWorker(PartCreateCtx, hDlg, uMsg, wParam, lParam);
                PostMessageW(
                    hDlg,
                    PM_FMTDLG_SHOWHIDE as UINT,
                    FALSE as WPARAM,
                    0 as LPARAM,
                );
                PostMessageW(
                    hDlg,
                    WM_COMMAND as UINT,
                    MAKEWPARAM!(IDOK, BN_CLICKED) as WPARAM,
                    0 as LPARAM,
                );
                //return ret;
            }
        }

        PM_FMTDLG_SHOWHIDE => {
            ShowWindow(
                hDlg,
                if wParam != 0 { (SW_SHOW as i32) } else { (SW_HIDE as i32) },
            );
        }

        WM_COMMAND => {
            if HIWORD!(wParam) as ::core::ffi::c_int == (BN_CLICKED as i32) {
                's_68: {
                    match (LOWORD!(wParam) as ::core::ffi::c_int) as u32 {
                        IDOK => {
                            /* Retrieve the formatting options */
                            FormatDlgProcWorker(PartCreateCtx, hDlg, uMsg, wParam, lParam);
                        }
                        IDCANCEL => {}
                        _ => {
                            break 's_68;
                        }
                    }
                    EndDialog(hDlg, (LOWORD!(wParam)) as INT_PTR);
                    return TRUE as INT_PTR;
                }
            }
        }

        _ => {}
    }

    return FormatDlgProcWorker(PartCreateCtx, hDlg, uMsg, wParam, lParam);
}

unsafe extern "system" fn PartitionDlgProc(
    hDlg: HWND,
    uMsg: UINT,
    wParam: WPARAM,
    lParam: LPARAM,
) -> INT_PTR {
    let mut PartCreateCtx: PPARTCREATE_CTX;

    /* Retrieve dialog context pointer */
    PartCreateCtx = GetWindowLongPtrW(hDlg, DWLP_USER) as PPARTCREATE_CTX;

    match uMsg {
        WM_INITDIALOG => {
            let mut PartEntry: PPARTENTRY = core::ptr::null_mut();
            let mut DiskEntry: PDISKENTRY = core::ptr::null_mut();
            let mut MaxSizeMB: ULONG;

            /* Save dialog context pointer */
            PartCreateCtx = lParam as PPARTCREATE_CTX;
            SetWindowLongPtrW(hDlg, DWLP_USER, PartCreateCtx as LONG_PTR);

            /* Retrieve the selected partition */
            PartEntry = (*(*PartCreateCtx).PartItem).PartEntry;
            DiskEntry = (*PartEntry).DiskEntry;

            /* Set the spinner to the maximum size in MB the partition can have */
            MaxSizeMB = (*PartCreateCtx).MaxSizeMB;
            SendDlgItemMessageW(
                hDlg,
                (IDC_UPDOWN_PARTSIZE as i32),
                UDM_SETRANGE32,
                1 as WPARAM,
                MaxSizeMB as LPARAM,
            );
            SendDlgItemMessageW(
                hDlg,
                (IDC_UPDOWN_PARTSIZE as i32),
                UDM_SETPOS32,
                0 as WPARAM,
                MaxSizeMB as LPARAM,
            );

            /* Default to regular partition (non-extended on MBR disks) */
            CheckDlgButton(hDlg, (IDC_CHECK_MBREXTPART as i32), BST_UNCHECKED);

            /* Also, disable and hide IDC_CHECK_MBREXTPART
             * if space is logical or the disk is not MBR */
            if (*DiskEntry).DiskStyle == PARTITION_STYLE_MBR
                && (*PartEntry).LogicalPartition == 0
            {
                ShowDlgItem!(hDlg, (IDC_CHECK_MBREXTPART as i32), (SW_SHOW as i32));
                EnableDlgItem!(hDlg, (IDC_CHECK_MBREXTPART as i32), (TRUE as i32));
            } else {
                ShowDlgItem!(hDlg, (IDC_CHECK_MBREXTPART as i32), (SW_HIDE as i32));
                EnableDlgItem!(hDlg, (IDC_CHECK_MBREXTPART as i32), (FALSE as i32));
            }
        }

        WM_COMMAND => {
            if HIWORD!(wParam) == (BN_CLICKED as u16) {
                match (LOWORD!(wParam)) as u32 {
                    IDC_CHECK_MBREXTPART => {
                        /* Check for MBR-extended (container) partition */
                        // BST_UNCHECKED or BST_INDETERMINATE => FALSE
                        if IsDlgButtonChecked(hDlg, (IDC_CHECK_MBREXTPART as i32))
                            == BST_CHECKED
                        {
                            /* It is, disable formatting options */
                            EnableDlgItem!(hDlg, (IDC_FS_STATIC as i32), (FALSE as i32));
                            EnableDlgItem!(hDlg, (IDC_FSTYPE as i32), (FALSE as i32));
                            EnableDlgItem!(hDlg, (IDC_CHECK_QUICKFMT as i32), (FALSE as i32));
                        } else {
                            /* It is not, re-enable formatting options */
                            EnableDlgItem!(hDlg, (IDC_FS_STATIC as i32), (TRUE as i32));
                            EnableDlgItem!(hDlg, (IDC_FSTYPE as i32), (TRUE as i32));
                            EnableDlgItem!(hDlg, (IDC_CHECK_QUICKFMT as i32), (TRUE as i32));
                        }
                        return (TRUE) as INT_PTR;
                    }

                    IDOK => {
                        /* Collect all the information and return it
                         * to the caller for creating the partition */
                        (*PartCreateCtx).PartSizeMB = SendDlgItemMessageW(
                            hDlg,
                            (IDC_UPDOWN_PARTSIZE as i32),
                            UDM_GETPOS32,
                            0,
                            core::ptr::null_mut::<core::ffi::c_void>() as LPARAM,
                        ) as ULONG;
                        (*PartCreateCtx).PartSizeMB = min!(
                            max!((*PartCreateCtx).PartSizeMB, 1),
                            (*PartCreateCtx).MaxSizeMB,
                        );
                        (*PartCreateCtx).MBRExtPart = (IsDlgButtonChecked(
                            hDlg,
                            (IDC_CHECK_MBREXTPART as i32),
                        ) == BST_CHECKED) as BOOLEAN;

                        /* Retrieve the formatting options */
                        FormatDlgProcWorker(PartCreateCtx, hDlg, uMsg, wParam, lParam);

                        /* fallthrough into COMMENT_TOKEN_ECHO____ */
                        EndDialog(hDlg, (LOWORD!(wParam)) as INT_PTR);
                        return (TRUE) as INT_PTR;
                    }
                    IDCANCEL => {
                        EndDialog(hDlg, (LOWORD!(wParam)) as INT_PTR);
                        return (TRUE) as INT_PTR;
                    }
                    _ => {}
                }
            }
        }
        _ => {}
    }

    return FormatDlgProcWorker(PartCreateCtx, hDlg, uMsg, wParam, lParam);
}
#[no_mangle]
pub unsafe extern "C" fn CreateTreeListColumns(
    hInstance: HINSTANCE,
    hWndTreeList: HWND,
    pIDs: *const UINT,
    pColsWidth: *const INT,
    pColsAlign: *const INT,
    nNumOfColumns: UINT,
) -> BOOL {
    let mut i: UINT;
    let mut tlC: TLCOLUMN = core::mem::zeroed();
    let mut szText: [WCHAR; 50] = [0; 50];

    /* Create the columns */
    tlC.mask = LVCF_FMT | LVCF_WIDTH | LVCF_TEXT | LVCF_SUBITEM;
    tlC.pszText = core::ptr::addr_of_mut!(szText) as *mut WCHAR;

    /* Load the column labels from the resource file */
    i = 0;
    while i < nNumOfColumns {
        tlC.iSubItem = i as INT;
        tlC.cx = *pColsWidth.offset(i as isize);
        tlC.fmt = *pColsAlign.offset(i as isize);

        LoadStringW(
            hInstance,
            *pIDs.offset(i as isize),
            core::ptr::addr_of_mut!(szText) as *mut WCHAR,
            (ARRAYSIZE!(szText)) as i32,
        );

        if TreeList_InsertColumn!(hWndTreeList, i as INT, core::ptr::addr_of_mut!(tlC)) == -1 {
            return (FALSE) as BOOL;
        }
        i = i.wrapping_add(1);
    }

    return (TRUE) as BOOL;
}
