// C: `BOOLEAN ForceFormat :1; BOOLEAN AutoFormat :1;` share one storage byte after
// MBRExtPart (bit 0 = ForceFormat, bit 1 = AutoFormat), exposed through bindgen-style
// accessors so the layout and the 1-bit truncation on store match the C exactly.
#[repr(C)]
pub struct _PARTCREATE_CTX {
    pub PartItem: PPARTITEM,
    pub MaxSizeMB: ULONG,
    pub PartSizeMB: ULONG,
    pub MBRExtPart: BOOLEAN,
    pub _bitfield_1: u8,
}
impl _PARTCREATE_CTX {
    #[inline]
    pub fn ForceFormat(&self) -> BOOLEAN {
        self._bitfield_1 & 0x1
    }
    #[inline]
    pub fn set_ForceFormat(&mut self, val: BOOLEAN) {
        self._bitfield_1 = (self._bitfield_1 & !0x1) | (val & 0x1);
    }
    #[inline]
    pub fn AutoFormat(&self) -> BOOLEAN {
        (self._bitfield_1 >> 1) & 0x1
    }
    #[inline]
    pub fn set_AutoFormat(&mut self, val: BOOLEAN) {
        self._bitfield_1 = (self._bitfield_1 & !0x2) | ((val & 0x1) << 1);
    }
}
pub type PARTCREATE_CTX = _PARTCREATE_CTX;
pub type PPARTCREATE_CTX = *mut _PARTCREATE_CTX;

