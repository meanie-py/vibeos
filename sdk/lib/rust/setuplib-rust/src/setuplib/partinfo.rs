#[no_mangle]
pub unsafe extern "system" fn LookupPartitionTypeString(
    PartitionStyle: PARTITION_STYLE,
    PartitionType: PVOID,
) -> PCSTR {
    let mut i: UINT;

    if PartitionStyle == PARTITION_STYLE_MBR {
        i = 0;
        while (i as usize) < _countof!(MbrPartitionTypes) as usize {
            if *(PartitionType as *mut UCHAR) == MbrPartitionTypes[i as usize].Type {
                return MbrPartitionTypes[i as usize].Description;
            }
            i = i.wrapping_add(1);
        }
    }

    return core::ptr::null_mut();
}
