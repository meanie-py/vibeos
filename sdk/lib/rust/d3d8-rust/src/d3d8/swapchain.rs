unsafe extern "C" fn impl_from_IDirect3DSwapChain8(mut iface: *mut IDirect3DSwapChain8) -> *mut d3d8_swapchain {
    return (iface as *mut u8).wrapping_sub(core::mem::offset_of!(d3d8_swapchain, IDirect3DSwapChain8_iface)) as *mut d3d8_swapchain;
}

unsafe extern "system" fn d3d8_swapchain_QueryInterface(iface: *mut IDirect3DSwapChain8, riid: REFIID, out: *mut *mut core::ffi::c_void) -> HRESULT {
    if IsEqualGUID!(riid, core::ptr::addr_of!(IID_IDirect3DSwapChain8)) != false
        || IsEqualGUID!(riid, core::ptr::addr_of!(IID_IUnknown)) != false
    {
        IDirect3DSwapChain8_AddRef(iface);
        *out = iface as *mut core::ffi::c_void;
        return S_OK;
    }

    WARN!("%s not implemented, returning E_NOINTERFACE.\n", debugstr_guid(riid as *const GUID));

    *out = core::ptr::null_mut();
    return E_NOINTERFACE;
}

unsafe extern "system" fn d3d8_swapchain_AddRef(iface: *mut IDirect3DSwapChain8) -> ULONG {
    let swapchain: *mut d3d8_swapchain = impl_from_IDirect3DSwapChain8(iface);
    let mut ref_0: ULONG = InterlockedIncrement(core::ptr::addr_of_mut!((*swapchain).refcount)) as ULONG;

    TRACE!("%p increasing refcount to %lu.\n", iface, ref_0);

    if ref_0 == 1 {
        if !(*swapchain).parent_device.is_null() {
            IDirect3DDevice8_AddRef((*swapchain).parent_device);
        }
        wined3d_swapchain_incref((*swapchain).wined3d_swapchain);
    }

    return ref_0;
}

unsafe extern "system" fn d3d8_swapchain_Release(iface: *mut IDirect3DSwapChain8) -> ULONG {
    let swapchain: *mut d3d8_swapchain = impl_from_IDirect3DSwapChain8(iface);
    let ref_: ULONG = InterlockedDecrement(
        core::ptr::addr_of_mut!((*swapchain).refcount) as *mut ::core::ffi::c_long,
    ) as ULONG;

    if ref_ == 0 {
        let parent_device: *mut IDirect3DDevice8 = (*swapchain).parent_device;

        wined3d_swapchain_decref((*swapchain).wined3d_swapchain);

        if !parent_device.is_null() {
            IDirect3DDevice8_Release(parent_device);
        }
    }
    return ref_;
}
#[no_mangle]
pub unsafe extern "system" fn d3d8_swapchain_Present(
    iface: *mut IDirect3DSwapChain8,
    src_rect: *const RECT,
    dst_rect: *const RECT,
    dst_window_override: HWND,
    dirty_region: *const RGNDATA,
) -> HRESULT {
    let swapchain: *mut d3d8_swapchain = impl_from_IDirect3DSwapChain8(iface);
    let device: *mut d3d8_device = impl_from_IDirect3DDevice8((*swapchain).parent_device);

    TRACE!(
        "iface %p, src_rect %s, dst_rect %s, dst_window_override %p, dirty_region %p.\n",
        iface,
        wine_dbgstr_rect(src_rect),
        wine_dbgstr_rect(dst_rect),
        dst_window_override,
        dirty_region
    );

    if ((*device).device_state) as u32 != D3D8_DEVICE_STATE_OK {
        return D3DERR_DEVICELOST;
    }

    if !dirty_region.is_null() {
        FIXME!("Ignoring dirty_region %p.\n", dirty_region);
    }

    return wined3d_swapchain_present(
        (*swapchain).wined3d_swapchain,
        src_rect,
        dst_rect,
        dst_window_override,
        (*swapchain).swap_interval,
        0,
    );
}
unsafe extern "system" fn d3d8_swapchain_GetBackBuffer(
    iface: *mut IDirect3DSwapChain8,
    backbuffer_idx: UINT,
    backbuffer_type: D3DBACKBUFFER_TYPE,
    backbuffer: *mut *mut IDirect3DSurface8,
) -> HRESULT {
    let swapchain: *mut d3d8_swapchain = impl_from_IDirect3DSwapChain8(iface);
    let mut wined3d_texture: *mut wined3d_texture = core::ptr::null_mut();
    let mut surface_impl: *mut d3d8_surface = core::ptr::null_mut();
    let mut hr: HRESULT = D3D_OK;

    TRACE!(
        "iface %p, backbuffer_idx %u, backbuffer_type %#x, backbuffer %p.\n",
        iface,
        backbuffer_idx,
        backbuffer_type as u32,
        backbuffer
    );

    /* backbuffer_type is ignored by native. */

    if backbuffer.is_null() {
        WARN!("The output pointer is NULL, returning D3DERR_INVALIDCALL.\n");
        return D3DERR_INVALIDCALL;
    }

    wined3d_mutex_lock();
    wined3d_texture = wined3d_swapchain_get_back_buffer((*swapchain).wined3d_swapchain, backbuffer_idx);
    if !wined3d_texture.is_null() {
        surface_impl = wined3d_texture_get_sub_resource_parent(wined3d_texture, 0) as *mut d3d8_surface;
        *backbuffer = core::ptr::addr_of_mut!((*surface_impl).IDirect3DSurface8_iface);
        IDirect3DSurface8_AddRef(*backbuffer);
    } else {
        /* Do not set *backbuffer = NULL, see tests/device.c, test_swapchain(). */
        hr = D3DERR_INVALIDCALL;
    }
    wined3d_mutex_unlock();

    return hr;
}
