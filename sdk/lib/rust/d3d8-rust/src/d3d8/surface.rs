unsafe extern "system" fn d3d8_surface_GetDesc(iface: *mut IDirect3DSurface8, desc: *mut D3DSURFACE_DESC) -> HRESULT {
    let surface: *mut d3d8_surface = impl_from_IDirect3DSurface8(iface);
    let mut wined3d_desc: wined3d_sub_resource_desc = core::mem::zeroed();

    TRACE!("iface %p, desc %p.\n", iface, desc);

    wined3d_mutex_lock();
    wined3d_texture_get_sub_resource_desc((*surface).wined3d_texture, (*surface).sub_resource_idx, core::ptr::addr_of_mut!(wined3d_desc));
    wined3d_mutex_unlock();

    (*desc).Format = d3dformat_from_wined3dformat(wined3d_desc.format);
    (*desc).Type = D3DRTYPE_SURFACE;
    (*desc).Usage = d3dusage_from_wined3dusage(wined3d_desc.usage, wined3d_desc.bind_flags);
    (*desc).Pool = d3dpool_from_wined3daccess(wined3d_desc.access, wined3d_desc.usage);
    (*desc).Size = wined3d_desc.size as UINT;
    (*desc).MultiSampleType = d3dmultisample_type_from_wined3d(wined3d_desc.multisample_type);
    (*desc).Width = wined3d_desc.width as UINT;
    (*desc).Height = wined3d_desc.height as UINT;

    return D3D_OK;
}

unsafe extern "system" fn d3d8_surface_LockRect(
    iface: *mut IDirect3DSurface8,
    locked_rect: *mut D3DLOCKED_RECT,
    rect: *const RECT,
    flags: DWORD,
) -> HRESULT {
    let surface: *mut d3d8_surface = impl_from_IDirect3DSurface8(iface);
    let mut box_: wined3d_box = core::mem::zeroed::<wined3d_box>();
    let mut map_desc: wined3d_map_desc = core::mem::zeroed::<wined3d_map_desc>();
    let mut hr: HRESULT;
    let mut type_: D3DRESOURCETYPE;

    TRACE!(
        "iface %p, locked_rect %p, rect %s, flags %#lx.\n",
        iface,
        locked_rect,
        wine_dbgstr_rect(rect),
        flags
    );

    wined3d_mutex_lock();

    if !(*surface).texture.is_null() {
        type_ = IDirect3DBaseTexture8_GetType(&raw mut (*(*surface).texture).IDirect3DBaseTexture8_iface);
    } else {
        type_ = D3DRTYPE_SURFACE;
    }

    if !rect.is_null() {
        let mut desc: D3DSURFACE_DESC = core::mem::zeroed::<D3DSURFACE_DESC>();
        IDirect3DSurface8_GetDesc(iface, &raw mut desc);

        if type_ != D3DRTYPE_TEXTURE
            && (((*rect).left < 0)
                || ((*rect).top < 0)
                || ((*rect).left >= (*rect).right)
                || ((*rect).top >= (*rect).bottom)
                || ((*rect).right as UINT > desc.Width)
                || ((*rect).bottom as UINT > desc.Height))
        {
            WARN!("Trying to lock an invalid rectangle, returning D3DERR_INVALIDCALL\n");
            wined3d_mutex_unlock();

            (*locked_rect).Pitch = 0;
            (*locked_rect).pBits = core::ptr::null_mut();
            return D3DERR_INVALIDCALL;
        }
        wined3d_box_set(
            &raw mut box_,
            ((*rect).left) as u32,
            ((*rect).top) as u32,
            ((*rect).right) as u32,
            ((*rect).bottom) as u32,
            0,
            1,
        );
    }

    hr = wined3d_resource_map(
        wined3d_texture_get_resource((*surface).wined3d_texture),
        (*surface).sub_resource_idx,
        &raw mut map_desc,
        if !rect.is_null() {
            &raw mut box_
        } else {
            core::ptr::null_mut()
        },
        wined3dmapflags_from_d3dmapflags(flags, 0),
    );
    wined3d_mutex_unlock();

    if hr >= 0 {
        (*locked_rect).Pitch = map_desc.row_pitch as INT;
        (*locked_rect).pBits = map_desc.data;
    } else if type_ != D3DRTYPE_TEXTURE {
        (*locked_rect).Pitch = 0;
        (*locked_rect).pBits = core::ptr::null_mut();
    }

    if hr == E_INVALIDARG {
        return D3DERR_INVALIDCALL;
    }
    return hr;
}

unsafe extern "system" fn d3d8_surface_UnlockRect(iface: *mut IDirect3DSurface8) -> HRESULT {
    let surface: *mut d3d8_surface = impl_from_IDirect3DSurface8(iface);
    let mut hr: HRESULT;

    TRACE!("iface %p.\n", iface);

    hr = wined3d_resource_unmap(wined3d_texture_get_resource((*surface).wined3d_texture), (*surface).sub_resource_idx);

    if hr == WINEDDERR_NOTLOCKED {
        let mut type_: D3DRESOURCETYPE;
        if !(*surface).texture.is_null() {
            type_ = IDirect3DBaseTexture8_GetType(core::ptr::addr_of_mut!((*(*surface).texture).IDirect3DBaseTexture8_iface));
        } else {
            type_ = D3DRTYPE_SURFACE;
        }
        hr = if type_ == D3DRTYPE_TEXTURE { D3D_OK } else { D3DERR_INVALIDCALL };
    }
    return hr;
}

unsafe extern "system" fn surface_wined3d_object_destroyed(parent: *mut ::core::ffi::c_void) {
    let mut surface: *mut d3d8_surface = parent as *mut d3d8_surface;
    d3d8_resource_cleanup(core::ptr::addr_of_mut!((*surface).resource));
    free(surface as *mut ::core::ffi::c_void);
}
#[no_mangle]
pub unsafe extern "C" fn d3d8_surface_create(
    wined3d_texture: *mut wined3d_texture,
    sub_resource_idx: ::core::ffi::c_uint,
    container: *mut IUnknown,
) -> *mut d3d8_surface {
    let mut texture: *mut IDirect3DBaseTexture8 = core::ptr::null_mut();
    let mut surface: *mut d3d8_surface = core::ptr::null_mut();

    surface = calloc(1, (core::mem::size_of::<d3d8_surface>()) as _) as *mut d3d8_surface;
    if surface.is_null() {
        return core::ptr::null_mut();
    }

    (*surface).IDirect3DSurface8_iface.lpVtbl = core::ptr::addr_of!(d3d8_surface_vtbl) as *const IDirect3DSurface8Vtbl;
    d3d8_resource_init(core::ptr::addr_of_mut!((*surface).resource));
    (*surface).resource.refcount = 0;
    list_init(core::ptr::addr_of_mut!((*surface).rtv_entry));
    (*surface).container = container;
    (*surface).wined3d_texture = wined3d_texture;
    (*surface).sub_resource_idx = sub_resource_idx;
    (*surface).swapchain = wined3d_texture_get_swapchain(wined3d_texture);

    if !(*surface).container.is_null()
        && IUnknown_QueryInterface(
            (*surface).container,
            core::ptr::addr_of!(IID_IDirect3DBaseTexture8),
            core::ptr::addr_of_mut!(texture) as *mut *mut ::core::ffi::c_void,
        ) >= 0
    {
        (*surface).texture = unsafe_impl_from_IDirect3DBaseTexture8(texture);
        IDirect3DBaseTexture8_Release(texture);
    }

    wined3d_texture_set_sub_resource_parent(
        wined3d_texture,
        sub_resource_idx,
        (surface).cast(),
        core::ptr::addr_of!(d3d8_surface_wined3d_parent_ops),
    );

    WINE_TRACE!("Created surface %p.\n", surface);

    return surface;
}
unsafe extern "system" fn view_wined3d_object_destroyed(parent: *mut core::ffi::c_void) {
    let mut surface: *mut d3d8_surface = parent as *mut d3d8_surface;
    (*surface).wined3d_rtv = core::ptr::null_mut();
    list_remove(core::ptr::addr_of_mut!((*surface).rtv_entry));
}
#[no_mangle]
pub unsafe extern "C" fn d3d8_surface_get_device(
    surface: *const d3d8_surface,
) -> *mut d3d8_device {
    let mut device: *mut IDirect3DDevice8 = core::ptr::null_mut::<IDirect3DDevice8>();
    device = if !(*surface).texture.is_null() {
        core::ptr::addr_of_mut!((*(*(*surface).texture).parent_device).IDirect3DDevice8_iface)
    } else {
        (*surface).parent_device
    };
    return impl_from_IDirect3DDevice8(device);
}
#[no_mangle]
pub unsafe extern "C" fn d3d8_surface_acquire_rendertarget_view(
    surface: *mut d3d8_surface,
) -> *mut wined3d_rendertarget_view {
    let mut hr: HRESULT;

    /* The surface reference count can be equal to 0 when this function is
     * called. In order to properly manage the render target view reference
     * count, we temporarily increment the surface reference count. */
    d3d8_surface_AddRef(core::ptr::addr_of_mut!((*surface).IDirect3DSurface8_iface));

    if !(*surface).wined3d_rtv.is_null() {
        return (*surface).wined3d_rtv;
    }

    hr = wined3d_rendertarget_view_create_from_sub_resource(
        (*surface).wined3d_texture,
        (*surface).sub_resource_idx,
        surface as *mut core::ffi::c_void,
        core::ptr::addr_of!(d3d8_view_wined3d_parent_ops),
        core::ptr::addr_of_mut!((*surface).wined3d_rtv),
    );
    if hr < 0 {
        ERR!("Failed to create rendertarget view, hr %#lx.\n", hr);
        d3d8_surface_Release(core::ptr::addr_of_mut!((*surface).IDirect3DSurface8_iface));
        return core::ptr::null_mut();
    }

    if !(*surface).texture.is_null() {
        list_add_head(
            core::ptr::addr_of_mut!((*(*surface).texture).rtv_list),
            core::ptr::addr_of_mut!((*surface).rtv_entry),
        );
    }

    return (*surface).wined3d_rtv;
}
#[no_mangle]
pub unsafe extern "C" fn d3d8_surface_release_rendertarget_view(
    mut surface: *mut d3d8_surface,
    mut rtv: *mut wined3d_rendertarget_view,
) {
    if !rtv.is_null() {
        d3d8_surface_Release(core::ptr::addr_of_mut!((*surface).IDirect3DSurface8_iface));
    }
}
#[no_mangle]
pub unsafe extern "C" fn unsafe_impl_from_IDirect3DSurface8(iface: *mut IDirect3DSurface8) -> *mut d3d8_surface {
    if iface.is_null() {
        return core::ptr::null_mut();
    }
    ASSERT!(
        ((*iface).lpVtbl as *const core::ffi::c_void)
            == (core::ptr::addr_of!(d3d8_surface_vtbl) as *const core::ffi::c_void)
    );

    return impl_from_IDirect3DSurface8(iface);
}

