unsafe extern "system" fn d3d8_surface_QueryInterface(iface: *mut IDirect3DSurface8, riid: REFIID, out: *mut *mut core::ffi::c_void) -> HRESULT {
    if IsEqualGUID!(riid, core::ptr::addr_of!(IID_IDirect3DSurface8))
        != false
        || IsEqualGUID!(riid, core::ptr::addr_of!(IID_IDirect3DResource8)) != false
        || IsEqualGUID!(riid, core::ptr::addr_of!(IID_IUnknown)) != false
    {
        IDirect3DSurface8_AddRef(iface);
        *out = iface as *mut core::ffi::c_void;
        return S_OK;
    }

    WARN!("%s not implemented, returning E_NOINTERFACE.\n", debugstr_guid(riid));

    *out = core::ptr::null_mut();
    return E_NOINTERFACE;
}

unsafe extern "system" fn d3d8_surface_AddRef(iface: *mut IDirect3DSurface8) -> ULONG {
    let surface: *mut d3d8_surface = impl_from_IDirect3DSurface8(iface);
    let mut refcount: ULONG;

    if !(*surface).texture.is_null() {
        return IDirect3DBaseTexture8_AddRef(core::ptr::addr_of_mut!((*(*surface).texture).IDirect3DBaseTexture8_iface));
    }

    refcount = InterlockedIncrement(core::ptr::addr_of_mut!((*surface).resource.refcount) as *mut i32) as ULONG;

    if refcount == 1 {
        if !(*surface).parent_device.is_null() {
            IDirect3DDevice8_AddRef((*surface).parent_device);
        }
        if !(*surface).wined3d_rtv.is_null() {
            wined3d_rendertarget_view_incref((*surface).wined3d_rtv);
        }
        wined3d_texture_incref((*surface).wined3d_texture);
        if !(*surface).swapchain.is_null() {
            wined3d_swapchain_incref((*surface).swapchain);
        }
    }

    return refcount;
}

unsafe extern "system" fn d3d8_surface_Release(iface: *mut IDirect3DSurface8) -> ULONG {
    let surface: *mut d3d8_surface = impl_from_IDirect3DSurface8(iface);
    let mut refcount: ULONG;

    if !(*surface).texture.is_null() {
        return IDirect3DBaseTexture8_Release(core::ptr::addr_of_mut!(
            (*(*surface).texture).IDirect3DBaseTexture8_iface
        ));
    }

    if (*surface).resource.refcount == 0 {
        WARN!("Surface does not have any references.\n");
        return 0;
    }

    refcount = InterlockedDecrement(
        core::ptr::addr_of_mut!((*surface).resource.refcount) as *mut LONG,
    ) as ULONG;

    if refcount == 0 {
        let parent_device: *mut IDirect3DDevice8 = (*surface).parent_device;

        if !(*surface).wined3d_rtv.is_null() {
            wined3d_rendertarget_view_decref((*surface).wined3d_rtv);
        }
        if !(*surface).swapchain.is_null() {
            wined3d_swapchain_decref((*surface).swapchain);
        }
        /* Releasing the texture may free the d3d8 object, so do not access it
         * after releasing the texture. */
        wined3d_texture_decref((*surface).wined3d_texture);

        if !parent_device.is_null() {
            IDirect3DDevice8_Release(parent_device);
        }
    }

    return refcount;
}

unsafe extern "system" fn d3d8_surface_GetDevice(iface: *mut IDirect3DSurface8, device: *mut *mut IDirect3DDevice8) -> HRESULT {
    let mut surface: *mut d3d8_surface = impl_from_IDirect3DSurface8(iface);

    if !(*surface).texture.is_null() {
        return IDirect3DBaseTexture8_GetDevice(core::ptr::addr_of_mut!((*(*surface).texture).IDirect3DBaseTexture8_iface), device);
    }

    *device = (*surface).parent_device;
    IDirect3DDevice8_AddRef(*device);

    return D3D_OK;
}

