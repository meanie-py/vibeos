pub unsafe extern "C" fn setup_richedit_olecallback(hEditorWnd: HWND) -> HRESULT {
    let hr: HRESULT = StgCreateDocfile(
        core::ptr::null_mut(),
        STGM_READWRITE | STGM_SHARE_EXCLUSIVE | STGM_DELETEONRELEASE,
        0,
        core::ptr::addr_of_mut!(olecallback.stg),
    );

    SendMessageW(
        hEditorWnd,
        EM_SETOLECALLBACK,
        0,
        core::ptr::addr_of_mut!(olecallback) as LPARAM,
    );
    return hr;
}

