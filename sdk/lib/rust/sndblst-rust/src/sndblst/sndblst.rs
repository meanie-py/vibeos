#[no_mangle]
pub unsafe extern "C" fn FoundDevice(DeviceType: UCHAR, DevicePath: PWSTR) -> BOOLEAN {
    let mut Result: MMRESULT;
    let mut SoundDevice: PSOUND_DEVICE = core::ptr::null_mut();
    let mut FuncTable: MMFUNCTION_TABLE = core::mem::zeroed();
    let mut PathCopy: PWSTR;

    SND_TRACE!(RUSTCONV_WSTR_A122E5DAF3ED.as_ptr(), DevicePath);

    PathCopy = AllocateWideString!(wcslen(DevicePath));

    if PathCopy.is_null() {
        return (FALSE) as BOOLEAN;
    }

    CopyWideString!(PathCopy, DevicePath);

    Result = ListSoundDevice(DeviceType as MMDEVICE_TYPE, PathCopy as PVOID, core::ptr::addr_of_mut!(SoundDevice));

    if MMSUCCESS!(Result) == 0 {
        return (FALSE) as BOOLEAN;
    }

    /* Set up our function table */
    ZeroMemory!(
        core::ptr::addr_of_mut!(FuncTable) as *mut core::ffi::c_void,
        core::mem::size_of::<MMFUNCTION_TABLE>() as usize,
    );
    FuncTable.__bindgen_anon_1.GetCapabilities = Some(
        GetSoundBlasterDeviceCapabilities
            as unsafe extern "C" fn(PSOUND_DEVICE, DWORD, PVOID, DWORD) -> MMRESULT,
    ) as MMGETCAPS_FUNC;
    FuncTable.QueryWaveFormatSupport = Some(
        QueryNt4WaveDeviceFormatSupport
            as unsafe extern "C" fn(PSOUND_DEVICE, LPWAVEFORMATEX, DWORD) -> MMRESULT,
    ) as MMWAVEQUERYFORMATSUPPORT_FUNC;
    FuncTable.SetWaveFormat = Some(
        SetNt4WaveDeviceFormat
            as unsafe extern "C" fn(PSOUND_DEVICE_INSTANCE, DWORD, LPWAVEFORMATEX, DWORD) -> MMRESULT,
    ) as MMWAVESETFORMAT_FUNC;
    FuncTable.Open = Some(
        OpenNt4SoundDevice as unsafe extern "C" fn(PSOUND_DEVICE, *mut PVOID) -> MMRESULT,
    ) as MMOPEN_FUNC;
    FuncTable.Close = Some(
        CloseNt4SoundDevice as unsafe extern "C" fn(PSOUND_DEVICE_INSTANCE, PVOID) -> MMRESULT,
    ) as MMCLOSE_FUNC;
    FuncTable.CommitWaveBuffer = Some(
        WriteFileEx_Committer
            as unsafe extern "C" fn(
                PSOUND_DEVICE_INSTANCE,
                PVOID,
                DWORD,
                PSOUND_OVERLAPPED,
                LPOVERLAPPED_COMPLETION_ROUTINE,
            ) -> MMRESULT,
    ) as WAVE_COMMIT_FUNC;
    //FuncTable.SubmitWaveHeaderToDevice = SubmitWaveHeaderToDevice;

    SetSoundDeviceFunctionTable(SoundDevice, core::ptr::addr_of_mut!(FuncTable));

    return (TRUE) as BOOLEAN;
}

