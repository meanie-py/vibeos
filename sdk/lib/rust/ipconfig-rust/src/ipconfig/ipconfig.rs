unsafe extern "C" fn DisplayDnsRecord(mut pszName: PWSTR, mut wType: WORD) {
    let mut pQueryResults: PDNS_RECORDW = core::ptr::null_mut();
    let mut pThisRecord: PDNS_RECORDW;
    let mut pNextRecord: PDNS_RECORDW;
    let mut szBuffer: [WCHAR; 48] = [0; 48];
    let mut Addr4: IN_ADDR = core::mem::zeroed();
    let mut Addr6: IN6_ADDR = core::mem::zeroed();
    let mut Status: DNS_STATUS;

    ConResPrintf(StdOut, IDS_DNSNAME, pszName);
    ConResPrintf(StdOut, IDS_DNSLINE);

    pQueryResults = core::ptr::null_mut();
    Status = DnsQuery_W(pszName,
                        wType,
                        DNS_QUERY_NO_WIRE_QUERY,
                        core::ptr::null_mut(),
                        core::ptr::addr_of_mut!(pQueryResults) as *mut PDNS_RECORD,
                        core::ptr::null_mut());
    if Status != ERROR_SUCCESS {
        if Status == DNS_ERROR_RCODE_NAME_ERROR {
            ConResPrintf(StdOut, IDS_DNSNONAME);
        } else if Status == DNS_INFO_NO_RECORDS {
            ConResPrintf(StdOut, IDS_DNSNORECORD, GetRecordTypeName(wType));
        }
        return;
    }

    pThisRecord = pQueryResults;
    while !pThisRecord.is_null() {
        pNextRecord = (*pThisRecord).pNext as PDNS_RECORDW;

        ConResPrintf(StdOut, IDS_DNSRECORDNAME, (*pThisRecord).pName);
        ConResPrintf(StdOut, IDS_DNSRECORDTYPE, (*pThisRecord).wType as ::core::ffi::c_int);
        ConResPrintf(StdOut, IDS_DNSRECORDTTL, (*pThisRecord).dwTtl);
        ConResPrintf(StdOut, IDS_DNSRECORDLENGTH, (*pThisRecord).wDataLength as ::core::ffi::c_int);

        match ((*pThisRecord).Flags.S.Section() as ::core::ffi::c_int) as u32 {
            DnsSectionQuestion => {
                ConResPrintf(StdOut, IDS_DNSSECTIONQUESTION);
            }
            DnsSectionAnswer => {
                ConResPrintf(StdOut, IDS_DNSSECTIONANSWER);
            }
            DnsSectionAuthority => {
                ConResPrintf(StdOut, IDS_DNSSECTIONAUTHORITY);
            }
            DnsSectionAdditional => {
                ConResPrintf(StdOut, IDS_DNSSECTIONADDITIONAL);
            }
            _ => {}
        }

        match ((*pThisRecord).wType as ::core::ffi::c_int) as u32 {
            DNS_TYPE_A => {
                Addr4.S_un.S_addr = (*pThisRecord).Data.A.IpAddress as ULONG;
                RtlIpv4AddressToStringW(core::ptr::addr_of_mut!(Addr4), szBuffer.as_mut_ptr());
                ConResPrintf(StdOut, IDS_DNSTYPEA, szBuffer.as_mut_ptr());
            }
            DNS_TYPE_NS => {
                ConResPrintf(StdOut, IDS_DNSTYPENS, (*pThisRecord).Data.NS.pNameHost);
            }
            DNS_TYPE_CNAME => {
                ConResPrintf(StdOut, IDS_DNSTYPECNAME, (*pThisRecord).Data.CNAME.pNameHost);
            }
            DNS_TYPE_SOA => {
                ConResPrintf(StdOut, IDS_DNSTYPESOA1,
                             (*pThisRecord).Data.SOA.pNamePrimaryServer,
                             (*pThisRecord).Data.SOA.pNameAdministrator,
                             (*pThisRecord).Data.SOA.dwSerialNo);
                ConResPrintf(StdOut, IDS_DNSTYPESOA2,
                             (*pThisRecord).Data.SOA.dwRefresh,
                             (*pThisRecord).Data.SOA.dwRetry,
                             (*pThisRecord).Data.SOA.dwExpire,
                             (*pThisRecord).Data.SOA.dwDefaultTtl);
            }
            DNS_TYPE_PTR => {
                ConResPrintf(StdOut, IDS_DNSTYPEPTR, (*pThisRecord).Data.PTR.pNameHost);
            }
            DNS_TYPE_MX => {
                ConResPrintf(StdOut, IDS_DNSTYPEMX,
                             (*pThisRecord).Data.MX.pNameExchange,
                             (*pThisRecord).Data.MX.wPreference as ::core::ffi::c_int,
                             (*pThisRecord).Data.MX.Pad as ::core::ffi::c_int);
            }
            DNS_TYPE_AAAA => {
                RtlCopyMemory!(core::ptr::addr_of_mut!(Addr6) as *mut ::core::ffi::c_void,
                              core::ptr::addr_of!((*pThisRecord).Data.AAAA.Ip6Address) as *const ::core::ffi::c_void,
                              core::mem::size_of::<IN6_ADDR>() as size_t);
                RtlIpv6AddressToStringW(core::ptr::addr_of_mut!(Addr6), szBuffer.as_mut_ptr());
                ConResPrintf(StdOut, IDS_DNSTYPEAAAA, szBuffer.as_mut_ptr());
            }
            DNS_TYPE_ATMA => {
                ConResPrintf(StdOut, IDS_DNSTYPEATMA);
            }
            DNS_TYPE_SRV => {
                ConResPrintf(StdOut, IDS_DNSTYPESRV,
                             (*pThisRecord).Data.SRV.pNameTarget,
                             (*pThisRecord).Data.SRV.wPriority as ::core::ffi::c_int,
                             (*pThisRecord).Data.SRV.wWeight as ::core::ffi::c_int,
                             (*pThisRecord).Data.SRV.wPort as ::core::ffi::c_int);
            }
            _ => {}
        }
        ConPuts(StdOut, RUSTCONV_WSTR_9D313EA1711F.as_ptr());

        pThisRecord = pNextRecord;
    }

    DnsRecordListFree(pQueryResults as PDNS_RECORD, DnsFreeRecordList);
}
#[no_mangle]
pub unsafe extern "C" fn DisplayDns() {
    let mut DnsEntry: PDNS_CACHE_ENTRY = core::ptr::null_mut::<_DNS_CACHE_ENTRY>();
    let mut pThisEntry: PDNS_CACHE_ENTRY;
    let mut pNextEntry: PDNS_CACHE_ENTRY;

    ConResPrintf(StdOut, IDS_HEADER);

    if DnsGetCacheDataTable(core::ptr::addr_of_mut!(DnsEntry)) == 0 {
        DoFormatMessage(GetLastError() as LONG);
        return;
    }

    if DnsEntry.is_null() {
        return;
    }

    pThisEntry = DnsEntry;
    while !pThisEntry.is_null() {
        pNextEntry = (*pThisEntry).pNext as PDNS_CACHE_ENTRY;

        if (*pThisEntry).wType1 as ::core::ffi::c_int != (DNS_TYPE_ZERO as i32) {
            DisplayDnsRecord((*pThisEntry).pszName, (*pThisEntry).wType1 as WORD);
        }

        if (*pThisEntry).wType2 as ::core::ffi::c_int != (DNS_TYPE_ZERO as i32) {
            DisplayDnsRecord((*pThisEntry).pszName, (*pThisEntry).wType2 as WORD);
        }

        if !(*pThisEntry).pszName.is_null() {
            LocalFree((*pThisEntry).pszName as HLOCAL);
        }
        LocalFree(pThisEntry as HLOCAL);

        pThisEntry = pNextEntry;
    }
}
