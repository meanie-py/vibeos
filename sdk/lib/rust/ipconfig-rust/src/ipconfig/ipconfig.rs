#[no_mangle]
pub unsafe extern "C" fn timeToStr(mut TimeStamp: time_t) -> PWSTR {
    let mut ptm: *mut tm = core::ptr::null_mut();
    let mut SystemTime: SYSTEMTIME = core::mem::zeroed();
    let mut DateCchSize: INT = 0;
    let mut TimeCchSize: INT = 0;
    let mut TotalCchSize: INT = 0;
    let mut i: INT = 0;
    let mut DateTimeString: PWSTR = core::ptr::null_mut();
    let mut psz: PWSTR = core::ptr::null_mut();

    /* Convert Unix time to SYSTEMTIME */
    /* localtime_s may be preferred if available */
    ptm = localtime(core::ptr::addr_of_mut!(TimeStamp));
    if ptm.is_null() {
        return core::ptr::null_mut();
    }
    SystemTime.wYear = ((*ptm).tm_year + 1900) as WORD;
    SystemTime.wMonth = ((*ptm).tm_mon + 1) as WORD;
    SystemTime.wDay = (*ptm).tm_mday as WORD;
    SystemTime.wHour = (*ptm).tm_hour as WORD;
    SystemTime.wMinute = (*ptm).tm_min as WORD;
    SystemTime.wSecond = (*ptm).tm_sec as WORD;

    /* Get total size in characters required of buffer */
    DateCchSize = GetDateFormatW(
        LOCALE_USER_DEFAULT,
        DATE_LONGDATE,
        core::ptr::addr_of_mut!(SystemTime),
        core::ptr::null::<WCHAR>(),
        core::ptr::null_mut::<WCHAR>(),
        0,
    ) as INT;
    if DateCchSize == 0 {
        return core::ptr::null_mut();
    }
    TimeCchSize = GetTimeFormatW(
        LOCALE_USER_DEFAULT,
        0,
        core::ptr::addr_of_mut!(SystemTime),
        core::ptr::null::<WCHAR>(),
        core::ptr::null_mut::<WCHAR>(),
        0,
    ) as INT;
    if TimeCchSize == 0 {
        return core::ptr::null_mut();
    }
    /* Two terminating null are included, the first one will be replaced by space */
    TotalCchSize = DateCchSize + TimeCchSize;

    /* Allocate buffer and format datetime string */
    DateTimeString = HeapAlloc(
        ProcessHeap,
        0 as DWORD,
        (TotalCchSize as SIZE_T).wrapping_mul(core::mem::size_of::<WCHAR>() as SIZE_T),
    ) as PWSTR;
    if DateTimeString.is_null() {
        return core::ptr::null_mut();
    }

    /* Get date string */
    i = GetDateFormatW(
        LOCALE_USER_DEFAULT,
        DATE_LONGDATE,
        core::ptr::addr_of_mut!(SystemTime),
        core::ptr::null::<WCHAR>(),
        DateTimeString as LPWSTR,
        TotalCchSize as ::core::ffi::c_int,
    ) as INT;
    if i != 0 {
        /* Append space and move pointer */
        *DateTimeString.offset((i as ::core::ffi::c_int - 1) as isize) =
            0x0020u16;
        psz = DateTimeString.offset(i as isize);
        TotalCchSize -= i;

        /* Get time string */
        if GetTimeFormatW(
            LOCALE_USER_DEFAULT,
            0,
            core::ptr::addr_of_mut!(SystemTime),
            core::ptr::null::<WCHAR>(),
            psz as LPWSTR,
            TotalCchSize as ::core::ffi::c_int,
        ) != 0
        {
            return DateTimeString;
        }
    }

    HeapFree(ProcessHeap, 0 as DWORD, DateTimeString as PVOID);
    return core::ptr::null_mut();
}
