#[no_mangle]
pub unsafe extern "C" fn GetUnicodeAdapterName(mut pszAnsiName: PSTR) -> PWSTR {
    let mut pszUnicodeName: PWSTR = core::ptr::null_mut::<WCHAR>();
    let mut i: size_t = 0;
    let mut len: size_t = 0;
    len = strlen(pszAnsiName as *const core::ffi::c_char);
    pszUnicodeName = HeapAlloc(
        GetProcessHeap(),
        0 as DWORD,
        (len as SIZE_T)
            .wrapping_add(1 as SIZE_T)
            .wrapping_mul(core::mem::size_of::<WCHAR>() as SIZE_T),
    ) as PWSTR;
    if pszUnicodeName.is_null() {
        return core::ptr::null_mut::<WCHAR>();
    }
    i = 0 as size_t;
    while i < len {
        *pszUnicodeName.offset(i as isize) = *pszAnsiName.offset(i as isize) as WCHAR;
        i = i.wrapping_add(1);
    }
    *pszUnicodeName.offset(i as isize) = UNICODE_NULL as WCHAR;
    return pszUnicodeName;
}
