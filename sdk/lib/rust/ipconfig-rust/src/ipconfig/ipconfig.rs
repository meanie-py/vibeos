#[no_mangle]
pub unsafe extern "C" fn SetClassId(mut pszAdapterName: PWSTR, mut pszClassId: PWSTR) {
    let mut pAdapterInfo: PIP_ADAPTER_INFO = core::ptr::null_mut();
    let mut pAdapter: PIP_ADAPTER_INFO = core::ptr::null_mut();
    let mut pFoundAdapter: PIP_ADAPTER_INFO = core::ptr::null_mut();
    let mut adaptOutBufLen: ULONG = 0;
    let mut ret: ULONG = 0;
    let mut szFriendlyName: [WCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut szKeyName: [WCHAR; 256] = [0; 256];
    let mut szUnicodeAdapterName: [WCHAR; (MAX_ADAPTER_NAME_LENGTH + 4) as _] =
        [0; (MAX_ADAPTER_NAME_LENGTH + 4) as _];
    let mut mibEntry: MIB_IFROW = core::mem::zeroed();
    let mut hKey: HKEY = core::ptr::null_mut();
    let mut PnpEvent: DHCP_PNP_EVENT = core::mem::zeroed();

    ConResPrintf(StdOut, IDS_HEADER);

    /* call GetAdaptersInfo to obtain the adapter info */
    ret = GetAdaptersInfo(pAdapterInfo, core::ptr::addr_of_mut!(adaptOutBufLen)) as ULONG;
    if ret != ERROR_BUFFER_OVERFLOW {
        DoFormatMessage(ret as LONG);
        return;
    }

    pAdapterInfo = HeapAlloc(ProcessHeap, 0, (adaptOutBufLen) as SIZE_T)
        as *mut IP_ADAPTER_INFO as PIP_ADAPTER_INFO;
    if pAdapterInfo.is_null() {
        DoFormatMessage((ERROR_NOT_ENOUGH_MEMORY) as LONG);
        return;
    }

    'done: {
        ret = GetAdaptersInfo(pAdapterInfo, core::ptr::addr_of_mut!(adaptOutBufLen)) as ULONG;
        if ret != NO_ERROR {
            DoFormatMessage(0);
            break 'done;
        }

        pAdapter = pAdapterInfo;
        while !pAdapter.is_null() {
            GetAdapterFriendlyName(
                core::ptr::addr_of_mut!((*pAdapter).AdapterName) as PSTR,
                MAX_PATH,
                core::ptr::addr_of_mut!(szFriendlyName) as PWSTR,
            );

            if MatchWildcard(
                pszAdapterName,
                core::ptr::addr_of_mut!(szFriendlyName) as PWSTR,
            ) != 0
            {
                mibEntry.dwIndex = (*pAdapter).Index;
                GetIfEntry(core::ptr::addr_of_mut!(mibEntry));

                if mibEntry.dwOperStatus == (MIB_IF_OPER_STATUS_CONNECTED as u32)
                    || mibEntry.dwOperStatus == (MIB_IF_OPER_STATUS_OPERATIONAL as u32)
                {
                    pFoundAdapter = pAdapter;
                    break;
                }
            }

            pAdapter = (*pAdapter).Next;
        }

        if !pFoundAdapter.is_null() {
            _swprintf(
                core::ptr::addr_of_mut!(szKeyName) as PWSTR,
                RUSTCONV_WSTR_05F9D79DDD82.as_ptr(),
                core::ptr::addr_of_mut!((*pFoundAdapter).AdapterName) as PSTR,
            );

            ret = RegOpenKeyExW(
                HKEY_LOCAL_MACHINE,
                core::ptr::addr_of_mut!(szKeyName) as PCWSTR,
                0,
                KEY_WRITE,
                core::ptr::addr_of_mut!(hKey),
            ) as ULONG;
            if ret != ERROR_SUCCESS {
                ConResPrintf(
                    StdOut,
                    IDS_DHCPSETIDERROR,
                    core::ptr::addr_of_mut!(szFriendlyName) as PWSTR,
                );
                DoFormatMessage(ret as LONG);
                break 'done;
            }

            if pszClassId.is_null() {
                pszClassId = RUSTCONV_WSTR_96A296D224F2.as_ptr() as PWSTR;
            }

            ret = RegSetValueExW(
                hKey,
                RUSTCONV_WSTR_2BE140FBE846.as_ptr(),
                0,
                REG_SZ,
                pszClassId as PBYTE,
                ((wcslen(pszClassId) + 1)
                    * core::mem::size_of::<WCHAR>()) as DWORD,
            ) as ULONG;
            RegCloseKey(hKey);
            if ret != ERROR_SUCCESS {
                ConResPrintf(
                    StdOut,
                    IDS_DHCPSETIDERROR,
                    core::ptr::addr_of_mut!(szFriendlyName) as PWSTR,
                );
                DoFormatMessage(ret as LONG);
                break 'done;
            }

            mbstowcs(
                core::ptr::addr_of_mut!(szUnicodeAdapterName) as *mut wchar_t,
                (core::ptr::addr_of_mut!((*pFoundAdapter).AdapterName) as *const core::ffi::c_char).cast(),
                strlen(
                    core::ptr::addr_of_mut!((*pFoundAdapter).AdapterName) as *const core::ffi::c_char,
                ) + 1,
            );

            ZeroMemory!(
                core::ptr::addr_of_mut!(PnpEvent) as *mut core::ffi::c_void,
                core::mem::size_of::<DHCP_PNP_EVENT>(),
            );
            PnpEvent.Unknown5 = 1;

            ret = DhcpHandlePnPEvent(
                0,
                1,
                core::ptr::addr_of_mut!(szUnicodeAdapterName) as PWSTR,
                core::ptr::addr_of_mut!(PnpEvent) as DWORD,
                0,
            ) as ULONG;
            if ret != ERROR_SUCCESS {
                ConResPrintf(
                    StdOut,
                    IDS_DHCPSETIDERROR,
                    core::ptr::addr_of_mut!(szFriendlyName) as PWSTR,
                );
                DoFormatMessage(ret as LONG);
                break 'done;
            }

            ConResPrintf(
                StdOut,
                IDS_DHCPSETIDSUCCESS,
                core::ptr::addr_of_mut!(szFriendlyName) as PWSTR,
            );
        } else {
            ConResPrintf(StdOut, IDS_DHCPNOADAPTER);
        }
    }

    if !pAdapterInfo.is_null() {
        HeapFree(
            ProcessHeap,
            0,
            pAdapterInfo as *mut core::ffi::c_void,
        );
    }
}
#[no_mangle]
pub unsafe extern "C" fn Usage(mut Error: BOOL) {
    if Error != 0 {
        ConResPrintf(core::ptr::addr_of_mut!(csStdOut), IDS_CMDLINEERROR as UINT);
    }
    ConResPrintf(core::ptr::addr_of_mut!(csStdOut), IDS_USAGE as UINT);
}
#[no_mangle]
pub unsafe extern "C" fn wmain(argc: i32, argv: *mut *mut wchar_t) -> i32 {
    let mut DoUsage: BOOL = (FALSE as i32);
    let mut DoAll: BOOL = (FALSE as i32);
    let mut DoRelease: BOOL = (FALSE as i32);
    let mut DoRenew: BOOL = (FALSE as i32);
    let mut DoFlushdns: BOOL = (FALSE as i32);
    let mut DoRegisterdns: BOOL = (FALSE as i32);
    let mut DoDisplaydns: BOOL = (FALSE as i32);
    let mut DoShowclassid: BOOL = (FALSE as i32);
    let mut DoSetclassid: BOOL = (FALSE as i32);

    /* Initialize the Console Standard Streams */
    ConInitStdStreams();

    hInstance = GetModuleHandle(core::ptr::null_mut()) as HINSTANCE;
    ProcessHeap = GetProcessHeap();

    /* Parse command line for options we have been given. */
    if (argc > 1)
        && (*(*argv.offset(1 as isize)).offset(0 as isize) == 0x002Fu16
            || *(*argv.offset(1 as isize)).offset(0 as isize) == 0x002Du16)
    {
        if _wcsicmp(
            (*argv.offset(1 as isize)).offset(1 as isize),
            RUSTCONV_WSTR_1B9E0FE7B740.as_ptr(),
        ) == 0
        {
            DoUsage = (TRUE as i32);
        }
        else if _wcsnicmp(
            (*argv.offset(1 as isize)).offset(1 as isize),
            RUSTCONV_WSTR_7EF8D2448D12.as_ptr(),
            wcslen((*argv.offset(1 as isize)).offset(1 as isize)) as usize,
        ) == 0
        {
            DoAll = (TRUE as i32);
        }
        else if _wcsnicmp(
            (*argv.offset(1 as isize)).offset(1 as isize),
            RUSTCONV_WSTR_EC0B2C212C7C.as_ptr(),
            wcslen((*argv.offset(1 as isize)).offset(1 as isize)) as usize,
        ) == 0
        {
            DoRelease = (TRUE as i32);
        }
        else if _wcsnicmp(
            (*argv.offset(1 as isize)).offset(1 as isize),
            RUSTCONV_WSTR_1DB56BA260C1.as_ptr(),
            wcslen((*argv.offset(1 as isize)).offset(1 as isize)) as usize,
        ) == 0
        {
            DoRenew = (TRUE as i32);
        }
        else if _wcsnicmp(
            (*argv.offset(1 as isize)).offset(1 as isize),
            RUSTCONV_WSTR_80A18E96690C.as_ptr(),
            wcslen((*argv.offset(1 as isize)).offset(1 as isize)) as usize,
        ) == 0
        {
            DoFlushdns = (TRUE as i32);
        }
        else if _wcsnicmp(
            (*argv.offset(1 as isize)).offset(1 as isize),
            RUSTCONV_WSTR_76795DC15899.as_ptr(),
            wcslen((*argv.offset(1 as isize)).offset(1 as isize)) as usize,
        ) == 0
        {
            DoRegisterdns = (TRUE as i32);
        }
        else if _wcsnicmp(
            (*argv.offset(1 as isize)).offset(1 as isize),
            RUSTCONV_WSTR_EFD5F2F18F7F.as_ptr(),
            wcslen((*argv.offset(1 as isize)).offset(1 as isize)) as usize,
        ) == 0
        {
            DoDisplaydns = (TRUE as i32);
        }
        else if _wcsnicmp(
            (*argv.offset(1 as isize)).offset(1 as isize),
            RUSTCONV_WSTR_A85D9911EC10.as_ptr(),
            wcslen((*argv.offset(1 as isize)).offset(1 as isize)) as usize,
        ) == 0
        {
            DoShowclassid = (TRUE as i32);
        }
        else if _wcsnicmp(
            (*argv.offset(1 as isize)).offset(1 as isize),
            RUSTCONV_WSTR_0EE6A07E0CD6.as_ptr(),
            wcslen((*argv.offset(1 as isize)).offset(1 as isize)) as usize,
        ) == 0
        {
            DoSetclassid = (TRUE as i32);
        }
    }

    if argc == 1 {
        /* Default behaviour if no options are given*/
        ShowInfo((TRUE) as BOOL, (FALSE) as BOOL);
    }
    else if argc == 2 {
        /* Process all the options that take no parameters */
        if DoUsage != 0 {
            Usage((FALSE) as BOOL);
        }
        else if DoAll != 0 {
            ShowInfo((TRUE) as BOOL, (TRUE) as BOOL);
        }
        else if DoRelease != 0 {
            Release(core::ptr::null_mut());
        }
        else if DoRenew != 0 {
            Renew(core::ptr::null_mut());
        }
        else if DoFlushdns != 0 {
            FlushDns();
        }
        else if DoRegisterdns != 0 {
            RegisterDns();
        }
        else if DoDisplaydns != 0 {
            DisplayDns();
        }
        else {
            Usage((TRUE) as BOOL);
        }
    }
    else if argc == 3 {
        /* Process all the options that can have 1 parameter */
        if DoRelease != 0 {
            Release(*argv.offset(2 as isize));
        }
        else if DoRenew != 0 {
            Renew(*argv.offset(2 as isize));
        }
        else if DoShowclassid != 0 {
            ShowClassId(*argv.offset(2 as isize));
        }
        else if DoSetclassid != 0 {
            SetClassId(*argv.offset(2 as isize), core::ptr::null_mut());
        }
        else {
            Usage((TRUE) as BOOL);
        }
    }
    else if argc == 4 {
        /* Process all the options that can have 2 parameters */
        if DoSetclassid != 0 {
            SetClassId(*argv.offset(2 as isize), *argv.offset(3 as isize));
        }
        else {
            Usage((TRUE) as BOOL);
        }
    }
    else {
        Usage((TRUE) as BOOL);
    }

    return 0;
}
