unsafe extern "C" fn IsSwitch(Switch: LPCWSTR, Arg: LPCWSTR) -> BOOL {
    if *Arg == '/' as u16 || *Arg == '-' as u16 {
        return (lstrcmpiW(Arg.add(1), Switch) == 0) as BOOL;
    }
    return (FALSE) as BOOL;
}

unsafe extern "C" fn OpenControlPanelItem(Name: LPCWSTR, Page: LPCWSTR) -> HRESULT {
    let mut hr: HRESULT = CoInitialize(core::ptr::null_mut());
    if hr >= 0 {
        let mut pOCP: *mut IOpenControlPanel = core::ptr::null_mut();
        hr = CoCreateInstance(
            core::ptr::addr_of!(CLSID_OpenControlPanel),
            core::ptr::null_mut(),
            CLSCTX_INPROC_SERVER,
            core::ptr::addr_of!(IID_IOpenControlPanel),
            core::ptr::addr_of_mut!(pOCP) as *mut LPVOID,
        );
        if hr >= 0 {
            hr = IOpenControlPanel_Open(pOCP, Name, Page, core::ptr::null_mut());
            IOpenControlPanel_Release(pOCP);
        }
        CoUninitialize();
    }
    return hr;
}

