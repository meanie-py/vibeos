unsafe extern "C" fn OpenUserAccounts() -> BOOL {
    let mut szPath: [WCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];

    GetSystemDirectoryW(szPath.as_mut_ptr(), _countof!(szPath) as UINT);
    PathAppendW(szPath.as_mut_ptr(), RUSTCONV_WSTR_EFB995918895.as_ptr());
    if IsOS(OS_ANYSERVER as DWORD) != 0
        && (ShellExec!(szPath.as_mut_ptr() as LPCWSTR, core::ptr::null_mut()) != false)
    {
        return (TRUE) as BOOL;
    }

    /*
     * TODO: OpenControlPanelItem(L"Microsoft.UserAccounts", NULL) on Vista+ (needs usercpl.dll)
     * See: https://learn.microsoft.com/en-us/windows/win32/shell/controlpanel-canonical-names#user-accounts
     */

    GetSystemDirectoryW(szPath.as_mut_ptr(), _countof!(szPath) as UINT);
    PathAppendW(szPath.as_mut_ptr(), RUSTCONV_WSTR_A53D83495E63.as_ptr()); /* The name used on WinXP */
    if PathFileExistsW(szPath.as_mut_ptr() as LPCWSTR) != 0
        && RunControlPanel(szPath.as_mut_ptr() as LPCWSTR) != 0
    {
        return (TRUE) as BOOL;
    }

    return RunControlPanel(RUSTCONV_WSTR_6B6359AAE07B.as_ptr()) as BOOL; /* ROS specific name (CORE-10226) */
}

