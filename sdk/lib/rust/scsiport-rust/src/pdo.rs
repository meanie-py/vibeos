unsafe fn PdoHandleQueryInstanceId(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
) -> NTSTATUS {
    let lunExt = (*DeviceObject).DeviceExtension as *mut SCSI_PORT_LUN_EXTENSION;
    let mut Buffer: [WCHAR; 26] = [0; 26];
    let mut Length: ULONG;
    let mut InstanceId: LPWSTR;

    const FORMAT: [WCHAR; 7] = [
        b'%' as WCHAR,
        b'x' as WCHAR,
        b'%' as WCHAR,
        b'x' as WCHAR,
        b'%' as WCHAR,
        b'x' as WCHAR,
        0,
    ];
    swprintf(
        &raw mut Buffer as *mut WCHAR,
        &FORMAT as *const WCHAR,
        (*lunExt).PathId as i32,
        (*lunExt).TargetId as i32,
        (*lunExt).Lun as i32,
    );
    Length = wcslen(&raw mut Buffer as *mut WCHAR).wrapping_add(1) as ULONG;
    InstanceId = ExAllocatePoolWithTag(
        PagedPool,
        (Length as SIZE_T).wrapping_mul(core::mem::size_of::<WCHAR>() as SIZE_T),
        TAG_SCSIPORT as ULONG,
    ) as LPWSTR;
    if InstanceId.is_null() {
        (*Irp).IoStatus.Information = (0 as ULONG_PTR) as _;
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    wcscpy(InstanceId as *mut WCHAR, &raw mut Buffer as *mut WCHAR);
    (*Irp).IoStatus.Information = (InstanceId as ULONG_PTR) as _;
    return STATUS_SUCCESS;
}
unsafe fn PdoHandleDeviceRelations(
    DeviceObject: *mut DEVICE_OBJECT,
    Irp: *mut IRP,
) -> NTSTATUS {
    let mut deviceRelations: *mut DEVICE_RELATIONS;
    let ioStack: *mut IO_STACK_LOCATION = IoGetCurrentIrpStackLocation(Irp);

    if (*ioStack).Parameters.QueryDeviceRelations.Type != TargetDeviceRelation {
        return (*Irp).IoStatus.__bindgen_anon_1.Status;
    }

    deviceRelations = ExAllocatePoolWithTag(
        PagedPool,
        core::mem::size_of::<DEVICE_RELATIONS>(),
        TAG_SCSIPORT as u32,
    ) as *mut DEVICE_RELATIONS;

    if deviceRelations.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }

    (*deviceRelations).Count = 1;
    (*deviceRelations).Objects[0] = DeviceObject;
    ObReferenceObject(DeviceObject as *mut core::ffi::c_void);

    (*Irp).IoStatus.Information = (deviceRelations as ULONG_PTR) as _;
    return STATUS_SUCCESS;
}
#[no_mangle]
pub unsafe extern "C" fn PdoDispatchPnp(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
) -> NTSTATUS {
    let ioStack: PIO_STACK_LOCATION = IoGetCurrentIrpStackLocation(Irp);
    let lunExt: PSCSI_PORT_LUN_EXTENSION = (*DeviceObject).DeviceExtension as PSCSI_PORT_LUN_EXTENSION;
    let mut status: NTSTATUS;

    // DPRINT removed

    if (*lunExt).Common.IsFDO != 0 {
        RtlAssert(
            b"!lunExt->Common.IsFDO\0" as *const u8 as *const i8 as PVOID,
            b"drivers/storage/port/scsiport/pdo.c\0"
                as *const u8 as *const i8 as PVOID,
            564,
            core::ptr::null_mut::<i8>(),
        );
    }

    match (*ioStack).MinorFunction {
        IRP_MN_START_DEVICE => {
            RegistryInitLunKey(lunExt);
            status = STATUS_SUCCESS;
        }
        IRP_MN_REMOVE_DEVICE
        | IRP_MN_QUERY_CAPABILITIES
        | IRP_MN_QUERY_REMOVE_DEVICE
        | IRP_MN_QUERY_STOP_DEVICE
        | IRP_MN_SURPRISE_REMOVAL => {
            status = STATUS_SUCCESS;
        }
        IRP_MN_QUERY_DEVICE_RELATIONS => {
            status = PdoHandleDeviceRelations(DeviceObject, Irp);
        }
        IRP_MN_QUERY_DEVICE_TEXT => {
            status = PdoHandleQueryDeviceText(DeviceObject, Irp);
        }
        IRP_MN_QUERY_ID => {
            // DPRINT removed

            if (*ioStack).Parameters.QueryId.IdType as u32 == BusQueryDeviceID as u32 {
                status = PdoHandleQueryDeviceId(DeviceObject, Irp);
            } else if (*ioStack).Parameters.QueryId.IdType as u32 == BusQueryHardwareIDs as u32 {
                status = PdoHandleQueryHardwareId(DeviceObject, Irp);
            } else if (*ioStack).Parameters.QueryId.IdType as u32 == BusQueryInstanceID as u32 {
                status = PdoHandleQueryInstanceId(DeviceObject, Irp);
            } else if (*ioStack).Parameters.QueryId.IdType as u32 == BusQueryCompatibleIDs as u32 {
                status = PdoHandleQueryCompatibleId(DeviceObject, Irp);
            } else {
                // fallthrough – acts like default case
                status = (*Irp).IoStatus.__bindgen_anon_1.Status;
            }
        }
        _ => {
            status = (*Irp).IoStatus.__bindgen_anon_1.Status;
        }
    }

    if status != STATUS_PENDING {
        (*Irp).IoStatus.__bindgen_anon_1.Status = status;
        IoCompleteRequest(Irp, IO_NO_INCREMENT as i8);
    }

    status
}
