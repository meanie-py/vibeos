unsafe fn ConvertToUnicodeString(
    Buffer: *mut i8,
    ResultBufferLength: u32,
    mut ResultBufferOffset: u32,
    ResultBuffer: *mut u16,
    NewResultBufferOffset: *mut u32,
) {
    let mut DeviceString: _UNICODE_STRING = _UNICODE_STRING {
        Length: 0,
        MaximumLength: 0,
        Buffer: core::ptr::null_mut::<u16>(),
    };
    let mut AnsiString: ANSI_STRING = ANSI_STRING {
        Length: 0,
        MaximumLength: 0,
        Buffer: core::ptr::null_mut::<i8>(),
    };
    let mut Status: NTSTATUS;
    if ResultBufferLength == 0 {
        RtlAssert(
            b"ResultBufferLength\0" as *const u8 as *const i8 as *mut core::ffi::c_void,
            b"drivers/storage/port/scsiport/pdo.c\0"
                as *const u8 as *const i8 as *mut core::ffi::c_void,
            320u32,
            core::ptr::null_mut::<i8>(),
        );
    } else {};
    if !(ResultBufferLength > ResultBufferOffset) {
        RtlAssert(
            b"ResultBufferLength > ResultBufferOffset\0" as *const u8 as *const i8
                as *mut core::ffi::c_void,
            b"drivers/storage/port/scsiport/pdo.c\0"
                as *const u8 as *const i8 as *mut core::ffi::c_void,
            321u32,
            core::ptr::null_mut::<i8>(),
        );
    } else {};
    DeviceString.Buffer = ResultBuffer.offset(ResultBufferOffset as isize) as *mut u16 as *mut u16;
    DeviceString.Length = 0u16;
    DeviceString.MaximumLength = (ResultBufferLength.wrapping_sub(ResultBufferOffset) as usize)
        .wrapping_mul(core::mem::size_of::<u16>())
        as u16;
    RtlInitAnsiString(&raw mut AnsiString, Buffer as *const i8);
    Status =
        RtlAnsiStringToUnicodeString(&raw mut DeviceString, &raw mut AnsiString, 0);
    if !(Status == 0i32) {
        RtlAssert(
            b"Status == STATUS_SUCCESS\0" as *const u8 as *const i8
                as *mut core::ffi::c_void,
            b"drivers/storage/port/scsiport/pdo.c\0"
                as *const u8 as *const i8 as *mut core::ffi::c_void,
            335u32,
            core::ptr::null_mut::<i8>(),
        );
    } else {};
    ResultBufferOffset = (ResultBufferOffset as u64).wrapping_add(
        (DeviceString.Length as usize)
            .wrapping_add(core::mem::size_of::<u16>())
            .wrapping_div(core::mem::size_of::<u16>())
            as u64,
    ) as u32 as u32;
    *NewResultBufferOffset = ResultBufferOffset as u32;
}

