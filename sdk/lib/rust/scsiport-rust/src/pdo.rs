unsafe fn PdoHandleQueryCompatibleId(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
) -> NTSTATUS {
    let mut PDODeviceExtension: PSCSI_PORT_LUN_EXTENSION = (*DeviceObject).DeviceExtension as PSCSI_PORT_LUN_EXTENSION;
    let mut Buffer: [i8; 100] = [0i8; 100];
    let mut Length: ULONG;
    let mut Offset: ULONG = 0;
    let mut InstanceId: LPWSTR;
    let mut DeviceType: LPCSTR;

    DeviceType = GetDeviceType(&raw mut (*PDODeviceExtension).InquiryData) as LPCSTR;

    Length = (sprintf(
        &raw mut Buffer as *mut i8,
        b"SCSI\\%s\0" as *const u8 as *const i8,
        DeviceType,
    ) + 1i32) as ULONG;

    Length = (Length as ULONG).wrapping_add(
        (sprintf(
            (&raw mut Buffer as *mut i8).offset(Length as isize),
            b"SCSI\\%s\0" as *const u8 as *const i8,
            b"RAW\0" as *const u8 as *const i8,
        ) + 2i32) as ULONG,
    );

    InstanceId = ExAllocatePoolWithTag(
        PagedPool,
        (Length as usize) * core::mem::size_of::<u16>(),
        TAG_SCSIPORT as u32,
    ) as LPWSTR;

    if InstanceId.is_null() {
        (*Irp).IoStatus.Information = (0 as usize) as _;
        return STATUS_INSUFFICIENT_RESOURCES;
    }

    ConvertToUnicodeString(
        &raw mut Buffer as *mut i8,
        Length,
        0u32,
        InstanceId,
        &raw mut Offset,
    );

    ConvertToUnicodeString(
        (&raw mut Buffer as *mut i8).offset(Offset as isize),
        Length,
        Offset,
        InstanceId,
        &raw mut Offset,
    );

    *InstanceId.offset(Offset as isize) = UNICODE_NULL;

    (*Irp).IoStatus.Information = (InstanceId as usize) as _;
    return STATUS_SUCCESS;
}

