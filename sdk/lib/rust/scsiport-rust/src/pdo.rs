#[no_mangle]
pub unsafe extern "C" fn PdoCreateLunDevice(
    DeviceExtension: *mut SCSI_PORT_DEVICE_EXTENSION,
) -> *mut DEVICE_OBJECT {
    let mut LunPDO: *mut DEVICE_OBJECT = core::ptr::null_mut();
    let LunExtensionSize: u32 = ((*DeviceExtension).LunExtensionSize as usize)
        .wrapping_add(core::mem::size_of::<SCSI_PORT_LUN_EXTENSION>())
        as u32;
    let mut Status: i32 = IoCreateDevice(
        (*(*DeviceExtension).Common.DeviceObject).DriverObject as *mut DRIVER_OBJECT,
        LunExtensionSize,
        core::ptr::null_mut::<_UNICODE_STRING>(),
        FILE_DEVICE_DISK as u32,
        (FILE_AUTOGENERATED_DEVICE_NAME | FILE_DEVICE_SECURE_OPEN) as u32,
        0,
        &raw mut LunPDO,
    );
    if Status < 0 {
        if DbgPrint(
            b"(%s:%d) Failed to create a Lun PDO, status: %x\n\0" as *const u8 as *const i8,
            b"drivers/storage/port/scsiport/pdo.c\0" as *const u8 as *const i8,
            36,
            Status,
        ) != 0 {
            DbgPrint(
                b"(%s:%d) DbgPrint() failed!\n\0" as *const u8 as *const i8,
                b"drivers/storage/port/scsiport/pdo.c\0" as *const u8 as *const i8,
                36,
            );
        }
        return core::ptr::null_mut();
    }
    let LunExtension: *mut SCSI_PORT_LUN_EXTENSION = (*LunPDO).DeviceExtension as *mut SCSI_PORT_LUN_EXTENSION;
    /* Zero everything */
    core::ptr::write_bytes(LunExtension as *mut u8, 0, LunExtensionSize as usize);
    (*LunExtension).Common.IsFDO = 0;
    (*LunExtension).Common.DeviceObject = LunPDO;
    (*LunExtension).Common.LowerDevice = (*DeviceExtension).Common.DeviceObject;
    InitializeListHead(&raw mut (*LunExtension).SrbInfo.Requests);
    (*LunExtension).RequestTimeout = -1;
    (*LunExtension).MaxQueueCount = 256;
    KeInitializeDeviceQueue(&raw mut (*LunExtension).DeviceQueue);
    (*LunPDO).Flags |= DO_DIRECT_IO;
    (*LunPDO).Flags &= !DO_DEVICE_INITIALIZING;
    LunPDO
}

#[no_mangle]
pub unsafe extern "C" fn GetLunByPath(
    DeviceExtension: PSCSI_PORT_DEVICE_EXTENSION,
    PathId: UCHAR,
    TargetId: UCHAR,
    Lun: UCHAR,
) -> PSCSI_PORT_LUN_EXTENSION {
    if PathId as i32 >= (*DeviceExtension).NumberOfBuses as i32 {
        if DbgPrint(
            b"(%s:%d) Invalid PathId: %u\n\0" as *const u8 as *const i8,
            b"drivers/storage/port/scsiport/pdo.c\0"
                as *const u8 as *const i8,
            76i32,
            PathId as i32,
        ) != 0
        {
            DbgPrint(
                b"(%s:%d) DbgPrint() failed!\n\0" as *const u8 as *const i8,
                b"drivers/storage/port/scsiport/pdo.c\0"
                    as *const u8 as *const i8,
                76i32,
            );
        }
        return core::ptr::null_mut::<SCSI_PORT_LUN_EXTENSION>();
    }
    let bus: PSCSI_BUS_INFO = (*DeviceExtension).Buses.add(PathId as usize) as PSCSI_BUS_INFO;
    let mut lunEntry: PLIST_ENTRY = (*bus).LunsListHead.Flink as PLIST_ENTRY;
    let lun_list_head = &mut (*bus).LunsListHead as *mut _;
    while lunEntry != lun_list_head {
        let offset = core::mem::offset_of!(SCSI_PORT_LUN_EXTENSION, LunEntry);
        let lunExt = (lunEntry as usize).wrapping_sub(offset) as PSCSI_PORT_LUN_EXTENSION;
        if (*lunExt).PathId as i32 == PathId as i32
            && (*lunExt).TargetId as i32 == TargetId as i32
            && (*lunExt).Lun as i32 == Lun as i32
        {
            return lunExt;
        }
        lunEntry = (*lunEntry).Flink as PLIST_ENTRY;
    }
    return core::ptr::null_mut::<SCSI_PORT_LUN_EXTENSION>();
}
#[no_mangle]
pub unsafe extern "C" fn SpiGetSrbData(
    DeviceExtension: PSCSI_PORT_DEVICE_EXTENSION,
    LunExtension: PSCSI_PORT_LUN_EXTENSION,
    QueueTag: u8,
) -> PSCSI_REQUEST_BLOCK_INFO {
    if QueueTag as i32 == SP_UNTAGGED as i32 {
        return &raw mut (*LunExtension).SrbInfo;
    } else if QueueTag as u32 > (*DeviceExtension).SrbDataCount
        || (QueueTag as i32) < 1
    {
        return core::ptr::null_mut::<_SCSI_REQUEST_BLOCK_INFO>();
    } else {
        return (*DeviceExtension)
            .SrbInfo
            .offset((QueueTag as i32 - 1) as isize) as PSCSI_REQUEST_BLOCK_INFO;
    }
}
unsafe fn CopyField(
    Name: *mut u8,
    Buffer: *mut i8,
    MaxLength: u32,
    DefaultCharacter: i8,
    Trim: u8,
) -> u32 {
    let mut Index: u32 = 0;
    while Index < MaxLength {
        if *Name.add(Index as usize) <= b' '
            || *Name.add(Index as usize) >= 0x7f
            || *Name.add(Index as usize) == b','
        {
            *Buffer.add(Index as usize) = DefaultCharacter;
        } else {
            *Buffer.add(Index as usize) = *Name.add(Index as usize) as i8;
        }
        Index = Index.wrapping_add(1);
    }
    if Trim != 0 {
        Index = MaxLength.wrapping_sub(1);
        loop {
            if *Buffer.add(Index as usize) != DefaultCharacter {
                Index = Index.wrapping_add(1);
                break;
            }
            Index = Index.wrapping_sub(1);
        }
    }
    return Index;
}
unsafe fn PdoHandleQueryDeviceText(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
) -> NTSTATUS {

    let DeviceExtension = (*DeviceObject).DeviceExtension as *mut SCSI_PORT_LUN_EXTENSION;
    let IoStack = IoGetCurrentIrpStackLocation(Irp);
    let mut Offset: u32 = 0;
    let InquiryData = addr_of_mut!((*DeviceExtension).InquiryData);
    let mut LocalBuffer: [i8; 64] = [0; 64];
    let mut AnsiString = ANSI_STRING {
        Length: 0,
        MaximumLength: 0,
        Buffer: ::core::ptr::null_mut(),
    };
    let mut DeviceDescription = _UNICODE_STRING {
        Length: 0,
        MaximumLength: 0,
        Buffer: ::core::ptr::null_mut(),
    };

    match (*IoStack).Parameters.QueryDeviceText.DeviceTextType as u32 {
        0 => { // DeviceTextDescription
            Offset = Offset.wrapping_add(CopyField(
                addr_of_mut!((*InquiryData).VendorId) as *mut u8,
                (LocalBuffer.as_mut_ptr() as *mut i8).offset(Offset as isize),
                size_of::<[u8; 8]>() as u32,
                b' ' as i8,
                1u8,
            ) as u32);
            let fresh0 = Offset;
            Offset = Offset.wrapping_add(1);
            LocalBuffer[fresh0 as usize] = b' ' as i8;
            Offset = Offset.wrapping_add(CopyField(
                addr_of_mut!((*InquiryData).ProductId) as *mut u8,
                (LocalBuffer.as_mut_ptr() as *mut i8).offset(Offset as isize),
                size_of::<[u8; 16]>() as u32,
                b' ' as i8,
                1u8,
            ) as u32);
            Offset = Offset.wrapping_add(sprintf(
                (LocalBuffer.as_mut_ptr() as *mut i8).offset(Offset as isize),
                b" SCSI %s Device\0".as_ptr() as *const i8,
                GetDeviceType(InquiryData),
            ) as u32);
            let fresh1 = Offset;
            Offset = Offset.wrapping_add(1);
            LocalBuffer[fresh1 as usize] = b'\0' as i8;
            RtlInitAnsiString(
                &mut AnsiString,
                LocalBuffer.as_ptr() as *const i8,
            );
            DeviceDescription.Length = 0;
            DeviceDescription.MaximumLength = (Offset as usize * size_of::<u16>()) as u16;
            DeviceDescription.Buffer = ExAllocatePoolWithTag(
                PagedPool,
                DeviceDescription.MaximumLength as usize,
                0x53435349u32, // TAG_SCSIPORT
            ) as *mut u16;
            if DeviceDescription.Buffer.is_null() {
                (*Irp).IoStatus.Information = 0;
                return STATUS_INSUFFICIENT_RESOURCES;
            }
            RtlAnsiStringToUnicodeString(
                &mut DeviceDescription,
                &mut AnsiString,
                0u8,
            );
            (*Irp).IoStatus.Information = (DeviceDescription.Buffer as usize) as _;
            return STATUS_SUCCESS;
        }
        1 => { // DeviceTextLocationInformation
            sprintf(
                LocalBuffer.as_mut_ptr() as *mut i8,
                b"Bus Number %d, Target ID %d, LUN %d\0".as_ptr() as *const i8,
                ((*DeviceExtension).PathId) as i32,
                ((*DeviceExtension).TargetId) as i32,
                ((*DeviceExtension).Lun) as i32,
            );
            RtlInitAnsiString(
                &mut AnsiString,
                LocalBuffer.as_ptr() as *const i8,
            );
            DeviceDescription.Length = 0;
            DeviceDescription.MaximumLength =
                ((strlen(LocalBuffer.as_ptr() as *const i8) as usize + 1)
                * size_of::<u16>()) as u16;
            DeviceDescription.Buffer = ExAllocatePoolWithTag(
                PagedPool,
                DeviceDescription.MaximumLength as usize,
                0x53435349u32, // TAG_SCSIPORT
            ) as *mut u16;
            if DeviceDescription.Buffer.is_null() {
                (*Irp).IoStatus.Information = 0;
                return STATUS_INSUFFICIENT_RESOURCES;
            }
            RtlAnsiStringToUnicodeString(
                &mut DeviceDescription,
                &mut AnsiString,
                0u8,
            );
            (*Irp).IoStatus.Information = (DeviceDescription.Buffer as usize) as _;
            return STATUS_SUCCESS;
        }
        _ => {
            (*Irp).IoStatus.Information = 0;
            return (*Irp).IoStatus.__bindgen_anon_1.Status;
        }
    }
}

