#[no_mangle]
pub unsafe extern "C" fn ShowTcpTable() -> BOOL {
    let mut tcpTable: PMIB_TCPTABLE_OWNER_PID = core::ptr::null_mut();
    let mut error: DWORD = 0;
    let mut dwSize: DWORD = 0;
    let mut i: DWORD = 0;
    let mut HostIp: [CHAR; (HOSTNAMELEN) as _] = [0; (HOSTNAMELEN) as _];
    let mut HostPort: [CHAR; (PORTNAMELEN) as _] = [0; (PORTNAMELEN) as _];
    let mut RemoteIp: [CHAR; (HOSTNAMELEN) as _] = [0; (HOSTNAMELEN) as _];
    let mut RemotePort: [CHAR; (PORTNAMELEN) as _] = [0; (PORTNAMELEN) as _];
    let mut Host: [CHAR; (ADDRESSLEN) as _] = [0; (ADDRESSLEN) as _];
    let mut Remote: [CHAR; (ADDRESSLEN) as _] = [0; (ADDRESSLEN) as _];
    let mut PID: [CHAR; 64] = [0; 64];

    /* Get the table of TCP endpoints */
    dwSize = core::mem::size_of::<MIB_TCPTABLE_OWNER_PID>() as DWORD;
    /* Should also work when we get new connections between 2 GetTcpTable()
     * calls: */
    loop {
        tcpTable = HeapAlloc(GetProcessHeap(), 0, dwSize as SIZE_T) as PMIB_TCPTABLE_OWNER_PID;
        error = GetExtendedTcpTable(tcpTable as PVOID, core::ptr::addr_of_mut!(dwSize), (TRUE) as BOOL, AF_INET, (TCP_TABLE_OWNER_PID_ALL) as TCP_TABLE_CLASS, 0);
        if error != NO_ERROR {
            HeapFree(GetProcessHeap(), 0, tcpTable as PVOID);
        }
        if !(error == ERROR_INSUFFICIENT_BUFFER) {
            break;
        }
    }

    if error != NO_ERROR {
        ConResPrintf(StdErr, IDS_ERROR_TCP_SNAPSHOT);
        DoFormatMessage(error);
        return (FALSE) as BOOL;
    }

    /* Dump the TCP table */
    i = 0;
    while i < (*tcpTable).dwNumEntries {
        /* If we aren't showing all connections, only display established, close wait
         * and time wait. This is the default output for netstat */
        if bDoShowAllCons != 0
            || (*(core::ptr::addr_of_mut!((*tcpTable).table) as *mut MIB_TCPROW_OWNER_PID).offset(i as isize)).dwState == (MIB_TCP_STATE_ESTAB as u32)
            || (*(core::ptr::addr_of_mut!((*tcpTable).table) as *mut MIB_TCPROW_OWNER_PID).offset(i as isize)).dwState == (MIB_TCP_STATE_CLOSE_WAIT as u32)
            || (*(core::ptr::addr_of_mut!((*tcpTable).table) as *mut MIB_TCPROW_OWNER_PID).offset(i as isize)).dwState == (MIB_TCP_STATE_TIME_WAIT as u32)
        {
            /* I've split this up so it's easier to follow */
            GetIpHostName((TRUE) as BOOL, (*(core::ptr::addr_of_mut!((*tcpTable).table) as *mut MIB_TCPROW_OWNER_PID).offset(i as isize)).dwLocalAddr as UINT, core::ptr::addr_of_mut!(HostIp) as *mut CHAR, core::mem::size_of::<[CHAR; (HOSTNAMELEN) as _]>() as INT);
            GetPortName((*(core::ptr::addr_of_mut!((*tcpTable).table) as *mut MIB_TCPROW_OWNER_PID).offset(i as isize)).dwLocalPort as UINT, b"tcp\0".as_ptr() as PCSTR, core::ptr::addr_of_mut!(HostPort) as *mut CHAR, core::mem::size_of::<[CHAR; (PORTNAMELEN) as _]>() as INT);
            sprintf(core::ptr::addr_of_mut!(Host) as *mut CHAR, b"%s:%s\0".as_ptr() as PCSTR, core::ptr::addr_of_mut!(HostIp) as *mut CHAR, core::ptr::addr_of_mut!(HostPort) as *mut CHAR);

            if (*(core::ptr::addr_of_mut!((*tcpTable).table) as *mut MIB_TCPROW_OWNER_PID).offset(i as isize)).dwState == (MIB_TCP_STATE_LISTEN as u32) {
                sprintf(core::ptr::addr_of_mut!(Remote) as *mut CHAR, b"%s:0\0".as_ptr() as PCSTR, core::ptr::addr_of_mut!(HostIp) as *mut CHAR);
            } else {
                GetIpHostName((FALSE) as BOOL, (*(core::ptr::addr_of_mut!((*tcpTable).table) as *mut MIB_TCPROW_OWNER_PID).offset(i as isize)).dwRemoteAddr as UINT, core::ptr::addr_of_mut!(RemoteIp) as *mut CHAR, core::mem::size_of::<[CHAR; (HOSTNAMELEN) as _]>() as INT);
                GetPortName((*(core::ptr::addr_of_mut!((*tcpTable).table) as *mut MIB_TCPROW_OWNER_PID).offset(i as isize)).dwRemotePort as UINT, b"tcp\0".as_ptr() as PCSTR, core::ptr::addr_of_mut!(RemotePort) as *mut CHAR, core::mem::size_of::<[CHAR; (PORTNAMELEN) as _]>() as INT);
                sprintf(core::ptr::addr_of_mut!(Remote) as *mut CHAR, b"%s:%s\0".as_ptr() as PCSTR, core::ptr::addr_of_mut!(RemoteIp) as *mut CHAR, core::ptr::addr_of_mut!(RemotePort) as *mut CHAR);
            }

            if bDoShowProcessId != 0 {
                sprintf((PID).as_mut_ptr() as *mut CHAR, b"%ld\0".as_ptr() as PCSTR, (*(core::ptr::addr_of_mut!((*tcpTable).table) as *mut MIB_TCPROW_OWNER_PID).offset(i as isize)).dwOwningPid);
            } else {
                PID[0] = 0;
            }

            ConPrintf(StdOut, RUSTCONV_WSTR_1758EAC64BE7.as_ptr(), RUSTCONV_WSTR_53B8D0B0DF4B.as_ptr(),
                      core::ptr::addr_of_mut!(Host) as *mut CHAR, core::ptr::addr_of_mut!(Remote) as *mut CHAR, TcpState[(*(core::ptr::addr_of_mut!((*tcpTable).table) as *mut MIB_TCPROW_OWNER_PID).offset(i as isize)).dwState as usize], (PID).as_mut_ptr() as *mut CHAR);
        }
        i = i.wrapping_add(1);
    }

    HeapFree(GetProcessHeap(), 0, tcpTable as PVOID);
    return (TRUE) as BOOL;
}
#[no_mangle]
pub unsafe extern "C" fn ShowUdpTable() -> BOOL {
    let mut udpTable: PMIB_UDPTABLE_OWNER_PID = core::ptr::null_mut();
    let mut error: DWORD;
    let mut dwSize: DWORD;
    let mut i: DWORD;
    let mut HostIp: [CHAR; (HOSTNAMELEN) as _] = [0; (HOSTNAMELEN) as _];
    let mut HostPort: [CHAR; (PORTNAMELEN) as _] = [0; (PORTNAMELEN) as _];
    let mut Host: [CHAR; (ADDRESSLEN) as _] = [0; (ADDRESSLEN) as _];
    let mut PID: [CHAR; 64] = [0; 64];

    /* Get the table of UDP endpoints */
    dwSize = 0;
    error = GetExtendedUdpTable(
        core::ptr::null_mut(),
        &raw mut dwSize,
        TRUE,
        AF_INET,
        UDP_TABLE_OWNER_PID,
        0,
    );
    if error != ERROR_INSUFFICIENT_BUFFER {
        ConResPuts(StdErr, IDS_ERROR_UDP_ENDPOINT);
        DoFormatMessage(error);
        return FALSE;
    }
    udpTable = HeapAlloc(
        GetProcessHeap(),
        0,
        dwSize as SIZE_T,
    ) as PMIB_UDPTABLE_OWNER_PID;
    error = GetExtendedUdpTable(
        udpTable as PVOID,
        &raw mut dwSize,
        TRUE,
        AF_INET,
        UDP_TABLE_OWNER_PID,
        0,
    );
    if error != 0 {
        ConResPuts(StdErr, IDS_ERROR_UDP_ENDPOINT_TABLE);
        DoFormatMessage(error);
        HeapFree(GetProcessHeap(), 0, udpTable as PVOID);
        return FALSE;
    }

    /* Dump the UDP table */
    i = 0;
    while i < (*udpTable).dwNumEntries {
        /* I've split this up so it's easier to follow */
        GetIpHostName(
            TRUE,
            (*(&raw mut (*udpTable).table as *mut MIB_UDPROW_OWNER_PID).offset(i as isize))
                .dwLocalAddr as UINT,
            &raw mut HostIp as *mut CHAR,
            core::mem::size_of::<[CHAR; (HOSTNAMELEN) as _]>() as INT,
        );
        GetPortName(
            (*(&raw mut (*udpTable).table as *mut MIB_UDPROW_OWNER_PID).offset(i as isize))
                .dwLocalPort as UINT,
            b"udp\0".as_ptr() as PCSTR,
            &raw mut HostPort as *mut CHAR,
            core::mem::size_of::<[CHAR; (PORTNAMELEN) as _]>() as INT,
        );

        sprintf(
            &raw mut Host as *mut CHAR,
            b"%s:%s\0".as_ptr() as *const CHAR,
            &raw mut HostIp as *mut CHAR,
            &raw mut HostPort as *mut CHAR,
        );

        if bDoShowProcessId != 0 {
            sprintf(
                &raw mut PID as *mut CHAR,
                b"%ld\0".as_ptr() as *const CHAR,
                (*(&raw mut (*udpTable).table as *mut MIB_UDPROW_OWNER_PID).offset(i as isize))
                    .dwOwningPid,
            );
        } else {
            PID[0 as usize] = 0 as CHAR;
        }

        ConPrintf(
            StdOut,
            RUSTCONV_WSTR_C1E30C68BF81.as_ptr(),
            RUSTCONV_WSTR_C68DDD38613C.as_ptr(),
            &raw mut Host as *mut CHAR,
            RUSTCONV_WSTR_CF5519A909ED.as_ptr(),
            &raw mut PID as *mut CHAR,
        );

        i = i.wrapping_add(1);
    }

    HeapFree(GetProcessHeap(), 0, udpTable as PVOID);
    return TRUE;
}
#[no_mangle]
pub unsafe extern "C" fn GetPortName(
    mut Port: UINT,
    mut Proto: PCSTR,
    mut Name: *mut CHAR,
    mut NameLen: INT,
) -> PCHAR {
    let mut pServent: *mut servent = core::ptr::null_mut::<servent>();
    if bDoShowNumbers != 0 {
        sprintf(
            Name as *mut i8,
            b"%d\0".as_ptr() as *const i8,
            htons(Port as WORD) as INT,
        );
        return Name as PCHAR;
    }
    pServent = getservbyport(
        Port as INT,
        Proto as *const i8,
    );
    if !pServent.is_null() {
        strcpy(Name as *mut i8, (*pServent).s_name);
    } else {
        sprintf(
            Name as *mut i8,
            b"%d\0".as_ptr() as *const i8,
            htons(Port as WORD) as INT,
        );
    }
    return Name as PCHAR;
}
#[no_mangle]
pub unsafe extern "C" fn GetIpHostName(Local: BOOL, IpAddr: UINT, Name: *mut CHAR, NameLen: INT) -> PCHAR {
    let mut nIpAddr: UINT;

    /* display dotted decimal */
    nIpAddr = htonl(IpAddr as u_long) as UINT;
    if bDoShowNumbers != 0 {
        sprintf(
            Name as *mut ::core::ffi::c_char,
            b"%d.%d.%d.%d\0".as_ptr() as *const ::core::ffi::c_char,
            (nIpAddr >> 24) & 0xFF,
            (nIpAddr >> 16) & 0xFF,
            (nIpAddr >> 8) & 0xFF,
            (nIpAddr) & 0xFF,
        );
        return Name as PCHAR;
    }

    *Name.offset(0 as isize) = 0 as CHAR;

    /* try to resolve the name */
    if IpAddr == 0 {
        if Local == 0 {
            sprintf(
                Name as *mut ::core::ffi::c_char,
                b"%d.%d.%d.%d\0".as_ptr() as *const ::core::ffi::c_char,
                (nIpAddr >> 24) & 0xFF,
                (nIpAddr >> 16) & 0xFF,
                (nIpAddr >> 8) & 0xFF,
                (nIpAddr) & 0xFF,
            );
        } else {
            if gethostname(
                Name as *mut ::core::ffi::c_char,
                NameLen as ::core::ffi::c_int,
            ) != 0
            {
                DoFormatMessage(WSAGetLastError() as DWORD);
            }
        }
    } else if IpAddr == 0x0100007f {
        if Local != 0 {
            if gethostname(
                Name as *mut ::core::ffi::c_char,
                NameLen as ::core::ffi::c_int,
            ) != 0
            {
                DoFormatMessage(WSAGetLastError() as DWORD);
            }
        } else {
            strncpy(
                (Name as *mut ::core::ffi::c_char).cast(),
                (b"localhost\0".as_ptr() as *const ::core::ffi::c_char).cast(),
                10 as size_t,
            );
        }
    } else {
        sprintf(
            Name as *mut ::core::ffi::c_char,
            b"%d.%d.%d.%d\0".as_ptr() as *const ::core::ffi::c_char,
            ((nIpAddr >> 24) & 0x000000FF),
            ((nIpAddr >> 16) & 0x000000FF),
            ((nIpAddr >> 8) & 0x000000FF),
            ((nIpAddr) & 0x000000FF),
        );
    }
    return Name as PCHAR;
}

#[no_mangle]
pub unsafe extern "C" fn wmain(argc: i32, argv: *mut *mut wchar_t) -> i32 {
    let mut Success: BOOL;
    let mut wsaData: WSADATA = core::mem::zeroed();

    /* Initialize the Console Standard Streams */
    ConInitStdStreams();

    if ParseCmdline(argc, argv) == 0 {
        return (EXIT_FAILURE as i32);
    }

    if WSAStartup(MAKEWORD!(2, 2), &mut wsaData) != 0 {
        ConResPrintf(StdErr, IDS_ERROR_WSA_START, WSAGetLastError());
        return (EXIT_FAILURE as i32);
    }

    Success = DisplayOutput();
    while bLoopOutput != 0 && Success != 0 {
        Sleep(Interval.wrapping_mul(1000));
        Success = DisplayOutput();
    }

    WSACleanup();
    return if Success != 0 { (EXIT_SUCCESS as i32) } else { (EXIT_FAILURE as i32) };
}
