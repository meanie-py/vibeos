pub unsafe extern "C" fn ParseCmdline(argc: ::core::ffi::c_int, argv: *mut *mut wchar_t) -> BOOL {
    let mut Proto: LPWSTR = core::ptr::null_mut();
    let mut c: WCHAR = 0;
    let mut i: INT = 0;

    if (argc == 1) || (iswdigit(**argv.offset(1 as isize) as wint_t) != 0) {
        bNoOptions = TRUE;
    }

    /* Parse command line for options we have been given. */
    i = 1;
    while i < argc {
        if (argc > 1)
            && ((*(*argv.offset(i as isize)).offset(0 as isize) == 0x002Du16)
                || (*(*argv.offset(i as isize)).offset(0 as isize) == 0x002Fu16))
        {
            loop {
                let p = argv.offset(i as isize);
                *p = (*p).offset(1);
                c = **p;
                if c == 0x0000u16 {
                    break;
                }
                let mut take_default: bool = false;
                match towlower(c as wint_t) as u16 {
                    0x0061u16 => {
                        bDoShowAllCons = TRUE;
                    }
                    0x0062u16 => {
                        // UNIMPLEMENTED.
                        ConPuts(StdErr, RUSTCONV_WSTR_33016F4FE309.as_ptr());
                        bDoShowProcName = TRUE;
                        bDoShowProcessId = TRUE;
                    }
                    0x0065u16 => {
                        bDoShowEthStats = TRUE;
                    }
                    0x006Eu16 => {
                        bDoShowNumbers = TRUE;
                    }
                    0x006Fu16 => {
                        bDoShowProcessId = TRUE;
                    }
                    0x0070u16 => {
                        bDoShowProtoCons = TRUE;
                        if i + 1 >= argc {
                            DisplayTableHeader();
                            return TRUE;
                        }

                        Proto = *argv.offset((i + 1) as isize);
                        if _wcsicmp(RUSTCONV_WSTR_DFC106660209.as_ptr() as *const wchar_t, Proto as *const wchar_t) == 0 {
                            Protocol = (IP as u32);
                        } else if _wcsicmp(RUSTCONV_WSTR_C3F8330A3ECD.as_ptr() as *const wchar_t, Proto as *const wchar_t) == 0 {
                            Protocol = (ICMP as u32);
                        } else if _wcsicmp(RUSTCONV_WSTR_53B8D0B0DF4B.as_ptr() as *const wchar_t, Proto as *const wchar_t) == 0 {
                            Protocol = (TCP as u32);
                        } else if _wcsicmp(RUSTCONV_WSTR_C68DDD38613C.as_ptr() as *const wchar_t, Proto as *const wchar_t) == 0 {
                            Protocol = (UDP as u32);
                        } else {
                            // goto StopParsingAndShowUsageHelp;
                            take_default = true;
                        }
                    }
                    0x0072u16 => {
                        bDoShowRouteTable = TRUE;
                    }
                    0x0073u16 => {
                        bDoShowProtoStats = TRUE;
                    }
                    0x0074u16 => {
                        // UNIMPLEMENTED.
                        ConPuts(StdErr, RUSTCONV_WSTR_A0919D4379A6.as_ptr());
                    }
                    0x0076u16 => {
                        // UNIMPLEMENTED.
                        ConPuts(StdErr, RUSTCONV_WSTR_1C7777A72E35.as_ptr());
                        bDoDispSeqComp = TRUE;
                    }
                    _ => {
                        take_default = true;
                    }
                }
                if take_default {
                    // StopParsingAndShowUsageHelp:
                    ConResPuts(StdErr, IDS_USAGE);
                    return FALSE;
                }
            }
        } else if iswdigit(**argv.offset(i as isize) as wint_t) != 0 {
            if swscanf(*argv.offset(i as isize), RUSTCONV_WSTR_F3C6A8F2AC47.as_ptr() as *const wchar_t, core::ptr::addr_of_mut!(Interval)) != EOF {
                bLoopOutput = TRUE;
            } else {
                return FALSE;
            }
        }
        i += 1;
    }

    return TRUE;
}
#[no_mangle]
pub unsafe extern "C" fn DisplayOutput() -> BOOL {
    if bNoOptions != 0 {
        DisplayTableHeader();
        return ShowTcpTable();
    }
    if bDoShowRouteTable != 0 {
        if _wsystem(RUSTCONV_WSTR_A2BBE3990933.as_ptr()) == -1 {
            ConResPuts(StdErr, IDS_ERROR_ROUTE);
            return FALSE;
        }
        return TRUE;
    }
    if bDoShowEthStats != 0 {
        ShowEthernetStatistics();
        return TRUE;
    }
    if bDoShowProtoCons != 0 {
        match (Protocol as ::core::ffi::c_uint) as i32 {
            IP => {
                if bDoShowProtoStats != 0 {
                    ShowIpStatistics();
                }
                return TRUE;
            }
            ICMP => {
                if bDoShowProtoStats != 0 {
                    ShowIcmpStatistics();
                }
                return TRUE;
            }
            TCP => {
                if bDoShowProtoStats != 0 {
                    ShowTcpStatistics();
                }
                DisplayTableHeader();
                return ShowTcpTable();
            }
            UDP => {
                if bDoShowProtoStats != 0 {
                    ShowUdpStatistics();
                }
                DisplayTableHeader();
                return if bDoShowAllCons != 0 {
                    ShowUdpTable()
                } else {
                    TRUE
                };
            }
            _ => {}
        }
    } else if bDoShowProtoStats != 0 {
        ShowIpStatistics();
        ShowIcmpStatistics();
        ShowTcpStatistics();
        ShowUdpStatistics();
        return TRUE;
    } else {
        DisplayTableHeader();
        if ShowTcpTable() != 0 && bDoShowAllCons != 0 {
            ShowUdpTable();
        }
    }

    return TRUE;
}
