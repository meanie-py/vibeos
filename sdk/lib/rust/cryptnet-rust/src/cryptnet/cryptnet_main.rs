unsafe extern "C" fn handle_ocsp_response(
    cert: *const CERT_INFO,
    issuer: *const CERT_INFO,
    encoded: *const BYTE,
    encoded_size: DWORD,
    next_update: *mut FILETIME,
) -> DWORD {
    let mut info: *mut OCSP_RESPONSE_INFO = core::ptr::null_mut::<OCSP_RESPONSE_INFO>();
    let mut size: DWORD = 0;
    let mut error: DWORD = CRYPT_E_NO_REVOCATION_CHECK as DWORD;
    if CryptDecodeObjectEx(
        X509_ASN_ENCODING as DWORD,
        OCSP_RESPONSE,
        encoded,
        encoded_size,
        CRYPT_DECODE_ALLOC_FLAG as DWORD,
        (core::ptr::null_mut::<core::ffi::c_void>()).cast(),
        &raw mut info as *mut core::ffi::c_void,
        &raw mut size,
    ) == 0
    {
        return GetLastError();
    }
    match (*info).dwStatus {
        OCSP_SUCCESSFUL_RESPONSE => {
            if (*info).pszObjId.is_null()
                || strcmp(
                    (*info).pszObjId as *const core::ffi::c_char,
                    szOID_PKIX_OCSP_BASIC_SIGNED_RESPONSE.as_ptr(),
                ) != 0
            {
                FIXME!("unhandled response type %s\n", debugstr_a((*info).pszObjId as *const core::ffi::c_char));
                // break;
            } else {
                error = verify_signed_ocsp_response_info(
                    cert,
                    issuer,
                    &raw mut (*info).Value,
                    next_update,
                );
            }
        }
        _ => {
            FIXME!("unhandled status %lu\n", (*info).dwStatus);
        }
    }
    LocalFree(info as HLOCAL);
    return error;
}

