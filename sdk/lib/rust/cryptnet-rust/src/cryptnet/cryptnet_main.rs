unsafe extern "C" fn CRYPT_CacheURL(
    pszURL: LPCWSTR,
    pObject: *const CRYPT_BLOB_ARRAY,
    dwRetrievalFlags: DWORD,
    expires: FILETIME,
) {
    let mut cacheFileName: [WCHAR; MAX_PATH as usize] = [0; MAX_PATH as usize];
    let mut hCacheFile: HANDLE = core::ptr::null_mut();
    let mut size: DWORD = 0 as DWORD;
    let mut entryType: DWORD = 0;
    let mut ft: FILETIME = FILETIME {
        dwLowDateTime: 0,
        dwHighDateTime: 0,
    };

    GetUrlCacheEntryInfoW(pszURL, core::ptr::null_mut(), core::ptr::addr_of_mut!(size));
    if GetLastError() == ERROR_INSUFFICIENT_BUFFER as DWORD
    {
        let mut info: *mut INTERNET_CACHE_ENTRY_INFOW =
            CryptMemAlloc(size as ULONG) as *mut INTERNET_CACHE_ENTRY_INFOW;

        if info.is_null()
        {
            ERR!("out of memory\n");
            return;
        }

        if GetUrlCacheEntryInfoW(pszURL, info, core::ptr::addr_of_mut!(size)) != 0
        {
            lstrcpyW(
                core::ptr::addr_of_mut!(cacheFileName) as LPWSTR,
                (*info).lpszLocalFileName as LPCWSTR,
            );
            /* Check if the existing cache entry is up to date.  If it isn't,
             * remove the existing cache entry, and create a new one with the
             * new value.
             */
            GetSystemTimeAsFileTime(core::ptr::addr_of_mut!(ft));
            if CompareFileTime(
                core::ptr::addr_of_mut!((*info).ExpireTime),
                core::ptr::addr_of_mut!(ft),
            ) < 0 as LONG
            {
                DeleteUrlCacheEntryW(pszURL);
            }
            else
            {
                (*info).ExpireTime = expires;
                SetUrlCacheEntryInfoW(
                    pszURL,
                    info as LPINTERNET_CACHE_ENTRY_INFOW,
                    CACHE_ENTRY_EXPTIME_FC as DWORD,
                );
                CryptMemFree(info as LPVOID);
                return;
            }
        }
        CryptMemFree(info as LPVOID);
    }

    if CreateUrlCacheEntryW(
        pszURL,
        (*(*pObject).rgBlob.offset(0 as isize)).cbData,
        core::ptr::null::<WCHAR>(),
        core::ptr::addr_of_mut!(cacheFileName) as LPWSTR,
        0 as DWORD,
    ) == 0
    {
        return;
    }

    hCacheFile = CreateFileW(
        core::ptr::addr_of_mut!(cacheFileName) as *mut WCHAR as LPCWSTR,
        GENERIC_WRITE as DWORD,
        0 as DWORD,
        core::ptr::null_mut(),
        OPEN_EXISTING as DWORD,
        FILE_ATTRIBUTE_NORMAL as DWORD,
        core::ptr::null_mut(),
    );
    if hCacheFile == INVALID_HANDLE_VALUE as HANDLE
    {
        return;
    }

    WriteFile(
        hCacheFile,
        (*(*pObject).rgBlob.offset(0 as isize)).pbData as LPCVOID,
        (*(*pObject).rgBlob.offset(0 as isize)).cbData,
        core::ptr::addr_of_mut!(size),
        core::ptr::null_mut(),
    );
    CloseHandle(hCacheFile);

    if (dwRetrievalFlags & CRYPT_STICKY_CACHE_RETRIEVAL as DWORD) != 0
    {
        entryType = STICKY_CACHE_ENTRY as DWORD;
    }
    else
    {
        entryType = NORMAL_CACHE_ENTRY as DWORD;
    }
    memset(
        core::ptr::addr_of_mut!(ft) as *mut core::ffi::c_void,
        0 as core::ffi::c_int,
        core::mem::size_of::<FILETIME>() as usize,
    );
    CommitUrlCacheEntryW(
        pszURL,
        core::ptr::addr_of_mut!(cacheFileName) as *mut WCHAR as LPCWSTR,
        expires,
        ft,
        entryType,
        core::ptr::null_mut(),
        0 as DWORD,
        core::ptr::null(),
        core::ptr::null(),
    );
}

