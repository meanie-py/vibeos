unsafe extern "system" fn CRYPT_CreateBlob(
    mut pszObjectOid: LPCSTR,
    mut dwRetrievalFlags: DWORD,
    mut pObject: *const CRYPT_BLOB_ARRAY,
    mut ppvContext: *mut *mut ::core::ffi::c_void,
) -> BOOL {
    let mut size: DWORD = 0;
    let mut i: DWORD = 0;
    let mut context: *mut CRYPT_BLOB_ARRAY = ::core::ptr::null_mut::<CRYPT_BLOB_ARRAY>();
    let mut ret: BOOL = FALSE as BOOL;
    size = (core::mem::size_of::<CRYPT_BLOB_ARRAY>() as usize).wrapping_add(
        ((*pObject).cBlob as usize).wrapping_mul(core::mem::size_of::<CRYPT_DATA_BLOB>() as usize),
    ) as DWORD;
    i = 0 as DWORD;
    while i < (*pObject).cBlob {
        size = size.wrapping_add((*(*pObject).rgBlob.offset(i as isize)).cbData);
        i = i.wrapping_add(1);
    }
    context = CryptMemAlloc(size as ULONG) as *mut CRYPT_BLOB_ARRAY;
    if !context.is_null() {
        let mut nextData: LPBYTE = ::core::ptr::null_mut::<BYTE>();
        (*context).cBlob = 0 as DWORD;
        (*context).rgBlob = (context as LPBYTE)
            .offset(core::mem::size_of::<CRYPT_BLOB_ARRAY>() as isize)
            as *mut CRYPT_DATA_BLOB as PCRYPT_DATA_BLOB;
        nextData = ((*context).rgBlob as LPBYTE).offset(
            ((*pObject).cBlob as usize).wrapping_mul(core::mem::size_of::<CRYPT_DATA_BLOB>() as usize) as isize,
        );
        i = 0 as DWORD;
        while i < (*pObject).cBlob {
            memcpy(
                nextData as *mut ::core::ffi::c_void,
                (*(*pObject).rgBlob.offset(i as isize)).pbData as *const ::core::ffi::c_void,
                (*(*pObject).rgBlob.offset(i as isize)).cbData as size_t,
            );
            let ref mut fresh19 = (*(*context).rgBlob.offset(i as isize)).pbData;
            *fresh19 = nextData as *mut BYTE;
            (*(*context).rgBlob.offset(i as isize)).cbData =
                (*(*pObject).rgBlob.offset(i as isize)).cbData;
            nextData = nextData.offset((*(*pObject).rgBlob.offset(i as isize)).cbData as isize);
            (*context).cBlob = (*context).cBlob.wrapping_add(1);
            i = i.wrapping_add(1);
        }
        *ppvContext = context as *mut ::core::ffi::c_void;
        ret = TRUE as BOOL;
    }
    return ret;
}

unsafe extern "C" fn decode_base64_blob(in_: *const CRYPT_DATA_BLOB, out: *mut CRYPT_DATA_BLOB) -> BOOL {
    let mut ret: BOOL;
    let mut len: DWORD = (*in_).cbData;

    while len != 0 && *(*in_).pbData.add((len - 1) as usize) == 0 {
        len -= 1;
    }
    if CryptStringToBinaryA(
        (*in_).pbData as *mut ::core::ffi::c_char as LPCSTR,
        len,
        CRYPT_STRING_BASE64_ANY,
        core::ptr::null_mut(),
        core::ptr::addr_of_mut!((*out).cbData),
        core::ptr::null_mut(),
        core::ptr::null_mut(),
    ) == 0
    {
        return (FALSE) as BOOL;
    }

    (*out).pbData = CryptMemAlloc((*out).cbData as ULONG) as *mut BYTE;
    if (*out).pbData.is_null() {
        return (FALSE) as BOOL;
    }
    ret = CryptStringToBinaryA(
        (*in_).pbData as *mut ::core::ffi::c_char as LPCSTR,
        len,
        CRYPT_STRING_BASE64_ANY,
        (*out).pbData,
        core::ptr::addr_of_mut!((*out).cbData),
        core::ptr::null_mut(),
        core::ptr::null_mut(),
    );
    if ret == 0 {
        CryptMemFree((*out).pbData as LPVOID);
    }
    return ret;
}

