unsafe extern "C" fn open_cached_revocation_file(
    cert: *const CERT_CONTEXT,
    params: *const CERT_REVOCATION_PARA,
    mode: *const WCHAR,
    sharing: ::core::ffi::c_int,
) -> *mut FILE {
    let mut hash_data: [BYTE; CACHED_CERT_HASH_SIZE] = [0; CACHED_CERT_HASH_SIZE];
    let mut path: [WCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut appdata_path: *mut WCHAR = core::ptr::null_mut::<WCHAR>();
    let mut len: DWORD = 0;
    let mut i: DWORD = 0;
    let mut size: DWORD = 0;
    let mut prov: HCRYPTPROV = 0;
    let mut hash: HCRYPTHASH = 0;
    let mut hr: HRESULT = 0;

    hr = SHGetKnownFolderPath!(
        &raw mut FOLDERID_LocalAppDataLow,
        0,
        core::ptr::null_mut(),
        &raw mut appdata_path,
    );
    if hr < 0 {
        ERR!("Failed to get LocalAppDataLow path, hr %#lx.\n", hr);
        return (INVALID_HANDLE_VALUE).cast();
    }

    len = swprintf(
        &raw mut path as *mut WCHAR,
        (ARRAY_SIZE!(path)) as _,
        RUSTCONV_WSTR_C91D67EBDF2F.as_ptr(),
        appdata_path,
    ) as DWORD;
    CoTaskMemFree(appdata_path as LPVOID);

    if (len as usize)
        + (CACHED_CERT_HASH_SIZE as usize)
            * (2 as usize)
            * core::mem::size_of::<WCHAR>()
        > (ARRAY_SIZE!(path) as usize) - (1 as usize)
    {
        WARN!("Hash length exceeds static buffer; not caching.\n");
        return (INVALID_HANDLE_VALUE).cast();
    }

    CryptAcquireContextW(
        &raw mut prov,
        core::ptr::null::<WCHAR>(),
        core::ptr::null::<WCHAR>(),
        PROV_RSA_FULL,
        CRYPT_VERIFYCONTEXT,
    );
    CryptCreateHash(
        prov,
        CALG_SHA1,
        0,
        0,
        &raw mut hash,
    );
    CryptHashData(
        hash,
        (*cert).pbCertEncoded,
        (*cert).cbCertEncoded,
        0,
    );
    if !params.is_null() && !(*params).pIssuerCert.is_null() {
        CryptHashData(
            hash,
            &raw const (*(*params).pIssuerCert).cbCertEncoded as *mut BYTE,
            core::mem::size_of::<DWORD>() as DWORD,
            0,
        );
        CryptHashData(
            hash,
            (*(*params).pIssuerCert).pbCertEncoded,
            (*(*params).pIssuerCert).cbCertEncoded,
            0,
        );
    } else {
        size = 0;
        CryptHashData(
            hash,
            &raw mut size as *mut BYTE,
            core::mem::size_of::<DWORD>() as DWORD,
            0,
        );
    }
    size = core::mem::size_of::<[BYTE; CACHED_CERT_HASH_SIZE]>() as DWORD;
    CryptGetHashParam(
        hash,
        HP_HASHVAL,
        &raw mut hash_data as *mut BYTE,
        &raw mut size,
        0,
    );
    CryptDestroyHash(hash);
    CryptReleaseContext(prov, 0);

    SHCreateDirectoryExW(
        core::ptr::null_mut::<HWND__>(),
        &raw mut path as *mut WCHAR as LPCWSTR,
        core::ptr::null_mut::<_SECURITY_ATTRIBUTES>(),
    );

    i = 0;
    while i < (CACHED_CERT_HASH_SIZE as DWORD) {
        swprintf(
            (&raw mut path as *mut WCHAR).offset(len as isize),
            3,
            RUSTCONV_WSTR_AA2A982F0618.as_ptr(),
            hash_data[i as usize] as ::core::ffi::c_int,
        );
        len = len.wrapping_add(2);
        i = i.wrapping_add(1);
    }

    return _wfsopen(
        &raw mut path as *mut WCHAR,
        mode,
        sharing,
    );
}

unsafe extern "C" fn find_cached_revocation_status(
    cert: *const CERT_CONTEXT,
    params: *const CERT_REVOCATION_PARA,
    time: *const FILETIME,
    status: *mut CERT_REVOCATION_STATUS,
) -> BOOL {
    let mut buffer: [core::ffi::c_char; 23] = [0; 23];
    let mut update_time: FILETIME = FILETIME {
        dwLowDateTime: 0,
        dwHighDateTime: 0,
    };
    let mut file: *mut FILE = core::ptr::null_mut();
    let mut len: core::ffi::c_int = 0;

    file = open_cached_revocation_file(cert, params, RUSTCONV_WSTR_76CFE90FF2FC.as_ptr(), (_SH_DENYWR as i32));
    if file.is_null() {
        return (FALSE) as BOOL;
    }

    len = fread(
        core::ptr::addr_of_mut!(buffer) as *mut core::ffi::c_void,
        1,
        core::mem::size_of::<[core::ffi::c_char; 23]>(),
        file,
    ) as core::ffi::c_int;
    if len as usize != core::mem::size_of::<[core::ffi::c_char; 23]>()
        || memcmp(
            core::ptr::addr_of!(buffer) as *const core::ffi::c_void,
            core::ptr::addr_of!(revocation_cache_signature) as *const core::ffi::c_void,
            len as usize,
        ) != 0
    {
        ERR!("Invalid cache signature.\n");
        fclose(file);
        return (FALSE) as BOOL;
    }

    if fread(
        core::ptr::addr_of_mut!(update_time) as *mut core::ffi::c_void,
        core::mem::size_of::<FILETIME>(),
        1,
        file,
    ) != 1
    {
        ERR!("Failed to read update time.\n");
        fclose(file);
        return (FALSE) as BOOL;
    }

    if CompareFileTime(time, core::ptr::addr_of!(update_time)) > 0 {
        TRACE!("Cached revocation status is potentially out of date.\n");
        fclose(file);
        return (FALSE) as BOOL;
    }

    if fread(
        core::ptr::addr_of_mut!((*status).dwError) as *mut core::ffi::c_void,
        core::mem::size_of::<DWORD>(),
        1,
        file,
    ) != 1
    {
        ERR!("Failed to read error code.\n");
        fclose(file);
        return (FALSE) as BOOL;
    }

    if (*status).dwError == (CERT_E_REVOKED) as u32
        && fread(
            core::ptr::addr_of_mut!((*status).dwReason) as *mut core::ffi::c_void,
            core::mem::size_of::<DWORD>(),
            1,
            file,
        ) != 1
    {
        ERR!("Failed to read revocation reason.\n");
        fclose(file);
        return (FALSE) as BOOL;
    }

    TRACE!(
        "Using cached status %#lx, reason %#lx.\n",
        (*status).dwError,
        (*status).dwReason
    );
    return (TRUE) as BOOL;
}

unsafe extern "C" fn cache_revocation_status(
    cert: *const CERT_CONTEXT,
    params: *const CERT_REVOCATION_PARA,
    time: *const FILETIME,
    status: *const CERT_REVOCATION_STATUS,
) {
    let mut file: *mut FILE = core::ptr::null_mut();

    file = open_cached_revocation_file(cert, params, RUSTCONV_WSTR_1EA9E69A696A.as_ptr(), (_SH_DENYRW as i32));
    if file.is_null() {
        return;
    }
    fwrite(
        core::ptr::addr_of!(revocation_cache_signature) as *const core::ffi::c_void,
        1 as usize,
        core::mem::size_of::<[core::ffi::c_char; 23]>() as usize,
        (file).cast(),
    );
    fwrite(
        time as *const core::ffi::c_void,
        core::mem::size_of::<FILETIME>() as usize,
        1 as usize,
        (file).cast(),
    );
    fwrite(
        core::ptr::addr_of!((*status).dwError) as *const core::ffi::c_void,
        core::mem::size_of::<DWORD>() as usize,
        1 as usize,
        (file).cast(),
    );
    if (*status).dwError == (CERT_E_REVOKED) as u32 {
        fwrite(
            core::ptr::addr_of!((*status).dwReason) as *const core::ffi::c_void,
            core::mem::size_of::<DWORD>() as usize,
            1 as usize,
            (file).cast(),
        );
    }
    fclose(file);
}

unsafe extern "C" fn verify_cert_revocation_with_crl_online(
    cert: *const CERT_CONTEXT,
    crl: *const CRL_CONTEXT,
    pTime: *mut FILETIME,
    pRevStatus: *mut CERT_REVOCATION_STATUS,
) -> DWORD {
    let mut entry: PCRL_ENTRY = core::ptr::null_mut();

    CertFindCertificateInCRL(
        cert as PCCERT_CONTEXT,
        crl as PCCRL_CONTEXT,
        0 as DWORD,
        core::ptr::null_mut(),
        core::ptr::addr_of_mut!(entry),
    );
    if !entry.is_null() {
        return CRYPT_E_REVOKED as DWORD;
    }

    /* Since the CRL was retrieved for the cert being checked, then it's
     * guaranteed to be fresh, and the cert is not revoked. */
    return ERROR_SUCCESS as DWORD;
}

unsafe extern "C" fn retrieve_crl_from_dist_points(
    mut array: *const CRYPT_URL_ARRAY,
    mut verify_flags: DWORD,
    mut timeout: DWORD,
) -> *const CRL_CONTEXT {
    let mut retrieve_flags: DWORD = 0;
    let mut crl: *const CRL_CONTEXT = core::ptr::null::<CRL_CONTEXT>();
    let mut i: DWORD = 0;

    if (verify_flags & CERT_VERIFY_CACHE_ONLY_BASED_REVOCATION) != 0 {
        retrieve_flags |= CRYPT_CACHE_ONLY_RETRIEVAL;
    }

    /* Yes, this is a weird algorithm, but the documentation for
     * CERT_CHAIN_REVOCATION_ACCUMULATIVE_TIMEOUT specifies this, and
     * tests seem to bear it out for CertVerifyRevocation() as well. */
    if (verify_flags & CERT_VERIFY_REV_ACCUMULATIVE_TIMEOUT_FLAG) != 0 {
        timeout /= 2;
    }

    i = 0;
    while i < (*array).cUrl {
        if CryptRetrieveObjectByUrlW(
            *(*array).rgwszUrl.offset(i as isize),
            CONTEXT_OID_CRL,
            retrieve_flags,
            timeout,
            core::ptr::addr_of_mut!(crl) as *mut LPVOID,
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            core::ptr::null_mut(),
        ) != 0
        {
            return crl;
        }

        /* We don't check the current time here. This may result in less
         * accurate timeouts, but this too seems to be true of Windows. */
        if ((verify_flags & CERT_VERIFY_REV_ACCUMULATIVE_TIMEOUT_FLAG) != 0)
            && GetLastError() == ERROR_TIMEOUT
        {
            timeout /= 2;
        }

        i = i.wrapping_add(1);
    }

    return core::ptr::null::<CRL_CONTEXT>();
}

unsafe extern "C" fn verify_cert_revocation_from_dist_points_ext(
    value: *const CRYPT_DATA_BLOB,
    cert: *const CERT_CONTEXT,
    time: *mut FILETIME,
    flags: DWORD,
    params: *const CERT_REVOCATION_PARA,
    status: *mut CERT_REVOCATION_STATUS,
    next_update: *mut FILETIME,
) -> DWORD {
    let mut url_array_size: DWORD = 0;
    let mut error: DWORD = 0;
    let mut url_array: *mut CRYPT_URL_ARRAY = core::ptr::null_mut();
    let mut crl: *const CRL_CONTEXT = core::ptr::null();
    let mut timeout: DWORD = 0;

    if params.is_null() || (*params).pIssuerCert.is_null() {
        return (CRYPT_E_REVOCATION_OFFLINE) as DWORD;
    }

    if CRYPT_GetUrlFromCRLDistPointsExt(
        value,
        core::ptr::null_mut(),
        core::ptr::addr_of_mut!(url_array_size),
        core::ptr::null_mut(),
        core::ptr::null_mut(),
    ) == 0
    {
        return GetLastError();
    }

    url_array = CryptMemAlloc(url_array_size as ULONG) as *mut CRYPT_URL_ARRAY;
    if url_array.is_null() {
        return ERROR_OUTOFMEMORY;
    }

    if CRYPT_GetUrlFromCRLDistPointsExt(
        value,
        url_array as PCRYPT_URL_ARRAY,
        core::ptr::addr_of_mut!(url_array_size),
        core::ptr::null_mut(),
        core::ptr::null_mut(),
    ) == 0
    {
        CryptMemFree(url_array as LPVOID);
        return GetLastError();
    }

    if !params.is_null()
        && (*params).cbSize as usize
            >= RTL_SIZEOF_THROUGH_FIELD!(CERT_REVOCATION_PARA, dwUrlRetrievalTimeout) as usize
    {
        timeout = (*params).dwUrlRetrievalTimeout;
    }

    crl = retrieve_crl_from_dist_points(url_array, flags, timeout);
    if crl.is_null() {
        CryptMemFree(url_array as LPVOID);
        return (CRYPT_E_REVOCATION_OFFLINE) as DWORD;
    }

    error = verify_cert_revocation_with_crl_online(cert, crl, time, status);

    *next_update = (*(*crl).pCrlInfo).NextUpdate;

    CertFreeCRLContext(crl as PCCRL_CONTEXT);
    CryptMemFree(url_array as LPVOID);
    return error;
}

unsafe extern "C" fn sha1_hash(data: *const BYTE, datalen: DWORD, buf: *mut BYTE, buflen: *mut DWORD) {
    let mut prov: HCRYPTPROV = 0;
    let mut hash: HCRYPTHASH = 0;

    CryptAcquireContextW(core::ptr::addr_of_mut!(prov), core::ptr::null_mut(), core::ptr::null_mut(), PROV_RSA_FULL, CRYPT_VERIFYCONTEXT);
    CryptCreateHash(prov, CALG_SHA1, 0, 0, core::ptr::addr_of_mut!(hash));
    CryptHashData(hash, data, datalen, 0);
    CryptGetHashParam(hash, HP_HASHVAL, buf, buflen, 0);

    CryptDestroyHash(hash);
    CryptReleaseContext(prov, 0);
}

unsafe extern "C" fn build_ocsp_request(
    mut cert: *const CERT_CONTEXT,
    mut issuer_cert: *const CERT_CONTEXT,
    mut ret_size: *mut DWORD,
) -> *mut BYTE {
    let mut entry: OCSP_REQUEST_ENTRY = core::mem::zeroed();
    let mut request: OCSP_REQUEST_INFO = core::mem::zeroed();
    let mut request_signed: OCSP_SIGNED_REQUEST_INFO = core::mem::zeroed();
    let mut issuer: *mut CERT_INFO = (*issuer_cert).pCertInfo as *mut CERT_INFO;
    let mut issuer_name_hash: [BYTE; 20] = [0; 20];
    let mut issuer_key_hash: [BYTE; 20] = [0; 20];
    let mut buf: *mut BYTE = core::ptr::null_mut::<BYTE>();
    let mut ret: *mut BYTE = core::ptr::null_mut::<BYTE>();
    let mut size: DWORD = 0 as DWORD;
    let mut hash_len: DWORD = ::core::mem::size_of::<[BYTE; 20]>() as DWORD;

    memset(
        &raw mut entry as *mut ::core::ffi::c_void,
        0 as ::core::ffi::c_int,
        ::core::mem::size_of::<OCSP_REQUEST_ENTRY>() as size_t,
    );
    entry.CertId.HashAlgorithm.pszObjId =
        szOID_OIWSEC_sha1.as_ptr() as *mut ::core::ffi::c_char as LPSTR;

    sha1_hash(
        (*issuer).Subject.pbData,
        (*issuer).Subject.cbData,
        &raw mut issuer_name_hash as *mut BYTE,
        &raw mut hash_len,
    );
    entry.CertId.IssuerNameHash.cbData = ::core::mem::size_of::<[BYTE; 20]>() as DWORD;
    entry.CertId.IssuerNameHash.pbData = &raw mut issuer_name_hash as *mut BYTE;

    sha1_hash(
        (*issuer).SubjectPublicKeyInfo.PublicKey.pbData,
        (*issuer).SubjectPublicKeyInfo.PublicKey.cbData,
        &raw mut issuer_key_hash as *mut BYTE,
        &raw mut hash_len,
    );
    entry.CertId.IssuerKeyHash.cbData = ::core::mem::size_of::<[BYTE; 20]>() as DWORD;
    entry.CertId.IssuerKeyHash.pbData = &raw mut issuer_key_hash as *mut BYTE;

    entry.CertId.SerialNumber.cbData = (*(*cert).pCertInfo).SerialNumber.cbData;
    entry.CertId.SerialNumber.pbData = (*(*cert).pCertInfo).SerialNumber.pbData;

    request.dwVersion = OCSP_REQUEST_V1 as DWORD;
    request.pRequestorName = core::ptr::null_mut();
    request.cRequestEntry = 1 as DWORD;
    request.rgRequestEntry = &raw mut entry as POCSP_REQUEST_ENTRY;
    request.cExtension = 0 as DWORD;
    request.rgExtension = core::ptr::null_mut();
    if CryptEncodeObjectEx(
        X509_ASN_ENCODING as DWORD,
        OCSP_REQUEST,
        &raw mut request as *const ::core::ffi::c_void,
        CRYPT_ENCODE_ALLOC_FLAG as DWORD,
        core::ptr::null_mut(),
        &raw mut buf as *mut ::core::ffi::c_void,
        &raw mut size,
    ) == 0
    {
        ERR!("failed to encode request %#lx\n", GetLastError());
        return core::ptr::null_mut::<BYTE>();
    }

    request_signed.ToBeSigned.pbData = buf;
    request_signed.ToBeSigned.cbData = size;
    request_signed.pOptionalSignatureInfo = core::ptr::null_mut();
    if CryptEncodeObjectEx(
        X509_ASN_ENCODING as DWORD,
        OCSP_SIGNED_REQUEST,
        &raw mut request_signed as *const ::core::ffi::c_void,
        CRYPT_ENCODE_ALLOC_FLAG as DWORD,
        core::ptr::null_mut(),
        &raw mut ret as *mut ::core::ffi::c_void,
        &raw mut size,
    ) == 0
    {
        ERR!("failed to encode signed request %#lx\n", GetLastError());
        LocalFree(buf as HLOCAL);
        return core::ptr::null_mut::<BYTE>();
    }

    LocalFree(buf as HLOCAL);
    *ret_size = size;
    return ret;
}

unsafe extern "C" fn escape_path(
    mut src: *const WCHAR,
    mut src_len: DWORD,
    mut dst: *mut WCHAR,
    mut dst_len: *mut DWORD,
) {
    static hex: [u16; 17] = [
    0x0030u16, 0x0031, 0x0032, 0x0033, 0x0034, 0x0035, 0x0036, 0x0037, 0x0038, 0x0039,
    0x0041, 0x0042, 0x0043, 0x0044, 0x0045, 0x0046, 0x0000,
];
    let mut ptr: *mut WCHAR = dst;
    let mut i: DWORD;
    *dst_len = src_len;
    i = 0 as DWORD;
    while i < src_len {
        if *src.offset(i as isize) as i32 == '+' as i32
            || *src.offset(i as isize) as i32 == '/' as i32
            || *src.offset(i as isize) as i32 == '=' as i32
        {
            if !dst.is_null() {
                *ptr.offset(0 as isize) = '%' as i32 as WCHAR;
                *ptr.offset(1 as isize) =
                    hex[((*src.offset(i as isize) as i32 >> 4)
                        & 0xf) as usize];
                *ptr.offset(2 as isize) =
                    hex[((*src.offset(i as isize) as i32) & 0xf) as usize];
                ptr = ptr.offset(3 as isize);
            }
            *dst_len = (*dst_len).wrapping_add(2 as DWORD);
        } else if !dst.is_null() {
            let fresh21 = ptr;
            ptr = ptr.offset(1);
            *fresh21 = *src.offset(i as isize);
        }
        i = i.wrapping_add(1);
    }
}

unsafe extern "C" fn build_request_path(data: *const BYTE, data_size: DWORD) -> *mut WCHAR {
    let mut path: *mut WCHAR = core::ptr::null_mut();
    let mut ret: *mut WCHAR = core::ptr::null_mut();
    let mut path_len: DWORD = 0;
    let mut ret_len: DWORD = 0;

    if CryptBinaryToStringW(data, data_size, CRYPT_STRING_BASE64 | CRYPT_STRING_NOCRLF, core::ptr::null_mut(), core::ptr::addr_of_mut!(path_len)) == 0 {
        return core::ptr::null_mut();
    }
    path = malloc((path_len as usize).wrapping_mul(core::mem::size_of::<WCHAR>())) as *mut WCHAR;
    if path.is_null() {
        return core::ptr::null_mut();
    }
    CryptBinaryToStringW(data, data_size, CRYPT_STRING_BASE64 | CRYPT_STRING_NOCRLF, path, core::ptr::addr_of_mut!(path_len));

    escape_path(path, path_len, core::ptr::null_mut(), core::ptr::addr_of_mut!(ret_len));
    ret = malloc((ret_len.wrapping_add(2) as usize).wrapping_mul(core::mem::size_of::<WCHAR>())) as *mut WCHAR;
    if ret.is_null() {
        free(path as *mut ::core::ffi::c_void);
        return core::ptr::null_mut();
    }
    escape_path(path, path_len, ret.offset(1 as isize), core::ptr::addr_of_mut!(ret_len));
    *ret.offset(ret_len.wrapping_add(1) as isize) = 0 as WCHAR;
    *ret.offset(0 as isize) = '/' as i32 as WCHAR;

    free(path as *mut ::core::ffi::c_void);
    return ret;
}

