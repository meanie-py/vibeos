/// winnt.h's RtlSecureZeroMemory, a FORCEINLINE no DLL exports: volatile stores, so the
/// clear of a secret cannot be dropped as a dead write (the reason the function exists).
#[inline(never)]
pub unsafe fn RtlSecureZeroMemory(Buffer: PVOID, Length: SIZE_T) -> PVOID {
    let p = Buffer as *mut u8;
    for i in 0..Length as usize {
        ::core::ptr::write_volatile(p.add(i), 0);
    }
    Buffer
}
