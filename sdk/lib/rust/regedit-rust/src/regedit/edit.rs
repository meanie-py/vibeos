    lvC.cx = ((rc.right - rc.left) - lvC.cx as LONG) as INT;
    LoadStringW(hInst, IDS_INTERFACE as UINT, szText.as_mut_ptr(), ARRAY_SIZE!(szText) as INT);
    if ListView_InsertColumn!(hWndListView, 1 as INT, core::ptr::addr_of_mut!(lvC)) == -1 {
        return (FALSE) as BOOL;
    }

    return (TRUE) as BOOL;
