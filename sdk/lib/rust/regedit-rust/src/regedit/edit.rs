unsafe extern "C" fn GetResourceType(
    mut ResourceType: UCHAR,
    mut pBuffer: LPWSTR,
    mut dwLength: DWORD,
) {
    match (ResourceType as ::core::ffi::c_int) as u32 {
        CmResourceTypePort => {
            LoadStringW(
                hInst,
                IDS_TYPE_PORT as UINT,
                pBuffer,
                dwLength as ::core::ffi::c_int,
            );
        }
        CmResourceTypeInterrupt => {
            LoadStringW(
                hInst,
                IDS_TYPE_INTERRUPT as UINT,
                pBuffer,
                dwLength as ::core::ffi::c_int,
            );
        }
        CmResourceTypeMemory => {
            LoadStringW(
                hInst,
                IDS_TYPE_MEMORY as UINT,
                pBuffer,
                dwLength as ::core::ffi::c_int,
            );
        }
        CmResourceTypeDma => {
            LoadStringW(
                hInst,
                IDS_TYPE_DMA as UINT,
                pBuffer,
                dwLength as ::core::ffi::c_int,
            );
        }
        _ => {
            wsprintf(
                pBuffer,
                RUSTCONV_WSTR_A610AF52BDCB.as_ptr(),
                ResourceType as ::core::ffi::c_int,
            );
        }
    }
}

