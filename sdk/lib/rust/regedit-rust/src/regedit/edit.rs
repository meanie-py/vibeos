#[no_mangle]
pub unsafe extern "system" fn DwordEditSubclassProc(hwnd: HWND, uMsg: UINT, wParam: WPARAM, lParam: LPARAM) -> LRESULT {
    let oldwndproc: WNDPROC = core::mem::transmute::<isize, WNDPROC>((GetWindowLongPtr(hwnd, GWLP_USERDATA)) as _);

    'sw: {
        match uMsg {
            x if x == WM_CHAR => {
                if dwordEditMode as ::core::ffi::c_uint == EDIT_MODE_DEC as ::core::ffi::c_uint {
                    if isdigit(wParam as ::core::ffi::c_int & 0xff) != 0
                        || iscntrl(wParam as ::core::ffi::c_int & 0xff) != 0
                    {
                        break 'sw;
                    } else {
                        return 0 as LRESULT;
                    }
                } else if dwordEditMode as ::core::ffi::c_uint == EDIT_MODE_HEX as ::core::ffi::c_uint {
                    if isxdigit(wParam as ::core::ffi::c_int & 0xff) != 0
                        || iscntrl(wParam as ::core::ffi::c_int & 0xff) != 0
                    {
                        break 'sw;
                    } else {
                        return 0 as LRESULT;
                    }
                } else {
                    break 'sw;
                }
            }
            _ => {}
        }
    }

    return CallWindowProcW(oldwndproc, hwnd, uMsg, wParam, lParam);
}
