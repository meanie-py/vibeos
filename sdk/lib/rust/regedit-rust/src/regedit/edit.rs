unsafe extern "C" fn AddRequirementsToList(mut hwndDlg: HWND, mut hwnd: HWND) {
    let mut pResourceList: PIO_RESOURCE_LIST = core::ptr::null_mut();
    let mut pDescriptor: PIO_RESOURCE_DESCRIPTOR = core::ptr::null_mut();
    let mut buffer: [WCHAR; 80] = [0; 80];
    let mut item: LVITEMW = core::mem::zeroed();
    let mut i: ULONG = 0;
    let mut j: ULONG = 0;
    let mut index: ULONG = 0;
    let mut iItem: INT = 0;

    index = 0;
    pResourceList = (core::ptr::addr_of_mut!((*requirementsValueData).List) as *mut IO_RESOURCE_LIST)
        .offset(0 as isize) as *mut IO_RESOURCE_LIST
        as PIO_RESOURCE_LIST;
    i = 0;
    while i < (*requirementsValueData).AlternativeLists {
        j = 0;
        while j < (*pResourceList).Count {
            pDescriptor = (core::ptr::addr_of_mut!((*pResourceList).Descriptors) as *mut IO_RESOURCE_DESCRIPTOR)
                .offset(j as isize) as *mut IO_RESOURCE_DESCRIPTOR
                as PIO_RESOURCE_DESCRIPTOR;

            wsprintf(
                core::ptr::addr_of_mut!(buffer) as LPWSTR,
                RUSTCONV_WSTR_F3C6A8F2AC47.as_ptr(),
                i + 1,
            );

            item.mask = (LVIF_TEXT | LVIF_PARAM) as UINT;
            item.iItem = index as INT;
            item.iSubItem = 0 as INT;
            item.state = 0 as UINT;
            item.stateMask = 0 as UINT;
            item.pszText = core::ptr::addr_of_mut!(buffer) as *mut WCHAR as LPWSTR;
            item.cchTextMax = wcslen(item.pszText as *const u16) as INT;
            item.lParam = pDescriptor as LPARAM;

            iItem = ListView_InsertItem!(hwnd, core::ptr::addr_of_mut!(item));
            if iItem != -1 {
                wsprintf(
                    core::ptr::addr_of_mut!(buffer) as LPWSTR,
                    RUSTCONV_WSTR_F3C6A8F2AC47.as_ptr(),
                    j + 1,
                );
                ListView_SetItemText!(
                    hwnd,
                    iItem,
                    1,
                    core::ptr::addr_of_mut!(buffer) as LPWSTR,
                );
                wsprintf(
                    core::ptr::addr_of_mut!(buffer) as LPWSTR,
                    RUSTCONV_WSTR_F3C6A8F2AC47.as_ptr(),
                    1,
                );
                ListView_SetItemText!(
                    hwnd,
                    iItem,
                    2,
                    core::ptr::addr_of_mut!(buffer) as LPWSTR,
                );

                GetResourceType(
                    (*pDescriptor).Type,
                    core::ptr::addr_of_mut!(buffer) as LPWSTR,
                    80,
                );
                ListView_SetItemText!(
                    hwnd,
                    iItem,
                    3,
                    core::ptr::addr_of_mut!(buffer) as LPWSTR,
                );
            }

            index += 1;
            j += 1;
        }

        pResourceList = (core::ptr::addr_of_mut!((*pResourceList).Descriptors) as *mut IO_RESOURCE_DESCRIPTOR)
            .offset((*pResourceList).Count as isize) as PIO_RESOURCE_LIST;
        i += 1;
    }

    GetInterfaceType(
        (*requirementsValueData).InterfaceType,
        core::ptr::addr_of_mut!(buffer) as LPWSTR,
        80,
    );
    SetDlgItemTextW(
        hwndDlg,
        (IDC_REQINTERFACETYPE as i32),
        core::ptr::addr_of_mut!(buffer) as *mut WCHAR as LPCWSTR,
    );
    SetDlgItemInt(
        hwndDlg,
        (IDC_REQBUSNUMBER as i32),
        (*requirementsValueData).BusNumber as UINT,
        (TRUE) as BOOL,
    );
    SetDlgItemInt(
        hwndDlg,
        (IDC_REQSLOTNUMBER as i32),
        (*requirementsValueData).SlotNumber as UINT,
        (FALSE) as BOOL,
    );
}

