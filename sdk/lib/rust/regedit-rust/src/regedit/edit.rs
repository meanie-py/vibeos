unsafe extern "C" fn ShowRequirement(mut hwndDlg: HWND) {
    let mut pDescriptor: PIO_RESOURCE_DESCRIPTOR = core::ptr::null_mut();
    let mut item: LVITEMW = core::mem::zeroed();

    if requirementsIndex == -1 {
        return;
    }

    item.mask = LVIF_PARAM as UINT;
    item.iItem = requirementsIndex as ::core::ffi::c_int;
    item.iSubItem = 0 as ::core::ffi::c_int;
    ListView_GetItem!(
        GetDlgItem(hwndDlg, (IDC_REQUIREMENTS_LIST as i32)),
        core::ptr::addr_of_mut!(item),
    );

    pDescriptor = item.lParam as PIO_RESOURCE_DESCRIPTOR;
    if !pDescriptor.is_null() {
        match ((*pDescriptor).Type as ::core::ffi::c_int) as u32 {
            CmResourceTypePort => {
                DialogBoxParamW(
                    core::ptr::null_mut(),
                    MAKEINTRESOURCEW!(IDD_EDIT_REQUIREMENTS_PORT),
                    hwndDlg,
                    Some(
                        show_requirements_port_dlgproc,
                    ),
                    pDescriptor as LPARAM,
                );
            }
            CmResourceTypeMemory => {
                DialogBoxParamW(
                    core::ptr::null_mut(),
                    MAKEINTRESOURCEW!(IDD_EDIT_REQUIREMENTS_MEMORY),
                    hwndDlg,
                    Some(
                        show_requirements_memory_dlgproc,
                    ),
                    pDescriptor as LPARAM,
                );
            }
            CmResourceTypeInterrupt => {
                DialogBoxParamW(
                    core::ptr::null_mut(),
                    MAKEINTRESOURCEW!(IDD_EDIT_REQUIREMENTS_INT),
                    hwndDlg,
                    Some(
                        show_requirements_interrupt_dlgproc,
                    ),
                    pDescriptor as LPARAM,
                );
            }
            CmResourceTypeDma => {
                DialogBoxParamW(
                    core::ptr::null_mut(),
                    MAKEINTRESOURCEW!(IDD_EDIT_REQUIREMENTS_DMA),
                    hwndDlg,
                    Some(
                        show_requirements_dma_dlgproc,
                    ),
                    pDescriptor as LPARAM,
                );
            }
            _ => {}
        }
    }
}

unsafe extern "C" fn OnRequirementsListNotify(hwndDlg: HWND, phdr: *mut NMHDR) -> BOOL {
    let lpnmlv: LPNMLISTVIEW = phdr as LPNMLISTVIEW;

    match (*phdr).idFrom as u32 {
        IDC_REQUIREMENTS_LIST => {
            match (*phdr).code {
                NM_CLICK => {
                    requirementsIndex = (*lpnmlv).iItem as INT;
                    EnableWindow(
                        GetDlgItem(hwndDlg, (IDC_SHOW_REQUIREMENT as i32)),
                        ((*lpnmlv).iItem != -1) as BOOL,
                    );
                }
                NM_DBLCLK => {
                    if (*lpnmlv).iItem != -1 {
                        requirementsIndex = (*lpnmlv).iItem as INT;
                        ShowRequirement(hwndDlg);
                    }
                }
                _ => {}
            }
        }
        _ => {}
    }

    return (FALSE) as BOOL;
}

unsafe extern "system" fn modify_requirements_list_dlgproc(hwndDlg: HWND, uMsg: UINT, wParam: WPARAM, lParam: LPARAM) -> INT_PTR {
    UNREFERENCED_PARAMETER!(lParam);

    match uMsg {
        WM_INITDIALOG => {
            CreateRequirementsListColumns(GetDlgItem(hwndDlg, (IDC_REQUIREMENTS_LIST as i32)));
            AddRequirementsToList(hwndDlg, GetDlgItem(hwndDlg, (IDC_REQUIREMENTS_LIST as i32)));
            return FALSE as INT_PTR;
        }
        WM_NOTIFY => {
            return OnRequirementsListNotify(hwndDlg, lParam as *mut NMHDR) as INT_PTR;
        }
        WM_COMMAND => {
            match (LOWORD!(wParam)) as u32 {
                IDC_SHOW_REQUIREMENT => {
                    if requirementsIndex != -1 {
                        ShowRequirement(hwndDlg);
                    }
                }
                IDOK => {
                    EndDialog(hwndDlg, (IDOK) as INT_PTR);
                }
                IDCANCEL => {
                    EndDialog(hwndDlg, (IDCANCEL) as INT_PTR);
                    return TRUE as INT_PTR;
                }
                _ => {}
            }
        }
        _ => {}
    }
    return FALSE as INT_PTR;
}
#[no_mangle]
pub unsafe extern "C" fn ModifyValue(hwnd: HWND, hKey: HKEY, valueName: LPCWSTR, EditBin: BOOL) -> BOOL {
    let mut type_: DWORD = 0;
    let mut lRet: LONG = 0;
    let mut result: BOOL = (FALSE) as i32;

    if hKey.is_null() {
        return (FALSE) as BOOL;
    }

    editValueName = valueName;

    lRet = RegQueryValueExW(hKey, valueName, core::ptr::null_mut(), &raw mut type_, core::ptr::null_mut(), &raw mut valueDataLen);
    if (lRet) as u32 != ERROR_SUCCESS && (valueName.is_null() || *valueName.offset(0 as isize) == 0) {
        lRet = (ERROR_SUCCESS) as i32; /* Allow editing of (Default) values which don't exist */
        type_ = REG_SZ;
        valueDataLen = 0;
        stringValueData = core::ptr::null_mut();
        binValueData = core::ptr::null_mut();
    }

    'done: {
        if (lRet) as u32 != ERROR_SUCCESS {
            error(hwnd, (IDS_BAD_VALUE) as INT, valueName);
            break 'done;
        }

        if (EditBin) as u32 == FALSE && ((type_ == REG_SZ) || (type_ == REG_EXPAND_SZ)) {
            if valueDataLen > 0 {
                stringValueData = HeapAlloc(GetProcessHeap(), 0, valueDataLen as SIZE_T) as *mut WCHAR;
                if stringValueData.is_null() {
                    error(hwnd, (IDS_TOO_BIG_VALUE) as INT, valueDataLen);
                    break 'done;
                }
                lRet = RegQueryValueExW(hKey, valueName, core::ptr::null_mut(), core::ptr::null_mut(), stringValueData as LPBYTE, &raw mut valueDataLen);
                if (lRet) as u32 != ERROR_SUCCESS {
                    error(hwnd, (IDS_BAD_VALUE) as INT, valueName);
                    break 'done;
                }
            } else {
                stringValueData = core::ptr::null_mut();
            }

            if (DialogBoxW!(0, MAKEINTRESOURCEW!(IDD_EDIT_STRING), hwnd, Some(modify_string_dlgproc))) as u32 == (IDOK) as _ {
                if !stringValueData.is_null() {
                    lRet = RegSetValueExW(hKey, valueName, 0, type_, stringValueData as LPBYTE, (((wcslen(stringValueData as *const WCHAR) + 1 as size_t) as DWORD as size_t) * (core::mem::size_of::<WCHAR>() as size_t)) as DWORD);
                } else {
                    lRet = RegSetValueExW(hKey, valueName, 0, type_, core::ptr::null(), 0);
                }
                if (lRet) as u32 == ERROR_SUCCESS {
                    result = (TRUE) as i32;
                }
            }
        }
        else if (EditBin) as u32 == FALSE && type_ == REG_MULTI_SZ {
            if valueDataLen > 0 {
                let mut llen: size_t = 0;
                let mut listlen: size_t = 0;
                let mut nl_len: size_t = 0;
                let mut src: LPWSTR = core::ptr::null_mut();
                let mut lines: LPWSTR = core::ptr::null_mut();

                stringValueData = HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY, ((valueDataLen as SIZE_T) + (core::mem::size_of::<WCHAR>() as SIZE_T))) as *mut WCHAR;
                if stringValueData.is_null() {
                    error(hwnd, (IDS_TOO_BIG_VALUE) as INT, valueDataLen);
                    break 'done;
                }
                lRet = RegQueryValueExW(hKey, valueName, core::ptr::null_mut(), core::ptr::null_mut(), stringValueData as LPBYTE, &raw mut valueDataLen);
                if (lRet) as u32 != ERROR_SUCCESS {
                    error(hwnd, (IDS_BAD_VALUE) as INT, valueName);
                    break 'done;
                }

                /* convert \0 to \r\n */
                src = stringValueData;
                nl_len = (wcslen(RUSTCONV_WSTR_80E09B2F645F.as_ptr()) as size_t) * (core::mem::size_of::<WCHAR>() as size_t);
                listlen = core::mem::size_of::<WCHAR>() as size_t;
                lines = HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY, ((listlen + (core::mem::size_of::<WCHAR>() as size_t)) as SIZE_T)) as LPWSTR;
                while *src != 0x0000u16 {
                    llen = wcslen(src as *const WCHAR) as size_t;
                    if llen == 0 {
                        break;
                    }
                    listlen += (llen * (core::mem::size_of::<WCHAR>() as size_t)) + nl_len;
                    lines = HeapReAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY, lines as PVOID, listlen as SIZE_T) as LPWSTR;
                    wcscat(lines as *mut WCHAR, src as *const WCHAR);
                    wcscat(lines as *mut WCHAR, RUSTCONV_WSTR_80E09B2F645F.as_ptr());
                    src = src.offset((llen + (1 as size_t)) as isize);
                }
                HeapFree(GetProcessHeap(), 0, stringValueData as PVOID);
                stringValueData = lines;
            } else {
                stringValueData = core::ptr::null_mut();
            }

            if (DialogBoxW!(0, MAKEINTRESOURCEW!(IDD_EDIT_MULTI_STRING), hwnd, Some(modify_multi_string_dlgproc))) as u32 == (IDOK) as _ {
                if !stringValueData.is_null() {
                    /* convert \r\n to \0 */
                    let mut EmptyLines: BOOL = (FALSE) as i32;
                    let mut src: LPWSTR = core::ptr::null_mut();
                    let mut lines: LPWSTR = core::ptr::null_mut();
                    let mut nl: LPWSTR = core::ptr::null_mut();
                    let mut linechars: size_t = 0;
                    let mut buflen: size_t = 0;
                    let mut c_nl: size_t = 0;
                    let mut dest: size_t = 0;

                    src = stringValueData;
                    buflen = core::mem::size_of::<WCHAR>() as size_t;
                    lines = HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY, ((buflen + (core::mem::size_of::<WCHAR>() as size_t)) as SIZE_T)) as LPWSTR;
                    c_nl = wcslen(RUSTCONV_WSTR_80E09B2F645F.as_ptr()) as size_t;
                    dest = 0 as size_t;
                    while *src != 0x0000u16 {
                        nl = wcsstr(src as *const WCHAR, RUSTCONV_WSTR_80E09B2F645F.as_ptr()) as LPWSTR;
                        if !nl.is_null() {
                            linechars = nl.offset_from(src) as size_t;
                            if nl == src {
                                EmptyLines = (TRUE) as i32;
                                src = nl.offset(c_nl as isize);
                                continue;
                            }
                        } else {
                            linechars = wcslen(src as *const WCHAR) as size_t;
                        }
                        if linechars > 0 {
                            buflen += ((linechars + (1 as size_t)) * (core::mem::size_of::<WCHAR>() as size_t));
                            lines = HeapReAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY, lines as PVOID, buflen as SIZE_T) as LPWSTR;
                            memcpy(lines.offset(dest as isize) as *mut core::ffi::c_void, src as *const core::ffi::c_void, linechars * (core::mem::size_of::<WCHAR>() as size_t));
                            dest += linechars;
                            *lines.offset(dest as isize) = 0x0000u16;
                            dest += 1;
                        } else {
                            EmptyLines = (TRUE) as i32;
                        }
                        src = src.offset((linechars + (if !nl.is_null() { c_nl } else { 0 as size_t })) as isize);
                    }
                    dest += 1;
                    *lines.offset(dest as isize) = 0x0000u16;

                    if EmptyLines != 0 {
                        warning(hwnd, (IDS_MULTI_SZ_EMPTY_STRING) as INT);
                    }

                    lRet = RegSetValueExW(hKey, valueName, 0, type_, lines as LPBYTE as *const BYTE, buflen as DWORD);
                    HeapFree(GetProcessHeap(), 0, lines as PVOID);
                } else {
                    lRet = RegSetValueExW(hKey, valueName, 0, type_, core::ptr::null(), 0);
                }
                if (lRet) as u32 == ERROR_SUCCESS {
                    result = (TRUE) as i32;
                }
            }
        }
        else if (EditBin) as u32 == FALSE && type_ == REG_DWORD {
            lRet = RegQueryValueExW(hKey, valueName, core::ptr::null_mut(), core::ptr::null_mut(), &raw mut dwordValueData as LPBYTE, &raw mut valueDataLen);
            if (lRet) as u32 != ERROR_SUCCESS {
                error(hwnd, (IDS_BAD_VALUE) as INT, valueName);
                break 'done;
            }

            if (DialogBoxW!(0, MAKEINTRESOURCEW!(IDD_EDIT_DWORD), hwnd, Some(modify_dword_dlgproc))) as u32 == (IDOK) as _ {
                lRet = RegSetValueExW(hKey, valueName, 0, type_, &raw mut dwordValueData as LPBYTE, core::mem::size_of::<DWORD>() as DWORD);
                if (lRet) as u32 == ERROR_SUCCESS {
                    result = (TRUE) as i32;
                }
            }
        }
        else if (EditBin) as u32 == FALSE && type_ == REG_RESOURCE_LIST {
            if valueDataLen > 0 {
                resourceValueData = HeapAlloc(GetProcessHeap(), 0, valueDataLen as SIZE_T) as PCM_RESOURCE_LIST;
                if resourceValueData.is_null() {
                    error(hwnd, (IDS_TOO_BIG_VALUE) as INT, valueDataLen);
                    break 'done;
                }

                lRet = RegQueryValueExW(hKey, valueName, core::ptr::null_mut(), core::ptr::null_mut(), resourceValueData as LPBYTE, &raw mut valueDataLen);
                if (lRet) as u32 != ERROR_SUCCESS {
                    error(hwnd, (IDS_BAD_VALUE) as INT, valueName);
                    break 'done;
                }
            } else {
                resourceValueData = core::ptr::null_mut();
            }

            if (DialogBoxW!(0, MAKEINTRESOURCEW!(IDD_EDIT_RESOURCE_LIST), hwnd, Some(modify_resource_list_dlgproc))) as u32 == (IDOK) as _ {
            }
        }
        else if (EditBin) as u32 == FALSE && type_ == REG_FULL_RESOURCE_DESCRIPTOR {
            if valueDataLen > 0 {
                resourceValueData = HeapAlloc(GetProcessHeap(), 0, ((valueDataLen as SIZE_T) + (core::mem::size_of::<ULONG>() as SIZE_T))) as PCM_RESOURCE_LIST;
                if resourceValueData.is_null() {
                    error(hwnd, (IDS_TOO_BIG_VALUE) as INT, valueDataLen);
                    break 'done;
                }

                lRet = RegQueryValueExW(hKey, valueName, core::ptr::null_mut(), core::ptr::null_mut(), (&raw mut (*resourceValueData).List as *mut CM_FULL_RESOURCE_DESCRIPTOR).offset(0 as isize) as LPBYTE, &raw mut valueDataLen);
                if (lRet) as u32 != ERROR_SUCCESS {
                    error(hwnd, (IDS_BAD_VALUE) as INT, valueName);
                    break 'done;
                }

                (*resourceValueData).Count = 1;
                fullResourceIndex = 0;
            } else {
                resourceValueData = core::ptr::null_mut();
            }

            if (DialogBoxW!(0, MAKEINTRESOURCEW!(IDD_EDIT_RESOURCE), hwnd, Some(modify_resource_dlgproc))) as u32 == (IDOK) as _ {
            }
        }
        else if (EditBin) as u32 == FALSE && type_ == REG_RESOURCE_REQUIREMENTS_LIST {
            if valueDataLen > 0 {
                requirementsValueData = HeapAlloc(GetProcessHeap(), 0, ((valueDataLen as SIZE_T) + (core::mem::size_of::<ULONG>() as SIZE_T))) as PIO_RESOURCE_REQUIREMENTS_LIST;
                if requirementsValueData.is_null() {
                    error(hwnd, (IDS_TOO_BIG_VALUE) as INT, valueDataLen);
                    break 'done;
                }

                lRet = RegQueryValueExW(hKey, valueName, core::ptr::null_mut(), core::ptr::null_mut(), requirementsValueData as LPBYTE, &raw mut valueDataLen);
                if (lRet) as u32 != ERROR_SUCCESS {
                    error(hwnd, (IDS_BAD_VALUE) as INT, valueName);
                    break 'done;
                }
            } else {
                requirementsValueData = core::ptr::null_mut();
            }

            if (DialogBoxW!(0, MAKEINTRESOURCEW!(IDD_EDIT_REQUIREMENTS_LIST), hwnd, Some(modify_requirements_list_dlgproc))) as u32 == (IDOK) as _ {
            }
        }
        else if ((EditBin) as u32 != FALSE) || (type_ == REG_NONE) || (type_ == REG_BINARY) {
            if valueDataLen > 0 {
                binValueData = HeapAlloc(GetProcessHeap(), 0, ((valueDataLen + 1 as DWORD) as SIZE_T));
                if binValueData.is_null() {
                    error(hwnd, (IDS_TOO_BIG_VALUE) as INT, valueDataLen);
                    break 'done;
                }

                /* Use the unicode version, so editing strings in binary mode is correct */
                lRet = RegQueryValueExW(hKey, valueName,
                                        core::ptr::null_mut(), core::ptr::null_mut(), binValueData as LPBYTE, &raw mut valueDataLen);
                if (lRet) as u32 != ERROR_SUCCESS {
                    HeapFree(GetProcessHeap(), 0, binValueData);
                    error(hwnd, (IDS_BAD_VALUE) as INT, valueName);
                    break 'done;
                }
            } else {
                binValueData = core::ptr::null_mut();
            }

            if (DialogBoxW!(0, MAKEINTRESOURCEW!(IDD_EDIT_BIN_DATA), hwnd, Some(modify_binary_dlgproc))) as u32 == (IDOK) as _ {
                /* Use the unicode version, so editing strings in binary mode is correct */
                lRet = RegSetValueExW(hKey, valueName,
                                      0, type_, binValueData as LPBYTE, valueDataLen);
                if (lRet) as u32 == ERROR_SUCCESS {
                    result = (TRUE) as i32;
                }
            }
            if binValueData != core::ptr::null_mut() {
                HeapFree(GetProcessHeap(), 0, binValueData);
            }
        }
        else {
            error(hwnd, (IDS_UNSUPPORTED_TYPE) as INT, type_);
        }
    }

    /* done: */
    if !resourceValueData.is_null() {
        HeapFree(GetProcessHeap(), 0, resourceValueData as PVOID);
    }
    resourceValueData = core::ptr::null_mut();

    if !stringValueData.is_null() {
        HeapFree(GetProcessHeap(), 0, stringValueData as PVOID);
    }
    stringValueData = core::ptr::null_mut();

    if !requirementsValueData.is_null() {
        HeapFree(GetProcessHeap(), 0, requirementsValueData as PVOID);
    }
    requirementsValueData = core::ptr::null_mut();

    return result;
}

unsafe extern "C" fn CopyKey(hDestKey: HKEY, lpDestSubKey: LPCWSTR, mut hSrcKey: HKEY, lpSrcSubKey: LPCWSTR) -> LONG {
    let mut lResult: LONG = 0;
    let mut dwDisposition: DWORD = 0;
    let mut hDestSubKey: HKEY = core::ptr::null_mut();
    let mut hSrcSubKey: HKEY = core::ptr::null_mut();
    let mut dwIndex: DWORD = 0;
    let mut dwType: DWORD = 0;
    let mut cbName: DWORD = 0;
    let mut cbData: DWORD = 0;
    let mut szSubKey: [WCHAR; 256] = [0; 256];
    let mut szValueName: [WCHAR; 256] = [0; 256];
    let mut szValueData: [BYTE; 512] = [0; 512];
    let mut ft: FILETIME = core::mem::zeroed();

    'done: {
        /* open the source subkey, if specified */
        if !lpSrcSubKey.is_null() {
            lResult = RegOpenKeyExW(
                hSrcKey,
                lpSrcSubKey,
                0 as DWORD,
                KEY_ALL_ACCESS as REGSAM,
                &raw mut hSrcSubKey,
            ) as LONG;
            if lResult != 0 {
                break 'done;
            }
            hSrcKey = hSrcSubKey;
        }

        /* create the destination subkey */
        lResult = RegCreateKeyExW(
            hDestKey,
            lpDestSubKey,
            0 as DWORD,
            core::ptr::null_mut::<WCHAR>(),
            REG_OPTION_NON_VOLATILE as DWORD,
            KEY_WRITE as REGSAM,
            core::ptr::null_mut::<_SECURITY_ATTRIBUTES>(),
            &raw mut hDestSubKey,
            &raw mut dwDisposition,
        ) as LONG;
        if lResult != 0 {
            break 'done;
        }

        /* copy all subkeys */
        dwIndex = 0 as DWORD;
        loop {
            cbName = ARRAY_SIZE!(szSubKey) as DWORD;
            let idx = dwIndex;
            dwIndex = dwIndex.wrapping_add(1);
            lResult = RegEnumKeyExW(
                hSrcKey,
                idx,
                &raw mut szSubKey as LPWSTR,
                &raw mut cbName,
                core::ptr::null_mut::<DWORD>(),
                core::ptr::null_mut::<WCHAR>(),
                core::ptr::null_mut::<DWORD>(),
                &raw mut ft,
            ) as LONG;
            if lResult == ERROR_SUCCESS as LONG {
                lResult = CopyKey(
                    hDestSubKey,
                    &raw mut szSubKey as *mut WCHAR as LPCWSTR,
                    hSrcKey,
                    &raw mut szSubKey as *mut WCHAR as LPCWSTR,
                );
                if lResult != 0 {
                    break 'done;
                }
            }
            if !(lResult == ERROR_SUCCESS as LONG) {
                break;
            }
        }

        /* copy all subvalues */
        dwIndex = 0 as DWORD;
        loop {
            cbName = ARRAY_SIZE!(szValueName) as DWORD;
            cbData = ARRAY_SIZE!(szValueData) as DWORD;
            let idx = dwIndex;
            dwIndex = dwIndex.wrapping_add(1);
            lResult = RegEnumValueW(
                hSrcKey,
                idx,
                &raw mut szValueName as LPWSTR,
                &raw mut cbName,
                core::ptr::null_mut::<DWORD>(),
                &raw mut dwType,
                &raw mut szValueData as LPBYTE,
                &raw mut cbData,
            ) as LONG;
            if lResult == ERROR_SUCCESS as LONG {
                lResult = RegSetValueExW(
                    hDestSubKey,
                    &raw mut szValueName as *mut WCHAR as LPCWSTR,
                    0 as DWORD,
                    dwType,
                    &raw mut szValueData as *mut BYTE,
                    cbData,
                ) as LONG;
                if lResult != 0 {
                    break 'done;
                }
            }
            if !(lResult == ERROR_SUCCESS as LONG) {
                break;
            }
        }

        lResult = ERROR_SUCCESS as LONG;
    }

    // done:
    if !hSrcSubKey.is_null() {
        RegCloseKey(hSrcSubKey);
    }
    if !hDestSubKey.is_null() {
        RegCloseKey(hDestSubKey);
    }
    if lResult != ERROR_SUCCESS as LONG {
        SHDeleteKey(hDestKey, lpDestSubKey);
    }
    return lResult;
}

unsafe extern "C" fn MoveKey(
    mut hDestKey: HKEY,
    mut lpDestSubKey: LPCWSTR,
    mut hSrcKey: HKEY,
    mut lpSrcSubKey: LPCWSTR,
) -> LONG {
    let mut lResult: LONG;

    if lpSrcSubKey.is_null() {
        return ERROR_INVALID_FUNCTION as LONG;
    }

    if _wcsicmp(lpDestSubKey, lpSrcSubKey) == 0 as i32 {
        /* Destination name equals source name */
        return ERROR_SUCCESS as LONG;
    }

    lResult = CopyKey(hDestKey, lpDestSubKey, hSrcKey, lpSrcSubKey);
    if lResult == ERROR_SUCCESS as LONG {
        SHDeleteKey(hSrcKey, lpSrcSubKey);
    }

    return lResult;
}
#[no_mangle]
pub unsafe extern "C" fn DeleteKey(mut hwnd: HWND, mut hKeyRoot: HKEY, mut keyPath: LPCWSTR) -> BOOL {
    let mut msg: [WCHAR; 128] = [0; 128];
    let mut caption: [WCHAR; 128] = [0; 128];
    let mut result: BOOL = (FALSE) as i32;
    let mut lRet: LONG = 0;
    let mut hKey: HKEY = core::ptr::null_mut();

    lRet = RegOpenKeyExW(
        hKeyRoot,
        keyPath,
        0 as DWORD,
        (KEY_READ | KEY_SET_VALUE) as REGSAM,
        core::ptr::addr_of_mut!(hKey),
    ) as LONG;
    if lRet != ERROR_SUCCESS as LONG {
        error_code_messagebox(hwnd, lRet as DWORD);
        return FALSE as BOOL;
    }

    LoadStringW(
        hInst,
        IDS_QUERY_DELETE_KEY_CONFIRM as UINT,
        core::ptr::addr_of_mut!(caption) as LPWSTR,
        ARRAY_SIZE!(caption) as ::core::ffi::c_int,
    );
    LoadStringW(
        hInst,
        IDS_QUERY_DELETE_KEY_ONE as UINT,
        core::ptr::addr_of_mut!(msg) as LPWSTR,
        ARRAY_SIZE!(msg) as ::core::ffi::c_int,
    );

    'done: {
        if MessageBoxW(
            (*g_pChildWnd).hWnd,
            core::ptr::addr_of_mut!(msg) as LPCWSTR,
            core::ptr::addr_of_mut!(caption) as LPCWSTR,
            (MB_ICONQUESTION | MB_YESNO) as UINT,
        ) != IDYES as i32
        {
            break 'done;
        }

        lRet = SHDeleteKey(hKeyRoot, keyPath) as LONG;
        if lRet != ERROR_SUCCESS as LONG {
            error(hwnd, (IDS_BAD_KEY) as INT, keyPath);
            break 'done;
        }
        result = (TRUE) as i32;
    }

    RegCloseKey(hKey);
    return result;
}
#[no_mangle]
pub unsafe extern "C" fn RenameKey(hKey: HKEY, lpSubKey: LPCWSTR, mut lpNewName: LPCWSTR) -> LONG {
    let mut s: LPCWSTR;
    let mut lpNewSubKey: LPWSTR = core::ptr::null_mut();
    let mut Ret: LONG = 0 as LONG;
    let mut cbNewSubKey: SIZE_T;

    if lpSubKey.is_null() {
        return Ret;
    }

    s = wcsrchr(lpSubKey, 0x005Cu16) as LPCWSTR;
    if !s.is_null() {
        s = s.offset(1);
        cbNewSubKey = ((s.offset_from(lpSubKey) as SIZE_T)
            + (wcslen(lpNewName) as SIZE_T)
            + (1 as SIZE_T))
            * (core::mem::size_of::<WCHAR>() as SIZE_T);
        lpNewSubKey = HeapAlloc(GetProcessHeap(), 0 as DWORD, cbNewSubKey) as LPWSTR;
        if !lpNewSubKey.is_null() {
            StringCbCopyNW(
                lpNewSubKey,
                (cbNewSubKey) as _,
                lpSubKey,
                ((s.offset_from(lpSubKey) as SIZE_T) * (core::mem::size_of::<WCHAR>() as SIZE_T)) as _,
            );
            StringCbCatW(lpNewSubKey, (cbNewSubKey) as _, lpNewName);
            lpNewName = lpNewSubKey as LPCWSTR;
        } else {
            return ERROR_NOT_ENOUGH_MEMORY as LONG;
        }
    }

    Ret = MoveKey(hKey, lpNewName, hKey, lpSubKey);

    if !lpNewSubKey.is_null() {
        HeapFree(GetProcessHeap(), 0 as DWORD, lpNewSubKey as PVOID);
    }
    return Ret;
}
#[no_mangle]
pub unsafe extern "C" fn RenameValue(mut hKey: HKEY, mut lpSubKey: LPCWSTR, mut lpDestValue: LPCWSTR, mut lpSrcValue: LPCWSTR) -> LONG {
    let mut lResult: LONG = 0;
    let mut hSubKey: HKEY = core::ptr::null_mut();
    let mut dwType: DWORD = 0;
    let mut cbData: DWORD = 0;
    let mut data: [BYTE; 512] = [0; 512];

    'done: {
        if !lpSubKey.is_null() {
            lResult = RegOpenKeyW(hKey, lpSubKey, core::ptr::addr_of_mut!(hSubKey)) as LONG;
            if lResult != ERROR_SUCCESS as LONG {
                break 'done;
            }
            hKey = hSubKey;
        }

        cbData = core::mem::size_of::<[BYTE; 512]>() as DWORD;
        lResult = RegQueryValueExW(
            hKey,
            lpSrcValue,
            core::ptr::null_mut::<DWORD>(),
            core::ptr::addr_of_mut!(dwType),
            data.as_mut_ptr(),
            core::ptr::addr_of_mut!(cbData),
        ) as LONG;
        if lResult != ERROR_SUCCESS as LONG {
            break 'done;
        }

        lResult = RegSetValueExW(
            hKey,
            lpDestValue,
            0 as DWORD,
            dwType,
            data.as_mut_ptr(),
            cbData,
        ) as LONG;
        if lResult != ERROR_SUCCESS as LONG {
            break 'done;
        }

        RegDeleteValue(hKey, lpSrcValue);
    }

    if !hSubKey.is_null() {
        RegCloseKey(hSubKey);
    }
    return lResult;
}
#[no_mangle]
pub unsafe extern "C" fn QueryStringValue(mut hKey: HKEY, lpSubKey: LPCWSTR, lpValueName: LPCWSTR, pszBuffer: LPWSTR, dwBufferLen: DWORD) -> LONG {
    let mut lResult: LONG = 0;
    let mut hSubKey: HKEY = core::ptr::null_mut();
    let mut cbData: DWORD = 0;
    let mut dwType: DWORD = 0;

    'done: {
        if !lpSubKey.is_null() {
            lResult = RegOpenKeyW(hKey, lpSubKey, core::ptr::addr_of_mut!(hSubKey)) as LONG;
            if lResult != ERROR_SUCCESS as LONG {
                break 'done;
            }
            hKey = hSubKey;
        }

        cbData = (dwBufferLen.wrapping_sub(1 as DWORD))
            .wrapping_mul(core::mem::size_of::<WCHAR>() as DWORD);
        lResult = RegQueryValueExW(
            hKey,
            lpValueName,
            core::ptr::null_mut::<DWORD>(),
            core::ptr::addr_of_mut!(dwType),
            pszBuffer as LPBYTE,
            core::ptr::addr_of_mut!(cbData),
        ) as LONG;
        if lResult != ERROR_SUCCESS as LONG {
            break 'done;
        }
        if dwType != REG_SZ as DWORD {
            lResult = -(1 as LONG);
            break 'done;
        }

        *pszBuffer.offset((cbData / core::mem::size_of::<WCHAR>() as DWORD) as isize) = 0x0000u16;
    }

    // done:
    if lResult != ERROR_SUCCESS as LONG {
        *pszBuffer.offset(0 as isize) = 0x0000u16;
    }
    if !hSubKey.is_null() {
        RegCloseKey(hSubKey);
    }
    return lResult;
}
#[no_mangle]
pub unsafe extern "C" fn GetKeyName(pszDest: LPWSTR, iDestLength: size_t, hRootKey: HKEY, lpSubKey: LPCWSTR) -> BOOL {
    let pszRootKey: LPCWSTR;

    if hRootKey == HKEY_CLASSES_ROOT {
        pszRootKey = RUSTCONV_WSTR_87D16031626E.as_ptr();
    } else if hRootKey == HKEY_CURRENT_USER {
        pszRootKey = RUSTCONV_WSTR_D0EE0F231465.as_ptr();
    } else if hRootKey == HKEY_LOCAL_MACHINE {
        pszRootKey = RUSTCONV_WSTR_50C930882486.as_ptr();
    } else if hRootKey == HKEY_USERS {
        pszRootKey = RUSTCONV_WSTR_9C98935C198E.as_ptr();
    } else if hRootKey == HKEY_CURRENT_CONFIG {
        pszRootKey = RUSTCONV_WSTR_111FD57AB4CB.as_ptr();
    } else if hRootKey == HKEY_DYN_DATA {
        pszRootKey = RUSTCONV_WSTR_5CDE252B65C7.as_ptr();
    } else {
        return (FALSE) as BOOL;
    }

    if *lpSubKey.add(0 as usize) != 0 {
        _snwprintf(pszDest, iDestLength, RUSTCONV_WSTR_BA2342D760A2.as_ptr(), pszRootKey, lpSubKey);
    } else {
        _snwprintf(pszDest, iDestLength, RUSTCONV_WSTR_FB47CCC40FE6.as_ptr(), pszRootKey);
    }
    return (TRUE) as BOOL;
}
