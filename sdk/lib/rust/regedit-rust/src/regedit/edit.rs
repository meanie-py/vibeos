unsafe extern "C" fn OnResourceNotify(hwndDlg: HWND, phdr: *mut NMHDR) -> BOOL {
    let lpnmlv: LPNMLISTVIEW = phdr as LPNMLISTVIEW;

    match (*phdr).idFrom as u32 {
        IDC_PORT_LIST | IDC_MEMORY_LIST | IDC_DMA_LIST | IDC_IRQ_LIST | IDC_DEVICE_LIST => {
            match (*phdr).code {
                NM_CLICK => {
                    if (*lpnmlv).iItem != -1 {
                        let mut pDescriptor: PCM_PARTIAL_RESOURCE_DESCRIPTOR = core::ptr::null_mut();
                        let mut item: LVITEMW = core::mem::zeroed();

                        item.mask = LVIF_PARAM;
                        item.iItem = (*lpnmlv).iItem;
                        item.iSubItem = 0;

                        if ListView_GetItem!((*phdr).hwndFrom, core::ptr::addr_of_mut!(item)) != 0 {
                            pDescriptor = item.lParam as PCM_PARTIAL_RESOURCE_DESCRIPTOR;

                            EnableWindow(GetDlgItem(hwndDlg, (IDC_UNDETERMINED as i32)),
                                         (((*pDescriptor).ShareDisposition as i32) as u32 == CmResourceShareUndetermined) as BOOL);

                            EnableWindow(GetDlgItem(hwndDlg, (IDC_SHARED as i32)),
                                         (((*pDescriptor).ShareDisposition as i32) as u32 == CmResourceShareShared) as BOOL);

                            EnableWindow(GetDlgItem(hwndDlg, (IDC_DEVICE_EXCLUSIVE as i32)),
                                         (((*pDescriptor).ShareDisposition as i32) as u32 == CmResourceShareDeviceExclusive) as BOOL);

                            EnableWindow(GetDlgItem(hwndDlg, (IDC_DRIVER_EXCLUSIVE as i32)),
                                         (((*pDescriptor).ShareDisposition as i32) as u32 == CmResourceShareDriverExclusive) as BOOL);
                        }
                    } else {
                        EnableWindow(GetDlgItem(hwndDlg, (IDC_UNDETERMINED as i32)), (FALSE) as BOOL);
                        EnableWindow(GetDlgItem(hwndDlg, (IDC_SHARED as i32)), (FALSE) as BOOL);
                        EnableWindow(GetDlgItem(hwndDlg, (IDC_DEVICE_EXCLUSIVE as i32)), (FALSE) as BOOL);
                        EnableWindow(GetDlgItem(hwndDlg, (IDC_DRIVER_EXCLUSIVE as i32)), (FALSE) as BOOL);
                    }
                }
                _ => {}
            }
        }
        _ => {}
    }

    return (FALSE) as BOOL;
}

