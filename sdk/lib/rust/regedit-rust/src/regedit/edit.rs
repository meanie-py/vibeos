unsafe extern "C" fn AddFullResourcesToList(hwnd: HWND) {
    let mut pFullDescriptor: PCM_FULL_RESOURCE_DESCRIPTOR = core::ptr::null_mut();
    let mut buffer: [WCHAR; 80] = [0; 80];
    let mut item: LVITEMW = core::mem::zeroed();
    let mut i: ULONG;
    let mut iItem: INT;

    pFullDescriptor = (&raw mut (*resourceValueData).List as *mut CM_FULL_RESOURCE_DESCRIPTOR)
        .add(0) as PCM_FULL_RESOURCE_DESCRIPTOR;
    i = 0;
    while i < (*resourceValueData).Count {
        wsprintf(
            buffer.as_mut_ptr(),
            RUSTCONV_WSTR_F3C6A8F2AC47.as_ptr(),
            (*pFullDescriptor).BusNumber,
        );

        item.mask = LVIF_TEXT;
        item.iItem = i as INT;
        item.iSubItem = 0;
        item.state = 0;
        item.stateMask = 0;
        item.pszText = buffer.as_mut_ptr();
        item.cchTextMax = wcslen(item.pszText as *const WCHAR) as INT;

        iItem = ListView_InsertItem!(hwnd, &raw mut item);
        if iItem != -1 {
            GetInterfaceType(
                (*pFullDescriptor).InterfaceType,
                buffer.as_mut_ptr(),
                80,
            );
            ListView_SetItemText!(hwnd, iItem, 1, buffer.as_mut_ptr());
        }
        pFullDescriptor = (&raw mut (*pFullDescriptor).PartialResourceList.PartialDescriptors
            as *mut CM_PARTIAL_RESOURCE_DESCRIPTOR)
            .add((*pFullDescriptor).PartialResourceList.Count as usize)
            as PVOID as PCM_FULL_RESOURCE_DESCRIPTOR;
        i = i.wrapping_add(1);
    }
}

unsafe extern "C" fn OnResourceListNotify(mut hwndDlg: HWND, mut phdr: *mut NMHDR) -> BOOL {
    let mut lpnmlv: LPNMLISTVIEW = phdr as LPNMLISTVIEW;
    if (*phdr).idFrom == (IDC_RESOURCE_LIST as _) {
        if (*phdr).code == NM_CLICK {
            fullResourceIndex = (*lpnmlv).iItem as INT;
            EnableWindow(
                GetDlgItem(hwndDlg, (IDC_SHOW_RESOURCE as i32)),
                ((*lpnmlv).iItem != -1) as BOOL,
            );
        } else if (*phdr).code == NM_DBLCLK {
            if (*lpnmlv).iItem != -1 {
                fullResourceIndex = (*lpnmlv).iItem as INT;
                DialogBoxW!(
                    0,
                    MAKEINTRESOURCEW!(IDD_EDIT_RESOURCE),
                    hwndDlg,
                    Some(modify_resource_dlgproc),
                );
            }
        }
    }

    return (FALSE) as BOOL;
}

