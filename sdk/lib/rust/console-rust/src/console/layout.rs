pub unsafe extern "C" fn RegisterWinPrevClass(mut hInstance: HINSTANCE) -> BOOL {
    let mut WndClass: WNDCLASSW = core::mem::zeroed::<WNDCLASSW>();
    WndClass.lpszClassName = (WIN_PREVIEW_CLASS).as_ptr() as LPCWSTR;
    WndClass.lpfnWndProc = Some(WinPrevProc);
    WndClass.style = 0 as UINT;
    WndClass.hInstance = hInstance;
    WndClass.hIcon = core::ptr::null_mut();
    WndClass.hCursor = LoadCursorW(
        core::ptr::null_mut(),
        IDC_ARROW as usize as LPCWSTR,
    );
    WndClass.hbrBackground =
        ((COLOR_BACKGROUND + 1) as usize) as HBRUSH;
    WndClass.lpszMenuName = core::ptr::null();
    WndClass.cbClsExtra = 0 as i32;
    WndClass.cbWndExtra = 0 as i32;

    return (RegisterClassW(core::ptr::addr_of_mut!(WndClass)) != 0 as _)
        as BOOL;
}
