unsafe extern "C" fn WinPrev_OnDisplayChange(pData: PWINPREV_DATA) {
    (*pData).siVirtScr.cx = GetSystemMetrics((SM_CXVIRTUALSCREEN) as i32) as LONG;
    (*pData).siVirtScr.cy = GetSystemMetrics((SM_CYVIRTUALSCREEN) as i32) as LONG;

    if (*pData).siVirtScr.cx * (*pData).rcMaxArea.bottom
        >= (*pData).siVirtScr.cy * (*pData).rcMaxArea.right
    {
        (*pData).siPreview.cx = MulDiv(
            (*pData).siVirtScr.cx,
            (*pData).rcMaxArea.right,
            (*pData).siVirtScr.cx,
        ) as LONG;
        (*pData).siPreview.cy = MulDiv(
            (*pData).siVirtScr.cy,
            (*pData).rcMaxArea.right,
            (*pData).siVirtScr.cx,
        ) as LONG;
    } else {
        (*pData).siPreview.cx = MulDiv(
            (*pData).siVirtScr.cx,
            (*pData).rcMaxArea.bottom,
            (*pData).siVirtScr.cy,
        ) as LONG;
        (*pData).siPreview.cy = MulDiv(
            (*pData).siVirtScr.cy,
            (*pData).rcMaxArea.bottom,
            (*pData).siVirtScr.cy,
        ) as LONG;
    }

    SetWindowPos(
        (*pData).hWnd,
        core::ptr::null_mut(),
        0,
        0,
        (*pData).siPreview.cx,
        (*pData).siPreview.cy,
        (SWP_NOMOVE | SWP_NOZORDER | SWP_NOACTIVATE) as UINT,
    );
}

unsafe extern "C" fn WinPrev_OnDraw(hDC: HDC, pData: PWINPREV_DATA) {
    let pConInfo: PCONSOLE_STATE_INFO = (*pData).pData as PCONSOLE_STATE_INFO;
    let mut hBrush: HBRUSH = core::ptr::null_mut();
    let mut rcWin: RECT = core::mem::zeroed();
    let mut fRect: RECT = core::mem::zeroed();
    let mut siFrame: SIZE = core::mem::zeroed();
    let mut siButton: SIZE = core::mem::zeroed();
    let mut siScroll: SIZE = core::mem::zeroed();
    let mut resize: SIZE = core::mem::zeroed();
    let mut rcItem: RECT = core::mem::zeroed();

    GetClientRect((*pData).hWnd, &raw mut rcItem);

    siFrame.cx = GetSystemMetrics((SM_CXFRAME) as i32);
    if siFrame.cx > 0 {
        siFrame.cx = RescaleCX!(pData, siFrame.cx);
        siFrame.cx = max(1, siFrame.cx);
    }
    siFrame.cy = GetSystemMetrics((SM_CYFRAME) as i32);
    if siFrame.cy > 0 {
        siFrame.cy = RescaleCY!(pData, siFrame.cy);
        siFrame.cy = max(1, siFrame.cy);
    }

    siButton.cx = GetSystemMetrics((SM_CXSIZE) as i32);
    siButton.cx = RescaleCX!(pData, siButton.cx);
    siButton.cx = max(1, siButton.cx);

    siButton.cy = GetSystemMetrics((SM_CYSIZE) as i32);
    siButton.cy = RescaleCY!(pData, siButton.cy);
    siButton.cy = max(1, siButton.cy);

    siButton.cy *= 2;

    siScroll.cx = GetSystemMetrics((SM_CXVSCROLL) as i32);
    siScroll.cx = RescaleCX!(pData, siScroll.cx);
    siScroll.cx = max(1, siScroll.cx);

    siScroll.cy = GetSystemMetrics((SM_CYHSCROLL) as i32);
    siScroll.cy = RescaleCY!(pData, siScroll.cy);
    siScroll.cy = max(1, siScroll.cy);

    if FontPreview.hFont.is_null() {
        RefreshFontPreview(&raw mut FontPreview, pConInfo);
    }

    SetRect(
        &raw mut rcWin,
        0,
        0,
        ((*pConInfo).WindowSize.X as UINT).wrapping_mul(FontPreview.CharWidth) as ::core::ffi::c_int,
        ((*pConInfo).WindowSize.Y as UINT).wrapping_mul(FontPreview.CharHeight) as ::core::ffi::c_int,
    );
    RescaleRect!(pData, rcWin);

    if (*pConInfo).WindowSize.X < (*pConInfo).ScreenBufferSize.X {
        rcWin.bottom += siScroll.cy;
    } else {
        siScroll.cy = 0;
    }
    if (*pConInfo).WindowSize.Y < (*pConInfo).ScreenBufferSize.Y {
        rcWin.right += siScroll.cx;
    } else {
        siScroll.cx = 0;
    }

    rcWin.top -= siButton.cy - 1;

    resize.cx = if siFrame.cx > 0 {
        1 + siFrame.cx
    } else {
        0
    };
    resize.cy = if siFrame.cy > 0 {
        1 + siFrame.cy
    } else {
        0
    };

    resize.cx += 1;
    resize.cy += 1;

    InflateRect(&raw mut rcWin, resize.cx, resize.cy);

    OffsetRect(&raw mut rcWin, -rcWin.left, -rcWin.top);

    if (*pConInfo).WindowPosition.x as ::core::ffi::c_ulong == MAXDWORD as ::core::ffi::c_ulong
        && (*pConInfo).WindowPosition.y as ::core::ffi::c_ulong == MAXDWORD as ::core::ffi::c_ulong
    {
        OffsetRect(&raw mut rcWin, 0, 0);
    } else {
        OffsetRect(
            &raw mut rcWin,
            RescaleCX!(pData, (*pConInfo).WindowPosition.x as ::core::ffi::c_int),
            RescaleCY!(pData, (*pConInfo).WindowPosition.y as ::core::ffi::c_int),
        );
    }

    FillRect(hDC, &raw mut rcItem as LPCRECT, GetSysColorBrush((COLOR_BACKGROUND) as i32));

    FillRect(hDC, &raw mut rcWin as LPCRECT, GetSysColorBrush((COLOR_WINDOWFRAME) as i32));
    InflateRect(&raw mut rcWin, -1, -1);

    hBrush = GetSysColorBrush((COLOR_ACTIVEBORDER) as i32);
    if siFrame.cx > 0 {
        SetRect(
            &raw mut fRect,
            rcWin.left,
            rcWin.top,
            rcWin.left + siFrame.cx,
            rcWin.bottom,
        );
        FillRect(hDC, &raw mut fRect as LPCRECT, hBrush);
        SetRect(
            &raw mut fRect,
            rcWin.right - siFrame.cx,
            rcWin.top,
            rcWin.right,
            rcWin.bottom,
        );
        FillRect(hDC, &raw mut fRect as LPCRECT, hBrush);

        InflateRect(&raw mut rcWin, -siFrame.cx, 0);
    }
    if siFrame.cy > 0 {
        SetRect(
            &raw mut fRect,
            rcWin.left,
            rcWin.top,
            rcWin.right,
            rcWin.top + siFrame.cy,
        );
        FillRect(hDC, &raw mut fRect as LPCRECT, hBrush);
        SetRect(
            &raw mut fRect,
            rcWin.left,
            rcWin.bottom - siFrame.cy,
            rcWin.right,
            rcWin.bottom,
        );
        FillRect(hDC, &raw mut fRect as LPCRECT, hBrush);

        InflateRect(&raw mut rcWin, 0, -siFrame.cy);
    }

    if siFrame.cx > 0 || siFrame.cy > 0 {
        InflateRect(
            &raw mut rcWin,
            if siFrame.cx > 0 { -1 } else { 0 },
            if siFrame.cy > 0 { -1 } else { 0 },
        );
    }

    hBrush = GetSysColorBrush((COLOR_BTNFACE) as i32);

    SetRect(
        &raw mut fRect,
        rcWin.left,
        rcWin.top,
        rcWin.left + siButton.cx,
        rcWin.top + siButton.cy - 2,
    );
    FillRect(hDC, &raw mut fRect as LPCRECT, hBrush);
    fRect.right += 1;

    SetRect(
        &raw mut fRect,
        fRect.right,
        fRect.top,
        rcWin.right - 2 * (siButton.cx + 1),
        fRect.bottom,
    );
    FillRect(hDC, &raw mut fRect as LPCRECT, GetSysColorBrush((COLOR_ACTIVECAPTION) as i32));
    fRect.right += 1;

    SetRect(
        &raw mut fRect,
        fRect.right,
        fRect.top,
        fRect.right + siButton.cx,
        fRect.bottom,
    );
    FillRect(hDC, &raw mut fRect as LPCRECT, hBrush);
    fRect.right += 1;

    SetRect(
        &raw mut fRect,
        fRect.right,
        fRect.top,
        fRect.right + siButton.cx,
        fRect.bottom,
    );
    FillRect(hDC, &raw mut fRect as LPCRECT, hBrush);

    rcWin.top += siButton.cy - 1;

    if siScroll.cy > 0 || siScroll.cx > 0 {
        let mut right: LONG = 0;
        let mut bottom: LONG = 0;

        right = rcWin.right;
        bottom = rcWin.bottom;

        if siScroll.cy > 0 && siScroll.cx > 0 {
            right -= 1 + siScroll.cx;
            bottom -= 1 + siScroll.cy;
        }

        hBrush = GetSysColorBrush((COLOR_SCROLLBAR) as i32);

        if siScroll.cy > 0 {
            SetRect(
                &raw mut fRect,
                rcWin.left,
                rcWin.bottom - siScroll.cy,
                right,
                rcWin.bottom,
            );
            FillRect(hDC, &raw mut fRect as LPCRECT, hBrush);
        }

        if siScroll.cx > 0 {
            SetRect(
                &raw mut fRect,
                rcWin.right - siScroll.cx,
                rcWin.top,
                rcWin.right,
                bottom,
            );
            FillRect(hDC, &raw mut fRect as LPCRECT, hBrush);
        }

        if siScroll.cy > 0 && siScroll.cx > 0 {
            SetRect(
                &raw mut fRect,
                rcWin.right - siScroll.cx,
                rcWin.bottom - siScroll.cy,
                rcWin.right,
                rcWin.bottom,
            );
            FillRect(hDC, &raw mut fRect as LPCRECT, hBrush);
        }

        rcWin.right -= siScroll.cx;
        rcWin.bottom -= siScroll.cy;
    }

    hBrush = CreateSolidBrush(
        (*pConInfo).ColorTable[BkgdAttribFromAttrib!((*pConInfo).ScreenAttributes) as usize],
    );
    FillRect(
        hDC,
        &raw mut rcWin as LPCRECT,
        if !hBrush.is_null() {
            hBrush
        } else {
            GetStockObject((BLACK_BRUSH as i32)) as HBRUSH
        },
    );
    if !hBrush.is_null() {
        DeleteObject((hBrush).cast());
    }
}

unsafe extern "system" fn WinPrevProc(hWnd: HWND, msg: UINT, wParam: WPARAM, lParam: LPARAM) -> LRESULT {
    let mut pData: PWINPREV_DATA = core::ptr::null_mut::<WINPREV_DATA>();

    pData = GetWindowLongPtrW(hWnd, GWLP_USERDATA) as PWINPREV_DATA;

    match msg {
        WM_CREATE => {
            pData = HeapAlloc(
                GetProcessHeap(),
                HEAP_ZERO_MEMORY as DWORD,
                core::mem::size_of::<WINPREV_DATA>() as SIZE_T,
            ) as PWINPREV_DATA;
            if pData.is_null() {
                /* We failed to allocate our private data, halt the window creation */
                return (-(1)) as LRESULT;
            }
            (*pData).hWnd = hWnd;
            (*pData).pData = ConInfo as PVOID;
            GetClientRect((*pData).hWnd, &raw mut (*pData).rcMaxArea);
            // LPCREATESTRUCT::cx and cy give window (not client) size
            WinPrev_OnDisplayChange(pData);
            SetWindowLongPtrW(hWnd, GWLP_USERDATA, pData as LONG_PTR);
        }

        WM_DESTROY => {
            if !pData.is_null() {
                HeapFree(GetProcessHeap(), 0 as DWORD, pData as PVOID);
            }
        }

        WM_DISPLAYCHANGE => {
            WinPrev_OnDisplayChange(pData);
            UpdateWindow(hWnd);
            // InvalidateRect(hWnd, NULL, FALSE);
        }

        WM_SIZE => {}

        WM_ERASEBKGND => {
            return 1 as LRESULT;
        }

        WM_PAINT => {
            let mut ps: PAINTSTRUCT = core::mem::zeroed::<PAINTSTRUCT>();
            BeginPaint(hWnd, &raw mut ps);
            WinPrev_OnDraw(ps.hdc, pData);
            EndPaint(hWnd, &raw mut ps);
            return 0 as LRESULT;
        }

        _ => {}
    }

    return DefWindowProcW(hWnd, msg, wParam, lParam);
}
#[no_mangle]
pub unsafe extern "C" fn PaintText(drawItem: LPDRAWITEMSTRUCT, pConInfo: PCONSOLE_STATE_INFO, TextMode: TEXT_TYPE) {
    let mut CurrentAttrib: USHORT = 0;
    let mut pbkColor: COLORREF = 0;
    let mut ptColor: COLORREF = 0;
    let mut nbkColor: COLORREF = 0;
    let mut ntColor: COLORREF = 0;
    let mut hBrush: HBRUSH = core::ptr::null_mut();
    let mut hOldFont: HFONT = core::ptr::null_mut();

    if TextMode as u32 == Screen as u32 {
        CurrentAttrib = (*pConInfo).ScreenAttributes;
    } else if TextMode as u32 == Popup as u32 {
        CurrentAttrib = (*pConInfo).PopupAttributes;
    } else {
        return;
    }

    nbkColor = (*pConInfo).ColorTable[BkgdAttribFromAttrib!(CurrentAttrib) as usize];
    ntColor = (*pConInfo).ColorTable[TextAttribFromAttrib!(CurrentAttrib) as usize];

    /* Draw the console background */
    hBrush = CreateSolidBrush(nbkColor);
    FillRect(
        (*drawItem).hDC,
        core::ptr::addr_of_mut!((*drawItem).rcItem),
        if !hBrush.is_null() {
            hBrush as *mut core::ffi::c_void
        } else {
            GetStockObject((BLACK_BRUSH as i32)) as *mut core::ffi::c_void
        } as HBRUSH,
    );
    if !hBrush.is_null() {
        DeleteObject(hBrush as HGDIOBJ);
    }

    /* Refresh the font preview, getting a new font if necessary */
    if FontPreview.hFont.is_null() {
        RefreshFontPreview(core::ptr::addr_of_mut!(FontPreview), pConInfo);
    }
    /* Recheck hFont since RefreshFontPreview() may not have updated it */
    if FontPreview.hFont.is_null() {
        return;
    }

    /* Draw the preview text using the current font */
    hOldFont = SelectObject((*drawItem).hDC, FontPreview.hFont as HGDIOBJ) as HFONT;
    // if (!hOldFont) return;

    /* Add a few space between the preview window border and the text sample */
    InflateRect(
        core::ptr::addr_of_mut!((*drawItem).rcItem),
        -2,
        -2,
    );

    ptColor = SetTextColor((*drawItem).hDC, ntColor);
    pbkColor = SetBkColor((*drawItem).hDC, nbkColor);
    DrawTextW(
        (*drawItem).hDC,
        core::ptr::addr_of!(szPreviewText) as LPCWSTR,
        wcslen(core::ptr::addr_of!(szPreviewText) as *const u16) as INT,
        core::ptr::addr_of_mut!((*drawItem).rcItem),
        0,
    );
    SetTextColor((*drawItem).hDC, ptColor);
    SetBkColor((*drawItem).hDC, pbkColor);

    SelectObject((*drawItem).hDC, hOldFont as HGDIOBJ);
}
#[no_mangle]
pub unsafe extern "system" fn LayoutProc(
    hDlg: HWND,
    uMsg: UINT,
    wParam: WPARAM,
    lParam: LPARAM,
) -> INT_PTR {
    match uMsg {
        WM_INITDIALOG => {
            /* Multi-monitor support */
            let mut xVirtScr: LONG = 0;
            let mut yVirtScr: LONG = 0;
            let mut cxVirtScr: LONG = 0;
            let mut cyVirtScr: LONG = 0;
            let mut cxFrame: LONG = 0;
            let mut cyFrame: LONG = 0;

            xVirtScr = GetSystemMetrics((SM_XVIRTUALSCREEN) as i32) as LONG;
            yVirtScr = GetSystemMetrics((SM_YVIRTUALSCREEN) as i32) as LONG;
            cxVirtScr = GetSystemMetrics((SM_CXVIRTUALSCREEN) as i32) as LONG;
            cyVirtScr = GetSystemMetrics((SM_CYVIRTUALSCREEN) as i32) as LONG;
            cxFrame = GetSystemMetrics((SM_CXFRAME) as i32) as LONG;
            cyFrame = GetSystemMetrics((SM_CYFRAME) as i32) as LONG;

            SendDlgItemMessageW(hDlg, (IDC_UPDOWN_SCREEN_BUFFER_HEIGHT as i32), UDM_SETRANGE, 0, MAKELONG!(9999, 1) as LPARAM);
            SendDlgItemMessageW(hDlg, (IDC_UPDOWN_SCREEN_BUFFER_WIDTH as i32), UDM_SETRANGE, 0, MAKELONG!(9999, 1) as LPARAM);
            SendDlgItemMessageW(hDlg, (IDC_UPDOWN_WINDOW_SIZE_HEIGHT as i32), UDM_SETRANGE, 0, MAKELONG!(9999, 1) as LPARAM);
            SendDlgItemMessageW(hDlg, (IDC_UPDOWN_WINDOW_SIZE_WIDTH as i32), UDM_SETRANGE, 0, MAKELONG!(9999, 1) as LPARAM);

            SetDlgItemInt(hDlg, (IDC_EDIT_SCREEN_BUFFER_HEIGHT as i32), (*ConInfo).ScreenBufferSize.Y as UINT, (FALSE) as BOOL);
            SetDlgItemInt(hDlg, (IDC_EDIT_SCREEN_BUFFER_WIDTH as i32), (*ConInfo).ScreenBufferSize.X as UINT, (FALSE) as BOOL);
            SetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_SIZE_HEIGHT as i32), (*ConInfo).WindowSize.Y as UINT, (FALSE) as BOOL);
            SetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_SIZE_WIDTH as i32), (*ConInfo).WindowSize.X as UINT, (FALSE) as BOOL);

            SendDlgItemMessageW(hDlg, (IDC_UPDOWN_WINDOW_POS_LEFT as i32), UDM_SETRANGE, 0,
                MAKELONG!(xVirtScr + cxVirtScr - cxFrame, xVirtScr - cxFrame) as LPARAM);
            SendDlgItemMessageW(hDlg, (IDC_UPDOWN_WINDOW_POS_TOP as i32), UDM_SETRANGE, 0,
                MAKELONG!(yVirtScr + cyVirtScr - cyFrame, yVirtScr - cyFrame) as LPARAM);

            SetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_POS_LEFT as i32), (*ConInfo).WindowPosition.x as UINT, (TRUE) as BOOL);
            SetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_POS_TOP as i32), (*ConInfo).WindowPosition.y as UINT, (TRUE) as BOOL);

            if (*ConInfo).AutoPosition != 0 {
                EnableDlgItem!(hDlg, (IDC_EDIT_WINDOW_POS_LEFT as i32), (FALSE) as i32);
                EnableDlgItem!(hDlg, (IDC_EDIT_WINDOW_POS_TOP as i32), (FALSE) as i32);
                EnableDlgItem!(hDlg, (IDC_UPDOWN_WINDOW_POS_LEFT as i32), (FALSE) as i32);
                EnableDlgItem!(hDlg, (IDC_UPDOWN_WINDOW_POS_TOP as i32), (FALSE) as i32);
            }
            CheckDlgButton(hDlg, (IDC_CHECK_SYSTEM_POS_WINDOW as i32),
                (if (*ConInfo).AutoPosition != 0 { BST_CHECKED } else { BST_UNCHECKED }) as UINT);

            return (TRUE) as INT_PTR;
        }

        WM_DISPLAYCHANGE => {
            /* Retransmit to the preview window */
            SendDlgItemMessageW(hDlg, (IDC_STATIC_LAYOUT_WINDOW_PREVIEW as i32),
                WM_DISPLAYCHANGE, wParam, lParam);
        }

        WM_NOTIFY => {
            let lppsn: LPPSHNOTIFY = lParam as LPPSHNOTIFY;

            if (*lppsn).hdr.code == (UDN_DELTAPOS) as u32 {
                let lpnmud: LPNMUPDOWN = lParam as LPNMUPDOWN;
                let mut wheight: DWORD = 0;
                let mut wwidth: DWORD = 0;
                let mut sheight: DWORD = 0;
                let mut swidth: DWORD = 0;
                let mut left: DWORD = 0;
                let mut top: DWORD = 0;

                if (*lppsn).hdr.idFrom == (IDC_UPDOWN_WINDOW_SIZE_WIDTH as UINT_PTR) {
                    wwidth = ((*lpnmud).iPos + (*lpnmud).iDelta) as DWORD;
                } else {
                    wwidth = GetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_SIZE_WIDTH as i32), core::ptr::null_mut(), (FALSE) as BOOL) as DWORD;
                }

                if (*lppsn).hdr.idFrom == (IDC_UPDOWN_WINDOW_SIZE_HEIGHT as UINT_PTR) {
                    wheight = ((*lpnmud).iPos + (*lpnmud).iDelta) as DWORD;
                } else {
                    wheight = GetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_SIZE_HEIGHT as i32), core::ptr::null_mut(), (FALSE) as BOOL) as DWORD;
                }

                if (*lppsn).hdr.idFrom == (IDC_UPDOWN_SCREEN_BUFFER_WIDTH as UINT_PTR) {
                    swidth = ((*lpnmud).iPos + (*lpnmud).iDelta) as DWORD;
                } else {
                    swidth = GetDlgItemInt(hDlg, (IDC_EDIT_SCREEN_BUFFER_WIDTH as i32), core::ptr::null_mut(), (FALSE) as BOOL) as DWORD;
                }

                if (*lppsn).hdr.idFrom == (IDC_UPDOWN_SCREEN_BUFFER_HEIGHT as UINT_PTR) {
                    sheight = ((*lpnmud).iPos + (*lpnmud).iDelta) as DWORD;
                } else {
                    sheight = GetDlgItemInt(hDlg, (IDC_EDIT_SCREEN_BUFFER_HEIGHT as i32), core::ptr::null_mut(), (FALSE) as BOOL) as DWORD;
                }

                if (*lppsn).hdr.idFrom == (IDC_UPDOWN_WINDOW_POS_LEFT as UINT_PTR) {
                    left = ((*lpnmud).iPos + (*lpnmud).iDelta) as DWORD;
                } else {
                    left = GetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_POS_LEFT as i32), core::ptr::null_mut(), (TRUE) as BOOL) as DWORD;
                }

                if (*lppsn).hdr.idFrom == (IDC_UPDOWN_WINDOW_POS_TOP as UINT_PTR) {
                    top = ((*lpnmud).iPos + (*lpnmud).iDelta) as DWORD;
                } else {
                    top = GetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_POS_TOP as i32), core::ptr::null_mut(), (TRUE) as BOOL) as DWORD;
                }

                if (*lppsn).hdr.idFrom == (IDC_UPDOWN_WINDOW_SIZE_WIDTH as UINT_PTR) || (*lppsn).hdr.idFrom == (IDC_UPDOWN_WINDOW_SIZE_HEIGHT as UINT_PTR) {
                    /* Automatically adjust screen buffer size when window size enlarges */
                    if wwidth >= swidth {
                        SetDlgItemInt(hDlg, (IDC_EDIT_SCREEN_BUFFER_WIDTH as i32), wwidth as UINT, (TRUE) as BOOL);
                        swidth = wwidth;
                    }
                    if wheight >= sheight {
                        SetDlgItemInt(hDlg, (IDC_EDIT_SCREEN_BUFFER_HEIGHT as i32), wheight as UINT, (TRUE) as BOOL);
                        sheight = wheight;
                    }
                }

                /* Be sure that the (new) screen buffer sizes are in the correct range */
                swidth = min(max(swidth, 1), 0xFFFF);
                sheight = min(max(sheight, 1), 0xFFFF);

                if (*lppsn).hdr.idFrom == (IDC_UPDOWN_SCREEN_BUFFER_WIDTH as UINT_PTR) || (*lppsn).hdr.idFrom == (IDC_UPDOWN_SCREEN_BUFFER_HEIGHT as UINT_PTR) {
                    /* Automatically adjust window size when screen buffer decreases */
                    if wwidth > swidth {
                        SetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_SIZE_WIDTH as i32), swidth as UINT, (TRUE) as BOOL);
                        wwidth = swidth;
                    }
                    if wheight > sheight {
                        SetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_SIZE_HEIGHT as i32), sheight as UINT, (TRUE) as BOOL);
                        wheight = sheight;
                    }
                }

                (*ConInfo).ScreenBufferSize.X = swidth as SHORT;
                (*ConInfo).ScreenBufferSize.Y = sheight as SHORT;
                (*ConInfo).WindowSize.X = wwidth as SHORT;
                (*ConInfo).WindowSize.Y = wheight as SHORT;
                (*ConInfo).WindowPosition.x = left as LONG;
                (*ConInfo).WindowPosition.y = top as LONG;

                InvalidateRect(GetDlgItem(hDlg, (IDC_STATIC_LAYOUT_WINDOW_PREVIEW as i32)), core::ptr::null_mut(), (TRUE) as BOOL);
                PropSheet_Changed!(GetParent(hDlg), hDlg);
            }
        }

        WM_COMMAND => {
            if (HIWORD!(wParam)) as u32 == EN_KILLFOCUS {
                match (LOWORD!(wParam)) as u32 {
                    IDC_EDIT_SCREEN_BUFFER_WIDTH => {
                        let mut swidth: DWORD = 0;
                        let mut wwidth: DWORD = 0;

                        swidth = GetDlgItemInt(hDlg, (IDC_EDIT_SCREEN_BUFFER_WIDTH as i32), core::ptr::null_mut(), (FALSE) as BOOL) as DWORD;
                        wwidth = GetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_SIZE_WIDTH as i32), core::ptr::null_mut(), (FALSE) as BOOL) as DWORD;

                        /* Be sure that the (new) screen buffer width is in the correct range */
                        swidth = min(max(swidth, 1), 0xFFFF);

                        /* Automatically adjust window size when screen buffer decreases */
                        if wwidth > swidth {
                            wwidth = swidth;
                            SetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_SIZE_WIDTH as i32), wwidth as UINT, (TRUE) as BOOL);
                        }

                        (*ConInfo).ScreenBufferSize.X = swidth as SHORT;
                        (*ConInfo).WindowSize.X = wwidth as SHORT;

                        InvalidateRect(GetDlgItem(hDlg, (IDC_STATIC_LAYOUT_WINDOW_PREVIEW as i32)), core::ptr::null_mut(), (TRUE) as BOOL);
                        PropSheet_Changed!(GetParent(hDlg), hDlg);
                    }

                    IDC_EDIT_WINDOW_SIZE_WIDTH => {
                        let mut swidth: DWORD = 0;
                        let mut wwidth: DWORD = 0;

                        swidth = GetDlgItemInt(hDlg, (IDC_EDIT_SCREEN_BUFFER_WIDTH as i32), core::ptr::null_mut(), (FALSE) as BOOL) as DWORD;
                        wwidth = GetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_SIZE_WIDTH as i32), core::ptr::null_mut(), (FALSE) as BOOL) as DWORD;

                        /* Automatically adjust screen buffer size when window size enlarges */
                        if wwidth >= swidth {
                            swidth = wwidth;

                            /* Be sure that the (new) screen buffer width is in the correct range */
                            swidth = min(max(swidth, 1), 0xFFFF);

                            SetDlgItemInt(hDlg, (IDC_EDIT_SCREEN_BUFFER_WIDTH as i32), swidth as UINT, (TRUE) as BOOL);
                        }

                        (*ConInfo).ScreenBufferSize.X = swidth as SHORT;
                        (*ConInfo).WindowSize.X = wwidth as SHORT;

                        InvalidateRect(GetDlgItem(hDlg, (IDC_STATIC_LAYOUT_WINDOW_PREVIEW as i32)), core::ptr::null_mut(), (TRUE) as BOOL);
                        PropSheet_Changed!(GetParent(hDlg), hDlg);
                    }

                    IDC_EDIT_SCREEN_BUFFER_HEIGHT => {
                        let mut sheight: DWORD = 0;
                        let mut wheight: DWORD = 0;

                        sheight = GetDlgItemInt(hDlg, (IDC_EDIT_SCREEN_BUFFER_HEIGHT as i32), core::ptr::null_mut(), (FALSE) as BOOL) as DWORD;
                        wheight = GetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_SIZE_HEIGHT as i32), core::ptr::null_mut(), (FALSE) as BOOL) as DWORD;

                        /* Be sure that the (new) screen buffer width is in the correct range */
                        sheight = min(max(sheight, 1), 0xFFFF);

                        /* Automatically adjust window size when screen buffer decreases */
                        if wheight > sheight {
                            wheight = sheight;
                            SetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_SIZE_HEIGHT as i32), wheight as UINT, (TRUE) as BOOL);
                        }

                        (*ConInfo).ScreenBufferSize.Y = sheight as SHORT;
                        (*ConInfo).WindowSize.Y = wheight as SHORT;

                        InvalidateRect(GetDlgItem(hDlg, (IDC_STATIC_LAYOUT_WINDOW_PREVIEW as i32)), core::ptr::null_mut(), (TRUE) as BOOL);
                        PropSheet_Changed!(GetParent(hDlg), hDlg);
                    }

                    IDC_EDIT_WINDOW_SIZE_HEIGHT => {
                        let mut sheight: DWORD = 0;
                        let mut wheight: DWORD = 0;

                        sheight = GetDlgItemInt(hDlg, (IDC_EDIT_SCREEN_BUFFER_HEIGHT as i32), core::ptr::null_mut(), (FALSE) as BOOL) as DWORD;
                        wheight = GetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_SIZE_HEIGHT as i32), core::ptr::null_mut(), (FALSE) as BOOL) as DWORD;

                        /* Automatically adjust screen buffer size when window size enlarges */
                        if wheight >= sheight {
                            sheight = wheight;

                            /* Be sure that the (new) screen buffer width is in the correct range */
                            sheight = min(max(sheight, 1), 0xFFFF);

                            SetDlgItemInt(hDlg, (IDC_EDIT_SCREEN_BUFFER_HEIGHT as i32), sheight as UINT, (TRUE) as BOOL);
                        }

                        (*ConInfo).ScreenBufferSize.Y = sheight as SHORT;
                        (*ConInfo).WindowSize.Y = wheight as SHORT;

                        InvalidateRect(GetDlgItem(hDlg, (IDC_STATIC_LAYOUT_WINDOW_PREVIEW as i32)), core::ptr::null_mut(), (TRUE) as BOOL);
                        PropSheet_Changed!(GetParent(hDlg), hDlg);
                    }

                    IDC_EDIT_WINDOW_POS_LEFT | IDC_EDIT_WINDOW_POS_TOP => {
                        (*ConInfo).WindowPosition.x = GetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_POS_LEFT as i32), core::ptr::null_mut(), (TRUE) as BOOL) as LONG;
                        (*ConInfo).WindowPosition.y = GetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_POS_TOP as i32), core::ptr::null_mut(), (TRUE) as BOOL) as LONG;

                        InvalidateRect(GetDlgItem(hDlg, (IDC_STATIC_LAYOUT_WINDOW_PREVIEW as i32)), core::ptr::null_mut(), (TRUE) as BOOL);
                        PropSheet_Changed!(GetParent(hDlg), hDlg);
                    }

                    _ => {}
                }
            } else if (HIWORD!(wParam)) as u32 == BN_CLICKED &&
                LOWORD!(wParam) == (IDC_CHECK_SYSTEM_POS_WINDOW as u16)
            {
                if IsDlgButtonChecked(hDlg, (IDC_CHECK_SYSTEM_POS_WINDOW as i32)) == BST_CHECKED {
                    EnableDlgItem!(hDlg, (IDC_EDIT_WINDOW_POS_LEFT as i32), (FALSE) as i32);
                    EnableDlgItem!(hDlg, (IDC_EDIT_WINDOW_POS_TOP as i32), (FALSE) as i32);
                    EnableDlgItem!(hDlg, (IDC_UPDOWN_WINDOW_POS_LEFT as i32), (FALSE) as i32);
                    EnableDlgItem!(hDlg, (IDC_UPDOWN_WINDOW_POS_TOP as i32), (FALSE) as i32);

                    (*ConInfo).AutoPosition = (TRUE) as i32;
                    // Do not touch ConInfo->WindowPosition !!

                    InvalidateRect(GetDlgItem(hDlg, (IDC_STATIC_LAYOUT_WINDOW_PREVIEW as i32)), core::ptr::null_mut(), (TRUE) as BOOL);
                    PropSheet_Changed!(GetParent(hDlg), hDlg);
                } else {
                    let mut left: ULONG = 0;
                    let mut top: ULONG = 0;

                    left = GetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_POS_LEFT as i32), core::ptr::null_mut(), (TRUE) as BOOL) as ULONG;
                    top = GetDlgItemInt(hDlg, (IDC_EDIT_WINDOW_POS_TOP as i32), core::ptr::null_mut(), (TRUE) as BOOL) as ULONG;

                    EnableDlgItem!(hDlg, (IDC_EDIT_WINDOW_POS_LEFT as i32), (TRUE) as i32);
                    EnableDlgItem!(hDlg, (IDC_EDIT_WINDOW_POS_TOP as i32), (TRUE) as i32);
                    EnableDlgItem!(hDlg, (IDC_UPDOWN_WINDOW_POS_LEFT as i32), (TRUE) as i32);
                    EnableDlgItem!(hDlg, (IDC_UPDOWN_WINDOW_POS_TOP as i32), (TRUE) as i32);

                    (*ConInfo).AutoPosition = (FALSE) as i32;
                    (*ConInfo).WindowPosition.x = left as LONG;
                    (*ConInfo).WindowPosition.y = top as LONG;

                    InvalidateRect(GetDlgItem(hDlg, (IDC_STATIC_LAYOUT_WINDOW_PREVIEW as i32)), core::ptr::null_mut(), (TRUE) as BOOL);
                    PropSheet_Changed!(GetParent(hDlg), hDlg);
                }
            }
        }

        _ => {}
    }

    return (FALSE) as INT_PTR;
}
