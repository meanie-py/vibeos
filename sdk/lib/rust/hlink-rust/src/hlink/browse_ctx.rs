unsafe extern "C" fn context_get_entry(ctxt: *mut HlinkBCImpl, hlid: ULONG) -> *mut link_entry {
    let mut entry: *mut list = core::ptr::null_mut::<list>();

    match hlid {
        HLID_PREVIOUS => {
            entry = list_prev(&raw mut (*ctxt).links, &raw mut (*(*ctxt).current).entry);
        }
        HLID_NEXT => {
            entry = list_next(&raw mut (*ctxt).links, &raw mut (*(*ctxt).current).entry);
        }
        HLID_CURRENT => {
            entry = &raw mut (*(*ctxt).current).entry;
        }
        HLID_STACKBOTTOM => {
            entry = list_tail(&raw mut (*ctxt).links);
        }
        HLID_STACKTOP => {
            entry = list_head(&raw mut (*ctxt).links);
        }
        _ => {
            WARN!("unknown id 0x%lx\n", hlid);
            entry = core::ptr::null_mut::<list>();
        }
    }

    return if !entry.is_null() {
        (entry as *mut u8).sub(core::mem::offset_of!(link_entry, entry)) as *mut link_entry
    } else {
        core::ptr::null_mut::<link_entry>()
    };
}

