// DisplayProc is a prototype only (LRESULT __stdcall DisplayProc(HWND, UINT, WPARAM, LPARAM));
// it is defined with its body in the function pass.

#[repr(C)]
pub struct DISPLAYDATA {
    pub nPageHeight: i32,
    pub szTypeFaceName: [WCHAR; (LF_FULLFACESIZE as usize)],
    pub szFormat: [WCHAR; (MAX_FORMAT as usize)],
    pub szString: [WCHAR; (MAX_STRING as usize)],

    pub hCaptionFont: HFONT,
    pub hCharSetFont: HFONT,
    pub hSizeFont: HFONT,
    pub hFonts: [HFONT; (MAX_SIZES as usize)],
    pub nSizes: [i32; (MAX_SIZES as usize)],
    pub nHeights: [i32; (MAX_SIZES as usize)],
}

pub type PDISPLAYDATA = *mut DISPLAYDATA;

#[no_mangle]
pub unsafe extern "C" fn Display_InitClass(hInstance: HINSTANCE) -> BOOL {
    let mut wincl: WNDCLASSEXW = core::mem::zeroed();

    /* Set the fontdisplay window class structure */
    wincl.cbSize = core::mem::size_of::<WNDCLASSEX>() as UINT;
    wincl.style = CS_DBLCLKS as UINT;
    wincl.lpfnWndProc = Some(DisplayProc);
    wincl.cbClsExtra = 0 as i32;
    wincl.cbWndExtra = 0 as i32;
    wincl.hInstance = hInstance;
    wincl.hIcon = core::ptr::null_mut();
    wincl.hCursor = LoadCursor(
        core::ptr::null_mut(),
        IDC_ARROW as usize as LPCWSTR,
    );
    wincl.hbrBackground = GetStockObject(WHITE_BRUSH as i32) as HBRUSH;
    wincl.lpszMenuName = core::ptr::null_mut();
    wincl.lpszClassName = core::ptr::addr_of!(g_szFontDisplayClassName) as *const WCHAR as LPCWSTR;
    wincl.hIconSm = core::ptr::null_mut();

    /* Register the window class, and if it fails return FALSE */
    if ((RegisterClassExW(core::ptr::addr_of_mut!(wincl))) == 0) {
        return (FALSE) as BOOL;
    }
    return (TRUE) as BOOL;
}

unsafe extern "C" fn Display_DrawText(hDC: HDC, pData: *mut DISPLAYDATA, nYPos: INT) -> INT {
    let mut hOldFont: HFONT;
    let mut tm: TEXTMETRIC = core::mem::zeroed();
    let mut i: INT;
    let mut y: INT;
    let mut szSize: [WCHAR; 5] = [0; 5];
    let mut szCaption: [WCHAR; (LF_FULLFACESIZE + 20) as _] =
        [0; (LF_FULLFACESIZE + 20) as _];

    /* This is the location on the DC where we draw */
    y = -nYPos;

    hOldFont = SelectObject(hDC, (*pData).hCaptionFont as HGDIOBJ) as HFONT;
    GetTextMetrics(hDC, core::ptr::addr_of_mut!(tm));

    _swprintf(
        szCaption.as_mut_ptr(),
        RUSTCONV_WSTR_E2CD87D16D16.as_ptr(),
        (*pData).szTypeFaceName.as_mut_ptr(),
        (*pData).szFormat.as_mut_ptr(),
    );
    TextOutW(
        hDC,
        0,
        y,
        szCaption.as_mut_ptr(),
        wcslen(szCaption.as_mut_ptr()) as INT,
    );
    y += tm.tmHeight + SPACING1;

    /* Draw a separation Line */
    SelectObject(hDC, GetStockObject((BLACK_PEN as i32)));
    MoveToEx(hDC, 0, y, core::ptr::null_mut());
    LineTo(hDC, 10000, y);
    y += SPACING2;

    /* TODO: Output font info */

    /* Output Character set */
    SelectObject(hDC, (*pData).hCharSetFont as HGDIOBJ);
    GetTextMetrics(hDC, core::ptr::addr_of_mut!(tm));
    _swprintf(szCaption.as_mut_ptr(), RUSTCONV_WSTR_75841A6A7454.as_ptr());
    TextOutW(
        hDC,
        0,
        y,
        szCaption.as_mut_ptr(),
        wcslen(szCaption.as_mut_ptr()) as INT,
    );
    y += tm.tmHeight + 1;

    _swprintf(szCaption.as_mut_ptr(), RUSTCONV_WSTR_C236A9AD0810.as_ptr());
    TextOutW(
        hDC,
        0,
        y,
        szCaption.as_mut_ptr(),
        wcslen(szCaption.as_mut_ptr()) as INT,
    );
    y += tm.tmHeight + 1;

    _swprintf(szCaption.as_mut_ptr(), RUSTCONV_WSTR_D8A4C91C5096.as_ptr());
    TextOutW(
        hDC,
        0,
        y,
        szCaption.as_mut_ptr(),
        wcslen(szCaption.as_mut_ptr()) as INT,
    );
    y += tm.tmHeight + 1;

    /* Draw a separation Line */
    SelectObject(hDC, GetStockObject((BLACK_PEN as i32)));
    MoveToEx(hDC, 0, y, core::ptr::null_mut());
    LineTo(hDC, 10000, y);
    y += SPACING2;

    /* Output the strings for different sizes */
    i = 0;
    while i < (MAX_SIZES as i32) {
        SelectObject(hDC, (*pData).hFonts[i as usize] as HGDIOBJ);
        TextOutW(
            hDC,
            20,
            y,
            (*pData).szString.as_mut_ptr(),
            wcslen((*pData).szString.as_mut_ptr()) as INT,
        );
        GetTextMetrics(hDC, core::ptr::addr_of_mut!(tm));
        y += tm.tmHeight + 1;
        SelectObject(hDC, (*pData).hSizeFont as HGDIOBJ);
        _swprintf(szSize.as_mut_ptr(), RUSTCONV_WSTR_A9EDBA2FC474.as_ptr(), (*pData).nSizes[i as usize]);
        TextOutW(
            hDC,
            0,
            y - 13 - tm.tmDescent,
            szSize.as_mut_ptr(),
            wcslen(szSize.as_mut_ptr()) as INT,
        );
        i += 1;
    }
    SelectObject(hDC, hOldFont as HGDIOBJ);

    return y;
}

unsafe extern "system" fn EnumFontFamProcW(
    lpelfe: *const LOGFONTW,
    lptm: *const TEXTMETRICW,
    FontType: DWORD,
    lParam: LPARAM,
) -> ::core::ffi::c_int {
    let pntmw: PNEWTEXTMETRICW = lptm as PNEWTEXTMETRICW;
    let pfOpenType: PBOOL = lParam as PBOOL;
    if FontType & TRUETYPE_FONTTYPE as DWORD != 0 {
        if (*pntmw).ntmFlags & (NTM_TT_OPENTYPE | NTM_PS_OPENTYPE) as DWORD != 0 {
            *pfOpenType = TRUE as BOOL;
            return FALSE as ::core::ffi::c_int;
        }
    }
    return TRUE as ::core::ffi::c_int;
}

unsafe extern "C" fn Display_SetTypeFace(hwnd: HWND, pLogFont: PLOGFONTW) -> LRESULT {
    let mut pData: *mut DISPLAYDATA = core::ptr::null_mut();
    let mut tm: TEXTMETRIC = core::mem::zeroed();
    let mut hDC: HDC = core::ptr::null_mut();
    let mut rect: RECT = core::mem::zeroed();
    let mut si: SCROLLINFO = core::mem::zeroed();
    let mut i: i32;
    let mut logfont: LOGFONTW = core::mem::zeroed();
    let mut fOpenType: BOOL;
    let mut Buffer: [BYTE; 512] = [0u8; 512];
    let mut pOTM: LPOUTLINETEXTMETRICW = core::ptr::addr_of_mut!(Buffer) as *mut u8 as LPOUTLINETEXTMETRICW;
    let mut pch: LPWSTR;

    /* Set the new type face name */
    pData = GetWindowLongPtr(hwnd, GWLP_USERDATA) as *mut DISPLAYDATA;
    lstrcpynW(
        core::ptr::addr_of_mut!((*pData).szTypeFaceName) as LPWSTR,
        core::ptr::addr_of!((*pLogFont).lfFaceName) as *const u16 as LPCWSTR,
        ARRAYSIZE!((*pData).szTypeFaceName) as i32,
    );

    /* Create the new fonts */
    hDC = GetDC(hwnd);
    DeleteObject(((*pData).hCharSetFont).cast());

    logfont = *pLogFont;
    logfont.lfHeight = -(MulDiv(
        16,
        GetDeviceCaps(GetDC(core::ptr::null_mut()), (LOGPIXELSY as i32)),
        72,
    )) as LONG;
    (*pData).hCharSetFont = CreateFontIndirectW(core::ptr::addr_of_mut!(logfont));

    /* Get font format */
    SelectObject(hDC, ((*pData).hCharSetFont).cast());
    GetTextMetrics(hDC, core::ptr::addr_of_mut!(tm));
    if ((tm.tmPitchAndFamily as i32) & (TMPF_TRUETYPE as i32)) != 0
    {
        if GetOutlineTextMetricsW(hDC, core::mem::size_of_val(&Buffer) as UINT, pOTM) != 0
        {
            let mut pb: LPBYTE = core::ptr::addr_of_mut!(Buffer) as *mut u8 as LPBYTE;
            pb = pb.offset((*pOTM).otmpStyleName as DWORD_PTR as WORD as i32 as isize);
            pch = pb as LPWSTR;
            if *pch != 0
            {
                // The C lstrcatW's the font's style name onto szTypeFaceName
                // (LF_FULLFACESIZE WCHARs) unbounded; a font with a long style name
                // overran DISPLAYDATA. Truncated to the array instead.
                let cch = (*pData).szTypeFaceName.len();
                StringCchCatW(
                    core::ptr::addr_of_mut!((*pData).szTypeFaceName) as LPWSTR,
                    cch,
                    RUSTCONV_WSTR_8D71B3FAAB82.as_ptr(),
                );
                StringCchCatW(
                    core::ptr::addr_of_mut!((*pData).szTypeFaceName) as LPWSTR,
                    cch,
                    pch as LPCWSTR,
                );
            }
        }

        fOpenType = (FALSE) as i32;
        EnumFontFamiliesExW(
            hDC,
            core::ptr::addr_of_mut!(logfont),
            Some(EnumFontFamProcW),
            core::ptr::addr_of_mut!(fOpenType) as LPARAM,
            0,
        );

        if fOpenType != 0
        {
            _swprintf(core::ptr::addr_of_mut!((*pData).szFormat) as *mut u16, RUSTCONV_WSTR_146738FAA5DB.as_ptr());
        }
        else
        {
            _swprintf(core::ptr::addr_of_mut!((*pData).szFormat) as *mut u16, RUSTCONV_WSTR_ED33FC35514E.as_ptr());
        }
    }
    else if ((tm.tmPitchAndFamily as i32) & (TMPF_VECTOR as i32)) != 0
    {
        _swprintf(core::ptr::addr_of_mut!((*pData).szFormat) as *mut u16, RUSTCONV_WSTR_2990E297309D.as_ptr());
    }
    else
    {
        _swprintf(core::ptr::addr_of_mut!((*pData).szFormat) as *mut u16, RUSTCONV_WSTR_202B64B64A36.as_ptr());
    }

    i = 0;
    while i < (MAX_SIZES as i32)
    {
        DeleteObject(((*pData).hFonts[i as usize]).cast());
        logfont.lfHeight = -(MulDiv(
            (*pData).nSizes[i as usize],
            GetDeviceCaps(hDC, (LOGPIXELSY as i32)),
            72,
        )) as LONG;
        (*pData).hFonts[i as usize] = CreateFontIndirectW(core::ptr::addr_of_mut!(logfont));
        i += 1;
    }

    /* Calculate new page dimensions */
    (*pData).nPageHeight = Display_DrawText(hDC, pData, 0);
    ReleaseDC(hwnd, hDC);

    /* Set the vertical scrolling range and page size */
    GetClientRect(hwnd, core::ptr::addr_of_mut!(rect));
    si.cbSize = core::mem::size_of::<SCROLLINFO>() as UINT;
    si.fMask = (SIF_RANGE | SIF_PAGE | SIF_POS | SIF_TRACKPOS) as UINT;
    si.nMin = 0;
    si.nMax = (*pData).nPageHeight;
    si.nPage = rect.bottom as UINT;
    si.nPos = 0;
    si.nTrackPos = 0;
    SetScrollInfo(
        hwnd,
        (SB_VERT) as i32,
        core::ptr::addr_of_mut!(si),
        (TRUE) as BOOL,
    );

    return 0;
}

unsafe extern "C" fn Display_SetString(hwnd: HWND, pszString: LPCWSTR) -> LRESULT {
    let mut pData: *mut DISPLAYDATA;

    pData = GetWindowLongPtr(hwnd, GWLP_USERDATA) as *mut DISPLAYDATA;
    lstrcpynW(&raw mut (*pData).szString as LPWSTR, pszString, ARRAYSIZE!((*pData).szString) as i32);

    InvalidateRect(hwnd, core::ptr::null_mut(), (TRUE) as BOOL);

    return 0;
}

unsafe extern "C" fn Display_OnCreate(mut hwnd: HWND) -> LRESULT {
    let mut pData: *mut DISPLAYDATA;
    let nSizes: [::core::ffi::c_int; (MAX_SIZES as usize)] = [
        8,
        12,
        18,
        24,
        36,
        48,
        60,
        72,
    ];
    let mut i: ::core::ffi::c_int;
    let mut LogFont: LOGFONTW = tagLOGFONTW {
        lfHeight: 50,
        lfWidth: 0,
        lfEscapement: 0,
        lfOrientation: 0,
        lfWeight: (FW_NORMAL as i32),
        lfItalic: (FALSE) as u8,
        lfUnderline: (FALSE) as u8,
        lfStrikeOut: (FALSE) as u8,
        lfCharSet: (ANSI_CHARSET as u8),
        lfOutPrecision: (OUT_DEFAULT_PRECIS as u8),
        lfClipPrecision: (CLIP_DEFAULT_PRECIS as u8),
        lfQuality: (PROOF_QUALITY as u8),
        lfPitchAndFamily: (DEFAULT_PITCH as u8),
        lfFaceName: [0u16; 32],
    };
    {
        let FaceSrc: *const u16 = RUSTCONV_WSTR_491507152B61.as_ptr();
        let mut k: usize = 0;
        while k < 32 && *FaceSrc.add(k) != 0 {
            LogFont.lfFaceName[k] = *FaceSrc.add(k);
            k += 1;
        }
    }

    /* Create data structure */
    pData = malloc(core::mem::size_of::<DISPLAYDATA>() as usize)
        as *mut DISPLAYDATA;
    ZeroMemory!(
        pData as *mut ::core::ffi::c_void,
        core::mem::size_of::<DISPLAYDATA>() as usize,
    );

    /* Set the window's GWLP_USERDATA to our data structure */
    SetWindowLongPtr(hwnd, GWLP_USERDATA, pData as LONG_PTR);

    i = 0;
    while i < (MAX_SIZES as i32) {
        (*pData).nSizes[i as usize] = nSizes[i as usize];
        i += 1;
    }

    (*pData).hCaptionFont = CreateFontIndirectW(core::ptr::addr_of_mut!(LogFont));
    LogFont.lfHeight = 12;
    (*pData).hSizeFont = CreateFontIndirectW(core::ptr::addr_of_mut!(LogFont));

    Display_SetString(hwnd, RUSTCONV_WSTR_3A223B11ADFE.as_ptr());

    Display_SetTypeFace(hwnd, core::ptr::addr_of_mut!(LogFont));

    return 0;
}

unsafe extern "C" fn Display_OnPaint(mut hwnd: HWND) -> LRESULT {
    let mut pData: *mut DISPLAYDATA = core::ptr::null_mut();
    let mut ps: PAINTSTRUCT = core::mem::zeroed();
    let mut si: SCROLLINFO = core::mem::zeroed();

    pData = GetWindowLongPtr(hwnd, GWLP_USERDATA) as *mut DISPLAYDATA;

    /* Get the Scroll position */
    si.cbSize = core::mem::size_of::<SCROLLINFO>() as UINT;
    si.fMask = SIF_POS as UINT;
    GetScrollInfo(hwnd, (SB_VERT) as i32, &raw mut si);

    BeginPaint(hwnd, &raw mut ps);

    /* Erase background */
    FillRect(
        ps.hdc,
        &raw mut ps.rcPaint as LPCRECT,
        GetStockObject((WHITE_BRUSH as i32)) as HBRUSH,
    );

    /* Draw the text */
    Display_DrawText(ps.hdc, pData, si.nPos);

    EndPaint(hwnd, &raw mut ps);

    return 0 as LRESULT;
}

unsafe extern "C" fn Display_OnSize(hwnd: HWND) -> LRESULT {
    let mut rect: RECT = core::mem::zeroed();
    let mut si: SCROLLINFO = core::mem::zeroed();
    let mut nOldPos: i32;

    GetClientRect(hwnd, core::ptr::addr_of_mut!(rect));

    /* Get the old scroll pos */
    si.cbSize = core::mem::size_of::<SCROLLINFO>() as UINT;
    si.fMask = SIF_POS;
    GetScrollInfo(hwnd, (SB_VERT) as i32, core::ptr::addr_of_mut!(si));
    nOldPos = si.nPos;

    /* Set the new page size */
    si.fMask = SIF_PAGE;
    si.nPage = rect.bottom as UINT;
    SetScrollInfo(hwnd, (SB_VERT) as i32, core::ptr::addr_of_mut!(si), (TRUE) as BOOL);

    /* Get the new scroll pos */
    si.fMask = SIF_POS;
    GetScrollInfo(hwnd, (SB_VERT) as i32, core::ptr::addr_of_mut!(si));

    /* If they don't match ... */
    if nOldPos != si.nPos {
        /* ... scroll the window */
        ScrollWindowEx(
            hwnd,
            0,
            nOldPos - si.nPos,
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            SW_INVALIDATE,
        );
        UpdateWindow(hwnd);
    }

    return 0;
}

unsafe extern "C" fn Display_OnVScroll(hwnd: HWND, wParam: WPARAM) -> LRESULT {
    let mut si: SCROLLINFO = core::mem::zeroed();
    let mut nPos: ::core::ffi::c_int;

    si.cbSize = core::mem::size_of::<SCROLLINFO>() as UINT;
    si.fMask = SIF_POS | SIF_RANGE | SIF_TRACKPOS;
    GetScrollInfo(hwnd, (SB_VERT) as i32, core::ptr::addr_of_mut!(si));

    match (LOWORD!(wParam) as ::core::ffi::c_int) as u32 {
        SB_PAGEUP => {
            nPos = si.nPos - 50;
        }
        SB_PAGEDOWN => {
            nPos = si.nPos + 50;
        }
        SB_LINEUP => {
            nPos = si.nPos - 10;
        }
        SB_LINEDOWN => {
            nPos = si.nPos + 10;
        }
        SB_THUMBTRACK | SB_THUMBPOSITION => {
            nPos = si.nTrackPos;
        }
        _ => {
            nPos = si.nPos;
        }
    }

    nPos = max(nPos, si.nMin);
    nPos = min(nPos, si.nMax);
    if nPos != si.nPos {
        ScrollWindowEx(
            hwnd,
            0,
            si.nPos - nPos,
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            SW_INVALIDATE,
        );
        si.cbSize = core::mem::size_of::<SCROLLINFO>() as UINT;
        si.nPos = nPos;
        si.fMask = SIF_POS;
        SetScrollInfo(
            hwnd,
            (SB_VERT) as i32,
            core::ptr::addr_of_mut!(si),
            (TRUE) as BOOL,
        );
        UpdateWindow(hwnd);
    }

    return 0;
}

unsafe extern "C" fn Display_OnDestroy(hwnd: HWND) -> LRESULT {
    let mut pData: *mut DISPLAYDATA;
    let mut i: ::core::ffi::c_int;

    pData = GetWindowLongPtr(hwnd, GWLP_USERDATA) as *mut DISPLAYDATA;

    /* Delete the fonts */
    DeleteObject((*pData).hCaptionFont as HGDIOBJ);
    DeleteObject((*pData).hCharSetFont as HGDIOBJ);
    DeleteObject((*pData).hSizeFont as HGDIOBJ);

    i = 0 as ::core::ffi::c_int;
    while i < MAX_SIZES as ::core::ffi::c_int {
        DeleteObject((*pData).hFonts[i as usize] as HGDIOBJ);
        i += 1;
    }

    /* Free the data structure */
    free(pData as *mut ::core::ffi::c_void);

    return 0 as LRESULT;
}
#[no_mangle]
pub unsafe extern "C" fn Display_OnPrint(hwnd: HWND) -> LRESULT {
    let mut pfont: PRINTDLG = core::mem::zeroed();
    let mut tm: TEXTMETRIC = core::mem::zeroed();
    let mut copies: core::ffi::c_int;
    let mut yPos: core::ffi::c_int;

    /* Clears the memory before using it */
    ZeroMemory!(
        core::ptr::addr_of_mut!(pfont) as *mut core::ffi::c_void,
        core::mem::size_of::<PRINTDLG>(),
    );

    pfont.lStructSize = core::mem::size_of::<PRINTDLG>() as DWORD;
    pfont.hwndOwner = hwnd;
    pfont.hDevMode = core::ptr::null_mut();
    pfont.hDevNames = core::ptr::null_mut();
    pfont.Flags = (PD_USEDEVMODECOPIESANDCOLLATE | PD_RETURNDC) as DWORD;
    pfont.nCopies = 1 as WORD;
    pfont.nFromPage = 0xFFFF as WORD;
    pfont.nToPage = 0xFFFF as WORD;
    pfont.nMinPage = 1 as WORD;
    pfont.nMaxPage = 0xFFFF as WORD;

    /* Opens up the print dialog box */
    if PrintDlg(core::ptr::addr_of_mut!(pfont)) != 0 {
        let mut docinfo: DOCINFO = core::mem::zeroed();
        docinfo.cbSize = core::mem::size_of::<DOCINFO>() as core::ffi::c_int;
        docinfo.lpszDocName = RUSTCONV_WSTR_61A09F6EE48E.as_ptr();
        docinfo.lpszOutput = core::ptr::null();
        docinfo.lpszDatatype = core::ptr::null();
        docinfo.fwType = 0 as DWORD;

        /* We start printing */
        StartDoc(pfont.hDC, core::ptr::addr_of_mut!(docinfo));

        /* Grabs the text metrics for the printer */
        GetTextMetrics(pfont.hDC, core::ptr::addr_of_mut!(tm));

        /* Start out with 0 for the y position for the page */
        yPos = 0 as core::ffi::c_int;

        /* Starts out with the current page */
        StartPage(pfont.hDC);

        /* Used when printing for more than one copy */
        copies = 0 as core::ffi::c_int;
        while copies < pfont.nCopies as core::ffi::c_int {
            /* Test output */
            TextOutW(
                pfont.hDC,
                10 as core::ffi::c_int,
                yPos,
                RUSTCONV_WSTR_179D92030CC9.as_ptr(),
                19 as core::ffi::c_int,
            );

            /* TODO: Determine if using Display_DrawText() will work for both rendering out to the
            window and to the printer output */

            /* Ends the current page */
            EndPage(pfont.hDC);

            /* If we are making more than one copy, start a new page */
            if copies != pfont.nCopies as core::ffi::c_int {
                yPos = 0 as core::ffi::c_int;
                StartPage(pfont.hDC);
            }
            copies += 1;
        }

        /* The printing is now over */
        EndDoc(pfont.hDC);

        DeleteDC(pfont.hDC);
    }

    return 0 as LRESULT;
}
#[no_mangle]
pub unsafe extern "C" fn Display_GetFullName(hwnd: HWND, length: INT, ptr: PWSTR) -> LRESULT {
    let mut pData: *mut DISPLAYDATA = core::ptr::null_mut();
    let mut len: INT = 0;
    pData = GetWindowLongPtr(hwnd, GWLP_USERDATA) as *mut DISPLAYDATA;
    len = (wcslen(core::ptr::addr_of_mut!((*pData).szTypeFaceName) as *mut WCHAR) as INT)
        + (wcslen(core::ptr::addr_of_mut!((*pData).szFormat) as *mut WCHAR) as INT)
        + 2;
    if !ptr.is_null() && length >= len {
        _swprintf(
            ptr,
            RUSTCONV_WSTR_E2CD87D16D16.as_ptr(),
            core::ptr::addr_of_mut!((*pData).szTypeFaceName) as *mut WCHAR,
            core::ptr::addr_of_mut!((*pData).szFormat) as *mut WCHAR,
        );
    }
    return len as LRESULT;
}

#[no_mangle]
pub unsafe extern "system" fn DisplayProc(hwnd: HWND, message: UINT, wParam: WPARAM, lParam: LPARAM) -> LRESULT {
    match message {
        WM_CREATE => {
            return Display_OnCreate(hwnd);
        }
        WM_PAINT => {
            return Display_OnPaint(hwnd);
        }
        WM_SIZE => {
            return Display_OnSize(hwnd);
        }
        WM_VSCROLL => {
            return Display_OnVScroll(hwnd, wParam);
        }
        FVM_SETTYPEFACE => {
            return Display_SetTypeFace(hwnd, lParam as PLOGFONTW);
        }
        FVM_SETSTRING => {
            return Display_SetString(hwnd, lParam as *mut WCHAR);
        }
        FVM_GETFULLNAME => {
            return Display_GetFullName(hwnd, wParam as INT, lParam as PWSTR);
        }
        WM_DESTROY => {
            return Display_OnDestroy(hwnd);
        }
        _ => {
            return DefWindowProcW(hwnd, message, wParam, lParam);
        }
    }

    return 0;
}
