pub const SPACING1: i32 = 8;

pub const SPACING2: i32 = 5;

// Values below come from the Windows/ReactOS headers, which are not in this preamble.
// LF_FULLFACESIZE is the standard Win32 value. MAX_FORMAT, MAX_STRING and MAX_SIZES are
