// ============================================================================
// _ftol -- Wine msvcrt math.c:568-587, moved verbatim from msvcrt-crt-rust's math.rs.
// ============================================================================

core::arch::global_asm!(
    ".text",
    ".align 4",
    ".globl __ftol",
    ".globl __ftol2",
    ".globl __ftol2_sse",
    ".def __ftol; .scl 2; .type 32; .endef",
    // crtmath's ftol2_asm.s: `__ftol2` and `__ftol2_sse` were `jmp __ftol`.
    "__ftol2:",
    "__ftol2_sse:",
    "__ftol:",
    "pushl   %ebp",
    "movl    %esp, %ebp",
    "subl    $12, %esp", // sizeof(LONGLONG) + 2*sizeof(WORD)
    "fnstcw  (%esp)",
    "mov     (%esp), %ax",
    "or      $0xc00, %ax",
    "mov     %ax, 2(%esp)",
    "fldcw   2(%esp)",
    "fistpq  4(%esp)",
    "fldcw   (%esp)",
    "movl    4(%esp), %eax",
    "movl    8(%esp), %edx",
    "leave",
    "ret",
    options(att_syntax)
);

// ============================================================================
// __libm_sse2_* -- crtmath math/i386/libm_sse2.c (Timo Kreuzer, MIT).
//
// MSVC's /arch:SSE2 code calls these with the argument(s) in xmm0 (xmm1) and takes the
// result from xmm0; the C spelled that as `__m128d f(__m128d)` and let the compiler
// apply the vector calling convention. Written out here so the convention is explicit:
// spill to the stack, call the cdecl function (x87 st0 result), reload into xmm0.
//
// * double: `_mm_set_sd(result)` -- `movsd` from memory zeroes the upper lane, the same.
// * float, computed in double (every f variant but powf): the C widens with
//   `_mm_cvtss_sd` (cvtss2sd), calls the double function, and narrows with
//   `_mm_cvtpd_ps` (cvtpd2ps) -- low lane the result, the rest 0.0f, the same here.
// * powf: `powf` on the floats, `_mm_set_ss` (movss load zeroes the upper lanes).
// * `_libm_sse2_*_precise` carry ONE leading underscore in C, hence `__` here.
// ============================================================================

