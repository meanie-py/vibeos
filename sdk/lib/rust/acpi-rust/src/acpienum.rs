//! acpienum.c → Rust (ACPI Phase 3b glue leaf). Cohab: #[no_mangle] symbols
//! replace the C file in acpi.sys at link time. ACPICA stays C (libacpica.a).
//!
//! ACPI namespace enumerator: Bus_PlugInDevice + ACPIEnumerateDevices.
#![allow(non_snake_case, non_camel_case_types, non_upper_case_globals, unused)]

use crate::shared::*;
use core::ffi::{c_char, c_int, c_void};
use core::ptr::addr_of_mut;

// Kernel types (ULONG, SIZE_T, PVOID, PWCHAR, BOOLEAN, PLIST_ENTRY, NTSTATUS,
// WCHAR, PDEVICE_OBJECT, IoCreateDevice, IoDeleteDevice) via the ddk glob. ACPI_*
// types come from crate::shared (acpica-sys) — ddk has no ACPI_HANDLE, no collision.
use ntkrnl_sys::ddk::*;
use ntkrnl_sys::ex::{ExAllocatePoolWithTag, ExFreePoolWithTag};
use ntkrnl_sys::mm::NonPagedPool;
use ntkrnl_sys::base::{STATUS_SUCCESS, STATUS_INSUFFICIENT_RESOURCES};

// ---- DDK constants the C glue uses (wdm.h). FILE_DEVICE_CONTROLLER is not in
//      the ddk glob (only hal_bindgen); define the well-known wdm.h value. ----
const FILE_DEVICE_CONTROLLER: u32 = 0x00000004; // wdm.h
const FILE_AUTOGENERATED_DEVICE_NAME: u32 = 0x00000080; // matches ntkrnl_sys::driver_ddk
const UNICODE_NULL: u16 = 0;

// Pool tag 'DpcA' = ('D'<<24)|('p'<<16)|('c'<<8)|'A'.
const TAG_DpcA: u32 = u32::from_be_bytes([b'D', b'p', b'c', b'A']);

#[inline]
fn NT_SUCCESS(status: NTSTATUS) -> bool {
    status >= 0
}

// ---- ACPICA root namespace device tree (defined in bus.rs). ----
extern "C" {
    static mut acpi_root: *mut acpi_device;
}

// ---- Sibling acpi-rust functions (all extern "C"/cdecl; #[no_mangle] elsewhere). ----
extern "C" {
    fn acpi_bus_get_device(handle: ACPI_HANDLE, device: *mut *mut acpi_device) -> c_int;
    fn Bus_InitializePdo(Pdo: PDEVICE_OBJECT, FdoData: PFDO_DEVICE_DATA);
}

// ---- CRT (libcntpr): strcmp, swprintf (C-variadic), RtlCopyMemory via ntkrnl. ----
extern "C" {
    fn strcmp(s1: *const c_char, s2: *const c_char) -> c_int;
    fn swprintf(buffer: *mut u16, format: *const u16, ...) -> c_int;
}

// ---- HAS_CHILDREN(d) = ((d)->children.next != &((d)->children)) ----
#[inline]
unsafe fn HAS_CHILDREN(d: *mut acpi_device) -> bool {
    (*d).children.next != addr_of_mut!((*d).children)
}

// ---- HAS_SIBLINGS(d) = ((d)->parent && ((d)->node.next != &(d)->parent->children)) ----
#[inline]
unsafe fn HAS_SIBLINGS(d: *mut acpi_device) -> bool {
    !(*d).parent.is_null() && (*d).node.next != addr_of_mut!((*(*d).parent).children)
}

// ---- NODE_TO_DEVICE(n) = list_entry(n, struct acpi_device, node) ----
#[inline]
unsafe fn NODE_TO_DEVICE(n: *mut list_head) -> *mut acpi_device {
    (n as *mut u8).wrapping_sub(core::mem::offset_of!(acpi_device, node)) as *mut acpi_device
}

#[no_mangle]
pub unsafe extern "C" fn Bus_PlugInDevice(
    Device: *mut acpi_device,
    FdoData: PFDO_DEVICE_DATA,
) -> NTSTATUS {
    let pdo: PDEVICE_OBJECT;
    let mut pdoData: PPDO_DEVICE_DATA;
    let status: NTSTATUS;
    let mut index: ULONG;
    let mut temp: [u16; 256] = [0; 256];
    let mut entry: PLIST_ENTRY;

    // PAGED_CODE();  (no-op)

    // Don't enumerate the root device
    if (*Device).handle == ACPI_ROOT_OBJECT {
        return STATUS_SUCCESS;
    }

    /* Check we didnt add this already */
    entry = (*FdoData).ListOfPDOs.Flink;
    while entry != addr_of_mut!((*FdoData).ListOfPDOs) {
        let mut CurrentDevice: *mut acpi_device = core::ptr::null_mut();

        pdoData = (entry as *mut u8)
            .wrapping_sub(core::mem::offset_of!(PDO_DEVICE_DATA, Link))
            as PPDO_DEVICE_DATA;

        // dont duplicate devices
        if (*pdoData).AcpiHandle == (*Device).handle {
            return STATUS_SUCCESS;
        }

        // check everything but fixed feature devices
        if !(*pdoData).AcpiHandle.is_null() {
            acpi_bus_get_device((*pdoData).AcpiHandle, &mut CurrentDevice);
        } else {
            entry = (*entry).Flink;
            continue;
        }

        // check if the HID matches
        if strcmp((*Device).pnp.hardware_id, (*CurrentDevice).pnp.hardware_id) == 0 {
            // check if UID exists for both and matches
            if (*Device).flags.unique_id() != 0
                && (*CurrentDevice).flags.unique_id() != 0
                && strcmp(
                    (*Device).pnp.unique_id.as_ptr(),
                    (*CurrentDevice).pnp.unique_id.as_ptr(),
                ) == 0
            {
                /* We have a UID on both but they're the same so we have to ignore it */
                DPRINT1!(
                    "Detected duplicate device: %hs %hs\n",
                    (*Device).pnp.hardware_id,
                    (*Device).pnp.unique_id.as_ptr()
                );
                return STATUS_SUCCESS;
            } else if (*Device).flags.unique_id() == 0 && (*CurrentDevice).flags.unique_id() == 0 {
                /* No UID so we can only legally have 1 of these devices */
                DPRINT1!("Detected duplicate device: %hs\n", (*Device).pnp.hardware_id);
                return STATUS_SUCCESS;
            }
        }

        entry = (*entry).Flink;
    }

    DPRINT!();

    //
    // Create the PDO
    //
    let mut pdo_out: PDEVICE_OBJECT = core::ptr::null_mut();
    status = IoCreateDevice(
        (*(*FdoData).Common.Self_).DriverObject,
        core::mem::size_of::<PDO_DEVICE_DATA>() as ULONG,
        core::ptr::null_mut(),
        FILE_DEVICE_CONTROLLER,
        FILE_AUTOGENERATED_DEVICE_NAME,
        0, // FALSE
        &mut pdo_out,
    );
    pdo = pdo_out;

    if !NT_SUCCESS(status) {
        return status;
    }

    pdoData = (*pdo).DeviceExtension as PPDO_DEVICE_DATA;
    (*pdoData).AcpiHandle = (*Device).handle;

    //
    // Copy the hardware IDs
    //
    index = 0;
    index = index.wrapping_add(swprintf(
        temp.as_mut_ptr().add(index as usize),
        ntkrnl_sys::w!("ACPI\\%hs").as_ptr(),
        (*Device).pnp.hardware_id,
    ) as ULONG);
    // Pointer writes (not `temp[i] = `) to avoid a slice-index bounds panic →
    // kernel HANG; C's temp[256] is itself unbounded here. Footgun #5.
    *temp.as_mut_ptr().add(index as usize) = UNICODE_NULL;
    index += 1;

    index = index.wrapping_add(swprintf(
        temp.as_mut_ptr().add(index as usize),
        ntkrnl_sys::w!("*%hs").as_ptr(),
        (*Device).pnp.hardware_id,
    ) as ULONG);
    *temp.as_mut_ptr().add(index as usize) = UNICODE_NULL;
    index += 1;
    *temp.as_mut_ptr().add(index as usize) = UNICODE_NULL;
    index += 1;

    (*pdoData).HardwareIDs = ExAllocatePoolWithTag(
        NonPagedPool,
        (index as usize * core::mem::size_of::<u16>()) as _,
        TAG_DpcA,
    ) as PWCHAR;

    if (*pdoData).HardwareIDs.is_null() {
        IoDeleteDevice(pdo);
        return STATUS_INSUFFICIENT_RESOURCES;
    }

    core::ptr::copy_nonoverlapping(
        temp.as_ptr(),
        (*pdoData).HardwareIDs,
        index as usize,
    );
    Bus_InitializePdo(pdo, FdoData);

    //
    // Device Relation changes if a new pdo is created. (IoInvalidateDeviceRelations
    // is commented out in the C source.)
    //

    status
}

/* looks alot like acpi_bus_walk doesnt it */
#[no_mangle]
pub unsafe extern "C" fn ACPIEnumerateDevices(DeviceExtension: PFDO_DEVICE_DATA) -> NTSTATUS {
    let mut Count: ULONG = 0;
    let mut Device: *mut acpi_device = acpi_root;

    while !Device.is_null() {
        if (*Device).status.present() != 0
            && (*Device).status.enabled() != 0
            && (*Device).flags.hardware_id() != 0
        {
            Bus_PlugInDevice(Device, DeviceExtension);
            Count = Count.wrapping_add(1);
        }

        if HAS_CHILDREN(Device) {
            Device = NODE_TO_DEVICE((*Device).children.next);
            continue;
        }
        if HAS_SIBLINGS(Device) {
            Device = NODE_TO_DEVICE((*Device).node.next);
            continue;
        }
        loop {
            Device = (*Device).parent;
            if Device.is_null() {
                break;
            }
            if HAS_SIBLINGS(Device) {
                Device = NODE_TO_DEVICE((*Device).node.next);
                break;
            }
        }
    }

    DPRINT!();
    STATUS_SUCCESS
}

