//! ntstatus.h `(NTSTATUS)0x...` cast-macros are NOT bindgen-
//! evaluable by design (audit §Phase 0.2). This is the ntdll-sys
//! analog of `ntkrnl-sys/src/constants.rs` — ported verbatim
