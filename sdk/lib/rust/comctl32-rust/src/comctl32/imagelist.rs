#[no_mangle]
pub unsafe extern "system" fn Internal_Add(himl: HIMAGELIST, hbmImage: HBITMAP, hbmMask: HBITMAP) -> INT {
    let mut hdcBitmap: HDC = core::ptr::null_mut();
    let mut hdcTemp: HDC = core::ptr::null_mut();
    let mut nFirstIndex: INT = 0;
    let mut nImageCount: INT = 0;
    let mut i: INT = 0;
    let mut bmp: BITMAP = core::mem::zeroed();
    let mut pt: POINT = core::mem::zeroed();

    if is_valid(himl) == 0 {
        return -1;
    }

    if GetObjectW(
        hbmImage as HANDLE,
        core::mem::size_of::<BITMAP>() as INT,
        core::ptr::addr_of_mut!(bmp) as LPVOID,
    ) == 0
    {
        return -1;
    }

    nImageCount = bmp.bmWidth / (*himl).cx;

    IMAGELIST_InternalExpandBitmaps(himl, nImageCount);

    hdcBitmap = CreateCompatibleDC(core::ptr::null_mut());

    SelectObject(hdcBitmap, hbmImage as HGDIOBJ);

    'done: {
        if add_with_alpha(
            himl,
            hdcBitmap,
            (*himl).cCurImage,
            nImageCount,
            (*himl).cx,
            if (*himl).cy < bmp.bmHeight { (*himl).cy } else { bmp.bmHeight },
            hbmImage,
            hbmMask,
        ) != 0
        {
            break 'done;
        }

        if !(*himl).hbmMask.is_null() {
            hdcTemp = CreateCompatibleDC(core::ptr::null_mut());
            SelectObject(hdcTemp, hbmMask as HGDIOBJ);
        }

        if (*himl).uBitsPixel <= 8
            && (bmp.bmBitsPixel as INT) <= 8
            && (*himl).color_table_set == 0
            && (*himl).cCurImage == 0
        {
            let mut colors: [RGBQUAD; 256] = core::mem::zeroed();
            let mut num: UINT = GetDIBColorTable(
                hdcBitmap,
                0,
                (1 << (bmp.bmBitsPixel as INT)) as UINT,
                core::ptr::addr_of_mut!(colors) as *mut RGBQUAD,
            );
            if num != 0 {
                ImageList_SetColorTable(
                    himl,
                    0,
                    num,
                    core::ptr::addr_of_mut!(colors) as *mut RGBQUAD,
                );
            }
        }

        i = 0;
        while i < nImageCount {
            'body: {
                imagelist_point_from_index(himl, ((*himl).cCurImage + i) as UINT, core::ptr::addr_of_mut!(pt));

                BitBlt(
                    (*himl).hdcImage,
                    pt.x,
                    pt.y,
                    (*himl).cx,
                    bmp.bmHeight,
                    hdcBitmap,
                    i * (*himl).cx,
                    0,
                    SRCCOPY,
                );

                if (*himl).hbmMask.is_null() {
                    break 'body;
                }

                BitBlt(
                    (*himl).hdcMask,
                    pt.x,
                    pt.y,
                    (*himl).cx,
                    bmp.bmHeight,
                    hdcTemp,
                    i * (*himl).cx,
                    0,
                    SRCCOPY,
                );

                BitBlt(
                    (*himl).hdcImage,
                    pt.x,
                    pt.y,
                    (*himl).cx,
                    bmp.bmHeight,
                    (*himl).hdcMask,
                    pt.x,
                    pt.y,
                    0x220326,
                );
            }
            i += 1;
        }

        if !hdcTemp.is_null() {
            DeleteDC(hdcTemp);
        }
    }

    DeleteDC(hdcBitmap);

    nFirstIndex = (*himl).cCurImage;
    (*himl).cCurImage += nImageCount;

    return nFirstIndex;
}

