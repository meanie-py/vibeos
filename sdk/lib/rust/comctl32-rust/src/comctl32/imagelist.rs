#[no_mangle]
pub unsafe extern "system" fn Internal_GetIcon(himl: HIMAGELIST, i: INT, fStyle: UINT) -> HICON {
    let mut ii: ICONINFO = ICONINFO {
        fIcon: 0,
        xHotspot: 0,
        yHotspot: 0,
        hbmMask: core::ptr::null_mut(),
        hbmColor: core::ptr::null_mut(),
    };
    let mut hIcon: HICON = core::ptr::null_mut();
    let mut hOldDstBitmap: HBITMAP = core::ptr::null_mut();
    let mut hdcDst: HDC = core::ptr::null_mut();
    let mut pt: POINT = POINT { x: 0, y: 0 };

    if (*__wine_dbch___default).flags as core::ffi::c_int
        & (1 as core::ffi::c_int) << __WINE_DBCL_TRACE as core::ffi::c_int
        != 0
    {
        let __dbch: *mut __wine_debug_channel = __wine_dbch___default;
        let __dbcl: __wine_debug_class = __WINE_DBCL_TRACE;
        ros_dbg_log(
            __dbcl,
            __dbch,
            b"dll/win32/comctl32/imagelist.c\0"
                as *const u8 as *const core::ffi::c_char,
            b"Internal_GetIcon\0" as *const u8 as *const core::ffi::c_char,
            1989 as core::ffi::c_int,
            b"%p %d %d\n\0" as *const u8 as *const core::ffi::c_char,
            himl,
            i,
            fStyle,
        );
    }

    if is_valid(himl) == 0 || (i < 0) || (i >= (*himl).cCurImage) {
        return core::ptr::null_mut();
    }

    ii.fIcon = TRUE as BOOL;
    ii.xHotspot = 0 as DWORD;
    ii.yHotspot = 0 as DWORD;

    /* create colour bitmap */
    hdcDst = GetDC(core::ptr::null_mut());
    ii.hbmColor = CreateCompatibleBitmap(hdcDst, (*himl).cx, (*himl).cy);
    ReleaseDC(core::ptr::null_mut(), hdcDst);

    hdcDst = CreateCompatibleDC(core::ptr::null_mut());

    imagelist_point_from_index(himl, (i) as UINT, &raw mut pt);

    /* draw mask*/
    ii.hbmMask = CreateBitmap(
        (*himl).cx,
        (*himl).cy,
        1 as UINT,
        1 as UINT,
        core::ptr::null(),
    );
    hOldDstBitmap = SelectObject(hdcDst, ii.hbmMask as HGDIOBJ) as HBITMAP;
    if !(*himl).hbmMask.is_null() {
        BitBlt(
            hdcDst,
            0 as INT,
            0 as INT,
            (*himl).cx,
            (*himl).cy,
            (*himl).hdcMask,
            pt.x as INT,
            pt.y as INT,
            SRCCOPY as DWORD,
        );
    } else {
        PatBlt(
            hdcDst,
            0 as INT,
            0 as INT,
            (*himl).cx,
            (*himl).cy,
            BLACKNESS as DWORD,
        );
    }

    /* draw image*/
    SelectObject(hdcDst, ii.hbmColor as HGDIOBJ);
    BitBlt(
        hdcDst,
        0 as INT,
        0 as INT,
        (*himl).cx,
        (*himl).cy,
        (*himl).hdcImage,
        pt.x as INT,
        pt.y as INT,
        SRCCOPY as DWORD,
    );

    /*
     * CreateIconIndirect requires us to deselect the bitmaps from
     * the DCs before calling
     */
    SelectObject(hdcDst, hOldDstBitmap as HGDIOBJ);

    hIcon = CreateIconIndirect(&raw mut ii);

    DeleteObject(ii.hbmMask as HGDIOBJ);
    DeleteObject(ii.hbmColor as HGDIOBJ);
    DeleteDC(hdcDst);

    return hIcon;
}

