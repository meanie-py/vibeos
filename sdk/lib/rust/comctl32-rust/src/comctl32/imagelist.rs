#[no_mangle]
pub unsafe extern "system" fn ImageList_DragMove(mut x: INT, mut y: INT) -> BOOL {
    if is_valid(InternalDrag.himl) == 0 {
        return FALSE;
    }
    if InternalDrag.bShow != 0 {
        let mut hdcDrag: HDC = core::ptr::null_mut::<HDC__>();
        let mut hdcOffScreen: HDC = core::ptr::null_mut::<HDC__>();
        let mut hdcBg: HDC = core::ptr::null_mut::<HDC__>();
        let mut hbmOffScreen: HBITMAP = core::ptr::null_mut::<HBITMAP__>();
        let mut origNewX: INT = 0;
        let mut origNewY: INT = 0;
        let mut origOldX: INT = 0;
        let mut origOldY: INT = 0;
        let mut origRegX: INT = 0;
        let mut origRegY: INT = 0;
        let mut sizeRegX: INT = 0;
        let mut sizeRegY: INT = 0;

        origNewX = x - InternalDrag.dxHotspot;
        origNewY = y - InternalDrag.dyHotspot;
        origOldX = InternalDrag.x - InternalDrag.dxHotspot;
        origOldY = InternalDrag.y - InternalDrag.dyHotspot;
        origRegX = min(origNewX, origOldX);
        origRegY = min(origNewY, origOldY);
        sizeRegX = (*InternalDrag.himl).cx + abs(x - InternalDrag.x);
        sizeRegY = (*InternalDrag.himl).cy + abs(y - InternalDrag.y);

        hdcDrag = GetDCEx(
            InternalDrag.hwnd,
            core::ptr::null_mut(),
            (DCX_WINDOW | DCX_CACHE | DCX_LOCKWINDOWUPDATE) as DWORD,
        );
        hdcOffScreen = CreateCompatibleDC(hdcDrag);
        hdcBg = CreateCompatibleDC(hdcDrag);

        hbmOffScreen = CreateCompatibleBitmap(hdcDrag, sizeRegX, sizeRegY);
        SelectObject(hdcOffScreen, hbmOffScreen as HGDIOBJ);
        SelectObject(hdcBg, InternalDrag.hbmBg as HGDIOBJ);

        /* get the actual background of the update region */
        BitBlt(
            hdcOffScreen,
            0,
            0,
            sizeRegX,
            sizeRegY,
            hdcDrag,
            origRegX,
            origRegY,
            SRCCOPY as DWORD,
        );
        /* erase the old image */
        BitBlt(
            hdcOffScreen,
            origOldX - origRegX,
            origOldY - origRegY,
            (*InternalDrag.himl).cx,
            (*InternalDrag.himl).cy,
            hdcBg,
            0,
            0,
            SRCCOPY as DWORD,
        );
        /* save the background */
        BitBlt(
            hdcBg,
            0,
            0,
            (*InternalDrag.himl).cx,
            (*InternalDrag.himl).cy,
            hdcOffScreen,
            origNewX - origRegX,
            origNewY - origRegY,
            SRCCOPY as DWORD,
        );
        /* draw the image */
        ImageList_InternalDragDraw(hdcOffScreen, origNewX - origRegX, origNewY - origRegY);
        /* draw the update region to the screen */
        BitBlt(
            hdcDrag,
            origRegX,
            origRegY,
            sizeRegX,
            sizeRegY,
            hdcOffScreen,
            0,
            0,
            SRCCOPY as DWORD,
        );

        DeleteDC(hdcBg);
        DeleteDC(hdcOffScreen);
        DeleteObject(hbmOffScreen as HGDIOBJ);
        ReleaseDC(InternalDrag.hwnd, hdcDrag);
    }

    /* update the image position */
    InternalDrag.x = x;
    InternalDrag.y = y;

    return TRUE;
}

#[no_mangle]
pub unsafe extern "system" fn ImageList_DragShowNolock(bShow: BOOL) -> BOOL {
    let mut hdcDrag: HDC = core::ptr::null_mut();
    let mut hdcBg: HDC = core::ptr::null_mut();
    let mut x: INT;
    let mut y: INT;

    if is_valid(InternalDrag.himl) == 0 {
        return FALSE;
    }

    /* DragImage is already visible/hidden */
    if (InternalDrag.bShow != 0 && bShow != 0) || (InternalDrag.bShow == 0 && bShow == 0) {
        return FALSE;
    }

    /* position of the origin of the DragImage */
    x = InternalDrag.x - InternalDrag.dxHotspot;
    y = InternalDrag.y - InternalDrag.dyHotspot;

    hdcDrag = GetDCEx(
        InternalDrag.hwnd,
        0 as _,
        (DCX_WINDOW | DCX_CACHE | DCX_LOCKWINDOWUPDATE) as DWORD,
    );
    if hdcDrag.is_null() {
        return FALSE;
    }

    hdcBg = CreateCompatibleDC(hdcDrag);
    if InternalDrag.hbmBg.is_null() {
        InternalDrag.hbmBg = CreateCompatibleBitmap(
            hdcDrag,
            (*InternalDrag.himl).cx,
            (*InternalDrag.himl).cy,
        );
    }
    SelectObject(hdcBg, InternalDrag.hbmBg as HGDIOBJ);

    if bShow != 0 {
        /* save the background */
        BitBlt(
            hdcBg,
            0,
            0,
            (*InternalDrag.himl).cx,
            (*InternalDrag.himl).cy,
            hdcDrag,
            x,
            y,
            SRCCOPY as DWORD,
        );
        /* show the image */
        ImageList_InternalDragDraw(hdcDrag, x, y);
    } else {
        /* hide the image */
        BitBlt(
            hdcDrag,
            x,
            y,
            (*InternalDrag.himl).cx,
            (*InternalDrag.himl).cy,
            hdcBg,
            0,
            0,
            SRCCOPY as DWORD,
        );
    }

    InternalDrag.bShow = (InternalDrag.bShow == 0) as BOOL;

    DeleteDC(hdcBg);
    ReleaseDC(InternalDrag.hwnd, hdcDrag);
    return TRUE;
}

