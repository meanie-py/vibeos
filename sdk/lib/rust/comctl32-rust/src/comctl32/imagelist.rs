#[no_mangle]
pub unsafe extern "system" fn ImageList_SetDragCursorImage(
    himlDrag: HIMAGELIST,
    iDrag: INT,
    dxHotspot: INT,
    dyHotspot: INT,
) -> BOOL {
    let mut himlTemp: HIMAGELIST = core::ptr::null_mut();
    let mut visible: BOOL;

    if is_valid(InternalDrag.himl) == 0 || is_valid(himlDrag) == 0 {
        return FALSE;
    }

    visible = InternalDrag.bShow;

    himlTemp = Internal_Merge(
        InternalDrag.himlNoCursor,
        0,
        himlDrag,
        iDrag,
        dxHotspot,
        dyHotspot,
    );

    if visible != 0 {
        /* hide the drag image */
        ImageList_DragShowNolock(FALSE);
    }
    if (*InternalDrag.himl).cx != (*himlTemp).cx || (*InternalDrag.himl).cy != (*himlTemp).cy {
        /* the size of the drag image changed, invalidate the buffer */
        DeleteObject(InternalDrag.hbmBg as HGDIOBJ);
        InternalDrag.hbmBg = core::ptr::null_mut();
    }

    if InternalDrag.himl != InternalDrag.himlNoCursor {
        ImageList_Destroy(InternalDrag.himl);
    }
    InternalDrag.himl = himlTemp;

    if visible != 0 {
        /* show the drag image */
        ImageList_DragShowNolock(TRUE);
    }

    return TRUE;
}

