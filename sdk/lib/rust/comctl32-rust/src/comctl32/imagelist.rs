pub const TILE_COUNT: u32 = 4;

unsafe extern "C" fn impl_from_IImageList2(mut iface: *mut IImageList2) -> HIMAGELIST {
    return (iface as ULONG_PTR).wrapping_sub(
        core::mem::offset_of!(_IMAGELIST, IImageList2_iface) as ULONG_PTR,
    ) as HIMAGELIST;
}

unsafe extern "C" fn imagelist_height(mut count: UINT) -> UINT {
    return count
        .wrapping_add(TILE_COUNT as UINT)
        .wrapping_sub(1 as UINT)
        .wrapping_div(TILE_COUNT as UINT);
}

unsafe extern "C" fn imagelist_point_from_index(
    mut himl: HIMAGELIST,
    mut index: UINT,
    mut pt: LPPOINT,
) {
    (*pt).x = index
        .wrapping_rem(TILE_COUNT as UINT)
        .wrapping_mul((*himl).cx as UINT) as LONG;
    (*pt).y = index
        .wrapping_div(TILE_COUNT as UINT)
        .wrapping_mul((*himl).cy as UINT) as LONG;
}

unsafe extern "C" fn imagelist_get_bitmap_size(
    mut himl: HIMAGELIST,
    mut count: UINT,
    mut sz: *mut SIZE,
) {
    (*sz).cx = ((*himl).cx as ::core::ffi::c_int * (TILE_COUNT as i32)) as LONG;
    (*sz).cy = imagelist_height(count).wrapping_mul((*himl).cy as UINT) as LONG;
}

unsafe extern "C" fn get_dib_stride(mut width: ::core::ffi::c_int, mut bpp: ::core::ffi::c_int) -> ::core::ffi::c_int {
    return ((width * bpp + 31) >> 3) & !3;
}

unsafe extern "C" fn get_dib_image_size(info: *const BITMAPINFO) -> i32 {
    return get_dib_stride(
        (*info).bmiHeader.biWidth as i32,
        (*info).bmiHeader.biBitCount as i32,
    ) * abs((*info).bmiHeader.biHeight as i32);
}

unsafe extern "C" fn imagelist_copy_images(himl: HIMAGELIST, hdcSrc: HDC, hdcDest: HDC, src: UINT, count: UINT, dest: UINT) {
    let mut ptSrc: POINT = POINT { x: 0, y: 0 };
    let mut ptDest: POINT = POINT { x: 0, y: 0 };
    let mut sz: SIZE = SIZE { cx: 0, cy: 0 };
    let mut i: UINT = 0;
    i = 0 as UINT;
    while i < TILE_COUNT as UINT {
        imagelist_point_from_index(himl, src.wrapping_add(i), core::ptr::addr_of_mut!(ptSrc));
        imagelist_point_from_index(himl, dest.wrapping_add(i), core::ptr::addr_of_mut!(ptDest));
        sz.cx = (*himl).cx as LONG;
        sz.cy = ((*himl).cy as UINT).wrapping_mul(imagelist_height(count.wrapping_sub(i))) as LONG;

        BitBlt(
            hdcDest,
            ptDest.x as INT,
            ptDest.y as INT,
            sz.cx as INT,
            sz.cy as INT,
            hdcSrc,
            ptSrc.x as INT,
            ptSrc.y as INT,
            SRCCOPY as DWORD,
        );
        i = i.wrapping_add(1);
    }
}

unsafe extern "C" fn add_dib_bits(
    himl: HIMAGELIST,
    pos: ::core::ffi::c_int,
    count: ::core::ffi::c_int,
    width: ::core::ffi::c_int,
    height: ::core::ffi::c_int,
    info: *mut BITMAPINFO,
    mask_info: *mut BITMAPINFO,
    bits: *mut DWORD,
    mask_bits: *mut BYTE,
) {
    let mut i: ::core::ffi::c_int;
    let mut j: ::core::ffi::c_int;
    let mut n: ::core::ffi::c_int;
    let mut pt: POINT = POINT { x: 0, y: 0 };
    let stride: ::core::ffi::c_int = (*info).bmiHeader.biWidth as ::core::ffi::c_int;
    let mask_stride: ::core::ffi::c_int = (((*info).bmiHeader.biWidth as ::core::ffi::c_int + 31) / 32) * 4;

    n = 0;
    while n < count {
        let mut has_alpha: BOOL = FALSE;

        imagelist_point_from_index(himl, (pos + n) as UINT, &raw mut pt);

        /* check if bitmap has an alpha channel */
        i = 0;
        while i < height && has_alpha == 0 {
            j = n * width;
            while j < (n + 1) * width {
                has_alpha = ((((*bits.offset((i * stride + j) as isize)) & 0xff000000) != 0) as ::core::ffi::c_int) as BOOL;
                if has_alpha != 0 {
                    break;
                }
                j += 1;
            }
            i += 1;
        }

        if has_alpha == 0 {  /* generate alpha channel from the mask */
            i = 0;
            while i < height {
                j = n * width;
                while j < (n + 1) * width {
                    if mask_info.is_null()
                        || ((((*mask_bits.offset((i * mask_stride + j / 8) as isize)) as ::core::ffi::c_int) << (j % 8)) & 0x80) == 0
                    {
                        *bits.offset((i * stride + j) as isize) |= 0xff000000;
                    } else {
                        *bits.offset((i * stride + j) as isize) = 0;
                    }
                    j += 1;
                }
                i += 1;
            }
        } else {
            *(*himl).has_alpha.offset((pos + n) as isize) = (1) as ::core::ffi::c_char;

            if !mask_info.is_null() && !(*himl).hbmMask.is_null() {  /* generate the mask from the alpha channel */
                i = 0;
                while i < height {
                    j = n * width;
                    while j < (n + 1) * width {
                        if ((*bits.offset((i * stride + j) as isize)) >> 24) > 25 { /* more than 10% alpha */
                            let p: *mut BYTE = mask_bits.offset((i * mask_stride + j / 8) as isize);
                            *p = ((*p as ::core::ffi::c_int) & !((0x80 as ::core::ffi::c_int) >> (j % 8))) as BYTE;
                        } else {
                            let p: *mut BYTE = mask_bits.offset((i * mask_stride + j / 8) as isize);
                            *p = ((*p as ::core::ffi::c_int) | ((0x80 as ::core::ffi::c_int) >> (j % 8))) as BYTE;
                        }
                        j += 1;
                    }
                    i += 1;
                }
            }
        }

        StretchDIBits(
            (*himl).hdcImage,
            pt.x as ::core::ffi::c_int,
            pt.y as ::core::ffi::c_int,
            (*himl).cx as ::core::ffi::c_int,
            (*himl).cy as ::core::ffi::c_int,
            n * width,
            0,
            width,
            height,
            bits as *const ::core::ffi::c_void,
            info,
            DIB_RGB_COLORS as UINT,
            SRCCOPY as DWORD,
        );
        if !mask_info.is_null() {
            StretchDIBits(
                (*himl).hdcMask,
                pt.x as ::core::ffi::c_int,
                pt.y as ::core::ffi::c_int,
                (*himl).cx as ::core::ffi::c_int,
                (*himl).cy as ::core::ffi::c_int,
                n * width,
                0,
                width,
                height,
                mask_bits as *const ::core::ffi::c_void,
                mask_info,
                DIB_RGB_COLORS as UINT,
                SRCCOPY as DWORD,
            );
        }
        n += 1;
    }
}

unsafe extern "C" fn add_with_alpha(
    mut himl: HIMAGELIST,
    mut hdc: HDC,
    mut pos: ::core::ffi::c_int,
    mut count: ::core::ffi::c_int,
    mut width: ::core::ffi::c_int,
    mut height: ::core::ffi::c_int,
    mut hbmImage: HBITMAP,
    mut hbmMask: HBITMAP,
) -> BOOL {
    let mut ret: BOOL = FALSE;
    let mut bm: BITMAP = core::mem::zeroed::<BITMAP>();
    let mut info: *mut BITMAPINFO = core::ptr::null_mut::<BITMAPINFO>();
    let mut mask_info: *mut BITMAPINFO = core::ptr::null_mut::<BITMAPINFO>();
    let mut bits: *mut DWORD = core::ptr::null_mut::<DWORD>();
    let mut mask_bits: *mut BYTE = core::ptr::null_mut::<BYTE>();
    let mut mask_width: DWORD = 0;

    if GetObjectW(
        hbmImage as HANDLE,
        core::mem::size_of::<BITMAP>() as ::core::ffi::c_int,
        core::ptr::addr_of_mut!(bm) as LPVOID,
    ) == 0
    {
        return FALSE;
    }

    /* if either the imagelist or the source bitmap don't have an alpha channel, bail out now */
    if (*himl).has_alpha.is_null() {
        return FALSE;
    }
    if bm.bmBitsPixel as ::core::ffi::c_int != 32 {
        return FALSE;
    }

    SelectObject(hdc, hbmImage as HGDIOBJ);
    mask_width = ((bm.bmWidth + 31) / 32 * 4) as DWORD;

    'done: {
        info = heap_alloc(
            FIELD_OFFSET!(BITMAPINFO, bmiColors[256]) as SIZE_T,
        ) as *mut BITMAPINFO;
        if info.is_null() {
            break 'done;
        }
        (*info).bmiHeader.biSize = core::mem::size_of::<BITMAPINFOHEADER>() as DWORD;
        (*info).bmiHeader.biWidth = bm.bmWidth;
        (*info).bmiHeader.biHeight = -height as LONG;
        (*info).bmiHeader.biPlanes = 1 as WORD;
        (*info).bmiHeader.biBitCount = 32 as WORD;
        (*info).bmiHeader.biCompression = BI_RGB as DWORD;
        (*info).bmiHeader.biSizeImage =
            (bm.bmWidth as ::core::ffi::c_int * height * 4) as DWORD;
        (*info).bmiHeader.biXPelsPerMeter = 0 as LONG;
        (*info).bmiHeader.biYPelsPerMeter = 0 as LONG;
        (*info).bmiHeader.biClrUsed = 0 as DWORD;
        (*info).bmiHeader.biClrImportant = 0 as DWORD;
        bits = heap_alloc((*info).bmiHeader.biSizeImage as SIZE_T) as *mut DWORD;
        if bits.is_null() {
            break 'done;
        }
        if GetDIBits(
            hdc,
            hbmImage,
            0 as UINT,
            height as UINT,
            bits as LPVOID,
            info as LPBITMAPINFO,
            DIB_RGB_COLORS as UINT,
        ) == 0
        {
            break 'done;
        }

        if !hbmMask.is_null() {
            mask_info = heap_alloc(
                FIELD_OFFSET!(BITMAPINFO, bmiColors[2]) as SIZE_T,
            ) as *mut BITMAPINFO;
            if mask_info.is_null() {
                break 'done;
            }
            (*mask_info).bmiHeader = (*info).bmiHeader;
            (*mask_info).bmiHeader.biBitCount = 1 as WORD;
            (*mask_info).bmiHeader.biSizeImage = mask_width.wrapping_mul(height as DWORD);
            mask_bits = heap_alloc_zero((*mask_info).bmiHeader.biSizeImage as SIZE_T) as *mut BYTE;
            if mask_bits.is_null() {
                break 'done;
            }
            if GetDIBits(
                hdc,
                hbmMask,
                0 as UINT,
                height as UINT,
                mask_bits as LPVOID,
                mask_info as LPBITMAPINFO,
                DIB_RGB_COLORS as UINT,
            ) == 0
            {
                break 'done;
            }
        }

        add_dib_bits(himl, pos, count, width, height, info, mask_info, bits, mask_bits);
        ret = TRUE as BOOL;
    }

    heap_free(info as *mut ::core::ffi::c_void);
    heap_free(mask_info as *mut ::core::ffi::c_void);
    heap_free(bits as *mut ::core::ffi::c_void);
    heap_free(mask_bits as *mut ::core::ffi::c_void);
    return ret;
}

