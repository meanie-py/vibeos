unsafe extern "C" fn ChangeColorDepth(mut himl: HIMAGELIST) -> BOOL {
    let mut ilc: UINT = (*himl).flags & ILC_COLORMASK as UINT;
    if ilc >= ILC_COLOR4 as UINT && ilc <= ILC_COLOR32 as UINT {
        (*himl).uBitsPixel = ilc;
    } else {
        (*himl).uBitsPixel = GetDeviceCaps((*himl).hdcImage, (BITSPIXEL as i32)) as UINT;
    }

    /* Create new himl->hbmImage for BPP changes (for SHELL32) */
    return ((*(*(himl as *mut IImageList)).lpVtbl)
        .SetImageCount
        .unwrap_unchecked()(himl as *mut IImageList, 0 as UINT)
        == S_OK) as BOOL;
}

#[no_mangle]
pub unsafe extern "system" fn ImageList_SetFlags(himl: HIMAGELIST, flags: DWORD) -> BOOL {
    if is_valid(himl) == 0 {
        return FALSE as BOOL;
    }

    if (flags & !(ILC_PUBLICFLAGS as DWORD)) != 0 {
        return FALSE as BOOL;
    }

    if (((*himl).flags ^ flags) & (ILC_SYSTEM as DWORD)) != 0
        && (WinVerMajor!() as i32) < (6 as i32)
    {
        return FALSE as BOOL; /* Can't change this flag */
    }

    if (*himl).flags == flags && (WinVerMajor!() as i32) >= (6 as i32) {
        return TRUE as BOOL;
    }

    (*himl).flags = flags as UINT;
    return ChangeColorDepth(himl);
}

#[no_mangle]
pub unsafe extern "system" fn Internal_SetIconSize(himl: HIMAGELIST, cx: INT, cy: INT) -> BOOL {
    let mut nCount: INT;
    let mut hbmNew: HBITMAP;

    if is_valid(himl) == 0 {
        return FALSE;
    }

    /* remove all images */
    (*himl).cMaxImage = (*himl).cInitial + 1;
    (*himl).cCurImage = 0;
    (*himl).cx = cx;
    (*himl).cy = cy;

    /* initialize overlay mask indices */
    nCount = 0;
    while nCount < (MAX_OVERLAYIMAGE as i32) {
        (*himl).nOvlIdx[nCount as usize] = -1;
        nCount += 1;
    }

    hbmNew = ImageList_CreateImage((*himl).hdcImage, himl, (*himl).cMaxImage as UINT);
    SelectObject((*himl).hdcImage, hbmNew as HGDIOBJ);
    DeleteObject((*himl).hbmImage as HGDIOBJ);
    (*himl).hbmImage = hbmNew;

    if !(*himl).hbmMask.is_null() {
        let mut sz: SIZE = core::mem::zeroed();
        imagelist_get_bitmap_size(himl, (*himl).cMaxImage as UINT, core::ptr::addr_of_mut!(sz));
        hbmNew = CreateBitmap(
            sz.cx as INT,
            sz.cy as INT,
            1 as UINT,
            1 as UINT,
            core::ptr::null(),
        );
        SelectObject((*himl).hdcMask, hbmNew as HGDIOBJ);
        DeleteObject((*himl).hbmMask as HGDIOBJ);
        (*himl).hbmMask = hbmNew;
    }

    return TRUE;
}
