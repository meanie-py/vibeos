#[no_mangle]
pub unsafe extern "system" fn ImageList_LoadImageA(
    hi: HINSTANCE,
    lpbmp: LPCSTR,
    cx: INT,
    cGrow: INT,
    clrMask: COLORREF,
    uType: UINT,
    uFlags: UINT,
) -> HIMAGELIST {
    let mut himl: HIMAGELIST = core::ptr::null_mut();
    let mut lpbmpW: LPWSTR = core::ptr::null_mut();
    let mut len: DWORD = 0;

    if IS_INTRESOURCE!(lpbmp) != false {
        return ImageList_LoadImageW(hi, lpbmp as LPCWSTR, cx, cGrow, clrMask, uType, uFlags);
    }

    len = MultiByteToWideChar(
        CP_ACP as UINT,
        0 as DWORD,
        lpbmp,
        -(1 as ::core::ffi::c_int),
        core::ptr::null_mut(),
        0 as ::core::ffi::c_int,
    ) as DWORD;
    lpbmpW = heap_alloc(
        (len as SIZE_T).wrapping_mul(core::mem::size_of::<WCHAR>() as SIZE_T),
    ) as LPWSTR;
    MultiByteToWideChar(
        CP_ACP as UINT,
        0 as DWORD,
        lpbmp,
        -(1 as ::core::ffi::c_int),
        lpbmpW,
        len as ::core::ffi::c_int,
    );

    himl = ImageList_LoadImageW(hi, lpbmpW as LPCWSTR, cx, cGrow, clrMask, uType, uFlags);
    heap_free(lpbmpW as *mut core::ffi::c_void);
    return himl;
}

#[no_mangle]
pub unsafe extern "system" fn ImageList_LoadImageW(
    hi: HINSTANCE,
    lpbmp: LPCWSTR,
    mut cx: INT,
    cGrow: INT,
    clrMask: COLORREF,
    uType: UINT,
    uFlags: UINT,
) -> HIMAGELIST {
    let mut himl: HIMAGELIST = core::ptr::null_mut();
    let mut handle: HANDLE = core::ptr::null_mut();
    let mut nImageCount: INT = 0;

    handle = LoadImageW(hi, lpbmp, uType, 0, 0, uFlags);
    if handle.is_null() {
        return core::ptr::null_mut();
    }

    if uType == IMAGE_BITMAP {
        let mut dib: DIBSECTION = core::mem::zeroed();
        let mut color: UINT = 0;

        if (GetObjectW(
            handle,
            core::mem::size_of::<DIBSECTION>() as INT,
            core::ptr::addr_of_mut!(dib) as LPVOID,
        ) as usize) == core::mem::size_of::<BITMAP>() as usize {
            color = ILC_COLOR as UINT;
        } else {
            color = dib.dsBm.bmBitsPixel as UINT;
        }

        /* To match windows behavior, if cx is set to zero and
         the flag DI_DEFAULTSIZE is specified, cx becomes the
         system metric value for icons. If the flag is not specified
         the function sets the size to the height of the bitmap */
        if cx == 0 {
            if uFlags & DI_DEFAULTSIZE != 0 {
                cx = GetSystemMetrics((SM_CXICON) as i32) as INT;
            } else {
                cx = dib.dsBm.bmHeight as INT;
            }
        }

        nImageCount = dib.dsBm.bmWidth as INT / cx;

        if clrMask != CLR_NONE {
            color |= ILC_MASK as UINT;
        }
        himl = ImageList_Create(cx, dib.dsBm.bmHeight as INT, color, nImageCount, cGrow);
        if himl.is_null() {
            DeleteObject(handle as HGDIOBJ);
            return core::ptr::null_mut();
        }
        if clrMask == CLR_NONE {
            nImageCount = Internal_Add(himl, handle as HBITMAP, core::ptr::null_mut());
        } else {
            nImageCount = Internal_AddMasked(himl, handle as HBITMAP, clrMask);
        }

        if nImageCount < 0 {
            ImageList_Destroy(himl);
            himl = core::ptr::null_mut();
        }
    } else if (uType == IMAGE_ICON) || (uType == IMAGE_CURSOR) {
        let mut ii: ICONINFO = core::mem::zeroed();
        let mut bmp: BITMAP = core::mem::zeroed();

        GetIconInfo(handle as HICON, core::ptr::addr_of_mut!(ii));
        GetObjectW(
            ii.hbmColor as HANDLE,
            core::mem::size_of::<BITMAP>() as INT,
            core::ptr::addr_of_mut!(bmp) as LPVOID,
        );
        himl = ImageList_Create(
            bmp.bmWidth as INT,
            bmp.bmHeight as INT,
            ILC_MASK | ILC_COLOR,
            1,
            cGrow,
        );
        if himl.is_null() {
            DeleteObject(ii.hbmColor as HGDIOBJ);
            DeleteObject(ii.hbmMask as HGDIOBJ);
            DeleteObject(handle as HGDIOBJ);
            return core::ptr::null_mut();
        }
        Internal_Add(himl, ii.hbmColor, ii.hbmMask);
        DeleteObject(ii.hbmColor as HGDIOBJ);
        DeleteObject(ii.hbmMask as HGDIOBJ);
    }

    DeleteObject(handle as HGDIOBJ);

    return himl;
}
#[no_mangle]
pub unsafe extern "system" fn Internal_Merge(
    himl1: HIMAGELIST,
    i1: INT,
    himl2: HIMAGELIST,
    i2: INT,
    dx: INT,
    dy: INT,
) -> HIMAGELIST {
    let mut himlDst: HIMAGELIST = core::ptr::null_mut();
    let mut cxDst: INT;
    let mut cyDst: INT;
    let mut xOff1: INT;
    let mut yOff1: INT;
    let mut xOff2: INT;
    let mut yOff2: INT;
    let mut pt1: POINT = POINT { x: 0, y: 0 };
    let mut pt2: POINT = POINT { x: 0, y: 0 };
    let mut newFlags: INT;

    if is_valid(himl1) == 0 || is_valid(himl2) == 0 {
        return core::ptr::null_mut();
    }

    if dx > 0 {
        cxDst = max((*himl1).cx, dx + (*himl2).cx);
        xOff1 = 0;
        xOff2 = dx;
    }
    else if dx < 0 {
        cxDst = max((*himl2).cx, (*himl1).cx - dx);
        xOff1 = -dx;
        xOff2 = 0;
    }
    else {
        cxDst = max((*himl1).cx, (*himl2).cx);
        xOff1 = 0;
        xOff2 = 0;
    }

    if dy > 0 {
        cyDst = max((*himl1).cy, dy + (*himl2).cy);
        yOff1 = 0;
        yOff2 = dy;
    }
    else if dy < 0 {
        cyDst = max((*himl2).cy, (*himl1).cy - dy);
        yOff1 = -dy;
        yOff2 = 0;
    }
    else {
        cyDst = max((*himl1).cy, (*himl2).cy);
        yOff1 = 0;
        yOff2 = 0;
    }

    newFlags = (((if (*himl1).flags > (*himl2).flags {
        (*himl1).flags
    } else {
        (*himl2).flags
    }) & ILC_COLORDDB) as INT);
    if newFlags == (ILC_COLORDDB as i32)
        && (((*himl1).flags & ILC_COLORDDB) as INT) == (ILC_COLOR16 as i32)
    {
        newFlags = (ILC_COLOR16 as i32);
    }
    himlDst = ImageList_Create(
        cxDst,
        cyDst,
        ((ILC_MASK | (newFlags) as u32) as UINT),
        1,
        1,
    );

    if !himlDst.is_null() {
        imagelist_point_from_index(himl1, i1 as UINT, &raw mut pt1);
        imagelist_point_from_index(himl2, i2 as UINT, &raw mut pt2);

        /* copy image */
        BitBlt(
            (*himlDst).hdcImage,
            0,
            0,
            cxDst,
            cyDst,
            (*himl1).hdcImage,
            0,
            0,
            BLACKNESS as DWORD,
        );
        if i1 >= 0 && i1 < (*himl1).cCurImage {
            BitBlt(
                (*himlDst).hdcImage,
                xOff1,
                yOff1,
                (*himl1).cx,
                (*himl1).cy,
                (*himl1).hdcImage,
                pt1.x as INT,
                pt1.y as INT,
                SRCCOPY as DWORD,
            );
        }
        if i2 >= 0 && i2 < (*himl2).cCurImage {
            if ((*himl2).flags & ILC_MASK) != 0 {
                BitBlt(
                    (*himlDst).hdcImage,
                    xOff2,
                    yOff2,
                    (*himl2).cx,
                    (*himl2).cy,
                    (*himl2).hdcMask,
                    pt2.x as INT,
                    pt2.y as INT,
                    SRCAND as DWORD,
                );
                BitBlt(
                    (*himlDst).hdcImage,
                    xOff2,
                    yOff2,
                    (*himl2).cx,
                    (*himl2).cy,
                    (*himl2).hdcImage,
                    pt2.x as INT,
                    pt2.y as INT,
                    SRCPAINT as DWORD,
                );
            }
            else {
                BitBlt(
                    (*himlDst).hdcImage,
                    xOff2,
                    yOff2,
                    (*himl2).cx,
                    (*himl2).cy,
                    (*himl2).hdcImage,
                    pt2.x as INT,
                    pt2.y as INT,
                    SRCCOPY as DWORD,
                );
            }
        }

        /* copy mask */
        BitBlt(
            (*himlDst).hdcMask,
            0,
            0,
            cxDst,
            cyDst,
            (*himl1).hdcMask,
            0,
            0,
            WHITENESS as DWORD,
        );
        if i1 >= 0 && i1 < (*himl1).cCurImage {
            BitBlt(
                (*himlDst).hdcMask,
                xOff1,
                yOff1,
                (*himl1).cx,
                (*himl1).cy,
                (*himl1).hdcMask,
                pt1.x as INT,
                pt1.y as INT,
                SRCCOPY as DWORD,
            );
        }
        if i2 >= 0 && i2 < (*himl2).cCurImage {
            BitBlt(
                (*himlDst).hdcMask,
                xOff2,
                yOff2,
                (*himl2).cx,
                (*himl2).cy,
                (*himl2).hdcMask,
                pt2.x as INT,
                pt2.y as INT,
                SRCAND as DWORD,
            );
        }

        (*himlDst).cCurImage = 1;
    }

    return himlDst;
}

unsafe extern "C" fn read_bitmap(pstm: *mut IStream, bmi: *mut BITMAPINFO) -> *mut core::ffi::c_void {
    let mut bmfh: BITMAPFILEHEADER = core::mem::zeroed();
    let mut bitsperpixel: core::ffi::c_int;
    let mut palspace: core::ffi::c_int;
    let mut bits: *mut core::ffi::c_void;

    if (IStream_Read(
        pstm,
        core::ptr::addr_of_mut!(bmfh) as *mut core::ffi::c_void,
        core::mem::size_of::<BITMAPFILEHEADER>() as ULONG,
        core::ptr::null_mut::<ULONG>(),
    )) < 0
    {
        return core::ptr::null_mut();
    }

    if bmfh.bfType as core::ffi::c_int
        != (('M' as core::ffi::c_int) << 8) | ('B' as core::ffi::c_int)
    {
        return core::ptr::null_mut();
    }

    if (IStream_Read(
        pstm,
        core::ptr::addr_of_mut!((*bmi).bmiHeader) as *mut core::ffi::c_void,
        core::mem::size_of::<BITMAPINFOHEADER>() as ULONG,
        core::ptr::null_mut::<ULONG>(),
    )) < 0
    {
        return core::ptr::null_mut();
    }

    if (*bmi).bmiHeader.biSize as usize != core::mem::size_of::<BITMAPINFOHEADER>() {
        return core::ptr::null_mut();
    }

    bitsperpixel = (*bmi).bmiHeader.biPlanes as core::ffi::c_int
        * (*bmi).bmiHeader.biBitCount as core::ffi::c_int;
    if bitsperpixel <= 8 {
        palspace = (((1 as usize) << bitsperpixel as usize)
            .wrapping_mul(core::mem::size_of::<RGBQUAD>()))
            as core::ffi::c_int;
    } else {
        palspace = 0;
    }

    (*bmi).bmiHeader.biSizeImage = get_dib_image_size(bmi) as DWORD;

    /* read the palette right after the end of the bitmapinfoheader */
    if palspace != 0
        && (IStream_Read(
            pstm,
            core::ptr::addr_of_mut!((*bmi).bmiColors) as *mut core::ffi::c_void,
            palspace as ULONG,
            core::ptr::null_mut::<ULONG>(),
        )) < 0
    {
        return core::ptr::null_mut();
    }

    bits = heap_alloc_zero((*bmi).bmiHeader.biSizeImage as SIZE_T);
    if bits.is_null() {
        return core::ptr::null_mut();
    }

    if (IStream_Read(
        pstm,
        bits,
        (*bmi).bmiHeader.biSizeImage as ULONG,
        core::ptr::null_mut::<ULONG>(),
    )) < 0
    {
        heap_free(bits);
        return core::ptr::null_mut();
    }
    return bits;
}

#[no_mangle]
pub unsafe extern "system" fn ImageList_Read(pstm: *mut IStream) -> HIMAGELIST {
    let mut image_buf: [u8; core::mem::size_of::<BITMAPINFOHEADER>() + core::mem::size_of::<RGBQUAD>() * (256) as usize] = [0; core::mem::size_of::<BITMAPINFOHEADER>() + core::mem::size_of::<RGBQUAD>() * (256) as usize];
    let mut mask_buf: [u8; core::mem::size_of::<BITMAPINFOHEADER>() + core::mem::size_of::<RGBQUAD>() * (256) as usize] = [0; core::mem::size_of::<BITMAPINFOHEADER>() + core::mem::size_of::<RGBQUAD>() * (256) as usize];
    let mut image_info: *mut BITMAPINFO = image_buf.as_mut_ptr() as *mut BITMAPINFO;
    let mut mask_info: *mut BITMAPINFO = mask_buf.as_mut_ptr() as *mut BITMAPINFO;
    let mut image_bits: *mut core::ffi::c_void = core::ptr::null_mut();
    let mut mask_bits: *mut core::ffi::c_void = core::ptr::null_mut();
    let mut ilHead: ILHEAD = core::mem::zeroed();
    let mut himl: HIMAGELIST = core::ptr::null_mut();
    let mut i: core::ffi::c_uint;

    if (IStream_Read(
        pstm,
        core::ptr::addr_of_mut!(ilHead) as *mut core::ffi::c_void,
        core::mem::size_of::<ILHEAD>() as ULONG,
        core::ptr::null_mut(),
    )) < 0
    {
        return core::ptr::null_mut();
    }
    if ilHead.usMagic as i32 != (((b'L' as i32) << 8) | (b'I' as i32)) {
        return core::ptr::null_mut();
    }
    if ilHead.usVersion as i32 != (IMAGELIST_VERSION as i32)
        && ilHead.usVersion as i32 != 0x600
        && ilHead.usVersion as i32 != 0x620
    {
        return core::ptr::null_mut();
    }

    himl = ImageList_Create(
        ilHead.cx as INT,
        ilHead.cy as INT,
        ilHead.flags as UINT,
        ilHead.cMaxImage as INT,
        ilHead.cGrow as INT,
    );
    if himl.is_null() {
        return core::ptr::null_mut();
    }

    /* keep version from stream */
    (*himl).usVersion = ilHead.usVersion;

    image_bits = read_bitmap(pstm, image_info);
    if image_bits.is_null() {
        return core::ptr::null_mut();
    }
    if (ilHead.flags as u32 & ILC_MASK) != 0 {
        mask_bits = read_bitmap(pstm, mask_info);
        if mask_bits.is_null() {
            return core::ptr::null_mut();
        }
    } else {
        mask_info = core::ptr::null_mut();
    }

    if !(*himl).has_alpha.is_null()
        && (*image_info).bmiHeader.biBitCount as i32 == 32
    {
        let mut ptr: *mut DWORD = image_bits as *mut DWORD;
        let mut mask_ptr: *mut BYTE = mask_bits as *mut BYTE;
        let mut stride: i32 = (*himl).cy as i32
            * (if ilHead.usVersion as i32 != (IMAGELIST_VERSION as i32) {
                (*himl).cx as i32
            } else {
                (*image_info).bmiHeader.biWidth as i32
            });
        let mut image_step: i32 = if ilHead.usVersion as i32 != (IMAGELIST_VERSION as i32) {
            1
        } else {
            (TILE_COUNT as i32)
        };
        let mut mask_step: i32 = if ilHead.usVersion as i32 != (IMAGELIST_VERSION as i32) {
            4
        } else {
            8
        };
        if (*image_info).bmiHeader.biHeight > 0 {
            /* bottom-up */
            ptr = ptr.offset(
                ((*image_info).bmiHeader.biHeight * (*image_info).bmiHeader.biWidth - stride)
                    as isize,
            );
            mask_ptr = mask_ptr.offset(
                (((*image_info).bmiHeader.biHeight * (*image_info).bmiHeader.biWidth - stride)
                    / mask_step) as isize,
            );
            stride = -stride;
            (*image_info).bmiHeader.biHeight = (*himl).cy as LONG;
        } else {
            (*image_info).bmiHeader.biHeight = -((*himl).cy as LONG);
        }
        i = 0 as core::ffi::c_uint;
        while i < ilHead.cCurImage as core::ffi::c_uint {
            add_dib_bits(
                himl,
                i as i32,
                min(
                    ilHead.cCurImage as core::ffi::c_uint - i,
                    image_step as core::ffi::c_uint,
                ) as i32,
                (*himl).cx as i32,
                (*himl).cy as i32,
                image_info,
                mask_info,
                ptr,
                mask_ptr,
            );
            ptr = ptr.offset(stride as isize);
            mask_ptr = mask_ptr.offset((stride / mask_step) as isize);
            i = i.wrapping_add(image_step as core::ffi::c_uint);
        }
    } else {
        StretchDIBits(
            (*himl).hdcImage,
            0,
            0,
            (*image_info).bmiHeader.biWidth,
            (*image_info).bmiHeader.biHeight,
            0,
            0,
            (*image_info).bmiHeader.biWidth,
            (*image_info).bmiHeader.biHeight,
            image_bits,
            image_info,
            DIB_RGB_COLORS,
            SRCCOPY,
        );
        if !mask_info.is_null() {
            StretchDIBits(
                (*himl).hdcMask,
                0,
                0,
                (*mask_info).bmiHeader.biWidth,
                (*mask_info).bmiHeader.biHeight,
                0,
                0,
                (*mask_info).bmiHeader.biWidth,
                (*mask_info).bmiHeader.biHeight,
                mask_bits,
                mask_info,
                DIB_RGB_COLORS,
                SRCCOPY,
            );
        }
    }
    heap_free(image_bits);
    heap_free(mask_bits);

    (*himl).cCurImage = ilHead.cCurImage as INT;
    (*himl).cMaxImage = ilHead.cMaxImage as INT;

    Internal_SetBkColor(himl, ilHead.bkcolor);
    i = 0 as core::ffi::c_uint;
    while i < 4 as core::ffi::c_uint {
        Internal_SetOverlayImage(
            himl,
            ilHead.ovls[i as usize] as INT,
            (i + 1 as core::ffi::c_uint) as INT,
        );
        i += 1;
    }
    return himl;
}
#[no_mangle]
pub unsafe extern "system" fn Internal_Remove(himl: HIMAGELIST, i: INT) -> BOOL {
    let mut hbmNewImage: HBITMAP = core::ptr::null_mut();
    let mut hbmNewMask: HBITMAP = core::ptr::null_mut();
    let mut hdcBmp: HDC = core::ptr::null_mut();
    let mut sz: SIZE = core::mem::zeroed();

    if is_valid(himl) == 0 {
        return FALSE;
    }

    if (i < -1) || (i >= (*himl).cCurImage) {
        return FALSE;
    }

    if i == -1 {
        let mut nCount: INT;

        /* remove all */
        if (*himl).cCurImage == 0 {
            /* remove all on empty ImageList is allowed */
            return TRUE;
        }

        (*himl).cMaxImage = (*himl).cGrow;
        (*himl).cCurImage = 0;
        nCount = 0;
        while nCount < (MAX_OVERLAYIMAGE as i32) {
            (*himl).nOvlIdx[nCount as usize] = -1;
            nCount += 1;
        }

        if !(*himl).has_alpha.is_null() {
            heap_free((*himl).has_alpha as *mut core::ffi::c_void);
            (*himl).has_alpha = heap_alloc_zero((*himl).cMaxImage as SIZE_T) as *mut core::ffi::c_char;
        }

        hbmNewImage = ImageList_CreateImage((*himl).hdcImage, himl, (*himl).cMaxImage as UINT);
        SelectObject((*himl).hdcImage, hbmNewImage as HGDIOBJ);
        DeleteObject((*himl).hbmImage as HGDIOBJ);
        (*himl).hbmImage = hbmNewImage;

        if !(*himl).hbmMask.is_null() {
            imagelist_get_bitmap_size(himl, (*himl).cMaxImage as UINT, &mut sz);
            hbmNewMask = CreateBitmap(
                sz.cx as INT,
                sz.cy as INT,
                1 as UINT,
                1 as UINT,
                core::ptr::null(),
            );
            SelectObject((*himl).hdcMask, hbmNewMask as HGDIOBJ);
            DeleteObject((*himl).hbmMask as HGDIOBJ);
            (*himl).hbmMask = hbmNewMask;
        }
    } else {
        /* delete one image */

        /* create new bitmap(s) */

        hbmNewImage = ImageList_CreateImage((*himl).hdcImage, himl, (*himl).cMaxImage as UINT);

        imagelist_get_bitmap_size(himl, (*himl).cMaxImage as UINT, &mut sz);
        if !(*himl).hbmMask.is_null() {
            hbmNewMask = CreateBitmap(
                sz.cx as INT,
                sz.cy as INT,
                1 as UINT,
                1 as UINT,
                core::ptr::null(),
            );
        } else {
            hbmNewMask = core::ptr::null_mut();  /* Just to keep compiler happy! */
        }

        hdcBmp = CreateCompatibleDC(core::ptr::null_mut());

        /* copy all images and masks prior to the "removed" image */
        if i > 0 {
            SelectObject(hdcBmp, hbmNewImage as HGDIOBJ);
            imagelist_copy_images(
                himl,
                (*himl).hdcImage,
                hdcBmp,
                0 as UINT,
                i as UINT,
                0 as UINT,
            );

            if !(*himl).hbmMask.is_null() {
                SelectObject(hdcBmp, hbmNewMask as HGDIOBJ);
                imagelist_copy_images(
                    himl,
                    (*himl).hdcMask,
                    hdcBmp,
                    0 as UINT,
                    i as UINT,
                    0 as UINT,
                );
            }
        }

        /* copy all images and masks behind the removed image */
        if i < (*himl).cCurImage - 1 {
            SelectObject(hdcBmp, hbmNewImage as HGDIOBJ);
            imagelist_copy_images(
                himl,
                (*himl).hdcImage,
                hdcBmp,
                (i + 1) as UINT,
                ((*himl).cCurImage - i) as UINT,
                i as UINT,
            );

            if !(*himl).hbmMask.is_null() {
                SelectObject(hdcBmp, hbmNewMask as HGDIOBJ);
                imagelist_copy_images(
                    himl,
                    (*himl).hdcMask,
                    hdcBmp,
                    (i + 1) as UINT,
                    ((*himl).cCurImage - i) as UINT,
                    i as UINT,
                );
            }
        }

        DeleteDC(hdcBmp);

        /* delete old images and insert new ones */
        SelectObject((*himl).hdcImage, hbmNewImage as HGDIOBJ);
        DeleteObject((*himl).hbmImage as HGDIOBJ);
        (*himl).hbmImage = hbmNewImage;
        if !(*himl).hbmMask.is_null() {
            SelectObject((*himl).hdcMask, hbmNewMask as HGDIOBJ);
            DeleteObject((*himl).hbmMask as HGDIOBJ);
            (*himl).hbmMask = hbmNewMask;
        }

        (*himl).cCurImage -= 1;
    }

    return TRUE;
}

#[no_mangle]
pub unsafe extern "system" fn Internal_Replace(
    himl: HIMAGELIST,
    i: INT,
    hbmImage: HBITMAP,
    hbmMask: HBITMAP,
) -> BOOL {
    let mut hdcImage: HDC;
    let mut bmp: BITMAP = core::mem::zeroed();
    let mut pt: POINT = core::mem::zeroed();

    if !(is_valid(himl) != 0) {
        return FALSE;
    }

    if (i >= (*himl).cMaxImage) || (i < 0) {
        return FALSE;
    }

    if !(GetObjectW(hbmImage as HANDLE, core::mem::size_of::<BITMAP>() as INT, &mut bmp as *mut BITMAP as LPVOID) != 0) {
        return FALSE;
    }

    hdcImage = CreateCompatibleDC(core::ptr::null_mut());

    /* Replace Image */
    SelectObject(hdcImage, hbmImage as HGDIOBJ);

    'done: {
        if add_with_alpha(himl, hdcImage, i, 1, bmp.bmWidth, bmp.bmHeight, hbmImage, hbmMask) != 0 {
            break 'done;
        }

        imagelist_point_from_index(himl, i as UINT, &mut pt as *mut POINT as LPPOINT);
        StretchBlt(
            (*himl).hdcImage,
            pt.x,
            pt.y,
            (*himl).cx,
            (*himl).cy,
            hdcImage,
            0,
            0,
            bmp.bmWidth,
            bmp.bmHeight,
            SRCCOPY,
        );

        if !(*himl).hbmMask.is_null() {
            let mut hdcTemp: HDC;
            let mut hOldBitmapTemp: HBITMAP;

            hdcTemp = CreateCompatibleDC(core::ptr::null_mut());
            hOldBitmapTemp = SelectObject(hdcTemp, hbmMask as HGDIOBJ) as HBITMAP;

            StretchBlt(
                (*himl).hdcMask,
                pt.x,
                pt.y,
                (*himl).cx,
                (*himl).cy,
                hdcTemp,
                0,
                0,
                bmp.bmWidth,
                bmp.bmHeight,
                SRCCOPY,
            );
            SelectObject(hdcTemp, hOldBitmapTemp as HGDIOBJ);
            DeleteDC(hdcTemp);

            /* Remove the background from the image
            */
            BitBlt(
                (*himl).hdcImage,
                pt.x,
                pt.y,
                bmp.bmWidth,
                bmp.bmHeight,
                (*himl).hdcMask,
                pt.x,
                pt.y,
                0x220326,
            ); /* NOTSRCAND */
        }
    }

    /* done: */
    DeleteDC(hdcImage);

    return TRUE;
}
#[no_mangle]
pub unsafe extern "system" fn Internal_ReplaceIcon(himl: HIMAGELIST, mut nIndex: INT, hIcon: HICON) -> INT {
    let mut hBestFitIcon: HICON;
    let mut ii: ICONINFO = core::mem::zeroed();
    let mut bmp: BITMAP = core::mem::zeroed();
    let mut ret: BOOL;
    let mut pt: POINT = core::mem::zeroed();

    if is_valid(himl) == 0 {
        return -1;
    }
    if (nIndex >= (*himl).cMaxImage) || (nIndex < -1) {
        return -1;
    }

    hBestFitIcon = CopyImage(
        hIcon as HANDLE,
        IMAGE_ICON as UINT,
        (*himl).cx as INT,
        (*himl).cy as INT,
        LR_COPYFROMRESOURCE as UINT,
    ) as HICON;
    /* the above will fail if the icon wasn't loaded from a resource, so try
     * again without LR_COPYFROMRESOURCE flag */
    if hBestFitIcon.is_null() {
        hBestFitIcon = CopyImage(
            hIcon as HANDLE,
            IMAGE_ICON as UINT,
            (*himl).cx as INT,
            (*himl).cy as INT,
            0 as UINT,
        ) as HICON;
    }
    if hBestFitIcon.is_null() {
        return -1;
    }

    if nIndex == -1 {
        if (*himl).cCurImage + 1 >= (*himl).cMaxImage {
            IMAGELIST_InternalExpandBitmaps(himl, 1 as INT);
        }

        nIndex = (*himl).cCurImage;
        (*himl).cCurImage += 1;
    }

    'done: {
        if !(*himl).has_alpha.is_null() && GetIconInfo(hBestFitIcon, &raw mut ii) != 0 {
            let hdcImage: HDC = CreateCompatibleDC(0 as HDC);
            GetObjectW(
                ii.hbmMask as HANDLE,
                core::mem::size_of::<BITMAP>() as INT,
                &raw mut bmp as LPVOID,
            );

            if ii.hbmColor.is_null() {
                let height: UINT = (bmp.bmHeight / (2 as LONG)) as UINT;
                let hdcMask: HDC = CreateCompatibleDC(0 as HDC);
                let color: HBITMAP = CreateBitmap(
                    bmp.bmWidth as INT,
                    height as INT,
                    1 as UINT,
                    1 as UINT,
                    core::ptr::null(),
                );
                SelectObject(hdcImage, color as HGDIOBJ);
                SelectObject(hdcMask, ii.hbmMask as HGDIOBJ);
                BitBlt(
                    hdcImage,
                    0 as INT,
                    0 as INT,
                    bmp.bmWidth as INT,
                    height as INT,
                    hdcMask,
                    0 as INT,
                    height as INT,
                    SRCCOPY as DWORD,
                );
                ret = add_with_alpha(
                    himl,
                    hdcImage,
                    nIndex,
                    1 as INT,
                    bmp.bmWidth as INT,
                    height as INT,
                    color,
                    ii.hbmMask,
                );
                DeleteDC(hdcMask);
                DeleteObject(color as HGDIOBJ);
            } else {
                ret = add_with_alpha(
                    himl,
                    hdcImage,
                    nIndex,
                    1 as INT,
                    bmp.bmWidth as INT,
                    bmp.bmHeight as INT,
                    ii.hbmColor,
                    ii.hbmMask,
                );
            }

            DeleteDC(hdcImage);
            DeleteObject(ii.hbmMask as HGDIOBJ);
            if !ii.hbmColor.is_null() {
                DeleteObject(ii.hbmColor as HGDIOBJ);
            }
            if ret != 0 {
                break 'done;
            }
        }

        imagelist_point_from_index(himl, nIndex as UINT, &raw mut pt);

        if !(*himl).hbmMask.is_null() {
            DrawIconEx(
                (*himl).hdcImage,
                pt.x as INT,
                pt.y as INT,
                hBestFitIcon,
                (*himl).cx as INT,
                (*himl).cy as INT,
                0 as UINT,
                0 as HBRUSH,
                DI_IMAGE as UINT,
            );
            PatBlt(
                (*himl).hdcMask,
                pt.x as INT,
                pt.y as INT,
                (*himl).cx as INT,
                (*himl).cy as INT,
                WHITENESS as DWORD,
            );
            DrawIconEx(
                (*himl).hdcMask,
                pt.x as INT,
                pt.y as INT,
                hBestFitIcon,
                (*himl).cx as INT,
                (*himl).cy as INT,
                0 as UINT,
                0 as HBRUSH,
                DI_MASK as UINT,
            );
        } else {
            let color: COLORREF = if (*himl).clrBk != CLR_NONE as COLORREF {
                (*himl).clrBk
            } else {
                comctl32_color.clrWindow
            };
            let brush: HBRUSH = CreateSolidBrush(GetNearestColor((*himl).hdcImage, color));

            SelectObject((*himl).hdcImage, brush as HGDIOBJ);
            PatBlt(
                (*himl).hdcImage,
                pt.x as INT,
                pt.y as INT,
                (*himl).cx as INT,
                (*himl).cy as INT,
                PATCOPY as DWORD,
            );
            SelectObject(
                (*himl).hdcImage,
                GetStockObject(BLACK_BRUSH as INT),
            );
            DeleteObject(brush as HGDIOBJ);
            DrawIconEx(
                (*himl).hdcImage,
                pt.x as INT,
                pt.y as INT,
                hBestFitIcon,
                (*himl).cx as INT,
                (*himl).cy as INT,
                0 as UINT,
                0 as HBRUSH,
                DI_NORMAL as UINT,
            );
        }
    }

    DestroyIcon(hBestFitIcon);

    return nIndex;
}
