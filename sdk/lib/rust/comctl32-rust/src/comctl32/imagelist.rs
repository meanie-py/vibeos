#[no_mangle]
pub unsafe extern "system" fn Internal_AddMasked(himl: HIMAGELIST, hBitmap: HBITMAP, clrMask: COLORREF) -> INT {
    let mut hdcMask: HDC;
    let mut hdcBitmap: HDC;
    let mut ret: INT;
    let mut bmp: BITMAP = core::mem::zeroed();
    let mut hMaskBitmap: HBITMAP;
    let mut bkColor: COLORREF;

    if (*__wine_dbch___default).flags as core::ffi::c_int
        & (1 as core::ffi::c_int) << __WINE_DBCL_TRACE as core::ffi::c_int
        != 0
    {
        let __dbch: *mut __wine_debug_channel = __wine_dbch___default;
        let __dbcl: __wine_debug_class = __WINE_DBCL_TRACE;
        ros_dbg_log(
            __dbcl,
            __dbch,
            b"dll/win32/comctl32/imagelist.c\0"
                as *const u8 as *const core::ffi::c_char,
            b"Internal_AddMasked\0" as *const u8 as *const core::ffi::c_char,
            581 as core::ffi::c_int,
            b"himl=%p hbitmap=%p clrmask=%x\n\0" as *const u8 as *const core::ffi::c_char,
            himl,
            hBitmap,
            clrMask,
        );
    }

    if is_valid(himl) == 0 {
        return -(1);
    }

    if GetObjectW((hBitmap).cast(), core::mem::size_of::<BITMAP>() as core::ffi::c_int, &raw mut bmp as LPVOID) == 0 {
        return -(1);
    }

    hdcBitmap = CreateCompatibleDC(core::ptr::null_mut());
    SelectObject(hdcBitmap, (hBitmap).cast());

    /* Create a temp Mask so we can remove the background of the Image */
    hdcMask = CreateCompatibleDC(core::ptr::null_mut());
    hMaskBitmap = CreateBitmap(
        bmp.bmWidth as INT,
        bmp.bmHeight as INT,
        1,
        1,
        core::ptr::null(),
    );
    SelectObject(hdcMask, (hMaskBitmap).cast());

    /* create monochrome image to the mask bitmap */
    bkColor = if clrMask != CLR_DEFAULT {
        clrMask
    } else {
        GetPixel(hdcBitmap, 0, 0)
    };
    SetBkColor(hdcBitmap, bkColor);
    BitBlt(
        hdcMask,
        0,
        0,
        bmp.bmWidth as INT,
        bmp.bmHeight as INT,
        hdcBitmap,
        0,
        0,
        SRCCOPY,
    );

    /*
     * Remove the background from the image
     *
     * WINDOWS BUG ALERT!!!!!!
     *  The statement below should not be done in common practice
     *  but this is how Internal_AddMasked works in Windows.
     *  It overwrites the original bitmap passed, this was discovered
     *  by using the same bitmap to iterate the different styles
     *  on windows where it failed (BUT Internal_Add is OK)
     *  This is here in case some apps rely on this bug
     *
     *  Blt mode 0x220326 is NOTSRCAND
     */
    if (bmp.bmBitsPixel as core::ffi::c_int) > 8 {
        /* NOTSRCAND can't work with palettes */
        SetBkColor(hdcBitmap, RGB!(255, 255, 255));
        BitBlt(
            hdcBitmap,
            0,
            0,
            bmp.bmWidth as INT,
            bmp.bmHeight as INT,
            hdcMask,
            0,
            0,
            0x220326,
        );
    }

    DeleteDC(hdcBitmap);
    DeleteDC(hdcMask);

    ret = Internal_Add(himl, hBitmap, hMaskBitmap);

    DeleteObject((hMaskBitmap).cast());
    return ret;
}
#[no_mangle]
pub unsafe extern "system" fn Internal_BeginDrag(himlTrack: HIMAGELIST, iTrack: INT, dxHotspot: INT, dyHotspot: INT) -> BOOL {
    let mut cx: INT;
    let mut cy: INT;
    let mut src: POINT = POINT { x: 0, y: 0 };
    let mut dst: POINT = POINT { x: 0, y: 0 };

    if is_valid(himlTrack) == 0 {
        return FALSE;
    }

    if iTrack >= (*himlTrack).cCurImage {
        return FALSE;
    }

    if !InternalDrag.himl.is_null() {
        return FALSE;
    }

    cx = (*himlTrack).cx;
    cy = (*himlTrack).cy;

    InternalDrag.himl = ImageList_Create(cx, cy, (*himlTrack).flags, 1, 1);
    InternalDrag.himlNoCursor = InternalDrag.himl;
    if InternalDrag.himl.is_null() {
        return FALSE;
    }

    InternalDrag.dxHotspot = dxHotspot;
    InternalDrag.dyHotspot = dyHotspot;

    /* copy image */
    imagelist_point_from_index(InternalDrag.himl, 0, core::ptr::addr_of_mut!(dst));
    imagelist_point_from_index(himlTrack, (iTrack) as UINT, core::ptr::addr_of_mut!(src));
    BitBlt(
        (*InternalDrag.himl).hdcImage,
        dst.x,
        dst.y,
        cx,
        cy,
        (*himlTrack).hdcImage,
        src.x,
        src.y,
        SRCCOPY,
    );
    BitBlt(
        (*InternalDrag.himl).hdcMask,
        dst.x,
        dst.y,
        cx,
        cy,
        (*himlTrack).hdcMask,
        src.x,
        src.y,
        SRCCOPY,
    );

    (*InternalDrag.himl).cCurImage = 1;

    return TRUE;
}
#[no_mangle]
pub unsafe extern "system" fn Internal_Copy(himlDst: HIMAGELIST, iDst: INT, himlSrc: HIMAGELIST, iSrc: INT, uFlags: UINT) -> BOOL {
    let mut ptSrc: POINT = POINT { x: 0, y: 0 };
    let mut ptDst: POINT = POINT { x: 0, y: 0 };

    if is_valid(himlSrc) == 0 || is_valid(himlDst) == 0 {
        return FALSE;
    }
    if iDst < 0 || iDst >= (*himlDst).cCurImage {
        return FALSE;
    }
    if iSrc < 0 || iSrc >= (*himlSrc).cCurImage {
        return FALSE;
    }

    imagelist_point_from_index(himlDst, iDst as UINT, core::ptr::addr_of_mut!(ptDst));
    imagelist_point_from_index(himlSrc, iSrc as UINT, core::ptr::addr_of_mut!(ptSrc));

    if (uFlags & ILCF_SWAP) != 0 {
        let mut hdcBmp: HDC = core::ptr::null_mut::<HDC__>();
        let mut hbmTempImage: HBITMAP = core::ptr::null_mut::<HBITMAP__>();
        let mut hbmTempMask: HBITMAP = core::ptr::null_mut::<HBITMAP__>();

        hdcBmp = CreateCompatibleDC(core::ptr::null_mut());

        hbmTempImage = CreateBitmap(
            (*himlSrc).cx,
            (*himlSrc).cy,
            1,
            (*himlSrc).uBitsPixel,
            core::ptr::null::<core::ffi::c_void>(),
        );
        hbmTempMask = CreateBitmap(
            (*himlSrc).cx,
            (*himlSrc).cy,
            1,
            1,
            core::ptr::null::<core::ffi::c_void>(),
        );

        SelectObject(hdcBmp, hbmTempImage as HGDIOBJ);
        StretchBlt(
            hdcBmp,
            0,
            0,
            (*himlSrc).cx,
            (*himlSrc).cy,
            (*himlDst).hdcImage,
            ptDst.x,
            ptDst.y,
            (*himlDst).cx,
            (*himlDst).cy,
            SRCCOPY,
        );

        SelectObject(hdcBmp, hbmTempMask as HGDIOBJ);
        StretchBlt(
            hdcBmp,
            0,
            0,
            (*himlSrc).cx,
            (*himlSrc).cy,
            (*himlDst).hdcMask,
            ptDst.x,
            ptDst.y,
            (*himlDst).cx,
            (*himlDst).cy,
            SRCCOPY,
        );

        StretchBlt(
            (*himlDst).hdcImage,
            ptDst.x,
            ptDst.y,
            (*himlDst).cx,
            (*himlDst).cy,
            (*himlSrc).hdcImage,
            ptSrc.x,
            ptSrc.y,
            (*himlSrc).cx,
            (*himlSrc).cy,
            SRCCOPY,
        );
        StretchBlt(
            (*himlDst).hdcMask,
            ptDst.x,
            ptDst.y,
            (*himlDst).cx,
            (*himlDst).cy,
            (*himlSrc).hdcMask,
            ptSrc.x,
            ptSrc.y,
            (*himlSrc).cx,
            (*himlSrc).cy,
            SRCCOPY,
        );

        BitBlt(
            (*himlSrc).hdcMask,
            ptSrc.x,
            ptSrc.y,
            (*himlSrc).cx,
            (*himlSrc).cy,
            hdcBmp,
            0,
            0,
            SRCCOPY,
        );

        BitBlt(
            (*himlSrc).hdcImage,
            ptSrc.x,
            ptSrc.y,
            (*himlSrc).cx,
            (*himlSrc).cy,
            hdcBmp,
            0,
            0,
            SRCCOPY,
        );

        DeleteObject(hbmTempMask as HGDIOBJ);
        DeleteObject(hbmTempImage as HGDIOBJ);
        DeleteDC(hdcBmp);
    } else {
        StretchBlt(
            (*himlDst).hdcImage,
            ptDst.x,
            ptDst.y,
            (*himlDst).cx,
            (*himlDst).cy,
            (*himlSrc).hdcImage,
            ptSrc.x,
            ptSrc.y,
            (*himlSrc).cx,
            (*himlSrc).cy,
            SRCCOPY,
        );

        StretchBlt(
            (*himlDst).hdcMask,
            ptDst.x,
            ptDst.y,
            (*himlDst).cx,
            (*himlDst).cy,
            (*himlSrc).hdcMask,
            ptSrc.x,
            ptSrc.y,
            (*himlSrc).cx,
            (*himlSrc).cy,
            SRCCOPY,
        );
    }

    return TRUE;
}

#[no_mangle]
pub unsafe extern "system" fn ImageList_Create(
    mut cx: INT,
    mut cy: INT,
    mut flags: UINT,
    mut cInitial: INT,
    mut cGrow: INT,
) -> HIMAGELIST {
    let mut himl: HIMAGELIST = core::ptr::null_mut();
    let mut nCount: INT = 0;
    let mut hbmTemp: HBITMAP = core::ptr::null_mut();
    let mut ilc: UINT = flags & 0xFE;
    static aBitBlend25: [WORD; 8] = [
        0xAA,
        0x00,
        0x55,
        0x00,
        0xAA,
        0x00,
        0x55,
        0x00,
    ];
    static aBitBlend50: [WORD; 8] = [
        0x55,
        0xAA,
        0x55,
        0xAA,
        0x55,
        0xAA,
        0x55,
        0xAA,
    ];

    'cleanup: {
        if cx < 0 || cy < 0 {
            return core::ptr::null_mut();
        }
        if !((flags & ILC_COLORDDB) == ILC_COLORDDB)
            && (cx == 0 || cy == 0)
        {
            return core::ptr::null_mut();
        }

        /* Create the IImageList interface for the image list */
        if ImageListImpl_CreateInstance(
            core::ptr::null(),
            core::ptr::addr_of!(IID_IImageList),
            core::ptr::addr_of_mut!(himl) as *mut *mut core::ffi::c_void,
        ) < 0
        {
            return core::ptr::null_mut();
        }

        cGrow = ((max(cGrow, 1) + 3)
            & !3) as WORD as INT;

        if cGrow > 256 {
            /* Windows doesn't limit the size here, but X11 doesn't let us allocate such huge bitmaps */
            cGrow = 256;
        }

        (*himl).cx = cx;
        (*himl).cy = cy;
        (*himl).flags = flags;
        (*himl).cMaxImage = cInitial + 1;
        (*himl).cInitial = cInitial;
        (*himl).cGrow = cGrow;
        (*himl).clrFg = CLR_DEFAULT;
        (*himl).clrBk = CLR_NONE;
        (*himl).color_table_set = FALSE;
        (*himl).usVersion = 0;

        /* initialize overlay mask indices */
        nCount = 0;
        while nCount < (MAX_OVERLAYIMAGE as i32) {
            (*himl).nOvlIdx[nCount as usize] = -1;
            nCount += 1;
        }

        /* Create Image & Mask DCs */
        (*himl).hdcImage = CreateCompatibleDC(core::ptr::null_mut());
        if (*himl).hdcImage.is_null() {
            break 'cleanup;
        }
        if ((*himl).flags & ILC_MASK) != 0 {
            (*himl).hdcMask = CreateCompatibleDC(core::ptr::null_mut());
            if (*himl).hdcMask.is_null() {
                break 'cleanup;
            }
        }

        /* Default to ILC_COLOR4 if none of the ILC_COLOR* flags are specified */
        if ilc == ILC_COLOR {
            ilc = ILC_COLOR4;
            (*himl).flags |= ILC_COLOR4;
        }

        if ilc >= ILC_COLOR4 && ilc <= ILC_COLOR32 {
            (*himl).uBitsPixel = ilc;
        } else {
            (*himl).uBitsPixel = GetDeviceCaps((*himl).hdcImage, (BITSPIXEL as i32)) as UINT;
        }

        if (*himl).cMaxImage > 0 {
            (*himl).hbmImage = ImageList_CreateImage(
                (*himl).hdcImage,
                himl,
                (*himl).cMaxImage as UINT,
            );
            SelectObject((*himl).hdcImage, (*himl).hbmImage as HGDIOBJ);
        } else {
            (*himl).hbmImage = core::ptr::null_mut();
        }

        if ((*himl).cMaxImage > 0)
            && (((*himl).flags & ILC_MASK) != 0)
        {
            let mut sz: SIZE = SIZE { cx: 0, cy: 0 };

            imagelist_get_bitmap_size(himl, (*himl).cMaxImage as UINT, core::ptr::addr_of_mut!(sz));
            (*himl).hbmMask = CreateBitmap(
                sz.cx,
                sz.cy,
                1,
                1,
                core::ptr::null(),
            );
            if (*himl).hbmMask == core::ptr::null_mut() {
                break 'cleanup;
            }
            SelectObject((*himl).hdcMask, (*himl).hbmMask as HGDIOBJ);
        } else {
            (*himl).hbmMask = core::ptr::null_mut();
        }

        if ilc == ILC_COLOR32 {
            (*himl).has_alpha = heap_alloc_zero((*himl).cMaxImage as SIZE_T) as *mut core::ffi::c_char;
        } else {
            (*himl).has_alpha = core::ptr::null_mut();
        }

        /* create blending brushes */
        hbmTemp = CreateBitmap(
            8,
            8,
            1,
            1,
            core::ptr::addr_of!(aBitBlend25) as *const core::ffi::c_void,
        );
        (*himl).hbrBlend25 = CreatePatternBrush(hbmTemp);
        DeleteObject(hbmTemp as HGDIOBJ);

        hbmTemp = CreateBitmap(
            8,
            8,
            1,
            1,
            core::ptr::addr_of!(aBitBlend50) as *const core::ffi::c_void,
        );
        (*himl).hbrBlend50 = CreatePatternBrush(hbmTemp);
        DeleteObject(hbmTemp as HGDIOBJ);

        return himl;
    }

    ImageList_Destroy(himl);
    return core::ptr::null_mut();
}

#[no_mangle]
pub unsafe extern "system" fn ImageList_Destroy(mut himl: HIMAGELIST) -> BOOL {
    if is_valid(himl) == 0 {
        return FALSE;
    }
    if ((*himl).flags & (ILC_SYSTEM as UINT)) != 0
        && (WinVerMajor!() as ::core::ffi::c_int) >= 6
    {
        return FALSE;
    }
    IImageList_Release(himl as *mut IImageList);
    return TRUE;
}

