#[cfg(feature = "invalid-parameter")]
#[no_mangle]
pub unsafe extern "C" fn _invalid_parameter(
    expr: *const u16,
    func: *const u16,
    file: *const u16,
    line: u32,
    arg: usize,
) {
    // At `_MSVCR_VER=0` both of the C's guarded blocks are compiled OUT: the `>= 140`
    // thread-local handler lookup, and the `RaiseException(STATUS_INVALID_CRUNTIME_PARAMETER)`
    // in the `>= 80` arm. What is left is "call the installed handler, else ERR() and
    // RETURN" — so the empty else is the whole behaviour here, not a dropped body. The
    // `ERR()` it replaces is a wine debug macro, already a no-op in this crate.
    if let Some(handler) = invalid_parameter_handler {
        handler(expr, func, file, line, arg);
    }
}


