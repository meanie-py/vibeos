#[no_mangle]
pub unsafe extern "C" fn msvcrt_set_errno(err: i32) {
    let errno_ptr = _errno();
    let doserrno = __doserrno();

    *doserrno = err as __msvcrt_ulong;

    // Scrutinee WIDENED rather than the arms narrowed. Every `ERROR_*` in the island is a
    // `u32` and there are no narrow siblings in this match, which is exactly the case the
    // field manual says to widen; a cast is illegal in a pattern, so crate-repair declined
    // all 126 of these rather than guess. Widening is also faithful: the C switches on an
    // `int` holding a Win32 DWORD, every label is positive and well under 2^31, and a value
    // outside the table falls to `_` either way.
    match err as u32 {
        ERROR_ACCESS_DENIED | ERROR_NETWORK_ACCESS_DENIED | ERROR_CANNOT_MAKE | ERROR_SEEK_ON_DEVICE | ERROR_LOCK_FAILED | ERROR_FAIL_I24 | ERROR_CURRENT_DIRECTORY | ERROR_DRIVE_LOCKED | ERROR_NOT_LOCKED | ERROR_INVALID_ACCESS | ERROR_SHARING_VIOLATION | ERROR_LOCK_VIOLATION => {
            *errno_ptr = (EACCES) as i32;
        }
        ERROR_FILE_NOT_FOUND | ERROR_NO_MORE_FILES | ERROR_BAD_PATHNAME | ERROR_BAD_NETPATH | ERROR_INVALID_DRIVE | ERROR_BAD_NET_NAME | ERROR_FILENAME_EXCED_RANGE | ERROR_PATH_NOT_FOUND => {
            *errno_ptr = (ENOENT) as i32;
        }
        ERROR_IO_DEVICE => {
            *errno_ptr = (EIO) as i32;
        }
        ERROR_BAD_FORMAT => {
            *errno_ptr = (ENOEXEC) as i32;
        }
        ERROR_INVALID_HANDLE => {
            *errno_ptr = (EBADF) as i32;
        }
        ERROR_OUTOFMEMORY | ERROR_INVALID_BLOCK | ERROR_NOT_ENOUGH_QUOTA | ERROR_ARENA_TRASHED => {
            *errno_ptr = (ENOMEM) as i32;
        }
        ERROR_BUSY => {
            *errno_ptr = (EBUSY) as i32;
        }
        ERROR_ALREADY_EXISTS | ERROR_FILE_EXISTS => {
            *errno_ptr = (EEXIST) as i32;
        }
        ERROR_BAD_DEVICE => {
            *errno_ptr = (ENODEV) as i32;
        }
        ERROR_TOO_MANY_OPEN_FILES => {
            *errno_ptr = (EMFILE) as i32;
        }
        ERROR_DISK_FULL => {
            *errno_ptr = (ENOSPC) as i32;
        }
        ERROR_BROKEN_PIPE => {
            *errno_ptr = (EPIPE) as i32;
        }
        ERROR_POSSIBLE_DEADLOCK => {
            *errno_ptr = (EDEADLK) as i32;
        }
        ERROR_DIR_NOT_EMPTY => {
            *errno_ptr = (ENOTEMPTY) as i32;
        }
        ERROR_BAD_ENVIRONMENT => {
            *errno_ptr = (E2BIG) as i32;
        }
        ERROR_WAIT_NO_CHILDREN | ERROR_CHILD_NOT_COMPLETE => {
            *errno_ptr = (ECHILD) as i32;
        }
        ERROR_NO_PROC_SLOTS | ERROR_MAX_THRDS_REACHED | ERROR_NESTING_NOT_ALLOWED => {
            *errno_ptr = (EAGAIN) as i32;
        }
        _ => {
            *errno_ptr = (EINVAL) as i32;
        }
    }
}

