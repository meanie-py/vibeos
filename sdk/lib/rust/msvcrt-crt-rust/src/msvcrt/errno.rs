/// `include/stdlib.h:259` — `typedef void (__cdecl *_invalid_parameter_handler)(
/// const wchar_t*, const wchar_t*, const wchar_t*, unsigned, uintptr_t);`
///
/// Not in the island (bindgen emits no `pub type` for a function-pointer typedef nothing
/// in the allowlisted surface mentions), so it is spelled from the header. `Option<..>` is
/// the null-able form: the C initialises the slot to NULL and tests it before calling, and
/// a bare `fn` pointer in Rust cannot be null.
pub type _invalid_parameter_handler =
    Option<unsafe extern "C" fn(*const u16, *const u16, *const u16, c_uint, usize)>;

/// The three kernel32 entry points errno.c reaches. `system`, never `C`: they are WINAPI
