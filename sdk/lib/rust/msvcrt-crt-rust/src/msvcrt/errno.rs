#[no_mangle]
pub unsafe extern "C" fn strerror(err: c_int) -> *mut c_char {
    let data: *mut thread_data_t = msvcrt_get_thread_data();

    if (*data).strerror_buffer.is_null() {
        (*data).strerror_buffer = (malloc(256)).cast();
        if (*data).strerror_buffer.is_null() {
            return core::ptr::null_mut();
        }
    }

    let err_index = if err < 0 || err > MSVCRT__sys_nerr as c_int {
        MSVCRT__sys_nerr as c_int
    } else {
        err
    };
    strcpy((*data).strerror_buffer, MSVCRT__sys_errlist[err_index as usize]);
    (*data).strerror_buffer
}

#[no_mangle]
pub unsafe extern "C" fn strerror_s(buffer: *mut i8, numberOfElements: usize, errnum: i32) -> i32 {
    let mut ptr: *mut i8;

    if buffer.is_null() || numberOfElements == 0 {
        *_errno() = (EINVAL) as i32;
        return (EINVAL) as i32;
    }

    let mut errnum = errnum;
    if errnum < 0 || errnum > MSVCRT__sys_nerr as i32 {
        errnum = MSVCRT__sys_nerr as i32;
    }

    ptr = MSVCRT__sys_errlist[errnum as usize];
    let mut buffer = buffer;
    let mut numberOfElements = numberOfElements;
    while *ptr != 0 && numberOfElements > 1 {
        *buffer = *ptr;
        buffer = buffer.offset(1);
        ptr = ptr.offset(1);
        numberOfElements -= 1;
    }

    *buffer = b'\0' as i8;
    0
}

#[no_mangle]
pub unsafe extern "C" fn _strerror(str: *const i8) -> *mut i8 {
    let data = msvcrt_get_thread_data();
    let mut err: i32;

    if (*data).strerror_buffer.is_null() {
        (*data).strerror_buffer = (malloc(256)).cast();
        if (*data).strerror_buffer.is_null() {
            return core::ptr::null_mut();
        }
    }

    err = (*data).thread_errno;
    if err < 0 || err > MSVCRT__sys_nerr as i32 {
        err = MSVCRT__sys_nerr as i32;
    }

    if !str.is_null() && *str != 0 {
        sprintf(
            (*data).strerror_buffer,
            b"%s: %s\n\0".as_ptr() as *const i8,
            str,
            MSVCRT__sys_errlist[err as usize]
        );
    } else {
        sprintf(
            (*data).strerror_buffer,
            b"%s\n\0".as_ptr() as *const i8,
            MSVCRT__sys_errlist[err as usize]
        );
    }

    (*data).strerror_buffer
}

// `perror` and `_wperror` are the only two entry points here that need an fd, and the
// `_write` they use lives in the stdio-gated file.rs (the scanf difftest owns the plain
// character-source names). Gating the IMPORT alone is not enough — the callers must carry
// the same cfg or they reference a function that does not exist. Every build that produces
// msvcrt.dll has stdio on, so nothing ships without them; the one consumer that loses them
// is msvcrt-scanf-difftest, which grades neither.
#[cfg(feature = "stdio")]
#[no_mangle]
pub unsafe extern "C" fn perror(str: *const i8) {
    let mut err = *_errno();
    if err < 0 || err > MSVCRT__sys_nerr as i32 {
        err = MSVCRT__sys_nerr as i32;
    }

    if !str.is_null() && *str != 0 {
        _write(2, str as *const core::ffi::c_void, strlen(str) as u32);
        _write(2, b": \0".as_ptr() as *const core::ffi::c_void, 2);
    }
    _write(2, MSVCRT__sys_errlist[err as usize] as *const core::ffi::c_void, strlen(MSVCRT__sys_errlist[err as usize]) as u32);
    _write(2, b"\n\0".as_ptr() as *const core::ffi::c_void, 1);
}

#[cfg(feature = "stdio")]
#[no_mangle]
pub unsafe extern "C" fn _wperror(str: *const u16) {
    let mut size: usize;
    let mut buffer: *mut i8 = core::ptr::null_mut();

    if !str.is_null() && *str != 0 {
        size = wcstombs(core::ptr::null_mut(), str, 0);
        if size == (-1 as isize) as usize {
            return;
        }
        size += 1;
        buffer = (malloc(size)).cast();
        if buffer.is_null() {
            return;
        }
        if wcstombs(buffer, str, size) == (-1 as isize) as usize {
            free((buffer).cast());
            return;
        }
    }
    perror(buffer);
    free((buffer).cast());
}

#[no_mangle]
pub unsafe extern "C" fn _wcserror_s(buffer: *mut u16, nc: usize, err: i32) -> i32 {
    if MSVCRT_CHECK_PMT!(buffer != core::ptr::null_mut()) == 0 {
        return (EINVAL) as i32;
    }
    if MSVCRT_CHECK_PMT!(nc > 0) == 0 {
        return (EINVAL) as i32;
    }

    let err = if err < 0 || err > MSVCRT__sys_nerr as i32 {
        MSVCRT__sys_nerr as i32
    } else {
        err
    };
    MultiByteToWideChar(CP_ACP, 0, MSVCRT__sys_errlist[err as usize], -1, buffer, nc as i32);
    0
}

#[no_mangle]
pub unsafe extern "C" fn _wcserror(err: i32) -> *mut u16 {
    let data = msvcrt_get_thread_data();

    if (*data).wcserror_buffer.is_null() {
        (*data).wcserror_buffer = malloc(256 * core::mem::size_of::<u16>()) as *mut u16;
        if (*data).wcserror_buffer.is_null() {
            return core::ptr::null_mut();
        }
    }
    _wcserror_s((*data).wcserror_buffer, 256, err);
    (*data).wcserror_buffer
}

#[no_mangle]
pub unsafe extern "C" fn __wcserror_s(buffer: *mut u16, nc: usize, str: *const u16) -> i32 {
    let mut err: i32;
    let mut len: usize;

    err = *_errno();
    if err < 0 || err > MSVCRT__sys_nerr as i32 {
        err = MSVCRT__sys_nerr as i32;
    }

    len = MultiByteToWideChar(
        CP_ACP,
        0,
        MSVCRT__sys_errlist[err as usize],
        -1,
        core::ptr::null_mut(),
        0
    ) as usize + 1;

    if !str.is_null() && *str != 0 {
        len += wcslen(str) + 2;
    }

    if len > nc {
        MSVCRT_INVALID_PMT!(b"buffer[nc] is too small\0".as_ptr() as *const i8, (ERANGE) as i32);
        return (ERANGE) as i32;
    }

    if !str.is_null() && *str != 0 {
        lstrcpyW(buffer, str);
        lstrcatW(buffer, [':' as u16, ' ' as u16, 0].as_ptr());
    } else {
        *buffer.offset(0 as isize) = 0;
    }

    len = wcslen(buffer);
    MultiByteToWideChar(
        CP_ACP,
        0,
        MSVCRT__sys_errlist[err as usize],
        -1,
        buffer.offset(len as isize),
        256 - len as i32
    );
    lstrcatW(buffer, ['\n' as u16, 0].as_ptr());

    0
}

#[no_mangle]
pub unsafe extern "C" fn __wcserror(str: *const u16) -> *mut u16 {
    let data = msvcrt_get_thread_data();
    let err: i32;

    if (*data).wcserror_buffer.is_null() {
        (*data).wcserror_buffer = malloc(256 * core::mem::size_of::<u16>()) as *mut u16;
        if (*data).wcserror_buffer.is_null() {
            return core::ptr::null_mut();
        }
    }

    err = __wcserror_s((*data).wcserror_buffer, 256, str);
    if err != 0 {
        FIXME!("bad wcserror call (%d)\n", err);
    }

    (*data).wcserror_buffer
}

