use core::ffi::c_void;
#[no_mangle]
pub unsafe extern "C" fn PrintService(lpServiceName: LPCTSTR, lpDisplayName: LPCTSTR, pStatus: LPSERVICE_STATUS_PROCESS, bExtended: BOOL) {
    static FMT_SERVICE_NAME: [u16; 18] = ['S' as u16, 'E' as u16, 'R' as u16, 'V' as u16, 'I' as u16, 'C' as u16, 'E' as u16, '_' as u16, 'N' as u16, 'A' as u16, 'M' as u16, 'E' as u16, ':' as u16, ' ' as u16, '%' as u16, 's' as u16, '\n' as u16, 0];
    static FMT_DISPLAY_NAME: [u16; 18] = ['D' as u16, 'I' as u16, 'S' as u16, 'P' as u16, 'L' as u16, 'A' as u16, 'Y' as u16, '_' as u16, 'N' as u16, 'A' as u16, 'M' as u16, 'E' as u16, ':' as u16, ' ' as u16, '%' as u16, 's' as u16, '\n' as u16, 0];
    static FMT_PID: [u16; 27] = ['\t' as u16, 'P' as u16, 'I' as u16, 'D' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ':' as u16, ' ' as u16, '%' as u16, 'l' as u16, 'u' as u16, '\n' as u16, 0u16]; // _T("\tPID                : %lu\n")
    static FMT_FLAGS: [u16; 27] = ['\t' as u16, 'F' as u16, 'L' as u16, 'A' as u16, 'G' as u16, 'S' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ' ' as u16, ':' as u16, ' ' as u16, '%' as u16, 'l' as u16, 'u' as u16, '\n' as u16, 0u16]; // _T("\tFLAGS              : %lu\n")
    static FMT_NEWLINE: [u16; 2] = ['\n' as u16, 0];

    _tprintf(FMT_SERVICE_NAME.as_ptr(), lpServiceName);

    if !lpDisplayName.is_null() {
        _tprintf(FMT_DISPLAY_NAME.as_ptr(), lpDisplayName);
    }

    // Re-use PrintServiceStatus(), as SERVICE_STATUS_PROCESS is in fact an extension of SERVICE_STATUS.
    PrintServiceStatus(pStatus as LPSERVICE_STATUS);

    if bExtended != 0 {
        _tprintf(FMT_PID.as_ptr(), (*pStatus).dwProcessId);
        _tprintf(FMT_FLAGS.as_ptr(), (*pStatus).dwServiceFlags);
    }

    _tprintf(FMT_NEWLINE.as_ptr());
}
