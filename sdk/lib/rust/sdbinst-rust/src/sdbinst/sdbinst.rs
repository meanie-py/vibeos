#[no_mangle]
pub unsafe extern "C" fn RegisterSdbEntry(
    sdbEntryName: PWCHAR,
    dbGuid: LPCWSTR,
    mut time: ULONGLONG,
    isInstall: BOOL,
    isExe: BOOL,
) -> HRESULT {
    let mut regName: [WCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut hKey: HKEY = core::ptr::null_mut();
    let mut status: LSTATUS;
    let mut hres: HRESULT;

    'end: {
        hres = StringCchPrintfW!(
            regName.as_mut_ptr(),
            MAX_PATH,
            RUSTCONV_WSTR_1B85193646AD.as_ptr(),
            if isExe != 0 {
                APPCOMPAT_CUSTOM_REG_PATH.as_ptr()
            } else {
                APPCOMPAT_LAYERS_REG_PATH.as_ptr()
            },
            sdbEntryName,
        );
        if hres < 0 {
            wprintf(RUSTCONV_WSTR_F3C1743F79F8.as_ptr(), hres);
            break 'end;
        }

        // Remove key
        if isInstall == 0 {
            status = RegDeleteKeyW(HKEY_LOCAL_MACHINE, regName.as_mut_ptr());
            if (status) as u32 == ERROR_FILE_NOT_FOUND {
                status = (ERROR_SUCCESS) as i32;
            }

            return HRESULT_FROM_WIN32!(status);
        }

        // Create main key
        status = RegCreateKeyExW(
            HKEY_LOCAL_MACHINE,
            regName.as_mut_ptr(),
            0,
            core::ptr::null_mut(),
            REG_OPTION_NON_VOLATILE,
            KEY_ALL_ACCESS,
            core::ptr::null_mut(),
            core::ptr::addr_of_mut!(hKey),
            core::ptr::null_mut(),
        );
        if (status) as u32 != ERROR_SUCCESS {
            wprintf(RUSTCONV_WSTR_AF4BA5E0FCDD.as_ptr(), status);
            hres = HRESULT_FROM_WIN32!(status);
            break 'end;
        }

        // Set installed time
        status = RegSetValueExW(
            hKey,
            dbGuid,
            0,
            REG_QWORD,
            core::ptr::addr_of_mut!(time) as PBYTE as *const BYTE,
            core::mem::size_of::<ULONGLONG>() as DWORD,
        );
        if (status) as u32 != ERROR_SUCCESS {
            wprintf(RUSTCONV_WSTR_E4F2671288E1.as_ptr(), status);
            hres = HRESULT_FROM_WIN32!(status);
            break 'end;
        }
    }

    // end:
    if !hKey.is_null() {
        RegCloseKey(hKey);
    }

    return hres;
}
