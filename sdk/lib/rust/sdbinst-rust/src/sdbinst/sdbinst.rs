#[no_mangle]
pub unsafe extern "C" fn GetSdbGuid(mut pdb: PDB, mut tagDb: TAGID, mut guid: *mut GUID) -> BOOL {
    let mut tagDbId: TAGID = 0;
    tagDbId = SdbFindFirstTag(pdb, tagDb, (TAG_DATABASE_ID) as TAG);
    if tagDbId == 0 {
        wprintf(RUSTCONV_WSTR_BD80045357BF.as_ptr());
        return (FALSE) as BOOL;
    }
    if SdbReadBinaryTag(
        pdb,
        tagDbId,
        guid as PBYTE,
        core::mem::size_of::<GUID>() as DWORD,
    ) == 0
    {
        wprintf(RUSTCONV_WSTR_E8B0CA58416E.as_ptr());
        return (FALSE) as BOOL;
    }
    return (TRUE) as BOOL;
}
#[no_mangle]
pub unsafe extern "C" fn ProcessLayers(
    mut pdb: PDB,
    mut tagDb: TAGID,
    mut guidDbStr: LPCWSTR,
    mut time: ULONGLONG,
    mut isInstall: BOOL,
) -> HRESULT {
    let mut res: HRESULT = (ERROR_SUCCESS) as i32;
    let mut tagLayerName: TAGID = 0;
    let mut prevTagLayer: TAGID = 0;

    let mut tagLayer: TAGID = SdbFindFirstTag(pdb, tagDb, (TAG_LAYER) as TAG);

    // Add all layers to registry (AppCompatFlags)
    while tagLayer != 0 && (tagLayer != prevTagLayer) {
        tagLayerName = SdbFindFirstTag(pdb, tagLayer, (TAG_NAME) as TAG);
        if tagLayerName == 0 {
            res = (ERROR_NOT_FOUND) as i32;
            break;
        }

        let mut name: LPWSTR = SdbGetStringTagPtr(pdb, tagLayerName);

        res = RegisterSdbEntry(name as PWCHAR, guidDbStr, time, isInstall, (FALSE) as BOOL);
        if res < 0 {
            wprintf(RUSTCONV_WSTR_500DDE430304.as_ptr());
            break;
        }

        prevTagLayer = tagLayer;
        tagLayer = SdbFindNextTag(pdb, tagDb, tagLayer);
    }

    return res;
}
#[no_mangle]
pub unsafe extern "C" fn ProcessExe(
    mut pdb: PDB,
    mut tagDb: TAGID,
    mut guidDbStr: LPCWSTR,
    mut time: ULONGLONG,
    mut isInstall: BOOL,
) -> HRESULT {
    let mut res: HRESULT = ERROR_SUCCESS as HRESULT;
    let mut tagExeName: TAGID = 0;
    let mut tagExePrev: TAGID = 0 as TAGID;

    let mut tagExe: TAGID = SdbFindFirstTag(pdb, tagDb, TAG_EXE as TAG);

    // Add all exe to registry (AppCompatFlags)
    while tagExe != 0 as TAGID && (tagExe != tagExePrev) {
        tagExeName = SdbFindFirstTag(pdb, tagExe, TAG_NAME as TAG);
        if tagExeName == 0 {
            wprintf(RUSTCONV_WSTR_A52EC4AE7F6E.as_ptr() as *const wchar_t);
            res = ERROR_NOT_FOUND as HRESULT;
            break;
        }

        let mut name: LPWSTR = SdbGetStringTagPtr(pdb, tagExeName);

        res = RegisterSdbEntry(name as PWCHAR, guidDbStr, time, isInstall, TRUE as BOOL);
        if res < 0 as HRESULT {
            wprintf(RUSTCONV_WSTR_C8A9E10BF690.as_ptr() as *const wchar_t, res);
            break;
        }

        tagExePrev = tagExe;
        tagExe = SdbFindNextTag(pdb, tagDb, tagExe);
    }

    return res;
}
#[no_mangle]
pub unsafe extern "C" fn CopySdbToAppPatch(
    sourceSdbPath: LPCWSTR,
    destSdbPath: LPCWSTR,
) -> HRESULT {
    let mut error: DWORD = ERROR_SUCCESS;
    let mut pTmpSysdir: PWCHAR = core::ptr::null_mut();
    let mut destLen: SIZE_T = wcslen(destSdbPath) as SIZE_T;
    let mut sysdirPath: PWCHAR = HeapAlloc(
        GetProcessHeap(),
        0,
        destLen * core::mem::size_of::<WCHAR>() as SIZE_T,
    ) as PWCHAR;

    'end: {
        if sysdirPath.is_null() {
            error = ERROR_NOT_ENOUGH_MEMORY;
            break 'end;
        }

        // Get parent folder fo sdb file
        CopyMemory!(
            sysdirPath as PVOID,
            destSdbPath as *const core::ffi::c_void,
            destLen * core::mem::size_of::<WCHAR>() as SIZE_T,
        );
        pTmpSysdir = StrRChrW(
            sysdirPath as LPCWSTR,
            sysdirPath.add((destLen) as _) as LPCWSTR,
            0x005Cu16,
        ) as PWCHAR;
        if pTmpSysdir.is_null() {
            wprintf(RUSTCONV_WSTR_C0D1EFC20945.as_ptr());
            break 'end;
        } else {
            *pTmpSysdir = UNICODE_NULL;
        }

        // Create directory if need
        if CreateDirectory(sysdirPath as LPCWSTR, core::ptr::null_mut()) == 0 {
            error = GetLastError();
            if error != ERROR_ALREADY_EXISTS {
                wprintf(RUSTCONV_WSTR_FE108BE37FEC.as_ptr(), sysdirPath, error);
                break 'end;
            }
            error = ERROR_SUCCESS;
        }

        // Copy file
        if CopyFile(sourceSdbPath, destSdbPath, TRUE as BOOL) == 0 {
            error = GetLastError();
            wprintf(RUSTCONV_WSTR_A000D2089361.as_ptr());
        }
    }

    // end:
    if !sysdirPath.is_null() {
        HeapFree(
            GetProcessHeap(),
            0,
            sysdirPath as PVOID,
        );
    }

    return HRESULT_FROM_WIN32!(error);
}
#[no_mangle]
pub unsafe extern "C" fn BuildPathToSdb(
    buffer: PWCHAR,
    bufLen: SIZE_T,
    guidDbStr: LPCWSTR,
) -> HRESULT {
    ZeroMemory!(buffer as *mut core::ffi::c_void, bufLen * (core::mem::size_of::<WCHAR>()) as SIZE_T);

    // Can't use here SdbGetAppPatchDir, because Windows XP haven't this function
    let count: UINT = GetSystemWindowsDirectory(buffer, bufLen as UINT);
    if *buffer.offset((count - 1) as isize) != 0x005Cu16 {
        *buffer.offset(count as isize) = 0x005Cu16;
    }

    let mut res: HRESULT = StringCchCatW(buffer, (bufLen) as _, RUSTCONV_WSTR_E907CDFE25C9.as_ptr());
    'end: {
        if res < 0 {
            break 'end;
        }

        res = StringCchCatW(buffer, (bufLen) as _, guidDbStr);
    }
    return res;
}
