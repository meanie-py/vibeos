unsafe extern "system" fn d3d9_device_UpdateSurface(
    iface: *mut IDirect3DDevice9Ex,
    src_surface: *mut IDirect3DSurface9,
    src_rect: *const RECT,
    dst_surface: *mut IDirect3DSurface9,
    dst_point: *const POINT,
) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let src: *mut d3d9_surface = unsafe_impl_from_IDirect3DSurface9(src_surface);
    let dst: *mut d3d9_surface = unsafe_impl_from_IDirect3DSurface9(dst_surface);
    let mut src_desc: wined3d_sub_resource_desc = core::mem::zeroed();
    let mut dst_desc: wined3d_sub_resource_desc = core::mem::zeroed();
    let mut src_box: wined3d_box = core::mem::zeroed();
    let mut hr: HRESULT;

    TRACE!(
        "iface %p, src_surface %p, src_rect %s, dst_surface %p, dst_point %p.\n",
        iface,
        src_surface,
        wine_dbgstr_rect(src_rect),
        dst_surface,
        dst_point
    );

    wined3d_mutex_lock();

    wined3d_texture_get_sub_resource_desc(
        (*src).wined3d_texture,
        (*src).sub_resource_idx,
        core::ptr::addr_of_mut!(src_desc),
    );
    wined3d_texture_get_sub_resource_desc(
        (*dst).wined3d_texture,
        (*dst).sub_resource_idx,
        core::ptr::addr_of_mut!(dst_desc),
    );
    if src_desc.format != dst_desc.format {
        wined3d_mutex_unlock();
        WARN!(
            "Surface formats (%#x/%#x) don't match.\n",
            d3dformat_from_wined3dformat(src_desc.format),
            d3dformat_from_wined3dformat(dst_desc.format)
        );
        return D3DERR_INVALIDCALL;
    }

    if src_desc.multisample_type != WINED3D_MULTISAMPLE_NONE || dst_desc.multisample_type != WINED3D_MULTISAMPLE_NONE
    {
        wined3d_mutex_unlock();
        WARN!("Cannot use UpdateSurface with multisampled surfaces.\n");
        return D3DERR_INVALIDCALL;
    }

    if !src_rect.is_null() {
        wined3d_box_set(
            core::ptr::addr_of_mut!(src_box),
            (*src_rect).left as u32,
            (*src_rect).top as u32,
            (*src_rect).right as u32,
            (*src_rect).bottom as u32,
            0,
            1,
        );
    } else {
        wined3d_box_set(
            core::ptr::addr_of_mut!(src_box),
            0,
            0,
            src_desc.width,
            src_desc.height,
            0,
            1,
        );
    }

    hr = wined3d_device_context_copy_sub_resource_region(
        (*device).immediate_context,
        wined3d_texture_get_resource((*dst).wined3d_texture),
        (*dst).sub_resource_idx,
        if !dst_point.is_null() {
            (*dst_point).x as u32
        } else {
            0
        },
        if !dst_point.is_null() {
            (*dst_point).y as u32
        } else {
            0
        },
        0,
        wined3d_texture_get_resource((*src).wined3d_texture),
        (*src).sub_resource_idx,
        core::ptr::addr_of_mut!(src_box),
        0,
    );
    if hr >= 0 && !(*dst).texture.is_null() {
        d3d9_texture_flag_auto_gen_mipmap((*dst).texture);
    }

    wined3d_mutex_unlock();

    if hr < 0 {
        return D3DERR_INVALIDCALL;
    }

    return hr;
}

unsafe extern "system" fn d3d9_device_UpdateTexture(iface: *mut IDirect3DDevice9Ex, src_texture: *mut IDirect3DBaseTexture9, dst_texture: *mut IDirect3DBaseTexture9) -> HRESULT {
    let mut device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut src_impl: *mut d3d9_texture;
    let mut dst_impl: *mut d3d9_texture;
    let mut hr: HRESULT;

    src_impl = unsafe_impl_from_IDirect3DBaseTexture9(src_texture);
    dst_impl = unsafe_impl_from_IDirect3DBaseTexture9(dst_texture);

    if !(*src_impl).draw_texture.is_null() || !(*dst_impl).draw_texture.is_null() {
        WARN!("Source or destination is managed; returning D3DERR_INVALIDCALL.\n");
        return D3DERR_INVALIDCALL;
    }

    wined3d_mutex_lock();
    hr = wined3d_device_update_texture(
        (*device).wined3d_device,
        (*src_impl).wined3d_texture,
        (*dst_impl).wined3d_texture,
    );
    if hr >= 0 {
        d3d9_texture_flag_auto_gen_mipmap(dst_impl);
    }
    wined3d_mutex_unlock();

    return hr;
}
unsafe extern "system" fn d3d9_device_GetRenderTargetData(iface: *mut IDirect3DDevice9Ex, render_target: *mut IDirect3DSurface9, dst_surface: *mut IDirect3DSurface9) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let rt_impl: *mut d3d9_surface = unsafe_impl_from_IDirect3DSurface9(render_target);
    let dst_impl: *mut d3d9_surface = unsafe_impl_from_IDirect3DSurface9(dst_surface);
    let mut wined3d_desc: wined3d_sub_resource_desc = core::mem::zeroed();
    let mut dst_rect: RECT = core::mem::zeroed();
    let mut src_rect: RECT = core::mem::zeroed();
    let mut hr: HRESULT = 0;

    if render_target.is_null() || dst_surface.is_null() {
        return D3DERR_INVALIDCALL;
    }

    wined3d_mutex_lock();
    wined3d_texture_get_sub_resource_desc((*dst_impl).wined3d_texture, (*dst_impl).sub_resource_idx, core::ptr::addr_of_mut!(wined3d_desc));
    SetRect(core::ptr::addr_of_mut!(dst_rect), 0, 0, wined3d_desc.width as i32, wined3d_desc.height as i32);

    wined3d_texture_get_sub_resource_desc((*rt_impl).wined3d_texture, (*rt_impl).sub_resource_idx, core::ptr::addr_of_mut!(wined3d_desc));
    SetRect(core::ptr::addr_of_mut!(src_rect), 0, 0, wined3d_desc.width as i32, wined3d_desc.height as i32);

    /* TODO: Check surface sizes, pools, etc. */
    if wined3d_desc.multisample_type as u64 != 0 {
        hr = D3DERR_INVALIDCALL;
    } else {
        hr = wined3d_device_context_blt(
            (*device).immediate_context,
            (*dst_impl).wined3d_texture,
            (*dst_impl).sub_resource_idx,
            core::ptr::addr_of_mut!(dst_rect),
            (*rt_impl).wined3d_texture,
            (*rt_impl).sub_resource_idx,
            core::ptr::addr_of_mut!(src_rect),
            0,
            core::ptr::null_mut(),
            WINED3D_TEXF_POINT,
        );
    }
    wined3d_mutex_unlock();

    return hr;
}

