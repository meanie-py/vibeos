#[no_mangle]
pub unsafe extern "C" fn wined3dmapflags_from_d3dmapflags(mut flags: u32, usage: u32) -> u32 {
    let handled: u32 = D3DLOCK_NOSYSLOCK
        | D3DLOCK_NOOVERWRITE
        | D3DLOCK_DISCARD
        | D3DLOCK_DONOTWAIT
        | D3DLOCK_NO_DIRTY_UPDATE;
    let mut wined3d_flags: u32;

    wined3d_flags = flags & handled;
    if (!usage & (D3DUSAGE_WRITEONLY as u32)) != 0
        && (flags & (D3DLOCK_NOOVERWRITE | D3DLOCK_DISCARD)) == 0
    {
        wined3d_flags |= WINED3D_MAP_READ;
    }
    if (flags & D3DLOCK_READONLY) == 0 {
        wined3d_flags |= WINED3D_MAP_WRITE;
    }
    if (wined3d_flags & (WINED3D_MAP_READ | WINED3D_MAP_WRITE)) == 0 {
        wined3d_flags |= WINED3D_MAP_WRITE;
    }
    flags &= !(handled | D3DLOCK_READONLY);

    if flags != 0 {
        FIXME!("Unhandled flags %#x.\n", flags);
    }

    return wined3d_flags;
}

unsafe extern "C" fn vertex_count_from_primitive_count(
    primitive_type: D3DPRIMITIVETYPE,
    primitive_count: UINT,
) -> UINT {
    match primitive_type {
        D3DPT_POINTLIST => {
            return primitive_count;
        }
        D3DPT_LINELIST => {
            return primitive_count.wrapping_mul(2);
        }
        D3DPT_LINESTRIP => {
            return primitive_count.wrapping_add(1);
        }
        D3DPT_TRIANGLELIST => {
            return primitive_count.wrapping_mul(3);
        }
        D3DPT_TRIANGLESTRIP | D3DPT_TRIANGLEFAN => {
            return primitive_count.wrapping_add(2);
        }
        _ => {
            FIXME!("Unhandled primitive type %#x.\n", primitive_type);
            return 0;
        }
    }
}

