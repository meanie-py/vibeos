unsafe extern "C" fn setup_fpu() {
    #[cfg(any(target_arch = "x86", target_arch = "x86_64"))]
    {
        let mut cw: WORD = 0;
        let cw_ptr: *mut WORD = core::ptr::addr_of_mut!(cw);
        core::arch::asm!("fnstcw word ptr [{0}]", in(reg) cw_ptr, options(nostack));
        cw = (cw & !(0xf3f as WORD)) | (0x3f as WORD);
        let cw_ptr2: *mut WORD = core::ptr::addr_of_mut!(cw);
        core::arch::asm!("fldcw word ptr [{0}]", in(reg) cw_ptr2, options(nostack));
    }

    #[cfg(not(any(target_arch = "x86", target_arch = "x86_64")))]
    {
        WINE_FIXME!("FPU setup not implemented for this platform.\n");
    }
}
#[no_mangle]
pub unsafe extern "C" fn device_init(
    device: *mut d3d9_device,
    parent: *mut d3d9,
    wined3d: *mut wined3d,
    adapter: UINT,
    device_type: D3DDEVTYPE,
    mut focus_window: HWND,
    flags: DWORD,
    parameters: *mut D3DPRESENT_PARAMETERS,
    mode: *mut D3DDISPLAYMODEEX,
) -> HRESULT {
    let mut swapchain_desc: *mut wined3d_swapchain_desc = core::ptr::null_mut();
    let mut wined3d_adapter: *mut wined3d_adapter = core::ptr::null_mut();
    let mut d3d_swapchain: *mut d3d9_swapchain = core::ptr::null_mut();
    let mut wined3d_caps: wined3d_caps = core::mem::zeroed();
    let mut output_idx: ::core::ffi::c_uint;
    let mut i: ::core::ffi::c_uint;
    let mut count: ::core::ffi::c_uint = 1;
    let mut caps: D3DCAPS9 = core::mem::zeroed();
    let mut hr: HRESULT;

    static feature_levels: [wined3d_feature_level; 7] = [
        WINED3D_FEATURE_LEVEL_9_3,
        WINED3D_FEATURE_LEVEL_9_2,
        WINED3D_FEATURE_LEVEL_9_1,
        WINED3D_FEATURE_LEVEL_8,
        WINED3D_FEATURE_LEVEL_7,
        WINED3D_FEATURE_LEVEL_6,
        WINED3D_FEATURE_LEVEL_5,
    ];

    output_idx = adapter as ::core::ffi::c_uint;
    if output_idx >= (*parent).wined3d_output_count {
        return D3DERR_INVALIDCALL;
    }

    if !mode.is_null() {
        FIXME!("Ignoring display mode.\n");
    }

    (*device).IDirect3DDevice9Ex_iface.lpVtbl =
        &raw const d3d9_device_vtbl as *const IDirect3DDevice9ExVtbl;
    (*device).IDirect3DDevice9On12_iface.lpVtbl =
        &raw const d3d9on12_vtbl as *const IDirect3DDevice9On12Vtbl;
    (*device).device_parent.ops =
        &raw const d3d9_wined3d_device_parent_ops as *const wined3d_device_parent_ops;
    (*device).adapter_ordinal = adapter as ::core::ffi::c_uint;
    (*device).refcount = 1 as LONG;

    if (flags as ::core::ffi::c_ulong & (D3DCREATE_FPU_PRESERVE as u32)) == 0 {
        setup_fpu();
    }

    wined3d_mutex_lock();
    wined3d_adapter =
        wined3d_output_get_adapter(*(*parent).wined3d_outputs.offset(output_idx as isize));
    hr = wined3d_device_create(
        wined3d,
        wined3d_adapter,
        wined3d_device_type_from_d3d(device_type),
        focus_window,
        flags as ::core::ffi::c_uint,
        4,
        &raw const feature_levels as *const wined3d_feature_level,
        ARRAY_SIZE!(feature_levels) as ::core::ffi::c_uint,
        &raw mut (*device).device_parent,
        &raw mut (*device).wined3d_device,
    );
    if hr < 0 {
        WARN!("Failed to create wined3d device, hr %#lx.\n", hr);
        wined3d_mutex_unlock();
        return hr;
    }

    (*device).immediate_context = wined3d_device_get_immediate_context((*device).wined3d_device);
    wined3d_get_device_caps(
        wined3d_adapter,
        wined3d_device_type_from_d3d(device_type),
        &raw mut wined3d_caps,
    );
    d3d9_caps_from_wined3dcaps(
        parent,
        adapter as ::core::ffi::c_uint,
        &raw mut caps,
        &raw mut wined3d_caps,
    );
    (*device).max_user_clip_planes = caps.MaxUserClipPlanes as ::core::ffi::c_uint;
    (*device).vs_uniform_count = caps.MaxVertexShaderConst as ::core::ffi::c_uint;
    if (flags as ::core::ffi::c_ulong & (D3DCREATE_ADAPTERGROUP_DEVICE as u32)) != 0 {
        count = caps.NumberOfAdaptersInGroup as ::core::ffi::c_uint;
    }

    hr = wined3d_stateblock_create(
        (*device).wined3d_device,
        core::ptr::null_mut(),
        WINED3D_SBT_PRIMARY,
        &raw mut (*device).state,
    );
    if hr < 0 {
        ERR!("Failed to create the primary stateblock, hr %#lx.\n", hr);
        wined3d_device_decref((*device).wined3d_device);
        wined3d_mutex_unlock();
        return hr;
    }
    (*device).stateblock_state = wined3d_stateblock_get_state((*device).state);
    (*device).update_state = (*device).state;

    wined3d_streaming_buffer_init(
        &raw mut (*device).vertex_buffer,
        WINED3D_BIND_VERTEX_BUFFER as ::core::ffi::c_uint,
    );
    wined3d_streaming_buffer_init(
        &raw mut (*device).index_buffer,
        WINED3D_BIND_INDEX_BUFFER as ::core::ffi::c_uint,
    );

    if (flags as ::core::ffi::c_ulong & (D3DCREATE_MULTITHREADED as u32)) != 0 {
        wined3d_device_set_multithreaded((*device).wined3d_device);
    }

    if (*parameters).Windowed == 0 {
        if focus_window.is_null() {
            focus_window = (*parameters).hDeviceWindow;
        }
        hr = wined3d_device_acquire_focus_window((*device).wined3d_device, focus_window);
        if hr < 0 {
            ERR!("Failed to acquire focus window, hr %#lx.\n", hr);
            wined3d_device_decref((*device).wined3d_device);
            wined3d_mutex_unlock();
            return hr;
        }
    }

    swapchain_desc = malloc(
        (::core::mem::size_of::<wined3d_swapchain_desc>() as size_t)
            .wrapping_mul(count as size_t),
    ) as *mut wined3d_swapchain_desc;
    if swapchain_desc.is_null() {
        ERR!("Failed to allocate wined3d parameters.\n");
        wined3d_device_release_focus_window((*device).wined3d_device);
        wined3d_device_decref((*device).wined3d_device);
        wined3d_mutex_unlock();
        return E_OUTOFMEMORY;
    }

    i = 0 as ::core::ffi::c_uint;
    while i < count {
        if wined3d_swapchain_desc_from_d3d9(
            swapchain_desc.offset(i as isize) as *mut wined3d_swapchain_desc,
            *(*parent).wined3d_outputs.offset(output_idx.wrapping_add(i) as isize),
            parameters.offset(i as isize) as *mut D3DPRESENT_PARAMETERS,
            (*parent).extended,
        ) == 0
        {
            wined3d_device_release_focus_window((*device).wined3d_device);
            wined3d_device_decref((*device).wined3d_device);
            free((swapchain_desc).cast());
            wined3d_mutex_unlock();
            return D3DERR_INVALIDCALL;
        }
        (*swapchain_desc.offset(i as isize)).flags |= WINED3D_SWAPCHAIN_IMPLICIT;
        if (flags as ::core::ffi::c_ulong & (D3DCREATE_NOWINDOWCHANGES as u32)) != 0 {
            (*swapchain_desc.offset(i as isize)).flags |= WINED3D_SWAPCHAIN_NO_WINDOW_CHANGES;
        }
        i = i.wrapping_add(1);
    }

    hr = d3d9_swapchain_create(
        device,
        swapchain_desc,
        wined3dswapinterval_from_d3d((*parameters).PresentationInterval as DWORD) as ::core::ffi::c_uint,
        &raw mut d3d_swapchain,
    );
    if hr < 0 {
        WARN!("Failed to create swapchain, hr %#lx.\n", hr);
        wined3d_device_release_focus_window((*device).wined3d_device);
        free((swapchain_desc).cast());
        wined3d_device_decref((*device).wined3d_device);
        wined3d_mutex_unlock();
        return hr;
    }

    wined3d_swapchain_incref((*d3d_swapchain).wined3d_swapchain);
    IDirect3DSwapChain9Ex_Release(&raw mut (*d3d_swapchain).IDirect3DSwapChain9Ex_iface);

    wined3d_stateblock_set_render_state(
        (*device).state,
        WINED3D_RS_ZENABLE as ::core::ffi::c_uint,
        ((*swapchain_desc).enable_auto_depth_stencil != 0) as ::core::ffi::c_int
            as ::core::ffi::c_uint,
    );
    device_reset_viewport_state(device);

    hr = d3d9_device_get_swapchains(device);
    if hr < 0 {
        wined3d_swapchain_decref((*d3d_swapchain).wined3d_swapchain);
        wined3d_device_release_focus_window((*device).wined3d_device);
        wined3d_device_decref((*device).wined3d_device);
        free((swapchain_desc).cast());
        wined3d_mutex_unlock();
        return E_OUTOFMEMORY;
    }

    i = 0 as ::core::ffi::c_uint;
    while i < count {
        present_parameters_from_wined3d_swapchain_desc(
            parameters.offset(i as isize) as *mut D3DPRESENT_PARAMETERS,
            swapchain_desc.offset(i as isize) as *mut wined3d_swapchain_desc,
            (*parameters.offset(i as isize)).PresentationInterval as DWORD,
        );
        i = i.wrapping_add(1);
    }

    wined3d_mutex_unlock();

    free((swapchain_desc).cast());

    /* We could also simply ignore the initial rendertarget since it's known
     * not to be a texture (we currently use these only for automatic mipmap
     * generation). */
    wined3d_mutex_lock();
    (*device).render_targets[0 as usize] = wined3d_rendertarget_view_get_sub_resource_parent(
        wined3d_device_context_get_rendertarget_view((*device).immediate_context, 0),
    ) as *mut d3d9_surface;
    wined3d_mutex_unlock();

    IDirect3D9Ex_AddRef(&raw mut (*parent).IDirect3D9Ex_iface);
    (*device).d3d_parent = parent;

    return D3D_OK;
}

