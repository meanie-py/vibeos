#[no_mangle]
pub unsafe extern "system" fn d3d9_device_ResetEx(
    iface: *mut IDirect3DDevice9Ex,
    present_parameters: *mut D3DPRESENT_PARAMETERS,
    mode: *mut D3DDISPLAYMODEEX,
) -> HRESULT {
    let mut device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);

    if ((*present_parameters).Windowed == 0) as i32 == (mode.is_null()) as i32 {
        WARN!("Mode can be passed if and only if Windowed is FALSE.\n");
        return D3DERR_INVALIDCALL;
    }

    if !mode.is_null()
        && ((*mode).Width != (*present_parameters).BackBufferWidth
            || (*mode).Height != (*present_parameters).BackBufferHeight)
    {
        WARN!(
            "Mode and back buffer mismatch (mode %ux%u, backbuffer %ux%u).\n",
            (*mode).Width,
            (*mode).Height,
            (*present_parameters).BackBufferWidth,
            (*present_parameters).BackBufferHeight
        );
        return D3DERR_INVALIDCALL;
    }

    return d3d9_device_reset(device, present_parameters, mode);
}

unsafe extern "system" fn d3d9_device_GetDisplayModeEx(
    iface: *mut IDirect3DDevice9Ex,
    swapchain_idx: UINT,
    mode: *mut D3DDISPLAYMODEEX,
    rotation: *mut D3DDISPLAYROTATION,
) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut wined3d_mode: wined3d_display_mode = core::mem::zeroed();
    let mut hr: HRESULT = 0;

    if (*mode).Size as usize != core::mem::size_of::<D3DDISPLAYMODEEX>() as usize {
        return D3DERR_INVALIDCALL;
    }

    wined3d_mutex_lock();
    hr = wined3d_device_get_display_mode(
        (*device).wined3d_device,
        swapchain_idx,
        core::ptr::addr_of_mut!(wined3d_mode),
        rotation as *mut wined3d_display_rotation,
    );
    wined3d_mutex_unlock();

    if hr >= 0 {
        (*mode).Width = wined3d_mode.width;
        (*mode).Height = wined3d_mode.height;
        (*mode).RefreshRate = wined3d_mode.refresh_rate;
        (*mode).Format = d3dformat_from_wined3dformat(wined3d_mode.format_id);
        (*mode).ScanLineOrdering = d3dscanlineordering_from_wined3d(wined3d_mode.scanline_ordering);
    }

    return hr;
}

