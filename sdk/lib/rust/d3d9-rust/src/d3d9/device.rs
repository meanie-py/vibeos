unsafe extern "C" fn d3d9_generate_auto_mipmaps(device: *mut d3d9_device) {
    let state: *const wined3d_stateblock_state = (*device).stateblock_state;
    let mut texture: *mut wined3d_texture = core::ptr::null_mut();
    let mut i: u32;
    let mut map: u32;
    map = (*device).auto_mipmaps;
    while map != 0 {
        i = wined3d_bit_scan(core::ptr::addr_of_mut!(map)) as u32;
        texture = (*state).textures[i as usize] as *mut wined3d_texture;
        if !texture.is_null() {
            d3d9_texture_gen_auto_mipmap(wined3d_texture_get_parent(texture) as *mut d3d9_texture);
        }
    }
}

unsafe extern "C" fn d3d9_device_upload_sysmem_vertex_buffers(
    device: *mut d3d9_device,
    base_vertex: ::core::ffi::c_int,
    mut start_vertex: ::core::ffi::c_uint,
    vertex_count: ::core::ffi::c_uint,
) {
    let state: *const wined3d_stateblock_state = (*device).stateblock_state;
    let mut wined3d_decl: *mut wined3d_vertex_declaration = core::ptr::null_mut();
    let mut box_0: wined3d_box = wined3d_box {
        left: 0,
        top: 0,
        right: 0,
        bottom: 1,
        front: 0,
        back: 1,
    };
    let mut stream: *const wined3d_stream_state = core::ptr::null();
    let mut d3d9_buffer: *mut d3d9_vertexbuffer = core::ptr::null_mut();
    let mut dst_resource: *mut wined3d_resource = core::ptr::null_mut();
    let mut decl: *mut d3d9_vertex_declaration = core::ptr::null_mut();
    let mut dst_buffer: *mut wined3d_buffer = core::ptr::null_mut();
    let mut desc: wined3d_resource_desc = core::mem::zeroed();
    let mut stride: ::core::ffi::c_uint = 0;
    let mut map: ::core::ffi::c_uint = 0;
    let mut hr: HRESULT = 0;

    if (*device).sysmem_vb() == 0 {
        return;
    }
    wined3d_decl = (*state).vertex_declaration as *mut wined3d_vertex_declaration;
    if wined3d_decl.is_null() {
        return;
    }

    if base_vertex >= 0
        || start_vertex >= base_vertex.wrapping_neg() as ::core::ffi::c_uint
    {
        start_vertex = start_vertex.wrapping_add(base_vertex as ::core::ffi::c_uint);
    } else {
        FIXME!("System memory vertex data offset is negative.\n");
    }

    decl = wined3d_vertex_declaration_get_parent(wined3d_decl) as *mut d3d9_vertex_declaration;
    map = ((*decl).stream_map & (*device).sysmem_vb()) as ::core::ffi::c_uint;
    while map != 0 {
        stream = core::ptr::addr_of!(
            (*state).streams[wined3d_bit_scan(core::ptr::addr_of_mut!(map)) as usize]
        );
        dst_buffer = (*stream).buffer as *mut wined3d_buffer;
        stride = (*stream).stride as ::core::ffi::c_uint;

        d3d9_buffer = wined3d_buffer_get_parent(dst_buffer) as *mut d3d9_vertexbuffer;
        dst_resource = wined3d_buffer_get_resource(dst_buffer);
        wined3d_resource_get_desc(dst_resource, core::ptr::addr_of_mut!(desc));
        box_0.left = ((*stream).offset as ::core::ffi::c_uint)
            .wrapping_add(start_vertex.wrapping_mul(stride)) as UINT;
        box_0.right = min!(
            (box_0.left as ::core::ffi::c_uint).wrapping_add(vertex_count.wrapping_mul(stride)),
            desc.size,
        ) as UINT;

        hr = wined3d_device_context_copy_sub_resource_region(
            (*device).immediate_context,
            dst_resource,
            0,
            box_0.left,
            0,
            0,
            wined3d_buffer_get_resource((*d3d9_buffer).wined3d_buffer),
            0,
            core::ptr::addr_of_mut!(box_0),
            0,
        );
        if hr < 0 {
            ERR!("Failed to update buffer.\n");
        }
    }
}

unsafe extern "C" fn d3d9_device_upload_sysmem_index_buffer(
    device: *mut d3d9_device,
    start_idx: *mut ::core::ffi::c_uint,
    idx_count: ::core::ffi::c_uint,
) -> HRESULT {
    let state: *const wined3d_stateblock_state = (*device).stateblock_state;
    let mut src_offset: ::core::ffi::c_uint = 0;
    let mut idx_size: ::core::ffi::c_uint = 0;
    let mut buffer_size: ::core::ffi::c_uint = 0;
    let mut pos: ::core::ffi::c_uint = 0;
    let mut resource_desc: wined3d_resource_desc = core::mem::zeroed();
    let mut index_buffer: *mut wined3d_resource = core::ptr::null_mut();
    let mut map_desc: wined3d_map_desc = core::mem::zeroed();
    let mut box_: wined3d_box = core::mem::zeroed();
    let mut hr: HRESULT = 0;

    if (((*device).sysmem_ib()) == 0) {
        return S_OK;
    }

    index_buffer = wined3d_buffer_get_resource((*state).index_buffer);
    wined3d_resource_get_desc(index_buffer, core::ptr::addr_of_mut!(resource_desc));
    idx_size = (if (*state).index_format == WINED3DFMT_R16_UINT {
        2
    } else {
        4
    });

    src_offset = (*start_idx).wrapping_mul(idx_size);
    buffer_size = min!(
        idx_count.wrapping_mul(idx_size),
        resource_desc.size.wrapping_sub(src_offset),
    );

    wined3d_box_set(
        core::ptr::addr_of_mut!(box_),
        src_offset,
        0,
        buffer_size,
        1,
        0,
        1,
    );
    hr = wined3d_resource_map(
        index_buffer,
        0,
        core::ptr::addr_of_mut!(map_desc),
        core::ptr::addr_of_mut!(box_),
        WINED3D_MAP_READ,
    );
    if hr < 0 {
        ERR!("Failed to map index buffer, hr %#lx.\n", hr);
        return hr;
    }
    wined3d_streaming_buffer_upload(
        (*device).wined3d_device,
        core::ptr::addr_of_mut!((*device).index_buffer),
        map_desc.data,
        buffer_size,
        idx_size,
        core::ptr::addr_of_mut!(pos),
    );
    wined3d_resource_unmap(index_buffer, 0);

    wined3d_device_context_set_index_buffer(
        (*device).immediate_context,
        (*device).index_buffer.buffer,
        (*state).index_format,
        pos,
    );
    *start_idx = 0;
    return S_OK;
}

unsafe extern "C" fn d3d9_device_flush_mapped_vertex_buffers(device: *mut d3d9_device) {
    let mut i: u32 = 0;
    while i < WINED3D_MAX_STREAMS {
        let buffer: *mut wined3d_buffer = (*(*device).stateblock_state).streams[i as usize].buffer;
        if !buffer.is_null() {
            wined3d_device_context_flush_mapped_buffer((*device).immediate_context, buffer);
        }
        i += 1;
    }
}

unsafe extern "C" fn d3d9_device_upload_managed_textures(device: *mut d3d9_device) {
    let state: *const wined3d_stateblock_state = (*device).stateblock_state;
    let mut i: ::core::ffi::c_uint;
    i = 0;
    while i < WINED3D_MAX_COMBINED_SAMPLERS {
        let wined3d_texture: *mut wined3d_texture = (*state).textures[i as usize];
        let mut d3d9_texture: *mut d3d9_texture = ::core::ptr::null_mut::<d3d9_texture>();

        if !wined3d_texture.is_null() {
            d3d9_texture = wined3d_texture_get_parent(wined3d_texture) as *mut d3d9_texture;
            if !(*d3d9_texture).draw_texture.is_null() {
                wined3d_device_update_texture(
                    (*device).wined3d_device,
                    (*d3d9_texture).wined3d_texture,
                    (*d3d9_texture).draw_texture,
                );
            }
        }
        i = i.wrapping_add(1);
    }
}

unsafe extern "system" fn d3d9_device_DrawPrimitive(iface: *mut IDirect3DDevice9Ex, primitive_type: D3DPRIMITIVETYPE, start_vertex: UINT, primitive_count: UINT) -> HRESULT {
    let mut device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut vertex_count: ::core::ffi::c_uint = 0;

    TRACE!("iface %p, primitive_type %#x, start_vertex %u, primitive_count %u.\n", iface, primitive_type as ::core::ffi::c_uint, start_vertex, primitive_count);

    wined3d_mutex_lock();
    if (*(*device).stateblock_state).vertex_declaration.is_null()
    {
        wined3d_mutex_unlock();
        WARN!("Called without a valid vertex declaration set.\n");
        return D3DERR_INVALIDCALL;
    }
    wined3d_device_apply_stateblock((*device).wined3d_device, (*device).state);
    vertex_count = vertex_count_from_primitive_count(primitive_type, primitive_count) as ::core::ffi::c_uint;
    d3d9_device_upload_managed_textures(device);
    d3d9_device_upload_sysmem_vertex_buffers(device, 0, start_vertex as ::core::ffi::c_uint, vertex_count);
    d3d9_device_flush_mapped_vertex_buffers(device);
    d3d9_generate_auto_mipmaps(device);
    wined3d_device_context_set_primitive_type((*device).immediate_context,
            wined3d_primitive_type_from_d3d(primitive_type), 0 as ::core::ffi::c_uint);

    /* Instancing is ignored for non-indexed draws. */
    wined3d_device_context_draw((*device).immediate_context, start_vertex as ::core::ffi::c_uint, vertex_count, 0 as ::core::ffi::c_uint, 0 as ::core::ffi::c_uint);

    d3d9_rts_flag_auto_gen_mipmap(device);
    wined3d_mutex_unlock();

    return D3D_OK;
}

