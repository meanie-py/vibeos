unsafe extern "system" fn d3d9_device_SetCursorProperties(
    iface: *mut IDirect3DDevice9Ex,
    hotspot_x: UINT,
    hotspot_y: UINT,
    bitmap: *mut IDirect3DSurface9,
) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let bitmap_impl: *mut d3d9_surface = unsafe_impl_from_IDirect3DSurface9(bitmap);
    let mut surface_desc: D3DSURFACE_DESC = core::mem::zeroed::<D3DSURFACE_DESC>();
    let mut mode: D3DDISPLAYMODE = core::mem::zeroed::<D3DDISPLAYMODE>();
    let mut hr: HRESULT;

    if bitmap.is_null() {
        WARN!("No cursor bitmap, returning D3DERR_INVALIDCALL.\n");
        return D3DERR_INVALIDCALL;
    }

    hr = IDirect3DSurface9_GetDesc(bitmap, core::ptr::addr_of_mut!(surface_desc));
    if hr < 0 {
        WARN!("Failed to get surface description, hr %#lx.\n", hr);
        return hr;
    }

    hr = IDirect3D9_GetAdapterDisplayMode(
        (core::ptr::addr_of_mut!((*(*device).d3d_parent).IDirect3D9Ex_iface)).cast(),
        (*device).adapter_ordinal as UINT,
        core::ptr::addr_of_mut!(mode),
    );
    if hr < 0 {
        WARN!("Failed to get device display mode, hr %#lx.\n", hr);
        return hr;
    }

    if surface_desc.Width > mode.Width || surface_desc.Height > mode.Height {
        WARN!(
            "Surface dimension %ux%u exceeds display mode %ux%u.\n",
            surface_desc.Width,
            surface_desc.Height,
            mode.Width,
            mode.Height
        );
        return D3DERR_INVALIDCALL;
    }

    wined3d_mutex_lock();
    hr = wined3d_device_set_cursor_properties(
        (*device).wined3d_device,
        hotspot_x,
        hotspot_y,
        (*bitmap_impl).wined3d_texture,
        (*bitmap_impl).sub_resource_idx,
    );
    wined3d_mutex_unlock();

    return hr;
}
