#[no_mangle]
pub unsafe extern "system" fn d3d9_device_PresentEx(
    iface: *mut IDirect3DDevice9Ex,
    src_rect: *const RECT,
    dst_rect: *const RECT,
    dst_window_override: HWND,
    dirty_region: *const RGNDATA,
    flags: DWORD,
) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut swapchain: *mut d3d9_swapchain = core::ptr::null_mut();
    let mut i: core::ffi::c_uint;
    let mut hr: HRESULT;

    TRACE!(
        "iface %p, src_rect %s, dst_rect %s, dst_window_override %p, dirty_region %p, flags %#lx.\n",
        iface,
        wine_dbgstr_rect(src_rect),
        wine_dbgstr_rect(dst_rect),
        dst_window_override,
        dirty_region,
        flags
    );

    if ((*device).device_state) as u32 != D3D9_DEVICE_STATE_OK {
        return S_PRESENT_OCCLUDED;
    }

    if !dirty_region.is_null() {
        FIXME!("Ignoring dirty_region %p.\n", dirty_region);
    }

    wined3d_mutex_lock();
    i = 0;
    while i < (*device).implicit_swapchain_count {
        swapchain = wined3d_swapchain_get_parent(*(*device).implicit_swapchains.offset(i as isize))
            as *mut d3d9_swapchain;
        hr = wined3d_swapchain_present(
            (*swapchain).wined3d_swapchain,
            src_rect,
            dst_rect,
            dst_window_override,
            (*swapchain).swap_interval,
            flags,
        );
        if hr < 0 {
            wined3d_mutex_unlock();
            return hr;
        }
        i = i.wrapping_add(1);
    }
    wined3d_mutex_unlock();

    return D3D_OK;
}
