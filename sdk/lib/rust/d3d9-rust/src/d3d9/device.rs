unsafe extern "C" fn reset_enum_callback(mut resource: *mut wined3d_resource) -> HRESULT {
    let mut vertex_buffer: *mut d3d9_vertexbuffer = core::ptr::null_mut();
    let mut index_buffer: *mut d3d9_indexbuffer = core::ptr::null_mut();
    let mut desc: wined3d_resource_desc = core::mem::zeroed();
    let mut texture: *mut IDirect3DBaseTexture9 = core::ptr::null_mut();
    let mut surface: *mut d3d9_surface = core::ptr::null_mut();
    let mut parent: *mut IUnknown = core::ptr::null_mut();

    wined3d_resource_get_desc(resource, core::ptr::addr_of_mut!(desc));
    if (desc.access & WINED3D_RESOURCE_ACCESS_CPU) != 0 || (desc.usage & WINED3DUSAGE_MANAGED) != 0 {
        return D3D_OK;
    }

    if desc.resource_type != WINED3D_RTYPE_TEXTURE_2D {
        if (desc.bind_flags & WINED3D_BIND_VERTEX_BUFFER) != 0 {
            vertex_buffer = wined3d_resource_get_parent(resource) as *mut d3d9_vertexbuffer;
            if !vertex_buffer.is_null() && !(*vertex_buffer).draw_buffer.is_null() {
                return D3D_OK;
            }
        }
        if (desc.bind_flags & WINED3D_BIND_INDEX_BUFFER) != 0 {
            index_buffer = wined3d_resource_get_parent(resource) as *mut d3d9_indexbuffer;
            if !index_buffer.is_null() && (*index_buffer).sysmem != false {
                return D3D_OK;
            }
        }

        WARN!("Resource %p in pool D3DPOOL_DEFAULT blocks the Reset call.\n", resource);
        return D3DERR_INVALIDCALL;
    }

    parent = wined3d_resource_get_parent(resource) as *mut IUnknown;
    if !parent.is_null()
        && (IUnknown_QueryInterface(
            parent,
            core::ptr::addr_of!(IID_IDirect3DBaseTexture9),
            core::ptr::addr_of_mut!(texture) as *mut *mut ::core::ffi::c_void,
        ) >= 0)
    {
        IDirect3DBaseTexture9_Release(texture);
        WARN!(
            "Texture %p (resource %p) in pool D3DPOOL_DEFAULT blocks the Reset call.\n",
            texture,
            resource
        );
        return D3DERR_INVALIDCALL;
    }

    surface = wined3d_texture_get_sub_resource_parent(wined3d_texture_from_resource(resource), 0) as *mut d3d9_surface;
    if surface.is_null() || (*surface).resource.refcount == 0 {
        return D3D_OK;
    }

    WARN!("Surface %p in pool D3DPOOL_DEFAULT blocks the Reset call.\n", surface);
    return D3DERR_INVALIDCALL;
}

unsafe extern "C" fn d3d9_device_get_swapchains(device: *mut d3d9_device) -> HRESULT {
    let mut i: UINT = 0;
    let new_swapchain_count: UINT = wined3d_device_get_swapchain_count((*device).wined3d_device);

    (*device).implicit_swapchains = malloc(
        (new_swapchain_count as usize).wrapping_mul(core::mem::size_of::<*mut wined3d_swapchain>()),
    ) as *mut *mut wined3d_swapchain;
    if (*device).implicit_swapchains.is_null() {
        return E_OUTOFMEMORY;
    }

    i = 0;
    while i < new_swapchain_count {
        *(*device).implicit_swapchains.offset(i as isize) =
            wined3d_device_get_swapchain((*device).wined3d_device, i);
        i = i.wrapping_add(1);
    }
    (*device).implicit_swapchain_count = new_swapchain_count;

    return D3D_OK;
}

unsafe extern "C" fn d3d9_device_reset(
    mut device: *mut d3d9_device,
    mut present_parameters: *mut D3DPRESENT_PARAMETERS,
    mut mode: *mut D3DDISPLAYMODEEX,
) -> HRESULT {
    let mut swapchain_desc: wined3d_swapchain_desc = core::mem::zeroed();
    let mut old_swapchain_desc: wined3d_swapchain_desc = core::mem::zeroed();
    let mut old_backbuffers: *mut *mut d3d9_surface = core::ptr::null_mut::<*mut d3d9_surface>();
    let mut extended: BOOL = (*(*device).d3d_parent).extended;
    let mut wined3d_mode: wined3d_display_mode = core::mem::zeroed();
    let mut rtv: *mut wined3d_rendertarget_view =
        core::ptr::null_mut::<wined3d_rendertarget_view>();
    let mut d3d9_swapchain: *mut d3d9_swapchain = core::ptr::null_mut::<d3d9_swapchain>();
    let mut output_idx: ::core::ffi::c_uint = 0;
    let mut i: ::core::ffi::c_uint = 0;
    let mut hr: HRESULT = 0;

    if extended == 0 && ((*device).device_state) as u32 == D3D9_DEVICE_STATE_LOST {
        WARN!("App not active, returning D3DERR_DEVICELOST.\n");
        return D3DERR_DEVICELOST;
    }

    if !mode.is_null() {
        wined3d_mode.width = (*mode).Width;
        wined3d_mode.height = (*mode).Height;
        wined3d_mode.refresh_rate = (*mode).RefreshRate;
        wined3d_mode.format_id = wined3dformat_from_d3dformat((*mode).Format);
        wined3d_mode.scanline_ordering = wined3d_scanline_ordering_from_d3d((*mode).ScanLineOrdering);
    }

    output_idx = (*device).adapter_ordinal;
    if wined3d_swapchain_desc_from_d3d9(
        &raw mut swapchain_desc,
        *(*(*device).d3d_parent)
            .wined3d_outputs
            .offset(output_idx as isize),
        present_parameters,
        extended,
    ) == 0
    {
        return D3DERR_INVALIDCALL;
    }
    swapchain_desc.flags =
        (swapchain_desc.flags as ::core::ffi::c_uint | WINED3D_SWAPCHAIN_IMPLICIT as ::core::ffi::c_uint)
            as uint32_t;

    wined3d_mutex_lock();

    wined3d_streaming_buffer_cleanup(&raw mut (*device).vertex_buffer);
    wined3d_streaming_buffer_cleanup(&raw mut (*device).index_buffer);

    if extended == 0 {
        if !(*device).recording.is_null() {
            wined3d_stateblock_decref((*device).recording);
        }
        (*device).recording = core::ptr::null_mut::<wined3d_stateblock>();
        (*device).update_state = (*device).state;
        wined3d_stateblock_reset((*device).state);
    }

    hr = d3d9_device_get_swapchains(device);
    if hr < 0 {
        wined3d_mutex_unlock();
        return hr;
    }
    d3d9_swapchain = wined3d_swapchain_get_parent(
        *(*device)
            .implicit_swapchains
            .offset(0 as isize),
    ) as *mut d3d9_swapchain;

    wined3d_swapchain_get_desc(
        (*d3d9_swapchain).wined3d_swapchain,
        &raw mut old_swapchain_desc,
    );

    /* wined3d_device_reset() may recreate swapchain textures.
     *
     * If the device is not extended, we don't need to remove the reference to
     * the wined3d swapchain from the old d3d9 surfaces: we will fail the reset
     * if they have 0 references, and therefore they are not actually holding a
     * reference to the wined3d swapchain, and will not do anything with it when
     * they are destroyed.
     *
     * If the device is extended, those swapchain textures can survive the
     * reset, and need to be detached from the implicit swapchain here. To add
     * some complexity, we need to add a temporary reference, but we can only do
     * that in the extended case, otherwise we'll try to validate that there are
     * 0 reference and fail. */

    if extended != 0 {
        old_backbuffers = malloc(
            (old_swapchain_desc.backbuffer_count as size_t)
                .wrapping_mul(core::mem::size_of::<*mut d3d9_surface>() as size_t),
        ) as *mut *mut d3d9_surface;
        if old_backbuffers.is_null() {
            wined3d_mutex_unlock();
            return hr;
        }

        i = 0 as ::core::ffi::c_uint;
        while i < old_swapchain_desc.backbuffer_count {
            let ref mut fresh18 = *old_backbuffers.offset(i as isize);
            *fresh18 = wined3d_texture_get_sub_resource_parent(
                wined3d_swapchain_get_back_buffer((*d3d9_swapchain).wined3d_swapchain, i as UINT),
                0 as ::core::ffi::c_uint,
            ) as *mut d3d9_surface;
            /* Resetting might drop the last reference, so grab an extra one here.
             * This also lets us always decref the swapchain, without needing to
             * worry about whether it's externally referenced. */
            IDirect3DSurface9_AddRef(
                &raw mut (**old_backbuffers.offset(i as isize)).IDirect3DSurface9_iface,
            );
            i = i.wrapping_add(1);
        }
    }

    hr = wined3d_device_reset(
        (*device).wined3d_device,
        &raw mut swapchain_desc,
        (if !mode.is_null() {
            &raw mut wined3d_mode
        } else {
            core::ptr::null_mut::<wined3d_display_mode>()
        }),
        Some(reset_enum_callback as unsafe extern "C" fn(*mut wined3d_resource) -> HRESULT),
        (extended == 0) as ::core::ffi::c_int,
    );
    if hr >= 0 {
        let mut surface: *mut d3d9_surface = core::ptr::null_mut::<d3d9_surface>();

        free((*device).implicit_swapchains as *mut ::core::ffi::c_void);

        if extended == 0 {
            (*device).auto_mipmaps = 0 as DWORD;
            wined3d_stateblock_set_render_state(
                (*device).state,
                WINED3D_RS_ZENABLE,
                (swapchain_desc.enable_auto_depth_stencil != 0) as ::core::ffi::c_int
                    as ::core::ffi::c_uint,
            );
            device_reset_viewport_state(device);
        }

        hr = d3d9_device_get_swapchains(device);
        if hr < 0 {
            (*device).device_state = D3D9_DEVICE_STATE_NOT_RESET as LONG;
        } else {
            d3d9_swapchain = wined3d_swapchain_get_parent(
                *(*device)
                    .implicit_swapchains
                    .offset(0 as isize),
            ) as *mut d3d9_swapchain;
            (*d3d9_swapchain).swap_interval = wined3dswapinterval_from_d3d(
                (*present_parameters).PresentationInterval as DWORD,
            ) as ::core::ffi::c_uint;
            wined3d_swapchain_get_desc(
                (*d3d9_swapchain).wined3d_swapchain,
                &raw mut swapchain_desc,
            );
            (*present_parameters).BackBufferWidth = swapchain_desc.backbuffer_width as UINT;
            (*present_parameters).BackBufferHeight = swapchain_desc.backbuffer_height as UINT;
            (*present_parameters).BackBufferFormat =
                d3dformat_from_wined3dformat(swapchain_desc.backbuffer_format);
            (*present_parameters).BackBufferCount = swapchain_desc.backbuffer_count as UINT;

            if extended != 0 {
                i = 0 as ::core::ffi::c_uint;
                while i < old_swapchain_desc.backbuffer_count {
                    surface = *old_backbuffers.offset(i as isize);
                    /* We have a reference to this surface, so we can assert that it's
                     * currently holding a reference to the swapchain. */
                    wined3d_swapchain_decref((*surface).swapchain);
                    (*surface).swapchain = core::ptr::null_mut::<wined3d_swapchain>();
                    (*surface).container =
                        &raw mut (*device).IDirect3DDevice9Ex_iface as *mut IUnknown;
                    i = i.wrapping_add(1);
                }
            }

            /* FIXME: This should be the new backbuffer count, but we don't support
             * changing the backbuffer count in wined3d yet. */
            i = 0 as ::core::ffi::c_uint;
            while i < old_swapchain_desc.backbuffer_count {
                let mut backbuffer: *mut wined3d_texture = wined3d_swapchain_get_back_buffer(
                    (*d3d9_swapchain).wined3d_swapchain,
                    i as UINT,
                );

                surface = d3d9_surface_create(
                    backbuffer,
                    0 as ::core::ffi::c_uint,
                    &raw mut (*device).IDirect3DDevice9Ex_iface as *mut IUnknown,
                );
                if !surface.is_null() {
                    (*surface).parent_device = &raw mut (*device).IDirect3DDevice9Ex_iface;
                }
                i = i.wrapping_add(1);
            }

            (*device).set_in_scene((FALSE as DWORD) as _);
            (*device).device_state = D3D9_DEVICE_STATE_OK as LONG;

            if extended != 0 {
                let mut current: *const wined3d_viewport =
                    &raw const (*(*device).stateblock_state).viewport;
                let mut vp: wined3d_viewport = core::mem::zeroed();
                let mut rect: RECT = core::mem::zeroed();

                vp.x = 0 as ::core::ffi::c_float;
                vp.y = 0 as ::core::ffi::c_float;
                vp.width = swapchain_desc.backbuffer_width as ::core::ffi::c_float;
                vp.height = swapchain_desc.backbuffer_height as ::core::ffi::c_float;
                vp.min_z = (*current).min_z;
                vp.max_z = (*current).max_z;
                wined3d_stateblock_set_viewport((*device).state, &raw mut vp);

                SetRect(
                    &raw mut rect,
                    0 as ::core::ffi::c_int,
                    0 as ::core::ffi::c_int,
                    swapchain_desc.backbuffer_width as ::core::ffi::c_int,
                    swapchain_desc.backbuffer_height as ::core::ffi::c_int,
                );
                wined3d_stateblock_set_scissor_rect((*device).state, &raw mut rect);
            }
        }

        rtv = wined3d_device_context_get_rendertarget_view(
            (*device).immediate_context,
            0 as ::core::ffi::c_uint,
        );
        (*device).render_targets[0 as usize] =
            wined3d_rendertarget_view_get_sub_resource_parent(rtv) as *mut d3d9_surface;
        i = 1 as ::core::ffi::c_uint;
        while (i as usize) < ARRAY_SIZE!((*device).render_targets) as usize {
            (*device).render_targets[i as usize] = core::ptr::null_mut::<d3d9_surface>();
            i = i.wrapping_add(1);
        }

        rtv = wined3d_device_context_get_depth_stencil_view((*device).immediate_context);
        if !rtv.is_null() {
            let mut resource: *mut wined3d_resource = wined3d_rendertarget_view_get_resource(rtv);

            surface = d3d9_surface_create(
                wined3d_texture_from_resource(resource),
                0 as ::core::ffi::c_uint,
                &raw mut (*device).IDirect3DDevice9Ex_iface as *mut IUnknown,
            );
            if !surface.is_null() {
                (*surface).parent_device = &raw mut (*device).IDirect3DDevice9Ex_iface;
            }
        }
    } else if extended == 0 {
        (*device).device_state = D3D9_DEVICE_STATE_NOT_RESET as LONG;
    }

    if extended != 0 {
        i = 0 as ::core::ffi::c_uint;
        while i < old_swapchain_desc.backbuffer_count {
            IDirect3DSurface9_Release(
                &raw mut (**old_backbuffers.offset(i as isize)).IDirect3DSurface9_iface,
            );
            i = i.wrapping_add(1);
        }
        free(old_backbuffers as *mut ::core::ffi::c_void);
    }

    wined3d_mutex_unlock();

    return hr;
}
