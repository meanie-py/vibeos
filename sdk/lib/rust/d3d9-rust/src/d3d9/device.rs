#[no_mangle]
pub unsafe extern "system" fn d3d9_device_CreateAdditionalSwapChain(
    iface: *mut IDirect3DDevice9Ex,
    present_parameters: *mut D3DPRESENT_PARAMETERS,
    swapchain: *mut *mut IDirect3DSwapChain9,
) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut creation_parameters: wined3d_device_creation_parameters = core::mem::zeroed();
    let mut desc: wined3d_swapchain_desc = core::mem::zeroed();
    let mut object: *mut d3d9_swapchain = core::ptr::null_mut();
    let mut swap_interval: core::ffi::c_uint;
    let mut output_idx: core::ffi::c_uint;
    let mut i: core::ffi::c_uint;
    let mut count: core::ffi::c_uint;
    let mut hr: HRESULT;

    TRACE!(
        "iface %p, present_parameters %p, swapchain %p.\n",
        iface,
        present_parameters,
        swapchain
    );

    if (*present_parameters).Windowed == 0 {
        WARN!("Trying to create an additional fullscreen swapchain, returning D3DERR_INVALIDCALL.\n");
        return D3DERR_INVALIDCALL;
    }

    wined3d_mutex_lock();
    count = wined3d_device_get_swapchain_count((*device).wined3d_device) as core::ffi::c_uint;
    i = 0;
    while i < count {
        let wined3d_swapchain: *mut wined3d_swapchain;

        wined3d_swapchain = wined3d_device_get_swapchain((*device).wined3d_device, i as UINT);
        wined3d_swapchain_get_desc(wined3d_swapchain, core::ptr::addr_of_mut!(desc));

        if desc.windowed == 0 {
            wined3d_mutex_unlock();
            WARN!("Trying to create an additional swapchain in fullscreen mode, returning D3DERR_INVALIDCALL.\n");
            return D3DERR_INVALIDCALL;
        }
        i = i.wrapping_add(1);
    }
    wined3d_mutex_unlock();

    output_idx = (*device).adapter_ordinal;
    if wined3d_swapchain_desc_from_d3d9(
        core::ptr::addr_of_mut!(desc),
        *(*(*device).d3d_parent).wined3d_outputs.offset(output_idx as isize),
        present_parameters,
        (*(*device).d3d_parent).extended,
    ) == 0
    {
        return D3DERR_INVALIDCALL;
    }
    wined3d_device_get_creation_parameters(
        (*device).wined3d_device,
        core::ptr::addr_of_mut!(creation_parameters),
    );
    if creation_parameters.flags & WINED3DCREATE_NOWINDOWCHANGES != 0 {
        desc.flags |= WINED3D_SWAPCHAIN_NO_WINDOW_CHANGES;
    }
    swap_interval = wined3dswapinterval_from_d3d((*present_parameters).PresentationInterval as DWORD)
        as core::ffi::c_uint;
    hr = d3d9_swapchain_create(
        device,
        core::ptr::addr_of_mut!(desc),
        swap_interval,
        core::ptr::addr_of_mut!(object),
    );
    if hr >= 0 {
        *swapchain = core::ptr::addr_of_mut!((*object).IDirect3DSwapChain9Ex_iface)
            as *mut IDirect3DSwapChain9;
    }
    present_parameters_from_wined3d_swapchain_desc(
        present_parameters,
        core::ptr::addr_of_mut!(desc),
        (*present_parameters).PresentationInterval as DWORD,
    );

    return hr;
}
#[no_mangle]
pub unsafe extern "system" fn d3d9_device_GetSwapChain(iface: *mut IDirect3DDevice9Ex, swapchain_idx: UINT, swapchain: *mut *mut IDirect3DSwapChain9) -> HRESULT {
    let mut device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut d3d9_swapchain: *mut d3d9_swapchain = core::ptr::null_mut();
    let mut hr: HRESULT = 0;

    TRACE!("iface %p, swapchain_idx %u, swapchain %p.\n", iface, swapchain_idx, swapchain);

    wined3d_mutex_lock();
    if swapchain_idx < (*device).implicit_swapchain_count {
        d3d9_swapchain = wined3d_swapchain_get_parent(*(*device).implicit_swapchains.add(swapchain_idx as usize)) as *mut d3d9_swapchain;
        *swapchain = core::ptr::addr_of_mut!((*d3d9_swapchain).IDirect3DSwapChain9Ex_iface) as *mut IDirect3DSwapChain9;
        IDirect3DSwapChain9Ex_AddRef((*swapchain).cast());
        hr = D3D_OK;
    } else {
        *swapchain = core::ptr::null_mut();
        hr = D3DERR_INVALIDCALL;
    }
    wined3d_mutex_unlock();

    return hr;
}

