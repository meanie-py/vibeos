unsafe extern "C" fn d3d9_rts_flag_auto_gen_mipmap(device: *mut d3d9_device) {
    let mut i: u32;
    i = 0 as u32;
    while (i as usize) < ARRAY_SIZE!((*device).render_targets) as usize {
        let surface: *mut d3d9_surface = (*device).render_targets[i as usize];
        if !surface.is_null() && !(*surface).texture.is_null() {
            d3d9_texture_flag_auto_gen_mipmap((*surface).texture);
        }
        i = i.wrapping_add(1);
    }
}
