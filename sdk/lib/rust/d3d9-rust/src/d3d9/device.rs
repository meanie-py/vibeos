unsafe extern "system" fn d3d9_device_CreateStateBlock(iface: *mut IDirect3DDevice9Ex, type_: D3DSTATEBLOCKTYPE, stateblock: *mut *mut IDirect3DStateBlock9) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let object: *mut d3d9_stateblock;
    let mut hr: HRESULT;

    if type_ != D3DSBT_ALL && type_ != D3DSBT_PIXELSTATE && type_ != D3DSBT_VERTEXSTATE
    {
        WARN!("Unexpected stateblock type, returning D3DERR_INVALIDCALL.\n");
        return D3DERR_INVALIDCALL;
    }

    wined3d_mutex_lock();
    if !(*device).recording.is_null()
    {
        wined3d_mutex_unlock();
        WARN!("Trying to create a stateblock while recording, returning D3DERR_INVALIDCALL.\n");
        return D3DERR_INVALIDCALL;
    }
    wined3d_mutex_unlock();

    object = calloc((1 as size_t) as _, (core::mem::size_of::<d3d9_stateblock>() as size_t) as _) as *mut d3d9_stateblock;
    if object.is_null()
    {
        return E_OUTOFMEMORY;
    }

    hr = stateblock_init(object, device, type_, core::ptr::null_mut());
    if hr < 0
    {
        WARN!("Failed to initialize stateblock, hr %#lx.\n", hr);
        free(object as *mut core::ffi::c_void);
        return hr;
    }

    *stateblock = core::ptr::addr_of_mut!((*object).IDirect3DStateBlock9_iface);

    return D3D_OK;
}

unsafe extern "system" fn d3d9_device_BeginStateBlock(iface: *mut IDirect3DDevice9Ex) -> HRESULT {
    let mut device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut stateblock: *mut wined3d_stateblock = core::ptr::null_mut();
    let mut hr: HRESULT;

    wined3d_mutex_lock();
    if !(*device).recording.is_null() {
        wined3d_mutex_unlock();
        WARN!("Trying to begin a stateblock while recording, returning D3DERR_INVALIDCALL.\n");
        return D3DERR_INVALIDCALL;
    }

    if {
        hr = wined3d_stateblock_create(
            (*device).wined3d_device,
            (*device).state,
            WINED3D_SBT_RECORDED,
            core::ptr::addr_of_mut!(stateblock),
        );
        hr
    } >= 0
    {
        (*device).recording = stateblock;
        (*device).update_state = (*device).recording;
    }
    wined3d_mutex_unlock();

    return hr;
}
unsafe extern "system" fn d3d9_device_EndStateBlock(iface: *mut IDirect3DDevice9Ex, stateblock: *mut *mut IDirect3DStateBlock9) -> HRESULT {
    let mut device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut wined3d_stateblock: *mut wined3d_stateblock = core::ptr::null_mut();
    let mut object: *mut d3d9_stateblock = core::ptr::null_mut();
    let mut hr: HRESULT;

    TRACE!("iface %p, stateblock %p.\n", iface, stateblock);

    wined3d_mutex_lock();
    if (*device).recording.is_null() {
        wined3d_mutex_unlock();
        WARN!("Trying to end a stateblock, but no stateblock is being recorded.\n");
        return D3DERR_INVALIDCALL;
    }
    wined3d_stateblock = (*device).recording;
    wined3d_stateblock_init_contained_states(wined3d_stateblock);
    (*device).recording = core::ptr::null_mut();
    (*device).update_state = (*device).state;
    wined3d_mutex_unlock();

    object = calloc(1, (core::mem::size_of::<d3d9_stateblock>()) as _) as *mut d3d9_stateblock;
    if object.is_null() {
        wined3d_stateblock_decref(wined3d_stateblock);
        return E_OUTOFMEMORY;
    }

    hr = stateblock_init(object, device, 0, wined3d_stateblock);
    if hr < 0 {
        WARN!("Failed to initialize stateblock, hr %#lx.\n", hr);
        wined3d_stateblock_decref(wined3d_stateblock);
        free(object as *mut core::ffi::c_void);
        return hr;
    }

    TRACE!("Created stateblock %p.\n", object);

    *stateblock = core::ptr::addr_of_mut!((*object).IDirect3DStateBlock9_iface);

    return D3D_OK;
}

