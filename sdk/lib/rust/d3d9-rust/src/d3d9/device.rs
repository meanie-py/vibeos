unsafe extern "system" fn d3d9_device_CreateTexture(iface: *mut IDirect3DDevice9Ex, width: UINT, height: UINT, mut levels: UINT, usage: DWORD, format: D3DFORMAT, pool: D3DPOOL, texture: *mut *mut IDirect3DTexture9, shared_handle: *mut HANDLE) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut object: *mut d3d9_texture;
    let mut set_mem: BOOL = (FALSE as i32);
    let mut i: UINT;
    let mut hr: HRESULT;

    *texture = core::ptr::null_mut();
    if !shared_handle.is_null() {
        if (*(*device).d3d_parent).extended == 0 {
            WARN!("Trying to create a shared or user memory texture on a non-ex device.\n");
            return E_NOTIMPL;
        }

        if pool == D3DPOOL_SYSTEMMEM {
            if levels != 1 {
                return D3DERR_INVALIDCALL;
            }
            set_mem = (TRUE as i32);
        } else {
            if pool != D3DPOOL_DEFAULT {
                WARN!("Trying to create a shared texture in pool %#x.\n", pool);
                return D3DERR_INVALIDCALL;
            }
        }
    }

    object = calloc((1 as size_t) as _, (core::mem::size_of::<d3d9_texture>() as size_t) as _) as *mut d3d9_texture;
    if object.is_null() {
        return D3DERR_OUTOFVIDEOMEMORY;
    }

    hr = d3d9_texture_2d_init(object, device, width, height, levels, usage, format, pool);
    if hr < 0 {
        WARN!("Failed to initialize texture, hr %#lx.\n", hr);
        free(object as *mut core::ffi::c_void);
        return hr;
    }

    if set_mem != 0 {
        wined3d_mutex_lock();
        wined3d_texture_update_desc((*object).wined3d_texture, 0, *shared_handle, 0);
        wined3d_mutex_unlock();
    }

    levels = wined3d_texture_get_level_count((*object).wined3d_texture) as UINT;
    i = 0;
    while i < levels {
        if d3d9_surface_create((*object).wined3d_texture, i, core::ptr::addr_of_mut!((*object).IDirect3DBaseTexture9_iface) as *mut IUnknown).is_null() {
            IDirect3DTexture9_Release((core::ptr::addr_of_mut!((*object).IDirect3DBaseTexture9_iface)).cast());
            return E_OUTOFMEMORY;
        }
        i = i.wrapping_add(1);
    }

    *texture = core::ptr::addr_of_mut!((*object).IDirect3DBaseTexture9_iface) as *mut IDirect3DTexture9;

    return D3D_OK;
}
