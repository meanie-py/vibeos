unsafe extern "C" fn wined3d_color_from_d3dcolor(wined3d_colour: *mut wined3d_color, d3d_colour: D3DCOLOR) {
    (*wined3d_colour).r = ((d3d_colour >> 16) & 0xff) as ::core::ffi::c_float / 255.0f32;
    (*wined3d_colour).g = ((d3d_colour >> 8) & 0xff) as ::core::ffi::c_float / 255.0f32;
    (*wined3d_colour).b = (d3d_colour & 0xff) as ::core::ffi::c_float / 255.0f32;
    (*wined3d_colour).a = ((d3d_colour >> 24) & 0xff) as ::core::ffi::c_float / 255.0f32;
}
