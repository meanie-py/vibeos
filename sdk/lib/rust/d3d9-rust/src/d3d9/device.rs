unsafe extern "system" fn d3d9_device_DrawPrimitiveUP(iface: *mut IDirect3DDevice9Ex, primitive_type: D3DPRIMITIVETYPE, primitive_count: UINT, data: *const core::ffi::c_void, stride: UINT) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let vtx_count: UINT = vertex_count_from_primitive_count(primitive_type, primitive_count);
    let size: UINT = vtx_count.wrapping_mul(stride);
    let mut vb_pos: core::ffi::c_uint = 0;
    let mut hr: HRESULT = 0;

    if stride == 0 {
        WARN!("stride is 0, returning D3DERR_INVALIDCALL.\n");
        return D3DERR_INVALIDCALL;
    }
    if primitive_count == 0 {
        WARN!("primitive_count is 0, returning D3D_OK.\n");
        return D3D_OK;
    }

    wined3d_mutex_lock();

    if (*(*device).stateblock_state).vertex_declaration.is_null() {
        wined3d_mutex_unlock();
        WARN!("Called without a valid vertex declaration set.\n");
        return D3DERR_INVALIDCALL;
    }

    'done: {
        hr = wined3d_streaming_buffer_upload(
            (*device).wined3d_device,
            core::ptr::addr_of_mut!((*device).vertex_buffer),
            data,
            size,
            stride,
            core::ptr::addr_of_mut!(vb_pos),
        );
        if hr < 0 {
            break 'done;
        }

        hr = wined3d_stateblock_set_stream_source(
            (*device).state,
            0,
            (*device).vertex_buffer.buffer,
            0,
            stride,
        );
        if hr < 0 {
            break 'done;
        }

        d3d9_generate_auto_mipmaps(device);
        d3d9_device_upload_managed_textures(device);
        wined3d_device_context_set_primitive_type(
            (*device).immediate_context,
            wined3d_primitive_type_from_d3d(primitive_type),
            0,
        );
        wined3d_device_apply_stateblock((*device).wined3d_device, (*device).state);

        /* Instancing is ignored for non-indexed draws. */
        wined3d_device_context_draw(
            (*device).immediate_context,
            vb_pos / stride,
            vtx_count,
            0,
            0,
        );

        wined3d_stateblock_set_stream_source(
            (*device).state,
            0,
            core::ptr::null_mut(),
            0,
            0,
        );
        d3d9_rts_flag_auto_gen_mipmap(device);
    }

    wined3d_mutex_unlock();
    return hr;
}

