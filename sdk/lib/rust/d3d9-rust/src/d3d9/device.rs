unsafe extern "system" fn d3d9_device_GetTexture(iface: *mut IDirect3DDevice9Ex, mut stage: DWORD, texture: *mut *mut IDirect3DBaseTexture9) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut wined3d_texture: *mut wined3d_texture = core::ptr::null_mut();
    let mut state: *const wined3d_stateblock_state = core::ptr::null();
    let mut texture_impl: *mut d3d9_texture = core::ptr::null_mut();

    if texture.is_null() {
        return D3DERR_INVALIDCALL;
    }

    if stage >= D3DVERTEXTEXTURESAMPLER0 as DWORD && stage <= D3DVERTEXTEXTURESAMPLER3 as DWORD {
        stage = stage.wrapping_sub((D3DVERTEXTEXTURESAMPLER0 - (WINED3D_VERTEX_SAMPLER_OFFSET as u32)) as DWORD);
    }

    if stage >= ARRAY_SIZE!((*state).textures) as DWORD {
        WARN!("Ignoring invalid stage %lu.\n", stage);
        *texture = core::ptr::null_mut();
        return D3D_OK;
    }

    wined3d_mutex_lock();
    state = (*device).stateblock_state;
    wined3d_texture = (*state).textures[stage as usize] as *mut wined3d_texture;
    if !wined3d_texture.is_null() {
        texture_impl = wined3d_texture_get_parent(wined3d_texture) as *mut d3d9_texture;
        *texture = core::ptr::addr_of_mut!((*texture_impl).IDirect3DBaseTexture9_iface);
        IDirect3DBaseTexture9_AddRef(*texture);
    } else {
        *texture = core::ptr::null_mut();
    }
    wined3d_mutex_unlock();

    return D3D_OK;
}
unsafe extern "system" fn d3d9_device_SetTexture(iface: *mut IDirect3DDevice9Ex, mut stage: DWORD, texture: *mut IDirect3DBaseTexture9) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut texture_impl: *mut d3d9_texture;

    TRACE!("iface %p, stage %lu, texture %p.\n", iface, stage, texture);

    texture_impl = unsafe_impl_from_IDirect3DBaseTexture9(texture);

    if stage >= (D3DVERTEXTEXTURESAMPLER0 as DWORD) && stage <= (D3DVERTEXTEXTURESAMPLER3 as DWORD) {
        stage = stage.wrapping_sub((D3DVERTEXTEXTURESAMPLER0 - (WINED3D_VERTEX_SAMPLER_OFFSET as u32)) as DWORD);
    }

    wined3d_mutex_lock();
    wined3d_stateblock_set_texture(
        (*device).update_state,
        stage as UINT,
        if !texture_impl.is_null() {
            d3d9_texture_get_draw_texture(texture_impl)
        } else {
            core::ptr::null_mut()
        },
    );
    if (*device).recording.is_null() {
        if stage < (D3D9_MAX_TEXTURE_UNITS as DWORD) {
            if !texture_impl.is_null()
                && (*texture_impl).usage as ::core::ffi::c_ulong
                    & (D3DUSAGE_AUTOGENMIPMAP as ::core::ffi::c_ulong)
                    != 0
            {
                (*device).auto_mipmaps |= (1 as ::core::ffi::c_uint) << stage;
            } else {
                (*device).auto_mipmaps &= !((1 as ::core::ffi::c_uint) << stage);
            }
        }
    }
    wined3d_mutex_unlock();

    return D3D_OK as HRESULT;
}

unsafe extern "system" fn d3d9_device_GetTextureStageState(
    iface: *mut IDirect3DDevice9Ex,
    stage: DWORD,
    state: D3DTEXTURESTAGESTATETYPE,
    value: *mut DWORD,
) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);

    if state as usize >= ARRAY_SIZE!(tss_lookup) as usize || tss_lookup[state as usize] == (WINED3D_TSS_INVALID as u32)
    {
        WARN!("Invalid state %#x passed.\n", state);
        return D3D_OK;
    }

    // Divergence: the C indexes texture_states[stage] unchecked, so stage 8 reads the
    // neighbouring state as the answer (modrun's d3d9 device case caught the Rust panicking
    // there). A stage the state block has no slot for is invalid, like an invalid state.
    let states = &(*(*device).stateblock_state).texture_states;
    if stage as usize >= states.len() {
        WARN!("Invalid stage %u passed.\n", stage);
        return D3D_OK;
    }

    wined3d_mutex_lock();
    *value = states[stage as usize][tss_lookup[state as usize] as usize] as DWORD;
    wined3d_mutex_unlock();

    return D3D_OK;
}
