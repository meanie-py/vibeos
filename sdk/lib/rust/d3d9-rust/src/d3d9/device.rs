unsafe extern "system" fn d3d9_device_GetVertexDeclaration(
    iface: *mut IDirect3DDevice9Ex,
    declaration: *mut *mut IDirect3DVertexDeclaration9,
) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut wined3d_declaration: *mut wined3d_vertex_declaration = core::ptr::null_mut();
    let mut declaration_impl: *mut d3d9_vertex_declaration = core::ptr::null_mut();

    if declaration.is_null() {
        return D3DERR_INVALIDCALL;
    }

    wined3d_mutex_lock();
    wined3d_declaration =
        (*(*device).stateblock_state).vertex_declaration as *mut wined3d_vertex_declaration;
    if !wined3d_declaration.is_null() {
        declaration_impl =
            wined3d_vertex_declaration_get_parent(wined3d_declaration) as *mut d3d9_vertex_declaration;
        *declaration =
            core::ptr::addr_of_mut!((*declaration_impl).IDirect3DVertexDeclaration9_iface);
        IDirect3DVertexDeclaration9_AddRef(*declaration);
    } else {
        *declaration = core::ptr::null_mut();
    }
    wined3d_mutex_unlock();

    return D3D_OK;
}

unsafe extern "C" fn device_get_fvf_declaration(
    mut device: *mut d3d9_device,
    mut fvf: DWORD,
) -> *mut wined3d_vertex_declaration {
    let mut wined3d_declaration: *mut wined3d_vertex_declaration =
        ::core::ptr::null_mut::<wined3d_vertex_declaration>();
    let mut fvf_decls: *mut fvf_declaration = (*device).fvf_decls;
    let mut d3d9_declaration: *mut d3d9_vertex_declaration =
        ::core::ptr::null_mut::<d3d9_vertex_declaration>();
    let mut elements: *mut D3DVERTEXELEMENT9 = ::core::ptr::null_mut::<D3DVERTEXELEMENT9>();
    let mut p: ::core::ffi::c_int = 0;
    let mut low: ::core::ffi::c_int = 0;
    let mut high: ::core::ffi::c_int = 0;
    let mut hr: HRESULT = 0;
    WINE_TRACE!("Searching for declaration for fvf %08lx... ", fvf);
    low = 0;
    high = (*device).fvf_decl_count.wrapping_sub(1) as ::core::ffi::c_int;
    while low <= high {
        p = (low + high) >> 1;
        WINE_TRACE!("%d ", p);
        if (*fvf_decls.offset(p as isize)).fvf == fvf {
            WINE_TRACE!("found %p.\n", (*fvf_decls.offset(p as isize)).decl);
            return (*fvf_decls.offset(p as isize)).decl;
        }
        if (*fvf_decls.offset(p as isize)).fvf < fvf {
            low = p + 1;
        } else {
            high = p - 1;
        }
    }
    WINE_TRACE!("not found. Creating and inserting at position %d.\n", low);
    hr = vdecl_convert_fvf(fvf, &raw mut elements);
    if hr < 0 {
        return ::core::ptr::null_mut::<wined3d_vertex_declaration>();
    }
    hr = d3d9_vertex_declaration_create(device, elements, &raw mut d3d9_declaration);
    free(elements as *mut ::core::ffi::c_void);
    if hr < 0 {
        return ::core::ptr::null_mut::<wined3d_vertex_declaration>();
    }
    if (*device).fvf_decl_size == (*device).fvf_decl_count {
        let mut grow: UINT = max!(
            (*device).fvf_decl_size / 2,
            8,
        );
        fvf_decls = realloc(
            fvf_decls as *mut ::core::ffi::c_void,
            (::core::mem::size_of::<fvf_declaration>() as size_t)
                .wrapping_mul((*device).fvf_decl_size.wrapping_add(grow) as size_t),
        ) as *mut fvf_declaration;
        if fvf_decls.is_null() {
            IDirect3DVertexDeclaration9_Release(
                &raw mut (*d3d9_declaration).IDirect3DVertexDeclaration9_iface,
            );
            return ::core::ptr::null_mut::<wined3d_vertex_declaration>();
        }
        (*device).fvf_decls = fvf_decls;
        (*device).fvf_decl_size = (*device).fvf_decl_size.wrapping_add(grow);
    }
    (*d3d9_declaration).fvf = fvf;
    wined3d_declaration = (*d3d9_declaration).wined3d_declaration;
    wined3d_vertex_declaration_incref(wined3d_declaration);
    IDirect3DVertexDeclaration9_Release(
        &raw mut (*d3d9_declaration).IDirect3DVertexDeclaration9_iface,
    );
    memmove(
        fvf_decls
            .offset(low as isize)
            .offset(1 as isize) as *mut ::core::ffi::c_void,
        fvf_decls.offset(low as isize) as *const ::core::ffi::c_void,
        (::core::mem::size_of::<fvf_declaration>() as size_t)
            .wrapping_mul((*device).fvf_decl_count.wrapping_sub(low as UINT) as size_t),
    );
    (*fvf_decls.offset(low as isize)).decl = wined3d_declaration;
    (*fvf_decls.offset(low as isize)).fvf = fvf;
    (*device).fvf_decl_count = (*device).fvf_decl_count.wrapping_add(1);
    WINE_TRACE!("Returning %p. %u declarations in array.\n", wined3d_declaration, (*device).fvf_decl_count);
    return wined3d_declaration;
}
unsafe extern "system" fn d3d9_device_SetFVF(iface: *mut IDirect3DDevice9Ex, fvf: DWORD) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut decl: *mut wined3d_vertex_declaration;

    if fvf == 0 {
        WARN!("%#lx is not a valid FVF.\n", fvf);
        return D3D_OK;
    }

    wined3d_mutex_lock();
    decl = device_get_fvf_declaration(device, fvf);
    if decl.is_null() {
        wined3d_mutex_unlock();
        ERR!("Failed to create a vertex declaration for fvf %#lx.\n", fvf);
        return D3DERR_DRIVERINTERNALERROR;
    }

    wined3d_stateblock_set_vertex_declaration((*device).update_state, decl);
    wined3d_mutex_unlock();

    return D3D_OK;
}
unsafe extern "system" fn d3d9_device_GetFVF(
    mut iface: *mut IDirect3DDevice9Ex,
    mut fvf: *mut DWORD,
) -> HRESULT {
    let mut device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut wined3d_declaration: *mut wined3d_vertex_declaration =
        ::core::ptr::null_mut::<wined3d_vertex_declaration>();
    let mut d3d9_declaration: *mut d3d9_vertex_declaration =
        ::core::ptr::null_mut::<d3d9_vertex_declaration>();
    WINE_TRACE!("iface %p, fvf %p.\n", iface, fvf);
    wined3d_mutex_lock();
    wined3d_declaration =
        (*(*device).stateblock_state).vertex_declaration as *mut wined3d_vertex_declaration;
    if !wined3d_declaration.is_null() {
        d3d9_declaration = wined3d_vertex_declaration_get_parent(wined3d_declaration)
            as *mut d3d9_vertex_declaration;
        *fvf = (*d3d9_declaration).fvf;
    } else {
        *fvf = 0 as DWORD;
    }
    wined3d_mutex_unlock();
    WINE_TRACE!("Returning FVF %#lx.\n", *fvf);
    return D3D_OK;
}

unsafe extern "system" fn d3d9_device_CreateVertexShader(
    iface: *mut IDirect3DDevice9Ex,
    byte_code: *const DWORD,
    shader: *mut *mut IDirect3DVertexShader9,
) -> HRESULT {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut object: *mut d3d9_vertexshader;
    let mut hr: HRESULT;

    object = calloc(1, (core::mem::size_of::<d3d9_vertexshader>()) as _) as *mut d3d9_vertexshader;
    if object.is_null() {
        return E_OUTOFMEMORY;
    }

    hr = vertexshader_init(object, device, byte_code);
    if hr < 0 {
        WARN!("Failed to initialize vertex shader, hr %#lx.\n", hr);
        free((object).cast());
        return hr;
    }

    *shader = core::ptr::addr_of_mut!((*object).IDirect3DVertexShader9_iface);

    return D3D_OK;
}
