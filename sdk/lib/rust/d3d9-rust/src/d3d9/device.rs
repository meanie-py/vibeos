unsafe extern "system" fn d3d9_device_QueryInterface(iface: *mut IDirect3DDevice9Ex, riid: REFIID, out: *mut *mut core::ffi::c_void) -> HRESULT {

    if IsEqualGUID!(riid, core::ptr::addr_of!(IID_IDirect3DDevice9))
            || IsEqualGUID!(riid, core::ptr::addr_of!(IID_IUnknown))
    {
        IDirect3DDevice9Ex_AddRef(iface);
        *out = iface as *mut core::ffi::c_void;
        return S_OK;
    }

    if IsEqualGUID!(riid, core::ptr::addr_of!(IID_IDirect3DDevice9Ex))
    {
        let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);

        /* Find out if the creating d3d9 interface was created with Direct3DCreate9Ex.
         * It doesn't matter with which function the device was created. */
        if (*(*device).d3d_parent).extended == 0
        {
            WARN!("IDirect3D9 instance wasn't created with CreateDirect3D9Ex, returning E_NOINTERFACE.\n");
            *out = core::ptr::null_mut();
            return E_NOINTERFACE;
        }

        IDirect3DDevice9Ex_AddRef(iface);
        *out = iface as *mut core::ffi::c_void;
        return S_OK;
    }

    if IsEqualGUID!(riid, core::ptr::addr_of!(IID_IDirect3DDevice9On12))
    {
        let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);

        if (*(*device).d3d_parent).d3d9on12 == 0
        {
            WARN!("IDirect3D9 instance wasn't created with D3D9On12 enabled, returning E_NOINTERFACE.\n");
            *out = core::ptr::null_mut();
            return E_NOINTERFACE;
        }

        IDirect3DDevice9Ex_AddRef(iface);
        *out = core::ptr::addr_of_mut!((*device).IDirect3DDevice9On12_iface) as *mut core::ffi::c_void;
        return S_OK;
    }

    WARN!("%s not implemented, returning E_NOINTERFACE.\n", debugstr_guid(riid));

    *out = core::ptr::null_mut();
    return E_NOINTERFACE;
}
unsafe extern "system" fn d3d9_device_AddRef(mut iface: *mut IDirect3DDevice9Ex) -> ULONG {
    let mut device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut refcount: ULONG = InterlockedIncrement(
        core::ptr::addr_of_mut!((*device).refcount) as *mut core::ffi::c_long,
    ) as ULONG;
    WINE_TRACE!("%p increasing refcount to %lu.\n", iface, refcount);
    return refcount;
}

#[no_mangle]
pub unsafe extern "system" fn d3d9_device_Release(iface: *mut IDirect3DDevice9Ex) -> ULONG {
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex(iface);
    let mut refcount: ULONG = 0;

    if (*device).in_destruction() != 0 {
        return 0;
    }

    refcount = InterlockedDecrement(
        core::ptr::addr_of_mut!((*device).refcount) as *mut ::core::ffi::c_long,
    ) as ULONG;

    WINE_TRACE!("%p decreasing refcount to %lu.\n", iface, refcount);

    if refcount == 0 {
        let mut i: ::core::ffi::c_uint = 0;
        (*device).set_in_destruction((TRUE) as _);

        wined3d_mutex_lock();
        i = 0;
        while i < (*device).fvf_decl_count {
            wined3d_vertex_declaration_decref((*(*device).fvf_decls.offset(i as isize)).decl);
            i = i.wrapping_add(1);
        }
        free((*device).fvf_decls as *mut ::core::ffi::c_void);

        wined3d_streaming_buffer_cleanup(core::ptr::addr_of_mut!((*device).vertex_buffer));
        wined3d_streaming_buffer_cleanup(core::ptr::addr_of_mut!((*device).index_buffer));

        i = 0;
        while i < (*device).implicit_swapchain_count {
            wined3d_swapchain_decref(*(*device).implicit_swapchains.offset(i as isize));
            i = i.wrapping_add(1);
        }
        free((*device).implicit_swapchains as *mut ::core::ffi::c_void);

        if !(*device).recording.is_null() {
            wined3d_stateblock_decref((*device).recording);
        }
        wined3d_stateblock_decref((*device).state);

        wined3d_device_release_focus_window((*device).wined3d_device);
        wined3d_device_decref((*device).wined3d_device);
        wined3d_mutex_unlock();

        IDirect3D9Ex_Release(core::ptr::addr_of_mut!(
            (*(*device).d3d_parent).IDirect3D9Ex_iface
        ));

        free(device as *mut ::core::ffi::c_void);
    }

    return refcount;
}

