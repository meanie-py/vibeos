unsafe extern "C" fn swapchain_init(
    swapchain: *mut d3d9_swapchain,
    device: *mut d3d9_device,
    desc: *mut wined3d_swapchain_desc,
    swap_interval: ::core::ffi::c_uint,
) -> HRESULT {
    let mut swapchain_desc: wined3d_swapchain_desc = core::mem::zeroed();
    let mut hr: HRESULT;

    (*swapchain).refcount = 1;
    (*swapchain).IDirect3DSwapChain9Ex_iface.lpVtbl =
        core::ptr::addr_of!(d3d9_swapchain_vtbl) as *const IDirect3DSwapChain9ExVtbl;
    (*swapchain).state_parent.ops =
        core::ptr::addr_of!(d3d9_swapchain_state_parent_ops) as *const wined3d_swapchain_state_parent_ops;
    (*swapchain).swap_interval = swap_interval;

    hr = wined3d_swapchain_create(
        (*device).wined3d_device,
        desc,
        core::ptr::addr_of_mut!((*swapchain).state_parent),
        swapchain as *mut ::core::ffi::c_void,
        core::ptr::addr_of!(d3d9_swapchain_wined3d_parent_ops),
        core::ptr::addr_of_mut!((*swapchain).wined3d_swapchain),
    );
    if hr < 0 {
        WARN!("Failed to create wined3d swapchain, hr %#lx.\n", hr);
        return hr;
    }

    wined3d_swapchain_get_desc(
        (*swapchain).wined3d_swapchain,
        core::ptr::addr_of_mut!(swapchain_desc),
    );
    (*desc).backbuffer_width = swapchain_desc.backbuffer_width;
    (*desc).backbuffer_height = swapchain_desc.backbuffer_height;
    (*desc).backbuffer_format = swapchain_desc.backbuffer_format;

    (*swapchain).parent_device = core::ptr::addr_of_mut!((*device).IDirect3DDevice9Ex_iface);
    IDirect3DDevice9Ex_AddRef((*swapchain).parent_device);

    return D3D_OK;
}
#[no_mangle]
pub unsafe extern "C" fn d3d9_swapchain_create(
    device: *mut d3d9_device,
    desc: *mut wined3d_swapchain_desc,
    swap_interval: ::core::ffi::c_uint,
    swapchain: *mut *mut d3d9_swapchain,
) -> HRESULT {
    let mut wined3d_dsv: *mut wined3d_rendertarget_view = core::ptr::null_mut();
    let mut object: *mut d3d9_swapchain = core::ptr::null_mut();
    let mut surface: *mut d3d9_surface = core::ptr::null_mut();
    let mut i: ::core::ffi::c_uint = 0;
    let mut hr: HRESULT = 0;

    object = calloc(1, (core::mem::size_of::<d3d9_swapchain>()) as _)
        as *mut d3d9_swapchain;
    if object.is_null() {
        return E_OUTOFMEMORY;
    }

    hr = swapchain_init(object, device, desc, swap_interval);
    if hr < 0 {
        WARN!("Failed to initialize swapchain, hr %#lx.\n", hr);
        free(object as *mut ::core::ffi::c_void);
        return hr;
    }

    i = 0;
    while i < (*desc).backbuffer_count {
        surface = d3d9_surface_create(
            wined3d_swapchain_get_back_buffer((*object).wined3d_swapchain, i as UINT),
            0,
            core::ptr::addr_of_mut!((*object).IDirect3DSwapChain9Ex_iface) as *mut IUnknown,
        );
        if surface.is_null() {
            IDirect3DSwapChain9Ex_Release(core::ptr::addr_of_mut!((*object).IDirect3DSwapChain9Ex_iface));
            return E_OUTOFMEMORY;
        }
        (*surface).parent_device = core::ptr::addr_of_mut!((*device).IDirect3DDevice9Ex_iface);
        i = i.wrapping_add(1);
    }

    if ((*desc).flags & WINED3D_SWAPCHAIN_IMPLICIT) != 0
        && {
            wined3d_dsv = wined3d_device_context_get_depth_stencil_view((*device).immediate_context);
            !wined3d_dsv.is_null()
        }
    {
        let resource: *mut wined3d_resource = wined3d_rendertarget_view_get_resource(wined3d_dsv);

        surface = d3d9_surface_create(
            wined3d_texture_from_resource(resource),
            0,
            core::ptr::addr_of_mut!((*device).IDirect3DDevice9Ex_iface) as *mut IUnknown,
        );
        if surface.is_null() {
            IDirect3DSwapChain9Ex_Release(core::ptr::addr_of_mut!((*object).IDirect3DSwapChain9Ex_iface));
            return E_OUTOFMEMORY;
        }
        (*surface).parent_device = core::ptr::addr_of_mut!((*device).IDirect3DDevice9Ex_iface);
    }

    TRACE!("Created swapchain %p.\n", object);

    *swapchain = object;

    return D3D_OK;
}

