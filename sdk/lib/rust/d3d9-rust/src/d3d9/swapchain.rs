unsafe extern "C" fn d3dpresentationinterval_from_wined3dswapinterval(interval: wined3d_swap_interval) -> DWORD {
    match interval as ::core::ffi::c_uint {
        WINED3D_SWAP_INTERVAL_IMMEDIATE => return D3DPRESENT_INTERVAL_IMMEDIATE as DWORD,
        WINED3D_SWAP_INTERVAL_ONE => return D3DPRESENT_INTERVAL_ONE as DWORD,
        WINED3D_SWAP_INTERVAL_TWO => return D3DPRESENT_INTERVAL_TWO as DWORD,
        WINED3D_SWAP_INTERVAL_THREE => return D3DPRESENT_INTERVAL_THREE as DWORD,
        WINED3D_SWAP_INTERVAL_FOUR => return D3DPRESENT_INTERVAL_FOUR as DWORD,
        WINED3D_SWAP_INTERVAL_DEFAULT => return D3DPRESENT_INTERVAL_DEFAULT as DWORD,
        _ => {
            ERR!("Invalid swap interval %#x.\n", interval as ::core::ffi::c_uint);
            return D3DPRESENT_INTERVAL_DEFAULT as DWORD;
        }
    }
}

