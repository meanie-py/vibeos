unsafe extern "system" fn d3d9_swapchain_QueryInterface(iface: *mut IDirect3DSwapChain9Ex, riid: REFIID, out: *mut *mut core::ffi::c_void) -> HRESULT {
    if IsEqualGUID!(riid, core::ptr::addr_of!(IID_IDirect3DSwapChain9)) != false
        || IsEqualGUID!(riid, core::ptr::addr_of!(IID_IUnknown)) != false
    {
        IDirect3DSwapChain9Ex_AddRef(iface);
        *out = iface as *mut core::ffi::c_void;
        return S_OK;
    }

    if IsEqualGUID!(riid, core::ptr::addr_of!(IID_IDirect3DSwapChain9Ex)) != false
    {
        let swapchain: *mut d3d9_swapchain = impl_from_IDirect3DSwapChain9Ex(iface);
        let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex((*swapchain).parent_device);

        /* Find out if the creating d3d9 interface was created with Direct3DCreate9Ex.
         * It doesn't matter with which function the device was created. */
        if (*(*device).d3d_parent).extended == 0
        {
            WARN!("IDirect3D9 instance wasn't created with CreateDirect3D9Ex, returning E_NOINTERFACE.\n");
            *out = core::ptr::null_mut();
            return E_NOINTERFACE;
        }

        IDirect3DSwapChain9Ex_AddRef(iface);
        *out = iface as *mut core::ffi::c_void;
        return S_OK;
    }

    WARN!("%s not implemented, returning E_NOINTERFACE.\n", debugstr_guid(riid));

    *out = core::ptr::null_mut();
    return E_NOINTERFACE;
}

unsafe extern "system" fn d3d9_swapchain_AddRef(iface: *mut IDirect3DSwapChain9Ex) -> ULONG {
    let swapchain: *mut d3d9_swapchain = impl_from_IDirect3DSwapChain9Ex(iface);
    let refcount: ULONG = InterlockedIncrement(
        core::ptr::addr_of_mut!((*swapchain).refcount) as *mut i32,
    ) as ULONG;

    TRACE!("%p increasing refcount to %lu.\n", iface, refcount);

    if refcount == 1 {
        if !(*swapchain).parent_device.is_null() {
            IDirect3DDevice9Ex_AddRef((*swapchain).parent_device);
        }

        wined3d_swapchain_incref((*swapchain).wined3d_swapchain);
    }

    return refcount;
}
unsafe extern "system" fn d3d9_swapchain_Release(iface: *mut IDirect3DSwapChain9Ex) -> ULONG {
    let swapchain: *mut d3d9_swapchain = impl_from_IDirect3DSwapChain9Ex(iface);
    let mut refcount: ULONG;

    if (*swapchain).refcount == 0 {
        WARN!("Swapchain does not have any references.\n");
        return 0;
    }

    refcount = InterlockedDecrement(core::ptr::addr_of_mut!((*swapchain).refcount) as *mut core::ffi::c_long) as ULONG;

    if refcount == 0 {
        let parent_device: *mut IDirect3DDevice9Ex = (*swapchain).parent_device;

        wined3d_swapchain_decref((*swapchain).wined3d_swapchain);

        /* Release the device last, as it may cause the device to be destroyed. */
        if !parent_device.is_null() {
            IDirect3DDevice9Ex_Release(parent_device);
        }
    }

    return refcount;
}
#[no_mangle]
pub unsafe extern "system" fn d3d9_swapchain_Present(
    iface: *mut IDirect3DSwapChain9Ex,
    src_rect: *const RECT,
    dst_rect: *const RECT,
    dst_window_override: HWND,
    dirty_region: *const RGNDATA,
    flags: DWORD,
) -> HRESULT {
    let swapchain: *mut d3d9_swapchain = impl_from_IDirect3DSwapChain9Ex(iface);
    let device: *mut d3d9_device = impl_from_IDirect3DDevice9Ex((*swapchain).parent_device);

    TRACE!(
        "iface %p, src_rect %s, dst_rect %s, dst_window_override %p, dirty_region %p, flags %#lx.\n",
        iface,
        wine_dbgstr_rect(src_rect),
        wine_dbgstr_rect(dst_rect),
        dst_window_override,
        dirty_region,
        flags
    );

    if ((*device).device_state) as u32 != D3D9_DEVICE_STATE_OK {
        return if (*(*device).d3d_parent).extended != 0 {
            S_PRESENT_OCCLUDED
        } else {
            D3DERR_DEVICELOST
        };
    }

    if !dirty_region.is_null() {
        FIXME!("Ignoring dirty_region %p.\n", dirty_region);
    }

    return wined3d_swapchain_present(
        (*swapchain).wined3d_swapchain,
        src_rect,
        dst_rect,
        dst_window_override,
        (*swapchain).swap_interval,
        flags as u32,
    );
}

unsafe extern "system" fn d3d9_swapchain_GetFrontBufferData(iface: *mut IDirect3DSwapChain9Ex, surface: *mut IDirect3DSurface9) -> HRESULT {
    let swapchain: *mut d3d9_swapchain = impl_from_IDirect3DSwapChain9Ex(iface);
    let dst: *mut d3d9_surface = unsafe_impl_from_IDirect3DSurface9(surface);
    let mut hr: HRESULT;

    TRACE!("iface %p, surface %p.\n", iface, surface);

    wined3d_mutex_lock();
    hr = wined3d_swapchain_get_front_buffer_data((*swapchain).wined3d_swapchain, (*dst).wined3d_texture, (*dst).sub_resource_idx);
    wined3d_mutex_unlock();

    return hr;
}
unsafe extern "system" fn d3d9_swapchain_GetBackBuffer(
    iface: *mut IDirect3DSwapChain9Ex,
    backbuffer_idx: UINT,
    backbuffer_type: D3DBACKBUFFER_TYPE,
    backbuffer: *mut *mut IDirect3DSurface9,
) -> HRESULT {
    let swapchain: *mut d3d9_swapchain = impl_from_IDirect3DSwapChain9Ex(iface);
    let mut wined3d_texture: *mut wined3d_texture = core::ptr::null_mut::<wined3d_texture>();
    let mut surface_impl: *mut d3d9_surface = core::ptr::null_mut::<d3d9_surface>();
    let mut hr: HRESULT = D3D_OK;

    TRACE!(
        "iface %p, backbuffer_idx %u, backbuffer_type %#x, backbuffer %p.\n",
        iface,
        backbuffer_idx,
        backbuffer_type as u32,
        backbuffer
    );

    /* backbuffer_type is ignored by native. */

    if backbuffer.is_null() {
        WARN!("The output pointer is NULL, returning D3DERR_INVALIDCALL.\n");
        return D3DERR_INVALIDCALL;
    }

    wined3d_mutex_lock();
    wined3d_texture = wined3d_swapchain_get_back_buffer((*swapchain).wined3d_swapchain, backbuffer_idx);
    if !wined3d_texture.is_null() {
        surface_impl = wined3d_texture_get_sub_resource_parent(wined3d_texture, 0) as *mut d3d9_surface;
        *backbuffer = core::ptr::addr_of_mut!((*surface_impl).IDirect3DSurface9_iface);
        IDirect3DSurface9_AddRef(*backbuffer);
    } else {
        /* Do not set *backbuffer = NULL, see tests/device.c, test_swapchain(). */
        hr = D3DERR_INVALIDCALL;
    }
    wined3d_mutex_unlock();

    return hr;
}

