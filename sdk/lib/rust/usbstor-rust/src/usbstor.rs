#[no_mangle]
pub unsafe extern "system" fn USBSTOR_AddDevice(
    DriverObject: PDRIVER_OBJECT,
    PhysicalDeviceObject: PDEVICE_OBJECT,
) -> NTSTATUS {
    let mut Status: NTSTATUS;
    let mut DeviceObject: PDEVICE_OBJECT = core::ptr::null_mut();
    let DeviceExtension: PFDO_DEVICE_EXTENSION;

    Status = IoCreateDevice(
        DriverObject,
        core::mem::size_of::<FDO_DEVICE_EXTENSION>() as ULONG,
        core::ptr::null_mut(),
        FILE_DEVICE_BUS_EXTENDER as ULONG,
        (FILE_AUTOGENERATED_DEVICE_NAME | FILE_DEVICE_SECURE_OPEN) as ULONG,
        0 as BOOLEAN,
        core::ptr::addr_of_mut!(DeviceObject),
    );
    if !NT_SUCCESS(Status) {
        return Status;
    }

    DeviceExtension = (*DeviceObject).DeviceExtension as PFDO_DEVICE_EXTENSION;
    RtlZeroMemory(
        DeviceExtension as PVOID,
        core::mem::size_of::<FDO_DEVICE_EXTENSION>() as SIZE_T,
    );

    (*DeviceExtension).Common.IsFDO = 1 as BOOLEAN;
    (*DeviceExtension).FunctionalDeviceObject = DeviceObject;
    (*DeviceExtension).PhysicalDeviceObject = PhysicalDeviceObject;
    (*DeviceExtension).LowerDeviceObject =
        IoAttachDeviceToDeviceStack(DeviceObject, PhysicalDeviceObject);

    KeInitializeSpinLock(core::ptr::addr_of_mut!((*DeviceExtension).CommonLock));

    IoInitializeTimer(
        DeviceObject,
        core::mem::transmute::<_, PIO_TIMER_ROUTINE>(USBSTOR_TimerRoutine as *const ()),
        DeviceExtension as PVOID,
    );

    if (*DeviceExtension).LowerDeviceObject.is_null() {
        IoDeleteDevice(DeviceObject);

        return STATUS_DEVICE_REMOVED;
    }

    (*DeviceObject).Flags |= (DO_BUFFERED_IO | DO_POWER_PAGABLE) as ULONG;

    (*DeviceObject).Flags &= !(DO_DEVICE_INITIALIZING as ULONG);

    return STATUS_SUCCESS;
}

#[no_mangle]
pub unsafe extern "system" fn USBSTOR_Unload(DriverObject: PDRIVER_OBJECT) {
    // no-op
}

#[no_mangle]
pub unsafe extern "system" fn USBSTOR_DispatchClose(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
) -> NTSTATUS {
    (*Irp).IoStatus.Information = 0;
    (*Irp).IoStatus.__bindgen_anon_1.Status = STATUS_SUCCESS;
    IoCompleteRequest(Irp, IO_NO_INCREMENT as i8);
    return STATUS_SUCCESS;
}

#[no_mangle]
pub unsafe extern "system" fn USBSTOR_DispatchDeviceControl(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
) -> NTSTATUS {
    let mut Status: NTSTATUS;

    Status = USBSTOR_HandleDeviceControl(DeviceObject, Irp);
    (*Irp).IoStatus.__bindgen_anon_1.Status = Status;
    IoCompleteRequest(Irp, IO_NO_INCREMENT as i8);
    return Status;
}

#[no_mangle]
pub unsafe extern "system" fn USBSTOR_DispatchScsi(
    mut DeviceObject: PDEVICE_OBJECT,
    mut Irp: PIRP,
) -> NTSTATUS {
    return USBSTOR_HandleInternalDeviceControl(DeviceObject, Irp);
}

#[no_mangle]
pub unsafe extern "system" fn USBSTOR_DispatchReadWrite(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
) -> NTSTATUS {
    (*Irp).IoStatus.Information = 0 as _;
    (*Irp).IoStatus.__bindgen_anon_1.Status = STATUS_INVALID_PARAMETER;
    IoCompleteRequest(Irp, IO_NO_INCREMENT as i8);
    return STATUS_INVALID_PARAMETER;
}

#[no_mangle]
pub unsafe extern "system" fn USBSTOR_DispatchPnp(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
) -> NTSTATUS {
    let mut DeviceExtension: PUSBSTOR_COMMON_DEVICE_EXTENSION;
    DeviceExtension = (*DeviceObject).DeviceExtension as PUSBSTOR_COMMON_DEVICE_EXTENSION;
    if (*DeviceExtension).IsFDO != 0 {
        return USBSTOR_FdoHandlePnp(DeviceObject, Irp);
    } else {
        return USBSTOR_PdoHandlePnp(DeviceObject, Irp);
    }
}

#[no_mangle]
pub unsafe extern "system" fn USBSTOR_DispatchSystemControl(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
) -> NTSTATUS {
    let DeviceExtension: PUSBSTOR_COMMON_DEVICE_EXTENSION =
        (*DeviceObject).DeviceExtension as PUSBSTOR_COMMON_DEVICE_EXTENSION;
    IoSkipCurrentIrpStackLocation(Irp);

    if (*DeviceExtension).IsFDO != 0 {
        return IoCallDriver(
            (*(DeviceExtension as PFDO_DEVICE_EXTENSION)).LowerDeviceObject,
            Irp,
        );
    } else {
        return IoCallDriver(
            (*(DeviceExtension as PPDO_DEVICE_EXTENSION)).LowerDeviceObject,
            Irp,
        );
    }
}

#[no_mangle]
pub unsafe extern "system" fn USBSTOR_DispatchPower(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
) -> NTSTATUS {
    let mut DeviceExtension: PFDO_DEVICE_EXTENSION = core::ptr::null_mut();

    // get common device extension
    DeviceExtension = (*DeviceObject).DeviceExtension as PFDO_DEVICE_EXTENSION;

    if (*DeviceExtension).Common.IsFDO != 0 {
        PoStartNextPowerIrp(Irp);
        IoSkipCurrentIrpStackLocation(Irp);
        return PoCallDriver((*DeviceExtension).LowerDeviceObject, Irp);
    } else {
        PoStartNextPowerIrp(Irp);
        (*Irp).IoStatus.__bindgen_anon_1.Status = STATUS_SUCCESS;
        IoCompleteRequest(Irp, IO_NO_INCREMENT as i8);
        return STATUS_SUCCESS;
    }
}

#[no_mangle]
pub unsafe extern "system" fn DriverEntry(
    DriverObject: PDRIVER_OBJECT,
    RegPath: PUNICODE_STRING,
) -> NTSTATUS {
    (*DriverObject).DriverUnload =
        core::mem::transmute::<_, PDRIVER_UNLOAD>(USBSTOR_Unload as *const ());
    (*(*DriverObject).DriverExtension).AddDevice =
        core::mem::transmute::<_, PDRIVER_ADD_DEVICE>(USBSTOR_AddDevice as *const ());
    (*DriverObject).DriverStartIo =
        core::mem::transmute::<_, PDRIVER_STARTIO>(USBSTOR_StartIo as *const ());
    (*DriverObject).MajorFunction[IRP_MJ_CREATE as usize] =
        core::mem::transmute::<_, PDRIVER_DISPATCH>(USBSTOR_DispatchClose as *const ());
    (*DriverObject).MajorFunction[IRP_MJ_CLOSE as usize] =
        core::mem::transmute::<_, PDRIVER_DISPATCH>(USBSTOR_DispatchClose as *const ());
    (*DriverObject).MajorFunction[IRP_MJ_DEVICE_CONTROL as usize] =
        core::mem::transmute::<_, PDRIVER_DISPATCH>(USBSTOR_DispatchDeviceControl as *const ());
    (*DriverObject).MajorFunction[IRP_MJ_READ as usize] =
        core::mem::transmute::<_, PDRIVER_DISPATCH>(USBSTOR_DispatchReadWrite as *const ());
    (*DriverObject).MajorFunction[IRP_MJ_WRITE as usize] =
        core::mem::transmute::<_, PDRIVER_DISPATCH>(USBSTOR_DispatchReadWrite as *const ());
    (*DriverObject).MajorFunction[IRP_MJ_SCSI as usize] =
        core::mem::transmute::<_, PDRIVER_DISPATCH>(USBSTOR_DispatchScsi as *const ());
    (*DriverObject).MajorFunction[IRP_MJ_PNP as usize] =
        core::mem::transmute::<_, PDRIVER_DISPATCH>(USBSTOR_DispatchPnp as *const ());
    (*DriverObject).MajorFunction[IRP_MJ_SYSTEM_CONTROL as usize] =
        core::mem::transmute::<_, PDRIVER_DISPATCH>(USBSTOR_DispatchSystemControl as *const ());
    (*DriverObject).MajorFunction[IRP_MJ_POWER as usize] =
        core::mem::transmute::<_, PDRIVER_DISPATCH>(USBSTOR_DispatchPower as *const ());
    return STATUS_SUCCESS;
}


