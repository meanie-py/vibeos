// FILE_DEVICE_BUS_EXTENDER — absent from the curated ddk/constants surface
// (only in x86-gated hal_ddk). Faithful to <iotypes.h>: 0x0000002a.
const FILE_DEVICE_BUS_EXTENDER: u32 = 0x0000002a;
// STATUS_DEVICE_REMOVED — not present in the curated constants surface.
// Faithful to <ntstatus.h>: ((NTSTATUS)0xC00002B6).
const STATUS_DEVICE_REMOVED: NTSTATUS = 0xC00002B6_u32 as i32;
// IRP_MJ_SCSI — alias of IRP_MJ_INTERNAL_DEVICE_CONTROL (0x0f) per <iotypes.h>.
const IRP_MJ_SCSI: u8 = 0x0f;

extern "system" {
    fn USBSTOR_HandleDeviceControl(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS;
    fn USBSTOR_HandleInternalDeviceControl(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS;
    fn USBSTOR_FdoHandlePnp(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS;
    fn USBSTOR_PdoHandlePnp(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS;
}

// ---- file-scope preamble (translated) ----
