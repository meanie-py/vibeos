#!/usr/bin/env python3
"""Post-process bindgen output for ntkrnl-sys.

Takes raw bindgen output and produces a clean Rust module:
- Strips the __BindgenBitfieldUnit boilerplate (we'll include it once in common)
- Removes derive(Debug) from types containing unions (can't derive Debug on unions)
- Adds module-level attributes
- Strips trailing whitespace

When --hal is passed, also adds `#[link(name = "ntoskrnl", kind = "raw-dylib")]`
to extern static blocks that import kernel data exports.  This is needed for
hal-rust because hal.dll links with `--disable-auto-import`, so cross-DLL data
references need explicit dllimport-equivalent decoration (vs functions, which
the import library handles automatically).
"""

import argparse
import re
import sys
from pathlib import Path


def load_kernel_data_exports() -> set[str]:
    """Parse ntoskrnl/ntoskrnl.spec for `@ extern Name` lines.

    Returns the set of data symbols exported by ntoskrnl.exe — i.e. the
    statics that other DLLs (hal.dll, win32k.sys, drivers) must import
    via cross-DLL data refs.
    """
    spec = Path(__file__).resolve().parent.parent.parent.parent.parent / "ntoskrnl" / "ntoskrnl.spec"
    if not spec.exists():
        print(f"WARNING: ntoskrnl.spec not found at {spec}; raw-dylib wrap will be a no-op", file=sys.stderr)
        return set()
    names = set()
    for line in spec.read_text().splitlines():
        # Match `@ extern Name` and `@ extern -arch=... Name` forms.
        m = re.match(r'@\s+extern\s+(?:-arch=\S+\s+)?(\w+)', line.strip())
        if m:
            names.add(m.group(1))
    return names


def wrap_kernel_data_imports(content: str, kernel_data: set[str]) -> tuple[str, int]:
    """Add `#[link(name = "ntoskrnl", kind = "raw-dylib")]` to extern blocks
    that declare a static whose name is in `kernel_data`.

    Bindgen emits one declaration per `unsafe extern "C" { ... }` block, so
    matching is straightforward.

    Returns (new_content, num_wrapped).
    """
    pattern = re.compile(
        r'(unsafe extern "C" \{\s*pub static (?:mut )?(\w+):[^}]*\})',
        re.MULTILINE,
    )
    wrapped = 0

    def replace(match: re.Match) -> str:
        nonlocal wrapped
        block = match.group(1)
        name = match.group(2)
        if name in kernel_data:
            wrapped += 1
            return '#[link(name = "ntoskrnl.exe", kind = "raw-dylib", modifiers = "+verbatim")]\n' + block
        return block

    return pattern.sub(replace, content), wrapped


def extract_bitfield_unit(content: str) -> tuple[str, str]:
    """Extract __BindgenBitfieldUnit definition and return (unit_code, rest)."""
    # bindgen >= 0.72 follows the unit with `#[derive(..)]\n#[repr(C)] pub struct
    # __BindgenOpaqueArray`, so the derive line must also end the match — without it the
    # unit swallowed that derive and bindgen_common.rs ended on a dangling attribute.
    pattern = r'(#\[repr\(C\)\]\n#\[derive\([^)]*\)\]\npub struct __BindgenBitfieldUnit.*?)(?=\n#\[repr|\n#\[derive|\npub type|\npub const|\nunsafe extern)'
    match = re.search(pattern, content, re.DOTALL)
    if match:
        unit_code = match.group(1)
        rest = content[:match.start()] + content[match.end():]
        return unit_code, rest
    return "", content


def extract_bindgen_flex_array(content: str) -> tuple[str, str]:
    """Extract __BindgenUnionField / __IncompleteArrayField definitions."""
    parts_to_remove = []
    for name in ['__BindgenUnionField', '__IncompleteArrayField']:
        pattern = rf'(#\[repr\(transparent\)\]\npub struct {name}.*?)(?=\n#\[repr|\npub type|\npub const|\nunsafe extern)'
        match = re.search(pattern, content, re.DOTALL)
        if match:
            parts_to_remove.append((match.start(), match.end(), match.group(1)))

    extracted = []
    for start, end, code in sorted(parts_to_remove, reverse=True):
        extracted.append(code)
        content = content[:start] + content[end:]

    return "\n".join(reversed(extracted)), content


def strip_auto_header(content: str) -> str:
    """Remove the 'automatically generated by rust-bindgen' comment."""
    return re.sub(r'/\* automatically generated by rust-bindgen.*?\*/\n*', '', content)


def add_module_header(content: str, arch: str, for_hal: bool) -> str:
    """Add module-level attributes and documentation."""
    flavor = "HAL+ACPI" if for_hal else "DDK"
    header = f"""//! Auto-generated {flavor} bindings for {arch}.
//!
//! Generated by `bindgen` from ReactOS `ntddk.h` headers.
//! Do not edit manually — regenerate with `postprocess_bindgen.py`.

#![allow(dead_code)]

"""
    return header + content


TRANSMUTE_CALL = "::core::mem::transmute("

_PRIMITIVE_SIGN = {
    "i8": True, "i16": True, "i32": True, "i64": True, "isize": True,
    "u8": False, "u16": False, "u32": False, "u64": False, "usize": False,
}


def _alias_sign_map(content: str) -> dict[str, bool]:
    """Map type names -> is_signed, resolved through the file's own
    `pub type X = Y;` alias chains, seeded with the primitive ints."""
    aliases = dict(
        re.findall(r"pub type (\w+) = (?:::core::ffi::c_)?(\w+);", content)
    )
    # core::ffi aliases spelled out by bindgen
    ffi = {"char": "i8", "schar": "i8", "uchar": "u8", "short": "i16",
           "ushort": "u16", "int": "i32", "uint": "u32", "long": "i32",
           "ulong": "u32", "longlong": "i64", "ulonglong": "u64"}
    sign: dict[str, bool] = dict(_PRIMITIVE_SIGN)
    def resolve(name: str, depth: int = 0) -> bool | None:
        if name in sign:
            return sign[name]
        if depth > 8:
            return None
        tgt = aliases.get(name) or ffi.get(name)
        if tgt is None:
            return None
        s = resolve(tgt, depth + 1)
        if s is not None:
            sign[name] = s
        return s
    for name in list(aliases):
        resolve(name)
    return sign


def fix_unnecessary_transmutes(content: str) -> tuple[str, int]:
    """Rewrite bindgen's same-size int transmutes (bitfield accessors) into
    plain integer casts so the generated module compiles clean under
    `unnecessary_transmutes` (warn on rustc >= 1.92, linted only when the
    signedness differs).

        let v: uN = transmute(v);       ->  let v: uN = v as uN;   (always safe)
        transmute(EXPR as uN) -> iN ret ->  (EXPR as uN).cast_signed()
        transmute(EXPR as uN) -> uN ret ->  (EXPR as uN)
        return type not resolvable      ->  left alone (e.g. enum bitfields)

    The getter's target type is the enclosing fn's return type, resolved
    through the file's own alias table (LONG64 -> i64, ULONG64 -> u64, ...).
    """
    sign = _alias_sign_map(content)
    n = 0
    # setter form: `let val: u32 = ::core::mem::transmute(val);` (opt. unsafe {})
    pat = re.compile(
        r"let (\w+): (u8|u16|u32|u64|usize) = "
        r"(unsafe \{ )?::core::mem::transmute\((\w+)\)( \})?;"
    )
    content, k = pat.subn(
        lambda m: f"let {m.group(1)}: {m.group(2)} = {m.group(4)} as {m.group(2)};",
        content,
    )
    n += k
    # getter form (possibly multiline): `transmute(<expr> as uN)` — target is
    # the nearest preceding `-> RET {` return type (positions precomputed;
    # bisect per site to stay O(n log n) on multi-MB files).
    import bisect
    ret_pos: list[int] = []
    ret_ty: list[str] = []
    for m_ret in re.finditer(r"->\s*([\w:]+)\s*\{", content):
        ret_pos.append(m_ret.start())
        ret_ty.append(m_ret.group(1).rsplit("::", 1)[-1])
    out = []
    i = 0
    while True:
        j = content.find(TRANSMUTE_CALL, i)
        if j < 0:
            out.append(content[i:])
            break
        depth, k2 = 1, j + len(TRANSMUTE_CALL)
        while k2 < len(content) and depth:
            if content[k2] == "(":
                depth += 1
            elif content[k2] == ")":
                depth -= 1
            k2 += 1
        inner = content[j + len(TRANSMUTE_CALL):k2 - 1].rstrip()
        if inner.endswith(","):
            inner = inner[:-1].rstrip()
        idx = bisect.bisect_left(ret_pos, j) - 1
        ret = ret_ty[idx] if idx >= 0 else None
        signed = sign.get(ret) if ret else None
        if re.search(r"as (u8|u16|u32|u64|usize)$", inner) and signed is not None:
            repl = f"({inner}).cast_signed()" if signed else f"({inner})"
            out.append(content[i:j])
            out.append(repl)
            n += 1
        else:
            out.append(content[i:k2])  # unknown target — leave alone
        i = k2
    return "".join(out), n


_CAST_MACRO_RE = re.compile(
    r"^#define (\w+) \(\(\s*(\w+)\s*\)\s*\(?\s*(-?)\s*(0[xX][0-9a-fA-F]+|\d+)[uUlL]*\s*\)?\s*\)$",
    re.M,
)
_INT_ALIAS_RE = re.compile(
    r"^pub type (\w+) = (?:::core::ffi::c_\w+|[iu](?:8|16|32|64|size));$", re.M
)


def recover_cast_macros(content: str, macro_dump: str) -> tuple[str, int]:
    """`#define NAME ((TYPE)LITERAL)` -> `pub const NAME: TYPE = LITERAL as TYPE;`.

    bindgen evaluates only macros that are plain constant expressions, so a C cast drops
    the constant entirely. winuser.h spells OBJID_* that way since the upstream merge, and a
    regenerated island silently lost all 16 of them. Only an integer literal cast to an
    integer typedef the island already defines is recovered; the `as` conversion reproduces
    C's cast (`(LONG)0xFFFFFFFC` is -4). Names bindgen did emit are never touched.
    """
    have = set(re.findall(r"^pub const (\w+):", content, re.M))
    int_types = set(_INT_ALIAS_RE.findall(content))
    added = []
    for name, ty, neg, lit in _CAST_MACRO_RE.findall(macro_dump):
        if name in have or ty not in int_types:
            continue
        value = f"{lit}_u64" if not neg else f"(-{lit}_i64)"
        added.append(f"pub const {name}: {ty} = {value} as {ty};")
        have.add(name)
    if not added:
        return content, 0
    return content + "\n// Integer cast macros bindgen skips (postprocess_bindgen.recover_cast_macros).\n" + "\n".join(added) + "\n", len(added)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input", help="raw bindgen output (.rs)")
    ap.add_argument("arch", help="target arch: arm64 | amd64 | i386")
    ap.add_argument("output", nargs="?", help="output path (.rs)")
    ap.add_argument(
        "--hal",
        action="store_true",
        help="wrap kernel-data-export extern statics with raw-dylib decoration "
             "(required for hal-rust because hal.dll is a separate binary from "
             "ntoskrnl.exe and the link is --disable-auto-import)",
    )
    ap.add_argument(
        "--macro-dump",
        help="`clang -dM -E` of the wrapper: recover integer-literal cast macros bindgen skips",
    )
    args = ap.parse_args()

    input_path = Path(args.input)
    arch = args.arch
    output_path = Path(args.output) if args.output else None

    content = input_path.read_text()

    # Strip the auto-generated header comment
    content = strip_auto_header(content)

    # Rewrite same-size int transmutes (bitfield accessors) -> casts so the
    # generated module compiles clean under `unnecessary_transmutes`.
    content, n_transmutes = fix_unnecessary_transmutes(content)
    if n_transmutes:
        print(f"  rewrote {n_transmutes} bitfield transmutes -> casts")

    if args.macro_dump:
        content, n_casts = recover_cast_macros(content, Path(args.macro_dump).read_text())
        print(f"  recovered {n_casts} integer cast macros")

    # Extract __BindgenBitfieldUnit — we'll put it in a shared module
    bitfield_unit, content = extract_bitfield_unit(content)

    # Extract __BindgenUnionField / __IncompleteArrayField
    flex_arrays, content = extract_bindgen_flex_array(content)

    # HAL output needs raw-dylib decoration on kernel-data extern statics.
    n_wrapped = 0
    if args.hal:
        kernel_data = load_kernel_data_exports()
        content, n_wrapped = wrap_kernel_data_imports(content, kernel_data)

    # Save the shared helpers separately
    shared_dir = output_path.parent if output_path else Path(".")
    shared_path = shared_dir / "bindgen_common.rs"
    if bitfield_unit or flex_arrays:
        shared_content = """//! Shared bindgen helper types.
//!
//! These are generated by bindgen and shared across all architecture modules.
//! Do not edit manually.

#![allow(dead_code)]

"""
        if bitfield_unit:
            shared_content += bitfield_unit + "\n\n"
        if flex_arrays:
            shared_content += flex_arrays + "\n"
        # Only write if it doesn't exist or is different
        if not shared_path.exists() or shared_path.read_text() != shared_content:
            shared_path.write_text(shared_content)
            print(f"  Wrote shared helpers: {shared_path} ({len(shared_content)} bytes)")

    # Add use for the shared helpers
    content = "use super::bindgen_common::*;\n\n" + content

    # Add module header
    content = add_module_header(content, arch, args.hal)

    # Strip trailing whitespace on each line
    content = "\n".join(line.rstrip() for line in content.split("\n"))

    # Remove excessive blank lines (3+ in a row → 2)
    content = re.sub(r'\n{4,}', '\n\n\n', content)

    if output_path:
        output_path.write_text(content)
        # Count stats
        funcs = len(re.findall(r'pub fn [A-Z]', content))
        structs = len(re.findall(r'pub struct ', content))
        types = len(re.findall(r'pub type ', content))
        consts = len(re.findall(r'pub const ', content))
        suffix = f", {n_wrapped} kernel-data raw-dylib wraps" if args.hal else ""
        print(f"  {arch}: {len(content.splitlines())} lines, {funcs} functions, {structs} structs, {types} types, {consts} constants{suffix}")
    else:
        sys.stdout.write(content)


if __name__ == "__main__":
    main()
