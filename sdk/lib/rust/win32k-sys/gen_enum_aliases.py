#!/usr/bin/env python3
"""Generate de-prefixed enum-constant aliases for win32k-sys.

bindgen constifies tagged C enums by prefixing every variant with the
enum *type* name, e.g. C `enum GDIObjType { GDIObjType_SURF_TYPE }`
becomes `pub const GDIObjType_GDIObjType_SURF_TYPE: GDIObjType = 5;`.
Translated win32k code (and the C it mirrors) refers to the original
name `GDIObjType_SURF_TYPE`, which `use win32k_sys::win32k::*` never
exposes — only the double-prefixed form is in the glob. rustconv's
catalog already de-prefixes for the *resolver*; this materialises the
same de-prefix as real Rust `pub const` aliases so the code compiles.

Rule (identical to catalog._scan_bindgen): for
`pub const <CNAME>: <ETYPE> = ...;` where CNAME startswith `<ETYPE>_`,
alias = CNAME[len(ETYPE)+1:]. An alias is emitted only when it is
unambiguous (one source CNAME) and does not collide with any existing
top-level bindgen item — otherwise it is dropped (the prefixed name
stays usable).

Run from sdk/lib/rust/win32k-sys/ after (re)generating bindgen:
    python3 gen_enum_aliases.py
Writes src/enum_aliases_{i386,amd64,arm64}.rs.
"""
import re
import sys
from pathlib import Path
from collections import defaultdict

SRC = Path(__file__).parent / "src"
ARCHES = ("i386", "amd64", "arm64")

RE_CONST_TYPED = re.compile(r'^pub const (\w+)\s*:\s*(\w+)\s*=')
RE_TOP_ITEM = re.compile(
    r'^pub (?:const|static(?: mut)?|type|fn|struct|enum|union) (\w+)'
)


def generate(arch: str) -> int:
    bindgen = SRC / f"bindgen_{arch}.rs"
    if not bindgen.exists():
        print(f"  skip {arch}: no {bindgen.name}")
        return 0
    text = bindgen.read_text()

    existing: set[str] = set()
    # (alias -> set of source cnames) to detect ambiguity
    candidates: dict[str, set[tuple[str, str]]] = defaultdict(set)

    for line in text.splitlines():
        mi = RE_TOP_ITEM.match(line)
        if mi:
            existing.add(mi.group(1))
        mc = RE_CONST_TYPED.match(line)
        if mc:
            cname, etype = mc.group(1), mc.group(2)
            pfx = etype + "_"
            if cname.startswith(pfx) and len(cname) > len(pfx):
                alias = cname[len(pfx):]
                candidates[alias].add((cname, etype))

    out = [
        "// @generated by gen_enum_aliases.py — DO NOT EDIT.",
        "// De-prefixed aliases for bindgen-constified tagged enums so",
        "// `use win32k_sys::win32k::*` exposes the original C names.",
        "#![allow(non_upper_case_globals, dead_code)]",
        "",
        f"use super::bindgen_{arch}::*;",
        "",
    ]
    n = 0
    for alias in sorted(candidates):
        srcs = candidates[alias]
        if len(srcs) != 1:
            continue  # ambiguous: same de-prefixed name from >1 enum
        if alias in existing:
            continue  # would shadow/duplicate a real bindgen item
        cname, etype = next(iter(srcs))
        out.append(f"pub const {alias}: {etype} = {cname};")
        n += 1
    out.append("")

    dest = SRC / f"enum_aliases_{arch}.rs"
    dest.write_text("\n".join(out))
    print(f"  {arch}: {n} aliases -> {dest.name}")
    return n


if __name__ == "__main__":
    total = sum(generate(a) for a in ARCHES)
    print(f"total: {total} aliases across {len(ARCHES)} arches")
    sys.exit(0 if total else 1)
