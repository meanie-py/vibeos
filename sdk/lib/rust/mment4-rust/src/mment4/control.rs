#[no_mangle]
pub unsafe extern "C" fn GetNt4SoundDeviceCapabilities(
    SoundDevice: PSOUND_DEVICE,
    Capabilities: PVOID,
    CapabilitiesSize: DWORD,
) -> MMRESULT {
    let mut Result: MMRESULT;
    let mut DeviceType: MMDEVICE_TYPE = 0;
    let mut IoCtl: DWORD;
    let mut DeviceHandle: HANDLE = core::ptr::null_mut();

    /* If these are bad there's an internal error with MME-Buddy! */
    SND_ASSERT!(!SoundDevice.is_null());
    SND_ASSERT!(!Capabilities.is_null());
    SND_ASSERT!(CapabilitiesSize > 0);

    SND_TRACE!(RUSTCONV_WSTR_9D8BEB1B79D2.as_ptr());

    /* Get the device type */
    Result = GetSoundDeviceType(SoundDevice, core::ptr::addr_of_mut!(DeviceType));
    SND_ASSERT!(Result == MMSYSERR_NOERROR);

    if ((MMSUCCESS!(Result)) == 0) {
        return TranslateInternalMmResult(Result);
    }

    /* Choose the appropriate IOCTL */
    if ((IS_WAVE_DEVICE_TYPE!(DeviceType)) != 0) {
        IoCtl = (IOCTL_WAVE_GET_CAPABILITIES as u32);
    } else if ((IS_MIDI_DEVICE_TYPE!(DeviceType)) != 0) {
        IoCtl = (IOCTL_MIDI_GET_CAPABILITIES as u32);
    } else {
        /* FIXME - need to support AUX and mixer devices */
        SND_ASSERT!(FALSE);
        IoCtl = 0;
    }

    /* Get the capabilities information from the driver */
    Result = OpenNt4KernelSoundDevice(
        SoundDevice,
        (TRUE) as BOOLEAN,
        core::ptr::addr_of_mut!(DeviceHandle),
    );

    if ((MMSUCCESS!(Result)) == 0) {
        SND_ERR!(RUSTCONV_WSTR_4FEAD6548D0C.as_ptr());
        return TranslateInternalMmResult(Result);
    }

    Result = SyncOverlappedDeviceIoControl(
        DeviceHandle,
        IoCtl,
        Capabilities,
        CapabilitiesSize,
        core::ptr::null_mut(),
        0,
        core::ptr::null_mut(),
    );

    CloseKernelSoundDevice(DeviceHandle);

    if ((MMSUCCESS!(Result)) == 0) {
        SND_ERR!(RUSTCONV_WSTR_384E3F2A36B9.as_ptr());
        Result = TranslateInternalMmResult(Result);
    }

    return Result;
}
