#!/bin/bash
# Generate the secur32 SSPI / security-provider / LSA-LPC / NTLM-MSV / wincred
# type substrate (secur32-sys) for all 3 arches.
#
# Allowlisted to the secur32-specific surface absent from ntdll-sys (which is
# NT-internal only). Flags/includes mirror the module's own C compile command so
# the usermode win32+NDK header context resolves exactly as the C build sees it.
# Per-arch (pointer widths + handle/LPC layout differ).
#
# Prereq: cargo install bindgen-cli. Build dirs must exist (generated headers
# under build-<arch> are referenced for the win32 include context).
set -e
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SRC="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
TC="$SRC/.build-tools/llvm-mingw"
OUT_DIR="$SCRIPT_DIR/src"
WRAPPER="$SCRIPT_DIR/wrapper_secur32.h"

COMMON_FLAGS=(
    --use-core --no-layout-tests --no-doc-comments
    --allowlist-function '(Lsa[A-Za-z0-9_]*|Sec[A-Za-z0-9_]*|Net[A-Za-z0-9_]*|Cred[A-Za-z0-9_]*|SystemFunction[0-9]+)'
    --allowlist-type '(P?SecBuffer.*|P?SecBufferDesc|P?SecHandle|P?SecPkgInfo.*|P?SecPkgContext.*|P?SecPkgCred.*|P?SecurityFunctionTable.*|P?CredHandle|P?CtxtHandle|P?TimeStamp|SECURITY_STATUS|P?SEC_.*|P?SecurityUserData|P?SECURITY_STRING|SEC_GET_KEY_FN|SEC_CHAR|SEC_WCHAR|P?CtxtHandle|P?SCHANNEL_.*|P?SecPkg.*|P?MSV1_0_.*|P?KERB_.*|P?LSA_.*|P?LSAPR_.*|P?SECURITY_LOGON_.*|P?QUOTA_LIMITS|P?TOKEN_SOURCE|P?LSA_STRING|P?LSA_UNICODE_STRING|P?CREDENTIAL.*|P?CRED_.*|P?CREDENTIALW|P?CREDENTIALA|P?USER_INFO.*|P?WKSTA_INFO.*|P?NETRESOURCE.*|P?SID_NAME_USE|P?POLICY_.*|P?TRUSTED_.*|P?PORT_MESSAGE|P?LSASS.*|P?LSA_CALL_.*|P?LSA_AP_.*|NTSTATUS|P?LUID|P?STRING|P?UNICODE_STRING|P?ANSI_STRING|HMODULE|HINSTANCE|P?HMODULE|P?HINSTANCE|HINSTANCE__)'
    --allowlist-var  '(SECPKG_.*|SECBUFFER_.*|SECURITY_.*|SEC_.*|ISC_.*|ASC_.*|SCHANNEL_.*|SP_PROT_.*|MSV1_0_.*|KERB_.*|UNISP_.*|CRED_.*|NERR_.*|SERVICE_.*|RTL_ENCRYPT_.*|MICROSOFT_KERBEROS_.*|NTLMSP_.*|NEGOSSP_.*)'
)

run_bindgen() {
    local ARCH=$1 TARGET=$2; shift 2
    local EXTRA=("$@")
    local BUILD_DIR="$SRC/build-${ARCH}"
    local RAW="/tmp/secur32_${ARCH}_raw.rs"
    local FINAL="$OUT_DIR/bindgen_${ARCH}.rs"
    echo "=== secur32-sys ${ARCH} (${TARGET}) ==="
    bindgen "$WRAPPER" "${COMMON_FLAGS[@]}" -o "$RAW" -- \
        -ferror-limit=0 -Wno-everything \
        -DUNICODE -D_UNICODE -D__REACTOS__ -D_USE_DUMMY_PSEH=1 \
        -DDBG=1 -DWINVER=0x502 -D_WIN32_WINNT=0x502 -D_WIN32_WINDOWS=0x502 \
        -D_WIN32_IE=0x603 -D_CRT_NON_CONFORMING_SWPRINTFS -D_CRT_SUPPRESS_RESTRICT \
        -D__SECUR32__ -DSECURITY_WIN32 \
        "${EXTRA[@]}" \
        -I"${BUILD_DIR}/dll/win32/secur32" \
        -I"${SRC}/dll/win32/secur32" \
        -I"${SRC}/sdk/include" \
        -I"${SRC}/sdk/include/crt" \
        -I"${SRC}/sdk/include/ddk" \
        -I"${SRC}/sdk/include/ndk" \
        -I"${SRC}/sdk/include/psdk" \
        -I"${SRC}/sdk/include/reactos" \
        -I"${SRC}/sdk/include/reactos/subsys" \
        -I"${SRC}/sdk/include/reactos/idl" \
        -I"${SRC}/sdk/include/reactos/libs" \
        -I"${SRC}/sdk/include/vcruntime" \
        -I"${SRC}/sdk/include/winrt" \
        -I"${SRC}/sdk/lib/pseh/include" \
        -I"${BUILD_DIR}/sdk/include" \
        -I"${BUILD_DIR}/sdk/include/psdk" \
        -I"${BUILD_DIR}/sdk/include/ddk" \
        -I"${BUILD_DIR}/sdk/include/dxsdk" \
        -I"${BUILD_DIR}/sdk/include/reactos" \
        -I"${BUILD_DIR}/sdk/include/reactos/mc" \
        -isystem "${TC}/lib/clang/19/include" \
        --target="${TARGET}"
    {
        echo "// AUTO-GENERATED by secur32-sys/generate_bindings.sh — do not edit by hand."
        echo "// SSPI/security-provider/LSA-LPC/NTLM-MSV/wincred substrate for secur32-rust."
        echo "#![allow(non_snake_case, non_camel_case_types, non_upper_case_globals, dead_code, unused_imports)]"
        cat "$RAW"
    } > "$FINAL"
    echo "  -> $FINAL ($(wc -l < "$FINAL") lines)"
}

run_bindgen arm64 aarch64-pc-windows-gnu -D_WIN64 -D_M_ARM64 -D__aarch64__ -D__arm64__ -D_ARM64_
run_bindgen amd64 x86_64-pc-windows-gnu  -D_WIN64 -D_M_AMD64 -D__x86_64__ -D_AMD64_
run_bindgen i386  i686-pc-windows-gnu    -D_M_IX86 -D__i386__ -D_X86_ -D_USE_32BIT_TIME_T
echo "=== done ==="
