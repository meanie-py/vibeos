unsafe extern "C" fn sink_writer_write_sample(writer: *mut sink_writer, stream: *mut stream, sample: *mut IMFSample) -> HRESULT {
    let mut timestamp: LONGLONG = 0;
    let mut length: DWORD = 0;
    let mut hr: HRESULT = 0;

    hr = sink_writer_get_buffer_length(sample, core::ptr::addr_of_mut!(timestamp), core::ptr::addr_of_mut!(length));
    if hr < 0 as HRESULT {
        return hr;
    }

    (*stream).stats.llLastTimestampReceived = timestamp;
    (*stream).stats.qwNumSamplesReceived = (*stream).stats.qwNumSamplesReceived.wrapping_add(1);
    (*stream).stats.dwByteCountQueued = (*stream).stats.dwByteCountQueued.wrapping_add(length);

    (*writer).stats.llLastTimestampReceived = timestamp;
    (*writer).stats.qwNumSamplesReceived = (*writer).stats.qwNumSamplesReceived.wrapping_add(1);
    (*writer).stats.dwByteCountQueued = (*writer).stats.dwByteCountQueued.wrapping_add(length);

    hr = sink_writer_encode_sample(writer, stream, sample);
    if hr < 0 as HRESULT {
        return hr;
    }

    if (*stream).stats.dwNumOutstandingSinkSampleRequests != 0 {
        hr = sink_writer_process_sample(writer, stream);
    }

    return hr;
}

