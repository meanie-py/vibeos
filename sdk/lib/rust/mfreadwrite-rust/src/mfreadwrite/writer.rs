unsafe extern "C" fn stream_create_transforms(
    stream: *mut stream,
    input_type: *mut IMFMediaType,
    output_type: *mut IMFMediaType,
    use_encoder: BOOL,
    attributes: *mut IMFAttributes,
) -> HRESULT {
    let mut encoder_input_type: *mut IMFMediaType = core::ptr::null_mut::<IMFMediaType>();
    let mut activates: *mut *mut IMFActivate = core::ptr::null_mut::<*mut IMFActivate>();
    let mut transform: *mut IMFTransform = core::ptr::null_mut::<IMFTransform>();
    let mut count: UINT32 = 0;
    let mut i: UINT32 = 0;
    let mut hr: HRESULT = 0;

    /* Enumerate available transforms. */
    hr = stream_enumerate_transforms(
        stream,
        input_type,
        output_type,
        use_encoder,
        attributes,
        core::ptr::addr_of_mut!(activates),
        core::ptr::addr_of_mut!(count),
    );
    if hr < 0 {
        return hr;
    }
    i = 0;
    while i < count {
        hr = IMFActivate_ActivateObject(
            *activates.offset(i as isize),
            core::ptr::addr_of!(IID_IMFTransform),
            core::ptr::addr_of_mut!(transform) as *mut *mut core::ffi::c_void,
        );
        if !(hr < 0) {
            hr = stream_set_transform(stream, transform, input_type, output_type, use_encoder);
            if hr >= 0 {
                break;
            }

            /* Failed to use a single encoder, try using an encoder and a converter. */
            if use_encoder != 0 && {
                hr = IMFTransform_GetInputAvailableType(
                    transform,
                    0,
                    0,
                    core::ptr::addr_of_mut!(encoder_input_type),
                );
                hr >= 0
            } {
                /* Create the converter with a recursive call. */
                hr = stream_create_transforms(
                    stream,
                    input_type,
                    encoder_input_type,
                    (FALSE) as BOOL,
                    attributes,
                );
                IMFMediaType_Release(encoder_input_type);
                if hr >= 0 {
                    /* Converter is already set in the recursive call, set encoder here. */
                    (*stream).encoder = transform;
                    TRACE!("Created encoder %p.", transform);
                    break;
                }
            }

            IMFTransform_Release(transform);
        }
        i = i.wrapping_add(1);
    }

    i = 0;
    while i < count {
        IMFActivate_Release(*activates.offset(i as isize));
        i = i.wrapping_add(1);
    }
    CoTaskMemFree(activates as LPVOID);

    return hr;
}

