unsafe extern "C" fn stream_enumerate_transforms(
    mut stream: *mut stream,
    mut input_type: *mut IMFMediaType,
    mut output_type: *mut IMFMediaType,
    mut use_encoder: BOOL,
    mut attributes: *mut IMFAttributes,
    mut out_activates: *mut *mut *mut IMFActivate,
    mut out_count: *mut UINT32,
) -> HRESULT {
    let mut flags: UINT32 = MFT_ENUM_FLAG_SYNCMFT | MFT_ENUM_FLAG_LOCALMFT | MFT_ENUM_FLAG_SORTANDFILTER;
    let mut disable_converter: UINT32 = 0;
    let mut use_hardware_transforms: UINT32 = 0;
    let mut input_type_info: MFT_REGISTER_TYPE_INFO = __WIDL_mfobjects_generated_name_0000002D {
        guidMajorType: _GUID {
            Data1: 0,
            Data2: 0,
            Data3: 0,
            Data4: [0; 8],
        },
        guidSubtype: _GUID {
            Data1: 0,
            Data2: 0,
            Data3: 0,
            Data4: [0; 8],
        },
    };
    let mut output_type_info: MFT_REGISTER_TYPE_INFO = __WIDL_mfobjects_generated_name_0000002D {
        guidMajorType: _GUID {
            Data1: 0,
            Data2: 0,
            Data3: 0,
            Data4: [0; 8],
        },
        guidSubtype: _GUID {
            Data1: 0,
            Data2: 0,
            Data3: 0,
            Data4: [0; 8],
        },
    };
    let mut category: GUID = _GUID {
        Data1: 0,
        Data2: 0,
        Data3: 0,
        Data4: [0; 8],
    };
    let mut hr: HRESULT = 0;

    /* Check writer attributes. */
    if !attributes.is_null() {
        IMFAttributes_GetUINT32(
            attributes,
            &raw const MF_READWRITE_DISABLE_CONVERTERS,
            &raw mut disable_converter,
        );
        IMFAttributes_GetUINT32(
            attributes,
            &raw const MF_READWRITE_ENABLE_HARDWARE_TRANSFORMS,
            &raw mut use_hardware_transforms,
        );
        if use_hardware_transforms != 0 {
            flags |= MFT_ENUM_FLAG_HARDWARE;
        }
    }

    /* Neither encoder nor converter is allowed, return failure. */
    if use_encoder == 0 && disable_converter != 0 {
        return E_FAIL;
    }

    /* Get type infos. */
    hr = IMFMediaType_GetMajorType(input_type, &raw mut input_type_info.guidMajorType);
    if hr < 0 || {
        hr = IMFMediaType_GetGUID(
            input_type,
            &raw const MF_MT_SUBTYPE,
            &raw mut input_type_info.guidSubtype,
        );
        hr < 0
    } {
        return hr;
    }
    hr = IMFMediaType_GetMajorType(output_type, &raw mut output_type_info.guidMajorType);
    if hr < 0 || {
        hr = IMFMediaType_GetGUID(
            output_type,
            &raw const MF_MT_SUBTYPE,
            &raw mut output_type_info.guidSubtype,
        );
        hr < 0
    } {
        return hr;
    }

    /* Set category according to major type. */
    if IsEqualGUID!(
        &raw mut output_type_info.guidMajorType,
        &raw const MFMediaType_Video,
    ) != false
    {
        category = if use_encoder != 0 {
            MFT_CATEGORY_VIDEO_ENCODER
        } else {
            MFT_CATEGORY_VIDEO_PROCESSOR
        };
    } else if IsEqualGUID!(
        &raw mut output_type_info.guidMajorType,
        &raw const MFMediaType_Audio,
    ) != false
    {
        category = if use_encoder != 0 {
            MFT_CATEGORY_AUDIO_ENCODER
        } else {
            MFT_CATEGORY_AUDIO_EFFECT
        };
    } else {
        return MF_E_TOPO_CODEC_NOT_FOUND;
    }

    /* Enumerate available transforms. */
    *out_count = 0;
    hr = MFTEnumEx(
        category,
        flags,
        if disable_converter != 0 {
            &raw mut input_type_info
        } else {
            core::ptr::null_mut()
        },
        &raw mut output_type_info,
        out_activates,
        out_count,
    );
    if hr < 0 {
        return hr;
    }
    if *out_count == 0 {
        return MF_E_TOPO_CODEC_NOT_FOUND;
    }

    return hr;
}

