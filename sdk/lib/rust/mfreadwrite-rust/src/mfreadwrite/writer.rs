unsafe extern "C" fn sink_writer_drop_pending_items(stream: *mut stream) {
    let mut item: *mut pending_item = core::ptr::null_mut::<pending_item>();
    let mut next: *mut pending_item = core::ptr::null_mut::<pending_item>();
    item = ((*stream).queue.next as *mut u8)
        .sub(core::mem::offset_of!(pending_item, entry)) as *mut pending_item;
    next = ((*item).entry.next as *mut u8)
        .sub(core::mem::offset_of!(pending_item, entry)) as *mut pending_item;
    while core::ptr::addr_of_mut!((*item).entry) != core::ptr::addr_of_mut!((*stream).queue) {
        sink_writer_release_pending_item(item);
        item = next;
        next = ((*item).entry.next as *mut u8)
            .sub(core::mem::offset_of!(pending_item, entry)) as *mut pending_item;
    }
}

unsafe extern "system" fn sink_writer_Release(iface: *mut IMFSinkWriterEx) -> ULONG {
    let writer: *mut sink_writer = impl_from_IMFSinkWriterEx(iface);
    let refcount: ULONG = InterlockedDecrement(core::ptr::addr_of_mut!((*writer).refcount)) as ULONG;
    let mut i: UINT32 = 0;

    TRACE!("%p, %lu.\n", iface, refcount);

    if refcount == 0 {
        if !(*writer).clock.is_null() {
            IMFPresentationClock_Release((*writer).clock);
        }
        if !(*writer).sink.is_null() {
            IMFMediaSink_Release((*writer).sink);
        }
        if !(*writer).attributes.is_null() {
            IMFAttributes_Release((*writer).attributes);
        }
        if !(*writer).callback.is_null() {
            IMFSinkWriterCallback_Release((*writer).callback);
        }
        while (i as size_t) < (*writer).streams.count {
            let stream: *mut stream = (*writer).streams.items.add(i as usize);

            if !(*stream).stream_sink.is_null() {
                IMFStreamSink_Release((*stream).stream_sink);
            }
            stream_release_transforms(stream);
            sink_writer_drop_pending_items(stream);
            i = i.wrapping_add(1);
        }
        DeleteCriticalSection(core::ptr::addr_of_mut!((*writer).cs));
        free(writer as *mut core::ffi::c_void);
    }

    return refcount;
}

unsafe extern "C" fn sink_writer_add_stream(writer: *mut sink_writer, stream_sink: *mut IMFStreamSink, index: *mut DWORD) -> HRESULT {
    let mut stream: *mut stream = core::ptr::null_mut();
    let mut id: DWORD = 0;
    let mut hr: HRESULT = 0;
    if mf_array_reserve(
        core::ptr::addr_of_mut!((*writer).streams.items) as *mut *mut core::ffi::c_void,
        core::ptr::addr_of_mut!((*writer).streams.capacity),
        (*writer).streams.count.wrapping_add(1),
        core::mem::size_of::<stream>() as size_t,
    ) == 0
    {
        return E_OUTOFMEMORY;
    }
    hr = IMFStreamSink_GetIdentifier(stream_sink, core::ptr::addr_of_mut!(id));
    if hr < 0 {
        return hr;
    }
    let fresh15 = (*writer).streams.count;
    (*writer).streams.count = (*writer).streams.count.wrapping_add(1);
    *index = fresh15 as DWORD;
    stream = (*writer).streams.items.offset(*index as isize);
    memset(
        stream as *mut core::ffi::c_void,
        0,
        core::mem::size_of::<stream>() as size_t,
    );
    (*stream).stream_sink = stream_sink;
    IMFStreamSink_AddRef(stream_sink);
    (*stream).stats.cb = core::mem::size_of::<MF_SINK_WRITER_STATISTICS>() as DWORD;
    list_init(core::ptr::addr_of_mut!((*stream).queue));
    (*writer).streams.next_id = max!((*writer).streams.next_id, id);
    return hr;
}

unsafe extern "system" fn sink_writer_AddStream(
    iface: *mut IMFSinkWriterEx,
    media_type: *mut IMFMediaType,
    index: *mut DWORD,
) -> HRESULT {
    let writer: *mut sink_writer = impl_from_IMFSinkWriterEx(iface);
    let mut hr: HRESULT = MF_E_INVALIDREQUEST;
    let mut stream_sink: *mut IMFStreamSink = core::ptr::null_mut();
    let mut id: DWORD = 0;

    TRACE!("%p, %p, %p.\n", iface, media_type, index);

    if media_type.is_null() {
        return E_INVALIDARG;
    }

    if index.is_null() {
        return E_POINTER;
    }

    EnterCriticalSection(core::ptr::addr_of_mut!((*writer).cs));

    if (*writer).state == SINK_WRITER_STATE_INITIAL {
        id = (*writer).streams.next_id.wrapping_add(1);
        hr = IMFMediaSink_AddStreamSink((*writer).sink, id, media_type, core::ptr::addr_of_mut!(stream_sink));
        if hr >= 0 {
            hr = sink_writer_add_stream(writer, stream_sink, index);
            if hr < 0 {
                IMFMediaSink_RemoveStreamSink((*writer).sink, id);
            }
        }
    }

    LeaveCriticalSection(core::ptr::addr_of_mut!((*writer).cs));

    return hr;
}
