unsafe extern "C" fn sink_writer_flush(writer: *mut sink_writer, index: ::core::ffi::c_uint) -> HRESULT {
    let mut stream: *mut stream = ::core::ptr::null_mut::<stream>();
    stream = sink_writer_get_stream(writer, index as DWORD);
    if stream.is_null() {
        return MF_E_INVALIDSTREAMNUMBER;
    }
    sink_writer_drop_pending_items(stream);
    IMFStreamSink_Flush((*stream).stream_sink);
    if !(*stream).converter.is_null() {
        IMFTransform_ProcessMessage(
            (*stream).converter,
            MFT_MESSAGE_COMMAND_FLUSH,
            0 as ULONG_PTR,
        );
    }
    if !(*stream).encoder.is_null() {
        IMFTransform_ProcessMessage(
            (*stream).encoder,
            MFT_MESSAGE_COMMAND_FLUSH,
            0 as ULONG_PTR,
        );
    }
    return sink_writer_place_marker(
        writer,
        stream,
        MFSTREAMSINK_MARKER_ENDOFSEGMENT as ::core::ffi::c_uint,
        0 as LONGLONG,
        core::ptr::null_mut(),
    );
}

unsafe extern "C" fn sink_writer_process_sample(
    mut writer: *mut sink_writer,
    mut stream: *mut stream,
) -> HRESULT {
    let mut item: *mut pending_item = core::ptr::null_mut::<pending_item>();
    let mut next: *mut pending_item = core::ptr::null_mut::<pending_item>();
    let mut timestamp: LONGLONG = 0;
    let mut sample: *mut IMFSample = core::ptr::null_mut::<IMFSample>();
    let mut hr: HRESULT = 0;

    if list_empty(&raw mut (*stream).queue) != 0 {
        return S_OK;
    }
    item = (list_head(&raw mut (*stream).queue) as *mut core::ffi::c_char).offset(
        -(core::mem::offset_of!(pending_item, entry) as core::ffi::c_ulonglong
            as isize),
    ) as *mut pending_item;
    if (*item).sample.is_null() {
        return S_OK;
    }

    sample = (*item).sample;
    IMFSample_AddRef(sample);
    sink_writer_release_pending_item(item);

    (*writer).stats.dwNumOutstandingSinkSampleRequests = (*writer)
        .stats
        .dwNumOutstandingSinkSampleRequests
        .wrapping_sub(1);
    (*stream).stats.dwNumOutstandingSinkSampleRequests = (*stream)
        .stats
        .dwNumOutstandingSinkSampleRequests
        .wrapping_sub(1);

    hr = IMFSample_GetSampleTime(sample, &raw mut timestamp);
    if hr < 0 {
        IMFSample_Release(sample);
        (*writer).status = hr;
        return S_OK;
    }

    (*writer).stats.llLastTimestampProcessed = timestamp;
    (*stream).stats.llLastTimestampProcessed = timestamp;

    hr = IMFStreamSink_ProcessSample((*stream).stream_sink, sample);
    IMFSample_Release(sample);
    if (hr) < 0 {
        return hr;
    }

    item = ((*stream).queue.next as *mut core::ffi::c_char).offset(
        -(core::mem::offset_of!(pending_item, entry) as core::ffi::c_ulonglong
            as isize),
    ) as *mut pending_item;
    next = ((*item).entry.next as *mut core::ffi::c_char).offset(
        -(core::mem::offset_of!(pending_item, entry) as core::ffi::c_ulonglong
            as isize),
    ) as *mut pending_item;
    while &raw mut (*item).entry != &raw mut (*stream).queue {
        if !(*item).sample.is_null() {
            break;
        }
        sink_writer_place_marker(
            writer,
            stream,
            (*item).marker_type,
            (*item).timestamp,
            (*item).user_context,
        );
        sink_writer_release_pending_item(item);
        item = next;
        next = ((*item).entry.next as *mut core::ffi::c_char).offset(
            -(core::mem::offset_of!(pending_item, entry) as core::ffi::c_ulonglong
                as isize),
        ) as *mut pending_item;
    }

    return hr;
}

