#[no_mangle]
pub unsafe extern "C" fn WhoamiGetTokenInfo(tokenType: TOKEN_INFORMATION_CLASS) -> *mut VOID {
    let mut hToken: HANDLE = 0 as HANDLE;
    let mut dwLength: DWORD = 0 as DWORD;
    let mut pTokenInfo: *mut VOID = 0 as *mut VOID;

    if OpenProcessToken(GetCurrentProcess(), TOKEN_READ as DWORD, core::ptr::addr_of_mut!(hToken)) != 0 {
        GetTokenInformation(hToken,
                            tokenType,
                            core::ptr::null_mut(),
                            dwLength,
                            core::ptr::addr_of_mut!(dwLength));

        if GetLastError() == ERROR_INSUFFICIENT_BUFFER as DWORD {
            pTokenInfo = HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY as DWORD, dwLength as SIZE_T) as *mut VOID;
            if pTokenInfo.is_null() {
                ConPuts(StdErr, RUSTCONV_WSTR_A5B8F7B1ACE3.as_ptr());
                exit(1);
            }
        }

        if GetTokenInformation(hToken, tokenType,
                                 pTokenInfo as LPVOID,
                                 dwLength,
                                 core::ptr::addr_of_mut!(dwLength)) == 0
        {
            ConPrintf(StdErr, RUSTCONV_WSTR_F8D1E1A22BE4.as_ptr(), GetLastError());
            WhoamiFree(pTokenInfo);
            exit(1);
        }

        CloseHandle(hToken);
    }

    return pTokenInfo;
}
