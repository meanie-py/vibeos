#[no_mangle]
pub unsafe extern "C" fn WhoamiPrintHeader(HeaderId: UINT) {
    let mut Header: PCWSTR = core::ptr::null();
    let mut Length: DWORD = 0;

    if NoHeader != 0 || PrintFormat == csv {
        return;
    }

    Length = LoadStringW(
        core::ptr::null_mut(),
        HeaderId,
        core::ptr::addr_of_mut!(Header) as LPWSTR,
        0,
    ) as DWORD;
    if Length == 0 || Header.is_null() {
        return;
    }

    ConPrintf(StdOut, RUSTCONV_WSTR_45AADD1C99F5.as_ptr(), Length, Header);

    while Length != 0 {
        Length -= 1;
        ConPrintf(StdOut, RUSTCONV_WSTR_28276425D458.as_ptr());
    }

    ConPrintf(StdOut, RUSTCONV_WSTR_9D313EA1711F.as_ptr());
}
#[no_mangle]
pub unsafe extern "C" fn WhoamiAllocTable(Rows: UINT, Cols: UINT) -> *mut WhoamiTable {
    let mut pTable: *mut WhoamiTable = HeapAlloc(
        GetProcessHeap(),
        HEAP_ZERO_MEMORY as DWORD,
        core::mem::size_of::<WhoamiTable>() as SIZE_T
            + core::mem::size_of::<LPWSTR>() as SIZE_T * Rows as SIZE_T * Cols as SIZE_T,
    ) as *mut WhoamiTable;
    if pTable.is_null() {
        ConPuts(StdErr, RUSTCONV_WSTR_A2EF95718510.as_ptr() as PCWSTR);
        exit(1 as core::ffi::c_int);
    }

    (*pTable).Rows = Rows;
    (*pTable).Cols = Cols;

    return pTable;
}
#[no_mangle]
pub unsafe extern "C" fn WhoamiSetTable(pTable: *mut WhoamiTable, Entry: *mut WCHAR, Row: UINT, Col: UINT) {
    let mut Target: LPWSTR = HeapAlloc(
        GetProcessHeap(),
        HEAP_ZERO_MEMORY,
        ((wcslen(Entry) as SIZE_T) + (1 as SIZE_T))
            * (core::mem::size_of_val(&*Entry.offset(0 as isize)) as SIZE_T),
    ) as LPWSTR;
    if Target.is_null() {
        ConPuts(StdErr, RUSTCONV_WSTR_41D8181DCDB8.as_ptr());
        exit(1);
    }

    wcscpy(Target, Entry);

    // C's `LPWSTR Content[1]` is a struct-hack tail over-allocated by AllocTable; Rust's
    // `[_; 1]` is bounds-checked, so index it through the pointer as the C does.
    (*pTable)
        .Content
        .as_mut_ptr()
        .add(Row.wrapping_mul((*pTable).Cols).wrapping_add(Col) as usize)
        .write(Target);
}
