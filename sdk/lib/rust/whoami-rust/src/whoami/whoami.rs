#[no_mangle]
pub unsafe extern "C" fn GetArgument(arg: *const WCHAR, argc: i32, argv: *mut *mut WCHAR) -> BOOL {
    let mut i: i32;

    if arg.is_null() {
        return FALSE;
    }

    i = 1;
    while i < argc {
        if _wcsicmp(*argv.offset(i as isize), arg) == 0 {
            return TRUE;
        }
        i += 1;
    }

    return FALSE;
}
