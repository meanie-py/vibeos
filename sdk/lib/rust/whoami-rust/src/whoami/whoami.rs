#[no_mangle]
pub unsafe extern "C" fn WhoamiGetUser(NameFormat: EXTENDED_NAME_FORMAT) -> LPWSTR {
    let mut UsrBuf: LPWSTR = HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY as DWORD, MAX_PATH as SIZE_T) as LPWSTR;
    let mut UsrSiz: ULONG = MAX_PATH as ULONG;

    if UsrBuf.is_null() {
        return core::ptr::null_mut();
    }

    if GetUserNameExW(NameFormat, UsrBuf, core::ptr::addr_of_mut!(UsrSiz)) != 0 {
        LCMapStringW(LOCALE_USER_DEFAULT as DWORD, LCMAP_LOWERCASE as DWORD, UsrBuf as LPCWSTR, UsrSiz as core::ffi::c_int, UsrBuf, MAX_PATH as core::ffi::c_int);
        return UsrBuf;
    }

    HeapFree(GetProcessHeap(), 0 as DWORD, UsrBuf as PVOID);
    return core::ptr::null_mut();
}
