#[no_mangle]
pub unsafe extern "C" fn PopulateWdmDeviceList(DeviceType: MMDEVICE_TYPE) -> MMRESULT {
    let mut Result: MMRESULT;
    let mut DeviceCount: DWORD = 0;
    let mut SoundDevice: PSOUND_DEVICE = core::ptr::null_mut();
    let mut FuncTable: MMFUNCTION_TABLE = core::mem::zeroed();
    let mut i: DWORD;

    VALIDATE_MMSYS_PARAMETER!(IS_VALID_SOUND_DEVICE_TYPE!(DeviceType));

    Result = WdmAudGetNumWdmDevsByMMixer(DeviceType, core::ptr::addr_of_mut!(DeviceCount));

    if ((MMSUCCESS!(Result)) == 0) {
        SND_ERR!(RUSTCONV_WSTR_76AEFE993746.as_ptr(), Result);
        return TranslateInternalMmResult(Result);
    }

    SND_TRACE!(RUSTCONV_WSTR_EFC489852957.as_ptr(), DeviceCount, DeviceType);

    i = 0;
    while i < DeviceCount {
        Result = ListSoundDevice(DeviceType, UlongToPtr!(i), core::ptr::addr_of_mut!(SoundDevice));

        if ((MMSUCCESS!(Result)) == 0) {
            SND_ERR!(RUSTCONV_WSTR_1689E5402E6B.as_ptr(), Result);
            return TranslateInternalMmResult(Result);
        }

        /* Set up our function table */
        ZeroMemory!(core::ptr::addr_of_mut!(FuncTable) as *mut core::ffi::c_void, core::mem::size_of::<MMFUNCTION_TABLE>() as usize);
        FuncTable.__bindgen_anon_1.GetCapabilities = Some(WdmAudGetCapabilitiesByMMixer);
        FuncTable.QueryWaveFormatSupport = Some(QueryWdmWaveDeviceFormatSupport); //FIXME
        FuncTable.Open = Some(WdmAudOpenSoundDeviceByMMixer);
        FuncTable.Close = Some(WdmAudCloseSoundDeviceByMMixer);
        FuncTable.GetDeviceInterfaceString = Some(WdmAudGetDeviceInterfaceStringByMMixer);

        if (DeviceType) as u32 == AUX_DEVICE_TYPE || (DeviceType) as u32 == MIDI_OUT_DEVICE_TYPE || (DeviceType) as u32 == WAVE_OUT_DEVICE_TYPE
        {
            FuncTable.GetVolume = Some(WdmAudGetVolumeByMMixer);
            FuncTable.SetVolume = Some(WdmAudSetVolumeByMMixer);
        }

        if (DeviceType) as u32 == MIXER_DEVICE_TYPE
        {
            FuncTable.SetWaveFormat = Some(WdmAudSetMixerDeviceFormatByMMixer);
            FuncTable.QueryMixerInfo = Some(WdmAudQueryMixerInfoByMMixer);
        }
        else if (DeviceType) as u32 == WAVE_IN_DEVICE_TYPE || (DeviceType) as u32 == WAVE_OUT_DEVICE_TYPE
        {
            FuncTable.SetWaveFormat = Some(WdmAudSetWaveDeviceFormatByMMixer);
            FuncTable.SetState = Some(WdmAudSetWaveStateByMMixer);
            FuncTable.ResetStream = Some(WdmAudResetStreamByMMixer);
            FuncTable.GetPos = Some(WdmAudGetWavePositionByMMixer);

            // #ifndef USERMODE_MIXER (USERMODE_MIXER is not defined in this file)
            FuncTable.CommitWaveBuffer = Some(WdmAudCommitWaveBufferByMMixer);
        }
        else if (DeviceType) as u32 == MIDI_IN_DEVICE_TYPE || (DeviceType) as u32 == MIDI_OUT_DEVICE_TYPE
        {
            FuncTable.SetWaveFormat = Some(WdmAudSetMixerDeviceFormatByMMixer);
            FuncTable.SetState = Some(WdmAudSetWaveStateByMMixer);
            FuncTable.GetPos = Some(WdmAudGetWavePositionByMMixer);
        }

        SetSoundDeviceFunctionTable(SoundDevice, core::ptr::addr_of_mut!(FuncTable));
        i = i.wrapping_add(1);
    }

    return MMSYSERR_NOERROR;
}

#[no_mangle]
pub unsafe extern "system" fn DriverProc(
    DriverId: DWORD,
    DriverHandle: HANDLE,
    Message: UINT,
    Parameter1: LONG,
    Parameter2: LONG,
) -> LONG {
    if Message == DRV_LOAD {
        let mut Handle: HANDLE = core::ptr::null_mut();
        let mut Result: MMRESULT = 0;
        SND_TRACE!(RUSTCONV_WSTR_5D01A5B78EB7.as_ptr());

        Result = InitEntrypointMutexes();

        if ((MMSUCCESS!(Result)) == 0) {
            return 0;
        }

        Result = WdmAudOpenSoundDeviceByMMixer(core::ptr::null_mut(), core::ptr::addr_of_mut!(Handle));

        if Result != MMSYSERR_NOERROR {
            SND_ERR!(RUSTCONV_WSTR_582E20CDA92B.as_ptr());
            //UnlistAllSoundDevices();

            return 0;
        }

        /* Populate the device lists */
        SND_TRACE!(RUSTCONV_WSTR_B1AAD380DBBB.as_ptr());
        PopulateWdmDeviceList((WAVE_OUT_DEVICE_TYPE) as MMDEVICE_TYPE);
        PopulateWdmDeviceList((WAVE_IN_DEVICE_TYPE) as MMDEVICE_TYPE);
        PopulateWdmDeviceList((MIDI_OUT_DEVICE_TYPE) as MMDEVICE_TYPE);
        PopulateWdmDeviceList((MIDI_IN_DEVICE_TYPE) as MMDEVICE_TYPE);
        PopulateWdmDeviceList((AUX_DEVICE_TYPE) as MMDEVICE_TYPE);
        PopulateWdmDeviceList((MIXER_DEVICE_TYPE) as MMDEVICE_TYPE);

        SND_TRACE!(RUSTCONV_WSTR_314F1653C099.as_ptr());

        return 1;
    } else if Message == DRV_FREE {
        SND_TRACE!(RUSTCONV_WSTR_D467FF4035C9.as_ptr());

        WdmAudCleanupByMMixer();

        /* TODO: Clean up the path names! */
        UnlistAllSoundDevices();

        CleanupEntrypointMutexes();

        SND_TRACE!(RUSTCONV_WSTR_E99F1AAC72E2.as_ptr(), GetMemoryAllocationCount());

        return 1;
    } else if Message == DRV_ENABLE || Message == DRV_DISABLE {
        SND_TRACE!(RUSTCONV_WSTR_220C76FC1E6A.as_ptr());
        return 1;
    } else if Message == DRV_OPEN || Message == DRV_CLOSE {
        SND_TRACE!(RUSTCONV_WSTR_8602B7F97D14.as_ptr());
        return 1;
    } else if Message == DRV_QUERYCONFIGURE {
        SND_TRACE!(RUSTCONV_WSTR_25615BA52EBA.as_ptr());
        return 0;
    } else if Message == DRV_CONFIGURE {
        return (DRVCNF_OK) as LONG;
    } else {
        SND_TRACE!(RUSTCONV_WSTR_38958393DA7B.as_ptr(), Message);
        return (DefDriverProc(
            (DriverId) as DWORD_PTR,
            (DriverHandle).cast(),
            Message,
            (Parameter1) as LPARAM,
            (Parameter2) as LPARAM,
        )) as LONG;
    }
}

