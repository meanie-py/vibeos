// WINE_DEFAULT_DEBUG_CHANNEL(dinput): debug-channel macro, expanded by the caller's logging setup.
// static const IDirectInputDevice8AVtbl SysMouseAvt / IDirectInputDevice8WVtbl SysMouseWvt: COM vtables, generated by vtbl_gen.py.

pub const WINE_MOUSE_X_AXIS_INSTANCE: i32 = 0;
pub const WINE_MOUSE_Y_AXIS_INSTANCE: i32 = 1;
pub const WINE_MOUSE_Z_AXIS_INSTANCE: i32 = 2;
pub const WINE_MOUSE_BUTTONS_INSTANCE: i32 = 3;

pub type WARP_MOUSE = i32;
pub const WARP_DEFAULT: WARP_MOUSE = 0;
pub const WARP_DISABLE: WARP_MOUSE = 1;
pub const WARP_FORCE_ON: WARP_MOUSE = 2;

#[repr(C)]
pub struct SysMouseImpl {
    pub base: IDirectInputDeviceImpl,

    /* SysMouseAImpl */
    /* These are used in case of relative -> absolute transitions */
    pub org_coords: POINT,
    pub clipped: BOOL,
    /* warping: whether we need to move mouse back to middle once we
     * reach window borders (for e.g. shooters, "surface movement" games) */
    pub need_warp: BOOL,
    pub last_warped: DWORD,

    /* This is for mouse reporting. */
    pub m_state: DIMOUSESTATE2,

    pub warp_override: WARP_MOUSE,
}

unsafe extern "C" fn impl_from_IDirectInputDevice8A(
    iface: *mut IDirectInputDevice8A,
) -> *mut SysMouseImpl {
    return ((iface as usize).wrapping_sub(
        core::mem::offset_of!(IDirectInputDeviceImpl, IDirectInputDevice8A_iface),
    ) as *mut IDirectInputDeviceImpl as usize)
        .wrapping_sub(core::mem::offset_of!(SysMouseImpl, base))
        as *mut SysMouseImpl;
}

unsafe extern "C" fn impl_from_IDirectInputDevice8W(
    iface: *mut IDirectInputDevice8W,
) -> *mut SysMouseImpl {
    let inner: *mut IDirectInputDeviceImpl = CONTAINING_RECORD!(iface, IDirectInputDeviceImpl, IDirectInputDevice8W_iface);
    return CONTAINING_RECORD!(inner, SysMouseImpl, base);
}

unsafe extern "C" fn IDirectInputDevice8W_from_impl(This: *mut SysMouseImpl) -> *mut IDirectInputDevice8W {
    return core::ptr::addr_of_mut!((*This).base.IDirectInputDevice8W_iface);
}

unsafe extern "C" fn _dump_mouse_state(m_state: *const DIMOUSESTATE2) {
    let mut i: ::core::ffi::c_int;

    if ((TRACE_ON!(__wine_dbch_dinput)) == 0) { return; }

    i = 0;
    while i < 5 {
        TRACE!(" B%d: %02x", i, (*m_state).rgbButtons[i as usize] as core::ffi::c_uint);
        i += 1;
    }
}

unsafe extern "C" fn fill_mouse_dideviceinstanceA(lpddi: LPDIDEVICEINSTANCEA, version: DWORD) {
    let mut dwSize: DWORD;
    let mut ddi: DIDEVICEINSTANCEA = core::mem::zeroed();

    dwSize = (*lpddi).dwSize;

    memset(
        lpddi as *mut core::ffi::c_void,
        0 as core::ffi::c_int,
        dwSize as usize,
    );
    memset(
        core::ptr::addr_of_mut!(ddi) as *mut core::ffi::c_void,
        0 as core::ffi::c_int,
        core::mem::size_of::<DIDEVICEINSTANCEA>() as usize,
    );

    ddi.dwSize = dwSize;
    ddi.guidInstance = GUID_SysMouse;
    ddi.guidProduct = GUID_SysMouse;
    if version >= 0x0800 {
        ddi.dwDevType = DI8DEVTYPE_MOUSE | (DI8DEVTYPEMOUSE_TRADITIONAL << 8);
    } else {
        ddi.dwDevType = DIDEVTYPE_MOUSE | (DIDEVTYPEMOUSE_TRADITIONAL << 8);
    }
    strcpy(
        core::ptr::addr_of_mut!(ddi.tszInstanceName) as *mut i8,
        b"Mouse\0".as_ptr() as *const i8,
    );
    strcpy(
        core::ptr::addr_of_mut!(ddi.tszProductName) as *mut i8,
        b"Wine Mouse\0".as_ptr() as *const i8,
    );

    memcpy(
        lpddi as *mut core::ffi::c_void,
        core::ptr::addr_of_mut!(ddi) as *const core::ffi::c_void,
        if (dwSize as usize) < core::mem::size_of::<DIDEVICEINSTANCEA>() {
            dwSize as usize
        } else {
            core::mem::size_of::<DIDEVICEINSTANCEA>()
        },
    );
}

