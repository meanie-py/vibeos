unsafe extern "C" fn InstallFiles(SourceDirBase: &CStringW, Spec: &CStringW, DestinationDir: &CStringW) -> BOOL {
    let Info: &mut InstallInfo = &mut *(g_pInfo as *mut InstallInfo);
    let mut sourcedir = CStringW::new();
    let mut filespec = CStringW::new();
    filespec = SplitFileAndDirectory(Spec.GetString(), &mut sourcedir); // Split "[OptionalDir\]*.ext"
    sourcedir = BuildPath__T0(SourceDirBase, (&sourcedir).GetString());
    let mut success: BOOL = (TRUE as i32);
    let mut wfd: WIN32_FIND_DATAW = core::mem::zeroed();
    let hFind = FindFirstFileW(BuildPath__T0(&sourcedir, (&filespec).GetString()).GetString(), (core::ptr::addr_of_mut!(wfd)).cast());
    if hFind == INVALID_HANDLE_VALUE
    {
        let error: DWORD = GetLastError();
        if error == ERROR_FILE_NOT_FOUND
        {
            return (TRUE) as BOOL;
        }
        else
        {
            return (ErrorBox__1(error) == 0) as BOOL;
        }
    }

    loop
    {
        let from = BuildPath__T0(&sourcedir, wfd.cFileName.as_ptr());
        let to = BuildPath__T0(DestinationDir, wfd.cFileName.as_ptr());
        let uninstpath = to.Mid((Info.InstallDirLen.wrapping_sub(1)) as i32);
        if (wfd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY) != 0
        {
            let p: LPWSTR = wfd.cFileName.as_mut_ptr();
            let dots: BOOL = (*p.offset(0 as isize) == '.' as u16
                && (*p.offset(1 as isize) == 0
                    || (*p.offset(1 as isize) == '.' as u16
                        && *p.offset(2 as isize) == 0))) as BOOL;
            if dots == 0
            {
                Info.__base0.Error = CreateDirectoryTree((&to).GetString());
                if Info.__base0.Error != 0
                {
                    success = (ErrorBox__1(Info.__base0.Error) == 0) as BOOL;
                }

                if success != 0
                {
                    success = InstallFiles(&from, &filespec, &to);
                }
                AddEntry((UNOP_EMPTYDIR) as WCHAR, uninstpath.GetString());
            }
        }
        else
        {
            success = MoveFileEx(from.GetString(), to.GetString(), MOVEFILE_COPY_ALLOWED | MOVEFILE_REPLACE_EXISTING);
            if success != 0
            {
                if Info.MainApp.IsEmpty()
                {
                    Info.MainApp = to;
                }
                success = AddEntry((UNOP_FILE) as WCHAR, uninstpath.GetString());
            }
            else
            {
                ErrorBox__1(GetLastError());
            }
            SendMessage((*g_pInfo).hDlg, IM_PROGRESS, 0, 0);
        }

        if success == 0 || FindNextFileW(hFind, (core::ptr::addr_of_mut!(wfd)).cast()) == 0
        {
            break;
        }
    }
    FindClose(hFind);
    return success;
}

