#[no_mangle]
pub unsafe extern "C" fn Move(dwLen: DWORD, pData: *mut PBYTE, dwSize: *mut DWORD) -> BOOL {
    if *dwSize < dwLen {
        return (FALSE) as BOOL;
    }

    *pData = (*pData).add(dwLen as usize);
    *dwSize -= dwLen;

    return (TRUE) as BOOL;
}
#[no_mangle]
pub unsafe extern "C" fn ParseTag(pData: *mut PBYTE, dwSize: *mut DWORD, dwTagAndClass: *mut DWORD) -> BOOL {
    if *dwSize == 0 {
        return (FALSE) as BOOL;
    }

    /* Is this a long form? */
    if (*(*pData).add(0 as usize) & 0x1f) != 0x1f {
        /* No, so extract the tag and class (in one identifier) */
        *dwTagAndClass = *(*pData).add(0 as usize) as DWORD;
        return Move(1, pData, dwSize);
    }

    let dwClass: DWORD = ((*(*pData).add(0 as usize) & 0xE0) as DWORD) >> 5;
    *dwTagAndClass = 0;
    let mut n: DWORD = 1;
    while n < *dwSize {
        *dwTagAndClass <<= 7;
        *dwTagAndClass |= (*(*pData).add(n as usize) & 0x7f) as DWORD;

        if (*(*pData).add(n as usize) & 0x80) == 0 {
            break;
        }
        n += 1;
    }

    Move(n, pData, dwSize);

    /* Any number bigger than this, we shift data out! */
    if n > 4 {
        return (FALSE) as BOOL;
    }

    /* Just drop this in the hightest bits*/
    *dwTagAndClass |= dwClass << (32 - 3);

    return (TRUE) as BOOL;
}
#[no_mangle]
pub unsafe extern "C" fn ParseLength(pData: *mut PBYTE, dwSize: *mut DWORD, dwLength: *mut DWORD) -> BOOL {
    if *dwSize == 0 {
        return (FALSE) as BOOL;
    }

    if (((*(*pData).add(0 as usize)) as DWORD) & 0x80) == 0 {
        *dwLength = (*(*pData).add(0 as usize)) as DWORD;
        return Move(1, pData, dwSize);
    }

    let dwBytes: DWORD = ((*(*pData).add(0 as usize)) as DWORD) & 0x7f;
    if dwBytes == 0 || dwBytes > 8 || dwBytes + 1 > *dwSize {
        return (FALSE) as BOOL;
    }

    *dwLength = 0;
    let mut n: DWORD = 0;
    while n < dwBytes {
        *dwLength <<= 8;
        *dwLength += (*(*pData).add((1 + n) as usize)) as DWORD;
        n += 1;
    }

    return Move(dwBytes + 1, pData, dwSize);
}
#[no_mangle]
pub unsafe extern "C" fn HexDump(pRoot: PBYTE, mut pData: PBYTE, mut dwSize: DWORD, wszPrefix: PWSTR) -> DWORD {
    loop {
        let Address: SIZE_T = pData.offset_from(pRoot) as SIZE_T;
        ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_906CA7CC2D3F.as_ptr(), Address);
        ConPuts(core::ptr::addr_of_mut!(csStdOut), wszPrefix);

        let mut n: DWORD = 0;
        while n < min!(dwSize, 0x10) {
            ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_A75A9106944B.as_ptr(), *pData.add(n as usize) as core::ffi::c_uint);
            n += 1;
        }

        if dwSize <= 0x10 {
            break;
        }

        Move(0x10, core::ptr::addr_of_mut!(pData), core::ptr::addr_of_mut!(dwSize));
        ConPuts(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_075DE2B906DB.as_ptr());
    }

    3 * dwSize
}
#[no_mangle]
pub unsafe extern "C" fn PrintTag(pRoot: PBYTE, pHeader: PBYTE, dwTag: DWORD, dwTagLength: DWORD, pData: PBYTE, wszPrefix: PWSTR) {
    let dwRemainder: DWORD = HexDump(pRoot, pHeader, pData.offset_from(pHeader) as DWORD, wszPrefix);

    let wszTag: LPCWSTR = TagToName(dwTag);
    let mut dwPadding: usize = dwRemainder as usize + wcslen(wszPrefix);
    while dwPadding > 50 {
        dwPadding -= 50;
    }
    ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_37E307B51D86.as_ptr(), 50 - dwPadding, CPP_COM_WSTR_96A296D224F2.as_ptr(), wszTag, dwTagLength);
}

#[no_mangle]
pub unsafe extern "system" fn CryptOIDEnumCallback(pInfo: PCCRYPT_OID_INFO, pvArg: *mut core::ffi::c_void) -> BOOL {
    let Names: *mut OID_NAMES = pvArg as *mut OID_NAMES;

    if !pInfo.is_null() && !(*pInfo).pszOID.is_null() && _stricmp((*pInfo).pszOID, (*Names).Oid) == 0 {
        if ((*Names).NumberOfNames as usize) < (RTL_NUMBER_OF!((*Names).Names) as usize) {
            let mut n: DWORD = 0;
            while n < (*Names).NumberOfNames {
                // We already have this..
                if _wcsicmp((*Names).Names[n as usize], (*pInfo).pwszName) == 0 {
                    return (TRUE) as BOOL;
                }
                n += 1;
            }

            let idx: usize = (*Names).NumberOfNames as usize;
            (*Names).NumberOfNames += 1;
            (*Names).Names[idx] = (*pInfo).pwszName;
        }
    }

    return (TRUE) as BOOL;
}
#[no_mangle]
pub unsafe extern "C" fn PrintOID(pRoot: PBYTE, pHeader: PBYTE, pData: PBYTE, dwSize: DWORD, wszPrefix: PWSTR) {
    /* CryptFindOIDInfo expects the OID to be in ANSI.. */
    let mut szOID: [CHAR; 250] = [0 as CHAR; 250];
    let mut ptr: *mut CHAR = szOID.as_mut_ptr();
    let mut cchRemaining: usize = (RTL_NUMBER_OF!(szOID)) as usize;

    /* CryptFindOIDInfo just returns the first, we want multiple */
    let mut Names: OID_NAMES = core::mem::zeroed();

    if dwSize == 0 {
        return;
    }

    let mut dwValue: DWORD = 0;
    let mut count: DWORD = 0;
    let mut n: DWORD = 0;
    'for_n: while n < dwSize {
        'body: {
            dwValue <<= 7;
            dwValue |= (*pData.add(n as usize) as DWORD) & 0x7f;

            if (*pData.add(n as usize) as DWORD) & 0x80 != 0 {
                count += 1;
                if count >= 4 {
                    break 'for_n;
                }
                break 'body; /* continue */
            }
            count = 0;

            /* First & second octet have a special encoding */
            if ptr == szOID.as_mut_ptr() {
                let mut id1: DWORD = dwValue / 40;
                let mut id2: DWORD = dwValue % 40;

                /* The first one can only be 0, 1 or 2, so handle special case: tc24.ber */
                if id1 > 2 {
                    id2 += (id1 - 2) * 40;
                    id1 = 2;
                }
                StringCchPrintfExA!(ptr, cchRemaining, core::ptr::addr_of_mut!(ptr), core::ptr::addr_of_mut!(cchRemaining), 0, b"%d.%d\0".as_ptr() as *const i8, id1, id2);
            } else {
                StringCchPrintfExA!(ptr, cchRemaining, core::ptr::addr_of_mut!(ptr), core::ptr::addr_of_mut!(cchRemaining), 0, b".%d\0".as_ptr() as *const i8, dwValue);
            }

            dwValue = 0;
        }
        n += 1;
    }

    if dwValue != 0 || count != 0 {
        /* We cannot format this, so just add abort */
        return;
    }

    let Address: usize = (pData as usize).wrapping_sub(pRoot as usize);
    /* Pad with spaces instead of printing the address again */
    let addrDigits: DWORD = (log10(Address as f64) as DWORD) + 1;
    ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_2EB084F01744.as_ptr(), max!(addrDigits, 4), CPP_COM_WSTR_96A296D224F2.as_ptr());
    ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_69550BA864B8.as_ptr(), wszPrefix, szOID.as_mut_ptr());

    Names.Oid = szOID.as_mut_ptr();

    /* The order does not match a naive call with '0'... */
    CryptEnumOIDInfo(0, 0, (core::ptr::addr_of_mut!(Names)).cast(), Some(CryptOIDEnumCallback));

    let mut n: DWORD = 0;
    while n < Names.NumberOfNames {
        if n == 0 {
            ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_DEEFE3BC3DD3.as_ptr(), Names.Names[n as usize]);
        } else if n == 1 {
            ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_A0D8D64F1658.as_ptr(), Names.Names[n as usize]);
        } else {
            ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_8ED4D495E704.as_ptr(), Names.Names[n as usize]);
        }
        n += 1;
    }

    ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_4BA5D7E4F16E.as_ptr(), if Names.NumberOfNames > 1 { CPP_COM_WSTR_4F2D892D6AF4.as_ptr() } else { CPP_COM_WSTR_96A296D224F2.as_ptr() });
}
#[no_mangle]
pub unsafe extern "C" fn ParseAsn(pRoot: PBYTE, mut pData: PBYTE, mut dwSize: DWORD, wszPrefix: PWSTR, fPrint: BOOL) -> BOOL {
    while dwSize != 0 {
        let pHeader: PBYTE = pData;
        let mut dwTagAndClass: DWORD = 0;

        if ParseTag(&mut pData, &mut dwSize, &mut dwTagAndClass) == 0 {
            if fPrint != 0 {
                ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_735F76E46DCD.as_ptr(), pHeader.offset_from(pRoot) as DWORD);
            }
            return (FALSE) as BOOL;
        }

        let mut dwTagLength: DWORD = 0;
        if ParseLength(&mut pData, &mut dwSize, &mut dwTagLength) == 0 {
            if fPrint != 0 {
                ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_BC84C9749F05.as_ptr(), pHeader.offset_from(pRoot) as DWORD);
            }
            return (FALSE) as BOOL;
        }

        if dwTagLength > dwSize {
            if fPrint != 0 {
                ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_A5AAC1784C83.as_ptr(), pHeader.offset_from(pRoot) as DWORD);
            }
            return (FALSE) as BOOL;
        }

        if fPrint != 0 {
            PrintTag(pRoot, pHeader, dwTagAndClass, dwTagLength, pData, wszPrefix);
        }

        let len: usize = wcslen(wszPrefix);
        StringCchCatW(wszPrefix, (MAX_PATH) as _, if dwTagLength != dwSize { CPP_COM_WSTR_18CC9F853E29.as_ptr() } else { CPP_COM_WSTR_2DD11AA35112.as_ptr() });

        if (dwTagAndClass & (ASN_TAG_IS_CONSTRUCTED as u32)) != 0 {
            if ParseAsn(pRoot, pData, dwTagLength, wszPrefix, fPrint) == 0 {
                return (FALSE) as BOOL;
            }
        } else {
            if fPrint != 0 {
                /* Special case for a bit string / octet string */
                if ((dwTagAndClass == (ASN_TAG_BITSTRING as u32)) || (dwTagAndClass == (ASN_TAG_OCTET_STRING as u32))) && dwTagLength != 0 {
                    if dwTagAndClass == (ASN_TAG_BITSTRING as u32) {
                        /* First, we print the 'unused bits' field of the bit string */
                        HexDump(pRoot, pData, 1, wszPrefix);
                        ConPuts(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_075DE2B906DB.as_ptr());

                        /* Move past it */
                        Move(1, &mut pData, &mut dwSize);
                        dwTagLength -= 1;
                    }

                    /* Do we have any data left? */
                    if dwTagLength != 0 {
                        /* Try to parse this as ASN */
                        if ParseAsn(pRoot, pData, dwTagLength, wszPrefix, (FALSE) as BOOL) != 0 {
                            /* We succeeded, this _could_ be ASN, so display it as if it is */
                            if ParseAsn(pRoot, pData, dwTagLength, wszPrefix, (TRUE) as BOOL) == 0 {
                                /* Uhhh, did someone edit the data? */
                                ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_AE70862B0FA8.as_ptr(), pData.offset_from(pRoot) as DWORD);
                                return (FALSE) as BOOL;
                            }

                            /* Move past what we just parsed */
                            Move(dwTagLength, &mut pData, &mut dwSize);
                            /* Lie about this so that we don't also print a hexdump */
                            dwTagLength = 0;
                        }
                    }
                }

                /* Is there any data (left) to print? */
                if dwTagLength != 0 {
                    HexDump(pRoot, pData, dwTagLength, wszPrefix);
                    ConPuts(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_075DE2B906DB.as_ptr());

                    StringCchCatW(wszPrefix, (MAX_PATH) as _, CPP_COM_WSTR_2DD11AA35112.as_ptr());

                    /* Do we have additional formatters? */
                    match (dwTagAndClass) as i32 {
                        ASN_TAG_OBJECT_ID => {
                            PrintOID(pRoot, pHeader, pData, dwTagLength, wszPrefix);
                        }
                        _ => {}
                    }
                }
            }
        }

        *wszPrefix.add(len) = 0;

        if Move(dwTagLength, &mut pData, &mut dwSize) == 0 {
            /* This should not be possible, it was checked before! */
            return (FALSE) as BOOL;
        }
    }

    (TRUE as i32)
}
#[no_mangle]
pub unsafe extern "C" fn asn_dump(Filename: LPCWSTR) -> BOOL {
    let hFile: HANDLE = CreateFileW(Filename, GENERIC_READ, FILE_SHARE_READ, core::ptr::null_mut(),
                               OPEN_EXISTING, FILE_FLAG_SEQUENTIAL_SCAN, core::ptr::null_mut());

    if hFile == INVALID_HANDLE_VALUE {
        ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_053C5322BBAA.as_ptr(), GetLastError());
        return (FALSE) as BOOL;
    }

    let dwSize: DWORD = GetFileSize(hFile, core::ptr::null_mut());
    if dwSize == INVALID_FILE_SIZE {
        ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_D9730048853C.as_ptr(), GetLastError());
        CloseHandle(hFile);
        return (FALSE) as BOOL;
    }

    if dwSize == 0 {
        ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_51AA504C9DA0.as_ptr());
        CloseHandle(hFile);
        return (FALSE) as BOOL;
    }

    let pData: PBYTE = LocalAlloc(0, dwSize as SIZE_T) as PBYTE;
    if pData.is_null() {
        ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_B81B777EEDDD.as_ptr(), GetLastError());
        CloseHandle(hFile);
        return (FALSE) as BOOL;
    }

    let mut cbRead: DWORD = 0;
    let fRead: BOOL = ReadFile(hFile, pData as LPVOID, dwSize, core::ptr::addr_of_mut!(cbRead), core::ptr::null_mut());
    let dwErr: DWORD = GetLastError();
    CloseHandle(hFile);

    if fRead == 0 || cbRead != dwSize {
        ConPrintf(core::ptr::addr_of_mut!(csStdOut), CPP_COM_WSTR_C927B4CA2CB8.as_ptr(), dwErr);
        LocalFree(pData as HLOCAL);
        return (FALSE) as BOOL;
    }

    let mut Buffer = [0u16; MAX_PATH as usize];
    let fSucceeded: BOOL = ParseAsn(pData, pData, dwSize, Buffer.as_mut_ptr(), (TRUE) as BOOL);

    LocalFree(pData as HLOCAL);
    return fSucceeded;
}

