unsafe extern "system" fn InputCleanup(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP
) -> NTSTATUS {
    let DevExt = (*DeviceObject).DeviceExtension as PINPUT_DEVICE_EXT;
    let FileObject = (*IoGetCurrentIrpStackLocation(Irp)).FileObject;
    let mut OldIrql: KIRQL = 0;
    let mut CancelList: LIST_ENTRY = core::mem::zeroed();
    let mut Entry: PLIST_ENTRY;
    let mut PendingIrp: PIRP;

    InitializeListHead(&mut CancelList);

    KeAcquireSpinLock(&mut (*DevExt).IrpLock, &mut OldIrql);
    Entry = (*DevExt).PendingIrps.Flink;
    while Entry != &mut (*DevExt).PendingIrps as PLIST_ENTRY {
        PendingIrp = (Entry as *mut u8).offset(-(core::mem::offset_of!(IRP, Tail.Overlay.__bindgen_anon_2.ListEntry) as isize)) as PIRP;
        Entry = (*Entry).Flink;
        if (*IoGetCurrentIrpStackLocation(PendingIrp)).FileObject == FileObject {
            RemoveEntryList(&mut (*PendingIrp).Tail.Overlay.__bindgen_anon_2.ListEntry);
            if IoSetCancelRoutine(PendingIrp, None) != None {
                InsertTailList(&mut CancelList, &mut (*PendingIrp).Tail.Overlay.__bindgen_anon_2.ListEntry);
            }
        }
    }
    KeReleaseSpinLock(&mut (*DevExt).IrpLock, OldIrql);

    while !IsListEmpty(&mut CancelList) {
        Entry = RemoveHeadList(&mut CancelList);
        PendingIrp = (Entry as *mut u8).offset(-(core::mem::offset_of!(IRP, Tail.Overlay.__bindgen_anon_2.ListEntry) as isize)) as PIRP;
        (*PendingIrp).IoStatus.__bindgen_anon_1.Status = STATUS_CANCELLED;
        (*PendingIrp).IoStatus.Information = 0;
        IoCompleteRequest(PendingIrp, IO_NO_INCREMENT);
    }

    (*Irp).IoStatus.__bindgen_anon_1.Status = STATUS_SUCCESS;
    (*Irp).IoStatus.Information = 0;
    IoCompleteRequest(Irp, IO_NO_INCREMENT);
    STATUS_SUCCESS
}

unsafe extern "system" fn InputRead(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP
) -> NTSTATUS {
    let DevExt = (*DeviceObject).DeviceExtension as PINPUT_DEVICE_EXT;
    let mut OldIrql: KIRQL = 0;

    if (*DevExt).IsKeyboard != 0 && RingHasData(DevExt) != 0 {
        let Data = RingPop(DevExt);
        let OutBuf = IrpOutputBuffer(Irp);
        if !OutBuf.is_null() {
            RtlCopyMemory(
                OutBuf,
                core::ptr::addr_of!(Data) as *const core::ffi::c_void,
                core::mem::size_of::<KEYBOARD_INPUT_DATA>()
            );
        }
        (*Irp).IoStatus.__bindgen_anon_1.Status = STATUS_SUCCESS;
        (*Irp).IoStatus.Information = core::mem::size_of::<KEYBOARD_INPUT_DATA>() as u64;
        IoCompleteRequest(Irp, IO_KEYBOARD_INCREMENT);
        return STATUS_SUCCESS;
    }

    if (*DevExt).IsKeyboard == 0 && MouRingHasData(DevExt) != 0 {
        let Data = MouRingPop(DevExt);
        let OutBuf = IrpOutputBuffer(Irp);
        if !OutBuf.is_null() {
            RtlCopyMemory(
                OutBuf,
                core::ptr::addr_of!(Data) as *const core::ffi::c_void,
                core::mem::size_of::<MOUSE_INPUT_DATA>()
            );
        }
        (*Irp).IoStatus.__bindgen_anon_1.Status = STATUS_SUCCESS;
        (*Irp).IoStatus.Information = core::mem::size_of::<MOUSE_INPUT_DATA>() as u64;
        IoCompleteRequest(Irp, IO_MOUSE_INCREMENT);
        return STATUS_SUCCESS;
    }

    IoMarkIrpPending(Irp);

    KeAcquireSpinLock(core::ptr::addr_of_mut!((*DevExt).IrpLock), core::ptr::addr_of_mut!(OldIrql));
    IoSetCancelRoutine(Irp, Some(InputCancelIrp));
    InsertTailList(
        core::ptr::addr_of_mut!((*DevExt).PendingIrps),
        core::ptr::addr_of_mut!((*Irp).Tail.Overlay.__bindgen_anon_2.ListEntry)
    );
    KeReleaseSpinLock(core::ptr::addr_of_mut!((*DevExt).IrpLock), OldIrql);

    STATUS_PENDING
}

unsafe extern "system" fn InputDeviceControl(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP
) -> NTSTATUS {
    let DevExt = (*DeviceObject).DeviceExtension as PINPUT_DEVICE_EXT;
    let IrpSp = IoGetCurrentIrpStackLocation(Irp);
    let mut Status: NTSTATUS = STATUS_NOT_SUPPORTED;
    let mut Information: ULONG_PTR = 0;

    if (*DevExt).IsKeyboard != 0 {
        match (*IrpSp).Parameters.DeviceIoControl.IoControlCode {
            IOCTL_ARM64INPUT_INJECT_BYTE => {
                if (*IrpSp).Parameters.DeviceIoControl.InputBufferLength >= 1 {
                    let pByte = (*Irp).AssociatedIrp.SystemBuffer as PUCHAR;
                    InjectByte(DevExt, *pByte);
                    Status = STATUS_SUCCESS;
                } else {
                    Status = STATUS_BUFFER_TOO_SMALL;
                }
            }

            IOCTL_KEYBOARD_QUERY_ATTRIBUTES => {
                if (*IrpSp).Parameters.DeviceIoControl.OutputBufferLength >= core::mem::size_of::<KEYBOARD_ATTRIBUTES>() as u32 {
                    let pAttr = (*Irp).AssociatedIrp.SystemBuffer as PKEYBOARD_ATTRIBUTES;
                    RtlZeroMemory(pAttr as *mut core::ffi::c_void, core::mem::size_of::<KEYBOARD_ATTRIBUTES>());
                    (*pAttr).KeyboardIdentifier.Type = 4;
                    (*pAttr).KeyboardIdentifier.Subtype = 0;
                    (*pAttr).NumberOfFunctionKeys = 12;
                    (*pAttr).NumberOfIndicators = 3;
                    (*pAttr).NumberOfKeysTotal = 101;
                    (*pAttr).InputDataQueueLength = 100;
                    (*pAttr).KeyRepeatMinimum.Rate = 2;
                    (*pAttr).KeyRepeatMinimum.Delay = 250;
                    (*pAttr).KeyRepeatMaximum.Rate = 30;
                    (*pAttr).KeyRepeatMaximum.Delay = 1000;
                    Status = STATUS_SUCCESS;
                    Information = core::mem::size_of::<KEYBOARD_ATTRIBUTES>() as ULONG_PTR;
                } else {
                    Status = STATUS_BUFFER_TOO_SMALL;
                }
            }

            IOCTL_KEYBOARD_QUERY_INDICATORS => {
                if (*IrpSp).Parameters.DeviceIoControl.OutputBufferLength >= core::mem::size_of::<KEYBOARD_INDICATOR_PARAMETERS>() as u32 {
                    let pInd = (*Irp).AssociatedIrp.SystemBuffer as PKEYBOARD_INDICATOR_PARAMETERS;
                    (*pInd).UnitId = 0;
                    (*pInd).LedFlags = 0;
                    Status = STATUS_SUCCESS;
                    Information = core::mem::size_of::<KEYBOARD_INDICATOR_PARAMETERS>() as ULONG_PTR;
                } else {
                    Status = STATUS_BUFFER_TOO_SMALL;
                }
            }

            IOCTL_KEYBOARD_QUERY_INDICATOR_TRANSLATION => {
                Status = STATUS_NOT_SUPPORTED;
            }

            IOCTL_KEYBOARD_SET_INDICATORS => {
                Status = STATUS_SUCCESS;
            }

            _ => {
                Status = STATUS_NOT_SUPPORTED;
            }
        }
    } else {
        match (*IrpSp).Parameters.DeviceIoControl.IoControlCode {
            IOCTL_ARM64INPUT_INJECT_MOUSE => {
                if (*IrpSp).Parameters.DeviceIoControl.InputBufferLength >= core::mem::size_of::<MOUSE_INPUT_DATA>() as u32 {
                    let pMou = (*Irp).AssociatedIrp.SystemBuffer as PMOUSE_INPUT_DATA;
                    MouRingPush(DevExt, pMou);
                    MouTryCompleteIrp(DevExt);
                    Status = STATUS_SUCCESS;
                } else {
                    Status = STATUS_BUFFER_TOO_SMALL;
                }
            }

            IOCTL_MOUSE_QUERY_ATTRIBUTES => {
                if (*IrpSp).Parameters.DeviceIoControl.OutputBufferLength >= core::mem::size_of::<MOUSE_ATTRIBUTES>() as u32 {
                    let pAttr = (*Irp).AssociatedIrp.SystemBuffer as PMOUSE_ATTRIBUTES;
                    RtlZeroMemory(pAttr as *mut core::ffi::c_void, core::mem::size_of::<MOUSE_ATTRIBUTES>());
                    (*pAttr).MouseIdentifier = MOUSE_SERIAL_HARDWARE as u16;
                    (*pAttr).NumberOfButtons = 3;
                    (*pAttr).SampleRate = 60;
                    (*pAttr).InputDataQueueLength = MOU_RING_SIZE as u32;
                    Status = STATUS_SUCCESS;
                    Information = core::mem::size_of::<MOUSE_ATTRIBUTES>() as ULONG_PTR;
                } else {
                    Status = STATUS_BUFFER_TOO_SMALL;
                }
            }

            _ => {
                Status = STATUS_NOT_SUPPORTED;
            }
        }
    }

    (*Irp).IoStatus.__bindgen_anon_1.Status = Status;
    (*Irp).IoStatus.Information = Information as u64;
    IoCompleteRequest(Irp, IO_NO_INCREMENT);
    Status
}

unsafe fn EvdevToScanCode(EvdevCode: USHORT, OutScanCode: *mut USHORT, OutFlags: *mut USHORT) -> BOOLEAN {
    let mut i: ULONG;

    if EvdevCode >= 1 && EvdevCode <= 88 {
        *OutScanCode = EvdevCode;
        *OutFlags = 0;
        return 1u8;
    }

    i = 0;
    while (i as usize) < EVDEV_EXT_COUNT {
        if EvdevExtendedKeys[i as usize].EvdevCode == EvdevCode {
            *OutScanCode = EvdevExtendedKeys[i as usize].ScanCode;
            *OutFlags = EvdevExtendedKeys[i as usize].Flags;
            return 1u8;
        }
        i += 1;
    }

    return 0u8;
}

unsafe fn VirtioSetupQueue(Dev: *mut VIRTIO_INPUT_DEV, QueueIdx: u32) -> i32 {
    let mut MaxSize: u32;
    let mut QueueSize: u32;
    let mut DescSize: u32;
    let mut AvailSize: u32;
    let mut UsedSize: u32;
    let mut EventsSize: u32;
    let mut AvailOff: u32;
    let mut UsedOff: u32;
    let mut EventsOff: u32;
    let mut TotalSize: u32;
    let mut HighAddr: PHYSICAL_ADDRESS = core::mem::zeroed();
    let mut i: u32;

    VirtioWrite32((*Dev).Mmio as *mut u8, 0x030, QueueIdx);
    virtio_mb();

    MaxSize = VirtioRead32((*Dev).Mmio as *mut u8, 0x034);
    if MaxSize == 0 {
        return 0xC00000E0u32 as i32;
    }

    QueueSize = if MaxSize < 64 { MaxSize } else { 64 };
    (*Dev).QueueSize = QueueSize;

    VirtioWrite32((*Dev).Mmio as *mut u8, 0x038, QueueSize);

    DescSize = core::mem::size_of::<VIRTQ_DESC>() as u32 * QueueSize;
    AvailSize = core::mem::size_of::<u16>() as u32 * 2 + core::mem::size_of::<u16>() as u32 * QueueSize + core::mem::size_of::<u16>() as u32;
    UsedSize = core::mem::size_of::<u16>() as u32 * 2 + core::mem::size_of::<VIRTQ_USED_ELEM>() as u32 * QueueSize + core::mem::size_of::<u16>() as u32;
    EventsSize = core::mem::size_of::<VIRTIO_INPUT_EVENT>() as u32 * QueueSize;

    if (*Dev).MmioVersion >= 2 {
        AvailOff = (DescSize + 0xFFF) & !0xFFF;
        UsedOff = (AvailOff + AvailSize + 0xFFF) & !0xFFF;
    } else {
        AvailOff = DescSize;
        UsedOff = (AvailOff + AvailSize + 0xFFF) & !0xFFF;
    }
    EventsOff = (UsedOff + UsedSize + 0xFFF) & !0xFFF;
    TotalSize = EventsOff + EventsSize;

    HighAddr.QuadPart = 0xFFFFFFFFu64 as i64;
    (*Dev).QueueVa = MmAllocateContiguousMemory(TotalSize as _, HighAddr);
    if (*Dev).QueueVa.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }

    (*Dev).QueuePa = MmGetPhysicalAddress((*Dev).QueueVa);
    (*Dev).QueueAllocSize = TotalSize;
    core::ptr::write_bytes((*Dev).QueueVa as *mut u8, 0, TotalSize as usize);

    (*Dev).Desc = (*Dev).QueueVa as *mut VIRTQ_DESC;
    (*Dev).Avail = ((*Dev).QueueVa as *mut u8).add(AvailOff as usize) as *mut VIRTQ_AVAIL;
    (*Dev).Used = ((*Dev).QueueVa as *mut u8).add(UsedOff as usize) as *mut VIRTQ_USED;
    (*Dev).Events = ((*Dev).QueueVa as *mut u8).add(EventsOff as usize) as *mut VIRTIO_INPUT_EVENT;
    (*Dev).EventsPa.QuadPart = (*Dev).QueuePa.QuadPart + EventsOff as i64;

    if (*Dev).MmioVersion >= 2 {
        let DescPa: PHYSICAL_ADDRESS = (*Dev).QueuePa;
        let mut AvailPa: PHYSICAL_ADDRESS = core::mem::zeroed();
        let mut UsedPa: PHYSICAL_ADDRESS = core::mem::zeroed();
        AvailPa.QuadPart = (*Dev).QueuePa.QuadPart + AvailOff as i64;
        UsedPa.QuadPart = (*Dev).QueuePa.QuadPart + UsedOff as i64;

        VirtioWrite32((*Dev).Mmio as *mut u8, 0x080, DescPa.QuadPart as u32);
        VirtioWrite32((*Dev).Mmio as *mut u8, 0x084, (DescPa.QuadPart >> 32) as u32);
        VirtioWrite32((*Dev).Mmio as *mut u8, 0x090, AvailPa.QuadPart as u32);
        VirtioWrite32((*Dev).Mmio as *mut u8, 0x094, (AvailPa.QuadPart >> 32) as u32);
        VirtioWrite32((*Dev).Mmio as *mut u8, 0x0A0, UsedPa.QuadPart as u32);
        VirtioWrite32((*Dev).Mmio as *mut u8, 0x0A4, (UsedPa.QuadPart >> 32) as u32);
        virtio_mb();
        VirtioWrite32((*Dev).Mmio as *mut u8, 0x044, 1);
    } else {
        // Legacy virtio-mmio (v1) queue setup, spec §4.2.4. The driver MUST
        // write QueueAlign (0x03c) so the device computes the used-ring
        // offset the same way the driver laid it out: used at
        // align(desc+avail, QueueAlign). We page-align the used ring
        // (UsedOff above), so QueueAlign must be 4096. Omitting this leaves
        // QEMU's align at its reset default (!= 4096) → the device writes
        // completed buffers to a different offset than the poll thread
        // reads → zero input ever delivered (the bug this smoke gate caught;
        // the legacy path was never exercised until a virtio-input device
        // was wired in). GuestPageSize (0x028) then QueuePFN (0x040) last.
        VirtioWrite32((*Dev).Mmio as *mut u8, 0x028, 4096);
        VirtioWrite32((*Dev).Mmio as *mut u8, 0x03c, 4096);
        virtio_mb();
        VirtioWrite32((*Dev).Mmio as *mut u8, 0x040, ((*Dev).QueuePa.QuadPart / 4096) as u32);
    }

    i = 0;
    while i < QueueSize {
        (*(*Dev).Desc.add(i as usize)).Addr = (*Dev).EventsPa.QuadPart as u64 + (i * core::mem::size_of::<VIRTIO_INPUT_EVENT>() as u32) as u64;
        (*(*Dev).Desc.add(i as usize)).Len = core::mem::size_of::<VIRTIO_INPUT_EVENT>() as u32;
        (*(*Dev).Desc.add(i as usize)).Flags = 2;
        (*(*Dev).Desc.add(i as usize)).Next = 0;

        *(core::ptr::addr_of_mut!((*(*Dev).Avail).Ring) as *mut u16).add(i as usize) = i as u16;
        i += 1;
    }
    virtio_wmb();
    (*(*Dev).Avail).Idx = QueueSize as u16;
    (*Dev).LastUsedIdx = 0;

    virtio_mb();
    VirtioWrite32((*Dev).Mmio as *mut u8, 0x050, QueueIdx);

    STATUS_SUCCESS
}

unsafe fn VirtioQueryInputCaps(Dev: *mut VIRTIO_INPUT_DEV) {
    let cfg = (*Dev).Mmio.offset(VIRTIO_MMIO_CONFIG as isize);
    let mut bitmap: [u8; 128] = [0; 128];
    let mut size: u32;
    let mut i: u32;

    (*Dev).IsKeyboard = 0u8;
    (*Dev).IsTablet = 0u8;

    core::ptr::write_volatile(cfg.offset(0), VIRTIO_INPUT_CFG_EV_BITS as u8);
    virtio_mb();
    core::ptr::write_volatile(cfg.offset(1), EV_KEY as u8);
    virtio_mb();
    size = core::ptr::read_volatile(cfg.offset(2)) as u32;

    if size > 0 && size <= core::mem::size_of::<[u8; 128]>() as u32 {
        i = 0;
        while i < size {
            bitmap[i as usize] = core::ptr::read_volatile(cfg.offset(8 + i as isize));
            i += 1;
        }

        if size > (KEY_A / 8) && (bitmap[(KEY_A / 8) as usize] & (1 << (KEY_A % 8))) != 0 {
            (*Dev).IsKeyboard = 1u8;
        }
    }

    core::ptr::write_volatile(cfg.offset(0), VIRTIO_INPUT_CFG_EV_BITS as u8);
    virtio_mb();
    core::ptr::write_volatile(cfg.offset(1), EV_ABS as u8);
    virtio_mb();
    size = core::ptr::read_volatile(cfg.offset(2)) as u32;

    if size > 0 {
        i = 0;
        while i < size && i < core::mem::size_of::<[u8; 128]>() as u32 {
            bitmap[i as usize] = core::ptr::read_volatile(cfg.offset(8 + i as isize));
            i += 1;
        }

        if (bitmap[0] & 1) != 0 {
            (*Dev).IsTablet = 1u8;
        }
    }

    if (*Dev).IsTablet != 0 {
        let mut absinfo: *const u32;

        core::ptr::write_volatile(cfg.offset(0), VIRTIO_INPUT_CFG_ABS_INFO as u8);
        virtio_mb();
        core::ptr::write_volatile(cfg.offset(1), ABS_X as u8);
        virtio_mb();
        size = core::ptr::read_volatile(cfg.offset(2)) as u32;
        if size >= 12 {
            absinfo = cfg.offset(8) as *const u32;
            (*Dev).AbsMaxX = core::ptr::read_volatile(absinfo.offset(1));
        } else {
            (*Dev).AbsMaxX = 32767;
        }

        core::ptr::write_volatile(cfg.offset(0), VIRTIO_INPUT_CFG_ABS_INFO as u8);
        core::ptr::write_volatile(cfg.offset(1), ABS_Y as u8);
        virtio_mb();
        size = core::ptr::read_volatile(cfg.offset(2)) as u32;
        if size >= 12 {
            absinfo = cfg.offset(8) as *const u32;
            (*Dev).AbsMaxY = core::ptr::read_volatile(absinfo.offset(1));
        } else {
            (*Dev).AbsMaxY = 32767;
        }
    }

    core::ptr::write_volatile(cfg.offset(0), VIRTIO_INPUT_CFG_UNSET as u8);
    core::ptr::write_volatile(cfg.offset(1), 0);
    virtio_mb();
}

unsafe fn VirtioScanDevices() {
    let mut i: u32;
    let mut PhysAddr: PHYSICAL_ADDRESS = core::mem::zeroed();
    let mut Mmio: *mut u8;
    let mut Magic: u32;
    let mut Version: u32;
    let mut DevId: u32;
    let mut Status: i32;

    VirtioInputCount = 0;

    i = 0;
    while i < VIRTIO_MMIO_SLOTS && (VirtioInputCount as usize) < MAX_VIRTIO_INPUTS {
        PhysAddr.QuadPart = (VIRTIO_MMIO_BASE + (i as u64) * VIRTIO_MMIO_STRIDE) as i64;
        Mmio = MmMapIoSpace(PhysAddr, VIRTIO_MMIO_SIZE as _, MmNonCached) as *mut u8;
        if Mmio.is_null() {
            i += 1;
            continue;
        }

        Magic = VirtioRead32(Mmio, VIRTIO_MMIO_MAGIC);
        if Magic != 0x74726976 {
            MmUnmapIoSpace(Mmio as *mut core::ffi::c_void, VIRTIO_MMIO_SIZE as _);
            i += 1;
            continue;
        }

        Version = VirtioRead32(Mmio, VIRTIO_MMIO_VERSION);
        DevId = VirtioRead32(Mmio, VIRTIO_MMIO_DEVICE_ID);

        if DevId != VIRTIO_DEVICE_ID_INPUT {
            MmUnmapIoSpace(Mmio as *mut core::ffi::c_void, VIRTIO_MMIO_SIZE as _);
            i += 1;
            continue;
        }

        DbgPrint(b"[VIRTIO-INPUT] Found input device at slot %lu (version %lu)\n\0".as_ptr() as *const i8, i, Version);

        let Dev = &mut VirtioInputs[VirtioInputCount as usize];
        core::ptr::write_bytes(Dev as *mut _VIRTIO_INPUT_DEV, 0, 1);
        (*Dev).Mmio = Mmio;
        (*Dev).MmioVersion = Version;
        (*Dev).Slot = i;

        VirtioWrite32(Mmio, VIRTIO_MMIO_STATUS, 0);
        virtio_mb();

        VirtioWrite32(Mmio, VIRTIO_MMIO_STATUS, VIRTIO_STATUS_ACK);
        virtio_mb();

        VirtioWrite32(Mmio, VIRTIO_MMIO_STATUS, VIRTIO_STATUS_ACK | VIRTIO_STATUS_DRIVER);
        virtio_mb();

        VirtioWrite32(Mmio, VIRTIO_MMIO_DRV_FEATURES_SEL, 0);
        VirtioWrite32(Mmio, VIRTIO_MMIO_DRV_FEATURES, 0);
        if Version >= 2 {
            VirtioWrite32(Mmio, VIRTIO_MMIO_DRV_FEATURES_SEL, 1);
            VirtioWrite32(Mmio, VIRTIO_MMIO_DRV_FEATURES, 1);
        }
        virtio_mb();

        if Version >= 2 {
            VirtioWrite32(Mmio, VIRTIO_MMIO_STATUS,
                          VIRTIO_STATUS_ACK | VIRTIO_STATUS_DRIVER | VIRTIO_STATUS_FEATURES_OK);
            virtio_mb();

            let StatusVal = VirtioRead32(Mmio, VIRTIO_MMIO_STATUS);
            if (StatusVal & VIRTIO_STATUS_FEATURES_OK) == 0 {
                DbgPrint(b"[VIRTIO-INPUT] FEATURES_OK not set, skipping slot %lu\n\0".as_ptr() as *const i8, i);
                MmUnmapIoSpace(Mmio as *mut core::ffi::c_void, VIRTIO_MMIO_SIZE as _);
                i += 1;
                continue;
            }
        }

        VirtioQueryInputCaps(Dev);

        Status = VirtioSetupQueue(Dev, 0);
        if !NT_SUCCESS(Status) {
            DbgPrint(b"[VIRTIO-INPUT] Queue setup failed: 0x%08lx\n\0".as_ptr() as *const i8, Status);
            MmUnmapIoSpace(Mmio as *mut core::ffi::c_void, VIRTIO_MMIO_SIZE as _);
            i += 1;
            continue;
        }

        VirtioWrite32(Mmio, VIRTIO_MMIO_STATUS,
                      VIRTIO_STATUS_ACK | VIRTIO_STATUS_DRIVER |
                      (if Version >= 2 { VIRTIO_STATUS_FEATURES_OK } else { 0 }) |
                      VIRTIO_STATUS_DRIVER_OK);
        virtio_mb();

        DbgPrint(b"[VIRTIO-INPUT] Initialized %s%sat slot %lu (abs %lu x %lu)\n\0".as_ptr() as *const i8,
                if (*Dev).IsKeyboard != 0 { b"keyboard \0".as_ptr() } else { b"\0".as_ptr() },
                if (*Dev).IsTablet != 0 { b"tablet \0".as_ptr() } else { b"\0".as_ptr() },
                i, (*Dev).AbsMaxX, (*Dev).AbsMaxY);

        VirtioInputCount += 1;
        i += 1;
    }

    DbgPrint(b"[VIRTIO-INPUT] Found %lu input device(s)\n\0".as_ptr() as *const i8, VirtioInputCount);
}

unsafe fn VirtioProcessKeyEvent(EvdevCode: USHORT, Value: ULONG) {
    let mut DevExt: PINPUT_DEVICE_EXT;
    let mut ScanCode: USHORT = 0;
    let mut Flags: USHORT = 0;

    if g_KbdDevice == core::ptr::null_mut() {
        return;
    }

    if EvdevToScanCode(EvdevCode, core::ptr::addr_of_mut!(ScanCode), core::ptr::addr_of_mut!(Flags)) == 0 {
        return;
    }

    DevExt = (*g_KbdDevice).DeviceExtension as PINPUT_DEVICE_EXT;

    if Value == 0 {
        Flags |= KEY_BREAK;
    }

    RingPush(DevExt, ScanCode, Flags);
    TryCompleteIrp(DevExt);

    // One-shot delivery oracle for the arm64 input smoke gate: proves the
    // QMP -> virtio-mmio -> ISR->DPC drain (or poll fallback) -> scancode
    // xlate -> KeyboardClass0 ring -> read-IRP path completed end-to-end.
    // Fires exactly once so a sustained key storm doesn't spam serial.
    static KBD_DELIVERED: core::sync::atomic::AtomicBool =
        core::sync::atomic::AtomicBool::new(false);
    if KBD_DELIVERED
        .compare_exchange(
            false,
            true,
            core::sync::atomic::Ordering::SeqCst,
            core::sync::atomic::Ordering::SeqCst,
        )
        .is_ok()
    {
        DbgPrint(
            b"[ARM64INPUT] KBD-DELIVERED sc=0x%04x fl=0x%04x\n\0".as_ptr() as *const i8,
            ScanCode as u32,
            Flags as u32,
        );
    }
}

unsafe fn VirtioProcessMouseButton(EvdevCode: USHORT, Value: ULONG, Dev: *mut VIRTIO_INPUT_DEV) {
    match EvdevCode {
        0x110 => {
            (*Dev).AccumButtons |= if Value != 0 {
                MOUSE_LEFT_BUTTON_DOWN
            } else {
                MOUSE_LEFT_BUTTON_UP
            };
            (*Dev).HasButton = 1u8;
        }
        0x111 => {
            (*Dev).AccumButtons |= if Value != 0 {
                MOUSE_RIGHT_BUTTON_DOWN
            } else {
                MOUSE_RIGHT_BUTTON_UP
            };
            (*Dev).HasButton = 1u8;
        }
        0x112 => {
            (*Dev).AccumButtons |= if Value != 0 {
                MOUSE_MIDDLE_BUTTON_DOWN
            } else {
                MOUSE_MIDDLE_BUTTON_UP
            };
            (*Dev).HasButton = 1u8;
        }
        _ => {}
    }
}

unsafe fn VirtioFlushMouseState(Dev: *mut VIRTIO_INPUT_DEV) {
    let mut DevExt: PINPUT_DEVICE_EXT;
    let mut Data: MOUSE_INPUT_DATA = core::mem::zeroed();

    if g_MouDevice.is_null() {
        return;
    }
    if (*Dev).HasMove == 0 && (*Dev).HasButton == 0 {
        return;
    }

    DevExt = (*g_MouDevice).DeviceExtension as PINPUT_DEVICE_EXT;

    RtlZeroMemory(core::ptr::addr_of_mut!(Data) as PVOID, core::mem::size_of::<MOUSE_INPUT_DATA>() as SIZE_T);

    if (*Dev).IsTablet != 0 && (*Dev).AbsValid != 0 {
        Data.Flags = MOUSE_MOVE_ABSOLUTE as u16;
        if (*Dev).AbsMaxX > 0 {
            Data.LastX = (((*Dev).AccumX as ULONGLONG) * 65535 / (*Dev).AbsMaxX as ULONGLONG) as LONG;
        } else {
            Data.LastX = (*Dev).AccumX;
        }
        if (*Dev).AbsMaxY > 0 {
            Data.LastY = (((*Dev).AccumY as ULONGLONG) * 65535 / (*Dev).AbsMaxY as ULONGLONG) as LONG;
        } else {
            Data.LastY = (*Dev).AccumY;
        }
    } else if (*Dev).HasMove != 0 {
        Data.Flags = 0;
        Data.LastX = (*Dev).AccumX;
        Data.LastY = (*Dev).AccumY;
    }

    Data.__bindgen_anon_1.__bindgen_anon_1.ButtonFlags = (*Dev).AccumButtons;

    MouRingPush(DevExt, core::ptr::addr_of_mut!(Data));
    MouTryCompleteIrp(DevExt);

    // One-shot delivery oracle (see KBD-DELIVERED): proves the pointer path
    // (virtio rel/abs+button -> MOUSE_INPUT_DATA -> PointerClass0 ring ->
    // read-IRP) completed end-to-end. Fires exactly once.
    static MOU_DELIVERED: core::sync::atomic::AtomicBool =
        core::sync::atomic::AtomicBool::new(false);
    if MOU_DELIVERED
        .compare_exchange(
            false,
            true,
            core::sync::atomic::Ordering::SeqCst,
            core::sync::atomic::Ordering::SeqCst,
        )
        .is_ok()
    {
        DbgPrint(
            b"[ARM64INPUT] MOU-DELIVERED btn=0x%04x dx=%d dy=%d\n\0".as_ptr() as *const i8,
            Data.__bindgen_anon_1.__bindgen_anon_1.ButtonFlags as u32,
            Data.LastX,
            Data.LastY,
        );
    }

    if (*Dev).IsTablet == 0 {
        (*Dev).AccumX = 0;
        (*Dev).AccumY = 0;
    }
    (*Dev).AccumButtons = 0;
    (*Dev).HasMove = 0u8;
    (*Dev).HasButton = 0u8;
}

unsafe fn VirtioPollDevice(Dev: *mut VIRTIO_INPUT_DEV) -> BOOLEAN {
    let mut FoundEvents: BOOLEAN = 0u8;
    let mut UsedIdx: USHORT;
    let mut DescId: ULONG;
    let mut Evt: *mut VIRTIO_INPUT_EVENT;

    // The used ring + event payloads are written by the DEVICE (QEMU) via
    // DMA — the guest never stores to them, so a plain Rust load is treated
    // as loop-invariant by LLVM and constant-folded to its initial 0. That
    // is THE bug this smoke gate caught: QEMU consumed all 64 buffers and
    // wrote used.idx=64 to the exact PA the guest reads, but the poll thread
    // saw a cached 0 and never processed a single event. Every device->guest
    // read here MUST be read_volatile (project DMA/MMIO volatile discipline).
    // VIRTQ_USED is repr(C, packed) → addr_of! (no references to packed
    // fields).
    virtio_rmb();
    UsedIdx = core::ptr::read_volatile(core::ptr::addr_of!((*(*Dev).Used).Idx));

    while (*Dev).LastUsedIdx != UsedIdx {
        FoundEvents = 1u8;
        let ring0 = core::ptr::addr_of!((*(*Dev).Used).Ring) as *const VIRTQ_USED_ELEM;
        let slot = ((*Dev).LastUsedIdx % (*Dev).QueueSize as u16) as usize;
        DescId = core::ptr::read_volatile(core::ptr::addr_of!((*ring0.add(slot)).Id));
        Evt = (*Dev).Events.offset(DescId as isize);
        let ev = core::ptr::read_volatile(Evt); // device-written payload

        match ev.Type {
            0x01 => {
                if ev.Code < 0x110 {
                    VirtioProcessKeyEvent(ev.Code, ev.Value);
                } else {
                    VirtioProcessMouseButton(ev.Code, ev.Value, Dev);
                }
            }

            0x02 => {
                match ev.Code {
                    0x00 => {
                        (*Dev).AccumX += ev.Value as LONG;
                        (*Dev).HasMove = 1u8;
                    }
                    0x01 => {
                        (*Dev).AccumY += ev.Value as LONG;
                        (*Dev).HasMove = 1u8;
                    }
                    0x08 => {
                    }
                    _ => {}
                }
            }

            0x03 => {
                match ev.Code {
                    0x00 => {
                        (*Dev).AccumX = ev.Value as LONG;
                        (*Dev).HasMove = 1u8;
                        (*Dev).AbsValid = 1u8;
                    }
                    0x01 => {
                        (*Dev).AccumY = ev.Value as LONG;
                        (*Dev).HasMove = 1u8;
                        (*Dev).AbsValid = 1u8;
                    }
                    _ => {}
                }
            }

            0x00 => {
                VirtioFlushMouseState(Dev);
            }

            _ => {}
        }

        (*(*Dev).Desc.offset(DescId as isize)).Len = core::mem::size_of::<VIRTIO_INPUT_EVENT>() as ULONG;
        (*(*Dev).Desc.offset(DescId as isize)).Flags = 2u16;
        virtio_wmb();
        // Ring is a C flexible array member ([u16; 0] in Rust) — safe indexing
        // bounds-panics on len 0 for ANY index (the 2026-07-06 "first keypress
        // wedges the machine" bug: scancode delivered, then panic_bounds_check
        // here → silent loop{} at DISPATCH → all DPCs dead). Use the same raw
        // pointer arithmetic as the init fill (VirtioSetupQueue) above.
        *(core::ptr::addr_of_mut!((*(*Dev).Avail).Ring) as *mut u16)
            .add((((*(*Dev).Avail).Idx % (*Dev).QueueSize as u16)) as usize) = DescId as USHORT;
        virtio_wmb();
        (*(*Dev).Avail).Idx = (*(*Dev).Avail).Idx.wrapping_add(1);

        (*Dev).LastUsedIdx = (*Dev).LastUsedIdx.wrapping_add(1);
    }

    if FoundEvents != 0 {
        virtio_mb();
        VirtioWrite32((*Dev).Mmio as *mut u8, 0x050, 0);
    }

    FoundEvents
}

// ---------------------------------------------------------------------------
// Interrupt-driven input (ISR → DPC), replacing the poll thread.
//
// QEMU virt wires virtio-mmio transport slot i to SPI 16+i (GIC INTID 48+i).
// The ISR runs at DIRQL: it only reads+acks VIRTIO_MMIO_INTERRUPT_STATUS
// (deasserting the level-triggered line) and queues the per-device DPC. The
// DPC drains the used ring at DISPATCH_LEVEL via VirtioPollDevice — the same
// single consumer the poll thread was, so ring ownership is unchanged (the
// poll thread and interrupts are never active together; see DriverEntry).
// ---------------------------------------------------------------------------

/// GIC INTID of the first virtio-mmio transport on QEMU `virt` (SPI 16).
const VIRTIO_MMIO_INTID_BASE: u32 = 48;

/// One-shot serial oracle proving the ISR→DPC→ring-drain path is live.
static FIRST_INPUT_IRQ: core::sync::atomic::AtomicBool =
    core::sync::atomic::AtomicBool::new(false);

unsafe extern "system" fn VirtioInputIsr(
    _Interrupt: *mut _KINTERRUPT,
    Context: PVOID,
) -> u8 {
    let Dev = Context as *mut VIRTIO_INPUT_DEV;
    let status = VirtioRead32((*Dev).Mmio as *mut u8, VIRTIO_MMIO_INTERRUPT_STATUS);
    if status == 0 {
        // Quiet device — a GIC-selftest fire (software-pended) or a shared
        // line. Nothing to ack or drain.
        return 0; // not ours (line is dedicated, but stay shared-safe)
    }
    // Ack first (deasserts the level line), then defer the drain to DISPATCH.
    VirtioWrite32((*Dev).Mmio as *mut u8, VIRTIO_MMIO_INTERRUPT_ACK, status);
    KeInsertQueueDpc(
        core::ptr::addr_of_mut!((*Dev).Dpc),
        core::ptr::null_mut(),
        core::ptr::null_mut(),
    );
    1
}

unsafe extern "system" fn VirtioInputDpc(
    _Dpc: *mut _KDPC,
    Context: PVOID,
    _Arg1: PVOID,
    _Arg2: PVOID,
) {
    let Dev = Context as *mut VIRTIO_INPUT_DEV;
    let found = VirtioPollDevice(Dev);
    if found != 0
        && FIRST_INPUT_IRQ
            .compare_exchange(
                false,
                true,
                core::sync::atomic::Ordering::SeqCst,
                core::sync::atomic::Ordering::SeqCst,
            )
            .is_ok()
    {
        DbgPrint(
            b"[ARM64INPUT] first interrupt-driven input event (INTID %lu, poll thread retired)\n\0"
                .as_ptr() as *const i8,
            VIRTIO_MMIO_INTID_BASE + (*Dev).Slot,
        );
    }
}

/// Connect every discovered device's virtio-mmio SPI through
/// HalGetInterruptVector + IoConnectInterrupt. All-or-nothing: on any failure
/// the already-connected lines are disconnected and the caller falls back to
/// the poll thread for everything — the used ring must have exactly one
/// consumer (DPC xor poll thread).
unsafe fn VirtioConnectInterrupts() -> u8 {
    let mut i: u32 = 0;
    while i < VirtioInputCount {
        let Dev = &mut VirtioInputs[i as usize] as *mut VIRTIO_INPUT_DEV;
        let intid = VIRTIO_MMIO_INTID_BASE + (*Dev).Slot;
        let mut irql: u8 = 0;
        let mut affinity: KAFFINITY = 0;
        let vector = HalGetInterruptVector(0, 0, intid, intid, &mut irql, &mut affinity);

        let mut ok = vector != 0;
        if ok {
            let dpc_routine: PKDEFERRED_ROUTINE =
                Some(core::mem::transmute(VirtioInputDpc as *const ()));
            let isr_routine: PKSERVICE_ROUTINE =
                Some(core::mem::transmute(VirtioInputIsr as *const ()));
            KeInitializeDpc(
                core::ptr::addr_of_mut!((*Dev).Dpc),
                dpc_routine,
                Dev as PVOID,
            );
            let status = IoConnectInterrupt(
                core::ptr::addr_of_mut!((*Dev).Interrupt),
                isr_routine,
                Dev as PVOID,
                core::ptr::null_mut(),
                vector,
                irql,
                irql,
                0, // LevelSensitive — virtio-mmio INTx is level-triggered
                0,
                affinity,
                0,
            );
            ok = NT_SUCCESS(status);
            if !ok {
                DbgPrint(
                    b"[ARM64INPUT] IoConnectInterrupt(INTID %lu) failed: 0x%08lx\n\0".as_ptr()
                        as *const i8,
                    intid,
                    status,
                );
            }
        } else {
            DbgPrint(
                b"[ARM64INPUT] HalGetInterruptVector(INTID %lu) returned 0\n\0".as_ptr()
                    as *const i8,
                intid,
            );
        }

        if !ok {
            // Roll back: one consumer rule — all interrupts or all polling.
            let mut j: u32 = 0;
            while j < i {
                let Prev = &mut VirtioInputs[j as usize] as *mut VIRTIO_INPUT_DEV;
                if !(*Prev).Interrupt.is_null() {
                    IoDisconnectInterrupt((*Prev).Interrupt);
                    (*Prev).Interrupt = core::ptr::null_mut();
                }
                j += 1;
            }
            return 0;
        }

        DbgPrint(
            b"[ARM64INPUT] slot %lu on IRQ (INTID %lu, DIRQL %lu)\n\0".as_ptr() as *const i8,
            (*Dev).Slot,
            intid,
            irql as u32,
        );
        i += 1;
    }
    1
}

unsafe extern "system" fn VirtioPollThread(Context: PVOID) {
    let mut Delay: LARGE_INTEGER = core::mem::zeroed();

    Delay.QuadPart = -10000;

    while VirtioPollRunning != 0 {
        let mut found: BOOLEAN = 0u8;
        let mut i: ULONG;

        i = 0;
        while i < VirtioInputCount {
            if VirtioPollDevice(&mut VirtioInputs[i as usize]) != 0 {
                found = 1u8;
            }
            i += 1;
        }

        KeDelayExecutionThread(0i32 as i8, 0u8, &mut Delay);

        if found == 0 {
            let mut j: ULONG;
            j = 0;
            while j < 5 {
                KeDelayExecutionThread(0i32 as i8, 0u8, &mut Delay);
                j += 1;
            }
        }
    }

    PsTerminateSystemThread(STATUS_SUCCESS);
}

#[no_mangle]
pub unsafe extern "system" fn DriverEntry(
    DriverObject: PDRIVER_OBJECT,
    RegistryPath: PUNICODE_STRING,
) -> i32 {
    let mut Status: i32;
    let mut KbdDevice: PDEVICE_OBJECT = core::ptr::null_mut();
    let mut MouDevice: PDEVICE_OBJECT = core::ptr::null_mut();
    let mut DevExt: *mut _INPUT_DEVICE_EXT;
    let mut DeviceName: _UNICODE_STRING = core::mem::zeroed();
    let mut SymlinkName: _UNICODE_STRING = core::mem::zeroed();

    DbgPrint(b"[ARM64INPUT] DriverEntry\n\0".as_ptr() as _);

    (*DriverObject).MajorFunction[0x00] = Some(InputCreate);
    (*DriverObject).MajorFunction[0x02] = Some(InputClose);
    (*DriverObject).MajorFunction[0x12] = Some(InputCleanup);
    (*DriverObject).MajorFunction[0x03] = Some(InputRead);
    (*DriverObject).MajorFunction[0x0E] = Some(InputDeviceControl);

    // Claim the class-device names only for virtio input we can actually serve.
    // win32k reads exactly \Device\KeyboardClass0 and \Device\PointerClass0; on a
    // machine without virtio-input (a Raspberry Pi, QEMU with USB input only)
    // those names belong to kbdclass/mouclass, which the USB HID stack feeds.
    // Taking them anyway left every USB keystroke delivered to a class device
    // nothing reads.
    VirtioScanDevices();
    if VirtioInputCount == 0 {
        DbgPrint(b"[ARM64INPUT] no virtio-input device: KeyboardClass0/PointerClass0 left to kbdclass/mouclass\n\0".as_ptr() as _);
        return STATUS_SUCCESS;
    }

    let n_kbd_dev = wsz!(b"\\Device\\KeyboardClass0");
    RtlInitUnicodeString(&mut DeviceName, n_kbd_dev.as_ptr());
    Status = IoCreateDevice(
        DriverObject,
        core::mem::size_of::<_INPUT_DEVICE_EXT>() as u32,
        &mut DeviceName,
        0x0000000B,
        0,
        0u8,
        &mut KbdDevice,
    );
    if !NT_SUCCESS(Status) {
        DbgPrint(
            b"[ARM64INPUT] Failed to create KeyboardClass0: 0x%08lx\n\0".as_ptr() as _,
            Status,
        );
        return Status;
    }

    let n_kbd_sym = wsz!(b"\\DosDevices\\KeyboardClass0");
    RtlInitUnicodeString(&mut SymlinkName, n_kbd_sym.as_ptr());
    IoCreateSymbolicLink(&mut SymlinkName, &mut DeviceName);

    DevExt = (*KbdDevice).DeviceExtension as *mut _INPUT_DEVICE_EXT;
    (*DevExt).IsKeyboard = 1u8;
    InitializeListHead(&mut (*DevExt).PendingIrps);
    KeInitializeSpinLock(core::ptr::addr_of_mut!((*DevExt).IrpLock) as *mut _);
    (*DevExt).RingHead = 0;
    (*DevExt).RingTail = 0;
    (*DevExt).SelfDevice = KbdDevice;

    // C: KbdDevice->Flags |= DO_BUFFERED_IO (0x04). The translation had
    // guessed 0x10 — which is DO_DIRECT_IO — so NtReadFile never allocated a
    // SystemBuffer and every input packet was copied to NULL (win32k's RIT
    // read back zeros: keys dropped at "no VK for sc=0x0", mouse packets were
    // no-ops). Same invented-constant class as the acpi CmResourceType bug.
    (*KbdDevice).Flags |= 0x00000004; // DO_BUFFERED_IO
    (*KbdDevice).Flags &= !ntkrnl_sys::driver_ddk::DO_DEVICE_INITIALIZING;
    g_KbdDevice = KbdDevice;

    DbgPrint(b"[ARM64INPUT] \\Device\\KeyboardClass0 created\n\0".as_ptr() as _);

    let n_ptr_dev = wsz!(b"\\Device\\PointerClass0");
    RtlInitUnicodeString(&mut DeviceName, n_ptr_dev.as_ptr());
    Status = IoCreateDevice(
        DriverObject,
        core::mem::size_of::<_INPUT_DEVICE_EXT>() as u32,
        &mut DeviceName,
        0x0000000F,
        0,
        0u8,
        &mut MouDevice,
    );
    if !NT_SUCCESS(Status) {
        DbgPrint(
            b"[ARM64INPUT] Failed to create PointerClass0: 0x%08lx\n\0".as_ptr() as _,
            Status,
        );
        IoDeleteDevice(KbdDevice);
        return Status;
    }

    DevExt = (*MouDevice).DeviceExtension as *mut _INPUT_DEVICE_EXT;
    (*DevExt).IsKeyboard = 0u8;
    InitializeListHead(&mut (*DevExt).PendingIrps);
    KeInitializeSpinLock(core::ptr::addr_of_mut!((*DevExt).IrpLock) as *mut _);
    (*DevExt).RingHead = 0;
    (*DevExt).MouRingHead = 0;
    (*DevExt).MouRingTail = 0;
    (*DevExt).SelfDevice = MouDevice;
    (*MouDevice).Flags |= 0x00000004; // DO_BUFFERED_IO (see kbd note above)
    (*MouDevice).Flags &= !ntkrnl_sys::driver_ddk::DO_DEVICE_INITIALIZING;

    let n_ptr_sym = wsz!(b"\\DosDevices\\PointerClass0");
    RtlInitUnicodeString(&mut SymlinkName, n_ptr_sym.as_ptr());
    RtlInitUnicodeString(&mut DeviceName, n_ptr_dev.as_ptr());
    IoCreateSymbolicLink(&mut SymlinkName, &mut DeviceName);

    g_MouDevice = MouDevice;

    DbgPrint(b"[ARM64INPUT] \\Device\\PointerClass0 created\n\0".as_ptr() as _);

    if VirtioConnectInterrupts() != 0 {
        DbgPrint(b"[ARM64INPUT] interrupt mode: all devices on GIC IRQs, no poll thread\n\0"
            .as_ptr() as _);
        // Software-pend the first device's line: `[GIC] selftest ... DELIVERED`
        // on serial proves GIC→dispatch→ISR wiring every boot, independent of
        // the device asserting (field-manual §9.19 tooling).
        extern "system" {
            fn HalSelfTestGicSpiArm64(intid: u32);
        }
        HalSelfTestGicSpiArm64(VIRTIO_MMIO_INTID_BASE + VirtioInputs[0].Slot);
    } else {
        // Fallback: no usable interrupt routing — poll as before.
        VirtioPollRunning = 1u8;
        Status = PsCreateSystemThread(
            &raw mut VirtioPollThreadHandle,
            0x001F03FF,
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            Some(VirtioPollThread),
            core::ptr::null_mut(),
        );
        if NT_SUCCESS(Status) {
            DbgPrint(b"[ARM64INPUT] Virtio poll thread started\n\0".as_ptr() as _);
        } else {
            DbgPrint(
                b"[ARM64INPUT] Failed to create poll thread: 0x%08lx\n\0".as_ptr() as _,
                Status,
            );
            VirtioPollRunning = 0u8;
        }
    }

    STATUS_SUCCESS
}


