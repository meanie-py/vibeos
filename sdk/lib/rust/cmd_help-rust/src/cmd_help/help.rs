unsafe extern "C" fn IsInternalCommand(Cmd: PCWSTR) -> BOOL {
    let mut i: size_t;
    let mut res: ::core::ffi::c_int;

    /* Invalid command */
    if Cmd.is_null() {
        return (FALSE) as BOOL;
    }

    i = 0 as size_t;
    while i < (ARRAYSIZE!(InternalCommands) as size_t) {
        res = _wcsicmp(InternalCommands[i as usize], Cmd);
        if res == 0 {
            /* This is an internal command */
            return (TRUE) as BOOL;
        } else if res > 0 {
            /*
             * The internal commands list is sorted in alphabetical order.
             * We can quit the loop immediately since the current internal
             * command is lexically greater than the command to be tested.
             */
            break;
        }
        i = i.wrapping_add(1);
    }

    /* Command not found */
    return (FALSE) as BOOL;
}

