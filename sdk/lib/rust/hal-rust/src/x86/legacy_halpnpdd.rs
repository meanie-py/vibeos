#[no_mangle]
pub unsafe extern "system" fn HalpQueryDeviceRelations(
    DeviceObject: PDEVICE_OBJECT,
    RelationType: DEVICE_RELATION_TYPE,
    DeviceRelations: *mut PDEVICE_RELATIONS,
) -> NTSTATUS {
    let mut ExtensionType: EXTENSION_TYPE;
    let mut PdoExtension: PPDO_EXTENSION;
    let FdoExtension: PFDO_EXTENSION;
    let mut PdoRelations: PDEVICE_RELATIONS;
    let mut FdoRelations: PDEVICE_RELATIONS;
    let mut ObjectEntry: *mut PDEVICE_OBJECT;
    let mut i: ULONG = 0;
    let mut PdoCount: ULONG = 0;

    FdoExtension = (*DeviceObject).DeviceExtension as PFDO_EXTENSION;
    ExtensionType = (*FdoExtension).ExtensionType;

    if RelationType == BusRelations as DEVICE_RELATION_TYPE {
        if ExtensionType == FdoExtensionType {
            PdoExtension = (*FdoExtension).ChildPdoList;
            while !PdoExtension.is_null() {
                PdoExtension = (*PdoExtension).Next;
                PdoCount += 1;
            }

            if !(*DeviceRelations).is_null() {
                PdoCount += (*(*DeviceRelations)).Count;
            }

            FdoRelations = ExAllocatePoolWithTag(
                PagedPool,
                core::mem::offset_of!(DEVICE_RELATIONS, Objects) as ULONG
                    + core::mem::size_of::<PDEVICE_OBJECT>() as ULONG * PdoCount,
                TAG_HAL,
            ) as PDEVICE_RELATIONS;
            if FdoRelations.is_null() {
                return STATUS_INSUFFICIENT_RESOURCES;
            }

            (*FdoRelations).Count = PdoCount;

            ObjectEntry = (*FdoRelations).Objects.as_mut_ptr();
            if !(*DeviceRelations).is_null() {
                if (*(*DeviceRelations)).Count != 0 {
                    loop {
                        *ObjectEntry = (*(*DeviceRelations)).Objects[i as usize];
                        ObjectEntry = ObjectEntry.add(1);
                        i += 1;
                        if i >= (*(*DeviceRelations)).Count {
                            break;
                        }
                    }
                }

                ExFreePool(*DeviceRelations as PVOID);
            }

            PdoExtension = (*FdoExtension).ChildPdoList;
            if !PdoExtension.is_null() {
                loop {
                    *ObjectEntry = (*PdoExtension).PhysicalDeviceObject;
                    ObReferenceObject((*PdoExtension).PhysicalDeviceObject as PVOID);
                    ObjectEntry = ObjectEntry.add(1);

                    PdoExtension = (*PdoExtension).Next;
                    if PdoExtension.is_null() {
                        break;
                    }
                }
            }

            *DeviceRelations = FdoRelations;
            return STATUS_SUCCESS;
        }
    } else {
        if (RelationType == TargetDeviceRelation as DEVICE_RELATION_TYPE)
            && (ExtensionType == PdoExtensionType)
        {
            PdoRelations = ExAllocatePoolWithTag(
                PagedPool,
                core::mem::size_of::<DEVICE_RELATIONS>() as ULONG,
                TAG_HAL,
            ) as PDEVICE_RELATIONS;
            if PdoRelations.is_null() {
                return STATUS_INSUFFICIENT_RESOURCES;
            }

            (*PdoRelations).Count = 1;
            (*PdoRelations).Objects[0] = DeviceObject;
            ObReferenceObject(DeviceObject as PVOID);

            *DeviceRelations = PdoRelations;
            return STATUS_SUCCESS;
        }
    }

    STATUS_NOT_SUPPORTED
}

#[no_mangle]
pub unsafe extern "system" fn HalpQueryCapabilities(
    DeviceObject: PDEVICE_OBJECT,
    Capabilities: PDEVICE_CAPABILITIES,
) -> NTSTATUS {
    let _ = DeviceObject;
    
    let status: NTSTATUS;
    
    if (*Capabilities).Version == 1 {
        (*Capabilities).LockSupported = 0;
        (*Capabilities).EjectSupported = 0;
        
        (*Capabilities).Removable = 0;
        (*Capabilities).DockDevice = 0;
        
        (*Capabilities).RawDeviceOK = 0;
        
        (*Capabilities).UniqueID = 1;
        (*Capabilities).SilentInstall = 1;
        
        (*Capabilities).Address = 0xFFFFFFFF;
        (*Capabilities).UINumber = 0xFFFFFFFF;
        
        (*Capabilities).D1Latency = 0;
        (*Capabilities).D2Latency = 0;
        (*Capabilities).D3Latency = 0;
        
        (*Capabilities).DeviceState[0] = 1;
        (*Capabilities).DeviceState[4] = 4;
        (*Capabilities).DeviceState[5] = 4;
        (*Capabilities).DeviceState[3] = 4;
        
        status = STATUS_SUCCESS;
    } else {
        status = 0xC0000002u32 as NTSTATUS;
    }
    
    status
}

#[no_mangle]
pub unsafe extern "system" fn HalpQueryResources(
    DeviceObject: PDEVICE_OBJECT,
    Resources: *mut PCM_RESOURCE_LIST,
) -> NTSTATUS {
    let DeviceExtension = (*DeviceObject).DeviceExtension as *mut PDO_EXTENSION;
    let Status: NTSTATUS;
    let ResourceList: PCM_RESOURCE_LIST;

    if (*DeviceExtension).PdoType == AcpiPdo {
        ResourceList = ExAllocatePoolWithTag(
            PagedPool,
            core::mem::size_of::<CM_RESOURCE_LIST>() as ULONG,
            TAG_HAL,
        ) as PCM_RESOURCE_LIST;
        
        if ResourceList.is_null() {
            Status = STATUS_INSUFFICIENT_RESOURCES;
            return Status;
        }

        RtlZeroMemory(
            ResourceList as PVOID,
            core::mem::size_of::<CM_RESOURCE_LIST>() as ULONG,
        );
        (*ResourceList).Count = 1;

        (*ResourceList).List[0].BusNumber = 0;
        (*ResourceList).List[0].InterfaceType = PCIBus;
        (*ResourceList).List[0].PartialResourceList.Version = 1;
        (*ResourceList).List[0].PartialResourceList.Revision = 1;
        (*ResourceList).List[0].PartialResourceList.Count = 0;

        *Resources = ResourceList;

        return STATUS_SUCCESS;
    } else if (*DeviceExtension).PdoType == WdPdo {
        return STATUS_NOT_SUPPORTED;
    } else {
        return STATUS_UNSUCCESSFUL;
    }
}

