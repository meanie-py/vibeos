#[no_mangle]
pub unsafe extern "system" fn HalpAddDevice(
    DriverObject: PDRIVER_OBJECT,
    TargetDevice: PDEVICE_OBJECT,
) -> NTSTATUS {
    let mut Status: NTSTATUS;
    let FdoExtension: PFDO_EXTENSION;
    let PdoExtension: PPDO_EXTENSION;
    let mut DeviceObject: PDEVICE_OBJECT = core::ptr::null_mut();
    let AttachedDevice: PDEVICE_OBJECT;
    let mut PdoDeviceObject: PDEVICE_OBJECT = core::ptr::null_mut();

    Status = IoCreateDevice(
        DriverObject,
        core::mem::size_of::<FDO_EXTENSION>() as ULONG,
        core::ptr::null_mut(),
        FILE_DEVICE_BUS_EXTENDER,
        0,
        0,
        &raw mut DeviceObject,
    );
    if !NT_SUCCESS(Status) {
        DbgBreakPoint();
        return Status;
    }

    FdoExtension = (*DeviceObject).DeviceExtension as PFDO_EXTENSION;
    (*FdoExtension).ExtensionType = FdoExtensionType;
    (*FdoExtension).PhysicalDeviceObject = TargetDevice;
    (*FdoExtension).FunctionalDeviceObject = DeviceObject;
    (*FdoExtension).ChildPdoList = core::ptr::null_mut();

    (*DeviceObject).Flags &= !DO_DEVICE_INITIALIZING;

    AttachedDevice = IoAttachDeviceToDeviceStack(DeviceObject, TargetDevice);
    if AttachedDevice.is_null() {
        IoDeleteDevice(DeviceObject);
        return STATUS_NO_SUCH_DEVICE;
    }

    (*FdoExtension).AttachedDeviceObject = AttachedDevice;

    Status = IoCreateDevice(
        DriverObject,
        core::mem::size_of::<PDO_EXTENSION>() as ULONG,
        core::ptr::null_mut(),
        FILE_DEVICE_BUS_EXTENDER,
        FILE_AUTOGENERATED_DEVICE_NAME,
        0,
        &raw mut PdoDeviceObject,
    );
    if !NT_SUCCESS(Status) {
        return Status;
    }

    PdoExtension = (*PdoDeviceObject).DeviceExtension as PPDO_EXTENSION;
    (*PdoExtension).ExtensionType = PdoExtensionType;
    (*PdoExtension).PhysicalDeviceObject = PdoDeviceObject;
    (*PdoExtension).ParentFdoExtension = FdoExtension;
    (*PdoExtension).PdoType = AcpiPdo;

    (*PdoExtension).Next = (*FdoExtension).ChildPdoList;
    (*FdoExtension).ChildPdoList = PdoExtension;

    (*PdoDeviceObject).Flags &= !DO_DEVICE_INITIALIZING;

    Status
}

