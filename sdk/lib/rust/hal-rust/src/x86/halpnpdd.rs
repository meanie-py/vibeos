#[unsafe(no_mangle)]
pub unsafe extern "system" fn HalpDispatchPower(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
) -> NTSTATUS {
    unsafe {
        let fdo = (*DeviceObject).DeviceExtension as *mut FDO_EXTENSION;
        if (*fdo).ExtensionType == EXT_FDO {
            PoStartNextPowerIrp(Irp);
            io_skip_current_stack_location(Irp);
            return PoCallDriver((*fdo).AttachedDeviceObject, Irp);
        }
        PoStartNextPowerIrp(Irp);
        (*Irp).IoStatus.__bindgen_anon_1.Status = STATUS_SUCCESS;
        IoCompleteRequest(Irp, IO_NO_INCREMENT as CCHAR);
        STATUS_SUCCESS
    }
}

// ---------------------------------------------------------------------------
// HalpDriverEntry — DriverObject hookup + the synthetic device we report.
// ---------------------------------------------------------------------------

#[unsafe(no_mangle)]
pub unsafe extern "system" fn HalpDriverEntry(
    DriverObject: PDRIVER_OBJECT,
    _RegistryPath: PUNICODE_STRING,
) -> NTSTATUS {
    unsafe {
        HalpDriverObject = DriverObject;

        // C: DriverObject->DriverExtension->AddDevice = HalpAddDevice;
        // bindgen's AddDevice is an NTAPI function pointer; on amd64 this is C ABI.
        (*(*DriverObject).DriverExtension).AddDevice =
            Some(core::mem::transmute(HalpAddDevice as usize));

        (*DriverObject).MajorFunction[IRP_MJ_PNP as usize] =
            Some(core::mem::transmute(HalpDispatchPnp as usize));
        (*DriverObject).MajorFunction[IRP_MJ_POWER as usize] =
            Some(core::mem::transmute(HalpDispatchPower as usize));
        (*DriverObject).MajorFunction[IRP_MJ_SYSTEM_CONTROL as usize] =
            Some(core::mem::transmute(HalpDispatchWmi as usize));

        let mut target_device: PDEVICE_OBJECT = core::ptr::null_mut();
        let status = IoReportDetectedDevice(
            DriverObject,
            IFT_UNDEF,
            !0u32, // -1
            !0u32, // -1
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            0,
            &raw mut target_device,
        );
        if !nt_success(status) {
            return status;
        }
        (*target_device).Flags &= !DO_DEVICE_INITIALIZING;

        let status = HalpAddDevice(DriverObject, target_device);
        if !nt_success(status) {
            IoDeleteDevice(target_device);
            return status;
        }
        status
    }
}

// ---------------------------------------------------------------------------
// HaliInitPnpDriver — register the driver with the PnP subsystem.
// ---------------------------------------------------------------------------

#[unsafe(no_mangle)]
pub unsafe extern "system" fn HaliInitPnpDriver() -> NTSTATUS {
    unsafe {
        let mut driver_name: _UNICODE_STRING = core::mem::zeroed();
        // RtlInitUnicodeString of L"\\Driver\\ACPI_HAL".
        let chars = (DRIVER_NAME_ACPIHAL.len() - 1) as USHORT; // exclude NUL
        driver_name.Length = chars * 2;
        driver_name.MaximumLength = (DRIVER_NAME_ACPIHAL.len() as USHORT) * 2;
        driver_name.Buffer = DRIVER_NAME_ACPIHAL.as_ptr() as *mut u16;
        IoCreateDriver(&raw mut driver_name, HalpDriverEntry)
    }
}
