//! ACPI HAL PnP driver — translated from `hal/halx86/acpi/halpnpdd.c`.
//!
//! amd64-only (acpi.cmake is included by the amd64 HAL).  Acts as the PnP
//! root bus driver for the ACPI HAL: presents a single ACPI PDO under a
//! HAL-rooted FDO, dispatches PnP/Power/WMI IRPs, and synthesizes the
//! device-relations/capabilities/resources required by the ACPI HAL surface.
//!
//! Function list (all NTAPI):
//!   HaliInitPnpDriver        — driver registration entry
//!   HalpDriverEntry          — DriverObject hookup + IoReportDetectedDevice
//!   HalpAddDevice            — FDO + ACPI PDO instantiation
//!   HalpDispatchPnp          — PnP IRP demux
//!   HalpDispatchPower        — pass-through power IRP handler
//!   HalpDispatchWmi          — stub (UNIMPLEMENTED)
//!   HalpQueryDeviceRelations — BusRelations / TargetDeviceRelation
//!   HalpQueryInterface       — STATUS_NOT_SUPPORTED stub
//!   HalpQueryCapabilities    — fill out PDO/FDO capabilities
//!   HalpQueryResources       — CM_RESOURCE_LIST from ACPI SCI requirements
//!   HalpQueryResourceRequirements — HalpQueryAcpiResourceRequirements
//!   HalpQueryIdPdo           — ACPI_HAL\PNP0C08 hardware ID, instance "0"
//!   HalpQueryIdFdo           — HalHardwareIdString, instance "0"

// Built for i386 too (task #4 ACPI-HAL backport) — replaces legacy_halpnpdd
// (PCI_HAL\PNP0A03) on i386 so the HAL root advertises ACPI_HAL\PNP0C08.

