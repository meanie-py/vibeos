// ---------------------------------------------------------------------------
// HalpQueryDeviceRelations — BusRelations: enumerate child PDOs (and merge
// any pre-existing relations the parent included).  TargetDeviceRelation
// (for PDOs): return self.
// ---------------------------------------------------------------------------

#[unsafe(no_mangle)]
pub unsafe extern "system" fn HalpQueryDeviceRelations(
    DeviceObject: PDEVICE_OBJECT,
    RelationType: u32, /* DEVICE_RELATION_TYPE */
    DeviceRelations: *mut PDEVICE_RELATIONS,
) -> NTSTATUS {
    unsafe {
        let fdo = (*DeviceObject).DeviceExtension as *mut FDO_EXTENSION;
        let ext_type = (*fdo).ExtensionType;

        if RelationType == REL_BUS {
            if ext_type == EXT_FDO {
                let mut pdo_iter = (*fdo).ChildPdoList;
                let mut pdo_count: ULONG = 0;
                while !pdo_iter.is_null() {
                    pdo_iter = (*pdo_iter).Next;
                    pdo_count += 1;
                }
                if !(*DeviceRelations).is_null() {
                    pdo_count += (**DeviceRelations).Count;
                }
                let alloc_size = core::mem::offset_of!(DEVICE_RELATIONS, Objects)
                    + core::mem::size_of::<PDEVICE_OBJECT>() * pdo_count as usize;
                let fdo_relations =
                    ExAllocatePoolWithTag(PAGED_POOL, alloc_size, TAG_HAL) as PDEVICE_RELATIONS;
                if fdo_relations.is_null() {
                    return STATUS_INSUFFICIENT_RESOURCES;
                }
                (*fdo_relations).Count = pdo_count;
                let mut object_entry = (*fdo_relations).Objects.as_mut_ptr();

                if !(*DeviceRelations).is_null() {
                    let existing = *DeviceRelations;
                    if (*existing).Count != 0 {
                        for i in 0..(*existing).Count as usize {
                            *object_entry = *(*existing).Objects.as_ptr().add(i);
                            object_entry = object_entry.add(1);
                        }
                    }
                    ExFreePool(existing as PVOID);
                }

                let mut pdo_iter = (*fdo).ChildPdoList;
                while !pdo_iter.is_null() {
                    *object_entry = (*pdo_iter).PhysicalDeviceObject;
                    ob_reference_object((*pdo_iter).PhysicalDeviceObject as PVOID);
                    object_entry = object_entry.add(1);
                    pdo_iter = (*pdo_iter).Next;
                }
                *DeviceRelations = fdo_relations;
                return STATUS_SUCCESS;
            }
        } else if RelationType == REL_TARGET && ext_type == EXT_PDO {
            let pdo_relations = ExAllocatePoolWithTag(
                PAGED_POOL,
                core::mem::size_of::<DEVICE_RELATIONS>(),
                TAG_HAL,
            ) as PDEVICE_RELATIONS;
            if pdo_relations.is_null() {
                return STATUS_INSUFFICIENT_RESOURCES;
            }
            (*pdo_relations).Count = 1;
            *(*pdo_relations).Objects.as_mut_ptr() = DeviceObject;
            ob_reference_object(DeviceObject as PVOID);
            *DeviceRelations = pdo_relations;
            return STATUS_SUCCESS;
        }

        STATUS_NOT_SUPPORTED
    }
}

// ---------------------------------------------------------------------------
// HalpQueryCapabilities — pin down the immutable capability flags.
// ---------------------------------------------------------------------------

#[unsafe(no_mangle)]
pub unsafe extern "system" fn HalpQueryCapabilities(
    _DeviceObject: PDEVICE_OBJECT,
    Capabilities: PDEVICE_CAPABILITIES,
) -> NTSTATUS {
    unsafe {
        if (*Capabilities).Version != 1 {
            return STATUS_NOT_SUPPORTED;
        }
        // Single bit-field via __bindgen_anon_1; the C code only writes flags
        // by name and bindgen exposes setter helpers.
        (*Capabilities).set_LockSupported(0);
        (*Capabilities).set_EjectSupported(0);
        (*Capabilities).set_Removable(0);
        (*Capabilities).set_DockDevice(0);
        (*Capabilities).set_RawDeviceOK(0);
        (*Capabilities).set_UniqueID(1);
        (*Capabilities).set_SilentInstall(1);

        // C: `Capabilities->Address = InterfaceTypeUndefined;` — that's -1 as ULONG.
        (*Capabilities).Address = IFT_UNDEF as ULONG;
        (*Capabilities).UINumber = IFT_UNDEF as ULONG;
        (*Capabilities).D1Latency = 0;
        (*Capabilities).D2Latency = 0;
        (*Capabilities).D3Latency = 0;

        (*Capabilities).DeviceState[PS_WORKING as usize] = PD_D0;
        (*Capabilities).DeviceState[PS_HIBERNATE as usize] = PD_D3;
        (*Capabilities).DeviceState[PS_SHUTDOWN as usize] = PD_D3;
        (*Capabilities).DeviceState[PS_SLEEPING3 as usize] = PD_D3;
        STATUS_SUCCESS
    }
}

// ---------------------------------------------------------------------------
// HalpQueryResources — single-entry CM_RESOURCE_LIST for the ACPI PDO,
// populated from HalpQueryAcpiResourceRequirements when the SCI descriptor is
// present.
// ---------------------------------------------------------------------------

#[unsafe(no_mangle)]
pub unsafe extern "system" fn HalpQueryResources(
    DeviceObject: PDEVICE_OBJECT,
    Resources: *mut PCM_RESOURCE_LIST,
) -> NTSTATUS {
    unsafe {
        let pdo = (*DeviceObject).DeviceExtension as *mut PDO_EXTENSION;
        if (*pdo).PdoType == PDO_ACPI {
            let mut requirements: PIO_RESOURCE_REQUIREMENTS_LIST = core::ptr::null_mut();
            let status = HalpQueryAcpiResourceRequirements(&raw mut requirements);
            if !nt_success(status) {
                return status;
            }

            let resource_list = ExAllocatePoolWithTag(
                PAGED_POOL,
                core::mem::size_of::<CM_RESOURCE_LIST>(),
                TAG_HAL,
            ) as PCM_RESOURCE_LIST;
            if resource_list.is_null() {
                ExFreePoolWithTag(requirements as PVOID, TAG_HAL);
                return STATUS_INSUFFICIENT_RESOURCES;
            }
            core::ptr::write_bytes(
                resource_list as *mut u8,
                0,
                core::mem::size_of::<CM_RESOURCE_LIST>(),
            );
            (*resource_list).Count = 1;
            let list0 = (*resource_list).List.as_mut_ptr();
            // i386: HalpLookupHandler indexes Element[BusNumber] guarded by
            // ArraySize >= BusNumber, so BusNumber = -1 (0xFFFFFFFF) never
            // matches; the legacy Internal handler is registered at bus 0.
            // amd64's ACPI HAL tolerates -1 (PNPBus path). Task #4.
            #[cfg(target_arch = "x86_64")]
            {
                (*list0).BusNumber = -1i32 as ULONG;
            }
            #[cfg(target_arch = "x86")]
            {
                (*list0).BusNumber = 0;
            }
            // ACPI PDO's SCI interrupt is translated via the HAL bus handler
            // for this InterfaceType. amd64's ACPI HAL (busemul) registers a
            // PNPBus handler; the i386 backport keeps legacy bussupp, which
            // registers only Internal(0)/Isa(1) — no PNPBus(15) handler, so
            // HalGetInterruptVector(PNPBus) returns 0 and
            // IopTranslateDeviceResources fails (STATUS_UNSUCCESSFUL),
            // stalling the ACPI_HAL devnode. The SCI is a fixed motherboard
            // PIC IRQ, so `Internal` (identity PIC translation) is correct on
            // i386. Task #4. (Sibling fix in halacpi HalpBuildAcpiResourceList
            // covers the requirements list; this is the boot CM list.)
            #[cfg(target_arch = "x86_64")]
            {
                (*list0).InterfaceType = IFT_PNPBUS;
            }
            #[cfg(target_arch = "x86")]
            {
                (*list0).InterfaceType = IFT_INTERNAL;
            }
            (*list0).PartialResourceList.Version = 1;
            (*list0).PartialResourceList.Revision = 1;
            (*list0).PartialResourceList.Count = 0;

            let partial_desc = (*list0).PartialResourceList.PartialDescriptors.as_mut_ptr()
                as PCM_PARTIAL_RESOURCE_DESCRIPTOR;
            let req_list0 = (*requirements).List.as_mut_ptr();
            for i in 0..(*req_list0).Count as usize {
                let descriptor =
                    (*req_list0).Descriptors.as_mut_ptr().add(i) as PIO_RESOURCE_DESCRIPTOR;
                if (*descriptor).Type == CmResourceTypeInterrupt as u8 {
                    (*partial_desc).Type = CmResourceTypeInterrupt as u8;
                    (*partial_desc).ShareDisposition = (*descriptor).ShareDisposition;
                    (*partial_desc).Flags = (*descriptor).Flags;
                    (*partial_desc).u.Interrupt.Vector = (*descriptor).u.Interrupt.MinimumVector;
                    (*partial_desc).u.Interrupt.Level = (*descriptor).u.Interrupt.MinimumVector;
                    (*partial_desc).u.Interrupt.Affinity = 0xFFFF_FFFF;
                    (*list0).PartialResourceList.Count += 1;
                    break;
                }
            }

            *Resources = resource_list;
            ExFreePoolWithTag(requirements as PVOID, TAG_HAL);
            STATUS_SUCCESS
        } else if (*pdo).PdoType == PDO_WD {
            STATUS_NOT_SUPPORTED
        } else {
            STATUS_UNSUCCESSFUL
        }
    }
}

// ---------------------------------------------------------------------------
// HalpQueryResourceRequirements — defer to halacpi.rs for ACPI SCI
// requirements; STATUS_NOT_SUPPORTED otherwise.
// ---------------------------------------------------------------------------

#[unsafe(no_mangle)]
pub unsafe extern "system" fn HalpQueryResourceRequirements(
    DeviceObject: PDEVICE_OBJECT,
    _Requirements: *mut PIO_RESOURCE_REQUIREMENTS_LIST,
) -> NTSTATUS {
    unsafe {
        let pdo = (*DeviceObject).DeviceExtension as *mut PDO_EXTENSION;
        if (*pdo).PdoType == PDO_ACPI {
            HalpQueryAcpiResourceRequirements(_Requirements)
        } else if (*pdo).PdoType == PDO_WD {
            STATUS_NOT_SUPPORTED
        } else {
            STATUS_UNSUCCESSFUL
        }
    }
}

// ---------------------------------------------------------------------------
// HalpQueryIdPdo — concatenate two UTF-16 strings into a freshly-allocated
// pool buffer.  Both strings are NUL-terminated and the buffer ends with a
// double NUL to mark the end of the multi-string.
// ---------------------------------------------------------------------------

#[unsafe(no_mangle)]
pub unsafe extern "system" fn HalpQueryIdPdo(
    DeviceObject: PDEVICE_OBJECT,
    IdType: u32, /* BUS_QUERY_ID_TYPE */
    BusQueryId: *mut PUSHORT,
) -> NTSTATUS {
    unsafe {
        let pdo = (*DeviceObject).DeviceExtension as *mut PDO_EXTENSION;
        let pdo_type = (*pdo).PdoType;

        let mut id_buffer: [u16; 100] = [0; 100];
        let mut length: usize = 0;

        if IdType == BQID_DEVICE || IdType == BQID_HARDWARE {
            let (device_id, compat_id) = if pdo_type == PDO_ACPI {
                (&ID_ACPI_DEVICE[..], &ID_ACPI_COMPAT[..])
            } else if pdo_type == PDO_WD {
                (&ID_WD_DEVICE[..], &ID_WD_COMPAT[..])
            } else {
                return STATUS_NOT_SUPPORTED;
            };

            let first_bytes = device_id.len() * 2;
            core::ptr::copy_nonoverlapping(
                device_id.as_ptr() as *const u8,
                id_buffer.as_mut_ptr() as *mut u8,
                first_bytes,
            );
            length += first_bytes;

            let first_u16s = device_id.len();
            let second_bytes = compat_id.len() * 2;
            core::ptr::copy_nonoverlapping(
                compat_id.as_ptr() as *const u8,
                id_buffer.as_mut_ptr().add(first_u16s) as *mut u8,
                second_bytes,
            );
            length += second_bytes;
        } else if IdType == BQID_INSTANCE {
            let bytes = ID_INSTANCE_ZERO.len() * 2;
            core::ptr::copy_nonoverlapping(
                ID_INSTANCE_ZERO.as_ptr() as *const u8,
                id_buffer.as_mut_ptr() as *mut u8,
                bytes,
            );
            length += bytes;
        } else {
            return STATUS_NOT_SUPPORTED;
        }

        // Plus one final NUL (double-NUL terminator for multi-string).
        let buffer = ExAllocatePoolWithTag(PAGED_POOL, length + 2, TAG_HAL) as PUSHORT;
        if buffer.is_null() {
            return STATUS_INSUFFICIENT_RESOURCES;
        }
        core::ptr::copy_nonoverlapping(id_buffer.as_ptr() as *const u8, buffer as *mut u8, length);
        *buffer.add(length / 2) = 0;
        *BusQueryId = buffer;
        STATUS_SUCCESS
    }
}

// ---------------------------------------------------------------------------
// HalpQueryIdFdo — return either HalHardwareIdString or "0", as a fresh
// pool buffer.
// ---------------------------------------------------------------------------

#[unsafe(no_mangle)]
pub unsafe extern "system" fn HalpQueryIdFdo(
    _DeviceObject: PDEVICE_OBJECT,
    IdType: u32,
    BusQueryId: *mut PUSHORT,
) -> NTSTATUS {
    unsafe {
        let id: *const u16 = if IdType == BQID_DEVICE || IdType == BQID_HARDWARE {
            HalHardwareIdString as *const u16
        } else if IdType == BQID_INSTANCE {
            ID_INSTANCE_ZERO.as_ptr()
        } else {
            return STATUS_NOT_SUPPORTED;
        };

        let len = wcslen(id);
        let length_bytes = (len * 2) + 2; // chars * sizeof(WCHAR) + UNICODE_NULL
        let buffer = ExAllocatePoolWithTag(PAGED_POOL, length_bytes + 2, TAG_HAL) as PUSHORT;
        if buffer.is_null() {
            return STATUS_INSUFFICIENT_RESOURCES;
        }
        core::ptr::copy_nonoverlapping(id as *const u8, buffer as *mut u8, length_bytes);
        *buffer.add(length_bytes / 2) = 0;
        *BusQueryId = buffer;
        STATUS_SUCCESS
    }
}

// ---------------------------------------------------------------------------
// HalpDispatchPnp — full IRP demux per ExtensionType.  Closely follows the
// C structure; comments correspond to C cases.
// ---------------------------------------------------------------------------

#[unsafe(no_mangle)]
pub unsafe extern "system" fn HalpDispatchPnp(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS {
    unsafe {
        let fdo = (*DeviceObject).DeviceExtension as *mut FDO_EXTENSION;
        let io_stack = io_get_current_stack_location(Irp);
        let minor = (*io_stack).MinorFunction as ULONG;

        // Helper: PVOID slot for IoStatus.Information at the right offset.
        let info_slot = &raw mut (*Irp).IoStatus.Information as *mut PVOID;

        if (*fdo).ExtensionType == EXT_FDO {
            let mut status = match minor {
                m if m == IRP_MN_QUERY_DEVICE_RELATIONS => HalpQueryDeviceRelations(
                    DeviceObject,
                    (*io_stack).Parameters.QueryDeviceRelations.Type,
                    info_slot as *mut PDEVICE_RELATIONS,
                ),
                m if m == IRP_MN_QUERY_INTERFACE => HalpQueryInterface(
                    DeviceObject,
                    (*io_stack).Parameters.QueryInterface.InterfaceType,
                    (*io_stack).Parameters.QueryInterface.Size,
                    (*io_stack).Parameters.QueryInterface.InterfaceSpecificData,
                    (*io_stack).Parameters.QueryInterface.Version as ULONG,
                    (*io_stack).Parameters.QueryInterface.Interface,
                    info_slot as *mut ULONG,
                ),
                m if m == IRP_MN_QUERY_ID => HalpQueryIdFdo(
                    DeviceObject,
                    (*io_stack).Parameters.QueryId.IdType,
                    info_slot as *mut PUSHORT,
                ),
                m if m == IRP_MN_QUERY_CAPABILITIES => HalpQueryCapabilities(
                    DeviceObject,
                    (*io_stack).Parameters.DeviceCapabilities.Capabilities,
                ),
                _ => STATUS_NOT_SUPPORTED,
            };

            if nt_success(status) || status == STATUS_NOT_SUPPORTED {
                if status != STATUS_NOT_SUPPORTED {
                    (*Irp).IoStatus.__bindgen_anon_1.Status = status;
                }
                io_skip_current_stack_location(Irp);
                return io_call_driver((*fdo).AttachedDeviceObject, Irp);
            }
            (*Irp).IoStatus.__bindgen_anon_1.Status = status;
            IoCompleteRequest(Irp, IO_NO_INCREMENT as CCHAR);
            return status;
        }

        // PDO path — `fdo` here is actually a PDO_EXTENSION* (same offset 0).
        let mut status: NTSTATUS = STATUS_SUCCESS;
        match minor {
            m if m == IRP_MN_START_DEVICE => { /* Complete normally. */ }
            m if m == IRP_MN_REMOVE_DEVICE => {
                status = STATUS_SUCCESS;
            }
            m if m == IRP_MN_SURPRISE_REMOVAL => {
                status = (*Irp).IoStatus.__bindgen_anon_1.Status;
            }
            m if m == IRP_MN_QUERY_DEVICE_RELATIONS => {
                status = HalpQueryDeviceRelations(
                    DeviceObject,
                    (*io_stack).Parameters.QueryDeviceRelations.Type,
                    info_slot as *mut PDEVICE_RELATIONS,
                );
            }
            m if m == IRP_MN_QUERY_INTERFACE => {
                status = HalpQueryInterface(
                    DeviceObject,
                    (*io_stack).Parameters.QueryInterface.InterfaceType,
                    (*io_stack).Parameters.QueryInterface.Size,
                    (*io_stack).Parameters.QueryInterface.InterfaceSpecificData,
                    (*io_stack).Parameters.QueryInterface.Version as ULONG,
                    (*io_stack).Parameters.QueryInterface.Interface,
                    info_slot as *mut ULONG,
                );
            }
            m if m == IRP_MN_QUERY_CAPABILITIES => {
                status = HalpQueryCapabilities(
                    DeviceObject,
                    (*io_stack).Parameters.DeviceCapabilities.Capabilities,
                );
            }
            m if m == IRP_MN_QUERY_RESOURCES => {
                status = HalpQueryResources(DeviceObject, info_slot as *mut PCM_RESOURCE_LIST);
            }
            m if m == IRP_MN_QUERY_RESOURCE_REQUIREMENTS => {
                status = HalpQueryResourceRequirements(
                    DeviceObject,
                    info_slot as *mut PIO_RESOURCE_REQUIREMENTS_LIST,
                );
            }
            m if m == IRP_MN_QUERY_ID => {
                status = HalpQueryIdPdo(
                    DeviceObject,
                    (*io_stack).Parameters.QueryId.IdType,
                    info_slot as *mut PUSHORT,
                );
            }
            m if m == IRP_MN_QUERY_DEVICE_TEXT
                || m == IRP_MN_FILTER_RESOURCE_REQUIREMENTS
                || m == IRP_MN_QUERY_PNP_DEVICE_STATE
                || m == IRP_MN_QUERY_BUS_INFORMATION =>
            {
                status = (*Irp).IoStatus.__bindgen_anon_1.Status;
            }
            _ => {
                status = (*Irp).IoStatus.__bindgen_anon_1.Status;
            }
        }
        if status == STATUS_NOT_SUPPORTED {
            status = (*Irp).IoStatus.__bindgen_anon_1.Status;
        }
        (*Irp).IoStatus.__bindgen_anon_1.Status = status;
        IoCompleteRequest(Irp, IO_NO_INCREMENT as CCHAR);
        status
    }
}

