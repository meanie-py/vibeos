// ---------------------------------------------------------------------------
// HalpAddDevice — create FDO + ACPI PDO, attach FDO to bus.
// ---------------------------------------------------------------------------

#[unsafe(no_mangle)]
pub unsafe extern "system" fn HalpAddDevice(
    DriverObject: PDRIVER_OBJECT,
    TargetDevice: PDEVICE_OBJECT,
) -> NTSTATUS {
    unsafe {
        let mut device_object: PDEVICE_OBJECT = core::ptr::null_mut();
        let status = IoCreateDevice(
            DriverObject,
            core::mem::size_of::<FDO_EXTENSION>() as ULONG,
            core::ptr::null_mut(),
            FILE_DEVICE_BUS_EXTENDER,
            0,
            0,
            &raw mut device_object,
        );
        if !nt_success(status) {
            DbgBreakPoint();
            return status;
        }

        let fdo = (*device_object).DeviceExtension as *mut FDO_EXTENSION;
        (*fdo).ExtensionType = EXT_FDO;
        (*fdo).PhysicalDeviceObject = TargetDevice;
        (*fdo).FunctionalDeviceObject = device_object;
        (*fdo).ChildPdoList = core::ptr::null_mut();

        (*device_object).Flags &= !DO_DEVICE_INITIALIZING;

        let attached = IoAttachDeviceToDeviceStack(device_object, TargetDevice);
        if attached.is_null() {
            IoDeleteDevice(device_object);
            return STATUS_NO_SUCH_DEVICE;
        }
        (*fdo).AttachedDeviceObject = attached;

        let mut pdo_device: PDEVICE_OBJECT = core::ptr::null_mut();
        let status = IoCreateDevice(
            DriverObject,
            core::mem::size_of::<PDO_EXTENSION>() as ULONG,
            core::ptr::null_mut(),
            FILE_DEVICE_BUS_EXTENDER,
            FILE_AUTOGENERATED_DEVICE_NAME,
            0,
            &raw mut pdo_device,
        );
        if !nt_success(status) {
            return status;
        }

        let pdo = (*pdo_device).DeviceExtension as *mut PDO_EXTENSION;
        (*pdo).ExtensionType = EXT_PDO;
        (*pdo).PhysicalDeviceObject = pdo_device;
        (*pdo).ParentFdoExtension = fdo;
        (*pdo).PdoType = PDO_ACPI;
        (*pdo).Next = (*fdo).ChildPdoList;
        (*fdo).ChildPdoList = pdo;

        (*pdo_device).Flags &= !DO_DEVICE_INITIALIZING;
        if !HalAcpiGetTable(core::ptr::null_mut(), WDRT_SIGNATURE).is_null() {
            // The C path only logs this and leaves watchdog support as TODO.
        }
        status
    }
}

