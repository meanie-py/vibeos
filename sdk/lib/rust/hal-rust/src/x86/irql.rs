//! IRQL ↔ 8259 PIC mask lookup tables for the i386 PIC HAL.
//!
//! Translated from `hal/halx86/pic/irql.c`.  Two parallel 32-entry
//! `[ULONG; 32]` tables indexed by KIRQL:
//!
//!   KiI8259MaskTable[irql]   — bits to OR into the 8259 IMR to mask
//!                              everything at or below the given IRQL
//!                              (consumed by pic.c::HalpEndSystemInterrupt
//!                              and friends to program the PIC IMR).
//!   FindHigherIrqlMask[irql] — bits in PCR.IRR that can still preempt
//!                              while running at the given IRQL
//!                              (consumed by pic.c::HalpDispatchInterrupt
//!                              when deciding whether to re-raise).
//!
//! The verbose comments in the C source explaining the bit layouts
//! (RTC at IRQ8 staying on until PROFILE_LEVEL, the IRQ2 cascade bit
//! that never gets masked, IRQL 24/25 + 18/19 being deliberately
//! identical to spread masks over 32 IRQLs) are kept in the C
//! historically — the table values speak for themselves and copying
//! the prose verbatim into Rust wouldn't add information.

use ntkrnl_sys::hal_ddk::ULONG;

#[unsafe(no_mangle)]
pub static KiI8259MaskTable: [ULONG; 32] = [
    0b00000000000000000000000000000000, // IRQL 0
    0b00000000000000000000000000000000, // IRQL 1
    0b00000000000000000000000000000000, // IRQL 2
    0b00000000000000000000000000000000, // IRQL 3
    0b11111111100000000000000000000000, // IRQL 4
    0b11111111110000000000000000000000, // IRQL 5
    0b11111111111000000000000000000000, // IRQL 6
    0b11111111111100000000000000000000, // IRQL 7
    0b11111111111110000000000000000000, // IRQL 8
    0b11111111111111000000000000000000, // IRQL 9
    0b11111111111111100000000000000000, // IRQL 10
    0b11111111111111110000000000000000, // IRQL 11
    0b11111111111111111000000000000000, // IRQL 12
    0b11111111111111111100000000000000, // IRQL 13
    0b11111111111111111110000000000000, // IRQL 14
    0b11111111111111111111000000000000, // IRQL 15
    0b11111111111111111111100000000000, // IRQL 16
    0b11111111111111111111110000000000, // IRQL 17
    0b11111111111111111111111000000000, // IRQL 18
    0b11111111111111111111111000000000, // IRQL 19 (identical to 18)
    0b11111111111111111111111010000000, // IRQL 20 — IRQ8 (RTC) stays unmasked
    0b11111111111111111111111011000000, // IRQL 21
    0b11111111111111111111111011100000, // IRQL 22
    0b11111111111111111111111011110000, // IRQL 23
    0b11111111111111111111111011111000, // IRQL 24
    0b11111111111111111111111011111000, // IRQL 25 (identical to 24)
    0b11111111111111111111111011111010, // IRQL 26
    0b11111111111111111111111111111010, // IRQL 27 — PROFILE_LEVEL kills RTC
    0b11111111111111111111111111111011, // IRQL 28 — CLOCK2_LEVEL
    0b11111111111111111111111111111011, // IRQL 29
    0b11111111111111111111111111111011, // IRQL 30
    0b11111111111111111111111111111011, // IRQL 31 — IRQ2 (cascade) always 0
];

