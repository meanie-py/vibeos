unsafe fn query_id(pdo: &PdoExtension, id_type: u32, out: *mut PVOID) -> NTSTATUS {
    let ids: &[u16] = match pdo.child {
        Child::Xhci => &XHCI_HARDWARE_IDS,
        Child::Genet => &GENET_HARDWARE_IDS,
        Child::Sdhc => &SDHC_HARDWARE_IDS,
        Child::Sdhc5 => &SDHC5_HARDWARE_IDS,
        Child::Rp1Gem => &RP1_GEM_HARDWARE_IDS,
        Child::VirtioBlk => &VIRTIO_BLK_HARDWARE_IDS,
        Child::PciRoot => &PCI_ROOT_HARDWARE_IDS,
    };
    // The instance ID is the node's _UID in decimal: unique among nodes that
    // share a _HID, and stable across boots.
    let mut instance = [0u16; 11];
    let mut digits = [0u16; 10];
    let (mut n, mut uid) = (0, pdo.acpi.uid);
    loop {
        digits[n] = b'0' as u16 + (uid % 10) as u16;
        n += 1;
        uid /= 10;
        if uid == 0 {
            break;
        }
    }
    for i in 0..n {
        instance[i] = digits[n - 1 - i];
    }
    let src: &[u16] = match id_type {
        // The device ID is the first string of the hardware-ID multi-sz.
        BUS_QUERY_DEVICE_ID => &ids[..=ids.iter().position(|&c| c == 0).unwrap_or(0)],
        BUS_QUERY_HARDWARE_IDS => ids,
        BUS_QUERY_INSTANCE_ID => &instance[..=n],
        _ => return STATUS_NOT_SUPPORTED,
    };
    let p = alloc(src.len() * 2) as *mut u16;
    if p.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    core::ptr::copy_nonoverlapping(src.as_ptr(), p, src.len());
    *out = p as PVOID;
    STATUS_SUCCESS
}

unsafe fn query_resources(x: &AcpiDevice, out: *mut PVOID) -> NTSTATUS {
    let size = core::mem::size_of::<ddk::CM_RESOURCE_LIST>() + core::mem::size_of::<ddk::CM_PARTIAL_RESOURCE_DESCRIPTOR>();
    let list = alloc(size) as ddk::PCM_RESOURCE_LIST;
    if list.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    (*list).Count = 1;
    let full = (*list).List.as_mut_ptr();
    (*full).InterfaceType = ddk::_INTERFACE_TYPE_Internal;
    (*full).BusNumber = 0;
    let partial = &mut (*full).PartialResourceList;
    partial.Version = 1;
    partial.Revision = 1;
    partial.Count = 2;
    let d = partial.PartialDescriptors.as_mut_ptr();

    (*d).Type = CM_RESOURCE_TYPE_MEMORY;
    (*d).ShareDisposition = SHARE_DEVICE_EXCLUSIVE;
    (*d).Flags = 0; // CM_RESOURCE_MEMORY_READ_WRITE
    (*d).u.Memory.Start.QuadPart = x.mmio as i64;
    (*d).u.Memory.Length = x.mmio_len as ULONG;

    let d = d.add(1);
    (*d).Type = CM_RESOURCE_TYPE_INTERRUPT;
    (*d).ShareDisposition = SHARE_SHARED;
    (*d).Flags = if x.edge { CM_RESOURCE_INTERRUPT_LATCHED } else { 0 };
    (*d).u.Interrupt.Level = x.gsiv;
    (*d).u.Interrupt.Vector = x.gsiv;
    (*d).u.Interrupt.Affinity = usize::MAX as _;

    *out = list as PVOID;
    STATUS_SUCCESS
}

unsafe fn query_requirements(x: &AcpiDevice, out: *mut PVOID) -> NTSTATUS {
    let size = core::mem::size_of::<ddk::IO_RESOURCE_REQUIREMENTS_LIST>()
        + core::mem::size_of::<ddk::IO_RESOURCE_DESCRIPTOR>();
    let req = alloc(size) as ddk::PIO_RESOURCE_REQUIREMENTS_LIST;
    if req.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    (*req).ListSize = size as ULONG;
    (*req).InterfaceType = ddk::_INTERFACE_TYPE_Internal;
    (*req).AlternativeLists = 1;
    let list = (*req).List.as_mut_ptr();
    (*list).Version = 1;
    (*list).Revision = 1;
    (*list).Count = 2;
    let d = (*list).Descriptors.as_mut_ptr();

    (*d).Type = CM_RESOURCE_TYPE_MEMORY;
    (*d).ShareDisposition = SHARE_DEVICE_EXCLUSIVE;
    (*d).u.Memory.Length = x.mmio_len as ULONG;
    (*d).u.Memory.Alignment = 1;
    (*d).u.Memory.MinimumAddress.QuadPart = x.mmio as i64;
    (*d).u.Memory.MaximumAddress.QuadPart = (x.mmio + x.mmio_len - 1) as i64;

    let d = d.add(1);
    (*d).Type = CM_RESOURCE_TYPE_INTERRUPT;
    (*d).ShareDisposition = SHARE_SHARED;
    (*d).Flags = if x.edge { CM_RESOURCE_INTERRUPT_LATCHED } else { 0 };
    (*d).u.Interrupt.MinimumVector = x.gsiv;
    (*d).u.Interrupt.MaximumVector = x.gsiv;

    *out = req as PVOID;
    STATUS_SUCCESS
}

/// A root bus's resources: its bus range, as PCI_SEGMENT_BUS_NUMBERs.
fn bus_range(w: &Window) -> (ULONG, ULONG) {
    let first = (w.segment as ULONG) << 8 | w.start as ULONG;
    (first, (w.end - w.start) as ULONG + 1)
}

unsafe fn query_bus_resources(w: &Window, out: *mut PVOID) -> NTSTATUS {
    let list = alloc(core::mem::size_of::<ddk::CM_RESOURCE_LIST>()) as ddk::PCM_RESOURCE_LIST;
    if list.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    let (first, count) = bus_range(w);
    (*list).Count = 1;
    let full = (*list).List.as_mut_ptr();
    (*full).InterfaceType = ddk::_INTERFACE_TYPE_PCIBus;
    (*full).BusNumber = first;
    let partial = &mut (*full).PartialResourceList;
    partial.Version = 1;
    partial.Revision = 1;
    partial.Count = 1;
    let d = partial.PartialDescriptors.as_mut_ptr();
    (*d).Type = CM_RESOURCE_TYPE_BUS_NUMBER;
    (*d).ShareDisposition = SHARE_DEVICE_EXCLUSIVE;
    (*d).u.BusNumber.Start = first;
    (*d).u.BusNumber.Length = count;
    *out = list as PVOID;
    STATUS_SUCCESS
}

unsafe fn query_bus_requirements(w: &Window, out: *mut PVOID) -> NTSTATUS {
    let size = core::mem::size_of::<ddk::IO_RESOURCE_REQUIREMENTS_LIST>();
    let req = alloc(size) as ddk::PIO_RESOURCE_REQUIREMENTS_LIST;
    if req.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    let (first, count) = bus_range(w);
    (*req).ListSize = size as ULONG;
    (*req).InterfaceType = ddk::_INTERFACE_TYPE_PCIBus;
    (*req).BusNumber = first;
    (*req).AlternativeLists = 1;
    let list = (*req).List.as_mut_ptr();
    (*list).Version = 1;
    (*list).Revision = 1;
    (*list).Count = 1;
    let d = (*list).Descriptors.as_mut_ptr();
    (*d).Type = CM_RESOURCE_TYPE_BUS_NUMBER;
    (*d).ShareDisposition = SHARE_DEVICE_EXCLUSIVE;
    (*d).u.BusNumber.MinBusNumber = first;
    (*d).u.BusNumber.MaxBusNumber = first + count - 1;
    (*d).u.BusNumber.Length = count;
    *out = req as PVOID;
    STATUS_SUCCESS
}

unsafe fn query_bus_information(out: *mut PVOID) -> NTSTATUS {
    let bi = alloc(core::mem::size_of::<ddk::PNP_BUS_INFORMATION>()) as *mut ddk::PNP_BUS_INFORMATION;
    if bi.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    // Bus 1, device 0: where the VL805 sits behind the root complex.
    (*bi).BusTypeGuid = GUID_BUS_TYPE_PCI;
    (*bi).LegacyBusType = ddk::_INTERFACE_TYPE_PCIBus;
    (*bi).BusNumber = 1;
    *out = bi as PVOID;
    STATUS_SUCCESS
}

unsafe fn query_capabilities(io: PIO_STACK_LOCATION) -> NTSTATUS {
    let caps = (*io).Parameters.DeviceCapabilities.Capabilities;
    if (*caps).Version != 1 {
        return STATUS_NOT_SUPPORTED;
    }
    (*caps).set_UniqueID(0);
    (*caps).set_SilentInstall(1);
    (*caps).set_Removable(0);
    (*caps).Address = 0; // device 0, function 0
    (*caps).UINumber = u32::MAX;
    (*caps).DeviceState[ddk::_SYSTEM_POWER_STATE_PowerSystemWorking as usize] = ddk::_DEVICE_POWER_STATE_PowerDeviceD0;
    for s in [
        ddk::_SYSTEM_POWER_STATE_PowerSystemSleeping1,
        ddk::_SYSTEM_POWER_STATE_PowerSystemSleeping2,
        ddk::_SYSTEM_POWER_STATE_PowerSystemSleeping3,
        ddk::_SYSTEM_POWER_STATE_PowerSystemHibernate,
        ddk::_SYSTEM_POWER_STATE_PowerSystemShutdown,
    ] {
        (*caps).DeviceState[s as usize] = ddk::_DEVICE_POWER_STATE_PowerDeviceD3;
    }
    STATUS_SUCCESS
}

unsafe fn relations_of(objects: &[PDEVICE_OBJECT], prior: ddk::PDEVICE_RELATIONS, out: *mut PVOID) -> NTSTATUS {
    let prior_count = if prior.is_null() { 0 } else { (*prior).Count as usize };
    let n = prior_count + objects.len();
    let size = core::mem::offset_of!(ddk::DEVICE_RELATIONS, Objects) + n.max(1) * core::mem::size_of::<PDEVICE_OBJECT>();
    let rel = alloc(size) as ddk::PDEVICE_RELATIONS;
    if rel.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    let slots = (*rel).Objects.as_mut_ptr();
    if !prior.is_null() {
        core::ptr::copy_nonoverlapping((*prior).Objects.as_ptr(), slots, prior_count);
        ddk::ExFreePool(prior as PVOID);
    }
    for (i, &o) in objects.iter().enumerate() {
        ddk::ObfReferenceObject(o as PVOID);
        *slots.add(prior_count + i) = o;
    }
    (*rel).Count = n as ULONG;
    *out = rel as PVOID;
    STATUS_SUCCESS
}

