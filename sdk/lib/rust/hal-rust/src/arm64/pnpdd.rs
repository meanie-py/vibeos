unsafe extern "system" fn DispatchPnp(device: PDEVICE_OBJECT, irp: PIRP) -> NTSTATUS {
    let io = stack(irp);
    let minor = (*io).MinorFunction;
    let info = &raw mut (*irp).IoStatus.Information as *mut PVOID;

    if *((*device).DeviceExtension as *const ULONG) == EXT_FDO {
        let fdo = (*device).DeviceExtension as *mut FdoExtension;
        if minor == IRP_MN_QUERY_DEVICE_RELATIONS && (*io).Parameters.QueryDeviceRelations.Type == BUS_RELATIONS {
            let mut kids: [PDEVICE_OBJECT; MAX_CHILDREN] = [core::ptr::null_mut(); MAX_CHILDREN];
            let mut n = 0;
            let mut p = (*fdo).children;
            while !p.is_null() && n < kids.len() {
                kids[n] = (*p).device;
                n += 1;
                p = (*p).next;
            }
            let status = relations_of(&kids[..n], *info as ddk::PDEVICE_RELATIONS, info);
            if status < 0 {
                return complete(irp, status);
            }
            (*irp).IoStatus.__bindgen_anon_1.Status = status;
        }
        skip_stack(irp);
        return ddk::IofCallDriver((*fdo).lower, irp);
    }

    let pdo = (*device).DeviceExtension as *mut PdoExtension;
    let status = match minor {
        IRP_MN_START_DEVICE | IRP_MN_REMOVE_DEVICE | IRP_MN_SURPRISE_REMOVAL => STATUS_SUCCESS,
        IRP_MN_QUERY_DEVICE_RELATIONS if (*io).Parameters.QueryDeviceRelations.Type == TARGET_DEVICE_RELATION => {
            relations_of(&[device], core::ptr::null_mut(), info)
        }
        // Only the xHCI child has a PCI face (usbport asks for one).
        IRP_MN_QUERY_INTERFACE if (*pdo).child == Child::Xhci => query_interface(pdo, io),
        IRP_MN_QUERY_INTERFACE if (*pdo).child == Child::PciRoot => query_root_interface(pdo, io),
        IRP_MN_QUERY_CAPABILITIES => query_capabilities(io),
        IRP_MN_QUERY_RESOURCES => match &(*pdo).window {
            Some(w) => query_bus_resources(w, info),
            None => query_resources(&(*pdo).acpi, info),
        },
        IRP_MN_QUERY_RESOURCE_REQUIREMENTS => match &(*pdo).window {
            Some(w) => query_bus_requirements(w, info),
            None => query_requirements(&(*pdo).acpi, info),
        },
        IRP_MN_QUERY_ID => query_id(&*pdo, (*io).Parameters.QueryId.IdType as u32, info),
        IRP_MN_QUERY_BUS_INFORMATION if (*pdo).child == Child::Xhci => query_bus_information(info),
        _ => STATUS_NOT_SUPPORTED,
    };
    // A PDO leaves an IRP it does not handle as the PnP manager sent it.
    let status = if status == STATUS_NOT_SUPPORTED { (*irp).IoStatus.__bindgen_anon_1.Status } else { status };
    complete(irp, status)
}

unsafe extern "system" fn DispatchPower(device: PDEVICE_OBJECT, irp: PIRP) -> NTSTATUS {
    PoStartNextPowerIrp(irp);
    if *((*device).DeviceExtension as *const ULONG) == EXT_FDO {
        skip_stack(irp);
        return PoCallDriver((*((*device).DeviceExtension as *mut FdoExtension)).lower, irp);
    }
    complete(irp, STATUS_SUCCESS)
}

unsafe extern "system" fn DispatchWmi(device: PDEVICE_OBJECT, irp: PIRP) -> NTSTATUS {
    if *((*device).DeviceExtension as *const ULONG) == EXT_FDO {
        skip_stack(irp);
        return ddk::IofCallDriver((*((*device).DeviceExtension as *mut FdoExtension)).lower, irp);
    }
    let status = (*irp).IoStatus.__bindgen_anon_1.Status;
    complete(irp, status)
}

/// Create a child PDO for an ACPI-only device.
unsafe fn create_pdo(driver: PDRIVER_OBJECT, child: Child, x: AcpiDevice, window: Option<Window>) -> *mut PdoExtension {
    let mut dev: PDEVICE_OBJECT = core::ptr::null_mut();
    let status = ddk::IoCreateDevice(
        driver,
        core::mem::size_of::<PdoExtension>() as ULONG,
        core::ptr::null_mut(),
        FILE_DEVICE_BUS_EXTENDER,
        FILE_AUTOGENERATED_DEVICE_NAME,
        0,
        &mut dev,
    );
    if status < 0 {
        DbgPrint(b"[HAL] ACPI child: IoCreateDevice failed 0x%x\n\0".as_ptr(), status);
        return core::ptr::null_mut();
    }
    let pdo = (*dev).DeviceExtension as *mut PdoExtension;
    core::ptr::write(
        pdo,
        PdoExtension { kind: EXT_PDO, next: core::ptr::null_mut(), device: dev, child, acpi: x, cfg: core::ptr::null_mut(), window },
    );
    match child {
        Child::Xhci => init_xhci(pdo),
        Child::VirtioBlk => DbgPrint(
            b"[HAL] ACPI virtio-mmio block (LNRO0005 #%u): regs %p+0x%x, GSIV %u %s\n\0".as_ptr(),
            x.uid,
            x.mmio as PVOID,
            x.mmio_len as u32,
            x.gsiv,
            if x.edge { b"edge\0".as_ptr() } else { b"level\0".as_ptr() },
        ),
        Child::PciRoot => match window {
            Some(w) => DbgPrint(
                b"[HAL] PCI segment %u: root bus %u-%u published for pci.sys\n\0".as_ptr(),
                w.segment as u32,
                w.start as u32,
                w.end as u32,
            ),
            None => 0,
        },
        Child::Genet | Child::Sdhc | Child::Sdhc5 | Child::Rp1Gem => DbgPrint(
            b"[HAL] ACPI %s: regs %p+0x%x, GSIV %u %s\n\0".as_ptr(),
            match child {
                Child::Genet => b"GENET (BCM6E4E)\0".as_ptr(),
                Child::Sdhc5 => b"SD host (BRCM5D12)\0".as_ptr(),
                Child::Rp1Gem => b"RP1 Ethernet (Cadence GEM, not in ACPI)\0".as_ptr(),
                _ => b"SD host (BRCME88C)\0".as_ptr(),
            },
            x.mmio as PVOID,
            x.mmio_len as u32,
            x.gsiv,
            if x.edge { b"edge\0".as_ptr() } else { b"level\0".as_ptr() },
        ),
    };
    (*dev).Flags &= !DO_DEVICE_INITIALIZING;
    pdo
}

/// Do what the xHCI child's _INI would have: enable memory decoding and bus
/// mastering in its command register.
unsafe fn init_xhci(pdo: *mut PdoExtension) -> u32 {
    let x = (*pdo).acpi;
    if x.cfg != 0 {
        let mut pa: ddk::PHYSICAL_ADDRESS = core::mem::zeroed();
        pa.QuadPart = x.cfg as i64;
        (*pdo).cfg = ddk::MmMapIoSpace(pa, PCI_CONFIG_SIZE as ddk::SIZE_T, ddk::_MEMORY_CACHING_TYPE_MmNonCached) as *mut u8;
    }
    let mut id = [0u8; 4];
    cfg_access(pdo, false, id.as_mut_ptr(), 0, 4);
    if !(*pdo).cfg.is_null() {
        let mut cmd = PCI_COMMAND_START.to_le_bytes();
        cfg_access(pdo, true, cmd.as_mut_ptr(), PCI_COMMAND, 2);
    }
    DbgPrint(
        b"[HAL] ACPI xHCI (PNP0D10 #%u): regs %p+0x%x, GSIV %u %s, config %p (%04x:%04x)\n\0".as_ptr(),
        x.uid,
        x.mmio as PVOID,
        x.mmio_len as u32,
        x.gsiv,
        if x.edge { b"edge\0".as_ptr() } else { b"level\0".as_ptr() },
        x.cfg as PVOID,
        u16::from_le_bytes([id[0], id[1]]) as u32,
        u16::from_le_bytes([id[2], id[3]]) as u32,
    )
}

/// The device type a virtio-mmio slot holds: 0 for an empty slot, or for a
/// window that does not answer as virtio-mmio.
unsafe fn virtio_mmio_device_id(x: &AcpiDevice) -> u32 {
    if x.mmio_len < 0x100 {
        return 0;
    }
    let mut pa: ddk::PHYSICAL_ADDRESS = core::mem::zeroed();
    pa.QuadPart = x.mmio as i64;
    let regs = ddk::MmMapIoSpace(pa, 0x100, ddk::_MEMORY_CACHING_TYPE_MmNonCached) as *const u32;
    if regs.is_null() {
        return 0;
    }
    let id = if regs.read_volatile() == VIRTIO_MMIO_MAGIC {
        regs.add(VIRTIO_MMIO_DEVICE_ID / 4).read_volatile()
    } else {
        0
    };
    ddk::MmUnmapIoSpace(regs as PVOID, 0x100);
    id
}

unsafe extern "system" fn AddDevice(driver: PDRIVER_OBJECT, pdo: PDEVICE_OBJECT) -> NTSTATUS {
    let mut dev: PDEVICE_OBJECT = core::ptr::null_mut();
    let status = ddk::IoCreateDevice(
        driver,
        core::mem::size_of::<FdoExtension>() as ULONG,
        core::ptr::null_mut(),
        FILE_DEVICE_BUS_EXTENDER,
        0,
        0,
        &mut dev,
    );
    if status < 0 {
        return status;
    }
    let fdo = (*dev).DeviceExtension as *mut FdoExtension;
    core::ptr::write(fdo, FdoExtension { kind: EXT_FDO, lower: core::ptr::null_mut(), children: core::ptr::null_mut() });
    (*fdo).lower = ddk::IoAttachDeviceToDeviceStack(dev, pdo);
    if (*fdo).lower.is_null() {
        ddk::IoDeleteDevice(dev);
        return STATUS_NO_SUCH_DEVICE;
    }
    super::acpi::log_device_ids();
    let add = |child, x, window| {
        let pdo = create_pdo(driver, child, x, window);
        if !pdo.is_null() {
            (*pdo).next = (*fdo).children;
            (*fdo).children = pdo;
        }
    };
    for_each_xhci(|x| add(Child::Xhci, x, None));
    for (child, found) in [
        (Child::Genet, find_genet()),
        (Child::Sdhc, find_sdhc()),
        (Child::Sdhc5, find_sdhc_pi5()),
        (Child::Rp1Gem, find_rp1_gem()),
    ] {
        if let Some(x) = found {
            add(child, x, None);
        }
    }
    for_each_virtio_mmio(|x| {
        if virtio_mmio_device_id(&x) == VIRTIO_ID_BLOCK {
            add(Child::VirtioBlk, x, None);
        }
    });
    for w in super::ecam::all() {
        add(Child::PciRoot, AcpiDevice { uid: w.segment as u32, ..Default::default() }, Some(w));
    }
    (*dev).Flags &= !DO_DEVICE_INITIALIZING;
    STATUS_SUCCESS
}

unsafe extern "system" fn DriverEntry(driver: PDRIVER_OBJECT, _registry: PUNICODE_STRING) -> NTSTATUS {
    (*(*driver).DriverExtension).AddDevice = Some(AddDevice);
    (*driver).MajorFunction[IRP_MJ_PNP] = Some(DispatchPnp);
    (*driver).MajorFunction[IRP_MJ_POWER] = Some(DispatchPower);
    (*driver).MajorFunction[IRP_MJ_SYSTEM_CONTROL] = Some(DispatchWmi);

    let mut root: PDEVICE_OBJECT = core::ptr::null_mut();
    let status = ddk::IoReportDetectedDevice(
        driver,
        ddk::_INTERFACE_TYPE_InterfaceTypeUndefined,
        u32::MAX,
        u32::MAX,
        core::ptr::null_mut(),
        core::ptr::null_mut(),
        0,
        &mut root,
    );
    if status < 0 {
        DbgPrint(b"[HAL] IoReportDetectedDevice failed 0x%x\n\0".as_ptr(), status);
        return status;
    }
    (*root).Flags &= !DO_DEVICE_INITIALIZING;
    let status = AddDevice(driver, root);
    if status < 0 {
        ddk::IoDeleteDevice(root);
    }
    status
}

/// HalDispatchTable.HalInitPnpDriver: IoInitSystem calls this once, before
/// the PnP manager's first enumeration.
pub unsafe extern "system" fn HaliInitPnpDriver() -> NTSTATUS {
    let mut name: ddk::UNICODE_STRING = core::mem::zeroed();
    name.Length = ((DRIVER_NAME.len() - 1) * 2) as USHORT;
    name.MaximumLength = (DRIVER_NAME.len() * 2) as USHORT;
    name.Buffer = DRIVER_NAME.as_ptr() as *mut u16;
    let status = IoCreateDriver(&mut name, DriverEntry);
    if status < 0 {
        DbgPrint(b"[HAL] HaliInitPnpDriver: IoCreateDriver failed 0x%x\n\0".as_ptr(), status);
        return STATUS_UNSUCCESSFUL;
    }
    status
}

