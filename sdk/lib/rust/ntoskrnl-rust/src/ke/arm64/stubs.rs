    let Interrupt = opaque_ptr(Interrupt);
    let ServiceContext = opaque_ptr(ServiceContext);
    (*Interrupt).Type = _KOBJECTS_InterruptObject as i16;
    (*Interrupt).Size = core::mem::size_of::<_KINTERRUPT>() as i16;
