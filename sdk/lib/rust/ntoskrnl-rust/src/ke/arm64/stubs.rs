/// Raise to DISPATCH_LEVEL and TAKE the lock. This used to be the raise alone,
/// which is all a UP kernel needs, so on the MP kernel every KeAcquireSpinLock
/// caller on arm64 - the PFN lock among them - had no cross-CPU exclusion at
/// all (its KeReleaseSpinLock pair in the HAL did clear the lock). Four cores
/// actually running threads tore the page lists apart within a minute:
/// 0x4E PFN_LIST_CORRUPT, in QEMU `--smp 4` and on a Raspberry Pi 4.
/// KxAcquireSpinLock is compiled away on UP, so the UP kernel is unchanged.
#[cfg(target_arch = "aarch64")]
#[no_mangle]
pub unsafe extern "system" fn KeAcquireSpinLockRaiseToDpc(SpinLock: PKSPIN_LOCK) -> KIRQL {
    let OldIrql = KfRaiseIrql(DISPATCH_LEVEL);
    ntkrnl_sys::inline::ke::KxAcquireSpinLock(SpinLock as *mut _);
    OldIrql
}

const CONTEXT_ARM64: ULONG = 0x00400000;
const CONTEXT_CONTROL: ULONG = CONTEXT_ARM64 | 0x1;
const CONTEXT_INTEGER: ULONG = CONTEXT_ARM64 | 0x2;
const CONTEXT_FLOATING_POINT: ULONG = CONTEXT_ARM64 | 0x4;
const CONTEXT_FULL: ULONG = CONTEXT_CONTROL | CONTEXT_INTEGER | CONTEXT_FLOATING_POINT;

/// trap.S's NEON save area, as NEON_SAVE lays it out (NEON_SAVE_LENGTH bytes).
#[repr(C)]
struct NeonArea {
    V: [ntkrnl_sys::ddk::NEON128; 32],
    Fpcr: u64,
    Fpsr: u64,
    TrapFrame: u64, // the frame that owns it; NEON_RESTORE clears that frame's VfpState
    _Pad: u64,      // NEON_SAVE_LENGTH keeps sp 16-aligned
}
const _: () = assert!(core::mem::size_of::<NeonArea>() == 0x220); // trap.S NEON_SAVE_LENGTH

/// The trap's saved V0-V31/FPCR/FPSR, found through KTRAP_FRAME.VfpState (trap.S
/// NEON_SAVE: it holds the area's distance below the frame while the area is live).
/// `None` for a frame that was zeroed (a new thread) or copied away from its area (a
/// user-callback frame) -- anything but the two distances the entry paths produce.
unsafe fn neon_area(TrapFrame: PKTRAP_FRAME) -> Option<*mut NeonArea> {
    const KEXCEPTION_FRAME_LENGTH: usize = 0x60; // trap.S; EXFRAME_SAVE sits between
    let len = core::mem::size_of::<NeonArea>();
    let below = (*TrapFrame).VfpState as usize;
    if below == len || below == len + KEXCEPTION_FRAME_LENGTH {
        Some((TrapFrame as *mut u8).sub(below) as *mut NeonArea)
    } else {
        None
    }
}

#[no_mangle]
pub unsafe extern "system" fn KeTrapFrameToContext(
    TrapFrame: PKTRAP_FRAME,
    ExceptionFrame: PKEXCEPTION_FRAME,
    Context: PCONTEXT,
) {
    let ContextFlags = (*Context).ContextFlags;

    if (ContextFlags & CONTEXT_INTEGER) == CONTEXT_INTEGER {
        for i in 0..19 {
            (*Context).__bindgen_anon_1.X[i] = (*TrapFrame).__bindgen_anon_3.X[i];
        }

        if !ExceptionFrame.is_null() {
            (*Context).__bindgen_anon_1.X[19] = (*ExceptionFrame).X19;
            (*Context).__bindgen_anon_1.X[20] = (*ExceptionFrame).X20;
            (*Context).__bindgen_anon_1.X[21] = (*ExceptionFrame).X21;
            (*Context).__bindgen_anon_1.X[22] = (*ExceptionFrame).X22;
            (*Context).__bindgen_anon_1.X[23] = (*ExceptionFrame).X23;
            (*Context).__bindgen_anon_1.X[24] = (*ExceptionFrame).X24;
            (*Context).__bindgen_anon_1.X[25] = (*ExceptionFrame).X25;
            (*Context).__bindgen_anon_1.X[26] = (*ExceptionFrame).X26;
            (*Context).__bindgen_anon_1.X[27] = (*ExceptionFrame).X27;
            (*Context).__bindgen_anon_1.X[28] = (*ExceptionFrame).X28;
        }

        (*Context).__bindgen_anon_1.X[29] = (*TrapFrame).Fp;
        (*Context).__bindgen_anon_1.X[30] = (*TrapFrame).Lr;
    }

    if (ContextFlags & CONTEXT_CONTROL) == CONTEXT_CONTROL {
        (*Context).Sp = (*TrapFrame).Sp;
        (*Context).Pc = (*TrapFrame).Pc;
        (*Context).Cpsr = (*TrapFrame).Spsr;
    }

    if (ContextFlags & CONTEXT_FLOATING_POINT) == CONTEXT_FLOATING_POINT {
        match neon_area(TrapFrame) {
            Some(area) => {
                (*Context).V = (*area).V;
                (*Context).Fpcr = (*area).Fpcr as ULONG;
                (*Context).Fpsr = (*area).Fpsr as ULONG;
            }
            None => {
                core::ptr::write_bytes(core::ptr::addr_of_mut!((*Context).V), 0, 1);
                (*Context).Fpcr = 0;
                (*Context).Fpsr = 0;
            }
        }
    }
}

#[no_mangle]
pub unsafe extern "system" fn KeContextToTrapFrame(
    Context: PCONTEXT,
    ExceptionFrame: PKEXCEPTION_FRAME,
    TrapFrame: PKTRAP_FRAME,
    ContextFlags: ULONG,
    PreviousMode: KPROCESSOR_MODE,
) {
    if (ContextFlags & CONTEXT_INTEGER) == CONTEXT_INTEGER {
        for i in 0..19 {
            (*TrapFrame).__bindgen_anon_3.X[i] = (*Context).__bindgen_anon_1.X[i];
        }
        (*TrapFrame).Fp = (*Context).__bindgen_anon_1.__bindgen_anon_1.Fp;
        (*TrapFrame).Lr = (*Context).__bindgen_anon_1.__bindgen_anon_1.Lr;

        if !ExceptionFrame.is_null() {
            (*ExceptionFrame).X19 = (*Context).__bindgen_anon_1.__bindgen_anon_1.X19;
            (*ExceptionFrame).X20 = (*Context).__bindgen_anon_1.__bindgen_anon_1.X20;
            (*ExceptionFrame).X21 = (*Context).__bindgen_anon_1.__bindgen_anon_1.X21;
            (*ExceptionFrame).X22 = (*Context).__bindgen_anon_1.__bindgen_anon_1.X22;
            (*ExceptionFrame).X23 = (*Context).__bindgen_anon_1.__bindgen_anon_1.X23;
            (*ExceptionFrame).X24 = (*Context).__bindgen_anon_1.__bindgen_anon_1.X24;
            (*ExceptionFrame).X25 = (*Context).__bindgen_anon_1.__bindgen_anon_1.X25;
            (*ExceptionFrame).X26 = (*Context).__bindgen_anon_1.__bindgen_anon_1.X26;
            (*ExceptionFrame).X27 = (*Context).__bindgen_anon_1.__bindgen_anon_1.X27;
            (*ExceptionFrame).X28 = (*Context).__bindgen_anon_1.__bindgen_anon_1.X28;
        }
    }

    if (ContextFlags & CONTEXT_CONTROL) == CONTEXT_CONTROL {
        (*TrapFrame).Sp = (*Context).Sp;
        (*TrapFrame).Pc = (*Context).Pc;

        // Which exception level this frame RETURNS to is a property of the
        // FRAME, not of whoever is asking. `PreviousMode` is the caller's trust
        // level, and the two differ exactly when a kernel-mode caller sets the
        // context of a user thread — NtContinue's kernel path, NtSetContextThread
        // — which stamped EL1h onto a frame whose Pc is a user VA. The eret then
        // lands at EL1 on a user page, which AArch64 makes implicitly PXN, so it
        // faults on the same instruction forever.
        //
        // i386 and amd64 never had this: they ask the frame, via KiUserTrap.
        // arm64 has no KiUserTrap, so ask the frame directly — its own
        // PreviousMode field, stamped by the trap prolog that built it
        // (trap.S: TRAP_PROLOG_EL0 writes UserMode, TRAP_PROLOG writes
        // KernelMode). Fall back to the caller's mode only for a frame that
        // claims neither.
        // NOTE the asymmetry, which is deliberate and was measured. A frame
        // that is merely ZEROED reads PreviousMode == KernelMode, and
        // KiInitializeContextThread hands us exactly that: RtlZeroMemory, then
        // this call, and only afterwards does it stamp PreviousMode = UserMode
        // and force Spsr = 0. Trusting the frame's field outright therefore
        // calls every brand-new user thread a kernel frame — 78 times in one
        // arm64 boot, harmless there only because that caller overwrites Spsr
        // straight after. So the caller's mode still decides.
        //
        // The frame gets a VETO in the one direction that cannot be a zeroed
        // field: the caller says KernelMode while the frame positively says
        // UserMode. Only a real user trap frame carries that, so the
        // disagreement is genuine and the frame is right — this is NtContinue's
        // kernel path and NtSetContextThread on a user thread, the case that
        // stamps EL1h onto a user Pc and erets into a fault that repeats
        // forever.
        let frame_says_user =
            (*TrapFrame).__bindgen_anon_1.__bindgen_anon_1.PreviousMode == 1i8;
        let to_user = PreviousMode == 1i8 || frame_says_user;
        if to_user && PreviousMode != 1i8 {
            ARM64_UART_TRACE_HEX(
                b"[CTX2TF] kernel caller, USER frame; honouring the frame, Pc=\0".as_ptr()
                    as PCSTR,
                (*Context).Pc as ULONG_PTR,
            );
        }
        if to_user {
            (*TrapFrame).Spsr = (*Context).Cpsr & !0xF;
        } else {
            (*TrapFrame).Spsr = ((*Context).Cpsr & !0xF) | 0x5;
        }
    }

    // Written into the trap's NEON area, which the way out reloads: NEON_RESTORE
    // for an ordinary return, KiExceptionExit for NtContinue/NtRaiseException. A
    // frame with no area (a new thread's) has nowhere to put them, and needs none.
    if (ContextFlags & CONTEXT_FLOATING_POINT) == CONTEXT_FLOATING_POINT {
        if let Some(area) = neon_area(TrapFrame) {
            (*area).V = (*Context).V;
            // Only the architected control/status fields: the rest are RES0.
            const FPCR_MASK: ULONG = 0x07C8_9F00; // AHP DN FZ RMode FZ16 + trap enables
            const FPSR_MASK: ULONG = 0xF800_009F; // NZCV QC + cumulative flags
            (*area).Fpcr = ((*Context).Fpcr & FPCR_MASK) as u64;
            (*area).Fpsr = ((*Context).Fpsr & FPSR_MASK) as u64;
        }
    }
}

#[no_mangle]
pub unsafe extern "system" fn KiInitializeUserApc(
    ExceptionFrame: PKEXCEPTION_FRAME,
    TrapFrame: PKTRAP_FRAME,
    NormalRoutine: PKNORMAL_ROUTINE,
    NormalContext: PVOID,
    SystemArgument1: PVOID,
    SystemArgument2: PVOID,
) {
    let NormalContext = opaque_ptr(NormalContext);
    let SystemArgument1 = opaque_ptr(SystemArgument1);
    let SystemArgument2 = opaque_ptr(SystemArgument2);
    let mut Context: _CONTEXT = core::mem::zeroed();
    let context_size = core::mem::size_of::<_CONTEXT>() as u64;
    // FULL, as Windows does: the handler sees V0-V31, and the NtContinue that
    // ends it hands them back instead of resuming with the handler's.
    Context.ContextFlags = CONTEXT_FULL;
    KeTrapFrameToContext(TrapFrame, ExceptionFrame, core::ptr::addr_of_mut!(Context));

    let mut Stack = Context.Sp & !15u64;
    Stack -= context_size;
    Stack &= !15u64;

    #[cfg(target_arch = "aarch64")]
    {
        // ARM64 runs with DUMMY_PSEH, so a faulting probe/copy can be skipped
        // by the generic kernel exception workaround instead of being handled
        // locally. Explicitly fault in the user stack pages before copying.
        let page_mask = !(PAGE_SIZE as u64 - 1);
        let page_start = Stack & page_mask;
        let page_end = (Stack + context_size + PAGE_SIZE as u64 - 1) & page_mask;
        let mut page = page_start;

        while page < page_end {
            if MmIsAddressValid(page as PVOID) == 0 {
                let status = MmAccessFault(0x02, page as PVOID, 1i8, TrapFrame as PVOID);
                if status < 0 {
                    ARM64_UART_TRACE_HEX(
                        b"[APC] FaultIn=\0".as_ptr() as PCSTR,
                        status as ULONG_PTR,
                    );
                }
            }
            page += PAGE_SIZE as u64;
        }

        if MmIsAddressValid(Stack as PVOID) == 0
            || MmIsAddressValid((Stack + context_size - 1) as PVOID) == 0
        {
            ARM64_UART_TRACE_HEX(
                b"[APC] StackInvalid=\0".as_ptr() as PCSTR,
                Stack as ULONG_PTR,
            );
            return;
        }

        Arm64DumpPte(b"[APC] StackPage=\0".as_ptr() as PCSTR, Stack as PVOID);
    }

    // C: probe + copy inside _SEH2_TRY; the handler skips this APC (plain
    // return). No SEH here: Result probe + fault-tolerant copy. (The probe was a
    // raising ProbeForWrite under cfg(not(aarch64)) in this aarch64-only module,
    // i.e. never compiled, and the copy was a raw memcpy.)
    if ntkrnl_sys::probe::probe_user_buffer(
        Stack as *const core::ffi::c_void,
        core::mem::size_of::<_CONTEXT>(),
        16,
        1,
    )
    .and_then(|()| ntkrnl_sys::probe::safe_copy_to_user(
        Stack as *mut core::ffi::c_void,
        core::ptr::addr_of!(Context) as *const core::ffi::c_void,
        core::mem::size_of::<_CONTEXT>(),
        16,
        1,
    ))
    .is_err()
    {
        return;
    }

    (*TrapFrame).__bindgen_anon_3.X[0] = NormalContext as u64;
    (*TrapFrame).__bindgen_anon_3.X[1] = SystemArgument1 as u64;
    (*TrapFrame).__bindgen_anon_3.X[2] = SystemArgument2 as u64;
    (*TrapFrame).__bindgen_anon_3.X[3] = NormalRoutine.map(|f| f as usize as u64).unwrap_or(0);
    (*TrapFrame).Sp = Stack;
    (*TrapFrame).Pc = KeUserApcDispatcher as u64;
    (*TrapFrame).Spsr &= !0xF;

    #[cfg(target_arch = "aarch64")]
    {
        ARM64_UART_TRACE_HEX(b"[APC] PC=\0".as_ptr() as PCSTR, (*TrapFrame).Pc as ULONG_PTR);
        ARM64_UART_TRACE_HEX(b"[APC] SP=\0".as_ptr() as PCSTR, (*TrapFrame).Sp as ULONG_PTR);
        ARM64_UART_TRACE_HEX(
            b"[APC] NR=\0".as_ptr() as PCSTR,
            NormalRoutine.map(|f| f as ULONG_PTR).unwrap_or(0),
        );
        ARM64_UART_TRACE_HEX(
            b"[APC] X0=\0".as_ptr() as PCSTR,
            (*TrapFrame).__bindgen_anon_3.X[0] as ULONG_PTR,
        );
        ARM64_UART_TRACE_HEX(
            b"[APC] X1=\0".as_ptr() as PCSTR,
            (*TrapFrame).__bindgen_anon_3.X[1] as ULONG_PTR,
        );
        ARM64_UART_TRACE_HEX(
            b"[APC] X2=\0".as_ptr() as PCSTR,
            (*TrapFrame).__bindgen_anon_3.X[2] as ULONG_PTR,
        );
        ARM64_UART_TRACE_HEX(
            b"[APC] X3=\0".as_ptr() as PCSTR,
            (*TrapFrame).__bindgen_anon_3.X[3] as ULONG_PTR,
        );
    }
}

