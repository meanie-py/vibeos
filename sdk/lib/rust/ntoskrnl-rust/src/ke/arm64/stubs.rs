#[repr(C)]
struct KUSER_EXCEPTION_STACK_ARM64 {
    Context: _CONTEXT,
    ExceptionRecord: _EXCEPTION_RECORD,
}

#[no_mangle]
pub unsafe extern "system" fn KiDispatchException(
    ExceptionRecord: PEXCEPTION_RECORD,
    ExceptionFrame: PKEXCEPTION_FRAME,
    TrapFrame: PKTRAP_FRAME,
    PreviousMode: KPROCESSOR_MODE,
    FirstChance: BOOLEAN,
) {
    use crate::ke::flightrec::*;
    // Record before dispatch can change the context. No UART on the recovery
    // path: the fatal sidecar prints this ring if a later return fails (#39).
    let fault_thread = crate::ke::ke_defs::KeGetCurrentThread() as usize;
    if PreviousMode == 0i8 {
        flightrec_log(OP_KERNEL_FAULT_PC, (*TrapFrame).Pc as usize,
                      fault_thread, (*ExceptionRecord).ExceptionCode as u32);
        flightrec_log(OP_KERNEL_FAULT_LR, (*TrapFrame).Lr as usize, fault_thread, 0);
        if (*ExceptionRecord).ExceptionCode == STATUS_ACCESS_VIOLATION
            && (*ExceptionRecord).NumberParameters >= 2
        {
            flightrec_log(OP_KERNEL_FAULT_FAR,
                          (*ExceptionRecord).ExceptionInformation[1] as usize,
                          fault_thread, (*ExceptionRecord).ExceptionInformation[0] as u32);
        }
    }
    let mut Context: _CONTEXT = core::mem::zeroed();
    // FULL, as Windows does: the handler sees V0-V31, and the NtContinue that
    // ends it hands them back instead of resuming with the handler's.
    Context.ContextFlags = CONTEXT_FULL;
    KeTrapFrameToContext(TrapFrame, ExceptionFrame, core::ptr::addr_of_mut!(Context));

    if PreviousMode == 0i8 {
        if FirstChance != 0 {
            if RtlDispatchException(ExceptionRecord, core::ptr::addr_of_mut!(Context)) != 0 {
                KeContextToTrapFrame(
                    core::ptr::addr_of_mut!(Context),
                    ExceptionFrame,
                    TrapFrame,
                    Context.ContextFlags,
                    PreviousMode,
                );
                flightrec_log(OP_KERNEL_RESUME_PC, (*TrapFrame).Pc as usize, fault_thread, 0);
                flightrec_log(OP_KERNEL_RESUME_LR, (*TrapFrame).Lr as usize, fault_thread, 0);
                return;
            }
        }

        // An unhandled kernel breakpoint (DbgBreakPoint with no debugger and no
        // __except that wants it) steps past the brk and continues, as amd64 does
        // for an int3. PC is still AT the brk (ELR for a synchronous exception).
        if (*ExceptionRecord).ExceptionCode == STATUS_BREAKPOINT {
            (*TrapFrame).Pc += 4;
            return;
        }

        if (*ExceptionRecord).ExceptionCode == STATUS_ACCESS_VIOLATION
            && (*ExceptionRecord).NumberParameters >= 2
            // The probe fixup below is for data accesses only. Skipping an
            // instruction-fetch fault walks PC through user memory, destroying
            // the original bad branch target (task #39 ended at 0x250000).
            && (*ExceptionRecord).ExceptionInformation[0] != 8
        {
            let FaultDataAddr = (*ExceptionRecord).ExceptionInformation[1];
            if FaultDataAddr < MmHighestUserAddress as u64 {
                let Instr = *((*TrapFrame).Pc as *const ULONG);
                let Rd = Instr & 0x1F;
                if (Instr & (1 << 22)) != 0 {
                    // Zero the destination register(s) of the faulting load so the
                    // kernel probe reads 0 and we skip the instruction (the
                    // DUMMY_PSEH safe-access fixup). NB: on arm64 the KTRAP_FRAME
                    // only holds X0..X18 (19 entries); X19..X28 live in the
                    // KEXCEPTION_FRAME and X29/X30 are Fp/Lr (see
                    // KeTrapFrameToContext). Writing TrapFrame.X[Rd] for Rd>=19
                    // is out of bounds -> panic_bounds_check.
                    macro_rules! zero_reg {
                        ($r:expr) => {{
                            let r = $r;
                            match r {
                                0..=18 => (*TrapFrame).__bindgen_anon_3.X[r as usize] = 0,
                                19 if !ExceptionFrame.is_null() => (*ExceptionFrame).X19 = 0,
                                20 if !ExceptionFrame.is_null() => (*ExceptionFrame).X20 = 0,
                                21 if !ExceptionFrame.is_null() => (*ExceptionFrame).X21 = 0,
                                22 if !ExceptionFrame.is_null() => (*ExceptionFrame).X22 = 0,
                                23 if !ExceptionFrame.is_null() => (*ExceptionFrame).X23 = 0,
                                24 if !ExceptionFrame.is_null() => (*ExceptionFrame).X24 = 0,
                                25 if !ExceptionFrame.is_null() => (*ExceptionFrame).X25 = 0,
                                26 if !ExceptionFrame.is_null() => (*ExceptionFrame).X26 = 0,
                                27 if !ExceptionFrame.is_null() => (*ExceptionFrame).X27 = 0,
                                28 if !ExceptionFrame.is_null() => (*ExceptionFrame).X28 = 0,
                                29 => (*TrapFrame).Fp = 0,
                                30 => (*TrapFrame).Lr = 0,
                                // 31 == xzr (no destination); 19..=28 with a null
                                // ExceptionFrame -> nothing we can fix up.
                                _ => {}
                            }
                        }};
                    }
                    zero_reg!(Rd);
                    if (Instr & 0x3B000000) == 0x29000000 || (Instr & 0x3B000000) == 0x28000000 {
                        let Rt2 = (Instr >> 10) & 0x1F;
                        zero_reg!(Rt2);
                    }
                }
                flightrec_log(OP_KERNEL_DATA_FIXUP, (*TrapFrame).Pc as usize, fault_thread, 0);
                (*TrapFrame).Pc += 4;
                return;
            }
        }

        #[cfg(target_arch = "aarch64")]
        {
            // Kernel-mode unhandled exception. If this is an EC=0/IL=1 illegal-
            // exec-state fault that kept us at EL1, it surfaces here (not [UEXC]).
            ARM64_UART_TRACE_HEX(
                b"[KEXC] Code=\0".as_ptr() as PCSTR,
                (*ExceptionRecord).ExceptionCode as ULONG_PTR,
            );
            ARM64_UART_TRACE_HEX(b"[KEXC] PC=\0".as_ptr() as PCSTR, (*TrapFrame).Pc as ULONG_PTR);
            ARM64_UART_TRACE_HEX(
                b"[KEXC] Spsr=\0".as_ptr() as PCSTR,
                (*TrapFrame).Spsr as ULONG_PTR,
            );
            ARM64_UART_TRACE_HEX(
                b"[KEXC] ESR=\0".as_ptr() as PCSTR,
                (*TrapFrame).Esr as ULONG_PTR,
            );
            // Which CPU faulted? MPIDR_EL1.Aff0 == 0 is the BSP, 1 = CPU1 (SMP
            // bring-up: pins whether an AP or the BSP took the trap).
            let mpidr: u64;
            core::arch::asm!("mrs {}, mpidr_el1", out(reg) mpidr, options(nomem, nostack));
            ARM64_UART_TRACE_HEX(b"[KEXC] MPIDR=\0".as_ptr() as PCSTR, mpidr as ULONG_PTR);
            super::trap::KiDumpTrapFrame(TrapFrame);
            if !ExceptionFrame.is_null() {
                let ef = &*ExceptionFrame;
                let saved = [ef.X19, ef.X20, ef.X21, ef.X22, ef.X23,
                             ef.X24, ef.X25, ef.X26, ef.X27, ef.X28];
                for (i, value) in saved.iter().enumerate() {
                    ARM64_UART_TRACE_HEX(b"[KREG] index=\0".as_ptr() as PCSTR, i + 19);
                    ARM64_UART_TRACE_HEX(b"[KREG] value=\0".as_ptr() as PCSTR, *value as ULONG_PTR);
                }
            }

            // [KSTACK] the §9.97 distinguishing test: was the faulting SP even inside
            // a thread stack?
            //
            // The first symbolicated kernel-side instance of this bug was 0x1E at
            // KiSynchronousExceptionEntry+4 — `stp x0, x1, [sp, #TfX0]`, the FIRST
            // store into the freshly-subtracted trap frame — faulting on a kernel-stack
            // VA. Three outcomes, and they point at three different bugs, so print the
            // bounds rather than guessing:
            //   * SP inside (StackLimit, StackBase]  -> the stack is FINE and the page
            //     under it went away: the page-reuse face (task #19), not exhaustion.
            //   * SP just BELOW StackLimit           -> genuine overflow; only then is
            //     kiinit.rs:63's half-size KERNEL_STACK_SIZE (0x6000 vs xdk's 0xC000)
            //     worth a rebuild sweep, and only for a fault on CPU0's boot/idle stack
            //     (per-thread stacks come from ARM3/helpers.rs:400 and ARE 0xC000).
            //   * SP in NEITHER range                -> we are on some other stack
            //     entirely (idle/P0/DPC), which is its own answer.
            // FaultPTE is the clincher for the first case: a not-present PTE under a
            // live stack VA is the free-while-mapped signature the [FREEMAPPED] probe
            // catches from the other side.
            // Fully qualified: stubs.rs glob-imports both crate::ke::ke_defs and
            // ntkrnl_sys::mm, and BOTH export a KeGetCurrentThread (E0659). Take
            // ke_defs' — it returns PKTHREAD, so the stack fields are reachable;
            // ntkrnl_sys::mm's returns a bare PVOID.
            let thread = crate::ke::ke_defs::KeGetCurrentThread();
            ARM64_UART_TRACE_HEX(b"[KSTACK] SP=\0".as_ptr() as PCSTR, (*TrapFrame).Sp as ULONG_PTR);
            if !thread.is_null() {
                ARM64_UART_TRACE_HEX(b"[KSTACK] Thread=\0".as_ptr() as PCSTR, thread as ULONG_PTR);
                let process = PsGetCurrentProcess() as *mut _EPROCESS;
                if !process.is_null() {
                    Arm64TraceImageName(
                        b"[KSTACK] Process=\0".as_ptr() as PCSTR,
                        (*process).ImageFileName.as_ptr(),
                        core::mem::size_of_val(&(*process).ImageFileName),
                    );
                }
                ARM64_UART_TRACE_HEX(
                    b"[KSTACK] StackBase=\0".as_ptr() as PCSTR,
                    (*thread).StackBase as ULONG_PTR,
                );
                ARM64_UART_TRACE_HEX(
                    b"[KSTACK] StackLimit=\0".as_ptr() as PCSTR,
                    (*thread).StackLimit as ULONG_PTR,
                );
                ARM64_UART_TRACE_HEX(
                    b"[KSTACK] InitialStack=\0".as_ptr() as PCSTR,
                    (*thread).InitialStack as ULONG_PTR,
                );
            }
            if (*ExceptionRecord).NumberParameters >= 2 {
                ARM64_UART_TRACE_HEX(
                    b"[KSTACK] FaultVA=\0".as_ptr() as PCSTR,
                    (*ExceptionRecord).ExceptionInformation[1] as ULONG_PTR,
                );
                Arm64DumpPte(
                    b"[KSTACK] FaultPTE=\0".as_ptr() as PCSTR,
                    (*ExceptionRecord).ExceptionInformation[1] as PVOID,
                );
            }
            // [KSTKW] the kernel-range words on the faulting stack. The trap
            // frame alone cannot name WHO got here when the fault is a wild
            // jump: PC is the bad target and LR is whatever the jumper left
            // (a `br` leaves it untouched, and the 2026-09-05 fault-loop frame
            // had LR=0 and every callee-saved register zero). The return
            // addresses of the frames that led to the jump are still on the
            // stack above SP, and a bugcheck is the last moment they exist.
            // Bounded to the thread's own stack and to pages that are mapped,
            // so the dump cannot fault on the way down.
            if !thread.is_null() {
                let sp = (*TrapFrame).Sp as ULONG_PTR;
                let base = (*thread).StackBase as ULONG_PTR;
                let limit = (*thread).StackLimit as ULONG_PTR;
                if sp >= limit && sp < base && (sp & 7) == 0 {
                    let mut printed: u32 = 0;
                    let mut off: ULONG_PTR = 0;
                    while sp + off < base && off < 0x800 && printed < 48 {
                        let at = sp + off;
                        if MmIsAddressValid(at as PVOID) == 0 {
                            break;
                        }
                        let w = *(at as *const ULONG_PTR);
                        // Kernel-range words only: return addresses and kernel
                        // pointers. User values and small integers are noise.
                        if w >= 0xFFFF_0000_0000_0000 {
                            ARM64_UART_TRACE_HEX(b"[KSTKW] sp+=\0".as_ptr() as PCSTR, off);
                            ARM64_UART_TRACE_HEX(b"[KSTKW]   =\0".as_ptr() as PCSTR, w);
                            printed += 1;
                        }
                        off += 8;
                    }
                }
            }
        }
        KeBugCheckEx(
            KMODE_EXCEPTION_NOT_HANDLED,
            (*ExceptionRecord).ExceptionCode as ULONG_PTR,
            (*ExceptionRecord).ExceptionAddress as ULONG_PTR,
            TrapFrame as ULONG_PTR,
            0,
        );
    } else {
        let PrintRecord = uexc_should_print((*ExceptionRecord).ExceptionCode);
        #[cfg(target_arch = "aarch64")]
        if PrintRecord {
            ARM64_UART_TRACE_HEX(
                b"[UEXC] Code=\0".as_ptr() as PCSTR,
                (*ExceptionRecord).ExceptionCode as ULONG_PTR,
            );
            ARM64_UART_TRACE_HEX(b"[UEXC] PC=\0".as_ptr() as PCSTR, (*TrapFrame).Pc as ULONG_PTR);
            ARM64_UART_TRACE_HEX(b"[UEXC] SP=\0".as_ptr() as PCSTR, (*TrapFrame).Sp as ULONG_PTR);
            ARM64_UART_TRACE_HEX(b"[UEXC] LR=\0".as_ptr() as PCSTR, (*TrapFrame).Lr as ULONG_PTR);
            ARM64_UART_TRACE_HEX(
                b"[UEXC] ESR=\0".as_ptr() as PCSTR,
                (*TrapFrame).Esr as ULONG_PTR,
            );
            // Spsr carries PSTATE at the fault: M[3:0] (0x0=EL0t, 0x5=EL1h) +
            // IL bit (0x00100000). For an EC=0/IL=1 illegal-exec-state fault this
            // tells us whether the bad eret landed us in EL0 (M=0, IL set) or kept
            // us at EL1 (M=0x5). ESR>>26 == EC disambiguates IL-fault vs real AV.
            ARM64_UART_TRACE_HEX(
                b"[UEXC] Spsr=\0".as_ptr() as PCSTR,
                (*TrapFrame).Spsr as ULONG_PTR,
            );
            ARM64_UART_TRACE_HEX(
                b"[UEXC] ExAddr=\0".as_ptr() as PCSTR,
                (*ExceptionRecord).ExceptionAddress as ULONG_PTR,
            );
            ARM64_UART_TRACE_HEX(
                b"[UEXC] 1st=\0".as_ptr() as PCSTR,
                FirstChance as ULONG_PTR,
            );
            if (*ExceptionRecord).NumberParameters >= 2 {
                ARM64_UART_TRACE_HEX(
                    b"[UEXC] P0=\0".as_ptr() as PCSTR,
                    (*ExceptionRecord).ExceptionInformation[0] as ULONG_PTR,
                );
                ARM64_UART_TRACE_HEX(
                    b"[UEXC] P1=\0".as_ptr() as PCSTR,
                    (*ExceptionRecord).ExceptionInformation[1] as ULONG_PTR,
                );
                Arm64DumpPte(
                    b"[UEXC] FaultPage=\0".as_ptr() as PCSTR,
                    (*ExceptionRecord).ExceptionInformation[1] as PVOID,
                );
            }
        }

        if FirstChance != 0 {
            let UserRsp = (Context.Sp - core::mem::size_of::<KUSER_EXCEPTION_STACK_ARM64>() as u64) & !15u64;
            let UserStack = UserRsp as *mut KUSER_EXCEPTION_STACK_ARM64;

            if UserRsp >= MmHighestUserAddress as u64
                || UserRsp < core::mem::size_of::<KUSER_EXCEPTION_STACK_ARM64>() as u64
            {
                #[cfg(target_arch = "aarch64")]
                {
                    ARM64_UART_TRACE_HEX(
                        b"[UEXC-STKBAD] SP=\0".as_ptr() as PCSTR,
                        Context.Sp as ULONG_PTR,
                    );
                }
                ZwTerminateProcess(NtCurrentProcess(), (*ExceptionRecord).ExceptionCode);
                KeBugCheckEx(
                    KMODE_EXCEPTION_NOT_HANDLED,
                    (*ExceptionRecord).ExceptionCode as ULONG_PTR,
                    (*ExceptionRecord).ExceptionAddress as ULONG_PTR,
                    TrapFrame as ULONG_PTR,
                    PreviousMode as ULONG_PTR,
                );
            }

            MmAccessFault(0x02, UserRsp as PVOID, 1i8, TrapFrame as PVOID);
            MmAccessFault(
                0x02,
                (UserRsp + core::mem::size_of::<KUSER_EXCEPTION_STACK_ARM64>() as u64 - 1) as PVOID,
                1i8,
                TrapFrame as PVOID,
            );

            if MmIsAddressValid(UserStack as PVOID) == 0
                || MmIsAddressValid(
                    (UserStack as *mut u8).add(core::mem::size_of::<KUSER_EXCEPTION_STACK_ARM64>() - 1) as PVOID,
                ) == 0
            {
                #[cfg(target_arch = "aarch64")]
                {
                    ARM64_UART_TRACE_HEX(
                        b"[UEXC-STKOVERFLOW] SP=\0".as_ptr() as PCSTR,
                        Context.Sp as ULONG_PTR,
                    );
                }
                ZwTerminateProcess(NtCurrentProcess(), (*ExceptionRecord).ExceptionCode);
                KeBugCheckEx(
                    KMODE_EXCEPTION_NOT_HANDLED,
                    (*ExceptionRecord).ExceptionCode as ULONG_PTR,
                    (*ExceptionRecord).ExceptionAddress as ULONG_PTR,
                    TrapFrame as ULONG_PTR,
                    PreviousMode as ULONG_PTR,
                );
            }

            core::ptr::write_bytes(UserStack as *mut u8, 0, core::mem::size_of::<KUSER_EXCEPTION_STACK_ARM64>());
            (*UserStack).Context = Context;
            (*UserStack).ExceptionRecord = *ExceptionRecord;

            (*TrapFrame).__bindgen_anon_3.X[0] = core::ptr::addr_of_mut!((*UserStack).ExceptionRecord) as u64;
            (*TrapFrame).__bindgen_anon_3.X[1] = core::ptr::addr_of_mut!((*UserStack).Context) as u64;
            (*TrapFrame).Sp = UserRsp;
            (*TrapFrame).Pc = KeUserExceptionDispatcher as u64;
            (*TrapFrame).Spsr &= !0xF;

            #[cfg(target_arch = "aarch64")]
            if PrintRecord {
                ARM64_UART_TRACE_HEX(
                    b"[UEXC-DISPATCH] PC=\0".as_ptr() as PCSTR,
                    (*TrapFrame).Pc as ULONG_PTR,
                );
                ARM64_UART_TRACE_HEX(
                    b"[UEXC-DISPATCH] SP=\0".as_ptr() as PCSTR,
                    (*TrapFrame).Sp as ULONG_PTR,
                );
                ARM64_UART_TRACE_HEX(
                    b"[UEXC-DISPATCH] X0=\0".as_ptr() as PCSTR,
                    (*TrapFrame).__bindgen_anon_3.X[0] as ULONG_PTR,
                );
                ARM64_UART_TRACE_HEX(
                    b"[UEXC-DISPATCH] X1=\0".as_ptr() as PCSTR,
                    (*TrapFrame).__bindgen_anon_3.X[1] as ULONG_PTR,
                );
            }
            return;
        }

        #[cfg(target_arch = "aarch64")]
        {
            ARM64_UART_TRACE_HEX(
                b"[UEXC-KILL] Code=\0".as_ptr() as PCSTR,
                (*ExceptionRecord).ExceptionCode as ULONG_PTR,
            );
            ARM64_UART_TRACE_HEX(
                b"[UEXC-KILL] PC=\0".as_ptr() as PCSTR,
                (*ExceptionRecord).ExceptionAddress as ULONG_PTR,
            );
            ARM64_UART_TRACE_HEX(
                b"[UEXC-KILL] LR=\0".as_ptr() as PCSTR,
                (*TrapFrame).Lr as ULONG_PTR,
            );
            ARM64_UART_TRACE_HEX(
                b"[UEXC-KILL] 1st=\0".as_ptr() as PCSTR,
                FirstChance as ULONG_PTR,
            );
            Arm64TraceImageName(
                b"[UEXC-KILL] Proc=\0".as_ptr() as PCSTR,
                (*(PsGetCurrentProcess() as *mut _EPROCESS)).ImageFileName.as_ptr(),
                core::mem::size_of_val(&(*(PsGetCurrentProcess() as *mut _EPROCESS)).ImageFileName),
            );
            if MmIsAddressValid((*ExceptionRecord).ExceptionAddress as PVOID) != 0 {
                let instr = *((*ExceptionRecord).ExceptionAddress as *const ULONG);
                ARM64_UART_TRACE_HEX(
                    b"[UEXC-KILL] Instr=\0".as_ptr() as PCSTR,
                    instr as ULONG_PTR,
                );
            }
            // User-mode FP-chain backtrace (arm64 keeps frame pointers; each
            // frame is [prev_fp, lr] at x29). We're on the dying thread so its
            // user VAs are current — walk with validity guards. This names the
            // CALLER chain of a user AV (e.g. which winlogon call site handed
            // ntdll printf a kernel-VA string — the 0x4C face of the TDI-window
            // flake) that PC/LR alone can't.
            let mut fp = (*TrapFrame).Fp;
            for i in 0..12u32 {
                if fp == 0
                    || (fp & 0x7) != 0
                    || MmIsAddressValid(fp as PVOID) == 0
                    || MmIsAddressValid((fp + 8) as PVOID) == 0
                {
                    break;
                }
                let next_fp = *(fp as *const u64);
                let lr = *((fp + 8) as *const u64);
                ARM64_UART_TRACE_HEX(
                    match i {
                        0 => b"[UEXC-BT] lr0=\0".as_ptr() as PCSTR,
                        1 => b"[UEXC-BT] lr1=\0".as_ptr() as PCSTR,
                        2 => b"[UEXC-BT] lr2=\0".as_ptr() as PCSTR,
                        3 => b"[UEXC-BT] lr3=\0".as_ptr() as PCSTR,
                        4 => b"[UEXC-BT] lr4=\0".as_ptr() as PCSTR,
                        5 => b"[UEXC-BT] lr5=\0".as_ptr() as PCSTR,
                        6 => b"[UEXC-BT] lr6=\0".as_ptr() as PCSTR,
                        7 => b"[UEXC-BT] lr7=\0".as_ptr() as PCSTR,
                        8 => b"[UEXC-BT] lr8=\0".as_ptr() as PCSTR,
                        9 => b"[UEXC-BT] lr9=\0".as_ptr() as PCSTR,
                        10 => b"[UEXC-BT] lrA=\0".as_ptr() as PCSTR,
                        _ => b"[UEXC-BT] lrB=\0".as_ptr() as PCSTR,
                    },
                    lr as ULONG_PTR,
                );
                if next_fp <= fp {
                    break; // stacks grow down; a non-increasing FP is a loop/corruption
                }
                fp = next_fp;
            }
        }

        ZwTerminateProcess(NtCurrentProcess(), (*ExceptionRecord).ExceptionCode);
        KeBugCheckEx(
            KMODE_EXCEPTION_NOT_HANDLED,
            (*ExceptionRecord).ExceptionCode as ULONG_PTR,
            (*ExceptionRecord).ExceptionAddress as ULONG_PTR,
            TrapFrame as ULONG_PTR,
            PreviousMode as ULONG_PTR,
        );
    }
}

#[no_mangle]
pub unsafe extern "system" fn KiSwapProcess(NewProcess: PKPROCESS, OldProcess: PKPROCESS) {
    let NewProcess = opaque_ptr(NewProcess);
    let OldProcess = opaque_ptr(OldProcess);
    let NewPageTable = (*NewProcess).DirectoryTableBase[0];

    if NewPageTable == (*OldProcess).DirectoryTableBase[0] {
        return;
    }

    core::arch::asm!("dsb ish", options(nomem, nostack));
    core::arch::asm!("msr ttbr0_el1, {}", in(reg) NewPageTable, options(nomem, nostack));
    core::arch::asm!("msr ttbr1_el1, {}", in(reg) NewPageTable, options(nomem, nostack));
    core::arch::asm!("tlbi vmalle1is", options(nomem, nostack));
    core::arch::asm!("dsb ish", options(nomem, nostack));
    core::arch::asm!("isb", options(nomem, nostack));
}

#[no_mangle]
pub unsafe extern "system" fn KeFlushCurrentTb() {
    // Local-only by CONTRACT (NT: flush the CURRENT processor's TLB) — the
    // non-IS `vmalle1` is correct here, not an SMP bug. The freeze path and the
    // sysldr post-relocation flush are local-scoped. The ARM3 sites that drop a
    // user mapping (MiDeletePte, MiProcessValidPteList, MiFlushTbAndCapture,
    // MiRemoveMappedPtes) called this too, as the C does, and lost user pages
    // at -smp 2; they now use KeFlushProcessTb.
    core::arch::asm!("dsb nshst", options(nomem, nostack));
    core::arch::asm!("tlbi vmalle1", options(nomem, nostack));
    core::arch::asm!("dsb nsh", options(nomem, nostack));
    core::arch::asm!("isb", options(nomem, nostack));
}

/// Zero whole pages with `dc zva` (one cache-line block per instruction), the
/// arm64 page-clear idiom. The C stub (and this port, until now) went through
/// RtlZeroMemory to the CRT's byte-at-a-time memset: 128 KB per zero-page-
/// thread batch took ~12 ms under TCG, and since arm64 acts on a timer only at
/// an IRQL crossing, every short wait that fell while the zero thread ran paid
/// that batch as extra latency (kmtest KeEvent's 1000-iteration scheduling
/// test went 12 s -> 45 s once the zero thread became preemptible).
/// Falls back to RtlZeroMemory only when the CPU prohibits DC ZVA (DCZID.DZP)
/// or the range is not whole blocks -- callers pass page-aligned pages.
#[no_mangle]
pub unsafe extern "system" fn KeZeroPages(Address: PVOID, Size: ULONG) {
    let Address = opaque_ptr(Address);
    let dczid: u64;
    core::arch::asm!("mrs {0}, dczid_el0", out(reg) dczid, options(nomem, nostack, preserves_flags));
    let block = 4usize << (dczid & 0xF);
    let (start, size) = (Address as usize, Size as usize);
    if dczid & (1 << 4) != 0 || start % block != 0 || size % block != 0 {
        RtlZeroMemory(Address, size);
        return;
    }
    let mut p = start;
    while p < start + size {
        core::arch::asm!("dc zva, {0}", in(reg) p, options(nostack, preserves_flags));
        p += block;
    }
    // The zeroed page is about to be handed out, possibly to another CPU.
    core::arch::asm!("dsb ish", options(nostack, preserves_flags));
}

