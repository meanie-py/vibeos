unsafe extern "C" fn UnregisterService() -> UINT {
    let mut error: UINT;
    let mut hServiceManager: SC_HANDLE;
    let mut hService: SC_HANDLE;
    hServiceManager = OpenSCManagerW(
        core::ptr::null(),
        core::ptr::null(),
        SC_MANAGER_CREATE_SERVICE as DWORD,
    );
    if hServiceManager.is_null() {
        error = GetLastError() as UINT;
        DbgPrint(
            b"OpenSCManager() failed, error %lu\n\0".as_ptr() as PCSTR,
            error,
        );
        return error;
    }
    hService = OpenServiceW(
        hServiceManager,
        g_pszServiceName,
        DELETE as DWORD,
    );
    error = GetLastError() as UINT;
    CloseServiceHandle(hServiceManager);
    if hService.is_null() {
        if error == ERROR_SERVICE_DOES_NOT_EXIST as UINT {
            return ERROR_SUCCESS as UINT;
        }
        DbgPrint(
            b"OpenService() failed, error %lu\n\0".as_ptr() as PCSTR,
            error,
        );
    } else {
        error = (if DeleteService(hService) != 0 {
            ERROR_SUCCESS as DWORD
        } else {
            GetLastError()
        }) as UINT;
        if error == ERROR_SERVICE_MARKED_FOR_DELETE as UINT {
            error = ERROR_SUCCESS as UINT;
        }
        if error != 0 {
            DbgPrint(
                b"DeleteService() failed, error %lu\n\0".as_ptr() as PCSTR,
                error,
            );
        }
        CloseServiceHandle(hService);
    }
    return error;
}

