#[cfg(feature = "mi_trace_pfns")]
#[used]
static mut IopPfnDumpDeviceObject: PDEVICE_OBJECT = core::ptr::null_mut();

#[cfg(feature = "mi_trace_pfns")]
unsafe extern "system" fn PnpRootCreateClose(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS {
    if DeviceObject != IopPfnDumpDeviceObject {
        (*Irp).IoStatus.__bindgen_anon_1.Status = STATUS_INVALID_DEVICE_REQUEST;
        IoCompleteRequest(Irp, IO_NO_INCREMENT);
        return STATUS_INVALID_DEVICE_REQUEST;
    }

    let IoStack: PIO_STACK_LOCATION = IoGetCurrentIrpStackLocation(Irp);
    if (*IoStack).MajorFunction == IRP_MJ_CREATE {
        MmDumpArmPfnDatabase(1u8);
    }

    (*Irp).IoStatus.__bindgen_anon_1.Status = STATUS_SUCCESS;
    IoCompleteRequest(Irp, IO_NO_INCREMENT);
    STATUS_SUCCESS
}

#[no_mangle]
pub unsafe extern "system" fn PnpRootDriverEntry(
    DriverObject: PDRIVER_OBJECT,
    RegistryPath: PUNICODE_STRING,
) -> NTSTATUS {
    let DriverObject = opaque_ptr(DriverObject);
    let RegistryPath = opaque_ptr(RegistryPath);
    #[cfg(feature = "mi_trace_pfns")]
    let mut PfnDumpDeviceName: _UNICODE_STRING = core::mem::zeroed();

    IopRootDriverObject = DriverObject;

    (*(*DriverObject).DriverExtension).AddDevice = core::mem::transmute(Some(PnpRootAddDevice as unsafe extern "system" fn(PDRIVER_OBJECT, PDEVICE_OBJECT) -> NTSTATUS));

    #[cfg(feature = "mi_trace_pfns")]
    {
        RtlInitUnicodeString(&mut PfnDumpDeviceName, W_DEVICE_PFN_DUMP.as_ptr());
        (*DriverObject).MajorFunction[IRP_MJ_CREATE as usize] = core::mem::transmute(Some(PnpRootCreateClose as unsafe extern "system" fn(PDEVICE_OBJECT, PIRP) -> NTSTATUS));
        (*DriverObject).MajorFunction[IRP_MJ_CLOSE as usize] = core::mem::transmute(Some(PnpRootCreateClose as unsafe extern "system" fn(PDEVICE_OBJECT, PIRP) -> NTSTATUS));
    }
    (*DriverObject).MajorFunction[IRP_MJ_PNP as usize] = core::mem::transmute(Some(PnpRootPnpControl as unsafe extern "system" fn(PDEVICE_OBJECT, PIRP) -> NTSTATUS));
    (*DriverObject).MajorFunction[IRP_MJ_POWER as usize] = core::mem::transmute(Some(PnpRootPowerControl as unsafe extern "system" fn(PDEVICE_OBJECT, PIRP) -> NTSTATUS));

    #[cfg(feature = "mi_trace_pfns")]
    {
        let Status = IoCreateDevice(
            DriverObject,
            0,
            &mut PfnDumpDeviceName,
            FILE_DEVICE_UNKNOWN,
            0,
            0u8,
            core::ptr::addr_of_mut!(IopPfnDumpDeviceObject),
        );
        if Status >= 0 {
            (*IopPfnDumpDeviceObject).Flags &= !DO_DEVICE_INITIALIZING;
        }
    }

    STATUS_SUCCESS
}


