unsafe fn PdoQueryBusInformation(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
    IrpSp: PIO_STACK_LOCATION,
) -> NTSTATUS {
    let BusInfo = ExAllocatePoolWithTag(
        PagedPool,
        core::mem::size_of::<_PNP_BUS_INFORMATION>(),
        TAG_PNP_ROOT,
    ) as PPNP_BUS_INFORMATION;
    let Status: NTSTATUS;
    if BusInfo.is_null() {
        Status = STATUS_NO_MEMORY;
    } else {
        core::ptr::copy_nonoverlapping(
            core::ptr::addr_of!(GUID_BUS_TYPE_INTERNAL) as *const u8,
            core::ptr::addr_of_mut!((*BusInfo).BusTypeGuid) as *mut u8,
            core::mem::size_of_val(&(*BusInfo).BusTypeGuid),
        );
        (*BusInfo).LegacyBusType = _INTERFACE_TYPE_PNPBus;
        (*BusInfo).BusNumber = 0;
        (*Irp).IoStatus.Information = BusInfo as ULONG_PTR;
        Status = STATUS_SUCCESS;
    }

    Status
}

unsafe fn PnpRootPdoPnpControl(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS {
    let DeviceExtension = (*DeviceObject).DeviceExtension as PPNPROOT_PDO_DEVICE_EXTENSION;
    let FdoDeviceExtension = core::ptr::addr_of_mut!(PnpRootDOExtension);
    let IrpSp: PIO_STACK_LOCATION = IoGetCurrentIrpStackLocation(Irp);
    let mut Status = (*Irp).IoStatus.__bindgen_anon_1.Status;

    match (*IrpSp).MinorFunction {
        IRP_MN_START_DEVICE => {
            Status = STATUS_SUCCESS;
        }
        IRP_MN_QUERY_DEVICE_RELATIONS => {
            Status = PdoQueryDeviceRelations(DeviceObject, Irp, IrpSp);
        }
        IRP_MN_QUERY_CAPABILITIES => {
            Status = PdoQueryCapabilities(DeviceObject, Irp, IrpSp);
        }
        IRP_MN_QUERY_RESOURCES => {
            Status = PdoQueryResources(DeviceObject, Irp, IrpSp);
        }
        IRP_MN_QUERY_RESOURCE_REQUIREMENTS => {
            Status = PdoQueryResourceRequirements(DeviceObject, Irp, IrpSp);
        }
        IRP_MN_QUERY_DEVICE_TEXT => {
            Status = PdoQueryDeviceText(DeviceObject, Irp, IrpSp);
        }
        IRP_MN_REMOVE_DEVICE => {
            KeAcquireGuardedMutex(core::ptr::addr_of_mut!((*FdoDeviceExtension).DeviceListLock));
            RemoveEntryList(core::ptr::addr_of_mut!((*(*DeviceExtension).DeviceInfo).ListEntry) as PLIST_ENTRY);
            (*FdoDeviceExtension).DeviceListCount -= 1;
            KeReleaseGuardedMutex(core::ptr::addr_of_mut!((*FdoDeviceExtension).DeviceListLock));

            RtlFreeUnicodeString(core::ptr::addr_of_mut!((*(*DeviceExtension).DeviceInfo).DeviceDescription));
            RtlFreeUnicodeString(core::ptr::addr_of_mut!((*(*DeviceExtension).DeviceInfo).DeviceID));
            RtlFreeUnicodeString(core::ptr::addr_of_mut!((*(*DeviceExtension).DeviceInfo).InstanceID));

            if !(*(*DeviceExtension).DeviceInfo).ResourceRequirementsList.is_null() {
                ExFreePool((*(*DeviceExtension).DeviceInfo).ResourceRequirementsList as PVOID);
            }

            if !(*(*DeviceExtension).DeviceInfo).ResourceList.is_null() {
                ExFreePool((*(*DeviceExtension).DeviceInfo).ResourceList as PVOID);
            }

            ExFreePool((*DeviceExtension).DeviceInfo as PVOID);

            IoDeleteDevice(DeviceObject);

            Status = STATUS_SUCCESS;
        }
        IRP_MN_QUERY_ID => {
            Status = PdoQueryId(DeviceObject, Irp, IrpSp);
        }
        IRP_MN_QUERY_BUS_INFORMATION => {
            Status = PdoQueryBusInformation(DeviceObject, Irp, IrpSp);
        }
        _ => {}
    }

    if Status != STATUS_PENDING {
        (*Irp).IoStatus.__bindgen_anon_1.Status = Status;
        IoCompleteRequest(Irp, IO_NO_INCREMENT);
    }

    Status
}

