#[used]
static mut PnpRootDOExtension: PNPROOT_FDO_DEVICE_EXTENSION = unsafe { core::mem::zeroed() };

unsafe fn LocateChildDevice(
    DeviceExtension: PPNPROOT_FDO_DEVICE_EXTENSION,
    DeviceId: PCUNICODE_STRING,
    InstanceId: PCWSTR,
    ChildDevice: *mut PPNPROOT_DEVICE,
) -> NTSTATUS {
    let mut InstanceIdU: _UNICODE_STRING = core::mem::zeroed();
    RtlInitUnicodeString(&mut InstanceIdU, InstanceId);

    let mut NextEntry = (*DeviceExtension).DeviceListHead.Flink;
    while NextEntry != core::ptr::addr_of_mut!((*DeviceExtension).DeviceListHead) as PLIST_ENTRY {
        let Device = CONTAINING_RECORD(
            NextEntry as PVOID,
            core::mem::size_of::<PNPROOT_DEVICE>(),
            core::mem::offset_of!(PNPROOT_DEVICE, ListEntry),
        ) as PPNPROOT_DEVICE;

        if RtlEqualUnicodeString(DeviceId, core::ptr::addr_of_mut!((*Device).DeviceID), 1u8) != 0
            && RtlEqualUnicodeString(
                &mut InstanceIdU,
                core::ptr::addr_of_mut!((*Device).InstanceID),
                1u8,
            ) != 0
        {
            if !ChildDevice.is_null() {
                *ChildDevice = Device;
            }
            return STATUS_SUCCESS;
        }
        NextEntry = (*NextEntry).Flink;
    }

    STATUS_NO_SUCH_DEVICE
}

#[no_mangle]
pub unsafe extern "C" fn PnpRootRegisterDevice(DeviceObject: PDEVICE_OBJECT) -> NTSTATUS {
    let DeviceObject = opaque_ptr(DeviceObject);
    let DeviceExtension = core::ptr::addr_of_mut!(PnpRootDOExtension);
    let mut InstancePathCopy: _UNICODE_STRING = core::mem::zeroed();

    let Device = ExAllocatePoolWithTag(
        PagedPool,
        core::mem::size_of::<PNPROOT_DEVICE>(),
        TAG_PNP_ROOT,
    ) as PPNPROOT_DEVICE;
    if Device.is_null() {
        return STATUS_NO_MEMORY;
    }

    let DeviceNode = IopGetDeviceNode(DeviceObject);
    if RtlCreateUnicodeString(
        &mut InstancePathCopy,
        (*DeviceNode).InstancePath.Buffer,
    ) == 0
    {
        ExFreePoolWithTag(Device as PVOID, TAG_PNP_ROOT);
        return STATUS_NO_MEMORY;
    }

    let InstancePath = wcsrchr(InstancePathCopy.Buffer, b'\\' as u16);

    if RtlCreateUnicodeString(
        core::ptr::addr_of_mut!((*Device).InstanceID),
        InstancePath.offset(1),
    ) == 0
    {
        RtlFreeUnicodeString(&mut InstancePathCopy);
        ExFreePoolWithTag(Device as PVOID, TAG_PNP_ROOT);
        return STATUS_NO_MEMORY;
    }

    *InstancePath = 0u16;

    if RtlCreateUnicodeString(
        core::ptr::addr_of_mut!((*Device).DeviceID),
        InstancePathCopy.Buffer,
    ) == 0
    {
        RtlFreeUnicodeString(&mut InstancePathCopy);
        RtlFreeUnicodeString(core::ptr::addr_of_mut!((*Device).InstanceID));
        ExFreePoolWithTag(Device as PVOID, TAG_PNP_ROOT);
        return STATUS_NO_MEMORY;
    }

    *InstancePath = b'\\' as u16;

    (*Device).Pdo = DeviceObject;

    let PdoDeviceExtension = (*DeviceObject).DeviceExtension as PPNPROOT_PDO_DEVICE_EXTENSION;
    core::ptr::write_bytes(
        PdoDeviceExtension as *mut u8,
        0,
        core::mem::size_of::<PNPROOT_PDO_DEVICE_EXTENSION>(),
    );
    (*PdoDeviceExtension).DeviceInfo = Device;

    KeAcquireGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));
    InsertTailList(
        core::ptr::addr_of_mut!((*DeviceExtension).DeviceListHead) as PLIST_ENTRY,
        core::ptr::addr_of_mut!((*Device).ListEntry) as PLIST_ENTRY,
    );
    (*DeviceExtension).DeviceListCount += 1;
    KeReleaseGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));

    RtlFreeUnicodeString(&mut InstancePathCopy);

    STATUS_SUCCESS
}

#[no_mangle]
pub unsafe extern "C" fn PnpRootCreateDeviceObject(
    DeviceObject: *mut PDEVICE_OBJECT,
) -> NTSTATUS {
    let DeviceObject = opaque_ptr(DeviceObject);
    IoCreateDevice(
        IopRootDriverObject,
        core::mem::size_of::<PNPROOT_PDO_DEVICE_EXTENSION>() as ULONG,
        core::ptr::null_mut(),
        FILE_DEVICE_CONTROLLER,
        FILE_AUTOGENERATED_DEVICE_NAME,
        0u8,
        DeviceObject,
    )
}

#[no_mangle]
pub unsafe extern "C" fn PnpRootCreateDevice(
    ServiceName: PUNICODE_STRING,
    PhysicalDeviceObject: *mut PDEVICE_OBJECT,
    FullInstancePath: PUNICODE_STRING,
) -> NTSTATUS {
    let ServiceName = opaque_ptr(ServiceName);
    let PhysicalDeviceObject = opaque_ptr(PhysicalDeviceObject);
    let FullInstancePath = opaque_ptr(FullInstancePath);
    let DeviceExtension = core::ptr::addr_of_mut!(PnpRootDOExtension);
    let mut DevicePath: _UNICODE_STRING = core::mem::zeroed();
    let mut InstancePath: [WCHAR; 5] = [0; 5];
    let mut Device: PPNPROOT_DEVICE = core::ptr::null_mut();
    let mut Status: NTSTATUS;
    let mut NextInstance: ULONG = 0;
    let mut EnumKeyName: _UNICODE_STRING = core::mem::zeroed();
    let mut EnumHandle: HANDLE = core::ptr::null_mut();
    let mut DeviceKeyHandle: HANDLE = core::ptr::null_mut();
    let mut InstanceKeyHandle: HANDLE = core::ptr::null_mut();
    let mut QueryTable: [RTL_QUERY_REGISTRY_TABLE; 2] = core::mem::zeroed();
    let mut ObjectAttributes: _OBJECT_ATTRIBUTES = core::mem::zeroed();

    RtlInitUnicodeString(
        &mut EnumKeyName,
        W_ENUM_KEY.as_ptr(),
    );

    KeAcquireGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));

    DevicePath.Length = 0;
    // sizeof(ENUM_NAME_ROOT) = sizeof(L"Root") = 5 WCHARs = 10 bytes
    DevicePath.MaximumLength =
        (5 * core::mem::size_of::<WCHAR>() + core::mem::size_of::<WCHAR>() + (*ServiceName).Length as usize) as u16;
    DevicePath.Buffer = ExAllocatePoolWithTag(
        PagedPool,
        DevicePath.MaximumLength as usize,
        TAG_PNP_ROOT,
    ) as PWSTR;
    if DevicePath.Buffer.is_null() {
        Status = STATUS_NO_MEMORY;
        KeReleaseGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));
        return Status;
    }
    RtlAppendUnicodeToString(&mut DevicePath, W_ROOT_BACKSLASH.as_ptr());
    RtlAppendUnicodeStringToString(&mut DevicePath, ServiceName);

    Device = ExAllocatePoolWithTag(
        PagedPool,
        core::mem::size_of::<PNPROOT_DEVICE>(),
        TAG_PNP_ROOT,
    ) as PPNPROOT_DEVICE;
    if Device.is_null() {
        Status = STATUS_NO_MEMORY;
        RtlFreeUnicodeString(&mut DevicePath);
        KeReleaseGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));
        return Status;
    }
    core::ptr::write_bytes(Device as *mut u8, 0, core::mem::size_of::<PNPROOT_DEVICE>());
    (*Device).DeviceID = DevicePath;
    RtlInitEmptyUnicodeString(&mut DevicePath, core::ptr::null_mut(), 0);

    Status = IopOpenRegistryKeyEx(&mut EnumHandle, core::ptr::null_mut(), &mut EnumKeyName, KEY_READ);
    if Status >= 0 {
        InitializeObjectAttributes(
            &mut ObjectAttributes,
            core::ptr::addr_of_mut!((*Device).DeviceID),
            OBJ_KERNEL_HANDLE | OBJ_CASE_INSENSITIVE,
            EnumHandle,
            core::ptr::null_mut(),
        );
        Status = ZwCreateKey(
            &mut DeviceKeyHandle,
            KEY_SET_VALUE,
            &mut ObjectAttributes,
            0,
            core::ptr::null_mut(),
            REG_OPTION_NON_VOLATILE,
            core::ptr::null_mut(),
        );
        ObCloseHandle(EnumHandle, 0i8);
    }

    if Status < 0 {
        RtlFreeUnicodeString(core::ptr::addr_of_mut!((*Device).DeviceID));
        RtlFreeUnicodeString(core::ptr::addr_of_mut!((*Device).InstanceID));
        ExFreePoolWithTag(Device as PVOID, TAG_PNP_ROOT);
        RtlFreeUnicodeString(&mut DevicePath);
        KeReleaseGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));
        return Status;
    }

    'tryagain: loop {
        core::ptr::write_bytes(
            QueryTable.as_mut_ptr() as *mut u8,
            0,
            core::mem::size_of_val(&QueryTable),
        );
        QueryTable[0].Name = W_NEXT_INSTANCE.as_ptr();
        QueryTable[0].EntryContext = core::ptr::addr_of_mut!(NextInstance) as PVOID;
        QueryTable[0].Flags = RTL_QUERY_REGISTRY_DIRECT | RTL_QUERY_REGISTRY_REQUIRED;

        Status = RtlQueryRegistryValues(
            RTL_REGISTRY_HANDLE,
            DeviceKeyHandle as PWSTR,
            QueryTable.as_mut_ptr(),
            core::ptr::null_mut(),
            core::ptr::null_mut(),
        );

        NextInstance = 0;
        while NextInstance <= 9999 {
            _snwprintf(
                InstancePath.as_mut_ptr(),
                InstancePath.len(),
                W_FMT_04LU.as_ptr(),
                NextInstance,
            );
            Status = LocateChildDevice(
                DeviceExtension,
                core::ptr::addr_of_mut!((*Device).DeviceID),
                InstancePath.as_ptr(),
                core::ptr::null_mut(),
            );
            if Status == STATUS_NO_SUCH_DEVICE {
                break;
            }
            NextInstance += 1;
        }

        if NextInstance > 9999 {
            Status = STATUS_INSUFFICIENT_RESOURCES;
            break 'tryagain;
        }

        _snwprintf(
            InstancePath.as_mut_ptr(),
            InstancePath.len(),
            W_FMT_04LU.as_ptr(),
            NextInstance,
        );
        Status = LocateChildDevice(
            DeviceExtension,
            core::ptr::addr_of_mut!((*Device).DeviceID),
            InstancePath.as_ptr(),
            core::ptr::null_mut(),
        );
        if Status != STATUS_NO_SUCH_DEVICE || NextInstance > 9999 {
            RtlDeleteRegistryValue(
                RTL_REGISTRY_HANDLE,
                DeviceKeyHandle as PWSTR,
                W_NEXT_INSTANCE.as_ptr(),
            );
            continue;
        }

        NextInstance += 1;
        Status = RtlWriteRegistryValue(
            RTL_REGISTRY_HANDLE,
            DeviceKeyHandle as PWSTR,
            W_NEXT_INSTANCE.as_ptr(),
            REG_DWORD,
            core::ptr::addr_of_mut!(NextInstance) as PVOID,
            core::mem::size_of::<ULONG>() as ULONG,
        );
        if Status < 0 {
            break 'tryagain;
        }

        break;
    }

    if Status >= 0 {
        if RtlCreateUnicodeString(
            core::ptr::addr_of_mut!((*Device).InstanceID),
            InstancePath.as_ptr(),
        ) == 0
        {
            Status = STATUS_NO_MEMORY;
        } else {
            InitializeObjectAttributes(
                &mut ObjectAttributes,
                core::ptr::addr_of_mut!((*Device).InstanceID),
                OBJ_KERNEL_HANDLE | OBJ_CASE_INSENSITIVE,
                DeviceKeyHandle,
                core::ptr::null_mut(),
            );
            Status = ZwCreateKey(
                &mut InstanceKeyHandle,
                KEY_QUERY_VALUE,
                &mut ObjectAttributes,
                0,
                core::ptr::null_mut(),
                REG_OPTION_NON_VOLATILE,
                core::ptr::null_mut(),
            );
            if Status >= 0 {
                ObCloseHandle(InstanceKeyHandle, 0i8);

                (*FullInstancePath).MaximumLength = (*Device).DeviceID.Length
                    + core::mem::size_of::<WCHAR>() as u16
                    + (*Device).InstanceID.Length;
                (*FullInstancePath).Length = 0;
                (*FullInstancePath).Buffer =
                    ExAllocatePool(PagedPool, (*FullInstancePath).MaximumLength as SIZE_T) as PWSTR;
                if (*FullInstancePath).Buffer.is_null() {
                    Status = STATUS_NO_MEMORY;
                } else {
                    RtlAppendUnicodeStringToString(
                        FullInstancePath,
                        core::ptr::addr_of_mut!((*Device).DeviceID),
                    );
                    RtlAppendUnicodeToString(FullInstancePath, W_BACKSLASH.as_ptr());
                    RtlAppendUnicodeStringToString(
                        FullInstancePath,
                        core::ptr::addr_of_mut!((*Device).InstanceID),
                    );

                    Status = PnpRootCreateDeviceObject(core::ptr::addr_of_mut!((*Device).Pdo));
                    if Status >= 0 {
                        let PdoDeviceExtension =
                            (*(*Device).Pdo).DeviceExtension as PPNPROOT_PDO_DEVICE_EXTENSION;
                        core::ptr::write_bytes(
                            PdoDeviceExtension as *mut u8,
                            0,
                            core::mem::size_of::<PNPROOT_PDO_DEVICE_EXTENSION>(),
                        );
                        (*PdoDeviceExtension).DeviceInfo = Device;

                        (*(*Device).Pdo).Flags |= DO_BUS_ENUMERATED_DEVICE;
                        (*(*Device).Pdo).Flags &= !DO_DEVICE_INITIALIZING;

                        InsertTailList(
                            core::ptr::addr_of_mut!((*DeviceExtension).DeviceListHead) as PLIST_ENTRY,
                            core::ptr::addr_of_mut!((*Device).ListEntry) as PLIST_ENTRY,
                        );
                        (*DeviceExtension).DeviceListCount += 1;

                        core::ptr::write_volatile(PhysicalDeviceObject, (*Device).Pdo);
                        Status = STATUS_SUCCESS;
                        Device = core::ptr::null_mut();
                    }
                }
            }
        }
    }

    KeReleaseGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));
    if !Device.is_null() {
        if !(*Device).Pdo.is_null() {
            IoDeleteDevice((*Device).Pdo);
        }
        RtlFreeUnicodeString(core::ptr::addr_of_mut!((*Device).DeviceID));
        RtlFreeUnicodeString(core::ptr::addr_of_mut!((*Device).InstanceID));
        ExFreePoolWithTag(Device as PVOID, TAG_PNP_ROOT);
    }
    RtlFreeUnicodeString(&mut DevicePath);
    if !DeviceKeyHandle.is_null() {
        ObCloseHandle(DeviceKeyHandle, 0i8);
    }
    Status
}

unsafe extern "system" fn QueryStringCallback(
    ValueName: PWSTR,
    ValueType: ULONG,
    ValueData: PVOID,
    ValueLength: ULONG,
    Context: PVOID,
    EntryContext: PVOID,
) -> NTSTATUS {
    let Destination = EntryContext as PUNICODE_STRING;
    let mut Source: _UNICODE_STRING = core::mem::zeroed();

    if ValueType != REG_SZ || ValueLength == 0 || ValueLength % core::mem::size_of::<WCHAR>() as ULONG != 0 {
        (*Destination).Length = 0;
        (*Destination).MaximumLength = 0;
        (*Destination).Buffer = core::ptr::null_mut();
        return STATUS_SUCCESS;
    }

    Source.MaximumLength = ValueLength as u16;
    Source.Length = ValueLength as u16;
    Source.Buffer = ValueData as PWSTR;

    RtlDuplicateUnicodeString(RTL_DUPLICATE_UNICODE_STRING_NULL_TERMINATE, &mut Source, Destination)
}

unsafe extern "system" fn QueryBinaryValueCallback(
    ValueName: PWSTR,
    ValueType: ULONG,
    ValueData: PVOID,
    ValueLength: ULONG,
    Context: PVOID,
    EntryContext: PVOID,
) -> NTSTATUS {
    let Buffer = EntryContext as PBUFFER;

    if ValueLength == 0 {
        *(*Buffer).Data = core::ptr::null_mut();
        return STATUS_SUCCESS;
    }

    let BinaryValue = ExAllocatePoolWithTag(PagedPool, ValueLength as usize, TAG_PNP_ROOT);
    if BinaryValue.is_null() {
        return STATUS_NO_MEMORY;
    }
    core::ptr::copy_nonoverlapping(ValueData as *const u8, BinaryValue as *mut u8, ValueLength as usize);
    *(*Buffer).Data = BinaryValue;
    if !(*Buffer).Length.is_null() {
        *(*Buffer).Length = ValueLength;
    }
    STATUS_SUCCESS
}

unsafe fn CreateDeviceFromRegistry(
    DeviceExtension: PPNPROOT_FDO_DEVICE_EXTENSION,
    DevicePath: PUNICODE_STRING,
    InstanceId: PCWSTR,
    SubKeyHandle: HANDLE,
) -> NTSTATUS {
    let mut Status: NTSTATUS;
    let mut Device: PPNPROOT_DEVICE = core::ptr::null_mut();
    let mut DeviceKeyHandle: HANDLE = core::ptr::null_mut();
    let mut QueryTable: [RTL_QUERY_REGISTRY_TABLE; 4] = core::mem::zeroed();
    let mut Buffer1: BUFFER = core::mem::zeroed();
    let mut Buffer2: BUFFER = core::mem::zeroed();

    Status = LocateChildDevice(DeviceExtension, DevicePath, InstanceId, core::ptr::addr_of_mut!(Device));
    if Status != STATUS_NO_SUCH_DEVICE {
        return STATUS_SUCCESS;
    }

    Device = ExAllocatePoolWithTag(
        PagedPool,
        core::mem::size_of::<PNPROOT_DEVICE>(),
        TAG_PNP_ROOT,
    ) as PPNPROOT_DEVICE;
    if Device.is_null() {
        return STATUS_NO_MEMORY;
    }
    core::ptr::write_bytes(Device as *mut u8, 0, core::mem::size_of::<PNPROOT_DEVICE>());

    (*Device).DeviceID = *DevicePath;
    RtlInitEmptyUnicodeString(DevicePath, core::ptr::null_mut(), 0);
    if RtlCreateUnicodeString(core::ptr::addr_of_mut!((*Device).InstanceID), InstanceId) == 0 {
        Status = STATUS_NO_MEMORY;
        RtlFreeUnicodeString(core::ptr::addr_of_mut!((*Device).DeviceID));
        RtlFreeUnicodeString(core::ptr::addr_of_mut!((*Device).InstanceID));
        ExFreePoolWithTag(Device as PVOID, TAG_PNP_ROOT);
        return Status;
    }

    Status = IopOpenRegistryKeyEx(
        &mut DeviceKeyHandle,
        SubKeyHandle,
        core::ptr::addr_of_mut!((*Device).InstanceID),
        KEY_READ,
    );
    if Status < 0 {
        Status = STATUS_SUCCESS;
        RtlFreeUnicodeString(core::ptr::addr_of_mut!((*Device).DeviceID));
        RtlFreeUnicodeString(core::ptr::addr_of_mut!((*Device).InstanceID));
        ExFreePoolWithTag(Device as PVOID, TAG_PNP_ROOT);
        return Status;
    }

    core::ptr::write_bytes(
        QueryTable.as_mut_ptr() as *mut u8,
        0,
        core::mem::size_of_val(&QueryTable),
    );
    QueryTable[0].QueryRoutine = core::mem::transmute(Some(QueryStringCallback as unsafe extern "system" fn(PWSTR, ULONG, PVOID, ULONG, PVOID, PVOID) -> NTSTATUS));
    QueryTable[0].Name = W_DEVICE_DESC.as_ptr();
    QueryTable[0].EntryContext = core::ptr::addr_of_mut!((*Device).DeviceDescription) as PVOID;

    RtlQueryRegistryValues(
        RTL_REGISTRY_HANDLE,
        DeviceKeyHandle as PCWSTR,
        QueryTable.as_mut_ptr(),
        core::ptr::null_mut(),
        core::ptr::null_mut(),
    );

    Buffer1.Data = core::ptr::addr_of_mut!((*Device).ResourceRequirementsList) as *mut PVOID;
    Buffer1.Length = core::ptr::null_mut();
    Buffer2.Data = core::ptr::addr_of_mut!((*Device).ResourceList) as *mut PVOID;
    Buffer2.Length = core::ptr::addr_of_mut!((*Device).ResourceListSize);
    core::ptr::write_bytes(
        QueryTable.as_mut_ptr() as *mut u8,
        0,
        core::mem::size_of_val(&QueryTable),
    );
    QueryTable[0].Flags = RTL_QUERY_REGISTRY_SUBKEY;
    QueryTable[0].Name = W_LOG_CONF.as_ptr();
    QueryTable[1].QueryRoutine = core::mem::transmute(Some(QueryBinaryValueCallback as unsafe extern "system" fn(PWSTR, ULONG, PVOID, ULONG, PVOID, PVOID) -> NTSTATUS));
    QueryTable[1].Name = W_BASIC_CONFIG_VECTOR.as_ptr();
    QueryTable[1].EntryContext = core::ptr::addr_of_mut!(Buffer1) as PVOID;
    QueryTable[2].QueryRoutine = core::mem::transmute(Some(QueryBinaryValueCallback as unsafe extern "system" fn(PWSTR, ULONG, PVOID, ULONG, PVOID, PVOID) -> NTSTATUS));
    QueryTable[2].Name = W_BOOT_CONFIG.as_ptr();
    QueryTable[2].EntryContext = core::ptr::addr_of_mut!(Buffer2) as PVOID;

    RtlQueryRegistryValues(
        RTL_REGISTRY_HANDLE,
        DeviceKeyHandle as PCWSTR,
        QueryTable.as_mut_ptr(),
        core::ptr::null_mut(),
        core::ptr::null_mut(),
    );

    InsertTailList(
        core::ptr::addr_of_mut!((*DeviceExtension).DeviceListHead) as PLIST_ENTRY,
        core::ptr::addr_of_mut!((*Device).ListEntry) as PLIST_ENTRY,
    );
    (*DeviceExtension).DeviceListCount += 1;

    if !DeviceKeyHandle.is_null() {
        ZwClose(DeviceKeyHandle);
    }
    STATUS_SUCCESS
}

unsafe fn IopShouldProcessDevice(SubKey: HANDLE, InstanceID: PCWSTR) -> NTSTATUS {
    let mut DeviceReportedValue: _UNICODE_STRING = core::mem::zeroed();
    let mut Control: _UNICODE_STRING = core::mem::zeroed();
    let mut InstanceIDU: _UNICODE_STRING = core::mem::zeroed();
    let mut InstanceKey: HANDLE = core::ptr::null_mut();
    let mut ControlKey: HANDLE = core::ptr::null_mut();
    let mut ObjectAttributes: _OBJECT_ATTRIBUTES = core::mem::zeroed();
    let Size: usize = 128;
    let mut DeviceReported: ULONG = 0;
    let mut ResultLength: ULONG = 0;
    let mut Status: NTSTATUS;

    RtlInitUnicodeString(&mut DeviceReportedValue, W_DEVICE_REPORTED.as_ptr());
    RtlInitUnicodeString(&mut Control, W_CONTROL.as_ptr());

    let pKeyValueFullInformation = ExAllocatePool(PagedPool, Size as SIZE_T) as PKEY_VALUE_FULL_INFORMATION;
    if pKeyValueFullInformation.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }

    RtlInitUnicodeString(&mut InstanceIDU, InstanceID);
    InitializeObjectAttributes(
        &mut ObjectAttributes,
        &mut InstanceIDU,
        OBJ_CASE_INSENSITIVE | OBJ_KERNEL_HANDLE,
        SubKey,
        core::ptr::null_mut(),
    );
    Status = ZwOpenKey(&mut InstanceKey, KEY_QUERY_VALUE, &mut ObjectAttributes);
    if Status < 0 {
        ExFreePool(pKeyValueFullInformation as PVOID);
        return Status;
    }

    Status = ZwQueryValueKey(
        InstanceKey,
        &mut DeviceReportedValue,
        _KEY_VALUE_INFORMATION_CLASS_KeyValueFullInformation,
        pKeyValueFullInformation as PVOID,
        Size as ULONG,
        &mut ResultLength,
    );
    if Status == STATUS_OBJECT_NAME_NOT_FOUND {
        ZwClose(InstanceKey);
        ExFreePool(pKeyValueFullInformation as PVOID);
        return STATUS_SUCCESS;
    } else if Status < 0 {
        ZwClose(InstanceKey);
        ExFreePool(pKeyValueFullInformation as PVOID);
        return Status;
    }
    if (*pKeyValueFullInformation).Type != REG_DWORD
        || (*pKeyValueFullInformation).DataLength != core::mem::size_of::<ULONG>() as ULONG
    {
        ZwClose(InstanceKey);
        ExFreePool(pKeyValueFullInformation as PVOID);
        return STATUS_UNSUCCESSFUL;
    }
    core::ptr::copy_nonoverlapping(
        (pKeyValueFullInformation as usize + (*pKeyValueFullInformation).DataOffset as usize) as *const u8,
        core::ptr::addr_of_mut!(DeviceReported) as *mut u8,
        core::mem::size_of::<ULONG>(),
    );

    InitializeObjectAttributes(
        &mut ObjectAttributes,
        &mut Control,
        OBJ_CASE_INSENSITIVE | OBJ_KERNEL_HANDLE,
        InstanceKey,
        core::ptr::null_mut(),
    );
    Status = ZwOpenKey(&mut ControlKey, KEY_QUERY_VALUE, &mut ObjectAttributes);
    ZwClose(InstanceKey);
    if Status == STATUS_OBJECT_NAME_NOT_FOUND {
        ExFreePool(pKeyValueFullInformation as PVOID);
        return STATUS_NO_SUCH_DEVICE;
    } else if Status < 0 {
        ExFreePool(pKeyValueFullInformation as PVOID);
        return Status;
    }

    Status = ZwQueryValueKey(
        ControlKey,
        &mut DeviceReportedValue,
        _KEY_VALUE_INFORMATION_CLASS_KeyValueFullInformation,
        pKeyValueFullInformation as PVOID,
        Size as ULONG,
        &mut ResultLength,
    );
    ZwClose(ControlKey);
    if Status == STATUS_OBJECT_NAME_NOT_FOUND {
        ExFreePool(pKeyValueFullInformation as PVOID);
        return STATUS_NO_SUCH_DEVICE;
    } else if Status < 0 {
        ExFreePool(pKeyValueFullInformation as PVOID);
        return Status;
    }
    if (*pKeyValueFullInformation).Type != REG_DWORD
        || (*pKeyValueFullInformation).DataLength != core::mem::size_of::<ULONG>() as ULONG
    {
        ExFreePool(pKeyValueFullInformation as PVOID);
        return STATUS_UNSUCCESSFUL;
    }
    core::ptr::copy_nonoverlapping(
        (pKeyValueFullInformation as usize + (*pKeyValueFullInformation).DataOffset as usize) as *const u8,
        core::ptr::addr_of_mut!(DeviceReported) as *mut u8,
        core::mem::size_of::<ULONG>(),
    );

    ExFreePool(pKeyValueFullInformation as PVOID);
    STATUS_SUCCESS
}

unsafe fn EnumerateDevices(DeviceObject: PDEVICE_OBJECT) -> NTSTATUS {
    let DeviceExtension = core::ptr::addr_of_mut!(PnpRootDOExtension);
    let mut KeyInfo: PKEY_BASIC_INFORMATION = core::ptr::null_mut();
    let mut SubKeyInfo: PKEY_BASIC_INFORMATION = core::ptr::null_mut();
    let mut LegacyU: _UNICODE_STRING = core::mem::zeroed();
    let mut KeyName: _UNICODE_STRING = core::mem::zeroed();
    let mut SubKeyName: _UNICODE_STRING = core::mem::zeroed();
    let mut DevicePath: _UNICODE_STRING = core::mem::zeroed();
    let mut KeyHandle: HANDLE = core::ptr::null_mut();
    let mut SubKeyHandle: HANDLE = core::ptr::null_mut();
    let mut KeyInfoSize: usize;
    let mut SubKeyInfoSize: usize;
    let mut ResultSize: ULONG = 0;
    let mut Index1: ULONG;
    let mut Index2: ULONG;
    let mut Status: NTSTATUS = STATUS_UNSUCCESSFUL;

    RtlInitUnicodeString(&mut LegacyU, W_LEGACY.as_ptr());
    RtlInitUnicodeString(
        &mut KeyName,
        W_ENUM_ROOT_KEY.as_ptr(),
    );

    KeAcquireGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));

    KeyInfoSize = core::mem::offset_of!(_KEY_BASIC_INFORMATION, Name) + 64 * core::mem::size_of::<WCHAR>();
    KeyInfo = ExAllocatePoolWithTag(
        PagedPool,
        KeyInfoSize + core::mem::size_of::<u16>(),
        TAG_PNP_ROOT,
    ) as PKEY_BASIC_INFORMATION;
    if KeyInfo.is_null() {
        Status = STATUS_NO_MEMORY;
        KeReleaseGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));
        return Status;
    }
    SubKeyInfoSize = KeyInfoSize;
    SubKeyInfo = ExAllocatePoolWithTag(
        PagedPool,
        SubKeyInfoSize + core::mem::size_of::<u16>(),
        TAG_PNP_ROOT,
    ) as PKEY_BASIC_INFORMATION;
    if SubKeyInfo.is_null() {
        Status = STATUS_NO_MEMORY;
        ExFreePoolWithTag(KeyInfo as PVOID, TAG_PNP_ROOT);
        KeReleaseGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));
        return Status;
    }

    Status = IopOpenRegistryKeyEx(&mut KeyHandle, core::ptr::null_mut(), &mut KeyName, KEY_ENUMERATE_SUB_KEYS);
    if Status < 0 {
        ExFreePoolWithTag(KeyInfo as PVOID, TAG_PNP_ROOT);
        ExFreePoolWithTag(SubKeyInfo as PVOID, TAG_PNP_ROOT);
        KeReleaseGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));
        return Status;
    }

    Index1 = 0;
    loop {
        Status = ZwEnumerateKey(
            KeyHandle,
            Index1,
            _KEY_INFORMATION_CLASS_KeyBasicInformation,
            KeyInfo as PVOID,
            KeyInfoSize as ULONG,
            &mut ResultSize,
        );
        if Status == STATUS_NO_MORE_ENTRIES {
            Status = STATUS_SUCCESS;
            break;
        } else if Status == STATUS_BUFFER_OVERFLOW || Status == STATUS_BUFFER_TOO_SMALL {
            KeyInfoSize = ResultSize as usize;
            ExFreePoolWithTag(KeyInfo as PVOID, TAG_PNP_ROOT);
            KeyInfo = ExAllocatePoolWithTag(
                PagedPool,
                KeyInfoSize + core::mem::size_of::<u16>(),
                TAG_PNP_ROOT,
            ) as PKEY_BASIC_INFORMATION;
            if KeyInfo.is_null() {
                Status = STATUS_NO_MEMORY;
                break;
            }
            continue;
        } else if Status < 0 {
            break;
        }

        *(((*KeyInfo).Name.as_mut_ptr() as usize + (*KeyInfo).NameLength as usize) as *mut WCHAR) = 0;

        RtlInitUnicodeString(&mut SubKeyName, (*KeyInfo).Name.as_ptr());
        if RtlPrefixUnicodeString(&mut LegacyU, &mut SubKeyName, 0u8) != 0 {
            Index1 += 1;
            continue;
        }

        Status = IopOpenRegistryKeyEx(&mut SubKeyHandle, KeyHandle, &mut SubKeyName, KEY_ENUMERATE_SUB_KEYS);
        if Status < 0 {
            break;
        }

        Index2 = 0;
        loop {
            Status = ZwEnumerateKey(
                SubKeyHandle,
                Index2,
                _KEY_INFORMATION_CLASS_KeyBasicInformation,
                SubKeyInfo as PVOID,
                SubKeyInfoSize as ULONG,
                &mut ResultSize,
            );
            if Status == STATUS_NO_MORE_ENTRIES {
                break;
            } else if Status == STATUS_BUFFER_OVERFLOW || Status == STATUS_BUFFER_TOO_SMALL {
                SubKeyInfoSize = ResultSize as usize;
                ExFreePoolWithTag(SubKeyInfo as PVOID, TAG_PNP_ROOT);
                SubKeyInfo = ExAllocatePoolWithTag(
                    PagedPool,
                    SubKeyInfoSize + core::mem::size_of::<u16>(),
                    TAG_PNP_ROOT,
                ) as PKEY_BASIC_INFORMATION;
                if SubKeyInfo.is_null() {
                    Status = STATUS_NO_MEMORY;
                    break;
                }
                continue;
            } else if Status < 0 {
                break;
            }

            *(((*SubKeyInfo).Name.as_mut_ptr() as usize + (*SubKeyInfo).NameLength as usize) as *mut WCHAR) = 0;

            DevicePath.Length = 0;
            // sizeof(ENUM_NAME_ROOT) = sizeof(L"Root") = 5 WCHARs = 10 bytes
            DevicePath.MaximumLength = (5 * core::mem::size_of::<WCHAR>()
                + core::mem::size_of::<WCHAR>()
                + SubKeyName.Length as usize) as u16;
            DevicePath.Buffer = ExAllocatePoolWithTag(
                PagedPool,
                DevicePath.MaximumLength as usize,
                TAG_PNP_ROOT,
            ) as PWSTR;
            if DevicePath.Buffer.is_null() {
                Status = STATUS_NO_MEMORY;
                break;
            }

            RtlAppendUnicodeToString(&mut DevicePath, W_ROOT_BACKSLASH.as_ptr());
            RtlAppendUnicodeStringToString(&mut DevicePath, &mut SubKeyName);

            Status = IopShouldProcessDevice(SubKeyHandle, (*SubKeyInfo).Name.as_ptr());
            if Status >= 0 {
                Status = CreateDeviceFromRegistry(
                    DeviceExtension,
                    &mut DevicePath,
                    (*SubKeyInfo).Name.as_ptr(),
                    SubKeyHandle,
                );

                RtlFreeUnicodeString(&mut DevicePath);

                if Status < 0 {
                    break;
                }
            } else if Status != STATUS_NO_SUCH_DEVICE {
                break;
            }

            Index2 += 1;
        }

        ZwClose(SubKeyHandle);
        SubKeyHandle = core::ptr::null_mut();
        if Status < 0 && Status != STATUS_NO_MORE_ENTRIES {
            break;
        }
        Index1 += 1;
    }

    if !SubKeyHandle.is_null() {
        ZwClose(SubKeyHandle);
    }
    if !KeyHandle.is_null() {
        ZwClose(KeyHandle);
    }
    if !KeyInfo.is_null() {
        ExFreePoolWithTag(KeyInfo as PVOID, TAG_PNP_ROOT);
    }
    if !SubKeyInfo.is_null() {
        ExFreePoolWithTag(SubKeyInfo as PVOID, TAG_PNP_ROOT);
    }
    KeReleaseGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));
    Status
}

unsafe fn PnpRootQueryDeviceRelations(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS {
    let DeviceExtension = core::ptr::addr_of_mut!(PnpRootDOExtension);
    let mut Relations: PDEVICE_RELATIONS = core::ptr::null_mut();
    let OtherRelations = (*Irp).IoStatus.Information as PDEVICE_RELATIONS;
    let mut Size: usize;
    let mut Status: NTSTATUS;

    Status = EnumerateDevices(DeviceObject);
    if Status < 0 {
        return Status;
    }

    Size = core::mem::offset_of!(_DEVICE_RELATIONS, Objects)
        + core::mem::size_of::<PDEVICE_OBJECT>() * (*DeviceExtension).DeviceListCount as usize;
    if !OtherRelations.is_null() {
        Size += core::mem::size_of::<PDEVICE_OBJECT>() * (*OtherRelations).Count as usize;
    }
    Relations = ExAllocatePool(PagedPool, Size as SIZE_T) as PDEVICE_RELATIONS;
    if Relations.is_null() {
        Status = STATUS_NO_MEMORY;
        if !OtherRelations.is_null() {
            ExFreePool(OtherRelations as PVOID);
        }
        return Status;
    }
    core::ptr::write_bytes(Relations as *mut u8, 0, Size);
    if !OtherRelations.is_null() {
        (*Relations).Count = (*OtherRelations).Count;
        core::ptr::copy_nonoverlapping(
            (*OtherRelations).Objects.as_ptr(),
            (*Relations).Objects.as_mut_ptr(),
            (*OtherRelations).Count as usize,
        );
    }

    KeAcquireGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));

    let mut NextEntry = (*DeviceExtension).DeviceListHead.Flink;
    while NextEntry != core::ptr::addr_of_mut!((*DeviceExtension).DeviceListHead) as PLIST_ENTRY {
        let Device = CONTAINING_RECORD(
            NextEntry as PVOID,
            core::mem::size_of::<PNPROOT_DEVICE>(),
            core::mem::offset_of!(PNPROOT_DEVICE, ListEntry),
        ) as PPNPROOT_DEVICE;

        if (*Device).Pdo.is_null() {
            Status = PnpRootCreateDeviceObject(core::ptr::addr_of_mut!((*Device).Pdo));
            if Status < 0 {
                break;
            }

            let PdoDeviceExtension = (*(*Device).Pdo).DeviceExtension as PPNPROOT_PDO_DEVICE_EXTENSION;
            core::ptr::write_bytes(
                PdoDeviceExtension as *mut u8,
                0,
                core::mem::size_of::<PNPROOT_PDO_DEVICE_EXTENSION>(),
            );
            (*PdoDeviceExtension).DeviceInfo = Device;

            (*(*Device).Pdo).Flags |= DO_BUS_ENUMERATED_DEVICE;
            (*(*Device).Pdo).Flags &= !DO_DEVICE_INITIALIZING;
        }

        ObReferenceObject((*Device).Pdo as PVOID);

        *(*Relations).Objects.as_mut_ptr().add((*Relations).Count as usize) = (*Device).Pdo;
        (*Relations).Count += 1;

        NextEntry = (*NextEntry).Flink;
    }
    KeReleaseGuardedMutex(core::ptr::addr_of_mut!((*DeviceExtension).DeviceListLock));

    (*Irp).IoStatus.Information = Relations as ULONG_PTR;

    if Status < 0 {
        if !OtherRelations.is_null() {
            ExFreePool(OtherRelations as PVOID);
        }
        if !Relations.is_null() {
            ExFreePool(Relations as PVOID);
        }
    }

    Status
}

unsafe fn PnpRootFdoPnpControl(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS {
    let IrpSp: PIO_STACK_LOCATION = IoGetCurrentIrpStackLocation(Irp);
    let mut Status = (*Irp).IoStatus.__bindgen_anon_1.Status;

    match (*IrpSp).MinorFunction {
        IRP_MN_QUERY_DEVICE_RELATIONS => {
            Status = PnpRootQueryDeviceRelations(DeviceObject, Irp);
        }
        _ => {}
    }

    if Status != STATUS_PENDING {
        (*Irp).IoStatus.__bindgen_anon_1.Status = Status;
        IoCompleteRequest(Irp, IO_NO_INCREMENT);
    }

    Status
}

unsafe fn PdoQueryDeviceRelations(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
    IrpSp: PIO_STACK_LOCATION,
) -> NTSTATUS {
    let mut Status = (*Irp).IoStatus.__bindgen_anon_1.Status;

    if (*IrpSp).Parameters.QueryDeviceRelations.Type != _DEVICE_RELATION_TYPE_TargetDeviceRelation {
        return Status;
    }

    let Relations = ExAllocatePool(PagedPool, core::mem::size_of::<_DEVICE_RELATIONS>() as SIZE_T) as PDEVICE_RELATIONS;
    if Relations.is_null() {
        Status = STATUS_NO_MEMORY;
    } else {
        ObReferenceObject(DeviceObject as PVOID);
        (*Relations).Count = 1;
        (*Relations).Objects[0] = DeviceObject;
        Status = STATUS_SUCCESS;
        (*Irp).IoStatus.Information = Relations as ULONG_PTR;
    }

    Status
}

unsafe fn PdoQueryCapabilities(
    DeviceObject: PDEVICE_OBJECT,
    Irp: PIRP,
    IrpSp: PIO_STACK_LOCATION,
) -> NTSTATUS {
    let DeviceCapabilities = (*IrpSp).Parameters.DeviceCapabilities.Capabilities;

    if (*DeviceCapabilities).Version != 1 {
        return STATUS_REVISION_MISMATCH;
    }

    (*DeviceCapabilities).set_UniqueID(1);

    STATUS_SUCCESS
}

