//! The service tables, as wowx64.dll needs them: the numbers of the few guest
//! syscalls it does not forward blind, and every service's ARGUMENT COUNT (how
//! many stack words to copy from the guest, as the amd64 kernel copies them).
//! Both come from the lists the arm64 kernel and the amd64 guest are built
//! from -- `ntoskrnl/sysfuncs.lst` and win32k's `w32ksvc64.h` (napi.h uses the
//! 64-bit table on arm64 as on amd64) -- so a number here IS the one a guest
//! puts in eax. A name missing from the list fails the build: a guessed number
//! would intercept the wrong service.

use std::{env, fs, path::PathBuf};

const INTERCEPTED: &[&str] = &[
    "NtContinue",
    "NtRaiseException",
    "NtOpenFile",
    "NtCreateFile",
    "NtQueryAttributesFile",
    "NtQueryFullAttributesFile",
    "NtOpenDirectoryObject",
    "NtMapViewOfSection",
    "NtUnmapViewOfSection",
    "NtAllocateVirtualMemory",
    "NtProtectVirtualMemory",
    "NtFreeVirtualMemory",
    "NtGetContextThread",
    "NtSetContextThread",
    "NtFlushInstructionCache",
    "NtCreateThread",
    "NtCallbackReturn",
    "NtTerminateProcess",
    "NtReadFile",
    "NtWriteVirtualMemory",
    "NtReadVirtualMemory",
];

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let list = manifest.join("../../../../ntoskrnl/sysfuncs.lst");
    println!("cargo:rerun-if-changed={}", list.display());
    let text = fs::read_to_string(&list)
        .unwrap_or_else(|e| panic!("wowx64-rust: cannot read {}: {e}", list.display()));
    let names: Vec<&str> = text.lines().map(|l| l.split_whitespace().next().unwrap_or("")).collect();

    let mut out = String::from("// @generated by wowx64-rust/build.rs from ntoskrnl/sysfuncs.lst\n");
    for want in INTERCEPTED {
        let index = names
            .iter()
            .position(|n| n == want)
            .unwrap_or_else(|| panic!("wowx64-rust: {want} is not in {}", list.display()));
        out += &format!("pub const SVC_{want}: u32 = {index};\n");
    }
    let counts: Vec<String> = text
        .lines()
        .map(|l| l.split_whitespace().nth(1).unwrap_or("0").to_string())
        .collect();
    out += &format!("pub const SERVICE_ARGC_NT: [u8; {}] = [{}];\n", counts.len(), counts.join(", "));

    // win32k: `SVC_(Name, Count)` lines, numbered from 0x1000 in file order.
    let w32k = manifest.join("../../../../win32ss/w32ksvc64.h");
    println!("cargo:rerun-if-changed={}", w32k.display());
    let w32k_text = fs::read_to_string(&w32k)
        .unwrap_or_else(|e| panic!("wowx64-rust: cannot read {}: {e}", w32k.display()));
    let mut w32k_counts = Vec::new();
    for line in w32k_text.lines() {
        let t = line.trim_start();
        if let Some(rest) = t.strip_prefix("SVC_(") {
            let n = rest
                .split(')')
                .next()
                .and_then(|inner| inner.split(',').nth(1))
                .map(|c| c.trim().parse::<u8>().unwrap_or_else(|_| panic!("wowx64-rust: bad count in {line}")))
                .unwrap_or_else(|| panic!("wowx64-rust: unparsable {line}"));
            w32k_counts.push(n.to_string());
        }
    }
    assert!(!w32k_counts.is_empty(), "wowx64-rust: no SVC_ entries in {}", w32k.display());
    out += &format!("pub const SERVICE_ARGC_W32K: [u8; {}] = [{}];\n", w32k_counts.len(), w32k_counts.join(", "));

    let dest = PathBuf::from(env::var("OUT_DIR").unwrap()).join("services.rs");
    fs::write(&dest, out).unwrap();
}
