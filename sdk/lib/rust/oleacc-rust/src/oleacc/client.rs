    (*client).hwnd = hwnd;
    (*client).enum_pos = core::ptr::null_mut();
    (*client).role = (ROLE_SYSTEM_CLIENT as i32);

    if !data.is_null() {
        (*client).vtbl = (*data).vtbl as *const win_class_vtbl;
    }
    if !(*client).vtbl.is_null() && (*(*client).vtbl).init.is_some() {
        ((*(*client).vtbl).init.unwrap_unchecked())(client);
    }

    hres = IAccessible_QueryInterface(core::ptr::addr_of_mut!((*client).IAccessible_iface), iid, obj);
    IAccessible_Release(core::ptr::addr_of_mut!((*client).IAccessible_iface));
