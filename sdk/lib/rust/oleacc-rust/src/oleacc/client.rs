unsafe extern "C" fn edit_get_value(
    mut client: *mut Client,
    mut id: VARIANT,
    mut value_out: *mut BSTR,
) -> HRESULT {
    let mut buf: *mut WCHAR = core::ptr::null_mut::<WCHAR>();
    let mut len: UINT = 0;

    if convert_child_id(core::ptr::addr_of_mut!(id)) != (CHILDID_SELF as i32) {
        return E_INVALIDARG;
    }

    if (GetWindowLongW((*client).hwnd, GWL_STYLE as i32) & (ES_PASSWORD as LONG)) != 0 {
        return E_ACCESSDENIED;
    }

    len = SendMessageW(
        (*client).hwnd,
        WM_GETTEXTLENGTH as UINT,
        0 as WPARAM,
        0 as LPARAM,
    ) as UINT;
    buf = heap_alloc_zero(
        ((len.wrapping_add(1 as UINT) as SIZE_T)
            .wrapping_mul(core::mem::size_of::<WCHAR>() as SIZE_T)) as _,
    ) as *mut WCHAR;
    if buf.is_null() {
        return E_OUTOFMEMORY;
    }

    SendMessageW(
        (*client).hwnd,
        WM_GETTEXT as UINT,
        len.wrapping_add(1 as UINT) as WPARAM,
        buf as LPARAM,
    );
    *value_out = SysAllocString(buf);
    heap_free(buf as *mut core::ffi::c_void);
    return S_OK;
}

