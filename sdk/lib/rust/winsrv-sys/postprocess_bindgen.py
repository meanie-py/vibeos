#!/usr/bin/env python3
"""Post-process bindgen output for ntkrnl-sys.

Takes raw bindgen output and produces a clean Rust module:
- Strips the __BindgenBitfieldUnit boilerplate (we'll include it once in common)
- Removes derive(Debug) from types containing unions (can't derive Debug on unions)
- Adds module-level attributes
- Strips trailing whitespace

When --hal is passed, also adds `#[link(name = "ntoskrnl", kind = "raw-dylib")]`
to extern static blocks that import kernel data exports.  This is needed for
hal-rust because hal.dll links with `--disable-auto-import`, so cross-DLL data
references need explicit dllimport-equivalent decoration (vs functions, which
the import library handles automatically).
"""

import argparse
import re
import sys
from pathlib import Path


def load_kernel_data_exports() -> set[str]:
    """Parse ntoskrnl/ntoskrnl.spec for `@ extern Name` lines.

    Returns the set of data symbols exported by ntoskrnl.exe — i.e. the
    statics that other DLLs (hal.dll, win32k.sys, drivers) must import
    via cross-DLL data refs.
    """
    spec = Path(__file__).resolve().parent.parent.parent.parent.parent / "ntoskrnl" / "ntoskrnl.spec"
    if not spec.exists():
        print(f"WARNING: ntoskrnl.spec not found at {spec}; raw-dylib wrap will be a no-op", file=sys.stderr)
        return set()
    names = set()
    for line in spec.read_text().splitlines():
        # Match `@ extern Name` and `@ extern -arch=... Name` forms.
        m = re.match(r'@\s+extern\s+(?:-arch=\S+\s+)?(\w+)', line.strip())
        if m:
            names.add(m.group(1))
    return names


def wrap_kernel_data_imports(content: str, kernel_data: set[str]) -> tuple[str, int]:
    """Add `#[link(name = "ntoskrnl", kind = "raw-dylib")]` to extern blocks
    that declare a static whose name is in `kernel_data`.

    Bindgen emits one declaration per `unsafe extern "C" { ... }` block, so
    matching is straightforward.

    Returns (new_content, num_wrapped).
    """
    pattern = re.compile(
        r'(unsafe extern "C" \{\s*pub static (?:mut )?(\w+):[^}]*\})',
        re.MULTILINE,
    )
    wrapped = 0

    def replace(match: re.Match) -> str:
        nonlocal wrapped
        block = match.group(1)
        name = match.group(2)
        if name in kernel_data:
            wrapped += 1
            return '#[link(name = "ntoskrnl.exe", kind = "raw-dylib", modifiers = "+verbatim")]\n' + block
        return block

    return pattern.sub(replace, content), wrapped


def extract_bitfield_unit(content: str) -> tuple[str, str]:
    """Extract __BindgenBitfieldUnit definition and return (unit_code, rest)."""
    pattern = r'(#\[repr\(C\)\]\n#\[derive\([^)]*\)\]\npub struct __BindgenBitfieldUnit.*?)(?=\n#\[repr|\n#\[derive|\npub type|\npub const|\nunsafe extern)'
    match = re.search(pattern, content, re.DOTALL)
    if match:
        unit_code = match.group(1)
        rest = content[:match.start()] + content[match.end():]
        return unit_code, rest
    return "", content


def extract_bindgen_flex_array(content: str) -> tuple[str, str]:
    """Extract __BindgenUnionField / __IncompleteArrayField definitions."""
    parts_to_remove = []
    for name in ['__BindgenUnionField', '__IncompleteArrayField']:
        pattern = rf'(#\[repr\(transparent\)\]\npub struct {name}.*?)(?=\n#\[repr|\n#\[derive|\npub type|\npub const|\nunsafe extern)'
        match = re.search(pattern, content, re.DOTALL)
        if match:
            parts_to_remove.append((match.start(), match.end(), match.group(1)))

    extracted = []
    for start, end, code in sorted(parts_to_remove, reverse=True):
        extracted.append(code)
        content = content[:start] + content[end:]

    return "\n".join(reversed(extracted)), content


def strip_auto_header(content: str) -> str:
    """Remove the 'automatically generated by rust-bindgen' comment."""
    return re.sub(r'/\* automatically generated by rust-bindgen.*?\*/\n*', '', content)


def add_module_header(content: str, arch: str, for_hal: bool) -> str:
    """Add module-level attributes and documentation."""
    flavor = "HAL+ACPI" if for_hal else "DDK"
    header = f"""//! Auto-generated {flavor} bindings for {arch}.
//!
//! Generated by `bindgen` from ReactOS `ntddk.h` headers.
//! Do not edit manually — regenerate with `postprocess_bindgen.py`.

#![allow(dead_code, unused_unsafe, unused_parens)]

"""
    return header + content


def add_enum_deprefix_aliases(content: str) -> tuple[str, int]:
    """Emit bare-name aliases for type-prefixed constified-enum consts.

    bindgen renders enum members as `pub const <ENUM>_<VARIANT>:
    <ENUM> = N;` but C (and the LLM translation) uses the bare
    `<VARIANT>` (ProcessBasePriority, OptionOk, …). The catalog already
    de-prefixes for *resolution*; this makes the bare name a real Rust
    const so the translated code actually compiles. Skip when the bare
    name would collide with an existing pub item (first def wins).
    """
    pat = re.compile(r'^pub const (\w+):\s*(\w+)\s*=\s*[^;]+;', re.M)
    existing = set(re.findall(r'^pub (?:const|type|struct|fn) (\w+)', content, re.M))
    aliases, seen = [], set()
    for m in pat.finditer(content):
        cname, etype = m.group(1), m.group(2)
        pfx = etype + "_"
        if not cname.startswith(pfx) or len(cname) <= len(pfx):
            continue
        bare = cname[len(pfx):]
        if not bare[:1].isalpha() and bare[:1] != "_":
            continue
        if bare in existing or bare in seen:
            continue
        seen.add(bare)
        aliases.append(f"pub const {bare}: {etype} = {cname};")
    if not aliases:
        return content, 0
    block = ("\n// --- enum de-prefix aliases (bare C/LLM names) ---\n"
             + "\n".join(aliases) + "\n")
    return content + block, len(aliases)


def fix_bitfield_ctor_const_collisions(content: str) -> tuple[str, int]:
    """Rename `new_bitfield_1` ctor params that collide with a `pub const`.

    bindgen names a bitfield struct's `new_bitfield_1` parameters after the
    bitfield fields. When a field name (e.g. `KernelMode`/`UserMode` on the
    `_SYSTEM_SUPPORTED_PROCESSOR_ARCHITECTURES_INFORMATION` bitfield) is also
    a module-level `pub const` — which happens on i386 only, where the NDK
    defines KernelMode/UserMode as bare `#define`s rather than a typed enum —
    Rust resolves the param/`let` binding as a (refutable) const pattern:
    `error[E0005]: refutable pattern in function argument`.

    These ctor params are pure-local convenience (the constructor is never
    called across the FFI boundary), so renaming them with a `__bf` suffix
    is always layout-neutral. Scoped strictly to `new_bitfield_1` bodies.
    """
    const_names = set(re.findall(r'^pub const (\w+):', content, re.M))
    if not const_names:
        return content, 0

    block_re = re.compile(r'    pub fn new_bitfield_1\(.*?\n    \}\n', re.S)
    renamed = 0

    def fix_block(m: re.Match) -> str:
        nonlocal renamed
        block = m.group(0)
        params = re.findall(r'\n        (\w+): ', block)
        for p in params:
            if p in const_names:
                block = re.sub(rf'\b{re.escape(p)}\b', p + '__bf', block)
                renamed += 1
        return block

    return block_re.sub(fix_block, content), renamed


# Bases bindgen flattens into `__bindgen_padding_0: [_; N]` because of the
# MS-extension anonymous-typedef-as-member syntax C uses for cheap "base
# class" inheritance (`struct _DERIVED { CONSOLE_SCREEN_BUFFER; … }`). The
# downstream Rust translation accesses base fields via flat names (mirrors
# the C source), so the padding-array shape is unusable. We expand the
# padding back into the named base struct fields.
#
# Add an entry per affected derived → base type. The dependent base struct
# definition has to APPEAR before the derived one in the bindgen output so
# Rust can refer to its fields by name; bindgen orders by topology already
# so this holds for the cases we know about.
ANON_BASE_INLINE = {
    "_TEXTMODE_SCREEN_BUFFER": "_CONSOLE_SCREEN_BUFFER",
    "_GRAPHICS_SCREEN_BUFFER": "_CONSOLE_SCREEN_BUFFER",
    # CONSRV_CONSOLE inherits from CONSOLE (conio_winsrv.h:206 — `CONSOLE;`
    # as an MS-extension anonymous base member). Phase 5.4 console.rs +
    # consumers access ReferenceCount/Lock/InputBuffer/etc. through the
    # CONSRV_CONSOLE pointer as flat fields.
    "_CONSRV_CONSOLE": "_CONSOLE",
    # CONSOLE_START_INFO embeds CONSOLE_PROPERTIES (the kernel32 →
    # csrss console-creation payload, conmsg.h). Without inline,
    # IconIndex / hIcon / hIconSm / wShowWindow / dwStartupFlags /
    # wFillAttribute / etc. are unreachable through PCONSOLE_START_INFO.
    "_CONSOLE_START_INFO": "_CONSOLE_PROPERTIES",
}


def inline_anon_base_padding(content: str) -> tuple[str, int]:
    """Replace `pub __bindgen_padding_0: [_; N]` in derived structs with
    the named fields of the base struct.

    Bindgen reduces an MS-extension anonymous base member to a
    padding-array placeholder. We splice the base struct's pub-field
    list in front of the derived's tail, so derived struct accesses
    like `(*buf).ScreenBufferSize.X` resolve normally.
    """
    if not ANON_BASE_INLINE:
        return content, 0
    n = 0
    for derived, base in ANON_BASE_INLINE.items():
        # Pull the base struct's body. Tolerate Debug/Copy/Clone derives.
        base_re = re.compile(
            rf'pub struct {re.escape(base)} \{{\n((?:    pub [^\n]+\n)+)\}}',
        )
        bm = base_re.search(content)
        if not bm:
            print(f"  WARN: base struct {base} not found; skip {derived}")
            continue
        base_fields = bm.group(1)

        # Patch the derived struct body in place. The anonymous base
        # member can be at the start (e.g. _TEXTMODE_SCREEN_BUFFER) or
        # the end (e.g. _CONSOLE_START_INFO has explicit fields, then
        # the anon `CONSOLE_PROPERTIES;` last). Match the padding line
        # ANYWHERE in the struct body; replace just that one line.
        derived_re = re.compile(
            rf'(pub struct {re.escape(derived)} \{{\n(?:(?:    pub [^\n]+\n)*?))'
            rf'    pub __bindgen_padding_0: \[[a-z0-9 ;]+\],\n',
        )
        new_content, did = derived_re.subn(rf'\1{base_fields}', content)
        if did:
            content = new_content
            n += did
        else:
            print(f"  WARN: derived {derived} __bindgen_padding_0 line "
                  f"not found; leaving as-is")
    return content, n


TRANSMUTE_CALL = "::core::mem::transmute("

_PRIMITIVE_SIGN = {
    "i8": True, "i16": True, "i32": True, "i64": True, "isize": True,
    "u8": False, "u16": False, "u32": False, "u64": False, "usize": False,
}


def _alias_sign_map(content: str) -> dict[str, bool]:
    """Map type names -> is_signed, resolved through the file's own
    `pub type X = Y;` alias chains, seeded with the primitive ints."""
    aliases = dict(
        re.findall(r"pub type (\w+) = (?:::core::ffi::c_)?(\w+);", content)
    )
    # core::ffi aliases spelled out by bindgen
    ffi = {"char": "i8", "schar": "i8", "uchar": "u8", "short": "i16",
           "ushort": "u16", "int": "i32", "uint": "u32", "long": "i32",
           "ulong": "u32", "longlong": "i64", "ulonglong": "u64"}
    sign: dict[str, bool] = dict(_PRIMITIVE_SIGN)
    def resolve(name: str, depth: int = 0) -> bool | None:
        if name in sign:
            return sign[name]
        if depth > 8:
            return None
        tgt = aliases.get(name) or ffi.get(name)
        if tgt is None:
            return None
        s = resolve(tgt, depth + 1)
        if s is not None:
            sign[name] = s
        return s
    for name in list(aliases):
        resolve(name)
    return sign


def fix_unnecessary_transmutes(content: str) -> tuple[str, int]:
    """Rewrite bindgen's same-size int transmutes (bitfield accessors) into
    plain integer casts so the generated module compiles clean under
    `unnecessary_transmutes` (warn on rustc >= 1.92, linted only when the
    signedness differs).

        let v: uN = transmute(v);       ->  let v: uN = v as uN;   (always safe)
        transmute(EXPR as uN) -> iN ret ->  (EXPR as uN).cast_signed()
        transmute(EXPR as uN) -> uN ret ->  (EXPR as uN)
        return type not resolvable      ->  left alone (e.g. enum bitfields)

    The getter's target type is the enclosing fn's return type, resolved
    through the file's own alias table (LONG64 -> i64, ULONG64 -> u64, ...).
    """
    sign = _alias_sign_map(content)
    n = 0
    # setter form: `let val: u32 = ::core::mem::transmute(val);` (opt. unsafe {})
    pat = re.compile(
        r"let (\w+): (u8|u16|u32|u64|usize) = "
        r"(unsafe \{ )?::core::mem::transmute\((\w+)\)( \})?;"
    )
    content, k = pat.subn(
        lambda m: f"let {m.group(1)}: {m.group(2)} = {m.group(4)} as {m.group(2)};",
        content,
    )
    n += k
    # getter form (possibly multiline): `transmute(<expr> as uN)` — target is
    # the nearest preceding `-> RET {` return type (positions precomputed;
    # bisect per site to stay O(n log n) on multi-MB files).
    import bisect
    ret_pos: list[int] = []
    ret_ty: list[str] = []
    for m_ret in re.finditer(r"->\s*([\w:]+)\s*\{", content):
        ret_pos.append(m_ret.start())
        ret_ty.append(m_ret.group(1).rsplit("::", 1)[-1])
    out = []
    i = 0
    while True:
        j = content.find(TRANSMUTE_CALL, i)
        if j < 0:
            out.append(content[i:])
            break
        depth, k2 = 1, j + len(TRANSMUTE_CALL)
        while k2 < len(content) and depth:
            if content[k2] == "(":
                depth += 1
            elif content[k2] == ")":
                depth -= 1
            k2 += 1
        inner = content[j + len(TRANSMUTE_CALL):k2 - 1].rstrip()
        if inner.endswith(","):
            inner = inner[:-1].rstrip()
        idx = bisect.bisect_left(ret_pos, j) - 1
        ret = ret_ty[idx] if idx >= 0 else None
        signed = sign.get(ret) if ret else None
        if re.search(r"as (u8|u16|u32|u64|usize)$", inner) and signed is not None:
            repl = f"({inner}).cast_signed()" if signed else f"({inner})"
            out.append(content[i:j])
            out.append(repl)
            n += 1
        else:
            out.append(content[i:k2])  # unknown target — leave alone
        i = k2
    return "".join(out), n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input", help="raw bindgen output (.rs)")
    ap.add_argument("arch", help="target arch: arm64 | amd64 | i386")
    ap.add_argument("output", nargs="?", help="output path (.rs)")
    ap.add_argument(
        "--hal",
        action="store_true",
        help="wrap kernel-data-export extern statics with raw-dylib decoration "
             "(required for hal-rust because hal.dll is a separate binary from "
             "ntoskrnl.exe and the link is --disable-auto-import)",
    )
    args = ap.parse_args()

    input_path = Path(args.input)
    arch = args.arch
    output_path = Path(args.output) if args.output else None

    content = input_path.read_text()

    # Strip the auto-generated header comment
    content = strip_auto_header(content)

    # Rewrite same-size int transmutes (bitfield accessors) -> casts so the
    # generated module compiles clean under `unnecessary_transmutes`.
    content, n_transmutes = fix_unnecessary_transmutes(content)
    if n_transmutes:
        print(f"  rewrote {n_transmutes} bitfield transmutes -> casts")

    # Extract __BindgenBitfieldUnit — we'll put it in a shared module
    bitfield_unit, content = extract_bitfield_unit(content)

    # Extract __BindgenUnionField / __IncompleteArrayField
    flex_arrays, content = extract_bindgen_flex_array(content)

    # i386: rename new_bitfield_1 ctor params that collide with pub consts
    # Bare-name aliases for type-prefixed constified-enum members so
    # translated code can use `ProcessBasePriority`, `OptionOk`, etc.
    # MUST precede the bitfield-collision fix so that pass sees the
    # complete final `pub const` set (a new bare alias like `Transition`
    # can itself collide with a new_bitfield_1 ctor param).
    content, n_alias = add_enum_deprefix_aliases(content)
    if n_alias:
        print(f"  {arch}: added {n_alias} enum de-prefix aliases")

    content, n_bf_fixed = fix_bitfield_ctor_const_collisions(content)
    if n_bf_fixed:
        print(f"  {arch}: renamed {n_bf_fixed} bitfield-ctor param(s) colliding with pub const")

    # Retype the console mode + char-attribute constants from u32 → u16
    # — they're untyped `#define X 0xN` literals in wincon.h that
    # bindgen defaults to u32, but every consumer field
    # (CONSOLE_SCREEN_BUFFER.Mode is USHORT, CHAR_INFO.Attributes is
    # WORD) is u16, producing systematic `u16 op u32` E0277 trait
    # mismatches in winsrv-rust. Catches ENABLE_*, COMMON_LVB_*,
    # FOREGROUND_* and BACKGROUND_*.
    n_retyped = 0
    def retype_console_flags(m):
        nonlocal n_retyped
        n_retyped += 1
        return f'pub const {m.group(1)}: u16 = {m.group(2)};'
    content = re.sub(
        r'pub const ((?:ENABLE_|COMMON_LVB_|FOREGROUND_|BACKGROUND_)[A-Z_]+):\s*u32\s*=\s*(\d+|0x[0-9a-fA-F]+);',
        retype_console_flags, content,
    )
    if n_retyped:
        print(f"  {arch}: retyped {n_retyped} console flag constants u32 → u16")

    # Inline MS-extension anonymous base members
    # (_TEXTMODE_SCREEN_BUFFER / _GRAPHICS_SCREEN_BUFFER inherit
    # CONSOLE_SCREEN_BUFFER). Bindgen flattens these to
    # `__bindgen_padding_0: [u16;42]`; we splice the base's fields back
    # in so flat field accesses translate cleanly.
    content, n_inlined = inline_anon_base_padding(content)
    if n_inlined:
        print(f"  {arch}: inlined {n_inlined} anonymous-base struct(s)")

    # HAL output needs raw-dylib decoration on kernel-data extern statics.
    n_wrapped = 0
    if args.hal:
        kernel_data = load_kernel_data_exports()
        content, n_wrapped = wrap_kernel_data_imports(content, kernel_data)

    # Save the shared helpers separately
    shared_dir = output_path.parent if output_path else Path(".")
    shared_path = shared_dir / "bindgen_common.rs"
    if bitfield_unit or flex_arrays:
        shared_content = """//! Shared bindgen helper types.
//!
//! These are generated by bindgen and shared across all architecture modules.
//! Do not edit manually.

#![allow(dead_code, unused_unsafe, unused_parens)]

"""
        if bitfield_unit:
            shared_content += bitfield_unit + "\n\n"
        if flex_arrays:
            shared_content += flex_arrays + "\n"
        # Only write if it doesn't exist or is different
        if not shared_path.exists() or shared_path.read_text() != shared_content:
            shared_path.write_text(shared_content)
            print(f"  Wrote shared helpers: {shared_path} ({len(shared_content)} bytes)")

    # Add use for the shared helpers
    content = "use super::bindgen_common::*;\n\n" + content

    # Add module header
    content = add_module_header(content, arch, args.hal)

    # Strip trailing whitespace on each line
    content = "\n".join(line.rstrip() for line in content.split("\n"))

    # Remove excessive blank lines (3+ in a row → 2)
    content = re.sub(r'\n{4,}', '\n\n\n', content)

    if output_path:
        output_path.write_text(content)
        # Count stats
        funcs = len(re.findall(r'pub fn [A-Z]', content))
        structs = len(re.findall(r'pub struct ', content))
        types = len(re.findall(r'pub type ', content))
        consts = len(re.findall(r'pub const ', content))
        suffix = f", {n_wrapped} kernel-data raw-dylib wraps" if args.hal else ""
        print(f"  {arch}: {len(content.splitlines())} lines, {funcs} functions, {structs} structs, {types} types, {consts} constants{suffix}")
    else:
        sys.stdout.write(content)


if __name__ == "__main__":
    main()
