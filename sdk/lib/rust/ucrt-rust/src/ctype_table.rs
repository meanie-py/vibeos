//! Independently GENERATED replacement data for `sdk/lib/ucrt/locale/ctype.cpp`'s two
//! character-classification tables (`_wctype` and `__newctype`), produced for the
//! ucrtbase de-Microsoft-ification quest.
//!
//! ## Provenance: GENERATED, not transcribed
//!
//! Every value below is computed by a small Python generator
//! (reproduced in full at the bottom of `ctype-table.md`) from two PUBLIC, non-Microsoft
//! fact sources:
//!   1. Python's stdlib `unicodedata` module, which ships the Unicode Character Database
//!      (general category, decomposition type, case properties) - a data set describing the
//!      Unicode standard itself, not any Microsoft product.
//!   2. The fixed rules ISO C assigns to the "C" locale for the ASCII range: which bytes are
//!      hex digits (`0-9A-Fa-f`) and which byte is "blank" (`0x20` only - `isblank()` special-
//!      cases the tab character itself rather than carrying a table bit for it).
//!
//! `sdk/lib/ucrt/locale/ctype.cpp` (Microsoft, about to be deleted) was used ONLY as a DIFF
//! ORACLE to check the generated values against - never copied from. See `ctype-table.md`
//! for the full comparison method and the (now-zero) list of disagreements found while
//! tuning the generator.
//!
//! ## Bit values (cited)
//!
//! The classification bits below are standard ISO-C/CRT `ctype.h` bits, defined at
//! `sdk/include/crt/ctype.h:65-76` and re-declared identically at
//! `sdk/include/ucrt/corecrt_wctype.h:48-58`:
//!   `_UPPER=0x01  _LOWER=0x02  _DIGIT=0x04  _SPACE=0x08`
//!   `_PUNCT=0x10  _CONTROL=0x20  _BLANK=0x40  _HEX=0x80`
//! `C1_ALPHA=0x0100` is a GetStringTypeW/NLS "is-alphabetic" bit, defined at
//! `sdk/include/psdk/winnls.h:266` (`#define C1_ALPHA 256`) and reused by ctype.cpp at the
//! SAME bit position as `_ALPHA`'s high bit (`_ALPHA = 0x0100 | _UPPER | _LOWER`,
//! `sdk/include/crt/ctype.h:76`) - not a coincidence, see ctype-table.md section 2.
//!
//! ## What these tables are
//!
//! `UCRT_WCTYPE` corresponds to `_wctype` (`sdk/lib/ucrt/locale/ctype.cpp:38`), the WIDE
//! (wchar_t / Unicode codepoint) classification table. Index 0 is the EOF(-1) sentinel;
//! index `i` (1..=256) is the classification of Unicode codepoint `i - 1` (0x00..=0x100).
//! `_pwctype = _wctype + 1` (ctype.cpp:745), so `UCRT_WCTYPE[i]` is what `_pwctype[i - 1]`
//! (equivalently `_pwctype[codepoint]`) reads.
//!
//! `UCRT_NEWCTYPE` corresponds to `__newctype` (ctype.cpp:296), the NARROW (char / byte)
//! classification table used by the DEFAULT "C" LOCALE. `_pctype = __newctype + 128`
//! (ctype.cpp:744), and `nlsdata.cpp:94` wires `__newctype + 128` into
//! `__acrt_initial_locale_data._locale_pctype` - i.e. this is the exact table `isalpha()`
//! etc. consult before any `setlocale()` call. Index `128 + c` is the classification of char
//! value `c` for `c` in `-128..=255`; entries for `c` in `-128..=-1` and `c` in `128..=255`
//! are unused/zero (verified: see ctype-table.md).
//!
//! No `#[no_mangle]`, no functions - wiring these into the crate is a separate step.

