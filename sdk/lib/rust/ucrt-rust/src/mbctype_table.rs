//! GENERATED, not transcribed, DBCS mbctype classification tables.
//!
//! # Provenance (read this before wiring anything in)
//!
//! These tables were built from *independent, publicly-documented codepage facts*
//! (DBCS lead-byte / trail-byte ranges, and the JIS X 0201 half-width-kana block),
//! NOT by copying Microsoft's `__rgcode_page_info` table out of the vendored
//! `sdk/lib/ucrt/mbstring/mbctype.cpp` (which is being deleted for licence reasons).
//! Microsoft's table was used only AFTERWARDS, as a diff oracle, to check the
//! generated values byte-for-byte. See `~/vibeos-rust-staging/ucrt/mbctype-table.md`
//! for the full comparison, method, and the one confirmed disagreement (CP936 / 0x7F).
//!
//! ## Bit values (cited to their defining header)
//! `sdk/include/crt/mbctype.h:40-46` (also `sdk/lib/ucrt/inc/corecrt_internal_mbstring.h:38-43`):
//! ```text
//! _MS    0x01   single-byte character in an otherwise-DBCS codepage (e.g. half-width kana)
//! _MP    0x02   single-byte punctuation in an otherwise-DBCS codepage (e.g. half-width kuten)
//! _M1    0x04   valid DBCS lead byte
//! _M2    0x08   valid DBCS trail byte
//! _SBUP  0x10   single-byte uppercase letter
//! _SBLOW 0x20   single-byte lowercase letter
//! ```
//! Table layout: 257 entries, index = char_value + 1 (index 0 is the -1/EOF slot), matching
//! `NUM_CHARS` in `sdk/lib/ucrt/mbstring/mbctype.cpp:29` and `_mbctype`/`mbcinfo.mbctype` in
//! `sdk/lib/rust/msvcrt-crt-rust/src/msvcrt/mbcs.rs`.
//!
//! ## Sources used to GENERATE (not verify) these ranges
//! - CP932 (Shift-JIS, Microsoft variant): lead 0x81-0x9F, 0xE0-0xFC; trail 0x40-0x7E, 0x80-0xFC.
//!   Base JIS X 0208 lead/trail structure plus the well-documented NEC-row-13 / IBM-extension
//!   rows that push the Microsoft lead-byte ceiling from 0xEF to 0xFC (en.wikipedia.org/wiki/Shift_JIS).
//!   Half-width kana/punctuation block 0xA1-0xDF is the JIS X 0201 single-byte set, split at
//!   0xA5/0xA6 into punctuation (0xA1-0xA5) and kana (0xA6-0xDF).
//! - CP936 (GBK): lead 0x81-0xFE; trail 0x40-0xA0 except 0x7F, and 0xA1-0xFE
//!   (en.wikipedia.org/wiki/GBK_(character_encoding)).
//! - CP949 (UHC / Microsoft codepage 949): lead 0x81-0xFE; trail 0x41-0xFE contiguous.
//!   NOTE: the *original* 1990s "Unified Hangul Code" proposal left gaps in the trail range
//!   (0x41-0x5A, 0x61-0x7A, 0x81-0xFE per en.wikipedia.org/wiki/Unified_Hangul_Code); Microsoft's
//!   CP949 fills those gaps with additional Hangul syllables, giving a contiguous 0x41-0xFE.
//!   This table follows Microsoft's actual (contiguous) CP949, which is also what the diff
//!   oracle table implements — see the .md report for the confidence caveat.
//! - CP950 (Big5, Microsoft/ETen variant): lead 0x81-0xFE; trail 0x40-0x7E, 0xA1-0xFE
//!   (en.wikipedia.org/wiki/Big5).
//! - Base single-byte case table (applied under every codepage): ASCII 'A'-'Z' -> _SBUP,
//!   'a'-'z' -> _SBLOW. This is the `_MBCTYPE_DEFAULT` baseline
//!   (`sdk/lib/ucrt/mbstring/mbctype.cpp:76-88`) and is plain ASCII, not Microsoft expression.
//!
//! CP1361 (Johab) is DELIBERATELY OMITTED — see the .md report, section "Could not determine".
//! A partial independent check suggested its true lead-byte range starts at 0x84, not the 0x81
//! `sdk/lib/ucrt/mbstring/mbctype.cpp:82-94` uses, but the check was not complete enough to
//! generate a trustworthy full replacement table. Shipping a half-verified guess here would be
//! the worst failure mode (a byte silently misclassified, never faulting) — so it is a gap, not
//! a guess.

