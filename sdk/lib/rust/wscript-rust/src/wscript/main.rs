unsafe extern "C" fn get_engine_clsid(ext: *const WCHAR, clsid: *mut CLSID) -> BOOL {
    let mut fileid: [WCHAR; 64] = [0; 64];
    let mut progid: [WCHAR; 64] = [0; 64];
    let mut res: DWORD;
    let mut size: LONG;
    let mut hkey: HKEY = core::ptr::null_mut();
    let mut hres: HRESULT;

    res = RegOpenKeyW(HKEY_CLASSES_ROOT, ext, core::ptr::addr_of_mut!(hkey)) as DWORD;
    if res != ERROR_SUCCESS as DWORD {
        return (FALSE) as BOOL;
    }

    size = ARRAY_SIZE!(fileid) as LONG;
    res = RegQueryValueW(
        hkey,
        core::ptr::null(),
        core::ptr::addr_of_mut!(fileid) as LPWSTR,
        core::ptr::addr_of_mut!(size),
    ) as DWORD;
    RegCloseKey(hkey);
    if res != ERROR_SUCCESS as DWORD {
        return (FALSE) as BOOL;
    }

    WINE_TRACE!(
        "fileid is %s\n",
        wine_dbgstr_w(core::ptr::addr_of_mut!(fileid) as *mut WCHAR),
    );

    lstrcatW(core::ptr::addr_of_mut!(fileid) as LPWSTR, RUSTCONV_WSTR_56352B0A08C4.as_ptr());
    res = RegOpenKeyW(
        HKEY_CLASSES_ROOT,
        core::ptr::addr_of_mut!(fileid) as *mut WCHAR as LPCWSTR,
        core::ptr::addr_of_mut!(hkey),
    ) as DWORD;
    if res != ERROR_SUCCESS as DWORD {
        return (FALSE) as BOOL;
    }

    size = ARRAY_SIZE!(progid) as LONG;
    res = RegQueryValueW(
        hkey,
        core::ptr::null(),
        core::ptr::addr_of_mut!(progid) as LPWSTR,
        core::ptr::addr_of_mut!(size),
    ) as DWORD;
    RegCloseKey(hkey);
    if res != ERROR_SUCCESS as DWORD {
        return (FALSE) as BOOL;
    }

    WINE_TRACE!(
        "ProgID is %s\n",
        wine_dbgstr_w(core::ptr::addr_of_mut!(progid) as *mut WCHAR),
    );

    hres = CLSIDFromProgID(
        core::ptr::addr_of_mut!(progid) as *mut WCHAR as LPCOLESTR,
        clsid as LPCLSID,
    );
    return (hres >= 0) as BOOL;
}

unsafe extern "C" fn create_engine(clsid: *mut CLSID, script_ret: *mut *mut IActiveScript, parser: *mut PIActiveScriptParse) -> BOOL {
    let mut script: *mut IActiveScript = core::ptr::null_mut();
    let mut unk: *mut IUnknown = core::ptr::null_mut();
    let mut hres: HRESULT = 0;

    hres = CoCreateInstance(
        clsid,
        core::ptr::null_mut(),
        (CLSCTX_INPROC_SERVER | CLSCTX_INPROC_HANDLER) as DWORD,
        core::ptr::addr_of!(IID_IUnknown),
        core::ptr::addr_of_mut!(unk) as *mut LPVOID,
    );
    if hres < 0 {
        return (FALSE) as BOOL;
    }

    hres = IUnknown_QueryInterface(
        unk,
        core::ptr::addr_of!(IID_IActiveScript),
        core::ptr::addr_of_mut!(script) as *mut *mut ::core::ffi::c_void,
    );
    IUnknown_Release(unk);
    if hres < 0 {
        return (FALSE) as BOOL;
    }

    hres = IActiveScript_QueryInterface(
        script,
        core::ptr::addr_of!(IID_IActiveScriptParse),
        parser as *mut *mut ::core::ffi::c_void,
    );
    if hres < 0 {
        IActiveScript_Release(script);
        return (FALSE) as BOOL;
    }

    *script_ret = script;
    return (TRUE) as BOOL;
}

