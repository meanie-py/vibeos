unsafe extern "C" fn run_wsfjob(mut jobtag: *mut IXMLDOMElement) -> HRESULT {
    // FIXME: We are supposed to somehow handle multiple languages in the same IActiveScript.
    let mut script: *mut IActiveScript = core::ptr::null_mut::<IActiveScript>();
    let mut deflang: LPCWSTR = RUSTCONV_WSTR_8DBABC31EFBF.as_ptr();
    let mut scripttag: *mut IXMLDOMNode = core::ptr::null_mut::<IXMLDOMNode>();
    let mut hr: HRESULT = S_OK;
    if (xmldomelem_getelembytag(jobtag, RUSTCONV_WSTR_36FE6B739493.as_ptr(), 0, &raw mut scripttag)) >= 0
    {
        let mut clsid: CLSID = core::mem::zeroed::<CLSID>();
        let mut parser: PIActiveScriptParse = core::ptr::null_mut();
        let mut lang: BSTR = core::ptr::null_mut::<OLECHAR>();
        let mut code: BSTR = core::ptr::null_mut::<OLECHAR>();
        if xmldomnode_getattributevalue(scripttag, RUSTCONV_WSTR_F140A88FAB51.as_ptr(), &raw mut lang) < 0
        {
            lang = core::ptr::null_mut::<OLECHAR>();
        }
        hr = CLSIDFromProgID(
            if !lang.is_null() {
                lang as LPCOLESTR
            } else {
                deflang as LPCOLESTR
            },
            &raw mut clsid,
        );
        SysFreeString(lang);

        if hr >= 0
        {
            hr = E_FAIL;
            if create_engine(&raw mut clsid, &raw mut script, &raw mut parser) != 0
            {
                if init_engine(script, parser) != 0
                {
                    let mut index: ::core::ffi::c_long = 0;
                    index = 0 as ::core::ffi::c_long;
                    while index < 0x7fffffff as ::core::ffi::c_long
                    {
                        let mut obj: *mut IXMLDOMNode = core::ptr::null_mut::<IXMLDOMNode>();
                        if !(xmldomelem_getelembytag(jobtag, RUSTCONV_WSTR_6CAF09C29887.as_ptr(), index, &raw mut obj) >= 0)
                        {
                            break;
                        }
                        wsf_addobjectfromnode(script, obj);
                        IUnknown_Release((obj).cast());
                        index += 1;
                    }

                    hr = IXMLDOMNode_get_text(scripttag, &raw mut code);
                    if hr >= 0
                    {
                        hr = IActiveScriptParse_ParseScriptText(
                            parser,
                            code as LPCOLESTR,
                            core::ptr::null::<OLECHAR>(),
                            core::ptr::null_mut::<IUnknown>(),
                            core::ptr::null::<OLECHAR>(),
                            1 as _, // DWORD_PTR: DWORDLONG on 64-bit, DWORD on 32-bit
                            1 as ULONG,
                            (SCRIPTTEXT_HOSTMANAGESSOURCE | SCRIPTITEM_ISVISIBLE) as DWORD,
                            core::ptr::null_mut::<VARIANT>(),
                            core::ptr::null_mut::<EXCEPINFO>(),
                        );
                        if hr >= 0
                        {
                            hr = IActiveScript_SetScriptState(script, SCRIPTSTATE_STARTED);
                            IActiveScript_Close(script);
                        }
                        SysFreeString(code);
                    }
                    ITypeInfo_Release(host_ti);
                }
                IUnknown_Release((parser).cast());
                IUnknown_Release((script).cast());
            }
        }
        IUnknown_Release((scripttag).cast());
    }
    return hr;
}

unsafe extern "C" fn run_wsf(xmlpath: LPCWSTR) -> HRESULT {
    // C: WCHAR url[ARRAY_SIZE(L"file://") + max(ARRAY_SIZE(scriptFullName), MAX_PATH)]; scriptFullName is WCHAR[MAX_PATH]
    // (a static mut, so its length is taken from the declaration rather than from the static).
    let mut url: [WCHAR; (ARRAY_SIZE!("file://") + MAX_PATH) as _] = [0; (ARRAY_SIZE!("file://") + MAX_PATH) as _];
    let mut cch: DWORD = ARRAY_SIZE!(url) as DWORD;
    let mut pdoc: *mut IXMLDOMDocument = core::ptr::null_mut();
    let mut hr: HRESULT = UrlCreateFromPathW(xmlpath, url.as_mut_ptr(), core::ptr::addr_of_mut!(cch), 0);
    let mut hrCom: HRESULT = 0;
    if hr < 0 {
        return hr;
    }

    hrCom = CoInitialize(core::ptr::null_mut());
    hr = CoCreateInstance(
        core::ptr::addr_of!(CLSID_DOMDocument30),
        core::ptr::null_mut(),
        CLSCTX_INPROC_SERVER,
        core::ptr::addr_of!(IID_IXMLDOMDocument),
        core::ptr::addr_of_mut!(pdoc) as *mut LPVOID,
    );
    if hr >= 0 {
        let mut succ: VARIANT_BOOL = VARIANT_FALSE;
        let mut pdocelm: *mut IXMLDOMElement = core::ptr::null_mut();
        let mut bsurl: BSTR = SysAllocString(url.as_mut_ptr());
        let mut v: VARIANT = core::mem::zeroed();
        v.n1.n2.vt = VT_BSTR as VARTYPE;
        v.n1.n2.n3.bstrVal = bsurl;
        if bsurl.is_null()
            || {
                hr = IXMLDOMDocument_load(pdoc, v, core::ptr::addr_of_mut!(succ));
                hr > 0
            }
            || (hr >= 0 && succ == 0)
        {
            hr = E_FAIL;
        }
        if hr >= 0
            && {
                hr = IXMLDOMDocument_get_documentElement(pdoc, core::ptr::addr_of_mut!(pdocelm));
                hr >= 0
            }
        {
            let mut tagName: BSTR = core::ptr::null_mut();
            if {
                hr = IXMLDOMElement_get_tagName(pdocelm, core::ptr::addr_of_mut!(tagName));
                hr >= 0
            } {
                if lstrcmpiW(tagName as LPCWSTR, RUSTCONV_WSTR_20A0C2B64EC9.as_ptr()) == 0 {
                    // FIXME: Accept job id as a function parameter and find the job here
                    let mut p: *mut IXMLDOMElement = core::ptr::null_mut();
                    if {
                        hr = xmldomelem_getelembytagasdomelem(pdocelm, RUSTCONV_WSTR_10CF5F02096B.as_ptr(), 0, core::ptr::addr_of_mut!(p));
                        hr >= 0
                    } {
                        IUnknown_Release((pdocelm).cast());
                        pdocelm = p;
                    }
                } else if lstrcmpiW(tagName as LPCWSTR, RUSTCONV_WSTR_10CF5F02096B.as_ptr()) != 0 {
                    hr = 0x800400C0 as u32 as HRESULT;
                }
                SysFreeString(tagName);
            }
            if hr >= 0 {
                // FIXME: Only support CDATA blocks if the xml tag is present?
                hr = run_wsfjob(pdocelm);
            }
            IUnknown_Release((pdocelm).cast());
        }
        VariantClear(core::ptr::addr_of_mut!(v));
        IUnknown_Release((pdoc).cast());
    }
    free_globals();
    if hrCom >= 0 {
        CoUninitialize();
    }
    return hr;
}

