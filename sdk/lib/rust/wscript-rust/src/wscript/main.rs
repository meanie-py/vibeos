unsafe extern "C" fn write_to_handle(handle: HANDLE, string: *const WCHAR) {
    let mut count: DWORD = 0;
    let mut ret: DWORD = 0;
    let mut len: DWORD = 0;
    let mut lena: DWORD = 0;
    let mut buf: *mut core::ffi::c_char = core::ptr::null_mut();
    len = lstrlenW(string as LPCWSTR) as DWORD;
    ret = WriteConsoleW(
        handle,
        string as *const core::ffi::c_void,
        len,
        core::ptr::addr_of_mut!(count),
        core::ptr::null_mut(),
    ) as DWORD;
    if ret != 0 {
        WriteConsoleW(
            handle,
            RUSTCONV_WSTR_80E09B2F645F.as_ptr() as *const core::ffi::c_void,
            2,
            core::ptr::addr_of_mut!(count),
            core::ptr::null_mut(),
        );
        return;
    }
    lena = WideCharToMultiByte(
        GetOEMCP(),
        0,
        string as LPCWSTR,
        len as core::ffi::c_int,
        core::ptr::null_mut(),
        0,
        core::ptr::null(),
        core::ptr::null_mut(),
    ) as DWORD;
    buf = malloc(lena as size_t) as *mut core::ffi::c_char;
    if buf.is_null() {
        return;
    }
    WideCharToMultiByte(
        GetOEMCP(),
        0,
        string as LPCWSTR,
        len as core::ffi::c_int,
        buf as LPSTR,
        lena as core::ffi::c_int,
        core::ptr::null(),
        core::ptr::null_mut(),
    );
    WriteFile(
        handle,
        buf as LPCVOID,
        lena,
        core::ptr::addr_of_mut!(count),
        core::ptr::null_mut(),
    );
    free(buf as *mut core::ffi::c_void);
    WriteFile(
        handle,
        b"\r\n\0".as_ptr() as *const core::ffi::c_char as LPCVOID,
        2,
        core::ptr::addr_of_mut!(count),
        core::ptr::null_mut(),
    );
}

unsafe extern "C" fn print_error(string: *const WCHAR) {
    if wshInteractive != 0 {
        MessageBoxW(core::ptr::null_mut(), string as LPCWSTR, RUSTCONV_WSTR_5BD1A4ED912F.as_ptr(), MB_OK);
        return;
    }

    write_to_handle(GetStdHandle(STD_ERROR_HANDLE), string);
}

unsafe extern "C" fn print_string(string: *const WCHAR) {
    write_to_handle(GetStdHandle(STD_OUTPUT_HANDLE), string);
}

unsafe extern "C" fn output_writeconsole(str: *const WCHAR, wlen: DWORD) {
    let mut count: DWORD = 0;
    if WriteConsoleW(
        GetStdHandle(STD_OUTPUT_HANDLE),
        str as *const core::ffi::c_void,
        wlen,
        core::ptr::addr_of_mut!(count),
        core::ptr::null_mut(),
    ) == 0
    {
        let mut len: DWORD = 0;
        let mut buf: *mut core::ffi::c_char = core::ptr::null_mut();

        /* On Windows WriteConsoleW() fails if the output is redirected. So fall
         * back to WriteFile() with OEM code page. */
        len = WideCharToMultiByte(
            GetOEMCP(),
            0,
            str as LPCWSTR,
            wlen as core::ffi::c_int,
            core::ptr::null_mut(),
            0 as core::ffi::c_int,
            core::ptr::null(),
            core::ptr::null_mut(),
        ) as DWORD;
        buf = malloc(len as usize) as *mut core::ffi::c_char;

        WideCharToMultiByte(
            GetOEMCP(),
            0,
            str as LPCWSTR,
            wlen as core::ffi::c_int,
            buf as LPSTR,
            len as core::ffi::c_int,
            core::ptr::null(),
            core::ptr::null_mut(),
        );
        WriteFile(
            GetStdHandle(STD_OUTPUT_HANDLE),
            buf as LPCVOID,
            len,
            core::ptr::addr_of_mut!(count),
            core::ptr::null_mut(),
        );
        free(buf as *mut core::ffi::c_void);
    }
}

unsafe extern "C" fn output_formatstring(fmt: *const WCHAR, mut va_args: va_list) {
    let mut str: *mut WCHAR = core::ptr::null_mut();
    let mut len: DWORD = 0;
    len = FormatMessageW(
        FORMAT_MESSAGE_FROM_STRING | FORMAT_MESSAGE_ALLOCATE_BUFFER,
        fmt as LPCVOID,
        0,
        0,
        core::ptr::addr_of_mut!(str) as LPWSTR,
        0,
        core::ptr::addr_of_mut!(va_args),
    );
    if len == 0 && GetLastError() != ERROR_NO_WORK_DONE {
        WINE_FIXME!(
            b"Could not format string: le=%lu, fmt=%s\n\0".as_ptr() as *const i8,
            GetLastError(),
            wine_dbgstr_w(fmt),
        );
        return;
    }
    if wshInteractive != 0 {
        MessageBoxW(
            core::ptr::null_mut(),
            str as LPCWSTR,
            RUSTCONV_WSTR_5BD1A4ED912F.as_ptr(),
            MB_OK,
        );
    } else {
        output_writeconsole(str, len);
    }
    LocalFree(str as HLOCAL);
}

#[no_mangle]
unsafe extern "C" fn print_resource_v(id: ::core::ffi::c_uint, ap_list: *mut ::core::ffi::c_void) {
    let mut fmt: *mut WCHAR = ::core::ptr::null_mut::<WCHAR>();
    let mut len: ::core::ffi::c_int = 0;
    let mut va_args: va_list = *(ap_list as *mut va_list);
    let mut str: *const WCHAR = ::core::ptr::null::<WCHAR>();

    if false {
        len = LoadStringW(
            GetModuleHandleW(::core::ptr::null_mut()),
            id,
            &raw mut fmt as *mut WCHAR,
            0,
        );
        if len == 0 {
            WINE_FIXME!(
                b"LoadString failed with %ld\n\0".as_ptr() as *const i8,
                GetLastError(),
            );
            return;
        }

        len += 1;
        fmt = malloc(
            (len as usize).wrapping_mul(::core::mem::size_of::<WCHAR>()),
        ) as *mut WCHAR;
        if fmt.is_null() {
            return;
        }

        LoadStringW(
            GetModuleHandleW(::core::ptr::null_mut()),
            id,
            fmt,
            len,
        );
    } else {
        match id {
            IDS_USAGE => {
                str = RUSTCONV_WSTR_672D09618619.as_ptr();
            }
            IDS_NO_SCRIPT_FILE => {
                str = RUSTCONV_WSTR_EEBDB9EE0F8E.as_ptr();
            }
            IDS_FILE_NOT_FOUND => {
                str = RUSTCONV_WSTR_DF748F39F7AA.as_ptr();
            }
            IDS_SCRIPT_LOAD_ERROR => {
                str = RUSTCONV_WSTR_6D1AB2E25748.as_ptr();
            }
            IDS_TIMEOUT_EXCEEDED => {
                str = RUSTCONV_WSTR_3BE63156B183.as_ptr();
            }
            _ => {}
        }
        if str.is_null() {
            WINE_FIXME!(b"Missing string %u\n\0".as_ptr() as *const i8, id);
            return;
        }
        len = lstrlenW(str as LPCWSTR);
        len += 1;
        fmt = malloc(
            (len as usize).wrapping_mul(::core::mem::size_of::<WCHAR>()),
        ) as *mut WCHAR;
        if fmt.is_null() {
            return;
        }
        lstrcpyW(fmt as LPWSTR, str as LPCWSTR);
    }


    output_formatstring(fmt, va_args);


    free(fmt as *mut ::core::ffi::c_void);
}



unsafe extern "system" fn timeout_thread_proc(arg: *mut core::ffi::c_void) -> DWORD {
    let mut ms: DWORD = arg as DWORD_PTR as DWORD;
    if WaitForSingleObject(timeout_cancel_event, ms) == WAIT_TIMEOUT {
        print_resource(IDS_TIMEOUT_EXCEEDED, core::ptr::addr_of_mut!(scriptFullName) as *mut WCHAR);
        ExitProcess(1);
    }
    return 0;
}
#[no_mangle]
pub unsafe extern "C" fn schedule_timeout(mut seconds: LONG) {
    if !timeout_thread.is_null() {
        SetEvent(timeout_cancel_event);
        WaitForSingleObject(timeout_thread, INFINITE as DWORD);
        CloseHandle(timeout_thread);
        timeout_thread = core::ptr::null_mut();
    }
    if seconds <= 0 as LONG {
        return;
    }
    if timeout_cancel_event.is_null() {
        timeout_cancel_event = CreateEventW(
            core::ptr::null_mut::<_SECURITY_ATTRIBUTES>(),
            TRUE as BOOL,
            FALSE as BOOL,
            core::ptr::null::<WCHAR>(),
        );
    } else {
        ResetEvent(timeout_cancel_event);
    }
    timeout_thread = CreateThread(
        core::ptr::null_mut::<_SECURITY_ATTRIBUTES>(),
        0 as DWORD,
        Some(timeout_thread_proc),
        (seconds * 1000 as LONG) as DWORD_PTR as PVOID,
        0 as DWORD,
        core::ptr::null_mut::<DWORD>(),
    );
}

