#[no_mangle]
pub unsafe extern "system" fn wWinMain(
    hInst: HINSTANCE,
    hPrevInst: HINSTANCE,
    cmdline: LPWSTR,
    cmdshow: i32,
) -> i32 {
    let mut ext: *mut WCHAR = core::ptr::null_mut();
    let mut filepart: *mut WCHAR = core::ptr::null_mut();
    let mut filename: *mut WCHAR = core::ptr::null_mut();
    let mut parser: *mut IActiveScriptParse = core::ptr::null_mut();
    let mut script: *mut IActiveScript = core::ptr::null_mut();
    let mut script_text: BSTR = core::ptr::null_mut();
    let mut argv: *mut *mut WCHAR = core::ptr::null_mut();
    let mut clsid: CLSID = core::mem::zeroed();
    let mut argc: i32 = 0;
    let mut i: i32 = 0;
    let mut ret: i32 = 0;
    let mut res: DWORD;

    WINE_TRACE!(
        b"(%p %p %s %x)\n\0".as_ptr() as *const i8,
        hInst,
        hPrevInst,
        wine_dbgstr_w(cmdline),
        cmdshow,
    );

    argv = CommandLineToArgvW(GetCommandLineW(), &mut argc) as *mut *mut WCHAR;
    if argv.is_null() {
        return 1;
    }

    /* Pass 1: consume // host options from all positions. */
    i = 1;
    while i < argc {
        if *(*argv.offset(i as isize)).offset(0 as isize) == '/' as WCHAR
            && *(*argv.offset(i as isize)).offset(1 as isize) == '/' as WCHAR
            && set_host_properties(*argv.offset(i as isize)) != 0
        {
            *argv.offset(i as isize) = core::ptr::null_mut();
        }
        i += 1;
    }

    /* Pass 2: find filename, consuming single-/ and - options before it. */
    i = 1;
    'pass2: while i < argc {
        'body2: {
            if (*argv.offset(i as isize)).is_null() {
                break 'body2;
            }
            if *(*argv.offset(i as isize)).offset(0 as isize) == '-' as WCHAR
                && *(*argv.offset(i as isize)).offset(1 as isize) == '-' as WCHAR
                && *(*argv.offset(i as isize)).offset(2 as isize) == 0
            {
                break 'body2; /* -- separator */
            }
            if (*(*argv.offset(i as isize)) == '/' as WCHAR
                || *(*argv.offset(i as isize)) == '-' as WCHAR)
                && set_host_properties(*argv.offset(i as isize)) != 0
            {
                break 'body2;
            }
            filename = *argv.offset(i as isize);
            i += 1;
            break 'pass2;
        }
        i += 1;
    }

    /* Pass 3: compact script args, skipping consumed // options. */
    if !filename.is_null() {
        let mut j: i32 = 0;
        let first_arg: i32 = i;
        while i < argc {
            'body3: {
                if (*argv.offset(i as isize)).is_null() {
                    break 'body3;
                }
                *argv.offset((first_arg + j) as isize) = *argv.offset(i as isize);
                j += 1;
            }
            i += 1;
        }
        argums = argv.offset(first_arg as isize);
        numOfArgs = j;
    }

    if filename.is_null() && argc == 1 {
        if wshInteractive != 0 {
            WINE_FIXME!(b"Settings dialog not implemented\n\0".as_ptr() as *const i8);
            return 0;
        }
        if nologo == 0 {
            print_banner();
        }
        print_resource(IDS_USAGE as u32);
        return 0;
    }

    if nologo == 0 {
        print_banner();
    }

    if filename.is_null() {
        print_resource(IDS_NO_SCRIPT_FILE as u32);
        return 1;
    }

    res = GetFullPathNameW(
        filename as LPCWSTR,
        ARRAY_SIZE!(scriptFullName) as DWORD,
        core::ptr::addr_of_mut!(scriptFullName) as LPWSTR,
        core::ptr::addr_of_mut!(filepart),
    );
    if res == 0 || res as usize > MAX_PATH as usize { // ARRAY_SIZE(scriptFullName), scriptFullName is WCHAR[MAX_PATH]
        return 1;
    }

    ext = wcsrchr(filepart, ('.' as i32) as u16) as *mut WCHAR;
    if !ext.is_null() && lstrcmpiW(ext as LPCWSTR, RUSTCONV_WSTR_7584232C41F0.as_ptr()) == 0 {
        return run_wsf(core::ptr::addr_of_mut!(scriptFullName) as *mut WCHAR as LPCWSTR)
            as i32;
    }

    script_text = get_script_str(core::ptr::addr_of_mut!(scriptFullName) as *mut WCHAR);
    if script_text.is_null() {
        let err: DWORD = GetLastError();
        if err == ERROR_FILE_NOT_FOUND as DWORD || err == ERROR_PATH_NOT_FOUND as DWORD {
            print_resource(
                IDS_FILE_NOT_FOUND as u32,
                core::ptr::addr_of_mut!(scriptFullName) as *mut WCHAR,
            );
        } else {
            let mut syserr: *mut WCHAR = core::ptr::null_mut();
            FormatMessageW(
                (FORMAT_MESSAGE_ALLOCATE_BUFFER | FORMAT_MESSAGE_FROM_SYSTEM | FORMAT_MESSAGE_IGNORE_INSERTS) as DWORD,
                core::ptr::null::<core::ffi::c_void>(),
                err,
                MAKELANGID!(LANG_NEUTRAL as USHORT, SUBLANG_DEFAULT as USHORT) as DWORD,
                core::ptr::addr_of_mut!(syserr) as LPWSTR,
                0 as DWORD,
                core::ptr::null_mut(),
            );
            if !syserr.is_null() {
                /* Trim trailing whitespace from system error message. */
                let mut len: i32 = lstrlenW(syserr as LPCWSTR);
                while len > 0
                    && (*syserr.offset((len - 1) as isize) == '\r' as WCHAR
                        || *syserr.offset((len - 1) as isize) == '\n' as WCHAR
                        || *syserr.offset((len - 1) as isize) == ' ' as WCHAR)
                {
                    len -= 1;
                    *syserr.offset(len as isize) = 0 as WCHAR;
                }
                print_resource(
                    IDS_SCRIPT_LOAD_ERROR as u32,
                    core::ptr::addr_of_mut!(scriptFullName) as *mut WCHAR,
                    syserr,
                );
                LocalFree(syserr as HLOCAL);
            } else {
                print_resource(
                    IDS_SCRIPT_LOAD_ERROR as u32,
                    core::ptr::addr_of_mut!(scriptFullName) as *mut WCHAR,
                    RUSTCONV_WSTR_96A296D224F2.as_ptr(),
                );
            }
        }
        return 1;
    }

    ext = wcsrchr(filepart, ('.' as i32) as u16) as *mut WCHAR;
    if !g_force_engine.is_null() {
        CLSIDFromProgID(g_force_engine, core::ptr::addr_of_mut!(clsid));
    } else if ext.is_null() || get_engine_clsid(ext, core::ptr::addr_of_mut!(clsid)) == 0 {
        WINE_FIXME!(
            b"Could not find engine for %s\n\0".as_ptr() as *const i8,
            wine_dbgstr_w(ext),
        );
        return 1;
    }

    CoInitialize(core::ptr::null_mut());

    if create_engine(
        core::ptr::addr_of_mut!(clsid),
        core::ptr::addr_of_mut!(script),
        core::ptr::addr_of_mut!(parser),
    ) == 0
    {
        WINE_FIXME!(b"Could not create script engine\n\0".as_ptr() as *const i8);
        CoUninitialize();
        return 1;
    }

    if init_engine(script, parser) != 0 {
        schedule_timeout(wshTimeout);
        if run_script(script_text, script, parser) == 0 {
            ret = 1;
        }
        schedule_timeout(0);
        IActiveScript_Close(script);
        ITypeInfo_Release(host_ti);
    } else {
        WINE_FIXME!(b"Script initialization failed\n\0".as_ptr() as *const i8);
    }

    SysFreeString(script_text);
    IActiveScript_Release(script);
    IActiveScriptParse_Release(parser);

    free_globals();

    CoUninitialize();

    return ret;
}

