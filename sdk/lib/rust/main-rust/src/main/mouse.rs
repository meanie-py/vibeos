unsafe extern "C" fn OnDrawItem(
    idCtl: UINT,
    lpdis: LPDRAWITEMSTRUCT,
    pPointerData: PPOINTER_DATA,
) {
    let mut rc: RECT = RECT {
        left: 0,
        top: 0,
        right: 0,
        bottom: 0,
    };

    if (*lpdis).itemState & (ODS_SELECTED as UINT) != 0 {
        FillRect(
            (*lpdis).hDC,
            core::ptr::addr_of_mut!((*lpdis).rcItem) as LPCRECT,
            ((COLOR_HIGHLIGHT + 1) as usize) as HBRUSH,
        );
        SetBkColor(
            (*lpdis).hDC,
            GetSysColor((COLOR_HIGHLIGHT) as i32) as COLORREF,
        );
        SetTextColor(
            (*lpdis).hDC,
            GetSysColor((COLOR_HIGHLIGHTTEXT) as i32) as COLORREF,
        );
    } else {
        FillRect(
            (*lpdis).hDC,
            core::ptr::addr_of_mut!((*lpdis).rcItem) as LPCRECT,
            ((COLOR_WINDOW + 1) as usize) as HBRUSH,
        );
        SetBkColor(
            (*lpdis).hDC,
            GetSysColor((COLOR_WINDOW) as i32) as COLORREF,
        );
        SetTextColor(
            (*lpdis).hDC,
            GetSysColor((COLOR_WINDOWTEXT) as i32) as COLORREF,
        );
    }

    if (*lpdis).itemID != ((-(1 as ::core::ffi::c_int)) as UINT) {
        CopyRect(
            core::ptr::addr_of_mut!(rc),
            core::ptr::addr_of_mut!((*lpdis).rcItem) as LPCRECT,
        );
        rc.left += 5 as LONG;
        DrawText(
            (*lpdis).hDC,
            core::ptr::addr_of!(g_CursorData[(*lpdis).itemData as usize].szCursorName)
                as *mut TCHAR as LPCWSTR,
            -(1 as ::core::ffi::c_int),
            core::ptr::addr_of_mut!(rc),
            (DT_SINGLELINE | DT_VCENTER | DT_LEFT) as UINT,
        );

        if !g_CursorData[(*lpdis).itemData as usize].hCursor.is_null() {
            DrawIcon(
                (*lpdis).hDC,
                ((*lpdis).rcItem.right - (*pPointerData).cxCursor as LONG - 4 as LONG)
                    as ::core::ffi::c_int,
                ((*lpdis).rcItem.top + 2 as LONG) as ::core::ffi::c_int,
                g_CursorData[(*lpdis).itemData as usize].hCursor as HICON,
            );
        }
    }

    if (*lpdis).itemState & (ODS_FOCUS as UINT) != 0 {
        CopyRect(
            core::ptr::addr_of_mut!(rc),
            core::ptr::addr_of_mut!((*lpdis).rcItem) as LPCRECT,
        );
        InflateRect(
            core::ptr::addr_of_mut!(rc),
            -(1 as ::core::ffi::c_int),
            -(1 as ::core::ffi::c_int),
        );
        DrawFocusRect(
            (*lpdis).hDC,
            core::ptr::addr_of_mut!(rc) as LPCRECT,
        );
    }
}

