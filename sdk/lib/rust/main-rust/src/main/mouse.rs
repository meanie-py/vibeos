unsafe extern "C" fn LoadInitialCursorScheme(hwndDlg: HWND) {
    let mut szSchemeName: [TCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut szSystemScheme: [TCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut szCursorPath: [TCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut hCursorKey: HKEY = core::ptr::null_mut();
    let mut lError: LONG = 0;
    let mut dwDataSize: DWORD = 0;
    let mut dwSchemeSource: DWORD = 0 as DWORD;
    let mut index: UINT = 0;
    let mut i: UINT = 0;
    let mut dwType: DWORD = 0;
    let mut nSel: INT = 0;

    index = IDS_ARROW as UINT;
    i = 0 as UINT;
    while index <= IDS_HAND as UINT {
        g_CursorData[i as usize].hCursor = core::ptr::null_mut();
        g_CursorData[i as usize].szCursorPath[0 as usize] = 0 as TCHAR;
        index = index.wrapping_add(1);
        i = i.wrapping_add(1);
    }

    lError = RegOpenKeyEx(
        HKEY_CURRENT_USER,
        (&[0x0043, 0x006f, 0x006e, 0x0074, 0x0072, 0x006f, 0x006c, 0x0020, 0x0050, 0x0061, 0x006e, 0x0065, 0x006c, 0x005c, 0x0043, 0x0075, 0x0072, 0x0073, 0x006f, 0x0072, 0x0073, 0x0000u16]).as_ptr() /* _T "Control Panel\\Cursors" */,
        0 as DWORD,
        (KEY_READ | KEY_QUERY_VALUE) as REGSAM,
        core::ptr::addr_of_mut!(hCursorKey),
    ) as LONG;
    if lError != ERROR_SUCCESS as LONG {
        return;
    }

    dwDataSize = core::mem::size_of::<DWORD>() as DWORD;
    lError = RegQueryValueEx(
        hCursorKey,
        (&[0x0053, 0x0063, 0x0068, 0x0065, 0x006d, 0x0065, 0x0020, 0x0053, 0x006f, 0x0075, 0x0072, 0x0063, 0x0065, 0x0000u16]).as_ptr() /* _T "Scheme Source" */,
        core::ptr::null_mut(),
        core::ptr::null_mut(),
        core::ptr::addr_of_mut!(dwSchemeSource) as LPBYTE,
        core::ptr::addr_of_mut!(dwDataSize),
    ) as LONG;

    if dwSchemeSource != 0 as DWORD {
        dwDataSize = (MAX_PATH as usize).wrapping_mul(core::mem::size_of::<TCHAR>()) as DWORD;
        lError = RegQueryValueEx(
            hCursorKey,
            core::ptr::null(),
            core::ptr::null_mut(),
            core::ptr::null_mut(),
            core::ptr::addr_of_mut!(szSchemeName) as LPBYTE,
            core::ptr::addr_of_mut!(dwDataSize),
        ) as LONG;

        index = IDS_ARROW as UINT;
        i = 0 as UINT;
        while index <= IDS_HAND as UINT {
            dwDataSize = (MAX_PATH as usize).wrapping_mul(core::mem::size_of::<TCHAR>()) as DWORD;
            lError = RegQueryValueEx(
                hCursorKey,
                g_CursorData[i as usize].lpValueName,
                core::ptr::null_mut(),
                core::ptr::addr_of_mut!(dwType),
                core::ptr::addr_of_mut!(szCursorPath) as LPBYTE,
                core::ptr::addr_of_mut!(dwDataSize),
            ) as LONG;
            if lError == ERROR_SUCCESS as LONG {
                if dwType == REG_EXPAND_SZ as DWORD {
                    ExpandEnvironmentStrings(
                        core::ptr::addr_of_mut!(szCursorPath) as *mut TCHAR,
                        core::ptr::addr_of_mut!(g_CursorData[i as usize].szCursorPath) as *mut TCHAR,
                        MAX_PATH as DWORD,
                    );
                } else {
                    _tcscpy(
                        core::ptr::addr_of_mut!(g_CursorData[i as usize].szCursorPath) as *mut TCHAR,
                        core::ptr::addr_of_mut!(szCursorPath) as *mut TCHAR,
                    );
                }
            }
            index = index.wrapping_add(1);
            i = i.wrapping_add(1);
        }
    }

    RegCloseKey(hCursorKey);

    ReloadCurrentCursorScheme();
    RefreshCursorList(hwndDlg, TRUE as BOOL);

    /* Build the full scheme name */
    if dwSchemeSource == 0 as DWORD {
        LoadString(
            hApplet,
            IDS_NONE as UINT,
            core::ptr::addr_of_mut!(szSchemeName) as LPTSTR,
            MAX_PATH as INT,
        );
    } else if dwSchemeSource == 2 as DWORD {
        LoadString(
            hApplet,
            IDS_SYSTEM_SCHEME as UINT,
            core::ptr::addr_of_mut!(szSystemScheme) as LPTSTR,
            MAX_PATH as INT,
        );
        _tcsncat(
            core::ptr::addr_of_mut!(szSchemeName) as *mut TCHAR,
            (&[0x0020, 0x0000u16]).as_ptr() /* _T " " */,
            (MAX_PATH as usize)
                .wrapping_sub(_tcslen(core::ptr::addr_of_mut!(szSchemeName) as *mut TCHAR) as usize)
                .wrapping_sub(1 as usize),
        );
        _tcsncat(
            core::ptr::addr_of_mut!(szSchemeName) as *mut TCHAR,
            core::ptr::addr_of_mut!(szSystemScheme) as *mut TCHAR,
            (MAX_PATH as usize)
                .wrapping_sub(_tcslen(core::ptr::addr_of_mut!(szSchemeName) as *mut TCHAR) as usize)
                .wrapping_sub(1 as usize),
        );
    }

    /* Search and select the current scheme name from the scheme list */
    nSel = SendDlgItemMessage(
        hwndDlg,
        (IDC_COMBO_CURSOR_SCHEME as i32),
        CB_FINDSTRINGEXACT as UINT,
        (0 as WPARAM).wrapping_sub(1 as WPARAM),
        core::ptr::addr_of_mut!(szSchemeName) as *mut TCHAR as LPARAM,
    ) as INT;
    if nSel != CB_ERR as INT {
        SendDlgItemMessage(
            hwndDlg,
            (IDC_COMBO_CURSOR_SCHEME as i32),
            CB_SETCURSEL as UINT,
            nSel as WPARAM,
            0 as LPARAM,
        );
    }

    /* Enable /disable delete button */
    EnableWindow(
        GetDlgItem(hwndDlg, (IDC_BUTTON_DELETE_SCHEME as i32)),
        (dwSchemeSource == 1 as DWORD) as core::ffi::c_int,
    );
}

