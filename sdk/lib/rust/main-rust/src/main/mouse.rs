unsafe extern "C" fn DeleteUserCursorScheme(hwndDlg: HWND) -> BOOL {
    let mut szSchemeName: [TCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut szTitle: [TCHAR; 128] = [0; 128];
    let mut szRawText: [TCHAR; 256] = [0; 256];
    let mut szText: [TCHAR; 256] = [0; 256];
    let mut hDlgCtrl: HWND = core::ptr::null_mut();
    let mut hCuKey: HKEY = core::ptr::null_mut();
    let mut hCuCursorKey: HKEY = core::ptr::null_mut();
    let mut lResult: LONG = 0;
    let mut nSel: INT = 0;

    hDlgCtrl = GetDlgItem(hwndDlg, IDC_COMBO_CURSOR_SCHEME as INT);
    nSel = SendMessage(hDlgCtrl, CB_GETCURSEL as UINT, 0 as WPARAM, 0 as LPARAM) as INT;
    if nSel == CB_ERR as INT {
        return FALSE as BOOL;
    }

    SendMessage(hDlgCtrl, CB_GETLBTEXT as UINT, nSel as WPARAM, core::ptr::addr_of_mut!(szSchemeName) as *mut TCHAR as LPARAM);

    LoadString(hApplet, IDS_REMOVE_TITLE as UINT, core::ptr::addr_of_mut!(szTitle) as *mut TCHAR, 128 as core::ffi::c_int);
    LoadString(hApplet, IDS_REMOVE_TEXT as UINT, core::ptr::addr_of_mut!(szRawText) as *mut TCHAR, 256 as core::ffi::c_int);

    _stprintf(core::ptr::addr_of_mut!(szText) as *mut TCHAR, core::ptr::addr_of_mut!(szRawText) as *mut TCHAR, core::ptr::addr_of_mut!(szSchemeName) as *mut TCHAR);

    /* Confirm scheme removal */
    if MessageBox(hwndDlg, core::ptr::addr_of_mut!(szText) as *mut TCHAR, core::ptr::addr_of_mut!(szTitle) as *mut TCHAR, (MB_YESNO | MB_ICONQUESTION) as UINT) == IDNO as INT {
        return TRUE as BOOL;
    }

    if RegOpenCurrentUser((KEY_READ | KEY_SET_VALUE) as REGSAM, core::ptr::addr_of_mut!(hCuKey)) != ERROR_SUCCESS as LSTATUS {
        return FALSE as BOOL;
    }

    if RegOpenKeyEx(hCuKey, (&[0x0043, 0x006f, 0x006e, 0x0074, 0x0072, 0x006f, 0x006c, 0x0020, 0x0050, 0x0061, 0x006e, 0x0065, 0x006c, 0x005c, 0x0043, 0x0075, 0x0072, 0x0073, 0x006f, 0x0072, 0x0073, 0x005c, 0x0053, 0x0063, 0x0068, 0x0065, 0x006d, 0x0065, 0x0073, 0x0000u16]).as_ptr() /* _T "Control Panel\\Cursors\\Schemes" */, 0 as DWORD, (KEY_READ | KEY_SET_VALUE) as REGSAM, core::ptr::addr_of_mut!(hCuCursorKey)) != ERROR_SUCCESS as LSTATUS
    {
        RegCloseKey(hCuKey);
        return FALSE as BOOL;
    }

    lResult = RegDeleteValue(hCuCursorKey, core::ptr::addr_of_mut!(szSchemeName) as *mut TCHAR) as LONG;

    RegCloseKey(hCuCursorKey);
    RegCloseKey(hCuKey);

    if lResult == ERROR_SUCCESS as LONG
    {
        SendMessage(hDlgCtrl, CB_DELETESTRING as UINT, nSel as WPARAM, 0 as LPARAM);
        SendMessage(hDlgCtrl, CB_SETCURSEL as UINT, 0 as WPARAM, 0 as LPARAM);
    }

    return (lResult == ERROR_SUCCESS as LONG) as BOOL;
}

unsafe extern "system" fn SaveSchemeProc(
    hwndDlg: HWND,
    uMsg: UINT,
    wParam: WPARAM,
    lParam: LPARAM,
) -> INT_PTR {
    let mut pSchemeName: LPTSTR = core::ptr::null_mut();

    match uMsg {
        WM_INITDIALOG => {
            pSchemeName = lParam as LPTSTR;
            SetWindowLongPtr(
                hwndDlg,
                DWLP_USER as ::core::ffi::c_int,
                pSchemeName as LONG_PTR,
            );
            SendDlgItemMessage(
                hwndDlg,
                (IDC_EDIT_SCHEME_NAME as i32),
                WM_SETTEXT as UINT,
                0 as WPARAM,
                pSchemeName as LPARAM,
            );
        }

        WM_COMMAND => {
            if (LOWORD!(wParam) as i32) == (IDOK as i32) {
                pSchemeName = GetWindowLongPtr(
                    hwndDlg,
                    DWLP_USER as ::core::ffi::c_int,
                ) as LPTSTR;
                SendDlgItemMessage(
                    hwndDlg,
                    (IDC_EDIT_SCHEME_NAME as i32),
                    WM_GETTEXT as UINT,
                    MAX_PATH as WPARAM,
                    pSchemeName as LPARAM,
                );
                EndDialog(hwndDlg, TRUE as INT_PTR);
            } else if (LOWORD!(wParam) as i32) == (IDCANCEL as i32) {
                EndDialog(hwndDlg, FALSE as INT_PTR);
            }
        }

        _ => {}
    }

    return FALSE as INT_PTR;
}

unsafe extern "C" fn SaveCursorScheme(hwndDlg: HWND) -> BOOL {
    let mut szSystemScheme: [TCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut szSchemeName: [TCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut szNewSchemeName: [TCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut szTempPath: [TCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut szTitle: [TCHAR; 128] = [0; 128];
    let mut szText: [TCHAR; 256] = [0; 256];
    let mut nSel: INT = 0;
    let mut index: INT = 0;
    let mut i: INT = 0;
    let mut nLength: INT = 0;
    let mut lpSchemeData: LPTSTR = core::ptr::null_mut();
    let mut hCuKey: HKEY = core::ptr::null_mut();
    let mut hCuCursorKey: HKEY = core::ptr::null_mut();
    let mut lError: LONG = ERROR_SUCCESS as LONG;
    let mut bSchemeExists: BOOL = 0;

    LoadString(hApplet, IDS_SYSTEM_SCHEME as UINT, core::ptr::addr_of_mut!(szSystemScheme) as LPTSTR, MAX_PATH as INT);

    nSel = SendDlgItemMessage(hwndDlg, IDC_COMBO_CURSOR_SCHEME as INT, CB_GETCURSEL as UINT, 0 as WPARAM, 0 as LPARAM) as INT;
    if nSel == CB_ERR as INT {
        return FALSE as BOOL;
    }

    if nSel == 0 as INT {
        szSchemeName[0 as usize] = 0 as TCHAR;
        szNewSchemeName[0 as usize] = 0 as TCHAR;
    } else {
        SendDlgItemMessage(hwndDlg, IDC_COMBO_CURSOR_SCHEME as INT, CB_GETLBTEXT as UINT, nSel as WPARAM, core::ptr::addr_of_mut!(szNewSchemeName) as LPARAM);

        if !_tcsstr(core::ptr::addr_of_mut!(szNewSchemeName) as LPTSTR, core::ptr::addr_of_mut!(szSystemScheme) as LPTSTR).is_null() {
            szNewSchemeName[(_tcslen(core::ptr::addr_of_mut!(szNewSchemeName) as LPTSTR) as usize)
                .wrapping_sub(_tcslen(core::ptr::addr_of_mut!(szSystemScheme) as LPTSTR) as usize)
                .wrapping_sub(1 as usize)] = 0 as TCHAR;
        }
    }

    /* Ask for a name for the new cursor scheme */
    if DialogBoxParam(hApplet, MAKEINTRESOURCE!(IDD_CURSOR_SCHEME_SAVEAS) as LPCWSTR,
                        hwndDlg, Some(SaveSchemeProc),
                        core::ptr::addr_of_mut!(szNewSchemeName) as LPARAM) == 0
    {
        return TRUE as BOOL;
    }

    /* Check all non-system schemes for the new name */
    nSel = SendDlgItemMessage(hwndDlg, IDC_COMBO_CURSOR_SCHEME as INT, CB_GETCOUNT as UINT, 0 as WPARAM, 0 as LPARAM) as INT;
    if nSel == CB_ERR as INT {
        return FALSE as BOOL;
    }

    bSchemeExists = FALSE as BOOL;
    i = 0 as INT;
    while i < nSel {
        SendDlgItemMessage(hwndDlg, IDC_COMBO_CURSOR_SCHEME as INT, CB_GETLBTEXT as UINT, i as WPARAM, core::ptr::addr_of_mut!(szSchemeName) as LPARAM);
        if _tcsstr(core::ptr::addr_of_mut!(szSchemeName) as LPTSTR, core::ptr::addr_of_mut!(szSystemScheme) as LPTSTR).is_null() {
            if _tcscmp(core::ptr::addr_of_mut!(szSchemeName) as LPTSTR, core::ptr::addr_of_mut!(szNewSchemeName) as LPTSTR) == 0 as INT {
                bSchemeExists = TRUE as BOOL;
                break;
            }
        }
        i += 1;
    }

    if bSchemeExists != 0 {
        LoadString(hApplet, IDS_OVERWRITE_TITLE as UINT, core::ptr::addr_of_mut!(szTitle) as LPTSTR, 128 as INT);
        LoadString(hApplet, IDS_OVERWRITE_TEXT as UINT, core::ptr::addr_of_mut!(szText) as LPTSTR, 256 as INT);

        /* Confirm scheme overwrite */
        if MessageBox(hwndDlg, core::ptr::addr_of_mut!(szText) as LPCTSTR, core::ptr::addr_of_mut!(szTitle) as LPCTSTR, (MB_YESNO as UINT) | (MB_ICONQUESTION as UINT)) == IDNO as INT {
            return TRUE as BOOL;
        }
    }

    /* Save the cursor scheme */
    nLength = 0 as INT;
    index = IDS_ARROW as INT;
    i = 0 as INT;
    while index <= IDS_HAND as INT {
        if i > 0 as INT {
            nLength += 1;
        }
        nLength += _tcslen(core::ptr::addr_of_mut!((*(core::ptr::addr_of_mut!(g_CursorData) as *mut CURSOR_DATA).offset(i as isize)).szCursorPath) as LPTSTR) as INT;
        index += 1;
        i += 1;
    }
    nLength += 1;

    lpSchemeData = HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY as DWORD, (nLength as SIZE_T).wrapping_mul(core::mem::size_of::<TCHAR>() as SIZE_T)) as LPTSTR;

    if lpSchemeData.is_null() {
        return FALSE as BOOL;
    }

    index = IDS_ARROW as INT;
    i = 0 as INT;
    while index <= IDS_HAND as INT {
        CompressPath(core::ptr::addr_of_mut!(szTempPath) as LPTSTR, core::ptr::addr_of_mut!((*(core::ptr::addr_of_mut!(g_CursorData) as *mut CURSOR_DATA).offset(i as isize)).szCursorPath) as LPTSTR);
        if i > 0 as INT {
            _tcscat(lpSchemeData, (&[0x002c, 0x0000u16]).as_ptr() /* _T "," */ as LPCTSTR);
        }
        _tcscat(lpSchemeData, core::ptr::addr_of_mut!(szTempPath) as LPTSTR);
        index += 1;
        i += 1;
    }

    if RegOpenCurrentUser((KEY_READ as REGSAM) | (KEY_SET_VALUE as REGSAM), core::ptr::addr_of_mut!(hCuKey)) != ERROR_SUCCESS as LSTATUS {
        HeapFree(GetProcessHeap(), 0 as DWORD, lpSchemeData as PVOID);
        return FALSE as BOOL;
    }

    if RegOpenKeyEx(hCuKey, (&[0x0043, 0x006f, 0x006e, 0x0074, 0x0072, 0x006f, 0x006c, 0x0020, 0x0050, 0x0061, 0x006e, 0x0065, 0x006c, 0x005c, 0x0043, 0x0075, 0x0072, 0x0073, 0x006f, 0x0072, 0x0073, 0x005c, 0x0053, 0x0063, 0x0068, 0x0065, 0x006d, 0x0065, 0x0073, 0x0000u16]).as_ptr() /* _T "Control Panel\\Cursors\\Schemes" */ as LPCTSTR, 0 as DWORD, (KEY_READ as REGSAM) | (KEY_SET_VALUE as REGSAM), core::ptr::addr_of_mut!(hCuCursorKey)) != ERROR_SUCCESS as LSTATUS {
        RegCloseKey(hCuKey);
        HeapFree(GetProcessHeap(), 0 as DWORD, lpSchemeData as PVOID);
        return FALSE as BOOL;
    }

    lError = RegSetValueEx(hCuCursorKey, core::ptr::addr_of_mut!(szNewSchemeName) as LPCTSTR, 0 as DWORD,
                           REG_EXPAND_SZ as DWORD, (lpSchemeData as LPBYTE) as *const BYTE,
                           ((_tcslen(lpSchemeData) as usize).wrapping_add(1 as usize)).wrapping_mul(core::mem::size_of::<TCHAR>() as usize) as DWORD) as LONG;

    RegCloseKey(hCuCursorKey);
    RegCloseKey(hCuKey);

    /* Add the new scheme to the scheme list and select it */
    if lError == ERROR_SUCCESS as LONG {
        let mut copy: LPTSTR = _tcsdup(lpSchemeData) as LPTSTR;

        nSel = SendDlgItemMessage(hwndDlg, IDC_COMBO_CURSOR_SCHEME as INT, CB_ADDSTRING as UINT, 0 as WPARAM, core::ptr::addr_of_mut!(szNewSchemeName) as LPARAM) as INT;
        SendDlgItemMessage(hwndDlg, IDC_COMBO_CURSOR_SCHEME as INT, CB_SETITEMDATA as UINT, nSel as WPARAM, copy as LPARAM);
        SendDlgItemMessage(hwndDlg, IDC_COMBO_CURSOR_SCHEME as INT, CB_SETCURSEL as UINT, nSel as WPARAM, 0 as LPARAM);
    }

    HeapFree(GetProcessHeap(), 0 as DWORD, lpSchemeData as PVOID);

    return (lError == ERROR_SUCCESS as LONG) as BOOL;
}

unsafe extern "C" fn BrowseCursor(hwndDlg: HWND) -> BOOL {
    let mut szFileName: [TCHAR; (MAX_PATH) as _] = [0 as TCHAR; (MAX_PATH) as _];
    let mut szFilter: [TCHAR; (MAX_PATH) as _] = [0 as TCHAR; (MAX_PATH) as _];
    let mut szTitle: [TCHAR; (MAX_PATH) as _] = [0 as TCHAR; (MAX_PATH) as _];
    let mut ofn: OPENFILENAME = core::mem::zeroed();
    let mut nSel: INT;
    let emptyStr: [u16; 1] = [0u16];
    let lbErrStr: [u16; 7] = [
        'L' as u16, 'B' as u16, '_' as u16, 'E' as u16, 'R' as u16, 'R' as u16, 0,
    ];
    let initDirStr: [u16; 17] = [
        '%' as u16, 'W' as u16, 'I' as u16, 'N' as u16, 'D' as u16, 'I' as u16, 'R' as u16,
        '%' as u16, '\\' as u16, 'C' as u16, 'u' as u16, 'r' as u16, 's' as u16, 'o' as u16,
        'r' as u16, 's' as u16, 0,
    ];

    LoadString(hApplet, (IDS_BROWSE_FILTER as u32), szFilter.as_mut_ptr(), (MAX_PATH) as i32);
    LoadString(hApplet, (IDS_BROWSE_TITLE as u32), szTitle.as_mut_ptr(), (MAX_PATH) as i32);

    memset(
        szFileName.as_mut_ptr() as *mut core::ffi::c_void,
        0x0 as core::ffi::c_int,
        (core::mem::size_of::<TCHAR>() * (MAX_PATH) as usize) as usize,
    );
    nSel = SendDlgItemMessage(
        hwndDlg,
        (IDC_LISTBOX_CURSOR as i32),
        LB_GETCURSEL,
        0,
        0,
    ) as INT;
    if nSel == LB_ERR {
        MessageBox(
            hwndDlg,
            lbErrStr.as_ptr(),
            emptyStr.as_ptr(),
            MB_ICONERROR,
        );
        return (FALSE) as BOOL;
    }

    ZeroMemory!(
        &raw mut ofn as *mut core::ffi::c_void,
        core::mem::size_of::<OPENFILENAME>() as usize,
    );
    ofn.lStructSize = core::mem::size_of::<OPENFILENAME>() as DWORD;
    ofn.hwndOwner = hwndDlg;
    ofn.lpstrFilter = szFilter.as_mut_ptr() as LPCWSTR;
    ofn.nFilterIndex = 1 as DWORD;
    ofn.lpstrFile = szFileName.as_mut_ptr() as LPWSTR;
    ofn.nMaxFile = MAX_PATH as DWORD;
    ofn.lpstrInitialDir = initDirStr.as_ptr() as LPCWSTR;
    ofn.lpstrTitle = szTitle.as_mut_ptr() as LPCWSTR;
    ofn.Flags = (OFN_EXPLORER | OFN_FILEMUSTEXIST | OFN_HIDEREADONLY) as DWORD;

    if GetOpenFileName(&raw mut ofn) == 0 {
        return (FALSE) as BOOL;
    }

    /* Store the new cursor file path */
    _tcsncpy(
        &raw mut (*(&raw mut g_CursorData as *mut CURSOR_DATA).offset(nSel as isize)).szCursorPath
            as *mut TCHAR,
        szFileName.as_mut_ptr(),
        MAX_PATH as usize,
    );

    return (TRUE) as BOOL;
}

unsafe extern "C" fn LoadCursorScheme(lpName: LPTSTR, bSystem: BOOL) {
    let mut index: UINT;
    let mut i: UINT;
    index = IDS_ARROW as UINT;
    i = 0 as UINT;
    while index <= IDS_HAND as UINT {
        if !g_CursorData[i as usize].hCursor.is_null() {
            DestroyCursor(g_CursorData[i as usize].hCursor);
            g_CursorData[i as usize].hCursor = core::ptr::null_mut();
        }
        g_CursorData[i as usize].szCursorPath[0 as usize] = 0;
        index = index.wrapping_add(1);
        i = i.wrapping_add(1);
    }

    if !lpName.is_null() {
        let mut pStart: LPTSTR = lpName;
        let mut pEnd: LPTSTR = pStart;
        let mut nLength: INT;

        i = 0 as UINT;
        while !pEnd.is_null() {
            pEnd = _tcschr(pStart, (',' as u16));
            if !pEnd.is_null() {
                nLength = (((pEnd as INT_PTR - pStart as INT_PTR) as usize)
                    .wrapping_div(core::mem::size_of::<TCHAR>())) as INT;
            } else {
                nLength = _tcslen(pStart) as INT;
            }

            _tcsncpy(
                &raw mut (*(&raw mut g_CursorData as *mut CURSOR_DATA).offset(i as isize)).szCursorPath as *mut TCHAR,
                pStart,
                nLength as usize,
            );
            g_CursorData[i as usize].szCursorPath[nLength as usize] = 0;

            pStart = pStart.offset((nLength + 1) as isize);
            i = i.wrapping_add(1);
        }
    }

    index = IDS_ARROW as UINT;
    i = 0 as UINT;
    while index <= IDS_HAND as UINT {
        if g_CursorData[i as usize].szCursorPath[0 as usize] == 0 {
            g_CursorData[i as usize].hCursor = LoadImage(
                core::ptr::null_mut(),
                MAKEINTRESOURCE!(g_CursorData[i as usize].uDefaultCursorId),
                IMAGE_CURSOR,
                0,
                0,
                LR_DEFAULTSIZE | LR_SHARED,
            ) as HCURSOR;
        } else {
            g_CursorData[i as usize].hCursor = LoadImage(
                core::ptr::null_mut(),
                &raw mut (*(&raw mut g_CursorData as *mut CURSOR_DATA).offset(i as isize)).szCursorPath as *mut TCHAR,
                IMAGE_CURSOR,
                0,
                0,
                LR_LOADFROMFILE | LR_DEFAULTSIZE,
            ) as HCURSOR;
        }
        index = index.wrapping_add(1);
        i = i.wrapping_add(1);
    }
}

