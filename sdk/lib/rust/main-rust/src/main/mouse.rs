unsafe extern "system" fn MouseHardwareProc(
    hwndDlg: HWND,
    uMsg: UINT,
    wParam: WPARAM,
    lParam: LPARAM,
) -> INT_PTR {
    let mut Guids: [GUID; 1] = [core::mem::zeroed(); 1];
    Guids[0] = GUID_DEVCLASS_MOUSE;

    UNREFERENCED_PARAMETER!(lParam);
    UNREFERENCED_PARAMETER!(wParam);

    if uMsg == WM_INITDIALOG {
        /* create the hardware page */
        DeviceCreateHardwarePageEx(
            hwndDlg,
            core::ptr::addr_of_mut!(Guids) as LPGUID,
            (core::mem::size_of::<[GUID; 1]>()
                / core::mem::size_of_val(&Guids[0])) as UINT,
            HWPD_STANDARDLIST,
        );
    }

    return FALSE as INT_PTR;
}

unsafe extern "system" fn ClickLockProc(
    hwndDlg: HWND,
    uMsg: UINT,
    wParam: WPARAM,
    lParam: LPARAM,
) -> INT_PTR {
    let mut hDlgCtrl: HWND;
    let mut pos: i32;
    static mut hIcon: HICON = core::ptr::null_mut();

    let mut pButtonData: PBUTTON_DATA;

    pButtonData = GetWindowLongPtr(hwndDlg, DWLP_USER) as PBUTTON_DATA;

    match uMsg {
        WM_INITDIALOG => {
            pButtonData = lParam as PBUTTON_DATA;
            SetWindowLongPtr(hwndDlg, DWLP_USER, pButtonData as LONG_PTR);

            hDlgCtrl = GetDlgItem(hwndDlg, (IDC_SLIDER_CLICK_LOCK as i32));
            SendMessage(
                hDlgCtrl,
                TBM_SETRANGE,
                TRUE as WPARAM,
                MAKELONG!(0, 10) as LPARAM,
            );
            pos = (((*pButtonData).g_ClickLockTime.wrapping_sub(200 as DWORD))
                / (200 as DWORD)) as i32;
            SendMessage(
                hDlgCtrl,
                TBM_SETPOS,
                TRUE as WPARAM,
                pos as LPARAM,
            );

            hIcon = LoadImage(
                hApplet,
                MAKEINTRESOURCE!(IDI_LOCK_KEY) as LPCWSTR,
                IMAGE_ICON,
                16,
                16,
                0,
            ) as HICON;
            SendMessage(
                hwndDlg,
                WM_SETICON,
                ICON_SMALL as WPARAM,
                hIcon as LPARAM,
            );
            return TRUE as INT_PTR;
        }
        WM_COMMAND => {
            if LOWORD!(wParam) as i32 == IDOK as i32 {
                hDlgCtrl = GetDlgItem(hwndDlg, (IDC_SLIDER_CLICK_LOCK as i32));
                (*pButtonData).g_ClickLockTime = ((SendMessage(
                    hDlgCtrl,
                    TBM_GETPOS,
                    0,
                    0,
                ) * 200 as LRESULT) as DWORD)
                    .wrapping_add(200 as DWORD);
                EndDialog(hwndDlg, (TRUE) as INT_PTR);
                if !hIcon.is_null() {
                    DestroyIcon(hIcon);
                }
            } else if LOWORD!(wParam) as i32 == IDCANCEL as i32 {
                EndDialog(hwndDlg, (FALSE) as INT_PTR);
                if !hIcon.is_null() {
                    DestroyIcon(hIcon);
                }
            }
        }
        _ => {}
    }

    return FALSE as INT_PTR;
}

unsafe extern "system" fn ButtonProc(
    hwndDlg: HWND,
    uMsg: UINT,
    wParam: WPARAM,
    lParam: LPARAM,
) -> INT_PTR {
    let mut hDlgCtrl: HWND = core::ptr::null_mut();
    let mut lResult: LRESULT = 0;
    let mut lppsn: LPPSHNOTIFY = core::ptr::null_mut();

    let mut pButtonData: PBUTTON_DATA = core::ptr::null_mut();

    pButtonData = GetWindowLongPtr(hwndDlg, DWLP_USER) as PBUTTON_DATA;

    match uMsg {
        WM_INITDIALOG => {
            pButtonData = HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY, core::mem::size_of::<BUTTON_DATA>() as SIZE_T) as PBUTTON_DATA;
            SetWindowLongPtr(hwndDlg, DWLP_USER, pButtonData as LONG_PTR);

            (*pButtonData).g_SwapMouseButtons = GetSystemMetrics((SM_SWAPBUTTON) as i32) as ULONG;
            (*pButtonData).g_OrigSwapMouseButtons = (*pButtonData).g_SwapMouseButtons;
            (*pButtonData).g_DoubleClickSpeed = GetDoubleClickTime() as ULONG;
            (*pButtonData).g_OrigDoubleClickSpeed = (*pButtonData).g_DoubleClickSpeed;

            /* Click lock time */
            SystemParametersInfo(SPI_GETMOUSECLICKLOCK, 0, core::ptr::addr_of_mut!((*pButtonData).g_ClickLockEnabled) as PVOID, 0);
            SystemParametersInfo(SPI_GETMOUSECLICKLOCKTIME, 0, core::ptr::addr_of_mut!((*pButtonData).g_ClickLockTime) as PVOID, 0);

            /* Load mouse button icons */
            (*pButtonData).hButtonLeft = LoadImage(hApplet, MAKEINTRESOURCE!(IDI_MOUSE_LEFT), IMAGE_ICON, 48, 48, LR_DEFAULTCOLOR) as HICON;
            (*pButtonData).hButtonRight = LoadImage(hApplet, MAKEINTRESOURCE!(IDI_MOUSE_RIGHT), IMAGE_ICON, 48, 48, LR_DEFAULTCOLOR) as HICON;

            /* Load folder icons */
            (*pButtonData).hIcon1 = LoadImage(hApplet, MAKEINTRESOURCE!(IDI_FOLDER_CLOSED), IMAGE_ICON, 48, 48, LR_DEFAULTCOLOR) as HICON;
            (*pButtonData).hIcon2 = LoadImage(hApplet, MAKEINTRESOURCE!(IDI_FOLDER_OPEN), IMAGE_ICON, 48, 48, LR_DEFAULTCOLOR) as HICON;

            if (*pButtonData).g_SwapMouseButtons != 0 {
                SendDlgItemMessage(hwndDlg, (IDC_SWAP_MOUSE_BUTTONS as i32), BM_SETCHECK as UINT, BST_CHECKED as WPARAM, 0 as LPARAM);
                SendDlgItemMessage(hwndDlg, (IDC_IMAGE_SWAP_MOUSE as i32), STM_SETIMAGE, (IMAGE_ICON) as _, (*pButtonData).hButtonRight as LPARAM);
            } else {
                SendDlgItemMessage(hwndDlg, (IDC_IMAGE_SWAP_MOUSE as i32), STM_SETIMAGE, (IMAGE_ICON) as _, (*pButtonData).hButtonLeft as LPARAM);
            }

            if (*pButtonData).g_ClickLockEnabled != 0 {
                hDlgCtrl = GetDlgItem(hwndDlg, (IDC_CHECK_CLICK_LOCK as i32));
                SendMessage(hDlgCtrl, BM_SETCHECK as UINT, BST_CHECKED as WPARAM, 0 as LPARAM);
            } else {
                hDlgCtrl = GetDlgItem(hwndDlg, (IDC_BUTTON_CLICK_LOCK as i32));
                EnableWindow(hDlgCtrl, (FALSE) as BOOL);
            }

            hDlgCtrl = GetDlgItem(hwndDlg, (IDC_SLIDER_DOUBLE_CLICK_SPEED as i32));
            SendMessage(hDlgCtrl, TBM_SETRANGE as UINT, TRUE as WPARAM, MAKELONG!(0, 14) as LPARAM);
            SendMessage(hDlgCtrl, TBM_SETPOS as UINT, TRUE as WPARAM, (14 as ULONG).wrapping_sub(((*pButtonData).g_DoubleClickSpeed.wrapping_sub(200 as ULONG)).wrapping_div(50 as ULONG)) as LPARAM);

            SendDlgItemMessage(hwndDlg, (IDC_IMAGE_DOUBLE_CLICK_SPEED as i32), STM_SETIMAGE, (IMAGE_ICON) as _, (*pButtonData).hIcon1 as LPARAM);
            (*pButtonData).bClicked = TRUE as BOOL;
            return TRUE as INT_PTR;
        }

        WM_DESTROY => {
            DestroyIcon((*pButtonData).hButtonLeft);
            DestroyIcon((*pButtonData).hButtonRight);
            DestroyIcon((*pButtonData).hIcon1);
            DestroyIcon((*pButtonData).hIcon2);
            HeapFree(GetProcessHeap(), 0 as DWORD, pButtonData as PVOID);
        }

        WM_COMMAND => {
            match ((LOWORD!(wParam)) as i32) as u32 {
                IDC_SWAP_MOUSE_BUTTONS => {
                    lResult = SendMessage(lParam as HWND, BM_GETCHECK as UINT, 0 as WPARAM, 0 as LPARAM);
                    if lResult == BST_CHECKED as LRESULT {
                        (*pButtonData).g_SwapMouseButtons = FALSE as ULONG;
                        SendMessage(lParam as HWND, BM_SETCHECK as UINT, BST_UNCHECKED as WPARAM, 0 as LPARAM);
                        SendDlgItemMessage(hwndDlg, (IDC_IMAGE_SWAP_MOUSE as i32), STM_SETIMAGE, (IMAGE_ICON) as _, (*pButtonData).hButtonLeft as LPARAM);
                    } else if lResult == BST_UNCHECKED as LRESULT {
                        (*pButtonData).g_SwapMouseButtons = TRUE as ULONG;
                        SendMessage(lParam as HWND, BM_SETCHECK as UINT, BST_CHECKED as WPARAM, 0 as LPARAM);
                        SendDlgItemMessage(hwndDlg, (IDC_IMAGE_SWAP_MOUSE as i32), STM_SETIMAGE, (IMAGE_ICON) as _, (*pButtonData).hButtonRight as LPARAM);
                    }
                    //SystemParametersInfo(SPI_SETMOUSEBUTTONSWAP, pButtonData->g_SwapMouseButtons, NULL, 0);
                    PropSheet_Changed!(GetParent(hwndDlg), hwndDlg);
                }

                IDC_CHECK_CLICK_LOCK => {
                    lResult = SendMessage(lParam as HWND, BM_GETCHECK as UINT, 0 as WPARAM, 0 as LPARAM);
                    hDlgCtrl = GetDlgItem(hwndDlg, (IDC_BUTTON_CLICK_LOCK as i32));
                    if lResult == BST_CHECKED as LRESULT {
                        SendMessage(lParam as HWND, BM_SETCHECK as UINT, BST_UNCHECKED as WPARAM, 0 as LPARAM);
                        (*pButtonData).g_ClickLockEnabled = FALSE as BOOL;
                        EnableWindow(hDlgCtrl, (FALSE) as BOOL);
                    } else if lResult == BST_UNCHECKED as LRESULT {
                        SendMessage(lParam as HWND, BM_SETCHECK as UINT, BST_CHECKED as WPARAM, 0 as LPARAM);
                        (*pButtonData).g_ClickLockEnabled = TRUE as BOOL;
                        EnableWindow(hDlgCtrl, (TRUE) as BOOL);
                    }
                    PropSheet_Changed!(GetParent(hwndDlg), hwndDlg);
                }

                IDC_BUTTON_CLICK_LOCK => {
                    DialogBoxParam(hApplet, MAKEINTRESOURCE!(IDD_CLICK_LOCK), hwndDlg, Some(ClickLockProc), pButtonData as LPARAM);
                }

                IDC_IMAGE_DOUBLE_CLICK_SPEED => {
                    if HIWORD!(wParam) == STN_DBLCLK as WORD {
                        (*pButtonData).bClicked = ((*pButtonData).bClicked == 0) as BOOL;
                        SendDlgItemMessage(hwndDlg, (IDC_IMAGE_DOUBLE_CLICK_SPEED as i32), STM_SETIMAGE as UINT, IMAGE_ICON as WPARAM,
                            (if (*pButtonData).bClicked != 0 { (*pButtonData).hIcon1 } else { (*pButtonData).hIcon2 }) as LPARAM);
                    }
                }

                _ => {}
            }
        }

        WM_NOTIFY => {
            lppsn = lParam as LPPSHNOTIFY;
            if (*lppsn).hdr.code == PSN_APPLY as UINT {
                if (*pButtonData).g_OrigSwapMouseButtons != (*pButtonData).g_SwapMouseButtons {
                    (*pButtonData).g_OrigSwapMouseButtons = (*pButtonData).g_SwapMouseButtons;
                    SystemParametersInfo(SPI_SETMOUSEBUTTONSWAP as UINT, (*pButtonData).g_OrigSwapMouseButtons as UINT, core::ptr::null_mut(), (SPIF_SENDCHANGE | SPIF_UPDATEINIFILE) as UINT);
                }
                SystemParametersInfo(SPI_SETDOUBLECLICKTIME as UINT, (*pButtonData).g_DoubleClickSpeed as UINT, core::ptr::null_mut(), (SPIF_SENDCHANGE | SPIF_UPDATEINIFILE) as UINT);
                //SetDoubleClickTime(pButtonData->g_DoubleClickSpeed);

#[cfg(all)]
                {
                    SystemParametersInfo(SPI_SETMOUSECLICKLOCK as UINT, 0 as UINT, UlongToPtr!((*pButtonData).g_ClickLockEnabled) as PVOID, (SPIF_SENDCHANGE | SPIF_UPDATEINIFILE) as UINT);
                    if (*pButtonData).g_ClickLockEnabled != 0 {
                        SystemParametersInfo(SPI_SETMOUSECLICKLOCKTIME as UINT, (*pButtonData).g_ClickLockTime as UINT, core::ptr::null_mut(), (SPIF_SENDCHANGE | SPIF_UPDATEINIFILE) as UINT);
                    }
                }
            } else if (*lppsn).hdr.code == PSN_RESET as UINT {
                /* Reset swap mouse button setting */
                SystemParametersInfo(SPI_SETMOUSEBUTTONSWAP as UINT, (*pButtonData).g_OrigSwapMouseButtons as UINT, core::ptr::null_mut(), 0 as UINT);

                /* Reset double-click speed setting */
                SystemParametersInfo(SPI_SETDOUBLECLICKTIME as UINT, (*pButtonData).g_OrigDoubleClickSpeed as UINT, core::ptr::null_mut(), 0 as UINT);
                //SetDoubleClickTime(pButtonData->g_OrigDoubleClickSpeed);
            }
            return TRUE as INT_PTR;
        }

        WM_HSCROLL => {
            if (lParam as HWND) == GetDlgItem(hwndDlg, (IDC_SLIDER_DOUBLE_CLICK_SPEED as i32)) {
                match (LOWORD!(wParam)) as u32 {
                    TB_LINEUP |
                    TB_LINEDOWN |
                    TB_PAGEUP |
                    TB_PAGEDOWN |
                    TB_TOP |
                    TB_BOTTOM |
                    TB_ENDTRACK => {
                        lResult = SendDlgItemMessage(hwndDlg, (IDC_SLIDER_DOUBLE_CLICK_SPEED as i32), (TBM_GETPOS as WPARAM) as u32, 0 as WPARAM, 0 as LPARAM);
                        (*pButtonData).g_DoubleClickSpeed = ((14 - (lResult as INT)) * 50 + 200) as ULONG;
                        //SystemParametersInfo(SPI_SETDOUBLECLICKTIME, pButtonData->g_DoubleClickSpeed, NULL, SPIF_SENDCHANGE | SPIF_UPDATEINIFILE);
                        SetDoubleClickTime((*pButtonData).g_DoubleClickSpeed as UINT);
                        PropSheet_Changed!(GetParent(hwndDlg), hwndDlg);
                    }

                    TB_THUMBTRACK => {
                        (*pButtonData).g_DoubleClickSpeed = ((14 - (HIWORD!(wParam) as INT)) * 50 + 200) as ULONG;
                        //SystemParametersInfo(SPI_SETDOUBLECLICKTIME, pButtonData->g_DoubleClickSpeed, NULL, 0);
                        SetDoubleClickTime((*pButtonData).g_DoubleClickSpeed as UINT);
                        PropSheet_Changed!(GetParent(hwndDlg), hwndDlg);
                    }

                    _ => {}
                }
            }
        }

        _ => {}
    }

    return FALSE as INT_PTR;
}

unsafe extern "C" fn CompressPath(lpShortPath: LPTSTR, lpPath: LPTSTR) {
    let mut szUserProfile: [TCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut szSystemRoot: [TCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut szProgramFiles: [TCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut dwUserProfile: DWORD;
    let mut dwSystemRoot: DWORD;
    let mut dwProgramFiles: DWORD;

    dwUserProfile = GetEnvironmentVariable((&[0x0055, 0x0053, 0x0045, 0x0052, 0x0050, 0x0052, 0x004f, 0x0046, 0x0049, 0x004c, 0x0045, 0x0000u16]).as_ptr() /* _T "USERPROFILE" */, szUserProfile.as_mut_ptr(), MAX_PATH);
    dwSystemRoot = GetEnvironmentVariable((&[0x0053, 0x0079, 0x0073, 0x0074, 0x0065, 0x006d, 0x0052, 0x006f, 0x006f, 0x0074, 0x0000u16]).as_ptr() /* _T "SystemRoot" */, szSystemRoot.as_mut_ptr(), MAX_PATH);
    dwProgramFiles = GetEnvironmentVariable((&[0x0050, 0x0072, 0x006f, 0x0067, 0x0072, 0x0061, 0x006d, 0x0046, 0x0069, 0x006c, 0x0065, 0x0073, 0x0000u16]).as_ptr() /* _T "ProgramFiles" */, szProgramFiles.as_mut_ptr(), MAX_PATH);

    if dwUserProfile > 0
        && _tcsncmp(lpPath, szUserProfile.as_mut_ptr(), (dwUserProfile) as _) == 0
    {
        _tcscpy(lpShortPath, (&[0x0025, 0x0055, 0x0053, 0x0045, 0x0052, 0x0050, 0x0052, 0x004f, 0x0046, 0x0049, 0x004c, 0x0045, 0x0025, 0x0000u16]).as_ptr() /* _T "%USERPROFILE%" */);
        _tcscat(lpShortPath, lpPath.add(dwUserProfile as usize));
    } else if dwSystemRoot > 0
        && _tcsncmp(lpPath, szSystemRoot.as_mut_ptr(), (dwSystemRoot) as _) == 0
    {
        _tcscpy(lpShortPath, (&[0x0025, 0x0053, 0x0079, 0x0073, 0x0074, 0x0065, 0x006d, 0x0052, 0x006f, 0x006f, 0x0074, 0x0025, 0x0000u16]).as_ptr() /* _T "%SystemRoot%" */);
        _tcscat(lpShortPath, lpPath.add(dwSystemRoot as usize));
    } else if dwProgramFiles > 0
        && _tcsncmp(lpPath, szProgramFiles.as_mut_ptr(), (dwProgramFiles) as _) == 0
    {
        _tcscpy(lpShortPath, (&[0x0025, 0x0050, 0x0072, 0x006f, 0x0067, 0x0072, 0x0061, 0x006d, 0x0046, 0x0069, 0x006c, 0x0065, 0x0073, 0x0025, 0x0000u16]).as_ptr() /* _T "%ProgramFiles%" */);
        _tcscat(lpShortPath, lpPath.add(dwProgramFiles as usize));
    } else {
        _tcscpy(lpShortPath, lpPath);
    }
}

unsafe extern "C" fn EnumerateCursorSchemes(hwndDlg: HWND) -> BOOL {
    let mut hCursorKey: HKEY = core::ptr::null_mut();
    let mut dwIndex: DWORD = 0;
    let mut szValueName: [TCHAR; (MAX_PATH) as _] = [0 as TCHAR; (MAX_PATH) as _];
    let mut dwValueName: DWORD = 0;
    let mut szSystemScheme: [TCHAR; (MAX_PATH) as _] = [0 as TCHAR; (MAX_PATH) as _];
    let mut szValueData: [TCHAR; 2000] = [0 as TCHAR; 2000];
    let mut szTempData: [TCHAR; 2000] = [0 as TCHAR; 2000];
    let mut dwValueData: DWORD = 0;
    let mut lError: LONG = 0;
    let mut hDlgCtrl: HWND = core::ptr::null_mut();
    let mut lResult: LRESULT = 0;

    hDlgCtrl = GetDlgItem(hwndDlg, (IDC_COMBO_CURSOR_SCHEME as i32));
    SendMessage(hDlgCtrl, CB_RESETCONTENT, 0 as WPARAM, 0 as LPARAM);

    /* Read the users cursor schemes */
    lError = RegOpenKeyEx(
        HKEY_CURRENT_USER as HKEY,
        (&[0x0043, 0x006f, 0x006e, 0x0074, 0x0072, 0x006f, 0x006c, 0x0020, 0x0050, 0x0061, 0x006e, 0x0065, 0x006c, 0x005c, 0x0043, 0x0075, 0x0072, 0x0073, 0x006f, 0x0072, 0x0073, 0x005c, 0x0053, 0x0063, 0x0068, 0x0065, 0x006d, 0x0065, 0x0073, 0x0000u16]).as_ptr() /* _T "Control Panel\\Cursors\\Schemes" */,
        0 as DWORD,
        (KEY_READ | KEY_QUERY_VALUE) as REGSAM,
        core::ptr::addr_of_mut!(hCursorKey),
    ) as LONG;
    if lError == ERROR_SUCCESS as LONG {
        dwIndex = 0 as DWORD;
        loop {
            dwValueName = (core::mem::size_of::<[TCHAR; (MAX_PATH) as _]>() / core::mem::size_of::<TCHAR>() as usize) as DWORD;
            dwValueData = (core::mem::size_of::<[TCHAR; 2000]>() / core::mem::size_of::<TCHAR>() as usize) as DWORD;
            lError = RegEnumValue(
                hCursorKey,
                dwIndex,
                szValueName.as_mut_ptr(),
                core::ptr::addr_of_mut!(dwValueName),
                core::ptr::null_mut(),
                core::ptr::null_mut(),
                szValueData.as_mut_ptr() as LPBYTE,
                core::ptr::addr_of_mut!(dwValueData),
            ) as LONG;
            if lError == ERROR_NO_MORE_ITEMS as LONG {
                break;
            }

            ExpandEnvironmentStrings(szValueData.as_ptr(), szTempData.as_mut_ptr(), 2000 as DWORD);

            if _tcslen(szTempData.as_ptr()) > 0 as usize {
                let mut lpCopy: LPTSTR;
                let mut lpStart: LPTSTR;

                /* Remove quotation marks */
                if szTempData[0 as usize] == ('"' as u16) {
                    lpStart = szTempData.as_mut_ptr().add(1 as usize);
                    szTempData[_tcslen(szTempData.as_ptr()) - 1 as usize] = 0 as TCHAR;
                } else {
                    lpStart = szTempData.as_mut_ptr();
                }

                lpCopy = _tcsdup(lpStart);

                lResult = SendMessage(hDlgCtrl, CB_ADDSTRING as UINT, 0 as WPARAM, szValueName.as_mut_ptr() as LPARAM);
                SendMessage(hDlgCtrl, CB_SETITEMDATA as UINT, lResult as WPARAM, lpCopy as LPARAM);
            }
            dwIndex = dwIndex.wrapping_add(1);
        }

        RegCloseKey(hCursorKey);
    }

    /* Read the system cursor schemes */
    lError = RegOpenKeyEx(
        HKEY_LOCAL_MACHINE as HKEY,
        (&[0x0053, 0x004f, 0x0046, 0x0054, 0x0057, 0x0041, 0x0052, 0x0045, 0x005c, 0x004d, 0x0069, 0x0063, 0x0072, 0x006f, 0x0073, 0x006f, 0x0066, 0x0074, 0x005c, 0x0057, 0x0069, 0x006e, 0x0064, 0x006f, 0x0077, 0x0073, 0x005c, 0x0043, 0x0075, 0x0072, 0x0072, 0x0065, 0x006e, 0x0074, 0x0056, 0x0065, 0x0072, 0x0073, 0x0069, 0x006f, 0x006e, 0x005c, 0x0043, 0x006f, 0x006e, 0x0074, 0x0072, 0x006f, 0x006c, 0x0020, 0x0050, 0x0061, 0x006e, 0x0065, 0x006c, 0x005c, 0x0043, 0x0075, 0x0072, 0x0073, 0x006f, 0x0072, 0x0073, 0x005c, 0x0053, 0x0063, 0x0068, 0x0065, 0x006d, 0x0065, 0x0073, 0x0000u16]).as_ptr() /* _T("SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Control Panel\") */,
        0 as DWORD,
        (KEY_READ | KEY_QUERY_VALUE) as REGSAM,
        core::ptr::addr_of_mut!(hCursorKey),
    ) as LONG;
    if lError == ERROR_SUCCESS as LONG {
        LoadString(hApplet, IDS_SYSTEM_SCHEME as UINT, szSystemScheme.as_mut_ptr(), MAX_PATH as i32);

        dwIndex = 0 as DWORD;
        loop {
            dwValueName = (core::mem::size_of::<[TCHAR; (MAX_PATH) as _]>() / core::mem::size_of::<TCHAR>() as usize) as DWORD;
            dwValueData = (core::mem::size_of::<[TCHAR; 2000]>() / core::mem::size_of::<TCHAR>() as usize) as DWORD;
            lError = RegEnumValue(
                hCursorKey,
                dwIndex,
                szValueName.as_mut_ptr(),
                core::ptr::addr_of_mut!(dwValueName),
                core::ptr::null_mut(),
                core::ptr::null_mut(),
                szValueData.as_mut_ptr() as LPBYTE,
                core::ptr::addr_of_mut!(dwValueData),
            ) as LONG;
            if lError == ERROR_NO_MORE_ITEMS as LONG {
                break;
            }

            if _tcslen(szValueData.as_ptr()) > 0 as usize {
                let mut lpCopy: LPTSTR;
                let mut lpStart: LPTSTR;

                /* Remove quotation marks */
                if szValueData[0 as usize] == ('"' as u16) {
                    lpStart = szValueData.as_mut_ptr().add(1 as usize);
                    szValueData[_tcslen(szValueData.as_ptr()) - 1 as usize] = 0 as TCHAR;
                } else {
                    lpStart = szValueData.as_mut_ptr();
                }

                lpCopy = _tcsdup(lpStart);

                _tcscat(szValueName.as_mut_ptr(), (&[0x0020, 0x0000u16]).as_ptr() /* TEXT " " */);
                _tcscat(szValueName.as_mut_ptr(), szSystemScheme.as_ptr());

                lResult = SendMessage(hDlgCtrl, CB_ADDSTRING as UINT, 0 as WPARAM, szValueName.as_mut_ptr() as LPARAM);
                SendMessage(hDlgCtrl, CB_SETITEMDATA as UINT, lResult as WPARAM, lpCopy as LPARAM);
            }
            dwIndex = dwIndex.wrapping_add(1);
        }

        RegCloseKey(hCursorKey);
    }

    /* Add the "(none)" entry */
    LoadString(hApplet, IDS_NONE as UINT, szSystemScheme.as_mut_ptr(), MAX_PATH as i32);
    lResult = SendMessage(hDlgCtrl, CB_ADDSTRING as UINT, 0 as WPARAM, szSystemScheme.as_mut_ptr() as LPARAM);
    SendMessage(hDlgCtrl, CB_SETITEMDATA as UINT, lResult as WPARAM, core::ptr::null_mut::<core::ffi::c_void>() as LPARAM);

    return TRUE as BOOL;
}

