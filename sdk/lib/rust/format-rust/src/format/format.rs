unsafe extern "C" fn ParseCommandLine(mut argc: ::core::ffi::c_int, mut argv: *mut *mut WCHAR) -> ::core::ffi::c_int {
    let mut i: ::core::ffi::c_int;
    let mut j: ::core::ffi::c_int;
    let mut gotFormat: BOOLEAN = (FALSE as u8);
    let mut gotQuick: BOOLEAN = (FALSE as u8);
    let mut gotSize: BOOLEAN = (FALSE as u8);
    let mut gotLabel: BOOLEAN = (FALSE as u8);
    let mut gotCompressed: BOOLEAN = (FALSE as u8);

    i = 1;
    while i < argc {
        let arg: *mut WCHAR = *argv.offset(i as isize);
        let c: WCHAR = *arg.offset(0 as isize);
        match c {
            x if x == 0x002Du16 || x == 0x002Fu16 => {
                if _wcsnicmp(
                    arg.offset(1 as isize),
                    RUSTCONV_WSTR_86C8C3DF2BBA.as_ptr(),
                    3 as size_t,
                ) != 0
                {
                    if gotFormat != 0 {
                        return -(1);
                    }
                    FileSystem = arg.offset(4 as isize) as PWCHAR;
                    gotFormat = (TRUE as u8);
                } else if _wcsnicmp(
                    arg.offset(1 as isize),
                    RUSTCONV_WSTR_74A76815B25D.as_ptr(),
                    2 as size_t,
                ) != 0
                {
                    if gotSize != 0 {
                        return -(1);
                    }
                    j = 0;
                    let sizes: *mut SIZEDEFINITION = &raw mut LegalSizes as *mut SIZEDEFINITION;
                    while (*sizes.offset(j as isize)).ClusterSize != 0
                        && _wcsicmp(
                            &raw mut (*sizes.offset(j as isize)).SizeString as *mut WCHAR,
                            arg.offset(3 as isize),
                        ) != 0
                    {
                        j += 1;
                    }

                    if (*sizes.offset(j as isize)).ClusterSize == 0 {
                        return i;
                    }
                    ClusterSize = (*sizes.offset(j as isize)).ClusterSize;
                    gotSize = (TRUE as u8);
                } else if _wcsnicmp(
                    arg.offset(1 as isize),
                    RUSTCONV_WSTR_9B9CBE4966E1.as_ptr(),
                    2 as size_t,
                ) != 0
                {
                    if gotLabel != 0 {
                        return -(1);
                    }
                    Label = arg.offset(3 as isize) as PWCHAR;
                    gotLabel = (TRUE as u8);
                    GotALabel = (TRUE as i32);
                } else if _wcsicmp(
                    arg.offset(1 as isize),
                    RUSTCONV_WSTR_B2DAD12F48DA.as_ptr(),
                ) == 0
                {
                    if gotQuick != 0 {
                        return -(1);
                    }
                    QuickFormat = (TRUE as i32);
                    gotQuick = (TRUE as u8);
                } else if _wcsicmp(
                    arg.offset(1 as isize),
                    RUSTCONV_WSTR_D23F96D836EB.as_ptr(),
                ) == 0
                {
                    if gotCompressed != 0 {
                        return -(1);
                    }
                    CompressDrive = (TRUE as i32);
                    gotCompressed = (TRUE as u8);
                } else {
                    return i;
                }
            }
            _ => {
                if !Drive.is_null() {
                    return i;
                }
                if *arg.offset(1 as isize) != 0x003Au16 {
                    return i;
                }

                Drive = arg as PWCHAR;
            }
        }
        i += 1;
    }
    return 0;
}
#[no_mangle]
pub unsafe extern "system" fn FormatExCallback(
    mut Command: CALLBACKCOMMAND,
    mut Modifier: ULONG,
    mut Argument: PVOID,
) -> BOOLEAN {
    let mut percent: PDWORD = core::ptr::null_mut::<DWORD>();
    let mut output: PTEXTOUTPUT = core::ptr::null_mut::<TEXTOUTPUT>();
    let mut status: PBOOLEAN = core::ptr::null_mut::<u8>();
    match Command {
        PROGRESS => {
            percent = Argument as PDWORD;
            ConResPrintf(&raw mut csStdOut, STRING_COMPLETE, *percent);
        }
        OUTPUT => {
            output = Argument as PTEXTOUTPUT;
            ConPrintf(&raw mut csStdOut, RUSTCONV_WSTR_3B905C121518.as_ptr(), (*output).Output);
        }
        DONE => {
            status = Argument as PBOOLEAN;
            if *status == (FALSE as u8) {
                ConResPuts(&raw mut csStdOut, STRING_FORMAT_FAIL);
                Error = (TRUE as i32);
            }
        }
        DONEWITHSTRUCTURE
        | UNKNOWN2
        | UNKNOWN3
        | UNKNOWN4
        | UNKNOWN5
        | INSUFFICIENTRIGHTS
        | FSNOTSUPPORTED
        | VOLUMEINUSE
        | UNKNOWN9
        | UNKNOWNA
        | UNKNOWNC
        | UNKNOWND
        | STRUCTUREPROGRESS
        | CLUSTERSIZETOOSMALL => {
            ConResPuts(&raw mut csStdOut, STRING_NO_SUPPORT);
            return (FALSE) as BOOLEAN;
        }
        _ => {}
    }
    return (TRUE) as BOOLEAN;
}

unsafe extern "C" fn Usage(ProgramName: LPWSTR) {
    let mut szFormats: [WCHAR; MAX_PATH as usize] = [0; MAX_PATH as usize];
    let mut szFormatW: [WCHAR; MAX_PATH as usize] = [0; MAX_PATH as usize];
    let mut Index: DWORD = 0 as DWORD;
    let mut dummy: BYTE = 0;
    let mut latestVersion: BOOLEAN = 0;

    szFormats[0 as usize] = UNICODE_NULL;
    loop {
        let idx: DWORD = Index;
        Index = Index.wrapping_add(1);
        if QueryAvailableFileSystemFormat(
            idx,
            addr_of_mut!(szFormatW) as PWCHAR,
            addr_of_mut!(dummy),
            addr_of_mut!(dummy),
            addr_of_mut!(latestVersion),
        ) == 0
        {
            break;
        }
        if latestVersion == 0 {
            continue;
        }
        if szFormats[0 as usize] != 0 {
            wcscat(addr_of_mut!(szFormats) as *mut WCHAR, RUSTCONV_WSTR_82294FD79A0D.as_ptr());
        }

        wcscat(addr_of_mut!(szFormats) as *mut WCHAR, addr_of_mut!(szFormatW) as *mut WCHAR);
    }
    ConResPrintf(StdOut, STRING_HELP, ProgramName, addr_of_mut!(szFormats) as *mut WCHAR);
}

#[no_mangle]
pub unsafe extern "C" fn wmain(mut argc: ::core::ffi::c_int, mut argv: *mut *mut WCHAR) -> ::core::ffi::c_int {
    let mut badArg: ::core::ffi::c_int = 0;
    let mut DeviceInformation: DEVICE_INFORMATION = core::mem::zeroed();
    let mut media: FMIFS_MEDIA_FLAG = FMIFS_HARDDISK;
    let mut driveType: DWORD = 0;
    let mut fileSystem: [WCHAR; 1024] = [0; 1024];
    let mut volumeName: [WCHAR; 1024] = [0; 1024];
    let mut input: [WCHAR; 1024] = [0; 1024];
    let mut serialNumber: DWORD = 0;
    let mut totalNumberOfBytes: ULARGE_INTEGER = core::mem::zeroed();
    let mut totalNumberOfFreeBytes: ULARGE_INTEGER = core::mem::zeroed();
    let mut dwError: DWORD = 0;
    let mut pszMsg: PCWSTR = core::ptr::null();
    let mut Len: INT = 0;

    /* Initialize the Console Standard Streams */
    ConInitStdStreams();

    ConPuts(StdOut,
        RUSTCONV_WSTR_E407CB5C2B97.as_ptr());

    //
    // Parse command line
    //
    badArg = ParseCommandLine(argc, argv);
    if badArg != 0 {
        ConResPrintf(StdErr, STRING_UNKNOW_ARG, *argv.offset(badArg as isize));
        Usage(*argv.offset(0 as isize));
        return -1;
    }

    //
    // Get the drive's format
    //
    if Drive.is_null() {
        ConResPuts(StdErr, STRING_DRIVE_PARM);
        Usage(*argv.offset(0 as isize));
        return -1;
    } else {
        wcscpy(core::ptr::addr_of_mut!(RootDirectory) as *mut WCHAR, Drive);
    }
    RootDirectory[2] = 0x005Cu16;
    RootDirectory[3] = 0x0000u16;

    //
    // See if the drive is removable or not
    //
    driveType = GetDriveTypeW(core::ptr::addr_of_mut!(RootDirectory) as *mut WCHAR);
    match driveType {
        DRIVE_UNKNOWN | DRIVE_NO_ROOT_DIR => {
            // This case used to report STRING_NO_VOLUME, which has no ".\n".
            ConResPuts(StdErr, STRING_ERROR_DRIVE_TYPE);
            return -1;
        }
        DRIVE_REMOTE | DRIVE_CDROM => {
            ConResPuts(StdOut, STRING_NO_SUPPORT);
            return -1;
        }
        DRIVE_REMOVABLE => {
            ConResPrintf(StdOut, STRING_INSERT_DISK, RootDirectory[0] as ::core::ffi::c_int);
            fgetws(core::ptr::addr_of_mut!(input) as *mut WCHAR, (ARRAYSIZE!(input)) as i32, __iob_func().add(0));
            media = FMIFS_FLOPPY;
        }
        DRIVE_FIXED | DRIVE_RAMDISK => {
            media = FMIFS_HARDDISK;
        }
        _ => {}
    }

    // Reject attempts to format the system drive
    {
        let mut path: [WCHAR; (MAX_PATH + 1) as _] = [0; (MAX_PATH + 1) as _];
        let mut rc: UINT = 0;
        rc = GetWindowsDirectoryW(core::ptr::addr_of_mut!(path) as *mut WCHAR, MAX_PATH);
        if rc == 0 || rc > MAX_PATH {
            // todo: Report "Unable to query system directory"
            return -1;
        }
        if towlower(path[0]) == towlower(*Drive.offset(0 as isize)) {
            // todo: report "Cannot format system drive"
            ConResPuts(StdOut, STRING_NO_SUPPORT);
            return -1;
        }
    }

    //
    // Get the existing name and file system, and print out the latter
    //
    if GetVolumeInformationW(core::ptr::addr_of_mut!(RootDirectory) as *mut WCHAR,
                               core::ptr::addr_of_mut!(volumeName) as *mut WCHAR, ARRAYSIZE!(volumeName),
                               core::ptr::null_mut(), core::ptr::null_mut(), core::ptr::null_mut(),
                               core::ptr::addr_of_mut!(fileSystem) as *mut WCHAR, ARRAYSIZE!(fileSystem)) == 0
    {
        dwError = GetLastError();
        if dwError == ERROR_UNRECOGNIZED_VOLUME {
            // Unformatted volume
            volumeName[0] = UNICODE_NULL;
            wcscpy(core::ptr::addr_of_mut!(fileSystem) as *mut WCHAR, RUSTCONV_WSTR_903B52F937BA.as_ptr());
        } else {
            PrintWin32Error(STRING_NO_VOLUME, dwError);
            return -1;
        }
    }

    ConResPrintf(StdOut, STRING_FILESYSTEM, core::ptr::addr_of_mut!(fileSystem) as *mut WCHAR);

    if QueryDeviceInformation(core::ptr::addr_of_mut!(RootDirectory) as *mut WCHAR,
                              core::ptr::addr_of_mut!(DeviceInformation) as PVOID,
                              core::mem::size_of::<DEVICE_INFORMATION>() as ULONG) == 0
    {
        totalNumberOfBytes.QuadPart = 0;
    } else {
        totalNumberOfBytes.QuadPart = (DeviceInformation.SectorSize as LONGLONG
            * DeviceInformation.SectorCount.QuadPart) as ULONGLONG;
    }

    /* QueryDeviceInformation returns more accurate volume length and works with
     * unformatted volumes, however it will NOT return volume length on XP/2003.
     * Fallback to GetFreeDiskSpaceExW if we did not get any volume length. */
    if totalNumberOfBytes.QuadPart == 0 &&
        GetDiskFreeSpaceExW(core::ptr::addr_of_mut!(RootDirectory) as *mut WCHAR,
                             core::ptr::null_mut(),
                             core::ptr::addr_of_mut!(totalNumberOfBytes) as *mut ULARGE_INTEGER,
                             core::ptr::null_mut()) == 0
    {
        dwError = GetLastError();
        PrintWin32Error(STRING_NO_VOLUME_SIZE, dwError);
        return -1;
    }

    //
    // Make sure they want to do this
    //
    if driveType == DRIVE_FIXED {
        if volumeName[0] != 0 {
            loop {
                ConResPrintf(StdOut, STRING_LABEL_NAME_EDIT, RootDirectory[0] as ::core::ffi::c_int);
                fgetws(core::ptr::addr_of_mut!(input) as *mut WCHAR, (ARRAYSIZE!(input)) as i32, __iob_func().add(0));
                input[(wcslen(core::ptr::addr_of_mut!(input) as *mut WCHAR) - 1) as usize] = UNICODE_NULL;

                if _wcsicmp(core::ptr::addr_of_mut!(input) as *mut WCHAR, core::ptr::addr_of_mut!(volumeName) as *mut WCHAR) == 0 {
                    break;
                }

                ConResPuts(StdOut, STRING_ERROR_LABEL);
            }
        }

        ConResPrintf(StdOut, STRING_YN_FORMAT, RootDirectory[0] as ::core::ffi::c_int);

        Len = LoadStringW(core::ptr::null_mut(), STRING_YES_NO_FAQ, core::ptr::addr_of_mut!(pszMsg) as PWSTR, 0);
        if Len < 2 {
            pszMsg = RUSTCONV_WSTR_E25EF5FFC43D.as_ptr();
        }
        loop {
            fgetws(core::ptr::addr_of_mut!(input) as *mut WCHAR, (ARRAYSIZE!(input)) as i32, __iob_func().add(0));
            if (towupper((input[0]) as _) as ::core::ffi::c_int)
                == (*pszMsg.offset(0 as isize) as ::core::ffi::c_int)
            {
                break;
            }
            if (towupper((input[0]) as _) as ::core::ffi::c_int)
                == (*pszMsg.offset(1 as isize) as ::core::ffi::c_int)
            {
                ConPuts(StdOut, RUSTCONV_WSTR_075DE2B906DB.as_ptr());
                return 0;
            }
        }
    }

    //
    // Tell the user we're doing a long format if appropriate
    //
    if QuickFormat == 0 {
        Len = LoadStringW(core::ptr::null_mut(), STRING_VERIFYING, core::ptr::addr_of_mut!(pszMsg) as PWSTR, 0);
        if totalNumberOfBytes.QuadPart > 1024 * 1024 * 10 {
            ConPrintf(StdOut, RUSTCONV_WSTR_F673F41CA18C.as_ptr(), Len, pszMsg,
                (totalNumberOfBytes.QuadPart / (1024 * 1024)) as DWORD);
        } else {
            ConPrintf(StdOut, RUSTCONV_WSTR_8D378B2339AF.as_ptr(), Len, pszMsg,
                ((totalNumberOfBytes.QuadPart as LONGLONG as f32) / (1024.0f64 * 1024.0f64) as f32) as f64);
        }
    } else {
        Len = LoadStringW(core::ptr::null_mut(), STRING_FAST_FMT, core::ptr::addr_of_mut!(pszMsg) as PWSTR, 0);
        if totalNumberOfBytes.QuadPart > 1024 * 1024 * 10 {
            ConPrintf(StdOut, RUSTCONV_WSTR_F673F41CA18C.as_ptr(), Len, pszMsg,
                (totalNumberOfBytes.QuadPart / (1024 * 1024)) as DWORD);
        } else {
            ConPrintf(StdOut, RUSTCONV_WSTR_0EC56D3B4346.as_ptr(), Len, pszMsg,
                ((totalNumberOfBytes.QuadPart as LONGLONG as f32) / (1024.0f64 * 1024.0f64) as f32) as f64);
        }
        ConResPuts(StdOut, STRING_CREATE_FSYS);
    }

    //
    // Format away!
    //
    FormatEx(core::ptr::addr_of_mut!(RootDirectory) as PWCHAR, media, FileSystem, Label, (QuickFormat) as u8,
             ClusterSize, Some(FormatExCallback));
    if Error != 0 {
        return -1;
    }
    ConPuts(StdOut, RUSTCONV_WSTR_075DE2B906DB.as_ptr());
    ConResPuts(StdOut, STRING_FMT_COMPLETE);

    //
    // Enable compression if desired
    //
    if CompressDrive != 0 {
        if EnableVolumeCompression(core::ptr::addr_of_mut!(RootDirectory) as PWCHAR, (TRUE as u16)) == 0 {
            ConResPuts(StdOut, STRING_VOL_COMPRESS);
        }
    }

    //
    // Get the label if we don't have it
    //
    if GotALabel == 0 {
        ConResPuts(StdOut, STRING_ENTER_LABEL);
        fgetws(core::ptr::addr_of_mut!(input) as *mut WCHAR, (ARRAYSIZE!(LabelString)) as i32, __iob_func().add(0));
        input[(wcslen(core::ptr::addr_of_mut!(input) as *mut WCHAR) - 1) as usize] = UNICODE_NULL;

        if SetVolumeLabelW(core::ptr::addr_of_mut!(RootDirectory) as *mut WCHAR, core::ptr::addr_of_mut!(input) as *mut WCHAR) == 0 {
            dwError = GetLastError();
            PrintWin32Error(STRING_NO_LABEL, dwError);
            return -1;
        }
    }

    //
    // Get and print out some stuff including the formatted size
    //
    if GetDiskFreeSpaceExW(core::ptr::addr_of_mut!(RootDirectory) as *mut WCHAR,
                             core::ptr::null_mut(),
                             core::ptr::addr_of_mut!(totalNumberOfBytes) as *mut ULARGE_INTEGER,
                             core::ptr::addr_of_mut!(totalNumberOfFreeBytes) as *mut ULARGE_INTEGER) == 0
    {
        dwError = GetLastError();
        PrintWin32Error(STRING_NO_VOLUME_SIZE, dwError);
        return -1;
    }

    ConResPrintf(StdOut, STRING_FREE_SPACE, totalNumberOfBytes.QuadPart,
                                            totalNumberOfFreeBytes.QuadPart);

    //
    // Get and print out the new serial number
    //
    if GetVolumeInformationW(core::ptr::addr_of_mut!(RootDirectory) as *mut WCHAR,
                               core::ptr::null_mut(), 0,
                               core::ptr::addr_of_mut!(serialNumber), core::ptr::null_mut(), core::ptr::null_mut(),
                               core::ptr::null_mut(), 0) == 0
    {
        dwError = GetLastError();
        PrintWin32Error(STRING_NO_VOLUME, dwError);
        return -1;
    }

    ConResPrintf(StdOut, STRING_SERIAL_NUMBER,
                         (serialNumber >> 16) as ::core::ffi::c_uint,
                         (serialNumber & 0xFFFF) as ::core::ffi::c_uint);

    return 0;
}
