unsafe extern "C" fn InputList_AppendNode() -> *mut INPUT_LIST_NODE {
    let mut pCurrent: *mut INPUT_LIST_NODE = ::core::ptr::null_mut::<INPUT_LIST_NODE>();
    let mut pNew: *mut INPUT_LIST_NODE = ::core::ptr::null_mut::<INPUT_LIST_NODE>();
    pNew = malloc(::core::mem::size_of::<INPUT_LIST_NODE>() as usize) as *mut INPUT_LIST_NODE;
    if pNew.is_null() {
        return ::core::ptr::null_mut::<INPUT_LIST_NODE>();
    }
    ZeroMemory!(
        pNew as *mut ::core::ffi::c_void,
        ::core::mem::size_of::<INPUT_LIST_NODE>() as usize,
    );
    if _InputList.is_null() {
        _InputList = pNew;
        return pNew;
    }
    pCurrent = _InputList;
    while !(*pCurrent).pNext.is_null() {
        pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
    }
    (*pCurrent).pNext = pNew as *mut _INPUT_LIST_NODE;
    (*pNew).pPrev = pCurrent as *mut _INPUT_LIST_NODE;
    return pNew;
}

unsafe extern "C" fn InputList_RemoveNode(mut pNode: *mut INPUT_LIST_NODE) {
    let mut pCurrent: *mut INPUT_LIST_NODE = pNode;
    if _InputList.is_null() {
        return;
    }
    if !pCurrent.is_null() {
        let mut pNext: *mut INPUT_LIST_NODE = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
        let mut pPrev: *mut INPUT_LIST_NODE = (*pCurrent).pPrev as *mut INPUT_LIST_NODE;
        free((*pCurrent).pszIndicator as *mut ::core::ffi::c_void);
        free(pCurrent as *mut ::core::ffi::c_void);
        if !pNext.is_null() {
            (*pNext).pPrev = pPrev as *mut _INPUT_LIST_NODE;
        }
        if !pPrev.is_null() {
            (*pPrev).pNext = pNext as *mut _INPUT_LIST_NODE;
        } else {
            _InputList = pNext;
        }
    }
}
#[no_mangle]
pub unsafe extern "C" fn InputList_Destroy() {
    let mut pCurrent: *mut INPUT_LIST_NODE;
    let mut pNext: *mut INPUT_LIST_NODE;

    if _InputList.is_null() {
        return;
    }

    pCurrent = _InputList;
    while !pCurrent.is_null() {
        pNext = (*pCurrent).pNext;

        free((*pCurrent).pszIndicator as *mut ::core::ffi::c_void);
        free(pCurrent as *mut ::core::ffi::c_void);

        pCurrent = pNext;
    }

    _InputList = core::ptr::null_mut();
}

