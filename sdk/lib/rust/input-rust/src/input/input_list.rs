unsafe extern "C" fn InputList_DoSubst(
    hPreloadKey: HKEY,
    hSubstKey: HKEY,
    dwPhysicalKLID: DWORD,
    dwLogicalKLID: DWORD,
) -> DWORD {
    let mut hPreloadKey = hPreloadKey;
    let mut hSubstKey = hSubstKey;
    let mut dwPhysicalKLID = dwPhysicalKLID;
    let mut dwLogicalKLID = dwLogicalKLID;
    let mut iTrial: DWORD;
    let mut bSubstNeeded: BOOL = ((dwPhysicalKLID != dwLogicalKLID)
        || ((HIWORD!(dwPhysicalKLID) as DWORD) != 0)) as BOOL;

    iTrial = 1;
    while iTrial <= 1000 {
        if InputList_FindPreloadKLID(hPreloadKey, dwLogicalKLID) == 0 {
            if bSubstNeeded != 0 {
                InputList_WriteSubst(hSubstKey, dwPhysicalKLID, dwLogicalKLID);
            }
            return dwLogicalKLID;
        }

        bSubstNeeded = (TRUE) as i32;

        if ((IS_SUBST_KLID!(dwLogicalKLID)) == 0) {
            dwLogicalKLID |= SUBST_MASK;
        } else {
            let wLow: WORD = LOWORD!(dwLogicalKLID);
            let wHigh: WORD = HIWORD!(dwLogicalKLID);
            dwLogicalKLID = MAKELONG!(
                wLow,
                (wHigh as ::core::ffi::c_int + 1) as WORD,
            ) as DWORD;
        }
        iTrial = iTrial.wrapping_add(1);
    }

    return 0;
}

unsafe extern "C" fn InputList_AddInputMethodToUserRegistry(
    mut hPreloadKey: HKEY,
    mut hSubstKey: HKEY,
    mut dwNumber: DWORD,
    mut pNode: *mut INPUT_LIST_NODE,
) {
    let mut szNumber: [WCHAR; 32] = [0; 32];
    let mut szLogicalKLID: [WCHAR; (KL_NAMELENGTH) as _] = [0; (KL_NAMELENGTH) as _];
    let mut dwPhysicalKLID: DWORD = 0;
    let mut dwLogicalKLID: DWORD = 0;
    let mut cbValue: DWORD = 0;
    let mut hKL: HKL = (*pNode).hkl;

    if IS_IME_HKL!(hKL) != 0 {
        /* Do not substitute the IME KLID */
        dwPhysicalKLID = HandleToUlong!(hKL as *const ::core::ffi::c_void) as DWORD;
        dwLogicalKLID = dwPhysicalKLID;
    } else {
        /* Substitute the KLID if necessary */
        dwPhysicalKLID = (*(*pNode).pLayout).dwKLID;
        dwLogicalKLID = (*(*pNode).pLocale).dwId;
        dwLogicalKLID = InputList_DoSubst(hPreloadKey, hSubstKey, dwPhysicalKLID, dwLogicalKLID);
    }

    /* Write the Preload value (number |--> logical KLID) */
    StringCchPrintfW!(
        addr_of_mut!(szNumber).cast::<u16>(),
        ARRAYSIZE!(szNumber),
        RUSTCONV_WSTR_F3C6A8F2AC47.as_ptr(),
        dwNumber,
    );
    StringCchPrintfW!(
        addr_of_mut!(szLogicalKLID).cast::<u16>(),
        ARRAYSIZE!(szLogicalKLID),
        RUSTCONV_WSTR_FE2DE33F78CD.as_ptr(),
        dwLogicalKLID,
    );
    cbValue = (wcslen(addr_of_mut!(szLogicalKLID).cast::<u16>() as *const u16) as DWORD
        + 1 as DWORD)
        * core::mem::size_of::<WCHAR>() as DWORD;
    RegSetValueExW(
        hPreloadKey,
        addr_of_mut!(szNumber).cast::<u16>() as LPCWSTR,
        0,
        REG_SZ,
        addr_of_mut!(szLogicalKLID).cast::<u16>() as LPBYTE as *const BYTE,
        cbValue,
    );

    if ((*pNode).wFlags as i32 & (INPUT_LIST_NODE_FLAG_ADDED as i32) != 0)
        || ((*pNode).wFlags as i32 & (INPUT_LIST_NODE_FLAG_EDITED as i32) != 0)
    {
        let mut uFlags: UINT = (KLF_SUBSTITUTE_OK | KLF_NOTELLSHELL) as UINT;
        if (*pNode).wFlags as i32 & (INPUT_LIST_NODE_FLAG_DEFAULT as i32) != 0 {
            uFlags |= KLF_REPLACELANG as UINT;
        }

        (*pNode).hkl = LoadKeyboardLayoutW(
            addr_of_mut!(szLogicalKLID).cast::<u16>() as LPCWSTR,
            uFlags,
        );
    }
}
#[no_mangle]
pub unsafe extern "C" fn InputList_Process() -> BOOL {
    let mut pCurrent: *mut INPUT_LIST_NODE = core::ptr::null_mut();
    let mut dwNumber: DWORD;
    let mut bRet: BOOL = (FALSE) as i32;
    let mut hPreloadKey: HKEY = core::ptr::null_mut();
    let mut hSubstKey: HKEY = core::ptr::null_mut();
    let mut hDefaultKL: HKL = core::ptr::null_mut();

    if InputList_PrepareUserRegistry(core::ptr::addr_of_mut!(hPreloadKey), core::ptr::addr_of_mut!(hSubstKey)) == 0 {
        if !hPreloadKey.is_null() {
            RegCloseKey(hPreloadKey);
        }
        if !hSubstKey.is_null() {
            RegCloseKey(hSubstKey);
        }
        return (FALSE) as BOOL;
    }

    /* Find change in the IME HKLs */
    pCurrent = _InputList;
    while !pCurrent.is_null() {
        if IS_IME_HKL!((*pCurrent).hkl) == 0 {
            pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
            continue;
        }

        if ((*pCurrent).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_ADDED as i32) != 0)
            || ((*pCurrent).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_EDITED as i32) != 0)
            || ((*pCurrent).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_DELETED as i32) != 0)
        {
            bRet = (TRUE) as i32; /* Reboot is needed */
            break;
        }
        pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
    }

    /* Process DELETED and EDITED entries */
    pCurrent = _InputList;
    while !pCurrent.is_null() {
        if ((*pCurrent).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_DELETED as i32) != 0)
            || ((*pCurrent).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_EDITED as i32) != 0)
        {
            /* Only unload the DELETED and EDITED entries */
            if UnloadKeyboardLayout((*pCurrent).hkl) != 0 {
                /* But the EDITED entries are used later */
                if (*pCurrent).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_DELETED as i32) != 0 {
                    InputList_RemoveNode(pCurrent);
                }
            }
        }
        pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
    }

    /* Add the DEFAULT entry and set font substitutes */
    pCurrent = _InputList;
    while !pCurrent.is_null() {
        if (*pCurrent).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_DELETED as i32) != 0 {
            pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
            continue;
        }

        if (*pCurrent).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_DEFAULT as i32) != 0 {
            bRet = InputList_SetFontSubstitutes((*(*pCurrent).pLocale).dwId as LCID);
            InputList_AddInputMethodToUserRegistry(hPreloadKey, hSubstKey, 1, pCurrent);

            /* Activate the DEFAULT entry */
            ActivateKeyboardLayout((*pCurrent).hkl, KLF_RESET);

            /* Save it */
            hDefaultKL = (*pCurrent).hkl;
            break;
        }
        pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
    }

    /* Add entries except DEFAULT to registry */
    dwNumber = 2;
    pCurrent = _InputList;
    while !pCurrent.is_null() {
        if (*pCurrent).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_DELETED as i32) != 0 {
            pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
            continue;
        }
        if (*pCurrent).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_DEFAULT as i32) != 0 {
            pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
            continue;
        }

        InputList_AddInputMethodToUserRegistry(hPreloadKey, hSubstKey, dwNumber, pCurrent);

        dwNumber = dwNumber.wrapping_add(1);
        pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
    }

    /* Remove ADDED and EDITED flags */
    pCurrent = _InputList;
    while !pCurrent.is_null() {
        (*pCurrent).wFlags = ((*pCurrent).wFlags as ::core::ffi::c_int
            & (!(INPUT_LIST_NODE_FLAG_ADDED | INPUT_LIST_NODE_FLAG_EDITED)) as i32) as WORD;
        pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
    }

    /* Change the default keyboard language */
    if SystemParametersInfoW(
        SPI_SETDEFAULTINPUTLANG,
        0,
        core::ptr::addr_of_mut!(hDefaultKL) as PVOID,
        0,
    ) != 0
    {
        let mut dwRecipients: DWORD = (BSM_ALLDESKTOPS | BSM_APPLICATIONS) as DWORD;

        BroadcastSystemMessageW(
            BSF_POSTMESSAGE,
            core::ptr::addr_of_mut!(dwRecipients),
            WM_INPUTLANGCHANGEREQUEST,
            (INPUTLANGCHANGE_SYSCHARSET) as WPARAM,
            hDefaultKL as LPARAM,
        );
    }

    /* Retry to delete (in case of failure to delete the default keyboard) */
    pCurrent = _InputList;
    while !pCurrent.is_null() {
        if (*pCurrent).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_DELETED as i32) != 0 {
            UnloadKeyboardLayout((*pCurrent).hkl);
            InputList_RemoveNode(pCurrent);
        }
        pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
    }

    RegCloseKey(hPreloadKey);
    RegCloseKey(hSubstKey);
    return bRet;
}
#[no_mangle]
pub unsafe extern "C" fn InputList_Add(mut pLocale: *mut LOCALE_LIST_NODE, mut pLayout: *mut LAYOUT_LIST_NODE) -> BOOL {
    let mut szIndicator: [WCHAR; (MAX_STR_LEN) as _] = [0; (MAX_STR_LEN) as _];
    let mut pInput: *mut INPUT_LIST_NODE = ::core::ptr::null_mut::<INPUT_LIST_NODE>();
    if pLocale.is_null() || pLayout.is_null() {
        return (FALSE) as BOOL;
    }
    pInput = _InputList;
    while !pInput.is_null() {
        if !(((*pInput).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_DELETED as i32)) != 0) {
            if (*pInput).pLocale == pLocale && (*pInput).pLayout == pLayout {
                return (FALSE) as BOOL;
            }
        }
        pInput = (*pInput).pNext as *mut INPUT_LIST_NODE;
    }
    pInput = InputList_AppendNode();
    (*pInput).wFlags = INPUT_LIST_NODE_FLAG_ADDED as WORD;
    (*pInput).pLocale = pLocale;
    (*pInput).pLayout = pLayout;
    if GetLocaleInfoW(
        LOWORD!((*(*pInput).pLocale).dwId) as LCID,
        (LOCALE_SABBREVLANGNAME | LOCALE_NOUSEROVERRIDE) as LCTYPE,
        &raw mut szIndicator as LPWSTR,
        ARRAYSIZE!(szIndicator) as ::core::ffi::c_int,
    ) != 0
    {
        let mut len: size_t = wcslen(&raw mut szIndicator as *mut WCHAR) as size_t;
        if len > 0 {
            szIndicator[len.wrapping_sub(1) as usize] = 0;
            (*pInput).pszIndicator = _wcsdup(&raw mut szIndicator as *mut WCHAR) as LPWSTR;
        }
    }
    return (TRUE) as BOOL;
}
#[no_mangle]
pub unsafe extern "C" fn InputList_SetDefault(mut pNode: *mut INPUT_LIST_NODE) {
    let mut pCurrent: *mut INPUT_LIST_NODE = ::core::ptr::null_mut::<INPUT_LIST_NODE>();
    if pNode.is_null() {
        return;
    }
    pCurrent = _InputList;
    while !pCurrent.is_null() {
        if pCurrent == pNode {
            (*pCurrent).wFlags =
                ((*pCurrent).wFlags as ::core::ffi::c_int | (INPUT_LIST_NODE_FLAG_DEFAULT as i32)) as WORD;
        } else {
            (*pCurrent).wFlags =
                ((*pCurrent).wFlags as ::core::ffi::c_int & (!INPUT_LIST_NODE_FLAG_DEFAULT) as i32) as WORD;
        }
        pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
    }
}
#[no_mangle]
pub unsafe extern "C" fn InputList_FindNextDefault(pNode: *mut INPUT_LIST_NODE) -> *mut INPUT_LIST_NODE {
    let mut pCurrent: *mut INPUT_LIST_NODE = ::core::ptr::null_mut::<INPUT_LIST_NODE>();
    pCurrent = (*pNode).pNext as *mut INPUT_LIST_NODE;
    while !pCurrent.is_null() {
        if (*pCurrent).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_DELETED as i32) != 0 {
            pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
        } else {
            return pCurrent;
        }
    }
    pCurrent = (*pNode).pPrev as *mut INPUT_LIST_NODE;
    while !pCurrent.is_null() {
        if (*pCurrent).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_DELETED as i32) != 0 {
            pCurrent = (*pCurrent).pPrev as *mut INPUT_LIST_NODE;
        } else {
            return pCurrent;
        }
    }
    return ::core::ptr::null_mut::<INPUT_LIST_NODE>();
}
#[no_mangle]
pub unsafe extern "C" fn InputList_Remove(pNode: *mut INPUT_LIST_NODE) -> BOOL {
    let mut ret: BOOL = (FALSE) as i32;
    let mut bRemoveNode: BOOL = (FALSE) as i32;
    if pNode.is_null() {
        return (FALSE) as BOOL;
    }
    if (*pNode).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_ADDED as i32) != 0 {
        bRemoveNode = TRUE as BOOL;
    } else {
        (*pNode).wFlags =
            ((*pNode).wFlags as ::core::ffi::c_int | (INPUT_LIST_NODE_FLAG_DELETED as i32)) as WORD;
    }
    if (*pNode).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_DEFAULT as i32) != 0 {
        let mut pCurrent: *mut INPUT_LIST_NODE = InputList_FindNextDefault(pNode);
        if !pCurrent.is_null() {
            (*pCurrent).wFlags =
                ((*pCurrent).wFlags as ::core::ffi::c_int | (INPUT_LIST_NODE_FLAG_DEFAULT as i32)) as WORD;
        }
        (*pNode).wFlags =
            ((*pNode).wFlags as ::core::ffi::c_int & (!INPUT_LIST_NODE_FLAG_DEFAULT) as i32) as WORD;
        ret = TRUE as BOOL;
    }
    if bRemoveNode != 0 {
        InputList_RemoveNode(pNode);
    }
    return ret;
}
#[no_mangle]
pub unsafe extern "C" fn InputList_RemoveByLang(wLangId: LANGID) -> BOOL {
    let mut ret: BOOL = (FALSE) as i32;
    let mut pCurrent: *mut INPUT_LIST_NODE = core::ptr::null_mut();

    'Retry: loop {
        pCurrent = _InputList;
        while !pCurrent.is_null() {
            if ((*pCurrent).wFlags as i32 & (INPUT_LIST_NODE_FLAG_DELETED as i32)) != 0 {
                pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
                continue;
            }

            if LOWORD!((*(*pCurrent).pLocale).dwId) == wLangId {
                if InputList_Remove(pCurrent) != 0 {
                    ret = (TRUE) as i32; /* default input is changed */
                }
                continue 'Retry;
            }

            pCurrent = (*pCurrent).pNext as *mut INPUT_LIST_NODE;
        }
        break;
    }

    return ret;
}
#[no_mangle]
pub unsafe extern "C" fn InputList_Create() {
    let mut iLayoutCount: INT = 0;
    let mut iIndex: INT = 0;
    let mut szIndicator: [WCHAR; (MAX_STR_LEN) as _] = [0 as WCHAR; (MAX_STR_LEN) as _];
    let mut pInput: *mut INPUT_LIST_NODE = core::ptr::null_mut();
    let mut pLayoutList: *mut HKL = core::ptr::null_mut();
    let mut hklDefault: HKL = core::ptr::null_mut();

    SystemParametersInfoW(
        SPI_GETDEFAULTINPUTLANG as UINT,
        0 as UINT,
        &raw mut hklDefault as PVOID,
        0 as UINT,
    );

    iLayoutCount = GetKeyboardLayoutList(0 as ::core::ffi::c_int, core::ptr::null_mut()) as INT;
    pLayoutList = malloc(
        (iLayoutCount as size_t).wrapping_mul(core::mem::size_of::<HKL>() as size_t),
    ) as *mut HKL;

    if pLayoutList.is_null()
        || GetKeyboardLayoutList(iLayoutCount as ::core::ffi::c_int, pLayoutList) <= 0 as UINT
    {
        free(pLayoutList as *mut ::core::ffi::c_void);
        return;
    }

    iIndex = 0 as INT;
    while iIndex < iLayoutCount {
        let mut hKL: HKL = *pLayoutList.offset(iIndex as isize);
        let mut pLocale: *mut LOCALE_LIST_NODE = LocaleList_GetByHkl(hKL);
        let mut pLayout: *mut LAYOUT_LIST_NODE = LayoutList_GetByHkl(hKL);
        if pLocale.is_null() || pLayout.is_null() {
            iIndex += 1;
            continue;
        }

        pInput = InputList_AppendNode();
        (*pInput).pLocale = pLocale;
        (*pInput).pLayout = pLayout;
        (*pInput).hkl = hKL;

        if (*pInput).hkl == hklDefault {
            (*pInput).wFlags =
                ((*pInput).wFlags as ::core::ffi::c_int | INPUT_LIST_NODE_FLAG_DEFAULT as ::core::ffi::c_int) as WORD;
            hklDefault = core::ptr::null_mut();
        }

        szIndicator[0 as usize] = 0 as WCHAR;
        if GetLocaleInfoW(
            LOWORD!((*(*pInput).pLocale).dwId) as LCID,
            (LOCALE_SABBREVLANGNAME | LOCALE_NOUSEROVERRIDE) as LCTYPE,
            szIndicator.as_mut_ptr(),
            ARRAYSIZE!(szIndicator) as ::core::ffi::c_int,
        ) != 0
        {
            let len: size_t = wcslen(szIndicator.as_mut_ptr()) as size_t;
            if len > 0 as size_t {
                szIndicator[len - 1 as size_t] = 0 as WCHAR;
                (*pInput).pszIndicator = _wcsdup(szIndicator.as_mut_ptr()) as LPWSTR;
            }
        }

        iIndex += 1;
    }

    free(pLayoutList as *mut ::core::ffi::c_void);
}

unsafe extern "C" fn InputList_Compare(pNode1: *mut INPUT_LIST_NODE, pNode2: *mut INPUT_LIST_NODE) -> INT {
    let mut nCompare: INT = _wcsicmp((*pNode1).pszIndicator as LPCWSTR, (*pNode2).pszIndicator as LPCWSTR) as INT;
    if nCompare != 0 {
        return nCompare;
    }

    return _wcsicmp((*(*pNode1).pLayout).pszName as LPCWSTR, (*(*pNode2).pLayout).pszName as LPCWSTR) as INT;
}
#[no_mangle]
pub unsafe extern "C" fn InputList_Sort() {
    let mut pList: *mut INPUT_LIST_NODE = _InputList;
    let mut pNext: *mut INPUT_LIST_NODE = ::core::ptr::null_mut::<INPUT_LIST_NODE>();
    let mut pPrev: *mut INPUT_LIST_NODE = ::core::ptr::null_mut::<INPUT_LIST_NODE>();
    let mut pMinimum: *mut INPUT_LIST_NODE = ::core::ptr::null_mut::<INPUT_LIST_NODE>();
    let mut pNode: *mut INPUT_LIST_NODE = ::core::ptr::null_mut::<INPUT_LIST_NODE>();
    _InputList = ::core::ptr::null_mut::<INPUT_LIST_NODE>();
    while !pList.is_null() {
        /* Find the minimum node */
        pMinimum = ::core::ptr::null_mut::<INPUT_LIST_NODE>();
        pNode = pList;
        while !pNode.is_null() {
            pNext = (*pNode).pNext as *mut INPUT_LIST_NODE;
            if pMinimum.is_null() {
                pMinimum = pNode;
            } else if InputList_Compare(pNode, pMinimum) < 0 {
                pMinimum = pNode;
            }
            pNode = pNext;
        }

        // Remove pMinimum from pList
        pNext = (*pMinimum).pNext as *mut INPUT_LIST_NODE;
        pPrev = (*pMinimum).pPrev as *mut INPUT_LIST_NODE;
        if !pNext.is_null() {
            (*pNext).pPrev = pPrev as *mut _INPUT_LIST_NODE;
        }
        if !pPrev.is_null() {
            (*pPrev).pNext = pNext as *mut _INPUT_LIST_NODE;
        } else {
            pList = pNext;
        }

        // Append pMinimum to _InputList
        if _InputList.is_null() {
            (*pMinimum).pNext = ::core::ptr::null_mut::<_INPUT_LIST_NODE>();
            (*pMinimum).pPrev = (*pMinimum).pNext;
            _InputList = pMinimum;
        } else {
            /* Find last node */
            pNode = _InputList;
            while !(*pNode).pNext.is_null() {
                pNode = (*pNode).pNext as *mut INPUT_LIST_NODE;
            }

            /* Add to the end */
            (*pNode).pNext = pMinimum as *mut _INPUT_LIST_NODE;
            (*pMinimum).pPrev = pNode as *mut _INPUT_LIST_NODE;
            (*pMinimum).pNext = ::core::ptr::null_mut::<_INPUT_LIST_NODE>();
        }
    }
}
#[no_mangle]
pub unsafe extern "C" fn InputList_GetAliveCount() -> INT {
    let mut pNode: *mut INPUT_LIST_NODE = ::core::ptr::null_mut::<INPUT_LIST_NODE>();
    let mut nCount: INT = 0;
    pNode = _InputList;
    while !pNode.is_null() {
        if !(((*pNode).wFlags as ::core::ffi::c_int & (INPUT_LIST_NODE_FLAG_DELETED as i32)) != 0) {
            nCount += 1;
        }
        pNode = (*pNode).pNext as *mut INPUT_LIST_NODE;
    }
    return nCount;
}
#[no_mangle]
pub unsafe extern "C" fn InputList_GetFirst() -> *mut INPUT_LIST_NODE {
    return _InputList;
}
