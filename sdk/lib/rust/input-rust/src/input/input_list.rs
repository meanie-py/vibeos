unsafe extern "C" fn InputList_FindPreloadKLID(hPreloadKey: HKEY, dwKLID: DWORD) -> BOOL {
    let mut dwNumber: DWORD = 0;
    let mut dwType: DWORD = 0;
    let mut cbValue: DWORD = 0;
    let mut szNumber: [WCHAR; 16] = [0 as WCHAR; 16];
    let mut szValue: [WCHAR; (KL_NAMELENGTH) as _] = [0 as WCHAR; (KL_NAMELENGTH) as _];
    let mut szKLID: [WCHAR; (KL_NAMELENGTH) as _] = [0 as WCHAR; (KL_NAMELENGTH) as _];

    StringCchPrintfW!(
        core::ptr::addr_of_mut!(szKLID) as *mut WCHAR,
        ARRAYSIZE!(szKLID),
        RUSTCONV_WSTR_FE2DE33F78CD.as_ptr(),
        dwKLID,
    );

    dwNumber = 1;
    while dwNumber <= 1000 {
        StringCchPrintfW!(
            core::ptr::addr_of_mut!(szNumber) as *mut WCHAR,
            ARRAYSIZE!(szNumber),
            RUSTCONV_WSTR_69A283E639E4.as_ptr(),
            dwNumber,
        );

        cbValue = (ARRAYSIZE!(szValue) as usize * core::mem::size_of::<WCHAR>()) as DWORD;
        if (RegQueryValueExW(
            hPreloadKey,
            core::ptr::addr_of_mut!(szNumber) as *mut WCHAR as LPCWSTR,
            core::ptr::null::<DWORD>() as LPDWORD,
            core::ptr::addr_of_mut!(dwType),
            core::ptr::addr_of_mut!(szValue) as *mut WCHAR as LPBYTE,
            core::ptr::addr_of_mut!(cbValue),
        )) as u32 != ERROR_SUCCESS
        {
            break;
        }

        if dwType != REG_SZ {
            dwNumber = dwNumber.wrapping_add(1);
            continue;
        }

        szValue[(ARRAYSIZE!(szValue) - 1) as usize] = 0;
        if _wcsicmp(
            core::ptr::addr_of_mut!(szKLID) as *mut WCHAR,
            core::ptr::addr_of_mut!(szValue) as *mut WCHAR,
        ) == 0
        {
            return (TRUE) as BOOL;
        }

        dwNumber = dwNumber.wrapping_add(1);
    }

    return (FALSE) as BOOL;
}

