#[no_mangle]
pub unsafe extern "system" fn DllGetClassObject(rclsid: REFCLSID, iid: REFIID, ppv: *mut LPVOID) -> HRESULT {
    let mut cf: *mut IClassFactory = core::ptr::null_mut();

    if IsEqualGUID!(rclsid, core::ptr::addr_of!(CLSID_Sti)) != false {
        cf = core::ptr::addr_of_mut!(the_sti_cf.IClassFactory_iface);
    }

    if !cf.is_null() {
        return IClassFactory_QueryInterface(cf, iid, ppv);
    }
    return STI_DllGetClassObject(rclsid, iid, ppv);
}

