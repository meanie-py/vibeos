unsafe extern "system" fn sti_cf_CreateInstance(
    iface: *mut IClassFactory,
    pOuter: LPUNKNOWN,
    riid: REFIID,
    ppobj: *mut LPVOID,
) -> HRESULT {
    let mut This: *mut sti_cf = impl_from_IClassFactory(iface);
    let mut r: HRESULT = 0;
    let mut punk: *mut IUnknown = core::ptr::null_mut();

    *ppobj = core::ptr::null_mut();

    r = (*This).pfnCreateInstance.unwrap_unchecked()(
        riid,
        pOuter,
        core::ptr::addr_of_mut!(punk) as *mut LPVOID,
    );
    if r < 0 {
        return r;
    }

    r = IUnknown_QueryInterface(punk, riid, ppobj);
    if r < 0 {
        return r;
    }

    IUnknown_Release(punk);
    return r;
}
