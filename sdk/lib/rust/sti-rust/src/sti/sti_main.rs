unsafe extern "C" fn sti_create(
    riid: *const IID,
    pUnkOuter: *mut IUnknown,
    ppObj: *mut LPVOID,
) -> HRESULT {
    if !pUnkOuter.is_null() && IsEqualIID!(riid, core::ptr::addr_of!(IID_IUnknown)) == 0 {
        return CLASS_E_NOAGGREGATION;
    }

    if IsEqualGUID!(riid, core::ptr::addr_of!(IID_IUnknown)) != false {
        return StiCreateInstanceW(
            GetCurrentProcess() as HINSTANCE,
            (STI_VERSION_REAL | STI_VERSION_FLAG_UNICODE) as DWORD,
            ppObj as *mut PSTIW,
            pUnkOuter as LPUNKNOWN,
        );
    } else if IsEqualGUID!(riid, core::ptr::addr_of!(IID_IStillImageW)) != false {
        return StiCreateInstanceW(
            GetCurrentProcess() as HINSTANCE,
            (STI_VERSION_REAL | STI_VERSION_FLAG_UNICODE) as DWORD,
            ppObj as *mut PSTIW,
            core::ptr::null_mut::<IUnknown>(),
        );
    } else if IsEqualGUID!(riid, core::ptr::addr_of!(IID_IStillImageA)) != false {
        return StiCreateInstanceA(
            GetCurrentProcess() as HINSTANCE,
            STI_VERSION_REAL as DWORD,
            ppObj as *mut PSTIA,
            core::ptr::null_mut::<IUnknown>(),
        );
    } else {
        if ((*__wine_dbch___default).flags as i32)
            & (1i32 << __WINE_DBCL_FIXME as i32)
            != 0
        {
            let __dbch: *mut __wine_debug_channel = __wine_dbch___default;
            let __dbcl: __wine_debug_class = __WINE_DBCL_FIXME;
            ros_dbg_log(
                __dbcl,
                __dbch,
                b"dll/win32/sti/sti_main.c\0"
                    as *const u8 as *const core::ffi::c_char,
                b"sti_create\0" as *const u8 as *const core::ffi::c_char,
                68 as i32,
                b"no interface %s\n\0" as *const u8 as *const core::ffi::c_char,
                debugstr_guid(riid as *const _GUID),
            );
        }
        return E_NOINTERFACE;
    }
}
unsafe extern "system" fn sti_cf_QueryInterface(iface: *mut IClassFactory, riid: *const IID, ppobj: *mut LPVOID) -> HRESULT {
    if IsEqualGUID!(riid, core::ptr::addr_of!(IID_IUnknown)) != false ||
        IsEqualGUID!(riid, core::ptr::addr_of!(IID_IClassFactory)) != false
    {
        IClassFactory_AddRef(iface);
        *ppobj = iface as LPVOID;
        return S_OK;
    }

    return E_NOINTERFACE;
}
