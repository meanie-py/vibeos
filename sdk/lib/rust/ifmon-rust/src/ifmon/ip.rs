unsafe extern "system" fn IpDumpFn(
    pwszRouter: LPCWSTR,
    ppwcArguments: *mut LPWSTR,
    dwArgCount: DWORD,
    pvData: LPCVOID,
) -> DWORD {
    let mut pTable: *mut IP_INTERFACE_NAME_INFO = core::ptr::null_mut::<IP_INTERFACE_NAME_INFO>();
    let mut dwCount: DWORD = 0 as DWORD;
    let mut i: DWORD = 0;
    let mut dwError: DWORD = 0;
    let mut szFriendlyName: [WCHAR; 80] = [0 as WCHAR; 80];
    let mut dwFriendlyNameSize: DWORD = 0;
    let mut pProperties: PTCPIP_PROPERTIES = core::ptr::null_mut::<_TCPIP_PROPERTIES>();
    let mut pBuffer: PWSTR = core::ptr::null_mut::<WCHAR>();

    DPRINT!("IpDumpFn(%S %p %lu %p)\n", pwszRouter, ppwcArguments, dwArgCount, pvData);

    dwError = NhpAllocateAndGetInterfaceInfoFromStack(
        core::ptr::addr_of_mut!(pTable),
        core::ptr::addr_of_mut!(dwCount),
        (FALSE as i32),
        GetProcessHeap(),
        0,
    ) as DWORD;
    if dwError != ERROR_SUCCESS as DWORD {
        DPRINT1!("NhpAllocateAndGetInterfaceInfoFromStack() failed (Error %lu)\n", dwError);
        return dwError;
    }

    PrintMessageFromModule((hDllInstance).cast(), IDS_DUMP_HEADERLINE);
    PrintMessageFromModule((hDllInstance).cast(), IDS_DUMP_IP_HEADER);
    PrintMessageFromModule((hDllInstance).cast(), IDS_DUMP_HEADERLINE);
    PrintMessage(RUSTCONV_WSTR_2CC42C7B320B.as_ptr());
    PrintMessageFromModule((hDllInstance).cast(), IDS_DUMP_NEWLINE);

    DPRINT!("\nEntries: %lu\n", dwCount);

    i = 0 as DWORD;
    while i < dwCount {
        DPRINT!("\nEntry %lu\n", i);
        DPRINT!("Index: %lu\n", (*pTable.add(i as usize)).Index);
        DPRINT!("MediaType: %lu\n", (*pTable.add(i as usize)).MediaType);
        DPRINT!("ConnectionType: %u\n", (*pTable.add(i as usize)).ConnectionType);
        DPRINT!("AccessType: %u\n", (*pTable.add(i as usize)).AccessType);
        DPRINT!("DeviceGuid: %08lx\n", (*pTable.add(i as usize)).DeviceGuid.Data1);
        DPRINT!("InterfaceGuid: %08lx\n", (*pTable.add(i as usize)).InterfaceGuid.Data1);

        dwFriendlyNameSize = core::mem::size_of::<[WCHAR; 80]>() as DWORD;
        NhGetInterfaceNameFromGuid(
            core::ptr::addr_of_mut!((*pTable.add(i as usize)).DeviceGuid),
            szFriendlyName.as_mut_ptr(),
            core::ptr::addr_of_mut!(dwFriendlyNameSize),
            0,
            0,
        );

        PrintMessageFromModule((hDllInstance).cast(), IDS_DUMP_NEWLINE);
        PrintMessageFromModule((hDllInstance).cast(), IDS_DUMP_IP_INTERFACE, szFriendlyName.as_mut_ptr());
        PrintMessageFromModule((hDllInstance).cast(), IDS_DUMP_NEWLINE);

        GetInterfaceProperties(
            core::ptr::addr_of_mut!((*pTable.add(i as usize)).DeviceGuid),
            core::ptr::addr_of_mut!(pProperties),
        );

        if !pProperties.is_null() {
            DPRINT!("Dhcp %lu\n", (*pProperties).dwDhcp);
            DPRINT!("IpAddress %S\n", (*pProperties).pszIpAddress);
            DPRINT!("SubnetMask %S\n", (*pProperties).pszSubnetMask);
            DPRINT!("Parameters %S\n", (*pProperties).pszParameters);

            if (*pProperties).dwDhcp != 0 {
                PrintMessage(
                    RUSTCONV_WSTR_8FAFE5258658.as_ptr(),
                    szFriendlyName.as_mut_ptr(),
                );
            } else {
                PrintMessage(
                    RUSTCONV_WSTR_CEDB4A6529CA.as_ptr(),
                    szFriendlyName.as_mut_ptr(),
                    (*pProperties).pszIpAddress,
                    (*pProperties).pszSubnetMask,
                );
            }

            if (*pProperties).dwDhcp != 0 {
                PrintMessage(
                    RUSTCONV_WSTR_9027C7116C57.as_ptr(),
                    szFriendlyName.as_mut_ptr(),
                );
            } else {
                pBuffer = ExtractParameterValue(
                    (*pProperties).pszParameters,
                    RUSTCONV_WSTR_26403B81D69B.as_ptr() as PWSTR,
                );
                if !pBuffer.is_null() {
                    PrintMessage(
                        RUSTCONV_WSTR_1AD68E037BFF.as_ptr(),
                        szFriendlyName.as_mut_ptr(),
                        pBuffer,
                    );
                    HeapFree(
                        GetProcessHeap(),
                        0,
                        (pBuffer).cast(),
                    );
                }
            }

            CoTaskMemFree(pProperties as LPVOID);
            pProperties = core::ptr::null_mut::<_TCPIP_PROPERTIES>();
        }
        i = i.wrapping_add(1);
    }

    PrintMessageFromModule((hDllInstance).cast(), IDS_DUMP_NEWLINE);
    PrintMessage(RUSTCONV_WSTR_DC3CC836BA3F.as_ptr());
    PrintMessageFromModule((hDllInstance).cast(), IDS_DUMP_IP_FOOTER);
    PrintMessageFromModule((hDllInstance).cast(), IDS_DUMP_NEWLINE);

    if !pTable.is_null() {
        HeapFree(
            GetProcessHeap(),
            0,
            pTable as PVOID,
        );
    }

    return ERROR_SUCCESS as DWORD;
}
