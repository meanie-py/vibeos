#!/bin/bash
# Generate the advapi32 Win32-SDK/RPC-client/winsafer/aclapi/evntrace/EFS type
# substrate (advapi32-sys) for all 3 arches.
#
# Allowlisted to the advapi32-specific surface absent from ntdll-sys (which is
# NT-internal only). Flags/includes mirror the module's own C compile command so
# the usermode win32+NDK header context resolves exactly as the C build sees it.
# Per-arch (pointer widths + RPC string layout differ).
#
# Prereq: cargo install bindgen-cli. Build dirs must exist (generated headers
# like svcctl_c.h/winreg_c.h live under build-<arch>/dll/win32/advapi32).
set -e
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SRC="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
TC="$SRC/.build-tools/llvm-mingw"
OUT_DIR="$SCRIPT_DIR/src"
WRAPPER="$SCRIPT_DIR/wrapper_advapi32.h"

COMMON_FLAGS=(
    --use-core --no-layout-tests --no-doc-comments
    --allowlist-function '(Lsar[A-Za-z0-9_]*|Elfr[A-Za-z0-9_]*|R[A-Z][A-Za-z0-9_]*|Secl[A-Za-z0-9_]*)'
    --allowlist-type '(P?TRUSTEE.*|P?EXPLICIT_ACCESS.*|ACCESS_MODE|MULTIPLE_TRUSTEE_OPERATION|TRUSTEE_FORM|TRUSTEE_TYPE|P?ACTRL_.*|P?OBJECTS_AND_.*|P?INHERITED_FROM.*|PROG_INVOKE_SETTING|P?FN_PROGRESS.*|SE_OBJECT_TYPE|P?SAFER_.*|P?EVENT_TRACE.*|P?TRACEHANDLE|EVENT_CALLBACK.*|TRACE_GUID.*|WNODE_.*|P?ENCRYPTION_CERTIFICATE.*|P?ENCRYPTION_PROTECTOR.*|EFS_.*|RPC_STATUS|handle_t|P?RPC_UNICODE_STRING|UUID|ustring|RPC_CSTR|RPC_WSTR|P?HKEY|REGSAM|P?VALENT.*|P?REGISTRY_SERVER_NAME|RRP_UNICODE_STRING|SC_HANDLE|SC_LOCK|P?SERVICE_STATUS.*|P?ENUM_SERVICE.*|P?QUERY_SERVICE.*|P?SERVICE_.*|P?SC_.*|P?SCM_.*|LP(ENUM_SERVICE|QUERY_SERVICE|SC_|STRING_PTRS).*|SVCCTL_HANDLE.*|P?TAG_INFO.*|P?SECL_.*|P?STRING_PTRS.*|RPC_SERVICE_STATUS_HANDLE|P?LPHANDLER_FUNCTION.*|P?HANDLER_FUNCTION.*|P?LPSERVICE_.*|PFN_OBJECT_MGR_FUNCTS|P?NTMARTA|P?MD4.*|P?MD5.*|P?EVENTLOGRECORD|P?PROFILEINFO.*|QUOTA_LIMITS|P?SID_NAME_USE|P?LSA_.*|P?LSAPR_.*|P?LSAP_.*|TRUSTED_INFORMATION_CLASS|POLICY_INFORMATION_CLASS|POLICY_DOMAIN_INFORMATION_CLASS|P?SECURITY_LOGON_TYPE|P?MSV1_0_.*|P?TRUSTED_DOMAIN.*|P?EVENTLOG_HANDLE.*|P?IELF_HANDLE|P?RPC_CLIENT_ID|P?RPC_SID|P?RPC_STRING|P?CRYPT.*|P?HCRYPT.*|P?CRYPTPROV|P?CRYPTKEY|P?CRYPTHASH|P?RC4_.*|ALG_ID|HCRYPTPROV_OR_NCRYPT_KEY_HANDLE|P?CREDENTIAL.*|P?CRED_MARSHAL_TYPE|P?CERT_CREDENTIAL_INFO|P?USERNAME_TARGET_CREDENTIAL_INFO)'
    --allowlist-var  '(TRUSTEE_.*|RPC_S_.*|SAFER_.*|INVALID_PROCESSTRACE_HANDLE|EVENT_TRACE_.*|SERVICE_.*|SC_.*|SCM_.*|RTL_ENCRYPT_.*|MAX_SERVICE_.*|CP_.*|REG_.*|MD4_.*|MAGIC_.*|CRYPT_.*|NTE_.*|LSA_.*|POLICY_.*|ALG_.*|PROV_.*|CALG_.*|CRED_.*|CERT_HASH_LENGTH)'
)

run_bindgen() {
    local ARCH=$1 TARGET=$2; shift 2
    local EXTRA=("$@")
    local BUILD_DIR="$SRC/build-${ARCH}"
    local RAW="/tmp/advapi32_${ARCH}_raw.rs"
    local FINAL="$OUT_DIR/bindgen_${ARCH}.rs"
    echo "=== advapi32-sys ${ARCH} (${TARGET}) ==="
    bindgen "$WRAPPER" "${COMMON_FLAGS[@]}" -o "$RAW" -- \
        -ferror-limit=0 -Wno-everything \
        -DUNICODE -D_UNICODE -D__REACTOS__ -D_USE_DUMMY_PSEH=1 \
        -DDBG=1 -DWINVER=0x502 -D_WIN32_WINNT=0x502 -D_WIN32_WINDOWS=0x502 \
        -D_WIN32_IE=0x603 -D_CRT_NON_CONFORMING_SWPRINTFS -D_CRT_SUPPRESS_RESTRICT \
        -D_ADVAPI32_ -D_WMI_SOURCE_ \
        "${EXTRA[@]}" \
        -I"${BUILD_DIR}/dll/win32/advapi32" \
        -I"${SRC}/dll/win32/advapi32" \
        -I"${SRC}/sdk/include" \
        -I"${SRC}/sdk/include/crt" \
        -I"${SRC}/sdk/include/ddk" \
        -I"${SRC}/sdk/include/ndk" \
        -I"${SRC}/sdk/include/psdk" \
        -I"${SRC}/sdk/include/reactos" \
        -I"${SRC}/sdk/include/reactos/idl" \
        -I"${SRC}/sdk/include/reactos/libs" \
        -I"${SRC}/sdk/lib/cryptlib" \
        -I"${SRC}/sdk/include/vcruntime" \
        -I"${SRC}/sdk/include/winrt" \
        -I"${SRC}/sdk/lib/pseh/include" \
        -I"${BUILD_DIR}/sdk/include" \
        -I"${BUILD_DIR}/sdk/include/psdk" \
        -I"${BUILD_DIR}/sdk/include/ddk" \
        -I"${BUILD_DIR}/sdk/include/dxsdk" \
        -I"${BUILD_DIR}/sdk/include/reactos" \
        -I"${BUILD_DIR}/sdk/include/reactos/mc" \
        -isystem "${TC}/lib/clang/19/include" \
        --target="${TARGET}"
    {
        echo "// AUTO-GENERATED by advapi32-sys/generate_bindings.sh — do not edit by hand."
        echo "// Win32-SDK/RPC-client/winsafer/aclapi/evntrace/EFS substrate for advapi32-rust."
        echo "#![allow(non_snake_case, non_camel_case_types, non_upper_case_globals, dead_code, unused_imports)]"
        cat "$RAW"
    } > "$FINAL"
    echo "  -> $FINAL ($(wc -l < "$FINAL") lines)"
}

run_bindgen arm64 aarch64-pc-windows-gnu -D_WIN64 -D_M_ARM64 -D__aarch64__ -D__arm64__ -D_ARM64_
run_bindgen amd64 x86_64-pc-windows-gnu  -D_WIN64 -D_M_AMD64 -D__x86_64__ -D_AMD64_
run_bindgen i386  i686-pc-windows-gnu    -D_M_IX86 -D__i386__ -D_X86_ -D_USE_32BIT_TIME_T
echo "=== done ==="

# Spell ABI-identical callback slots `extern "system"` across the three islands this run just
# wrote, projecting per symbol from the i386 witness (the only arch that still records which
# callbacks are stdcall). Without this the slots keep the arch's literal convention, a
# translated `extern "system"` callback will not unify with them, and the standing workaround
# is a transmute that erases the whole fn type. Idempotent — safe to re-run.
#
# This lives in EVERY generator on purpose: normalization that only some of them apply is
# normalization that the next regeneration of any other crate silently undoes.
_isl_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
python3 "${_isl_dir}/../../../../tools/rustconv/normalize_island_abi.py" --apply "${_isl_dir}"
