//! Compile reference TU #13 — the GENUINE `dll/win32/msvcrt/except_i386.c` — for a 32-bit
//! Linux host, with its seven exported definitions renamed to `ref_*`, plus the SEH
//! substrate that makes a Windows exception environment exist on this platform.
//!
//! The reference sees EMPTY stand-ins where it asks for windef.h / winbase.h / winternl.h /
//! msvcrt.h / cppexcept.h / fpieee.h / setjmp.h / excpt.h / wine's two headers, and gets
//! everything from `refstub/seh_prelude.h`, force-included ahead of the first line.  That
//! is the same trick msvcrt-difftest uses; what is new here is `refstub/seh_layout.h`,
//! generated from the REAL i386 headers, which turns the transcription from a promise into
//! a compile-time assertion.
//!
//! `sehimpl.c` deliberately does NOT get the prelude — only the types.  It has to name both
//! `_except_handler4_common` and `ref__except_handler4_common` in one file, so the rename
//! wall must not be in scope, and it needs glibc's real `<setjmp.h>`, which the stand-in
//! would shadow.

use std::env;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let refstub = manifest.join("refstub");
    let repo = manifest
        .ancestors()
        .nth(4)
        .expect("crate is sdk/lib/rust/<crate>")
        .to_path_buf();
    let msvcrt_c = repo.join("dll/win32/msvcrt/except_i386.c");

    println!("cargo:rerun-if-changed={}", msvcrt_c.display());
    println!("cargo:rerun-if-changed={}", manifest.join("sehimpl.c").display());
    println!("cargo:rerun-if-changed={}", refstub.join("seh_prelude.h").display());
    println!("cargo:rerun-if-changed={}", refstub.join("seh_types.h").display());
    println!("cargo:rerun-if-changed={}", refstub.join("seh_layout.h").display());

    // Off-arch this crate has nothing to build and nothing to grade. `cargo check
    // --workspace` on an x86-64 host lands here, and linking 32-bit objects into a 64-bit
    // test binary would be a confusing link error rather than a clear one.
    let arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    let os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    if arch != "x86" || os != "linux" {
        println!("cargo:rustc-cfg=seh_difftest_off_target");
        return;
    }

    if !msvcrt_c.is_file() {
        panic!(
            "msvcrt-seh-difftest: {} is missing — the reference TU IS the oracle, so there \
             is nothing honest to fall back to.",
            msvcrt_c.display()
        );
    }
    if !refstub.join("seh_layout.h").is_file() {
        panic!(
            "msvcrt-seh-difftest: refstub/seh_layout.h is missing.\n\
             fix: python3 tools/gen_msvcrt_seh_layout.py\n\
             Without it the i386 transcription in seh_types.h is unchecked, and an unchecked \
             oracle reports confident nonsense (field manual §9.66)."
        );
    }

    // ── the empty sockets ────────────────────────────────────────────────
    // Each one is a header the reference asks for and the harness answers itself.  They are
    // empty rather than absent so the `#include` still resolves and the reader of the C sees
    // the same include list msvcrt.dll compiles.
    //
    // msvcrt.h and cppexcept.h are NOT among them: they sit beside except_i386.c, so a
    // quoted include finds them whatever `-I` says.  seh_prelude.h claims their include
    // guards instead — and this is where that claim is checked, because a header that
    // renamed its guard would silently un-shadow itself and pull the whole PSDK chain in.
    for (header, guard) in [
        ("dll/win32/msvcrt/msvcrt.h", "__WINE_MSVCRT_H"),
        ("dll/win32/msvcrt/cppexcept.h", "__MSVCRT_CPPEXCEPT_H"),
    ] {
        let text = std::fs::read_to_string(repo.join(header)).unwrap();
        assert!(
            text.contains(&format!("#ifndef {guard}")),
            "msvcrt-seh-difftest: {header} no longer guards with `{guard}`, so \
             refstub/seh_prelude.h's pre-claim of that guard shadows nothing and the \
             reference TU is about to include the real PSDK chain. Update both."
        );
    }

    let sockets = out.join("sockets");
    std::fs::create_dir_all(sockets.join("wine")).unwrap();
    for h in [
        "windef.h",
        "winbase.h",
        "winternl.h",
        "excpt.h",
        "fpieee.h",
        "setjmp.h",
        "wine/debug.h",
        "wine/exception.h",
    ] {
        std::fs::write(
            sockets.join(h),
            "/* generated by msvcrt-seh-difftest/build.rs: an empty socket. \
             refstub/seh_prelude.h answers for this header. */\n",
        )
        .unwrap();
    }

    // ── reference TU #13 ─────────────────────────────────────────────────
    let mut reference = cc::Build::new();
    reference
        .include(&sockets) // the sockets FIRST — they shadow the tree's real headers
        .include(&refstub)
        .define("__REACTOS__", None)
        .define("_MSVCR_VER", "0")
        .flag("-fno-omit-frame-pointer")
        .flag("-fno-builtin")
        // `-w` because this TU assigns its own handler types into `PEXCEPTION_ROUTINE` slots
        // and compares `int` against `UINT`, exactly as it does in the DLL build — noise
        // that belongs to the reference, not to the harness. The two -Werror= flags below
        // still bite; they are diagnostics `-w` does not turn off.
        .flag("-w")
        // Implicit declarations are how a reference TU silently truncates a pointer to int.
        // This TU calls through function pointers stored in tables; a wrong-width return is
        // exactly the class that would look like a translation bug.
        .flag("-Werror=implicit-function-declaration")
        .flag("-Werror=implicit-int")
        .flag("-U_FORTIFY_SOURCE")
        .flag("-include")
        .flag(refstub.join("seh_prelude.h").to_str().unwrap())
        .file(&msvcrt_c)
        .out_dir(out.join("ref"));
    reference.compile("msvcrt_seh_reference");

    // ── the substrate ────────────────────────────────────────────────────
    // Types but NOT the rename wall, and glibc's headers left reachable: see the module
    // docstring.  `-fno-omit-frame-pointer` is load-bearing rather than stylistic — the
    // callbacks read the %ebp the asm thunk installed out of their own saved-EBP slot, and
    // without a frame pointer that slot does not exist.
    let mut substrate = cc::Build::new();
    substrate
        .include(&refstub)
        .flag("-fno-omit-frame-pointer")
        .flag("-Werror=implicit-function-declaration")
        .flag("-Werror=implicit-int")
        .flag("-U_FORTIFY_SOURCE")
        .flag("-include")
        .flag(refstub.join("seh_types.h").to_str().unwrap())
        .file(manifest.join("sehimpl.c"))
        .out_dir(out.join("impl"));
    substrate.compile("msvcrt_seh_impl");

    // `except.rs` exports `#[no_mangle] signal`, and a static definition beats glibc's for
    // the whole binary — including for Rust's own startup, which calls `signal(SIGPIPE, …)`
    // and aborts on SIG_ERR. msvcrt's `signal` has no SIGPIPE, so the harness died before
    // `main` with "fatal runtime error", nowhere near the cause.
    //
    // `--wrap` redirects the REFERENCES rather than replacing the definition, so the subject
    // keeps its own `signal` exactly as msvcrt.dll has it and sehimpl.c's `__wrap_signal`
    // answers for std. (`__real_signal` is deliberately not used: it would resolve straight
    // back to the subject's.) The one thing this forecloses is grading `signal`/`raise`
    // here, which belongs to except.c's own rows, not to the SEH ones.
    println!("cargo:rustc-link-arg=-Wl,--wrap=signal");
}
