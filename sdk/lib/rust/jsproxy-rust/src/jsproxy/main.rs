unsafe extern "C" fn strdupAW(src: *const ::core::ffi::c_char, mut len: ::core::ffi::c_int) -> *mut WCHAR {
    let mut dst: *mut WCHAR = ::core::ptr::null_mut::<WCHAR>();
    if !src.is_null() {
        let mut dst_len: ::core::ffi::c_int = MultiByteToWideChar(
            CP_ACP as UINT,
            0 as DWORD,
            src as LPCSTR,
            len,
            ::core::ptr::null_mut::<WCHAR>(),
            0 as ::core::ffi::c_int,
        );
        dst = malloc(
            ((dst_len + 1 as ::core::ffi::c_int) as size_t)
                .wrapping_mul(::core::mem::size_of::<WCHAR>() as size_t),
        ) as *mut WCHAR;
        if !dst.is_null() {
            len = MultiByteToWideChar(
                CP_ACP as UINT,
                0 as DWORD,
                src as LPCSTR,
                len,
                dst as LPWSTR,
                dst_len,
            );
            *dst.offset(dst_len as isize) = 0 as WCHAR;
        }
    }
    return dst;
}

