unsafe extern "C" fn load_script(filename: *const i8) -> *mut WCHAR {
    let mut handle: HANDLE = core::ptr::null_mut();
    let mut size: DWORD = 0;
    let mut bytes_read: DWORD = 0;
    let mut buffer: *mut i8 = core::ptr::null_mut();
    let mut len: i32 = 0;
    let mut script: *mut WCHAR = core::ptr::null_mut();

    handle = CreateFileA(filename, GENERIC_READ, FILE_SHARE_READ, core::ptr::null_mut(), OPEN_EXISTING, 0, core::ptr::null_mut());
    if handle == INVALID_HANDLE_VALUE {
        return core::ptr::null_mut();
    }

    size = GetFileSize(handle, core::ptr::null_mut());
    'done: {
        buffer = malloc(size as usize) as *mut i8;
        if buffer.is_null() {
            break 'done;
        }
        if ReadFile(handle, buffer as *mut core::ffi::c_void, size, core::ptr::addr_of_mut!(bytes_read), core::ptr::null_mut()) == 0 || bytes_read != size {
            break 'done;
        }

        len = MultiByteToWideChar(CP_ACP, 0, buffer as *const i8, size as i32, core::ptr::null_mut(), 0);
        script = malloc(((len + 1) as usize).wrapping_mul(core::mem::size_of::<WCHAR>())) as *mut WCHAR;
        if script.is_null() {
            break 'done;
        }
        MultiByteToWideChar(CP_ACP, 0, buffer as *const i8, size as i32, script, len);
        *script.offset(len as isize) = 0;
    }

    CloseHandle(handle);
    free(buffer as *mut core::ffi::c_void);
    return script;
}
