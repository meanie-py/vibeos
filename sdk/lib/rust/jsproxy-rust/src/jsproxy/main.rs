unsafe extern "C" fn dns_resolve(hostname: *const WCHAR, result: *mut VARIANT) -> HRESULT {
    let mut addr: [WCHAR; 16] = [0; 16];
    let mut ai: *mut addrinfo = core::ptr::null_mut();
    let mut elem: *mut addrinfo = core::ptr::null_mut();
    let mut hostnameA: *mut c_char = core::ptr::null_mut();
    let mut res: c_int = 0;

    if *hostname.offset(0 as isize) != 0 {
        hostnameA = strdupWA(hostname);
    } else {
        hostnameA = get_computer_name(ComputerNamePhysicalDnsFullyQualified);
    }

    if hostnameA.is_null() {
        return E_OUTOFMEMORY;
    }
    res = getaddrinfo(
        hostnameA as PCSTR,
        core::ptr::null(),
        core::ptr::null(),
        core::ptr::addr_of_mut!(ai),
    );
    free(hostnameA as *mut c_void);
    if res != 0 {
        return S_FALSE;
    }

    elem = ai;
    while !elem.is_null() && (*elem).ai_family != (AF_INET as i32) {
        elem = (*elem).ai_next;
    }
    if elem.is_null() {
        freeaddrinfo(ai);
        return S_FALSE;
    }
    printf_addr(
        RUSTCONV_WSTR_03971BB4A692.as_ptr(),
        addr.as_mut_ptr(),
        (ARRAY_SIZE!(addr)) as SIZE_T,
        (*elem).ai_addr as *mut sockaddr_in,
    );
    freeaddrinfo(ai);
    V_VT!(result) = VT_BSTR as VARTYPE;
    V_BSTR!(result) = SysAllocString(addr.as_mut_ptr());
    return S_OK;
}

