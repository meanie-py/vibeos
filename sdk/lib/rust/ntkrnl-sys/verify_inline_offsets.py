#!/usr/bin/env python3
"""Verify that Rust inline function field access paths match C struct offsets.

Cross-compiles offsetof() expressions for critical kernel struct fields via
clang → LLVM IR, then generates Rust compile-time assertions that the
bindgen __bindgen_anon_N paths produce the same offsets.

Usage:
    python3 verify_inline_offsets.py          # Generate + check
    python3 verify_inline_offsets.py --check  # Only check (no file write)
"""

import re
import subprocess
import sys
import tempfile
from pathlib import Path

SCRIPT_DIR = Path(__file__).parent
SRC_DIR = SCRIPT_DIR / "src"
REACTOS = (SCRIPT_DIR / "../../../..").resolve()

# Try macOS toolchain first, then Linux
TOOLCHAIN_MACOS = REACTOS.parent / "llvm-mingw-20250114-ucrt-macos-universal"
TOOLCHAIN_LINUX = REACTOS.parent / "llvm-mingw"
TOOLCHAIN_LINUX_FULL = REACTOS.parent / "llvm-mingw-20250114-ucrt-ubuntu-20.04-x86_64"

if TOOLCHAIN_MACOS.exists():
    TOOLCHAIN = TOOLCHAIN_MACOS
elif TOOLCHAIN_LINUX.exists():
    TOOLCHAIN = TOOLCHAIN_LINUX
elif TOOLCHAIN_LINUX_FULL.exists():
    TOOLCHAIN = TOOLCHAIN_LINUX_FULL
else:
    raise RuntimeError("Cannot find llvm-mingw toolchain")

ARCHS = [
    {
        "name": "arm64",
        "clang_target": "aarch64-pc-windows-gnu",
        "defs": ["-D_WIN64", "-D_M_ARM64", "-D__aarch64__", "-D__arm64__", "-D_ARM64_"],
        "rust_target_arch": "aarch64",
    },
    {
        "name": "amd64",
        "clang_target": "x86_64-pc-windows-gnu",
        "defs": ["-D_WIN64", "-D_M_AMD64", "-D__x86_64__", "-D_AMD64_", "-mxsave"],
        "rust_target_arch": "x86_64",
    },
    {
        "name": "i386",
        "clang_target": "i686-pc-windows-gnu",
        "defs": ["-D_M_IX86", "-D__i386__", "-D_X86_"],
        "rust_target_arch": "x86",
    },
]

# Fields we want to verify offsets for.
# (c_type, c_field, description)
FIELDS = [
    # KPCR fields
    ("KPCR", "Prcb", "KPCR.Prcb (i386 only — pointer to PRCB)"),
    ("KPCR", "CurrentPrcb", "KPCR.CurrentPrcb (amd64/arm64)"),

    # KTHREAD APC disable fields
    ("KTHREAD", "KernelApcDisable", "KTHREAD.KernelApcDisable"),
    ("KTHREAD", "SpecialApcDisable", "KTHREAD.SpecialApcDisable"),
    ("KTHREAD", "CombinedApcDisable", "KTHREAD.CombinedApcDisable"),

    # KTHREAD APC state
    ("KTHREAD", "ApcState", "KTHREAD.ApcState"),

    # KPRCB CurrentThread
    ("KPRCB", "CurrentThread", "KPRCB.CurrentThread"),

    # OBJECT_HEADER fields used by OB inline functions
    ("OBJECT_HEADER", "Type", "OBJECT_HEADER.Type"),

    # OBJECT_TYPE fields
    ("OBJECT_TYPE", "Mutex", "OBJECT_TYPE.Mutex"),

    # OBJECT_DIRECTORY Lock field
    ("OBJECT_DIRECTORY", "Lock", "OBJECT_DIRECTORY.Lock"),

    # EX_FAST_REF — Value is an anonymous union member, accessed via transmute
    # not through bindgen field paths, so no offset check needed.
]


def get_include_flags(arch_name: str) -> list[str]:
    """Return clang include flags matching generate_bindings.sh."""
    build_dir = REACTOS.parent / f"build-{arch_name}"
    return [
        '-I', str(build_dir / "ntoskrnl"),
        '-I', str(REACTOS / "ntoskrnl"),
        '-I', str(REACTOS / "sdk/include"),
        '-I', str(REACTOS / "sdk/include/ddk"),
        '-I', str(REACTOS / "sdk/include/ndk"),
        '-I', str(REACTOS / "sdk/include/psdk"),
        '-I', str(REACTOS / "sdk/include/xdk"),
        '-I', str(REACTOS / "sdk/include/reactos"),
        '-I', str(REACTOS / "sdk/include/reactos/libs"),
        '-I', str(REACTOS / "sdk/include/reactos/drivers"),
        '-I', str(REACTOS / "sdk/include/vcruntime"),
        '-I', str(REACTOS / "sdk/include/winrt"),
        '-I', str(REACTOS / "sdk/lib/pseh/include"),
        '-I', str(REACTOS),
        '-I', str(REACTOS / "sdk/lib/drivers/arbiter"),
        '-I', str(REACTOS / "sdk/lib/cmlib"),
        '-I', str(REACTOS / "ntoskrnl/include"),
        '-I', str(build_dir / "ntoskrnl/include"),
        '-I', str(build_dir / "ntoskrnl/include/internal"),
        '-I', str(build_dir / "sdk/include"),
        '-I', str(build_dir / "sdk/include/psdk"),
        '-I', str(build_dir / "sdk/include/ddk"),
        '-I', str(build_dir / "sdk/include/dxsdk"),
        '-I', str(build_dir / "sdk/include/reactos"),
        '-I', str(build_dir / "sdk/include/reactos/mc"),
        '-I', str(REACTOS / "sdk/include/dxsdk"),
        '-isystem', str(REACTOS / "sdk/include/crt"),
        '-isystem', str(TOOLCHAIN / "lib/clang/19/include"),
    ]


def generate_c_source() -> str:
    """Generate C source with offsetof() for each field."""
    lines = [
        '/* Auto-generated by verify_inline_offsets.py */',
        '#include <stddef.h>',
        '#define _NTOSKRNL_',
        '#define _NTSYSTEM_',
        '#define _USE_DUMMY_PSEH 1',
        '#define __REACTOS__',
        '#define _INTRIN_H_',
        '#define _INTRIN_X86_H_',
        '#ifndef __int64',
        '#define __int64 long long',
        '#endif',
        '#undef FORCEINLINE',
        '#define FORCEINLINE',
        '#include <ntoskrnl.h>',
        '#include "mm/ARM3/miarm.h"',
        '',
    ]
    for i, (c_type, c_field, desc) in enumerate(FIELDS):
        lines.append(
            f'volatile unsigned int off_{i} = offsetof({c_type}, {c_field}); /* {desc} */'
        )
    lines.append('')
    return '\n'.join(lines)


def compile_and_extract(arch: dict, tmpdir: Path) -> dict[int, int]:
    """Compile C to LLVM IR and extract offsetof values."""
    clang = TOOLCHAIN / "bin" / "clang"
    c_source = generate_c_source()
    c_path = tmpdir / f"offsets_{arch['name']}.c"
    ll_path = tmpdir / f"offsets_{arch['name']}.ll"

    c_path.write_text(c_source)

    cmd = [
        str(clang), '-emit-llvm', '-S', '-O0',
        '-std=gnu89',
        '-target', arch["clang_target"],
        *arch["defs"],
        '-DDBG=1', '-DWINVER=0x502', '-D_WIN32_WINNT=0x502',
        *get_include_flags(arch["name"]),
        '-ferror-limit=0', '-Wno-everything',
        str(c_path),
        '-o', str(ll_path),
    ]

    result = subprocess.run(cmd, capture_output=True, text=True)

    if result.returncode != 0:
        # Some fields may not exist on all arches (e.g. KPCR.Prcb is i386 only).
        # Retry with failing lines removed.
        error_lines: set[int] = set()
        for line in result.stderr.split('\n'):
            m = re.search(rf'{re.escape(c_path.name)}:(\d+):\d+: error:', line)
            if m:
                error_lines.add(int(m.group(1)))

        if error_lines:
            source_lines = c_path.read_text().split('\n')
            removed = []
            for line_num in sorted(error_lines, reverse=True):
                idx = line_num - 1
                if 0 <= idx < len(source_lines):
                    m2 = re.search(r'/\* (.+?) \*/', source_lines[idx])
                    if m2:
                        removed.append(m2.group(1))
                    source_lines[idx] = ''
            if removed:
                print(f"  {arch['name']}: skipped {', '.join(removed)}")
            c_path.write_text('\n'.join(source_lines))
            result = subprocess.run(cmd, capture_output=True, text=True)

    if result.returncode != 0:
        print(f"  ERROR: compilation failed for {arch['name']}")
        for line in result.stderr.split('\n')[:5]:
            print(f"    {line}")
        return {}

    ir = ll_path.read_text()
    offsets = {}
    for m in re.finditer(r'@off_(\d+)\s*=\s*.*?\bi32\s+(\d+)', ir):
        offsets[int(m.group(1))] = int(m.group(2))
    return offsets


def main():
    check_only = '--check' in sys.argv

    print("Extracting C struct field offsets via clang → LLVM IR...")

    with tempfile.TemporaryDirectory() as tmpdir:
        tmpdir = Path(tmpdir)
        all_offsets: dict[str, dict[int, int]] = {}

        for arch in ARCHS:
            offsets = compile_and_extract(arch, tmpdir)
            all_offsets[arch['name']] = offsets
            print(f"  {arch['name']}: {len(offsets)} offsets extracted")

    # Print offset table
    print("\nField offsets (C):")
    print(f"  {'Field':<45} {'i386':>6} {'amd64':>6} {'arm64':>6}")
    print(f"  {'-'*45} {'-'*6} {'-'*6} {'-'*6}")

    for i, (c_type, c_field, desc) in enumerate(FIELDS):
        i386_off = all_offsets.get('i386', {}).get(i, None)
        amd64_off = all_offsets.get('amd64', {}).get(i, None)
        arm64_off = all_offsets.get('arm64', {}).get(i, None)

        i386_s = str(i386_off) if i386_off is not None else '-'
        amd64_s = str(amd64_off) if amd64_off is not None else '-'
        arm64_s = str(arm64_off) if arm64_off is not None else '-'

        print(f"  {desc:<45} {i386_s:>6} {amd64_s:>6} {arm64_s:>6}")

    # Generate Rust assertions
    out_path = SRC_DIR / "offset_check_inline.rs"
    lines = [
        '//! Compile-time field offset assertions for inline function access paths.',
        '//!',
        '//! Auto-generated by `verify_inline_offsets.py` — do not edit manually.',
        '//! Verifies that bindgen __bindgen_anon_N paths match C field offsets.',
        '//!',
        '//! Regenerate: `cd sdk/lib/rust/ntkrnl-sys && python3 verify_inline_offsets.py`',
        '',
        '#![allow(dead_code)]',
        '',
        'use core::mem::offset_of;',
        '',
    ]

    count = 0
    for i, (c_type, c_field, desc) in enumerate(FIELDS):
        for arch in ARCHS:
            offset = all_offsets.get(arch['name'], {}).get(i, None)
            if offset is None:
                continue

            rust_type = f"super::ddk::_{c_type}"
            rust_path = get_rust_field_path(c_type, c_field, arch['rust_target_arch'])
            if rust_path is None:
                continue

            lines.append(f'#[cfg(target_arch = "{arch["rust_target_arch"]}")]')
            lines.append(
                f'const _: () = assert!(offset_of!({rust_type}, {rust_path}) == {offset}); '
                f'// {desc}'
            )
            count += 1

    lines.append('')
    content = '\n'.join(lines)

    if check_only:
        if out_path.exists() and out_path.read_text() == content:
            print(f"\n{count} offset assertions up to date.")
        else:
            print(f"\nOffset assertions need regeneration. Run without --check.")
            sys.exit(1)
    else:
        out_path.write_text(content)
        print(f"\nWrote {count} offset assertions to {out_path.relative_to(SCRIPT_DIR)}")


def get_rust_field_path(c_type: str, c_field: str, rust_arch: str) -> str | None:
    """Map (C type, C field, arch) to the Rust bindgen field access path.

    Returns the path used in offset_of!() macro, or None if not applicable.
    """
    if c_type == "KPCR":
        if c_field == "Prcb":
            if rust_arch == "x86":
                return "Prcb"
            return None  # Prcb is i386-only
        if c_field == "CurrentPrcb":
            if rust_arch == "x86":
                return None  # CurrentPrcb is amd64/arm64-only
            return "__bindgen_anon_1.__bindgen_anon_1.CurrentPrcb"

    if c_type == "KTHREAD":
        if c_field == "KernelApcDisable":
            if rust_arch == "x86":
                return "__bindgen_anon_4.__bindgen_anon_1.KernelApcDisable"
            return "__bindgen_anon_5.__bindgen_anon_8.__bindgen_anon_1.__bindgen_anon_1.KernelApcDisable"
        if c_field == "SpecialApcDisable":
            if rust_arch == "x86":
                return "__bindgen_anon_4.__bindgen_anon_1.SpecialApcDisable"
            return "__bindgen_anon_5.__bindgen_anon_8.__bindgen_anon_1.__bindgen_anon_1.SpecialApcDisable"
        if c_field == "CombinedApcDisable":
            if rust_arch == "x86":
                return "__bindgen_anon_4.CombinedApcDisable"
            return "__bindgen_anon_5.__bindgen_anon_8.__bindgen_anon_1.CombinedApcDisable"
        if c_field == "ApcState":
            return "__bindgen_anon_1.ApcState"

    if c_type == "KPRCB":
        if c_field == "CurrentThread":
            return "CurrentThread"

    if c_type == "OBJECT_HEADER":
        if c_field == "Type":
            return "Type"

    if c_type == "OBJECT_TYPE":
        if c_field == "Mutex":
            return "Mutex"

    if c_type == "OBJECT_DIRECTORY":
        if c_field == "Lock":
            return "Lock"

    return None


if __name__ == '__main__':
    main()
