//! driver_ddk — standard kernel-mode *driver* DDK surface that the bindgen
//! pass does not emit.
//!
//! bindgen runs over `ntoskrnl.h` (the kernel-internal master header), which
//! does NOT pull the plain-driver headers (`wdm.h`/`ntddk.h` family). So the
//! ordinary constants and FORCEINLINE/macro helpers every kernel-mode *driver*
//! uses — `DO_BUFFERED_IO`, `IRP_MJ_*`, `IoCompleteRequest`, `DbgPrint`, … —
//! are absent from `ntkrnl_sys::ddk`. Before this module each translated
//! driver (arm64input, framebuf, kbdclass, …) hand-wrote its own copy.
//!
//! Everything here is reproduced verbatim from the ReactOS XDK headers
//! (`sdk/include/xdk/iotypes.h`, `rtlfuncs.h`, `ntbasedef.h`,
//! `psdk/ntstatus.h`). Values are header-authoritative; see the citation on
//! each block. A driver crate gets the whole surface with one glob:
//!   `use ntkrnl_sys::driver_ddk::*;`
//!
//! Disjoint from `constants.rs` (so a driver can glob BOTH without an E0659
//! collision): `IRP_MJ_READ` is the lone symbol that already lives in
//! `constants.rs`, so it is intentionally NOT redefined here.

