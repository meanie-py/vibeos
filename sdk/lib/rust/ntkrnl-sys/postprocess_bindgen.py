#!/usr/bin/env python3
"""Post-process bindgen output for ntkrnl-sys.

Takes raw bindgen output and produces a clean Rust module:
- Strips the __BindgenBitfieldUnit boilerplate (we'll include it once in common)
- Removes derive(Debug) from types containing unions (can't derive Debug on unions)
- Adds module-level attributes
- Strips trailing whitespace

When --hal is passed, also adds `#[link(name = "ntoskrnl", kind = "raw-dylib")]`
to extern static blocks that import kernel data exports.  This is needed for
hal-rust because hal.dll links with `--disable-auto-import`, so cross-DLL data
references need explicit dllimport-equivalent decoration (vs functions, which
the import library handles automatically).
"""

import argparse
import re
import sys
from pathlib import Path


def load_kernel_data_exports() -> set[str]:
    """Parse ntoskrnl/ntoskrnl.spec for `@ extern Name` lines.

    Returns the set of data symbols exported by ntoskrnl.exe — i.e. the
    statics that other DLLs (hal.dll, win32k.sys, drivers) must import
    via cross-DLL data refs.
    """
    spec = Path(__file__).resolve().parent.parent.parent.parent.parent / "ntoskrnl" / "ntoskrnl.spec"
    if not spec.exists():
        print(f"WARNING: ntoskrnl.spec not found at {spec}; raw-dylib wrap will be a no-op", file=sys.stderr)
        return set()
    names = set()
    for line in spec.read_text().splitlines():
        # Match `@ extern Name` and `@ extern -arch=... Name` forms.
        m = re.match(r'@\s+extern\s+(?:-arch=\S+\s+)?(\w+)', line.strip())
        if m:
            names.add(m.group(1))
    return names


def wrap_kernel_data_imports(content: str, kernel_data: set[str]) -> tuple[str, int]:
    """Add `#[link(name = "ntoskrnl", kind = "raw-dylib")]` to extern blocks
    that declare a static whose name is in `kernel_data`.

    Bindgen emits one declaration per `unsafe extern "C" { ... }` block, so
    matching is straightforward.

    Returns (new_content, num_wrapped).
    """
    pattern = re.compile(
        r'(unsafe extern "C" \{\s*pub static (?:mut )?(\w+):[^}]*\})',
        re.MULTILINE,
    )
    wrapped = 0

    def replace(match: re.Match) -> str:
        nonlocal wrapped
        block = match.group(1)
        name = match.group(2)
        if name in kernel_data:
            wrapped += 1
            return '#[link(name = "ntoskrnl.exe", kind = "raw-dylib", modifiers = "+verbatim")]\n' + block
        return block

    return pattern.sub(replace, content), wrapped


def extract_bitfield_unit(content: str) -> tuple[str, str]:
    """Extract __BindgenBitfieldUnit definition and return (unit_code, rest)."""
    pattern = r'(#\[repr\(C\)\]\n#\[derive\([^)]*\)\]\npub struct __BindgenBitfieldUnit.*?)(?=\n#\[repr|\npub type|\npub const|\nunsafe extern)'
    match = re.search(pattern, content, re.DOTALL)
    if match:
        unit_code = match.group(1)
        rest = content[:match.start()] + content[match.end():]
        return unit_code, rest
    return "", content


def extract_bindgen_flex_array(content: str) -> tuple[str, str]:
    """Extract __BindgenUnionField / __IncompleteArrayField definitions."""
    parts_to_remove = []
    for name in ['__BindgenUnionField', '__IncompleteArrayField']:
        pattern = rf'(#\[repr\(transparent\)\]\npub struct {name}.*?)(?=\n#\[repr|\npub type|\npub const|\nunsafe extern)'
        match = re.search(pattern, content, re.DOTALL)
        if match:
            parts_to_remove.append((match.start(), match.end(), match.group(1)))

    extracted = []
    for start, end, code in sorted(parts_to_remove, reverse=True):
        extracted.append(code)
        content = content[:start] + content[end:]

    return "\n".join(reversed(extracted)), content


def strip_auto_header(content: str) -> str:
    """Remove the 'automatically generated by rust-bindgen' comment."""
    return re.sub(r'/\* automatically generated by rust-bindgen.*?\*/\n*', '', content)


def add_module_header(content: str, arch: str, for_hal: bool) -> str:
    """Add module-level attributes and documentation."""
    flavor = "HAL+ACPI" if for_hal else "DDK"
    header = f"""//! Auto-generated {flavor} bindings for {arch}.
//!
//! Generated by `bindgen` from ReactOS `ntddk.h` headers.
//! Do not edit manually — regenerate with `postprocess_bindgen.py`.

#![allow(dead_code)]

"""
    return header + content


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input", help="raw bindgen output (.rs)")
    ap.add_argument("arch", help="target arch: arm64 | amd64 | i386")
    ap.add_argument("output", nargs="?", help="output path (.rs)")
    ap.add_argument(
        "--hal",
        action="store_true",
        help="wrap kernel-data-export extern statics with raw-dylib decoration "
             "(required for hal-rust because hal.dll is a separate binary from "
             "ntoskrnl.exe and the link is --disable-auto-import)",
    )
    args = ap.parse_args()

    input_path = Path(args.input)
    arch = args.arch
    output_path = Path(args.output) if args.output else None

    content = input_path.read_text()

    # Strip the auto-generated header comment
    content = strip_auto_header(content)

    # Extract __BindgenBitfieldUnit — we'll put it in a shared module
    bitfield_unit, content = extract_bitfield_unit(content)

    # Extract __BindgenUnionField / __IncompleteArrayField
    flex_arrays, content = extract_bindgen_flex_array(content)

    # HAL output needs raw-dylib decoration on kernel-data extern statics.
    n_wrapped = 0
    if args.hal:
        kernel_data = load_kernel_data_exports()
        content, n_wrapped = wrap_kernel_data_imports(content, kernel_data)

    # Save the shared helpers separately
    shared_dir = output_path.parent if output_path else Path(".")
    shared_path = shared_dir / "bindgen_common.rs"
    if bitfield_unit or flex_arrays:
        shared_content = """//! Shared bindgen helper types.
//!
//! These are generated by bindgen and shared across all architecture modules.
//! Do not edit manually.

#![allow(dead_code)]

"""
        if bitfield_unit:
            shared_content += bitfield_unit + "\n\n"
        if flex_arrays:
            shared_content += flex_arrays + "\n"
        # Only write if it doesn't exist or is different
        if not shared_path.exists() or shared_path.read_text() != shared_content:
            shared_path.write_text(shared_content)
            print(f"  Wrote shared helpers: {shared_path} ({len(shared_content)} bytes)")

    # Add use for the shared helpers
    content = "use super::bindgen_common::*;\n\n" + content

    # Add module header
    content = add_module_header(content, arch, args.hal)

    # Strip trailing whitespace on each line
    content = "\n".join(line.rstrip() for line in content.split("\n"))

    # Remove excessive blank lines (3+ in a row → 2)
    content = re.sub(r'\n{4,}', '\n\n\n', content)

    if output_path:
        output_path.write_text(content)
        # Count stats
        funcs = len(re.findall(r'pub fn [A-Z]', content))
        structs = len(re.findall(r'pub struct ', content))
        types = len(re.findall(r'pub type ', content))
        consts = len(re.findall(r'pub const ', content))
        suffix = f", {n_wrapped} kernel-data raw-dylib wraps" if args.hal else ""
        print(f"  {arch}: {len(content.splitlines())} lines, {funcs} functions, {structs} structs, {types} types, {consts} constants{suffix}")
    else:
        sys.stdout.write(content)


if __name__ == "__main__":
    main()
