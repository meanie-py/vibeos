def extract_hand_written_types() -> list[tuple[str, str, str]]:
    """Return (rust_name, c_sizeof_expr, rust_module) for hand-written FFI structs.

    These structs live in hand-written modules (mm, ke, base, ex) and are NOT
    in bindgen output. Their C sizeof expression uses the C typedef name.
    """
    return [
        # mm module
        ("POOL_HEADER", "POOL_HEADER", "mm"),
        ("POOL_DESCRIPTOR", "POOL_DESCRIPTOR", "mm"),
        ("POOL_TRACKER_TABLE", "POOL_TRACKER_TABLE", "mm"),
        ("POOL_TRACKER_BIG_PAGES", "POOL_TRACKER_BIG_PAGES", "mm"),
        ("MMFREE_POOL_ENTRY", "MMFREE_POOL_ENTRY", "mm"),
        ("MM_PAGED_POOL_INFO", "MM_PAGED_POOL_INFO", "mm"),
        ("RTL_BITMAP", "RTL_BITMAP", "mm"),
        ("MMPTE", "MMPTE", "mm"),
        ("MMPFN", "MMPFN", "mm"),
        # ke module
        ("KGUARDED_MUTEX", "KGUARDED_MUTEX", "ke"),
        ("KDPC", "KDPC", "ke"),
        ("KLOCK_QUEUE_HANDLE", "KLOCK_QUEUE_HANDLE", "ke"),
        ("PP_LOOKASIDE_LIST", "PP_LOOKASIDE_LIST", "ke"),
        ("GENERAL_LOOKASIDE", "GENERAL_LOOKASIDE", "ke"),
        # base module
        ("LIST_ENTRY", "LIST_ENTRY", "base"),
        ("SINGLE_LIST_ENTRY", "SINGLE_LIST_ENTRY", "base"),
        ("SLIST_HEADER", "SLIST_HEADER", "base"),
        ("UNICODE_STRING", "UNICODE_STRING", "base"),
        # ex module
        ("SYSTEM_POOLTAG", "SYSTEM_POOLTAG", "ex"),
    ]


def extract_types(rs_path: Path) -> list[tuple[str, str]]:
    """Extract (rust_struct_name, c_sizeof_expression) pairs from bindgen output.

    For each `pub struct _FOO`, finds the typedef alias (e.g., `FOO`) from
    `pub type FOO = _FOO;` lines. Uses the typedef name in C sizeof() since
    it works regardless of struct/union/enum.
    """
    content = rs_path.read_text()

    # Collect pub struct names (skip bindgen helpers and anonymous sub-types)
    # Also skip types known to have bindgen layout mismatches
    SKIP_TYPES = {
        '_GENERAL_LOOKASIDE_POOL',  # Complex union, bindgen disagrees with C
        '_LONGDOUBLE',              # x87 long double, platform-specific padding
    }
    structs = set()
    for m in re.finditer(r'^pub struct (\w+)', content, re.MULTILINE):
        name = m.group(1)
        if name.startswith('__Bindgen') or name.startswith('__Incomplete'):
            continue
        if '__bindgen_ty_' in name:
            continue
        if name in SKIP_TYPES:
            continue
        structs.add(name)

    # Map struct names to their shortest non-pointer typedef alias
    struct_to_alias: dict[str, str] = {}
    for m in re.finditer(r'^pub type (\w+)\s*=\s*(\w+)\s*;', content, re.MULTILINE):
        alias, target = m.group(1), m.group(2)
        if target not in structs:
            continue
        # Skip pointer typedefs (PFOO, LPFOO)
        if f'pub type {alias} = *' in content:
            continue
        if target not in struct_to_alias or len(alias) < len(struct_to_alias[target]):
            struct_to_alias[target] = alias

    result = []
    for name in sorted(structs):
        c_expr = struct_to_alias.get(name, name)
        result.append((name, c_expr))
    return result


def generate_c_source(types: list[tuple[str, str]]) -> str:
    """Generate C source with sizeof() for each type."""
    lines = [
        '/* Auto-generated by verify_sizes.py */',
        '#define _NTOSKRNL_',
        '#define _NTSYSTEM_',
        '#define _USE_DUMMY_PSEH 1',
        '#define __REACTOS__',
        '#define _INTRIN_H_',
        '#define _INTRIN_X86_H_',
        '#ifndef __int64',
        '#define __int64 long long',
        '#endif',
        # NOT the bindgen wrapper's __wfi()/__yield() stubs. Those exist because
        # libclang cannot handle the intrinsics' inline-asm bodies; a real clang can.
        # Worse, they BREAK arm64 here: a zero-arg function-like __yield() turns
        # intrin_arm64.h's `void __yield(void)` declaration into a one-argument macro
        # invocation ("too many arguments provided to function-like macro invocation"),
        # and since the error is in a header, the retry loop that blanks offending type
        # lines can never clear it — arm64 silently produced no assertions at all.
        '#undef FORCEINLINE',
        '#define FORCEINLINE',
        '/* Full ntoskrnl master header (DDK + NDK + internal) */',
        '#include <ntoskrnl.h>',
        '/* ARM3 memory manager internals */',
        '#include "mm/ARM3/miarm.h"',
        '',
    ]
    for i, (rust_name, c_expr) in enumerate(types):
        lines.append(f'volatile unsigned int size_{i} = sizeof({c_expr}); /* {rust_name} */')
    lines.append('')
    return '\n'.join(lines)


