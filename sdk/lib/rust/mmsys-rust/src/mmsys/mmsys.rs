pub unsafe extern "C" fn InitPropSheetPage(psp: *mut PROPSHEETPAGEW, idDlg: WORD, DlgProc: DLGPROC) {
    ZeroMemory!(psp as *mut core::ffi::c_void, core::mem::size_of::<PROPSHEETPAGEW>());
    (*psp).dwSize = core::mem::size_of::<PROPSHEETPAGEW>() as DWORD;
    (*psp).dwFlags = PSP_DEFAULT as DWORD;
    (*psp).hInstance = hApplet;
    (*psp).__bindgen_anon_1.pszTemplate = MAKEINTRESOURCEW!(idDlg) as LPCWSTR;
    (*psp).pfnDlgProc = DlgProc;
}

#[no_mangle]
pub unsafe extern "system" fn CPlApplet(
    hwndCpl: HWND,
    uMsg: UINT,
    lParam1: LPARAM,
    lParam2: LPARAM,
) -> LONG {
    let i: UINT = lParam1 as UINT;

    match uMsg {
        CPL_INIT => {
            return TRUE as LONG;
        }

        CPL_GETCOUNT => {
            return NUM_APPLETS as LONG;
        }

        CPL_INQUIRE => {
            if i < NUM_APPLETS as UINT {
                let CPlInfo: *mut CPLINFO = lParam2 as *mut CPLINFO;
                (*CPlInfo).lData = 0 as LONG_PTR;
                (*CPlInfo).idIcon = Applets[i as usize].idIcon as ::core::ffi::c_int;
                (*CPlInfo).idName = Applets[i as usize].idName as ::core::ffi::c_int;
                (*CPlInfo).idInfo = Applets[i as usize].idDescription as ::core::ffi::c_int;
            } else {
                return TRUE as LONG;
            }
        }

        CPL_DBLCLK => {
            if i < NUM_APPLETS as UINT {
                Applets[i as usize]
                    .AppletProc
                    .unwrap_unchecked()(
                    hwndCpl, uMsg, lParam1, lParam2
                );
            } else {
                return TRUE as LONG;
            }
        }

        CPL_STARTWPARMSW => {
            if i < NUM_APPLETS as UINT {
                return Applets[i as usize]
                    .AppletProc
                    .unwrap_unchecked()(
                    hwndCpl, uMsg, lParam1, lParam2
                );
            }
        }

        _ => {}
    }

    return FALSE as LONG;
}

