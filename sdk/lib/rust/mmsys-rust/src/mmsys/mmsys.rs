#[no_mangle]
pub unsafe extern "C" fn IsSoftwareBusPnpEnumeratorInstalled() -> BOOL {
    let mut hDevInfo: HDEVINFO = core::ptr::null_mut();
    let mut DeviceInterfaceData: SP_DEVICE_INTERFACE_DATA = core::mem::zeroed();
    let mut SWBusGuid: GUID = GUID {
        Data1: 0x4747b320,
        Data2: 0x62ce,
        Data3: 0x11cf,
        Data4: [0xa5, 0xd6, 0x28, 0xdb, 0x04, 0xc1, 0x00, 0x00],
    };
    let mut DeviceInterfaceDetailData: PSP_DEVICE_INTERFACE_DETAIL_DATA_W = core::ptr::null_mut();

    hDevInfo = SetupDiGetClassDevsW(
        &raw mut SWBusGuid,
        core::ptr::null::<WCHAR>(),
        core::ptr::null_mut::<HWND__>(),
        (DIGCF_DEVICEINTERFACE | DIGCF_PRESENT) as DWORD,
    );
    if hDevInfo.is_null() {
        // failed
        return (FALSE) as BOOL;
    }

    DeviceInterfaceData.cbSize = core::mem::size_of::<SP_DEVICE_INTERFACE_DATA>() as DWORD;
    if SetupDiEnumDeviceInterfaces(
        hDevInfo,
        core::ptr::null_mut::<_SP_DEVINFO_DATA>(),
        &raw mut SWBusGuid,
        0,
        &raw mut DeviceInterfaceData,
    ) == 0
    {
        // failed
        SetupDiDestroyDeviceInfoList(hDevInfo);
        return (FALSE) as BOOL;
    }

    DeviceInterfaceDetailData = HeapAlloc(
        GetProcessHeap(),
        0,
        ((MAX_PATH as usize) * core::mem::size_of::<WCHAR>()
            + core::mem::size_of::<SP_DEVICE_INTERFACE_DETAIL_DATA_W>()) as SIZE_T,
    ) as PSP_DEVICE_INTERFACE_DETAIL_DATA_W;
    if DeviceInterfaceDetailData.is_null() {
        // failed
        SetupDiDestroyDeviceInfoList(hDevInfo);
        return (FALSE) as BOOL;
    }

    (*DeviceInterfaceDetailData).cbSize =
        core::mem::size_of::<SP_DEVICE_INTERFACE_DETAIL_DATA_W>() as DWORD;
    if SetupDiGetDeviceInterfaceDetailW(
        hDevInfo,
        &raw mut DeviceInterfaceData,
        DeviceInterfaceDetailData,
        ((MAX_PATH as usize) * core::mem::size_of::<WCHAR>()
            + core::mem::size_of::<SP_DEVICE_INTERFACE_DETAIL_DATA_W>()) as DWORD,
        core::ptr::null_mut::<DWORD>(),
        core::ptr::null_mut::<_SP_DEVINFO_DATA>(),
    ) == 0
    {
        // failed
        HeapFree(
            GetProcessHeap(),
            0,
            DeviceInterfaceDetailData as PVOID,
        );
        SetupDiDestroyDeviceInfoList(hDevInfo);
        return (FALSE) as BOOL;
    }
    HeapFree(
        GetProcessHeap(),
        0,
        DeviceInterfaceDetailData as PVOID,
    );
    SetupDiDestroyDeviceInfoList(hDevInfo);
    return (TRUE) as BOOL;
}
#[no_mangle]
pub unsafe extern "C" fn InstallSoftwareBusPnpEnumerator(InfPath: LPCWSTR, HardwareIdList: LPCWSTR) -> DWORD {
    let mut DeviceInfoSet: HDEVINFO = INVALID_HANDLE_VALUE;
    let mut DeviceInfoData: SP_DEVINFO_DATA = core::mem::zeroed();
    let mut ClassGUID: GUID = core::mem::zeroed();
    let mut ClassName: [WCHAR; 50] = [0; 50];
    let mut Result: ::core::ffi::c_int = 0 as ::core::ffi::c_int;
    let mut hModule: HMODULE = core::ptr::null_mut();
    let mut UpdateProc: Option<UpdateDriverForPlugAndPlayDevicesProto> = None;
    let mut reboot: BOOL = FALSE as BOOL;
    let mut flags: DWORD = 0 as DWORD;

    if SetupDiGetINFClassW(
        InfPath as PCWSTR,
        core::ptr::addr_of_mut!(ClassGUID),
        core::ptr::addr_of_mut!(ClassName) as PWSTR,
        (core::mem::size_of::<[WCHAR; 50]>() / core::mem::size_of::<WCHAR>()) as DWORD,
        core::ptr::null_mut(),
    ) == 0
    {
        return -(1 as ::core::ffi::c_int) as DWORD;
    }

    DeviceInfoSet = SetupDiCreateDeviceInfoList(core::ptr::addr_of_mut!(ClassGUID), core::ptr::null_mut());
    if DeviceInfoSet == INVALID_HANDLE_VALUE {
        return -(1 as ::core::ffi::c_int) as DWORD;
    }

    DeviceInfoData.cbSize = core::mem::size_of::<SP_DEVINFO_DATA>() as DWORD;
    if SetupDiCreateDeviceInfoW(
        DeviceInfoSet,
        core::ptr::addr_of_mut!(ClassName) as *mut WCHAR as PCWSTR,
        core::ptr::addr_of_mut!(ClassGUID),
        core::ptr::null(),
        core::ptr::null_mut(),
        DICD_GENERATE_ID as DWORD,
        core::ptr::addr_of_mut!(DeviceInfoData),
    ) == 0
    {
        SetupDiDestroyDeviceInfoList(DeviceInfoSet);
        return -(1 as ::core::ffi::c_int) as DWORD;
    }

    if SetupDiSetDeviceRegistryPropertyW(
        DeviceInfoSet,
        core::ptr::addr_of_mut!(DeviceInfoData),
        SPDRP_HARDWAREID as DWORD,
        HardwareIdList as LPBYTE as *const BYTE,
        ((wcslen(HardwareIdList) as usize)
            .wrapping_add(1 as usize)
            .wrapping_add(1 as usize))
            .wrapping_mul(core::mem::size_of::<WCHAR>()) as DWORD,
    ) == 0
    {
        SetupDiDestroyDeviceInfoList(DeviceInfoSet);
        return -(1 as ::core::ffi::c_int) as DWORD;
    }

    if SetupDiCallClassInstaller(
        DIF_REGISTERDEVICE as DI_FUNCTION,
        DeviceInfoSet,
        core::ptr::addr_of_mut!(DeviceInfoData),
    ) == 0
    {
        SetupDiDestroyDeviceInfoList(DeviceInfoSet);
        return -(1 as ::core::ffi::c_int) as DWORD;
    }

    if GetFileAttributesW(InfPath) == INVALID_FILE_ATTRIBUTES as DWORD {
        SetupDiDestroyDeviceInfoList(DeviceInfoSet);
        return -(1 as ::core::ffi::c_int) as DWORD;
    }

    flags |= INSTALLFLAG_FORCE as DWORD;
    hModule = LoadLibraryW(RUSTCONV_WSTR_0C41A9A8F095.as_ptr()) as HMODULE;
    if hModule.is_null() {
        SetupDiDestroyDeviceInfoList(DeviceInfoSet);
        return -(1 as ::core::ffi::c_int) as DWORD;
    }

    UpdateProc = core::mem::transmute::<FARPROC, Option<UpdateDriverForPlugAndPlayDevicesProto>>(
        GetProcAddress(hModule as HINSTANCE, (UPDATEDRIVERFORPLUGANDPLAYDEVICES).as_ptr() as LPCSTR),
    );
    if UpdateProc.is_none() {
        SetupDiDestroyDeviceInfoList(DeviceInfoSet);
        FreeLibrary(hModule);
        return -(1 as ::core::ffi::c_int) as DWORD;
    }
    let UpdateProc = UpdateProc.unwrap_unchecked();

    if UpdateProc(
        core::ptr::null_mut(),
        HardwareIdList,
        InfPath,
        flags,
        core::ptr::addr_of_mut!(reboot),
    ) == 0
    {
        SetupDiDestroyDeviceInfoList(DeviceInfoSet);
        FreeLibrary(hModule);
        return -(1 as ::core::ffi::c_int) as DWORD;
    }

    FreeLibrary(hModule);
    SetupDiDestroyDeviceInfoList(DeviceInfoSet);
    return Result as DWORD;
}
#[no_mangle]
pub unsafe extern "C" fn MMSYS_InstallDevice(hDevInfo: HDEVINFO, pspDevInfoData: PSP_DEVINFO_DATA) -> DWORD {
    let mut Length: UINT = 0;
    let mut szBuffer: [WCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
    let mut hInf: HINF = core::ptr::null_mut();
    let mut Context: PVOID = core::ptr::null_mut();
    let mut Result: BOOL = 0;
    let mut hSCManager: SC_HANDLE = core::ptr::null_mut();
    let mut hService: SC_HANDLE = core::ptr::null_mut();
    let mut WaveName: [WCHAR; 20] = [0; 20];
    let mut hKey: HKEY = core::ptr::null_mut();
    let mut BufferSize: DWORD = 0;
    let mut Index: ULONG = 0;

    if IsEqualIID!(core::ptr::addr_of_mut!((*pspDevInfoData).ClassGuid), core::ptr::addr_of!(GUID_DEVCLASS_SOUND)) == 0
        && IsEqualIID!(core::ptr::addr_of_mut!((*pspDevInfoData).ClassGuid), core::ptr::addr_of!(GUID_DEVCLASS_MEDIA)) == 0
    {
        return ERROR_DI_DO_DEFAULT;
    }

    Length = GetWindowsDirectoryW(szBuffer.as_mut_ptr(), _countof!(szBuffer));
    if Length == 0 || Length >= _countof!(szBuffer) - CONST_STR_LEN!(RUSTCONV_WSTR_5393BD9480C9)
    {
        return ERROR_GEN_FAILURE;
    }

    //PathCchAppend(szBuffer, _countof(szBuffer), L"inf\\audio.inf");
    StringCchCatW(szBuffer.as_mut_ptr(), (_countof!(szBuffer)) as _, RUSTCONV_WSTR_5393BD9480C9.as_ptr());

    hInf = SetupOpenInfFileW(szBuffer.as_mut_ptr(),
                             core::ptr::null_mut(),
                             INF_STYLE_WIN4,
                             core::ptr::null_mut());

    if hInf == INVALID_HANDLE_VALUE
    {
        return ERROR_GEN_FAILURE;
    }

    Context = SetupInitDefaultQueueCallback(core::ptr::null_mut());
    if Context.is_null()
    {
        SetupCloseInfFile(hInf);
        return ERROR_GEN_FAILURE;
    }

    Result = SetupInstallFromInfSectionW(core::ptr::null_mut(),
                                         hInf,
                                         RUSTCONV_WSTR_5F09220CCC0C.as_ptr(),
                                         SPINST_ALL,
                                         core::ptr::null_mut(),
                                         core::ptr::null_mut(),
                                         SP_COPY_NEWER,
                                         Some(SetupDefaultQueueCallbackW),
                                         Context,
                                         core::ptr::null_mut(),
                                         core::ptr::null_mut());

    if Result != 0
    {
        Result = SetupInstallServicesFromInfSectionW(hInf,
                                                     RUSTCONV_WSTR_F132B53C01DE.as_ptr(),
                                                     0);
    }

    SetupTermDefaultQueueCallback(Context);
    SetupCloseInfFile(hInf);

    if IsSoftwareBusPnpEnumeratorInstalled() == 0
    {
        Length = GetWindowsDirectoryW(szBuffer.as_mut_ptr(), _countof!(szBuffer));
        if Length == 0 || Length >= _countof!(szBuffer) - CONST_STR_LEN!(RUSTCONV_WSTR_788D260FEB61)
        {
            return ERROR_GEN_FAILURE;
        }

        //PathCchAppend(szBuffer, _countof(szBuffer), L"inf\\machine.inf");
        StringCchCatW(szBuffer.as_mut_ptr(), (_countof!(szBuffer)) as _, RUSTCONV_WSTR_788D260FEB61.as_ptr());

        InstallSoftwareBusPnpEnumerator(szBuffer.as_mut_ptr(), RUSTCONV_WSTR_BA874B2E5630.as_ptr());
    }

    hSCManager = OpenSCManagerW(core::ptr::null_mut(), core::ptr::null_mut(), SC_MANAGER_CONNECT);
    if hSCManager.is_null()
    {
        return ERROR_DI_DO_DEFAULT;
    }

    hService = OpenServiceW(hSCManager, RUSTCONV_WSTR_DCE29ED1807F.as_ptr(), SERVICE_ALL_ACCESS);
    if !hService.is_null()
    {
        /* Make AudioSrv start automatically */
        ChangeServiceConfigW(hService, SERVICE_NO_CHANGE, SERVICE_AUTO_START, SERVICE_NO_CHANGE, core::ptr::null_mut(), core::ptr::null_mut(), core::ptr::null_mut(), core::ptr::null_mut(), core::ptr::null_mut(), core::ptr::null_mut(), core::ptr::null_mut());

        StartServiceW(hService, 0, core::ptr::null_mut());
        CloseServiceHandle(hService);
    }
    CloseServiceHandle(hSCManager);

    if (RegOpenKeyExW(HKEY_LOCAL_MACHINE, RUSTCONV_WSTR_A08269DA3A04.as_ptr(), 0, KEY_READ | KEY_WRITE, core::ptr::addr_of_mut!(hKey))) as u32 == ERROR_SUCCESS
    {
        Length = GetSystemDirectoryW(szBuffer.as_mut_ptr(), _countof!(szBuffer));
        if Length == 0 || Length >= _countof!(szBuffer) - CONST_STR_LEN!(RUSTCONV_WSTR_953B401E79F1)
        {
            RegCloseKey(hKey);
            return ERROR_DI_DO_DEFAULT;
        }

        //PathCchAppend(szBuffer, _countof(szBuffer), L"wdmaud.drv");
        StringCchCatW(szBuffer.as_mut_ptr(), (_countof!(szBuffer)) as _, RUSTCONV_WSTR_953B401E79F1.as_ptr());

        Index = 1;
        while Index <= 4
        {
            StringCchPrintfW!(WaveName.as_mut_ptr(), _countof!(WaveName), RUSTCONV_WSTR_9A23FDE17071.as_ptr(), Index);
            if (RegQueryValueExW(hKey, WaveName.as_mut_ptr(), core::ptr::null_mut(), core::ptr::null_mut(), core::ptr::null_mut(), core::ptr::addr_of_mut!(BufferSize))) as u32 != ERROR_MORE_DATA
            {
                /* Store new audio driver entry */
                RegSetValueExW(hKey, WaveName.as_mut_ptr(), 0, REG_SZ, szBuffer.as_mut_ptr() as LPBYTE, ((wcslen(szBuffer.as_mut_ptr()) + 1) * core::mem::size_of::<WCHAR>()) as DWORD);
                break;
            }
            else
            {
                let mut Buffer: [WCHAR; (MAX_PATH) as _] = [0; (MAX_PATH) as _];
                BufferSize = core::mem::size_of::<[WCHAR; (MAX_PATH) as _]>() as DWORD;

                if (RegQueryValueExW(hKey, WaveName.as_mut_ptr(), core::ptr::null_mut(), core::ptr::null_mut(), Buffer.as_mut_ptr() as LPBYTE, core::ptr::addr_of_mut!(BufferSize))) as u32 == ERROR_SUCCESS
                {
                    /* Make sure the buffer is zero terminated */
                    Buffer[(_countof!(Buffer) - 1) as usize] = UNICODE_NULL;

                    if _wcsicmp(Buffer.as_mut_ptr(), szBuffer.as_mut_ptr()) == 0
                    {
                        /* An entry already exists */
                        break;
                    }
                }
            }
            Index = Index + 1;
        }
        RegCloseKey(hKey);
    }
    InstallSystemSoundScheme();

    return ERROR_DI_DO_DEFAULT;
}

