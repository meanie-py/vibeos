#[no_mangle]
pub unsafe extern "system" fn DllMain(
    hinstDLL: HINSTANCE,
    dwReason: DWORD,
    lpReserved: LPVOID,
) -> BOOL {
    UNREFERENCED_PARAMETER!(lpReserved);
    match dwReason {
        DLL_PROCESS_ATTACH => {
            hApplet = hinstDLL;
            DisableThreadLibraryCalls(hinstDLL as HMODULE);
        }
        _ => {}
    }

    return (TRUE) as BOOL;
}
