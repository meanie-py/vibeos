/// Controllers numbered in the order they start, for messages and SCSI addresses.
static NEXT_CONTROLLER: AtomicU32 = AtomicU32::new(0);

/// The controller FDO's extension.
#[repr(C)]
struct Fdo {
    kind: u32,
    number: u32,
    device: PDEVICE_OBJECT,
    pdo: PDEVICE_OBJECT,
    lower: PDEVICE_OBJECT,
    /// The MSI-X messages connected (the table to disconnect them by); null on
    /// the pin or when polling.
    messages: PIO_INTERRUPT_MESSAGE_INFO,
    /// Set in START before any disk is published; from then on it is shared
    /// by the namespaces' dispatch routines and the DPCs (nvme.rs locks).
    controller: Option<Controller>,
    /// The interrupt and the completion timer, which reach the controller.
    irq: Irq,
    disks: [PDEVICE_OBJECT; NAMESPACES_PER_CONTROLLER],
    disk_count: usize,
}

/// A namespace PDO's extension.
#[repr(C)]
struct DiskExt {
    kind: u32,
    fdo: *mut Fdo,
    namespace: Namespace,
    disk: Disk,
    claimed: AtomicBool,
}

unsafe fn status_of(irp: PIRP) -> NTSTATUS {
    (*irp).IoStatus.__bindgen_anon_1.Status
}

unsafe fn complete(irp: PIRP, status: NTSTATUS, information: usize) -> NTSTATUS {
    (*irp).IoStatus.__bindgen_anon_1.Status = status;
    (*irp).IoStatus.Information = information as _;
    IoCompleteRequest(irp, 0);
    status
}

unsafe fn pass_down(fdo: &Fdo, irp: PIRP) -> NTSTATUS {
    IoSkipCurrentIrpStackLocation(irp);
    IoCallDriver(fdo.lower, irp)
}

pub unsafe extern "system" fn add_device(driver: PDRIVER_OBJECT, pdo: PDEVICE_OBJECT) -> NTSTATUS {
    let mut device: PDEVICE_OBJECT = null_mut();
    let status = IoCreateDevice(
        driver,
        size_of::<Fdo>() as ULONG,
        null_mut(),
        FILE_DEVICE_CONTROLLER,
        FILE_DEVICE_SECURE_OPEN,
        0,
        &mut device,
    );
    if status < 0 {
        nvprint!("IoCreateDevice (controller) failed {:#010x}\n", status as u32);
        return status;
    }
    let lower = ntkrnl_sys::ddk::IoAttachDeviceToDeviceStack(device, pdo);
    if lower.is_null() {
        ntkrnl_sys::ddk::IoDeleteDevice(device);
        return STATUS_NO_SUCH_DEVICE;
    }
    let fdo = (*device).DeviceExtension as *mut Fdo;
    fdo.write(Fdo {
        kind: FDO_KIND,
        number: u32::MAX,
        device,
        pdo,
        lower,
        messages: null_mut(),
        controller: None,
        irq: Irq::new(),
        disks: [null_mut(); NAMESPACES_PER_CONTROLLER],
        disk_count: 0,
    });
    opt_in_to_msix(pdo);
    (*device).Flags &= !DO_DEVICE_INITIALIZING;
    STATUS_SUCCESS
}

/// A UTF-16 literal without a terminator: UNICODE_STRING lengths exclude it.
macro_rules! utf16 {
    ($s:literal) => {{
        const W: &[u16] = &{
            const B: &[u8] = $s.as_bytes();
            let mut out = [0u16; B.len()];
            let mut i = 0;
            while i < B.len() {
                out[i] = B[i] as u16;
                i += 1;
            }
            out
        };
        W
    }};
}

unsafe fn unicode(s: &[u16]) -> UNICODE_STRING {
    let mut u: UNICODE_STRING = core::mem::zeroed();
    u.Buffer = s.as_ptr() as *mut u16;
    u.Length = (s.len() * 2) as u16;
    u.MaximumLength = u.Length;
    u
}

/// Create (or open) `name` under `parent`.
unsafe fn create_key(parent: HANDLE, name: &[u16]) -> Option<HANDLE> {
    let mut name = unicode(name);
    let mut oa: OBJECT_ATTRIBUTES = core::mem::zeroed();
    oa.Length = size_of::<OBJECT_ATTRIBUTES>() as ULONG;
    oa.RootDirectory = parent;
    oa.ObjectName = &mut name;
    oa.Attributes = OBJ_CASE_INSENSITIVE_KERNEL_HANDLE;
    let mut key: HANDLE = null_mut();
    (ZwCreateKey(&mut key, KEY_ALL_ACCESS, &mut oa, 0, null_mut(), 0, null_mut()) >= 0).then_some(key)
}

unsafe fn set_dword(key: HANDLE, name: &[u16], value: u32) {
    let mut name = unicode(name);
    let mut v = value;
    ZwSetValueKey(key, &mut name, 0, REG_DWORD, (&raw mut v).cast(), 4);
}

/// The messages this driver can use: the admin queue's, and one per CPU for an
/// I/O queue each.
unsafe fn messages_wanted() -> u32 {
    1 + (ntkrnl_sys::ddk::KeQueryActiveProcessors() as u64).count_ones().clamp(1, nvme::MAX_IO_QUEUES as u32)
}

/// A test-rig tripwire token, `<key>=<hex>`, which the kernel publishes as
/// `VibeTripwire` under CurrentControlSet\Control:
/// - `NVME_AFFINITY`: the processors this boot's NVMe messages should go to, as an
///   INF's Affinity Policy would say;
/// - `NVME_LOSE_COMPLETION`: the I/O completion (counted from 1) the engine throws
///   away, so its command hangs and the controller is reset.
unsafe fn tripwire_value(key: &[u16]) -> Option<u64> {
    let mut name = unicode(utf16!("\\Registry\\Machine\\SYSTEM\\CurrentControlSet\\Control"));
    let mut oa: OBJECT_ATTRIBUTES = core::mem::zeroed();
    oa.Length = size_of::<OBJECT_ATTRIBUTES>() as ULONG;
    oa.ObjectName = &mut name;
    oa.Attributes = OBJ_CASE_INSENSITIVE_KERNEL_HANDLE;
    let mut control: HANDLE = null_mut();
    if ZwOpenKey(&mut control, KEY_READ, &mut oa) < 0 {
        return None;
    }
    let mut value = unicode(utf16!("VibeTripwire"));
    // KEY_VALUE_PARTIAL_INFORMATION: TitleIndex, Type, DataLength, then the string.
    let mut buf = [0u32; 3 + 128];
    let mut got: ULONG = 0;
    let status = ZwQueryValueKey(
        control,
        &mut value,
        _KEY_VALUE_INFORMATION_CLASS_KeyValuePartialInformation,
        buf.as_mut_ptr().cast(),
        size_of::<[u32; 3 + 128]>() as ULONG,
        &mut got,
    );
    ZwClose(control);
    if status < 0 || buf[1] != REG_SZ {
        return None;
    }
    let chars = core::slice::from_raw_parts(buf.as_ptr().add(3) as *const u16, (buf[2] as usize / 2).min(256));
    let mut tokens = chars.split(|&c| c == b' ' as u16 || c == b';' as u16 || c == 0);
    let token = tokens.find(|t| t.len() > key.len() && t.starts_with(key) && t[key.len()] == b'=' as u16)?;
    let digits = &token[key.len() + 1..];
    let digits = digits.strip_prefix(utf16!("0x")).unwrap_or(digits);
    digits.iter().try_fold(0u64, |acc, &c| Some(acc << 4 | char::from_u32(c as u32)?.to_digit(16)? as u64)).filter(|&m| m != 0)
}

/// Ask pci.sys for MSI-X the Windows way: `MSISupported` under the device key's
/// Interrupt Management\MessageSignaledInterruptProperties, which an INF's HKR
/// AddReg would write (stornvme's does). Done here because there is no INF; the
/// PnP manager has not assigned resources yet, so pci.sys sees it in time.
unsafe fn opt_in_to_msix(pdo: PDEVICE_OBJECT) {
    let mut device_key: HANDLE = null_mut();
    if IoOpenDeviceRegistryKey(pdo, PLUGPLAY_REGKEY_DEVICE, KEY_ALL_ACCESS, &mut device_key) < 0 {
        nvprint!("could not open the device key; no MSI-X\n");
        return;
    }
    if let Some(management) = create_key(device_key, utf16!("Interrupt Management")) {
        if let Some(props) = create_key(management, utf16!("MessageSignaledInterruptProperties")) {
            set_dword(props, utf16!("MSISupported"), 1);
            set_dword(props, utf16!("MessageNumberLimit"), messages_wanted());
            ZwClose(props);
        }
        if let Some(mask) = tripwire_value(utf16!("NVME_AFFINITY")) {
            if let Some(policy) = create_key(management, utf16!("Affinity Policy")) {
                set_dword(policy, utf16!("DevicePolicy"), IRQ_POLICY_SPECIFIED_PROCESSORS);
                let mut name = unicode(utf16!("AssignmentSetOverride"));
                let mut set = mask as usize; // a KAFFINITY's bytes, as Windows stores it
                ZwSetValueKey(policy, &mut name, 0, REG_BINARY, (&raw mut set).cast(), size_of::<usize>() as ULONG);
                ZwClose(policy);
                nvprint!("affinity policy from the tripwire: messages on processors {:#x}\n", mask);
            }
        }
        ZwClose(management);
    }
    ZwClose(device_key);
}

pub unsafe extern "system" fn dispatch(device: PDEVICE_OBJECT, irp: PIRP) -> NTSTATUS {
    let ext = (*device).DeviceExtension;
    match if ext.is_null() { 0 } else { *(ext as *const u32) } {
        FDO_KIND => fdo_dispatch(&mut *(ext as *mut Fdo), irp),
        DISK_KIND => disk_dispatch(device, &*(ext as *const DiskExt), irp),
        _ => complete(irp, STATUS_INVALID_DEVICE_REQUEST, 0),
    }
}

