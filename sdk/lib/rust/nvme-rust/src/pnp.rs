/// The data buffer at a system address: DataBuffer is an address in the MDL's
/// range, reached through the system mapping since the caller's context is
/// not ours (and the completion runs in none at all). Null when unmappable.
unsafe fn system_address(irp: PIRP, srb: *mut Srb) -> *mut u8 {
    let data = (*srb).DataBuffer as *mut u8;
    let mdl = (*irp).MdlAddress;
    if mdl.is_null() || data.is_null() {
        return data;
    }
    let system = MmGetSystemAddressForMdlSafe(mdl, NORMAL_PAGE_PRIORITY) as *mut u8;
    if system.is_null() {
        return system;
    }
    system.add(data as usize - mdl_va(mdl))
}

/// MmGetMdlVirtualAddress: the address of the MDL's first byte.
unsafe fn mdl_va(mdl: PMDL) -> usize {
    (*mdl).StartVa as usize + (*mdl).ByteOffset as usize
}

unsafe fn finish(irp: PIRP, srb: *mut Srb, result: Result<usize, scsidisk::Sense>) -> NTSTATUS {
    let status = scsidisk::finish(srb, result);
    let n = if status >= 0 { (*srb).DataTransferLength as usize } else { 0 };
    (*irp).IoStatus.__bindgen_anon_1.Status = status;
    (*irp).IoStatus.Information = n as _;
    IoCompleteRequest(irp, IO_DISK_INCREMENT);
    status
}

/// An SRB that moves data, flushes, or asks something: the first two become a
/// [`Request`] on the controller's queue; the rest are answered here.
unsafe fn execute(ext: &DiskExt, irp: PIRP, srb: *mut Srb) -> NTSTATUS {
    // The disk is published only after the controller is set, so this cannot
    // miss; if it ever does, fail the request rather than the machine.
    let Some(c) = (*ext.fdo).controller.as_ref() else {
        nvprint!("an SRB reached a namespace before its controller was up\n");
        (*srb).SrbStatus = scsidisk::SRB_STATUS_ERROR;
        return complete(irp, STATUS_DEVICE_CONFIGURATION_ERROR, 0);
    };
    let ns = &ext.namespace;
    let len = (*srb).DataTransferLength as usize;
    let request = if (*srb).Function == scsidisk::SRB_FUNCTION_EXECUTE_SCSI {
        scsidisk::decode_transfer(&ext.disk, &(*srb).Cdb, len)
    } else {
        Some(scsidisk::Request::Flush) // SRB_FUNCTION_FLUSH / SHUTDOWN
    };
    let (op, lba, blocks) = match request {
        Some(scsidisk::Request::Read { lba, blocks }) => (Op::Read, lba, blocks),
        Some(scsidisk::Request::Write { lba, blocks }) => (Op::Write, lba, blocks),
        Some(scsidisk::Request::Flush) => (Op::Flush, 0, 0),
        Some(scsidisk::Request::Done(result)) => return finish(irp, srb, result),
        // Everything else is answered from what Identify said, into the buffer.
        None => {
            let data = system_address(irp, srb);
            if data.is_null() && len != 0 {
                (*srb).SrbStatus = scsidisk::SRB_STATUS_ERROR;
                return complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0);
            }
            let buf: &mut [u8] = if len == 0 { &mut [] } else { core::slice::from_raw_parts_mut(data, len) };
            let scsidisk::Request::Done(result) = scsidisk::decode(&ext.disk, &(*srb).Cdb, buf) else {
                unreachable!("decode_transfer takes every transfer");
            };
            return finish(irp, srb, result);
        }
    };

    let r = ExAllocatePoolWithTag(NONPAGED_POOL as _, size_of::<Request>() as _, NVME_POOL_TAG) as *mut Request;
    if r.is_null() {
        (*srb).SrbStatus = scsidisk::SRB_STATUS_ERROR;
        return complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0);
    }
    let mut req = Request::new(op, ns, lba, blocks, irp_done, irp.cast());
    let mdl = (*irp).MdlAddress;
    if op != Op::Flush {
        let data = (*srb).DataBuffer as usize;
        if !mdl.is_null() && (data < mdl_va(mdl) || data - mdl_va(mdl) + req.bytes() > (*mdl).ByteCount as usize) {
            nvprint!("controller {}: an SRB's data lies outside its MDL; refused\n", (*ext.fdo).number);
            ExFreePoolWithTag(r.cast(), 0);
            (*srb).SrbStatus = scsidisk::SRB_STATUS_INVALID_REQUEST;
            return complete(irp, scsidisk::STATUS_INVALID_PARAMETER, 0);
        }
        if !mdl.is_null() {
            req.mdl = mdl;
            req.mdl_offset = data - mdl_va(mdl);
        }
        if !dma_ready(req.mdl, req.mdl_offset, req.bytes()) {
            req.system = system_address(irp, srb);
            if req.system.is_null() {
                ExFreePoolWithTag(r.cast(), 0);
                (*srb).SrbStatus = scsidisk::SRB_STATUS_ERROR;
                return complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0);
            }
        }
    }
    r.write(req);
    (*srb).SrbStatus = scsidisk::SRB_STATUS_PENDING;
    IoMarkIrpPending(irp);
    c.submit(r);
    STATUS_PENDING
}

/// A request's `done`, at DISPATCH_LEVEL: complete its IRP.
unsafe fn irp_done(r: *mut Request) {
    let irp = (*r).context as PIRP;
    let io = IoGetCurrentIrpStackLocation(irp);
    let ext = &*((*(*io).DeviceObject).DeviceExtension as *const DiskExt);
    let srb = (*io).Parameters.Scsi.Srb as *mut Srb;
    let (op, lba, bytes, error) = ((*r).op, (*r).lba, (*r).bytes(), (*r).error);
    ExFreePoolWithTag(r.cast(), 0);
    if let Some(e) = error {
        nvprint!("controller {}: {} of {} bytes at block {} failed: {:?}\n", (*ext.fdo).number, op.name(), bytes, lba, e);
    }
    if matches!(error, Some(nvme::Error::Reset)) {
        // Not the medium's fault: the controller was reset under it.
        (*srb).SrbStatus = SRB_STATUS_BUS_RESET;
        (*srb).DataTransferLength = 0;
        complete(irp, scsidisk::STATUS_IO_DEVICE_ERROR, 0);
        return;
    }
    if (*srb).Function != scsidisk::SRB_FUNCTION_EXECUTE_SCSI {
        // SRB_FUNCTION_FLUSH / SHUTDOWN: no CDB, so no sense to report.
        let status = if error.is_none() { STATUS_SUCCESS } else { scsidisk::STATUS_IO_DEVICE_ERROR };
        (*srb).SrbStatus = if error.is_none() { scsidisk::SRB_STATUS_SUCCESS } else { scsidisk::SRB_STATUS_ERROR };
        complete(irp, status, 0);
        return;
    }
    let result = match error {
        None => Ok(bytes),
        Some(_) => Err(scsidisk::media_error(op != Op::Read)),
    };
    finish(irp, srb, result);
}
