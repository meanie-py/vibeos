unsafe fn fdo_dispatch(fdo: &mut Fdo, irp: PIRP) -> NTSTATUS {
    let io = IoGetCurrentIrpStackLocation(irp);
    match ((*io).MajorFunction, (*io).MinorFunction) {
        (IRP_MJ_PNP, IRP_MN_START_DEVICE) => {
            let status = if IoForwardIrpSynchronously(fdo.lower, irp) == 0 {
                STATUS_NO_SUCH_DEVICE
            } else if status_of(irp) < 0 {
                status_of(irp)
            } else if fdo.controller.is_some() {
                STATUS_SUCCESS // already running: a restart after a stop that never happened
            } else {
                start(fdo, io)
            };
            complete(irp, status, 0)
        }
        (IRP_MJ_PNP, IRP_MN_QUERY_DEVICE_RELATIONS)
            if (*io).Parameters.QueryDeviceRelations.Type as i32 == BUS_RELATIONS =>
        {
            if fdo.disk_count > 0 {
                let prior = (*irp).IoStatus.Information as PDEVICE_RELATIONS;
                let mut out: PVOID = null_mut();
                let status = relations(prior, &fdo.disks[..fdo.disk_count], &mut out);
                if status < 0 {
                    return complete(irp, status, 0);
                }
                (*irp).IoStatus.__bindgen_anon_1.Status = STATUS_SUCCESS;
                (*irp).IoStatus.Information = out as _;
            }
            pass_down(fdo, irp)
        }
        (IRP_MJ_PNP, minor) => {
            if minor == IRP_MN_REMOVE_DEVICE {
                nvprint!("controller {}: removal is not supported; it stays running\n", fdo.number);
            }
            pass_down(fdo, irp)
        }
        (IRP_MJ_POWER, _) => {
            PoStartNextPowerIrp(irp);
            IoSkipCurrentIrpStackLocation(irp);
            PoCallDriver(fdo.lower, irp)
        }
        (IRP_MJ_CREATE | IRP_MJ_CLOSE, _) => complete(irp, STATUS_SUCCESS, 0),
        _ => pass_down(fdo, irp),
    }
}

/// A DEVICE_RELATIONS holding `prior`'s objects and `extra` (each referenced).
unsafe fn relations(prior: PDEVICE_RELATIONS, extra: &[PDEVICE_OBJECT], out: *mut PVOID) -> NTSTATUS {
    let n = if prior.is_null() { 0 } else { (*prior).Count as usize };
    let header = offset_of!(ntkrnl_sys::ddk::DEVICE_RELATIONS, Objects);
    let size = header + (n + extra.len()) * size_of::<PDEVICE_OBJECT>();
    let r = ExAllocatePoolWithTag(PAGED_POOL as _, size as _, NVME_POOL_TAG) as PDEVICE_RELATIONS;
    if r.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    let objects = (*r).Objects.as_mut_ptr();
    if n > 0 {
        core::ptr::copy_nonoverlapping((*prior).Objects.as_ptr(), objects, n);
        ExFreePoolWithTag(prior as PVOID, 0);
    }
    for (i, &d) in extra.iter().enumerate() {
        ObReferenceObject(d as PVOID);
        *objects.add(n + i) = d;
    }
    (*r).Count = (n + extra.len()) as ULONG;
    *out = r as PVOID;
    STATUS_SUCCESS
}

/// The register window: BAR0, the first memory resource.
unsafe fn registers(io: PIO_STACK_LOCATION) -> Option<(u64, u64)> {
    let list = (*io).Parameters.StartDevice.AllocatedResourcesTranslated;
    if list.is_null() || (*list).Count == 0 {
        return None;
    }
    let partial = &(*(*list).List.as_ptr()).PartialResourceList;
    let descs = core::slice::from_raw_parts(partial.PartialDescriptors.as_ptr(), partial.Count as usize);
    descs.iter().find_map(|d| match d.Type {
        CM_RESOURCE_TYPE_MEMORY => Some((d.u.Memory.Start.QuadPart as u64, d.u.Memory.Length as u64)),
        // A BAR above 4 GiB (Graviton's are): the length is scaled by the flags.
        CM_RESOURCE_TYPE_MEMORY_LARGE => {
            let shift = match d.Flags {
                f if f & CM_RESOURCE_MEMORY_LARGE_40 != 0 => 8,
                f if f & CM_RESOURCE_MEMORY_LARGE_48 != 0 => 16,
                f if f & CM_RESOURCE_MEMORY_LARGE_64 != 0 => 32,
                _ => 0,
            };
            Some((d.u.Memory.Start.QuadPart as u64, (d.u.Memory.Length as u64) << shift))
        }
        _ => None,
    })
}

/// How many MSI-X messages START assigned.
unsafe fn message_count(io: PIO_STACK_LOCATION) -> u32 {
    let list = (*io).Parameters.StartDevice.AllocatedResourcesTranslated;
    if list.is_null() || (*list).Count == 0 {
        return 0;
    }
    let partial = &(*(*list).List.as_ptr()).PartialResourceList;
    let descs = core::slice::from_raw_parts(partial.PartialDescriptors.as_ptr(), partial.Count as usize);
    descs
        .iter()
        .filter(|d| d.Type == CM_RESOURCE_TYPE_INTERRUPT && d.Flags & CM_RESOURCE_INTERRUPT_MESSAGE != 0)
        .count() as u32
}

/// Connect the controller's interrupt: its MSI-X messages when it was assigned
/// any, else (IoConnectInterruptEx falls back on its own) the pin. Returns how
/// many messages connected (0: the pin), or None when nothing did and it polls.
unsafe fn connect(fdo: &mut Fdo) -> Option<u32> {
    let n = fdo.number;
    let irq = &raw mut fdo.irq;
    KeInitializeDpc((*irq).dpc(), Some(crate::nvme::dpc), irq.cast());
    // One slot receives what connected: the message table, or, when it fell
    // back to the pin, that interrupt's KINTERRUPT (wdm.h's ConnectionContext).
    let mut connection: PVOID = null_mut();
    let mut p: IO_CONNECT_INTERRUPT_PARAMETERS = core::mem::zeroed();
    p.Version = CONNECT_MESSAGE_BASED;
    {
        let m = &mut p.__bindgen_anon_1.MessageBased;
        m.PhysicalDeviceObject = fdo.pdo;
        m.ConnectionContext.Generic = &mut connection;
        m.MessageServiceRoutine = Some(crate::nvme::message_isr);
        m.ServiceContext = irq.cast();
        m.FallBackServiceRoutine = Some(crate::nvme::isr);
    }
    let status = IoConnectInterruptEx(&mut p);
    if status < 0 {
        nvprint!("controller {}: IoConnectInterruptEx failed {:#010x}; polling\n", n, status as u32);
        return None;
    }
    if p.Version == CONNECT_LINE_BASED {
        (*irq).interrupt = connection.cast();
        nvprint!("controller {}: interrupt connected: the pin (no MSI-X assigned)\n", n);
        return Some(0);
    }
    let table = connection as PIO_INTERRUPT_MESSAGE_INFO;
    fdo.messages = table;
    let count = (*table).MessageCount;
    let entries = core::slice::from_raw_parts((*table).MessageInfo.as_ptr(), count as usize);
    let io = if count > 2 { "vectors from" } else { "vector" };
    nvprint!(
        "controller {}: MSI-X: {} message(s) connected at level {}: admin on vector {}, I/O on {} {}\n",
        n,
        count,
        (*table).UnifiedIrql,
        entries[0].Vector,
        io,
        entries[(count as usize - 1).min(1)].Vector
    );
    Some(count)
}

/// Map the registers, bring the controller up, and publish its namespaces.
unsafe fn start(fdo: &mut Fdo, io: PIO_STACK_LOCATION) -> NTSTATUS {
    fdo.number = NEXT_CONTROLLER.fetch_add(1, Ordering::Relaxed);
    let n = fdo.number;
    let Some((base, len)) = registers(io) else {
        nvprint!("controller {}: START_DEVICE carried no register window\n", n);
        return STATUS_DEVICE_CONFIGURATION_ERROR;
    };
    let len = len.min(MAX_REGISTER_MAP);
    let mut pa: PHYSICAL_ADDRESS = core::mem::zeroed();
    pa.QuadPart = base as i64;
    let regs = MmMapIoSpace(pa, len as _, _MEMORY_CACHING_TYPE_MmNonCached) as *mut u8;
    if regs.is_null() {
        nvprint!("controller {}: could not map the registers at {:#x}\n", n, base);
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    nvprint!("controller {}: registers at {:#x}+{:#x}\n", n, base, len);

    // Messages are connected before bring-up: under MSI-X the admin queue's
    // interrupts cannot be masked, so its completions during bring-up must find
    // a vector that is ours (the ISR absorbs them until the worker is armed).
    // The pin is connected after, once bring-up has masked it.
    let early = if message_count(io) > 0 { connect(fdo) } else { None };
    let messages = early.unwrap_or(0);
    // Where each message is delivered: an I/O queue per message, for its CPUs.
    let mut targets = [0u64; nvme::MAX_IO_QUEUES + 1];
    let count = (messages as usize).min(targets.len());
    if count > 0 {
        let entries = core::slice::from_raw_parts((*fdo.messages).MessageInfo.as_ptr(), messages as usize);
        for (t, e) in targets.iter_mut().zip(entries) {
            *t = e.TargetProcessorSet as u64;
        }
    }
    if let Some(lose) = tripwire_value(utf16!("NVME_LOSE_COMPLETION")) {
        nvme::LOSE_COMPLETION.store(lose as u32, Ordering::Relaxed);
        nvprint!("controller {}: tripwire: I/O completion {} will be thrown away\n", n, lose);
    }

    let t0 = now_us();
    let mut c = match Controller::start(regs, len as usize, &targets[..count]) {
        Ok(c) => c,
        Err(e) => {
            nvprint!("controller {}: bring-up failed: {:?}\n", n, e);
            return STATUS_ADAPTER_HARDWARE_ERROR;
        }
    };
    let id = c.identity;
    nvprint!(
        "controller {}: '{}' serial '{}' firmware '{}', vendor {:#06x}, {} namespace(s), {} KiB per command, {} commands deep, write cache {}, ready in {} ms\n",
        n,
        text(&id.model),
        text(&id.serial),
        text(&id.firmware),
        id.vendor,
        id.namespaces,
        c.max_transfer / 1024,
        c.depth(),
        if id.volatile_cache { "present (disabled)" } else { "none" },
        (now_us() - t0) / 1000
    );

    for (q, vector, cpus) in c.queues() {
        nvprint!("controller {}: I/O queue {} on {} {}, for CPUs {:#x}\n", n, q, if messages > 0 { "message" } else { "vector" }, vector, cpus);
    }

    // The admin commands are all here, before the I/O path is armed: they poll.
    let mut ids = [0u32; NAMESPACES_PER_CONTROLLER];
    let active = c.active_namespaces(&mut ids);
    let mut found: [Option<Namespace>; NAMESPACES_PER_CONTROLLER] = [None; NAMESPACES_PER_CONTROLLER];
    for (slot, &nsid) in found.iter_mut().zip(&ids[..active]) {
        match c.namespace(nsid) {
            Ok(Some(ns)) => {
                nvprint!(
                    "controller {}: namespace {}: {} blocks of {} B ({} MiB)\n",
                    n,
                    nsid,
                    ns.blocks,
                    1u32 << ns.block_shift,
                    (ns.blocks << ns.block_shift) >> 20
                );
                *slot = Some(ns);
            }
            Ok(None) => {}
            Err(e) => nvprint!("controller {}: namespace {}: identify failed: {:?}\n", n, nsid, e),
        }
    }

    let connected = if messages > 0 { early } else { connect(fdo) };
    if connected.is_none() {
        nvprint!("controller {}: no interrupt connected; the {} ms timer reaps every completion\n", n, nvme::POLL_MS);
    }
    // Arm where the controller will stay: the DPCs keep its address.
    let c = fdo.controller.insert(c);
    c.arm(&raw mut fdo.irq, n, connected.is_some());

    if let Some(ns) = found.iter().flatten().next() {
        self_test(n, c, ns);
    }

    let max_transfer = c.max_transfer;
    for ns in found.iter().flatten() {
        match publish(fdo, id, max_transfer, ns) {
            Ok(disk) => {
                fdo.disks[fdo.disk_count] = disk;
                fdo.disk_count += 1;
                nvprint!("controller {}: namespace {} published as a disk\n", n, ns.id);
            }
            Err(status) => nvprint!("controller {}: namespace {}: IoCreateDevice failed {:#010x}\n", n, ns.id, status as u32),
        }
    }
    STATUS_SUCCESS
}

/// Identify-data strings: space-padded ASCII.
fn text(field: &[u8]) -> &str {
    core::str::from_utf8(scsidisk::trimmed(field)).unwrap_or("?")
}

unsafe fn publish(fdo: &mut Fdo, id: Identity, max_transfer: usize, ns: &Namespace) -> Result<PDEVICE_OBJECT, NTSTATUS> {
    let mut device: PDEVICE_OBJECT = null_mut();
    let status = IoCreateDevice(
        (*fdo.device).DriverObject,
        size_of::<DiskExt>() as ULONG,
        null_mut(),
        FILE_DEVICE_MASS_STORAGE,
        FILE_AUTOGENERATED_DEVICE_NAME | FILE_DEVICE_SECURE_OPEN,
        0,
        &mut device,
    );
    if status < 0 {
        return Err(status);
    }
    let mut disk = Disk {
        vendor: [b' '; 8],
        product: [b' '; 16],
        revision: [b' '; 4],
        serial: id.serial,
        block_size: 1 << ns.block_shift,
        blocks: ns.blocks,
        removable: false,
        writable: true,
        bus_type: scsidisk::BUS_TYPE_NVME,
        bus_version: ((id.version >> 16) as u16, (id.version >> 8 & 0xFF) as u16),
        max_transfer: max_transfer as u32,
        address: [fdo.number as u8, 0, 0, fdo.disk_count as u8],
    };
    scsidisk::ascii_field(&mut disk.vendor, b"NVMe");
    scsidisk::ascii_field(&mut disk.product, scsidisk::trimmed(&id.model));
    scsidisk::ascii_field(&mut disk.revision, scsidisk::trimmed(&id.firmware));
    scsidisk::ascii_field(&mut disk.serial, &id.serial);
    ((*device).DeviceExtension as *mut DiskExt).write(DiskExt {
        kind: DISK_KIND,
        fdo,
        namespace: *ns,
        disk,
        claimed: AtomicBool::new(false),
    });
    (*device).Flags |= DO_DIRECT_IO;
    (*device).Flags &= !DO_DEVICE_INITIALIZING;
    Ok(device)
}

/// The self-test's reads, at most this much at once.
const SELF_TEST_BYTES: usize = 1 << 20;
/// Long enough for any command to complete or be reported overdue (nvme.rs).
const SELF_TEST_WAIT_MS: i64 = 35_000;

/// The self-test's state, in nonpaged pool: its requests' memory must outlive
/// a wait that gives up.
struct SelfTest {
    request: Request,
    event: KEVENT,
    mdl: PMDL,
    buffer: *mut u8,
}

unsafe fn self_test_done(r: *mut Request) {
    KeSetEvent((*r).context.cast(), 0, 0);
}

/// One read through the I/O path, waited for. Err(()) when the wait gave up,
/// leaving `t` in the device's hands.
unsafe fn self_test_read(c: &Controller, t: *mut SelfTest, ns: &Namespace, lba: u64, blocks: u64) -> Result<Option<nvme::Error>, ()> {
    let event = &raw mut (*t).event;
    let request = &raw mut (*t).request;
    let mut r = Request::new(Op::Read, ns, lba, blocks, self_test_done, event.cast());
    r.mdl = (*t).mdl;
    r.system = (*t).buffer;
    request.write(r);
    // Once more after a reset failed it back, as the disk class driver would
    // (submit starts a request afresh).
    for _ in 0..2 {
        KeInitializeEvent(event, NOTIFICATION_EVENT as _, 0);
        c.submit(request);
        let mut timeout: LARGE_INTEGER = core::mem::zeroed();
        timeout.QuadPart = -10_000 * SELF_TEST_WAIT_MS;
        if KeWaitForSingleObject(event.cast(), 0, 0, 0, &mut timeout) == STATUS_TIMEOUT {
            return Err(());
        }
        if !matches!((*request).error, Some(nvme::Error::Reset)) {
            break;
        }
        nvprint!("controller {}: self-test: a read was failed back by a reset; retrying it\n", c.number());
    }
    Ok((*request).error)
}

/// Read the partition table, then a timed megabyte as ONE request, which the
/// I/O path cuts into commands and runs all at once. Into a nonpaged buffer
/// with an MDL, the way classpnp's reads arrive, so it is the direct-DMA path
/// under test. Read-only: on real hardware this is someone's drive.
unsafe fn self_test(n: u32, c: &Controller, ns: &Namespace) {
    let t = ExAllocatePoolWithTag(NONPAGED_POOL as _, size_of::<SelfTest>() as _, NVME_POOL_TAG) as *mut SelfTest;
    let buffer = ExAllocatePoolWithTag(NONPAGED_POOL as _, SELF_TEST_BYTES as _, NVME_POOL_TAG) as *mut u8;
    let mdl = if buffer.is_null() { null_mut() } else { IoAllocateMdl(buffer.cast(), SELF_TEST_BYTES as _, 0, 0, null_mut()) };
    if t.is_null() || mdl.is_null() {
        nvprint!("controller {}: self-test: no memory for it\n", n);
        for p in [t.cast::<u8>(), buffer] {
            if !p.is_null() {
                ExFreePoolWithTag(p.cast(), 0);
            }
        }
        return;
    }
    MmBuildMdlForNonPagedPool(mdl);
    (&raw mut (*t).mdl).write(mdl);
    (&raw mut (*t).buffer).write(buffer);
    let given_up = || nvprint!("controller {}: self-test: a read has not completed in {} s; leaving it\n", n, SELF_TEST_WAIT_MS / 1000);

    match self_test_read(c, t, ns, 0, 1) {
        Err(()) => return given_up(),
        Ok(Some(e)) => nvprint!("controller {}: self-test: reading block 0 failed: {:?}\n", n, e),
        Ok(None) => {
            let mbr = core::slice::from_raw_parts(buffer, 512);
            if mbr[510] == 0x55 && mbr[511] == 0xAA {
                for i in 0..4 {
                    let e = &mbr[446 + 16 * i..462 + 16 * i];
                    if e[4] != 0 {
                        let first = u32::from_le_bytes([e[8], e[9], e[10], e[11]]);
                        let count = u32::from_le_bytes([e[12], e[13], e[14], e[15]]);
                        nvprint!("controller {}: self-test: partition {} type {:#04x} at block {}, {} blocks\n", n, i + 1, e[4], first, count);
                    }
                }
            } else {
                nvprint!("controller {}: self-test: block 0 holds no MBR signature\n", n);
            }
        }
    }

    let blocks = ((SELF_TEST_BYTES >> ns.block_shift) as u64).min(ns.blocks);
    let t0 = now_us();
    match self_test_read(c, t, ns, 0, blocks) {
        Err(()) => return given_up(),
        Ok(Some(e)) => nvprint!("controller {}: self-test: the timed read failed: {:?}\n", n, e),
        Ok(None) => {
            let us = (now_us() - t0).max(1);
            let kib = (blocks << ns.block_shift) / 1024;
            let s = c.stats();
            nvprint!(
                "controller {}: self-test: read {} KiB in {} ms ({} KiB/s), up to {} commands in flight; completions so far: {} by interrupt, {} by the poll; {} commands by DMA to the caller's pages, {} through the bounce buffer\n",
                n,
                kib,
                us / 1000,
                kib * 1_000_000 / us,
                s.peak,
                s.by_interrupt,
                s.by_poll,
                s.direct,
                s.bounced
            );
        }
    }
    if let Some((admin, io)) = c.message_counts() {
        nvprint!("controller {}: self-test: MSI-X messages taken: {} admin, {} I/O\n", n, admin, io);
    }
    let s = c.stats();
    if s.resets > 0 {
        nvprint!("controller {}: self-test: {} reset(s), {} command(s) failed back by them\n", n, s.resets, s.reset_failed);
    }
    IoFreeMdl(mdl);
    ExFreePoolWithTag(buffer.cast(), 0);
    ExFreePoolWithTag(t.cast(), 0);
}

