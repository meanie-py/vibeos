unsafe fn disk_dispatch(device: PDEVICE_OBJECT, ext: &DiskExt, irp: PIRP) -> NTSTATUS {
    let io = IoGetCurrentIrpStackLocation(irp);
    match (*io).MajorFunction {
        IRP_MJ_SCSI => {
            let srb = (*io).Parameters.Scsi.Srb as *mut Srb;
            match (*srb).Function {
                scsidisk::SRB_FUNCTION_EXECUTE_SCSI | scsidisk::SRB_FUNCTION_FLUSH | scsidisk::SRB_FUNCTION_SHUTDOWN => {
                    execute(ext, irp, srb)
                }
                scsidisk::SRB_FUNCTION_CLAIM_DEVICE => {
                    if ext.claimed.swap(true, Ordering::AcqRel) {
                        (*srb).SrbStatus = scsidisk::SRB_STATUS_BUSY;
                        return complete(irp, STATUS_DEVICE_BUSY, 0);
                    }
                    (*srb).DataBuffer = device.cast();
                    (*srb).SrbStatus = scsidisk::SRB_STATUS_SUCCESS;
                    complete(irp, STATUS_SUCCESS, 0)
                }
                scsidisk::SRB_FUNCTION_RELEASE_DEVICE => {
                    ext.claimed.store(false, Ordering::Release);
                    (*srb).SrbStatus = scsidisk::SRB_STATUS_SUCCESS;
                    complete(irp, STATUS_SUCCESS, 0)
                }
                // The SRBs go straight to the controller's queue, which never
                // freezes: there is nothing of classpnp's to release, flush or lock.
                scsidisk::SRB_FUNCTION_RELEASE_QUEUE
                | scsidisk::SRB_FUNCTION_FLUSH_QUEUE
                | scsidisk::SRB_FUNCTION_LOCK_QUEUE
                | scsidisk::SRB_FUNCTION_UNLOCK_QUEUE => {
                    (*srb).SrbStatus = scsidisk::SRB_STATUS_SUCCESS;
                    complete(irp, STATUS_SUCCESS, 0)
                }
                // Miniport IOCTLs (SMART and the like): nothing to answer, and
                // classpnp asks on every disk, so not worth a line each time.
                SRB_FUNCTION_IO_CONTROL => {
                    (*srb).SrbStatus = scsidisk::SRB_STATUS_INVALID_REQUEST;
                    complete(irp, scsidisk::STATUS_NOT_SUPPORTED, 0)
                }
                f => {
                    nvprint!("SRB function {:#04x} not supported\n", f);
                    (*srb).SrbStatus = scsidisk::SRB_STATUS_INVALID_REQUEST;
                    complete(irp, scsidisk::STATUS_NOT_SUPPORTED, 0)
                }
            }
        }
        IRP_MJ_DEVICE_CONTROL => {
            let p = (*io).Parameters.DeviceIoControl;
            let (inl, outl) = (p.InputBufferLength as usize, p.OutputBufferLength as usize);
            let sys = (*irp).AssociatedIrp.SystemBuffer as *mut u8;
            let buf: &mut [u8] = if sys.is_null() { &mut [] } else { core::slice::from_raw_parts_mut(sys, inl.max(outl)) };
            let (status, n) = scsidisk::device_control(&ext.disk, p.IoControlCode, buf, inl, outl);
            complete(irp, status, n)
        }
        IRP_MJ_PNP => disk_pnp(device, ext, irp, io),
        IRP_MJ_POWER => {
            PoStartNextPowerIrp(irp);
            complete(irp, STATUS_SUCCESS, 0)
        }
        IRP_MJ_CREATE | IRP_MJ_CLOSE => complete(irp, STATUS_SUCCESS, 0),
        _ => {
            let status = status_of(irp);
            complete(irp, status, (*irp).IoStatus.Information as usize)
        }
    }
}

/// A multi-sz (or a plain string) of `parts` in paged pool, for QUERY_ID / DEVICE_TEXT.
unsafe fn wide(parts: &[&[u8]], multi: bool) -> PVOID {
    let chars: usize = parts.iter().map(|p| p.len() + 1).sum::<usize>() + multi as usize;
    let p = ExAllocatePoolWithTag(PAGED_POOL as _, (chars * 2) as _, NVME_POOL_TAG) as *mut u16;
    if p.is_null() {
        return null_mut();
    }
    let mut at = 0;
    for part in parts {
        for &b in *part {
            *p.add(at) = b as u16;
            at += 1;
        }
        *p.add(at) = 0;
        at += 1;
    }
    if multi {
        *p.add(at) = 0;
    }
    p.cast()
}

/// `SCSI\Disk` + the INQUIRY vendor, product and revision, spaces as `_`,
/// the way Windows names a SCSI disk: `SCSI\DiskNVMe____QEMU_NVMe_Ctrl___1.0_`.
fn scsi_id(disk: &Disk, out: &mut [u8; 37]) {
    out[..9].copy_from_slice(b"SCSI\\Disk");
    for (o, &b) in out[9..].iter_mut().zip(disk.vendor.iter().chain(&disk.product).chain(&disk.revision)) {
        *o = if b == b' ' || b == b',' { b'_' } else { b };
    }
}

unsafe fn disk_pnp(device: PDEVICE_OBJECT, ext: &DiskExt, irp: PIRP, io: PIO_STACK_LOCATION) -> NTSTATUS {
    match (*io).MinorFunction {
        IRP_MN_START_DEVICE
        | IRP_MN_QUERY_REMOVE_DEVICE
        | IRP_MN_CANCEL_REMOVE_DEVICE
        | IRP_MN_STOP_DEVICE
        | IRP_MN_QUERY_STOP_DEVICE
        | IRP_MN_CANCEL_STOP_DEVICE
        | IRP_MN_SURPRISE_REMOVAL
        | IRP_MN_DEVICE_USAGE_NOTIFICATION
        // The namespace lives as long as its controller: a removal leaves it.
        | IRP_MN_REMOVE_DEVICE => complete(irp, STATUS_SUCCESS, 0),
        IRP_MN_QUERY_ID => {
            let mut full = [0u8; 37];
            scsi_id(&ext.disk, &mut full);
            let mut instance = [0u8; 8];
            for (i, c) in instance.iter_mut().enumerate() {
                *c = b"0123456789ABCDEF"[(ext.namespace.id >> (28 - 4 * i)) as usize & 0xF];
            }
            let ids = match (*io).Parameters.QueryId.IdType as i32 {
                BUS_QUERY_DEVICE_ID => wide(&[&full], false),
                // Most specific first; GenDisk is what the critical device database maps to disk.sys.
                BUS_QUERY_HARDWARE_IDS => wide(&[&full, &full[..33], &full[..17], b"SCSI\\Disk", b"GenDisk"], true),
                BUS_QUERY_COMPATIBLE_IDS => wide(&[b"SCSI\\Disk", b"GenDisk"], true),
                BUS_QUERY_INSTANCE_ID => wide(&[&instance], false),
                _ => return complete(irp, status_of(irp), (*irp).IoStatus.Information as usize),
            };
            if ids.is_null() {
                return complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0);
            }
            complete(irp, STATUS_SUCCESS, ids as usize)
        }
        IRP_MN_QUERY_DEVICE_TEXT
            if (*io).Parameters.QueryDeviceText.DeviceTextType as i32 == DEVICE_TEXT_DESCRIPTION =>
        {
            let model = (*ext.fdo).controller.as_ref().map(|c| c.identity.model).unwrap_or([b' '; 40]);
            let text = wide(&[scsidisk::trimmed(&model)], false);
            if text.is_null() {
                return complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0);
            }
            complete(irp, STATUS_SUCCESS, text as usize)
        }
        IRP_MN_QUERY_CAPABILITIES => {
            let caps = &mut *(*io).Parameters.DeviceCapabilities.Capabilities;
            caps.set_Removable(0);
            caps.set_UniqueID(0);
            caps.set_SilentInstall(1);
            caps.set_RawDeviceOK(0);
            caps.set_SurpriseRemovalOK(0);
            caps.Address = ext.namespace.id;
            caps.UINumber = ext.namespace.id;
            for (i, s) in caps.DeviceState.iter_mut().enumerate() {
                *s = if i == POWER_SYSTEM_WORKING { POWER_DEVICE_D0 } else { POWER_DEVICE_D3 } as _;
            }
            complete(irp, STATUS_SUCCESS, 0)
        }
        IRP_MN_QUERY_DEVICE_RELATIONS
            if (*io).Parameters.QueryDeviceRelations.Type as i32 == TARGET_DEVICE_RELATION =>
        {
            let mut out: PVOID = null_mut();
            let status = relations(null_mut(), &[device], &mut out);
            complete(irp, status, out as usize)
        }
        // Resources, bus information, device state, ...: nothing to add.
        _ => complete(irp, status_of(irp), (*irp).IoStatus.Information as usize),
    }
}

