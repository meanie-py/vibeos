//! The device stacks: our FDO on pci.sys's PDO for each controller, and one
//! child PDO per namespace, which disk.sys attaches to through `GenDisk`.
//!
//!   disk.sys FDO (+ partmgr)          classpnp sends SRBs and storage IOCTLs
//!   our namespace PDO(s)              ── queued to the controller's worker ─┐
//!   our controller FDO                IRP_MN_START_DEVICE: bring it up      │
//!   pci.sys PDO (PCI\CC_010802)                                             │
//!                                     worker: one command at a time, polled ◄┘
//!
//! A controller and its namespaces live for the life of the system once
//! started: NVMe drives are not hot-removed here, so removal leaves them be.

