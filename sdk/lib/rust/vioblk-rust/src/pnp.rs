type Dispatch = unsafe extern "system" fn(PDEVICE_OBJECT, PIRP) -> NTSTATUS;
type AddDevice = unsafe extern "system" fn(PDRIVER_OBJECT, PDEVICE_OBJECT) -> NTSTATUS;

/// SCSIPORT's dispatch entries and AddDevice, as ScsiPortInitialize left them.
static mut SCSIPORT_DISPATCH: [Option<Dispatch>; IRP_MJ_MAXIMUM_FUNCTION + 1] = [None; IRP_MJ_MAXIMUM_FUNCTION + 1];
static mut SCSIPORT_ADD_DEVICE: Option<AddDevice> = None;

/// Every device object this module created: an FDO and a disk PDO per slot.
const MAX_DEVICE_OBJECTS: usize = 32;
static DEVICES: [AtomicPtr<ntkrnl_sys::ddk::DEVICE_OBJECT>; MAX_DEVICE_OBJECTS] =
    [const { AtomicPtr::new(null_mut()) }; MAX_DEVICE_OBJECTS];

fn record(device: PDEVICE_OBJECT) -> bool {
    DEVICES.iter().any(|d| d.compare_exchange(null_mut(), device, Ordering::AcqRel, Ordering::Acquire).is_ok())
}

fn ours(device: PDEVICE_OBJECT) -> bool {
    DEVICES.iter().any(|d| d.load(Ordering::Acquire) == device)
}

/// Take over the driver object's AddDevice and dispatch table, keeping
/// SCSIPORT's entries for its own devices. Call after ScsiPortInitialize.
pub unsafe fn install(driver: PDRIVER_OBJECT) {
    let driver = &mut *driver;
    let saved = &mut *(&raw mut SCSIPORT_DISPATCH);
    for (slot, f) in saved.iter_mut().zip(driver.MajorFunction[..=IRP_MJ_MAXIMUM_FUNCTION].iter_mut()) {
        *slot = *f;
        *f = Some(dispatch);
    }
    SCSIPORT_ADD_DEVICE = (*driver.DriverExtension).AddDevice;
    (*driver.DriverExtension).AddDevice = Some(add_device);
}

unsafe extern "system" fn dispatch(device: PDEVICE_OBJECT, irp: PIRP) -> NTSTATUS {
    if ours(device) {
        let ext = (*device).DeviceExtension;
        return match *(ext as *const u32) {
            SLOT_FDO_KIND => fdo_dispatch(&mut *(ext as *mut Fdo), irp),
            SLOT_DISK_KIND => disk_dispatch(device, &*(ext as *const DiskExt), irp),
            _ => complete(irp, STATUS_INVALID_DEVICE_REQUEST, 0),
        };
    }
    let major = (*IoGetCurrentIrpStackLocation(irp)).MajorFunction as usize;
    match (*(&raw const SCSIPORT_DISPATCH)).get(major).copied().flatten() {
        Some(f) => f(device, irp),
        None => complete(irp, STATUS_INVALID_DEVICE_REQUEST, 0),
    }
}

/// Does the PDO's hardware-ID list name a virtio-mmio block slot?
unsafe fn is_virtio_mmio_block(pdo: PDEVICE_OBJECT) -> bool {
    let mut ids = [0u16; 128];
    let mut len: ULONG = 0;
    let status = IoGetDeviceProperty(
        pdo,
        DEVICE_REGISTRY_PROPERTY_DevicePropertyHardwareID,
        size_of::<[u16; 128]>() as ULONG,
        ids.as_mut_ptr().cast(),
        &mut len,
    );
    if status < 0 {
        return false;
    }
    let ids = &ids[..(len as usize / 2).min(ids.len())];
    ids.split(|&c| c == 0)
        .any(|id| id.len() == HARDWARE_ID.len() && id.iter().zip(HARDWARE_ID).all(|(&a, &b)| a == b as u16))
}

unsafe extern "system" fn add_device(driver: PDRIVER_OBJECT, pdo: PDEVICE_OBJECT) -> NTSTATUS {
    if !is_virtio_mmio_block(pdo) {
        // A PCI function the critical device database also names this driver
        // for: SCSIPORT's, as it always was.
        return match *(&raw const SCSIPORT_ADD_DEVICE) {
            Some(f) => f(driver, pdo),
            None => STATUS_SUCCESS,
        };
    }
    let mut device: PDEVICE_OBJECT = null_mut();
    let status =
        IoCreateDevice(driver, size_of::<Fdo>() as ULONG, null_mut(), FILE_DEVICE_CONTROLLER, FILE_DEVICE_SECURE_OPEN, 0, &mut device);
    if status < 0 {
        vlog!("virtio-mmio: IoCreateDevice failed {:#010x}", status as u32);
        return status;
    }
    let fdo = (*device).DeviceExtension as *mut Fdo;
    fdo.write(Fdo {
        kind: SLOT_FDO_KIND,
        device,
        lower: null_mut(),
        regs: 0,
        blk: None,
        arena: null_mut(),
        req: null_mut(),
        resp: null_mut(),
        irq: Irq::new(),
        queue: core::mem::zeroed(),
        lock: 0,
        event: core::mem::zeroed(),
        disk: null_mut(),
    });
    if !record(device) {
        vlog!("virtio-mmio: more than {} device objects; slot left unserved", MAX_DEVICE_OBJECTS);
        ntkrnl_sys::ddk::IoDeleteDevice(device);
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    (*fdo).lower = ntkrnl_sys::ddk::IoAttachDeviceToDeviceStack(device, pdo);
    if (*fdo).lower.is_null() {
        // Left recorded: the slot is never reused, and the object is gone.
        ntkrnl_sys::ddk::IoDeleteDevice(device);
        return STATUS_NO_SUCH_DEVICE;
    }
    InitializeListHead(&raw mut (*fdo).queue);
    KeInitializeEvent(&raw mut (*fdo).event, SYNCHRONIZATION_EVENT as _, 0);
    (*device).Flags &= !DO_DEVICE_INITIALIZING;
    STATUS_SUCCESS
}

