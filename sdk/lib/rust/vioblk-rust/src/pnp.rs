/// The slot's interrupt: the ISR acks the transport and the DPC wakes the worker.
struct Irq {
    regs: *mut u8,
    armed: AtomicBool,
    event: KEVENT,
    dpc: KDPC,
    interrupt: PKINTERRUPT,
    /// Interrupts the ISR has claimed.
    claimed: AtomicU32,
}

impl Irq {
    const fn new() -> Self {
        Irq {
            regs: null_mut(),
            armed: AtomicBool::new(false),
            event: unsafe { core::mem::zeroed() },
            dpc: unsafe { core::mem::zeroed() },
            interrupt: null_mut(),
            claimed: AtomicU32::new(0),
        }
    }
}

unsafe extern "system" fn isr(_interrupt: PKINTERRUPT, context: PVOID) -> BOOLEAN {
    let irq = &*(context as *const Irq);
    if !irq.armed.load(Ordering::Acquire) {
        return 0;
    }
    let status = irq.regs.add(REG_INTERRUPT_STATUS).cast::<u32>().read_volatile();
    if status == 0 {
        return 0;
    }
    // Acking drops the level-triggered line; the worker reads the used ring.
    irq.regs.add(REG_INTERRUPT_ACK).cast::<u32>().write_volatile(status);
    irq.claimed.fetch_add(1, Ordering::Relaxed);
    KeInsertQueueDpc(&irq.dpc as *const KDPC as *mut KDPC, null_mut(), null_mut());
    1
}

unsafe extern "system" fn dpc(_dpc: *mut KDPC, context: PVOID, _a: PVOID, _b: PVOID) {
    let irq = context as *mut Irq;
    KeSetEvent(&raw mut (*irq).event, 0, 0);
}

#[repr(C)]
struct Fdo {
    kind: u32,
    device: PDEVICE_OBJECT,
    lower: PDEVICE_OBJECT,
    /// Physical base of the slot's registers, for messages.
    regs: u64,
    /// Set in START before the disk is published; then the worker's alone.
    blk: Option<Blk>,
    arena: *mut u8,
    req: *mut BlkReq,
    resp: *mut BlkResp,
    irq: Irq,
    /// SRB IRPs waiting for the worker, linked through Irp->Tail.Overlay.ListEntry.
    queue: LIST_ENTRY,
    lock: ntkrnl_sys::ke::KSPIN_LOCK,
    event: KEVENT,
    disk: PDEVICE_OBJECT,
}

/// The disk PDO's extension.
#[repr(C)]
struct DiskExt {
    kind: u32,
    fdo: *mut Fdo,
    disk: Disk,
    claimed: AtomicBool,
}

unsafe fn status_of(irp: PIRP) -> NTSTATUS {
    (*irp).IoStatus.__bindgen_anon_1.Status
}

unsafe fn complete(irp: PIRP, status: NTSTATUS, information: usize) -> NTSTATUS {
    (*irp).IoStatus.__bindgen_anon_1.Status = status;
    (*irp).IoStatus.Information = information as _;
    IoCompleteRequest(irp, 0);
    status
}

unsafe fn pass_down(fdo: &Fdo, irp: PIRP) -> NTSTATUS {
    IoSkipCurrentIrpStackLocation(irp);
    IoCallDriver(fdo.lower, irp)
}

unsafe fn fdo_dispatch(fdo: &mut Fdo, irp: PIRP) -> NTSTATUS {
    let io = IoGetCurrentIrpStackLocation(irp);
    match ((*io).MajorFunction, (*io).MinorFunction) {
        (IRP_MJ_PNP, IRP_MN_START_DEVICE) => {
            let status = if IoForwardIrpSynchronously(fdo.lower, irp) == 0 {
                STATUS_NO_SUCH_DEVICE
            } else if status_of(irp) < 0 {
                status_of(irp)
            } else if fdo.blk.is_some() {
                STATUS_SUCCESS // already running: a restart after a stop that never happened
            } else {
                start(fdo, io)
            };
            complete(irp, status, 0)
        }
        (IRP_MJ_PNP, IRP_MN_QUERY_DEVICE_RELATIONS)
            if (*io).Parameters.QueryDeviceRelations.Type as i32 == BUS_RELATIONS =>
        {
            if !fdo.disk.is_null() {
                let prior = (*irp).IoStatus.Information as PDEVICE_RELATIONS;
                let mut out: PVOID = null_mut();
                let status = relations(prior, &[fdo.disk], &mut out);
                if status < 0 {
                    return complete(irp, status, 0);
                }
                (*irp).IoStatus.__bindgen_anon_1.Status = STATUS_SUCCESS;
                (*irp).IoStatus.Information = out as _;
            }
            pass_down(fdo, irp)
        }
        (IRP_MJ_PNP, minor) => {
            if minor == IRP_MN_REMOVE_DEVICE {
                vlog!("virtio-mmio {:#x}: removal is not supported; it stays running", fdo.regs);
            }
            pass_down(fdo, irp)
        }
        (IRP_MJ_POWER, _) => {
            PoStartNextPowerIrp(irp);
            IoSkipCurrentIrpStackLocation(irp);
            PoCallDriver(fdo.lower, irp)
        }
        (IRP_MJ_CREATE | IRP_MJ_CLOSE, _) => complete(irp, STATUS_SUCCESS, 0),
        _ => pass_down(fdo, irp),
    }
}

/// A DEVICE_RELATIONS holding `prior`'s objects and `extra` (each referenced).
unsafe fn relations(prior: PDEVICE_RELATIONS, extra: &[PDEVICE_OBJECT], out: *mut PVOID) -> NTSTATUS {
    let n = if prior.is_null() { 0 } else { (*prior).Count as usize };
    let header = offset_of!(ntkrnl_sys::ddk::DEVICE_RELATIONS, Objects);
    let size = header + (n + extra.len()) * size_of::<PDEVICE_OBJECT>();
    let r = ExAllocatePoolWithTag(PAGED_POOL as _, size as _, VIOBLK_POOL_TAG) as PDEVICE_RELATIONS;
    if r.is_null() {
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    let objects = (*r).Objects.as_mut_ptr();
    if n > 0 {
        core::ptr::copy_nonoverlapping((*prior).Objects.as_ptr(), objects, n);
        ExFreePoolWithTag(prior as PVOID, 0);
    }
    for (i, &d) in extra.iter().enumerate() {
        ObReferenceObject(d as PVOID);
        *objects.add(n + i) = d;
    }
    (*r).Count = (n + extra.len()) as ULONG;
    *out = r as PVOID;
    STATUS_SUCCESS
}

/// The slot's register window and interrupt from START's translated resources:
/// ((base, length), (vector, level, affinity, latched, shared)).
#[allow(clippy::type_complexity)]
unsafe fn resources(io: PIO_STACK_LOCATION) -> (Option<(u64, u64)>, Option<(ULONG, u8, usize, bool, bool)>) {
    let list = (*io).Parameters.StartDevice.AllocatedResourcesTranslated;
    if list.is_null() || (*list).Count == 0 {
        return (None, None);
    }
    let partial = &(*(*list).List.as_ptr()).PartialResourceList;
    let descs = core::slice::from_raw_parts(partial.PartialDescriptors.as_ptr(), partial.Count as usize);
    let regs = descs
        .iter()
        .find(|d| d.Type == CM_RESOURCE_TYPE_MEMORY)
        .map(|d| (d.u.Memory.Start.QuadPart as u64, d.u.Memory.Length as u64));
    let irq = descs.iter().find(|d| d.Type == CM_RESOURCE_TYPE_INTERRUPT).map(|d| {
        let i = d.u.Interrupt;
        (
            i.Vector,
            i.Level as u8,
            i.Affinity as usize,
            d.Flags & CM_RESOURCE_INTERRUPT_LATCHED != 0,
            d.ShareDisposition == CM_RESOURCE_SHARE_SHARED,
        )
    });
    (regs, irq)
}

/// Map the slot, bring the block device up, and publish it as a disk.
unsafe fn start(fdo: &mut Fdo, io: PIO_STACK_LOCATION) -> NTSTATUS {
    let (regs, irq) = resources(io);
    let Some((base, len)) = regs else {
        vlog!("virtio-mmio: START_DEVICE carried no register window");
        return STATUS_DEVICE_CONFIGURATION_ERROR;
    };
    fdo.regs = base;
    let mut pa: PHYSICAL_ADDRESS = core::mem::zeroed();
    pa.QuadPart = base as i64;
    let va = MmMapIoSpace(pa, len as _, _MEMORY_CACHING_TYPE_MmNonCached) as *mut u8;
    let Some(header) = NonNull::new(va) else {
        vlog!("virtio-mmio {:#x}: could not map the registers", base);
        return STATUS_INSUFFICIENT_RESOURCES;
    };
    let transport = match MmioTransport::new(header.cast::<VirtIOHeader>(), len as usize) {
        Ok(t) => t,
        Err(e) => {
            vlog!("virtio-mmio {:#x}: not a usable transport: {:?}", base, e);
            return STATUS_ADAPTER_HARDWARE_ERROR;
        }
    };
    if !init_bounce_pool() {
        vlog!("virtio-mmio {:#x}: could not allocate the bounce page", base);
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    let (arena, arena_pa) = alloc_contiguous(ARENA_LEN + ARENA_TAIL);
    if arena.is_null() || !register_arena(arena, arena_pa, ARENA_LEN + ARENA_TAIL) {
        vlog!("virtio-mmio {:#x}: could not set up a {} KiB transfer arena", base, ARENA_LEN / 1024);
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    let mut blk = match Blk::new(transport) {
        Ok(b) => b,
        Err(e) => {
            vlog!("virtio-mmio {:#x}: virtio-blk init failed: {:?}", base, e);
            return STATUS_ADAPTER_HARDWARE_ERROR;
        }
    };
    let req = arena.add(ARENA_LEN).cast::<BlkReq>();
    let resp = req.add(1).cast::<BlkResp>();
    req.write(BlkReq::default());
    resp.write(BlkResp::default());
    fdo.arena = arena;
    fdo.req = req;
    fdo.resp = resp;

    let mut serial = [b' '; 20];
    let mut id = [0u8; 20];
    if let Ok(n) = blk.device_id(&mut id) {
        scsidisk::ascii_field(&mut serial, &id[..n]);
    }
    let disk = Disk {
        vendor: *b"VirtIO  ",
        product: *b"Block Device    ",
        revision: *b"1.0 ",
        serial,
        block_size: SECTOR_SIZE as u32,
        blocks: blk.capacity(),
        removable: false,
        writable: !blk.readonly(),
        bus_type: scsidisk::BUS_TYPE_SCSI,
        bus_version: (1, 0),
        max_transfer: ARENA_LEN as u32,
        address: [0, 0, 0, 0],
    };
    vlog!(
        "virtio-mmio {:#x}: {} sectors ({} MiB){}",
        base,
        disk.blocks,
        disk.blocks * SECTOR_SIZE as u64 >> 20,
        if disk.writable { "" } else { ", read-only" }
    );
    fdo.irq.regs = va;
    fdo.blk = Some(blk);
    connect(fdo, irq);
    self_test(fdo);

    let mut thread: HANDLE = null_mut();
    let status = PsCreateSystemThread(
        &mut thread,
        THREAD_ALL_ACCESS,
        null_mut(),
        null_mut(),
        null_mut(),
        Some(worker),
        (fdo as *mut Fdo).cast(),
    );
    if status < 0 {
        vlog!("virtio-mmio {:#x}: PsCreateSystemThread failed {:#010x}", base, status as u32);
        return STATUS_INSUFFICIENT_RESOURCES;
    }
    ZwClose(thread);

    match publish(fdo, disk) {
        Ok(d) => fdo.disk = d,
        Err(status) => vlog!("virtio-mmio {:#x}: disk IoCreateDevice failed {:#010x}", base, status as u32),
    }
    STATUS_SUCCESS
}

/// Connect the slot's interrupt and switch the device's notifications on.
/// Without one (no resource, or the connect fails) transfers are polled.
unsafe fn connect(fdo: &mut Fdo, irq: Option<(ULONG, u8, usize, bool, bool)>) {
    let base = fdo.regs;
    let Some((vector, level, affinity, latched, shared)) = irq else {
        vlog!("virtio-mmio {:#x}: START_DEVICE carried no interrupt; polling", base);
        return;
    };
    let i = &raw mut fdo.irq;
    KeInitializeEvent(&raw mut (*i).event, SYNCHRONIZATION_EVENT as _, 0);
    KeInitializeDpc(&raw mut (*i).dpc, Some(dpc), i.cast());
    // The line can already be asserted (the device raises it during setup,
    // whatever the driver asked for), and it is level-triggered: the ISR must
    // claim it from the moment the GIC enables it, or it fires forever.
    let pending = (*i).regs.add(REG_INTERRUPT_STATUS).cast::<u32>().read_volatile();
    (*i).regs.add(REG_INTERRUPT_ACK).cast::<u32>().write_volatile(pending);
    (*i).armed.store(true, Ordering::Release);
    let status = IoConnectInterrupt(
        &raw mut (*i).interrupt,
        Some(isr),
        i.cast(),
        null_mut(),
        vector,
        level,
        level,
        if latched { _KINTERRUPT_MODE_Latched } else { _KINTERRUPT_MODE_LevelSensitive },
        shared as u8,
        affinity as _,
        0,
    );
    if status < 0 {
        (*i).armed.store(false, Ordering::Release);
        vlog!("virtio-mmio {:#x}: IoConnectInterrupt (vector {}) failed {:#010x}; polling", base, vector, status as u32);
        return;
    }
    if let Some(blk) = fdo.blk.as_mut() {
        blk.enable_interrupts();
    }
    vlog!(
        "virtio-mmio {:#x}: interrupt connected: vector {}, level {}, {}",
        base,
        vector,
        level,
        if latched { "latched" } else { "level-sensitive" }
    );
}

/// Read the first sectors back, so the boot log shows the data path working,
/// and whether its interrupt does, before anything above depends on them.
unsafe fn self_test(fdo: &mut Fdo) {
    let base = fdo.regs;
    let sectors = (ARENA_LEN / SECTOR_SIZE) as u64;
    let n = sectors.min(fdo.blk.as_ref().map_or(0, |b| b.capacity())) as usize;
    if n == 0 {
        return;
    }
    if let Err(e) = transfer(fdo, false, 0, n * SECTOR_SIZE) {
        vlog!("virtio-mmio {:#x}: self-test read failed: {}", base, e);
        return;
    }
    let first = core::slice::from_raw_parts(fdo.arena, SECTOR_SIZE);
    vlog!(
        "virtio-mmio {:#x}: self-test: read {} KiB, block 0 {}",
        base,
        n * SECTOR_SIZE / 1024,
        if first[510] == 0x55 && first[511] == 0xAA { "holds an MBR" } else { "has no MBR signature" }
    );
    if !fdo.irq.armed.load(Ordering::Acquire) {
        return;
    }
    // The read may have completed before the transfer first looked, so it says
    // nothing about the interrupt; the ISR's count does. Give a late one a second.
    for _ in 0..1000 / INTERRUPT_POLL_MS {
        if fdo.irq.claimed.load(Ordering::Relaxed) != 0 {
            break;
        }
        let mut interval: LARGE_INTEGER = core::mem::zeroed();
        interval.QuadPart = -10_000 * INTERRUPT_POLL_MS;
        KeWaitForSingleObject((&raw mut fdo.irq.event).cast(), 0, 0, 0, &mut interval);
    }
    match fdo.irq.claimed.load(Ordering::Relaxed) {
        0 => vlog!("virtio-mmio {:#x}: no interrupt arrived for the self-test read; transfers will poll", base),
        _ => vlog!("virtio-mmio {:#x}: interrupts working", base),
    }
}

/// Move `bytes` (at most the arena) between sector `lba` and the arena,
/// waiting for the completion.
unsafe fn transfer(fdo: &mut Fdo, write: bool, lba: u64, bytes: usize) -> Result<(), &'static str> {
    let Some(blk) = fdo.blk.as_mut() else { return Err("device not started") };
    let buf = core::slice::from_raw_parts_mut(fdo.arena, bytes);
    let (req, resp) = (&mut *fdo.req, &mut *fdo.resp);
    let token = if write {
        blk.write_blocks_nb(lba as usize, req, buf, resp)
    } else {
        blk.read_blocks_nb(lba as usize, req, buf, resp)
    }
    .map_err(|_| "the virtqueue refused the request")?;
    // The DPC wakes this on the slot's interrupt; the timeout is the poll
    // that keeps a lost interrupt from losing the disk.
    while blk.peek_used() != Some(token) {
        let mut interval: LARGE_INTEGER = core::mem::zeroed();
        interval.QuadPart = -10_000 * INTERRUPT_POLL_MS;
        KeWaitForSingleObject((&raw mut fdo.irq.event).cast(), 0, 0, 0, &mut interval);
    }
    let done = if write {
        blk.complete_write_blocks(token, req, buf, resp)
    } else {
        blk.complete_read_blocks(token, req, buf, resp)
    };
    done.map_err(|_| "the device failed the request")
}

unsafe fn publish(fdo: &mut Fdo, disk: Disk) -> Result<PDEVICE_OBJECT, NTSTATUS> {
    let mut device: PDEVICE_OBJECT = null_mut();
    let status = IoCreateDevice(
        (*fdo.device).DriverObject,
        size_of::<DiskExt>() as ULONG,
        null_mut(),
        FILE_DEVICE_MASS_STORAGE,
        FILE_AUTOGENERATED_DEVICE_NAME | FILE_DEVICE_SECURE_OPEN,
        0,
        &mut device,
    );
    if status < 0 {
        return Err(status);
    }
    if !record(device) {
        ntkrnl_sys::ddk::IoDeleteDevice(device);
        return Err(STATUS_INSUFFICIENT_RESOURCES);
    }
    ((*device).DeviceExtension as *mut DiskExt).write(DiskExt { kind: SLOT_DISK_KIND, fdo, disk, claimed: AtomicBool::new(false) });
    (*device).Flags |= DO_DIRECT_IO;
    (*device).Flags &= !DO_DEVICE_INITIALIZING;
    Ok(device)
}

