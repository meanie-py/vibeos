unsafe fn queue_to_worker(fdo: *mut Fdo, irp: PIRP) -> NTSTATUS {
    IoMarkIrpPending(irp);
    {
        let _g = ntkrnl_sys::guards::SpinLockGuard::acquire(&raw mut (*fdo).lock);
        InsertTailList(&raw mut (*fdo).queue, &raw mut (*irp).Tail.Overlay.__bindgen_anon_2.ListEntry);
    }
    KeSetEvent(&raw mut (*fdo).event, 0, 0);
    STATUS_PENDING
}

unsafe fn disk_dispatch(device: PDEVICE_OBJECT, ext: &DiskExt, irp: PIRP) -> NTSTATUS {
    let io = IoGetCurrentIrpStackLocation(irp);
    match (*io).MajorFunction {
        IRP_MJ_SCSI => {
            let srb = (*io).Parameters.Scsi.Srb as *mut Srb;
            match (*srb).Function {
                // Moving data, and flushing, are the worker's.
                scsidisk::SRB_FUNCTION_EXECUTE_SCSI | scsidisk::SRB_FUNCTION_FLUSH | scsidisk::SRB_FUNCTION_SHUTDOWN => {
                    (*srb).SrbStatus = scsidisk::SRB_STATUS_PENDING;
                    queue_to_worker(ext.fdo, irp)
                }
                scsidisk::SRB_FUNCTION_CLAIM_DEVICE => {
                    if ext.claimed.swap(true, Ordering::AcqRel) {
                        (*srb).SrbStatus = scsidisk::SRB_STATUS_BUSY;
                        return complete(irp, STATUS_DEVICE_BUSY, 0);
                    }
                    (*srb).DataBuffer = device.cast();
                    (*srb).SrbStatus = scsidisk::SRB_STATUS_SUCCESS;
                    complete(irp, STATUS_SUCCESS, 0)
                }
                scsidisk::SRB_FUNCTION_RELEASE_DEVICE => {
                    ext.claimed.store(false, Ordering::Release);
                    (*srb).SrbStatus = scsidisk::SRB_STATUS_SUCCESS;
                    complete(irp, STATUS_SUCCESS, 0)
                }
                // One request at a time, completed in order: nothing to
                // release, flush or lock in the queue itself.
                scsidisk::SRB_FUNCTION_RELEASE_QUEUE
                | scsidisk::SRB_FUNCTION_FLUSH_QUEUE
                | scsidisk::SRB_FUNCTION_LOCK_QUEUE
                | scsidisk::SRB_FUNCTION_UNLOCK_QUEUE => {
                    (*srb).SrbStatus = scsidisk::SRB_STATUS_SUCCESS;
                    complete(irp, STATUS_SUCCESS, 0)
                }
                // Miniport IOCTLs (SMART and the like): classpnp asks on every
                // disk and there is nothing to answer.
                SRB_FUNCTION_IO_CONTROL => {
                    (*srb).SrbStatus = scsidisk::SRB_STATUS_INVALID_REQUEST;
                    complete(irp, scsidisk::STATUS_NOT_SUPPORTED, 0)
                }
                f => {
                    vlog!("virtio-mmio: SRB function {:#04x} not supported", f);
                    (*srb).SrbStatus = scsidisk::SRB_STATUS_INVALID_REQUEST;
                    complete(irp, scsidisk::STATUS_NOT_SUPPORTED, 0)
                }
            }
        }
        IRP_MJ_DEVICE_CONTROL => {
            let p = (*io).Parameters.DeviceIoControl;
            let (inl, outl) = (p.InputBufferLength as usize, p.OutputBufferLength as usize);
            let sys = (*irp).AssociatedIrp.SystemBuffer as *mut u8;
            let buf: &mut [u8] = if sys.is_null() { &mut [] } else { core::slice::from_raw_parts_mut(sys, inl.max(outl)) };
            let (status, n) = scsidisk::device_control(&ext.disk, p.IoControlCode, buf, inl, outl);
            complete(irp, status, n)
        }
        IRP_MJ_PNP => disk_pnp(device, ext, irp, io),
        IRP_MJ_POWER => {
            PoStartNextPowerIrp(irp);
            complete(irp, STATUS_SUCCESS, 0)
        }
        IRP_MJ_CREATE | IRP_MJ_CLOSE => complete(irp, STATUS_SUCCESS, 0),
        _ => {
            let status = status_of(irp);
            complete(irp, status, (*irp).IoStatus.Information as usize)
        }
    }
}

/// A multi-sz (or a plain string) of `parts` in paged pool, for QUERY_ID / DEVICE_TEXT.
unsafe fn wide(parts: &[&[u8]], multi: bool) -> PVOID {
    let chars: usize = parts.iter().map(|p| p.len() + 1).sum::<usize>() + multi as usize;
    let p = ExAllocatePoolWithTag(PAGED_POOL as _, (chars * 2) as _, VIOBLK_POOL_TAG) as *mut u16;
    if p.is_null() {
        return null_mut();
    }
    let mut at = 0;
    for part in parts {
        for &b in *part {
            *p.add(at) = b as u16;
            at += 1;
        }
        *p.add(at) = 0;
        at += 1;
    }
    if multi {
        *p.add(at) = 0;
    }
    p.cast()
}

/// `SCSI\Disk` + the INQUIRY vendor, product and revision, spaces as `_`,
/// the way Windows names a SCSI disk: `SCSI\DiskVirtIO__Block_Device____1.0_`.
fn scsi_id(disk: &Disk, out: &mut [u8; 37]) {
    out[..9].copy_from_slice(b"SCSI\\Disk");
    for (o, &b) in out[9..].iter_mut().zip(disk.vendor.iter().chain(&disk.product).chain(&disk.revision)) {
        *o = if b == b' ' || b == b',' { b'_' } else { b };
    }
}

unsafe fn disk_pnp(device: PDEVICE_OBJECT, ext: &DiskExt, irp: PIRP, io: PIO_STACK_LOCATION) -> NTSTATUS {
    match (*io).MinorFunction {
        IRP_MN_START_DEVICE
        | IRP_MN_QUERY_REMOVE_DEVICE
        | IRP_MN_CANCEL_REMOVE_DEVICE
        | IRP_MN_STOP_DEVICE
        | IRP_MN_QUERY_STOP_DEVICE
        | IRP_MN_CANCEL_STOP_DEVICE
        | IRP_MN_SURPRISE_REMOVAL
        | IRP_MN_DEVICE_USAGE_NOTIFICATION
        // The disk lives as long as its slot: a removal leaves it.
        | IRP_MN_REMOVE_DEVICE => complete(irp, STATUS_SUCCESS, 0),
        IRP_MN_QUERY_ID => {
            let mut full = [0u8; 37];
            scsi_id(&ext.disk, &mut full);
            let ids = match (*io).Parameters.QueryId.IdType as i32 {
                BUS_QUERY_DEVICE_ID => wide(&[&full], false),
                // Most specific first; GenDisk is what the critical device database maps to disk.sys.
                BUS_QUERY_HARDWARE_IDS => wide(&[&full, &full[..33], &full[..17], b"SCSI\\Disk", b"GenDisk"], true),
                BUS_QUERY_COMPATIBLE_IDS => wide(&[b"SCSI\\Disk", b"GenDisk"], true),
                // One disk per slot, and the slot's own instance tells slots apart.
                BUS_QUERY_INSTANCE_ID => wide(&[b"0"], false),
                _ => return complete(irp, status_of(irp), (*irp).IoStatus.Information as usize),
            };
            if ids.is_null() {
                return complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0);
            }
            complete(irp, STATUS_SUCCESS, ids as usize)
        }
        IRP_MN_QUERY_DEVICE_TEXT
            if (*io).Parameters.QueryDeviceText.DeviceTextType as i32 == DEVICE_TEXT_DESCRIPTION =>
        {
            let text = wide(&[b"VirtIO Block Device"], false);
            if text.is_null() {
                return complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0);
            }
            complete(irp, STATUS_SUCCESS, text as usize)
        }
        IRP_MN_QUERY_CAPABILITIES => {
            let caps = &mut *(*io).Parameters.DeviceCapabilities.Capabilities;
            caps.set_Removable(0);
            caps.set_UniqueID(0);
            caps.set_SilentInstall(1);
            caps.set_RawDeviceOK(0);
            caps.set_SurpriseRemovalOK(0);
            caps.Address = 0;
            caps.UINumber = 0;
            for (i, s) in caps.DeviceState.iter_mut().enumerate() {
                *s = if i == POWER_SYSTEM_WORKING { POWER_DEVICE_D0 } else { POWER_DEVICE_D3 } as _;
            }
            complete(irp, STATUS_SUCCESS, 0)
        }
        IRP_MN_QUERY_DEVICE_RELATIONS
            if (*io).Parameters.QueryDeviceRelations.Type as i32 == TARGET_DEVICE_RELATION =>
        {
            let mut out: PVOID = null_mut();
            let status = relations(null_mut(), &[device], &mut out);
            complete(irp, status, out as usize)
        }
        // Resources, bus information, device state, ...: nothing to add.
        _ => complete(irp, status_of(irp), (*irp).IoStatus.Information as usize),
    }
}

// ---------------------------------------------------------------------------
// The worker: every request runs here, at PASSIVE_LEVEL, in order
// ---------------------------------------------------------------------------

unsafe extern "system" fn worker(context: PVOID) {
    let fdo = context as *mut Fdo;
    loop {
        KeWaitForSingleObject((&raw mut (*fdo).event).cast(), 0, 0, 0, null_mut());
        loop {
            let entry = {
                let _g = ntkrnl_sys::guards::SpinLockGuard::acquire(&raw mut (*fdo).lock);
                if IsListEmpty(&raw const (*fdo).queue) { null_mut() } else { RemoveHeadList(&raw mut (*fdo).queue) }
            };
            if entry.is_null() {
                break;
            }
            let irp = (entry as *mut u8).sub(offset_of!(IRP, Tail.Overlay.__bindgen_anon_2.ListEntry)) as PIRP;
            execute(&mut *fdo, irp);
        }
    }
}

unsafe fn flush(fdo: &mut Fdo) -> Result<(), scsidisk::Sense> {
    // virtio-drivers has no non-blocking flush; it is rare and short.
    match fdo.blk.as_mut().map(|b| b.flush()) {
        Some(Ok(())) => Ok(()),
        _ => {
            vlog!("virtio-mmio {:#x}: flush failed", fdo.regs);
            Err(scsidisk::media_error(true))
        }
    }
}

unsafe fn execute(fdo: &mut Fdo, irp: PIRP) {
    let io = IoGetCurrentIrpStackLocation(irp);
    let ext = &*((*(*io).DeviceObject).DeviceExtension as *const DiskExt);
    let srb = (*io).Parameters.Scsi.Srb as *mut Srb;
    if (*srb).Function != scsidisk::SRB_FUNCTION_EXECUTE_SCSI {
        // SRB_FUNCTION_FLUSH / SHUTDOWN.
        let ok = flush(fdo).is_ok();
        (*srb).SrbStatus = if ok { scsidisk::SRB_STATUS_SUCCESS } else { scsidisk::SRB_STATUS_ERROR };
        complete(irp, if ok { STATUS_SUCCESS } else { scsidisk::STATUS_IO_DEVICE_ERROR }, 0);
        return;
    }

    let mut data = (*srb).DataBuffer as *mut u8;
    let len = (*srb).DataTransferLength as usize;
    let mdl = (*irp).MdlAddress;
    if len != 0 && !mdl.is_null() {
        // DataBuffer is an address in the MDL's range; reach it through the
        // system mapping, since the worker is not in the requester's context.
        let system = MmGetSystemAddressForMdlSafe(mdl, NORMAL_PAGE_PRIORITY) as *mut u8;
        if system.is_null() {
            (*srb).SrbStatus = scsidisk::SRB_STATUS_ERROR;
            complete(irp, STATUS_INSUFFICIENT_RESOURCES, 0);
            return;
        }
        let va = ((*mdl).StartVa as usize) + (*mdl).ByteOffset as usize;
        data = system.add(data as usize - va);
    }
    let buf: &mut [u8] = if data.is_null() || len == 0 { &mut [] } else { core::slice::from_raw_parts_mut(data, len) };
    let result = match scsidisk::decode(&ext.disk, &(*srb).Cdb, buf) {
        Request::Done(r) => r,
        Request::Flush => flush(fdo).map(|()| 0),
        Request::Read { lba, blocks } => run(fdo, false, lba, blocks, buf),
        Request::Write { lba, blocks } => run(fdo, true, lba, blocks, buf),
    };
    let status = scsidisk::finish(srb, result);
    let n = if status >= 0 { (*srb).DataTransferLength as usize } else { 0 };
    (*irp).IoStatus.__bindgen_anon_1.Status = status;
    (*irp).IoStatus.Information = n as _;
    IoCompleteRequest(irp, IO_DISK_INCREMENT);
}

/// A read or write of `blocks` sectors at `lba`, through the arena a chunk at a time.
unsafe fn run(fdo: &mut Fdo, write: bool, lba: u64, blocks: u64, buf: &mut [u8]) -> Result<usize, scsidisk::Sense> {
    let total = blocks as usize * SECTOR_SIZE;
    let mut done = 0;
    while done < total {
        let chunk = (total - done).min(ARENA_LEN);
        let sector = lba + (done / SECTOR_SIZE) as u64;
        if write {
            core::ptr::copy_nonoverlapping(buf[done..].as_ptr(), fdo.arena, chunk);
        }
        if let Err(e) = transfer(fdo, write, sector, chunk) {
            vlog!(
                "virtio-mmio {:#x}: {} of {} sectors at {}: {}",
                fdo.regs,
                if write { "write" } else { "read" },
                chunk / SECTOR_SIZE,
                sector,
                e
            );
            return Err(scsidisk::media_error(write));
        }
        if !write {
            core::ptr::copy_nonoverlapping(fdo.arena, buf[done..].as_mut_ptr(), chunk);
        }
        done += chunk;
    }
    Ok(total)
}
