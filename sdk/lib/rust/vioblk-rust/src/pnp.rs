//! The PnP front end: virtio-blk on the virtio-mmio transport, which is how
//! QEMU's arm64 `virt` machine attaches a `virtio-blk-device` disk.
//!
//! SCSIPORT cannot reach these. It finds adapters by its own legacy bus scan,
//! and a virtio-mmio slot is on no bus it scans: the only description is the
//! ACPI node (_HID LNRO0005), which the arm64 HAL's PnP root publishes as
//! `ACPI\LNRO0005&DEV_0002` with the slot's registers and SPI as boot
//! resources (hal-rust/src/arm64/pnpdd.rs). So the driver takes those stacks
//! itself, in the shape nvme.sys uses:
//!
//!   disk.sys FDO (+ partmgr)          classpnp sends SRBs and storage IOCTLs
//!   our disk PDO                      ── queued to the slot's worker ──┐
//!   our FDO                           IRP_MN_START_DEVICE: bring it up │
//!   HAL PDO (ACPI\LNRO0005&DEV_0002)                                   │
//!                                     worker: one request at a time ◄──┘
//!
//! The SCSI side is the shared scsidisk layer; the virtio side is the same
//! `virtio-drivers` block device the miniport drives, over `MmioTransport`
//! instead of `PciTransport`. A transfer waits on the slot's interrupt (ISR
//! acks the slot, DPC wakes the worker), with a 10 ms poll behind it so a lost
//! interrupt costs time rather than the disk.
//!
//! SCSIPORT has already claimed the driver object's dispatch table for the PCI
//! adapters by the time this installs, so `install` keeps its entries and
//! routes by device object: the stacks created here are recorded in DEVICES,
//! and every other IRP goes to SCSIPORT's handler exactly as before.

