//! COBJMACROS-shaped call helpers (`IFoo_Method(p, ...)`) — the role the C macros from the
//! COBJMACROS headers played for the wine sources. Bodies call straight through the vtbl
//! slot; `unwrap_unchecked()` on the `Option<fn>` keeps C semantics exactly (a NULL slot
//! faults at the call, same as C).
//!
//! GENERATED — do not hand-edit. Regenerate all three with:
//!
//! ```sh
//! COM='IUnknown,IDispatch,IRecordInfo,IClassFactory,IClassFactory2,IMoniker,IRunningObjectTable,IPSFactoryBuffer,IMalloc,IEnumConnections,IEnumConnectionPoints,IEnumOleUndoUnits,IEnumVARIANT,IPersistMemory,IPropertyBag,IAdviseSinkEx,ITypeComp,ITypeInfo,ITypeInfo2,ITypeLib,ITypeLib2,IConnectionPoint,IConnectionPointContainer,IFont,IFontDisp,IFontEventsDisp,IPicture,IPictureDisp,IPersist,IPersistStream,IPersistStreamInit,IPersistPropertyBag,IPropertyNotifySink,IPropertyPage,IPropertyPageSite,IStream,IBindCtx'
//! WIC='IWICBitmapSource,IWICBitmapDecoder,IWICBitmapFrameDecode,IWICImagingFactory,IWICStream'
//! for a in i386 amd64 arm64; do
//!   tools/gen_commacros.py --bindgen sdk/lib/rust/com-sys/src/bindgen_$a.rs --only "$COM" -o /tmp/com_$a.rs
//!   tools/gen_commacros.py --bindgen sdk/lib/rust/oleaut32-rust/src/win_sys_$a.rs --only "$WIC" -o /tmp/wic_$a.rs
//!   { echo '// GENERATED by tools/gen_commacros.py — do not hand-edit. See commacros_gen.rs.'
//!     tail -n +10 /tmp/com_$a.rs; echo
//!     echo '// ===== WIC (wincodec.h): vtbls come from the win_sys island, not com-sys ====='
//!     tail -n +11 /tmp/wic_$a.rs; } > sdk/lib/rust/oleaut32-rust/src/commacros_$a.rs
//! done
//! ```
//!
//! **Two sources, on purpose.** The COM interfaces come from com-sys's bindgen; the five WIC
//! interfaces come from the `win_sys` island (com-sys does not wrap wincodec.h). Both are
//! bindgen output, so both carry the real vtbl slot order — which is the point: a hand-written
//! vtbl call with one slot out of place calls the wrong method, silently, with no compile or
//! link error.
//!
//! **PER-ARCH, and the cfg below is not ceremony.** A method whose *parameter* is a function
//! pointer (e.g. `IViewObject::Draw`'s `pfnContinue`) carries that callback's calling
//! convention in its type, and bindgen spells it per-arch — so an amd64-generated file fails
//! i386 with `expected "stdcall" fn, found "C" fn`. As it happens, none of the 42 interfaces
//! selected above takes a callback parameter today, so the three files are currently
//! byte-identical (`diff commacros_i386.rs commacros_amd64.rs` is empty). That is a property
//! of the current interface set, NOT an invariant — add one interface with a callback param
//! and the files diverge. Keeping them cfg-selected means that day is a no-op instead of a
//! silent i386 stack corruption.
//!
//! The wrapper bodies themselves never name a calling convention: they invoke the `Option<fn>`
//! slot, whose type already encodes STDMETHODCALLTYPE per arch (stdcall on i386, C elsewhere).
#![allow(clippy::all)]

#[cfg(target_arch = "x86")]
include!("commacros_i386.rs");

#[cfg(target_arch = "x86_64")]
include!("commacros_amd64.rs");

#[cfg(target_arch = "aarch64")]
include!("commacros_arm64.rs");
