// sdk/lib/crt/except/amd64/chkstk_ms.s -- `__chkstk` with `__alloca_probe` and a weak
// `___chkstk_ms` on the same address. The .s's `.PROC`/`.pushreg`/`.endprolog` are the
// asm.inc spellings of the SEH directives written out here.
#[cfg(target_arch = "x86_64")]
core::arch::global_asm!(
    ".intel_syntax noprefix",
    ".text",
    ".globl __chkstk",
    ".globl __alloca_probe",
    ".weak ___chkstk_ms",
    "__alloca_probe:",
    "___chkstk_ms:",
    "__chkstk:",
    ".seh_proc __chkstk",
    "    push rcx",
    ".seh_pushreg rcx",
    "    push rax",
    ".seh_pushreg rax",
    ".seh_endprologue",
    "    cmp rax, 4096",
    "    lea rcx, [rsp + 24]",
    "    jb .Lchkstk64_less",
    ".Lchkstk64_more:",
    "    sub rcx, 4096",
    "    or byte ptr [rcx], 0",
    "    sub rax, 4096",
    "    cmp rax, 4096",
    "    ja .Lchkstk64_more",
    ".Lchkstk64_less:",
    "    sub rcx, rax",
    "    or byte ptr [rcx], 0",
    "    pop rax",
    "    pop rcx",
    "    ret",
    ".seh_endproc",
    ".att_syntax prefix",
);
