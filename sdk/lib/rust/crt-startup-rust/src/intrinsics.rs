// sdk/lib/crt/math/i386/alldiv_asm.s
#[cfg(target_arch = "x86")]
core::arch::global_asm!(
    ".intel_syntax noprefix",
    ".text",
    ".globl __alldiv",
    "__alldiv:",
    "    push edi",
    "    push esi",
    "    push ebx",
    "    xor edi,edi",
    "    mov eax,[esp + 20]",
    "    or eax,eax",
    "    jge .Lalldiv_L1",
    "    inc edi",
    "    mov edx,[esp + 16]",
    "    neg eax",
    "    neg edx",
    "    sbb eax,0",
    "    mov [esp + 20],eax",
    "    mov [esp + 16],edx",
    ".Lalldiv_L1:",
    "    mov eax,[esp + 28]",
    "    or eax,eax",
    "    jge .Lalldiv_L2",
    "    inc edi",
    "    mov edx,[esp + 24]",
    "    neg eax",
    "    neg edx",
    "    sbb eax,0",
    "    mov [esp + 28],eax",
    "    mov [esp + 24],edx",
    ".Lalldiv_L2:",
    "    or eax,eax",
    "    jnz .Lalldiv_L3",
    "    mov ecx,[esp + 24]",
    "    mov eax,[esp + 20]",
    "    xor edx,edx",
    "    div ecx",
    "    mov ebx,eax",
    "    mov eax,[esp + 16]",
    "    div ecx",
    "    mov edx,ebx",
    "    jmp .Lalldiv_L4",
    ".Lalldiv_L3:",
    "    mov ebx,eax",
    "    mov ecx,[esp + 24]",
    "    mov edx,[esp + 20]",
    "    mov eax,[esp + 16]",
    ".Lalldiv_L5:",
    "    shr ebx,1",
    "    rcr ecx,1",
    "    shr edx,1",
    "    rcr eax,1",
    "    or ebx,ebx",
    "    jnz .Lalldiv_L5",
    "    div ecx",
    "    mov esi,eax",
    "    mul dword ptr [esp + 28]",
    "    mov ecx,eax",
    "    mov eax,[esp + 24]",
    "    mul esi",
    "    add edx,ecx",
    "    jc .Lalldiv_L6",
    "    cmp edx,[esp + 20]",
    "    ja .Lalldiv_L6",
    "    jb .Lalldiv_L7",
    "    cmp eax,[esp + 16]",
    "    jbe .Lalldiv_L7",
    ".Lalldiv_L6:",
    "    dec esi",
    ".Lalldiv_L7:",
    "    xor edx,edx",
    "    mov eax,esi",
    ".Lalldiv_L4:",
    "    dec edi",
    "    jnz .Lalldiv_L8",
    "    neg edx",
    "    neg eax",
    "    sbb edx,0",
    ".Lalldiv_L8:",
    "    pop ebx",
    "    pop esi",
    "    pop edi",
    "    ret 16",
    ".att_syntax prefix",
);

