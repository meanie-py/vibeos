//! The compiler-support entry points msvcrtex linked as assembly (msvcrtex_asm): the
//! stack probes clang calls for frames over a page (`_chkstk`, `_alloca_probe[_16]`,
//! mingw's `___chkstk_ms`), the i386 64-bit division helpers (`_alldiv`, `_aulldiv`), and
//! i386 `ceilf`/`floorf` (x86 msvcrt.dll has no float variants, and clang lowers to them).
//! Transcribed instruction for instruction from the .s files named above each block: their
//! `#define`d stack offsets expanded and labels renamed per file so they cannot collide.
//! Windows only (PE names; the division helpers clean up with `ret 16`).

// sdk/lib/crt/except/i386/chkstk_asm.s
#[cfg(target_arch = "x86")]
core::arch::global_asm!(
    ".intel_syntax noprefix",
    ".text",
    ".globl __chkstk",
    ".globl __alloca_probe",
    ".globl __alloca_probe_16",
    ".globl ___alloca",
    "__alloca_probe_16:",
    "    push ecx",
    "    lea ecx, [esp + 8]",
    "    sub ecx, eax",
    "    and ecx, 15",
    "    add eax, ecx",
    "    jnc .Lchkstk_l1",
    "    mov eax, 0xffffffff",
    ".Lchkstk_l1:",
    "    pop ecx",
    "__chkstk:",
    "__alloca_probe:",
    "___alloca:",
    "    push ecx",
    "    lea ecx, [esp + 8]",
    "    cmp eax, 4096",
    "    jl .Lchkstk_l_LessThanAPage",
    ".Lchkstk_l_MoreThanAPage:",
    "    sub ecx, 4096",
    "    test [ecx], eax",
    "    sub eax, 4096",
    "    cmp eax, 4096",
    "    jge .Lchkstk_l_MoreThanAPage",
    ".Lchkstk_l_LessThanAPage:",
    "    sub ecx, eax",
    "    test [ecx], eax",
    "    mov eax, esp",
    "    mov esp, ecx",
    "    mov ecx, [eax]",
    "    mov eax, [eax + 4]",
    "    push eax",
    "    ret",
    ".att_syntax prefix",
);

