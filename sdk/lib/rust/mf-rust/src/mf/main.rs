unsafe extern "C" fn mf_get_handler_strings(
    mut path: *const WCHAR,
    mut filter: WCHAR,
    mut maxlen: ::core::ffi::c_uint,
    mut dst: *mut PROPVARIANT,
) -> HRESULT {
    static mut hkey_roots: [HKEY; 2] = [HKEY_CURRENT_USER, HKEY_LOCAL_MACHINE];
    let mut capacity: ::core::ffi::c_uint = 0 as ::core::ffi::c_uint;
    let mut count: ::core::ffi::c_uint = 0;
    let mut hr: HRESULT = S_OK;
    let mut i: ::core::ffi::c_int = 0 as ::core::ffi::c_int;
    let mut index: ::core::ffi::c_int = 0;
    let mut buffW: *mut WCHAR = ::core::ptr::null_mut::<WCHAR>();
    let mut size: DWORD = 0;
    buffW = calloc((maxlen as size_t) as _, (::core::mem::size_of::<WCHAR>() as size_t) as _) as *mut WCHAR;
    if buffW.is_null() {
        return E_OUTOFMEMORY;
    }
    memset(
        dst as *mut ::core::ffi::c_void,
        0 as ::core::ffi::c_int,
        ::core::mem::size_of::<PROPVARIANT>() as size_t,
    );
    (*dst).vt = (VT_VECTOR as ::core::ffi::c_int | VT_LPWSTR as ::core::ffi::c_int) as VARTYPE;
    i = 0 as ::core::ffi::c_int;
    while (i as usize) < ARRAY_SIZE!(hkey_roots) as usize {
        let mut hkey: HKEY = ::core::ptr::null_mut::<HKEY__>();
        if !(RegOpenKeyW(hkey_roots[i as usize], path as LPCWSTR, ::core::ptr::addr_of_mut!(hkey)) != 0) {
            index = 0 as ::core::ffi::c_int;
            size = maxlen as DWORD;
            count = (*dst).__bindgen_anon_1.calpwstr.cElems as ::core::ffi::c_uint;
            loop {
                let fresh15 = index;
                index = index + 1;
                if !(RegEnumKeyExW(
                    hkey,
                    fresh15 as DWORD,
                    buffW as LPWSTR,
                    ::core::ptr::addr_of_mut!(size),
                    ::core::ptr::null_mut::<DWORD>(),
                    ::core::ptr::null_mut::<WCHAR>(),
                    ::core::ptr::null_mut::<DWORD>(),
                    ::core::ptr::null_mut::<_FILETIME>(),
                ) == 0)
                {
                    break;
                }
                if filter as ::core::ffi::c_int != 0 && wcschr(buffW, filter as wchar_t).is_null() {
                    size = maxlen as DWORD;
                } else {
                    hr = prop_string_vector_append(
                        dst,
                        ::core::ptr::addr_of_mut!(capacity),
                        (i > 0 as ::core::ffi::c_int) as ::core::ffi::c_int,
                        buffW,
                    );
                    if hr < 0 as HRESULT {
                        break;
                    }
                    size = maxlen as DWORD;
                }
            }
            qsort(
                (*dst).__bindgen_anon_1.calpwstr.pElems.offset(count as isize) as *mut LPWSTR
                    as *mut ::core::ffi::c_void,
                (*dst)

                    .__bindgen_anon_1.calpwstr
                    .cElems
                    .wrapping_sub(count as ULONG) as size_t,
                ::core::mem::size_of::<WCHAR>() as size_t,
                Some(
                    qsort_string_compare
                        as unsafe extern "C" fn(
                            *const ::core::ffi::c_void,
                            *const ::core::ffi::c_void,
                        ) -> ::core::ffi::c_int,
                ),
            );
            RegCloseKey(hkey);
        }
        i += 1;
    }
    if hr < 0 as HRESULT {
        PropVariantClear(dst);
    }
    free(buffW as *mut ::core::ffi::c_void);
    return hr;
}

