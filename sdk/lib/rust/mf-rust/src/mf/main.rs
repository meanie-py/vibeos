pub unsafe extern "C" fn debugstr_media_type(mut media_type: *mut IMFMediaType) -> *const ::core::ffi::c_char {
    let mut channels: UINT = 0;
    let mut sps: UINT = 0;
    let mut subtype: GUID = GUID {
        Data1: 0,
        Data2: 0,
        Data3: 0,
        Data4: [0; 8],
    };
    let mut frame_size: UINT64 = 0;

    if media_type.is_null() {
        return b"{null}\0" as *const u8 as *const core::ffi::c_char;
    }

    IMFMediaType_GetGUID(media_type, &raw const MF_MT_SUBTYPE, &raw mut subtype);

    if (IMFMediaType_GetUINT64(media_type, &raw const MF_MT_FRAME_SIZE, &raw mut frame_size) >= 0)
        && frame_size != 0
    {
        return wine_dbg_sprintf(
            b"{%p %s %ux%u}\0" as *const u8 as *const core::ffi::c_char,
            media_type,
            debugstr_mf_guid(&raw mut subtype),
            (frame_size >> 32) as UINT,
            frame_size as UINT32,
        );
    } else if (IMFMediaType_GetUINT32(media_type, &raw const MF_MT_AUDIO_NUM_CHANNELS, &raw mut channels) >= 0)
        && channels != 0
    {
        if IMFMediaType_GetUINT32(media_type, &raw const MF_MT_AUDIO_SAMPLES_PER_SECOND, &raw mut sps) >= 0 {
            return wine_dbg_sprintf(
                b"{%p %s %u-ch %u}\0" as *const u8 as *const core::ffi::c_char,
                media_type,
                debugstr_mf_guid(&raw mut subtype),
                channels,
                sps,
            );
        }
        return wine_dbg_sprintf(
            b"{%p %s %u-ch}\0" as *const u8 as *const core::ffi::c_char,
            media_type,
            debugstr_mf_guid(&raw mut subtype),
            channels,
        );
    } else {
        return wine_dbg_sprintf(
            b"{%p %s ?}\0" as *const u8 as *const core::ffi::c_char,
            media_type,
            debugstr_mf_guid(&raw mut subtype),
        );
    }
}

