// ===========================================================================
// amd64 IRQL helpers (CONTRACT2 trap B). hidclass.c does NOT raise/lower IRQL
// explicitly (it uses KeAcquireSpinLock/KeReleaseSpinLock which manage IRQL
// internally), so these are provided for completeness but currently unused.
// ===========================================================================
#[inline]
pub unsafe fn KeRaiseIrqlInternal(new: ntkrnl_sys::base::KIRQL, old: *mut ntkrnl_sys::base::KIRQL) {
    #[cfg(not(target_arch = "x86_64"))]
    {
        ntkrnl_sys::inline::tier1::KeRaiseIrqlInternal(new, old);
    }
    #[cfg(target_arch = "x86_64")]
    {
        *old = ntkrnl_sys::inline::ke::KfRaiseIrql_amd64(new);
    }
}
#[inline]
pub unsafe fn KeLowerIrqlInternal(new: ntkrnl_sys::base::KIRQL) {
    #[cfg(not(target_arch = "x86_64"))]
    {
        ntkrnl_sys::inline::tier1::KeLowerIrqlInternal(new);
    }
    #[cfg(target_arch = "x86_64")]
    {
        ntkrnl_sys::inline::ke::KeLowerIrql_amd64(new);
    }
}

