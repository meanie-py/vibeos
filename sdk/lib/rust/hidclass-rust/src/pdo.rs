// ---------------------------------------------------------------------------
// Wide-string literal helper: compile-time L"..." → null-terminated [u16; N+1].
// ---------------------------------------------------------------------------
macro_rules! wstr {
    ($s:expr) => {{
        const S: &str = $s;
        const N: usize = S.len();
        const ARR: [u16; N + 1] = {
            let bytes = S.as_bytes();
            let mut a = [0u16; N + 1];
            let mut i = 0;
            while i < N {
                a[i] = bytes[i] as u16;
                i += 1;
            }
            a
        };
        ARR.as_ptr()
    }};
}

#[inline]
fn nt_success(status: NTSTATUS) -> bool {
    status >= 0
}

// ===========================================================================
// HidClassPDO_GetCollectionDescription
// ===========================================================================
pub unsafe fn HidClassPDO_GetCollectionDescription(
    DeviceDescription: PHIDP_DEVICE_DESC,
    CollectionNumber: ULONG,
) -> PHIDP_COLLECTION_DESC {
    let mut Index: ULONG = 0;
    while Index < (*DeviceDescription).CollectionDescLength {
        if (*(*DeviceDescription).CollectionDesc.add(Index as usize)).CollectionNumber as ULONG
            == CollectionNumber
        {
            // found collection
            return (*DeviceDescription).CollectionDesc.add(Index as usize);
        }
        Index += 1;
    }

    // failed to find collection
    // ASSERT(FALSE);
    null_mut()
}

// ===========================================================================
// HidClassPDO_GetReportDescription
// ===========================================================================
pub unsafe fn HidClassPDO_GetReportDescription(
    DeviceDescription: PHIDP_DEVICE_DESC,
    CollectionNumber: ULONG,
) -> PHIDP_REPORT_IDS {
    // hidparse gives each report ID its own entry, so a collection can have several. The
    // read path sizes its buffer from the one returned here, so return the entry with the
    // longest input report; the first entry may be a feature-only ID with InputLength 0.
    let mut Best: PHIDP_REPORT_IDS = null_mut();
    let mut Index: ULONG = 0;
    while Index < (*DeviceDescription).ReportIDsLength {
        let Entry = (*DeviceDescription).ReportIDs.add(Index as usize);
        if (*Entry).CollectionNumber as ULONG == CollectionNumber
            && (Best.is_null() || (*Entry).InputLength > (*Best).InputLength)
        {
            Best = Entry;
        }
        Index += 1;
    }
    if !Best.is_null() {
        return Best;
    }

    // failed to find collection
    // ASSERT(FALSE);
    null_mut()
}

// ===========================================================================
// HidClassPDO_GetReportDescriptionByReportID
// ===========================================================================
pub unsafe fn HidClassPDO_GetReportDescriptionByReportID(
    DeviceDescription: PHIDP_DEVICE_DESC,
    ReportID: UCHAR,
) -> PHIDP_REPORT_IDS {
    let mut Index: ULONG = 0;
    while Index < (*DeviceDescription).ReportIDsLength {
        if (*(*DeviceDescription).ReportIDs.add(Index as usize)).ReportID == ReportID {
            // found report id
            return (*DeviceDescription).ReportIDs.add(Index as usize);
        }
        Index += 1;
    }

    // failed to find report id
    // ASSERT(FALSE);
    null_mut()
}

// ===========================================================================
// HidClassPDO_HandleQueryDeviceId
// ===========================================================================
unsafe fn HidClassPDO_HandleQueryDeviceId(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS {
    // copy current stack location
    IoCopyCurrentIrpStackLocationToNext(Irp);

    // call mini-driver
    let Status = crate::fdo::HidClassFDO_DispatchRequestSynchronous(DeviceObject, Irp);
    if !nt_success(Status) {
        // failed
        return Status;
    }

    // get buffer
    let Buffer = (*Irp).IoStatus.Information as *mut u16; // LPWSTR
    let Length = wcslen(Buffer);

    // allocate new buffer
    let NewBuffer = ExAllocatePoolWithTag(
        NonPagedPool,
        ((Length + 1) * size_of::<u16>()) as _,
        HIDCLASS_TAG,
    ) as *mut u16;
    if NewBuffer.is_null() {
        // failed to allocate buffer
        return STATUS_INSUFFICIENT_RESOURCES;
    }

    // replace bus
    wcscpy(NewBuffer, wstr!("HID\\"));

    // get offset to first '\\'
    let Ptr = wcschr(Buffer, b'\\' as u16);
    if !Ptr.is_null() {
        // append result
        wcscat(NewBuffer, Ptr.add(1));
    }

    // free old buffer
    ExFreePoolWithTag(Buffer as PVOID, 0);

    // store result
    (*Irp).IoStatus.Information = NewBuffer as _;
    STATUS_SUCCESS
}

// ===========================================================================
// HidClassPDO_HandleQueryHardwareId
// ===========================================================================
unsafe fn HidClassPDO_HandleQueryHardwareId(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS {
    let mut Buffer: [u16; 200] = [0; 200];
    let mut Offset: ULONG = 0;

    // get device extension
    let PDODeviceExtension = (*DeviceObject).DeviceExtension as PHIDCLASS_PDO_DEVICE_EXTENSION;
    ntkrnl_sys::ASSERT!((*PDODeviceExtension).Common.IsFDO == 0);

    // copy current stack location
    IoCopyCurrentIrpStackLocationToNext(Irp);

    // call mini-driver
    let Status = crate::fdo::HidClassFDO_DispatchRequestSynchronous(DeviceObject, Irp);
    if !nt_success(Status) {
        // failed
        return Status;
    }

    let vid = (*PDODeviceExtension).Common.Attributes.VendorID as u32;
    let pid = (*PDODeviceExtension).Common.Attributes.ProductID as u32;
    let rev = (*PDODeviceExtension).Common.Attributes.VersionNumber as u32;
    let col = (*PDODeviceExtension).CollectionNumber;

    if (*PDODeviceExtension).Common.DeviceDescription.CollectionDescLength > 1 {
        // multi-tlc device
        Offset = (swprintf(
            Buffer.as_mut_ptr().add(Offset as usize),
            wstr!("HID\\Vid_%04x&Pid_%04x&Rev_%04x&Col%02x"),
            vid, pid, rev, col,
        ) + 1) as ULONG;
        Offset += (swprintf(
            Buffer.as_mut_ptr().add(Offset as usize),
            wstr!("HID\\Vid_%04x&Pid_%04x&Col%02x"),
            vid, pid, col,
        ) + 1) as ULONG;
    } else {
        // single tlc device
        Offset = (swprintf(
            Buffer.as_mut_ptr().add(Offset as usize),
            wstr!("HID\\Vid_%04x&Pid_%04x&Rev_%04x"),
            vid, pid, rev,
        ) + 1) as ULONG;
        Offset += (swprintf(
            Buffer.as_mut_ptr().add(Offset as usize),
            wstr!("HID\\Vid_%04x&Pid_%04x"),
            vid, pid,
        ) + 1) as ULONG;
    }

    // get collection description
    let CollectionDescription = HidClassPDO_GetCollectionDescription(
        &mut (*PDODeviceExtension).Common.DeviceDescription,
        (*PDODeviceExtension).CollectionNumber,
    );
    ntkrnl_sys::ASSERT!(!CollectionDescription.is_null());

    if (*CollectionDescription).UsagePage == HID_USAGE_PAGE_GENERIC {
        match (*CollectionDescription).Usage {
            x if x == HID_USAGE_GENERIC_POINTER || x == HID_USAGE_GENERIC_MOUSE => {
                // Pointer / Mouse
                Offset += (swprintf(
                    Buffer.as_mut_ptr().add(Offset as usize),
                    wstr!("HID_DEVICE_SYSTEM_MOUSE"),
                ) + 1) as ULONG;
            }
            x if x == HID_USAGE_GENERIC_GAMEPAD || x == HID_USAGE_GENERIC_JOYSTICK => {
                // Joystick / Gamepad
                Offset += (swprintf(
                    Buffer.as_mut_ptr().add(Offset as usize),
                    wstr!("HID_DEVICE_SYSTEM_GAME"),
                ) + 1) as ULONG;
            }
            x if x == HID_USAGE_GENERIC_KEYBOARD || x == HID_USAGE_GENERIC_KEYPAD => {
                // Keyboard / Keypad
                Offset += (swprintf(
                    Buffer.as_mut_ptr().add(Offset as usize),
                    wstr!("HID_DEVICE_SYSTEM_KEYBOARD"),
                ) + 1) as ULONG;
            }
            x if x == HID_USAGE_GENERIC_SYSTEM_CTL => {
                // System Control
                Offset += (swprintf(
                    Buffer.as_mut_ptr().add(Offset as usize),
                    wstr!("HID_DEVICE_SYSTEM_CONTROL"),
                ) + 1) as ULONG;
            }
            _ => {}
        }
    } else if (*CollectionDescription).UsagePage == HID_USAGE_PAGE_CONSUMER
        && (*CollectionDescription).Usage == HID_USAGE_CONSUMERCTRL
    {
        // Consumer Audio Control
        Offset += (swprintf(
            Buffer.as_mut_ptr().add(Offset as usize),
            wstr!("HID_DEVICE_SYSTEM_CONSUMER"),
        ) + 1) as ULONG;
    }

    // add HID_DEVICE_UP:0001_U:0002'
    Offset += (swprintf(
        Buffer.as_mut_ptr().add(Offset as usize),
        wstr!("HID_DEVICE_UP:%04x_U:%04x"),
        (*CollectionDescription).UsagePage as u32,
        (*CollectionDescription).Usage as u32,
    ) + 1) as ULONG;

    // add HID
    Offset += (swprintf(
        Buffer.as_mut_ptr().add(Offset as usize),
        wstr!("HID_DEVICE"),
    ) + 1) as ULONG;

    // free old buffer
    ExFreePoolWithTag((*Irp).IoStatus.Information as PVOID, 0);

    // allocate buffer
    let Ptr = ExAllocatePoolWithTag(
        NonPagedPool,
        ((Offset as usize + 1) * size_of::<u16>()) as _,
        HIDCLASS_TAG,
    ) as *mut u16;
    if Ptr.is_null() {
        // no memory
        (*Irp).IoStatus.Information = 0;
        return STATUS_INSUFFICIENT_RESOURCES;
    }

    // copy buffer
    RtlCopyMemory(
        Ptr as PVOID,
        Buffer.as_ptr() as PVOID,
        Offset as usize * size_of::<u16>(),
    );
    *Ptr.add(Offset as usize) = UNICODE_NULL;

    // store result
    (*Irp).IoStatus.Information = Ptr as _;
    STATUS_SUCCESS
}

// ===========================================================================
// HidClassPDO_HandleQueryInstanceId
// ===========================================================================
unsafe fn HidClassPDO_HandleQueryInstanceId(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS {
    // get device extension
    let PDODeviceExtension = (*DeviceObject).DeviceExtension as PHIDCLASS_PDO_DEVICE_EXTENSION;
    ntkrnl_sys::ASSERT!((*PDODeviceExtension).Common.IsFDO == 0);

    // allocate buffer
    let Buffer =
        ExAllocatePoolWithTag(NonPagedPool, (5 * size_of::<u16>()) as _, HIDCLASS_TAG) as *mut u16;
    if Buffer.is_null() {
        // failed
        return STATUS_INSUFFICIENT_RESOURCES;
    }

    // write device id
    swprintf(Buffer, wstr!("%04x"), (*PDODeviceExtension).CollectionNumber);
    (*Irp).IoStatus.Information = Buffer as _;

    STATUS_SUCCESS
}

// ===========================================================================
// HidClassPDO_HandleQueryCompatibleId
// ===========================================================================
unsafe fn HidClassPDO_HandleQueryCompatibleId(_DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS {
    let Buffer =
        ExAllocatePoolWithTag(NonPagedPool, (2 * size_of::<u16>()) as _, HIDCLASS_TAG) as *mut u16;
    if Buffer.is_null() {
        // no memory
        return STATUS_INSUFFICIENT_RESOURCES;
    }

    // zero buffer
    *Buffer.add(0) = 0;
    *Buffer.add(1) = 0;

    // store result
    (*Irp).IoStatus.Information = Buffer as _;
    STATUS_SUCCESS
}

// ===========================================================================
// HidClassPDO_PnP
// ===========================================================================
#[no_mangle]
pub unsafe extern "system" fn HidClassPDO_PnP(DeviceObject: PDEVICE_OBJECT, Irp: PIRP) -> NTSTATUS {
    // get device extension
    let PDODeviceExtension = (*DeviceObject).DeviceExtension as PHIDCLASS_PDO_DEVICE_EXTENSION;
    ntkrnl_sys::ASSERT!((*PDODeviceExtension).Common.IsFDO == 0);

    // get current irp stack location
    let IoStack = IoGetCurrentIrpStackLocation(Irp);

    let mut Status: NTSTATUS;

    // handle request
    match (*IoStack).MinorFunction {
        x if x == IRP_MN_QUERY_ID => {
            if (*IoStack).Parameters.QueryId.IdType == BusQueryDeviceID {
                // handle query device id
                Status = HidClassPDO_HandleQueryDeviceId(DeviceObject, Irp);
            } else if (*IoStack).Parameters.QueryId.IdType == BusQueryHardwareIDs {
                // handle instance id
                Status = HidClassPDO_HandleQueryHardwareId(DeviceObject, Irp);
            } else if (*IoStack).Parameters.QueryId.IdType == BusQueryInstanceID {
                // handle instance id
                Status = HidClassPDO_HandleQueryInstanceId(DeviceObject, Irp);
            } else if (*IoStack).Parameters.QueryId.IdType == BusQueryCompatibleIDs {
                // handle instance id
                Status = HidClassPDO_HandleQueryCompatibleId(DeviceObject, Irp);
            } else {
                Status = STATUS_NOT_SUPPORTED;
                (*Irp).IoStatus.Information = 0;
            }
        }
        x if x == IRP_MN_QUERY_CAPABILITIES => {
            if (*IoStack).Parameters.DeviceCapabilities.Capabilities.is_null() {
                // invalid request
                Status = crate::glue::STATUS_DEVICE_CONFIGURATION_ERROR;
            } else {
                // copy capabilities
                RtlCopyMemory(
                    (*IoStack).Parameters.DeviceCapabilities.Capabilities as PVOID,
                    &(*PDODeviceExtension).Capabilities as *const _ as PVOID,
                    size_of::<DEVICE_CAPABILITIES>(),
                );

                // override some capabilities
                let caps = (*IoStack).Parameters.DeviceCapabilities.Capabilities;
                (*caps).set_Removable(FALSE as ULONG);
                (*caps).set_SilentInstall(TRUE as ULONG);
                (*caps).set_SurpriseRemovalOK(TRUE as ULONG);

                Status = STATUS_SUCCESS;
            }
        }
        x if x == IRP_MN_QUERY_BUS_INFORMATION => {
            let BusInformation = ExAllocatePoolWithTag(
                NonPagedPool,
                size_of::<PNP_BUS_INFORMATION>() as _,
                HIDCLASS_TAG,
            ) as *mut PNP_BUS_INFORMATION;

            // fill in result
            RtlCopyMemory(
                &mut (*BusInformation).BusTypeGuid as *mut _ as PVOID,
                &GUID_BUS_TYPE_HID as *const GUID as PVOID,
                size_of::<GUID>(),
            );
            (*BusInformation).LegacyBusType = PNPBus;
            (*BusInformation).BusNumber = 0; //FIXME

            // store result
            (*Irp).IoStatus.Information = BusInformation as _;
            Status = STATUS_SUCCESS;
        }
        x if x == IRP_MN_QUERY_PNP_DEVICE_STATE => {
            // FIXME set flags when driver fails / disabled
            Status = STATUS_SUCCESS;
        }
        x if x == IRP_MN_QUERY_DEVICE_RELATIONS => {
            // only target relations are supported
            if (*IoStack).Parameters.QueryDeviceRelations.Type != TargetDeviceRelation {
                // not supported
                Status = (*Irp).IoStatus.__bindgen_anon_1.Status;
            } else {
                // allocate device relations
                let DeviceRelation = ExAllocatePoolWithTag(
                    NonPagedPool,
                    size_of::<_DEVICE_RELATIONS>() as _,
                    HIDCLASS_TAG,
                ) as PDEVICE_RELATIONS;
                if DeviceRelation.is_null() {
                    // no memory
                    Status = STATUS_INSUFFICIENT_RESOURCES;
                } else {
                    // init device relation
                    (*DeviceRelation).Count = 1;
                    *(*DeviceRelation).Objects.as_mut_ptr().add(0) = DeviceObject;
                    ObReferenceObject(
                        *(*DeviceRelation).Objects.as_ptr().add(0) as PVOID,
                    );

                    // store result
                    (*Irp).IoStatus.Information = DeviceRelation as _;
                    Status = STATUS_SUCCESS;
                }
            }
        }
        x if x == IRP_MN_START_DEVICE => {
            // FIXME: support polled devices
            // ASSERT(DevicesArePolled == FALSE);

            // now register the device interface
            Status = IoRegisterDeviceInterface(
                (*PDODeviceExtension).Common.HidDeviceExtension.PhysicalDeviceObject,
                &GUID_DEVINTERFACE_HID,
                null_mut(),
                &mut (*PDODeviceExtension).DeviceInterface,
            );
            if nt_success(Status) {
                // enable device interface
                Status = IoSetDeviceInterfaceState(
                    &mut (*PDODeviceExtension).DeviceInterface,
                    TRUE,
                );
            }

            // done
            Status = STATUS_SUCCESS;
        }
        x if x == IRP_MN_REMOVE_DEVICE => {
            /* Disable the device interface */
            if (*PDODeviceExtension).DeviceInterface.Length != 0 {
                IoSetDeviceInterfaceState(&mut (*PDODeviceExtension).DeviceInterface, FALSE);
            }

            // remove us from the fdo's pdo list
            let mut bFound: ULONG = FALSE as ULONG;
            let mut Index: ULONG = 0;
            let count = (*(*(*PDODeviceExtension).FDODeviceExtension).DeviceRelations).Count;
            while Index < count {
                if *(*(*(*PDODeviceExtension).FDODeviceExtension).DeviceRelations)
                    .Objects
                    .as_ptr()
                    .add(Index as usize)
                    == DeviceObject
                {
                    // remove us
                    bFound = TRUE as ULONG;
                    *(*(*(*PDODeviceExtension).FDODeviceExtension).DeviceRelations)
                        .Objects
                        .as_mut_ptr()
                        .add(Index as usize) = null_mut();
                    break;
                }
                Index += 1;
            }

            /* Complete the IRP */
            (*Irp).IoStatus.__bindgen_anon_1.Status = STATUS_SUCCESS;
            IoCompleteRequest(Irp, IO_NO_INCREMENT);

            if bFound != 0 {
                /* Delete our device object */
                IoDeleteDevice(DeviceObject);
            }

            return STATUS_SUCCESS;
        }
        x if x == IRP_MN_QUERY_INTERFACE => {
            // return error default
            Status = (*Irp).IoStatus.__bindgen_anon_1.Status;

            // check for known interfaces. Upstream 445d0881b82: before this, the PDO
            // answered every QUERY_INTERFACE with the incoming status, so hidparse-backed
            // clients (which ask for GUID_HID_INTERFACE_HIDPARSE to get at HidP_GetCaps
            // without loading hidparse themselves) got nothing.
            let iface_type = (*IoStack).Parameters.QueryInterface.InterfaceType;
            if guid_eq(iface_type, &crate::guid::GUID_HID_INTERFACE_NOTIFY) {
                // The C names a PHID_INTERFACE_NOTIFY_PNP local only to spell
                // sizeof(*it); size_of::<T>() says the same thing without the binding.
                if (*IoStack).Parameters.QueryInterface.Size as usize
                    == core::mem::size_of::<crate::types::HID_INTERFACE_NOTIFY_PNP>()
                    && (*IoStack).Parameters.QueryInterface.Version == 1
                {
                    ntkrnl_sys::driver_ddk::DbgPrint(
                        b"[HIDCLASS] PDO IRP_MN_QUERY_INTERFACE/GUID_HID_INTERFACE_NOTIFY not implemented\n\0"
                            .as_ptr() as *const i8,
                    );
                    ntkrnl_sys::ASSERT!(false);
                }
            } else if guid_eq(iface_type, &crate::guid::GUID_HID_INTERFACE_HIDPARSE) {
                let HidInterfaceHidparse = (*IoStack).Parameters.QueryInterface.Interface
                    as crate::types::PHID_INTERFACE_HIDPARSE;
                if (*IoStack).Parameters.QueryInterface.Size as usize
                    == core::mem::size_of::<crate::types::HID_INTERFACE_HIDPARSE>()
                    && (*IoStack).Parameters.QueryInterface.Version == 1
                {
                    (*HidInterfaceHidparse).HidpGetCaps = Some(HidP_GetCaps);
                    Status = STATUS_SUCCESS;
                }
            }
        }
        x if x == IRP_MN_QUERY_REMOVE_DEVICE
            || x == IRP_MN_CANCEL_STOP_DEVICE
            || x == IRP_MN_QUERY_STOP_DEVICE
            || x == IRP_MN_CANCEL_REMOVE_DEVICE =>
        {
            // no/op
            // #if 0 → Status = STATUS_SUCCESS; #else (active branch):
            // "Denying removal of HID device due to IRP cancellation bugs"
            Status = STATUS_UNSUCCESSFUL;
        }
        _ => {
            // do nothing
            Status = (*Irp).IoStatus.__bindgen_anon_1.Status;
        }
    }

    // complete request
    if Status != STATUS_PENDING {
        // store result
        (*Irp).IoStatus.__bindgen_anon_1.Status = Status;

        // complete request
        IoCompleteRequest(Irp, IO_NO_INCREMENT);
    }

    // done processing
    Status
}

// ===========================================================================
// HidClassPDO_CreatePDO
// ===========================================================================
pub unsafe fn HidClassPDO_CreatePDO(
    DeviceObject: PDEVICE_OBJECT,
    OutDeviceRelations: *mut PDEVICE_RELATIONS,
) -> NTSTATUS {
    let mut Status: NTSTATUS = STATUS_SUCCESS;
    let mut PDODeviceObject: PDEVICE_OBJECT = null_mut();

    // get device extension
    let FDODeviceExtension = (*DeviceObject).DeviceExtension as PHIDCLASS_FDO_EXTENSION;
    ntkrnl_sys::ASSERT!((*FDODeviceExtension).Common.IsFDO != 0);

    // first allocate device relations
    // FIELD_OFFSET(DEVICE_RELATIONS, Objects) + sizeof(PDEVICE_OBJECT) * CollectionDescLength
    let Length: ULONG = (field_offset_objects()
        + size_of::<PDEVICE_OBJECT>()
            * (*FDODeviceExtension).Common.DeviceDescription.CollectionDescLength as usize)
        as ULONG;
    let DeviceRelations =
        ExAllocatePoolWithTag(PagedPool, Length as _, HIDCLASS_TAG) as PDEVICE_RELATIONS;
    if DeviceRelations.is_null() {
        // no memory
        return STATUS_INSUFFICIENT_RESOURCES;
    }

    // zero device relations
    RtlZeroMemory(DeviceRelations as PVOID, Length as usize);

    // let's create a PDO for top level collection
    let mut Index: ULONG = 0;
    while Index < (*FDODeviceExtension).Common.DeviceDescription.CollectionDescLength {
        // let's create the device object
        Status = IoCreateDevice(
            (*(*FDODeviceExtension).Common.DriverExtension).DriverObject,
            size_of::<crate::types::HIDCLASS_PDO_DEVICE_EXTENSION>() as ULONG,
            null_mut(),
            FILE_DEVICE_UNKNOWN,
            FILE_AUTOGENERATED_DEVICE_NAME,
            FALSE,
            &mut PDODeviceObject,
        );
        if !nt_success(Status) {
            // failed to create device
            break;
        }

        // patch stack size
        (*PDODeviceObject).StackSize = (*DeviceObject).StackSize + 1;

        // get device extension
        let PDODeviceExtension =
            (*PDODeviceObject).DeviceExtension as PHIDCLASS_PDO_DEVICE_EXTENSION;

        // init device extension
        (*PDODeviceExtension).Common.HidDeviceExtension.MiniDeviceExtension =
            (*FDODeviceExtension).Common.HidDeviceExtension.MiniDeviceExtension;
        (*PDODeviceExtension).Common.HidDeviceExtension.NextDeviceObject =
            (*FDODeviceExtension).Common.HidDeviceExtension.NextDeviceObject;
        // The PDO's own PhysicalDeviceObject is ITSELF, not the FDO's. Copying the FDO's
        // registers GUID_DEVINTERFACE_HID against the parent, so every child collection
        // publishes its interface on the wrong object. Upstream 938c14e3276.
        (*PDODeviceExtension).Common.HidDeviceExtension.PhysicalDeviceObject = PDODeviceObject;
        (*PDODeviceExtension).Common.IsFDO = FALSE;
        (*PDODeviceExtension).FDODeviceExtension = FDODeviceExtension;
        (*PDODeviceExtension).FDODeviceObject = DeviceObject;
        (*PDODeviceExtension).Common.DriverExtension =
            (*FDODeviceExtension).Common.DriverExtension;
        (*PDODeviceExtension).CollectionNumber = (*(*FDODeviceExtension)
            .Common
            .DeviceDescription
            .CollectionDesc
            .add(Index as usize))
        .CollectionNumber as ULONG;

        // copy device data
        RtlCopyMemory(
            &mut (*PDODeviceExtension).Common.Attributes as *mut _ as PVOID,
            &(*FDODeviceExtension).Common.Attributes as *const _ as PVOID,
            size_of::<HID_DEVICE_ATTRIBUTES>(),
        );
        RtlCopyMemory(
            &mut (*PDODeviceExtension).Common.DeviceDescription as *mut _ as PVOID,
            &(*FDODeviceExtension).Common.DeviceDescription as *const _ as PVOID,
            size_of::<HIDP_DEVICE_DESC>(),
        );
        RtlCopyMemory(
            &mut (*PDODeviceExtension).Capabilities as *mut _ as PVOID,
            &(*FDODeviceExtension).Capabilities as *const _ as PVOID,
            size_of::<DEVICE_CAPABILITIES>(),
        );

        // set device flags
        (*PDODeviceObject).Flags |= DO_MAP_IO_BUFFER;

        // device is initialized
        (*PDODeviceObject).Flags &= !DO_DEVICE_INITIALIZING;

        // store device object in device relations
        *(*DeviceRelations).Objects.as_mut_ptr().add(Index as usize) = PDODeviceObject;
        (*DeviceRelations).Count += 1;

        // move to next
        Index += 1;
    }

    // check if creating succeeded
    if !nt_success(Status) {
        // failed
        let mut Index: ULONG = 0;
        while Index < (*DeviceRelations).Count {
            // delete device
            IoDeleteDevice(*(*DeviceRelations).Objects.as_ptr().add(Index as usize));
            Index += 1;
        }

        // free device relations
        ExFreePoolWithTag(DeviceRelations as PVOID, HIDCLASS_TAG);
        return Status;
    }

    // store device relations
    ntkrnl_sys::driver_ddk::DbgPrint(
        b"[HIDCLASS] CreatePDO done count=%u\n\0".as_ptr() as *const i8,
        (*DeviceRelations).Count,
    );
    *OutDeviceRelations = DeviceRelations;

    STATUS_SUCCESS
}

// FIELD_OFFSET(DEVICE_RELATIONS, Objects) — Count(ULONG) then Objects[].
// Objects is pointer-aligned, so offset == size_of::<PDEVICE_OBJECT>() on all
// arches (4 on i386, 8 on amd64/arm64), matching the C FIELD_OFFSET.
#[inline]
fn field_offset_objects() -> usize {
    core::mem::offset_of!(_DEVICE_RELATIONS, Objects)
}

