#[no_mangle]
pub unsafe extern "C" fn SetDriverLoadPrivilege() -> DWORD {
    let mut TokenPrivileges_local: TOKEN_PRIVILEGES = core::mem::zeroed();
    let mut hToken: HANDLE = core::mem::zeroed();
    let mut luid: LUID = core::mem::zeroed();
    let mut bSuccess: BOOL;
    let mut dwError: DWORD = ERROR_SUCCESS;

    bSuccess = OpenProcessToken(GetCurrentProcess(),
                                TOKEN_ADJUST_PRIVILEGES,
                                core::ptr::addr_of_mut!(hToken));
    if (bSuccess) as u32 == FALSE {
        return GetLastError();
    }

    if !(LookupPrivilegeValueW(core::ptr::null_mut(), SE_LOAD_DRIVER_NAME, core::ptr::addr_of_mut!(luid)) != 0) {
        return GetLastError();
    }

    TokenPrivileges_local.PrivilegeCount = 1;
    TokenPrivileges_local.Privileges[0 as usize].Luid = luid;
    TokenPrivileges_local.Privileges[0 as usize].Attributes = SE_PRIVILEGE_ENABLED;

    bSuccess = AdjustTokenPrivileges(hToken,
                                     (FALSE) as BOOL,
                                     core::ptr::addr_of_mut!(TokenPrivileges_local),
                                     core::mem::size_of::<TOKEN_PRIVILEGES>() as DWORD,
                                     core::ptr::null_mut(),
                                     core::ptr::null_mut());
    if (bSuccess) as u32 == FALSE {
        dwError = GetLastError();
    }

    CloseHandle(hToken);

    return dwError;
}

#[no_mangle]
pub unsafe extern "C" fn LoadFilter(FilterName: LPWSTR) {
    let mut dwError: DWORD;
    dwError = SetDriverLoadPrivilege();
    if dwError != ERROR_SUCCESS {
        LoadAndPrintString!(IDS_ERROR_PRIV, HRESULT_FROM_WIN32!(dwError as LONG));
        return;
    }

    let hr: HRESULT = FilterLoad(FilterName);
    if hr != S_OK {
        LoadAndPrintString!(IDS_ERROR_LOAD, hr);
        PrintErrorText((hr) as ULONG);
    }
}

#[no_mangle]
pub unsafe extern "C" fn UnloadFilter(FilterName: LPWSTR) {
    let mut dwError: DWORD;
    dwError = SetDriverLoadPrivilege();
    if dwError != ERROR_SUCCESS {
        LoadAndPrintString!(IDS_ERROR_PRIV, HRESULT_FROM_WIN32!(dwError as LONG));
        return;
    }

    let hr: HRESULT = FilterUnload(FilterName);
    if hr != S_OK {
        LoadAndPrintString!(IDS_ERROR_UNLOAD, hr);
        PrintErrorText((hr) as ULONG);
    }
}

