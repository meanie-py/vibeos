#[no_mangle]
pub unsafe extern "C" fn ListFilters() {
    let mut FindHandle: HANDLE = core::ptr::null_mut();
    let mut Buffer: [BYTE; 1024] = [0; 1024];
    let mut BytesReturned: ULONG = 0;
    let mut IsNewStyle: BOOL = (TRUE) as i32;
    let mut hr: HRESULT = 0;

    hr = FilterFindFirst(FilterAggregateStandardInformation,
                         Buffer.as_mut_ptr() as PVOID,
                         core::mem::size_of::<[BYTE; 1024]>() as ULONG,
                         core::ptr::addr_of_mut!(BytesReturned),
                         core::ptr::addr_of_mut!(FindHandle));
    if !((hr) >= 0) {
        IsNewStyle = (FALSE) as i32;
        hr = FilterFindFirst(FilterFullInformation,
                             Buffer.as_mut_ptr() as PVOID,
                             core::mem::size_of::<[BYTE; 1024]>() as ULONG,
                             core::ptr::addr_of_mut!(BytesReturned),
                             core::ptr::addr_of_mut!(FindHandle));
    }

    if !((hr) >= 0) {
        LoadAndPrintString!(IDS_ERROR_FILTERS, hr);
        PrintErrorText((hr) as ULONG);
        return;
    }

    if IsNewStyle == 0 {
        LoadAndPrintString!(IDS_DISPLAY_FILTERS1);
        wprintf(CPP_COM_WSTR_6E296A9AFC9F.as_ptr());
    } else {
        LoadAndPrintString!(IDS_DISPLAY_FILTERS2);
        wprintf(CPP_COM_WSTR_0FC3CCFBA47B.as_ptr());
    }

    PrintFilterInfo(Buffer.as_mut_ptr() as PVOID, IsNewStyle);

    loop {
        hr = FilterFindNext(FindHandle,
                            if IsNewStyle == 0 { FilterAggregateStandardInformation } else { FilterFullInformation },
                            Buffer.as_mut_ptr() as PVOID,
                            core::mem::size_of::<[BYTE; 1024]>() as ULONG,
                            core::ptr::addr_of_mut!(BytesReturned));
        if (hr) >= 0 {
            PrintFilterInfo(Buffer.as_mut_ptr() as PVOID, IsNewStyle);
        } else if hr == HRESULT_FROM_WIN32!(ERROR_NO_MORE_ITEMS as LONG) {
            LoadAndPrintString!(IDS_ERROR_FILTERS, hr);
            PrintErrorText((hr) as ULONG);
        }
        if !((hr) >= 0) {
            break;
        }
    }

    hr = FilterFindClose(FindHandle);
    if !((hr) >= 0) {
        LoadAndPrintString!(IDS_ERROR_FILTERS, hr);
        PrintErrorText((hr) as ULONG);
    }
}

#[no_mangle]
pub unsafe extern "C" fn ListVolumes() {
    let mut FindHandle: HANDLE = core::ptr::null_mut();
    let mut Buffer: [BYTE; 1024] = [0u8; 1024];
    let mut BytesReturned: ULONG = 0;
    let mut hr: HRESULT = 0;

    hr = FilterVolumeFindFirst(FilterVolumeStandardInformation,
                               Buffer.as_mut_ptr() as PVOID,
                               1024,
                               core::ptr::addr_of_mut!(BytesReturned),
                               core::ptr::addr_of_mut!(FindHandle));
    if ((hr) >= 0) {
        LoadAndPrintString!(IDS_DISPLAY_VOLUMES);
        wprintf(CPP_COM_WSTR_B51611DE387E.as_ptr());

        PrintVolumeInfo(Buffer.as_mut_ptr() as PVOID);

        loop {
            hr = FilterVolumeFindNext(FindHandle,
                                      FilterVolumeStandardInformation,
                                      Buffer.as_mut_ptr() as PVOID,
                                      1024,
                                      core::ptr::addr_of_mut!(BytesReturned));
            if ((hr) >= 0) {
                PrintVolumeInfo(Buffer.as_mut_ptr() as PVOID);
            }

            if !((hr) >= 0) {
                break;
            }
        }

        FilterVolumeFindClose(FindHandle);
    }

    if !((hr) >= 0) && hr == HRESULT_FROM_WIN32!(ERROR_NO_MORE_ITEMS as LONG) {
        LoadAndPrintString!(IDS_ERROR_VOLUMES, hr);
        PrintErrorText((hr) as ULONG);
    }
}

#[no_mangle]
pub unsafe extern "C" fn wmain(argc: i32, argv: *mut *mut u16) -> i32 {
    wprintf(CPP_COM_WSTR_075DE2B906DB.as_ptr());

    if (argc < 2) || (_wcsicmp(*argv.add(1 as usize), CPP_COM_WSTR_A9218E7BF0B5.as_ptr()) == 0) {
        if argc < 3 {
            ListFilters();
        } else {
            LoadAndPrintString!(IDS_USAGE_FILTERS);
            wprintf(CPP_COM_WSTR_5901AB74E2F5.as_ptr());
        }
    } else if _wcsicmp(*argv.add(1 as usize), CPP_COM_WSTR_6509121F99F7.as_ptr()) == 0 {
        LoadAndPrintString!(IDS_USAGE);
    } else if _wcsicmp(*argv.add(1 as usize), CPP_COM_WSTR_78CE70519B47.as_ptr()) == 0 {
        if argc == 3 {
            LoadFilter(*argv.add(2 as usize));
        } else {
            LoadAndPrintString!(IDS_USAGE_LOAD);
            wprintf(CPP_COM_WSTR_74FA4D56EC36.as_ptr());
        }
    } else if _wcsicmp(*argv.add(1 as usize), CPP_COM_WSTR_21BC2E8D2574.as_ptr()) == 0 {
        if argc == 3 {
            UnloadFilter(*argv.add(2 as usize));
        } else {
            LoadAndPrintString!(IDS_USAGE_UNLOAD);
            wprintf(CPP_COM_WSTR_3B244D714A45.as_ptr());
        }
    } else if _wcsicmp(*argv.add(1 as usize), CPP_COM_WSTR_B655681B81BE.as_ptr()) == 0 {
        if argc == 2 {
            ListVolumes();
        } else {
            LoadAndPrintString!(IDS_USAGE_VOLUMES);
            wprintf(CPP_COM_WSTR_559E5233A80E.as_ptr());
        }
    }

    return 0;
}
