// winnt.h `#define TRUE 1` / `FALSE 0`. ntdll-sys's bindgen types them u32; every use here is
// a BOOL return. An explicit item beats a glob import, so naming them here re-types them
// crate-wide without a cast at each of the 31 sites.
pub const TRUE: BOOL = 1;
pub const FALSE: BOOL = 0;

