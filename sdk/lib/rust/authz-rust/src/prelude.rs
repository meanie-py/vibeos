//! authz-rust prelude — the single import surface the translated modules use.
//! Bridges the bindgen `types` island and the translated C. Anything bindgen leaves out
//! (CRT, inlines, sibling-C externs, hand-transcribed consts) is declared here ONCE.
#![allow(non_snake_case, non_camel_case_types, non_upper_case_globals)]

pub use crate::types::*;
pub use core::ffi::{c_char, c_int, c_long, c_short, c_uchar, c_uint, c_ushort, c_void};
pub use core::ptr::{addr_of, addr_of_mut};

// ================= debug ======================================================================
// `NDEBUG` silences DPRINT only. DPRINT1 sits OUTSIDE that guard in
// sdk/include/reactos/debug.h, so it is live whenever DBG is set — and our media is
// built -DCMAKE_BUILD_TYPE=Debug, i.e. -DDBG=1. Both stay MACROS, never out-of-line
// fns (field manual §9.65: a no-op fn is an optimization barrier). The C passes
// __RELFILE__/__LINE__ as two extra varargs; file!()/line!() fold into the literal.
#[macro_export] macro_rules! DPRINT  { ($($arg:tt)*) => {{}}; }
// ntdll exports DbgPrint; every usermode DLL links it.
extern "C" {
    pub fn DbgPrint(Format: *const c_char, ...) -> u32;
}
#[macro_export]
macro_rules! DPRINT1 {
    ($fmt:literal $(, $arg:expr)* $(,)?) => {
        unsafe {
            $crate::prelude::DbgPrint(
                concat!("(", file!(), ":", line!(), ") ", $fmt, "\0").as_ptr() as *const _
                $(, $arg)*,
            )
        }
    };
}
pub use crate::{DPRINT, DPRINT1};

// ================= CRT ========================================================================
// NEVER hand-write memcpy/memset/memmove/memcmp in Rust: LLVM folds any byte-copy loop back into
// a call to the function itself → infinite self-recursion → silent hang. Import them (AGENTS.md).
extern "C" {
    pub fn memcpy(dest: *mut c_void, src: *const c_void, n: usize) -> *mut c_void;
    pub fn memset(dest: *mut c_void, c: c_int, n: usize) -> *mut c_void;
    pub fn memmove(dest: *mut c_void, src: *const c_void, n: usize) -> *mut c_void;
    pub fn memcmp(a: *const c_void, b: *const c_void, n: usize) -> c_int;
}

// bindgen does not emit NULL (a macro) nor NT_SUCCESS (an inline).
pub const NULL: *mut c_void = core::ptr::null_mut();
#[inline(always)]
pub fn NT_SUCCESS(s: NTSTATUS) -> bool {
    s >= 0
}

// The island re-exports the base NT identity: pub use ntdll_sys::nt::*;

// ================= function-like MACROS =======================================================
// Macros in C, macros here (field manual §9.65: an out-of-line no-op is an optimization barrier
// that can uncloak a latent ABI mismatch into `ud2`).
//
// precomp.h:21-22 — the handle-tag assertions. `ASSERT` compiles away in a release build, so
// these are genuinely no-ops here; the C shape is preserved so a debug build can grow them back.
#[macro_export] macro_rules! VALIDATE_RESMAN_HANDLE    { ($h:expr $(,)?) => {{}}; }
#[macro_export] macro_rules! VALIDATE_CLIENTCTX_HANDLE { ($h:expr $(,)?) => {{}}; }
// reactos/debug.h
#[macro_export] macro_rules! UNIMPLEMENTED { () => {{}}; }
#[macro_export] macro_rules! UNREFERENCED_PARAMETER { ($($arg:tt)*) => {{}}; }
// winbase.h ZeroMemory→RtlZeroMemory, CopyMemory→RtlCopyMemory. Routed to the CRT entry points
// rather than a Rust byte loop: LLVM folds any such loop back into a call to memset/memcpy.
// The zeroing macros live in `win32macros-rust`, ported once from the header and
// known-answer tested there. Re-exported under the same names, so no call site changed.
pub use win32macros_rust::ZeroMemory;
#[macro_export]
macro_rules! CopyMemory {
    ($d:expr, $s:expr, $l:expr $(,)?) => {
        $crate::prelude::memcpy($d as *mut c_void, $s as *const c_void, $l as usize)
    };
}
pub use crate::{CopyMemory, UNIMPLEMENTED, UNREFERENCED_PARAMETER, VALIDATE_CLIENTCTX_HANDLE, VALIDATE_RESMAN_HANDLE};

