unsafe extern "C" fn GetUserToken(ppUserToken: *mut PTOKEN_USER) -> BOOL {
    let mut Success_local: BOOL = (FALSE as i32);
    let mut dwError: DWORD = 0;
    let mut hToken: HANDLE = core::ptr::null_mut();
    let mut cbTokenBuffer: DWORD = 0;
    let mut pUserToken: PTOKEN_USER = core::ptr::null_mut();

    *ppUserToken = core::ptr::null_mut();

    /* Get the process token */
    if OpenProcessToken(GetCurrentProcess(), TOKEN_QUERY, core::ptr::addr_of_mut!(hToken)) == 0 {
        return (FALSE) as BOOL;
    }

    'quit: {
        /* Retrieve token's information */
        if GetTokenInformation(hToken, TokenUser, core::ptr::null_mut(), 0, core::ptr::addr_of_mut!(cbTokenBuffer)) == 0 {
            dwError = GetLastError();
            if dwError != ERROR_INSUFFICIENT_BUFFER {
                break 'quit;
            }
        }

        pUserToken = HeapAlloc(GetProcessHeap(), HEAP_ZERO_MEMORY, cbTokenBuffer as SIZE_T) as PTOKEN_USER;
        if pUserToken.is_null() {
            dwError = ERROR_NOT_ENOUGH_MEMORY;
            break 'quit;
        }

        if GetTokenInformation(hToken, TokenUser, pUserToken as PVOID, cbTokenBuffer, core::ptr::addr_of_mut!(cbTokenBuffer)) == 0 {
            dwError = GetLastError();
            break 'quit;
        }

        Success_local = (TRUE as i32);
        dwError = ERROR_SUCCESS;
        *ppUserToken = pUserToken;
    }

    /* Quit: */
    if Success_local == (FALSE as i32) {
        if !pUserToken.is_null() {
            HeapFree(GetProcessHeap(), 0, pUserToken as PVOID);
        }
    }

    CloseHandle(hToken);

    SetLastError(dwError);

    return Success_local;
}

unsafe extern "C" fn InstallEventSource(
    mut hEventLogKey: HKEY,
    mut EventLogSource: PCWSTR,
) -> LONG {
    let mut lRet: LONG;
    let mut hSourceKey: HKEY = core::ptr::null_mut();
    let mut dwDisposition: DWORD = 0 as DWORD;
    let mut dwData: DWORD;

    let mut EventMessageFile: PCWSTR;
    let mut PathSize: DWORD;
    let mut ExePath: [WCHAR; MAX_PATH as usize] = [0; MAX_PATH as usize];

    'quit: {
        lRet = RegCreateKeyExW(
            hEventLogKey,
            EventLogSource as LPCWSTR,
            0 as DWORD,
            core::ptr::null_mut::<WCHAR>(),
            REG_OPTION_NON_VOLATILE as DWORD,
            KEY_SET_VALUE as REGSAM,
            core::ptr::null_mut::<_SECURITY_ATTRIBUTES>(),
            core::ptr::addr_of_mut!(hSourceKey),
            core::ptr::addr_of_mut!(dwDisposition),
        ) as LONG;
        if lRet != ERROR_SUCCESS as LONG {
            break 'quit;
        }
        if dwDisposition != REG_CREATED_NEW_KEY as DWORD {
            /* The source key already exists, just quit */
            break 'quit;
        }

        /* We just have created the new source. Add the values. */

        /*
         * Retrieve the full path of the current running executable.
         * We need it to install our custom event source.
         * - In case of success, try to replace the ReactOS installation path
         *   (if present in the executable path) by %SystemRoot%.
         * - In case of failure, use a default path.
         */
        PathSize = GetModuleFileNameW(
            core::ptr::null_mut::<HINSTANCE__>(),
            core::ptr::addr_of_mut!(ExePath) as *mut WCHAR as LPWSTR,
            ARRAYSIZE!(ExePath) as DWORD,
        );
        if (PathSize == 0 as DWORD)
            || (GetLastError() == ERROR_INSUFFICIENT_BUFFER as DWORD)
        {
            /* We failed, copy the default value */
            StringCchCopyW(
                addr_of_mut!(ExePath) as *mut WCHAR as LPWSTR,
                ARRAYSIZE!(ExePath) as usize,
                RUSTCONV_WSTR_E00673CFE80F.as_ptr(),
            );
        } else {
            /* Alternatively one can use SharedUserData->NtSystemRoot */
            let mut TmpDir: [WCHAR; MAX_PATH as usize] = [0; MAX_PATH as usize];
            PathSize = GetSystemWindowsDirectoryW(
                core::ptr::addr_of_mut!(TmpDir) as *mut WCHAR as LPWSTR,
                ARRAYSIZE!(TmpDir) as UINT,
            ) as DWORD;
            if (PathSize > 0 as DWORD)
                && (_wcsnicmp(
                    core::ptr::addr_of_mut!(ExePath) as *mut WCHAR,
                    core::ptr::addr_of_mut!(TmpDir) as *mut WCHAR,
                    PathSize as usize,
                ) == 0 as core::ffi::c_int)
            {
                StringCchCopyW(
                    core::ptr::addr_of_mut!(TmpDir) as *mut WCHAR as LPWSTR,
                    ARRAYSIZE!(TmpDir) as usize,
                    RUSTCONV_WSTR_2B585AE3D008.as_ptr(),
                );
                StringCchCatW(
                    core::ptr::addr_of_mut!(TmpDir) as *mut WCHAR as LPWSTR,
                    ARRAYSIZE!(TmpDir) as usize,
                    (core::ptr::addr_of_mut!(ExePath) as *mut WCHAR).offset(PathSize as isize) as LPCWSTR,
                );
                StringCchCopyW(
                    core::ptr::addr_of_mut!(ExePath) as *mut WCHAR as LPWSTR,
                    ARRAYSIZE!(ExePath) as usize,
                    core::ptr::addr_of_mut!(TmpDir) as *mut WCHAR as LPCWSTR,
                );
            }
        }
        EventMessageFile = core::ptr::addr_of_mut!(ExePath) as *mut WCHAR as PCWSTR;

        lRet = ERROR_SUCCESS as LONG;

        dwData = 1 as DWORD;
        RegSetValueExW(
            hSourceKey,
            RUSTCONV_WSTR_AFD9FD76A995.as_ptr(),
            0 as DWORD,
            REG_DWORD as DWORD,
            core::ptr::addr_of_mut!(dwData) as PBYTE as *const BYTE,
            core::mem::size_of::<DWORD>() as DWORD,
        );

        // FIXME: Set those flags according to caller's rights?
        // Or, if we are using the Security log?
        dwData = (EVENTLOG_SUCCESS as DWORD)
            | (EVENTLOG_ERROR_TYPE as DWORD)
            | (EVENTLOG_WARNING_TYPE as DWORD)
            | (EVENTLOG_INFORMATION_TYPE as DWORD)
            /* | EVENTLOG_AUDIT_SUCCESS | EVENTLOG_AUDIT_FAILURE */;
        RegSetValueExW(
            hSourceKey,
            RUSTCONV_WSTR_D587A5BCAA56.as_ptr(),
            0 as DWORD,
            REG_DWORD as DWORD,
            core::ptr::addr_of_mut!(dwData) as PBYTE as *const BYTE,
            core::mem::size_of::<DWORD>() as DWORD,
        );

        RegSetValueExW(
            hSourceKey,
            RUSTCONV_WSTR_BB2F7BE27363.as_ptr(),
            0 as DWORD,
            REG_EXPAND_SZ as DWORD,
            EventMessageFile as PBYTE as *const BYTE,
            ((wcslen(EventMessageFile as *const wchar_t) as usize
                + 1 as usize)
                * core::mem::size_of::<WCHAR>()) as DWORD,
        );

        RegFlushKey(hSourceKey);
    }

    // Quit:
    if !hSourceKey.is_null() {
        RegCloseKey(hSourceKey);
    }

    return lRet;
}

unsafe extern "C" fn CheckLogOrSourceExistence(
    UNCServerName: PCWSTR,
    EventLogName: PCWSTR,
    EventLogSource: PCWSTR,
    AllowAppSources: BOOL,
) -> BOOL {
    let mut Success_local: BOOL = (FALSE as i32);
    let mut lRet: LONG = 0;
    let mut hEventLogKey: HKEY = core::ptr::null_mut();
    let mut hLogKey: HKEY = core::ptr::null_mut();
    let mut NameLen: DWORD = 0;
    let mut dwIndex: DWORD = 0;

    let mut LogNameValid: BOOL = 0;
    let mut LogSourceValid: BOOL = 0;
    let mut FoundLog: BOOL = (FALSE as i32);
    let mut FoundSource: BOOL = (FALSE as i32);
    let mut SourceAlreadyExists: BOOL = (FALSE as i32);
    let mut SourceCreated: BOOL = (FALSE as i32);
    let mut IsCustomSource: BOOL = (FALSE as i32);

    let mut LogName: [WCHAR; (MAX_KEY_LENGTH as _)] = [0; (MAX_KEY_LENGTH as _)];
    let mut LogNameErr: [WCHAR; (MAX_KEY_LENGTH as _)] = [0; (MAX_KEY_LENGTH as _)];

    UNREFERENCED_PARAMETER!(UNCServerName);

    LogNameValid = (!EventLogName.is_null() && *EventLogName != 0) as BOOL;
    LogSourceValid = (!EventLogSource.is_null() && *EventLogSource != 0) as BOOL;

    if LogNameValid == 0 && LogSourceValid == 0 {
        return (FALSE) as BOOL;
    }

    'quit: {
        'finalize: {
            lRet = RegOpenKeyExW(
                HKEY_LOCAL_MACHINE,
                RUSTCONV_WSTR_17BA4ECEC082.as_ptr(),
                0,
                KEY_ENUMERATE_SUB_KEYS,
                core::ptr::addr_of_mut!(hEventLogKey),
            );
            if lRet != (ERROR_SUCCESS as i32) {
                break 'quit;
            }

            if LogNameValid != 0 && LogSourceValid == 0 {
                lRet = RegOpenKeyExW(
                    hEventLogKey,
                    EventLogName,
                    0,
                    KEY_QUERY_VALUE,
                    core::ptr::addr_of_mut!(hLogKey),
                );
                RegCloseKey(hLogKey);
                FoundLog = (lRet == (ERROR_SUCCESS as i32)) as BOOL;

                if FoundLog != 0 {
                    SourceCreated = (TRUE as i32);
                    IsCustomSource = (TRUE as i32);
                }
                break 'finalize;
            }

            dwIndex = 0;
            loop {
                NameLen = ARRAYSIZE!(LogName) as DWORD;
                LogName[0] = 0x0000u16;

                lRet = RegEnumKeyExW(
                    hEventLogKey,
                    dwIndex,
                    core::ptr::addr_of_mut!(LogName) as *mut WCHAR,
                    core::ptr::addr_of_mut!(NameLen),
                    core::ptr::null_mut(),
                    core::ptr::null_mut(),
                    core::ptr::null_mut(),
                    core::ptr::null_mut(),
                );
                if dwIndex > 0 {
                    if lRet == (ERROR_NO_MORE_ITEMS as i32) {
                        break;
                    }
                }
                if lRet != (ERROR_SUCCESS as i32) {
                    break 'quit;
                }

                dwIndex = dwIndex.wrapping_add(1);

                if LogNameValid != 0
                    && _wcsicmp(
                        core::ptr::addr_of_mut!(LogName) as *const WCHAR,
                        EventLogName,
                    ) == 0
                {
                    FoundLog = (TRUE as i32);
                }

                if FoundLog != 0 {
                    if SourceAlreadyExists != 0 {
                        break;
                    }
                }

                if LogSourceValid != 0 && FoundSource == 0 {
                    let mut hKeySource: HKEY = core::ptr::null_mut();

                    lRet = RegOpenKeyExW(
                        hEventLogKey,
                        core::ptr::addr_of_mut!(LogName) as *const WCHAR,
                        0,
                        KEY_READ,
                        core::ptr::addr_of_mut!(hLogKey),
                    );
                    if lRet != (ERROR_SUCCESS as i32) {
                        break 'quit;
                    }

                    lRet = RegOpenKeyExW(
                        hLogKey,
                        EventLogSource,
                        0,
                        KEY_QUERY_VALUE,
                        core::ptr::addr_of_mut!(hKeySource),
                    );

                    RegCloseKey(hLogKey);
                    hLogKey = core::ptr::null_mut();

                    if lRet == (ERROR_SUCCESS as i32) {
                        FoundSource = (TRUE as i32);
                    } else if lRet == (ERROR_FILE_NOT_FOUND as i32) {
                        lRet = (ERROR_SUCCESS as i32);
                        hKeySource = core::ptr::null_mut();
                    } else {
                        hKeySource = core::ptr::null_mut();
                    }

                    if FoundSource == 0 {
                        continue;
                    }

                    if LogNameValid != 0
                        && !(FoundLog != 0
                            && _wcsicmp(
                                core::ptr::addr_of_mut!(LogName) as *const WCHAR,
                                EventLogName,
                            ) == 0)
                    {
                        RegCloseKey(hKeySource);
                        hKeySource = core::ptr::null_mut();

                        SourceAlreadyExists = (TRUE as i32);

                        RtlCopyMemory!(
                            core::ptr::addr_of_mut!(LogNameErr) as *mut WCHAR as *mut core::ffi::c_void,
                            core::ptr::addr_of_mut!(LogName) as *const WCHAR as *const core::ffi::c_void,
                            core::mem::size_of::<[WCHAR; (MAX_KEY_LENGTH as _)]>(),
                        );

                        continue;
                    }

                    SourceCreated = (TRUE as i32);
                    IsCustomSource = (FALSE as i32);

                    lRet = RegQueryValueExW(
                        hKeySource,
                        RUSTCONV_WSTR_AFD9FD76A995.as_ptr(),
                        core::ptr::null_mut(),
                        core::ptr::null_mut(),
                        core::ptr::null_mut(),
                        core::ptr::null_mut(),
                    );

                    RegCloseKey(hKeySource);
                    hKeySource = core::ptr::null_mut();

                    if lRet == (ERROR_SUCCESS as i32) {
                        IsCustomSource = (TRUE as i32);
                    } else if lRet == (ERROR_FILE_NOT_FOUND as i32) {
                        // IsCustomSource = FALSE;
                    } else {
                        break 'quit;
                    }

                    break;
                }
            }
        }

        // Finalize:
        lRet = (ERROR_SUCCESS as i32);

        UNREFERENCED_PARAMETER!(SourceCreated);

        if LogNameValid != 0 && FoundLog == 0 {
            ConResPrintf(StdErr, IDS_LOG_NOT_FOUND, EventLogName);
            break 'quit;
        }

        if LogNameValid != 0 && LogSourceValid == 0 {
            Success_local = (TRUE as i32);
            break 'quit;
        }

        if FoundSource != 0 && SourceAlreadyExists != 0 {
            ConResPrintf(
                StdErr,
                IDS_SOURCE_EXISTS,
                core::ptr::addr_of_mut!(LogNameErr) as *mut WCHAR,
            );
            break 'quit;
        }

        if FoundSource != 0 && SourceAlreadyExists == 0 {
            if IsCustomSource != 0 || AllowAppSources != 0 {
                Success_local = (TRUE as i32);
                break 'quit;
            } else {
                ConResPuts(StdErr, IDS_SOURCE_NOT_CUSTOM);
                break 'quit;
            }
        }

        if LogSourceValid != 0 && FoundSource == 0 {
            if LogNameValid == 0 {
                ConResPuts(StdErr, IDS_SOURCE_NOCREATE);
                break 'quit;
            } else {
                lRet = RegOpenKeyExW(
                    hEventLogKey,
                    EventLogName,
                    0,
                    KEY_CREATE_SUB_KEY,
                    core::ptr::addr_of_mut!(hLogKey),
                );
                if lRet != (ERROR_SUCCESS as i32) {
                    break 'quit;
                }

                lRet = InstallEventSource(hLogKey, EventLogSource);

                RegCloseKey(hLogKey);

                if lRet != (ERROR_SUCCESS as i32) {
                    PrintError((lRet) as DWORD);
                    ConPrintf(
                        StdErr,
                        RUSTCONV_WSTR_D2D10514D703.as_ptr(),
                        EventLogSource,
                        EventLogName,
                    );
                    break 'quit;
                }

                SourceCreated = (TRUE as i32);
                Success_local = (TRUE as i32);
            }
        }
    }

    // Quit:
    if !hEventLogKey.is_null() {
        RegCloseKey(hEventLogKey);
    }

    SetLastError((lRet) as DWORD);

    return Success_local;
}

unsafe extern "C" fn TrimLeftRightWhitespace(mut String: PWSTR) -> PWSTR {
    let mut pStr: PWSTR = core::ptr::null_mut();

    /* Trim whitespace on left (just advance the pointer) */
    while *String != 0 && iswspace((*String as u32) as u16) != 0 {
        String = String.offset(1);
    }

    /* Trim whitespace on right (NULL-terminate) */
    pStr = String.offset(wcslen(String as *const u16) as isize - 1 as isize);
    while pStr >= String && iswspace((*pStr as u32) as u16) != 0 {
        pStr = pStr.offset(-1);
    }
    pStr = pStr.offset(1);
    *pStr = 0x0000u16;

    /* Return the modified pointer */
    return String;
}
#[no_mangle]
pub unsafe extern "C" fn DoParse(
    mut argc: INT,
    mut argv: *mut *mut WCHAR,
    mut Options: POPTION,
    mut NumOptions: ULONG,
    mut PrintErrorFunc: PRINT_ERROR_FUNC,
) -> BOOL {
    let mut ExclusiveOptionPresent: BOOL = (FALSE as i32);
    let mut OptionStr: PWSTR = core::ptr::null_mut::<WCHAR>();
    let mut i: UINT = 0;

    /*
     * The 'Option' index is reset to 'NumOptions' (total number of elements in
     * the 'Options' list) before retrieving a new option. This is done so that
     * we know it cannot index a valid option at that moment.
     */
    let mut Option: UINT = NumOptions as UINT;

    /* Parse command line for options */
    i = 1 as UINT;
    while i < argc as UINT {
        /* Check for new options */

        if *(*argv.offset(i as isize)).offset(0 as isize) == 0x002Du16
            || *(*argv.offset(i as isize)).offset(0 as isize) == 0x002Fu16
        {
            /// FIXME: This test is problematic if this concerns the last option in the command-line!
            /// A hack-fix is to repeat this check after the 'for'-loop.
            if (Option as ULONG) != NumOptions {
                if PrintErrorFunc.is_some() {
                    PrintErrorFunc(ValueRequired, OptionStr);
                }
                return (FALSE) as BOOL;
            }

            /*
             * If we have already encountered an (unique) exclusive option,
             * just break now.
             */
            if ExclusiveOptionPresent != 0 {
                break;
            }

            OptionStr = *argv.offset(i as isize);

            /* Lookup for the option in the list of options */
            Option = 0 as UINT;
            while (Option as ULONG) < NumOptions {
                if _wcsicmp(
                    OptionStr.offset(1 as isize) as *const WCHAR,
                    (*Options.offset(Option as isize)).OptionName as *const WCHAR,
                ) == 0
                {
                    break;
                }
                Option = Option.wrapping_add(1);
            }

            if (Option as ULONG) >= NumOptions {
                if PrintErrorFunc.is_some() {
                    PrintErrorFunc(InvalidOption, OptionStr);
                }
                return (FALSE) as BOOL;
            }

            /* An option is being set */

            if (*Options.offset(Option as isize)).MaxOfInstances != 0
                && (*Options.offset(Option as isize)).Instances
                    >= (*Options.offset(Option as isize)).MaxOfInstances
            {
                if PrintErrorFunc.is_some() {
                    PrintErrorFunc(
                        TooManySameOption,
                        OptionStr,
                        (*Options.offset(Option as isize)).MaxOfInstances,
                    );
                }
                return (FALSE) as BOOL;
            }
            (*Options.offset(Option as isize)).Instances =
                (*Options.offset(Option as isize)).Instances.wrapping_add(1);

            (*Options.offset(Option as isize)).OptionStr = OptionStr;

            /*
             * If this option is exclusive, remember it for later.
             * We will then short-circuit the regular validity checks
             * and instead check whether this is the only option specified
             * on the command-line.
             */
            if ((*Options.offset(Option as isize)).Flags & OPTION_EXCLUSIVE) != 0 {
                ExclusiveOptionPresent = (TRUE as i32);
            }

            /* Preprocess the option before setting its value */
            match (*Options.offset(Option as isize)).Type {
                0 => {
                    /* Set the associated boolean */
                    let mut pBool: *mut BOOL = (*Options.offset(Option as isize)).Value as *mut BOOL;
                    *pBool = (TRUE as i32);

                    /* No associated value, so reset the index */
                    Option = NumOptions as UINT;

                    /* Fall-back (TYPE_None falls through to TYPE_Str: break) */
                }

                /* TYPE_Str, and the fall-back target */
                1 | TYPE_U32 => {}

                _ => {
                    wprintf(
                        RUSTCONV_WSTR_D22093549D92.as_ptr(),
                        (*Options.offset(Option as isize)).Type,
                    );
                }
            }
        } else {
            /* A value for an option is being set */
            match (*Options.offset(Option as isize)).Type {
                0 => {
                    /* There must be no associated value */
                    if PrintErrorFunc.is_some() {
                        PrintErrorFunc(ValueNotAllowed, OptionStr);
                    }
                    return (FALSE) as BOOL;
                }

                1 => {
                    /* Retrieve the string */
                    let mut pStr: *mut PWSTR =
                        (*Options.offset(Option as isize)).Value as *mut PWSTR;
                    *pStr = *argv.offset(i as isize);

                    /* Trim whitespace if needed */
                    if ((*Options.offset(Option as isize)).Flags & OPTION_TRIM_SPACE) != 0 {
                        *pStr = TrimLeftRightWhitespace(*pStr);
                    }

                    /* Check whether or not the value can be empty */
                    if ((*Options.offset(Option as isize)).Flags & OPTION_NOT_EMPTY) != 0
                        && **pStr == 0
                    {
                        /* Value cannot be empty */
                        if PrintErrorFunc.is_some() {
                            PrintErrorFunc(ValueIsEmpty, OptionStr);
                        }
                        return (FALSE) as BOOL;
                    }

                    /* Check whether the value is part of the allowed list of values */
                    if ((*Options.offset(Option as isize)).Flags & OPTION_ALLOWED_LIST) != 0 {
                        let mut AllowedValues: PWSTR = core::ptr::null_mut::<WCHAR>();
                        let mut Scan: PWSTR = core::ptr::null_mut::<WCHAR>();
                        let mut Length: SIZE_T = 0;

                        AllowedValues = (*Options.offset(Option as isize)).AllowedValues;
                        if AllowedValues.is_null() {
                            /* The array is empty, no allowed values */
                            if PrintErrorFunc.is_some() {
                                PrintErrorFunc(InvalidValue, *pStr, OptionStr);
                            }
                            return (FALSE) as BOOL;
                        }

                        Scan = AllowedValues;
                        while *Scan != 0 {
                            /* Find the values separator */
                            Length = wcscspn(
                                Scan as *const WCHAR,
                                RUSTCONV_WSTR_041F8C928EFC.as_ptr(),
                            ) as SIZE_T;

                            /* Check whether this is an allowed value */
                            if (wcslen(*pStr as *const WCHAR) == (Length) as _)
                                && (_wcsnicmp(
                                    *pStr as *const WCHAR,
                                    Scan as *const WCHAR,
                                    Length as usize,
                                ) == 0)
                            {
                                /* Found it! */
                                break;
                            }

                            /* Go to the next test value */
                            Scan = Scan.offset(Length as isize);
                            if *Scan != 0 {
                                Scan = Scan.offset(1);
                            } // Skip the separator
                        }

                        if *Scan == 0 {
                            /* The value is not allowed */
                            if PrintErrorFunc.is_some() {
                                PrintErrorFunc(InvalidValue, *pStr, OptionStr);
                            }
                            return (FALSE) as BOOL;
                        }
                    }
                }

                TYPE_U32 => {
                    let mut pszNext: PWCHAR = core::ptr::null_mut::<WCHAR>();

                    /* The number is specified in base 10 */
                    // NOTE: We might use '0' so that the base is automatically determined.
                    *((*Options.offset(Option as isize)).Value as *mut ULONG) =
                        wcstoul(
                            *argv.offset(i as isize),
                            core::ptr::addr_of_mut!(pszNext),
                            10,
                        ) as ULONG;
                    if *pszNext != 0 {
                        /* The value is not a valid numeric value and is not allowed */
                        if PrintErrorFunc.is_some() {
                            PrintErrorFunc(
                                InvalidValue,
                                *argv.offset(i as isize),
                                OptionStr,
                            );
                        }
                        return (FALSE) as BOOL;
                    }
                }

                _ => {
                    wprintf(
                        RUSTCONV_WSTR_D22093549D92.as_ptr(),
                        (*Options.offset(Option as isize)).Type,
                    );
                }
            }

            /* Reset the index */
            Option = NumOptions as UINT;
        }
        i = i.wrapping_add(1);
    }

    /// HACK-fix for the check done inside the 'for'-loop.
    if (Option as ULONG) != NumOptions {
        if PrintErrorFunc.is_some() {
            PrintErrorFunc(ValueRequired, OptionStr);
        }
        return (FALSE) as BOOL;
    }

    /* Finalize options validity checks */

    if ExclusiveOptionPresent != 0 {
        /*
         * An exclusive option present on the command-line:
         * check whether this is the only option specified.
         */
        i = 0 as UINT;
        while (i as ULONG) < NumOptions {
            if ((*Options.offset(i as isize)).Flags & OPTION_EXCLUSIVE) == 0
                && ((*Options.offset(i as isize)).Instances != 0)
            {
                /* A non-exclusive option is present on the command-line, fail */
                if PrintErrorFunc.is_some() {
                    PrintErrorFunc(InvalidSyntax);
                }
                return (FALSE) as BOOL;
            }
            i = i.wrapping_add(1);
        }

        /* No other checks needed, we are done */
        return (TRUE) as BOOL;
    }

    /* Check whether the required options were specified */
    i = 0 as UINT;
    while (i as ULONG) < NumOptions {
        /* Regular validity checks */
        if ((*Options.offset(i as isize)).Flags & OPTION_MANDATORY) != 0
            && ((*Options.offset(i as isize)).Instances == 0)
        {
            if PrintErrorFunc.is_some() {
                PrintErrorFunc(
                    MandatoryOptionAbsent,
                    (*Options.offset(i as isize)).OptionName,
                );
            }
            return (FALSE) as BOOL;
        }
        i = i.wrapping_add(1);
    }

    /* All checks are done */
    return (TRUE) as BOOL;
}

#[no_mangle]
unsafe extern "C" fn PrintParserError_v(Error: PARSER_ERROR, ap_list: *mut ::core::ffi::c_void) {
    static mut ErrorIDs: [UINT; 9] = [
        0,
        IDS_BADSYNTAX_0,
        IDS_INVALIDSWITCH,
        IDS_BADSYNTAX_1,
        IDS_BADSYNTAX_2,
        IDS_BADSYNTAX_3,
        IDS_BADSYNTAX_4,
        IDS_BADSYNTAX_5,
        IDS_BADSYNTAX_6,
    ];

    let mut args_va: va_list;

    if (Error as u32) < ARRAYSIZE!(ErrorIDs) {
        args_va = *(ap_list as *mut va_list);
        ConResPrintfV(&raw mut csStdErr, ErrorIDs[Error as usize], args_va);

        if Error != Success {
            ConResPuts(&raw mut csStdErr, IDS_USAGE);
        }
    } else {
        ConPrintf(&raw mut csStdErr, RUSTCONV_WSTR_2D5A5BFFEA85.as_ptr(), Error);
    }
}



