//! Builds the genuine schannel mbedTLS backend as a host translation unit.
//!
//! Three inputs, all taken from the tree rather than copied into the harness:
//!   * the 46 mbedTLS sources `dll/3rdparty/mbedtls/CMakeLists.txt` actually lists,
//!     parsed from that file so a source added or dropped there reaches this harness;
//!   * `sdk/include/reactos/libs/mbedtls/config.h`, the same configuration the
//!     shipping mbedtls.dll is built with — not upstream's defaults, because the
//!     backend's behaviour depends on which ciphersuites and TLS versions are on;
//!   * `dll/win32/schannel/schannel_mbedtls.c` itself, compiled with `__REACTOS__`
//!     so this grades the arm we ship rather than Wine's lazy-loading one.
use std::{env, fs, path::PathBuf};

fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../../..");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let mbedtls_dir = root.join("dll/3rdparty/mbedtls");
    let schannel_dir = root.join("dll/win32/schannel");
    let libs_inc = root.join("sdk/include/reactos/libs");

    // The backend contract, sliced out of the real header so it cannot drift. Taking
    // a copy instead is how a fixture ends up grading a shape the tree no longer has.
    let priv_h = fs::read_to_string(schannel_dir.join("schannel_priv.h")).unwrap();
    let start = priv_h
        .find("/* schannel internal interface */")
        .expect("schannel_priv.h lost its internal-interface marker");
    let end = priv_h[start..]
        .find("\nSECURITY_STATUS\nWINAPI\nschan_FreeContextBuffer")
        .expect("schannel_priv.h lost schan_FreeContextBuffer, the slice's end anchor")
        + start;
    fs::write(
        out.join("schan_backend_contract.h"),
        format!(
            "/* GENERATED by build.rs from dll/win32/schannel/schannel_priv.h. */\n\
             #ifndef SCHAN_BACKEND_CONTRACT_H\n#define SCHAN_BACKEND_CONTRACT_H\n{}\n#endif\n",
            &priv_h[start..end]
        ),
    )
    .unwrap();

    // The wincrypt ALG_ID table, EXTRACTED rather than retyped. Writing these by hand
    // is how a fixture ends up grading against constants Windows never used: the first
    // cut of this file had ALG_SID_RIPEMD160 as 9 (it is 7) and invented CALG_BLOWFISH,
    // CALG_CAMELLIA and CALG_PSK outright. They are self-contained `#define`s over each
    // other with no type dependencies, so lifting the lines verbatim is safe and exact.
    let wincrypt = fs::read_to_string(root.join("sdk/include/psdk/wincrypt.h")).unwrap();
    let mut algs = String::from(
        "/* GENERATED by build.rs from sdk/include/psdk/wincrypt.h. */\n         #ifndef HARNESS_WINCRYPT_ALGS_H\n#define HARNESS_WINCRYPT_ALGS_H\n         typedef unsigned int ALG_ID;\n",
    );
    let mut n = 0;
    for line in wincrypt.lines() {
        let t = line.trim_start();
        if t.starts_with("#define ") {
            let name = t[8..].trim_start();
            if name.starts_with("ALG_") || name.starts_with("CALG_") {
                algs.push_str(line);
                algs.push('\n');
                n += 1;
            }
        }
    }
    algs.push_str("#endif\n");
    assert!(n > 100, "only {n} ALG_/CALG_ defines found in wincrypt.h");
    fs::write(out.join("wincrypt_algs.h"), algs).unwrap();

    // The source list, parsed rather than restated.
    let cmake = fs::read_to_string(mbedtls_dir.join("CMakeLists.txt")).unwrap();
    let block = {
        let s = cmake.find("list(APPEND SOURCE").expect("mbedtls CMakeLists lost its SOURCE list");
        let e = cmake[s..].find(')').unwrap() + s;
        &cmake[s..e]
    };
    let mut mbedtls_sources: Vec<PathBuf> = Vec::new();
    for line in block.lines().skip(1) {
        let line = line.trim();
        // `#` is upstream-disabled, `${...}` are the two ReactOS adapters which are
        // Win32-only (strsafe, QueryPerformanceCounter) and have no host meaning.
        if line.starts_with('#') || line.contains("${") || !line.ends_with(".c") {
            continue;
        }
        mbedtls_sources.push(mbedtls_dir.join(line));
    }
    assert!(
        mbedtls_sources.len() > 40,
        "parsed only {} mbedtls sources — the CMakeLists shape changed",
        mbedtls_sources.len()
    );

    let mut mb = cc::Build::new();
    mb.include(&libs_inc).opt_level(1).warnings(false);
    for f in &mbedtls_sources {
        mb.file(f);
        println!("cargo:rerun-if-changed={}", f.display());
    }
    // THE ONE DEVIATION FROM THE SHIPPED CONFIGURATION. Our config.h switches
    // MBEDTLS_SSL_SRV_C off ("we don't need anything server-related") and drops
    // ssl_srv.c from the source list, so the mbedtls.dll we ship CANNOT act as a TLS
    // server. A loopback test needs a peer, so the harness compiles the server arm in.
    //
    // IT HAS TO BE ON FOR THE WHOLE HARNESS, not just ssl_srv.c: MBEDTLS_SSL_SRV_C
    // guards FIELDS inside mbedtls_ssl_config and mbedtls_ssl_context, so a
    // translation unit compiled without it sees a different struct layout and the
    // handshake dies on garbage. That cost an hour and a confident wrong diagnosis
    // here; the symptom was the server reporting MBEDTLS_ERR_SSL_CONN_EOF while the
    // client sat waiting for a reply that had never been parsed.
    //
    // So schannel_mbedtls.c is compiled with it too. It references nothing the switch
    // guards, so the code under test is unchanged -- but say "as shipped" about this
    // harness only with that asterisk.
    //
    // Note what the switch also means in production: schannel_mbedtls.c maps
    // SECPKG_CRED_INBOUND to MBEDTLS_SSL_IS_SERVER, so schannel's server path calls
    // into a library with no server support compiled in. That is a finding about the
    // tree, not about this harness.
    mb.file(mbedtls_dir.join("ssl_srv.c")).define("MBEDTLS_SSL_SRV_C", None);
    mb.compile("mbedtls_host");

    // Compiled from OUT_DIR, not in place. `#include "precomp.h"` is QUOTED, so it
    // resolves against the including file's own directory before any -I — from
    // dll/win32/schannel that is the real PSDK-wide precomp.h, and the fixture never
    // gets a look in. Moving the translation unit is what lets the shim win.
    let reference = out.join("schannel_mbedtls.c");
    fs::copy(schannel_dir.join("schannel_mbedtls.c"), &reference).unwrap();

    cc::Build::new()
        .file(&reference)
        .file("fixtures/harness.c")
        .define("__REACTOS__", None)
        // Layout parity with the mbedtls above; see the note there.
        .define("MBEDTLS_SSL_SRV_C", None)
        .include("fixtures")
        .include(&out)
        .include(&libs_inc)
        .include(libs_inc.join("mbedtls"))
        .opt_level(1)
        .warnings(false)
        .compile("schan_backend");

    for p in [
        schannel_dir.join("schannel_mbedtls.c"),
        schannel_dir.join("schannel_priv.h"),
        mbedtls_dir.join("CMakeLists.txt"),
        libs_inc.join("mbedtls/config.h"),
        root.join("sdk/include/psdk/wincrypt.h"),
    ] {
        println!("cargo:rerun-if-changed={}", p.display());
    }
    println!("cargo:rerun-if-changed=fixtures");
}
